	<h2>What is The HDTV Expo?</h2>
	The HDTV Expo is a series of weekend consumer educational events which also showcase current high-definition and digital television technologies;
	HDTV programming; and available accessory products. Classes will be presented by industry experts and will cover the entire spectrum of HDTV topics.
	Exhibitors will be displaying their very best products in the main exhibit hall and will have knowledgeable manufacturer representatives on hand to assist 
	you with an up-close and personal look at the latest in Digital Television technology. The HDTV Expo is an interactive sight and sound experience. You won't want to miss it.

