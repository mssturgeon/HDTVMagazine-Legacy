				<p class="editorial">The following article originally appeared in Wide Screen Review (WSR) magazine at the end of 2010 and is being republished courtesy of it's author, Terry Paullin.</p><p>No, this isn't the I-told-ya-so column ... yet. Events have moved much faster than I predicted when I wrote a column on this topic about a year ago, but it seems we are headed for the same forecasted result.  In that column I pointed to lack of standards, lack of content, the glasses nuisance and the problematic usage model in the home as probable deterrents to wide (or any) adoption of 3D in your living room. Press releases received over the past few months from various independent surveys have "leaked" reports of disappointing sales from even the most conservative manufacturers estimates. Last week, an article in reuters.com confirmed "3DTV hasn't caught the imagination of consumers". Reasons cited later in the article were ... uhh ... lack of standards, lack of content and, yup, those pesky glasses. To make matters even worse, in an almost unbelievably inept marketing move, studios partnered with specific manufacturers to offer "exclusive" content packages - as if wanting to spend an hour and a half with "Coraline" would cause you to buy a Panasonic display over a Samsung, all other features and functions, including price, be damned.
</p><p>Here's where I think we are. The only delivery scheme that has a chance in your living room is "active shutter" - that's right, the battery powered, expensive glasses. Truth is, they aren't that bad, but if you intend to outfit the room on Super Sunday, bring big $. Barring some newly discovered Law of Physics, auto-stereoscopic 3D (sans glasses) in the home is unlikely in this decade. The only way to move hardware now is to minimize the delta (price difference between comparable 2D and 3D sets) so that folks who are "thinking about 3D" will spend a little extra in the name of "insurance", while postponing the purchase of yet another shiny-disc player. Since the Fat Lady hasn't appeared on stage yet, that might be a good policy.
</p><p>Those who would liken the adoption curve of 3D to that of HDTV are three balls and a pallino short of a Bocce Set. The latter was legislated by the Federal Government and had a payload of "WOW". The former is the dreamvision of a gaggle of Marketeers overdosed on Avatar. The payload? ... well, the jury's still out, but starting to yawn.
</p><p>To reprise an admonition from the previous column, I DO have a dog in this fight. I run a Home Theatre design and installation company. If I could replace all the 2D players and displays with ones sporting and extra "D", I would enjoy a better retirement. I truly want to be wrong on this one. Our beloved Industry is "All In" and I don't want to see any more fallout than we have witnessed to date. 
</p><p>I'm just sayin' ..................
</p><p>
 </p><p>Having apparently given up on that "Sky" thing, Chicken Little has a new chant - "The Disc is dying, the Disc is dying, streaming video is everywhere". ...... Not so fast, little chickey. 
</p><p>I subscribe to every magazine that serves the Home Theatre community. For the last couple months an inordinate amount of space has been relagated to "Company A has just announced a deal with Company B to stream Product C to your ... (pick one) AVR, BD player, TV, media server. Apparantly it's not enough that everbody can download anything to your latest i-trinket, now we can get bombarded from all sides in our holiest of sanctuaries, our Theatre Room. I'm still not buying it. 
</p><p>Although the blight of discretionary income is still upon us, I still do 20 to 25 theatres a year across several geographies. Not one client (yet) has inquired about streaming movie content. A few have connected to the BD player for the purpose of s/w updates. It's true, by natural selection (mine), I don't see the bottom two quartiles ($/theatre) - I send them to my I'll-install-anything friends, but I still do a lot of my work in Silicon Valley, the epicenter of Hi-Tek. I've come to believe they think, as I do, that we prefer our movies to come with a tactile sensation. We want to hold them in our hands  and read the liner notes. We want to know, to the minute, how long they screen. We want to know who the actors are and who directed and what the N.Y. Times had to say about this flick. We want to know the choices of audio codecs available. If aunt Juanita is visiting, we'd like to select the Spanish subtitling. We may even want to peruse the deleted scenes and special features ... and we'd like to have all this data in advance and be able to change it on the fly if necessary. Hell, if it's a keeper, we may even want to watch it a second or third time (at no additional charge).  When we're done, we may want to loan it to the guy next door or send it across town to cousin Fred. 
</p><p>Stream if you like folks, but know (apart from the aforementioned) that you won't get the "whole" picture. At a minimum, your selection will be laced with compression artifacts that range from discernable by the average eye to toxic from across the street.  And the show-stopper for this readership should be the fact that you won't get half the value added from BD, the lossless audio codec's from Dolby TruHD and DTS-HD Master Audio. I have been pleasantly surprised, of late, by how much the higher definition audio has brought to the overall movie experience in current releases. 
</p><p>Perhaps Mr. Little should look for a new chant.
</p><p>
 </p><p>As I write, I'm psychologically packing my bags for the 2011 CES (Consumer Electronics Show). I'm expecting the 3D rhetoric to be as loud as last year in an attempt to breath (more) life into a huge, collective investment. I'm guessing much of the traffic will be re-routed to the booths featuring the latest i-toys. I smell a hint of "5G" in the air.
</p><p>As always, I'll be involved with ISF training before the opening bell at the Convention Center. A solid grounding in reality from Joel Silver is always healthy before venturing off into Fantasyland. God, I love Las Vegas!</p>
