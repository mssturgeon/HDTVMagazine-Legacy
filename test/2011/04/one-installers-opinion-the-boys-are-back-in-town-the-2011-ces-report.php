</p><p>The big news in Las Vegas this year wasn't a new app. for the next i-Trinket that prints money in eleventeen different languages, nor was it a 175 in. flat panel, or even the announcement of Smell-o-Vision as a 3D accessory - although there's a joke in there somewhere. It was, in fact, the attendance itself. By some counts up 50% from last year, it was heralded by many as an early indicator of at least 12 better months to come. Clearly, manufacturers large and small resurrected their Trade Show budgets and sent record amounts of hardware and supporting casts to the Las Vegas Convention Center and the circus we love to hate. I hope they knew something I didn't and that for the sake of all the CE stakeholders the turn indeed materializes and the trickle down comes quickly to those still (barely) hanging on. 
</p><p>For me, the show brought mixed emotions. Buoyed by the positive spirit that the consensus was "up and to the right" for business in 2011, it was somewhat eerily countered by the harsh realization (really in the air for 2 or 3 years now) that this (C.E.S.) was no longer "our show".
</p><p>Not all that long ago, if "Home Theatre" was not the centric theme of the show, it was certainly among the largest draws. Now-a-days, not so much. In fact, regulars who used to inhabit the South Hall have either opted out or are scattered to various, more obscure venues. It was good to talk to Joe Kane in the Da-Lite booth and see old and new friends at Dolby and DTS, and renew contacts at most all the display vendors ... but it just wasn't the same. Back in the day, anybody and everybody built a temporary theatre to show off their latest and greatest. Now we risk life and limb (did I mention the show floor was Japanese Train crowded) to go from Big panel display "A" to Big panel display "B". 
</p><p>Someone once said, "You can never go home". It seems in MY favorite World, you can't even get back to the old toy box.
</p><p>Fortunately for custom installers, system integrators, and pretty much everyone who sells into the Home Theatre market, we HAVE had our own show for some time now. CEDIA. (Custom Electronics Design &amp; Installation Association)
</p><p>The large annual show is a great place to see all of "our stuff" in one place, network with key industry contacts and , for the newbies, partake in all manner of professional training ... ... only thing missing - Las Vegas Boulevard and all that it holds .... and a few hundred fine restaurants .... and world class Show Productions .... and .... well, you've been there. You know.
</p><p>It was also good to help instruct an ISF class just before the show opened -  get's you in just the right state of mind to confront the latest wave of marketing claims from the usual suspects. Turns out, at its core, Imaging Science is just a technology-specific subset of the laws of Physics. Yet I am continually amazed at how various Marketing Departments "invent" new laws all the time (see YELLOW below). 
</p><p>By this time, you have, no doubt, read about every cool thing that caught the eye of the battalions of E-reporters who converged there at C.E.S. While it's difficult for a print magazine to keep up with those who were blogging before the show doors opened on Thursday, I offer here a couple things they may have missed.
</p><p>...Funniest sign seen on the show floor ... "World's largest 84" LCD " ... (think about it).
</p><p>...Longest line for a demo ... the massage chairs in South Hall
</p><p>...Longest line for a REPEAT demo ... the massage chairs in the South Hall
</p><p>...Best use of color to attract  Prospects to Product ... that girl in the ACME projector booth (nothing says color saturation like a red bikini)
</p><p>...Most (only) useful booth giveaway...the thumb drive shaped like a poker chip from Verizon
</p><p>...Worst looking displays...Any manufacture showing display devices with more than 2Ds in the signage
</p><p>...Largest violation of truth-in-advertising ...any of the several booths that advertised "LED HDTV" ... (no such thing in production)
</p><p>...Best Party (hands down) ...the Monster Bash ...(Earth, Wind and Fire with cameo by Stevie Wonder)
</p><p>...Funniest thing I heard at the show. One manufacture proudly informed me that although "they've had many inquiries" they were NOT going to license their (apparently recent) extraordinary discovery of the long lost fourth primary color - YELLOW. hmmm, how could we have missed it all this time. (rumors are that Samsung is scary close to rediscovering "magenta")
</p><p>...Most often seen video clip ..."Jeff Beck - Live at Ronnie Scott's" - really! (we even used it in class - a diagonally strummed guitar string provides an ultimate motion artifact torture test)
</p><p>Although I didn't really see anything this year that made my socks go up and down, as usual, the overall quality of video products offered was up. There were new, larger panels in all technologies and demonstrations of even better things to come. Alas, as is also the usual case, for every 100 new company names, we are likely to see only a handful return next year. And so, CEDIA notwithstanding, breakthrough technologies or not, good times or bad,  I will return to the desert next year as always. 
</p><p>Viva Las Vegas!</p>
