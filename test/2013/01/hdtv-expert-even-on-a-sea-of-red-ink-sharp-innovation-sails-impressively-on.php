<p class="none">Sharp has not lost its ability to impress with significant LCD and TV innovations, and incorporate them in shipping (or soon-to-ship) products. That must mean that despite all the red ink, Sharp corporate is still investing in R&amp;D. And, unlike at some companies, the researchers have avoided the ‚Äúengineering disease‚Äù are producing the kind of innovations that make more attractive products.</p>
