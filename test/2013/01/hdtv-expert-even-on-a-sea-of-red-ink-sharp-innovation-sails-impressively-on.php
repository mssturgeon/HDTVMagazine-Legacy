<p class="none">In a guest appearance at the event, James Clappin, President of the Corning Glass Technologies Group, commented that Corning‚Äôs Lotus glass had been optimized for IGZO. Previously, Corning executives told me that IGZO requires longer heat exposure than amorphous silicon, so the glass must be able to tolerate that without reaching the temperature at which it loses its dimensional stability.</p>
<p class="none">John Herrington, President of Sharp Electronics Marketing Company of America, stated that Sharp has been the fastest growing brand in the U.S. for the last two years, but did not say that this growth was from the single-digital market share to which the company had fallen. Herrington proudly spoke of Sharp‚Äôs leadership in the 60-inch-and-over TV segment, and announced that for 2013 the company would have 21 models 60 inches and over across three series, including Quattron and 4K models.</p>
<p class="none">Herrington also described ‚ÄúMoth Eye Technology,‚Äù which uses a nanoscale cone structure on the screen surface to eliminate glare and reflection.</p>
<p class="none">On the show floor, Sharp showed its 85-inch 8Kx4K (yes, 32-megapixel) liquid-crystal display. On an image showing an expansive field of sunflowers, a viewer who nearly touched his nose to the screen could see individual pollen grains on a sunflower petal.</p>
<p class="none">But the most interesting innovation that will appear in a near term product, and which was very poorly explained in the press conference, is Sharp‚Äôs clever approach to generating a real 4Kx1K image a from a Quattron screen having only 1920√ó1080 pixels. As technical source within Sharp explained it to me, this works because Quattron‚Äôs 4-subpixel pixels can create white light in two different ways: the traditional way, by mixing appropriate amounts of red, green, and blue; and by mixing blue and yellow. This allows two luminance peaks to be formed and arrayed horizontally in each RGBY-stripe pixel, and a FHD screen can produce 3840 luminance peaks horizontally. It is possible to play this trick vertically as well as horizontally by changing the pixel architecture, and Sharp is working on that for the future.</p>
<p><img class="aligncenter size-full wp-image-2780" alt="sharp" src="http://www.hdtvexpert.com/wp-content/uploads/2013/02/sharp.jpg" width="600" height="436" /></p>
<p class="none">Sharp‚Äôs new-generation Quattron with technology that allows an FHD panel to produce a true 4,000 luminance peaks horizontally presented a much sharper image than a conventional FHD Quattron. (Photo: Ken Werner)</p>
<p class="none">On the show floor, a 4Kx1K ‚ÄúNext Generation Quattron‚Äù prototype, looked significantly sharper than a current FHD (2Kx1K) model in a side-by-side comparison. And a 70-inch 4Kx2K TV with Moth Eye looked very good indeed, although it will take comparison testing under controlled conditions to accurately assess how good it is.</p>
