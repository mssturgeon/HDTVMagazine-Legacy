<p>The company plans to begin spending money on the line, which will focus on WRGB OLED evaporation process, in the first quarter of 2013, with mass production scheduled for the first half of 2014 at a monthly capacity of 26,000 input sheets. LG should be able to put 6 55-inch panels on each sheet, which might sound like the line will produce a lot of OLED-TVs. And someday it will. But there are persistent, if highly unofficial, reports, that LGD’s manufacturing yield is running at about 10%, with plans to increase it to 30% by repairing some of the defective units. That is still a dismal yield, and it will keep prices high until yields improve and manufacturing costs decline. And they will, eventually.</p>
<p>In fact, we have lived through this story before. When Samsung began making cell-phone-sized OLED displays, it took more time than anyone – including Samsung – expected before yields rose to acceptable levels and prices came down to acceptable levels, and OLED market projections from the leading market intelligence companies were revised downward multiple times.</p>
<div id="attachment_2893" class="wp-caption alignright" style="width: 310px"><a href="http://www.hdtvexpert.com/?attachment_id=2893" rel="attachment wp-att-2893"><img class="size-medium wp-image-2893" alt="Displaybank's latest projection of OLED-TV sales recognizes that no OLED-TVs were sold in 2012, and 2013 sales will measure in the hundreds." src="http://www.hdtvexpert.com/wp-content/uploads/2013/02/OLED-TV-market-update-300x195.jpg" width="300" height="195" /></a><p class="wp-caption-text">Displaybank&#8217;s latest projection of OLED-TV sales recognizes that no OLED-TVs were sold in 2012, and 2013 sales will measure in the hundreds.</p></div>
<p>Late last year DisplaySearch projected that 500 OLED-TVs would be shipped worldwide in 2012, 5000 in 2013, 1.7 million in 2014, and 4.8 million in 2015. Now, Displaybank is putting those numbers at 1600 for 2013 and 1.7 million in 2015. And I wouldn’t take bets that those numbers won’t be revised downward before all this is done.</p>
<p>When it comes to OLED-TVs, we have all spent so much time looking at LG and Samsung, that Panasonic and Sony caught many of us by surprise when each of them showed a 56-inch 4K OLED-TV at CES this January. That diagonal and pixel count are unusual enough in the OLED world that you might expect the panels are coming from the same place, and that is partly true. The backplanes are coming from the Gen 6 fab of Korea’s AUO. One report said the backplane was LTPS; another that it was IGZO. It is worth noting that AUO has done a great deal of R&amp;D on oxide TFTs over the years. On the other hand, while LTPS is certainly not impossible on a Gen 6 substrate (Samsung has been doing it on its Gen 5.5), it is not easy and it does not scale readily to Gen 8 (although Samsung has been planning to do exactly that for its first Gen 8 OLED plant). I will speculate that IGZO is the more likely approach from AUO, and it is the approach that will ultimately drive OLED prices down faster.</p>
<p>The front planes are different. Panasonic used a printing process for at least some of the OLED front-plane layers, while Sony used vacuum thermal evaporation. Printing of some sort is likely to be a significantly lower-cost approach, but development has been going on for many years.</p>
<p>So where are our OLED-TVs? They’re coming, which is what I said last year.</p>
