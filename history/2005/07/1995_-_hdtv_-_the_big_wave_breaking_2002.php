			<p>When RCA announced the formation of the NBC radio network in 1926, they wrote: "The market for receiving sets in the future will be determined largely by the quantity and quality of the programs broadcast. We say quantity because they must be diversified enough so that some of them will appeal to all possible listeners.</p>

