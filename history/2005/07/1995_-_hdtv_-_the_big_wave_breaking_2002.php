<p>"...Quality, appeal to all possible listeners, best of its kind..."<br />
Sounds like a road map for HDTV...</p>

<p>by Dale E. Cripps<br />
 <br />
The commercialization of HDTV is a staggering task, one which alters the nature of broadcasting in all its forms as it converges with the telephone and computer industries. </p>

<p>HDTV delivers not only the most perfect theatrical experience you will likely have, it comes spiced with the full power of the computer. It is big in every way--big screen, big experience, big vision, big money, BIG RISK! Those who have seriously contemplated its future say that it will become great and leave the consumers breathless for generations to come...providing that the transition from today's television standard to H/DTV can be completed.</p>

<p>No signal provider knows yet how money is to be made with HDTV. Broadcast. Pioneer broadcaster John Green from WRAL (Raleigh, NC) thinks it is not a matter of making money as it is an essential requirement for remaining in the broadcast business. Even the most armed doubters agree that we are on a course which cannot be reversed without a catastrophe and/or national communications crisis. </p>

<p><em>We are now diving headfirst into the next phase of the H/DTV roll out--we can call it Phase II--the defining year. </em></p>

<p>More H/DTV products--over three hundred--fill showrooms across the nation. That will make Phase II both cheaper and better than Phase I. But more programming to fill those new screens is still slow in coming, though some more IS coming. ABC has just added three more series. Movies are showing more often. Big sports events are in the works. Major League Baseball will see 29 games in HDTV. And, if my time should decide to come, I would love to build from this highly charged movement the finest television global network the world has ever known. I see no reason why anyone starting a HDTV network should aim any lower. The talent will fall in love with it as will the homeowner. We already hear the phrase "I love HDTV" more than any other.</p>

<p>Whether national objective or not, the transition demands a God-like patience. Dr. Joseph Flaherty, the God-father of HDTV in the U.S.A., said that those in charge must have the <em>courage of lions</em>. They must make decisions at times against their own immediate self-interests, and they must possess the power to look forward into uncharted space. An 'unshakable determination to succeed' with the DTV transition is the prerequisite for its success. A steady hand on the tiller must guide television executives, computer executives, state and federal government officials, local agencies, the program producers, retailers, and. most importantly, see every consumer through the transition. All will then act in their own time doing their own thing if this revolution is to continue bloodlessly. </p>

<p><em>Supposing the transition gets tangled-up and stalls in mid-air,  leaving an un-fixable mess to replace our once-powerful national NTSC broadcast business?</em> </p>

<p>Broadcasting can go to ruin with a misfiring of the DTV transition. All who still depend on it could be left scrambling for scarce resources. </p>

<p>CEA had given up on broadcasting, or so it would seem from their DTVGuide of May 2001. "Network programming is not only fracturing, but it is falling apart," said the trade association’s organ, "Why should we bind any perceived success or failure to the outdated dogmas of the past." </p>

<p>This old and reliable NTSC standard is still proclaimed by older captains of television to be their most valuable asset--even more than their spectrum. H/DTV is a threat to those assets until installed in as many homes as is NTSC. That is still 97 million households away. We have a lot of work to do.</p>

<p>To complete the transition the consumers must be courted as never before by manufacturers, retailers, program providers, satellite channels, cable channels, and the government. <u>The public must be genuinely excited about the promise of H/DTV if they are to do their part on time. </u></p>

<p>For those hoping for better programming, <em>act soon</em>. You will need to influence such an outcome. The soul of great artists can power the entire HDTV movement. Whoever gathers together the great ones from the arts and engages them in service to the transition will undoubtedly succeed in fulfilling the promise of delivering the finest television network in the world. </p>

<p><strong>Who Is Now In The Lead? </strong></p>

<p>The developers of the FCC standard--the Grand Alliance--dissolved into competitive factions when the standard was submitted to the FCC in 1996. The Consumer Electronics Association (CEA) assumed much of the lead on behalf of its manufacturers in the last years with NAB popping up now and then and cable and satellite duking it out for market share. It has been running mostly on its own like a new mutation landing in a favorable environment. A few members of CEA have made investments in program and signal sources to support hardware sales. Some think that has been only a light seeding. It's very expensive to gain the public's conviction on something new. "That is at least one billion dollars," says former RCA CEO, Dr. Joseph Donahue. </p>

<p>Mark Cuban, the Broadcast.Com success story, has launched a new HDTV/DBS & Cable carriage network. He was instrumental in causing NBC to share a HDTV feed for the Olympics. Both HDNet and the NBC affiliates delivered stunning Winter Olympic footage that will be talked about for many years. </p>

<p><strong>INFORMATION IS LEADING</strong></p>

<p>Right now information about H/DTV is leading the movement. It looks like it will continue to lead it until the arts come into play with their compelling programming. Then the lead is clearly theirs. When that is established everyone will have to scramble to keep up. <em>The BIG wave has arrived.</em></p>

<p>Everything, of course, hinges on the consumer and where they place their demand$. Many have written that in a post 9|11 period people are looking more for substance and quality than for the hollow and cheap.  </p>

<p>All in all one can certainly conclude without the fear of contradiction that HDTV will swell to form the biggest wave on the cultural/business horizon for consumer electronics. It is already the fastest growing product in consumer electronics. It is going world wide. It is not unreasonable to say that HDTV will transform the image we have of the world and we trust that is for the better.</p>

<p>Dale E. Cripps <br />
Revised March 2002 </p>
