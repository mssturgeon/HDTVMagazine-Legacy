<p>In the archive section of our Magazine we will post a huge body of work and documents from our long participation in the field. It will finally be where the history of HDTV and digital television is found. I will include the archives of the HDTV Newsletter. It should be remembered that many of those things found on the drawing boards today owe their genesis to the advent of High-definition television. HDTV is a huge subject. While the triple play, where service providers wish to offer you voice, data and video, over one line, looms large, the video that must ultimately be provided through it is HDTV. _Dale Cripps</p>

<p>From 1993</p>

<p>I have followed HDTV daily for the last ten years. Few developments have been so dramatic, far reaching, and personally impacting as HDTV.  Its development spanned nearly 30 years, yet it is still a measure away from being a household item. In this review to give you some fundamental reasons why HDTV is certain to be a valuable asset and shed light on those things which still obstruct it. </p>

<p>Trying to convey the value of HDTV without you first enjoying it is like explaining in writing how bumble bees fly. There is a danger of getting us lost in the explanation.</p>

<p>A high school drop out, Thomas Edison, started it all with his invention of the phonograph. He ushered in with that the era of home entertainment appliances. That device opened in time every nation to the idea of receiving and playing professionally produced entertainment as well as instructional programs in the home. </p>

<p>Musicians feared Mr. Edison had ruined their trade. Who would hire them if platters or cylinders would suffice?</p>

<p>David Sarnoff, while still a vice president of the Radio Corporation of America, ushered in commercial radio broadcasting in the 20s. Live programs of news, drama, and music were heard in cities and country farms in various parts of the nation. Newspapers charged Sarnoff at that time with the intent to single-handedly destroy the newspaper business with radio news. They refused advertising for radio products and program listing. But nothing could stop it. Networks formed out of local amateurish attempts to finally make the big national services. Stars from stage and phonograph moved to radio as it distributed their voices to more people in one day than ever they could in a lifetime from the stage. It was exciting. It was growing. It was important. It created a national community with a local lodge. It caused new business to develop. It was not regulated by the Federal Government. It was the wild west.</p>

<p>With Sarnoff again leading the way black and white television struggled into spotty use  following WWII. Few at first but then more and more living rooms across the United States tuned to Hopalong Cassidy movies and local wrestling. They came to faithfully tune in at 7:30 PM Tuesday nights to Texaco's Star Theater starring Milton Berle. He  gave the nation its last fading look at vaudeville. Those same personalities that lent radio their stature quickly saw that the future was in television. With the help of cigar salesman, William Paley (CBS Chairman), they jumped to the new visual medium. That did what Paley expected - carried the audiences from radio to television. The elixir of winning the war, the talent shift from radio to TV, exploitation of the remaining strengths of vaudeville, inspired writers and actors, and solid news reporting made for what is now called the golden age of television.  Television became one of the greatest growth industries of post WWII. RCA, the chief player in television, became the Microsoft of its day.</p>

<p>Color was the dream of TV engineers from the beginning. It didn't hold out quite the excitement as did radio or black and white. Those were, after all, brand new services forming whole new ways of looking at society. Those first developments required gutsy pioneers to get services started.  Color would be an extension of those by-then established services.  </p>

<p>It again was David Sarnoff, by that time the trusted Chairman of RCA (which owned NBC), who headed the drive to color. He gambled most- all of his company's resources to color television, and it nearly failed. Not only did he see in color the culmination of television engineering he wanted to expand RCA's presence and dominate beyond domestic market by having a system that could be sold to Europe and Japan as well. To insure order in the developmental process a committee was established from within the industry. Their mission was to create a color standard to be accepted by the FCC. The committee was called the National Television Systems Committee (NTSC). After lengthy struggles and one misstep (a promptly aborted standard using a color wheel), the Committee agreed upon the compatible color system we have today. It is often called just NTSC after the committee that devised it. </p>

<p>Japan adopted the US standard for color but Europe rejected it, opting for their own versions of color. Both Japan and Europe entered color television and made sets from within their own regions. They later expanded the distribution of their products to all regions of the world. RCA did not. Sarnoff failed to dominate color television around the world though many of RCA's patents were used in all color system.</p>

<p>Fast Forward to 1964 Japan </p>

<p>Japan had only one national broadcaster after the war - Japan Broadcasting Corporation, or NHK. They remained a monopoly until deregulation allowed competition in the 70s. The revenue to operate the NHK network came from (and still does) a monthly levy on every television set in use in Japan. Huge revenues stream in with a small percentage (less than 1%) of it being dedicated by law to primary research. This research is done  in the world renowned NHK Science & Technical Research Laboratories in Tokyo. All television innovation for both professional and consumer products is developed there and with a cozy co-operative arrangement between the Japanese electronic manufacturers and NHK labs. The most significant innovation in television were developed from this co-operative. The NHK engineers are forced to retire at 55 years of age and are then employed until their retirement by one or the other of the large electronic manufacturers like Panasonic, Ekegami, Sony, Toshiba, etc. It is one of the most successful partnerships in the world which is paid for by the Japanese consumers of television programming by way of this program licensing fee paid every month for every set operating in Japan. </p>

<p>The Next Generation of Television-HDTV </p>

<p>NHK began work on the future of broadcasting in 1963.  The reasons for starting it have been obscured in folk lore. Some say NHK simply wanted to increase the enjoyment for their viewers. Others point out that NHK knew the day of their monopoly status in Japan would end with deregulation and technical quality could be used as a competitive barrier or advantage. Another view has it that a new world production standard was being first sought and Japan would particularly benefit from world co-productions. Some critics see a more sinister side to the initiative saying that Japan would focus all its resources to creating a new television era with a strategy of leaping ahead of everyone else so as to finally dominate global communications when image would be everything. All others around the world would have to compete with what Japan had in order to maintain their own national self-respect and Japan would then sell the rest of the world production and consumer HDTV equipment.</p>

<p>Some evidence for accepting this later view surfaced in the latter part of the 80s. But international domination of this sort would have been Japan's worst nightmare as they didn't have enough international good will to carry such a heavy political responsibility.</p>

<p>Following on the heels of the first satellite transmission of HDTV in Japan (in the early 1980s using their MUSE decoding scheme) the American Electronics Association reacted in the U.S. saying that HDTV would be the most powerful driver of advanced electronics in the world. If Japan had a dominant role in such a powerful communications system they could dominate other fields. Uncle Sam fretted openly about the defense card and the Bush administration told the FCC to get America in the lead, or else. </p>

<p>But I am ahead of myself. The purpose of this article is to give you a fundamental understanding of why billions of dollars have been spent on HDTV and why.</p>

<p>Understanding the Subtleties of HDTV</p>

<p>Following exhaustive tests in the early 70s NHK decided that the next generation of television must increase the sense of reality (therefore greater engagement in the program for the viewer) as the major feature. HDTV is not just a clearer picture. It is about the size of the clear picture and the added involvement in the program which then occurs. Also the Japanese homes and viewing distance is scant. To have a television system that didn’t produce visual artifacts meant that larger sets could be acquired. </p>

<p>This heightened sense of realism gives to a viewer an almost three dimensional sense. Achieving the NHK objective a definition of the general parameters for the production equipment was made. Prior to digital the production standard would also define the HD receiver standard. Japan presented their parameters at an international meeting of television engineers in Algiers in 1981.<br />
 </p>

