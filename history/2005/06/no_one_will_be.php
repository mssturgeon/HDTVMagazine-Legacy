<p><br />
The HDTV movement began in 1963 from within Japan's huge public broadcaster, NHK (Japan Broadcasting Company). </p>

<p>NHK must, by Government decree, spend a small percentage (less than 1/2 of 1%) of their multi-billion dollar income for research and development in television for the public benefit. They do so in cooperation with the electronic manufacturers of Japan. Ventures from this cooperation become commercial products from the manufacturers. <br />
HDTV bounced on to the world stage in 1981 with demonstrations given by NHK in the US and Europe. The goal of the early movement was to achieve an international agreement on a single worldwide production standard. The first proposed HDTV production standard-with parameters of 1125 scanning lines and 60 fields-came out of the Japanese research. </p>

<p>The parameters were set so as to make conversions to all existing analog transmission standards around the world as easy as possible. Europe and other 50 Hz regions were slightly disadvantaged with these parameters due to the 60 Hz field rates in the Japanese proposals. The Japanese proposal was endorsed by the U.S. The hope of a single standard was sunk in 1987, the result of protective politics in Europe. Europe offered their own standard as the single standard and the world fell into two camps-one with 1125/60 parameters and the other 1250/50. That sapped much of the strength from the movement. <br />
First transmission demonstration for HDTV appeared in 1985. This solution from Japan (MUSE) required 8.3 MHz from a satellite and suffered a softening of the image when in motion. </p>

<p>Europe stepped up their research and development to reach parity with Japan and delivered their own HDTV satellite broadcasting system two years later (HD-MAC). Both systems, while digital in much of their internal operations, were in the end analog and fell on hard times when the whole world decided it must go digital. The Japanese were determined to be first every step of the way and introduced MUSE HDTV as a commercial product in 1991. Eight hours a day experimental broadcasting fed a very weak market. The MUSE system has taken considerable heat and been declared obsolete before it was ever launched. Still, this analog system is slated to run until the year 2007 when a new satellite will be launched with increased capacity. At that time a conversion to all digital will be made. This left the HDTV movement gasping for air as still another apparent misstep showed up on the ledger for this unlucky technology. </p>

<p>The US was on the verge of industrial paranoia in the late '80s and early '90s. Worry that Japan and Europe were sure to gain a technical advantage with HDTV swept through Washington. President George Bush responded by ordering his FCC Chairman, Al Sikes, to get America in the lead.  Broadcasters had by 1987 asked the FCC to look at the HDTV question, freeze spectrum allocations in the broadcast bands, cause a HDTV transmission system to be created and tested, and then allocate spectrum to broadcast it if more was needed. Prior to assuming duties as Chairman of the FCC, Sikes had been head of the NTIA, an advisory organization to the White House on telecommunications policy. He was widely regarded, knowledgeable, and had extraordinary influence. He was our leader and the HDTV movement followed every word. But the word was transferred out when the Clinton Administration was on the verge of coming in. Sikes dove for cover within the executive offices of The Hearst Corporation in NYC and a relative unknown, Reed Hundt, assumed the chairman's office. Hundt had little reputation as a technology expert and the FCC lead was left to the influence coming from outside its office. HDTV was no longer the thing to save American face, that being replaced by the internet. </p>

<p>The Grand Alliance system can do more than encode and decode HDTV. Within a 6 MHz spectrum a station could choose lesser resolution and allocate bits in the 6 MHz spectrum for 4 or more additional programs in a lower quality (equal to studio grade NTSC). Additionally there is a data-only capacity to the GA system. This is designed in for still-to-be-found ancillary data services, such as stock market information delivered to a TV set or PC.  </p>

<p>This flexibility has raised concern that HDTV will be abandoned in favor of more program services, but no solid business vision has emerged on how to do that. More importantly, Congress has smelled money in the water and auctioning spectrum that is used for non-traditional public services has become a popular idea. This threat of auction of spectrum has made the broadcasters to say, oh, yes, we always thought HDTV was the primary purpose for the new channel. "Get the spectrum free and worry later what to do with it," has become the underlying strategy for today. <br />
  <br />
HDTVs Arrival?<br />
  <br />
For HDTV to come to the home a complete revolution in television technology will have to be completed. Nothing remains the same. The technology will inevitably induce a revolution in the business of television itself with a probable change in powers. No one can be left unaffected-not the program producers, the signal providers, the transmission providers, the advertisers, the manufacturers, the retailers, and certainly not the end users. Each will need to adapt to the new to avoid obsolescence. It is a system designer's dream. The great danger is that the movement gets off to a half hearted commercial start and is dragged back by the inertia of the old. Then it would pause in mid air and careers and investments would come crashing down. It is a difficult task, full of risk unless there is an orchestrated effort where the manufacturers, the program suppliers, the signal's providers, the alternate media groups, and the end users all play the same tune together? </p>

<p>Dale Cripps<br />
HDTV Magazine</p>
