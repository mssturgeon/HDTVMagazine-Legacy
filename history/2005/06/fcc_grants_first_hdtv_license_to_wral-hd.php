<p><em>This historic press release announced the very first HDTV license granted by the FCC.</em><br />
<strong>FCC Grants First HDTV License to WRAL-HD </strong></p>

<p>Raleigh, NC, June 19, 1996 The Federal Communications Commission today granted the nation's first experimental high definition television ( HDTV) license to WRAL-TV, Channel 5 Raleigh, NC. The new experimental station, with the call sign of "WRAL-HD", will operate on channel 32. James F. Goodmon, President and Chief Executive Officer of WRAL's parent company, Capitol Broadcasting Co., Inc., said Capitol is building the station because HDTV is critical to the future of free television. "Broadcaster," he said, "must move forward to effectively compete with pay services of cable and satellite. We're excited about the new technology and hope to begin testing in the Raleigh-Durham area by the end of the year."</p>

<p>The engineering and technology staffs at the CBS television network are serving as consultant to the project. CBS spokesman Joseph A. Flaherty, Senior Vice President, Technology, said the network "is fully supportive of this important initiative in digital TV broadcasting and will cooperate with WRAL-TV to ensure success of the experiment." a Harris Sigma transmitter system will deliver the HDTV signal to a special Andrew UHF antenna. The antenna, mounted at the 1750-foot level on Capitol's existing tower, will deliver 100 kilowatts of power to the Raleigh, Durham, Fayetteville, Chapel Hill areas. </p>

<p>Capitol's HDTV Project Manager John L. Greene said Harris and Andrew were selected because of their vast experience with advanced television technology. Harris and Andrew were involved with early Advanced Television (ATV) test facility in Charlotte. Harris has been involved in HDTV from the beginning (1990) when it built the test bed for the ATV test center in Alexandria, Virginia. Andrew beamed the first over-the-air demonstration of ATV to the 1993 NAB convention. Other applications for experimental licenses (including two in the Washington, DC area) have been filed with the FCC but the Raleigh license is the first to be granted. "This is not a strictly competitive venture." said Goodmon, "We like to offer our viewer the latest technology and the best possible product. We plan to work with the model station project in Washington, with the Grand Alliance folks, and with the Public Broadcasting System in the development of what we believe is the best television delivery system in the world."</p>

<p>FCC Chairman Reed Hundt had earlier applauded the initiative of WRAL-TV in applying for a license. "It will only be through efforts of technology leaders like WRAL-TV that the potential benefits of digital television in today's highly competitive marketplace can be fully tested and demonstrated to the American people," he said.</p>

<p>HDTV is a new technology for television that will deliver a sharper, wide-screen digital picture with much improved color clarity and CD-quality, Dolby surround-sound. The new format is slated to replace existing television systems over several years as determined by congress and the FCC. Development of the system and adoption of a standard for the medium has taken more than ten years. <br />
