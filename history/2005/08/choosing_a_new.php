<p>Had we depended upon surveys, then the famous one done by MIT in '89 comparing HD and NTSC would have led us back to 480i and one added channel of audio...nothing more.  <a href="http://www.hdtvmagazine.com/history/2005/06/during_the_earl.php">http://www.hdtvmagazine.com/history/2005/06/during_the_earl.php</a></p>

<p>But we didn't rely upon those surveys nor did we cower from the admonitions from their powerful supporters. We forged ahead into new territory. Instead of a dead-end with NTSC we have HDTV with headroom to grow.</p>

<p>I take this page from HDTV's history and apply it to the Blu-Ray vs. HD-DVD controversy. With HDTV we moved to a new platform (digital) which allowed all of the potential power of present day technology to be applied to it. Had we not taken that leap, we would be hanging on to the last of analog.</p>

<p>It was a perilous leap, no question. But as long as the performance of the new was superior to the old the greater risk would have been in not making that leap. The smart decision was to embrace the new and jettison the old. If that came with a cost...ask yourself what technical progress didn't come with a price?  We bore the price for HDTV as we did for computers, cars over horses, and now new automated homes. Every life-enhancing convenience has had its price along with its reward.  </p>

<p>To endorse HD-DVD is to leap to the end of the road. Where can it take us? With Blu-ray a new force is born.  Who can foretell where that will take us? It hasn't been explored yet. HD-DVS is the last struggle of a dying format. As with most living things a format goes through a brief period of reanimation at the end of its life when its dependants struggle to avoid impending doom. In this classic case you see HD-DVD suddenly "discovering" more capacity with supporters beating their breast about it. Its rightful claim for backwards compatibility gives it a ring of authority--something they exploit. But the format is done. The new kid leaves it at the starting gate.  </p>

<p>There were reasons given in the 80s for why we should remain with the old analog TV system. Tens of millions of dollars were spent in selling the ideas of its backers. I can recall several proposals for "improvements" to NTSC that would provide at least ghost canceling and 16:9 aspect ratio...and backwards compatibility...even some resolution enhancements. Compatibility was looked upon by the brighter side not as an asset but rather as a foot stuck in cement. To get to the true HDTV we have today we needed a new departure, and we took it. In light of the rapid technical advances of today we had to leap ahead if real progress was to be realized. </p>

<p>For those who fear intolerance form two incompatible formats on the same shelves...all I can point you to is television itself and note that every retailer carries two formats during the transition period. That will be the case only for awhile--a very short while when measured against the lifespan of the new format. </p>

<p>Dale</p>
