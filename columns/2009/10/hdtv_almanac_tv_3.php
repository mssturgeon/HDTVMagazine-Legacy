				<p><img src="http://hdtvprofessor.com/HDTVAlmanac/FloTV.png" alt="The Personal Television from FLO TV lets you watch streaming television programming." /></p>
	<p>FLO TV announced the <strong>FLO TV Personal Television</strong> last week, a $249 pocket device that receives streaming television content over the air. Instead of using terrestrial broadcast television stations, it uses its <strong>own network of transmitters</strong>. Until now, FLO TV has been available on <strong>select AT&#038;T and Verizon mobile phones</strong>, but the Personal Television is the company&#8217;s first attempt at a<strong> stand-alone television </strong>device. The FLO TV programming comes from CBS, CBS College Sports, CBS News, CNBC, Comedy Central, ESPN, ESPNews, FOX, FOX News, FOX Sports, MSNBC, MTV, NBC2Go, NBC, NBC News, NBC Sports and Nickelodeon. (<strong>Not all channels </strong>are available on all platforms.) </p>
	<p>The Personal Television has a <strong>3.5&#8243; LCD display</strong>, and you can watch up to five hours of content on<strong> a single charge</strong>. (It offers about 300 hours of standby time.) Subscriptions for the service run about $9  a month.</p>
	<p>The advantage of the service is that it should give you <strong>better coverage </strong>than you might get with local television broadcasts. And the subscription fee is certainly reasonable. I think that the Personal Television <strong>may not succeed </strong>at promoting the FLO TV service, however, as it still is tethered to the <strong>old programming schedule </strong>model. You have a choice of channels, but you can only watch <strong>what they&#8217;re broadcasting </strong>at that time. For news and weather that are on<strong> a fairly tight loop</strong>, that&#8217;s not too much of a problem, but I think consumers are becoming used to picking <strong>what </strong>they want to watch as well as <strong>when </strong>they will watch it. Mobile broadband Internet services are likely to have<strong> more traction </strong>for mobile video programming as the consumer <strong>will get to choose </strong>what they want to watch. Yes, this will require greater bandwidth and at least in the short term <strong>will cost more </strong>than the FLO TV solution, but in time, I expect that&#8217;s the model that <strong>will eventually win</strong>.</p>
