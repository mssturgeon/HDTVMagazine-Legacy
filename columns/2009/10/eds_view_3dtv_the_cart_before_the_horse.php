<p>Here again, the US consumer electronics industry as well as broadcasters find themselves and their consumers in a technical/marketing quandary because of lack of foresight, planning and just plain incompetence. This time it may really hurt. It didn't take any genius to foresee the possibilities of in-home 3D years ago, particularly in light of the economic success of digital 3D movies over the past three years. Since movies derive more than 55% (and climbing) of their revenues from in-home distribution channels (disc, VOD, PPV etc.), it doesn't take much prescience to predict 3DTV possibilities. Did the salient organizations react? Yes. Being unencumbered by the thought process, their reaction was something like a bunch of night drunks during a bar raid. </p>

<p>A couple of years ago a few manufactures started marketing "3D ready" rear projection units with no particular performance standards or technology in mind. Then about a year and a half ago SMPTE decided to have a gathering of interested industry representatives to discuss the possibility of having a meeting to further discuss the practicality of establishing a "3D Home Master" standard. Then CEA finally woke up and started to have preliminary meetings to assess the possibility of a technical 3D standard of some type. ATSC is halfheartedly doing somewhat the same thing on the broadcast side as is the SCTE on the Cable end.</p>

<p>This past summer with all the publicity, popularity and economic success surrounding a rash of 3D movies, big boys-Sony and Panasonic-and a few lesser players announced ambitious plans to market new 3D models based on what appears to be proprietary "standards" and undefined signal sources. One must assume, of course, they are incompatible. This, coupled with all the prior mentioned thousands of sold "3D ready" units, presents a very interesting dilemma. How does the SMPTE (i.e. "Hollywood") establish a "3D Home Master" specification that does not compromise the critical production elements required for quality 3D? The answer is - they don't. The SMPTE standard will be driven by whatever Sony and Panasonic says it is, they both being major content, software and hardware suppliers to the movie industry. The process will be further constipated by the fact that Sony and Panasonic seldom agree on anything (by design). So, next year, here we are again, with another format fight, compromised performance and a potential lucrative market stymied by a commercial thought process that continuously shoots itself in both feet. I hope I'm wrong; but right now the cart is squarely in front of the horse.</p>

