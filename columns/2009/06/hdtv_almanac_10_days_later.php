				<p>Okay, I&#8217;ll grudgingly give the FCC some <strong>credit where credit is due</strong>; I&#8217;m not sure that the end of analog television broadcasts on June 12 was the<strong> complete train wreck</strong> that I expected it to be. But I also give FCC Acting Chairman Michael Copps credit for being honest about the fact that it was <strong>not all cookies and cream</strong>. “This was never going to be an easy transition, as I have said many times. It appears to have worked well for the majority of over-the-air viewers, but for those who are experiencing a less-satisfactory outcome, we are committed to staying on the job to help.”</p>
	<p>Clearly, many people experienced a &#8220;<strong>less-satisfactory outcome</strong>.&#8221; By the FCC&#8217;s own tally, their toll-free support line handled <strong>more than 900,000 </strong>phone calls in the week from June 8 to June 14. <strong>More than a third</strong> of those were received on Friday, June 12, which was the day most stations cut off their analog broadcasts for good. Note that this only includes the calls <strong>to the FCC hotline</strong>. The calls to the <strong>hundreds of local stations </strong>across the country could easily add several hundred thousand more calls to this total.</p>
	<p>According to the FCC, <strong>28% of the calls </strong>requested help with installing or configuring digital converter boxes that allow TV sets with only analog tuners to receive the digitl TV signals. Another 49% &#8212; <strong>just about half of the total </strong>&#8211; called because they were having reception problems. And this just <strong>what I expected</strong>.</p>
	<p>Part of the problem may have been that people with digital tuners &#8212; either in a converter box or in a TV set &#8212; did not know to<strong> rescan after the transition</strong>. As part of the switch over, stations in many markets changed their broadcast frequency. (Note that the broadcast frequency is not directly related to <strong>the &#8220;channel&#8221; number </strong>that has been assigned to a station.)</p>
	<p>Even after rescanning, however, many people <strong>continued to have difficulties</strong>. Right here in Philadelphia, many people could not receive<strong> Channel 6</strong>, the local ABC affiliate. Before the transition, the digital broadcasts for this station were in <strong>the UHF range</strong>, but after the switch the station moved the signal to its assigned frequency in <strong>the VHF range</strong>. Many people in Philadelphia couldn&#8217;t receive the signal, and the FCC has since granted permission for <strong>a temporary power boost </strong>to see if that helps resolve the problems. Part of the problem, however, is that many people have been sold<strong> &#8220;digital&#8221; TV antennas </strong>that actually are no different than that required for an analog TV, except that many of these new antennas are designed to <strong>only receive signals in the UHF range</strong>. Some people mistakenly thought that none of the new digital broadcasts would be in the VHF range, but that&#8217;s <strong>not the case</strong>. In many major markets, some stations <strong>are still broadcasting </strong>in the VHF range. To receive these signals, you need at least<strong> a set of &#8220;rabbit ears&#8221;</strong>: the kind of antenna with two rods (as opposed to must UHF antennas which are<strong> just a wire loop</strong>). If you go to <a href="http://www.antennaweb.org">www.antennaweb.org</a>, you can find a listing of the television stations that you can expect to receive at your location, and which ones are <strong>VHF or UHF</strong>.</p>
	<p>It will take a bit more time to sort all this out, and I expect to see <strong>a surge in new cable and satellite subcriptions </strong>for June as people give up with trying to resolve problems with the free broadcasts. The transition wasn&#8217;t as bad as I expected, but it wasn&#8217;t smooth either. About the best I can say is that I&#8217;m very glad <strong>it&#8217;s behind us</strong>. Now the various segments of the <strong>broadcast spectrum </strong>will be freed up, and we&#8217;ll start seeing some interesting new services become available, such as the <a href="http://www.flotv.com">FloTV mobile TV</a> service <strong>available on cell phones </strong>from AT&#038;T and Verizon.
</p>
