	<p>However, I expect that the content producers will have <strong>little choice </strong>but to work out some sort of a deal. We&#8217;ll assume for the moment that Comcast and Time Warner have <strong>the resources to create a system </strong>that will scale smoothly to meet demand. (According to The Bridge, the two companies had more than<strong> 37 million subscribers</strong>, which is a bit of a leap from the 5,000 trial participants.) I love watching Hulu, but I don&#8217;t love <strong>the too-frequent pauses </strong>while the buffer fills. (And I have a <strong>high-speed broadband connection</strong>, so I don&#8217;t think it&#8217;s my end that&#8217;s the problem.) Working it out so that <strong>high-definition streams </strong>can be fed to millions of viewers at the same time will require <strong>some serious hardware </strong>to do the heavy lifting on this project. But hardware is easy compared to <strong>negotiating licenses </strong>with all the different networks.</p>
	<p>But where is this headed? As I see it, the industry is eventually going to <strong>have to split </strong>into focusing either on the hardware or the software. By this, I mean that there are<strong> two entirely different businesses </strong>here. The first is in the business of building <strong>high speed broadband networks </strong>and delivering them to the home. The second is the business of <strong>obtaining the rights</strong> to the content that people want to see, and then making them available on the Web. These two sides <strong>were created together </strong>when cable TV was invented; the same company had to <strong>lay the wire </strong>so that it could sell its content service. In fact, we needed to award <strong>sanctioned monopolies </strong>to cable companies in order to make it affordable for them to <strong>wire a whole community</strong>.</p>
	<p>That has all changed now, and I fully expect these functions to <strong>split eventually</strong>. One service will create and maintain the <strong>physical infrastructure</strong>, and another will aggregate and <strong>deliver the content</strong>. Netflix is <strong>not in the broadband business</strong>; the cable and phone companies are already doing that just fine. Initially, cable and satellite companies may <strong>have an advantage </strong>at rolling out television services on the Internet because they <strong>already have experience in negotiation </strong>with the content producers. But over time, I see that the goals of these two businesses <strong>may not mesh well</strong>, leading some of these companies to split the services<strong> into two entities</strong>.</p>
	<p>So will they sell <strong>the pipes or the water</strong>? It will be interesting to see how it works out.
</p>
