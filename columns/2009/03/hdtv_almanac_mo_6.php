				<p>Nielsen has posted <a href="http://blog.nielsen.com/nielsenwire/media_entertainment/digital-tv-readiness-improves-in-march/">their latest estimate </a>of how many U.S. households <strong>remain unprepared </strong>for the end of analog TV broadcasts in June. With just over <strong>two months left to go</strong>, the number of households has been <strong>cut nearly in half </strong>from December to now, leaving only <strong>4.1 million homes </strong>still not ready according to Nielsen; this is <strong>3.6% of the national total</strong>. That represents more than a<strong> million homes per month </strong>have gone from unprepared to at least partially prepared since December.</p>
	<p>I&#8217;m now ready to say that <strong>I was wrong</strong>, at least in part, if Nielsen&#8217;s numbers are accurate. One of <strong>the most startling figures </strong>is that the population segment showing the most improvement was <strong>the &#8220;Over 55&#8243; portion</strong>. They&#8217;ve gone from 5.2% unprepared in December to<strong> just 2.0%</strong> in March. I&#8217;ve been particularly <strong>concerned about the elderly </strong>making the transition smoothly, and it would appear that the situation is <strong>better than I expected</strong>. (It&#8217;s not clear whether the Nielsen numbers include those residents of <strong>elderly group homes </strong>that do not provide cable service; this could amount to a sizable number.) And I thought that we would <strong>not see a lot of change </strong>between February and June, which is why<strong> Congress delayed </strong>the transition. The trajectory of the improvement is definitely <strong>flattening out</strong>, so we may not see as much change in the next two months as we&#8217;ve seen in the last two, but the situation is <strong>still improving</strong>.</p>
	<p>On the other hand, I continue to be concerned about the <strong>low-income population</strong>. According to Nielsen&#8217;s numbers, Hispanic households have only gone from 11.5% unprepared in December to <strong>6.1% unprepared </strong>in March. That&#8217;s a big percentage drop, but the<strong> remainder is much higher </strong>than the national average. And for African American households, the drop has been from <strong>10.8% to 6.6%</strong>. I expect that the rate of change for these two segments is <strong>likely to go flat</strong> over the next two months, and these people will be <strong>disproportionately unprepared </strong>for the end of analog broadcasts. I expect that there is also a correlation between <strong>income level and the unprepared portion</strong> of these groups, though Nielsen doesn&#8217;t report on this factor. While I don&#8217;t believe that having free television broadcasts is <strong>a fundamental right </strong>of U.S. citizens, I do believe that television provides an <strong>important source of news and information</strong>, and so it is in society&#8217;s interest as a whole to do what we can to see that these people <strong>aren&#8217;t left out </strong>by the transition.
