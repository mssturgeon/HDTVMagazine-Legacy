d to be extensible, say to ˜15Mb/s, then at least two full 4:2:2 HD programs plus one legacy (MPEG-2) program could be accommodated in the allocated 19 Mb/s digital channel. Wouldn't that be a hoot! However, legacy HDTV receivers would require a separate M/H box to select and decode the M/H sub-channel multiplex. (So, what's another box? You always wanted something to stick into that extra HDMI input. Right?) No doubt, as soon as the M/H Standard is finally blessed, all ATSC receivers will include built-in M/H capability. <p>Hopefully, ATSC will have the foresight to design bandwidth extensibility in the M/H standard. This will give broadcasters further market leverage by offering viewers true Blu-ray quality programming. <p>- Ed</p>
