	<p>AmeriCorps is a &#8220;Peace Corps&#8221; type government program that enlists <strong>volunteers between 18 and 24 </strong>to help with domestic programs. The members of this residential program are based in <strong>five campuses </strong>spread across the country. Members make a <strong>ten-month commitment</strong>, and receive training before being sent out in teams of 10 to 12 members to help with programs around the U.S.</p>
	<p>Teams of AmeriCorps members will work with <strong>FCC area coordinators </strong>to &#8220;to visit homes where individuals need help to connect their antennas and analog televisions to digital converter boxes, help consumers apply for the $40 converter box coupons, make presentations at community events, serve in walk-in DTV help centers and otherwise spread the word.&#8221; According to the press release, <strong>Denver is targeted </strong>for the initial roll-out of this collaborative effort between the FCC and AmeriCorps, because several of the Denver stations are slated to <strong>end their analog broadcasts early</strong>, in April.</p>
	<p>This is clearly a good idea, but the timing is <strong>weak at best</strong>. We are now nearly two months <strong>past the original deadline</strong>, and yet the FCC is only now thinking about using AmeriCorps? The press release indicates that the FCC intends to <strong>mobilize other groups</strong>, such as the International Association of Fire Chiefs, but why did they <strong>wait until 10 weeks before the cut-off </strong>to start organizing these groups? And the press release does not indicate <strong>how many teams </strong>of AmeriCorps members will be involved in these 49 different markets, but <strong>how many housecalls </strong>can one person make in a day? I expect that 10 would be an ambitious goal. If half of the <strong>4 million unprepared households </strong>are in these target markets, and we assume that these groups start today, they would have <strong>about 50 days </strong>to reach 2 million households. It would take at least 4,000 volunteers to manage that. The program does apparently have <strong>about 40,000 members</strong>, but presumably most are <strong>already committed </strong>to other programs.</p>
	<p>I <strong>hope that this works</strong>, and that other state and local community government and private organizations will be able to <strong>enlist additional volunteers </strong>to help others with the transition, but it remains an enormous task. Waiting until<strong> the 11th hour </strong>like this does not bode well for success.
</p>
