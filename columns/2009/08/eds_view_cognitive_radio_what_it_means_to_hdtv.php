				<p>"Cognitive Radio." What a strange, oblique name for one of the greatest technology advances in telecommunications since Ma Bell decided that ones and zeros made better use of our precious spectrum (over both wired and wireless media) than wavy, wriggly voltage changes. Clearly, the academics who coined the name failed PR101. Why not call it "Smart Radio" - because that's what it is - really smart radio. So, I'll compromise in this wheeze on the subject by cowardly retreating into the technical acronym morass - henceforth tagging "Cognitive Radio" as "COR" and its TV version as "COTV."</p>

<p>The precise definition of COR continues to evolve, but in its most basic sense has been developing in the last decade as a dynamic spectrum selection technology applied to two-way data communications. The idea is to cause the radio to automatically and dynamically select those transmission and reception bands and frequencies that achieve optimum communications objectives. Those objectives could include (obviously) optimizing signal-to-noise (S/N) ratio, minimizing interference with other RF signals and a combination of both. Therefore, the COR must continuously "sniff" through the various RF bands over which it is designed to operate and instantaneously select the discrete frequency that optimizes signal throughput without compromising defined quality-of-service (QOS) levels (i.e. loss or corruption of data that degrades functionality).</p>

<p>As expected, the Defense Department has an immense strategic interest in COR, therefore, significant R&amp;D is being accomplished through DARPA grants. Obviously, COR technology is now being deployed in several military applications. The FCC also has shown a profound interest in COR as a solution to the effective utilization of DTV "white space" (adjacent TV channels) to extend broadband internet access. Consequently, several wireless service providers such as ATT, Verizon, Microsoft etc. and their hardware associates are salivating over the availability of this spectrum and the viability of its use without interfering with DTV. As a result COR technology is presently being tested with mobile and stationary ("hot spot") unlicensed Wi-Fi devices utilizing the broadcast television spectrum. These devices dynamically sample the TV spectrum looking for "clean" frequencies on which to operate. To narrow the search, some of these devices also use GPS receivers along with TV station location look-up tables. In this manner the COR does not even try to search frequencies where there are known, active TV stations. This makes the working frequency selection process much faster and more accurate.</p>

<p>Like most other "game changing" and thus commercially disruptive innovations, COR would not be possible without some "enabling" technology. In COR's case one key enabling technology is the so-called "software radio." In its purest form, software radio is simply the application of microcomputer technology to perform all the functions necessary to make a radio work. In a pure software radio, there are essentially two computing blocks each consisting of a central procession unit (CPU) along with associated memory. One computing block runs the RF functions including tuning and modulation/demodulation; the other runs all the encoding/decoding and application functions. Therefore, all the salient radio functionality is in the form of software algorithms. Dynamically changing these algorithms in an adaptive manner allows COR itself to work. The diagram below illustrates the software radio philosophy.</p>

<p><img src="/images/articles/software-radio.gif" alt="Software Radio" /></p>

<p>Another critical enabling technology employed by COR is the MIMO (Multiple Input Multiple Output) antenna system. MIMO antennas may be best described as very smart diversity antennas that dynamically change element characteristics to optimize performance, i.e. S/N ratio. These antennas are now being used in 4G cell devices and have been employed in critical DOD applications for several years.</p>

<p>So, what's this all mean for HDTV, you ask with an impatient laugh. Well, so far, most of the COR R&amp;D and applications have focused on the so-called "physical" or actual transmission/reception technique end of the network tasks. The big news is that the COR philosophy is now being applied to all of the network functions and protocols. Without getting into the arcane terminology of the "network stack," this simply means that the COR can dynamically handle various modulation schemes, (COFDM, VSB, QAM, QPSK, DPSK etc.), network protocols (IP, Wi-Fi, WiMax, ATSC, DVB etc.) along with their associated compression codec's (MPEG2, AVC, VC-1 etc.). Obviously, various applications protocols (API's) and security schemes can be managed with the same philosophy. </p>

<p>With that in mind, the "network" environment becomes truly democratic and highly competitive. The user selects an HD program or service (not a "channel number") and the COTV automatically "finds" and maintains the best throughput quality available, seamlessly skipping across bands, frequencies and network boundaries to maintain that quality. Many of us now have a crude, manual version of COTV (we manually supply the "cognitive" part), being connected to several networks: broadband, cable, off-air, satellite, disc, server, etc.) Sometimes some or all of these terminate at the TV receiver itself and/or are connected to the TV display via various boxes. So, if we know the program is not available on one network or service at the quality we desire, we can certainly change it, not seamlessly or quickly, but it works. </p>

<p>Clearly, the commercial implications of COR and COTV are profound. "Walled gardens" tumble down, "network neutrality" becomes a reality, QOS becomes the driver and the users communicate directly with the service sources. </p>

<p>What hath God wrought?</p>

