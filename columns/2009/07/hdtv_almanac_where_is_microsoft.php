				<p>An announcement last week that Macrovision has <strong>changed it&#8217;s name to &#8220;Rovi&#8221; </strong>(which was cleverly extracted from the middle of its old name) got me to thinking. According to a <a href="http://www.twice.com/article/315486-Macrovision_Becomes_Rovi_.php">story in TWICE</a>, the company is focusing on &#8220;a new <strong>multi-faceted integrated graphical user interface</strong>&#8221; that lets users find and view content from a variety of sources, including <strong>local storage, the Internet, and traditional broadcast services </strong>such as cable or over-the-air television. Rovi is building this system so that it can be incorporated into<strong> televisions and other consumer electronic devices</strong>.</p>
	<p>This is a great idea as I have <strong>not yet found </strong>an interface that really accomplishes all this well. Microsoft&#8217;s Media Center is intended to reside on a<strong> stand-alone computer </strong>which is supposed to work as the entertainment hub for your living room, but it has<strong> many shortcomings </strong>and is not particularly easy to use. I&#8217;ve used Hauppauge&#8217;s tuner and DVR software, but it&#8217;s <strong>a patchwork of separate applications </strong>that is not that user-friendly unless you come at it from a strong computing perspective. Our old (and now useless since we watch TV over the air) Panasonic analog DVR was pretty good at showing the recorded shows, but it was <strong>stuck in chronological order</strong>. I have seen demos of other interfaces &#8212; such as the Digeo Moxi &#8212; which have been pretty good, including <strong>ways to search for recorded content</strong>, but are still designed to reside in <strong>separate boxes</strong>.</p>
	<p>The answer really seems to be to create <strong>embedded systems in our televisions </strong>that can access all this content and make it easy for us to find it. Most of the manufacturers are starting to support Internet connectivity such as <strong>Yahoo! Widgets and Netflix streaming movies </strong>directly in their sets. But why isn&#8217;t Microsoft<strong> in the middle</strong> of creating these embedded systems? Yes, it can be argued that Apple seems to know more about <strong>designing a good user interface</strong>, but the company seems to prefer to control the entire system, including the <strong>hardware, software, and delivery service</strong>. And I don&#8217;t see Apple getting into the HDTV market in a big way <strong>any time soon</strong>.</p>
	<p>So that <strong>leaves Microsoft</strong>. The company puts a lot of effort into <a href="http://www.microsoft.com/windowsembedded/en-us/products/windowsce/default.mspx">embedded systems</a>, so it would seem that they would have sufficient expertise to come up with something that would work. True, the Media Center interface falls short on some counts, but <strong>it&#8217;s a start</strong>. Why don&#8217;t Samsung and LG and Sharp HDTVs boast about a &#8220;<strong>Microsoft Interface</strong>&#8221; inside?</p>
	<p>My best guess is that competition in the flat panel TV market remains <strong>dominated by minimizing price</strong>, and that Microsoft would probably want <strong>more money </strong>for their software than the current pricing would support. But I expect that we&#8217;ll be entering a period <strong>within the next year or two </strong>where prices will start to flatten out, and feature sets for flat panel HDTVs will become <strong>more or less identical</strong>. (This is what happened to <strong>the personal computer market </strong>five to ten years ago, and the HDTV market seems to be following<strong> a similar trajectory</strong>.) At that point, manufacturers will become<strong> hungry for differentiation</strong>, and a software giant like Microsoft would have the opportunity to<strong> establish the new standard</strong>. So I find it puzzling that they aren&#8217;t getting <strong>their foot in the door now</strong>. Could it be that Rovi will be <strong>the next Microsoft</strong>, using consumer electronics interfaces as their springboard, just as Microsoft did with <strong>the personal computer 28 years ago?</strong>
</p>
