				<p><img src="http://hdtvprofessor.com/images/T-patrol-s.jpg" alt="HDTV Truth Patrol" /></p>
	<p>Most of the Truth Patrol tips are<strong> sent in by readers</strong>, but this is one that I found myself, thanks to a lead from TWICE eNews Daily. They published a link to <a href="http://www.youtube.com/watch?v=I63Lq1UbHVM">a YouTube video</a> that was apparently <strong>created by Best Buy </strong>to train its staff about the Samsung &#8220;<strong>LED TVs</strong>&#8220;. As I and many others have pointed out (including the New York Times), <strong>the name is misleading </strong>because it implies that it&#8217;s a display technology <strong>different from LCD TVs</strong>. So it&#8217;s informative to see what Best Buy <strong>tells its employees </strong>to emphasize about these new sets.</p>
	<p>Here are <strong>the main points </strong>covered in the video: ultra thin, picture quality, eco-friendly, InfoLink Internet connection, and a soundbard. In the entire <strong>four minute video</strong>, the onscreen trainer says the word &#8220;LCD&#8221; <strong>exactly twice</strong>. And in both cases, the context is <strong>ambiguous at best</strong>.</p>
	<p>The first occurance comes<strong> near the end </strong>of the picture quality segment, as the trainer says &#8220;That&#8217;s going to give you <strong>the LED LCD at 120 Hz 3D effect</strong>.&#8221; Huh? First, it&#8217;s a lot of jargon to cram in one phrase, and no, this is <strong>not a 3D television</strong>. Yes, you can get a 3D impression from some images, but it&#8217;s not a<strong> stereoscopic 3D display</strong>. But let&#8217;s see what leads up to this statement. It comes after discussing the &#8220;<strong>Clear Panel Display</strong>&#8221; feature: &#8220;There&#8217;s no barrier between the LEDs and the front of the panel screen. That light will shine through a lot better.&#8221; <strong>No barrier </strong>between the LED and the front of the screen? So it must be the <strong>LEDs that are making the image</strong>, right? No, there is in fact a barrier; the <strong>LCD layer </strong>between the LED lights and the front of the screen are responsible for <strong>blocking the light </strong>so that you get an image. No blocking of the light, <strong>no picture</strong>.</p>
	<p><img src="http://hdtvprofessor.com/HDTVAlmanac/SamsungLED_BB_video.jpg" alt="This image from the Samsung LED training video shows how the Clear Panel design reflects light from the room, especially on a black screen." /></p>
	<p>And for the record, the clear panel design simply means that they didn&#8217;t put on <strong>an anti-reflective coating or film </strong>as a top layer. This layer would diffuse the light from the screen slightly and reduce sharpness a bit, but would also reduce <strong>the sharp reflections </strong>you see on the screen in the video.</p>
	<p>The other mention of &#8220;LCD&#8221; comes in the<strong> eco-friendly section</strong>, where the trainer states that &#8220;you&#8217;re going to use about 40% less energy than your traditional LCD TV.&#8221; Okay, they <strong>get partial credit </strong>for not being outright misleading by saying &#8220;with your LCD TV&#8221;, but adding the modifier &#8220;traditional&#8221; <strong>does not make it clear </strong>that the LED TV and the traditional TV are both LCDs. In fact, I expect that <strong>many people would infer </strong>from this statement that the LED TV was <strong>not an LCD</strong>.</p>
	<p>The bottom line is <strong>at no time </strong>does the trainer say that LED TVs are a new and improved form of <strong>LCD TV</strong>, or that they replace the traditional fluorescent backlight with LEDs. Most of <strong>the performance claims are credible</strong> (though a few stumbles like the 3D statement may <strong>raise a few eyebrows</strong>), but it is clear that the creators of this video <strong>did not want to emphasize </strong>that these are in fact LCD TVs. And apparently this is how Samsung and Best Buy want <strong>the floor staff </strong>to understand these TVs.</p>
	<p>Is this video misleading? I&#8217;ll leave it to you to <strong>decide for yourself</strong> after you watch the video. These Samsung TVs have some <strong>real performance benefits </strong>to offer, but I wish these could be marketed without making it sound like it&#8217;s <strong>some new technology </strong>that is not LCD. I don&#8217;t see how this benefits consumers, or <strong>in the long run</strong>, either Samsung or Best Buy.</p>
