				<p><img src="http://hdtvprofessor.com/images/HDTV%20BUSINESS%20CONFERENCE-s.jpg" alt="Alfred Poor at the HDTV Business Conference in Las Vegas" />Wow &#8212; <strong>where did this week go?</strong> I&#8217;ve been digging through all the information I picked up at CES in Las Vegas (plus catching up on all the work that accumulates when you&#8217;re away from your desk for a week). And I still haven&#8217;t given a summary of the <em>HDTV Business Conference </em>that was held on Wednesday, January 4, sponsored by <a href="http://www.insightmedia.info">Insight Media </a>and Elliot Schlam Associates. It was an <strong>all-day affair</strong>, running from 8 AM to 7 PM, and gave me a chance to hear from and exchange ideas with executives from all branches of the <strong>HDTV industry</strong>.</p>
	<p>Rather than give a blow-by-blow summary, let me hit a few of the <strong>high points </strong>and major take-aways from the day. Some of these reinforce some themes that are already running through a number of my posts here, and others are <strong>new insights</strong>.</p>
	<p>1.<strong> IPTV is a force to be reckoned with</strong>. Sending video entertainment content as packetized data is a good thing, but it means different things to different people. Some see it as a method for content distribution where the network broadcasters are replaced by a systems of servers. One important byproduct of this is that you don&#8217;t need to send all content to all destinations all the time (which is what cable, satellite, and terrestrial broadcast do now). By sending only the requested programming, an enormous amount of <strong>bandwidth is conserved</strong>, possibly for other uses. Other people see IPTV as a way to distribute content within your home using wired and wireless networking. This means that you can have all your content arrive at one central point (computer geeks might call it a &#8220;server&#8221;) and then you can enjoy that content at various points around your home. The common thread in all these views is that you get to <strong>watch what you want, when you want, where you want</strong>. I think that there is a lot of <strong>pent-up demand </strong>for such freedom, and expect that we&#8217;ll see lots of new systems and hardware that delivers on this promise.</p>
	<p>2. &#8220;Convential wisdom&#8221; points out all the reasons that HDTV won&#8217;t take off. Many of those <strong>roadblocks </strong>are being <strong>obliterated</strong>. Bryan Burns, VP at ESPN, spoke eloquently about how his company and other content producers are making the big investments necessary to produce HD content. This year, <strong>ESPN </strong>alone will have <strong>7,000 hours</strong> of original HD programming. And advertisers are now starting to provide commercials in HD as well. And Robert Seidel, VP of CBS Television pointed out that the<strong> vast majority </strong>of broadcast and cable networks have chosen <strong>1080i </strong>over 720p as the HD signal (which makes 1080p displays the better choice for best image quality). He also said that traditional movie production on film cost $75, compared with $2.35 per minute for digital production. <strong>CBS </strong>produces <strong>40 hours a week </strong>of original HD programming. So there clearly is <strong>more than just football games and tours of coral reefs </strong>to watch on HD.</p>
	<p>3. The <strong>technology battle </strong>between different display technologies &#8212; LCD, plasma, and rear-projection &#8212; will continue <strong>without a clear winner </strong>for some time (aside from the fact that LCD had won already in sizes below 40&#8243;). Blue laser DVDs for HD content may resolve within a year or two, but it&#8217;s still too close to call. Joseph McQuire, President and CEO of Tweeter, pointed out that his <strong>customers don&#8217;t care about the technology</strong>; they care about the experience. (And that&#8217;s why I make my recommendations based on what the technology will mean to you as a viewer, and not based on what&#8217;s &#8220;cool&#8221; or more &#8220;advanced.&#8221;) And as Bruce Berkoff, Executive VP at LG.Philips, pointed out &#8220;Science loses to engineering; engineering loses to economics.&#8221; I take this to mean that <strong>&#8220;good enough&#8221;</strong> will beat <strong>&#8220;better&#8221;</strong> if the price is right, which is essentially what caused VHS to win out over BetaMax.</p>
	<p>Needless to say, there was a lot more covered in the 11 hours of this conference, but this hits the high points. If you have any <strong>questions </strong>about any of this, feel free to write me at <em>alfred@hdtvprovessor.com</em> and we can discuss them further.</p>
