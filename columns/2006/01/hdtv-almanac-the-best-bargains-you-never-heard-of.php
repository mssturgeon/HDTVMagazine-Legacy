	<p>In almost all the cases, <strong>the story was the same</strong>. They had LCD TVs or plasma TVs or both (or in a few rare cases, rear-projection display light engines) which they were ready to sell in the United States either under their <strong>own brand </strong>or as OEMs for <strong>some other brand</strong>. And all were looking for <strong>distribution</strong>.</p>
	<p>Having a product and a good price is <strong>not enough</strong>. You have to have a way to <strong>get it on the shelves </strong>of stores (or the Web pages of online retailers),  and given the fierce competition for space, this is not an easy task. A major retailer can&#8217;t carry all models of all brands, and many only have a limited number of choices in the traditional &#8220;<strong>good, better, best</strong>&#8221; marketing scheme. But occasionally, one of these newcomers will get an order, and you&#8217;ll see an <strong>unfamiliar brand </strong>appear in an ad or on a floor display.</p>
	<p>In general, <strong>don&#8217;t expect too much </strong>from these companies. What you see is likely to be what you get, so don&#8217;t count on great documentation or expert after-sales support from the manufacturer. (You should be able to expect this from the retailer who sold the set to you, however.) But these companies are <strong>hungry</strong>, and looking to feed off the scraps that fall off the table where <strong>the big guys </strong>are chowing down. And their deals tend to <strong>focus more on price </strong>than technology. One company sent me their <strong>wholesale price sheet</strong>; they&#8217;re asking <strong>$800 for a 32&#8243; LCD HDTV</strong>. Even with shipping costs added in, that can still result in a retail price that can <strong>grab the attention </strong>of buyers.</p>
	<p>So next time you see an <strong>amazing price </strong>for an HDTV from a brand that <strong>you don&#8217;t recognize</strong>, it&#8217;s probably from a small Asian company. Whether they will be able to take this <strong>initial foothold </strong>and step up to become a <strong>significant factor </strong>in the marketplace is unlikely, but there&#8217;s a real chance <strong>it could happen</strong>.
</p>
