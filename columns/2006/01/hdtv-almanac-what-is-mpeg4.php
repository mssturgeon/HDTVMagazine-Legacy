				<p>[And <strong>Why </strong>Should You Care?]</p>
	<p>In order to fit a typical <strong>90-minute movie </strong>on a single <strong>DVD </strong>(plus all those director&#8217;s commentaries, out-takes, deleted scenese, alternate endings, and other bonus material), the sound and images had to be <strong>compressed</strong>. <strong>MPEG2 </strong>is the name of the standard used to compress the video and audio on movie DVDs. Movie DVDs are in Standard Definition, and if you increase the resolution to either the <strong>720p or 1080i HD standards</strong>, MPEG2 compression is no longer sufficient to squeeze the data onto a standard DVD. Thus the battle of the <strong>higher-capacity, blue-laser DVD </strong>standards was born.</p>
	<p>In the time since the blue laser development efforts were launched, however, <strong>computer processing </strong>speed and power have continued to <strong>increase</strong>, even as prices continue to drop. (This weekend&#8217;s sales flyer from CompUSA advertises a desktop <strong>computer system </strong>that is actually <strong>free after rebates</strong>, provided that you sign up for a year&#8217;s service with AOL. <strong>A free computer with an Internet contract?</strong> Sounds like how they sell <strong>cell phones</strong>!) This increased power has made it practical to create more complex schemes for compressing video and audio.</p>
	<p>And so along comes <strong>MPEG4</strong>. Actually, it&#8217;s been around since 1998. The variety of MPEG4 that is of most interest at the moment, however, was known as <strong>Part 10</strong>. It&#8217;s also known by its acronym for <strong>Advanced Video Codec, or AVC</strong>. Just to confuse matters more, an identical standard has been adopted by ITU &#8212; International Telecommunication Union &#8212; named <strong>H.264</strong>. So if you see H.264 or MPEG4 AVC or MPEG4 Part 10, <strong>it&#8217;s all the same thing</strong>.</p>
	<p>So what is it? Well, it uses more <strong>flexible approaches </strong>in handling data for compression, with more effective motion compensation. The result is <strong>better image quality </strong>&#8211; especially on fast-moving images &#8212; at <strong>lower bit rates</strong>. In other words, it <strong>compresses the data more yet degrades the image less </strong>than MPEG2. By some accounts, it results in files <strong>half the size or smaller</strong> than MPEG2 compression.</p>
	<p>You&#8217;re going to start seeing MPEG4 AVC showing up <strong>more and more</strong>. DVD players will support it, digital camcorders will use it to store images, and digital video software will use it. Satellite providers of HD content are using it to make the most of their transmission bandwidth. It&#8217;s also one of the new technologies that could help put HD content on standard red-laser DVDs. How important will it be? It&#8217;s hard to tell at this point, but it&#8217;s definitely <strong>going to be significant </strong>so keep an eye out for it.
</p>
