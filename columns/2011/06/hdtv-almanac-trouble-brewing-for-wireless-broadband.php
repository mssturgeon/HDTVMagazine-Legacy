	<p>If you&#8217;re still with me, then let&#8217;s turn our attention to an outfit named <a href="http://www.lightsquared.com/">Lightsquared</a>. This company is building what it calls &#8220;the only national 4G-LTE open wireless broadband network that incorporates <strong>nationwide satellite coverage </strong>and offers the capacity to support the explosive demand generated by new consumer devices and mobile applications.&#8221; So far, so good. The company even was granted<strong> a conditional waiver </strong>by the FCC to allow the expansion of terrestrial use of the existing satellite radio spectrum. Companies including<strong> Best Buy, Cablevision, and Time Warner Cable </strong>apparently expressed interest in using Lightsquared&#8217;s system.</p>
	<p>And then <strong>the Law of Unintended Consequences </strong>reared its ugly head. Some people got the idea that Lightsquared&#8217;s signals might <strong>interfere with GPS devices</strong>. By April, the <a href="http://www.saveourgps.com">Coalition to Save Our GPS</a> represented more than 30,000 companies and was raising the alarm with the FCC and Congress. According to the group, &#8220;LightSquared plans to transmit ground-based radio signals that would be <strong>one billion or more times more powerful </strong>as received on earth than GPS&#8217;s low-powered satellite-based signals, potentially causing <strong>severe interference </strong>impacting millions of GPS receivers.&#8221;</p>
	<p>What&#8217;s the truth of the situation? Last week,<strong> results of tests </strong>by a working group were announced and they clearly showed that the system will cause <strong>significant problems </strong>with GPS operations, especially in urban areas. This could cause<strong> serious problems for aircraft </strong>which rely heavily on GPS for navigation systems.</p>
	<p>After pushing the FCC to<strong> rush the approval process</strong>, Lightsquared yesterday suddenly put on the brakes and asked for <strong>a two week delay </strong>in delivering the working group test report. It appears that the only solution will be to find <strong>other parts of the radio spectrum </strong>for the company to use, and radio spectrum is something that is in <strong>short supply </strong>these days.</p>
	<p>It is likely that this setback for Lightsquared will only increase the calls for access to the<strong> &#8220;unused&#8221; spectrum </strong>that is currently assigned to local television broadcast stations. It is possible that it will also encourage those who are questioning whether we <strong>need terrestrial broadcast of television at all</strong>. This is a subject that could have <strong>wide-reaching implications </strong>for many aspects of the consumer entertainment industry, and I&#8217;ll try to keep you <strong>posted on developments.</strong></p>
