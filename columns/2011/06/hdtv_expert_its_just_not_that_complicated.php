          <p>In a survey guaranteed not to bring smiles to the faces of TV manufacturers, 14,000 TV owners around the globe are downplaying the importance of Internet connectivity and 3D capability as they decide to purchase a new TV.</p>
<p>The DisplaySearch study, <a href="http://www.displaysearch.com/cps/rde/xchg/displaysearch/hs.xsl/110608_new_tv_features_not_strong_drivers_of_new_tv_purchases.asp" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.displaysearch.com']);">which is summarized here</a>, shows that 3D capability runs a distant third behind LED backlights and LAN or WiFi connections in order of importance, and that order of importance is remarkably consistent worldwide, except in Indonesia (3D was ranked #1, just ahead of LED backlights) and India (Internet connectivity and 3D functionality were close behind LED backlights).</p>
<p>In some countries, 3D was one of the weakest drivers of the TV replacement cycle, ranking near the bottom of the list in Germany, Japan, and the United Kingdom. LED backlighting was three times more important than 3D in the USA, and about twice as important as Internet connectivity. In urban China, 3D commanded about 25% of the interest of LED backlighting, while in Russia, the number was closer to 10%.</p>
<p>Indonesians are apparently contrarians. They ranked 3D capability as “most important” of all three features, edging out LED backlights by about 20%. In India, the three drivers were almost equally weighted, while in France, Internet connectivity outranked both LEDs and 3D.</p>
<p>This must be the season of studies! DisplaySearch’s parent company <a href="http://www.npd.com/press/releases/press_110608.html" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.npd.com']);">NPD also released a report</a> last week that stated 15 percent of U.S. consumers reported using a Blu-ray player in the prior six months to March 2011, up from 9 percent the prior year. By way of comparison, 57 percent of U.S consumers reported using a standard (red laser) DVD player in 2010, unchanged from 2009.</p>
<p>The NPD summary doesn’t break down how, exactly, the study group “used a Blu-ray player” in the six month period. Was it for streaming Netflix? Watching Hulu? Watching rented or purchased Blu-ray movies? We don’t know.</p>
<p>Other interesting tidbits: 49 percent of Sony PlayStation 3 owners are viewing Blu-ray movies on their consoles at least once a month, and Y-Y sales of Blu-ray players have increased 16%.</p>
<p>In their press release, NPD makes the case that sales of Blu-ray discs are starting to offset the decline in DVD sales. Keep in mind that NPD identified 116 million current physical disc buyers in the United States (not sure how they made that determination), down from 128 million in 2009 – a decline of about 10%. The 26 million Blu-ray buyers ‘offsetting’ that number amount to about 22% of the ‘current’ total.</p>
<p>The most interesting part of the study was summarized near the end, where it was reported 50% of consumers who intend to buy a Blu-ray player in the next six months said that they were primarily interested in using said players to view <em>“available subscription video download services”</em> (read: Netflix) as opposed to buying and/or renting Blu-ray movies.</p>
<p>If NPD had told us how respondents were using their Blu-ray players, we might have enough information to spot a trend. Alas, we can only assume that streaming is becoming a bigger driver of Blu-ray player sales than the discs themselves. 50% is a substantial number!</p>
<p>Even so, both surveys may tie together nicely. The lower levels of interest in Internet-connected TVs in the first survey may be due to the fact that late model TVs can add Internet connectivity a lot less expensively with a connected Blu-ray player.</p>
<p>Why replace a perfectly good 5- or 6-year-old LCD or plasma TV when you can ‘soup it up’ for another $125 – $150? That’s exactly what I did with my 2008-vintage Panasonic TH-42PZ80U 1080p plasma TV, installing a Panasonic DMP-BD85 connected Blu-ray player to replace an older red laser DVD player. I watch about 1-2 Blu-ray movies per month on it at most, and it streams Netflix quite nicely.</p>
<p>There’s no question we’re seeing a big change in how movies and TV shows are acquired and watched, and the playing field is tilting more towards streaming with every passing month. This change affects everyone from movie studios (some of which have been announcing sizable layoffs in recent weeks) to cable companies (Gen Y viewers are more likely to cut their cable ‘cords’ and rely on free OTA TV and broadband streaming) and retailers of packaged media (Wal-Mart and Best Buy have scaled back the size of their CD, DVD, and Blu-ray departments in the past year, and of course, Blockbuster went into bankruptcy last year and has been closing stores left and right).</p>
<p>In the meantime, I’m still waiting for that consumer survey that <span style="text-decoration: underline;">really</span> drills down to see (a) just how consumers are using Blu-ray players, (b) what they think of renting and purchasing packaged media in general, (c) if they are seriously considering ‘cutting the cord’ – or have cut it already, and (d) if and how they supplement streaming video and YouTube with free over-the-air digital TV and HDTV.</p>
<p>Of course, that survey would have to be conducted by an organization that is primarily interested in finding out the truth, and letting the facts point to a conclusion instead of jumping to one like the DEG did recently, or advancing an agenda as the CEA has been doing.</p>
<p>Sigh…</p>
