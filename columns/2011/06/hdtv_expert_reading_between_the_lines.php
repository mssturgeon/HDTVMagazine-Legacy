          <p>In a report released yesterday, the Consumer Electronics Association states that 10% of American households are either ‘very likely’ or ‘likely’ to cancel pay TV services this year, while an additional 14% are either ‘somewhat likely’ or ‘somewhat unlikely’ to cut the cord. 76% of those surveyed were in the ‘unlikely’ or ‘very unlikely’ group.</p>
<p>While those numbers should give some pay TV operators a little cause for concern – maybe as an incentive to offer simpler, basic channel packages at lower costs – the CEA report then veered off in another direction.</p>
<p>The report, <a href="http://www.cesweb.org/shared_files/ECD-TOC/CEACordCuttingAnalysis.pdf" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.cesweb.org']);">which you can read here</a>, states that only 8% of all U.S. households rely exclusively on over-the-air (OTA) TV reception, a number that was immediately disputed by the national Association of Broadcasters, according to a story in Multichannel News.</p>
<p>The MCN story quoted CEA president and CEO Gary Shapiro as saying, <em>“Contrary to the National Association of Broadcasters’ assertions, antenna sales are falling and cord-cutters are not shifting to over-the-air television but rather to the Internet. The only cord being cut these days is the one to the antenna.”</em></p>
<p>NAB’s spokesman Dennis Wharton was quick to respond. <em>“CEA has zero credibility when it comes to calculating over-the-air TV viewership. Knowledge Networks has stated that over-the-air exclusive homes are more than 14% and rising. We trust an unbiased research firm over a survey paid for by CEA,” </em>he replied.</p>
<p>Both my own experience and national news stories about cord-cutting have clearly shown that free, over-the-air TV is a key component of the cord-cutting experience. Why? Because it’s doggone difficult to watch sports and prime time TV shows in HDTV over a typical Internet connection, that’s why! And of course, OTA TV is free to viewers. So it is often combined with broadband access as part of the kiss-off to Comcast or Time Warner.</p>
<p>As it turns out, CEA has an obvious bias here. (Wow – this has been a bad week for objective research!) In a press release that came out earlier today, CEA announced that its Innovation Movement and Small Business Council would bring a ‘small business message’ to Capitol Hill.</p>
<p>The message? That small businesses <em>“…run a gauntlet of new laws, new regulations and new costs that can put them out of business. Instead of imposing additional burdens, policymakers should be creating small businesses to invest, expand and create additional jobs.”</em></p>
<p>So where’s the bias? In the fifth paragraph of the press release, CEA states:</p>
<p><em>“Online, CEA’s Innovation Movement will be hosting a <a href="http://lists.ce.org/t/4639271/19393671/27343/0/" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','lists.ce.org']);">Virtual Lobby Day</a> for its 114,000-plus members to encourage them to act on one key issue affecting small businesses: incentive spectrum auctions. CEA Innovation Movement members will be called to ask their congressional representatives to authorize the FCC to move forward with “incentive auctions,” which would provide broadcasters the ability to repurpose their frequencies through a spectrum auction in exchange for proceeds from auction revenues. Broadcasters could participate on a voluntary basis and purchasers could redeploy the spectrum for wireless broadband that could generate $33 billion for the U.S. Treasury and would allow endless opportunities for innovation in small business. “</em></p>
<p>A-HA! Apparently the primary motivation of this Innovation Movement is to pressure congress into selling off more broadcast TV spectrum. How, exactly, does that benefit a so-called ‘small business’ like mine? Seems to me such auctions would be far more useful Verizon and AT&amp;T more than anyone else, and they’re as far removed from ‘small businesses’ as you can get.</p>
<p>According to Shapiro, <em>“Using huge swaths of wireless spectrum to deliver TV to homes no longer makes economic sense. Congress should pass legislation to allow for incentive auctions so free market dynamics can find the best purposes for underused broadcast spectrum, such as wireless broadband.”</em></p>
<p><span style="text-decoration: underline;">OK, connect the dots with me:</span> (1) CEA’s members want more spectrum for broadband and other WiFi gadgets. (2) They think terrestrial broadcasters are vulnerable now. (3) So, CEA commissions a study that shows only while a small number of people are dropping or planning to drop pay TV service, these cord-cutters are NOT moving to over-the-air reception. No, they are instead turning to Internet-delivered video services. (4) Therefore, the country needs more bandwidth for broadband delivery of (among other things) video content, and less bandwidth for broadcast TV programs.</p>
<p>And I thought the recent Digital Entertainment Group survey of 3D TV trends was self-serving!  While I have no issue with the small number of cord-cutters the CEA identified, I simply cannot believe these ‘cutters’ would turn away from free HDTV programming for their new LCD and plasma TVs.</p>
<p>The CEA’s bias is clear now. In the last decade, they fought the digital TV tuner mandate, calling it an undue burden on TV manufacturers. Once the DTV transition got rolling, however, CEA did a flip-flop and showered praise on the FCC’s decision to move to a digital TV future, bringing free HDTV to millions of American homes.</p>
<p>Now, CEA has flipped again and says that free OTA TV is a dinosaur, and should be consigned to the dustbin of history in favor of wireless broadband in the UHF television band (a concept that is still on shaky ground technically).</p>
<p>I’m surprised the folks at CEA haven’t gotten whiplash from constantly reversing their positions. But it’s pretty clear now who’s really behind the curtains, calling the shots for CEA and also putting pressure on the FCC these days.</p>
<p>The question is; how many Americans still care that they can watch free HDTV anymore?</p>
<p>I’ll bet it’s a lot more than 8% of all U.S. households…</p>
