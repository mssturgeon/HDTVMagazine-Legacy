          <p>Three news items in the past few days are all focused on front projectors (pardon the pun). And each of these news items has a decided air of uncertainty around it, which of course reflects the sluggish economy and a looming paradigm shift away from projected images to self-contained, larger-than-life display technologies.</p>
<p> </p>
<p>The first item is courtesy of <em>Engadget</em>, <a href="http://www.engadget.com/2011/11/28/sony-4k-home-cinema-projector-coming-in-january-for-18-000/" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.engadget.com']);">who reports that Sony is getting ready to bring a $28,000 4K-resolution projector to the home cinema market</a>. They won’t be the first (Meridian previously offered the JVC 4K D-ILA platform for about $200K), but they will be the cheapest.</p>
<p> </p>
<p>This announcement, which will no doubt be one of Sony’s big PR blasts at CES 2012, raises a few questions. First, who needs 4K resolution? That represents four times the detail on a full 1920×1080 image, and there isn’t any content available to consumers (yet) that is authored at that resolution.</p>
<p> </p>
<p>Sure, HDMI v1.4 supports 4K. And you could certainly master a 4K Blu-ray disc, although at current disc capacities, you’d be limited to about 30 – 45 minutes of content with aggressive MPEG4 compression. But for now, 2K (or, more accurately, 2,073,600) pixels represents the upper limit for home viewing.</p>
<p> </p>
<p>That gives rise to the second question: How will Sony scale 2K content to fit the 4K imaging devices, which are almost certain to be SXRD LCoS chips? It’s not just a line-doubling job. No, scaling 2K to 4K is akin to scaling standard definition video to the 720p HDTV format. And what will 720p broadcasts look like on this projector?</p>
<p> </p>
<p>Third, how big a screen would you need to actually see the difference between 4K and 2K source material? I’m thinking that the typical 92-inch 16:9 screen at 12 feet isn’t going to cut it.</p>
<p> </p>
<p>The second news item comes from <em>Quixel Research</em>, <a href="http://www.quixelresearch.com/pdfs/Q3_2011_FT_PJ_Press_Release.pdf" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.quixelresearch.com']);">who reports that USA sales of 3D projectors for home use increased by 121% between Q2 and Q3 of 2011</a>. That number represents 16% of all home theater projector sales, which sounds pretty impressive.</p>
<p> </p>
<p>Ahh, but the devil is in the details, as usual. Sales revenue for 3D home projectors grew by only 14% in the same time period, a trend Quixel attributes to a “recent onslaught of low-cost 3D models” in the channel. Not so impressive, and even less so when you learn that the overall home theater projector market saw a 7% decrease in volume from Q2 to Q3 2011, even though the category saw a 2% increase year-to-year.</p>
<p> </p>
<p>The culprit? Look no further than plummeting prices on bigger and bigger TV screens. For less than $3,000, you can buy a Sharp Aquos 70-inch LED LCD TV with all the trimmings. And their newest model measures 80 inches diagonally, and will retail for less than $5,000. Who needs a projector when you’ve got a self-contained TV screen that large? (Betcha Sharp shows a 90-inch+ LCD TV at CES!)</p>
<p> </p>
<p>My belief is that 3D front projection make a whole lot more sense at home than small 3D TVs (less than 55 inches). Most people sit too far away from 3D TVs to get the full effect, and they rarely pay attention to controlling ambient light spilling on the screen.</p>
<p> </p>
<p>But 3D front projection turns that equation around. It’s easy to get a big 3D image and not spend a ton of money to do it, and screens tend to be placed in rooms where lights can be lowered or shut off altogether, just like in a movie theater.</p>
<p> </p>
<p>The problem is that projector manufacturers have slashed prices too low, too quickly. Got $2,000 in your pocket? You have quite a selection of stereoscopic DLP and 3LCD front projectors to choose from; of which a few models are tagged around $1,500. That’s a lot less than a 70-inch LED LCD TV costs – for now. But margins are very thin on such products.</p>
<p> </p>
<p>The last item comes by way of <em>AV Interactive</em>, the top pro AV publication in the United Kingdom. According to their Web site, <a href="http://www.avinteractive.com/top-story/36654/sanyo-name-to-cease-by-april-1-2012-panasonic-tells-parters" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.avinteractive.com']);">Sanyo will cease to exist as a brand name by the end of the 1<sup>st</sup> quarter of 2012</a> (also the end of the fiscal year for Japanese companies).</p>
<p> </p>
<p>How the AVI staff found this out is interesting: They got hold of a letter circulated by Panasonic to ‘business partners’ informing them of the decision. (I assume ‘business partners’ means dealers and distributors.)</p>
<p> </p>
<p>Readers from the pro AV industry will of course recognize Sanyo as one of the top projector brands, fronting an amazingly-large lineup that ranges from ultraportables to 10,000-lumens behemoths for auditoriums and theaters. They’ve also done pioneering work with short-throw projection as well as LED-powered light engines.</p>
<p> </p>
<p>For those readers who missed the headlines, Panasonic acquired Sanyo in December of 2008 for about $4.6 billon, primarily to scoop up the latter’s industry-leading battery and renewable energy technologies. Solar cell technologies were also in the mix. I found out about the acquisition while having dinner with several Sanyo executives in Osaka that night, which of course made for some very interesting conversations.</p>
<p> </p>
<p>At the time, I assumed that the Sanyo and Panasonic projector business units could co-exist nicely. Panasonic does very well in high-brightness DLP projectors, while Sanyo projectors are ubiquitous in hotels, classrooms, conference rooms, and even home theaters. But it appears that’s not going to be the case, as Panasonic will instead pull a ‘borg’ move and completely assimilate its prized acquisition.</p>
<p> </p>
<p>Ironically, the two companies have family ties that go all the way back to the period just after World War II. Sanyo was born when Toshio Iue, a former Matsushita employee and the brother-in-law of Konosuke Matsushita (the founder of Panasonic), began manufacturing bicycle generator lamps in an unused Matsushita plant in 1947.</p>
<p> </p>
<p>What will happen to all of the Sanyo and Panasonic projector business unit employees is uncertain at this writing; although it’s likely there will be substantial staff reductions. No word yet on whether Panasonic will continue to offer Sanyo-designed appliances (possibly), LCD TVs (unlikely), and cameras and camcorders (also unlikely).</p>
<p> </p>
<p>What we will see from Panasonic is a wider portfolio of rechargeable batteries and energy-efficient devices. That may be the only legacy of Sanyo to survive after April 1 of next year. Too bad, because I love my Sanyo Xacti 1080p pistol camera and my brother loves his Sanyo 32-inch LCD TV. And I’m sure many readers love their PLV-series Sanyo home theater projectors, too.</p>
<p> </p>
<p>Tempus fugit…</p>
