          <p>Last week, the <a href="http://www.hollywoodreporter.com/news/is-3d-home-dead-101226" onclick="javascript:pageTracker._trackPageview('/outbound/article/www.hollywoodreporter.com');">Hollywood Reporter reported</a> (accurately) that a majority of the attendees at the 2011 Hollywood Post Alliance Technology Retreat believe that 3D in the home is ‘dead’ and will never catch on.</p>
<p>Yes, I know you’ve heard about and read several surveys taken in the past year that show little or no enthusiasm for 3D at home. However, when people who create and distribute movies and TV shows for a living give 3D at home the thumbs-down, that’s big news.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2011/03/3D-Question-Graphic-MR.jpg"><img class="aligncenter size-full wp-image-1049" title="3D Question Graphic MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/03/3D-Question-Graphic-MR.jpg" alt="" width="600" height="145" /></a></p>
<p>I’ve attended every HPA Tech Retreat since 2002 and presented at most of them. Last year, we had a 3D supersession where many attendees expressed skepticism that 3D at home was viable. This year, the number of naysayers was substantial, as evidenced by a show of hands during the Day 1 presentation recaps by HPA leaders Leon Silverman and Jerry Pierce.  (This year’s Retreat had 450 registrants, by the way.)</p>
<p>The annual broadcasters’ panel brought forth more skepticism, with Fox saying that until there was a workable, viable ATSC 3D standard, they would stay on the sidelines. Those sentiments were pretty much echoed by ABC, NBC, Sinclair, PBS, and CBS.</p>
<p>As I mention in another post, we had a great breakfast roundtable discussion on 3D in the home, and whether it was a flop, partially successful, or had any real future. We also discussed the relative scarcity of 3D movies, which led to a question about why Hollywood isn’t remastering more of their older 3D movie titles into the Blu-ray format. The reply was that the cost to do those remasters probably wouldn’t be justified by Blu-ray disc sales, let alone rentals.</p>
<p>Let’s face it; 3D TV stumbled badly out of the gate in 2010. TV manufacturers locked up the most desirable 3D Blu-ray discs as part of exclusive TV bundles, creating an instant shortage of compelling 3D content. Want to watch <em>Avatar</em> in 3D? Sorry, you’ll have to buy a Panasonic 3D TV. How about any of the Shrek movies? You’ll need to buy a new Samsung 3D TV. Despicable Me? You’re looking at a new Sharp Aquos, pal.</p>
<p>What’s that – you just dropped $2,000 on a new 55-inch 120 Hz LED LCD TV a year ago? Hmmm – that’s a problem.</p>
<p>How about the new 3D TV networks? Well, ESPN 3D is a barker channel during most of the day. The World Cup was fun, but half the shots didn’t benefit at all from 3D.</p>
<p>Last fall, DirecTV’s 3D pay-per-view channel was showing <em>Journey to the Center of the Earth</em>, followed by <em>Journey to the Center of the Earth</em>, followed by <em>Journey to the Center of the Earth</em>…well, you get it.</p>
<p>As far as 2011 goes, the outlook for 3D TV sales isn’t very sunny. Nielsen’s annual State of All Media survey, taken in Q4 of 2010, showed that <em>“…76% of respondents ‘probably won’t or ‘definitely won’t’ buy a 3D TV in the next 12 months. 2% of respondents already own a 3D TV, while only 6% “definitely’ or ‘probably’ will buy one.”</em></p>
<p>The problem is compounded by VIZIO and Toshiba saying that consumers don’t need to buy expensive LCD glasses to watch 3D TV. VIZIO is leading a charge to passive (half-resolution) 3D TV, with the selling point being that you can use those same 50-cent RealD circular polarized glasses they gave you at the local multiplex cinema. (LG showed passive 3D at CES and may also go this way, and JVC is pushing into passive 3D TV in 2011.)</p>
<p>Toshiba’s claim that you can drop glasses altogether upsets the apple cart even more, and has apparently convinced the average Joe that there is a format war in 3D (shades of the 1080i vs. 720p battles ten years ago). Skipping past the technical details, what today’s consumers are hearing is that 3D is very much in the laboratory stage and that it is probably a smart idea to sit on the sidelines for a while until all of the details are worked out – and until 3D TVs without glasses are widely available.</p>
<p>So, what’s a TV manufacturer to do?</p>
<p>First off, it’s evident that consumers will NOT pay a premium for 3D functionality. There are simply too many 2D TV models available for less than $1,000, including a couple of 55-inch screens. Asking consumers to pony up an additional $500 – $1,000 just to watch a handful of movies and 3D networks is a waste of energy right now…particularly when you consider all of the people who bought new big-screen LCD and plasma TVs in the past five years.</p>
<p>Second, release the exclusively-bundled 3D Blu-ray discs immediately to the open market. If you want someone to buy a fancy new sports car, make sure there are plenty of gas stations where they can fill it up!</p>
<p>Third, drop the prices on 3D Blu-ray players to a level commensurate with networked Blu-ray players. Those are selling very well because consumers are using them as Internet TV set-top boxes to gain access to Netflix (20 million subscribers and counting).</p>
<p>Fourth, continue exploring marketing partnerships with content producers to create 3D channels that more people can watch. Currently, only the Sony-Discovery-IMAX 3Net channel and ESPN’s 3D channel are available to any viewer on any Pay TV system. 3D on DirecTV does nothing for a Comcast subscriber, or a Dish Network subscriber. Comcast’s new 3D channel is inaccessible to Verizon FiOS customers. Content drives TV viewership – HDTV started in 1998 but didn’t really take off until about 2004, when all of the major TV networks finally had a strong slate of HD programming to watch.</p>
<p>Unfortunately, the perceived format war between active shutter, passive, and autostereo (a really inferior way to watch 3D, if you ask me) is going to keep sales of 3D TVs down in 2011. Consumer enthusiasm is so low that most of the 3D demos at my nearby Best Buy appear to have been turned off for good. (Not that they could find any working active shutter glasses if they needed to…)</p>
<p>At this past Sunday’s Ambler Theater Oscars Party, I set up a Samsung PN50C8000 3D plasma TV with four pairs of glasses (fresh batteries in every one) and a 3D animated movie (<em>Monsters vs. Aliens</em>), smack in the middle of the concessions lobby. Plenty of people (young and old) came over to watch for a few minutes, were appropriately wowed, asked what the 3D set-up cost, said <em>“that’s nice, but I can’t see having to wear glasses to watch TV”</em> and then walked away to one of the three main theaters.</p>
<p>They’re just not buying it.</p>
