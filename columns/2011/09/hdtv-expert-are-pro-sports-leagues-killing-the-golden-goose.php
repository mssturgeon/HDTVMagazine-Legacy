          <p><a href="latimes.com/business/la-fi-ct-sports-rights-20110908,0,7676976.story">An article in today’s Los Angeles Times</a> asks if the TV broadcast rights fees paid to sports leagues are reaching the breaking point for many subscribers. Currently; CBS, Fox, and ESPN are forking over $3.1 billion a year to broadcast 16 games, preseason, and playoffs, plus the Super Bowl. And those contracts will be up for renegotiation in two years.</p>
<p> </p>
<p>For those of you who don’t know, the most expensive pay TV channel in terms of per-viewer fees is ESPN, which commands nearly $5 per subscriber in some markets (about $4 per sub here in the Philadelphia market). The pile of cash generated by those per-subscriber fees is what has allowed ESPN to cover last year’s World Cup in 3D, not to mention lock up the exclusive rights to the Bowl Championship Series (BCS) college football games.</p>
<p> </p>
<p>It also allows ESPN to bid aggressively against conventional TV networks to secure rights to the top sporting events. Recently, ESPN snatched away the TV rights to the Wimbledon tennis tournament from NBC, which had broadcast it for the past 43 years.</p>
<p> </p>
<p><em>“OK, what do those two things have to do with each other?”</em> you’re thinking right now. Simple: As ESPN takes in more money from subscribers, it has more to throw on the table for future rights negotiations, ensuring that more and more HDTV coverage of professional sports will migrate to pay channels from free networks.</p>
<p> </p>
<p>And Comcast is getting into the act with its Versus channel, which now carries NHL games and is expected to be a major bidder in the future for TV coverage of pro sports. Not only that, each of the major sports leagues now has its own TV channel (MLB, the NFL Network, NBA TV), and a select number of games are available on each channel for an additional per-subscriber fee.</p>
<p> </p>
<p>Even colleges are joining the fun, with the University of Texas, the Big 12, the Pac 10, and the Big Ten all operating or getting ready to launch TV channels.</p>
<p> </p>
<p>A few years ago, I predicted to my old college roommate that eventually, ALL sports would wind up on pay TV channels, whether they be within the ESPN family, Versus, or one of the league TV channels. It looks now like that day isn’t too far off.</p>
<p> </p>
<p>The Times article quoted representatives of cable and satellite TV networks as saying that we’ve reached the breaking point with regards to per-subscriber charges, and that subscribers are dumping cable and satellite packages accordingly to cut costs.</p>
<p> </p>
<p>Another reason that TV broadcast rights have gotten so expensive is because ratings for just about everything else on TV have diminished. It’s a classic application of the law of diminishing returns: As the number of pay TV channels increases, each program attracts smaller audiences.</p>
<p> </p>
<p>On the other hand, sporting events draw big numbers, particularly NFL games, each of which drew an average of 18 million viewers last season, mostly men ages 18 to 34. And advertisers will pay plenty to reach those viewers. (Think beer and car ads.)</p>
<p> </p>
<p>Representatives of Mediacom (a small cable TV system operator) and DirecTV both believe that sports programming should be carried on a separate, premium tier. If viewers want to ante up the big bucks to see the Longhorns play the Sooners, or UCLA and USC duke it out, then let them. But don’t force other subscribers to foot the bill, too.</p>
<p> </p>
<p>The various sports entities don’t want to discuss such an approach, as it would seriously dilute the number of subscribers and put a dent in revenue.  Yet, we are seeing increasing evidence that average viewers think pay TV is just too darn expensive and are either dropping channel packages or ‘cutting the cord’ by moving to Internet video and terrestrial HDTV to save money.</p>
<p> </p>
<p>The irony is that many of the collegiate bowl games will involve publicly-funded universities, and the taxpayers who subsidize those universities won’t be able to watch unless they pay extra for the privilege.</p>
<p> </p>
<p>Keep that in mind as you enjoy your Sunday and Monday NFL games in HD this fall. You may not be able to do that for too many more years.</p>
