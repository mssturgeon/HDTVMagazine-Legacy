          <p>At the September 14 Pepcom table-top show (dubbed the ‘Parisian Holiday Spectacular’ show, as so many gadgets were being pushed for gift-wrapping under the tree), Channel Master showed something that ought to bring a smile to every cord-cutter’s face: A dual DVR for digital terrestrial television.</p>
<p> </p>
<p>Not only that, this same product also supports Vudu streaming and Vudu apps, in case you’re jonesing for a movie and don’t want to mess with DVDs or Blu-ray discs. It’s called Channel Master TV, and it will start shipping in mid-October. (Yes, I’ve already asked for a review unit. C’est si bon!)</p>
<p> </p>
<p>You can find out all of the details about this new product <a href="http://www.channelmaster.com/" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','www.channelmaster.com']);">by clicking here</a> (the dedicated Channel Master TV Web site still was not up and running at the time I wrote this), or you can read on.</p>
<div id="attachment_1506" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1506" href="http://www.hdtvexpert.com/?attachment_id=1506"><img class="size-full wp-image-1506" title="CMTV on Box V MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/09/CMTV-on-Box-V-MR.jpg" alt="" width="600" height="663" /></a><p class="wp-caption-text">It's smaller than a TiVo Premiere. Dig those three WiFi antennas!</p></div>
<p>Channel Master’s big selling point for this dual-DVR box is that there are NO monthly subscription fees required. Well, that’s not exactly true: If you are content to rely on the Program and System Information Protocol (PSIP) data transmitted by each station – correctly or not – then you don’t need additional program guide data.</p>
<p> </p>
<p>But if you want to program recordings more than 14 days out, you’ll want to add CM’s optional enhanced program guide service, for which no firm price was stated at the event. Both basic PSIP and day/time scheduling can be used to record DTV programs.</p>
<p> </p>
<p>And you’ll have plenty of space to record. The CM TV box comes with a 320 GB hard disk drive, which ought to be sufficient for up to 35 hours of HDTV programs and about 150 hours of SD programs. Like TiVo’s HD and Premier DVRs, you can watch one program while recording another, or playback a program while recording two others.</p>
<div id="attachment_1507" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1507" href="http://www.hdtvexpert.com/?attachment_id=1507"><img class="size-full wp-image-1507" title="CMTV Main Menu GUI MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/09/CMTV-Main-Menu-GUI-MR.jpg" alt="" width="600" height="476" /></a><p class="wp-caption-text">Mira esto! Una telenovela de WXTV-HD!</p></div>
<p>Vudu movies are generally pay-as-you-go, so there’s no monthly subscription fee. And the supported apps include Pandora, MTV News, Discovery, Twitter, Facebook, AP, and The New York Times, among others.</p>
<p> </p>
<p>From a technical perspective, CM TV interfaces to your existing HDTV either through an HDMI connection or component video outputs. You can set the video output of the box to 1080p/30, 1080p/24, 1080i/30, or 720p/60. (Sorry, no support for 1080p/60 yet. I did ask…)</p>
<p> </p>
<p>There’s also a discrete optical digital audio (Dolby AC-3, Dolby 5.1) connection for a separate AV receiver, along with wireless (802.11n) and wired Ethernet connectivity for Vudu access and Vudu Apps, a USB port for viewing photos and videos from a flash drive, and an eSATA connection for an external expansion hard drive.</p>
<p> </p>
<p>Technically speaking, CM TV will also receive ‘in the clear’ digital cable broadcasts, but you won’t receive any program guide data as cable systems use a different implementation of PSIP.</p>
<div id="attachment_1508" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1508" href="http://www.hdtvexpert.com/?attachment_id=1508"><img class="size-full wp-image-1508" title="CMTV Channel Scan MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/09/CMTV-Channel-Scan-MR.jpg" alt="" width="600" height="448" /></a><p class="wp-caption-text">Scanning for active DTV channels can take a while, as all of the PSIP information is read and stored.</p></div>
<p>And the price for all of this wonderfulness? Why, just $399. That is a substantial premium over the latest TiVo boxes, but then again, you won’t be paying $12.99 a month for program guide information. (Mark my words, the price on this box will drop below $300 by December. There’s a big psychological difference between $299 and $399 to the average consumer.)</p>
<p> </p>
<p>So if you’ve been seriously thinking about dumping your digital cable channel package and relying on broadband video and free, over-the-air HDTV, your days of waiting are over. Now you have the missing piece of the puzzle – a dual DVR with a nice electronic program guide GUI (and it is VERY nice and user-friendly.)</p>
<p> </p>
<p>Watch your local brick-and-mortar store for the first shipments in mid-October. You can also buy the box directly from Channel Master, and I suspect it will also be available from major Web outlets like Amazon.</p>
