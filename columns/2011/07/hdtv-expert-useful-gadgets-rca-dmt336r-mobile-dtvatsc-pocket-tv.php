          <p>It’s hard to believe it’s been just 13 years since the digital TV transition started in 1998 when TV stations WFAA and WRAL first signed on the air.</p>
<p>Back then, ‘watching digital TV’ meant shelling out a couple thousand dollars for a large, energy-guzzling converter box and experimenting with different antennas to try and pull in the signals, which (more often than not) dropped out or froze up.</p>
<p>Fast-forward to 2011: The DTV transition has been history for two years. Every new TV has a built-in ATSC tuner, and the adaptive equalizers in that tuner work so well that signal drop-out from fading and multipath is mostly an unpleasant memory. In fact, ATSC set-top receivers are mostly a memory now, given that you can a new LCD or plasma digital TV for about $10 per diagonal inch.</p>
<p>Even computers can join in the fun, thanks to the latest generation of ‘plug and play’ <a href="http://www.hdtvexpert.com/?p=1344" target="_blank">USB stick tuners</a> from companies like Hauppauge that let you use your laptop or desktop as a fully-featured DVR. Just add an antenna, and you’re ready to go.</p>
<p>Along the way, several manufacturers found the time to bring out some models of portable digital TVs. This product category was pretty thin two years ago, but now there are several brands to choose from, among them the familiar white dogs of RCA (now owned by Audiovox). At the June CES Summer Line Show, RCA unveiled a bevy of portable digital TVs, several of which also receive the nascent MH (mobile handheld) DTV service.</p>
<p>The DMT336R falls into that category. It has a 3.5″ screen, runs for over 2 hours on a single charge, and does an excellent job pulling in both MH and regular over-the-air ATSC broadcasts.</p>
<p><a rel="attachment wp-att-1380" href="http://www.hdtvexpert.com/?attachment_id=1380"><img class="aligncenter size-full wp-image-1380" title="RCA-DMT336R" src="http://www.hdtvexpert.com/wp-content/uploads/2011/07/RCA-DMT336R.jpg" alt="" width="600" height="344" /></a></p>
<p>WHAT’S IN THE BOX</p>
<p>There’s not much to the DMT336R. It’s a little bigger than a digital camera, and features a 4:3 TFT LCD screen. (Why RCA didn’t use a widescreen aspect ratio for the LCD remains a mystery.) It has a power button on the side, just above the 5V power jack for recharging the internal battery pack, which is supposed to deliver three hours of viewing time. (It comes close!)</p>
<p>On the opposite side of the case are three connectors. The first is a SMB-type jack for an external antenna. (RCA didn’t provide an adapter from this connector for the review.) There’s also the usual composite video output connection with stereo audio, connected through a mini AV jack. You can also plug in a pair of headphones through a separate audio output jack.</p>
<p>The upper left of the TV housing hides a telescoping 10″ antenna, which can be rotated in any direction. That’s plenty long enough for UHF TV reception, but a tad short for VHF. Even so, if you have enough signal strength at your location, you’ll haul in high-band VHF DTV stations (channels 7-13) just fine.</p>
<p>For such a small TV, the menu is pretty loaded. ATSC and MH programs are tuned separately; you have to access different menus to scan for and select channels from each service. The main reason for that is the ATSC over-the-air standard uses MPEG2 digital video, while the MH service uses MPEG4.</p>
<p>Even though the LCD screen is 4:3, you can select a 16:9 aspect ratio for HD channels. You’ll see black bars above and below the image (also known as “letterboxing”). But you should be aware that most HDTV programs are composed to favor a 4:3 ‘safe area’ so you’ll still see the important stuff even if you opt to watch in 4:3 mode. There are two other aspect ratio settings that allow a partial zoom into the letterboxed image and a setting that takes a ‘center cut’ of the widescreen image.</p>
<p>When tuning in MH services, it takes a few seconds for an active channel to lock up. In the Philadelphia area, only WCAU (digital 10.1) was broadcasting MH when I tested the DMT336R. The long lock-up is due to the massive amounts of Forward Error Correction (FEC) used in the MH service. It’s what keeps the signal present even when you are watching MH TV in a moving car, bus, train, or bicycle. (Wait – how do you watch TV on a bicycle?) You also can watch MH while walking, or in a sedan chair, or in a kayak, or while skiing.  (OK, now I’m just being silly…)</p>
<div id="attachment_1381" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1381" href="http://www.hdtvexpert.com/?attachment_id=1381"><img class="size-full wp-image-1381" title="John Turner and MH TV 1 MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/07/John-Turner-and-MH-TV-1-MR.jpg" alt="" width="600" height="337" /></a><p class="wp-caption-text">For MH and ATSC reception, we recommend pepperoni pizza and a nice Cabernet Blanc!</p></div>
<p>HOW IT TESTED</p>
<p>I’ve tried the DMT336R in a few locations, most of them stationary. In mid-July, I visited John Turner of Turner Engineering at home, w-a-y up in the hills of northern New Jersey. The elevation was about 700 feet and we had a line-of-sight path to New York City.</p>
<p>Not surprisingly, the DMT336R pulled in all of the available UHF stations, along with high-band VHF channels 7, 11, and 13. Reception on each channel was rock-steady using the internal whip antenna, although the position of the antenna was somewhat changed for a few channels. I also identified and pulled in MH broadcasts from WNBC, ION, and Telemunco. All of that error correction introduces lots of latency – it can take 5-6 seconds to lock up an MH broadcast, so don’t expect fast channel changes in this mode. But you will be amazed at how stable an MH signal is once you’re watching it, even if you move the TV around.</p>
<p>During these tests, John took out an older Eviant T7 portable ATSC receiver and we did a side-by side comparison. The DMT336R was clearly more sensitive on weaker ATSC signals, and that’s probably because its adaptive equalizer is at least Gen 6. We also watched a Yankees game on WWOR-9 while enjoying pizza and a bottle of wine, and the battery held out for almost 3 hours. The internal audio isn’t very powerful (900 milliwatts) – it’s loud enough in a quiet room or with headphones, but will be hard to pick up in public spaces or out on your boat. So plan on using a pair of headphones while traveling.</p>
<p>My second round of tests were at home, using my rooftop antenna and the built-in whip. I pulled in all of the Philly ATSC stations, plus a single MH service on WCAU (NBC). My particular location isn’t favorable for indoor DTV reception of any kind, save for megapower DTV station WFMZ in Allentown, PA (channel 46). So a powered antenna is a big help. Still, with WFMZ coming in, I could wander around the house and up and down stairs and still hold the signal 80% of the time. Pretty impressive performance!</p>
<p>Did I mention that the DMT336R also contains an FM radio? Just plug in a set of headphones and tune away – the headphone wires double as the FM antenna.</p>
<div id="attachment_1382" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1382" href="http://www.hdtvexpert.com/?attachment_id=1382"><img class="size-full wp-image-1382" title="RCA DMT336R and Eviant T7 Compared MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/07/RCA-DMT336R-and-Eviant-T7-Compared-MR.jpg" alt="" width="600" height="337" /></a><p class="wp-caption-text">There is only a two-year difference between the receiver technology in the Eviant T7 and RCA's DMT336R, but that made for quite a difference in my tests.</p></div>
<p>THE WRAP-UP</p>
<p>Portable digital TVs have become so inexpensive that it makes plenty of sense to have a few around the house, especially if you suffer from frequent power outages and severe weather. Some portable DTV manufacturers have referred to these gadgets as “hurricane TVs” for that reason.</p>
<p>You can also catch your local sports team in action with the DMT336R. Want to sit on your boat on a Sunday afternoon and catch an NFL game? Or the Saturday baseball game of the week? Here’s one way to do it. There are also plenty of ‘retro’ TV networks carried as secondary DTV channels these days (like This TV) that are fun to watch when traveling. With over 1700 digital TV stations broadcasting across the country, you’ll find something to watch.</p>
<p>The DMT336R delivers the goods. Yes, it could use a more powerful speaker, and yes, it should have come with a widescreen display. But the DMT336R tunes ATSC and MH channels like a champ and costs only $169 (retail), and it’s a low-cost way to access the new MH broadcast services.</p>
<p>You can find out more about the full line of RCA portable digital TVs at www.getmyelectronics.com.</p>
