<p> </p>
<p>In the past, so-called ‘tentpole’ movies have realized as much as 60% of their revenue from 3D screenings. But that’s not the case for <em>Pirates</em>, which had a softer opening than its three predecessors and is seeing only 47% of its revenue coming from 3D screenings.</p>
<p> </p>
<p>Granted, the <em>Pirates</em> franchise may finally be running out of steam – reviews of this movie have generally been tepid. But the drop for <em>Panda</em> is of greater concern, as animated movies generally do very well in 3D.</p>
<p> </p>
<p>The <em>Times</em> article stated that Panda sold only $54 million in tickets from Thursday May 26 through Sunday May 29. That is considered a ‘soft’ opening when compared to the original <em>Panda</em>. Of greater concern is the fact that 3D screenings only accounted for 45% of the total box office, even though Panda is expected to be one of the top animated releases for 2011.</p>
<p> </p>
<p>Ironically, 3D screenings of Pirates are doing very well overseas, where 3D is still a novelty. The movie earned $256 million internationally in its first weekend of release, with 3D driving a good deal of the box office.</p>
