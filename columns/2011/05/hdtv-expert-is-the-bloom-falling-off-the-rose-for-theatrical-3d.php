<p>No one is quite sure of the reasons for the decline in 3D ticket sales. Richard Greenfield, an outspoken analyst of the entertainment industry for BTIG, stated flatly that <em>“The American Consumer is rejecting 3D,”</em> while Greg Foster of Imax Filmed Entertainment implied that moviegoers have finally <em>“caught on”</em> to the higher prices being charged for mediocre movies presented in the 3D format.</p>
<p> </p>
<p>The importance of strong 3D box office can’t be understated. A total of 16 movies will be released in 3D by September, and this weekend’s tentpole 3D flick will quickly become yesterday’s news, especially with the likes of <em>Green Lantern</em> and <em>Transformers 3</em> looming on the horizon.</p>
<p> </p>
<p>The fact is; a good movie is a good movie – period. Even the best animated films like <em>Toy Story 3</em> don’t give up anything when viewed in 2D, and it’s rare that an animated feature comes along that actually works better in 3D than 2D (think 2010’s <em>How To Train Your Dragon</em>, one of the best 3D animated movies ever).</p>
<p> </p>
<p>The Times article opines that it might be a better idea for Hollywood to cut back on the number of 3D releases as American moviegoers are increasingly blanching at paying a premium of $3 to $5 for the privilege of wearing RealD glasses. Greenfield agreed, stating that the Memorial Day results show audiences are quite happy with 2D, thank you very much, and that too many screens have been allocated to 3D.</p>
<p> </p>
<p>While it may be too early to declare a trend, the 3D picture has clearly changed from 2010. Have 3D movies peaked? If so, what will this trend mean for 3D TV and Blu-ray sales down the road?</p>
