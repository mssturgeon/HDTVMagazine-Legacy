				<p><strong>ATSC </strong>stands for Advanced Television Systems Committee, and about<strong> 20 years ago</strong>, this group developed the standard that became the basis for our <strong>digital terrestrial TV broadcasts</strong>. (Remember all that confusion about the digital transition two years ago?) The standard is <strong>due for updating</strong>, and the group has been hard at work on<strong> ATSC 2.0</strong> already. At their annual meeting this week, the committee talked about <strong>some of the changes </strong>that could come with a revised standard.</p>
	<p>One of the key changes would be a provision that supports the transmission of <strong>stereoscopic 3DTV </strong>content in high definition. This could seem to be a major challenge, especially given <strong>the current battles </strong>over the broadcast spectrum that has been assigned to terrestrial television stations. The fact is, however, that 3DTV could be accomodated <strong>within the existing bandwidth</strong>. The current digital broadcast standard is based on MPEG2 compression technology, which is the form that was <strong>used for DVDs</strong>. We now routinely use MPEG4 for video compression, including<strong> Blu-ray and satellite TV </strong>transmissions. This newer approach can be roughly <strong>twice as efficient </strong>as MPEG2, which means that two frames &#8211;<strong> left and right </strong>&#8211; could be sent in the same bandwidth currently required for<strong> a single frame</strong>.</p>
	<p>There are other ways that the data stream could be <strong>condensed even further</strong>. For example, there is no difference in the appearance of <strong>distant objects </strong>between the two stereoscopic views. As a result, that data only needs to be <strong>sent once</strong>. The right hand frame could be sent in its entirety, followed by<strong> the data that is different </strong>for the left frame. This has the added advantage of maintaining backward compatibility with 2D sets; they could <strong>just ignore the second frame </strong>if they do not have 3D capabilities.</p>
	<p>In order to get to this point, we <strong>need a standard </strong>for the broadcaster and television manufacturers to use. And we&#8217;d probably need <strong>external adapters </strong>for legacy sets, but that would probably be a low-cost addition.</p>
	<p>ATSC is reportedly exploring other additions to the standard, including the ability to <strong>deliver data files </strong>in the background of the signal transmission, interactive features,  audience measurement tools, and <strong>advanced program guide information</strong>.</p>
	<p>This is not going to happen any time soon &#8212; remember that it took <strong>more than 15 years </strong>to implement the first ATSC standard &#8212; so don&#8217;t hold your breath. But it is entirely possible that broadcast television will <strong>get the chance to keep up </strong>with some of the other program distribution choices.
