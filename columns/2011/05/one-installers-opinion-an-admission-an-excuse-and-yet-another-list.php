</p><p>The long overstayed stinko economy has taken a toll on almost everything, including ... the wholesale transition to the new video standard, BD (Blu-Ray disc). The Studios will have to be convinced, beyond any doubt, that there are enough BD players out there (hence acceptance) to take up the slack before they pull the plug on their Golden, tarnished, but fully amortized, Goose.
</p><p>Here's some recent data, circa end of 2010. 61% of American homes have at least one HDTV. 26% have more than one. Another study says 90% of HDTV owners have a BD transport, split roughly 35/65, Sony PS3s vs. stand-alone BD players. A modicum of simple math, extrapolated one year out into a better economy, makes a much more compelling case. I'm doubling down on post Christmas, 2011.
</p><p>
 </p><p>When I do a pre-proposal interview with a perspective client, I always ask about intended use, framed in a question about relative mix between TV/Movies/Music. I toss concert videos in with movies. Pure music includes CDs, SACD, DVD-Audio and the very occasional 2-ch phonograph guy, God love 'em. A bias toward music may influence my speaker selection, but movies vs. TV will have no bearing on equipment selection. I'm just curious as to the answer. If you added 30 minutes to most prime-time dramas, they would beat a lot of Hollywood releases at the box office ... which is the point of this "alert".
</p><p>In the discovery portion of these interviews, I often hear things like "Oh, we don't watch much TV" or "There's nothing good on TV anymore". 
</p><p>Nonsense! 
</p><p>To the first allegation, I contend that they don't realize how much TV they actually DO watch, and even if their assertion is accurate, I know that's all about to change once they explore the capabilities of their new, large(r) screened, high(er) definition Home Theatre. To the latter group, I say welcome to the New Millennium. We've come a long way Baby since the first HD broadcast from WRAL-TV in Raleigh, N.C. in  July of 1996.
</p><p>I allege the combination of a newly expanded pallet, enabling glorious images with deeper saturated colors, more perceived brightness and multi-channel audio capabilities, has caused TV Producers, Directors and production technicians to ratchet up their game several notches. I used to state the primary reason to have a properly installed and calibrated Home Theatre was to guaranty accurate delivery of movie content, with a focus on "The Director's Art", in exchange for an hour and a half of your life. The fact that it made TV a better experience was just a collateral benefit. I have now come to believe that TV and Movies are on a roughly equal footing as motivation to make the investment.
</p><p>The following is absolutely true.
</p><p>My girlfriend and I are "addicted" to 32 hours of high definition prime-time television per week. I have about 500 DVD/BDs in shrink wrap that I'm having trouble getting to, because the prime-time is so compelling. For the purpose of what follows, I'm defining prime-time as one-hour drama/comedy series' broadcast between 8PM and 11PM in HD, Monday through Friday.  This DOES NOT include many worthwhile "specials", sporting events or game shows. Yes, we have other things in our lives, but the magic of two DVRs, the fact that at any point in time some of these are on network hiatus, and the ability to condense an on-air hour into 45 seamless, commercial-free minutes of pure program content make this an (almost) manageable task (weekends are catch-up). 
</p><p>The 32 programs listed below are OUR favorites. With a little exploration, it's a certainty that your list will be different (and probably shorter). Sure, from time to time our friends suggest that we watch this or that, but if it means crossing even ONE of our favorites off the list, it probably won't happen. 
</p><p>The point is, Prime-Time has never been better and viewing it on a "reference" system makes "watching TV" a whole new experience.
</p><p>Some of these were picked for snappy repartee (House, Hawaii 5-0, Lie to me, The Mentalist) - some for stunning visuals (CSI Miami, Hawaii 5-0, Boardwalk Empire, NCIS L.A., Burn Notice). The rest are just, for us, high on entertainment value featuring good writing and Scorsese-like production values. So if you are among those who think "There is nothing on TV" I offer the following alphabetical list. O.K., I couldn't resist placing an asterisk by my Top Ten ..............   
