          <p>Today is Bob Dylan’s 70<sup>th</sup> birthday. Whether you like the man’s music or not, there can be no argument that it has had a profound impact on countless artists and bands ever since his first album was released 49 years ago.</p>
<p> </p>
<p>One of my favorite Dylan tunes is the aforementioned <em>“Times,”</em> and it couldn’t be more appropriate in 2011. The world of media distribution is turning on its head, thanks to the Internet and digital technology.</p>
<p> </p>
<p>Consider these recent stories. At a meeting of the Telecommunications Industry Association (TIA) last week in Dallas, FCC Chairman Julius Genachowski emphatically stated that there is no need for further debate on the topic of spectrum shortages. Quote: <em>“Any objective observer would have to say that the spectrum crunch debate has been put to rest.” </em></p>
<p> </p>
<p>Genachowski, of course, has been advocating that TV broadcasters give up yet another chunk of their spectrum that would be re-assigned for wireless broadband services (something TIA members like Verizon and AT&amp;T are salivating over).</p>
<p> </p>
<p>Obviously Genachowski feels that the importance of free, over-the-air television has greatly diminished, and that <em>‘broadband for everybody’</em> should be the modus operandi going forward, using ‘voluntary’ spectrum auctions to free up UHF TV channels for his pet project.</p>
<p> </p>
<p>Aside from some technical reasons why using UHF TV channels for wireless broadband isn’t a good idea, Genachowski is clearly overlooking other spectrum that could just as easily be put to the same purpose, such as the 800 MHz analog cellular phone band. (Betcha didn’t know those channels were still in use!) Or, how about the hundreds of MHz reserved exclusively for government use? A 120-MHz bite out of that would hardly be noticed.</p>
<p> </p>
<p>The point, however, is that Genachowski feels the availability of free digital TV (and free HDTV, I should add) isn’t nearly as important as having broadband access to Netflix streaming, or to eBay auctions, or to the Huffington Post, or to ESPN.com.</p>
<p> </p>
<p>And that is a sea change in the thinking of the FCC from 1934, when it was created from the old Federal Radio Commission to ‘regulate the airwaves in the public interest,’ to 2009 when the digital TV transition was complete, and the FCC had largely devolved into a glorified spectrum auction house.</p>
<p> </p>
<p>Wireless isn’t the only place where the old order of media distribution is under siege. Two recent reports from the Digital Entertainment Group and SNL Kagan clearly show that America’s love affair with the DVD is over, and that more and more households are embracing a ‘cloud’ model for accessing and watching movies and TV shows.</p>
<p> </p>
<p>Kagan’s study revealed that wholesale revenue from DVDs (not Blu-ray discs) in 2010 dropped almost 44% from 2009, even though 2010 was a decent year at the box office. This decline in DVD sales has been evident for nearly six years now, and is picking up speed – Kagan calculates that the annual compound negative growth rate for DVD revenue is over 13% in the past five years.</p>
<p> </p>
<p>Granted, DVD rental income from $1-per-night kiosks was up last year, and video-on-demand (including Netflix streaming) is in a strong growth mode. Even so, overall consumer spending on entertainment declined almost 11% in 2010, and that’s nothing to sneeze at.</p>
<p> </p>
<p>The important thing to note here is that streaming is growing by leaps and bounds. As you’ve probably read elsewhere, Netflix now has more subscribers than Comcast (over 23 million). And Netflix streaming is largely what’s driving sales of connected Blu-ray players, not sales and rentals of Blu-ray discs. There’s that ‘cloud’ thing, again!</p>
<p> </p>
<p>The problem with Netflix streaming is that the revenue that goes back to Hollywood studios doesn’t even come close to replacing the cash cow that DVDs once represented. And that drop-off in revenue will definitely be a sticking point when each studio’s contracts with Netflix are renegotiated in t near future.</p>
<p> </p>
<p>On the hardware side of things, we’re seeing an accelerating shift away from traditional notebook computers to touchscreen tablets and eBook readers. A recent news story stated that women, who generally read more books than men, are flocking to Barnes &amp; Nobles’ color Nook reader and are also reading more magazines than ever before on said reader.</p>
<p> </p>
<p>That fact, plus the embedded but largely hidden Android OS that has the potential to turn the Nook into a full-blown media tablet, may be the reason why John Malone’s Liberty Media is making a play for Barnes &amp; Noble. Last Thursday, Malone’s company announced a $1B offer for 70% of the company. The bid price is about $17 per share, which represents a 20% premium over the current stock price.</p>
<p> </p>
<p>Why would Malone, who made his fortune in the cable TV business, want to own the largest bookseller in the United States? Because he can deliver all sorts of content – print or otherwise – directly to Nooks through a ‘cloud’ structure. (And he might need some of those UHF TV frequencies to do it!)</p>
<p> </p>
<p>There you have it. TV and movies everywhere, anytime (just not on optical discs). A media center in your coat pocket. Cloud servers set up by everyone from Amazon to Apple. Wireless broadband access to everything, even if it means you have to pay Verizon and AT&amp;T to watch TV programs, over the air, with an antenna. And the increasing likeliness that you will have to pay to watch HDTV content, wherever it comes from.</p>
<p> </p>
<p>The times, they are indeed a-changin’…</p>
