</p><p>By the time I get my clients, they've usually answered those Qs. Now I have, and I offer the following as objectively as I can. Having installed somewhere around 1,000 home theatres in the last 22 years, I have some pretty firm convictions about what recipes yield success and which paths go...ah, elsewhere. 
