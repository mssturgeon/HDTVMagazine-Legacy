 </p><p>Here's the thing.
</p><p>
 </p><p>Just as you could unknowingly pick a lawyer who barely passed the BAR out of the phonebook or worse, draw a surgeon who graduated in the bottom decile of his/her class for your upcoming transplant, signing up with the first outfit you talk to that displays the red "CEDIA" logo is no guarantee of A/V bliss at project's end. 
</p><p>Here's the problem. Most Cedia shops have roughly the same business model. They have to, in order to survive. If you look hard at the scope of the services they are likely to provide, they do telephone systems, alarm systems, central vacuum systems, intercom systems, lighting control systems, computer networking, commercial A/V and, oh-by-the-way, home theatre. You've undoubtedly heard the term, "Jack of all trades, master of none". That's preciously my Cedia caveat. If you are looking for a truly good air conditioner and would like the choice to be backed with solid information about what you should be considering, you go to an air conditioning specialist, not to Sears. I'm at one of several large wholesalers nearly every day, and I constantly run into guys (with very successful businesses) who are far more interested in price margins and how a flat panel looks when it is turned "off" than any real performance metric when a new product hits the price sheet. Most have barely heard of calibration (audio OR video), let alone offer it to their clients who truly care about quality and performance. To be fair, the larger "houses" may have someone on staff who HAS been trained and specializes in  those disciplines that will determine the ultimate quality of your Home Theatre experience. HT has been steadily growing in popularity, a trend that has not been lost on most Cedia shops and if for no other reason than a defensive move, many have acquired enough knowledge to at least be able to "talk the talk" with prospective clients. Now it's your task to be sure they and also "walk the talk" ... ... ... which gets us to the remaining question, "What questions should I ask?"
</p><p>     
 </p><p>
 </p><p>A truly awesome Home Theatre experience comes from  a combination of roughly equal parts Audio and Video design. Those disciplines have some similarities, but from a "science" perspective, they are two different worlds. You need someone well versed in both to get the most bang for your installation dollar, or, more importantly, to have any hope of Movie nirvana. So a good opening question might be, "Have you been certified in Imaging Science (by ISF or THX). If they say "Imaging what?, thank them for their time and move on. The follow-up question is "What training have you had regarding small room acoustics?". "I have been to Level One and Level Two HAA (Home Acoustic Alliance) classes" is the best answer. "I own a sound-level meter", ... not so much. Even apart from depth of training issues, there is really no substitute for experience. You are not likely to find someone who has done a thousand systems or even several hundred, but "dozens" would be a good start and names and phone numbers a must. Don't confuse # of systems done by a company with # of systems done by the guy who is going to do YOURS! Turnover is a problem with the lesser shops and it's continuity of knowledge you are looking for. Be sure to read their contracts, and don't pay for labor until everything works and you are happy with system operation.
</p><p> 
 </p><p>
 </p><p>B.S. DETECTION. 
</p><p>Even though you may not understand everything you're hearing, have the prospective installer talk to you about the reasons for his particular A/V equipment recommendations, about his calibration process (both audio and video), and about the test equipment he uses. Talk to him about your intended use of the system and try to ascertain if he's listening. My experience is that most people can see through thinly disguised "knowledge" and conversely sense when someone knows what they are talking about without the need for 3-decimal precision. 
</p><p> Shawn, and others doing new construction for their Home Theatre have another whole set of questions to ask regarding room design, but don't short-change any of the previous interrogatories ... they truly will make all the difference between a mediocre movie night and one to remember ... and eager to repeat!
</p><p>
 </p><p>Where to find Superman? Well, you could start with the "Cedia List", but I recommend calling a local wholesaler like AVAD (22 locations in the U.S.) or someone similar who sees lots of Custom Installers. Ask them for names of known companies who SPECIALIZE in Home Theatre. They may or may not be Cedia members. Then, roll up your sleeves and do your homework. 
</p><p>
 </p><p>"I'll take Imaging Science, Alex, for $25,000"</p>
