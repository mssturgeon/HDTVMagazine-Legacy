          <p>The past few weeks have been mostly a blur for me, what with trips to and presentations at the annual Hollywood Post Alliance Technology Retreat the week of February 14, plus presentations to the Delaware Valley chapter of SCTE last Wednesday (my annual CES recap) and the New York City chapter of SMPTE last Thursday (plasma and OLEDs as candidates for reference monitor technologies).</p>
<p>Through it all, I’ve been staying on top of a blizzard of news stories and press releases pertaining to media distribution (over the top, or OTT), the continued decline in packaged media sales and rentals, a new streaming service from Redbox (presumably with Amazon) and a new 3D channel from Comcast.</p>
<p>If you’re not tracking this brave new world of media distribution and consumption on a daily basis, it’s almost impossible to keep up with the changes. At the Tech Retreat, we had an interesting breakfast roundtable discussion on 3D in the home, and whether it was a flop, partially successful, or had any real future.</p>
<p>That discussion also turned to the relative scarcity of 3D movies, which in turn brought up a comment from one of the participants (Ethan Schur of TDVision) as to why more studios didn’t remaster more of their older 3D movie titles into the Blu-ray format.</p>
<p>The reply, as worded by participant Wade Hannibal of NBC Universal, is that the cost to do those remasters probably wouldn’t be justified by Blu-ray disc sales, let alone rentals. Similar comments were offered after we watched a beautiful restoration of Stanley Kubrick’s 1965 masterpiece <em>Dr. Strangelove</em> on Thursday evening. Kudos to everyone involved, but how would Sony Pictures possibly recover its investment, instead of charging it off as goodwill against taxable income?</p>
<p>The fact is; Hollywood does not like streaming at all. At least, not the way Netflix practices it. The revenue stream isn’t substantial enough to replace the lost income from DVD and Blu-ray sales and rentals. But with Netflix now boasting in excess of 20 million subscribers (second only to Comcast) and Blockbuster in Chapter 11 – and possible Chapter 7 bankruptcy – the studios are rapidly losing all of the high-value outlets they once had for selling movies and TV shows.</p>
<p>Along with Jerry Pierce, I moderated a panel discussion at HPA on over-the-top (OTT) video. Panel participants included Dan Holden of Comcast, Jeff Cove of Panasonic, and Dani Grindlinger of TiVo, and the discussions were lively. Is OTT video a real threat to traditional pay TV channel subscriptions? Comcast’s Q4 2010 financial results, released during the conference, would seem to indicate ‘no’ as they only lost about 135,000 subscribers during that time period.</p>
<p>TiVo has made some nice gains with Charter Communications, who will offer their Premiere series of DVRs to customers for traditional pay TV service. But TiVo also supports Netflix, YouTube, and other Internet video channels that could compete with Charter’s bread-and-butter services. Is this tantamount to letting the fox into the chicken coop and hoping he’ll stay honest?</p>
<p>Panasonic, who was among the leaders in pushing 3D last year, now has a Viera tablet PC and their TVs offer a wide range of connected (OTT) services, including Netflix (who else?), Pandora, Skype, Facebook, Twitter, MLB.com and NHL.com. But they’ve also opted for a proprietary ‘apps’ platform, which means that app developers have yet another proprietary format to deal with.</p>
<p>The one company missing from our discussion was (of course) Netflix. Their business lately can best be described as “a house on fire,” and with their stock price in the mid-$200s per share, they don’t need to explain themselves to anyone.</p>
<p>But there will be pushback against the big red N. And that will come with higher rights fees in future licensing agreements from the likes of Sony Pictures, Warner Brothers, Disney, Fox, et al not to mention major TV networks. It’s been pretty much conceded that packaged media (for better or worse) is on the way out, and that digital downloads and streaming are what the marketplace wants.</p>
<p>So the big question is how to make any money from it. Believe me, studios are <span style="text-decoration: underline;">very</span> concerned about future revenue streams, which is why some of them are also discussing a shorter exclusivity window with movie theaters before popular movie titles would be available on pay-per-view (probably for $29.95 or $39.95), a proposal that is being roundly criticized by the North American Theater Owners (NATO) group.</p>
<p>The so-called 28-day reserve period that protects Blockbuster against Netflix and Redbox may also have to go out the window. The latest news from ‘the Block” is that it may shed as many as 600 stores, and that even a move to a streaming model isn’t going to save their chestnuts as studios sue to get millions of dollars back in unsold DVDs and Blu-rays.</p>
<p>However all of this turns out, there will be casualties. Blockbuster looks to be cooked and I don’t see anyone else looking to get into the brick-and-mortar DVD rental/sale model. What DVD/BD sales there are will be handled by the likes of Target, Wal-Mart, Amazon, and even my local Acme market (which had a 3’ x 3’ bin full of $9 DVDs in the candy aisle last week, including recent titles like <em>Kick-Ass</em>).</p>
<p>Netflix will likely pass Comcast in total subscribers by June of this year; maybe sooner (they added 3 million subscribers in Q4 of 2010). Redbox should have its movie streaming service up and running by then, and they may soon be joined by none other than YouTube. What kinds of deals will Hollywood ink with these companies?</p>
<p>One of the great ironies of all this is that Blu-ray player sales are picking up speed as their prices continue to drop. But anecdotal evidence so far is that consumers are buying BD players mostly for Netflix streaming – it’s cheaper than buying a new TV to gain Internet connectivity, and you can always play the occasional DVD or Blu-ray disc if you need to. (And I know where you can find some really good deals on cheap Blu-ray discs, over by the detergent, paper towels, napkins, and household items aisle…)</p>
