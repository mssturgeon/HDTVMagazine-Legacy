          <p>In an attempt to stimulate more sales of consumer electronics, Best Buy has announced a new “buy back” program whereby you can bring back older electronics to the store and Best Buy will buy them on the spot.</p>
<p>That is, for a greatly depreciated amount! And you’ll have to pay a yet-undisclosed amount for the privilege beforehand, which leads me to wonder if this program makes any sense at all.</p>
<div id="attachment_1030" class="wp-caption aligncenter" style="width: 510px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2011/02/Best-Buy-Buy-back-Program-MR.jpg"><img class="size-full wp-image-1030" title="Best Buy Buy-back Program MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/02/Best-Buy-Buy-back-Program-MR.jpg" alt="" width="500" height="447" /></a><p class="wp-caption-text">A still frame from Best Buy's Super Bowl commercial.</p></div>
<p>The Buy Back program – which launched during the recent Super Bowl with a crazy ad featuring (of all people) Ozzy Osbourne and Justin Bieber trying to peddle successive generations of smart phones – works like this. When you pay for your new smart phone, notebook computer, netbook, tablet computer, or television, you buy what amounts to an extended warranty from a company called Chartis WarrantyGuard, Inc.</p>
<p>This ‘agreement,’ for which you pay extra (the Best Buy Web site doesn’t yet spell out much extra), says that you can return your purchase after at least 31 days to any BB store, and they will buy it back on the spot. The actual amount of money you will get depends on the condition of the product and how long you’ve had it.</p>
<p>Not surprisingly, two years is the maximum window for returning any laptops, phones, and tablets, while the return window for televisions is between two and four years. The condition of your device also determines how much you’ll get back, so if you return a notebook computer in good or fair condition (who determines that?) after 6 months, you can expect to recover 50% of your purchase price.  If however, you bring back a smart phone after two years of intense service (i.e. ‘poor’ condition); don’t expect to see more than 10% of what you originally paid.</p>
<p>Oh, and by the way, be sure you bring back ALL accessories with your product, including (from the Best Buy Web site) <em>“…original software, power adapters, cables, pedestals (TV), remotes and batteries. Each Accessory is expected to be in good condition and in working order. Buy Back Amounts will be further reduced at the sole discretion of CWG by the replacement value of each such Accessory that is either not included with your Device or is not in good condition or in working order regardless of the Acceptance Testing Condition Grade that is ultimately assigned to your Device.”</em></p>
<p>And don’t forget your original receipt! Otherwise, you’re dead in the water.<em><br /></em></p>
<p>The sad fact is that most consumer electronic devices have little or no depreciated value after two years (excepting TVs). They are, in a word, ‘consumable’ items. And frankly, you’d be better off trying to sell a two-year-old notebook PC privately on eBay or through the classifieds – or perhaps even donating it (assuming it still works) to a charitable organization for a tax deduction, or an underprivileged family.</p>
<p>Best Buy knows this. They also know that lots of people who buy extended coverages never use them, just as many people never use gift cards they receive at the holidays or on birthdays. So they get some extra up-front cash from you and other customers for taking this plan, then if you are lucky, they’ll pay you back about 30 cents on the dollar after a year.</p>
<p>The Best Buy plan excludes TVs that cost more than $5,000. (Really? Where do you even find TVs that expensive in Best Buy these days? Let’s see…OK, there are 3 models out of 319 TVs listed that top the $5K figure. No worries there.)</p>
<p>Also excluded are desktop computers. And if you don’t like the valuation that Best Buy places on your returned product, there is apparently little you can do. Read this excerpt from the Buy Back program FAQs:</p>
<p><strong>What if I feel that I should receive more back for my product? Will there be room for negotiation and feedback?</strong></p>
<p><em>You’ll know how much your product in good condition is worth upfront, as soon as you buy your product, without guessing or haggling about the price. We do always welcome and value feedback from our customers — just talk to any Best Buy employee for additional information.</em></p>
<p>Well, THAT was helpful. Now, as to where <span style="text-decoration: underline;">your</span> old electronics will wind up:</p>
<p><strong>What is Best Buy going to do with all of the products you buy back? Will they just end up in a landfill somewhere?</strong></p>
<p><em>There are actually multiple channels for reclaimed product:</em></p>
<p><em> </em></p>
<p><em> * Dealtree/Best Buy Outlet (resale)</em></p>
<p><em> * Geek Squad® Service Centers (for parts and refurbs sold via the Best Buy Outline Center online)</em></p>
<p><em> * Recycling</em></p>
<p><em> </em></p>
<p><em> For those items we cannot repurpose, Best Buy ensures the products will be responsibly recycled. Best Buy makes sure that the recyclers we work with adhere to the highest guidelines and standards so that these products don’t end up in landfills and that all hazardous materials are disposed of properly. </em></p>
<p>Yes, some of those “bought back” products will wind up refurbished and resold through Best Buy’s outlets or Dealtree. So if you realize six months in that you really wanted a MacBook instead of an Toshiba Windows 7 notebook, you will get something back for it with little hassle (and don’t forget those accessories!). And Best Buy will ‘pretty it up’ and re-sell it for at least what they paid you for it – and maybe more.</p>
<p>Otherwise, you should probably just skip the Buy Back option altogether and figure that your brand-new $500 Toshiba Satellite notebook computer will cost you $20.80 per month to operate, or about 70 cents a day, and that it won’t owe you anything after two years, when (if you are lucky) Best Buy will give you $100 for it – a figure you could probably match on eBay, or even at a garage sale.</p>
<p>Oh, and did I mention that you will be paid for your Buy Back item with a Best Buy gift card, and <span style="text-decoration: underline;">not</span> cash? (Read the boilerplate on the <a href="http://www.bestbuy.com/sb11/buyback.html" onclick="javascript:pageTracker._trackPageview('/outbound/article/www.bestbuy.com');">Best Buy Web site</a>.) Such a deal!</p>
<p><em>NOTE: The Buy Back program is free through February 12. After that, you will have to pay to enroll in the program. </em></p>
