	<p>The reason for this is <strong>straightforward</strong>, but a full explanation takes more space than I have here. Here&#8217;s the problem in a nutshell. A 3DTV (or cinema or any other stereoscopic 3D image device) must deliver <strong>different images to the left and right eyes </strong>of the viewer. If there is just one viewer watching, it&#8217;s pretty simple. (3M has <a href="http://solutions.3m.com/3MContentRetrievalAPI/BlobServlet?locale=en_US&#038;lmd=1280414246000&#038;assetId=1273661049961&#038;assetType=MMM_Image&#038;blobAttribute=ImageFile">a very clever stereoscopic technology </a>for single-viewer screens.) When you have multiple users, however, it is<strong> far more difficult</strong> to control how the left and right images are delivered. Obviously <strong>it can&#8217;t work </strong>if the left eye of one viewer is in the same line as the right eye of another viewer (which is <strong>a common situation </strong>when cuddling is involved). All the current technology that I know about requires that you <strong>sit in specific &#8220;sweet spots&#8221;, </strong>and all the screens of this sort that I have seen have<strong> fewer than 10 sweet spots</strong>. It is possible that there may be some technology over the horizon that can <strong>&#8220;steer&#8221; the images </strong>a bit using face-recognition and head-tracking technology, but that still has <strong>some severe limitations </strong>and still does not solve <strong>the &#8220;cuddle&#8221; scenario</strong>.</p>
	<p>Look, I understand that many people think that <strong>the glasses are goofy</strong> and they don&#8217;t want to wear them for one reason or another. But it&#8217;s not reasonable to expect an <strong>affordable autostereoscopic </strong>flat panel technology within the next five years that will provide <strong>a natural viewing experience</strong>. If there was a way to do this, don&#8217;t you think that the movie theaters would have <strong>jumped on it</strong> already?</p>
	<p>The problem is that others in the media <strong>persist on holding out the hope </strong>that there will be some solution coming soon. You can find lots of examples if you search the Web, but the one that set me off on this rant was a segment on NPR&#8217;s &#8220;Weekend Edition Saturday&#8221; in which &#8220;Popular Science&#8221; magazine&#8217;s editor-in-chief Mark Jannot <a href="http://www.npr.org/2011/01/01/132548988/What-Tech-Gadgets-Will-2011-Put-In-Your-Pocket">said the following</a>:</p>
	<blockquote><p>&#8220;So the great trend that we&#8217;re seeing emerge is glasses-free 3D, naked-eye 3D, and it&#8217;s already sort of about to emerge on the Nintendo 3DS handheld game. And that&#8217;s the way it&#8217;s going to emerge in this year, on small screens and smartphones and things like that. But within the next couple of years, we should see actual TV screens where you can watch your shows and your sports in glorious 3D without having to look like a geek.&#8221;</p></blockquote>
	<p>I don&#8217;t know <strong>what technology</strong> he expects to be here in &#8220;the next couple of years&#8221; that can do this affordably, if at all. And I believe that if the American consumers think that <strong>wearing glasses is goofy</strong>, they&#8217;re going to think that having to sit isolated in a specific location in their living room in order to watch 3DTV without glasses is <strong>just plain stupid at any price</strong>.</p>
	<p><em>I&#8217;m going to be at CES 2011 this week starting tomorrow, and you can be sure I&#8217;ll be asking the HDTV makers about their plans for autostereoscopic 3D features. If I find out anything that contradicts what I&#8217;ve said here, I&#8217;ll let you know.</em>
</p>
