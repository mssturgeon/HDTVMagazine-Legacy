          <p>You see them at trade shows and technical conferences. They’re available (by mail) from Staples and other retailers. Nikon has a digital camera (CoolPix S1000PJ, about $399) with a built-in projector, and Sony just announced three new models of camcorders equipped with projectors (HDR-PJ50V, $1000; HDR-PJ30V, $950, and HDR-PJ10, $750) at CES.</p>
<p>But who’s using them? Have you seen any in use for an office or classroom presentation? Do any of your friends and neighbors own a picoprojector? None of mine do, and I know a lot of ‘cutting edge’ techno freaks.</p>
<p>In my most recent <em>Wake-Up Call</em> e-blast for Pro AV magazine, I asked the same questions. Aside from trade show like CES and InfoComm and technology conferences such as SID, I have yet to see one of these little buggers in actual use.</p>
<p>Last night, on my way out of the local Giant grocery store, I passed by Larmon Photo, a regional camera retailer based in Abington, PA.  I’ve known the folks at Larmon for many years and have purchased quite a few digital cameras there.</p>
<div id="attachment_1021" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2011/01/Nikon-CoolPix-S1000PJ-RS-MR.jpg"><img class="size-full wp-image-1021" title="Nikon CoolPix S1000PJ RS MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/01/Nikon-CoolPix-S1000PJ-RS-MR.jpg" alt="" width="600" height="450" /></a><p class="wp-caption-text">Nikon's S1000PJ digital camera with built-in projector.</p></div>
<p>Larmon is an authorized Nikon dealer and sells a ton of Nikon digital SLRs and CoolPix point-and-shoot cameras. So that means they’d also carry the CoolPix S1000PJ in their line.</p>
<p>I asked my friend at the store if they carried the camera, and indeed they have since it was launched in the fall of 2009. But have they sold any of them since then? Not a one.</p>
<p>In fact, he said they had never gotten a single inquiry about the S1000PJ, but they have moved bucket loads of other, less-expensive CoolPix cameras in the past year and a half.</p>
<p>Last week, I had lunch with a client who works for a second-tier projector manufacturer. (His company doesn’t sell picos, by the way.)  His comment was that he regarded picoprojectors as ‘rebound’ products – that is, they are frequently returned to AV dealers after purchase. The most common reason was ‘it’s not bright enough.’ (In fact, one of his dealers reported he had customers trying to return more picoprojectors than he had originally sold!)</p>
<p>Picoprojectors have two things working against them. First, most of them are simply too dim. How big an image can you reasonably project with 10, 20, or 30 lumens? Even 50 lumens isn’t much to start with when you are making a small group presentation. You’d be better off using a larger notebook computer screen, as you wouldn’t have to dim the room lights.</p>
<p>Secondly, picoprojectors are EXPENSIVE. Really! Staples sells a few models of picoprojectors – all of which must be ordered by mail with a 5 – 8 day delivery cycle, no stores carry them – and they start at $300 (Optoma PK201, 20 lumens, 852×480 resolution). Staples also carries the Optoma PK301 (50 lumens, 854×480 resolution, $400) and the 3M MPro 150 (15 lumens, 640×480 resolution, $400).</p>
<div id="attachment_1022" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2011/01/3M-Mpro-150-Side-View-MR.jpg"><img class="size-full wp-image-1022" title="3M Mpro 150 Side View MR" src="http://www.hdtvexpert.com/wp-content/uploads/2011/01/3M-Mpro-150-Side-View-MR.jpg" alt="" width="600" height="450" /></a><p class="wp-caption-text">3M' MPro 150 pocket projector.</p></div>
<p>Hmmm…For $360, you can buy an NEC NP115 (800×600 resolution, 2500 lumens) that weighs all of 5 pounds, and will project big images on just about any surface under full room lighting. It doesn’t fit in your pocket, but has three video inputs and varifocal lens.</p>
<p>See the problem here? $400 is a lot of money to spend on something that can barely light up a sheet of paper three feet away. And yet, numerous companies are spending lots of money to develop and bring these products to market, including Texas Instruments, 3M, Optoma, Vivitek, Syndiant, Microdisplay, and ViewSonic.</p>
<p>In my <em>Wake-Up Call</em> newsletter, I mentioned that I saw tablet computers as a direct threat to picoprojectors. And apparently a good part of the picoprojector industry agrees, according to a January 3 press release from Pacific Media Associates, which surveyed pico manufacturers and suppliers about the present and future market for picos. (Apparently, 70,00 of them were sold in 2010 – who knew?)</p>
<p>I noticed several negative user comments about picos, mostly focused on low light output and how impractical the projectors turned out to be.  Here’s one comment from the Staples Web site: <em>“Performance leaves a LOT to be desired. Product says it has adjustable brightness, but was too dim to use in a room with any light what so ever, and brightness would not adjust. Might be a good item for a very small room with no light and limited attendees.” </em>Here’s another. <em>“No practical use for this product. Great for use in a closet!”</em></p>
<p>To be fair, there were also a couple of positive reviews of this particular pocket projector. But there are no user reviews of the two other picoprojectors on the Staples Web site so far, even though they’ve been available for over a year.</p>
<p>At CES, TI had a demo room full of picos – built-in to cameras and tablets, as well as stand-alone models with brightness ranges approaching a more practical 500 lumens. But 500 lumens isn’t a real pico; it’s just an underpowered ultraportable projector. Most of the demos were just too dim to be of any practical use.</p>
<p>So I repeat my question. Does anybody use picoprojectors? Does anybody even want a picoprojector?</p>
<p>How about you?</p>
