          <div id="attachment_1434" class="wp-caption aligncenter" style="width: 610px"><a rel="attachment wp-att-1434" href="http://www.hdtvexpert.com/?attachment_id=1434"><img class="size-full wp-image-1434" title="Sharp Elite LCD TVs" src="http://www.hdtvexpert.com/wp-content/uploads/2011/08/Sharp-Elite-LCD-TVs.jpg" alt="" width="600" height="374" /></a><p class="wp-caption-text">These Elite sets may look great, but you can't get by on looks anymore in the TV game.</p></div>
<p>Last Thursday in New York City, Pioneer and Sharp took the wraps off a new line of high-end LCD TVs that will carry the familiar Elite brand. These products are intended to fill a hole in the high-end television retail channel; one that was created when Pioneer pulled the plug on their Kuro plasma sets a couple of years ago.</p>
<p> </p>
<p>For readers who didn’t know, Sharp owns a 14% stake in Pioneer, and the two companies have collaborated on products in the past. You may not remember, but Sharp once carried 42-inch and 50-inch Pioneer plasma TVs in their line. That was back in the day when large LCD panels were difficult to manufacture and very expensive.</p>
<p> </p>
<p>It’s instructive here to remember why Pioneer pulled out of the plasma TV business. First off, Pioneer had the smallest fabrication capacity of any of the big plasma brands, cranking out a fraction of the monthly yields of Panasonic and Samsung.</p>
<p> </p>
<p>Second, Pioneer made the mistake of continuing to focus only on high-end retail channels for their plasma TVs long after it was clear that the plasma market was being commoditized. Panasonic’s best plasma TV sets were widely available through numerous brick-and-mortar stores for much lower prices and offered comparable performance to Pioneer’s offerings.</p>
<p> </p>
<p>Even the vaunted Kuro sets couldn’t compete. Sure, they had super-deep black levels. But the additional first surface polarizers used to pull off that trick also dropped brightness levels to the point where the Kuro sets had to be viewed in dark or near-dark rooms. Panasonic, Samsung, and LG suffered from no such limitations.</p>
<p> </p>
<p>In the end, the math is what did Pioneer in. You can’t make money these days selling a mass-produced flat screen display product in limited quantities at a price premium. It simply will not work. That is one reason why Hitachi exited the plasma TV business and ultimately the LCD TV business in the United States.</p>
<p> </p>
<p>It appears that Pioneer didn’t learn that lesson. Neither did Sharp, who has a seen a precipitous drop in LCD TV market share since 2006. The Aquos brand, which once commanded better than 20% of the U.S. TV market, now struggles to hold onto 3% of it. Even the new Quattron four-color LCD TVs have met largely with yawns, and it doesn’t help that TVs are a tough sell in general these days. (Notice how even market giant Vizio has been pushing tablets and phones lately?)</p>
<p> </p>
<p>According to a story in TWICE, the motivation for the new Elite LCD TVs came from Cedia dealers who said there was a definite hole in the market after the Kuro sets were discontinued and Runco shut down its Vidikron brand. (Runco/Planar’s misadventures in the home theater channel are another story altogether.)</p>
<p> </p>
<p>Hence, Sharp and Pioneer created an Elite sales and marketing channel, with Sharp providing the TVs and Pioneer supplying Blu-ray players and AV receivers. The Elite TVs will be sold exclusively in North America, limited at first to about 750 dealers with the possibility of expansion into a larger base.</p>
<p> </p>
<p>Elite dealers can either order TVs directly from Sharp or through a one-step distribution process. That last sentence should give pause; moving products to distribution guarantees that prices will drop over time and more retail outlets will be found to increase the volume of sales, thereby removing the ‘elite’ part of the equation. That’s what distributors do, unless they’re not serious about making money.</p>
<p> </p>
<p>If this is such a good idea, why haven’t Sony and Samsung taken a similar approach? <a href="http://www.hdtvexpert.com/?p=1405">Sony’s woes with TV profitability are well-documented</a>, while Samsung (and LG, and even Panasonic) recognized that mass-produced products can’t be sold in onesies and twosies for very long. But with Sharp’s inability to reverse its six-year slide in TV market share and Pioneer’s apparent jonesing to get back into the TV business, it appears both companies will give any idea a try these days.</p>
<p> </p>
<p>For the record, the two Elite models that were launched were the 60-inch PRO-60X5FD, shipping this week for $5,999, and the 70-inch PRO-70X5FD, shipping later this month for $8,499. Those same screen sizes in the Aquos LCD TV line can be had for about $3,300 and $4,800, respectively.</p>
<p> </p>
<p>The usual hype accompanied the press event, with Pioneer claiming these sets have the best black levels in the LCD TV business (that’s not saying much) and no competitors can come close. Sound familiar?</p>
<p> </p>
<p>Here’s something else to think about. According to HIS iSuppli research, the “sweet spot” for U.S. TV sales is in the range of 40 to 49 inches. In the first quarter of 2011, that bracket accounted for 40% of all TV sales. The #2 position was occupied by the 30 – 39 inch group with 25% of all TV sales. In short. these two categories combined accounted for two out of every three TVs sold in this country from January through March.</p>
<p> </p>
<p>Screens measuring 50 inches and larger represented 23% of all TV sales in that same time period. Although iSuppli didn’t drill down, I’d bet that 60 to 70 percent of the TVs sold within that category measured between 50 and 55 inches. That doesn’t leave a lot of market share to play with, if you want to sell 60-inch and larger screens.</p>
<p> </p>
<p>My colleague Ken Werner of Nutmeg Consulting repeatedly asked Pioneer execs how many units they would have to sell to be profitable and how many units the professional AV and Cedia channels could absorb at the retail prices announced, but couldn’t get a straight answer.</p>
<p> </p>
<p>That’s probably because no one at Pioneer (or Sharp) had taken the time to crunch the numbers. The scenario was reminiscent of the Kuro launch a few years back when similar questions were asked. Ken and I quickly ran our own numbers and figured out that the Kuro venture was probably doomed from the start. Again, it’s all about the numbers these days – competitive prices and volume of sales.</p>
<p> </p>
<p>Sharp has additional pressure on it to perform, given that it built the world’s only Gen 10 LCD fab a couple of years ago in Sakai, Japan. Sony was supposed to hold a 34% stake in the fab, but has capped its investment below 10% and is instead looking to China for lower-cost LCD TV panels. What will Sharp do with all of that capacity? And the fact that their finished panels are too expensive when compared to Korean and Chinese glass?</p>
<p> </p>
<p>You can’t exist on high-end TV sales alone. Mitsubishi was the latest company to figure this out and underwent a massive re-organization this past spring to try and salvage what’s left of their rear-projection TV operations. Sony has lost so much money in the television business that it may have to walk away from manufacturing altogether and just private-label Chinese-made products in the future.</p>
<p> </p>
<p>Wishing won’t make it so.</p>
