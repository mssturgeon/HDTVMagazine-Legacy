</p><p>So on these "service" topics, here's the thing.
</p><p>First for some definitions. Often the terms "Serviceability" and "Useful life expectancy" get interchanged and confused.
</p><p>Indeed, they are quite different things. Serviceability used to mean "how many screws do I have to take out of the chassis cage to get at that leaky filter capacitor in the power supply".
</p><p>Forget serviceability. We don't do that anymore. There is precious little we can do inside any modern day "box", other than bridge a high voltage terminal to ground with a forefinger and discover that our vocabulary was far more colorful than we had previously imagined. I confess that once, while chasing a "chassis buzz" I removed a back panel from a PDP (mostly because I hadn't done it before and was curious). Miraculously, I avoided electrocution.
</p><p>Even "Authorized Repair Centers" do little in the way of repair today, at least for flat panels. About six months ago I contacted one such service center regarding a potential repair of a 37 " plasma that suddenly died. I'd bet my mortgage it was the power supply. After providing make and serial# of said panel, the answer quickly came back "There are no replaceable parts for that unit". The panel was less than 4 years old. I think that's shameful, and it's just one more beef I have with a manufacturer who should remain nameless - they should, but their name starts with "S" and ends with "G". 
</p><p>The days of pulling out the vacuum tubes and heading down to the drug store for testing are over! (opps, I think I just lost about 2/3 of the readership ...)
</p><p>So to me, "Serviceability" simply means "How long will the manufacturer commit to any attempt at repair" and "What's the backlog at the nearest Service Center". For front projectors, specifically, I would add to that, where did they put the lamp compartment - or, what kind of contortions do I have to go through, while standing on a ladder, to replace the lamp?  ... or, do I have to take the damn projector and mount down off the ceiling, remove the mount to get at the lamp door, replace the lamp, re-assemble the mount, put it all back on the ceiling and then readjust the screen geometry. In case you couldn't tell, that sequence was fresh in my mind! 
</p><p>The question Greg (and the rest of us) would love to know the answer to  is, "What is the MTBF ............ (mean time between failure)", which gets us to the other issue, product Life Expectancy.
</p><p>Useful Life Expectancy is a whole other kettle of fish. Publish data? ... oh, would that we could. First of all, no manufacture that I know of would actually release that data if they knew it, unless, of course, like all marketing data, they thought they could justify the largest number.
</p><p>...and why wouldn't they know it? Consider the case of a display device used primarily as a TV. Most people's expectations (grounded in ancient time - CRTs) are that a "set" should provide a useful life of 10 to 12 years. Reasonable. If the average "on cycle" is 6 hours/day (less during the week, more on weekends and holidays), then to life test such endurance you would have to run a display 24/7 for 3 years to get a "pass" and be able publish hard data. By that time, any particular model would be 4 to 6 generations old. Nobody would care. If any manufactures are still life testing it's probably to compare actuals with design goals and thereby "calibrate" the design team for future products.
</p><p>Unfortunately, Greg cited unusually bad luck with successive front projector purchases from Sony, Hitachi and Sanyo, never  getting beyond 2,000 hours with any of them. No wonder he wants more data!
</p><p>Having installed nearly 1,000 displays in Home Theatres and having visibility to thousands more through calibrations, I can assure you that the industry is much, much better than that. They are not building "throw away" projectors. In most projectors, the "temporary limiter" is the lamp - often spec'ed at 2,000 hours, twice that in economy mode. I have dozens of front projectors that I installed 10+ years ago and have only had to do lamp replacement since. The number of projectors that have failed inside of 5 years I can count on one hand and all of those were repairable. I suppose it should be noted that "judicious selection" played a hand in all that. I will concede that returning a front projector to the manufacturer is not a happy task.
</p><p>So here's what I believe. Although there are several variables involved (REAL on time, calibrated or not, cleanliness of the environment, etc.), on average, most front projectors you would buy today will last at least 10 years.
</p><p>I also believe it doesn't matter.
</p><p>We are at a point in the evolution of the underlying technology that you are certain to want something else long before your last purchase dies. Admittedly, I haven't done the exact accounting, but as I think about all the past projector/screen installs I can recall, I believe they have all "turned over" on something closer to a 5 year cycle. Most people who invest in front projection are truly seeking a quality movie experience, so when the state-of-the-art advances, they want to "keep up".
</p><p>Greg, I don't know where you live, but if you are anywhere in the western 13, I'd be happy to change your luck. I hereby offer to specify, install, calibrate and warranty a 10 year happy life with your next front projector. Sounds like you deserve it!</p>
