<p>The quantum-dot approach produces narrow spectral emissions for blue, red, and green, whereas the conventional approach produces a broad spectrum relatively weak in red and green components. Critically, the center wavelength of a quantum dot’s emission can be adjusted very precisely, primarily by adjusting the diameter of the dot when it is made. The result can be – if the panel designers choose to make it so — a larger color gamut and more saturated colors that result in an almost OLED-like appearance.</p>
<p>QD Vision and competitor Nanosys (Palo Alto, Calif.) have both been developing quantum-dot solutions for some time. Nanosys has been the more visible over the last two years, showing prototype small- and TV-sized systems, and announcing development relationships with LG Innotek and Samsung. At the SID show in Boston in May 2012, Nanosys and 3M announced Quantum Dot Enhancement Film (QDEF), which incorporated Nanosys quantum dots in a 3M diffuser sheet protected with moisture protection film.</p>
<p>Nanosys started its display backlight work with a prism-shaped optical element not unlike the one now being used by QD Vision. Nanosys CEO Jason Harlove has told me that the change to the diffusion-sheet approach was appreciated by BLU makers, because it required no change at all in their assembly procedures. And the alliance with 3M – with its proven record of supplying customer-ready optical enhancement films to BLU and panel makers – was considered a major step forward within the industry.<br />
Meanwhile, QD Vision only talked about relatively minor applications for LED lighting. So Sony’s announcement of Triluminos in soon-to-ship TV models came as a surprise, even to those of us who think we follow this business closely. Coe-Sullivan told me that QD Vision and Sony had been carefully working in stealth mode, and that QD Vision had been waiting for its customer Sony to make the first announcement.</p>
<p>Let me step back. Nanosys’ Hartlove’s explanation for switching from a prism to a sheet quantum-dot optical element is very plausible, and 3M seems happy to be involved in QDEF development. But QD Vision’s Coe-Sullivan has another take on the transition. In a conversation with Coe-Sullivan at CES, he told me that Nanosys’ quantum dot materials could not handle the luminous flux and heat loading that derived from having the quantum dots in a polymer prism right next to LEDs. Moving to a sheet optical element reduces the flux and heat loading tremendously, but it also requires that much larger quantities of quantum-dot materials must be used. According to Coe-Sullivan, much of QD Visions’s development work was in developing materials that could take the high heat loading associated with the polymer prism element’s position near the LED strip. The engineering and staff training required to change the BLU assembly to accommodate the prism, Coe-Sullivan implied, was more than worth the substantial savings in quantum-dot material.</p>
<p>The color improvement in Sony’s Triluminos sets is obvious, and the overall appearance is quite OLED-like, although without OLED’s very deep blacks, very wide viewing angle, and very fast response time. Still, quantum-dot backlights narrow the image-quality gap between LCD and OLED tremendously. Given OLED-TV’s very high projected prices, and the delays in bringing OLED-TV to market at any price, Sony’s Triluminos (and its competitors that are sure to come from other vendors) has a very exciting window of opportunity.</p>
<p>Yet another spin on quantum-dot BLUs is combining them with 4K (Ultra HD) screens. 4K provides a remarkable sense of depth, particularly with contrasty images. Combining the saturated colors of quantum dots with 4K should provide an even more remarkable three-dimensional feeling with 2D images. That could make stereoscopic 3D even less relevent for consumer TV than it is today. Sony seems to understand this: Two of the Triluminos models on display at CES were 4K.</p>
