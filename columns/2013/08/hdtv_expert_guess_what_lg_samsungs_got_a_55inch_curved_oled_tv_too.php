<div id="attachment_3354" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-3354" alt="Remember the Pioneer KURO plasma TVs? These look even better." src="http://www.hdtvexpert.com/wp-content/uploads/2013/08/OLED-Beauty-Shot-2-WR.jpg" width="600" height="409" /><p class="wp-caption-text">Remember the Pioneer KURO plasma TVs? The KN55S9Cs look even better than those. And they&#8217;re brighter, too.</p></div>
<p>One reason may be that Samsung is getting better-than-expected yields on their large OLED panels. (The company confirmed that, but would not be specific about actual yields.) I’ve heard that LG Display’s yields range anywhere from 10% to 30%, but would think the lower number is more realistic. So Samsung may be seeing yields in the range of 20% or so.</p>
<p>The pixel structure in the KN559SC is intriguing. There are actually two dark blue pixels for every single red and green pixel. (See photo.) And Samsung claims to have some sort of brightness compensation circuit to offset differential aging of the dark blue pixels. Well, running two of them at half-brightness would certainly extend their half-brightness lifetime. (The blue color materials are licensed from Universal Display Corporation in Ewing, NJ.)</p>
<div id="attachment_3356" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-3356" alt="This micro view of the KN55S9C shows the red, green, and blue pixel array. Notice that the blue pixels are twice the size of the red and green pixels." src="http://www.hdtvexpert.com/wp-content/uploads/2013/08/TCU-OLED-Pixels-2.jpg" width="600" height="401" /><p class="wp-caption-text">This micro view of the KN55S9C shows the red, green, and blue pixel array. Notice that the blue pixels are larger than the red and green pixels.</p></div>
<p>One cool feature that Samsung showed was MultiView. OLEDs, being emissive devices like plasma display panels, have very fast on/off cycling speeds. So switching at high frame rates like 120 and 240 Hz is a walk in the park for them.</p>
<p>Samsung uses this characteristic to show two different video programs simultaneously, using 3D active shutter glasses to open on either the even or odd-numbered video frames (not fields). With MultiView, one person could be watching a basketball game while the other is enjoying a soap opera. Texas Instruments also showed this trick over a decade ago at CES and CEDIA Expo, using Samsung DLP rear-projection TVs.</p>
<div id="attachment_3352" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-3352" alt="Samsung's MultiView technology lets two viewers watch two different TV programs at the same time (even 3D) while wearing active shutter glasses." src="http://www.hdtvexpert.com/wp-content/uploads/2013/08/MultiView-OLED-Demo-WR.jpg" width="600" height="450" /><p class="wp-caption-text">Samsung&#8217;s MultiView technology lets two viewers watch two different TV programs at the same time (even 3D) while wearing active shutter glasses.</p></div>
<p>&nbsp;</p>
<div id="attachment_3348" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-3348" alt="It would take a lot of upstage an 85-inch 4K TV...and apparently, a 55-inch curved OLED TV is &quot;a lot.&quot;" src="http://www.hdtvexpert.com/wp-content/uploads/2013/08/4K-TV-Demos-MR.jpg" width="600" height="378" /><p class="wp-caption-text">It would take a lot to upstage an 85-inch 4K TV&#8230;and apparently, a 55-inch curved OLED TV is &#8220;a lot.&#8221;</p></div>
<p>Almost overlooked at the event were Samsung’s UHD TVs. In addition to 55-inch and 65-inch models, the new 85-incher took a bow (I saw it previously at NAB and CES). These sets have spectacular image quality, but you’ll pay about $1K per diagonal inch for the smaller sets and a cool $40K for the 85-inch version. Look for major adjustments on those prices as the Chinese TV manufacturers start pushing more 4K product into the US market.</p>
<p>All of these TVs come with Samsung’s Smart TV Smart Hub feature, and each is future-proofed with the Evolution Kit interface for OS and other updates. One trend we’re starting to see is exterior frames with suspended TV screens inside them, as the 85-inch and 110-inch LCD sets from CES were shown. Now, the KN559SC borrows from this styling with a glossy black frame surrounding the TV, giving the impression that it floats. Pretty cool.</p>
<p>Will we see comparable products from Sony and Panasonic? Both companies have shown 56-inch 4K OLED TVs, but these products aren’t anywhere near ready for prime time. And Sony’s introduction of quantum dot backlights on their Triluminous LCD TVs took color reproduction to a new level, probably extending the dominance of LCD technology for a few more years.</p>
<p>Keep your eye on both the LG and Samsung TV products to see if (a) market demand is there, even at these higher prices, (b) differential aging of the blue pixels manifests as a problem or not, and (c) 4K versions of these products are announced later his year, or at the 2014 CES. That will tell you how committed both companies are to the technology&#8230;</p>
