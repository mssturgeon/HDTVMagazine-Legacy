				<p>Yesterday at the cavernous Cipriani’s Restaurant in New York City, Samsung let us in on what had to be the worst-kept secret of 2013: They’re bringing a 55-inch curved OLED TV to market.</p>
<p>By “worst-kept,” I don’t mean to imply that any Samsung employees or PR agency personnel broke any embargo rules. No, they did a fine job keeping mum until the noontime press conference.</p>
<p>But Samsung had previously shown this product at CES. And so had LG (three of ‘em, to be exact). When LG announced earlier this month that they had begun shipments of their $15K 55-inch curved OLED, you just knew that Samsung would answer in short order with not just one, but multiple volleys.</p>
<p>And answer they did! The KN55S9C is Samsung’s official entry into the OLED television market. Like the LG product, it has a slight curved screen. Unlike LG’s version, it uses RGB OLED emitters (LG employs a white OLED emitter design with color filters). And unlike the LG product, Samsung’s OLED TV will sell for less than $10,000.</p>
<p>In fact, the SRP for the KN559SC is $8,999.99 (OK, let’s round it up to $9,000), which should result in a price drop from the folks in Englewood Cliffs pretty quickly. Analysts have wondered just where the market for OLED TVs would start, and $10K is quite a bit below where I targeted.</p>
