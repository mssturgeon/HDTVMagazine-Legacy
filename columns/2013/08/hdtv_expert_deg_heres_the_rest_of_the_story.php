				<p>The headlines sure look impressive: <i>“Overall Consumer Spending on Home Entertainment Up 2 Percent in First Half of 2013!” “Blu-ray Disc Sales Up 15 Percent Over Mid-Year 2012!” “Electronic Sell-Through Surges 50 Percent!”</i></p>
<p>Yes, it’s the latest <a href="http://www.dvdinformation.com/pressreleases/2013/DEG%20Mid-Year%202013%20Home%20Entertainment%20Report.pdf">Home Entertainment Report</a> from the Digital Entertainment Group, the industry association that promotes the Blu-ray disc format, and to a lesser degree digital downloads and Internet streaming of movies and TV shows.</p>
<p>The DEG’s original mission (and its predecessor&#8217;s, the Blu-ray Disc Association) was to push Blu-ray into every home as a replacement for the standard-definition red laser DVD. But a funny thing happened along the way while the Blu-ray and HD-DVD camps were slugging it out: Consumers discovered streaming, specifically from Netflix. And many of those same consumers decided they didn’t need an optical disc format anymore.</p>
<p>DVD sales began to tank in 2005, and DVD rentals starting falling off a few years later. The popularity of video-on-demand (streaming, downloads) grew so quickly that it surpassed the revenue from optical disc sales and rentals in 2011, and quite frankly, very few people saw that coming.</p>
<p>The problem with streaming and digital downloads is that they’re not as profitable as selling and renting optical discs, or “packaged media” as Hollywood calls them. Blockbuster found this out the hard way, as did Hollywood Video a few years earlier. And 3D did absolutely squat to boost the fortunes of the Blu-ray format after all of the hullaballoo died down.</p>
<p>It would appear that consumers who want to watch movies have decided they don’t need an actual physical copy sitting on their shelf. All they need is “anytime, anywhere” access to that movie. The net result is $4 and $5 rentals of Blu-ray quality movies through iTunes, Nook, Amazon, and other online stores…and not sales of $20 and $25 Blu-ray combo packs at Best Buy, Wal-Mart, and Target.</p>
<p><i>So what’s with the skepticism?</i> you may ask, given the upbeat headlines from DEG. Hmmm…If you scan the press release in more detail, you’ll find these gems hidden within:</p>
<p>* Overall DVD and Blu-ray disc sales <span style="text-decoration: underline;">fell</span> 4.7% Y-Y to nearly $3.6 billion in the first half of 2013.</p>
<p>* Overall rental revenue, including digital, <span style="text-decoration: underline;">fell</span> more than 5.5% Y-Y to nearly $3.1 billion.</p>
<p>* DVD/BD rentals from physical stores like Blockbuster <span style="text-decoration: underline;">fell</span> 12.6% Y-Y to $522 million.</p>
<p>* Subscription-based DVD/BD rental revenue <span style="text-decoration: underline;">declined</span> nearly 21% Y-Y to $531 million.</p>
<p>* Revenue from DVD/BD kiosks <span style="text-decoration: underline;">fell</span> nearly 4% Y-Y to $955 million.</p>
<p>Notice the underlined words “fell” and “declined.” And how they all apply to optical disc formats. These trends haven’t changed significantly in the past eight years for DVDs, and an uptick in revenue from the sale of Blu-ray movies (usually in combo packs with DVDs and a digital copy) to the tune of 15% so far this year hasn’t been enough to offset any of these trends.</p>
<p>DEG, who has been known in the past to cherry-pick the data but not fill in the blanks, also stated that <i>“Consumers bought more than five million Blu-ray compatible devices during the first six months. There are now more than 61 million Blu-ray players in U.S. homes.” </i></p>
<p>An interesting data set, but the big follow-up question is; how exactly are those &#8220;Blu-ray compatible devices and players&#8221; being used? Keep in mind that iPads, Galaxys, Kindles, and Nooks are in one sense &#8220;Blu-ray compatible devices&#8221; in that they can play back 1080p movies with 8-bit color. As for those 61 million Blu-ray players &#8211; are they functioning more often than not (as my experience tells me) as low-cost streaming media boxes, with the occasional BD loaded up now and then? DEG doesn’t say, so the number hasn’t any real significance right now.</p>
<p>Well, what was the good news, if any? For starters, video-on-demand services were up 6.9% Y-Y, earning nearly $1.1B.  And subscription-based streaming (read: Netflix) saw a gain of 32% Y-Y, generating about $1.5B in cold hard cash for studios and media conglomerates. And total home entertainment spending in the USA hit $4.63B for the first six months of this year, up 3% Y-Y.</p>
<p>In other words; streaming and downloads are in, physical disc rentals are on the way out. And to some degree, so are physical disc purchases. And that’s a perfectly logical development: If you can access any movie any time you want on any device, why on earth would you buy a physical copy of it that you might watch only once or twice?</p>
<p>As has been pointed out to me on more than one occasion, streaming doesn’t provide anywhere near the quality of a blue laser optical disc. True, and you also don’t see “buffering” on-screen messages or suffer through locked-up I-frames when watching a Blu-ray disc, unless your BD player has a problem.</p>
<p>Lately, I’ve been renting movies in HD resolution (1080p/60) and downloading (not streaming) them to my Nook HD+. I can watch them on a plane, anywhere in my house, or even on my family room TV or through my home theater projection system simply by plugging in an HDMI cable.  That’s pretty doggone convenient, and easy to carry around.</p>
<p>New releases usually command a $4 to $6 rental fee at the Nook store and I have 30 days to watch any movie after paying for it. I downloaded two movies for a recent flight to Italy (<i>Amelia</i> and <i>The Great and Powerful Oz</i>; I passed on <i>Flight</i> for obvious reasons!) and while I enjoyed both of them, I have no desire to own either movie or rent them again. I suspect I’m not unlike many consumers in feeling that way.</p>
<p>Long story short; while the DEG headlines raised my eyebrows, the true story behind the numbers did not. DEG’s data clearly indicates that the trend away from physical media continues to accelerate, albeit slowly. What that means for the BD format in the near future is uncertain, particularly when MPEG4 H.265 (HEVC) is implemented in a couple of years and we will be able to stream 1080p/60 content at 2-3 Mb/s – slow enough for the average cable Internet connection.</p>
<p>And that’s the rest of the story…</p>
