<p>For the third year in a row, shipments and sales of digital cameras have declined worldwide – and the decline is accelerating, based on the latest numbers I’ve been able to find.</p>
<p>Canon, a venerable, 80-year-old Japanese company who has successfully weathered recent downturns in CE sales that have brought its competitors to their knees, announced a couple of months ago that sales of single-lens reflex digital cameras with interchangeable lenses fell for the first time in 2013 and would be off by at least 10% by year’s end, having a direct negative impact on the company’s bottom line.</p>
<p><a href="http://www.bloomberg.com/news/2013-10-24/canon-cuts-full-year-net-income-forecast-as-camera-sales-slow.html">According to a story on the Bloomberg News site,</a> Canon said net income would likely total 240 billion yen ($2.5 billion) for the year ending December, cutting its earlier forecast of 260 billion yen. According to the Camera &amp; Imaging Products Association in Tokyo, the value of worldwide camera shipments dropped 19 percent in August from a year earlier, representing a ninth consecutive monthly decline.</p>
<p>The final tally for 2013 won’t be available until late January, but you can already see the effects of this slide in sales, which started in 2011. The year-to-year data compiled by CIPA in December of 2012 revealed that worldwide shipments of point-and-shoot digital cameras had plummeted by an astounding 40%. Still, it was assumed that higher-priced, fully-featured digital SLRs would be immune from the onslaught of smartphones with improved cameras and lenses.</p>
<p>Now, we know that’s not the case. And you needn’t look any further for proof than your Sunday newspaper. Last weekend’s <i>Philadelphia Inquirer</i> featured a slick, eight-page flier from Nikon, printed on bright yellow glossy stock. The supposed beneficiary of this flier was Jack’s Cameras, a once-large regional chain of camera stores in the Delaware Valley that has been shuttering locations due to declining sales of cameras and photo printing/finishing orders.</p>
<p>This flier extolled the virtues of Nikon digital cameras and prominently featured Nikon’s role as <i>“The Official Walt Disney World Camera.”</i> Aside from the massive shrugging of shoulders and yawns that statement instigated, there were some revealing lines of copy in the flier. Several pages had a bold banner that read, <i>“Superior Image Quality Your Smartphone Can’t Match<sup>1</sup>.”</i> The footnote (<sup>1</sup>) read, <i>“Based on digital SLR cameras with DX-format or FX-format sensor versus smartphones without DX-format or FX-format sensor.”</i></p>
<p>Well, DUHHH! There aren’t any smartphones with full-sized CMOS sensors available. (Yet?) But that’s not the point: Smartphones do have pretty good cameras. And they’re getting better with each passing year. Although the limitations of this Web site limit me to 600 pixel resolution for photos, you can see the photo (below) of La Spezia Harbor in Italy below looks awfully darn good – and I took it with my Motorola Droid Razr Maxx HD smartphone (3264&#215;1836 resolution).</p>
<div id="attachment_3507" style="width: 610px" class="wp-caption aligncenter"><img class="size-full wp-image-3507" alt="The scenic harbor of La Spezia, Italy." src="http://www.hdtvexpert.com/wp-content/uploads/2013/12/La-Spezia-Droid-Razr-Maxx-HD-600p.jpg" width="600" height="338" /><p class="wp-caption-text">The scenic harbor of La Spezia, Italy.</p></div>
<p>Read the flier in more detail, and you will see just how desperate camera manufacturers are becoming. Nikon’s showcase deal is for a D3200 D-SLR with 18-55mm zoom lens for $497, after a $100 instant rebate. Add a 55-200mm Nikkor zoom lens for just $147.</p>
<p>I should mention that the D3200 has a 24.2 megapixel sensor, can shoot up to four frames per second, records 1080p/60 video, and offers an optional WU-1a mobile Wi-Fi adapter, so you can upload and share your photos.  (Aside from the Wi-Fi adapter, that level of performance in a digital SLR was a $2,000 investment just a few years ago.)</p>
<p>The problem for Nikon is; I can already do most of those things with my smartphone. No, it doesn’t have anywhere near the resolution of the D3200, but I’ll bet I can still get some pretty good-looking photos with it anyway at Disney World – and I can instantly post them to Facebook, Instagram, and other social media sites. Plus, make phone calls, sent and receive texts and emails, check sports scores, and waste hours playing <i>Candy Crush</i>. Can the D3200 do that?</p>
<p>OK, let’s check out the Nikon specials on point-and-shoots. In early 2012, I bought a CoolPix 8200 for about $250 to use at trade shows and when traveling. It had 16 MP of resolution and a 14x zoom lens. I shot thousands of photos with it during the year, and discovered back in February that the lens had a scratch in it.</p>
<p>So, I took it to the nearby Jack’s Camera (since closed back in August), where I was promptly told (a) it would cost at least $200 to repair and replace the lens, (b) the camera was only worth about $30 anyway, and (c) I could get a $100 instant rebate on a new CoolPix P310 which had a much better lens, a 16 MP sensor, 4.2x optical zoom, and would wind up costing me all of $229.</p>
<p>Flash forward twelve months: There is only one camera store remaining in my town, out of four in 1993. My CoolPix P310 has performed yeoman duty and will serve me faithfully again at CES in two weeks. The updated model is the P330, which has only 12 MP resolution but extends the zoom range to 5x and includes a GPS function. Or, I could pick up a shiny new CoolPix S9500 with 18 MP resolution, 22x optical zoom, and built-in Wi-Fi and GPS for all of $247.</p>
<p>As a former professional photographer, I fully understand and appreciate the benefits of a digital SLR. (I still have a six-year-old Olympus D-SLR sitting in a camera bag somewhere around the house.)  As a pragmatist, I see no point in dragging a D-SLR to a trade show when my P310 pocket camera does the job just as well and takes up little room.</p>
<p>And as an analyst, I completely understand why digital cameras are in full retreat. Smartphones may not take the best pictures or have the best light sensitivity, but they are doggone good at what they do, and getting better with each year. And they’re small, portable, and convenient.</p>
<p>One of my economics professors told me years ago that everyone weighs three factors when making a purchase decision – price, quality, and convenience. And price and convenience win out more times than you’d think.</p>
<p>Need proof? Just look at what’s happening to the digital camera marketplace…</p>
