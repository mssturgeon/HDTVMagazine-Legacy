<p>&nbsp;</p>
<p>Given that this was a CEA event, we did hear a lot of positive spin and wishful thinking about Ultra HD (UHDTV). And that’s not surprising, considering that the actual outlook for television sales for the upcoming holiday selling season isn’t all that wonderful. According to Shawn DuBravac of CEA, consumer spending on technology gifts is expected to increase in 2013 by just 2.6% over 2012, with tablet (14%) and notebook computers (12%) leading televisions (11%) as the most desired gifts on holiday wish lists. (Smartphones tied with videogame consoles at 7%.)</p>
<p>More tellingly; when survey participants were asked why they would adjust their holiday gift expenditures lower, 67% replied that they already have what gadgets they need and 68% said they had concerns about the economy. An additional 66% said they didn’t have the money, while 64% cited the increased cost of living as a reason to cut back on spending. None of that is good news for a new class of 4K televisions that retail for about $65 per diagonal inch, quite a premium above the $15 per diagonal inch that 2K LCD and plasma TVs sell for.</p>
<p>The following day, across the reviver at the Meadowlands Convention Center, I taught a class on HDMI troubleshooting at the Almo E4 Expo. This show, which is focused on the commercial AV industry, featured plenty of large screen displays from Sharp, Panasonic, Samsung, and others. And the discussions largely focused on the challenge of moving 4K content around a facility.</p>
<p><i>Would HDMI 2.0 be good enough?</i> (Not for high frame rate 2160p content with deep color.) <i>How about DisplayPort 1.2?</i> (Yes, it is fast enough to handle 2160p/60 with 10-bit color, but needs to get faster.) <i>Who is using DisplayPort?</i> (Not enough manufacturers to date, although it appears to be the interface of choice for a growing number of digital signage media players.) <i>Are there 4K media players available?</i> (Yes, but in very limited quantities from a handful of manufacturers.)</p>
<div id="attachment_3488" style="width: 610px" class="wp-caption aligncenter"><img class="size-full wp-image-3488" alt="Panasonic's first-in-class 4K Toughpad will be yours for all of $6,000." src="http://www.hdtvexpert.com/wp-content/uploads/2013/11/Toughpad-4K-Tablet-WR.jpg" width="600" height="542" /><p class="wp-caption-text">Panasonic&#8217;s first-in-class 4K Toughpad will be yours for all of $6,000.</p></div>
<p>&nbsp;</p>
<p>One day later, the CCW / SATCON show at the Javits Center had several panel discussions and presentations focused on the nitty-gritty of capturing, editing, and distributing 4K workflows. Several booths featured 4K monitors (Panasonic had both their 4K Toughpad tablet and 31.5” 4K reference LCD monitor at the show), plus 4K encoding/decoding solutions and camera interfaces. Once again, the biggest challenge appeared to be moving enormous amounts of data around reliably and quickly.</p>
<p>I had an interesting sidebar discussion with veteran journalist Stewart Wolpin at the CEA event. I stated that the Chinese are going to wreak havoc on the UHDTV market as they ramp up glass production and slash prices. Wolpin replied that he didn’t see it as a problem: <i>“Who is going to give these brands (TCL, Haier, ChangHong, etc.) any shelf space? They don’t have much if any presence in the U.S. now and just won’t be competitive with the established TV brands. They’re really more concerned with making tons of money selling TVs in their own country.”</i></p>
<p>True, China is the only part of the world where there is growth in TV sales Y-Y right now. But they <span style="text-decoration: underline;">have</span> become a presence to reckon with, if for no other reason than they can make inexpensive 4K TVs with all of the bells and whistles that sell for about as much as a 1<sup>st</sup>-tier 2K TV. TCL has shipped a 50-inch 4K TV that will retail for $999, and Seiki is also raising eyebrows with their recent announcement of a 65-inch 4K TV for $2,999.</p>
<p>It would be a fool’s errand to predict just how fast UHDTV will be embraced by consumers. Not all parts of the ecosystem are in place yet (HDMI limitations and the lack of H.265 encoder chips are just two stumbling blocks), and there’s still the issue of content delivery to be addressed.</p>
<p>Even so, the trend towards using 4K glass in larger LCD (and eventually, OLED) TVs is pretty clear. Remember the days of 720p and 1080p TVs? The move to 4K will follow a similar pattern, especially where LCD panel manufacturers are seeing little or no profit cranking out 2K glass.</p>
<p>So – UHDTV is definitely coming, from this analyst’s perspective. How fast is still hard to tell. Check back in a year!</p>
