<p>First off was the CES 2014 Unveiled event, held at the Metropolitan Pavilion. The morning and part of the afternoon were taken up by an Ultra HD Conference, which featured several panel discussions and a keynote address during lunch. The first panel, titled <i>“Ultra HD: An Evolution, or Revolution?”</i> featured executives from LG, Sony, Toshiba, and Sharp, and set the table for many ad hoc discussions later on in the day, such as (a) does the public REALLY want or understand UHDTV, and (b) will UHDTV stimulate a stagnating market for televisions?</p>
<p>The second panel, moderated by Deborah McAdams of TV Technology, was called <i>“Native Ultra HD Content: Where’s The Beef?”</i> and addressed the elephant in the room; namely, where is 4K video content going to come from, and how will we get it into the home? Panelists from the ATSC, the Digital Entertainment Group, and Rovi tackled those questions, while yet another group discussed <i>“Taking Ultra HD to Retail”</i> later in the day.</p>
