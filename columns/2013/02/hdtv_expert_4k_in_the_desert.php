				<p>I’m writing this while sitting in the Day 2 session of the annual Hollywood Post Alliance Technology Retreat, which has become one of the leading cutting-edge technology conferences for those working in movie and TV production.</p>
<p>From its humble beginnings at the turn of the century, the Tech Retreat has outgrown two hotels and now attracts over 500 attendees each year. This year’s edition is being held at the Hyatt Resort in Indian Wells and featured a full-day super session on high frame rate / high dynamic range / high resolution imaging, followed by two and a half days of presentations on everything from file-based workflows to consumer TV viewing preferences, the next generation of ATSC (3.0), and a behind the scenes look at NHK’s operations center for their 8K coverage of the 2012 Olympics.</p>
<p>Did you know the adaptive dynamic range of the human eye is 10<sup>14</sup>, or about 46 stops of light? (I learned this on Day 1.) I also discovered that the fire department in Paris played an integral role in the Lumiere demonstration of 60mm projected images on a 30 meter-wide screen in 1898. (More on that later!)</p>
<p>And I also heard about viewer preferences for high dynamic range displays, along with the trials, tribulations, successes, and failures of the UltraViolet online “locker” system for viewing movies and TV shows across a wide range of devices.</p>
<div id="attachment_2903" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2903" alt="General sessions at HPA are packed wall-to-wall on Wednesday." src="http://www.hdtvexpert.com/wp-content/uploads/2013/02/Wide-View-of-HPA-Seidel-Presentation-WEB.jpg" width="600" height="338" /><p class="wp-caption-text">General sessions at HPA are packed wall-to-wall on Wednesday.</p></div>
<p>As might be expected, there is a lot of interest among attendees in the emerging crop of 4K TVs and displays. 4K has already made significant inroads to the post-production industry, but the end game remains uncertain: Is the best use of 4K to make better 2K digital files for movies, and improved 2K video for broadcasts? Do 4K displays beg for greater color bit depths, as opposed to the barely-adequate 8-bit system used for Blu-ray and digital TV? What are the challenges in building an end-to-end 4K production ecosystem?</p>
<p>How about displays that can harness the wide dynamic range that the newest high-end 4K cameras can reproduce? And what display technology shows the most promise for reference-grade 4K monitoring in post-production and color grading facilities? It’s clear that plasma is on the way out, based on sales trends for the past three years. Yet, LCDs still face major challenges in assuming the “reference” mantle. And OLEDs remain tantalizingly out of reach, due to continued yield issues.</p>
<p>And then there’s the “gotcha!” – delivering 4K content to the consumer. The MPEG4 H.264 codec can work miracles, but isn’t able to pack down 4K files small enough for existing terrestrial, satellite, and cable “pipes.” However, the emerging H.265 codec promises a further bit rate reduction of 50% over H.264. Will H.265 make 4K delivery feasible?</p>
<p>And what will we play 4K content from? Blu-ray discs? There’s certainly enough capacity in dual-layer blue laser discs, but there’s that 8-bit color limitation. How about hard drive or solid-state memory solutions, such as RED’s $1,500 4K media player? Streaming 4K seems out of the question for now, and digital downloads of 4K movies would certainly tax even the fastest broadband service providers.</p>
<p>In an informal poll of attendees after Day 1, a majority (at least 80%) indicated they believed that 4K TV was just another attempt by CE manufacturers to sell TVs, while a much smaller group (perhaps 20%) thought that 4K was a legitimate next step in the progression of content production. (HPA attendees also largely agree that 3D TV is dead and that “smart TVs” are yet another misfire on the part of Japan, Korea, and China.)</p>
<p>In my morning breakfast roundtable that focused on the struggles of the consumer TV industry, one comment was made that perhaps Apple’s long-rumored television product might use a 4K display (along with advanced gesture and voice control.) We also talked about the rapid decline in LCD panel and TV prices, and observed that some Taiwanese and Chinese manufacturers (Westinghouse, Hisense, and TCL) are already floating aggressive prices on 4K TVs; about $50 &#8211; $60 per diagonal inch in sizes up to 65 inches.</p>
<p>Clearly, 4K is coming. Just how fast and in what forms isn’t immediately obvious. There is talk of a need for standardization beyond what is happening in SMPTE and EBU groups, specifically focusing on high dynamic range 4K video with a wide color gamut that will display consistently both on cinema-grade projectors <span style="text-decoration: underline;">and </span>across multiple brands of 4K consumer TVs.</p>
<p>In other words, it’s past time to stop worrying about being “backwards compatible” with legacy format and imaging standards developed for CRT displays, and blaze new trails for acquisition, post-production, distribution, and delivery of HDR UHD visual content.</p>
<p>Only then will the transition to 4K TV be worthwhile. And you can be certain that Tech Retreat presenters and attendees will be on the cutting edge as it happens&#8230;</p>
