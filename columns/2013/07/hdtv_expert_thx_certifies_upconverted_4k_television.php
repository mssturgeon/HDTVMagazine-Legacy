<p>The threat coming fast over the western horizon is a flood of very inexpensive Chinese 4K sets. These sets are so cheap that it&#8217;s unlikely they could be produced at the price without significant corner-cutting. The first- and second-tier brands are concerned that consumers will be seduced by these too-low prices and wind up buying sets that give them a deeply disappointing 4K viewing experience. The result, they fear, is that these sets will give 4K an undeservedly bad name that more sophisticated products will not be able to overcome.</p>
<p>A solution &#8212; at least a partial one &#8212; to both of these problems is to certify the quality of the native and up-converted 4K images that appear on TV sets: A &#8220;Good Housekeeping Seal&#8221; of 4K approval that will let consumers buy with confidence.</p>
<p>Both THX and Technicolor have announced 4K certificaion programs. On July 12th, I had a telephone conference call with members of the THX team headquartered in San Francisco. On the call were Eric Gemmer, Sr. Video Engineer; Jon Cielo, Senior Systems Engineer; and Matt Severaid, Partner Marketing Manager.</p>
<p>Severaid started the call with a brief recap of THX&#8217;s origins. George Lucas established THX to certify the ability of individual movie theaters to reproduce the visual and audio experience of his <em>Star Wars</em> movies faithfully. Lucas had been very disappointed with the quality of reproduction of the first two <em>Star Wars</em> movies at many cinemas. The THX standard was introduced prior to the release of <em>The Return of the Jedi</em>, the third movie in the series. Lucas released <em>The Return of the Jedi</em> only to theaters that could meet the THX standards. Naturally, the standards improved the viewers&#8217; experience of movies, too. THX standards were applied home viewing in the 1990s, and the display program began in 2006.</p>
<p>The first globally available TV set to by THX 4K Certified is Sharp&#8217;s 70-inch 4K set, which will become available in August. My colleage Matt Brennesholtz saw this set at CE Week in New York in late June, and was impressed with the up-converted 4K image quality.</p>
<p>Cielo emphasized that THX certification assures that a TV set delivers the image the way the creator intended. &#8220;We don&#8217;t want to change content from the source material, and that includes image grain. We try to make sure the image is as beautiful as it can look.&#8221; The goal is &#8220;cinema quality in the home.&#8221;</p>
<p>For the Sharp 70-inch, two certified modes are the THX Cinema Mode for dark ambients and THX Movie for bright ambients. The color space for up-converted material is Rec. 709 since its based on a 2K source. An expanded color gamut will be defined under Rec. 2020, but that is under development now and a final recommendation is &#8220;way down the road.&#8221; The wider gamut seen in digital cinema and specified by the DCI standard is for professional applications and is not appropriate for consumer devices, Severaid said. Studios retune masters to accomodate the limitations of HD. &#8220;Ultimately, our goal is to present images that don&#8217;t change the meaning of the content,&#8221; Severaid said. Specifically, THX wants to be sure that the 2K-to-4K processing does not hurt the image. Following the Hippocratic Oath, &#8220;First, do no harm.&#8221;</p>
<p>THX authentication is based on industry standards, and focuses on panel performance, including good black-and-white uniformity and off-axis consistency. But, said Cielo, &#8220;It&#8217;s difficult to make a TV work as precisely as we would like it to.&#8221; Among the issues are light leakage and blotchiness. Most non-THX-certified sets would probably not pass the requiremets for motion artifacts and jaggies, he said.</p>
<p>The certification process requires collaboration between the set-maker and THX. Sharp personnel were present during testing, and available &#8220;when the TV needs to be tweaked, and they always need to be tweaked.&#8221; The tweaks are embedded in the set&#8217;s software, and sometimes a set requires modifications beyond the software before THX&#8217;s requirements are achieved.</p>
<p>The Sharp 70-inch with THX 4K certification produces beautiful up-converted images. Does Technicolor&#8217;s approach differ from THX&#8217;s? Is one better than the other? That is what we&#8217;ll be discussing next time.</p>
