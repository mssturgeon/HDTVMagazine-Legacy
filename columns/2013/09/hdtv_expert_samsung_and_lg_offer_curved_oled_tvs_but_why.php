				<p>Samsung and LG have both started shipping 55-inch curved-screen TV sets. The volumes are low and the prices are high, but they are shipping. In the US, you can buy Samsung&#8217;s offering from Amazon for $8999. LG&#8217;s version is $14,999 in the US, but the company has cut its price for the Korean market to $9800, so expect the US price to drop, too.</p>
<p>But why do a curved OLED-TV screen at all, other than to prove that you can? My own guess is that it&#8217;s a ploy to distract us &#8212; and by &#8220;us&#8221; I mean the technology press, analysts, retailers, and consumers &#8212; from focusing on the obvious fact that the two manufacturers do not yet have a robust manufacturing process that can make appreciable volumes of large OLED panels at high yield and moderate cost.</p>
<p>Recently, LG issued a press release making strong claims for their curved-screen OLED-TV, including a broader angle of view, and greater color fidelity from center to edge. Now, there is presumably no difference between the flat 55-inch and the curved one, so, if these claims are true, it must be because the curved screen geometry makes them true.</p>
<p>Assuming the viewing distance and the radius of curvature are the same, what can we say about LG&#8217;s claim that the angle of view is improved? (Please note that even if our assumption about the radius of curvature is true, only one viewer&#8217;s head can be at the center of curvature at a given time.)</p>
<p>For some of you, high school geometry and trigonometry may be a few years (or decades) in the past, so let&#8217;s take a moment to review. If the screen has a constant radius of curvature, which I will bet it does, its long edge, looking down from above, forms a portion of a circle. Extend the curve around to make a complete circle, and the radius of the circle is the screen&#8217;s radius of curvature. Now, if the radius of curvature is equal to the typical viewing distance for a 55-inch screen (roughly 8 feet), at least one of LG&#8217;s claims will be true. As the viewer&#8217;s eyes sweep across the screen at eye level, his or her direction of view will always be perpendicular to the screen surface, and he will enjoy optimal brightness, contrast, and color. Even when he or she looks upward or downward from eye level, the total difference of the direction of view from perpendicular to the screen will generally be less than with a flat screen. In addition, the viewer&#8217;s eyes will be equidistant from all points on the screen that are at eye level. So far, so good, IF the radius of curvature equals the typical viewing distance.</p>
<p>My intuition tells me that a curved display really will provide a greater included horizontal angle of view from center to either side than a flat display of the same size whose center is placed at the same viewing distance. Doing the trigonometry convinced me this is correct, and that a flat display would have to be about one inch larger horizontally to match the included viewing angle of the 55-inch curved display. So this claim is also true, even if the difference is not great.</p>
<p>But here is a trickier significant question. Assuming you are not a hermit and that friends come over to watch TV with you, what will their curved-screen experience be? At some angle of view that is offset from yours, my geometrical intuition tells me that (if your friend is sitting on your right), he will see the left side of the screen with less extreme viewing angles than he would if the two of you were watching a flat screen, but all points on the right side of the screen will be viewed at more extreme angles. If you are watching not with a friend but with a significant other, and you are watching cheek to cheek, there is probably some angle of separation within which all or most of the right side of the screen will have smaller viewing angles than a flat screen for your partner. As they used to say in physics textbooks (and perhaps still do), &#8220;the demonstration is left to the reader.&#8221;</p>
<p>Now, you may have noticed that I have written this entire article without actually telling you what the radius of curvature for the LG curved screen actually is, and the reason is that I didn&#8217;t know. If the information exists anywhere on the Web, very diligent Googling did not find it.</p>
<p>However, Jean Lee, Manager of LG Display&#8217;s PR Team in Seoul has now come to my (actually our) rescue. The radius of curvature is 5000 mm, which is 5 meters or 16.4 feet., so a viewer sitting at typical viewing distance will be well within the radius of curvature. As a result, the benefits in viewing angle to any point on the screen will better than they would be for a flat screen, but not nearly as good as they would be if the viewer were sitting at the center of curvature.</p>
<p>The angles can certainly be calculated, and we could determine whether the improvements in color, contrast, and brightness relative to a flat screen would be significant. Let&#8217;s do that calculation now. Oh, sorry. I&#8217;ve run out of space.</p>
<p>To conclude, I&#8217;m inclined to say that as far as the viewer is concerned, LG&#8217;s claims for a superior viewing experience with the curved-screen display are justified, but the differences are probably not significant. For both LG and Samsung, this looks like more of a marketing and public relations ploy than a genuine improvement in the art and science of display design.</p>
