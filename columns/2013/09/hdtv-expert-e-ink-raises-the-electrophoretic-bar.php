				<p>E Ink recently announced the availability of Carta, its new electrophoretic imaging film, which will be the face of Amazon&#8217;s new Kindle Paperwhite eReader. The Paperwhite can be pre-ordered now and will ship on September 30.</p>
<p>What Carta does, said E Ink Product Management Director Giovanni Mancini in an exclusive phone conversation on September 10, is replace both the black and white pigmented particles used in Pearl, the company&#8217;s previous top-of-the-line display film, with new pigments. These pigments offer a blacker black and a whiter white. Combined with some processing changes, the result is an increase in reflectivity to 50% from Pearl&#8217;s 41%. The contrast ratio jumps to 15:1 from 10:1. Mechanically, said Mancini, Carta is similar to Pearl.</p>
<p>Carta does not replace Pearl, which will still be available at its existing price. E Ink&#8217;s intention is for Carta to be sold at 10% to 30% premium of Pearl, and expects first-tier eReader brands to migrate to Carta over the next year or so.</p>
