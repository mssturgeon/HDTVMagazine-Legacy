<p>Although the pigments are the biggest factor in the improved performance, it turns out that changing the order in which some assembly processes are performed and improve the film&#8217;s reflectivity. Previously, for example, E Ink applied adhesive the previously assembled display layers and then applied the ITO electrode layer to it. Now, the company applies the adhesive to the ITO layer and then lays the ITO layer, and sees an improvement in the brightness of the white state.</p>
<p>Another recent announcement is for E-Ink Regal, a new driving waveform. When a signal changes the state of a portion of the display from black to white, or from one gray level to another, the pigmented particles are accelerated to their new positions. Although the particles have very little mass, they must still be actively decelerated to maintain precise levels and sharp character edges. Regal is a new, more complicated waveform for doing this more precisely. Regal can be applied to both Carta and Pearl, controls edge artifacts on bothe imaging films. In addition, Regal allows full-page refreshes, which some readers find annoying, to be performed much less frequently. A Pearl display without Regal must receive a full-page refresh every five pages. With Regal, that becomes every 100 pages, which means that in many cases there won&#8217;t be a refresh in an entire reading session.</p>
<p>Regal is available to customers as an option for both Carta and Pearl. Tuning Regal waveforms is more complex and time-consuming than tuning the simpler standard waveform, and constitutes a one-time cost for each product model to which it is applied. So, the unit cost for incorporating Regal depends strongly on the quantity of panels to be produced. By making Regal an option, product managers are free to tailor their products to individual market profiles. The new Kobo 6-inch eReader, said Mancini, uses Pearl with the Regal waveform, and Kobo advertises &#8220;smoother page transitions.&#8221;</p>
<p>The eReader market is mature and is stabilizing at 12 to 15 million units a year. That&#8217;s not a bad business, but E Ink is working on other applications and is encouraged to find customers developing new product, said Mancini. Among these products are snap-on covers for the Samsung Galazy S4 smart phone that integrate 4.3-inch E Ink displays. Samsung itself makes hinged covers (without the display) that snap on to the back of the handset in place of the existing battery cover and then wrap around to provide a very slim and lightweight cover. The display covers follow the same pattern, but include the E Ink display, which is very thin. The user can then choose to read either from the E Ink display or from the handset&#8217;s own OLED display. The E Ink display would be the obvous choice in bright sunlight, and one manufacturer has said that missed-call and SMS information would also apper on the E Ink display.</p>
<p>Covers have been developed by PocketBook and TCL-Alcatel. The electrical connection for PocketBook&#8217;s PocketCover is through the phone&#8217;s micro-USB port. TCL-Alcatel connects through the side of the phone. Both companies plan to start volume product in October, beginning with the European market. PocketBook Readers Sales Manager Enrico Muller, said this is a highly anticipated product and that the company plans to produce models for other smart phones, such as Sony and HTC, as quickly as possible. Apparently, the product&#8217;s introduction at IFA supported the company&#8217;s enthusiasm.</p>
<p>In a less-than-clear press release, Plastic Logic seemed to say that it would be producing the subsequent generation of E Ink display for PocketBook, and that the size of that second-generation display would be 4.8 inches on the diagonal.</p>
<p>Smart covers appear to be an ideal application for electrophoretic displays. With significant electrophoretic technical improvements already here, with the introduction of new eReader models, and with new applications on the way, it seems the comments of electrophoretic pessimists are overwrought. My interview with Giovanni Mancini closed with his cheerfully adapting a quote from Mark Twain: &#8220;The news of our death has been greatly exaggerated.&#8221;</p>
