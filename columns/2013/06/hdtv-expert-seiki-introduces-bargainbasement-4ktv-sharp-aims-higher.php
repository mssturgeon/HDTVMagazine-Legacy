<p>As is the case with Seiki&#8217;s 50-inch 4K set, announced in April and currently available through Amazon for $1399.99 (as well as through other outlets), the 39-inch (Model SE39UY04) attains its bargain-basement price, at least in part, with a no-frills strategy. If you don&#8217;t include features such as Internet TV, WiFi, or 3D capability, you are obviously reducing your bill of materials and your cost, and without necessarily impairing image quality. The question with an extreme &#8220;value model,&#8221; is whether the manufacturer has been able to cut only fat and not bone.</p>
<p>Unfortunately, in the case of the the SE39UY04&#8242;s 50-inch cousin, responsible reviewers (CNET and PC Magazine) had reservations about the color accuracy of the images, as well as dark-level and bright-level details. And, given the fact that native 4K media is not readily available in a form that is usable on 4K-TVs, the quality of a set&#8217;s HD-to-UHD up-converter is crucial. Both CNET and PC Magazine had serious reservations here.</p>
<p>Let&#8217;s note that if you spend the money, up-conversion of very high quality is possible. As previously reported on HDTVexpert, Marseille Networks has  introduced  a phenomenally good family of 4K up-converting chips that earned Technicolor&#8217;s 4K Image Certified stamp of approval. These chips are designed for media-source products such as Blu-ray players, but versions for TV sets are not likely to be far behind.</p>
<p>In part, Seiki&#8217;s design cycle may have prevented them from using the latest technology, but other TV manufacturers have introduced sets with decent proprietary up-converters, so it is reasonable to suspect that Seiki cut a bit more from the cost of its BOM than it should have.</p>
<div id="attachment_3274" class="wp-caption alignright" style="width: 629px"><a href="http://www.hdtvexpert.com/?attachment_id=3274" rel="attachment wp-att-3274"><img class="size-full wp-image-3274" alt="You can buy five of Sharp's 70-inch 4Kx2K TV sets for the price of one Samsung 85-inch 4Kx2K.  (Photo:  Sharp)" src="http://www.hdtvexpert.com/wp-content/uploads/2013/06/sharpaquos619pxhedimg-2013-06-26-01.jpg" width="619" height="389" /></a><p class="wp-caption-text">You can buy five of Sharp&#8217;s 70-inch 4Kx2K TV sets for the price of one Samsung 85-inch 4Kx2K. (Photo: Sharp)</p></div>
<p>There&#8217;s another way to look at 4K price reduction:  by remembering that the MSRP&#8217;s of the LG and Sony 84-inch sets that came out last fall were $20,000 to $25,000, and that the MSRP of the truly spectacular Samsung 85-inch introduced a couple of months ago is $40,000. From that perspective, the Sharp 70-inch Ultra HD introduced at CE Week for $8000 seems upper-middle-class affordable. This set is anything but bare-bones. Sharp&#8217;s up-scaling technology with dual-core processor has earned THX certification, and the set can show 3D at 4K using the two included pairs of Bluetooth shutter glasses. You can also control the set with your smart phone and beam video directly from the smart phone to the set.</p>
<p>Westinghouse Digital will also be introducing a 4K line-up but had not revealed details when this article was being written.  However, Westinghouse is known for its aggressive pricing.</p>
<p>With every trade show, we are seeing different segments of the 4K market pie being filled in.  Inevitably, the cost of top-tier technology will decline and the quality of value-oriented models will improve.  4K is a technology with legs, and it will grow rapidly.  There are still a few naysayers who don&#8217;t believe 4K will take off.  They are wrong.  4K is already airborne.</p>
