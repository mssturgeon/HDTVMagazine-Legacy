<p>The chip family is intended for source devices such as Blu-ray Disk players and streaming TV boxes. George Alexy, Marseille&#8217;s VP of Marketing, said the chips are not readily compatible with TV reciever architecture. Although he would not confirm that TV-specific designs are in the works, his non-confirmation was delivered with a wink and a nod.</p>
<p>Alexy said that commercial products using Marseille chips would be available soon, but he wouldn&#8217;t identify his customers. Toshiba, however, which was diagonally across the aisle, wasn&#8217;t so circumspect. The company was showing its soon-to-be top-of-the-line BDX6400 Symbio media box and Blu-ray player, which up-converts media to 4K. Although Marseille was not mentioned in Toshiba&#8217;s descriptive material, a Toshiba rep readily confirmed that Marseille&#8217;s chip is indeed inside the box. Incidently, the BDX6400 represents an impressive feat of packaging. The entire box, seen from the top, is not very much larger that a Blu-ray disk, with the disk being inserted into a barely visible slot.</p>
<div id="attachment_3263" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/?attachment_id=3263" rel="attachment wp-att-3263"><img class="size-full wp-image-3263" alt="Toshiba's 58-inch 4K TV set from the L9300U series will be available this summer.  The set uses Toshiba's own CEVO 4K Quad+Dual Core Processor for image processing, including 4K up-conversion.  (Photo:  Ken Werner)" src="http://www.hdtvexpert.com/wp-content/uploads/2013/06/xToshiba-58-4K.jpg" width="600" height="402" /></a><p class="wp-caption-text">Toshiba&#8217;s 58-inch 4K TV set from the L9300U series will be available this summer. The set uses Toshiba&#8217;s own CEVO 4K Quad+Dual Core Processor for image processing, including 4K up-conversion.<em> (Photo: Ken Werner)</em></p></div>
<p>The BDX6400 was sitting next to Toshiba&#8217;s new 58-inch 4K TV set, which displayed lovely images. Toshiba will also have 65-inch and 84-inch 4K TVs, all of which, together with the Sensio line of BRD players, will be available this summer.</p>
<p>Returning to Marseille&#8217;s VTV-122X family, let&#8217;s try to get some idea of the sophistication of these chips without filling up another screen with text. The VTV-1223, to be specific, in addition to 2D and 3D up-conversion, performs adaptive edge enhancement of lines and curves and adaptive sharpening and noise reduction. Low-latency processing keeps gamers from getting shot.</p>
<p>Modern motion pictures are produced using the Digital Cinema Initiative (DCI) format, which incorporates a color gamut significantly larger that the Rec 709 gamut that defines the color pipeline for HDTV. The VTV-1223 supports xvYCC, which defines a larger gamut than Rec 709. Martin Fishman, COO of Portrait Displays, which works closely with Technicolor on its color certification program, noted that a new standard, Rec 2020, is in the works and is likely to be the color standard for 4K TV. However, he said, this will take a while.</p>
<p>The Marseille chip has an integrated HDMI 1.4b receiver and transmitter, and up to 2160p output at 24 or 30Hz. Color depth is 8, 10, or 12 bits. The chip has an embedded CPU for HDMI stacks, which relieves the host from complicated real-time processing. All of this is in a 169-pin, 12x12mm, TFBG package that is RoHS compliant.</p>
<p>In North America, at least, 3D consumer TV is kaput. 4K is now in its infancy but is growing rapidly and kicking like crazy. 4K offers a very important characteristic that 3D did not: People want to watch it. While most 3D TV programming pushes you away from the story or sporting event, 4K draws you in. These images have depth, and they add to your emotional involvement in the content. All we need are affordable receivers, which are coming, and 4K content, which Marseille&#8217;s VTV-122X family gives us. TV sets with this kind of functionality can not be far behind.</p>
