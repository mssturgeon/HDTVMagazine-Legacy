				<p>In 1969 Japan's National Broadcast Network (NHK) started research on an advanced television system to bring truly high definition television to the public. Their goal for such an endeavor was to "appeal to a higher level of psychological sensation and emotion by transmitting highly intellectual information with detailed characters and graphics." <sup>1</sup></p>

<p>That highly eclectic goal for HDTV remained through its complex evolution to the US system commercialized in 1996. Unfortunately, that goal is being severely and continuously eroded by most of the purveyors of "HDTV." Granted, there are some HDTV offerings with quality of production and distribution levels reaching and perhaps exceeding that lofty NHK aspiration - but not many.</p>

<p>There are several reasons for HDTV quality reduction in the US broadcast distribution industry; that industry including OTA, Cable, DBS, et al. Indeed the pioneers of broadcasting - both in radio and television - such as Sarnoff, Armstrong, Farnsworth and others - were frustrated over the de facto applications of the media they labored so hard to create. The hope was that broadcast HDTV would rise to that higher, loftier level and deliver images and sound that would raise the sensual sensitivities of the viewers and ultimately mankind in general. But the economic forces that finance the commercial success of the system interfered, causing, hopefully, a temporary compromise in the quality of HDTV delivery. Interestingly, it took the NTSC delivery system almost 50 years to get it right. Then, along came digitization and the signals were up-converted, down-converted, reformatted, scaled, compressed, transcoded and "bit-starved" to force them down very expensive "pipes."</p>

<p>For those who just purchases new HDTV displays, it is possibly frustrating not to be able to see the high quality HDTV images they saw in the showroom, save for some sports and live OTA productions. Generally poor receiver upconverters create fuzzy SD images that are even more myopic when stretched to full screen.</p>

<p>So, is there any hope? Yes, there is - a bunch of hope. Allow me to summarize:</p>

<ul><li><b>Time</b> - Generally, the HDTV program production qualities are much better than the signal distribution qualities because of high bandwidth costs. There are several local and national communications initiatives now in play that will significantly increase available bandwidth and thus allow cost effective, true HDTV signal distribution. As HDTV approaches market maturity, the novelty factor decreases, and the content battles will be increasing fought on the quality front.</li><li><b>Superior Displays</b> - Present 1080p display systems are capable of producing much better images than they receive. As the signal quality of HDTV improves over time, the images will be better. Thinking of the HDTV display as a monitor in a systems concept will allow customers to continuously upgrade the signal processors in set-top-boxes (STBs) to match monitor capability.</li><li><b>Technology</b> - Increasingly sophisticated signal processing technology becoming available at all levels of signal distribution is allowing networks and local distributors to greatly improve HDTV signal quality. Developments such as the Texas Instruments "DaVinci" processors will provide extremely high quality, cost effective single-chip solutions to virtually all the complex signal processing tasks required in the distribution pipeline, including those in STBs.</li><li><b>Business Models</b> - Wonderful opportunities exist for OTA broadcasters and their network providers to leverage true HDTV services. Seizing these opportunities may very well determine their survival as viable program suppliers. Time will tell, but the clock is ticking.</li><li><b>Us</b> - Last, but far from least are those of us who recognize the potential of HDTV, but are disappointed in the results so far. The power of the consumer is very strong. Now there are a substantial number of us expecting true HDTV but not getting it. Phone calls, letters, e-mail comments to all levels of signal providers, either on a program or general basis, will go a long way in influencing the "powers-that-be" in the system.</li></ul>

<p>Consider the above bullet point a "call-to-action." I don't think we should expect anything less than the original NHK goal for HDTV. Without us, it may take another 50 years to get it right. But it will get at lot better.</p>

<p>Ed</p>

