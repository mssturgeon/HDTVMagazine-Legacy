	<blockquote><p>&#8220;If you want to get the absolute biggest screen for your buck&#8230; check out a rear-projection LCD set. They come with technology names like &#8216;DLP&#8217; and &#8216;LCOS&#8217; They&#8217;re thicker, but lighter than LCD and Plasma displays. They&#8217;re also cheaper for bigger screens but they&#8217;re powered by a light bulb that will have to be changed every few years, to the tune of about a couple hundred bucks.&#8221;</p></blockquote>
	<p>Now, I&#8217;ll admit that this becoming <strong>a moot point</strong>, since American buyers continue to stay away from rear projection <strong>in droves</strong>, in spite of the fact that some deliver the <strong>best picture quality </strong>available from any technology, and they certainly do provide<strong> bang for the buck</strong>. But if we&#8217;re going to mention them, let&#8217;s <strong>get it right</strong>. Yes, there are rear projection LCD HDTVs available on the market. But the technology &#8220;with names like&#8221; <strong>DLP and LCoS are not LCD</strong>; they&#8217;re something very different. There are <strong>three different flavors </strong>of rear projection HDTVS: LCD, DLP, and LCoS. (And note that Sony calls its LCoS &#8220;SXRD&#8221;, while JVC calls theirs &#8220;D-ILA&#8221;.) Each of the three has its own <strong>advantages and disadvantages </strong>in terms of cost and performance.</p>
	<p>As for <strong>the lamp issue</strong>, it is certainly true that many rear projection sets still rely on traditional UHP projector lamps, and these do <strong>cost $200 to $300</strong>, and they do get dimmer over time. It&#8217;s probably fair to say that you&#8217;ll want to replace them <strong>every three years</strong> or so, depending on usage. But &#8212; and this is a big but &#8212; <strong>not all rear projection models </strong>use these lamps. For example, <strong>Panasonic </strong>has models out that use a <strong>LiFi light engine</strong>, which uses microwaves to excite plasma in a tiny quartz capsule, and it probably will <strong>not need to be replaced </strong>in the lifetime of the HDTV. <strong>Samsung </strong>also has models with solid state lighting &#8212; <strong>high brightness LEDs </strong>&#8211; that should last as long as the television set. So if the lamp issue is <strong>a turn off</strong> for you, know that you have <strong>alternative choices </strong>that still let you pick a rear projection HDTV.</p>
