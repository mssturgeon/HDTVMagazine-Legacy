<p>What are you guys thinking?!! </p>

<p>How many HD DVD players were sold? 750,000......1,000,000? Doesn't matter the number, if it were 1,000,000 and I'm a Warner Exec, I would EXPECT 1,000,000 names on the petition and not one less. Not new news! OF COURSE everyone that has an HD-DVD player wants to see content continue from all possible sources. No mind-reading required there. But this was never about wondering which format the Consumer wanted. It's all about making a return on the investment already sunk. Clearly, John Q. Public was conflicted, sitting on the sidelines waiting for a winner, while neither side was capitalizing on their investment. The only way to win (make any ROI) was to ensure a winner. So Sony wrote the big check, and now they are the winner. End of game.</p>

<p>The only thing sillier than the Warner petition was the guy who wanted to petition Toshiba - to kill the format. Believe me, I was the one in the HD-DVD Promotion Group's booth before CES opened, calibrating 22 Toshiba monitors. Those who stayed for the party had faces longer than a Lindsay Lohan rap sheet. Trust me, they heard the bells toll. </p>

<p>If you must petition somebody, petition Sony to give all those disgruntled a $100 trade-in on a Blu-Ray player, since they put you in this box. If you bought an XA2, hang on to it as a decent upconverting NTSC player. Otherwise, stack your orphans in the closet, next to the D-VHS player, the Sony Elcaset and the Quadraphonic sound decoder.</p>

<p>Petition for Consumer Justice...a quaint idea, but very, very naive.</p>
