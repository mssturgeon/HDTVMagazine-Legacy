			<p>As my DirecTV monthly contribution approaches $100 and with heating bills up 20% and auto gas prices up 30% and the economy under increasing stress, I decided to do an audit on the $100 bill.  I would guess that many other families are doing the same thing, particularly as Cable and Satellite bills seem to have no ceiling.</p>

<p>The result of my audit was not at all surprising: 90% or our viewing is among ten channels, six of them are available over-the-air and therefore free.  I can use a comparatively simple attic antenna and receive these six digital channels with virtually 100% reliability (better than via DirecTV), and I am approximately 30 statute miles from the nearest transmitter.  Importantly, these six channels carry an abundant amount of "HDTV" programming.  Further, I can reliably receive 25 different program streams from 12 different channels.  (I do not live in a major market area.)</p>

<p>So, what is wrong with this picture?  Not much. Other than not being able to enjoy the male sport of constantly skipping through 1000 or so channels (most of which nobody watches more that one second at a time), or that OTA (Over-The-Air) does not offer a 24/7 national news service, the Discovery Channel and The History Channel, little of value is sacrificed.  The other problem, and one that is frightening, is that the HDTV quality of over the OTA channels is severely compromised because local stations steel bandwidth for the various low definition sub-channels.  And that problem would only be exacerbated by the carriage of mobile/handheld data streams.  With all of this, OTA HDTV could easily be relegated to half its specified data rate.  Sorry, even now this is virtually no true broadcast HDTV, only fairly good SDTV, and that difference would be obvious to those owning the newer, higher resolution displays.  About the only way to experience true HDTV is via high definition video discs (some game systems and the few premium MPEG 2 satellite channels notwithstanding).</p>

<p>So, how can this be fixed in a win-win-win way so that we can enjoy programming most of us could watch-in true HDTV at no cost-while having the opportunities offered by mobile-handheld technology and/or PPV TV?  To do this requires local broadcasters to consider all the bandwidth they have available in totality, and market the digital services available in a cooperative revenue sharing model.  In this manner, those channels offering network (and local) HDTV programs could devote full bandwidth to HDTV while marketing their sub-channels through alternate channels that transmit only SD and mobile/handheld services.  The most popular cable channels (such as Discovery, CNN etc.) could be legally and/or commercially compelled to offer their programming for local, free OTA distribution. </p>

<p>In the final analysis, it's all about programming that viewers want to watch.  It seems that, even though their total viewing audience remains high, the four major networks are fighting each other to the grave as their audience continues to decrease at an accellerating rate.  Perhaps there is a viable economic model based on the networks combining their resources to create broadcast versions of ESPN, CNN, HBO, etc instead of trying to adhere to the increasingly obsolete "we'll do the programming for you (and badly)" model.  That model started to decline 40 years ago with the invention of the remote control and focused cable programming.</p>

<p>But, that's all in the future, maybe.  The amazing thing is that this vision requires very little additional investment in technology.  It's all here, and most of it has been deployed, or soon will be.  Clearly, such vision requires commercial and regulatory innovation, which is much more difficult. </p>

<p>In the meantime, put up a small stick in the attic, switch your high-speed internet to DSL, cut the Cable, lock the kids in their rooms with books, and save $100/ month.  You may even see true HDTV and educate the kids at the same time!</p>

