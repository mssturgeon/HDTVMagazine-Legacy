				<p>A report out yesterday from <strong>ABI Research </strong>predicts that <strong>&#8220;universal&#8221; </strong>high-definition DVD drives will account for <strong>two-thirds </strong>of the high-definition DVD drives in desktop PCs and notebook computers <strong>in 2012</strong>. Part of this prediction is based on the expectation that <strong>by 2009</strong>, hybrid drives that can read both HD DVD and Blu-ray discs will be available for <strong>about the same cost </strong>as a Blu-ray only drive. Citing consumer confusion about which format will ultimately win, the company predicts that &#8220;<strong>all of the above</strong>&#8221; will be the answer.</p>
	<p>It&#8217;s an interesting interpretation, but I think <strong>it&#8217;s flawed</strong>. I&#8217;ve been as big a fan of multi-format drives as anyone over the years; I was almost alone in my support for the read/write/erase <strong>PD format </strong>that preceeded CD-R and CD-RW. I&#8217;ve always liked the DVD drives that handle  <strong>DVD-RAM </strong>(which is another format that few others seem to have championed) as well as DVD+/-R/RW. But these combo drives have not been compelling winners in the marketplace. You <strong>cannot point </strong>to the success of the CD+/-R/RW and DVD+/-R/RW drives as an indication that the high-def combos will succeed; the multiple formats that they support are<strong> nearly identical</strong>, and far less different than Blu-ray is from HD DVD.</p>
	<p>Instead, let&#8217;s look through <strong>the other end </strong>of the telescope. If a combo drive will be about the same price as the Blu-ray only drive, that implies that the Blu-ray components will be <strong>the expensive parts</strong>. It stands to reason that the HD DVD costs will be a small fraction of the total. If this means that an HD DVD drive can be built for<strong> half the price of the combo</strong>, then this could become a significant factor. The difference between a $300 and a $150 component in <strong>a $2,000 computer </strong>does not make a lot of difference, and I can see consumers choosing the more expensive option as a &#8220;future proofing&#8221; decision. However, if we&#8217;re talking about a computer that costs <strong>$200 without the drive</strong>, the difference is a lot bigger and I expect that most consumers will choose the <strong>$350 configuration </strong>over the $500 version. <strong>Wouldn&#8217;t you?</strong></p>
	<p>Even <strong>if only half </strong>the consumers make the choice based on total dollars, that still puts <strong>a few million PC users </strong>in the HD DVD only camp, and don&#8217;t forget that <strong>there&#8217;s a reason </strong>that all these desktop monitors and notebook <strong>screens are in wide format</strong>. People are using them to watch movies. And do you think that the major studios will stick with their allegience to Blu-ray for long when <strong>half the computer users </strong>in the country won&#8217;t be able to watch their movies? I expect them to fold like a cheap suit and <strong>start publishing in HD DVD </strong>as well as Blu-ray. (Sony will likely hold out to the end, but that&#8217;s because their so invested in Blu-ray&#8217;s success.)</p>
	<p>So I&#8217;ll add <strong>the future of high-def drives on PCs and notebooks </strong>to my growing evidence that HD DVD will be the ultimate winner. If nothing else, <strong>I&#8217;ve been consistent </strong>on this one.</p>
