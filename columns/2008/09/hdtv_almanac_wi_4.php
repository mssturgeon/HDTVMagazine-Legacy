				<p>On September 8, <strong>most of the TV stations </strong>in Wilmington, NC turned off their analog broadcasts and broadcast only in digital. While most say that the transition went <strong>smoothly</strong>, there were still plenty of people caught unprepared for the change. This experiment was important so that local, state, and federal government officials <strong>could learn </strong>from the Wilmington experience, and hopefully maket the transition smoother for the rest of the country when it occurs <strong>next February.</strong></p>
	<p>We all are fortunate that <strong>Dr. Connie Ledoux Book of Elon University </strong>in North Carolina had the foresight to have a team of<strong> student observers </strong>in Wilmington on the day of the transition. Dr. Book and her students helped <strong>answer the phone calls </strong>from area residents with problems, and the team&#8217;s observations provide some <strong>helpful details</strong> about the experience. Dr. Book was invited to testify about the event before the <strong>House Subcommittee on Telecommunications and the Internet </strong>on September 16. She generously shared <strong>a copy of her testimony </strong>with me, which contained a number of useful insights.</p>
	<p>Dr. Book&#8217;s overall impression is that the Wilmington transition <strong>went well</strong>. Government at all levels was involved in helping <strong>educate residents</strong>, and most were prepared. On the day of the transition, <strong>special resources </strong>were available. For example, Wilmington <strong>firefighters </strong>formed special crews who go to residents&#8217; homes on request, and help them <strong>connect their converter boxes </strong>correctly. While they were there, they would also provide a courtesy <strong>test of the smoke alarms </strong>in the home. Dr. Book reports that this sort of outreach is an important part of making the transition go smoothly.</p>
	<p>She also suggests that local stations<strong> &#8220;blink&#8221;</strong> their analog broadcasts more often, especially during some of the <strong>most popular shows</strong>. This means interrupting the progam to put up a <strong>text screen </strong>stating that this television might not be prepared for the transition, and <strong>contact details </strong>for additional information. She also recommends that station personnel go out and <strong>test signal strength </strong>on a block-by-block basis in their broadcast area, and make this information available to residents. Dr. Book found in Wilmington that there were <strong>hardship cases</strong>, and that the local stations should have <strong>a supply of converter boxes </strong>to give to viewers on the day of transition. These could be <strong>bought by the stations</strong> themselves, or some provision could be made to cover their cost through the <strong>rebate coupon program</strong>.</p>
	<p>Dr. Book made a number of <strong>other recommendations</strong>, but the key point is that television programming is the <strong>most effective way </strong>to communicate with viewers.</p>
	<p>It was valuable to have Dr. Book and her students <strong>on the ground </strong>in Wilmington on the day of the transition, as their observations can indeed <strong>help other communities </strong>prepare. I&#8217;m not sure that I<strong> share her optimism </strong>about the process, however. Wilmington has been placed under <strong>a national magnifying glass</strong>, and all sorts of resources have been focused on helping residents make the transition smoothly. Even with this effort, many residents<strong> were not prepared</strong>. The local WalMart<strong> sold out of converter boxes </strong>three days before the changeover.</p>
	<p>I doubt that most stations have the resources to do <strong>thorough testing </strong>of their broadcast signal strength throughout their range, even if they limited it to<strong> the fringe areas</strong>. And getting that information efficiently to the residents who need it will be a challenge, since <strong>most people don&#8217;t need it </strong>(because they have cable or satellite service). And the idea that all communities will be able to <strong>mobilize their fire departments </strong>or other agencies to assist anyone with problems connecting their converter boxes paints a nice image of <strong>community service</strong>, but it&#8217;s not going to be practical in many places, ranging from<strong> dense urban markets </strong>to broadly spread out rural communities. Wilmington is a fairly <strong>compact and self-contained </strong>market, so there are aspects of this test that are<strong> not representative </strong>of what people will experience in their cities and towns.</p>
	<p>I do agree with Dr. Book that <strong>much has been done </strong>already, and that more can be done <strong>easily </strong>&#8211; such as blinking analog programming &#8212; to help make people aware of the transition. I still believe that many people, primarily <strong>poor and elderly </strong>residents, are going to have <strong>most of the problems </strong>when the changeover occurs, and local communities need to <strong>be prepared </strong>to field their questions and provide them effective assistance if they can. I expect that there will still be<strong> some bumps </strong>left in this road to all-digital TV broadcasts.
</p>
