				<p>February 17, 2009 is just <strong>four months away</strong>. If you have any of your TVs connected to <strong>an antenna</strong>, you should be thinking about how you&#8217;re going to get a signal after the digital conversion. Your <strong>old analog set </strong>can have a long life after the digital switch-over, but you&#8217;ll need a<strong> digital converter box</strong>. (My old <a href="http://hdtvprofessor.com/HDTVAlmanac/?p=569">Almanac entry</a> from a year ago still gets <strong>a number one position </strong>on several Google searches.) You may even still have time to get one or two of the federal rebate coupons from <a href="https://www.dtv2009.gov/">https://www.dtv2009.gov/</a>.</p>
	<p>If you do get a converter box &#8211;<strong> or know someone </strong>who is getting one &#8212; it&#8217;s easy to set it up. Basically, you connect it between <strong>your antenna and your TV</strong>. Like a VCR, you set the box to <strong>Channel 3 or Channel 4 </strong>(depending on which one is vacant in your market), and then tune your TV to that channel to get the digital channels. <strong>Zenith </strong>is one of the brands that is supplying a lot of the converter boxes, and they have <strong>posted a good video </strong>that demonstrates how to set up a digital converter box at <a href="http://www.zenith.com/dtv/setup.html">http://www.zenith.com/dtv/setup.html</a>. It glosses over a few points, but it is a <strong>simple and accurate explanation </strong>of the steps.</p>
	<p>One of the <strong>lessons learned </strong>from the Wilmington, NC switch-over <strong>last September </strong>was that people <strong>needed a lot of help</strong> hooking up their converter boxes. The <strong>local fire departments </strong>had squads that would come out and <strong>make house calls </strong>to set up the boxes for residents &#8212; and give <strong>a free check </strong>of their smoke detectors while they were there &#8212; but not every community is going to be able to <strong>make such resources available</strong>. If you can be ready to <strong>help friends and neighbors</strong>, you can help provide a welcome service.</p>
	<p>The other lesson was that the time to <strong>make sure </strong>you can get digital reception is <strong>before they turn off </strong>the analog broadcasts. Get your converter box<strong> as soon as you can</strong>, and hook it up. Weak reception of analog signals results in a <strong>snowy picture</strong>; weak reception of a digital signal results in <strong>a blank screen</strong>. You may discover that you&#8217;ll need to <strong>upgrade your antenna </strong>in order to get adequate reception.</p>
	<p>So for the digital transition, follow the Boy Scout motto, and &#8220;<strong>Be prepared!</strong>&#8220;
