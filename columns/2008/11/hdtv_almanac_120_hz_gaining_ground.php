				<p>A new flat panel report from <a href="http://displaysearch.com/cps/rde/xchg/displaysearch/hs.xsl/120_Hz_Panels_in_LCD_TVs_and_LED_Backlights_in_Notebook_PCs.asp">DisplaySearch</a> indicates that the proportion of LCD panels with <strong>120 Hz refresh </strong>increased from 12% in the second quarter of 2008 to <strong>16% in the third quarter</strong>. This is a big increase: one third more in just one quarter.</p>
	<p>The shift becomes more significant when you<strong> break it down by size</strong>. 120 Hz panels held just a <strong>6% share in 32&#8243; panels</strong>, increasing to 25% in 42&#8243; panels, and a whopping <strong>59% for panels 52&#8243; and larger</strong>. The faster refresh rate is coming to <strong>dominate </strong>the larger sizes.</p>
	<p>This makes sense on a number of fronts. LCD TV manufacturers are<strong> struggling to differentiate </strong>their products. After all, once they have the same 1080p resolution and a bunch of <strong>HDMI connectors</strong>, what more can you do to make an LCD panel in a plastic case more appealing or <strong>worth more </strong>to buyers? There isn&#8217;t much, except increase peformance. 120 Hz refresh does help <strong>reduce motion blur</strong>, so this could be viewed as a premium feature by consumers. I expect that it will soon become <strong>a standard feature</strong>, however, which won&#8217;t command a premium price but instead will be expected by consumers and sets without the feature will be at a <strong>competitive disadvantage</strong>.</p>
	<p>The fact that 120 Hz is more popular <strong>in the larger sizes </strong>is also informative. One the one hand, the larger sizes tend to be the <strong>premium products</strong>, so it makes sense that people would pay a little more for the feature. Next, the electronics of the set represent<strong> a smaller portion </strong>of the total cost of the TV when you get to larger sizes, so manufacturers <strong>can afford </strong>to spend a little more on electronic features without it affecting their costs as much as it would with a smaller set.</p>
	<p>But I think perhaps the most important reason is that 120 Hz probably doesn&#8217;t make as <strong>much difference </strong>on smaller sets. Now, this may sound strange at first glance. After all, if the sets have the<strong> same resolution</strong>, wouldn&#8217;t motion blur affect them equally? I haven&#8217;t seen any studies on this, but it is possible that the larger <strong>liquid crystal cell size </strong>of the larger panels might result in more blurring, but I don&#8217;t expect that&#8217;s a factor. Instead, I expect that people who buy smaller LCD TVs are buying them to<strong> save money</strong>. As a result, I expect that most people watch their 32&#8243; sets from a <strong>distance much greater </strong>than the four feet that would be optimal. At a greater distance, the blur would be <strong>less noticeable</strong>, so adding 120 Hz refresh is not as important.</p>
	<p>The fact remains, however, that everything else being equal, 120 Hz gives you <strong>sharper results </strong>for moving images. Given two choices at the same price, <strong>pick the one </strong>with 120 Hz.
</p>
