	<p>The<strong> LCDs win </strong>on resolution alone. The 32&#8243; plasma has the requisite <strong>720 lines </strong>for high-definition images, but it falls down on the horizontal resolution. Like many smaller plasma panels, it <strong>only has 1,024 horizontal pixels</strong>. This means that it cannot display the full detail of a 720p image; I call it <strong>&#8220;almost HD&#8221;. </strong>The LCD panels, on the other hand, have no difficulty in making small pixels. They have <strong>Wide XGA </strong>resolution, which is <strong>1,366 by 768 pixel native resolution</strong>, which is more than enough to display the <strong>1,280 by 720 required for 720p images</strong>.</p>
	<p>Now, I&#8217;ll grant you that both of these pixel arrangements will have to <strong>scale a 720p image </strong>in order to fit it on the screen, but the plasma will have to <strong>throw away information </strong>where the LCD will be interpolating to <strong>fill in the gaps </strong>of an expanded image. Assuming <strong>equal quality scaling circuitry</strong>, I&#8217;ll take the solution that expands existing information over one that throws it away. For 1080p images, both the LCD and plasma will have to throw away information from the image, but the LCD will have throw away less.</p>
	<p>I expect to see prices for 32&#8243; LCD HDTVs <strong>continue to fall</strong>, especially if sales are slow in September, and I doubt that plasma will <strong>be able to keep up </strong>competitively. The small plasma models enjoyed<strong> a nice bump </strong>in the first half of this year, but I don&#8217;t expect them to remain as <strong>a significant part </strong>of the flat panel landscape going forward.
</p>
