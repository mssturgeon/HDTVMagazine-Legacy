				<p>Let me start by saying that I&#8217;m<strong> a bit hawkish </strong>about copyright protection; I&#8217;ve made my living for more than 25 years by creating copyrighted content. However, I&#8217;m also opposed to <strong>heavy-handed enforcement </strong>that gathers in innocents while trying to deter violators.</p>
	<p>One problem is that copyrights are <strong>frequently abused </strong>on online video sites, particularly YouTube. People think nothing of taping a segment of <strong>a TV show or movie </strong>and posting it on the site. This is content that <strong>cost a lot of money </strong>to create, and content that its creators rely on as <strong>a source of revenue</strong>. So I agree that it&#8217;s proper for them to have the option to <strong>defend their rights </strong>to determine how and where that content is distributed. (I won&#8217;t get into the strategic issues related to this, and the value of<strong> free publicity</strong>. I will point out that WordStar was the <strong>most pirated software </strong>program of its day, and also the most successful <strong>financially</strong>; many believe that all those &#8220;free samples&#8221; helped build the market for the product.)</p>
	<p>But what about someone creating <strong>a funny home video </strong>that uses a commercially-recorded song as the background? Or even if such a song was <strong>playing in the background </strong>as the video was being shot? If this was done in a movie that was going into <strong>commercial distribution</strong>, you&#8217;d have to pay for a license to include the song (and those fees can be <strong>pretty steep </strong>if you&#8217;re a small-time documentary film maker). But if you&#8217;re just a person making a home video that you want to <strong>share for free </strong>with people, that&#8217;s a different matter. Should this sort of use be <strong>viewed the same </strong>as simply copying a protected work and distributing it?</p>
	<p>Until recently, a copyright holder could issue a &#8220;<strong>take-down</strong>&#8221; notice to a site like YouTube, and they would typically remove the <strong>offending content </strong>from the site, with no questions asked. But when Universal told YouTube to take down <strong>a home video </strong>that happened to have a Prince song playing in the background, the woman who posted the clip sued, claiming that the use of the song was permitted under &#8220;<strong>Fair Use</strong>&#8221; provisions of copyright law.</p>
	<p>Last week, a judge agreed. In order for there to be a copyright violation, <strong>four factors </strong>must be considered. Is the offending work intended for sale? What is the nature of the copyrighted content? How much of it was used? And does the new work devalue the original content? So now copyright holders are required to take<strong> Fair Use provisions </strong>into account before issuing a take-down notice.</p>
	<p>I view this decision as good news. Yes, this will mean <strong>more work </strong>for the copyright holders in order to determine which posted clips are truly violations of their rights, and which are likely permitted under Fair Use. But I think that this is <strong>the cost of doing business </strong>in the digital age, and companies should not be able to transfer that workload to the <strong>innocent users </strong>protected by Fair Use. This is certainly not going to <strong>stop pirated content </strong>from appearing on YouTube, but it&#8217;s also not likely to open <strong>the floodgates </strong>to violators either. And I believe that in the long run, this decision <strong>will do little to suppress </strong>the creation of new, copyrighted, commercial content, but may encourage <strong>more people </strong>to get involved in creating new content of their own. And that will make the Internet <strong>a richer place </strong>for all of us.
