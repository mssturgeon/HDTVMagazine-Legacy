	<p>A press release from <strong>Futuresource Consulting </strong>argues that Blu-ray is on <strong>the fast track </strong>for adoption. Many people hold up standard DVD technology as <strong>the fastest consumer electronics adoption </strong>ever, and Futuresource believes that Blu-ray is running <strong>ahead of that pace</strong>. They call 2008 the third year of Blu-ray availability, and point to more <strong>than 10 million </strong>players installed by the end of this year. In contrast, DVD players only had <strong>1.5 million units </strong>in place at the end of their third year.</p>
	<p>Futuresource admits that the <strong>PlayStation 3 </strong>units contribute a significant number to Blu-ray&#8217;s total. Market researcher iSupply is predicting that the PS3 installed base in <strong>2011 will be about 38 million units</strong>, while Futuresource is predicting more than <strong>45 million Blu-ray players</strong>. If these numbers are accurate, then there will be<strong> fewer than 7 million Blu-ray DVD players </strong>in homes around the world. That number is considerably smaller than the <strong>37 million DVD players </strong>that were out by that technology&#8217;s sixth year (2002).</p>
	<p>So <strong>the key question </strong>is whether or not people are buying PS3 consoles in order to <strong>play Blu-ray movies </strong>on them. I&#8217;m guessing that the answer is no. And research mentioned by the president of <strong>Warner Home Video </strong>would seem to back that up. According to a report in <a href="http://www.screendigest.com/online_services/intelligence/video_and_dvd/updates/vi-010508-mb1/view.html">Screen Digest</a>, less than <strong>10% of U.S. PS3 households </strong>bought Blu-ray discs to play on their console in October 2007. This increased to more than <strong>15% in December 2007</strong>. The increase is hardly surprising, with the <strong>holiday gift-giving season</strong>, but let&#8217;s give the PS3 credit for the<strong> full 15%</strong>. Reduce the Futuresource numbers so that only 15% of the PS3s are counted as Blu-ray players, and the<strong> numbers fall back </strong>to about the same as for the original DVD adoption. And the curve is<strong> a lot flatter </strong>in the early years, so there&#8217;s no reason yet to expect <strong>the geometric rise </strong>in the next three years that we saw with DVD players.</p>
	<p>If I were one of the Blu-ray developers, I&#8217;d still be <strong>anxious about recovering the development costs </strong>on this one.
</p>
