			<p>Look, I'll admit it. I like to find a bargain as much as the next guy. When I walk into "DVDs 'R US", I always slide by the "previously viewed" bin first. When I travel, Budget Inn is high on my list. But experience has taught me that there are times when spending MORE is the smart thing to do in the name of economy. Recently, in the quest to find material to be contrary about (that's my mission here - had you guessed?), I found a significant number of posts on various websites focused on where to find the absolute rock bottom price for this or that piece of A/V gear. It's not unusual to find a subsequent post a week or two later looking for help on how to "fix" that same item.</p>

<p>Here's the thing. I appreciate that everyone has a budget, but there is some price point, below which, you would be better off to save your money until you can get something that has a reasonable "performance" return on your investment. I walk into potential clients homes all the time who are "disappointed" with that Home Theater-in-a-box that Sparky sold them down at Circuit Barn. Sadly, nothing can be saved from that pile. It either goes to Aunt Martha or ends up on E-Bay for 25 cents on the dollar.</p>

<p>When I spec a system for a client, I always get a sense for what the total budget is. Then, after backing out installation and calibration fees, I try to keep all the individual components at about the same quality level. In other words, on a scale of 1 to 10, I wouldn't pair a "4" DVD player with a "9" video display. Neither should you, but I've seen $8,000+ displays reviewed with sub-$100 DVD players. One couldn't possibly tell a thing about the video quality of the display, as any artifacts seen are likely generated by the player. Consequently, I'm advocating you keep relative quality levels in mind as you build your systems. Yes, there will always be a "weak link", and that's the piece you will probably target as your next up-grade from time to time, but don't let things get too far out of balance or you will never get the value returned on your most expensive component, as in the 4/9 scenario described above.</p>

<p>It is an extremely competitive world out there in our favorite sector and every manufacturer wants an unfair share of your discretionary income. This is good news in that it generally means we get what we pay for. No one should be surprised then, that we currently have to deal with a rash of problems with the sub-$300 High Definition DVD players that have just flooded the market in an attempt to gain share.</p>

<p>This readership is undoubtedly more knowledgeable about A/V value vs. performance than the hundreds of thousands who will be out shopping as the 02/09 transition draws near. They need your help. Remember, friends don't let friends buy anything that says "lifestyle" on the box.</p>
