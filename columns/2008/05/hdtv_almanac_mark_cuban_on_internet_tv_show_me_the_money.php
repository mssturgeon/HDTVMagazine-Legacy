	<p>Cuban then picks up on this, and adds the uncertainty of <strong>how many viewers </strong>a given show will be able to deliver for the advertisers. How do you know what to watch when <strong>there&#8217;s no schedule</strong>? Are TV networks making <strong>a huge mistake </strong>by putting their current TV schedules online for free? Will Web video be <strong>at the mercy of the search engines</strong>, relying on them to drive viewers to their content? He ends with the big question &#8220;The question is whether the dollars the<strong> big TV and media companies </strong>are creating online from the streaming of their current TV lineups are <strong>sustainable incremental dollars</strong>?&#8221;, drawing a possible parallel between online video and the sub-prime credit crisis.</p>
	<p>The column is interesting, and I certainly agree with Cuban that the &#8220;bottom line is that <strong>something has got to give</strong>. Business as usual is not going to cut it.&#8221; However, I found a lot of lucid points among <strong>the reader comments </strong>that are worth consideration.</p>
	<p>For example, one comment pointed out that advertisers might indeed be <strong>happy to pay 16 times </strong>as much for an online video ad than they would for a broadcast ad. If they were <strong>only one of two </strong>minutes of ads &#8212; rather than one of eight &#8212; in a half hour show, they might stand out more. And on the Web, if there&#8217;s<strong> no way to &#8220;TiVo&#8221; </strong>around the commercials, a lot higher percentage of the viewers will actually see the ad. And finally, the viewers of the Web content could be<strong> highly targeted </strong>for the ads. I was watching <strong>a broadcast show </strong>last night &#8212; no, I don&#8217;t remember which one &#8212; and I noticed an ad for <strong>Jaguar cars</strong>. I can tell you that I&#8217;m <strong>not in the market </strong>for a Jag, and I doubt I ever will be. I don&#8217;t know anyone with a Jag, and I don&#8217;t know anyone who is planning (<strong>or even hoping</strong>) to buy one. Yet the company apparently feels that by blanketing the US market with<strong> a prime time ad </strong>is a good way to reach their potential customers.  On the Web, you can<strong> know a great deal </strong>about the person who is viewing your content, and you can<strong> match the ads </strong>to their profile. Targeted ads that are <strong>actually watched </strong>could well be worth a lot more than 16 times the cost per viewer of a broadcast ad.</p>
	<p>Other comments made some good points as well. True, there is no schedule for a lot of the Web programming, but <strong>why not use RSS feeds </strong>to notify fans whenever a new episode or related program is posted? And don&#8217;t forget that there are <strong>other revenue models </strong>to consider; product placement can go a long way to fund programming. Have you ever watched any of the <strong>BMW &#8220;The Hire&#8221;</strong> episodes? (You can find them on YouTube.) Are they <strong>commercials or entertainment</strong>, or does it matter?</p>
	<p>Television is changing, and the Web is going to be a part of <strong>the future of video entertainment</strong>. Nobody knows for sure yet just how it will work and who will pay for it, but it&#8217;s coming and I&#8217;m <strong>betting that it will be better </strong>than the broadcast system we had 20 years ago.
</p>
