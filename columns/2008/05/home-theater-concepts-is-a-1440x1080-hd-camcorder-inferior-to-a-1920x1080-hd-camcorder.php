				<p><strong>1440x1080 HD video via modern HD camcorders "explained" through pixel geometry.</strong> <p>The question has been raised regarding how good 1440x1080 resolution from HD camcorders is when compared to "full" 1920x1080 resolution devices. While it is technically accurate to say that 1920x1080 images contain more pixels than 1440x1080 images the actual appearance to the native eye is not as different as logic might make you think. And the choice of "1440" as the resolution in the horizontal direction in a "1920x1080" world is not an arbitrary number but carefully selected due to pixel geometry considerations. Here's why. <p>1440x1080 video is recorded using <b><u>rectangular</u></b> pixels with an aspect ratio of 1.33:1 (the actual shape of the pixels, not the shape of the 1440x1080 image). Taking into consideration that most people like to try to understand screen ratios in terms of "square" (1:1) dots or pixels, this would mean that If you were to compare the 1440x1080 images <b><i><u>with 1.33:1 rectangular pixels</u></i></b> to 1920x1080 images with square (1:1) pixels then the two images so described would both end up with the same overall shape for the image - and that would be a 16:9 (or what we like to call a "1920x1080") shape. That's because when calculating the horizontal length for both situations 1.000 x 1920 = 1920 (of course) and 1.333333 x 1440 = 1920! Granted, a "true" HD 1920x1080 image contains more pixels in the horizontal direction but the fact of the matter is that in the vast majority of filming applications capturing 16:9 images with 1920 horizontally arranged "square" pixels is not perceptibly different than capturing 16.9 images with 1440 horizontally arranged "rectangular" pixels. A lot of this has to do with the fact that for most filming situations adjacent pixels contain a lot of the same or very similar video information. Add to this the possibility of interlacing or de-interlacing the final viewed product on a screen and the rectangular pixels might actually be better at displaying fast action with fewer visual artifacts, but that's another issue for another time. If one were filming highly intricate source material where there is a pixel to pixel difference due to source density (like, perhaps, microfiche or similar) then this would be a different story entirely. But the major application for most HD camcorders is movies, not high density data so one should not dismiss 1440x1080 "rectangular pixel-based" images in favor of 1920x1080 "square pixel -based" images. In fact, in some ways, the 1440x1080 images may actually look less digitized and slightly more "film-like" because of the rectangular pixels employed, but that purely subjective. <p>In other words, sometimes let your eyes tell you which you prefer, not simply the specification sheets.</p>
