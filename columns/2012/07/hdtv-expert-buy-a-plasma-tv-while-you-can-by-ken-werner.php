          <p>Videophiles prefer plasma TV to LCD, and plasma rates higher than LCD in side-by-side testing.  In addition, large-sized plasmas are less expensive than comparable LCDs, and their greater refresh rate allows them to produce cleaner 3D images.  Nonetheless, the days of plasma TV are numbered.</p>
<p>As consultant David Barnes observes, you need look no farther than the difference in expenditures on manufacturing facilities to understand why PDP’s market share is declining and will continue to decline.  The remaining manufacturers of plasma display panels for consumer TV – Panasonic, Samsung, and LG – are making evolutionary upgrades to their panel technologies but they are not investing anything in new fabs.  Indeed, Panasonic recently discontinued manufacturing at one of its lines.  On the other hand, thanks in large part to the Chinese, significant new LCD capacity is coming on line.  At a certain point, the market share will drop to such a low level that companies whose life blood is high-volume manufacturing, will not be able to justify PDP production.<img class="alignright size-full wp-image-2244" title="Declining PDP-TV Market Share" src="http://www.hdtvexpert.com/wp-content/uploads/2012/07/35313__1086855663B42362D13BBC8CBD7B3B938.png" alt="" /></p>
<p>That’s not all.  Manufacturing of large-screen OLED-TVs has barely begun, but eventually – not for quite a while, but eventually – it should be possible to manufacture OLED-TVs less expensively that LCD-TVs, and quite possible less than PDP-TVs.  Although PDP has significant image-quality advantages over LCD, that is not true for OLED.  (OLED does have some remaining technical issues, such as blue lifetime, but they will be resolved.)  If the market-share issue is not enough to force the discontinuation of PDP-TV manufacturing, the rise of OLED-TV will be.</p>
<p>There is, of course, a background for all of this.  The flat-panel industry and the flat-panel TV industry are in desperate straits.  Most panel makers, and most TV makers are losing money – lots of it.  The margin on a TV-sized panel is small, if not zero, and TV sales are disappointing.  Financial gurus and panel makers see salvation in OLED:  a high-performance, high-value panel with a less expensive bill of materials and potentially lower manufacturing costs, that can generate higher margins.  For how long that will remain true is an open question, but few people seem to be worrying about that at the moment.</p>
<p>On the other side is consolidation in the LCD industry, which will further reduce costs.  Early this month, Samsung Display Co. (which had earlier been spun out of Samsung Electronics as a stand-along company), announced it had officially started doing business as “newly merged corporation with Samsung Mobile Display and S-LCD corporations.”  This was no surprise, but it formally combined the previously separate companies that had individually made LCDs and PDPs.  There are several motivations for this merger, but one of them has to be the smoother transition from LCD to OLED manufacturing.  In its formal announcement Samsung skated around this point, but not too much.  Samsung said, “The company also intends to strengthen its global competitive edge by combining OLED production technology with precision large panel operations and seasoned supply chain management.”</p>
<p>And Kazuhiro Tsuga, Panasonic’s new president, is the guy who, in his previous job running the consumer electronics business, closed one of the company’s PDP manufacturing lines and fired 1000 workers.  In late June, Panasonic and Sony announced they would work jointly to produce OLED panels and TVs, with industry sources saying Panasonic will invest about $370 million for a pilot line at its Himeji plant, according to Reuters.</p>
<p>Don’t panic, though.  You have three or four years to buy your next PDP-TV.  But it will probably be your last one.</p>
