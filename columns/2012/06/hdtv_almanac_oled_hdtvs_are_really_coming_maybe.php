<p>Which brings us to the topic at hand: OLED TV. Samsung and LG both showed 55&#8243; monsters at CES, but since I didn&#8217;t attend, I didn&#8217;t see them. I did get to see them last week, up close and personal. And I was certainly impressed. After discussing them with my friend and colleague <a href="http://www.displaymate.com" target="_blank">Ray Soneira of Displaymate</a>, I went back and looked at them even harder. Ray said that they had terrible color shift with off-axis viewing. I have great respect for Ray&#8217;s ability to see and identify quality issues in displays, but try as I might, I could not see any hint of color shift on either OLED TV. Now, if I had been able to throw some good test images on the screens (like you get with Displaymate), I might have been able to spot some differences. But from what I saw, they looked awesome.</p>
<p>Okay, so much for the good news.</p>
<p>Right off the bat, I am slapping LG&#8217;s wrist for claiming &#8220;infinite contrast&#8221; on their OLED TV sets. Yes, the screen probably puts out no light when displaying an all-black image, but that&#8217;s a pointless way to measure contrast. If you have a dark area next to a light area, I guarantee that some of that light will leak from the light area to the dark area. I&#8217;ll grant that these OLED screens will look terrific and have great contrast under these conditions, but the contrast ratio will definitely be something less than infinite. The bottom line is that &#8220;contrast ratio&#8221; as a meaningful specification for flat panel televisions is officially dead and LG holds the smoking gun. So from now on, ignore contrast ratio specifications and just trust your eyes.</p>
<p>And as good as the sets appeared, don&#8217;t start moving your LCD to the guest room just yet. Both LG and Samsung seem to be on track to ship an OLED TV model this year, but it may depend on your definition of &#8220;ship.&#8221; It is not clear that either company will be able to produce the OLED panels in large quantity this year. LG is relying on new and relatively untested &#8220;metal oxide&#8221; semiconductor technology to take the place of amorphous silicon. Even the OLED Association&#8217;s own forecasts show large panel production capacity to be just over 500 square meters per year for this year (but nearly tripling by next year). At a bit less than a square meter per 55&#8243; OLED panel, that means that there&#8217;s only capacity to make 600,000 panels. And that&#8217;s IF they started in January, which they didn&#8217;t, and IF they were running around the clock, which they aren&#8217;t, and IF they are getting 100% yield, which would be a miracle. The consensus seems to be that the manufacturers will be lucky to build 100,000 OLED TV panels this year. Just putting one demo unit in every store that will want to carry them will eat up most of that production.</p>
<p>But you&#8217;ll probably want to wait in any case. The initial price projections are at about $7,500 to $8,500 per set. That&#8217;s a hefty premium over LCD. In his SID keynote speech, Dr. James Lee from LG projected that the price will drop to 1.5 times the LCD price by 2015, and will reach price parity by 2017. The way that LCD prices continue to tumble, however, those are aggressive forecasts and I will be amazed if the company can hit those goals.</p>
<p>So let&#8217;s sum up: gorgeous image, crazy expensive, unproven technologies, aggressive manufacturing expansion, and possibly overly optimistic about future pricing. As much as I&#8217;d love to have an OLED screen in my living room, I&#8217;m accepting the fact that it will probably be on a cell phone or tablet, and not on my television.</p>

