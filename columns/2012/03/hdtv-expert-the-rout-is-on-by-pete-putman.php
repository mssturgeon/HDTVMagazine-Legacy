          <p>As things go, the flat screen TV business is relatively young. Until ten years ago, large LCD TVs weren’t even viable products. And plasma dominated the large screen (42” and up) flat screen TV business.</p>
<p> </p>
<p>But neither technology held any substantial market share. Instead, CRT televisions (and rear-projection CRT sets) were ‘kings of the hill.’</p>
<p> </p>
<p>Going back through some of my archives, I found that in the fourth quarter of 2005, CRT TVs held a 78.9% worldwide market share. That represented a decline of 15% from Q4 of 2004, no doubt due to the 137% increase in LCD TV market share in the same time period (yes, you read that right, 137%!).</p>
<p> </p>
<p>While LCD TVs held a 14.7% market share, plasma TV share grew from 1.8% of all TVs sold to 3.9%, a growth rate of 109%. CRT rear-projection TVs held .9% of the market, a drop of 60% from Q4 ’04, while microdisplay RPTVs grew to 1.6% of the pie, an increase of 52% over the same time period. (All numbers compiled from DisplaySearch reports.)</p>
<p> </p>
<p>How about the major TV brands? From Q3 ’05 to Q4 ’05, it might surprise you to learn that Sony had the top TV brand revenue share and growth, with 14% of all TV sales revenue (a quarterly growth rate of 130%)! Samsung was right behind with 11% revenue share and 36% Q-Q growth, followed by Philips (9.1% revenue share, 31% Q-Q growth), Panasonic (8.3% revenue share, 13% Q-Q growth), and LG (7.8% revenue share, 28% Q-Q growth).</p>
<p> </p>
<p>These five companies accounted for 50% of all TV revenue in Q4 of 2005. And there was only about a 6-point spread between #1 and #5, so the pie was being divvied up pretty equally.</p>
<p> </p>
<p>In terms of TV brand unit share, the order was changed somewhat. LG captured the number one spot with 9.8% unit share in Q4 ‘05, followed by Samsung (9.2%), TTE (7.5%), Philips (7.1%), and Sony (6.9%). The remaining 60% was chopped up among a host of brands.</p>
<p> </p>
<p>The eye-opener here was when I went back to the beginning of 2005. For the first quarter of the year, Sharp topped the branded TV market share with an amazing 21% (a year-to-year growth of 82%). Philips was number 2 with 14.7% share, followed by Samsung (10.8%), Sony (10%), and LG (7.3%). The five brands accounted for 60% of all TV sales back then.</p>
<p> </p>
<p>So – in a little less than a year, Sony added 7% to its brand share, while Samsung marched in place, LG picked up about 2 points, Sharp fell off the map completely, and Philips lost half its brand share. (TTE didn’t show up in the 2005 listings at all.)</p>
<p> </p>
<p>Now, let’s jump ahead to Q4 2011. NPD DisplaySearch’s latest numbers show that LCD flatscreen TVs now account for 86.5% of all TVs sold worldwide. Plasma continues to decline as it pushes into a larger screen ‘niche,’ grabbing a miniscule 6.9% market share. Amazingly, CRT TVs still held a 6.4% share, while RPTVs managed to eke out a .0004% market share – look for this category to be killed off completely in 2012.</p>
<p> </p>
<p>And the tables have turned completely from 2005 in terms of worldwide market share. Samsung managed the amazing feat of increasing its market share to 26.3% from Q4 ’10 to Q4 ’11, an all-time record and an amazing growth rate of 18% in an otherwise-flat (no pun intended) industry. LG was far behind Samsung with a 13.4% market share, essentially unchanged since Q4 ’10.</p>
<p> </p>
<p>As for Sony, they also held steady at 9.8%, basically the same as a year before, while Panasonic saw a decline of 2% to 6.9%. Sharp – who continues to sell fewer LCD TVs than Panasonic, incredibly – experienced a decline of 7% from Q4 ’10 to a 5.9% market share in Q4 ’11. These five brands accounted for 62.3% of the 74,236,000 TVs sold.</p>
<p> </p>
<p>So what does this all mean? First, Samsung has clearly blown away everyone else in the TV industry, opening up a double-digit lead over their nearest competitor (LG) in market share. And those two guys waste time arguing about whether passive or active is better for 3D viewing?</p>
<p> </p>
<p>Second, we’re seeing the slow, inexorable end of the Japanese television industry, just as we saw it happen in the United States in the late 1970s to the late 1980s. Sharp, Sony, and Panasonic are all hemorrhaging money for the current fiscal year that ends on March 31, and the consumer TV business is the primary reason.</p>
<p> </p>
<p>When TVs sold for $50 per diagonal inch and up, there was plenty of money on the table for everyone. But now that mainstream TVs screen sizes (up to 55 inches) are selling for $10 – $15 per diagonal inch, the Japanese simply can’t compete anymore. And it will only get worse with Chinese TV brands Haier, Hisense, TCL, and others establishing beachheads on all continents.</p>
<p> </p>
<p>Third, it’s over. The fat lady has sung. Samsung has won. They set out in the mid-1990s to beat Sony at their own game, and by any reasonable account, have succeeded beyond their wildest dreams. Samsung will make a nice profit on 2011 TV sales, and LG will at least get their LCD TV business back into the black.</p>
<p> </p>
<p>But the story isn’t so pretty for Sharp, Sony, and Panasonic. Sharp still has no explanation for their continual slide in market share, which apparently began in 2005 and continued uninterrupted, and which has now idled (by some accounts) 50% of their LCD fab capacity. As for Panasonic, they’d already shut down one LCD and one plasma factory in 2011, because demand just isn’t there. And no one in Osaka knows how to fix the problem.</p>
<p> </p>
<p>Sony is being pressured by financial analysts in Japan to get out of the TV business altogether, a decision which, as painful as it might be to management given Sony’s long and rich history with TV manufacturing, is probably the most sensible thing to do. The company’s TV business has lost money for eight straight years – never mind the strong market share numbers that popped up early on.</p>
<p> </p>
<p>And it’s not going to get better any time soon, as DisplaySearch stated that 2011 worldwide TV shipments actually declined .3% in 2011, reversing six consecutive years of growth. Only the LCD TV category showed any increase with a bare-bones 1% uptick. Everything else was on a downhill slide, with plasma declining 7%, CRTs falling 43%, and RPTVs in a 51% tailspin.</p>
<p> </p>
<p>Hitachi has already pulled the plug on their TV business. Toshiba and Mitsubishi will no doubt follow suit in the next 12-24 months. And that will leave us with the Hatfields &amp; McCoys in Korea, plus a host of Chinese brands you may want to get familiar with. (The running joke at CES 2012 is that it was the “Chinese” Electronics Show, and that’s not far from the truth!)</p>
<p> </p>
<p>The rout is on…</p>
