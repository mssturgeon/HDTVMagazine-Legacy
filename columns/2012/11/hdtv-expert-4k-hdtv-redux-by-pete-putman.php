          <p><strong>4K acquisition and display</strong> was the topic of a panel discussion I participated in during last week’s CCW / SATCON show at the Javits Center in New York City. My fellow panelists were technology guru and veteran video engineer Mark Schubin, and Larry Thorpe, senior fellow at Canon’s Imaging Technologies Group, and we gave attendees some useful perspective on what may be the next “gold rush” for television manufacturers.</p>
<p>Schubin’s comments pertained to just how much detail the human eye can perceive, and how contrast is often more important than viewing distance and screen sizes. (Did you know the average viewer sits about nine feet away from a TV, which measures most often between 40 and 49 inches in diagonal screen size? So much for 42-inch 4K televisions…)</p>
<p>He went on to add that perhaps the greatest benefit of 4K digital film and video production would be higher quality 2K HDTV delivered to the home, as 4K imaging sensors can capture far more detail than native 2K sensors because they have 4x the number of photosites.</p>
<p>Thorpe talked about the challenges of designing lenses for 4K cameras and illustrated that there are no lenses for 4K cameras with equivalent zoom ratios to today’s 2K camera optics – not an insurmountable obstacle, but a challenge nonetheless for camera manufacturers.</p>
<p>He also provided details about a live 4K broadcast earlier this of a baseball game in Japan via satellite links, using a nominal data rate of 120 Mb/s, and discussed how Fox Sports has used a pair of 4K Sony F65 cameras this season to assist NFL referees when they review challenged plays.</p>
<p>My comments were focused on the availability of 4K projection and direct-view displays, the majority of which are very large screens that present logistical challenges in the average home. I also gave the audience an idea of the bit rates involved in moving 4K content at high frame rates from source to display (how does 6 Gb/s per color channel at 3840×2160/60Hz with 10-bit color grab you?) and why this will be a headache for current implementations of HDMI and DisplayPort.</p>
<p>At the <strong>2012 SMPTE Fall Technical Conference</strong> last month in Hollywood, I chaired a session on UHDTV, and the three papers presented detailed an 8K camera/projection system developed by NHK; a compact, 25-megapixel 70mm (4K) Panavision camera with flash memory, and an update on SMPTE standards for transporting ever-greater amounts of data as we move to higher resolution imaging and workflows.</p>
<p>Interestingly, the last presentation, made by John Hudson of Semtech Corporation, showed quite clearly that copper isn’t quite dead yet when it comes to high data rates, and that reaching speed as high as 96 Gb/s is clearly possible over short lengths of coaxial cable. (To be sure; there’s still plenty of work for optical fiber interfaces in broadcast and film production environments.)</p>
<p>Hudson talked about the SMPTE 32NF40 Multi-Link 3G Ad Hoc Group that is currently working to standardize doubling and even quadrupling of 3G HD-SDI interfaces towards the goal of achieving 6 Gb/s and 12 Gb/s uncompressed data rates, suitable for 10-bit and 12-bit 4K production workflows. He also pointed out that telecom switches capable of handling 6, 12, and even 24 Gb/s data rates are readily accessible and not cost-prohibitive.</p>
<p><img class="aligncenter size-full wp-image-2527" title="Hisense XT880 UHD (4K) TV CORR 600p" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Hisense-XT880-UHD-4K-TV-CORR-600p.jpg" alt="" width="600" height="437" /></p>
<p>In the consumer world, <strong>Hisense</strong> made some news when it announced <strong>three new 4K (3840×2160) edge-lit LCD TVs</strong> would launch at CES 2013. This new line, known as the XT-880 series, will be available in 50-inch, 58-inch, and 65-inch screen sizes. All three models will support active shutter 3D, come with Internet access (built-in WiFi), and are equipped with an ARM dual-core microprocessor running on Android’s Ice Cream Sandwich OS. (They even support gesture recognition and voice control!) No retail prices have been announced yet.</p>
<p>At CES, we’re likely to see a <strong>larger 4K TV from Toshiba</strong>, who is apparently going to source the 84-inch IPS glass that LG Display is selling to LG and Sony. <strong>Not so JVC</strong>, who confirmed to me that they have no interest in selling their 84-inch version of the LGD glass (PS-840UD) to consumers, save for high-end home theater installations. It’s more of a general-purpose 4K monitor for professional work. And we know <strong>Samsung will put the spotlight on their 85-inch 4K PVA LCD TV</strong>, which was announced two weeks ago but has yet to make its appearance in any kind of an “official’ press release photo.</p>
<p>Finally, I was asked by a friend in the TV industry regarding rumors that we’d hear about an <strong>updated version of HDMI,</strong> to be announced in Las Vegas. This version, which will allegedly be v1.5, will supposedly address the data transfer speed limitations of HDMI (currently capped at 8 Gb/s with overhead and 10.2 Gb/s with all overhead removed). Presently, HDMI is hard-pressed to show 4K content at frame rates higher than 30 Hz, which requires about 2.5 Gb/s per color channel for a 3840×2160 video stream).</p>
<p>If you hadn’t heard, there is a group of manufacturers working with Silicon Image on a specification for <strong>HDMI 2.0</strong>, which is intended to address a whole host of problems with the currently interface – not the least of which is its speed limit. One motivator for the upgrade to 2.0 is clearly DisplayPort, a competitive digital display interface targeted at notebooks and ultrabooks and which, at 17.2 Gb/s, is clearly fast enough to carry a 4K signal at 60 Hz with 10-bit color (about 6 Gb/s per channel). So a short-term ‘jump’ to HDMI 1.5 seems more like a Band-Aid right now, but you never know what the marketing guys at the big TV brands are yelling for.</p>
<div id="attachment_2528" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2528" title="JVC PS-840UD CROP MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/JVC-PS-840UD-CROP-MR.jpg" alt="" width="600" height="371" /><p class="wp-caption-text">JVC’s 84-inch PS-840UD will be available for home theater enthusiasts, but is really targeted at professional applications.</p></div>
<p>And speaking of DisplayPort, the Wireless Gigabit (WiGig) Alliance announced last Friday that it is now collaborating with the Video Electronics Standards Association (VESA) to define and refine a specification for <strong>60 GHz wireless DisplayPort</strong>, using 2.6 GHz-wide channels available in many countries. So it’s entirely possible that we’ll be able to connect 4K displays without any cables at all by the time 4K content becomes widely available.</p>
<p>If you’ve spotted parallels between these developments and the early days of the transition to HDTV, you’re not alone. At present, there are (a) questions about what a “true” 4K resolution specification should be, (b) scarcities in cameras and production equipment, (c) bandwidth challenges to overcome, (d) high-priced displays that we know will become affordable quickly enough, and € competing interface standards.</p>
<p>The only thing missing is an optical disc format war, but with the Blu-ray format currently limited to 8-bit color, don’t be surprised if that conflagration breaks once again. Just like the good old days of HDTV…</p>
