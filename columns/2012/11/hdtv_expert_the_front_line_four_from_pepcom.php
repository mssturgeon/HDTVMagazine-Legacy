          <p>Last Thursday (11/15), the Hammerstein Ballroom on 34<sup>th</sup> Street in New York City was full of tango dancers, Argentine wine, good food – and some interesting products that will get plenty of exposure at January’s International CES.</p>
<p>Pepcom puts on this show several times a year, rotating between the midtown location and the Metropolitan Ballroom on 18<sup>th</sup> Street.  It’s a chance to get a much more “up close and personal” look at many cutting-edge CE products that would be tough to seek out at larger trade shows.</p>
<p>The November event featured a slew of interesting products from the latest Roomba robotic vacuum cleaners to high-efficiency LED lighting panels and super-dense flash memory sticks and drives. But there were four products in particular that caught my attention.</p>
<div id="attachment_2515" class="wp-caption aligncenter" style="width: 599px"><img class="size-full wp-image-2515" title="Lenovo Win8 Tablet with Keyboard MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Lenovo-Win8-Tablet-with-Keyboard-MR.jpg" alt="" width="589" height="600" /><p class="wp-caption-text">Lenovo’s IdeaTab Lynx is a clever, hybrid tablet/notebook concept.</p></div>
<p>Lenovo had a demonstration of its first tablet computer; complete with a snap-on full-size keyboard (the attachment is magnetic). It’s called the IdeaTab Lynx, and is a pretty cool product. The keyboard, which is actually a dock, weighs about 1.5 pounds, and the 11.6-inch screen/tablet comes in just below that. The tablet/screen has a resolution of 1366×768 pixels and employs a 5-point capacitive multi-touch system.</p>
<p>Other features include a 2 MP front camera, 2 GB of DRAM, 32 GB or 64 GB of eMMC storage, and stereo speakers. The IdeaTab Lynx runs Windows 8 from an Intel ATOM dual-core 1.8 GHz processor and battery life is estimated at eight hours for the tablet and another eight hours from the dock. Lenovo has a suggested starting price of $599 for the tablet and another $150 for the keyboard/dock.</p>
<p>Across the aisle, Vizio had its new 70-inch LCD TV set up for inspection. The E70121-A3 Razor LED has all of the usual bells and whistles you’d expect in this size class, including built-in WiFi, a “smart” remote with full QWERTY keyboard, and an extremely slim bezel. Vizio claims the viewable area on this TV is 69.51 inches, and it uses 10-bit signal processing.</p>
<p>Of course, the E7011-A3 comes with Vizio Apps, including access to Netflix, YouTube, Hulu Plus, and Vudu (which together constitute about 85% of all Internet video traffic). Taking a look at the panel, I noticed a resemblance in off-axis performance to Sharp’s 70-inch Aquos and I wouldn’t be surprised if Vizio is sourcing the panel from Sharp. The target MSRP is $1,999, which is where Sharp’s 70-inch Aquos was selling in late January of 2012.</p>
<div id="attachment_2516" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2516" title="Vizio 70-inch LCD TV - 2 CROP MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Vizio-70-inch-LCD-TV-2-CROP-MR.jpg" alt="" width="600" height="524" /><p class="wp-caption-text">Is this really a Sharp Aquos in Vizio clothing? Could be…</p></div>
<p> </p>
<div id="attachment_2517" class="wp-caption aligncenter" style="width: 610px"><img class=" wp-image-2517" title="Nook HD+ MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Nook-HD+-MR.jpg" alt="" width="600" height="450" /><p class="wp-caption-text">The B&amp;N Nook HD+ adds to an already overcrowded market for tablets, but is competitively priced.</p></div>
<p> </p>
<p>Next to Vizio, I found the folks from Barnes &amp; Noble showing off their latest Nook tablets – the 7-inch Nook HD and the 9-inch Nook HD+. B&amp;N has come a long way in two years from the original Nook reader, and the product migration appears to be towards do-it-all tablets instead of basic readers. (Nook’s Color tablet reader is still in the line, but apparently will be phased out.)</p>
<p>The Nook HD uses a 1440×900 pixel LCD display and is available with 8 GB ($199) or 16 GB ($229) internal flash memory. It runs a Dual-Core 1.3 GHz OMAP4470 processor and the Android OS. I noticed there is support for Google Office, meaning that Microsoft Office documents can be opened and worked on with this tablet. Battery life is rated at 10.5 hours for reading and 9 hours for video.</p>
<p>The Nook HD+ moves up to a 9-inch screen with 1920×1280 (WUXGA) resolution and comes with 16 Gb ($269) or 32 GB ($299) of internal memory. It employs the same processor and OS as the 7-inch tablet and has similar battery life. I found both tablets very bright and contrasty under the overhead spotlights used in the ballroom, and reflection from the LCD screen was minimal. Alas; there’s still no place to make an external display connection like there is on the iPads.</p>
<div id="attachment_2518" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2518" title="Mohu Sky HDTV Antenna MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Mohu-Sky-HDTV-Antenna-MR.jpg" alt="" width="600" height="450" /><p class="wp-caption-text">Mohu has decided it’s spending too much time indoors! This Sky HDTV antenna is the result.</p></div>
<p>Finally, I ventured to the back of the room by the wine bar and ran into the folks from Mohu. Regular readers will recall my frequent tests of indoor TV antennas earlier this year; a competition that Mohu generally won or tied for first place. The news this year is a re-design of the Leaf Plus into the Leaf Ultimate, with the preamplifier now encased in a separate module. You can also buy this preamp by itself as the Jolt Amplifier.</p>
<p>That re-design allowed Mohu to simplify its manufacturing process – just add the Jolt module to an existing Mohu Leaf and you have an Ultimate model. But Mohu isn’t done there: They’ve also unveiled a new outdoor TV antenna that closely resembles a crossed dipole, used by many antenna manufacturers. The Sky HDTV is designed for mast-mounting on a roof or in an attic, and will also work with the Jolt amplifier. No prices have been announced yet.</p>
