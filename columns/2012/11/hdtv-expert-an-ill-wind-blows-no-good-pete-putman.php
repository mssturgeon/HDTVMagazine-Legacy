<p>But we have no Internet access, as the fallen tree bent and snapped the combined Comcast/Verizon feeder cables on the same pole as our electrical service. Mobile phone service is spotty – many of the cell towers nearby are operating on limited emergency power with generators – and trying to access the Internet on my Droid phone takes forever.</p>
<p>With Comcast knocked out, I have no cable TV service. But I do have an ace in the hole: Unlike my neighbors, I have a few rooftop TV antennas and can watch over-the-air digital TV broadcasts from Philadelphia and New York City.</p>
<p>My antenna system is powered by a few Channel Master preamplifiers and the OTA signals are available in several rooms. To power everything, I have a large 700-ampere truck battery driving a Radio Shack 300-watt AC inverter I picked up years ago. The inverter also connects to a power strip in my family room, where I can charge my phones, my eBook readers, my computers, and power an Eviant T7 LCD TV.</p>
<p>After the storm passed through Monday night, the Eviant TV and a Hauppauge Aero-M USB stick tuner were the only ways I could get any updates on storm damage. The Internet and cell phones were either out of commission or unreliable. But I was still able to watch broadcast digital TV.</p>
<p>No doubt about it; Hurricane Sandy was an unprecedented Category 1storm. We were lucky to avoid the devastation of the Jersey Shore, as only 1 – 2 inches of rain fell in our area and most wind gusts were well under 50 miles per hour. Even so, our roads are littered with downed trees and many of them won’t be cleared for another week.</p>
<div id="attachment_2478" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2478" title="DTV by the fireplace WPR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/DTV-by-the-fireplace-WPR.jpg" alt="" width="600" height="558" /><p class="wp-caption-text">Eviant’s T7 portable LCD TV did yeoman duty during the storm. I was able to watch DTV stations from Philadelphia and New York City any time I wanted.</p></div>
<p> </p>
