<p> </p>
<div id="attachment_2480" class="wp-caption aligncenter" style="width: 610px"><img class="size-full wp-image-2480" title="Rooftop Antenna System WPR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/11/Rooftop-Antenna-System-WPR.jpg" alt="" width="600" height="450" /><p class="wp-caption-text">…and here’s how I got the signals to the receivers. Fortunately, my VHF/UHF antennas held up nicely under Sandy’s 60+ mph wind gusts.</p></div>
<p>Not surprisingly, I ran into many people at the nearby convenience stores standing in line for coffee and clearing the shelves of milk, bread, and other supplies. A few of them expressed frustration with spotty mobile phone service, and of course everyone is at their wit’s end without Internet access. (How ever did our grandparents manage to survive storms all those years ago?)</p>
<p>When a few of my neighbors bemoaned the cutoff of TV service, I mentioned my antenna system and how it had withstood high winds to provide me with a multitude of channels, by which I was able to stay on top of road closings, weather forecasts, and see just how much damage Sandy had done to the immediate area.</p>
<p>I write this keeping in mind that Verizon, AT&amp;T, and the CTIA continue to push the FCC to take away more UHF TV spectrum through auctions in favor of expanding mobile broadband service. Ironically, in a crunch, the only reliable electronic information service I have is over-the-air TV, and it looks like that will be the case for at least another day or two.</p>
<p>And this storm has provided a perfect example of why shared-bandwidth networks (cell phones and the public Internet) are simply not reliable during widespread emergencies:  There are just too many people trying to use them, and falling trees and flooding can knock out a connection for days on end.</p>
<p>In contrast, it doesn’t matter whether ten people or ten million people watch a digital TV broadcast – the picture and sound quality are constant, and there is no network to overload and crash. And you can watch digital TV on a variety of portable devices, such as the Eviant LCD TV or a computer equipped with an appropriate USB stick tuner.</p>
<p>Our free, over-the-air digital TV system continues to serve us well in emergencies – <span style="text-decoration: underline;">Hurricane Sandy has proved that conclusively</span>. And there are other ways to address the so-called “wireless broadband spectrum crunch” that the CTIA claims is imminent, such more efficient channel modulation techniques using time domain multiplexing and freeing up vast numbers of frequencies currently occupied by the federal government.</p>
<p>The bigger problem is that our current mobile phone services still have major reliability issues when disaster strikes. Perhaps the Verizons and AT&amp;Ts of the world should concentrate their efforts on improving their existing networks for when the next big storm hits. What good is an expanded mobile broadband system if it’s still going to crash during an emergency?</p>
<p>Like I said at the start of this piece: If it ain’t broke, don’t fix it…</p>
