<p>Analysts have called for Panasonic to shed more personnel, but so far, the company plans to stand pat. <a href="http://www.reuters.com/article/2012/11/01/us-panasonic-earnings-idUSBRE8A003O20121101" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://www.reuters.com']);">According to Reuters</a>, the company is likely to change direction and move away from money-losing television and other consumer electronics business units. The company’s stock price has dropped by more than 35 percent as it continues to restructure after closing the acquisition of Sanyo.</p>
<p>Panasonic’s earnings announcement was a surprise as the company had eked out a modest profit in the 2nd quarter of this year. But once again, the culprit appears to be televisions, an area where Panasonic has lost money for four consecutive years.</p>
<p>Sony, the poster boy for mismanaging a flat panel television business strategy, fared slightly better than its competitors. The company managed to squeeze out a $379M operating profit for the 2nd quarter, compared to a $20M loss a year ago during the same time period. But analysts attributed a good portion of that profit to the sale of a chemicals business, <a href="http://www.reuters.com/article/2012/11/01/us-sony-earnings-idUSBRE89U1M220121101" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://www.reuters.com']);">according to yet another Reuters story</a>.</p>
<p>Even so, Sony is sticking to its original forecast of a $1.63B profit for fiscal 2012, which ends in March of 2013. But analysts still expect the company to lose money for the ninth consecutive year in its television operations, and Sony did announce it expects to sell fewer televisions this year (14.5M) than in 2011.</p>
<p>How much longer can this go on? The answer (at least in Sharp’s case) is until 2014, thanks to an additional $4.5B in bank loans obtained from Bank of Tokyo-Mitsubishi UFJ and Mizuho Corporate Bank. (Betcha the Japanese government was involved in that decision!)</p>
<p>How all of these companies got into this mess is a long story, but the main culprit is the near-commoditization of the television business. Worldwide television shipments are dominated by Samsung and LG, who control nearly 45% of the market between them.</p>
<p>In comparison; Sony, Sharp, and Panasonic together account for about 20% of worldwide TV shipments. It wasn’t that many years ago that Sharp had 21% of the LCD business to itself. Now, it struggles to maintain a 5% market share, and Sony is barely attaining 9%.</p>
<p>The decline of the Japanese TV industry has been well-documented by this and other publications. The trend is so clear and irreversible that we analysts often wonder just how far these companies will go to deny the truth and continue struggling to right what is obviously a sunken (not sinking) ship.</p>
<p>The fact is; all three companies have other business units that have plenty of upside. Assuming Sony comes to its senses and gives up on television manufacturing, it can do well in cameras, computers, and imaging – and may even see some gains from its PlayStation operations. Sony is doubling its efforts in cell phones and tablets, too.</p>
<p>Panasonic, thanks to its acquisition of Sanyo, is well-positioned to be a leader in both solar energy and battery technology, even though worldwide demand for solar cells is weak right now. The company has expanded its IPS-alpha LCD manufacturing capacity at its Gen 8 Himeji plant, showing 20-inch, 32-inch, and even 47-inch 4K panels. And it appears Panasonic is pushing ahead with OLED R&amp;D, anticipating the eventual sunset of plasma technology.</p>
<p>That leaves Sharp, whose decision to build the Gen 10 Sakai LCD fab may or may not have been a smart idea in retrospect. But what’s done is done, and now Sharp has to find a way to push plant utilization back to full capacity.</p>
<p>Given that Sharp appears to be closer to implementing IGZO (oxide) backplane technology than anyone else, and that Hon Hai is in the driver’s seat with Apple for now, the storm clouds over Osaka should be parting in the next year <span style="text-decoration: underline;">if</span> the Hon Hai deal closes and <span style="text-decoration: underline;">if</span> Sharp does the sensible thing and exits the TV business in an orderly fashion.</p>
<p>Otherwise, we may witness an enormous corporate bankruptcy, created by financial winds so strong that no one on earth can possible control them…</p>
