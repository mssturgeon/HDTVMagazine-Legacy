<p>The technology demos have also been impressive and feature a 4K LCD display (Panasonic) and 3D and 4K home theater projectors (JVC and Sony), a 2K reference-grade LCD monitor (Dolby), reference OLED monitors (Sony again), critical display calibration (Spectracal), and numerous exhibits of image processing, file management, color correction, format conversion, and cloud-based workflows (do you know what ‘snowflakes’ are? If not, you should…)</p>
<p> </p>
<p>As usual, I presented my annual CES review and roundup, ripping through 80+ slides and numerous video clips in 30 minutes (Tech Retreat chair Mark Schubin is a stickler for starting and ending on time), and also co-moderated the Next-Generation (lampless) Projection panel with HPA vice-president and multi-panel moderator Jerry Pierce.</p>
<p> </p>
<p>During my CES Review, I used a wireless HDMI connection from my Toshiba Satellite notebook to the house projection system (stacked Panasonic 10,000 lumens 1080p DLP projectors on 16-foot screens). That’s a distance of 75 feet from lectern to receiver, and the signal never dropped through any of my slides or video clips.<em> (A tip of the hat to Les Chard of the WHDI Consortium, who graciously overnighted me a replacement WHDI receiver – mine was left at home!)</em></p>
<p> </p>
<div id="attachment_1806" class="wp-caption aligncenter" style="width: 510px"><a href="http://www.hdtvexpert.com/?attachment_id=1806" rel="attachment wp-att-1806"><img class="size-full wp-image-1806" title="Peter Lude and Jerry Pierce WR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/02/Peter-Lude-and-Jerry-Pierce-WR.jpg" alt="" width="500" height="667" /></a><p class="wp-caption-text">Peter Lude (standing) talks about the new Laser-Illuminated Projector Association (LIPA) while Jerry Pierce moderates.</p></div>
<p>Another feature of the Retreat is the informal breakfast roundtables. You propose a topic and if it is accepted, you get to “chair” a group of fellow attendees and are free to hold court on your topic. So far, I’ve hosted two roundtables on digital display interfaces and wireless display interfaces, and both tables were ‘sold out!’ In fact, I got to my first roundtable on Wednesday a bit late and there were no seats left – that is, until I subsequently informed the seated attendees that they wouldn’t have a moderator, after which a space was hastily freed up for my chair.</p>
<p> </p>
<p>The Tech Retreat has been around for a little more than a decade, and during that time has almost doubled in size. This year’s edition moved to the Hyatt Grand Champions Resort in Indian Wells, CA because the old venue was just too small. The pictures show why – Wednesday’s crowd was standing room only!</p>
<p> </p>
<p>Several companies have chosen the Retreat to do pre-NAB product introductions. Sony’s 2011 launch of its new TriMaster OLED reference monitors is a good example. The Tech Retreat is also where I saw my first 3D NFL footage and my first multi-random-projector image tiling system, heard detailed explanations of human visual response and how it affects 3D viewing, experienced the visual quality of high dynamic range cameras, and witness how MPEG program splicing actually works.</p>
<div id="attachment_1807" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/?attachment_id=1807" rel="attachment wp-att-1807"><img class="size-full wp-image-1807" title="Bob Lambert at Podium with H1650 Speaker Support WR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/02/Bob-Lambert-at-Podium-with-H1650-Speaker-Support-WR.jpg" alt="" width="600" height="450" /></a><p class="wp-caption-text">Long-time Disney tech guru Bob Lambert recounts the history of projection "light engines" (including candles) with his slides shown on a Casio XJ-H1650 hybrid laser/LED projector.</p></div>
<p> </p>
<p>It all makes for a stimulating and worthwhile program. Many technical innovations are first shown at the Retreat, as are fascinating programs on film restoration and archiving. And it’s all very informal – come as you are, no need for speaker bios or power suits. To paraphrase Shakespeare,<em> ‘the information’s the thing,’</em> and you’ll be challenged and baffled by Mark’s multiple technology history quizzes. (Example: What significant invention that we use every day was first unveiled at the 1876 Centennial Exposition in Philadelphia? Come on, you know!)</p>
<p> </p>
<p>Here’s the best part about the Retreat: <span style="text-decoration: underline;">Anyone can attend</span>, and the program draws from a wide range of industries and disciplines. You’re just as likely to find yourself sitting at a general session table or sharing dinner with a studio executive, TV network engineer, or colorist for a post-production facility as you would with a creative services manager from a major insurance company, a media services supervisor at a large university, or a director of one or more state or federal government agencies.</p>
<p> </p>
<p>TIP: If you plan to attend in 2013, better register early as the event usually sells out a month in advance. (So do the hotel rooms!)</p>
<p> </p>
<p>See you next year!</p>
