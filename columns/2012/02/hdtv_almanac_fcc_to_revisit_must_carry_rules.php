				<p>I&#8217;ve already written a bunch about <a href="http://hdtvprofessor.com/HDTVAlmanac/?p=1596">the problems with retransmission fees</a> and how pay-television subscribers get caught in the squeeze between their services and the content providers. Many people don&#8217;t realize that there is <a href="http://www.fcc.gov/guides/cable-carriage-broadcast-stations">a fascinating flip-side to this problem</a>, which is known as &#8220;must carry&#8221;. It works like this.</p>
	<p>Every three years, local television broadcasters have to make a choice. They can either make their content available to local pay-TV services (cable, satellite, and telco) in return for a retransmission fee, or they can choose to forego the fee and just require the pay-TV service to carry their signal on the subscriber system. It&#8217;s a tricky proposition. If you&#8217;re sure that consumers will want your programming (note that the pay-TV service is not allowed to go to some adjacent market to replace yours if it&#8217;s from the same network), then you go for the gold. If you&#8217;re not sure that anyone would miss it if your programming gets left off, then you may want to invoke the &#8220;must carry&#8221; rule so that you can reach a bigger audience and get more money from your advertisers.</p>
	<p>This whole system got more complicated with the digital transition. Cable companies started as community antennas, distributing the over-the-air signals through cables on the ground so that all homes in the area could get good reception. Originally, all cable systems were analog, and they just pumped the signals from the antennas through the wires. Then they got premium channels which they encrypted, which led to set top boxes to decrypt them. And then we got digital systems that offer improved image quality (and more secure encryption). The digital systems also made it possible to deliver high-definition images.</p>
	<p>So now we have digital transmissions from almost all television broadcasters, but many cable companies still maintain analog distribution networks. This means that the digital signals have to be converted back to analog in order to be sent to analog subscribers. Cable companies would like to convert over to all-digital systems, but this requires capital investment and converter boxes for any subscribers who still don&#8217;t have a television set with a digital tuner.</p>
	<p>Cable companies would like to free up some of their capacity by dropping local stations that don&#8217;t have much of an audience. Smaller broadcasters want to keep the &#8220;must carry&#8221; rule so that they don&#8217;t lose a major part of their audience (since so few people rely on over-the-air signals these days).</p>
	<p>This issue has come to a head because cable services were given a three-year waiver from the requirement to not degrade the rebroadcast signal. This was required because the standard definition analog systems cannot display the high definition content of some digital broadcasts without scaling it down significantly. That waiver expires in June, and the FCC needs to decide whether or not to renew it. If it does not renew the waiver, then local cable companies may be forced to switch to digital networks unless the FCC makes other changes to the &#8220;must carry&#8221; rule as well. In preparation for these deliberations, the <a href="http://www.fcc.gov/document/carriage-digital-television-broadcast-signals-rules">FCC has called for comments on the issue</a>.
</p>
