	<p>Well, the hard fact is that unless you own about 80% of the market share, you don&#8217;t get to name the catgory. The consumers might come up with one on their own, but the Balkanization of the terminology is likely to continue for a long time. Look at the devices that we connect to the Internet to get video content onto our TVs; I prefer to call them &#8220;network media players&#8221; but you&#8217;ll see them called &#8220;set-top boxes&#8221;, &#8220;digital media receivers&#8221;, or a bunch of other terms. About the only recent case that I can think of where the industry quickly standardized on a term was the ill-advised &#8220;LED TV&#8221; which created far more confusion for consumers than clarity.</p>
