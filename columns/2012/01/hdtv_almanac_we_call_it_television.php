	<p>But just because it&#8217;s difficult to get unanimous support for a term doesn&#8217;t mean that I won&#8217;t try anyway. I&#8217;m guided by a great quote from Esther Dyson, who once said of artificial intelligence, &#8220;that&#8217;s what we call it until we can do it&#8221; (or something like that; I can&#8217;t find the source.) The point is that we need names for new technologies until they get assimilated or they wither up and drop off the technology tree, but after that, the new term is extraneous. How many of us mention that we watch &#8220;color TV&#8221; these days? It was a big deal when I was in elementary school, but it&#8217;s just TV now. Or how many people still make the distinction that they watched &#8220;cable TV&#8221; or &#8220;satellite TV&#8221; last night? Heck, I doubt many people even make a distinction about high definition anymore.</p>
	<p>So what do we call this brave new world that lets us view moving images on demand, spanning both time and space so that they can reach us in our living rooms or on our computers, tablets, or even telephones? I don&#8217;t know what we call it now, but I&#8217;m pretty sure that we&#8217;ll end up calling it &#8220;television&#8221;.
</p>
