	<p>For example, take the &#8220;Large OLED HDTV&#8221; story. LG telegraphed its intention to show its <a href="http://hdtvprofessor.com/HDTVAlmanac/?p=1567">55&#8243; OLED HDTV</a> well in advance, so we knew to expect it. The big surprise came from Samsung, which <strong>also</strong> showed<a href="http://global.samsungtomorrow.com/?p=9422"> a 55&#8243; OLED HDTV</a>. It appears that when it comes to display technology, &#8220;Anything You Can Do I Can Do Better&#8221; must be the national anthem of South Korea. One reason that this was such a surprise is that Samsung has been pretty quiet about large screen OLED technology for the past year or so.</p>
	<p>There are some important differences between the two announcements. LG&#8217;s panel is a &#8220;color by white&#8221; design, which means that they make white-emitting OLED sub-pixels for the panel, and then cover them with red, green, or blue filters. (In an effort to boost brightness, the LG pixel layout also includes white sub-pixels with no filter at all.) The advantage of this approach is that you only have one OLED material which (we hope) will age uniformly. The Samsung design uses separate red, green, and blue emissive materials. This indicates that Samsung has apparently come up with a way to deposit the different materials in a finely patterned way on a large panel, which is no mean feat. We don&#8217;t yet know how the faster aging of the blue OLED material will affect the picture quality of the sets over time, and if this is a disadvantage compared with the LG design. Samsung also announced that they plan to fabricate the panels on a Gen 8 production line later this year, which could mean lower manufacturing costs than the panels built on smaller Gen 5.5 lines.</p>
	<p>The LG and Samsung announcements are more alike than different, in my opinion. Both promise vague &#8220;later this year&#8221; ship dates. Neither has offered any information about price or production volume. Remember that the Sony OLED TV never made it beyond pilot production volumes, and it remained a collectible rather than a competitive product for the brief time that it was on the market.</p>
	<p>I&#8217;m ready to be proven wrong, but I have not yet been given any reason to believe that these sets will come out at prices below the $5,000 to $10,000 range. If they cost that much when they finally ship, it will still be an important milestone for the OLED display industry, but that&#8217;s still too high for them to be considered viable competition for LCD or plasma models. These announcements from LG and Samsung are hopeful signs, but I expect that we could still be years away from competitive OLED HDTVs available in the marketplace.
</p>
