          <p>In the electronic displays world, medium-sized displays are those that are larger than cell-phone size and up to 10 inches on the diagonal.  Anything larger than 10 inches is a “large display.”</p>
<p>In an era of 90-inch TV sets, calling a 10.1-inch display “large” sounds silly, and it is.  The nomenclature dates back to a nearly forgotten time when the standard LCD in a laptop computer was 8.4 inches and 10 inches really was large, and it persists in part because certain display market intelligence companies will not let go of the old categories.</p>
<p>Obviously, the hot product application for medium-sized displays today is tablets, and thanks to one of Steve Jobs’ parting shots, high pixel density is quickly becoming a requirement for premium tablets, as it already is for smart phones.  For cell phones, “high pixel density” means 300 pixels per inch (ppi) or more.  The new iPad leads the tablet pack with 2048×1536 pixels on 9.7 inches for a pixel density of 264 ppi.  Expect others to follow quickly, as they have with displays for smart phones.</p>
<p>But here’s the question:  Do high-ppi tablet displays create problems – perhaps we should say challenges – for panel and tablet makers?  Yes, they do.  When you cram lots of pixels together for high pixel density, the pixels have to be small.  That means that traditional pixel-switching thin-film transistors (TFTs) made from amorphous silicon (a-Si) become relatively large compared to the size of each sub-pixel, and the TFT (which must be protected from light with a black ink-like material) blocks a lot of the light that you would like to have come through the sub-pixel when that sub-pixel is switched on.  This is called a small aperture ratio, and it means you need to have a more powerful backlight to deliver an image of a given brightness to the person using the tablet.</p>
<p>So, the new iPad has four times the number of pixels as the previous model, the iPad 2; and it uses a-Si TFTs just as the iPad 2 does.  And Apple has installed a whopping 42.5 Watt-hour battery in the new iPad, compared to 25 Watt-hours for the iPad 2     The new model is 51 grams heavier and runs significantly hotter.  (See <a href="http://displaydaily.com/2012/03/22/ipad-3-lhooq/" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://displaydaily.com']);">http://displaydaily.com/2012/03/22/ipad-3-lhooq/</a>.)  That shouldn’t  be surprising.  The new iPad is using 70% more power.  The associated heat has to go somewhere.  We should note that the display isn’t the only new component in the new iPad that is more power-hungry than its predecessor, but displays usually account for a big part of the power budget in portable devices.</p>
<p>Isn’t there a solution?  Don’t high-end smart phones, including Apple’s own iPhone, use a higher-quality semiconductor called low-temperature polysilicon (LTPS) so the TFTs can be smaller and the aperture ratio can be larger?  Yes, they do, but LTPS is fabricated with a manufacturing process that works best on the smaller panel fabs used for smart-phone displays.  It has proven very difficult to scale LTPS up to the larger fab sizes that could economically produce tablet-sized displays, although Samsung and others are trying hard.</p>
<p>How about OLEDs?  OLEDs need LTPS, too, so they are currently limited to Samsung’s largest OLED fab, which is Generation 5.5.  (There are also other reasons why OLED is currently limited to Gen 5.5.  You may have noticed that LG Display, which has intended to produce 55-inch OLED-TV panels on a Gen 8 fab, has delayed its introduction date three times in the last six months, and is now talking about a 2013 introduction.)  Until they can be made on larger fabs, 10-inch OLED displays, it is likely they will be too expensive to be used in full-sized tablets.  (Samsung’s largest OLED product is its 7.7-inch OLED Galaxy Tab.)</p>
<p>Another possibility is to use Indium Gallium Zinc Oxide (IGZO), a TFT material that is just now being introduced to large-volume LCD manufacturing and will sometime be used for OLEDs, as well.  It is said that Sharp is making oxide-TFT LCDs for Apple, but it is not yet clear for which product the first of these displays are intended or when they will appear.</p>
<p>There is another approach, Pentile Matrix, which Samsung Mobile Display has successfully used on millions of smart-phone-sized OLEDs.  At this year’s Crystal Valley Conference and Exposition (CVCE), which was held in Cheonan, Korea in September, Samsung showed a 10.1-inch Pentile LCD with 300 ppi.  The obvious application is a tablet, and the obvious competition is the “Retina” display in the new iPad, which has only 264 ppi, not really a “Retina” display by Apple’s own definition.</p>
<p>The advantage of Pentile technology for LCD is similar to the advantage it has for OLED.  By using a different sub-pixel arrangement and addressing the display in steps of one sub-pixel instead of whole pixels (done with on-the-fly re-coding), Pentile can generate a full-color pixel with only two sub-pixels instead of three.  That means that for any given pixel density, each sub-pixel can be 50% larger.  In the case of AMOLEDs, this reduces current density through the sub-pixel and extends life-time (or permits higher brightness at the same current density).  In the case of LCDs, it allows the TFT pixel switch to be larger.  In some cases that could allow a- TFTs to be used in high-pixel-density LCDs instead of the more expensive LTPS, or the as-yet-unproved (except by Sharp) oxide.</p>
<p>Samsung showed a 10.1-inch Pentile liquid-crystal display next to a traditional RGB 10.1-inch LC display.  The Pentile display had 2560×1600 pixels (300 ppi), 450 nits luminance, and 72% NTSC color gamut, and consumed 2.5W (max) @ 400 nits, with the BLU consuming 1.75W of that.</p>
<p>By contrast, the RGB stripe display had 1280×800 pixels (150 ppi), 400 nits, 50% NTSC, and consumed 3.2W @ 400 nits, of which 2.5W was consumed by the BLU.  That means the Pentile display consumed about 20% less power while delivering far greater resolution, which was clearly shown in a side-by-side demonstration featuring both images and print.</p>
<p>Prediction:  Expect a 10-inch-class Pentile LCD to appear in a Samsung Galaxy Tab, perhaps as soon as the first half of 2013.</p>
