          <p>This will be my last post for 2012. And what a year it’s been.</p>
<p>We were dazzled by 55-inch OLEDS at CES nearly a year ago that will not make it to market. We’ve seen record financial losses at some of the most venerated names in consumer electronics (Sony, Panasonic) and one long-time Japanese brand on the verge of bankruptcy (Sharp.)</p>
<p>TV sales continued their decline from last year, as did TV prices. It’s now possible to buy 42-inch LCD TVs for quite a bit less than $400. The obituary is being written for plasma, according to most analysts. (I agree.) Many LCD TV manufacturers and retail brands are now branching into (get this) LED lighting.</p>
<p>Viewing of traditional broadcast TV channels fell off the cliff this year, except at NBC. AMC is the hot channel now, and ironically,  they used to just run old movies with innumerable commercial interruptions. There is evidence that cord-cutting is gaining in popularity (it’s the economy, stupid!) and video streaming has supplanted sales and rentals of DVDs and Blu-ray discs. My gosh, Disney and Netflix are now partners in streaming!</p>
<p>The hot products this season aren’t TVs, although really big screens are dirt cheap and have seen a spike in sales. Digital cameras are threatened by smart phones, with 2012 shipments off by as much as 40% from last year. Now, we have DSLRs and point-and-shoots with built-in Web browsers, quickie image editors, and the Android OS. (I think that’s called a phone now?)</p>
<p>No, the hot product this year is the tablet. iPad, Surface, Nook, Galaxy, Kindle, take your pick – they’re all popular, and the Consumer Electronics Association predicts that 50% of American homes could own at least one tablet by the end of the holiday selling season.</p>
<p>Interest in 3D has largely waned among the general public and TV manufacturers, contrary to what you may read on some die-hard 3D enthusiast Web sites. From all accounts, the 3D Olympics broadcasts found their biggest audience in the production trucks adjacent to the events in London.</p>
<p>So what’s the next big thing? Why, it’s 4K, otherwise known as Ultra HD (except at Sony, who always marches to the beat of a different drum). Never mind that there’s no content to watch; you can buy in for a mealy twenty grand. Or, you can wait until after CES and pick up one of the new Chinese 4K TVs for a lot less.</p>
<p>Prices for flash memory are dirt cheap, further depressing optical disc sales. You can buy 32 GB SD and Micro SD cards for all of twenty bucks now. That’s enough space to hold almost six two-hour 1080p movies, using MPEG4 H.264 compression.</p>
<p>We’re seeing a major shift away from value in hardware to value in software – content, apps, whatever you want to call them. Face it; “electronics is cheap!” And more and more of our gadgets are coming from China, which is evolving into the largest market for consumer electronics in the world.</p>
<p>Front projectors came under heavy fire in the commercial AV space, threatened by super-cheap and big LCD TVs. But they’re firing back by adopting lamp-less projection engines, using LEDs, lasers, or combinations of the two. The rear-projection TV category is officially RIP now, after Mitsubishi threw in the towel in late November. If it ain’t flat, consumers don’t want it.</p>
<p>You know things are nutty when Samsung and Apple seem to spend most of their time in court suing each other (and Google, and vice-versa), yet all three companies paired up to make a $500M bid for Kodak’s digital imaging patents. You remember Kodak, right? They once made photographic film, and cameras, and processing chemicals, etc. (Don’t remember them? You must be a Millennial.)</p>
<p>The industry is obsessed with the “second screen,” although they can’t quite define how it is used and how often. We’re obsessed with the idea that we can stream any movie or TV show we want, at any time and in any place, but continue to be surprised when the monthly bill comes in from Verizon, AT&amp;T, Comcast, Time Warner, and so on. And why is it that broadband speeds are so much faster abroad, in countries where the government often maintains the telecommunications infrastructure?</p>
<p>Despite claims that more airwaves are needed for wireless broadband (at the expense of UHF TV broadcasters), we found out the hard way during Hurricane Sandy and other extreme weather that, more often than not, broadcast TV was the only reliable way to get news updates when the power went out, trees fell down, and buildings flooded. (Some lessons are just hard to learn!)</p>
<p>It’s been quite a year, and Ken and I have enjoyed trying to explain the significance of many of the developments that you’ve heard and read about. We’ll continue to do so in 2013 on an all-new Web site (same name) that should be somewhat easier on the eyes and faster to navigate.</p>
<p>Look for a launch of the new site sometime in mid-January, right after that annual exercise in electronic insanity that takes place in Las Vegas every year. Both Ken and I will have our usual coverage and analysis, and maybe we can even find a couple of gems amongst all of the electronic detritus that lines the aisles of the Las Vegas Convention Center.</p>
<p>That’s it for now. Have a safe and happy holiday season and a safe New Year. And in the wake of the Newtown, CT tragedy, remember to keep all the gadgets we lust after and “can’t live without” in perspective: It’s just a bunch of dumb wires and components when all is said and done.</p>
<p>There are more important things in life…</p>
