<p>And just how “awe-inspiring” will that experience be? The 4K movie offerings include the recent remake of <em>Total Recall</em>, a movie that was universally panned by critics (30% rating on the Rotten Tomatoes Web site) and didn’t even make back half of its production budget.</p>
<p>You’ll also receive Adam Sandler’s <em>That’s My Boy</em>!; another box office bomb that scored even lower among critics and made a brief appearance in theaters. Want more? How about <em>Battle: Los Angeles</em>, of which one RT critic said, <em>“…… this humorless film (is) as unimaginative — and as exhausting — as you can get.”</em></p>
<p>The 4K bundle also includes <em>Salt, The Karate Kid (2010), The Amazing Spider-Man, The Other Guys, Taxi Driver,</em> and <em>The Bridge on the River Kwai.</em> I enjoyed the first three Spider-Man movies, but skipped this year’s re-boot. The rest of the movies gathered decent reviews, but from my perspective, there are only two true classics on the list – <em>Taxi Driver</em> and <em>River Kwai</em>.</p>
<p>Sadly, they can’t even stock their media player with movies worthy of 4K transfers, like their recently-restored <em>Dr. Strangelove, </em>which looks gorgeous in 4K. (Hey Sony, how about offering some Academy Award nominees and winners instead, like <em>The Last Emperor, </em>or<em> A Few Good Men? Moneyball? The Social Network? </em>Remember those?)</p>
<p>Sharp is also practicing misdirection. Thursday’s business newswires were buzzing with rumors that Sharp is in talks to sell shares of the company to Dell, Intel, and Qualcomm to bolster its balance sheet in return for a stable supply of breakthrough display technology.</p>
<p><a href="http://online.wsj.com/article/SB10001424127887323751104578148220208818586.html" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://online.wsj.com']);">According to the Wall Street Journal,</a> Sharp wants an investment of about $240M from both Dell and Intel, and a smaller investment from Qualcomm. The prize? Sharp’s IGZO (indium-gallium-zinc oxide) backplane technology, which makes displays lighter and thinner, increases pixel density, and improves energy efficiency. Any deal these companies would make with Sharp would guarantee them a corresponding percentage of the Sakai IGZO panel output.</p>
<p>Sharp’s negotiations with Hon Hai stalled a few months ago, and the latter company sees no point rushing to close a deal while Sharp’s market valuation is falling off a cliff. Ironically, Hon Hai’s reluctance is a contributory factor in Sharp’s share price dropping to bargain-basement numbers – trading last Friday for about 172 yen, a decline from well over 2,000 yen in 2008.</p>
<p>According to the WSJ story, Sharp President Takashi Okuda was quoted as saying that <em>“Sharp is counting on IGZO to save the company.”</em> However, Sharp’s struggles with low IGZO production yields are well-known, and the company’s cash reserves are rapidly dwindling.</p>
<div id="attachment_2553" class="wp-caption aligncenter" style="width: 583px"><img class="size-full wp-image-2553" title="Sharp 4K PR Photo MR" src="http://www.hdtvexpert.com/wp-content/uploads/2012/12/Sharp-4K-PR-Photo-MR.jpg" alt="" width="573" height="355" /><p class="wp-caption-text">It’s 4K or bust for Sharp!</p></div>
<p>So what do you say to the press?  Pay no attention to that; look at this shiny new thing over here instead! Sharp’s “shiny new thing” is a 32-inch 4K (3840×2160) LCD monitor that will go on sale in February for ¥450,000 in Japan (about $5,500 in USD). It uses the IGZO backplane, weighs about 17 pounds, and will include a pair of HDMI connectors and internal speakers, <a href="http://www.pcworld.com/article/2017340/sharp-to-launch-worlds-thinnest-4k-monitor-for-about-5-500.html" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://www.pcworld.com']);">according to IDG’s News Service</a>.</p>
<p>Note that this is not a 4K TV; just a ‘dumb’ monitor. But its price per diagonal inch is far below that of the 84-inch 4K TVs announced by Sony, LG, and Toshiba. Unfortunately, the screen size is too small to be of much value to the consumer market, which is why the company stated that they expect more interest from computer graphics professionals, the medical industry, and architects.</p>
<p>Both 4K announcements show that while both companies may be losing their shirts, they haven’t lost their technical mojo. Now, the question is how long before analysts, investors, and the press refocus on the elephant in the room: Profitability. <em></em></p>
