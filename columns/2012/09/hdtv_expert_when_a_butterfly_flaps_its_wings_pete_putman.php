          <p>Two weeks ago, I wrote about the decline in television sales and how manufacturers are scratching their heads trying to figure out a way to kick-start consumer interest and get those cash registers jingling again, as the all-important 2012 holiday selling season is barely two months away.</p>
<p> </p>
<p>Misery loves company. Hollywood is in a similar pickle as declining sales of movies on optical disc and increasing use of streaming video-on-demand (SVOD) are challenging revenue projections, particularly for ‘weak’ theatrical releases that could previously count on back-end physical media sales to make up revenue.</p>
<p> </p>
<p>The steady decline in optical disc sales and rentals since 2005 has been well-documented by myself and other industry analysts, and has been tracked and confirmed by a number or research organizations. While it is true that Blu-ray disc sales continue to grow, they haven’t made up for the drop-off in DVD sales and rentals – and are unlikely ever to do so.</p>
<p> </p>
<p>What’s ‘hot’ these days is streaming and playback of movie and TV show files on portable devices. On a flight back from California last week, the passenger next to me enjoyed <em>Battleship</em> on an iPad, downloaded from iTunes. While making a trip to the restroom, I noticed at least ten other passengers watching video on tablets, e-readers, and even a smart phone.</p>
<p> </p>
<p>In contrast, just about every laptop I spotted appeared to be open to a word processor or spreadsheet program. I had my Toshiba laptop with me on the flight, along with a couple of Blu-ray movies, but the combination of a tight middle seat and a very large passenger to my right made using my laptop difficult, so I opted to read an eBook on my Nook Simple Touch instead.</p>
<p> </p>
<p>But I digress. <a href="http://www.homemediamagazine.com/paramount/viacom-ceo-declining-dvd-sales-have-altered-moviemaking-economics-28359" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://www.homemediamagazine.com']);">In a recent Home Media article</a>, Viacom CEO Philipe Dauman was quoted as saying that the continuing decline in optical disc sales has led Hollywood to change their economic model, forcing producers, directors, and actors to share in the risk of a movie and reap any rewards at the back end instead of getting a large upfront payment.</p>
<p> </p>
<p><em>“We don’t mind sharing the upside [of a movie with talent] as long as we don’t have a downside, or we have a sharing of that risk,”</em> said Dauman. <em>“Digital revenues are growing, but it’s not a perfect transference [with disc sales] at this point.”</em> As a result, Viacom is one of many content owners seeking to make up revenue by licensing programming to SVOD companies Netflix and Amazon Prime Instant Video.</p>
<p> </p>
<p>Some movies are produced exclusively for DVD and Blu-ray sales. This is a big part of Disney’s revenue stream, as they are the largest producer of packaged media. But Disney has already taken steps to move to a SVOD model, ramping up a digital delivery portal two years ago to transition away from physical media for its ‘direct to disc’ releases.</p>
<p> </p>
<p>The explosive growth of packaged media in the 1980s and 1990s – something Hollywood vigorously fought against at the start – turned out to be a very profitable business in the end, and strong sales on VHS and DVD after a theatrical run made it possible to ‘greenlight’ some movies that otherwise would have been major box office flops. (The <em>Austin Powers</em> series is a good example.)</p>
<p> </p>
<p>But the butterfly started flapping its wings about seven years ago with the first stirrings of streaming video (YouTube). That gentle breeze has now turned into a storm, with movies and TV shows watched across an almost bewildering variety of platforms.</p>
<p> </p>
<p>And that storm is impacting TV sales as well. With new e-readers from Amazon and the latest iPhone now coming to store shelves, buying a new TV or upgrading an older model isn’t at the top of nearly as many holiday shopping lists as it would have been two years ago.</p>
<p> </p>
<p>Even the digital video recorder – an integral part of the transition to digital TV a decade ago – is threatened by SVOD. <a href="http://adage.com/article/media/endangered-dvr-vod-make-obsolete/237206/" onclick="javascript:_gaq.push(['_trackEvent','outbound-article','http://adage.com']);">A recent Advertising Age article</a> points out that media companies and ad buyers are anticipating a day in the near future where demand for ‘anywhere, anytime’ playback will displace the ability to skip advertising.</p>
<p> </p>
<p>According to Alan Wurtzel of NBC Universal, <em>“Video on demand is going to play a major role in how people consume video going forward.”</em> Subscribers to  SVOD services can already watch recent episodes from major broadcast networks and a few pay TV channels ‘on demand’ on almost any device, but they give up the ability to skip advertisements.</p>
<p> </p>
<p>Not surprisingly; TiVo, the company that basically invented the DVR, is in the thick of this transition. The article quoted Tara Maitra, senior vice president for TiVo’s content and media sales and operations, as saying that consumers really don’t care how they access programming as long as it is on their own terms.</p>
<p> </p>
<p>What does all of this portend for the display industry? Simply that consumer demand, going forward, won’t be for big, cheap, and thin televisions stuffed with apps and other goodies. No; it will be for small, ‘go anywhere’ displays that offer higher resolution, brighter screens, improved viewing angles, and enhanced sound. And consumers will demand improved wireless access with higher broadband speeds to fully enjoy movies and TV shows, served up from ‘the cloud.’ (Can’t have a storm without clouds!)</p>
<p> </p>
<p>It all starts when a butterfly flaps its wings.</p>
