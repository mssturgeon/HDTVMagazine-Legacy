<div id="attachment_3636" style="width: 211px" class="wp-caption alignleft"><a href="http://www.hdtvexpert.com/januarys-tv-is-februarys-digital-sign/xdsc_5028_/" rel="attachment wp-att-3636"><img class="size-medium wp-image-3636" alt="Transparent LCD from LG-MRI in a commercial refrigerator door. (Photo:  Ken Werner)" src="http://www.hdtvexpert.com/wp-content/uploads/2014/03/xDSC_5028_-201x300.jpg" width="201" height="300" /></a><p class="wp-caption-text">Transparent LCD from LG-MRI in a commercial refrigerator door. (Photo: Ken Werner)</p></div>
<p>Although somebody has shown a transparent TV at CES in each of the last couple of years, it&#8217;s hard to see how the idea makes sense. The most interesting argument comes from Bobs Raikes (MEKO Ltd.), who notes that some people with a hypersensitivity to interior design issues are offended by the &#8220;black hole&#8221; on the wall when their TV set is turned off. If the set were transparent when turned off, the wall would show through and the whole lash-up would be more aesthetically pleasing. Give me a break, Bob!</p>
<p>But in the signage world, there are places where transparent displays make a great deal of sense: retail windows, retail display boxes, vending machines and kiosks, and commercial refrigerator doors for supermarkets. Several vendors were showing transparent displays at DSE, including LG-MRI (a marketing JV between LG and Atlanta-based MRI), VER, 4YouSee, and GDS. In general the transparent displays seemed more transparent where they were supposed to be transparent and significantly more saturated where they were supposed to be saturated.</p>
<p>There were also examples of custom-sized displays from LG-MRI, BSI, Tannas Electronic Displays, and others.</p>
<p>LG was showing its 100-inch HECTO &#8220;truly cinematic, ultra sort throw&#8221; laser display. It was a TV at CES but a sign at DSE. NEC showed a startling round display inside a round frame, which turned out to be a projected image.</p>
<p>In the consumer world, touch displays only make sense for small and medium-size displays. Nobody is going to walk across the room to use a touch interface on his large-screen TV set. But it makes a great deal of sense for many signs, where customers can be very close to large displays. Touch and multi-touch are already important in signage, but the vigorous movement toward increased interactivity also incorporates gesture, customer analytics (which Intel is pushing hard), virtual fitting rooms, and systems that respond (say by showing you an appropriate video) when you touch a product on a display shelf.</p>
<p>Horizontal table-top displays were being shown by several vendors, including Planar, D3, and Multi-Taction. Multi-Taction&#8217;s table presented a digital version of air hockey.</p>
<p>E Ink was pushing hard to demonstrate the benefits of both passive and active-matrix electrophoretic technology for small and large signs. E Ink has established an alliance with sign company GDS to move the technology for ward more rapidly.</p>
<p>The display panel is only a part of any signage solution. A new wrinkle in distributing content to the signs in your network is to get it from the cloud.</p>
<p>DSE has been names as one of the 50 fastest-growing trade shows in the country. This year, there were just over 4000 verified attendees, plus 1813 exhibitors personnel for a total attendance of over 5800. There were a few more than 200 exhibiting companies, which occupied just over 70,000 net square feet. That&#8217;s 13% more than 2013, said the organizers. For next year, the show has reserved 6,000 square feet more than that. The dismal weather in the mid-west and northeast kept some registrants away from the show. Next year DSE will be in early March instead of early February, which should help unless our seemingly endless winter becomes truly endless.</p>
