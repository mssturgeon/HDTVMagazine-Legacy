				<p>For readers who aren’t up to speed, Aereo is a new service that receives terrestrial digital TV broadcasts in major markets and re-transmits them over the Internet, using AVC coding with IP headers. The concept is to provide local reception for those who can’t pick up these signals for one reason or another on their regular TV.</p>
<p>Now, the devil in the details: Ever since Aereo launched a couple of years ago, it has been in court, fighting off challenges by the major broadcast networks who are crying “foul!” and saying that Aereo’s retransmission is a violation of copyright laws. They also claim that Aereo owes them retransmission fees.</p>
<p>Aereo’s rebuttal and defense centers around a flimsy (to me) technical argument: Each subscriber gains access to an individual antenna about the size of a dime, which then is connected to an individual receiver, decoder, DVR, and encoder. It’s as if the subscriber built his or her own TV antenna system, which is certainly within their rights.</p>
<p>I remain skeptical because the cost of actually setting up thousands of individual antennas, terrestrial receivers, video decoders, and video encoders would be prohibitively expensive and never be recovered by the $8 monthly subscriber fee (for 20 hours of recording time, $12 for 40 hours).</p>
<p>And anyone who has ever taken a modicum of courses in electrical physics and RF theory knows that (a) the tiny antennas Aereo assigns to each subscriber can’t possibly have enough gain to work for high band VHF reception, let along UHF reception, and (b) the close spacing of those antennas – as seen from earlier PR photos released by the service – means they interact with each other to form a larger array, based on the principles of inductive and capacitive coupling. That, in essence, is a master antenna TV system – delivering TV channels to many viewers, not one.</p>
<p>Thanks to a sub-par presentation by expert witnesses called by broadcasters at the first hearing, the 2<sup>nd</sup> Circuit Court (New York City) ruled 2-1 that Aereo didn’t infringe on copyrights and cited the earlier Cablevision “cloud” DVR decision as precedent. Aereo’s right to operate was subsequently upheld in the 1<sup>st</sup> Circuit (Boston). Service is active in both cities now.</p>
<p>However; two weeks ago, Aereo was rebuffed by a 10<sup>th</sup> Circuit judge in Salt Lake City, who unequivocally stated that <i>“The plain language of the 1976 Copyright Act supports the plaintiffs’ position. Aereo’s retransmission of plaintiffs’ copyrighted programs is indistinguishable from a cable company.” </i>As a result, Aereo had to shut down its service in Salt Lake City and Denver for the time being.</p>
<p>While this case winds its way on to the Supreme Court, another twist in the story has surfaced. Apparently subscribers in New York City had massive problems with the Aereo stream of the Oscars telecast on WABC-TV a week ago Sunday. Consequently, the company’s Twitter feed was lit up with complaints about “buffering” and “locked-up pictures.”</p>
<p>Here are some of the dozens of tweets I found: <i>“Awful service, bad image quality &amp; not recording scheduled shows but it sad you treat ORIGINAL customers the way you do.”</i> <i>“It goes out now and then requiring me to select Oscars all over again. Common? I have it on auto quality.” </i> <i>“Thanks for doing work on the site tonight. It&#8217;s not like I wanted to watch the Oscars. No big deal.”</i> (Gotta LOVE that sarcasm!)</p>
<p>And more: <i>“C&#8217;mon Aereo. Get your s&#8211;t together.”</i> <i>“Anyone else watching the Oscars using Aereo like me? S&#8211;t keeps buffering every 30 seconds. Frustrating the hell out of me.”</i> <i>“Hmm is Aereo down for anyone else? Is it just an East Village or Roku thing? #CordCutting fail during the Oscars”</i> <i>“@Aereo Support I keep getting the message </i>&#8220;The Oscars has ended.&#8221;<i> A total of 8 seconds recorded. Worst. Oscars. Ever.”</i></p>
<p>This one was my personal favorite: <i>“@Aereo I don&#8217;t have time to run to Best Buy and buy some rabbit ears right now.”</i> Well, maybe that would have been the best thing to do.</p>
<p>A couple of observations are in order. First, I don’t know how exactly Aereo has its front end configured, but if they’ve actually tried to keep every single subscriber’s hardware separate by various technical tricks to pass legal review, then they might have run out of server capacity and brought this service failure on themselves. (Apparently this also happened during the Golden Globes, <a href="http://techcrunch.com/2014/01/12/aereo-apologizes-to-customers-affected-by-service-outage-during-golden-globes/">according to a story on the Quartz Web site</a>.)</p>
<p>There <span style="text-decoration: underline;">is</span> a reason why cable and satellite companies use a single receiver for each broadcast and premium channel they carry, and multiplex (copy and repeat) those channels on their outgoing RF and IP channels: It’s WAY more cost-effective and less troublesome! So they have to pay a retransmission fee: Big deal! What will the cost be now to Aereo in dropped subscriptions, not to mention bad publicity from these service problems?</p>
<p>Second, I’ll bet that more than a few Aereo subscribers could actually pick up the HD broadcasts from New York City stations if they tried. Over the years, I’ve tested numerous indoor TV antennas and there have been some real winners out there like the Mohu Leaf Ultimate series and Winegard’s amplified FlatWave antenna.</p>
<p>Both are reasonably priced and perform adequately on VHF channels and very well on UHF channels, which in New York City means you can also use them to watch WNBC, WCBS, and WNYW among the major networks. (By the way, those are the three networks that carry NFL games in the New York City metro area.)</p>
<p>Third; if you can pick up local TV broadcasts with one of the aforementioned antennas, there are terrestrial DVR products that will let you record those channels, like Channel Master’s new DVR+. It has dual tuners, built-in capacity for about 2 hours of HD recording (expandable with any external hard drives or solid state drives through USB ports), plus Wi-Fi connectivity and support for Internet video services like Vudu.</p>
<p>Or you can pick up one of Hauppauge’s WinTV receivers that plug directly into a USB port on your computer and provide terrestrial digital TV reception, letting you use your hard drive as a DVR. I carry around a few of the Hauppauge Aero-M stick receivers and a Mohu Leaf for reception on the road, and they work great.</p>
<p>We’ll never know the actual reason for Aereo’s system failures during the Golden Globes and Oscars, but it’s entirely possible that the company was too clever for its own good by engineering and building a system that was designed to neatly parse and side-step copyright laws.</p>
<p>It’s funny how the law of unintended consequences works, isn’t it?</p>
