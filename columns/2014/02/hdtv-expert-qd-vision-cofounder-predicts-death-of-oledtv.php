<p>Argument 1: OLED has response spead 1000 times that of LCD.<br />
Coe-Sullivan&#8217;s counter-argument: The combinatin of faster-switchng LC materials, new LC modes, and thinner cell gaps give LCDs speeds up o 240Hz. The factors limiting speed is jitter and other optical effects, not LC response. &#8220;OLEDs offer no benefit in response speed over LCDs.&#8221;</p>
<div id="attachment_3620" style="width: 281px" class="wp-caption alignleft"><a href="http://www.hdtvexpert.com/?attachment_id=3620" rel="attachment wp-att-3620"><img class="size-medium wp-image-3620" alt="Seth Coe-Sullivan, co-founder and CTO of QD Vision, created a stir by predicting the demise of OLED-TV.  (Photo:  Ken Werner) " src="http://www.hdtvexpert.com/wp-content/uploads/2014/02/DSC_4919-Coe-Sullivan-271x300.jpg" width="271" height="300" /></a><p class="wp-caption-text">Seth Coe-Sullivan, co-founder and CTO of QD Vision, created a stir by predicting the demise of OLED-TV. (Photo: Ken Werner)</p></div>
<p>Argument 2: OLED has twice the viewing angle of LCD.<br />
Counter-argument: The combination of new LC modes, thinner LC cell gaps, and new optical control films gives LCD-TVs viewing angles that are &#8220;good enough.&#8221; OLEDs offer little practical viewing angle benefit over LCDs.</p>
<p>Argument 3: OLEDs will have a thickness 1/25 that of LCDs.<br />
Counter-argument: The LED-BLU edge-lit designs that became established in 2008/2009 result in OLEDs offering only a minimal thinness benefit over LCD TVs.</p>
<p>Argument 4: OLEDs will offer a 10x power efficiency increase.<br />
Counter-argument: The combination of LED BLUs, light-control films, and that fact that OLEDs have not delivered the promised power savings, has resulted in OLED-TVs consuming more power than LCDs when displaying a white screen, and the situation is worse for higher resolutions and larger screens. In short, it is LCDs that have a significant power efficiency advantage over OLEDs &#8212; not the other way around.</p>
<p>Argument 5: OLEDs will offer a bill of materials (BoM) cost one half that of LCDs.<br />
Counter-argument: The combination of reductions in the cost of LED BLUs, incremental improvements in LCDs,<br />
and the persistance of low volumes in OLED manufacturing have resulted in OLED&#8217;s BoM being no less or greater than that of LCDs. And that is before the significantly lower yield of OLEDs compared to LCDs is taken into account.</p>
<p>Argument 6: New OLED manufacturing processes will further reduce costs.<br />
Counter-argument: Fine metal masks waste material and generate dust. The anticipated new low-cost processes &#8212; such as ink-jet printing, laser transfer, nozzle jet, and OVJP &#8212; are harder than we thought, and roll-to-roll isn’t amenable to high-resolution displays. In short, &#8220;OLED manufacturing is a yield and cost negative compared to mature LCD fabs.&#8221;</p>
<p>Argument 7: New OLED display modes will further increase the attractiveness and utility of displays.<br />
Counter-argument: Since this argument was first put forth, LCD technology has demonstrated transparent and curved displays. If these new display modes ever get past the gimmick phase, they are equally possible with<br />
LCDs.</p>
<p>Argument 8: OLED color gamut can be 50% greater than LCD.<br />
Counter-argument: Quantum-dot enhancement of LED backlights can produce a better color gamut than OLED-TVs.</p>
<p>The only argument for OLED-TVs that Coe-Sullivan acknowledged is their much greater contrast (in a dark room).</p>
<p>One of OLED’s problems is cost, which has kept market penetration low. Although not widely recognized by the general public, quantum dots appeared in major products in 2013: three models of Sony television (in the U.S.), which use QD Vision’s Color IQ rail, and, one of Amazon’s new Kindle Fire HDX models, which uses 3M’s quantum dot enhancement film (QDEF). Coe-Sullivan, 3M’s Erik Jostes, and Touch Display Research’s Jennifer Colegrove all predicted a rapid growth in design wins for quantum dots in 2014, with increasingly rapid growth coming in 2015 and following years.</p>
<p>That doesn&#8217;t mean that any of the other speakers at the conference &#8212; including 3M’s Jostes &#8212; echoed Coe-Sullivan’s position that OLED was fated for early extinction. The consensus is for a slow but steady increase in OLED-TV penetration. Market Intelligence company IHS has predicted a 3.9% penetration in panels for OLED-TV in 2018.</p>
