<p>But that’s not the real story. Our cable and Internet service come from Comcast, and it was dead as a doornail when we arose Wednesday morning. Verizon’s mobile phone service wasn’t much better; it could pass calls and texts, but data wouldn’t move, nor could I load any Web pages.</p>
<p>As many readers know, I’m a big proponent of terrestrial digital TV. So my home system has three different TV antennas – one on a rotator atop the roof, one below it that is aimed permanently at Philadelphia, and one in my attic, also aimed at Phily. It’s a nice complement to our cable service, especially if I want to watch TV stations from New York City (about 65 miles away).</p>
<p>Thanks to those rigs, we were able to get uninterrupted TV service and catch up on the latest weather, traffic conditions, and power outage updates. All I had to do was switch over to the RF inputs on each TV, and I was in business. And apparently, I was the only one of my neighbors in this subdivision able to do so. (And I could keep using my TiVo HD DVR, as it also has a terrestrial DTV tuner.)</p>
<p>So – here we are on a beautiful but chilly Saturday morning with no Internet, no cable, and no VoIP telephone service. I can’t get any emails or data through my mobile phone. But I can watch as much TV as I want, on as many channels as I want (about 55 minor channels here in the metro Philly market).</p>
<p>Why is this important? The FCC has been planning a spectrum auction for some time to free up more UHF TV channels for mobile phone and Internet service. This auction, the rules of which are still being developed and vetted, will rely on broadcasters “willingly” giving up channels in exchange for cash, presumably to be paid by the likes of Verizon, AT&amp;T, T-Mobile, and Sprint.</p>
<p>But there are some flies in the ointment. So far, there hasn’t been much of a positive response to the idea from broadcasters, the majority of whom seem content to hang onto their licenses – licenses that they paid plenty of cash to get in the first place, in case you didn’t know.</p>
<p>The CTIA (aka The Wireless Association) and other broadband advocacy groups like to talk about how broadcasters got their spectrum “for free.” Hogwash. They had to pay millions of dollars for licenses, construction permits, and related costs to light up transmitters and keep them on the air 24/7.  <a href="http://www.nab.org/documents/newsRoom/pdfs/011614_Navigant_spectrum_study.pdf">A recent analysis by analyst Jeffery Eisenach of Navigant Economics</a> illustrated in detail that broadcasters had to pay their way &#8211; and plenty &#8211; to use the airwaves, just like anyone else.</p>
<p>In the meantime, Verizon and AT&amp;T are sitting on chunks of unused spectrum that they’ve had for several years. Numerous studies over the past three years have illustrated that there is no “wireless broadband crisis,” as former FCC chairman Julius Genachowski insisted. (There have been plenty of new ideas for more efficient ways to use exiting wireless spectrum, though.) And locally, we’ve found out several times in the past two years that cellular networks are notoriously unreliable when there is a natural disaster, as they are easily overwhelmed with traffic.</p>
<p>Meanwhile, the terrestrial “one serving many” digital TV broadcast model continues to chug along reliably, providing timely news and weather updates and helping us feel like we’re not cut off from the rest of the world. Yes, I do miss my Internet connection, and shudder to think about how many emails I’ll have to plow through when it comes back.</p>
<p>But I don’t miss the telemarketing calls. And I’ve gained a new appreciation for just how dogged (and perhaps crazy) local reporters are from Philly TV stations KYW, WCAU, WPVI, and WTXF as they drive through dark neighborhoods, sliding on ice and dodging downed power lines to keep us updated on the progress of PECO crews. And what’s happening on the local roads . And which sections of which towns are still dark. And what to expect from the next storm system heading our way. (No, not more snow!)</p>
<p>When all else fails…</p>
