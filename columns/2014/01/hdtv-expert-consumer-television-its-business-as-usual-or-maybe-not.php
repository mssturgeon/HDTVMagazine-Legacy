				<p>The official numbers haven’t been released yet, but <a href="http://www.koreaherald.com/view.php?ud=20140122000524">a report in The Korea Herald, dated January 22</a> says that the final data will show Samsung dominated the global television business in 2013.</p>
<p>According to the story, Samsung was estimated to have sold 49 million units of flat-panel TVs last year. DisplaySearch had the totals at 32 million from January through September (the final DisplaySearch numbers for 2013 haven’t been compiled yet) and Yoon Boo-keun, Samsung’s consumer electronics division chief, stated at CES earlier this month that the company sold around 15 million TVs in Q4.</p>
<p>That’s an impressive number by anyone’s standards and reflects the complete dominance Samsung has in the television business. Think back 20 years to when Samsung was an afterthought; perceived as a 3<sup>rd</sup>-tier “bargain” brand for electronics.</p>
<p>Now, they’re on top of the heap, and have been so for eight consecutive years. In the meantime, LG looks to maintain its grip on 2<sup>nd</sup> place, with a varying market share number in the low to mid-teens throughout 2013. Between the two companies, they control over 40% of the worldwide television business.</p>
<p>The Japanese, on the other hand, will no doubt be disappointed by the final numbers for ’13. In the third quarter; Sony, Panasonic, and Sharp were hovering around 8%, 6%, and 5% market share respectively – and those numbers are expected to drop when the final tally comes in.</p>
<p>As I noted in my last DD, Panasonic seems to be charting a course away from televisions, based on what they didn’t show at CES (a full line-up of 2014 models) and their emphasis on commercial sales of everything from cameras and storage devices to digital signs and batteries. And of course, Panasonic pulled the plug on plasma panel and TV manufacturing at the end of December.</p>
<p>The other remaining player in televisions – Toshiba – took a similar approach to their CES booth, choosing to show a wide variety of 4K (Ultra HD) display applications for home and office and skipping the TV line-up. Toshiba has already shut down two manufacturing plants and laid off over 3,000 employees because of continued losses in television and computer manufacturing.</p>
<p>That leaves Sony and Sharp. The former continues to stay the course in sales and marketing of consumer TVs, but I’d be surprised if they don’t turn in yet another year of red ink – the ninth in a row. Sharp, meanwhile, has chosen to emphasize their super-sized lineup of TVs, plus clever engineering tricks like the Quattron+ line and their ability to manufacture IGZO TFTs with decent yields.</p>
<p>The problem for both companies is their uninterrupted slide in television market share that has been going on for eight years. With a 5% share worldwide and 3% in the United States as of Q3 2013, Sharp can’t afford to stay in this game for much longer. Neither can Sony, if they are serious about returning a profit to shareholders.</p>
<p>It doesn’t help matters that television sales are expected to have declined worldwide by 2.2% from 2012 when the accountants are done. The double-digit boom in TV sales in China kept that number from being a lot worse.</p>
<p>Amid the flurry of post-CES news stories about curved, super-sized UHDTVs was another item that went almost unnoticed, except for the sharp eyes of analyst Paul Gagnon of NPD DisplaySearch. <a href="http://www.displaysearchblog.com/2014/01/lge-discounting-oled-tv-before-rolling-out-new-products">In his blog post of January 17</a>, Gagnon revealed how three retailers in the United Kingdom are already selling LG’s “first to market” 55-inch curved OLED TV for just £3,000 ($4,910).</p>
<p>This product, which launched on these shores in July of 2013 for nearly $15,000, was quickly discounted when Samsung rolled out their curved 55-inch model for about $9,000 one month later. And now, the LG model is selling for almost half that, just seven months down the road, a breathtaking price drop of 67%. (Perhaps they underestimated demand?)</p>
<p>And the cannibalizing of TV prices continues unabated. On the last day of CES, Vizio announced its prices for a line of full-array LED 4K (UHDTV) “smart” LCD models – and they aren’t much higher than conventional LED “smart” TVs from LG and Samsung.</p>
<p>Case in point: The 50-inch P502ui-B1 will retail for $1,000, while the 55-inch version will have a sticker price of $1,400. The P602ui-B3 is set at $1,800, and the 65-inch model will command $2,199. Finally, a 70-inch skew (P702ui-B3) will be offered at $2,600. Consider that Samsung and Sony are trying to peddle 55-inch 4K LCD smart TVs for about $2,900 right now and you can clearly see the train wreck coming.</p>
<p>Summing up: Samsung dominates the consumer television world – business as usual. Panasonic and Toshiba de-emphasize TVs at CES – maybe not. Sony and Sharp keep pouring money into consumer television manufacturing and marketing, even though they are incurring substantial losses – business as usual. LG and Vizio slashing prices on OLEDs and 4K TVs – definitely not!</p>
