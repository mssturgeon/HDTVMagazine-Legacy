<p>But the real point of this story is what happened next. Joe Stinziano, Executve VP of Samsung Electronics America, who was hosting the segment that included Bay, gracefully fielded the hot grounder hit to his corner. With complete professionalism, he quickly got the event back on track and continued delivering Samsung&#8217;s TV-related message. And that message was, &#8220;UHD will drive the next change in the television industry.&#8221;</p>
