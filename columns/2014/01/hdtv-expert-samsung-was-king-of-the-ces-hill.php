<p>Unlike Bay, Mark Cuban performed as intended during his celebrity walk-on by amplifying the message: &#8220;UHD is incredible. It will help turn the TV into a unique multimedia platform.&#8221;</p>
<div id="attachment_3598" style="width: 290px" class="wp-caption alignleft"><a href="http://www.hdtvexpert.com/?attachment_id=3598" rel="attachment wp-att-3598"><img class=" wp-image-3598  " alt="Joe Stinziano, man of the hour at Samsung's press event. (Photo: Ken Werner)" src="http://www.hdtvexpert.com/wp-content/uploads/2014/01/DSC_4227.jpg" width="280" height="286" /></a><p class="wp-caption-text">Joe Stinziano, man of the hour at Samsung&#8217;s press event. (Photo: Ken Werner)</p></div>
<p>The Bay espisode may have been embarrassing for Bay, but not really for Samsung. They hunkered down and got the job done, which is what they almost always do. They lead the world in TV sales, LCD panel sales, and smart phone sales. They popularized the phablet, a category that the allegedly creative Apple completely missed, and they kept their noses to the grindstone when small and medium OLED displays were an embarrassing failure and then made them a huge success.</p>
<p>Stinziano said Samsung is leader in UHD-TV, and that the company expects to sell 60 million UHD sets in 2017. &#8220;UHD,&#8221; he said, &#8220;will drive TV growth for Samsung.&#8221; Samsung&#8217;s UHD sets for 2014 will have screen sizes ranging from 50 to 110 inches, will feature a technology call PurColor that extends color gamut and purity (but was not described in more detail than that), and will embody UHD upscaling that provides near-native-4K image quality. The sets will accommodate Samsung&#8217;s &#8220;Evolution Kit,&#8221; which will allow UHD sets to receive electronic and firmware upgrades without replacing the set.</p>
<p>Although high-quality upscaling really is good enough to provide enjoyable UHD viewing without native 4K media, Samsung isn&#8217;t stopping there. Some native-4K movies will be pre-loaded in their UHD sets, and a 4K streaming service is being developed with Amazon. The sets also contain a faster quad-core processor.</p>
<p>Since Samsung does not have a dedicated game platform, as does another leading consumer electronics company whose name also begins with S, Samsung is including the intelligence so the TV set can serve as a sophisticated game platform.</p>
<p>At the Technicolor Press Breakfast two days later, Samsung and M-Go announced it is an M-Go core embedded in the Samsung chip that will deliver 4K native and up-scaled content. The Samsung sets will presumably earn Technicolor certification. At the press breakfast, M-Go and Technicolor provided a side-by-side demonstration of up-converted vs. native-4K video. Experienced viewers were largely unable to tell the difference between the two at distances much less than typical living-room viewing distances. John Batter of M-Go noted that native-4K programming requires a bandwidth of 15Mb/sec, while upscaled programming optimized for streaming requires as little as 3Mb/sec. Streaming service providers will have some interesting choices to make as time goes on.</p>
<p>At the press event, Samsung described its new 105-inch as &#8220;the world&#8217;s largest curved UHD TV&#8221; and also showed &#8220;the world&#8217;s first curved UHD TV.&#8221; Of course, LG Display also showed &#8220;The World&#8217;s First 105 inch Ultra HD Curved TV,&#8221; which had an aspect ratio of 21:9. For now, let&#8217;s agree that both of these Korean competitors make very impressive large curved UHD displays.</p>
<div id="attachment_3599" style="width: 610px" class="wp-caption aligncenter"><a href="http://www.hdtvexpert.com/?attachment_id=3599" rel="attachment wp-att-3599"><img class="size-full wp-image-3599" alt="Samsung's curved 105-inch display at CES. (Photo: Ken Werner)" src="http://www.hdtvexpert.com/wp-content/uploads/2014/01/xDSC_4613_.jpg" width="600" height="402" /></a><p class="wp-caption-text">Samsung&#8217;s curved 105-inch display at CES. (Photo: Ken Werner)</p></div>
<p>The claim made by both Samsung and LG that 55- and 65-inch TVs with screens having a radius of curvature in the vicinity of 15 feet provide &#8220;a more immersive experience&#8221; for viewers is not supported either by geometry or personal experience. However, when the screen has a 105-inch diagonal and a 21:9 aspect ratio, the claim for curvature offering a more immersive viewing experience has more credibility. Samsung also increased the &#8220;immersiveness&#8221; of moderately sized curved displays by tiling a bunch of them side to side. The result was impressive, and this approach should have significant appeal for digital signage.</p>
<div id="attachment_3600" style="width: 610px" class="wp-caption aligncenter"><a href="http://www.hdtvexpert.com/?attachment_id=3600" rel="attachment wp-att-3600"><img class="size-full wp-image-3600" alt="xDSC_4476_" src="http://www.hdtvexpert.com/wp-content/uploads/2014/01/xDSC_4476_.jpg" width="600" height="402" /></a><p class="wp-caption-text">Tiling moderately sized, curved displays side by side can provide an impressive experience for digital signage. (Photo: Ken Werner)</p></div>
<p style="text-align: left;">Both at the press event and in its large booth on the show floor, Samsung showed a moderately sized OLED display that could be bent from flat to gently curved by small motors whirring away inside the case. Since I&#8217;m not convinced that moderately sized curved displays make any sense, I&#8217;m even less convinced that it makes sense to bend such a display from flat to curved and back again. But the gadget drew lots of attention, and that was probably its main function. Besides, we all need an extra button on our remote controls.</p>
<div id="attachment_3601" style="width: 610px" class="wp-caption aligncenter"><a href="http://www.hdtvexpert.com/?attachment_id=3601" rel="attachment wp-att-3601"><img class="size-full wp-image-3601" alt="Samsung's bendable TV with the corner pushed out into the screen's curved configuration. (Photo: Ken Werner)" src="http://www.hdtvexpert.com/wp-content/uploads/2014/01/xDSC_4594_.jpg" width="600" height="366" /></a><p class="wp-caption-text">Samsung&#8217;s bendable TV with the corner pushed out into the screen&#8217;s curved configuration. (Photo: Ken Werner)</p></div>
<p>Market share produces industry influence, along with resources for R&amp;D, product design, marketing, elaborate exhibits at CES, and huge press events. Samsung has that, and has made the most of it with steady, professional management; talented engineering; good product management; and the patience to allow long-term projects to come to fruition. And they can also indulge in the whimsy of whirring motors bending OLED displays. Samsung is truly king of the TV hill, which doesn&#8217;t mean that aggressive competitors aren&#8217;t trying their best to scramble up it.</p>
