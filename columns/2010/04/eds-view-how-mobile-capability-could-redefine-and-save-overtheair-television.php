<p>Arguably, 3D HD was the "star" of CES 2010 and is the primary focus of the television business starting now.  And rightfully so, as 3D will be a welcome incrementally profitable business as HD approaches market maturity.  However, the same cannot be said for broadcasters as they gather in Las Vegas this month for NAB (National Association of Broadcasters) Convention 2010.  To OTA broadcasters, whose very lifeblood – their spectrum – is under assault, the issue is survival.  And that survival may very well depend on their successful embrace of the new ATSC Mobile/Handheld (M/H) standard.  So, in spite of its glitter, 3D may very well take a second seat to M/H at NAB 2010.</p>

<p>To some extent M/H is a solution waiting for a problem.  It is not clear there is any driving conventional need for linear mobile television and/or non-internet data services, at least in the US, or any that would appear to be economically viable.  However, here are some factors, both commercial and technical, that could allow broadcasters to successfully leverage their spectrum to turn M/H into a win-win proposition or to secure survival itself:</p>

<h2>ATSC does not work in a mobile environment.</h2>

<p>That fact has always been the "dirty little secret" of ATSC DTV.  In a fast changing signal reception environment, with large varying signal levels and complex multipath reflections, conventional ATSC tuners cannot reacquire data quickly enough to successfully overcome errors and generate continuous video frames.  In short, in these conditions reception fails; the receiver produces either distorted frames with intermittent audio and/or no A/V at all.  M/H essentially fixes these problems with a robust transport protocol including additional error correction coding and training sequences.  The result is reliable reception in very harsh signal environments.  Even analog (NTSC) TV was not successful as a mobile/portable medium because of the deleterious effects of multipath.  So, essentially, M/H effectively opens up an entirely new market for OTA television.</p>

<h2>Portable Audio is a key asset</h2>

<p>The loss of audio reception capability was a major DTV transition disappointment in those markets with a channel 6 analog license.  Most FM radios could receive the channel six 87.75Mhz FM aural carrier allowing listeners to enjoy the audio content of the programming.  Marketing statistics were not objectively collected related to this channel 6 audio-only impact in those areas, but indications are listener numbers were not insignificant.</p>

<p>With TV display capability now becoming ubiquitous in most new cars, the addition of an ATSC M/H chip set will undoubtedly become commonplace.  Even though the front seat "video" will be disabled for safety reasons when the vehicle is in motion, the audio will remain a key attraction.  This factor in addition to the availability of inexpensive audio-only M/H receivers will become a key market multiplier.</p>

<h2>M/H capability will be in every new television receiver.</h2>

<p>The comparatively low incremental cost of adding M/H functionality to DTV receivers coupled with the HD up-scaling capability of today's display systems will virtually assure M/H reception as a feature in all new television receivers.  In addition, low cost M/H accessory boxes will be available for legacy TV's.</p>

<h2>M/H capability will be in every "smart" mobile device.</h2>

<p>No doubt the second and third generation of M/H chip sets will be found as a standard feature in all "smart" phones and "pad" devices.  Because of the unique public security implications of reliable, ubiquitous broadcast video, M/H may indeed become a government mandated feature in all such devices.</p>

<h2>"Localization" will permit diverse audiences.</h2>

<p>Because of the large number of M/H channels available in any medium-to-large metropolitan area, the opportunity exists for a high degree of local content such as "hyper" news, school and community programming. </p>

<h2>Receiver storage capability will allow inclusion of a DVR feature.</h2>

<p>The continually dropping costs of storage and M/H tuners will enable "smart" DVR features in M/H receivers, most of which will have some recording capability.  This feature will greatly expand the utilitarian value of M/H receivers when short trips interrupt viewing longer form programming.</p>

<h2>Return channel capability will permit precise viewer statistics to rate advertising value.</h2>

<p>The M/H standard does allow for optional return data functionality using existing networks.  This capability will not only permit a rich potential of applications but also will enable a more precise measurement of viewer activity for advertising rating purposes.  Such back channel capability also permits logical demarcation functionality for subscription based services thus allowing for additional revenue.</p>

<h2>It's easy to do.</h2>

<p>To most broadcasters, adding M/H capability will be comparatively easy.  Installing M/H is nothing like the financial and technical stress and strain that accompanied the digital transition itself.  And the capability can be easily scaled and expanded as experience and budgets permit. For approximately $100K stations can get on the air with virtually "plug and play" installation.  As the service is "tweaked" and more M/H channels are added as the market builds, budgets can be more easily managed as there are no deadlines except those driven by competition.</p>

<p>As a complement to the ease of M/H facilitation by broadcasters, the receiver costs will be comparatively inexpensive both for stand-alone devices or M/H added capability.  This means a fast ramp-up of potential viewers.  The tough task will be on the content creative end – i.e. making the M/H service compelling.  That may not so easy to do, but it will be done.  It will be exciting to watch M/H develop.  Man can do some very creative things when survival is at stake.</p>

<p>So what does all this mean for OTA HD?  In the final analysis, OTA HD may not survive the trip.  M/H is not bandwidth free; something will have to give somewhat to accommodate it.  In the short term, more efficient MPEG 2 encoders will permit HD to be squeezed somewhat (about 20%) without sacrificing quality.  But if M/H is commercially successful, HD will be gradually shifted away from OTA to other services that can more efficiently handle HD bandwidth demands.  This may not be all that bad.  Some program and commercial producers who have spend bunches of money on HD origination are beginning to question the quality of some HD delivery systems and are starting to press for better HD quality control. </p>

<p>In the meantime, welcome the new M/H service.  After all, it was the digital solution to HD that made it possible, and it may indeed assure the continuation of free OTA TV if not the broadcasters themselves.</p>

<p>Ed</p>
