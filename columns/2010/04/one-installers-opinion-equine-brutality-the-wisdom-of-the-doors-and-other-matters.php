<p>Look, I hate to beat a dead horse, ...well, maybe occasionally I ... O.K., O.K., I love to milk a topic that deserves it, and this horse ain't runnin' off into the sunset anytime soon. Yup, I'm talking about the NEW stallion on the block, 3D. While most periodicals are still gushing "2010 is the year of 3D", I'm more convinced than ever that it won't be. Clearly, the hype will be excruciatingly loud and constant for the remainder of the year, but the substance will remain elusive.</p>

<p>Here's the thing.</p>

<p>First of all, there is the simple issue of the calendar. By the time you read this, it will be Q2. Most manufacturers at January's CES (Consumer Electronics Show) weren't promising "real" 3D products until sometime in Q3. Run that through the not-so-secret marketing decoder and it comes out "Late Q4", at best. Now add another quarter for Early Adopters to place their bets (and open their wallets) and yet another quarter to gather the sales data and spin it into positive press releases and we're mid-2011 before we know if this next-new-thing has any real traction at all.</p>

<p>Regardless of the REAL inaugural year, and on the very outside chance ...  :-)  ... you missed last month's column, here is a brief rundown of the roots of my skepticism.</p>

<p>1. Consumer Acceptance. Just not sure that 3D can shed its historical "Gimmicky" image acquired in the '50s and beyond (regardless of the obvious advances in the current technology), especially in a down economy and just after discretionary budgets have been drained by HDTVs and BD players.</p>

<p>2. Different Usage Model. Watching 3D in a commercial theater will be one thing, but watching it in your living room will be quite another. Number of guests vs. glasses, kid abuse, hungry dogs, dead batteries and synchronization problems will likely conspire against having a memorable (in a good way) 3D movie experience at the Johnson's on Saturday night.</p>

<p>3. Dubious Motivation. It's no secret that the predictable ramp-up in volume leading to ramp down in cost leading to near invisible margins have run their course with HDTVs and Blu-Ray players. "3D hype" is an all too convenient vehicle to attempt to restore profitability to a huge industry's hemorrhaging bottom line. If it catches on of its own volition, I'll be thankful - I have a large dog in this fight. Right now, I'm just suspect.</p>

<p>4. Too Big A Tent - Too Few Indians. Regardless of the truth (or not) of #1 above, some 50%+ of the CE buying public, while willing to pop for the $99 BD player or maybe even the $399 LCD screen at Wal-Mart, will NEVER invest in all that is required to make 3D a reality in their living room. Now subtract another 10% who, though they could afford it, will, under NO circumstances be caught dead in those "goofy glasses". Now another 5 to 10% who, though they might enjoy it, can't watch 3D for any extended period of time without running for the Dramamine. Finally, exclude yet another 5 to 10% who (clinically) weren't born with stereoscopic (3D) vision. Now you are left with 20 to 30% of the "Normal" CE market to absorb the huge trainload of products being readied as we speak ... ur, read.</p>

<p>The noise level on this topic is bound to be so incessant that I may have to revisit this steed, whip in hand, yet another time!</p>

<p><br />
Jim Morrison was certainly not the first to utter it (I'm guessing you have, yourself, at least thought it) but he and his band were the only ones I know who put the phrase on the Billboard charts......but it comes to mind often as I observe various phenomena within our amusing little CE market sector...</p>

<p>PEOPLE ARE STRANGE ...</p>

<p>Is it just me, or is anyone else stumped as to why someone would want to spend an hour and a half of their life watching a blockbuster movie on the 2 1/2 inch screen of their cell phone?</p>

<p>I'm still vexed as to why, in the name of improved video quality, someone would fall for a $79 BD player!</p>

<p>I saw an ad this week for a $700 sound bar (you know, the little rectangular box, 3" tall, that sits under your flat panel TV) and it promised "Enveloping 5-ch. surround sound with 30hz bass". Did everyone in this generation skip Physics 101?</p>

<p>I continue to see (in other pubs, of course) mid-level products reviewed with a low-end source device and an even worse display to evaluate the results. The reviewers were underwhelmed ... DUH! These guys also skipped Metrology 101.</p>

<p>Calibration confusion. I read an article in our regional newspaper (circ. 3+ million) wherein the author alleged, in response to a reader's question, that "There is no need to calibrate sets smaller than a 50" diagonal". Really? It's true, larger screens make video artifacts more egregious, ... but what about geometry, color accuracy, color temperature, black and white levels, edge enhancement, not to mention general detoxification of user-menu defaults. Why would a "technical" journalist embarrass himself in front of millions for lack of just a little bit of research?</p>

<p>I'm pretty sure Jim was right.</p>

<p>Finally, I feel compelled to opine on the topic of internet based content. Countless product offerings are encouraging you to download this, "stream" that, to their mega-storage boxes, as if what comes out the other end is the original Director's art.  It's not.</p>

<p>Just as we have all but lost an entire generation to MP-3 audio, I worry about a similar fate for video. Kids who were reared on i-pods may never experience the pure thrill of high end, (nearly) uncompressed audio. Had they been exposed to it and had the means, they surely would have opted for it, but alas, that exposure may elude them to beyond the "roll-off" years. Now comes the internet with a similar "convenience over quality" argument. Just be aware of this before you sign up.</p>

<p>Video quality is synonymous with absence of artifacts. Anything that is in an image that isn't exactly like the original presentation is an artifact. Our ocular sensors don't like artifacts! Anything that comes at you from cyber-space has been bit-starved to one degree or another to save the Holy Grail of the internet, bandwidth. There are a variety of video "codecs" that enable this pixel plundering, some way better than others, but the game is always the same - "Let's see how much of this picture (and sound) we can take away from this guy before he notices". So the movie you download from "Cyber-Flix" will almost certainly not render the Director's Art. Indeed, compared to the best we've got, over-the-air broadcast, it will likely disappoint. The higher the resolution demanded, the more bits need to be transmitted and consequently, the more compression necessary to get it to you in a reasonable time. Caveat emptor.</p>

<p>Many will not care about the decline in video quality. You wouldn't be reading this magazine if you didn't.</p>
