	<p>The active glasses use <strong>LCD panels </strong>to block or transmit the light. They can also partially block the light. This means that they could <strong>serve as sunglasses</strong>, and they would change from dark to light in an instant (instead of the slow change with the photosensitive glasses you can buy now). As a result, these could serve as your sunglasses. With <strong>a corrective prescription</strong>, they could be the sole pair of glasses that you wear, indoors or out.</p>
	<p>Okay, now the glasses here <strong>play MP3s</strong>. That&#8217;s fine as it goes, but let&#8217;s imagine that it can also get <strong>radio signals</strong>. Not just radio station transmissions (which would be nice) but maybe <strong>Bluetooth</strong> as well. Now, your cell phone can stay in your pocket or on your belt, and you&#8217;ll always be wearing<strong> your phone headset</strong>. Add a button or two and some voice recognition commands, and you&#8217;re in business.</p>
	<p>This requires power, but there are lots of<strong> power-scavenging technologies </strong>being developed that can use heat, light, or motion to recharge your glasses. Let&#8217;s imagine that it powers up when you <strong>put them on</strong>, and shuts off automatically when you take them off, and <strong>never needs to be plugged in </strong>to recharge. That&#8217;s pretty convenient. And finally, if you&#8217;re ever in range of a 3D display &#8212; either <strong>at home or work or at the local mall </strong>&#8211; it will automatically go into shutter mode so that you can see the 3D images.</p>
	<p>I contend that this could result in an accessory that you would find <strong>so useful </strong>that you&#8217;d put it on first thing in the morning, and not take it off until you go to bed at night. Like cell phones, it could <strong>acquire additional functions </strong>that we haven&#8217;t even realized that we&#8217;d want, which would make it even more useful. I can imagine a future where millions of people would wear these <strong>all day, every day</strong>. Who knows, maybe they&#8217;ll even be called &#8220;<strong>iGlasses</strong>&#8220;.
</p>
