          <p>Do you own a CableCARD TV?</p>
<p>Not many people do. (I have a CableCARD-equipped TiVo HD, but that’s all.) And that’s precisely why I’m writing this commentary.</p>
<p>Many of you are probably scratching your heads right now, wondering where you remember the name “CableCARD” from.</p>
<p>Actually, it goes back almost ten years, when TV manufacturers and cable TV service providers teamed up briefly to ‘ditch the box’ – that is, eliminate the good old set-top cable box and instead build its functionality right into the innards of new TV sets. The belief then was that consumers hated having a separate set-top box, and that CableCARD functionality would make cable-ready TVs truly ‘plug and play,’ not to mention get rid of all that clutter of wiring.</p>
<p>Plasma, LCD, and rear-projection TVs from LG, Panasonic, Sharp, Samsung, Mitsubishi, Toshiba, Philips, and others soon appeared with a PCMCIA card slot on their rear panels. A call to your local cable company brought out a technician with a matching card for that slot. He’d plug it in, and then spend about 30 minutes on the phone ‘pairing’ four different numbers with a customer service representative.</p>
<p style="text-align: center;">
</p><div id="attachment_538" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/05/cc2a.jpg"><img class="size-full wp-image-538 " title="cc2a" src="http://www.hdtvexpert.com/wp-content/uploads/2010/05/cc2a.jpg" alt="" width="600" height="420" /></a><p class="wp-caption-text">We called it 'plug and pray' back then...</p></div>
<p>Assuming all went well (and it often didn’t!), you’d soon be able to watch digital cable channels box-free, with full electronic program guide information. I tested many of the first CC-equipped TVs when they were introduced, and there was a marked inconsistency in operation from one brand to the next. Some (Mitsubishi and Panasonic) worked beautifully, while others (Sharp) stubbornly refused to recognize valid channel packages even when all conditional access was disabled.</p>
<p>The pairing issues, and reluctance of manufacturers to support more than a handful of CC-compatible models, resulted in a very slow rate of adoption. I stopped tracking the market around 2005, when (as I recall) fewer than 200,000 CableCARD sets had been deployed nationally. Enthusiasm for CC declined sharply after that, and in a few short years, there were no more CC-ready HDTVs on store shelves.</p>
<p>But CableLabs and MSOs hadn’t given up yet. Their ‘next big thing’ would be a bi-directional version of CableCARD, allowing a greater degree of interactivity and the ability to get video-on-demand – something the original CableCARD platform couldn’t do. To differentiate this new feature, they called it ‘<strong><em>tru2way</em></strong>.’</p>
<p>If you attend the Consumer Electronics Show on a regular basis, you may recall big, splashy demonstrations of <strong><em>tru2way</em></strong> HDTV prototypes in the Panasonic and Samsung booths a few years back. According to company representatives, <strong><em>tru2way</em></strong> sets were going to sell like hotcakes.</p>
<p>As usual, a funny thing happened on the way to retail: NeTVs. While <strong><em>tru2way</em></strong> was a proprietary solution for customers who wanted box-free digital cable reception, NeTVs were an open platform that anyone could tie into an Internet connection and access videos from YouTube, Netflix, Amazon, USA Today, Yahoo, and other sources.</p>
<p>It’s telling that not a single TV manufacturer showed a <strong><em>tru2way</em></strong> set this year (or last, for that matter) at CES. The mad rush to 3D had something to do with that. But the realization that broadband-connected TVs were inexpensive to manufacture and could be used by just about anyone with an Internet connection sealed the deal.</p>
<p>Why spend all that money to develop an expensive media delivery platform -–a TV that subscribers to DirecTV, Dish, FiOS, and U-Verse wouldn’t buy? Nahhh, just stick an Ethernet port on there and a few widgets. Now, ANY customer could use that TV to get content on demand, or stream it.</p>
<p>As for that rat’s nest of cable, HDMI has it pretty much under control now. One wire, two plugs, automatic configuration – who could ask for anything more? Even those ugly, big-as-a-dictionary set-top boxes have gotten a lot smaller. My current cable box is about ½ the size of my old Motorola DCT6200.</p>
<p>As it turns out, customers aren’t clamoring at all to get rid of the set-top box. There are still plenty of them out there, most equipped with a hard drive for time-shifting programs. And from a maintenance standpoint, it makes more sense to keep the DVR separate from the TV anyway. (Ask LG sometime about how well their DVR-equipped plasma HDTVs worked out.)</p>
<p>From the looks of things, it appears interest in <strong><em>tru2way</em></strong> has also waned within the cable industry. At the Cable Show last year, there was an entire <strong><em>tru2way</em></strong> Developer’s Conference, run by CableLabs. But this year? According to a show preview in <em>TV Technology </em>magazine, there will be one lone seminar on the topic.</p>
<p>Who cares?</p>
