          <p>Yesterday was a hot, dry summer day, perfect for a ‘triple play’ – the CEA summer Line Show on 34<sup>th</sup> Street, Mitsubishi’s New York press exhibition, and Pepcomm’s Digital Experience tabletop shmoozefest to cap off the evening.</p>
<p>I decided to visit Mits first, and will have a separate report on the sole remaining player in DLP rear-projection TVs. After that, I hiked on uptown to the CEA event, where I met up with colleague and friend Ken Werner of Insight Media to tour the show floor.</p>
<p>Our first stop was the Sony booth, where numerous Bravia 3D LCD sets were showing the Germany – Ghana World Cup match in 3D. There was plenty of comfortable seating, so Ken and I each grabbed a pair of Sony 3D glasses to check out the action.</p>
<p>Whoa! What’s this? I could clearly see ghost images of each player racing around the field, a phenomenon that only got worse with a slight tilt of my head. Ken picked up on it, too. As I tilted my head even more, the ghosting (crosstalk) got even worse, rendering the images largely unwatchable at about a 30-degree angle to either side.</p>
<p>Looking even more clearly, we both found that, even with our heads perfectly level to the screen, we were seeing dark gray ghost images of each player (Ghana was wearing white), and these ghosts changed from dark gray to white as we tilted out heads just 20 degrees to either side.</p>
<p>Yikes! I sure wouldn’t want to see THAT on my home 3D TV. It would be back at the store faster than you could say ‘vuvuzela!’</p>
<p>How bad was the crosstalk? To put my money where my mouth is, I whipped out my trusty Sanyo Xacti HD digital camcorder, placed it directly behind one of the lenses, and shot a series of photos to show you exactly what I saw as I rotated the glasses to either side of the TV screen.</p>
<p>In this first series, a floating banner shows the halftime score, along with two yellow cards. So far, so good!</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-Correct.jpg"><img class="aligncenter size-full wp-image-593" title="Halftime Score Correct" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-Correct.jpg" alt="" width="600" height="419" /></a></p>
<p>The next two images show what happens when I tilt the glasses 45 degrees to the left and right. Not so good! The ghost images became apparent with as little as a 20-degree tilt.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-45L.jpg"><img class="aligncenter size-full wp-image-594" title="Halftime Score 45L" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-45L.jpg" alt="" width="600" height="448" /></a><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-45R.jpg"><img class="aligncenter size-full wp-image-595" title="Halftime Score 45R" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Halftime-Score-45R.jpg" alt="" width="600" height="448" /></a></p>
<p>Think those are bad? Check out this next series, which shows the crowd at the game. Once again, we’re in pretty good shape with the camera and glasses held perfectly level to the screen, although if you look carefully, you can see some double images.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Crowd-Shot-Correct.jpg"><img class="aligncenter size-full wp-image-596" title="Crowd Shot Correct" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Crowd-Shot-Correct.jpg" alt="" width="600" height="448" /></a></p>
<p>Now, another view, again with the camera/glasses tiled 45 degrees to the left. That image is sure to bring on a migraine in quick time.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Crowd-Shot-45L.jpg"><img class="aligncenter size-full wp-image-597" title="Crowd Shot 45L" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Crowd-Shot-45L.jpg" alt="" width="600" height="448" /></a></p>
<p>Finally, here’s a view of the cheerleaders performing at halftime. (I didn’t know there even <span style="text-decoration: underline;">were</span> cheerleaders at World Cup games!)  Viewed straight on, they look OK in 3D.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-Correct.jpg"><img class="aligncenter size-full wp-image-598" title="Cheerleaders Correct" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-Correct.jpg" alt="" width="600" height="448" /></a></p>
<p>But with the glasses and camera tiled to either side, it appears I’ve had one too many Budweisers (the official beer of the World Cup) and am about ready to do a full face plant.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-45L.jpg"><img class="aligncenter size-full wp-image-599" title="Cheerleaders 45L" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-45L.jpg" alt="" width="600" height="448" /></a><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-45R.jpg"><img class="aligncenter size-full wp-image-600" title="Cheerleaders 45R" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-45R.jpg" alt="" width="600" height="448" /></a></p>
<p>These results were the same through the left or right lens on any pair of glasses we tried on. And they’re consistent with the cross talk problems I saw at Sony’s NAB demo of the Masters 3D coverage.</p>
<p>I know what you’re thinking. And you’re right, people should NOT watching 3D TV with their head tilted to one side. But people DO watch 2D TV with their head tilted to one side, not to mention laying on a couch or the floor, perpendicular to the TV screen. (And here’s what that viewing position looks like through the Sony 3D glasses.)</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-90R.jpg"><img class="aligncenter size-full wp-image-601" title="Cheerleaders 90R" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Cheerleaders-90R.jpg" alt="" width="600" height="448" /></a></p>
<p>Ironically, at the Bit Cauldron booth at the other end of the hall, that company’s wireless (RF) 3D active shutter glasses were being demo’ed with a Sony Bravia TV, and these glasses were largely free of the cross-talk problem (although as you turned them more and more towards 90 degrees, the TV screen got darker and darker until it turned black).</p>
<p>These tests were disappointing, to say the least. I expect much better of Sony. They are an acknowledged leader in consumer electronics technology and a strong brand, right up there with Apple. And I’m afraid that thousands of customers are going to buy a Bravia 3D package, take it home, hook it up, see exactly what I saw, and return the entire kit and kaboodle to Best Buy or a refund.</p>
<p>I can tell you from my tests so far that Samsung and Panasonic are doing a much better job with their glasses and have almost insignificant issues with crosstalk. So it can be done!</p>
<p>In the meantime, here’s a <em>caveat emptor</em> to those readers who are thinking about jumping into Sony 3D: Your best move is to wait on the sidelines a little longer until Sony gets the bugs out of their system.</p>
