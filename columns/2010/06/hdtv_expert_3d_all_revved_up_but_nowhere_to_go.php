          <p>How much fun would it be to buy a new sports car if there wasn’t any gas available to power it, or roads to drive it on?</p>
<p>That’s exactly the situation that today’s consumers are facing with 3D TVs: There just isn’t enough content to watch on them. And it’s even more of a problem with 3D movies, as manufacturers have inked several deals giving them exclusive rights to bundle specific 3D movie releases with their 3D TVs and Blu-ray players.</p>
<p>Remember when HDTV first got off the ground, back in 1998? There wasn’t a whole lot of HD content to watch, aside from a few prime time shows on CBS and the occasional movie on ABC.</p>
<p>Consequently, retail demand for HDTVs didn’t really take off until HD programming picked up with movies on HBO, an expanded slate of shows and sports on major TV networks, and the introduction of HD program services by Dish Network. The 2000 Super Bowl, the first to be broadcast in HD, helped generate more interest in HDTV sets.</p>
<p>Even so, it took a few more years before the ball really got rolling and events such as the 2004 Olympics, the Stanley Cup, NBA Playoffs, and World Series were all broadcast in HD formats.</p>
<p>While it’s true that 3D programming choices will expand considerably this month as ESPN launches its World Cup 3D coverage and DirecTV begins 24/7 3D broadcasts, the pickings are slim when it comes to 3D movies.</p>
<p>Those exclusive ‘bundling’ deals are part of the reason. Samsung has locked up 3D Blu-ray distribution of the <em>Shrek</em> franchise (four movies in all) for the rest of 2010, and had a recent exclusive deal for 3D BD copies of <em>Monsters vs. Aliens</em>.</p>
<p>Panasonic has a similar deal to ship 3D BD copies of <em>Coraline</em> and <em>Ice Age: Dawn of the Dinosaurs </em> in 3D with their 3D TVs, and apparently will have first dibs on <em>Avatar</em> when it’s released in 3D this fall, according to the Web site <a href="http://www.hollywoodinhighdef.com/" onclick="javascript:pageTracker._trackPageview('/outbound/article/www.hollywoodinhighdef.com');">www.hollywoodinhighdef.com</a>.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Coraline-Ice-Age-Panasonic-Bundle-MR.jpg"><img class="aligncenter size-medium wp-image-558" title="Coraline - Ice Age Panasonic Bundle MR" src="http://www.hdtvexpert.com/wp-content/uploads/2010/06/Coraline-Ice-Age-Panasonic-Bundle-MR-300x171.jpg" alt="" width="300" height="171" /></a></p>
<p>What’s more, Sony is apparently negotiating a deal with Disney to have exclusive rights to the 3D BD release of <em>Alice in Wonderland</em> this fall, bundling it with Sony 3D Bravia TVs and BD players. <em>Cloudy with a Chance of Meatballs</em> is supposed to be the first ‘open’ 3D BD release later this month, but even it will be part of a Sony 3D TV bundle (no surprise there, <em>Cloudy</em> was released by Sony Pictures!).</p>
<p>They jury’s still out on whether 3D in the home will be a success. But limiting the pipeline of 3D movies to a trickle at this critical juncture simply isn’t good business. If TV manufacturers really wanted to drive sales, they should pick up the costs of 3D BD mastering for popular movies and let distributors flood the market with these movies.</p>
<p>Frankly, I’m surprised the Blu-ray Marketing Association and Digital Entertainment Group aren’t lobbying more vigorously for this approach. The Blu-ray format hasn’t exactly been an overwhelming success, and 3D is a way for it to ‘niche’ its way forward as the replacement for red laser DVDs. (Incorporating DVRs and BD-R capacity into BD players is another, equally important way to drive adoption of the BD format.)</p>
<p>The DVD format wasn’t hamstrung like this, when it launched in 1997. Players were expensive at the time, but within months, consumers had plenty of DVD movies to choose from at retail, and it didn’t take long for rental stores to start offering them, either.</p>
<p>Reverting back to my analogy: For now, consumers can enjoy their shiny new sports car while it sits in the garage, or zips around the neighborhood. But until those fast roads get built and there is an ample supply of fuel, consumers will continue to drive around in their older sedans and SUVs.</p>
<p>Supply drives demand these days in the HDTV business. Come on, Hollywood – when will the floodgates open on 3D Blu-ray movies?</p>
<p>Aside to Netflix: What’s YOUR timetable for 3D movie streaming? Hmmm?</p>
