          <p>Yesterday I made the trek up to northern New Jersey to visit John Turner at Turner Engineering, a 40-year-old broadcast systems integration company that is well-known in the industry for having built (among other things) the video infrastructure at EPCOT, the experimental WHD TV station, control rooms and distribution facilities for companies such as AT&amp;T and Prudential, and a host of other projects including re-wiring the Las Vegas Convention Center and dropping the sixteen HD-SDI fiber optic feeds required for NHK’s 2009 demo of 8K resolution UHDTV.</p>
<p>The occasion was an attempt to get a DirecTV HD receiver to “talk” to a Hyundai S465D commercial 3D LCD monitor. The S465D, which sells for about $7,000, uses built-in micropolarizers and works with passive X-pol (circular polarized) eyewear, such as RealD’s move theater glasses.</p>
<p>It displays top+bottom and side-by-side frame-compatible 3D signals as half-resolution images – 1920×540 pixels to the left eye, and 1920×540 pixels to the right eye. (Sorry, the S465D doesn’t support the Blu-ray frame-packing 3D format (HDMI v1.4a) – we tried that test with Samsung C6800 and C6900 BD players.)</p>
<p style="text-align: center;">
</p><div id="attachment_820" class="wp-caption aligncenter" style="width: 580px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/10/s465d.jpg"><img class="size-large wp-image-820 " title="Hyundai S465D" src="http://www.hdtvexpert.com/wp-content/uploads/2010/10/s465d-814x1024.jpg" alt="" width="570" height="717" /></a><p class="wp-caption-text">Hyundai's 465D 3D LCD monitor. (The tropical fish are optional! )</p></div>
<p>The problem was that the Hyundai’s EDID (Electronic Display Interface Data) is not supported by the DirecTV receiver, so we couldn’t see any of the available 3D channels. That problem was solved by using Gefen’s HDMI Detective to read and save the EDID from a Samsung UN46C7000 3D LCD TV and subsequently ‘spoofing’ the DirecTV receiver into delivering the desired programming.</p>
<p>Once that was set up, we donned the glasses and scanned through all three channels. The first one consisted of a DirecTV 3D logo sitting in mid-air, which was interesting to watch for all of five seconds. There was no crawl, or barker, to tell us what programming was coming up later.</p>
<p>The second channel, n3D (sponsored by Panasonic), was running a loop of content promoting 3D concerts featuring Peter Gabriel and Jane’s Addiction from the Guitar Center, wherever that is. These were interspersed with promos for a couple of nature shows. And that was it.</p>
<p>The third channel was running an on-demand promo for <em>Journey to the Center of the Earth</em> in 3D for $4.99. And that was it.</p>
<p>Granted, we checked out the programming between 2 PM and 6 PM EST, when there probably wouldn’t be too many viewers to tap into. But why not loop entire 3D programs all day, as the old PBS HDTV demos used to do ten years ago?</p>
<p>Comcast isn’t any better now. I have a choice of ESPN 3D (also available on DirecTV), which is mostly a barker channel during the daytime promoting the upcoming Saturday 3D NCAA college football game. Go up one channel, and you see a graphic telling you that Comcast’s own 3D channel is “coming soon!” And that’s it.</p>
<p>It’s unrealistic to expect consumers to spend the extra $$ on a new 3D TV when there is so little content to choose from. Once you get through the “bundled” Blu-ray disc(s) that came with your set and watch a football game or a pay-per-view movie, you’re going to be sitting on your hands waiting for more 3D content to come along.</p>
<p>The TV manufacturers have to take some of the blame here. Yes, I know that Sony has a partnership with IMAX and Discovery, but that 3D channel won’t launch until next year. And the pickings on n3D are like finding a couple of cans of beans in an otherwise-empty pantry.</p>
<p>Want to buy a 3D Blu-ray? There’s not a lot to choose from there, either, and won’t be until we get closer to Christmas. All of the ‘hot’ 3D movies are already tied up in bundling arrangements with TV manufacturers, and that’s just plain silly.</p>
<p><em>How to Train Your Dragon</em>, <em>Alice in Wonderland</em>, and <em>Despicable Me</em> are three of the highest-grossing 3D movies of 2010. But you have to buy a new 3D TV to get a 3D BD copy of any of them.</p>
<p>Oh, well. There’s always that 3D DirecTV logo to look at…</p>
<p><em>Afterthought:</em> The Hyundai S465D does a decent job displaying 3D, but a reference-grade monitor it’s not. I tried to do a basic calibration, but the monitor’s image adjustments were so limited that it wasn’t worth the effort. And the S465D has inconsistent gamma response and wanders over 1000 degrees in color temperature from black to white. I’ve seen consumer TVs do a better job for one-third the price.</p>
<p>As an air check monitor, it works fine. Don’t expect any more than that from it, though. You will be disappointed.</p>
