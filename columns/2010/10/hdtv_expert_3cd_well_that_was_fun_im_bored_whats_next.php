<p>Yep, it’s time to get out on the Internet and dig for content, using Google’s search engine and Sony’s incredibly small and dense keyboard. I didn’t see a single person attempt to use it during my 30 minute visit to the store.</p>
<p>In addition to Sony’s support for Google TV, Logitech has a new set-top box you can connect to the Ethernet port on your existing TV – or to the HDMI input.</p>
<p>Sony also showed a new “Internet TV Blu-ray Disc Player” that incorporates the Google interface. It’s the silvery box in the lower middle part of the photo, and encourages you to “take advantage of Full HD 1080p Blu-ray Disc Capabilities.” (???) No mention of 3D anywhere in the exhibit, so there may be a ’separation of church and state’ thing going on as far as Sony is concerned.</p>
<p>Oh, and that inexpensive upscaling DVD player? I wound up going down the street to 6th Avenue Electronics and scoring a Panasonic DVD-S58PP-K with HDMI output and CEC for $50. Can’t beat that with a stick.</p>
