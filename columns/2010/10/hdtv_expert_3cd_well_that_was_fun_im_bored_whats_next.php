          <p>I stopped in at my local Best Buy this past Saturday (10/30) to look for an inexpensive upscaling DVD player (yeah, I know that’s redundant) for my in-laws.</p>
<p>While I was there, I wandered around the store to see what was being showcased in the store demos. 3D, which was a big thing back in April, had clearly fizzled out – at least, as far as store personnel were concerned.</p>
<p>Of four possible 3D demo stations, only one had any glasses – the Sony Bravia 3D demo in the Magnolia section. A nearby Panasonic 3D demo had clips from <em>Avatar</em> rolling in 3D on a plasma TV, but not a pair of glasses to be found.</p>
<p>At the entrance to the Magnolia store was a Samsung 55-inch LCD 3D demo. Trouble was, the channel was set to a 2D telecast of the Michigan State – Iowa college football game and no 3D glasses were anywhere to be seen.</p>
<p>Behind the service counter in the regular TV section was yet another 3D demo, this time featuring the 46-inch UN46C7000 Samsung LCD TV. And just like my last visit, the TV was showing <em>Monsters vs. Aliens</em> in 2D, again sans 3D glasses.</p>
<p>A possible fifth demo at the end of one of the aisles used to feature Panasonic’s 50VT20 plasma, but it had been taken down. This was the only demo that had any working 3D glasses a few months back.</p>
<p>So, what was all the  buzz about at BB this time? Why, Sony Internet TV, of course!</p>
