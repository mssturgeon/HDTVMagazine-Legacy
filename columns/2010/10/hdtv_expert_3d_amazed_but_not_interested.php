<p>NPD’s report also showed that consumers have objections about cost, the need to wear glasses, the relatively short time that 3D technology has been available, and whether or not all technical issues with 3D TV viewing have been addressed (whatever they are).</p>
<p>Of those intending to buy a 3D TV, <em>“…more than half say that 3D enhances the viewing experience, and 42 percent agree with the statement that 3D is the future.”</em> So, about 6% of all 1,100 respondents said that 3D enhances the viewing experience. That’s a VERY low number. (What puzzles me is that only about half of the people intending to buy a 3D TV agreed with that statement. Why buy a 3D TV in the first place, if you don’t think it is an enhancement?)</p>
<p>It’s becoming apparent to me that two things are really holding back 3D TV. The first is cost. There are simply too many great deals on conventional (2D) HDTVs out there, and plain vanilla HDTV (never thought I’d say that) programming is available in abundance. For folks that are upgrading older TVs, the jump to HD is big enough for now. 3D can wait. Prices need to drop and drop fast on 3D-ready sets, which can just replace existing 2D-only models.</p>
<p>The second problem is all of the exclusive Blu-ray bundle deals. Between the TV manufacturers who cooked up these schemes and studios who agreed to go along, they’ve managed to shoot themselves in both feet quite nicely. Marketing 101 teaches you that you don’t make a product hard to find or expensive if you expect to sell a lot of it. (Unless it’s an upscale brand with a solid reputation, like Ferrari or Tiffany.)</p>
<p>We’re closing in on Black Friday and a major selling season for TVs, and right now, it looks like most consumers will be ‘sitting it out’ this year with 3D.  (Hey, TV sales are tough all over. 6<sup>th</sup> Avenue Electronics can’t even get rid of Panasonic 2D 50-inch 720p plasma TVs for $397, and that deal has been running for almost a month!)</p>
