<p>Wow. Only twenty percent were ‘amazed?’? That’s not very impressive for a new technology that has been marketed like crazy for the past ten months, and on which most manufacturers are hanging their hopes for a robust holiday TV selling season.</p>
<p>The report goes on to state that <em>“…42 percent of consumers surveyed were at least somewhat interested in watching 3D movies at home, but only 11 percent intend to purchase a 3D television.”</em> More discouraging news, as you’d reasonably expect interest in 3D TV to be peaking now after ESPN’s 3D World Cup coverage and a slew of 3D theatrical releases that earned big bucks at the box office.</p>
<p>Oh, wait: I forgot – Blu-ray releases of most of 2010’s box office 3D movie hits are already tied up in exclusive TV manufacturer bundles for the foreseeable future. It’s that ‘availability of 3D content’ thing again – there’s just not enough of it out there for most consumers to justify the purchase of a new 3D TV right now.</p>
