          <p>3D: Expect a Long Slog</p>
<p>It took nearly seven years before HDTV really took off. So how can we expect 3D to launch in less time?</p>
<p>There’s been a lot of discussion lately in the trade and consumer press that 3D is at danger of falling back into a novelty entertainment category.</p>
<p>Several prominent movie directors (among them J. J. Abrams) have come out against the format. Christopher Nolan (<em>Inception</em>) said it was too dark. And sloppy 2D-to-3D conversions, such as <em>Clash of the Titans</em>, may scare some people away from the format.</p>
<p>There’s also anecdotal evidence that the initial fascination that movie audiences had with 3D is starting to wear off. The premium for a 3D ticket can be anywhere from $3 to $5, depending on the theater chain and location. And experiences like <em>Titans</em> will make consumers gun-shy about spending 25% to 40% more for a 3D presentation.</p>
<p>But that’s a movie theater issue. What CE manufacturers want is for 3D to take off like HDTV did, back in the late 1990s.</p>
<p>The only problem with that thinking is that HDTV did <span style="text-decoration: underline;">not</span> take off in the late 1990s at all! As a matter of fact, it moved at a glacial pace for quite a few years.</p>
<p>I installed my first HDTV (Princeton Graphics AF3.0HD) in the fall of 1999, and connected it to a Panasonic TU-DST51W set-top box and antenna to watch a smattering of HD movies on Saturday nights (ABC) and a few sitcoms and hour-long dramas (CBS), along with Monday Night Football games (ABC again).</p>
<p>My TV market (Philadelphia) didn’t have a full slate of HD content available on the top four networks until 2003, five years after the first HDTV stations lit up. Remember NBC’s experimental HD coverage of the Winter Olympics in February of 2002? Remember the Fox network’s 480i ‘high-resolution digital TV?’ in 2000 and 2001?</p>
<p>The fact is; HDTV set sales didn’t hit their stride until the third and fourth quarters of 2005. That’s when the price wars began in earnest and the HD DVD – Blu-ray war was just starting up.  (Coincidentally or not, 2005 was also the high-water mark for DVD sales.)</p>
<p>Consider that HDTV turned the idea of TV viewing upside down. Gone was analog TV, replaced by digital bits and bytes. Gone too were big, bulky cathode-ray tubes, replaced by matrices of tiny pixels actuated by LCD and plasma technology.</p>
<p>Good-bye, VHS tapes – DVDs were well on their way to killing off this format by the start of 2005. And of course we were no longer limited to just 480 lines of picture resolution, but could enjoy programs with 1280×720 and 1920×1080 pixels of picture detail…win widescreen, no less!</p>
<p>Think about it. TV was literally re-invented from 1998 to 2005. And in 2009, we pulled the plug completely and analog TV broadcasts, completing the switch. But that was 11 years after the process started.</p>
<div id="attachment_705" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Putting-On-3D-Glasses.jpg"><img class="size-full wp-image-705" title="Putting On 3D Glasses" src="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Putting-On-3D-Glasses.jpg" alt="" width="600" height="337" /></a><p class="wp-caption-text">For most viewers, 3D is still an expensive novelty</p></div>
<p>So…manufacturers want people to buy into 3D. Currently, there are a limited number of 3DTV sets for sale, and they’re not as cheap as 2D sets. And there’s not much 3D content available on Blu-ray to watch right now. You can count the number of 3D TV networks on the fingers of one hand.</p>
<p>And the glasses! Depending on which model 3DTV you watch, you may see ghost images. Or, the picture may get darker as you tilt your head. (You may even get a headache after a few minutes.) And the glasses are expensive, and you need a separate pair for every viewer.</p>
<p>Did I mention that most 3D glasses will not work with other brands of 3D TVs? Hey, you could make anyone’s HDTV set-top box work with anyone’s DTV set. Ditto DVD players and Blu-ray players, and set-top boxes. But not 3D glasses.</p>
<p>It also doesn’t help that we’re in a nasty recession. People are reluctant to spend money now, especially with close to 10% unemployment.  So 3DTV winds up being an exotic luxury for now.</p>
<p>I return to my main point, and that is the long adoption curve I anticipate for 3D. The price premium is one drawback, and the other is the fact that millions of U.S. homes just bought one or more new HDTVs within the past three years.</p>
<p>Depending on whose numbers you believe, we are at or around 50% penetration for HDTV, meaning 50% of all homes have at least one HDTV set. I can guarantee that more than half of those sets were purchased after Q3 of 2005. So, where’s the impetus to buy a new 3DTV?</p>
<p>The good thing about a long adoption curve: Within two years, all models of HDTV sets 50 inches and larger will have the capability to play back 3D programming. (They’ll all have network connections too, but that’s another story.) So it won’t matter which set you buy – you’ll have the 3D playback built-in.</p>
<p>The same thing will happen with Blu-ray players and set-top boxes. They’ll be able to process 3D content as easily as 2D content. So you won’t have to buy an expensive special model just to watch 3D Blu-ray discs.</p>
<p>How long a curve are we looking at? I’d say about five years. By then, broadband speeds will have picked up considerably and we’ll be able to access 3D content through Internet TV channels, as well as from optical disc and video-on-demand.</p>
<p>Content drives demand, and there just isn’t enough of it in 3D right now. By 2015, the situation will have changed dramatically and we’ll have 3D movies, games, and TV programs coming out the wazoo.</p>
<p>Until then, expect 3D to penetrate the TV market slowly, in fits and starts…just like HDTV did.</p>
