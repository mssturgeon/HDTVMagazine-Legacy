<p>- 3.5-inch autostereoscopic LCD display with lenticular surface</p>
<p>The REAL 3D W3 can also be used as a 2D camera. You can shoot close-up and wide angle views of the same subject simultaneously. Or, you can shoot one view in color, and the other in black and white. Or, shoot one scene with normal light sensitivity and the other with higher sensitivity. Pretty cool!</p>
<p>I had a chance to test-drive one at the event, held at the American Museum of Natural History. Fuji handed out cameras to numerous journalists and we wandered among the skeletons of prehistoric mammals, trying for interesting perspective views. I also set up some of the press people in different perspectives to try and get a 3D feel. <strong><em>(All photos were taken with the FinePix REAL3D W3)</em></strong></p>
<div id="attachment_691" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Ken-Sander-Tries-Camera.jpg"><img class="size-full wp-image-691" title="Ken Sander Tries Camera" src="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Ken-Sander-Tries-Camera.jpg" alt="" width="600" height="337" /></a><p class="wp-caption-text">Veteran consumer electronics journalist Ken Sander takes the FinePix REAL 3D W3 for a test drive</p></div>
<p>My best effort was to switch to 3D video mode and walk from the main hall all way the way back to the Astor Turret, where several LCD 3D TVs were set up for viewing our efforts. This long “unsteadicam” shot provided the best 3D effects as I moved the camera over people’s shoulders and around them, dodging around pillars.</p>
<p>I have to say I was more impressed with the 3D still photos than the 3D video clips. The 3D effect was much more pronounced in still mode, but of course the resolution of left and right eye images was much higher. In video mode, I didn’t see as much depth and in fact spotted some crosstalk during the clip.</p>
<p>(Unfortunately, we had to give the cameras back. (Oh, well…) However, we did get to keep our 4GB Fuji SD memory cards loaded with left and right eye views, as well as our video clips.</p>
<div id="attachment_692" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Viewing-The-Results.jpg"><img class="size-full wp-image-692" title="Viewing The Results" src="http://www.hdtvexpert.com/wp-content/uploads/2010/08/Viewing-The-Results.jpg" alt="" width="600" height="337" /></a><p class="wp-caption-text">Fujifilm set up five LCD 3D TVs so we could check out the results of our shooting</p></div>
<p>The FinePix REAL 3D W3 is an intriguing product, although I suspect buyers will wind up using it more for its 2D camera features. The dual-perspective mode should prove to be very popular – you just won’t miss the shot.</p>
