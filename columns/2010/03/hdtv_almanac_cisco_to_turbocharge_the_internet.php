	<p>Well, clearly<strong> I was wrong then</strong>, so I&#8217;m betting on the expanding universe side of the question this time. Look at the experiments that Google and others are making for<strong> 1 Gbps Internet connections</strong>. (I just upgraded to 25/25 Mbps service, so I&#8217;m already a quarter of the way there!) And then there&#8217;s <strong>the CRS-3</strong>.</p>
	<p>In case that model number isn&#8217;t familiar, it&#8217;s a new router that <a href="http://newsroom.cisco.com/dlls/2010/prod_030910.html">Cisco announced earlier this month</a>. According to Cisco, it provides <strong>triple the bandwidth</strong> over the previous model: 322 Terabits per second. How fast is that? Cisco says it&#8217;s so fast that &#8220;every motion picture ever created to be streamed in <strong>less than four minutes</strong>.&#8221; (emphasis added)</p>
	<p>Pretty cool, huh? <strong>Who wouldn&#8217;t love </strong>to have this sort of power running the Internet? But wait; remember that Law of Unintended Consequences? Erik Heinrich provided <strong>an interesting analysis </strong>of this development in a <a href="http://www.time.com/time/business/article/0,8599,1972540,00.html">recent Time Magazine article</a>. He pointed out that <strong>Hollywood might not be ready </strong>to embrace this new development. Keep in mind that the Motion Picture Association of America (MPAA) fought <strong>both the VCR and the DVD </strong>on the grounds that they would make it easier to steal copyrighted movie and television program content. Given the problems that various operations including<strong> Hulu and Netflix </strong>have had in getting licenses to stream this sort of content, it&#8217;s clear that some folks in Hollywood are not ready to release all <strong>their latest productions </strong>on streaming services.</p>
	<p>From my vantage point, <strong>it&#8217;s inevitable </strong>that the studios and networks will come around, and see that Internet streaming is going to take <strong>a big bite </strong>out of the traditional distribution channels sooner or later. It&#8217;s already providing consumers with the <em>a la carte</em> option that cable and satellite services <strong>refuse to offer</strong>. And as more discover that they can already get<strong> most of the programming they want </strong>over the Internet for a lot less than they are paying for subscription TV services, the Internet services will gain <strong>increasing leverage for their negotiations </strong>with Hollywood. Developments such as <strong>Cisco&#8217;s new router and 1 Gbps broadband </strong>experiments will only bring that day that much sooner.
</p>
