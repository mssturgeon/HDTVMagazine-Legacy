          <p>The Blu-ray format has struggled for several years to gain the wide acceptance accorded to its lower-resolution sibling. Even though the latest market figures show Blu-ray player penetration at nearly 20% of U.S. households, packaged media rental and sales continue to decline (they’re down about 7% Y-Y), and Blu-ray disc sales and rentals are not sufficient to make up the difference.</p>
<p>There’s no question that the format war with HD DVD was a major setback. (China is now using a version of HD DVD as its de facto blue laser DVD format.) But the biggest problem Blu-ray had was bad timing – the world is slowly moving away from packaged media to digital downloads and streaming.</p>
<p>The high cost of players and discs didn’t help, either, and in fact may have hastened the move towards digital file capture. In a conversation with a Disney executive a few years ago (right after Warner Brothers pulled the plug on HD DVD), he stated that the easiest way to make sure Blu-ray caught on was to stop pressing red laser DVDs and stop manufacturing red laser DVD players.</p>
<p>Time marches on. Blu-ray prices have plummeted for both the players and discs. In fact, you can buy the four-disc <em>Toy Story 3</em> set from Amazon.com for $24.99 right now, and wind up with the main feature in the BD format, a BD extras disc, a red laser DVD, and a digital copy. That’s an amazingly low price on a supposedly ‘hot’ new BD release.</p>
<p><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/11/DMP-BD85-w-remote-MR.jpg"><img class="aligncenter size-full wp-image-936" title="DMP-BD85 w remote MR" src="http://www.hdtvexpert.com/wp-content/uploads/2010/11/DMP-BD85-w-remote-MR.jpg" alt="" width="600" height="234" /></a></p>
<p>So, why did I decide to buy a new player? For starters, they are dirt cheap right now, and getting cheaper by the day. I paid $180 for my Panasonic DMP-DB85  through B&amp;H Video, a price that was matched by Amazon.com. And that included free shipping via UPS Ground, which usually means overnight for me for anything coming from B&amp;H.</p>
<p>Secondly, I wanted a player that would work with the CEC interface on my Panasonic TH-42PZ80U plasma. One-touch control of the player and TV is just easier for family members than fussing with a bunch of remotes.</p>
<p>Third, our family subscribes to Netflix, so I was interested in adding streaming to my bag of media tricks. Granted, my TiVo HD can also stream, but I don’t want to tie it up if I’m recording shows to one or both of the internal DVRs.</p>
<p>Fourth, <em>Consumer Reports</em> gave the DMP-BD85 its second-highest ranking in a recent review of Blu-ray players. Yes, I subscribe to CR, and they do a bang-up job of product testing – particularly TVs and accessories.</p>
<p>Finally, the image quality from the Panasonic DMP-BD65 is very good, rivaling the OPPO upscaling player it replaced. Plus, the Panasonic remote is a lot easier to use than the older-style OPPO remotes. Readers who have older OPPOs know exactly what I mean.</p>
<p>I don’t play that many DVDs any more, but this unit should suffice as my media hub for a while. The DMP-BD85 comes with a USB 2.0 plug-in 802.11n adapter and isn’t too difficult to configure, although the on-screen menu could use some massaging. I had everything up and running in 5 minutes, even on a secure network.</p>
<p>Are we getting closer to the day that conventional DVD players become extinct? Well, Wal-Mart announced they’ll have a $65 Magnavox Blu-ray player available on Black Friday. And you can buy Panasonic 65-series players for about $100 now at BJ’s Wholesale Club.</p>
<p>So, yes – we are getting closer to that day when Blu-ray is the only optical disc format for packaged media. Only question is, will it happen before the American consumer makes a wholesale move to digital streaming and downloads?</p>
