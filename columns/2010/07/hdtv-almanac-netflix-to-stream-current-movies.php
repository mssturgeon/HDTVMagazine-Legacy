	<p>Well, now a bit <strong>more of the camel&#8217;s nose</strong> is showing. Netflix <a href="http://netflix.mediaroom.com/index.php?s=43&#038;item=361">announced this week </a>that it has an agreement with Relativity Media to stream the company&#8217;s <strong>first-run theatrical films </strong>at the same time that HBO and Showtime get them. Reality Media is the company behind hits including &#8220;Get Him to the Greek&#8221; and &#8220;Robin Hood&#8221;. This means that instead of having to <strong>wait years </strong>after the release of a movie on DVD, Netflix will be able to stream the movies <strong>just months </strong>after the DVD hits the shelves.</p>
	<p>Colin Dixon of The Diffusion Group (TDG) made <a href="http://tdgresearch.com/blogs/tdg-opinions/archive/2010/07/07/netflix-breaking-through-the-paytv-window.aspx">an interesting observation </a>about this announcement: &#8220;As long ago as May of 2009 TDG identified premium PayTV as Netflix’ true competition.&#8221; As I&#8217;ve been saying, Netflix clearly is positioning itself for the day when it doesn&#8217;t have to manage <strong>an enormous inventory of plastic discs </strong>and cope with the steady increase of postage costs. The competition is <strong>not Redbox and Blockbuster</strong>; it&#8217;s HBO and Showtime and Starz and the on-demand offerings by<strong> the subscription TV services</strong>.</p>
	<p>Netflix is clearly succeeding, as about <strong>three out of four subscribers </strong>apparently are using the streaming service. If people start getting their movies and archived TV episodes <strong>from Netflix (and Hulu)</strong>, how much are they going to be willing to pay for all those channels that <strong>they don&#8217;t watch </strong>on the subscription TV services? This is going to increase the pressure on <strong>a la carte pricing</strong>, which I contend will be the end of subscription TV as we know it. Those services will have to become <strong>data transmission utilities </strong>delivering the Internet to your home.</p>
	<p>(And you know what would accelerate the process? If <strong>ESPN were to expand its online streaming </strong>offerings to match what&#8217;s available on the subscription services &#8212; even at<strong> a monthly fee </strong>&#8211; I expect that users would cut the cable cord <strong>in droves</strong>.  ESPN is one of the remaining valued content sources that is <strong>not available over the air </strong>or by streaming.)</p>
	<p>So this announcement definitely qualifies as <strong>a BIG DEAL</strong>. It&#8217;s another incremental step in the redefinition of Netflix and video content delivery. The world of television is changing <strong>right before our eyes</strong>.
</p>
