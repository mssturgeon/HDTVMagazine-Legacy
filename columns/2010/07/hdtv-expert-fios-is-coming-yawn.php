          <p>They’re here!</p>
<p>The big orange spools of fiber optic jackets. The rows of white utility trucks. The polycarbonate junction boxes sitting every few feet along the curb. The spray-painted lines and alien glyphs all over my lawn, and my neighbor’s lawns.</p>
<p>Yes, FiOS has finally made it to our neighborhood. After nearly six years of waiting, Verizon has hired an army of subcontractors to run fiber optic cables under our lawns and breach the once-impenetrable Comcast wall.</p>
<p style="text-align: center;">
</p><div id="attachment_663" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/07/FiOS-Spool.jpg"><img class="size-full wp-image-663 " title="FiOS Spool" src="http://www.hdtvexpert.com/wp-content/uploads/2010/07/FiOS-Spool.jpg" alt="" width="600" height="448" /></a><p class="wp-caption-text">This is FiOS! This is Big! (Well, the spools certainly are!)</p></div>
<p>Thing is, some of my neighbors are kinda blase about the whole thing. And I am, too.</p>
<p>Here’s why: Verizon first wired up nearby Doylestown Borough in 2003-2004, back when most people had separate telephone and cable TV hookups and broadband access was starting to pick up steam. Repeated calls to Verizon about the availability of FiOS in our township brought the same results – “We’re negotiating with your township over the franchise fees.” Seems that, unlike every other township around Doylestown, our supervisors insisted that Verizon pay the same franchise fees that Comcast had, back in the day.</p>
<p>This, even though Verizon had successfully negotiated discounted franchise deals with most other townships in central Bucks County.</p>
<p>Finally, after years of haggling, our supervisors reached an accommodation with Verizon, who had already announced they would not build out their national FiOS infrastructure any further, due to the high labor/materials costs and challenging ROI environment. Fortunately, we already had the required fiber optic ‘drops’ sitting in a Verizon service cabinet at the corner of our development from six years ago.</p>
<p>A few things have changed along the way since 2004. First off, Comcast’s broadband speeds have picked up considerably, and their service is quite reliable. Secondly, I, along with some of my neighbors, dropped Verizon landline telephone service and consolidated everything into the ‘triple play’ option (broadband, phone, and cable TV). And the quality of phone service is much, much better than what I had with Verizon. (Other neighbors opted to install DirecTV dishes and forego any kind of cable connection.)</p>
<p>I’ve also got a CableCARD-enabled TiVo HD that I use constantly to time-shift programs, and it works very well. Not only that, there are numerous ‘in the clear’ digital TV channels present on my system that can be accessed by conventional TV sets without extra set-top boxes.</p>
<p>I saved myself about $40 a month with the consolidation. And have gotten pretty used to the high level of service. So maybe it’s understandable that I’m not in any hurry to change over to a new provider, even if their Internet speeds are supposedly faster (something that was definitely true back in 2004, but maybe not now).</p>
<p>And it doesn’t help when a Verizon contractor shows up at my door, asking me if he can disconnect my cable TV wiring so he can trace the underground line back to the house. Hell, no! Not while I’m reviewing artwork for a client project!</p>
<div id="attachment_664" class="wp-caption aligncenter" style="width: 610px"><a href="http://www.hdtvexpert.com/wp-content/uploads/2010/07/CU-of-Flags.jpg"><img class="size-full wp-image-664" title="CU of Flags" src="http://www.hdtvexpert.com/wp-content/uploads/2010/07/CU-of-Flags.jpg" alt="" width="600" height="448" /></a><p class="wp-caption-text">The wires are definitely here...unless they're somewhere else.</p></div>
<p>And that’s another thing to consider. When you call Comcast for a service problem (something I haven’t had to do in over a year), a Comcast-trained service person shows up in a Comcast truck.</p>
<p>When you call Verizon, you may get a Verizon tech. Or, you may get a subcontractor, particularly if you have wiring issues.  There are numerous ‘installation disaster’ stories of subcontractors puncturing gas lines and shorting out electrical lines while installing FiOS connections in the central Bucks County area. That alone gives me pause about the whole ’switch to FiOS’ thing.</p>
<p>Now, don’t get me wrong. I’m not a particularly big fan of Comcast, who seems to raise their rates at the drop of a hat.  And I wonder what Comcast’s pending acquisition of NBC Universal will mean for future monthly rates and access to content.</p>
<p>The fact that I could switch to FiOS at any time may be useful to me to get a better rate from Comcast, or hold the line on future rate increases.</p>
<p>But to be honest, the service I get right right now is very good. And it’s reliable. And I can troubleshoot most of it myself with my own test equipment. And I know a lot of the service and engineering folks at Big C. So I guess I’ll stick with Comcast for a while longer, while those Verizon contractors continue to tear up everyone’s lawns and finish pulling fiber to all the houses in the ‘hood. Then we’ll see how it’s working out for any of my neighbors who decide to make the switch.</p>
<p>Maybe it’s simply a case of dealing with the devil you know, versus the one you don’t know?</p>
