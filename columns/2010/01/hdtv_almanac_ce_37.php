				<p>The <strong>arms race </strong>continues. When you have a product category where the competing products<strong> do not differ significantly</strong>, manufacturers must find a way to make their product stand out. Almost all televisions are now <strong>thin and flat and have 1080p resolution</strong>, so what can they do? Competing on price is difficult, with <strong>margins already cut thin </strong>and retail prices still dropping by <strong>20% a year</strong>. So you have to make a difference with features. In most cases, consumers <strong>can&#8217;t see the difference </strong>in the image quality, so manufacturers have to rely on differentiation based on specifications. Everyone knows that <strong>a bigger number is better</strong>, so in terms that &#8220;Spinal Tap&#8221; fans will understand, manufacturers are figuring out ways to get their dials to <strong>go to &#8220;11&#8243;.</strong></p>
	<p>Leading the charge at <strong>CES 2010</strong> was Toshiba, which announced <strong>a new line of CELL TVs</strong>. These are named for their CELL Engine processor, which reportedly packs<strong> 143 times </strong>the processing power of a typical HDTV. There&#8217;s no doubt that TVs are now being asked to perform a lot of <strong>complex calculations </strong>on the fly, and these new Toshiba sets can even convert 2D programming into 3D in real time.</p>
	<p>But this processing power is also being used to attack<strong> LCD motion blur </strong>as well, raising the stakes with Toshiba&#8217;s &#8220;<strong>ClearScan 480</strong>&#8221; feature. Starting with the standard 60 frames per second (60 Hz) provided by the source signal, the processor creates <strong>three intermediate frames </strong>for each original frame. This results in an image with 240 frames per second (240 Hz).</p>
	<p><img src="http://hdtvprofessor.com/HDTVAlmanac/Toshiba_ClearScan_480.jpg" alt="Toshiba's new ClearScan 480 technology creates three new frames for each original frame, then uses a scanning backlight to simulate a 480 Hz image update rate." /></p>
	<p>The set then <strong>strobes the backlight </strong>at twice the frame rate (also known as &#8220;black frame insertion&#8221; or BFI), which simulates a <strong>480 Hz refresh rate</strong>. I say that it simulates that rate, because it is not presenting <strong>480 different frames </strong>per second: just 240.</p>
	<p>The bigger question is whether or not you can <strong>see the difference </strong>between it and a 120 Hz LCD HDTV. I don&#8217;t think that it&#8217;s a big improvement, and I&#8217;m not at all sure that most users could see the difference, even with <strong>two sets side by side</strong>.</p>
	<p>In any case, this is yet another salvo in <strong>the specifications war</strong>. Before long, we can expect to have LCD HDTVs that go <strong>all the way to &#8220;12&#8243;.</strong>
</p>
