	<p>The set then <strong>strobes the backlight </strong>at twice the frame rate (also known as &#8220;black frame insertion&#8221; or BFI), which simulates a <strong>480 Hz refresh rate</strong>. I say that it simulates that rate, because it is not presenting <strong>480 different frames </strong>per second: just 240.</p>
	<p>The bigger question is whether or not you can <strong>see the difference </strong>between it and a 120 Hz LCD HDTV. I don&#8217;t think that it&#8217;s a big improvement, and I&#8217;m not at all sure that most users could see the difference, even with <strong>two sets side by side</strong>.</p>
	<p>In any case, this is yet another salvo in <strong>the specifications war</strong>. Before long, we can expect to have LCD HDTVs that go <strong>all the way to &#8220;12&#8243;.</strong>
</p>
