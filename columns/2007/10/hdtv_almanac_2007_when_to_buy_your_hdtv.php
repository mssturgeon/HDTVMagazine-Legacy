	<p>Note that this forecast is an informed guess, but it&#8217;s <strong>still a guess</strong>. Here&#8217;s how I see things playing out. The manufacturers have been building a lot of product, encouraged by the fact that prices have <strong>stayed fairly constant </strong>over the summer. (Prices for some models have declined sharply, but that was largely <strong>the typical result </strong>of an older model being replaced by a newer one.) Some retailers such as Circuit City and Tweeter have <strong>not had a good year</strong>;  this holiday buying season is going to be a make-or-break time for many of them, and they&#8217;re <strong>counting on HDTV </strong>sales to carry a large part of the load. Best Buy has already stated that they will do <strong>what they have to do </strong>to maintain market share. And Wal-Mart is making <strong>a much bigger play </strong>for HDTV sales this year, with an expanded line-up of top brand products.</p>
	<p>If the consumers come out waving<strong> wads of cash</strong>, all will be well for the manufacturers and retailers. But I don&#8217;t think that is going to happen. Yes, the Dow Jones Industrial Average is at an<strong> all-time high</strong>, but that doesn&#8217;t really matter to the bulk of the American buying public. Bigger factors are <strong>higher interest rates </strong>and the difficulty of getting credit. <strong>Without home mortgage refinancing</strong>, many families are not going to have ready cash for big ticket items like HDTVs. And with the whispers of <strong>recession</strong> being spoken out loud, more and more workers are feeling uneasy about the future of their jobs.</p>
	<p>So while people will tell you that <strong>they really want </strong>a flat screen TV this year, they may not be quite so anxious to shell out the bucks to get one. This leads to my big &#8220;if&#8221;; if consumers don&#8217;t start spending on HDTVs in <strong>the next five weeks</strong>, someone is going to blink. Maybe it will be a manufacturer looking at <strong>thousands of sets </strong>stuck in warehouses, with factories still churning out thousands more. Maybe it will be a retailer who<strong> needs cash flow </strong>at any price, or who is concerned that they won&#8217;t hit their <strong>target market share</strong>. But someone will blink. And all<strong> the brave talk </strong>about not slashing profit margins the way they did last year will go <strong>right out the door</strong>. One will drop prices, and the others<strong> will have to follow</strong>.</p>
	<p>I think this will happen, and the most likely point to try to &#8220;buy&#8221; sales with lower prices is <strong>Black Friday</strong>, the day after Thanksgiving. So if you want a good bargain, <strong>wait until then </strong>to buy. If the market is as bad as I think it may be, the lower prices will not be a one day or one weekend event, but will <strong>carry through </strong>the end of the year.</p>
	<p>If you&#8217;re a gambler and you want to roll the dice for an <strong>even better deal</strong> and are willing to wait, then the last week of the year may be your best bet. I expect that even with lower prices, the stores will have <strong>more inventory </strong>than they will want to carry over into 2008, and some may <strong>do crazy things </strong>to get rid of some of that during the last week of the year. This is far enough in advance of the build-up to the Super Bowl that you may see another round of <strong>desperation discounts </strong>for that last week of December.</p>
