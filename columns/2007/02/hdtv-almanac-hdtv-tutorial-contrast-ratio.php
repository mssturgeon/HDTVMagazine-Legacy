				<p>I have noticed that a large number of people have come to the HDTV Almanac as part of online searches for information about <strong>HDTV contrast ratios</strong>. I go into the subject in some detail in <a href="http://hdtvbuyguide.com"><em>Professor Poor&#8217;s Guide to Buying HDTV</em></a>, but here&#8217;s the quick overview.</p>
	<p>Contrast ratio is probably the<strong> single most important </strong>performance factor in determining how you perceive the image quality of your HDTV. It is defined as the ratio of the difference between the <strong>brightest</strong> part of an image on the screen and the <strong>darkest</strong>. As a practical matter, it&#8217;s the <strong>bottom end </strong>that is most important. Some sets display &#8220;black&#8221; as a <strong>dark gray</strong>, while others have &#8220;black&#8221; that looks as deep and rich as <strong>outer space </strong>and that you could just dive right into it.</p>
	<p>A solid, dark black is important because it is what gives the<strong> color on the screen </strong>its life. If the black level is gray, then the whole image will look <strong>faded</strong> and washed out, no matter how bright the colors may be. When you have a good, solid black, however, <strong>the colors &#8220;pop&#8221;</strong> from the screen and you get the nearly three-dimensional experience. And if you watch DVD <strong>movies</strong>, a good black is especially important; the average movie scene uses <strong>less than 25%</strong> of the maximum available light (a full white image), which implies that there is lots of dark or black content in many images.</p>
	<p>Now, while contrast ratio performance is important, the contrast ratio<strong> specifications </strong>published by most manufacturers are <strong>useless </strong>at predicting performance. This is because the way they measure contrast ratio has nothing to do with the way that you <strong>actually watch images </strong>on a television. A lot of factors can affect contrast ratio performance, not the least of which is <strong>room lighting</strong>. For example, the black level of most plasma sets will look better than most LCD sets if you&#8217;re in a windowless room with all the lights turned off. If you&#8217;re in a room with <strong>strong ambient light </strong>&#8211; such as a family room in the afternoon with lots of windows &#8212; then the black level will likely look better on the<strong> LCDs</strong>.</p>
	<p>If you want to find out how well a given model produces black,<strong> most reliable approach </strong>is to go and look for yourself. A few minutes at the controls will tell you <strong>all you need to know.</strong></p>
	<p><em>To learn more about HDTV contrast ratio and how to evaluate HDTVs for yourself, get</em> <a href="http://hdtvbuyguide.com">Professor Poor&#8217;s Guide to Buying HDTV</a>.
