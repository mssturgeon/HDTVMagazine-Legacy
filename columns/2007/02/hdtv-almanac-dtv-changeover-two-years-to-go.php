	<p>So what do you <strong>need to know </strong>about the transition to digital TV broadcasts, and what should you do about it?</p>
	<p>First, digital broadcasts are happening right now in just about every TV market. Just like analog broadcasts, these are <strong>free</strong>, over-the-air (OTA) broadcasts of television signals from your<strong> local television stations</strong>.</p>
	<p>In order to receive these signals, you need an <strong>antenna</strong>. The frequencies are similar to the analog broadcasts, so an existing antennal may work for you. You can get new antennas that are tuned for the digital signals, however, which may<strong> improve your reception</strong>.</p>
	<p>You also need <strong>a digital tuner </strong>in your television (or any other device that receives broadcast television signals). All products with a television tuner must have a digital tuner starting at the <strong>end of March </strong>of this year, so if you buy <strong>any TV or video recorder</strong>, it will likely have a digital tuner. Look for &#8220;<strong>ATSC tuner</strong>&#8221; or &#8220;Built-in HD&#8221; or &#8220;Integrated HD&#8221; on the spec sheets or advertisements to find products with digital tuners.</p>
	<p>You <strong>do not need </strong>a digital tuner if you only rely on <strong>cable or satellite </strong>for your broadcast television content. You already have a settop box or similar device that receives the signal from these services, and that will <strong>continue to work</strong>. It is not related to the changeover to digital broadcasts.</p>
	<p>And just because you get OTA digital broadcasts does not mean that you&#8217;ll be watching everything in <strong>high-definition</strong>. If you have an <strong>HDTV with a digital tuner</strong>, then you will be able to watch any programming that is broadcast in HD, but at present, that is limited to <strong>prime time shows and sporting events </strong>(and not even all of those are in HD). And while you can watch digital television on a <strong>standard definition television</strong>, you won&#8217;t get the<strong> extra detail </strong>of the HD images on the shows that are in HD.
