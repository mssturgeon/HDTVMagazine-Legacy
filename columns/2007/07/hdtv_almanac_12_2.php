				<p>One of the &#8220;hot&#8221; new features for LCD HDTV is a <strong>120 Hz refresh rate</strong>. Okay, it&#8217;s not all that new; I wrote about it in my CES coverage last January. But the products that include this feature are <strong>starting to show up </strong>on the shelves in even greater numbers, so I figure it&#8217;s <strong>time to review </strong>the technology.</p>
	<p>Most LCD panels refresh the image <strong>60 times a second</strong>. This is fast enough to eliminate any image flicker for most viewers. The problem is that the liquid crystal molecules <strong>take time to react </strong>to the electrical charges in each cell, and you can get <strong>motion blurring </strong>between frames. By writing the image to the screen twice as often &#8212; <strong>120 times per second </strong>&#8211; it causes the liquid crystals to respond faster, and motion blur is <strong>decreased</strong>.</p>
	<p>Many LCD TV manufacturers are also <strong>pulsing the backlight</strong> in sync with the image refresh rate. For those of you who are into the club scene (or who remember the <strong>disco days</strong>), you are familiar with the &#8220;freeze frame&#8221; effect of a <strong>strobe light</strong>. Flashing the light <strong>freezes the image</strong>, further reducing motion blur.</p>
	<p>As a result, some LCD HDTVs with <strong>120 Hz refresh rate </strong>create fast moving images that look <strong>nearly as sharp </strong>as a CRT, which still is the gold standard for smooth motion on the screen. Most viewers would have a <strong>difficult time </strong>telling the difference between the two.</p>
	<p>There&#8217;s also one added benefit to 120 Hz. Some devices &#8212; such as some Blu-ray DVD players &#8212; now put out 1080p signals at<strong> 24 frames per second </strong>(fps) instead of the typical 30 fps. This slower speed matches the rate of <strong>film used in movies</strong>. Until now, the 24 frames have had to be <strong>shuffled </strong>in order to fit the 30 fps used by standard video signals.  The solution is an awkward stutter-step called &#8220;<strong>3:2 pulldown</strong>&#8221; which involves taking three images of the first frame, and then interleaving them with two images of the next frame, and then three of the next. This can result in an artifact that results in<strong> jerky motion </strong>that has been dubbed &#8220;<strong>judder</strong>&#8220;. The advantage of a 120 Hz refresh rate is that it handles the <strong>30 fps </strong>of standard video easily &#8212; just show each frame four times &#8212; as well as film&#8217;s <strong>24 fps</strong>; show each frame five times. The fact that it is an even multiple of both rates makes for <strong>less video processing </strong>and a better image quality.
</p>
