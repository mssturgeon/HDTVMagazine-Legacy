				<p>If you managed to miss the fact that <strong>Daylight Savings Time </strong>(DST) started yesterday &#8212; three weeks earlier than in years past &#8212; you probably showed up <strong>an hour early </strong>for your first appointment today. Unless you had at least one clock in your home that <strong>made the change </strong>for you.</p>
	<p>Here&#8217;s the &#8220;Spring Forward&#8221; scorecard from our home and office. We had <strong>nine devices </strong>that changed themselves to DST: two computers, one notebook, a Palm TX, two cell phones, a VCR, a DVR (digital video recorder), and a clock radio. Two other clock radios <strong>failed to make the change </strong>on their own, as did the microwave, the stove, a battery-powered wall clock, various wrist watches, the office telephone system, both cars, an indoor-outdoor thermometer, and my multifunction printer. (And there are probably a half dozen other clocks around the compound that I have <strong>forgotten to change</strong>.)</p>
	<p>Frankly, I&#8217;m surprised that so many devices were <strong>smart enough </strong>to make the change on their own. The computers are connected to the <strong>Internet</strong>, which knows what time it is. The <strong>cell phone system </strong>relies on accurate time, so the phones should know the time. And the VCR and DVR and clock radio all receive <strong>radio frequency waves </strong>&#8211; television and radio &#8212; which carry time information. I&#8217;m not surprised that they have access to the time information; I&#8217;m just surprised that they actually can <strong>take advantage of it</strong>.</p>
	<p>The simple fact is this; any device that receives radio waves or is attached to the Internet <strong>should know </strong>what time it is without you having to do anything about it. VCR manufacturers finally decided to solve the &#8220;<strong>flashing 12:00</strong>&#8221; problem years ago by getting the time information over the air. But it shouldn&#8217;t stop there. Any device that is <strong>connected to or communicates with </strong>any device that gets radio waves or is connected to the Internet should also know what time it is. My multifunction printer should be smart enough to <strong>ask my computer </strong>for the correct time.</p>
	<p>And let&#8217;s take it one step further.<strong> On-screen television guides </strong>are available over the airwaves and on the Internet, and every television device should be able to access this information. Our DVR has this feature; I don&#8217;t think my wife or I have opened the Sunday <strong>newspaper TV guide </strong>since we got the DVR. And any device connected to something with a TV tuner or the Internet <strong>should also know </strong>the program listings.</p>
	<p>The cars we drive no longer have levers on the steering wheel that let you <strong>advance or retard the spark</strong>. (I&#8217;m going to guess that the vast majority of the readers of this item don&#8217;t know what the heck I&#8217;m talking about.) How many of you have driven a car with a <strong>manual choke</strong>? Detroit automakers figured out long ago how to hide the <strong>mundane and technical </strong>details of internal combustion engines from the average driver. Consumer electronics makers have <strong>made strides </strong>towards a similar goal for their products, but the DST scorecard shows that the job is <strong>not yet complete</strong>. We should not have to spend time <strong>configuring and adjusting and tuning </strong>our televisions and related devices; they should just know. And then we can spend more time using these devices for their primary functions: to <strong>inform and entertain </strong>us.
</p>
