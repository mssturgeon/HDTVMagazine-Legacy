				<p><strong>DRM</strong>: it stands for &#8220;digital rights management&#8221; but the definition is really &#8220;<strong>copy protection</strong>&#8220;. We are currently coping with heavy-handed implementations of protection at a number of levels. Why can&#8217;t your <strong>iTunes</strong> music play on an MP3 player that is <strong>not an iPod</strong>? DRM. Why will some high-definition DVD players produce a 1080p signal only over an HDMI connection, and <strong>not a component video </strong>connection? DRM. And there&#8217;s something called the <a href="http://www.copyright.gov/legislation/dmca.pdf">&#8220;Digital Millennium Copyright Act&#8221;</a> that makes it <strong>illegal </strong>to try to find ways to work around the copy protection.</p>
	<p>It&#8217;s a <strong>complex issue</strong>. I am both a consumer of copyrighted material and a producer, so perhaps that makes it easier for me to see both sides. On the one hand, you have the <strong>rights of the content creators </strong>and publishers who have invested valuable time, money, and creative skill; in the case of a blockbuster movie, this can amount to <strong>millions and millions of dollars</strong>. This money is spent employing people and buying materials and services that provide additional jobs. On the other hand, you have the <strong>rights of consumers </strong>to enjoy the content that they have &#8220;bought&#8221; in any way that they choose. One of the favorite analogies is the paperback book; if you buy a book, you can read it in your home, or in the car, or on an airplane, or at the beach. Why shouldn&#8217;t you be able to <strong>do the same </strong>with music or a movie?</p>
	<p>There are signs that the balance on copy protection may be <strong>slowly shifting </strong>back in favor of the consumer, as a result of market pressure. This is exactly what happened to computer software 15 to 20 years ago, when <strong>Lotus 1-2-3 </strong>was one of the most popular productivity programs. It was copy protected, but Lotus spent so much time dealing with support problems that prevented legitimate owners from using the program that they eventually <strong>had to stop </strong>using it. Last year, we saw the <strong>Sony debacle </strong>with their &#8220;root kit&#8221; protection scheme on some music CDs. And now comes word that some <strong>major music publishers </strong>are starting to experiment with <strong>unprotected </strong>downloadable tunes.</p>
	<p>There&#8217;s an organization that is working to achieve <strong>a better balance </strong>between producer and consumer rights for digital media. It&#8217;s the <strong>Digital Freedom Campaign</strong>, and you can go to their Web site at <a href="http://www.digitalfreedom.org">www.digitalfreedom.org</a> to find out more about them and to sign a petition supporting their goals. As they state on their home page, &#8220;the Digital Freedom campaign is dedicated to defending the rights of artists, innovators, creators and consumers to use lawful technology free of unreasonable government restrictions and without fear of costly lawsuits.&#8221; As we enter the <strong>new era </strong>of downloadable HD movies, high-definition personal video recorders, and content sharing across home networks, it&#8217;s more important than ever to make sure that <strong>reasonable rules</strong> and standards are in place.
</p>
