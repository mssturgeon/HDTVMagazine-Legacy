				<blockquote>This is the next in a series of articles taken from the <b>H/DTV Technology Review & CES 2005 Report</b> by Rodolfo La Maestra, published in March 2005. If you are interested in downloading the full version of this report, it is currently available for purchase from our <a href="/store/ces-2005.php">CES Report</a> page.</blockquote>

<p><br />
<h2>Aurora</h2><br />
The company announced a new 1080p HD LCoS panel in October 2004, the ASI6000, a 0.7-inch diagonal 1920x1080 microdisplay panel, and its ASI6100 companion driver for RPTVs.  The panel is an upgrade path to existing ASI5000/5100 panel implementations, minimizing the optical system changes.</p>

<p><br />
<h2>Broadcom Corporation</h2><br />
On April 22, 2004, Broadcom Corporation announced the BMC3520 chip; an advanced single-chip DTV receiver for cable and digital broadcast integrated with an NTSC analog tuner, with plug-and-play features.  One main characteristic is its ability to acquire, track and demodulate signals in an environment of interference and multi-path noisy conditions, exceeding VSB performance.  The BMC3520 is priced at $20 each in 10,000 units, and is packaged as 144-pin PQFP with stereo audio.</p>

<p><br />
<h2>ELCOS</h2><br />
The company was expected to show at CES their implementation of their chip on an LCoS RPTV of 60 inches (eHD70), 4000:1 CR, 1920x1080 eHD70, 90000 hours lifetime; the chip could be applied to FPTV and RPTV.  They also have the eWX70 with 1280x768, 1000:1 CR</p>

<p><br />
<h2>Intel</h2><br />
On Aug 2004, Intel announced a delay on their plans to release their first LCoS chip for projection sets.  Their competitor, Advanced Micro Devices Inc., is continuing as planned.  Intel anticipated that the chip would not be ready by the end of 2004, as announced at CES 2004 in January.  There were no technical problems reported as the reason of the decision.</p>

<p>Later in October 2004, Intel announced that was canceling the plans to produce LCoS chips.</p>

<p><br />
<h2>Philips</h2><br />
On Oct 04, Philips announced that it has decided to discontinue their LCoS business with engines and RPTV, the company indicated that it had invested approximately $200 million in LCoS, the RPTV market was too small, and is not willing to increase the investment for the company to compete with these products.  Operations were planned to stop on November 19, 2004.  Philips also announced that it has cut $500 out of the MSRP of the remaining models, and will continue CRT RPTV production. </p>

<p><br />
<h2>Samsung</h2><br />
On January 2005, the company announced their development of a new DTV receiver chip (S5H1406) designed to perform well in harsh conditions of multi-path and weak signal conditions.  The chip will be made available by 1Q05 in the Asia region.</p>

<p><br />
<h2>Silicon Image</h2><br />
The company introduced in January 5, 2005 the SiI 8100 IC video-processing chip with HDMI connectivity capabilities.  In addition, Silicon Image has introduced a number of chips for HDMI connectivity for the manufacturing of H/DTV equipment.  Please consult the full detail on the HDMI Connectivity Chips section.</p>

<p><br />
<h2>Silicon Optix</h2><br />
Silicon Optix joined (and later bought) Teranex to implement a video processor in a single chip called Realta HQV (Hollywood Quality Video).  The chip is a programmable DSP that can perform one trillion operations per second and is able to upconvert 1080i to 1080p at up to 120 fps.  The company showed the product at CES 2005 in an interesting comparison setup.  The first consumer product to implement the Realta HQV chip is the Denon-5910 DVD player, $3500 TTM 1Q05 (see later on the report). </p>

<p><img src="/articles/images/mt/image112.jpg" alt="" align="left"><br />
The technology HQV was developed by Teranex and previously used in professional products costing $60000 and up.  It employs pixel-by-pixel processing, scaling, detail enhancement, etc and is fully programmable for receiving future firmware upgrades.  The quality is so good that it has won fourth awards since its introduction in the 4Q04, and the Best of Innovations CES 2005 award.</p>

<p>I witnessed a demo offered by Ray Lego, Product Manager of Teranex Business Unit at Silicon Optix Inc, and by Menno Stoffels, Director of Systems Engineering of Silicon Optics Canada Inc.  We went thru a side-by-side comparison of the effect of the product in direct-view TVs, RPTVs and FPTVs, with varied material that showed the improvements in typical test content like the flag, building bricks, noise in building windows, etc.  </p>

<p>It will be a big step forward for the H/DTV industry if manufacturers start considering the inclusion of this chip into their products as an option to whatever they are using now, especially considering that 1080p displays are here and now.</p>

<p>Silicon Optix/Teranex is planning to make available the new Realta HQV chip as OEM to manufacturers that want to implement it on their video processing, and Algolith has already in the works a scaler/noise reduction unit that incorporates the chip, the unit is expected to come out in Jun/Jul 05, its name is "Dragon Fly" and it will have a $3499 MSRP.</p>

<p>On a conversation I had with Mr. Michael Poirier, VP of Sales and Marketing of Algolith, he indicated that the specs of the "Dragon Fly" are still in development at this time, but the unit is expected to output 1080p/60 frames x second refresh rate from various input rates from 480i to 1080i, he indicated that by the time the unit is out it might happen that the 1080p output could be offered at other refresh rates such as 24fps or 30fps if the particular application benefits from those rates.</p>

<p><br />
<h2>STMicroelectronics</h2><br />
On Sep 04 the company announced the Sti7710 integrated chip for HD-STBs, which combines the functions of the Sti7020 HD decoder IC and the Sti5517 Omega decoder, adding Hi-speed USB (480-Mbps, 40 times faster than USB 1.1) which would permit external expansions of additional DVRs, and HDCP processing features to its DVI and HDMI connections.  The company is the world's larger supplier of MPEG-2 decoder silicon chips for STBs (77% of the market).  Production is planned for 1Q05 at a volume price of $18.</p>

<p><br />
<h2>Texas Instruments</h2><br />
<img src="/articles/images/mt/image113.jpg" alt="DLP Chips" align="right">On December 2004, TI announced that they have already reached their 5 million mark of sold products using their DLP technology.  According to TI, in perspective, it took 5 years to reach the first million (until December 2001), two additional years to reach the two million mark (until August 2003), by March 2004 the three million (six months later), and 4 months later the fourth million mark.<br />
