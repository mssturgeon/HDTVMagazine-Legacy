				<blockquote>This is the next in a series of articles taken from the <b>H/DTV Technology Review & CES 2005 Report</b> by Rodolfo La Maestra, published in March 2005. If you are interested in downloading the full version of this report, it is currently available for purchase from our <a href="/store/ces-2005.php">CES Report</a> page.</blockquote>

<p>The following statistics originate from the official announcements of the Consumer Electronics Association (CEA).</p>

<p><br />
<h2>CEA</h2><br />
The organization "Represents more than 1,850 corporate members involved in the design, development, manufacturing, distribution and integration of audio, video, mobile electronics, wireless and landline communications, information technology, home networking, multimedia and accessory products, as well as related services that are sold through consumer channels.  Combined, CEA's members account for more than $100 billion in annual sales."</p>

<p><br />
<h2>The Growth by the Numbers</h2><br />
In August 2004, the CEA announced that one of every four TVs sold in 2004 would be an HDTV.  2.8 million DTV units (integrated or monitor capable of at least ED 480p) were sent to dealers on the first semester of 2004, equivalent to 2.7 billion dollars of revenue; an increase of 80% compared to 1.5 million sets sold in the same period last year, making the total of DTV sales to 11.7 million sets since their introduction in 1998, most of those sales have occurred over the last two years.</p>

<p>In Sep 04 (CEDIA), upon showing the existing line, Mitsubishi commented "under the FCC mandate half of every manufacturer's big screen TV line had to include digital cable ready tuners this year, 68% of our sales have been with integrated tuners"</p>

<p>In November 2004, the CEA reported 13.3 million DTV sets sold since 1998, about $20 billion of investment.  4.4 million DTV sets were sold between January and September 2004 alone (71% increase compared to same period in 2003), which is about the same total number sold on the complete 4 years period of early adoption of H/DTV (Nov 1998 - Nov 2002).  September alone was recorded as close to 750,000 sets sold, a 40% increase compared to September 2003; October sales was reported as 968,000 (1.29 billion dollars), a 136% increase over October 2003 (and a 102% increase in dollars).</p>

<p>Furthermore, the CEA Market Research projected in November 2004 that the total sales for the year 2004 as almost 7 million H/DTV sets.  The same report projected sales as 10.8 million in 2005, 16.8 million in 2006, 23.3 million in 2007, and 27 million in 2008.</p>

<p><br />
<h2>Trend from the Previous Two Years</h2> <br />
To provide a perspective of how the market of H/DTV is growing I include below a couple of projections made over the last two years, together with their corresponding actual sales volume, first, a statistic provided on my CES 2003 report (Jan 2003) two years ago:</p>

<p><i>A projection from the CEA showed that 2.7 million of DTV products would have sold in 2002 alone, 4 million would be sold in 2003, 5.4 million in 2004, 8 million in 2005 and 10.5 million in 2006.  There are now approximately 4 million HDTVs sold since 1998.</i></p>

<p>A year later, on my CES 2004 report (Jan 2004), the statistics showed an even better trend:</p>

<p><i>"In October 03, the CEA reported the year-to-date DTV with an increase in market penetration because of strong sales in the plasma and liquid crystal display (LCD) monitor categories.  The year-to-date DTV sales actually reached over 2 million units in the period of January-August 2003, representing $3 billion dollars of DTV investment.  DTV unit sales increased by 26 percent in August compared to August 2002, 18 percent in dollar revenues.</i></p>

<p><i>Regarding HD-set-top-boxes (HD-STBs) January through August 2003 showed also 148 thousand units sold, an increase of 376 percent in August 2003 compared to the same month in 2002.  August 2003 sales alone totaled approximately 26,000 units.  The cumulative DTV set-top box sales figure - sales from 1999 through June 2003 - was close to 400,000 units.  That brings ATSC-receiving products, including both integrated sets and stand-alone set-top boxes, to over 700,000 units.</i></p>

<p><i>From the introduction of DTV until August 2003, DTV product sales totaled about 6,800,000 units, a dollar investment of almost $12 billion.  CEA Market Research projections at Oct 2003 updated the estimate of DTV products sales as 4.3 million DTV units will be sold in 2003, 5.8 million in 2004, 8.3 million in 2005, 11.9 million in 2006 and 16.2 million in 2007."</i></p>

<p>Note that the projection made over a year ago, of 5.8 million for 2004, was still short compared to the actual numbers (4.4 million of actual sales on 75% of the period, or 7 million projected for the full year 2004).</p>

<p>The years 2003 and 2004 were important periods of growth and acceleration of sales, the numbers are indicative that people are more interested in H/DTV, not as early adopters as it happened between 1998-2002 but as TV customers stretching their budget to enjoy better quality TV, rather than just to experiment with the technology as most early adopters do.</p>

<p>By December 2004, the total DTV sets sold since 1998 jumped to 14.3 million, representing about $23 billion dollar sales.  Considerable sales are being experienced in flat panel displays, 1.4 million LCD panels would be sold by the end of 2004, 290,000 LCD panels were sold in October alone.</p>

