<h2>Broadcast Flag</h2><br />
Below is a brief summary of the Broadcast Flag.  The text was extracted from an article I wrote for the HDTVetc magazine issue #6, which covers the subject of H/DTV content protection in general:</p>

<p><i>"In November 2003, to limit the indiscriminate redistribution of digital broadcast content, the FCC approved the 'Broadcast Flag' anti-piracy order.  A digital code embedded into a digital broadcasting stream would signal DTV reception equipment to activate the redistribution limit.  The mandate will take effect in July 1, 2005. </p>

<p>This regulation excludes digital devices not built with internal digital tuners, such as existing digital VCRs, DVD players, personal computers, etc.  According to the FCC ruling, all existing equipment incapable of reading the broadcast flag, such as televisions, VCRs, DVD players, will remain fully functional.</p>

<p>The new rules still allow consumers to make digital copies of broadcast HD content; they are intended to prevent only the mass distribution over the Internet, and to encourage availability of 'high value content' on broadcast television by discouraging its migration to more secure platforms such as cable and satellite TV service, according to the FCC.</p>

<p>In the words of the FCC ruling documents, "The broadcast flag protects consumers use and enjoyment of broadcast video programming.  The flag does not restrict copying in any way".</p>

<p>A demodulator (within equipment capable of tuning DTV) that complies with the flag mandate could still send the tuned signal to the analog component outputs of the device, but only to those digital outputs that meet with a copy-protection technology approved by the FCC (possibly 5c). </p>

<p>The FCC still needs to go thru the process of approving those future copy-protection broadcast-flag technologies; several are already pre-approved, including 5c.  Companies that are part of the Broadcast Protection Discussion Group developed those technologies.  Vendors of a particular content protection or recording technology need to be certified by the FCC in that such technology is an appropriate tool to give effect to the broadcast flag."</i></p>

<p>Additional background about the Broadcast Flag is on the CES 2004 report. </p>

<p><br />
<h2>Broadcast Flag Implementation Update</h2><br />
The following is an update of how the above is been implemented. </p>

<p>The FCC announced on August 2004 their approval of 13 digital content protection technologies applicable in a transport-to transport and media-to-media basis, and intended to comply with the deadline of July 1, 2005 in order to implement the Broadcast Flag mandate.  </p>

<p>Some of the technologies for the recording methods are VCPS (Vidi, developed by Philips and HP for recording DTV broadcast into DVD+R/RW discs), CPRM (4C for SD sources), D-VHS (JVC), and four versions of Magic Gate Type R developed by Sony for recording protection on Memory Stick Pro and Hi-MD.</p>

<p>The systems for output protection are DTCP (5C), HDCP and TivoGuard (for limited relaying among Tivo DVRs); and for Digital Rights Management (DRM) are Microsoft's Windows Media WMDRM, Helix (developed by RealNetworks), and SmartRight, developed by the SmartRight Association (of which Thomson is a member), the system establishes a personal private home network with smart-cards to deter piracy.</p>

<p>Under the protection conditions, content that is flagged may be subject to copy restriction and output-down-resolution when DTCP copy protection is applied over IEEE1394 (Firewire), and HDCP copy protection is applied over DVI/HDMI connections. </p>

<p>The Vidi recordable-DVD-system from Philips and HP will allow copies on compliant drives, not a copy of that copy.</p>

<p>JVC's D-VHS flagged content is copy protected, a loophole converts that flag to "copy one generation", allowing to connect to another D-VHS unit and make copies one at the time.</p>

<p>TivoGuard restricts by securing the registered DVR in a secured viewing group, the setup is done via a Web interface, which is password protected.</p>

<p>Thomson SmartRight home networking has an encoded flag making the content a private copy, that allows for up to 10 video displays and unlimited number of reception or secured storage devices in a network that can span to other physical properties of the same network owner, such as a second home, office, boat, etc.</p>

<p>The MS Windows Media Digital Rights Management technology works by setting a limit on the streaming and storage devices by establishing a cap on the permitted number of milliseconds of the traveling signal to keep it inside the home.<br />
