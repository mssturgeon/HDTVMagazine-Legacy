			<p>In my first discussion regarding this subject, I stated several factors that probably preclude the compromising of HDTV quality.  However, that doesn't mean such compromises are not happening.  Indeed, there are several ways quality can be degraded in the HDTV production, distribution, reception and display chain.  </p>

<p>Obviously, if the production qualities are unsatisfactory at the point of origination, they will not improve throughout the chain.  There are multiple reasons production qualities may not be optimum.  These include: camera quality, lighting, audio quality, set design, editing quality, post production elements, encoding factors, etc.  When programming is produced in HDTV, even small compromises in these factors can result in a large degradation of picture quality. SDTV productions, being lower resolution, can "hide" a greater degree of production error. HDTV, on the other hand, is not near as forgiving as SDTV relative to production values. This means we can expect a much wider variation of HDTV quality from program to program.</p>

<p>The many elements of the HDTV signal distribution chain offer several opportunities for displayed image quality compromises. Such compromises usually occur at the distribution end-point, that is the local broadcaster or cable service provider. The most serious of these is probably in the re-encoding process. Re-encoding involves decoding the received network HDTV compressed digital stream to base-band and then re-recording that stream. Sometimes the provider will filter and re-encode the HDTV program stream at a bit-rate significantly lower than 19Mb/s, resulting in loss of image definition. How much quality compromise is made depends on the quality of the head-end/broadcasters encoder and the number of multiplexes transmitted. Another source of distribution quality problems is associated with special effects generators and text inserting equipment. These devices may actually convert the digital stream to analog, add the effects, and then re-digitize the signal.  The potential losses generated by this process are obvious.</p>

<p>At the signal reception end of the chain, the antenna, tuner and decoder add numerous opportunities for image degradation. If the signal is too weak or intermittent, the tuner multi-path performance inadequate, and/or the error correction mechanism of low quality, the picture may freeze, break up into "blocks" or disappear completely.  The decoder may sample (or "clock") the digital stream at an inadequate bit rate, resulting is a loss of resolution.  </p>

<p>The display system quality represents the greatest opportunity for HDTV image degradation.  If all of the other factors in the chain are perfect, obviously a low quality display system will seriously compromise HDTV picture quality. In addition, all of the critical electronic image parameters, such as contrast, black lever, color, and sharpness must be adjusted properly to achieve a quality HDTV image.  </p>

<p>The audio channel also is vulnerable to these various factors.  In fact, even more variations can be expected in audio quality.  Producing good multi-channel sound is not an easy task for the producer.  The same variables in the signal chain can cause audio degradation, sometimes independent of the video channel.</p>

<p>For the same reasons explained in the previous article on this subject, it is imperative that all the players in the production chain strive for and maintain the highest HDTV quality possible.  If the end consumer of the service (that's us) suspects compromises on the HDTV signal chain, it behooves us to communicate our concerns appropriately. Don't forget, every local provider has a phone number.</p>

<p>With the aid of our vigilance, HDTV will only get better.</p>

