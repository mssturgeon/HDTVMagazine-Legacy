			<p>I have a fine collection of knives, and I actually use most of them regularly. I have a hunting knife for general outdoor tasks, a fishing knife for tackle tasks, a machete for heavy work, a Bowie for armed robbery and a miniature switchblade pocketknife that has been my faithful companion for many years. I also own three multipurpose Swiss Army type knives that gather dust in a drawer. The major blades on all three are fairly good, but the rest of the cute doodads are very much a compromise.</p>

<p>I believe this is a good analogy to consumer electronics products.  The history of CE products is littered with the carcasses of combination designs that did nothing very well, including sell.  There were some moderate successes such as the radio/phonograph combo. Perhaps the most successful was, and remains, the clock radio. It goes downhill from there.</p>

<p>Starting in the mid 1950's with the growth of hi-fi, design engineers realized that optimum system performance could be obtained if each device or component were designed separately for an individual task coupled with physical interface specifications that allowed mixing and matching of these components. In addition, since the technological advances of each of the components varied at different rates, the "obsolete" component could be replaced without compromising the entire system.  </p>

<p>This optimized component concept remains true with today's numerous A/V devices. The biggest problem with these devices, as now designed, is the complexity of the physical and user interfaces, i.e. too many wires and too many remote controls. But the advent of an increasing number of HDTV components coupled with advances in interface technology is solving those problems. The solution involves placing all of the separate component functions in a local area network. </p>

<p>To examine this further, consider that there are basically two philosophies of network configuration: centralized intelligence and distributed intelligence. </p>

<p>With a centralized intelligence network, as the name implies, most of the network's intelligence is in a central location with the individual operating terminals being "dumb." This is somewhat analogous to a traditional telephone system network in which the central office contains most of the network's intelligence, and the customers' telephone handset is relatively "dumb," providing only the user interface to the network.</p>

<p>In a distributed intelligence network system, as the name implies, most of the network's intelligence is located at the customers' terminals. This is somewhat analogous to the Internet in which the network infrastructure itself is relatively dumb, and the terminals (customer computers) are "smart."  Increasingly powerful microprocessors and relatively inexpensive memory have allowed more and more intelligence to exist in the terminal(s).</p>

<p>These two network philosophies are presently being played out in consumer electronics peripheral design. As the number of applications grows i.e. broadcast reception, cable/DBS reception, DVD, VCR, games, communications, audio, home security, etc., the centralized network philosophy places most of these functions in one very intelligent, multipurpose box, sometimes referred to as a "media server."  The complete package becomes sort of a super electronic "Swiss Army" knife.</p>

<p>The distributed network philosophy maintains each function in a separate physical unit ("box") along with the intelligence associated with that function. This intelligence also includes the user interface associated with the function. Again, the major problem with the "big box" (centralized) network philosophy is the inevitable technical obsolescence of one or more of the functions in addition of the inevitability of one or more new functions not included in the capability of the "big box."</p>

<p>Interestingly, two major consumer electronics players - Sony and Microsoft - are in a heated battle to capture the consumer electronics central intelligence space. Indeed, the next generation of both the Sony Play Station and Microsoft XBox, both due to hit the market within a year, are media servers in disguise. The "Trojon Horse" of these devices will be a new super game player. But really what both want is control over the operating software in the consumers' homes. Each wants his concept to become the defacto operating software standard of the centralized network. Why? Because both realize there is very little if any profit in the hardware itself, indeed both boxes will be highly subsidized. Their real money (they hope) will come from the software licensing deals that are possible with an acceptable standard.  </p>

<p>Contrast this approach to a multi-box, distributed network concept.  In this approach, each applications unit ("box") would have its own separate operating intelligence, but would communicate with every other unit in the network via a standard network protocol. The network itself would consist of a single variety of known physical standards, such as Ethernet, Wi-Fi, Wi-Max, power line, Blue Tooth, etc., and would interconnect via routers.  The network protocol would be an accepted standard such as IP (Internet Protocol). When a network compatible device is connected to the network (only one connection required by the customer), the device would announce its presence on the network (a process called "hailing") and would add its own graphic user interface (GUI) to the other devices on the network.  A standard user interface customer controller (remote control transmitter) would allow control of any of the devices via a master menu. This distributed network concept makes the A/V system truly "plug-and-play," the "Holy Grail" of consumer usability. </p>

<p>The standards for this distributed network approach are presently being designed by a CEA (Consumer Electronics Association) standards making group. When adopted, this network standard will allow an economic, user friendly, focused design, obsolescent protected approach to device function and control. However, the downside of this approach is that these standards are not finished. But they soon will be. And then the "big box" Swiss Army knives will gather dust in the drawer. </p>

