<p>HDMI Licensing LLC, the agent responsible for licensing the High-Definition Multimedia Interface(TM) (HDMI(TM)) Specification, today announced at the Shanghai Information Household Appliances Trade Association's (SIAA's) 2005 HDMI and Copy Protection Technology Seminar that more than 200 companies worldwide have become HDMI Adopters, in addition to the seven HDMI Founders. HDMI has quickly emerged as the standard for connecting high-definition television (HDTV). By delivering crystal-clear, all-digital audio and video quality via a single cable, HDMI dramatically simplifies cabling and helps provide consumers with the highest-quality home theater experience.</p>

<p>Signifying the rapid adoption of HDMI on a global scale, HDMI Adopters include cable/connector, semiconductor, system and test equipment vendors in the United States, Asia-Pacific, China, Japan and Europe. Hollywood studios, cable operators and satellite operators also support HDMI.</p>

<p>"Manufacturers across the globe are rapidly embracing HDMI, which is now featured on more than 400 consumer electronics devices from more than 40 manufacturers," stated Les Chard, president of HDMI Licensing, LLC. "HDMI's performance and ease-of-use advantages make it appealing to consumers, and it has quickly become a check-list item for DTVs and high-definition source devices. HDMI's simple application process, reasonable terms and the availability of the HDMI test specification make it easy for manufacturers to efficiently meet their customers' needs."</p>

<p>Various standards bodies have incorporated HDMI in their standards, further driving adoption. The FCC has mandated that after July 1, 2005, all "Digital Cable-Ready" TVs sold in the United States with screen sizes 36 inches and above, and 50 percent of those with screen sizes 25 to 35 inches, must feature an HDMI-HDCP or a DVI-HDCP input, and that all HD set-top boxes offered by cable providers must feature an HDMI or DVI output. In addition, the DVD Copy Control Association has established HDMI as an approved digital output for DVD players playing CSS-protected content at resolutions higher than 480p/576p. U.S. cable industry association CableLabs also requires that all OpenCable HD STBs must have HDMI-HDCP or DVI-HDCP outputs, and satellite operators DIRECTV and EchoStar require HDMI-HDCP or DVI-HDCP on all HD STBs. In addition, the European HDTV Forum recommends an HDCP-compliant HD digital interface, such as HDMI-HDCP or DVI-HDCP, be provided on both HD integrated receiver decoders and HD displays.</p>

