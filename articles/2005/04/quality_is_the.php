				<p><em>I wrote the following piece several years go. As you will see from the TIPS LIST post below it the warning contained in the article is as relevant today as it was when first published.</em> _Dale Cripps<br />
<em></em><br />
Quality is the infectious and addictive thing which digital brings to terrestrial broadcasting and all television services that engage HDTV. Low quality digital has already brought us multiple low-quality channels (by way of cable and DBS) to all but a few. This opportunity with HDTV is one time in our nation's history when high-quality can be accepted and delivered to the masses. Never before has a studio creation been so completely deliverable to the home as it is today. A new standard of living, many believe (and me among them) is being given birth through HDTV.</p>

<p>We can choose to squander this unique opportunity with a shortsightedness that claims the good of the public is served by reducing the cost using lowered quality. The old adage that "the best is the enemy of the good" no longer applies here. The best is the common good as far as HDTV is concerned. The only new thing that the digital television movement has to sell is quality. We already have interactive. We certainly have quantity. What we have not had up until HDTV came along was full viewing satisfaction on a big screen. For our long-term good we should resist the influence to take the faux-cheaper lower quality standard that many are sure to offer. The movement to "quality" is not a financial decision any more than buying a beach front house is. It is in many respects a moral decision first. We owe the best we can deliver to the future. What letters do we write to coming generations to explain why we robbed them of the potential of HDTV for just a few pieces of silver? If we embrace a 480p solution now any subsequent initiative to HDTV will suffer failure. There is simply not enough of a differentiation for a market to take a lead and overturn a widescreen 480p base with true HDTV. Europe may still suffer from this condition as they attempt in coming days to have HDTV whip their widescreen 625 installed base. You have to have sufficient differentiation in a new product before you can even hope to replace the old. HDTV has that 10 JND (Just Noticible Difference) spread needed between the old standard and the new, but according to market test, just barely. To expect widescreen 480p to be overturned by a widescreen 720p or 1080i is to expect a miracle.</p>

<p>If you think that the influence leading us to a lower installed base is not always lurking in the woods read the post to our TIPS LIST DAILY from Jason Burroughs. _Dale Cripps</p>

