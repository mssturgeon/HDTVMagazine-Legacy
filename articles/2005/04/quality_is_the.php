If anyone is into computers, you probably know about Tom's Hardware Page<a href="http://www.tomshardware.com">www.tomshardware.com</a>

<p>It's generally known as an excellent source of information about anything and everything to do with technology. TonightI was disgusted to read a recent article on HD that basically says 848 x 480 is HD and that HD is not standardized, and that there's nocontent on HD today, but you should go ahead and buy a 848 x 480 projector so that some day you can watch 1080i content down rezed to 848x480 and it will look great. The article is at <a href="http://graphics.tomshardware.com/video/20050413/">http://graphics.tomshardware.com/video/20050413/</a> and my letter is below. I was pretty harsh, but hope I got all my facts straight.</p>

<p>Corrections are welcome:</p>

<p>Dear Tom,</p>

<p>You're doing a disservice to your readers by publishing this review. It makes it appear as if High Definition is some marketing propag and a not standardized and unorganized. You are muddying the waters even further by passing off these half truths and innacurate information. Allow me to deconstruct it from the opening paragraph:"Now that the first wave of 16:9 video projectors has passed, new models are arriving, all of them able to display High Definition (HD) signals."Two of the four are 848 x 480 native resolution. Just because somethingcan ACCEPT HD, that doesn't mean it can DISPLAY (your word) HD. 848 x 480 is NOT HD - it's just widescreen standard video, at most it can be called Enhanced Definition if you go by the CEA's relaxed standards. A great example would be a high-definition over-the-air tuner connected via S-video to a 27" TV. you would never say that TV is capable of'displaying HD signals' because it is downconverted in the set top box to output the lower resolution. similarly, any projector whose resolution is 848 x 480 will receive the 720p or 1080i signal and downconvert it to a non-HD output.</p>

<p>"HD is in fact a generic term for all types of signals whose resolution is higher than standard video images with a resolution of 720 pixels wide by 480 (NTSC) or 576 (PAL) lines." Anyone who uses the phrase High-Definition and doesn't mean at least 1280 x 720p is using the phrase incorrectly. The US has a full set of standards and so does Europe. If you're talking about some third world country, that's hardly relevant.</p>

<p>"There is no real HD standard - the US uses a system called ATSC, whereas Europe uses DVBS".</p>

<p>The ATSC and DVB-S are standards for digital television, including High-Definition, which is defined as having atleast 1280 x 720 pixels in progressive scan format. There ARE standards and just because we have different names for them doesn't mean that there isn't a 'real' standard.</p>

<p>"To display HD images, video projectors must be 720p- and1080i-compatible, but they also need to accept input via HDMI, DVI, orYUV connectors". The phrase "720p or 1080 compatible" is too vague to have any real meaning. Again, just because something can accept an HD signal, if it down rezzes the signal to 480p, it's NOT HD. Also, YUV is an obscure naming convention for 'component video' and your readers probably do not know what it means. If they do, they likely know more about HD than the authors of this article.</p>

<p>"HDMI ... can handle resolutions of 1920x1080 pixels (HDTV) without compression. Video signals can also be 1080i, 720p...".</p>

<p>You've now made it even more confusing by labeling 1920 x 1080 as HDTV then said "also 1080i" ... but 1920 x 1080 IS 1080i (unless you're referring to the new1080p, which wasn't even mentioned in the article).</p>

<p>"Microsoft's proprietary format, WMHD, which can only be read by a PC".</p>

<p>This is actually called WMV-HD and there are set top boxes that can read it. Buffalo Tech makes one, as does IO data, both powered by a Crystal Magic chipset. Additionally, Microsoft has hyped the Bravo D3 as a certified WMV-HD player, although its release has been delayed again and again."In the US there are several networks (including ABC and Fox) broadcastin HD via satellite or cable." As of this writing, I personally receive14 channels in High Definition, including all major networks, HBO,Showtime, Discovery, TNT, and a handful of specialty HD channels. You've completely left out the entire Over-the-Air broadcast industry, which millions of people are receiving today. Every single major network is broadcasting almost all of its prime time lineup in HD, and all the major cable companies are offering an impressive suite of HD channels.</p>

<p>Overall, this article sounds like it was written by someone in Europe five years ago, with no knowledge of what millions of Americans are enjoying every day. Please consider deleting the article from your site, or at the very least putting a huge disclaimer as to the veracity of the information stated. I've depended on Tom's Hardware for accurateinformation for many years and am sorely disappointed at this amateurisharticle.</p>

