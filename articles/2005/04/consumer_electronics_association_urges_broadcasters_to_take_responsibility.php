<p>Shapiro's comments came as the NAB issued a misleading attack on CEA's good faith attempt to modify the DTV tuner rollout schedule and accelerate the DTV transition. CEA is requesting the Federal Communications Commission (FCC) advance the deadline for manufacturers to include digital tuners in all televisions with screens sized 25- to 36-inches from July 1, 2006, to March 1, 2006. In exchange, the association is urging the Commission to eliminate the July 1, 2005, deadline that requires 50 percent of sets offered for sale in this size range include a digital tuner.</p>

<p>"How the NAB can distort the facts and accuse CEA of delaying the DTV roll out with our proposal is unfathomable. Yet again, the NAB is pushing for regulations on other industries instead of taking seriously their responsibility to move the DTV transition forward," said Shapiro. "</p>

<p>CEA opposed the tuner mandate because so few Americans (less than 15 percent) rely on antennas to receive a television signal for the primary TVs in their homes. We accept the fact that the mandate is now law but our proposal would accelerate the DTV transition as the 50 percent requirement has not worked because consumers are not demanding tuner-equipped sets. The FCC cannot order consumers and retailers to buy products."</p>

<p>Shapiro continued, "Broadcasters are benefiting from the greatest wealth transfer in the history, namely the interest free "loan" of public spectrum. Their continued efforts to delay the transition indicate that NAB is trying to convert this loan into an outright gift. The American public deserves better."</p>

<p>In yesterday's speech, Shapiro noted that the move to DTV was designed in part to help support over-the-air broadcasts. But, he observed, broadcasters haven't taken advantage of this "unprecedented opportunity to revive their business. They have reacted to new competitive entrants with aggressive lobbying rather than aggressive business strategy."</p>

<p>Shapiro also noted that despite the challenges they face, broadcasters have refused to market their own product. Shapiro said, "While broadcasters have sought mandates on others, they have totally failed to promote free over-the-air broadcasting. CEA alone has created, funded and promoted a web site to help consumers choose antennas, visited by over 200,000 consumers a month."</p>

<p>Shapiro offered four steps for broadcasters to win back share and help save their industry: * Promote free over-the-air broadcasting.</p>

<p>* Shift to HDTV quickly and promote DTV on analog channels.</p>

<p>* Support a hard cut-off date for analog broadcasts.</p>

<p>* Defend the First Amendment.</p>

<p><br />
"I hope the broadcast industry does not sit idly by as broadcasting becomes wimpish, milquetoast media," said Shapiro in conclusion. "The answer is not to regulate competitors, it is to stand up and fight using broadcast strengths. It would be sad to see a great industry fade into oblivion or further into dependency on government regulation on other media. Instead of endless blame and delay, broadcasters need to embrace their digital future, move the DTV transition forward and do the right thing for the American public."</p>

