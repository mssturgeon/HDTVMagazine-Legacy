All of us love HDTV and are impressed, as we should be, by even downrezed resolution. But how much better could the picture be with an uncompressed (not commercially realistic I guess) picture on an excellent monitor that is 1080p. I realize that MPEG-2 and MPEG-4 are already compressed but the issue of further compression makes me wonder if the providers, be it cable, DirecTV, Dish, etc. Think that we will put up with lower and lower quality over time without looking for a better solution. </div><div align="left"></div><div align="left"></div><div align="left">I work for Verizon. I am looking forward to what resolution is going to be available with their FTTP-FiOS video offering. Fortunately, they are in the process of installing the fiber in my neighborhood. I haven't seen any of the technical specs yet but Verizon will be offering the video in the second half of 2005 in some parts of the country as they start to roll out the data and video services. I'm <strong>guessing</strong> that highspeed Internet access will be offered initially followed a few months later by the video offering. No, this is NOT a commercial for Verizon but I will admit that I am strongly considering going that way <strong><em>IF I can get better resolution at less cost</em></strong>. I know that the high-speed Internet access from them is going to be much less expensive than what I am paying Comcast, and I will get much higher bandwidth. I'm <strong>hoping</strong> that the video cost will also be less than what I am paying DirecTV. With the advent of MPEG-4 with DirecTV in the near future requiring that the dish, LNB(s) and receiver all be replaced I am <strong>hoping</strong> that Verizon may offer me increased resolution without anywhere near the additional cost that it <strong>looks like</strong> DirecTV will force on us. Yes, there has been talk to "trade-in" etc. From DirecTV but I haven't seen any specific information from DirecTV themselves. Unfortunately, I bought the HD DirecTV DVR a few months ago when I acquired my <strong>second</strong> HDTV. It would be worthless if I went the Verizon route. Well, I could sell it I guess. _Tom B. Kemp</div><div align="left"> </div><div align="left"></div><div align="left"></div><div align="left"></div><div align="left"><strong>COMMENTARY: This consumer of YOUR products has been using the TIPS List daily for several years. He is a professional in the field of communications and still his commentary is riddled with terms of uncertainties (which I have bolded). If that doesn't tell the HDTV industry that it has not done all what it required to educate the most willing of its public, what will? _Dale Cripps</strong></div>
