<p><br />
<strong>SOUND</strong></p>

<p>It is amazing to me how much the quality of HDTV sound production has advanced in the past couple of years. Almost all of the film based HDTV programs, i.e., most of the prime time fare, make full use of ATSC Dolby Surround sound encoding. Also, many of the live productions now include audio using all six channels of Dolby Surround. That is in addition to most movies shown in HDTV as will as on DVD's and Cable/Satellite PPV offerings.  </p>

<p>The ATSC system specifies the use of the Dolby AC-3 six-channel, sound-encoding format. The six channels, sometimes referred to as Dolby 5.1, are comprised of front left and right channels, a front center channel, left and right surround (rear) channels, and a low frequency effects (subwoofer) channel. The subwoofer channel is encoded at a lower bit rate than the others, and is referred to as the .1 channel, therefore, 5.1 channels. The motion picture version of Dolby Surround comprises many more surround channels, and is referred to as Dolby Digital, but it is easily down-mixed to 5.1 channels for HDTV, DVD's et. al. </p>

<p>Dolby 5.1 indeed adds another dimension to the HDTV viewing experience. Most HDTV projection receiver cabinets do a very reasonable job in providing stereo or even three channel front sound reproduction. The larger cabinets allow for larger speakers and better baffling, therefore providing a better wide band frequency response. But once a subwoofer and surround speakers are added, the whole experience changes as the sound field "lights up" the room.  Now, this is truly the "theater" experience!  Of course, smaller screen "table model" and flat panel monitors don't have the baffling advantage of projection cabinets; therefore, the 5.1 channel experience is greatly compromised with these units. But this is easily fixed.</p>

<p>Virtually all ATSC decoders, whether built-in or in separate boxes, have a digital optical (and/or coaxial) output jack. This jack most always carries either the fully decoded AC-3 digital stream and/or the un-decoded AC-3 information in PCM (Pulse-Code-Modulation) format. This digital audio output can be coupled to a "Home Theater System," available from several manufactures for less than $200.  These units accept either the decoded AC-3 digital signal stream or the un-decoded PCM stream and deliver to speaker terminal all six audio channels. Several inputs are provided for other devices, such as DVD players, that provide digital audio outputs. These home theater systems come complete with the full complement of speakers required for six channel sound reproduction.  </p>

<p>If a home theater system is not an option, at least one should invest in a powered subwoofer. This accessory will provide a surprisingly amount of "richness" to the sound experience, regardless of the audio source.</p>

<p>Not every HDTV program is produced with all six channels, especially the surround channels. Therefore, one should not expect having surround output with every HDTV program. Some programs are not conducive for employment of surround audio. But as production experience is gained, we will see an increasing incorporation of all of the full AC-3 capability.  <em>It will only get better.</em></p>

