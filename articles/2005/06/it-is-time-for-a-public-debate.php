<p>Why? Things were just too complex. Not only would the public falter in any debate on compression, the cliff effect, multicasting, or color space, or transmission schemes to name just a few, we would have foundered in the deep electro-geo-politics of the times. The move to DTV was initiated by strong willed people who had an unshakable belief that we would respond to the best that could be done. We are, after all, a republic. We elect or hire experts to represent us in forming the strategies of state and industry. </p>

<p>But there is one troubling issue which is again bouncing between legislation and the courts. It is an issue which was highlighted by this DTV transition. If any issue needs the clarity that a public debate delivers, it is this one. It is an issue which casts a long, and possibly dark, shadow across the future. Some think the fundamental strength of capitalism is at stake.</p>

<p>So what is this issue?  </p>

<p><strong>How do we deal with intellectual property rights in the digital age? </strong></p>

<p>"Seeking to encourage socially beneficial innovation, intellectual property rights are a public policy tradition that dates back to the 15th century, when the Venetians enacted the first patent law. The framers of the U.S. Constitution empowered Congress "to promote the progress of science and useful arts by securing for limited times to authors and inventors the exclusive right to their respective writings and discoveries." And Abraham Lincoln, who first journeyed outside of Illinois to litigate a patent case, observed that legal protection "added the fuel of interest to the fire of genius, in the discovery of new and useful things."</p>

<p>Throughout history there has been tension between legal rights that promote innovation and anti-trust policies that encourage competition. Some contemporary critics of intellectual property charge that legal protection for ideas inhibits free expression and is poorly suited to the information age. </p>

<p>Protecting ideas always demands a delicate balance between competing objectives and values: stimulating creativity but thwarting monopoly; creating knowledge yet disseminating it broadly; enforcing rules while responding to change. Economic, technical, and social changes have complicated the balance between these competing goals and renewed debate over who should own what ideas and for how long. Nevertheless, it is a time-tested proposition that society benefits enormously when the expression or product of some ideas is owned and exploited for profit." __ David S. Evans, "Who Owns Ideas? The War Over Global Intellectual Property," Foreign Affairs, November/December 2002.</p>

<p>"In an economy powered by knowledge and creativity, intellectual property (IP) is a significant corporate asset for companies in virtually every industry. Patents for inventions, trademarks for names and commercial symbols, and copyrights for publications and other works of authorship provide their owners with exclusive commercial rights for some period of time. Enabling businesses to create value in a variety of ways, IP helps companies gain a sustainable competitive advantage." Peter J. Gerken</p>

<p>"Digital Rights Management, abbreviated DRM, is an umbrella term referring to any of several technical methods used to control or restrict the use of digital media content on electronic devices with such technologies installed. The media most often restricted by DRM techniques include music, visual artwork, and movies.</p>

<p>Some digital media content publishers claim DRM technologies are necessary to prevent revenue loss due to illegal duplication of their copyrighted works. Civil libertarians, in contrast, argue that transferring control of the use of media from consumers to a consolidated media industry will lead to loss of existing end-user rights, as well as stifling innovation in software and cultural productions. No current DRM technology includes a mechanism to enable fair use rights per se, though some DRM methods allow acts of copying which may coincidentally align with legal use rights. Arguably, a technology cannot, in principle, know what legal restrictions and rights apply in a specific jurisdiction, usage context, under an external contract, or to an individual author, owner, or publisher." __Wikipedia</p>

