				<p>For those hungering for a little insight into the HDTV movement there is no one person more important to know than Richard (Dick) Wiley. A former Chairman of the FCC and presently a general partner in one of the most important law firms in the nation he accepted the pro bono assignment from the FCC for leading the industry to a technical conclusion -- one that answered a broadcast petition made to the FCC in 1987 by 57 broadcast groups. </p>

<p>That petition told the FCC that a threat to free broadcasting was coming (from Japan) in the form of HDTV. If they (broadcasting) could not meet the competition the institution of free broadcasting could be seriously endangered and fail. A failure would disenfranchising millions of people who get most of their world view from free television. From the standpoint of bandwidth both cable and DBS were in a better position. The FCC has no jurisdiction on the use of those frequencies in a closed system like cable or satellite.</p>

<p>The terrestrial bandwidth that is used by broadcasting is governed by the FCC. Whenever the slightest change is desired by a broadcaster the FCC is involved employing number of safeguards. The FCC is primarily a protectorate to all terrestrial spectrum users by insuring through careful investigation and due process that no interference will disable any other terrestrial spectrum using services. </p>

<p>For broadcast HDTV to be enabled the FCC had to be involved. They do not see themselves in the role of standards creators. They ratify recommendations but do not offer recommendations. In this case they asked Dick Wiley to head a blue ribbon advisory committee dubbed the Advisory Committee on Advanced Television Services (ACATS). </p>

<p>Anyone who was anybody in communications became a member of that committee. Sub-committees were formed to undertake the work of finding and building and testing a suitable standard for the United States broadcast environment that would also work with all other signal providing services. </p>

<p>The standard was to be originated at no cost to the government--all voluntary from industry. Over a dozen companies presented their proposals to a group of experts. Five of the proposals were selected for building and testing. I won't go into all that went into selecting the candidates nor the course changes taken when analog was dropped and digital introduced. All of the digital systems had something special to say about this or that feature. Rather than competing on features that gave emphasis to "that" at a cost of "this" Dick Wiley reached for an amalgamation in what was a quest for the best of the best systems. To get the best of the best a break down of the competitive ambitions within the voluntary proponents had to occur. </p>

<p>Dick Wiley formed the Grand Alliance out of the surviving members of the contest. Each company quite naturally wanted their patents to rule the future. With a deft hand Wiley caused those ferocious ambitions to be set aside long enough for them to work jointly on what has become the centerpiece for television -- a digital broadcast standard for HDTV which has a working relationship to all commercial signal distribution systems.</p>

<p>From the outset of HDTV our nation's professional worry warts were deeply concerned that any foreign lead in HDTV would be devastating to our national morale as well as threaten the chip business, which in turn would threaten our supremacy in military technology. The White House concluded that we had to get into the lead with a new HDTV standard and demanded it from all those working on its development, myself included. </p>

<p>Dick Wiley succeeded in getting America the best HDTV standard in the world. While in its manufacturing infancy it appeared threatened by yet another standard later introduced from Europe, but in later iterations the U.S. developed standard proved itself supreme. </p>

<p>This nation has never quite understood the heroic proportions of Dick Wiley's pro bono work as chairman of this world altering committee (ACATS). By his causing of this last and highly unlikely cooperative effort among the fiercest competitors in the world what was to become the ATSC standard was built, tested, FCC approved, and is destined to enrich all home life forever.  </p>

<p>Dick spoke recently before the ATSC at their annual meeting on May 10th. I thought you might like to "listen in" to his remarks below and get a big fix of "insight.". _Dale Cripps </p>

<p><br />
Remarks <br />
by Richard E. Wiley <br />
To the Annual Meeting of the Advanced Television Systems Committee </p>

<p>May 10, 2005</p>

<p>Recently, I chanced to come across a magazine article in which the author proclaimed that the Grand Alliance was a "messy process", one "essentially all about money" and whose success was "uncertain". Having closely witnessed the gestation, birth and development of this coalition, let me strongly beg to differ.</p>

<p>Of course, those involved in the Alliance wanted to try and recoup the tremendous investments that they had made - and justifiably so. And the same goes for the numerous entities (drawn from a variety of industries) involved in the entire national transition to digital television. Again, in a free enterprise economy, there is nothing unnatural or inappropriate about such an objective. However, the Grand Alliance - and, indeed, the all-important standards activity of ATSC - was hardly just about money. Instead, I would suggest, it was more about pioneering initiative, exacting science, technical innovation, prolonged dedication, risk taking, and, yes, a profound commitment to the public interest. Indeed, through nine long years, I saw this spirit up close and personal. And all the cynics and naysayers that you and I have encountered along the way can't make it otherwise. Thus, I am privileged and proud to come here this morning to thank and salute the legions (in this audience and elsewhere) who made it happen - who had a key role in one of the great technological and service transformations of our time. And make no mistake about it, the U.S. digital television effort does not represent just a stunning engineering achievement, it also will become - I'm willing to predict -- an enormous marketplace success as well and, with each passing year, this will become ever more evident.</p>

<p>To those who might question such an assertion - such as our Doubting Thomas columnist - I would point to the lengthy introduction of color television and of a number of other important communications advances. Simply speaking, these transitions take time - and especially so where extensive consumer education and investment in new and expensive equipment are required. But, as you can attest better than I, we are on the right road now - one on which there is general agreement concerning the desired destination and one on which there can be no turning back. And further to the critics, I would ask: where else in the world is the change-over to digital transmission moving ahead more effectively? Where else is the public at large being offered the opportunity to experience a wholly new (and vastly enhanced) viewing experience? Where else can consumers have access to some 2,000 hours per week of dramatic HDTV programming and also to over 800 models of world-class digital receivers (at prices that have fallen better than 75% in the last five years)? And where else will the entire transition likely be completed in this decade - hopefully, in a reasoned manner and one that will not disenfranchise our less economically advantaged citizens?</p>

<p>However, it should be understood that we are not nearing the end of the DTV era - rather, this really is just the beginning of a bright new video future for our country. All the elements of this revolutionary metamorphosis - from a static analog service to a dynamic digital one - are only going to get better as time passes.</p>

<p>After 2007, the television sets that Americans buy all will be essentially digital from the get-go. The programs that they watch will be increasingly in higher resolution - and provided not just by national networks but, more and more, by local stations and outlets as well. The digital services they receive will expand beyond television programming to myriad data and interactive offerings. And again - and I say this not in a jingoistic fashion but simply as a matter of actual fact - the United States will be at the forefront of this epic adventure.</p>

<p>Through it all, we can be thankful that there was a Grand Alliance - without it, we might still be discussing, debating, and maybe even litigating various aspects of individual (and less optimum) proponent systems. And we can be thankful as well that there is an ATSC. Like the Advisory Committee on Advanced Television Services before it, your organization has offered a unique forum in which differences over complex technical issues can be subjected to expert and civilized discourse. You may not always agree initially but everyone has a seat at the table and an opportunity to make his or her case. And in the end, a consensus judgment usually can be achieved.</p>

<p>"A messy process"? Well, perhaps at times. But in a non-centralized managed society like ours, I believe that the open, collaborative procedures employed by the Advisory Committee, the Grand Alliance, and the ATSC have well-served the future course of digital technology, the marketplace, and the citizens of this wonderful country. Indeed, I only hope that our policy-makers fully appreciate the nation's leading role in digital high definition television and the prolonged effort that it took on the part of so many to make it all happen.</p>

<p>So I am indeed pleased to be with you this morning to say "Happy Anniversary" on this memorable occasion. In closing, let me also express my admiration for the leadership and membership of this outstanding association.</p>

<p>Thank you and good luck.</p>
