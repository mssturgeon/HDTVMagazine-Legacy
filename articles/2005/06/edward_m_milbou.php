				<p><em><strong>NEWS RELEASE TODAY, JUNE 10, 2005</strong></em><br />
<strong>Edward M. Milbourn Joins HDTV Magazine</strong></p>

<p><em>Veteran television set developer to clarify HDTV products and services for public and professionals alike.</em></p>

<p>HDTV (High-definition television) has reached the stage where no one can afford to misunderstand it. While this complex and often confusing revolution marches forward globally at a record clip the call from every sector of the industry is for a greater public education about it.</p>

<p>HDTV Magazine is pleased to announce the addition of Edward  M. Milbourn to our list of authoritative Blog contributing editors. Mr. Milbourn brings 38 years of professional experience gained in his service to TV set maker, RCA, to clarify for both consumers and professionals around the world the intricacies of the digital television revolution.</p>

<p>"Nothing educates better than does authority." said Dale Cripps, Co-publisher of HDTV Magazine. "Mr. Milbourn brings that authority in spades and will help crystallize this massive revolution with each word he writes."</p>

<p><strong>Background</strong><br />
Edward M. Milbourn</p>

<p>After graduating from Purdue University with degrees in Electrical Engineering and Industrial Education in 1961 and 1963 respectively, Ed Milbourn joined the RCA Home Entertainment Division in 1963.  During his thirty-eight year career with RCA (later GE and Thomson multimedia), Mr. Milbourn held the positions of Field Service Engineer, Manager of Technical Training and Manager of Sales Training.  In 1987, he joined Thomson's Product Management group as Manager of Advanced Television Systems Planning, with responsibilities including Digital Television and High Definition Television Product Management. Mr. Milbourn retired from Thomson multimedia in December 2001.</p>

<p>And now a I proudly present to you Mr. Ed Milbourn. Please feel free to comment on any of Mr. Milbourn's contributions. _Dale Cripps</p>

<p><br />
<em><strong>Ed's view.</strong></em></p>

<p><strong>SO, WHAT SHOULD YOU BUY?</strong></p>

<p>Due to my several years with RCA/Thomson, many involving the HDTV project, I am often asked by friends and relatives, who are in the market for a new TV set, three (at least) fundamental questions:</p>

<p>1)	Should I buy an HDTV set now or wait for (unidentified) "technical improvements?"<br />
2)	What would I buy?<br />
3)	From whom should I buy it?  (No, since I am retired from Thompson, I can't get them any special "deals" as before - which is a good thing.)</p>

<p>My answer to question one is always "yes" - in spades. I explain there is now a sufficient amount of HDTV programming to justify the investment for the average TV family, and the thrill of the HDTV experience is well worth it. Yes, there will always be technical improvements, as with any technology. But the HDTV display system capability is at least three times greater than the best NTSC they have ever seen. However, it is more like eight times better that the average NTSC display.  </p>

<p>It will take a significant amount of improvement in HDTV display capability to achieve this much incremental visual impact.  </p>

<p>Yes, there will be continued display system improvements, but nothing soon that will achieve the visual impact of the jump from NTSC to HDTV.</p>

<p>The second question is prompted by my friends' bewilderment over the confusing "vegetable soup" or acronyms and abbreviations associated with digital TV in general and HDTV specifically.  ATSC, NTSC, HDTV, DLP, LcOS, Plasma, CRT, 16x9, 4x3, CableCard, 1080I, 720p, HDNI, YUV, and on and on - it's enough to make the average customer stomp away from the sales floor in utter disgust and confusion.  So, my answer to the "what should I buy" question is that it really doesn't matter, as long as the display system has HDTV performance, and it is large enough to appreciate the HDTV experience.  </p>

<p>I advise you to look at them all, but stick with name brands; compare performance, styling, and price in the desired size category.  (I do have my own display favorites that will be the subject of another wheeze from me.)</p>

<p>Although virtually all of my friends and relatives are receiving their signals via cable or DSS, I do suggest they select an HDTV receiver, not an HDTV monitor or HDTV "ready" set.  The reason for this, besides the extra capability of off-air ATSC and the CableCard, is that the extra "goes-ins" and "goes-outs" on an HDTV receiver are more likely to accommodate any foreseeable signal sources and/or accessories.</p>

<p>"How big should the screen be?" they ask.  I reply that the picture height should measure approximately 1/3 the measured distance from where they intend to view the set.  This is not critical, of course, but I want them to get the most out of their HDTV experience.</p>

<p>Further, I advise them not to forget the sound.  Most all HDTV units have a respectable built-in two channel audio system, but in the near future, if not immediately, my friends must consider installing a full 5.1 channel sound system to get the full HDTV experience.  To that end I advise them to make sure the unit contemplated has an optical digital audio output. (HDTV sound will be yet another "wheeze" from me.)</p>

<p>The last question pertaining to the "best place" to by their HDTV set is a personal one.  I suggest they shop around and buy from the retailer with whom they are most comfortable.  Retailers are doing an increasingly better job of showcasing HDTV. And the sales forces are becoming increasing more knowledgeable. </p>

<p>This day has been a long time coming for the industry and the consumer. And, it will only get better. </p>
