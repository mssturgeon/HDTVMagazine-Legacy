			<p>Normally, I don't do product reviews.  Others do that much more completely and with greater expertise than I.  However, I am going to make a small exception as I own this product and have copious hands-on experience with it.  This unit (the DIRECTV HD DVR HR 10-250) is actually the third DVR I have owned.  The others being the R 10 non-HD version of the HR 10-250 and an early RCA Ultimate unit, so I have some basis for comparison.</p>

<p>From a capability standpoint, the HR 10 is first rate.  A dual platter hard drive records up to 200 hours of SDTV or 30 hours of HDTV from twin DBS and ATSC tuners. NTSC (analog) reception is not supported. Output interfaces include HDMI and optical SPDIF (Dolby Digital) as well as composite (SDTV) outputs for connecting to a VCR or DVD recorder (or SDTV analog monitor).  The TiVo DVR/Guide service enables the recording capability.</p>

<p>Performance is also excellent.  The "server" type recording system simply records the ATSC/DBS bit stream as received with no trans-coding.  Therefore, what is received and decoded is what is recorded and thus retrieved during playback.  The requisite effects (pause, fast forward and reverse) are well executed.</p>

<p>The performance of the ATSC tuner(s) is on par with other such tuners I have installed, however, sensitivity may be a tad low, possibly because of internal splatters.  I have no way of characterizing ATSC sensitivity except with reference to other tuners.  In any regard, the differences appear to be comparatively small and would be noticeable only in extremely weak signal conditions.</p>

<p>Now for the bad news.  The software used in the HR 10 is unstable.  I had to replace one unit due to intermittent lock-ups and freezes.  The replacement unit is somewhat better in that it does not totally "lock-up," but it continues to exhibit annoying software glitches.  Some of this appears to be related to channel changes dictated by TiVo to record promotions.  This "feature" unfortunately cannot be disabled.  However, it appears the design engineers anticipated a number of software problems because a "soft reset" option is offered on the main menu.  Sometimes this option works, and normal operation is restored.  Other times a "cold" reset must be performed (power completely disconnected for a period of time) to reestablish operation.  Performing either soft or cold resets is particularly annoying do the extremely long reset time required - about ten minutes. </p>

<p>The user interface (UI) is a disgrace.  The menu tree is unnecessarily deep, arcane and non-intuitive.  The instruction book (user's guide) is not much better.  I believe the UI was written by a committee with lots of compromises decided over a conference table.  I have been down that road, and can easily understand how that happens.  Too bad, such a well performing product with such a terrible UI.</p>

<p>The other part of the UI - the remote control transmitter - is a total disaster.  Who ever designed that abomination should be taken out back and shot.  This unit has absolutely no redeeming ergonomic qualities - a true joke.  I won't even start to list the problems with this thing - I'll just get mad and throw it (again) across the room.  (It is rugged, however.)</p>

<p>So, would I recommend acquiring this unit?  If you have engineering and/or computer expertise plus patients, go for it.  It performs very well.  To the average HDTV user, I would suggest waiting on the availability of the new DIRECTV unit with NDS service, and hope for a better design.</p>

<p>Ed </p>

