				<p>VOOM is back in the news and so it gives me great pleaure to introduce to you one of the key men making it happen, Mr. Greg Moyer. VOOM held out a tremendous promise for HDTV fans when CableVision prematurely entered into the marketplace with VOOM and its 21 seperate HDTV channels. As with many premature projects VOOM lost its footing only to quickly find a new and permanent home for 11 of its channels on Dish. Far more extensive distribution is planned from this starting point.   </p>

<p>"Is HD Ready for the Real World?" Moyer answers this challenging question in his premiere column for HDTV Magazine. Moyer serves as co-general manager of the VOOM HD Networks and recently joined our growing roster of HDTV columnists along with Ed Milbourn (RCA-retired); Yves Faroudja;  John Reder (Texas Instruments); Robert Graves (ATSC Forum); and Rodolfo LaMaestra (consultant) with the HD mission to educate and excite the online public. </p>

<p>Moyer brings a wealth of program knowledge and contemporary insight to our readers.   </p>

<p>In this column Moyer focuses on "reality" programming. "As a group," he writes, "these high-concept, lower cost series pioneered by 'The Real World' on MTV and popularized by 'Survivor' on CBS have resisted the urge to go HD largely due to the added cost and complications of extensive field production. If 'reality' represents the final frontier for HD to conquer, when will the battle be engaged?"    </p>

<p> Moyer pulls back the curtain on this "final frontier" to show VOOM HD's fashion and style channel--ULTRA-HD--leading the way.   </p>

<p>Moyer knows television. He rose to chief creative officer at Discovery Channel during a 13-year tenure where he oversaw the rapid growth of two of the World's most respected and successful cable networks--Discovery Channel and The Learning Channel. He also spearheaded the development of Discovery Channel Pictures, Discovery's global initiatives, and its active retailing and interactive divisions. Moyer joined Rainbow Media in 1999 as president of regional programming and from there he assumed his post with VOOM earlier this year.</p>

<p>We look forward to carrying Greg's column every month and hope the world tunes in to one of the true leaders of our industry._Dale Cripps</p>

<p><strong>Is HD Ready for the Real World?</strong></p>

<p>With more programs converting to HD, the standard definition "dead zones" on a typical night of television are becoming fewer and fewer. Now scripted series, movies, prime time sports and late night strips hosted by the likes of Jay Leno, David Letterman and Conan O'Brien are reliably in HD.</p>

<p>The big exception is the genre of unscripted "reality" shows that still make up a third or more of the prime time diet. As a group, these high-concept, lower cost series pioneered by "The Real World" on MTV and popularized by "Survivor" on CBS have resisted the urge to go HD largely due to the added cost and complications of extensive field production. If "reality" represents the final frontier for HD to conquer, when will the battle be engaged? Sooner than you think.</p>

<p>VOOM HD's fashion and style channel ULTRA-HD has just wrapped production of the first season of a reality elimination series "Style Me with Rachel Hunter" using all-HD gear. The series, which is a co-production with WE: Women's Entertainment, relied on Sony 750s and the new miniature Sony HDV miracle, the HVR-Z1U, to capture the antics of 12 contestants - all aspiring fashion stylists - who compete to dress host and supermodel Rachel Hunter for a major red carpet event.</p>

<p>The production went around the clock for 30 days and marshaled up to five cameras shooting simultaneously to cover the multi-ring circus of challenges set for the budding fashionistas. The smaller HDV rigs were employed to capture the behind-the scenes dramas that unfolded back at the hotel base camp where the contestants let their emotions hang out.</p>

<p>Executive Producer Liz Dewey blew through 550 cassettes of HD stock to get coverage for the eight-episode series. The biggest production hurdle proved to be the inability of HD cameras to couple with wireless transmitters so that the producer could switch between shooters and monitor the action. Instead, production staff needed to physically tether a lightweight monitor to any camera where instant feedback was necessary.</p>

<p>Despite the bulk, Dewey would not go back to SD. "For a reality show, HD is ideal. In situations where you have very little control over lighting and action, this medium gives you more production value. Obviously, the pictures are crystal clear, but the extra sensitivity to shoot in low light gives the production a cleaner, more even effect." Dewey added that typical of any HD production, the quality of set construction and care in make-up are paramount. But, according to Dewey, these hurdles are surmountable after a short learning curve.</p>

<p>Another surprise was the success of shooting the HDV camera for behind-the-scenes moments. Dewey reports that the videographer and audio tech could assimilate into the background of the hotel environment and move quickly to capture the outbursts that make these reality series such a guilty pleasure.</p>

<p>"There is no way that the bigger cameras could have allowed us as much access to the contestants as we achieved with the HDV rigs," she said.</p>

<p>In advance of the production the VOOM technology group put the Sony HDV camera through its paces by comparing it side-by-side to the Sony 750. "What we saw from the field tests was pleasantly surprising," said Michael Lahey, head of the tech unit. "Close-ups were tight, and when isolated from a high bandwidth reference, were convincing as true HDTV."</p>

<p>(We'll be exploring the findings of our HDV field tests and go deeper into the editing integration of HDV with HDCam in a future column.)</p>

<p>Does HD make economic sense for reality producers? Much depends on the cost to a company of fielding HD cameras and gaining access to HD post-production suites. In this instance, VOOM HD Networks own the required complement of HD cameras and edit facilities making the uptick in cost a non-issue. If forced to rent the kits and suites, price could be problematic depending on budget constraints. HD tape is also about three times as expensive as SD stock.</p>

<p>However, farsighted channels, such as ULTRA-HD's partner, WE, know that soon the future will be HD. Most of WE's 2006 original production slate will be commissioned in high definition despite the fact that as of today the cable net is only available in standard definition.</p>

<p>With MTV Networks announcing MHD, its first channel in high definition, can it be long before the originator of the reality TV movement, "The Real World" takes the plunge into HD? We doubt it. <br />
