			<p>There is no doubt that the next "big thing" on the horizon to augment the HDTV viewing experience is three-dimensional (3D) display. To any who have seen IMAX 3D, the 3D effect is awesome. Immediately, one concludes that this is the way all motion picture images should be displayed. Other than the non-compatibility with systems using regular displays and the polarizing filters (those plastic glasses) one must wear, the same IMAX 3D technology would work well with today's HDTV system. (Other than that, Mrs. Lincoln, how was the play?)</p>

<p>However, a small company on the East Coast has demonstrated and patented an HDTV 3D system that is fully compatible with ATSC and does not require glasses - the "Holly Grail" of three-dimensional television. Further, the system does not require the use of arcane holographic or electro-mechanical oscillating screen elements.  Although I have not seen the display, the operational theory seems valid and reasonable. Here is a brief summary:</p>

<p>The 3DHD camera, like 3D movie cameras, is actually two cameras in one with two imagers slightly horizontally offset to generate the binocular signal. Because the horizontal scanning of both imagers is synchronized, the slight image offset causes the output of each imager to be displaced in time. Therefore, subtracting these two signals generates a composite signal that contains the binocular image information. (This is somewhat analogous to encoding stereo audio information by subtracting the right and left channel signals.)  The image binocular "difference" signal is easily compressed to a very low data rate and inserted in the ATSC digital stream with its own Program Identifier flag (PID).  Therefore, only one full bandwidth image is encoded and transmitted along with the difference signal.</p>

<p>That is the easy part.  Now comes the hard (and expensive) stuff - the display. Obviously, a standard (non 3D) receiver will respond only to the main (full bandwidth) signal and will produce a normal 2D image.  In a 3D receiver the difference information is decoded and added to the main signal to reconstruct the original two image signals. But, the real heart of this system is the physical display itself. It is actually a plasma (or it could be LCD et al) direct view system with approximately four million pixels. The display is driven by a frame generator containing twice a many sub-frames as a normal (2M pixel) display. One half of the sub-frames fires the pixels corresponding to the left image and, simultaneously, the other half of the sub-frames fires the pixels corresponding to the right signal.  </p>

<p>Now, if this were viewed on a display containing normally constructed pixels, the image would appear to the eye as "ghosts," with the two images varying in separation. (This effect would be similar to viewing a 3D movie without the grasses.) However, the physical construction of the pixels on this 3D system is anything but normal.  The salient intellectually property (IP) of this system is in the display pixel optics. Using micro-technology, mounted to the front of each pixel is a lens with a very short focal length. The lensed image from each pair (right and left) pixels is focused on special prisms (one for each two pixels) that mix the two images. The result is that the viewer sees a fully reconstructed 3D image without any special filters. In addition, there is no viewing "sweet spot," with the 3D effect present at wide angles and several feet from the screen.  Further, since the eye is not required to do image mixing, there is no eyestrain. </p>

<p>The downside of this system is, of course, the high present cost of the display optics. Each display must now be hand-built, requiring several hours. But isn't high initial cost not true with any new technology? These production problems will be solved, and soon HDTV will take on a new dimension and really get better.</p>

