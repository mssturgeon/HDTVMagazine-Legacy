				<p>As HDTV becomes increasingly popular as both a production and display medium, the subjective differences between motion picture and video originations become more apparent. This is because HDTV reproduces the image more accurately than SDTV, i.e., by definition HDTV is much more "transparent" than SDTV.</p>

<p>The motion picture film image has significantly different qualities than images produced by video cameras. There is not one specific factor that characterizes the difference, but a litany of them.  Interestingly, attempts by engineering texts to quantify and precisely define the "film look" have met with dubious success. This is little agreement as to the exact characteristics defining the film image. It is a "you know it when you see it" thing - very ephemeral.  Subjective characterizations such as smooth, muted, and surreal are identified with film as compared to video characterizations such as sharp, harsh and vivid.</p>

<p>There are many aspects of motion picture film photography, processing and production techniques that contribute to the "film look." Some are perhaps more significant than others, and all are exploited by directors and cinematographers to achieve a desired visual "mood," similar to the use of music. Great pains are taken in the movie-to-DVD authorizing and video retransmission processes to preserve these specific film production qualities. </p>

<p>It is important to note that the "film look" can be emulated purposely by video producers. Although most of the prime time HDTV productions are originated on 35mm film - not video, various cinemagraphic, lighting and postproduction techniques can be employed to give video originated productions a decided film produced quality.</p>

<p> Let's now take a look "under-the-hood" at these various "film look" characteristics as compared to video.</p>

<p>The "smooth" look can be attributed to several factors. Most importantly is the way the film grain structure defines image edges.  A close examination of film edge transitions indicates that the pixel brightness tends to drop off more slowly than video. Since the film grain structure is much more dense than the video pixel structure, the image edges are defined by the brightness gradients maintained by the dense grain structure. The video images, even with HDTV, are defined by a much coarser pixel structure. This means that the image edges can be artificially defined by the pixel structure, creating a much sharper edge transition cut-off. This effect is exacerbated with SDTV by excessive "peaking" or "sharpness" enhancement techniques.</p>

<p>Progressive scan, which minimizes the visible horizontal scanning line structure, and 3:2 pull-down, which virtually eliminates the film to video transfer temporal artifacts, also contribute to the "smoother" film-type-look.</p>

<p>The muted color look of film is due primarily by the reduced amount of color saturation permitted during film processing and production.  In the early days of color film, color was showcased by highly saturated images, as is evidenced by early Technicolor movies such as Gone With The Wind and The Wizard of Oz. Today, the cinematographers judiciously use color to add just enough realism. In addition, film color temperature is much lower than video, giving uncorrected film color a much "redder" tint. Thirdly, the video color gamut is somewhat greater than that of film. This gives video the capability of reproducing a slightly wider range of colors than film, adding to the color "snap" of HDTV video.  All of these factors (and a few others) combine to give film color a more muted, realistic look than video.</p>

<p>The high sensitivity of today's film stock gives cinematographers great flexibility in the use of low light effects and depth-of-field.  "Depth-of-field" refers to the distance objects appear in focus behind and forward of the primary object in focus. Most film cinematographers make full use of the depth-of-field capability; making sure objects in the background are highly defocused so that the viewer is directed only to the object of interest. This background defocusing adds to the overall film "soft" or "smooth" look.</p>

<p>Low light effects such as high-contrast highlighting, particularly of actors' faces, is a film technique not generally associated with video. Note that the majority of scenes of both today's theatrical and film-based productions (e.g., most prime time programming) are shot at very low light levels. Law and Order, West Wing and CSI are good examples of the low light effects used. These low light film and video/film-emulated techniques greatly add to the "film look."</p>

<p>There are other factors such as contrast, dissolve, polarization, grain, film stock, projection ratios and others too numerous to mention that contribute to the film look, but those described are the most salient. With today's films and electronic filters, video can be made to look like film and film can be made to look like video.  The "look" of the image is clearly a production choice, not a technological one. The ability of HDTV to faithfully reproduce the look desired by the production team is a very important attribute of HDTV. This means the full creative capability of both media can be had in every HDTV home. It only gets better.</p>

