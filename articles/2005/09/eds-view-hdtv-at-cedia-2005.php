<p>While the high-performance commercial DLP front projection units employ three separate 1920 x 1080 panels, the consumer versions of the DLP 1080p technology operate somewhat differently. Essentially, the light engine divides each frame into two sub-frames, with each sub-frame composed of half of the pixels required of a full 1920 x 1080 display. An electro-mechanical toggling mirror arrangement, synchronized with the appearance of each sub-frame, sequentially "builds" a full 1920 x 1080p display. The viewer's eye performs the integration much like occurs with the sequential images from the color wheel. The result is a very cost-effective, high performing single chip solutions for 1080p displays.</p>

<p>So, how does it look? Very good. Interestingly, one of the by-products of this new technology and its applied circuitry is a significant reduction of picture noise and artifacts compared with the 720p versions. This is important for two reasons: First, although most picture noise is not visible at normal viewing distances,it is resolved and interpreted by the eye as loss of resolution. Secondly, since virtually all sales conversations on the sales room floor occur within two feet of the displayed set, it is very easy to see and/or demonstrate the benefit of lower noise displays.</p>

<p>But DLP 1080p, while very good, was not the best. The best by any measurement was the <a href="/cgi-bin/ntlinktrack.cgi?http://www.sony.net/SonyInfo/News/Press/200302/03-008E/">SONY SXRD</a> technology. SXRD is essentially a highly refined version of LcOS (Liquid Crystal on Silicon) technology. Sony has (evidently) succeeded is overcoming the LcOS very critical production challenges to offer a very high performance and cost-effective design, letting all the inherent benefits of LcOS technology to be showcased.  </p>

<p>LcOS is a type of LCD application in which the incoming light to the panel is polarized, passed through a very thin liquid crystal layer and reflected from an aluminum mirror. Drivers located under or on the edge of the panel deliver a charge to each pixel, causing the polarization of the liquid crystal to change, thereby varying the amount of light exiting each panel pixel. The SXRD refinements of the basic LcOS technology optimize the inherent light modulation and throughput efficiencies of this technology. The result is a high contrast, artifact free, bright high- resolution image. Couple this with the many light engine driver refinements, and you have a real HDTV winner. It is getting better.</p>

