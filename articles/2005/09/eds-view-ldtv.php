<p>No, that's not a typo. I mean <i>LDTV</i> - Low Definition Television*. So, what is LDTV, and how is it relevant to HDTV? To answer that, let's first consider an interesting development now taking place in the wireless world. Cell phone providers, flush with 3G technologies, are beginning to offer television type services to cell phones. However, to consumers, this is a very costly way to get a few minutes of very low quality video. And, to the service providers, this is also a very costly way to use valuable spectrum. A much better solution is to <i>broadcast </i>the video programming, adding the receiving circuitry to the cell phone. In fact, Germany and Korea are in the process of adopting standards and systems to provide broadcast video services to cell phones (and other low priced portable receivers).</p>

<p>The beauty of providing such a broadcast service in the US is that the spectrum already exists - in the form of that now licensed to television broadcasters. Providing an LDTV service would allow a whole new revenue source to broadcasters, perhaps saving their business. By using one of the new digital compression standards, such as MPEG4 or Windows Media (WM), each station could supply as many as 25 channels of LDTV, if all of their spectrum were dedicated to this service. Yes, I am suggesting the broadcasters get out of the bandwidth demanding HDTV transmission business and focus on providing dedicated programming to portable LDTV receivers. HDTV would be relegated to those services that possess the necessary spectrum such as Cable and DBS.</p>

<blockquote>
