</blockquote>

<p>The beauty of this LDTV model is that nothing has to be invented - the technology exists and has been proven. Yes, a new broadcast standard would be required and FCC rulings made. But, with any kind of luck, it would not take a generation to do it. The difficulty would be in designing a suitable business model while maintaining some "free" service for the public. To be more succinct, here is a non conclusive list of some of the issues that must be address:</p>

<ul style="margin-top: 0in; margin-bottom: 0in" type="disc">
  <li><u>The compression standard</u>. Obvious candidates include one of the various versions of MPEG4 or Windows Media (XX). There are others, but those are the most technically and commercially developed.</li>
  <li><u>The modulation standard</u>. There is no reason to change the modulation standard from the present 8VSB system. The new forth generation VSB tuners provide sufficient multi-path and sensitivity performance to allow highly reliable reception in the grade "A" and "B" coverage areas of most TV transmitters.</li>
  <li><u>The legacy issue</u>. It may be necessary to maintain one low bit-rate MPEG2 multiplex stream for a fixed period of time in order not to disenfranchise legacy receivers with only MPGE2 capability. This multiplex would not be part of the LDTV economic model, allowing "free" TV for the legacy receivers.</li>
  <li><u>The economic model</u>. I see the networks and local station broadcasters in a dual roll: as a program supplier to both LDTV marketers and to Cable/DBS (etc) service providers. The model servicing Cable/DBS would remain essentially the same as presently established with re-transmission and "must carry" agreements. The LDTV service would be marketed through the cell-phone service suppliers using a customer subscription model, with the broadcasters receiving a percentage of the subscription revenue and all of the advertising revenue.</li>
  <li><u>Program content</u>. Most of the programming would need to be produced in short-format form in order to efficiently accommodate the time frame available to the average mobile viewer - perhaps 15 to 20 minutes. These would include news, sports news, weather, traffic, serials, games et al. Longer format entertaining programs could also be available, but these would be in the minority. In addition, the broadcasters' "primary" program feed to Cable/DBS could be offered. A free "{emergency" stream also could be included in the package, allowing every LDTV device the capability of receiving local homeland security information without a subscription. All of this specially purposed LDTV programming offers a complete new genre of television program creative opportunities.</li>
</ul>

<p>There are, of course, many other factors, but these are the most important issues that must be addressed for LDTV to be successful as a local TV broadcasting service. One thing, however, is for sure. If the local TV broadcasters do not seize of this opportunity, other broadcasters successfully will. These others include, but not limited to: satellite radio, HD radio, and the cell phone service providers themselves. In any regard, LDTV could be a net plus for HDTV.</p>

<p>Ed</p>

