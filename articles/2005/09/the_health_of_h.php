				<p>This article will appear in the next edition of Highdef.org Magazine. You can subscribe to this publication at no cost by going to <a href="/cgi-bin/ntlinktrack.cgi?http://www.highdef.org">www.highdef.org</a>.<br />
________________________________________________________________</p>

<p>The health of HDTV could hardly be better. Sales are up 45% over this time last year. Fully 11% of all displays sold in the second quarter were HDTV.  Europe is now entering with lower start-up consumer and infrastructure cost than we did (though they have a tough bandwidth issue for terrestrial). Korea and Japan are booming with 3 more HD channels just licensed from Japan's BS satellite. China is gearing up to deliver 35 million HDTV sets in time for their Olympics. Both Argentina and Brazil are committed to digital television and will make their system choices by January, 2006. Zenith is showing Congress just today a $50 ATSC decoder box for low cost completion of the transition. Best of all is that the traditional enemies are nearly at peace with one another with only cable carriage as the last bone of contention. HDTV has become a world wide phenomenon with no end in sight.  </p>

<p>The best news is that displays are not only holding their own but have now caught up-actually exceeds in performance what the ATSC standard can support. It was the other way around for years. The ATSC HD signal had more in it than the display could deliver. Dr. Joe Flaherty (CBS, Inc), the undisputed father of HDTV in the U.S., was frequently heard saying in his speeches that "HDTV is better than it looks." He meant that there was more in the signal than could be seen on the (then) display. Now with that reversed new pressure to improve the signal has arrived. Where will we see a 1080p 60 signal? The ATSC is in a quandary. When the standard was being established MPEG 2 did not support 1080p 60 and the ATSC wanted to keep to the specs of MPEG 2. They would like to propose something but no one is to hold their breath.  It is easier for cable, but the demand for new boxes would have to be strong. Telephone triple play operators have some edge as their business is still forming. The new High-Definition DVD can also deliver that signal, and should.</p>

<p>"It is always optimum to reproduce video material in the same format in which it is originated." advises TV designer Ed Milbourn. "Obviously, the optimum production and delivery format for 1080p is with a 60 per second frame rate." </p>

<p>While some material will be produced and delivered at 1080p 60fps most of the HD in the foreseeable future will be in the ATSC standards of 1080i 30fps or 1080p 30fps. That means that the display must convert the 1080p 30fps material to 60fps via some sort of up-conversion (or line interpolation) process in order to add another 1/60th of a second's worth of 1080 lines to emulate 60fps.<br />
 <br />
"Although Interpolation algorithms have greatly improved," says Milbourn, "none of them are perfect. The most common problem of badly designed up-converters is the introduction of horizontal movement artifacts - the dreaded motion smear. The newer up-converter algorithms have enough sophistication, memory and bandwidth to produce extremely accurate interpolated lines." </p>

<p>All digitally switched display--DLP. LCoS, SED, LCDs and plasmas-now offer "full HDTV" 1080p models. They bear some price penalty (about 20% over 720p and 1080i sets), but that will disappear. As manufacturing yields come up displays roll off the production lines just about briskly as do lesser displays. The big money (many tens of billions) is riding on big displays of over 60 inches. The manufacturers are driven to 1080p by the desire to sell larger screen sizes. The higher the resolution, the lager can be screen size in a given room. In the final analysis the drive to "true HDTV" about selling square inches of viewable picture. </p>

<p>Many question why they should buy a display that exceed the ATSC standard, (which limits HD to 720p 60 or 1080i 60)? Isn't something that will display 1080i good enough?  Pete Putman, noted display analysts, tells buyers "1080p is a waste of your money".  </p>

<p>Not all agree.  "I've been buying audio/video gear for 40 years; and I'm sure I've never bought anything that someone didn't think was a waste of money." says a loyal HDTV Magazine reader.<br />
</p>
