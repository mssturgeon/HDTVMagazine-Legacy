				<p>Video over IP, telephone over IP, two way or more teleconferencing (even families will be able to use this), and high speed data over IP is a UNIFIED business often called the Triple Play, which both cable and telephone companies will compete for. As time goes on those companies will be harder and harder to distinguish apart in your minds as to what got them started -- telephone or cable -- for they will have exactly the same competitive functions, with some bells and whistles to call their own, but the basic functions will be identical. They will use the same hardware to deliver anything you will buy in digital form.  Once you are in IP you no longer have the same traditional head-in to connect to nor cable program packaging.  You will likely go directly to the owners of programming --the studios, who are becoming themselves distribution hubs for their own programs---at least as long as you like them and buy them.  Due to the interactive feedback -- which operates like instant polling--they may even do better at learning and then delivering to you what you want.</p>

<p>The beginning of this model of studio/hubs is in place as each "hub" (or what we call today the TV networks) owns a motion picture studio.  ABC/Disney, CBS/Paramount, NBC/Universal, Fox/Fox Studios, and, of course,Sony owns two studios and libraries - Columbia and MGM (if that deal has gone though).  The "common carrier" of the last mile away from the fiber backbone is the company that rents you the bandwidth and you may call them your cable company or your telephone company...and your kids will grow up not being able to tell them apart. Was Comcast a telephone company or was it a cable company? "Gee, I can't remember, dad. That was in the olden days."</p>

<p>Whatever you receive over that rented bandwidth comes by your choice, just as it does for web surfing.  Instead of pages, it's programs. We have begun our own little hub with Rodolfo's program ready for you to view anytime you feel like it.</p>

<p>The cable model is searching for new "holds" on program selling and distribution and they are trying to find reasons why you would buy programming packaged by them instead of individually from a massive media server in China, for instance. Why would you go to Yahoo today other than to get what value they add to your web experience? You may continue using your present cable system as your home page -- they will encourage that with some kind of coupons -- and you they will undoubtedly represent themselves as being the portal to your favorite video entertainment, as Yahoo is to all of those services you see listed on their page.  If you buy a program through them, it's quite like buying a Book from HDTV Magazine.  But that book is actually shipped by Amazon.com. We get a little commission for having attracted you to our site and made some convenience for you to return and continue buying books from us, priced exactly the same as had you gone to Amazon.com. We may find sponsors who would encourage your presences too, as will the cable and telephone companies do also.</p>

<p>For local broadcasters the game is up. In an IP world who do you insists carries local stations? Certainly it cannot be what used to be the cable company and is now your IP company.  Must carry by whom? The locals become no more than another competitor in the world wide web jungle of video competitors and their value added is that they may still tell you who shot your neighborhood up or when the school board is meeting with the parents.  Those things you can search for and instantly be advised by static page or video over IP.</p>

<p>This is the inevitable world ahead. Everything is already in place and it is only human momentum and a few last mile entries that keep it from being already the way things are. There is so much fiber now that to think this vision I present will clog the lines is laughable for at least 50 years, perhaps 100. There will always be advances in the efficiency of fiber data carriage (capacity) and there will be new efficiencies in compression and storage. The more technically "leak proof" the IP network is the less bits must be devoted to overhead and error correction. Also, the media you call for by demand will be able to determine how much bandwidth you are buying and using, i.e., that which is suitable for 480i, 480p, 720p, 1080i, 1080p, or even 2160 P! You do some of that today when listing in your video player on your computer what speed you use for downloading.</p>

<p>Satellites will struggle to maintain their business model and will increasingly promote rural living because those in the urban wired world will have all they can digest at the lowest possible cost. The rural will still suffer from a scantily wired infrastructure. Of course, wireless will help in sparsely populated regions and insure that the interactivity you will learn to love...to a point...will be there too.</p>

<p>Sports will be the only mainstay of package cable programming but the NFL will also "broadcast" via fiber IP HDTV and would be thrilled to see that you drop by their web page and order the game today. ESPN may actually stay in business as an aggregator of real time programming which is more efficiently broadcast than it is streamed on demand.</p>

<p>It's a brave new world coming and the only thing that will stay the same is the image for the 21st Century, which will always be called, no matter how much higher it goes than we have today, HDTV.</p>

