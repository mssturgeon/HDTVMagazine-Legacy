<p><strong>U.S. COMMUNICATIONS POLICY IS A SUCCESS, SAYS SHAPIRO</strong> <br />
Points to Marketplace Successes, Increasing Consumer Choices <br />
Lays Out Goals for Continued Success</p>

<p>Arlington, Va., May 13, 2005 - U.S. communications policy today, "albeit imperfect and even messy, is a success" and history will judge well the radical changes in society brought about by the phenomenal progress of technology during our era, said Consumer Electronics Association (CEA) President and CEO Gary Shapiro in a speech delivered this week. Shapiro gave his comments as the keynote speaker before a breakfast held yesterday by the Federal Communications Bar Association in Washington, D.C.<br />
 <br />
"It has become fashionable to say the U.S. is not doing well in terms of communications policy," said Shapiro."But I submit to you, the U.S. communications forest is growing, robust and stunningly beautiful. Sure, we have some trees that need pruning - but we often are too close to objectively see the situation."<br />
 <br />
Shapiro noted that technological innovation is creating a better world for today's citizens and will lead to an even better future.<br />
 <br />
"It will be a better world, a connected world," Shapiro predicted. "A world where culture and shared interests transform local, regional and national boundaries so the higher ideal of human potential and spirit can be realized. And for all of us I hope, it is a world where the communications our technologies allow, inspire, entertain and inform, while reducing the chance of misunderstandings and conflict.<br />
 <br />
"Every day, we are getting closer to that ideal, as our technologies reduce energy costs by allowing telework and remote access," he noted.  </p>

<p>"These technologies encourage interaction by creating venues for common ground and encourage efficiencies by allowing real-time market information and customer interaction."<br />
 <br />
Shapiro stated that America's form of government has played a key role in the nation's technological success. He pointed to the interplay of interests along with a forum that "crystallizes the differences at the edge and provides healthy give and take leading to the creation of laws."<br />
 <br />
"Our government has done it right," stated Shapiro. "Through our checks and balances we have avoided regulation or taxation of the Internet and have encouraged competition among broadband providers and deployment of new wireless technologies and satellite radio services. Even the shift from analog to digital broadcasting had been prodded along by a government-industry partnership appropriately deploying bully pulpit leadership and 'hoe downs' with the stick of the law. Indeed, the U.S. has the world's best HDTV standard and Americans own more than 16 million HDTV products."<br />
 <br />
As proof, Shapiro pointed to the marketplace and the broad array of technology and communications offerings expanding almost daily.<br />
 <br />
Despite this success, Shapiro contended that it is important to plan for the future. To this end, he suggested six goals for national communications policy:<br />
 <br />
1. Every American should have broadband access of at least 1 mbps.  <br />
 <br />
2. We must complete the shift to digital.<br />
 <br />
3. We must encourage competition among alternative media providers.  <br />
 <br />
4. We need to follow the telephone model of competition at the edge of the network. "With open standards there will be competition among technology providers allowing consumers choice in which products they buy," Shapiro stated.  <br />
 <br />
5. We must protect consumer rights to manage content and shift it in time and place.  <br />
 <br />
6."We must protect the First Amendment," said Shapiro. "We must honor Americans who died on battlefields and resist content regulation no matter how offensive we may find it." <br />
 <br />
Shapiro urged the attendees to be vocal advocates to help reach these goals.  <br />
 <br />
"We all have a role as Americans to participate," he urged. "Industry and company advocates must present their views.Journalists must not only accept advocacy, they must dig and find the truth. Policymakers must agree on the goals and figure out what's best."<br />
 <br />
In conclusion, Shapiro said, "I believe that communications technologies create the path to democracy and self-determination.  Tyranny only survives in silence. And as we transition to the digital world, it is the increasing array of choice, services and information that technology offers which will make it a better world.<br />
 <br />
"Ladies and gentlemen, join me in celebrating our nation, sharing a future and creating a digital world."</p>
