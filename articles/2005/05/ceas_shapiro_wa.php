<p>CEA'S SHAPIRO URGES CONGRESS TO SUPPORT A HARD DEADLINE TO END THE BROADCAST DTV TRANSITION<br />
Education and Market Reality Play Key Role in DTV Success New CEA Research Underscores Declining Market Share of OTA Television </p>

<p>Arlington, Virginia 5/26/2005 </p>

<p>A hard deadline to end analog television broadcasts will help "foster the creation of new, high-skill jobs and it will promote America's technology leadership in an increasingly competitive world," said Consumer Electronics Association (CEA) President and CEO Gary Shapiro in testimony delivered today before a congressional committee. Shapiro made his comments before a hearing held by the House Committee on Energy and Commerce's Subcommittee on Telecommunications and the Internet regarding a staff discussion draft of the DTV (digital television) Transition Act of 2005. </p>

<p>In his testimony, Shapiro advocated that a hard deadline will provide certainty to consumers, manufacturers and all others involved in the nation's transition to digital television. He stated, "It is right for consumers, it is right for innovation and it is right for America's national security." </p>

<p>Shapiro reported that DTV continues to be a strong marketplace success. According to the latest factory-to-dealer DTV sales released today by CEA, 2.3 million units have been shipped through April of this year. These sales figures mark a 36 percent increase over the same period 2004 in unit sales and a 16 percent increase in dollar sales. CEA Market Research projects that 15 million DTV units will be sold in 2005 alone. </p>

<p>"Most relevant to the current debate, consumers now can choose from 200 television models that include over-the-air ATSC tuners," added Shapiro. </p>

<p>CEA forecasts that 9 million DTV products with tuners will be sold this year, 16.7 million in 2006, 27 million in 2007 and 33 million in 2008. "By 2009 we will have sold 97 million DTV tuners, and we estimate that digital over-the-air tuners will be found in 86 percent of American homes," Shapiro stated. </p>

<p>With this marketplace momentum in mind, Shapiro urged Congress to consider market realities as it debates steps to facilitate the end of the transition to DTV. He pointed to new research released by CEA that underscores the declining market share of over-the-air broadcast television. </p>

<p>CEA's new survey found that of the nearly 110 million American homes with at least one TV, 87 percent are receiving local and national broadcast programming via cable or satellite. This data is in-line with statistics provided by cable and satellite providers, Nielsen Media Research and in filings submitted to the Federal Communications Commission (FCC) by individual broadcast networks. </p>

<p>"This means that if the analog cut off occurred today, less than 13 percent of the U.S. population of 110 million TV households would not have access to a broadcast signal," Shapiro noted. </p>

<p>CEA's survey also found that in the 96 million households that have cable or satellite, only 14 percent use an antenna on their second, third or fourth television set. More, fully three-quarters of "antenna-only" homes indicated they are willing to buy a new TV, buy a $50 decoder or subscribe to cable or satellite once analog broadcasts are ended. </p>

<p>"While an analog broadcast cut-off is important for our nation, it will have little practical impact on the viewing habits of the vast majority of Americans. </p>

<p>"At the same time, some consumers may be adversely affected by a hard date. That's why we respect and understand the interest in creating a program whereby those viewers would have access to low cost digital to analog converters," Shapiro added. </p>

<p>Shapiro also commented on other provisions in the current staff draft. He expressed concerns about the draft bills requirement that the FCC move up the deadline for the inclusion of over-the-air tuners in 13- to 24-inch sets from July 1 of 2007 to July 1 of 2006 - a full year before the original deadline set by the FCC and nearly 2.5 years before the 2008 hard deadline. </p>

<p>"We are concerned that, if implemented, such a requirement would severely reduce the retail market for these sets," said Shapiro. "A July 2006 date could result in severe cost increases that the marketplace cannot sustain." </p>

<p>Shapiro also urged the committee to lengthen the amount of time manufacturers will be required to include educational labels on analog televisions to inform consumers about the impending end date for analog broadcasts. In addition, he applauded provisions in the draft bill that address the issue of high definition television (HDTV) signal degradation by cable operators and set a final date for the FCC to issue final broadcast channel allotments for DTV signals. At the same time, he called on the committee to step up broadcasters' obligations to educate their viewers on the DTV transition. </p>

<p>"In light of our own aggressive consumer education efforts, CEA has been disappointed with the paltry level of DTV consumer education offered by the broadcasters to date, especially the almost complete lack of broadcaster-sponsored public service announcements (PSAs)," stated Shapiro. </p>

<p>He noted that CEA has been chosen by the National Association of Consumer Agency Administrators (NACAA) to receive the "Achievement in Consumer Education" (ACE) Award. NACAA is recognizing CEA for its work with the FCC to educate consumers about digital television. </p>

<p>In conclusion, Shapiro applauded the committee for its efforts. "Setting a realistic date certain for the end of analog broadcasting and the recovery of the analog spectrum for new purposes is the right thing to do," he said. "I pledge CEA's continuing commitment to working with this committee and other stakeholders to ensure an expedited and consumer-friendly transition and a prompt return of the analog broadcast spectrum. </p>
