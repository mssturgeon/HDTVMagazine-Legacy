			<p>It is interesting to note how the motion picture industry has been able to technologically "re-invent" itself to provide audiences with ever increasingly compelling movie-going experiences.  The litany is long, starting with silent monochrome "flickers" and adding "talkies," color, wide-screen, digital sound, surround sound, THX, 70mm, etc.  It is also interesting to muse how the television industry has followed with similar technological advances to enhance the home viewing experience.</p>

<p>A little heralded, but seminal event occurred last July with the adoption by a consortium of movie production houses of the Digital Cinema Systems Initiative (DCI) specification for the electronic digital distribution and projection of motion pictures.  The consortium consists of Disney, Fox, MGM, Paramount, Sony Pictures Entertainment, Universal and Warner Bros. Studios.  The DCI initiative opens the door for the mass deployment of electronic distribution and projection of motion pictures.  </p>

<p>But, the real news is the "killer app" for this technology - digital distribution and projection of 3D movies.  Digital distribution is significant enough, providing the movie audience with consistently high quality images and enabling the producers to distribute movies at significantly lower costs.  But 3D - that's another story.</p>

<p>This is not your daddy's gimmickry, eye-straining novelty 3D of the 1950's, but an effect that truly enhances the motion picture viewing experience.  It is the difference between watching a movie and truly experiencing it.  True, no technology can overcome poor screen plays, talent and production qualities, but certainly the addition of 3D to an already excellent production can elevate the movie entertainment value immeasurably.</p>

<p>To start the digital 3D ball rolling, this year Walt Disney Productions and Dolby Laboratories elicited the 3D projection technology of Real D Inc. to allow viewing the Disney animated production, Chicken Little, in 3D.  Although there is no motion picture 3D projection standard for DCI, certainly Real D has a tremendous head start thanks to Disney and Dolby's incentives. These incentives effectively subsidized the $135,000 per screen cost of adding DCI and Real D technology to 88 screens in North America.  Indeed, the economic model associated with DCI that spreads the costs of digitizing movie auditoriums, based on distribution cost savings, is as significant as the DCI technical specification itself.</p>

<p>Although the DCI specification outlines several digital distribution methods - including physical media (hard disc drives), satellite and terrestrial broadband- currently the media utilized is physical.  The delivered disc drive data are loaded to local storage media, and the material is prepared for projection, i.e. play lists assembled, interstitials added etc.  Security management includes the periodic reception of a separate "license" (key), which enables and renews the decrypting process.</p>

<p>The Technicolor Digital Cinema division of the Thomson/Technicolor Corp., the premier supplier of film replication and distribution services for the motion picture industry, has recently secured agreements with virtually all of the major Hollywood production houses to supply digital service to motion picture theaters.  Under these agreements, Technicolor Digital Cinema will equip up to 5000 theaters with DCI-compliant projection capability within three to four years.  Strategically, Technicolor Digital Cinema plans to equip up to 15,000 theaters in the US and Canada within the next 10 years.</p>

<p>Technically, the normal (2D) digital image consists of a 2048 x 1080  (1.89:1) pixel array projected at 48 fps.  However, for the Real D 3D system the projected frame rate is accelerated to 144 fps to provide alternating 72 fps right/left images from one projector. The high frame rate is necessary to eliminate visible flicker.  A special polarizing filter placed in front of the projector alternately polarizes each frame.  The viewer wears polarized disposable glasses to recover the right/left images and thus produce the stereo effect.  Because the polarizing process attenuates light, a special high gain screen is utilized to ameliorate the light loss.  The screen is fully compatible with 2D digital projectors.  </p>

<p>No doubt, digital projection, with an increasing amount of content in 3D, is the future of the motion picture theater experience.  At least two more digital 3D movies are planned for 2006 - Monster House and Meet the Robinson's.  Although cartoons are not my taste in movies, I was impressed with Chicken Little in 3D.  So, for a glimpse of the future of visual imaging, and a delightful entertaining experience, grab your family for a holiday treat and see Chicken Little  in 3D.  Then you will understand why Chicken Little was right.<br />
</p>
