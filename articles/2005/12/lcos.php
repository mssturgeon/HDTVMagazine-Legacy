<p>The basic LCD operation is illustrated in Figure 1.  Note the light from an external light source (i.e. lamp) passes first through a polarizing filter.  This filter allows the passage of only those light wave fronts oriented in only one direction, say vertical.  The polarized light then passes through the LCD.  When a voltage is applied across the LCD, the liquid crystal material "twists" up to about 90 degrees, effectively blocking the passage of the vertically polarized light.  The amount of light that is allowed to pass is directly proportional to the voltage applied across the liquid crystal pixel.</p>

<p>The light then passes through a second polarizing filter identical to the input polarizer.  This output polarizer, sometimes called an "analyzer," further attenuate any "off axis" light that may have passes through the LCD.  The analyzer thus acts to increase the contrast and linearity of the LCD action, but with some loss of brightness.</p>

<p>Figure 2 illustrates schematically the structure of an LCD pixel array.  Note that a driving transistor occupies a large area of each pixel surface.  Typically, this driver and its associated circuitry can consume up to 50% of the pixel surface area.  The percentage of LCD material on each pixel is referred to as the "fill factor."  Clearly, the lower the fill factor, the less light the pixel can pass, and the lower the efficiency of the display.</p>

<p><br />
 <img alt="Fig2lcos.jpg" src="http://www.hdtvmagazine.com/articles/images/mt/Fig2lcos.jpg" width="342" height="283" /><br />
Figure 2, LCD Pixel Array Structure</p>

<p><br />
Now, let's take a look at LCoS.  LCD and LCoS share the operational capability of liquid crystal to modulate light intensity, but LCoS applies this capability in a much different may.  Referring to Figure 3, note that the LCoS device utilizes reflected light instead of influencing light transmitted through it, as with LCD.  LCoS is thus referred to as a "reflective" device  </p>

<p>The individual mirrors that reflect light back through the liquid crystal layer define the LCoS pixel structure.  The liquid crystal material reacts to a charge between the aluminized mirror array and a transparent conductive layer deposited on the top of the liquid crystal material.  The driving electronics vary the strength of the charge on each pixel mirror, causing the polarized light to shift polarization as with LCD devices.  The output light is directed to the projection optics and displayed on the screen.  As in the case of LCD, three separate devices and associated optics are employed, one for each primary color (red, green and blue). </p>

<p><br />
 <img alt="Fig3lcos.jpg" src="http://www.hdtvmagazine.com/articles/images/mt/Fig3lcos.jpg" width="408" height="355" /><br />
Figure 3, Basic LCoS Pixel Structure</p>

<p><br />
LCoS has two primary advantages over LCD:  First, due to the fact that the pixel driving circuitry is located on the edge of the chip, not within the pixel structure, a much higher fill factor can be obtained.  The LCoS fill factor can be as much as 90% or greater, greatly increasing device efficiency.  This means chip sizes can be smaller than LCD for a given number of pixels, thus less expensive.  Conversely, a given chip size will allow brighter images, permitting a given light engine to be "scaled-up" to accommodate larger screen sizes while maintaining high brightness levels.</p>

<p>Secondly, the IC fabrication technique employing multiple layers etched and bonded on a silicon backplane is very similar to that required for manufacturing LCoS devices.  Therefore, existing chip fabricating processes can be adapted to manufacturing LCoS devices.   This fact not only minimizes the costs of LCoS fabrication, but facilitates the use of very small layers of material, further increasing performance.</p>

<p>However, obtaining commercial viability and desired performance levels have not been without difficulty.  To data, yields have been low due to problems achieving consistence performance.  In addition, heat and time dependent problems have compromised long-term reliability.  But, because the advantages of LCoS are so significant, developers have doggedly pursued solutions to these problems.  It appears, finally, success has been achieved.</p>

