			<p>The digital/HDTV transition now in progress by the television industry is arguably (certainly by that industry) the most complex ever experienced, though likely not since the evolution of radio communications from Morse coded pulses to commercial broadcast radio.  That took about 15 years and with a lot of glitches along the way, But they were overlooked and corrected as the excited public knew that, glitches aside, the result would be a revolutionary, increasing improved public service.</p>

<p>We are all aware of the interim and subsequent radio/television industry transitions:  from wireless telephony to commercial broadcast radio; "picture-radio;" all electronic B/W television; color television and now to HDTV digital television.  This latter transition step has taken almost 15 years, too, and it remains in its adolescence.  And, as we all know, teenagers tend to stumble a bunch, and, we as parents, largely ignore the minor bumps, knowing that it is all part of moving to a mature adulthood.  So it should be with the television industry's vast, complex transition to digital/HDTV service. </p>

<p>One key element of this particular fundamental world wide broadcast television communications revolution is that it is actually a double transition of - analog to digital and standard definition to HDTV picture and sound formats.  I think it is interesting to take a (very) high-level look at what the US broadcast industry, particularly the local providers, have had to deal with over the past 12 years of so to get us the quality of service we expect (HDTV "adulthood"). </p>

<p><strong>1)	Obtaining digital licenses</strong> - This involved complex calculations and equally complex applications for channel assignments, power levels and antenna parameters, some of which are temporary and must be changed at the time of the 2009 official transition date. </p>

<p><strong>2)	Obtaining initial equipment to get on-the-air digitally within the specified FCC interval</strong> - These series of tasks in many cases required extensive tower work or new towers, transmitter and antenna acquisition, mounting, alignment and testing.  Also, ATSC encoders had to be obtained, programmed and tested.  Many of these early encoders suffered unacceptable performance from either poor compliance with ATSC standards, slow engineering application learning curves and/or poor design.  In short, many did not work, with audio and video bugs too numerous to mention.  In addition early DTV receivers suffered from similar compliance problems and poor tuner performance, making the situation even more "dicey." Many times the only "receiver" the broadcasters had was a spectrum analyzer that confirmed they were indeed "on-the-air" with a digital signal.</p>

<p><strong>3)	Establishing the digital transmission commercial plan</strong> - Overlaying and indeed preceding all of the technical aspect of the digital transition was the establishment of the business plan and project schedules.  This involved not only key fundamental philosophical decisions (such as whether to initially design for full 1080 HDTV, to migrate there in steps or not at all).<br />
[An even more fundamental commercial debate continues today as broadcasters expand their programming assets to various multimedia options and ponder how they can best optimize the value of their allocated digital spectrum.]</p>

<p>    <br />
<strong>4)	Obtaining initial digital programming</strong> - There was very little initial digital program material available from the networks to feed the digital encoders, virtually none in HDTV.  Most initial digital material was simply digitized analog feeds.  HDTV programming was either up-converted and reformatted analog feeds and/or some digital material available for early HDTV tape players and digital servers.  Although full of glitches, at least something was becoming available to allow initial HDTV receivers to be demonstrated at retail with off-air video.  </p>

<p><strong>5)	Designing and building the digital/HDTV studio/transmitter infrastructure </strong>- <br />
In most cases this meant (and continue to mean) a complete overall of the entire control room technical structure to incorporate digital switching, cabling and storage, first to digitalize the analog infrastructure, then to embrace HDTV origination.  This has been a huge financial and technical challenge particularly when considering cameras, text/weather graphics displays, switchers, editing, lighting, audio/video monitoring equipment and studio set design.  Clearly, this aspect of the broadcasters' digital upgrade continues to be a work-in-progress.  </p>

<p>Add this to the fact that similar upgrades are going on at the network level as well (in most cases slower that at the local level), and the opportunity for numerous glitches increase geometrically.</p>

<p><strong>6)	Migration to HDTV ENG Remote Coverage </strong>- The cost reductions of remote HDTV equipment has made possible a viable migration path to local and network electronic news gathering in HDTV.  However, remote HDTV bandwidth costs remain high, so many are using various hybrid 16x9 SD and HD approaches in a mix or both live, stored and file server transmission schemes.  Considering the heavy real-time editing demand requirements or ENG coverage, many glitches can be expected as the equipment is improved and the learning curve is increased. </p>

<p><strong>7)	Etc.  The above 6 items are apologetically gross oversimplifications and omissions.  </strong>                      </p>

<p>We must not forget all of this is happening while the broadcasters - network and local; satellite and cable - are maintaining an analog/SD service to the receivers.  I suppose one could relate this digital/HDTV transition as analogs to building both a 757 and 787 while maintaining a 737 all in flight, in formation, and on schedule.<br />
  <br />
The combined broadcaster/CE industry is only about 10% up the transition curve to the consistent production/presentation quality levels that we have been accustomed with NTSC.  But with every glitch and growing pain, there seems to be a much more rapid improvement in the quality and quantity of this great cultural phenomenon we now know as HDTV.  Hail to the glitches!</p>

<p>Ed<br />
