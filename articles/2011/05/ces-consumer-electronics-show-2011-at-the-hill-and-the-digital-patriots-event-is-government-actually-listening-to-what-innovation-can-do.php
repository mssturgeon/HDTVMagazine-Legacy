</p><p>If you were not one of the 149,000+ attendees of the recent Consumer Electronics Show at Las Vegas, but you are in Congress and did not have the chance to be among the one hundred government leaders mentioned above, you had the chance to receive a tailored walk-through of some of the main CES introductions at the <a href="http://www.ce.org/Events/default.asp?siteUrl=%20http://speaker.ce.org/index.cfm?do=cus.eventSchedule|style=0|meetingID=1444|meetingContentType=meetingSchedule">CES at the Hill</a> event, right in your backyard (but in a tent) in Washington D.C.  
