</p><p>And as I do almost every year, I am heading to Washington to attend both events.  After almost 30 years of driving to D.C. in the rush hour when I was in the computer industry I was certainly not eager to make the trip.   
</p><p> According to the CEA "<em>31,677 industry professionals from outside the U.S. attended the 2011 International CES January 6-9, 2011, in Las Vegas, Nevada. Up 30 percent from last year, international attendance at the 2011 CES set a new record for the show's 45 year history.  An independent audit, performed by Veris Consulting LLC, confirms CES' status as the world's largest consumer technology tradeshow and North America's largest annual tradeshow of any kind. Overall, the 2011 International CES welcomed 149,529 technology attendees during its four day run</em>."
</p><p>
 </p><p><span class="caption right" style="width:436px"><img width="434" height="327" src="http://www.hdtvmagazine.us/articles/images/051311_0458_CESConsumer3.jpg" alt=""/><br />RCA portable ATSC and Mobile DTVs, shown at the CES at the Hill</span>CES 2011 had more than 1.6 million net square feet of exhibit space for more than 2700 exhibiting companies to launch an estimated 20,000 new products.  International attendees represented 140 countries, aside from the U.S., the top 10 countries represented in terms of attendees were: Canada, South Korea, Japan, China, United Kingdom, Mexico, Taiwan, France, Germany and Brazil.
</p><p><span class="caption left" style="width:347px"><img width="345" height="260" src="http://www.hdtvmagazine.us/articles/images/051311_0458_CESConsumer4.jpg" alt=""/><br />Google TV at CES at the Hill</span><span class="caption right" style="width:297"><img width="295" height="205" src="http://www.hdtvmagazine.us/articles/images/051311_0458_CESConsumer5.jpg" alt=""/><br />Samsung at CES at the Hill</span>The CEA added "<em>More than 40,000 top decision makers and senior level executives attend the International CES for its unparalleled networking and business opportunities. The Veris audit confirms that 43 percent of 2011 CES attendees are senior level executives, on par with last year. Presidents, CEOs and/or business owners made up 16 percent of attendees. Nearly one third of all attendees are the final decision makers when it comes to new product purchases and partnerships with new companies, with 97 percent identified as having buying decision influence. More than 11,500 attendees represented companies with more than $500 million in total annual sales, up 37 percent over 2010 CES</em>.
</p><p><em>Leaders from diverse business areas including entertainment, retail, education, engineering and financial services attend the International CES, according to the Veris audit. More than 12,000 retail buying organizations, 6,500 manufacturers and 3,500 engineering companies came to the 2011 CES. Additionally, more than 9,500 attendees from the content development and entertainment industry came to CES' inaugural year of the Entertainment Matters program, providing entertainment executives the chance to  experience the products and technologies that deliver their entertainment to the consumer."</em>
