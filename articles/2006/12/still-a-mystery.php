				<p>Still a mystery ... </p>

<p>USA Today said last week that a Frank N. Magid Associates' Report confirmed that consumers are still "confused over what HDTV is and whether it costs extra to get programming" (in the HD format). The study found that 47% of consumers buying an HD set now planned to watch TV programs in HD, versus 63% two years ago. Moreover, 30% of HDTV owners have yet to add HD service through their cable or satellite provider, and those that have, complain that HD stations tend to occupy the farthest reaches of the channel range (Channels 800 and up, etc.).    </p>

<p>Commentary ... </p>

<p>The success of DTV has always depended upon a voluntary cooperative between government, consumers, the consumer electronics industry, broadcasters, cablers, satellite operators, and retailing with each faction pulling their own weight at just the right time. If the confusion that is cited in the Magid report is left unchecked there is a very real threat that this holy balance could crumble, which could lead to "the bloom falling off the rose". For one, the 30% of HD owners who are not attached to any HD signals are ineffectual promoters of the format. That is different from the days when early adopters of Color TV did everything they could to get high performance out of their systems and show those glorious TV pictures to as many as possible, as often as possible. The threat to accelerating a viral marketing experience (the fast spreading of positive word of mouth advertising)) comes when consumer confusion clogs the private "megaphones" hailing the coming of HDTV. </p>

<p>This 30% who are not hooked-up to an HD source is the same percentage as quoted from another report published earlier this year.  Zero progress has been made between reporting periods which clearly illustrates that the education needed to smooth the path and optimize HDTV programming take rates has failed. As much as CE retailers like to claim they are the consumer educators the report suggests something quite different is going on at the grass roots level. </p>

<p>Another recent report said that most buyers of HDTV have spent on average two and one half hours of research on their purchase. That research was mostly done online. But 30% of US households are still not online. What to do about them? How do they educate themselves?</p>

<p>The good news in the report is the fact that despite the confusion a lot more digital sets have still landed in American homes.  Those sets not hooked to HD cable or satellite are hungry candidates for over-the-air signals. The darker side is that this weakness will have to be dealt with one way or another.  Unfortunately it will invariably lead to a higher cost of servicing the remaining market. Education of a consumer reduces returns and other servicing costs.  An educated consumer is always the "best" customer.</p>

<p>The lack of consumer education...</p>

<p>Of the many challenges facing broadcasting, the hard shut-off date (February 17, 2009) of analog signals is the most traumatic. All TV sets dependant upon over-the-air signals and without a digital capability will go dark the end of that day. Both government and industry tend to gloss over the idea of a block of uneducated consumers phoning on the 18th of February 2009 to ask why their TV no longer works. The more thoughtful among the stakeholders, however, do view and consider this end-game scenario with some trepidation. Those who are closest to the scene seem to breathe harder and shudder more. They know that there will be countless consumer complaints that will surely arise if the public is not sufficiently made aware and given a cause or good reason upon which to act on their own. </p>

<p>In reaction to this view, an educational program is being constructed by a combine of the Consumer Electronics Association (CEA) and the National Association Broadcasters (NAB).  While the messages they can deliver will no doubt be free of error, at times these institutions themselves can be viewed by the general public with considerable skepticism. To the this segment of the public, "the folks in Washington, D.C." are a bunch of spin doctors hired by special interest groups to exploit the public and confuse them even more. To successfully educate the public, the educator must be independent and above such suspicion as well as supported by ALL of the stakeholders in the digital transition.  </p>

<p>Here's another point, for years I have postulated that for purposes of clarity, and in order to overcome confusion, a "unifier" is indispensable. For discussion purposes, let's consider that the stakeholders elect an independent "Czar of Digital Transition" with a courtly mission given to help finish the transition with minimal pain to all sectors.  There are, of course, huge arguments against such an aggregation of interests, but such an aggregation is exactly what occurred when the HDTV Grand Alliance was formed under the guidance of Washington Attorney and former FCC Chairman Dick Wiley.  From that union, forged by Wiley, came HDTV for all of America, and the success in this nation has literally sparked a march towards HDTV by consumers all around the world.</p>

<p>As a civilization we grow with every increase in communications, but only when its sending and receiving technology is assimilated by its people. "History has shown," said the founder of the Society of Motion Picture (and later Television) Engineers, "that with every increase in communications facility there has been an increase in business volume (and to the general welfare)". What's sad is that whatever contributes to consumer confusion retards advancement and growth.  This is a challenge that must be solved.  </p>

<p>"HDTV has the potential to both inspire and to display a new world vision." I wrote those words nearly twenty years ago, and I find them truer today than I had ever hoped for back then. The kind of penetrating programming I thought would follow, along with the vast improvement in HDTV images has more than happened. All the civilizations of the world are being transported flawlessly into our homes and becoming, through the miracle of HDTV, familiar, understandable, even embraceable in their beauty. If there is anything more urgently needed than a broadly appreciated new world vision, the alert has not as yet crossed my desk. </p>

<p>Stephan Hawkins said just last week that for humanity to survive we must colonize far distant planets. The more realistic alternative, of course, is to understand 1) the planet we are on, 2) the nature of our humanity, and 3) the influence of the universe upon us ... If we do this, we can then begin to formulate a new culture that thrives and grows upon a foundation that is in accord with our advancement in general knowledge and technology. Nothing that I have seen in 67 years will more insure our deeper appreciation of these things than will the spreading of HDTV.  If this last statement is only fractionally true, one must not do things that could block the way without having to answer to more than man. And, don't forget, it's absolutely great for football too!</p>

