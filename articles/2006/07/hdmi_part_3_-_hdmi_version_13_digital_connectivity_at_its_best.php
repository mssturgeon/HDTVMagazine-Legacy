			<p>Lets us review the new features and what those would mean for your HD system.</p>

<h2>Double the bandwidth</h2>
HDMI 1.3 increases its single-link bandwidth from 165MHz (4.95 gigabits per second) to 340 MHz (10.2 Gbps) to support the demands of future high definition display devices, such as higher resolutions, Deep Color, and high frame rates.

<p><img src="/images/articles/hdmi-color-depth.gif" alt="HDMI Color Depth"><br />
The foundation has been set for even higher bandwidths over a single-link. With double-link, if implemented, the 10.2 Gbps could virtually be doubled, if ever needed. How the possibility of several 1080p/60fps running simultaneously over HDMI for future applications sounds to you?</p>

<p><br />
<h2>Deep Color</h2><br />
As mentioned before, HDMI 1.3 supports 30-bit, 36-bit, and 48-bit (RGB or YCbCr) color depths, up from the 24-bit depths in previous versions of the HDMI specification. With the adoption of Deep Color and the xvYCC color space HDMI 1.3 removes the previous interface-related restrictions on color selection.</p>

<p>HDMI 1.3 enables manufacturers to build devices that can represent any color in nature, with as fine detail as can be seen by the human eye. The interface will no longer be a constraining pipe that forces all content to fit within a limited set of colors, unlike all previous video interfaces. In other words, this will let HDTVs and other displays go from millions of colors to billions of colors.</p>

<p>Significantly, the increased color bit-depth of HDMI 1.3 eliminates on-screen color banding, for smooth tonal transitions and subtle gradations between colors. This enables manufacturers to deliver significantly increased contrast ratio.</p>

<center><b>Eliminates color banding</b><br><img src="/images/articles/hdmi-color-banding.gif" alt="HDMI Color Banding"></center>

<p>HDMI 1.3 allows displays to represent many times more shades of gray between black and white.</p>

<p>At 30-bit pixel depth, four times more shades of gray would be the minimum, and the typical improvement would be eight times or more.</p>

<p>Many devices cannot accurately represent many colors that exist in nature - leading to the sometimes cartoony look that you see on some displays. What is worse is that current display technologies, such as backlit LCD displays, can display colors far beyond those described by previously existing color space standards.</p>

<p><img src="/images/articles/rgb-color-space.jpg" alt="RGB Color Space" align="right">The diagram on the right is a standard type of diagram used to display color spaces (the colors that can be depicted by a given device). The shaded area represents the colors in nature that the human eye can see. The triangle is a representation of the RGB color space.</p>

<p><img src="/images/articles/xvycc-color-space.jpg" alt="xvYCC Color Space" align="left">The new xvYCC color standard is a real innovation. Current color standards represent only a small portion of colors that are viewable by the human eye.</p>

<p>By implementing the xvYCC color space standard, HDMI 1.3 removes virtually all limits on color selection and supports 1.8 times as many colors as existing HDTV signals. This is because the xvYCC color space standard defines colors by means of an algorithm that can specify any color in nature. This lets HDTVs display colors more accurately and with more natural and vivid colors. The first TV to use this standard was the Sony Bravia, which premiered at the 2006 CES in Las Vegas.<br />
<br clear=all></p>

<p><br />
<h2>Greater PC/CE convergence</h2><br />
HDMI was enhanced for easier integration into low voltage, AC-coupled PC graphics controllers, cementing HDMI's position as the de facto standard digital multimedia interface enabling true convergence cross PC and CE platforms. The HDMI Founders also support compatibility between HDMI and the Unified Display Interface (UDI), the HDMI-compatible digital video interface for PC displays announced recently by a group of leading PC technology makers.</p>

<p><br />
<h2>Higher resolution and Refresh Rates</h2><br />
Over 400% greater resolution than 720p HDTV for greater detail and larger display sizes</p>

<p><img src="/images/articles/hdmi-resolution.gif" alt="HDMI Resolution"></p>

<p>Higher refresh rates (up to 120hz) for smoother motion, less blurring and better gaming (faster response time).</p>

<p><br />
<h2>New mini connector</h2><br />
With small portable devices such as HD camcorders and still cameras demanding seamless HDTV connectivity, HDMI 1.3 offers a new, smaller form-factor connector option. Since HDMI offers the highest quality digital audio and video on a single connection, such devices will be also benefit from a reduced connector count.</p>

<p><br />
<h2>Lip Sync</h2><br />
CE devices are employing increasingly complex digital signal processing of high-resolution video and audio formats to enhance the clarity and detail of the content. As a result, synchronization of video and audio in user devices has become a greater challenge and could potentially require complex end-user adjustments. HDMI 1.3 incorporates features to enable this synchronization to be done automatically by the devices with greater accuracy.</p>

<p><br />
<h2>New compressed audio formats</h2><br />
In addition to HDMI's current ability to support high-bandwidth uncompressed digital audio and all currently-available compressed formats (such as Dolby Digital and DTS), HDMI 1.3 adds additional support for new compressed lossless digital audio formats Dolby TrueHD and DTS-HD. More detail about this subject will be brought to light on part 5 of this series. However, a complete analysis of how each HDMI version could transport those multichannel audio formats between audio components was covered in the article:</p>

