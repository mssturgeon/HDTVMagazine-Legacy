<p>First of all, please keep in mind these units are true "kludges."  DirecTV contracts the reference hardware design, based on their specifications, to one company, the software design to another and the integration and manufacturing to third parties.  Good luck!  But this type of disintegrated "outsourcing" product development and production model is becoming the norm these days.  In this manner the blame can be spread among several entities.</p>

<p>To punctuate the degree of design confidence and stability DirecTV has in this unit (the HR 20), they have adopted a leasing model, allowing them to provide customers with update capability by exchanging the units and/or the dishes, no doubt at extra charges.  Gee, just like Cable.  </p>

<p>The HR 20 does not receive off-air digital signals in spite of the fact that it has an integrated DTV tuner. Even though this capability is advertised on the carton, one must look very closely to see a little add-on sticker that reads: "Coming late 2006:  This box can also integrate local channels from an off-air antenna (ATSC)."</p>

<p>Add this revelation to the fact that the unit only receives two of the advertised five local HDTV feeds (and no other DTV multiplexes of those channels), makes this offering about as useful as a screen door on a submarine.  A call to DirecTV - a very painful experience at its best - reveals that extended channel capability continues to be "under negotiation," with no conclusive date for HDTV service expansion. Really!</p>

<p>In a subsequent article, I will discuss the HR 20 performance, as soon as DirecTV downloads the capability to turn the unit "on."</p>

