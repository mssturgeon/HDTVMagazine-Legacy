"With today's action," said Consumer Electronics Association President Gary Shapiro, "President Bush set a hard finish line for the nation's transition to DTV." The CEA, along with several other lobbying groups including the National Association of Broadcasters (NAB), supported a hard cut-off date. The stated belief has been that it would settle things down for the industry and public alike as well a free spectrum for more crucial uses, like homeland security communications. "This deadline," said Shapiro, "will provide certainty to manufacturers, retailers, consumers and all others with a stake in the transition."  </p>

<p>The newly installed NAB president David K. Rehr said at the time of the signing, "We have crossed an important threshold...The NAB is pleased that Congress adopted many pro-consumer DTV measures in the legislation, and we're encouraged that the bill thwarted cable industry attempts to degrade the quality of HDTV pictures to consumers."</p>

<p> CEA is forecasting that U.S. consumers will take home more than 18 million DTV sets and displays this year (2006). That would rack up a whopping 50 percent increase over 2005 sales. </p>

<p>Programming has increased<br />
Millions of Americans watched the Super Bowl on ABC in HD this last weekend and starting the 10th of this month can catch the Winter Olympics on NBC (and several affiliates).  Programming for HDTV receivers has vastly increased in the last few years. "There are hundreds of HD programs coming into homes each week." said Shapiro. HDTV Magazine, the first to publish a schedule for HDTV programs, reports that from February 12 to February 18 an astonishing 4,670.46 hours of HDTV programming will run on the distribution grids of America.  You can get a full schedule of that programming by registering with HDTV Magazine (www.hdtvmagazine.com)</p>

<p>You can add to that the introduction of HD-DVD and Blu-ray players and its programming scheduled for launch later this year. Those guarding against consumer confusion, however, fear that competing formats with a poorly understood copy protection scheme (imposed by the MPAA) will leave the mass market paralyzed. Those who follow the 10 JND school-of-thought worry that the quality spread  between the HD disk and the standard DVD is not obvious enough to overcome the higher prices attendant with new technology. Those supporting the formats believe that the advancements in authoring and extra content will make the difference and demand for that alone will overcome any lack of quality perception. </p>

<p>Shapiro remains optimistic: "With the combination of the hard cut-off date, continuing strong sales of DTV products, an increasing array of quality high definition (HD) programming and the coming advent of new pre-recorded HD content, we are well on our way toward making the U.S. a 'DTV nation'."</p>

<p>In a press release today Shapiro gave thanks to those who helped over the last 43 years to make H/DTV possible (yes, that is how long it took to get to where we are today from its inception in Japan) and with typical Washington largess granted a special thanks to the Senate Commerce Committee Chairman Ted Stevens (R-AK), House Commerce Committee Chairman Joe Barton (R-TX) and House Subcommittee on Telecommunications and the Internet Chairman Fred Upton (R-MI) for their leadership in holding hearings and guiding the bill through the legislative process. "And, of course, our thanks to President Bush for signing the bill into law." As of the last Congressional hearing on DTV none had HDTV   </p>

<p>Shapiro used the last of his release to advise the industry, saying:  "Our job is not yet done. All industries involved in this transition have a responsibility to educate consumers about this exciting new era in television. CEA will continue our award-winning efforts to meet this responsibility and we look forward to working with our industry and government partners to develop and implement educational programs." </p>

<p>This educational mission is not a trivial one. It will take massive resources and high-quality thinking to manage a very consistent and long-lasting cross-industry campaign. With new terms daily bombarding the public many feel like they are learning a new language that randomly changes meanings of its words.  Many have also seen bad demonstrations or improper set ups in their friend's homes and have little concept of what good HDTV looks like. When you see added to these dilemmas the general complexities associated with emerging technologies (new terms to learn like DLP, SED, LCD, LCOS, DILA, Plasma and all the things behind them) the educational challenge becomes clear. If educators can show us, however, that HDTV goes beyond mere self-gratification, and, when installed across the nation, actually enriches our culture and life we can be moved to duty -- equipping ourselves. Japanese families have purchased new technologies for 50 years running from their electronic fabricators, not because they necessarily needed them, but because in doing so the price of introduction in other nations became lower. Their patriotic duty, as they saw it, was to make the new products abroad more affordable at introduction. They did that with HDTV too by buying first iteration devices of 38" for $28,000 each. HDTV was introduced in this country at half that price. The net payoff to all of Japan has been an enormous influx of money from around the world. The calculated result was realized as those tactics raised the general standard of living in Japan. All within the nation have profited in some way from their investments if only from the enrichment of a common infrastructure.  A higher social or cultural purpose attached to such a sweeping and all-encompassing movement as is HD is indispensable for increasing our willingness to outfit the nation with digital broadcasting. We have to know that it is well worth the fuss and cost. With the signing of the bill the President sent flying a wrecking ball through all of NTSC broadcasting. There better be a good reason for doing that, and there is. It is always right to lead with a superior idea that serves the greater good. Finding that superior idea and holding its banner high is the chief work left for the industry. _Dale Cripps</p>
