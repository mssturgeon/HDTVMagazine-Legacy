ALSEA OR-February 8, 2006 - President George Bush signed legislation into law today that set February 17, 2009 as the date when U.S. broadcasters must end their transmission of analog television signals. Some in the press have called it the "end of television as we know it." Others see it as a dawning of a new era. The legislation also allocates up to $1.5 billion to reimburse consumers who purchase digital-to-analog converter boxes, so their analog TV sets continue to work after the shut-off. The legislation excluded a provision that would have allowed cable operators to degrade a broadcaster's HDTV signals to "standard definition," and in doing denying consumers the means to see the highest-quality digital programming.<br />
