<h2>What are Podcasts?</h2>
<p>I would venture a guess that most of you know what a podcast is, how to receive them, and how to listen to them. But for those who don't, here's a quick primer:</p>
<p>A podcast is an audio or video file that is distributed using "feeds". It differs from direct downloading or streaming in that it can be downloaded automatically using software capable of reading these "feeds". The term derives from a combination of the terms "iPod" and "broadcasting", although an iPod is not required to receive podcasts. You can play them on any mp3 player (or video player, for video podcasts), or your home computer or laptop. Each of the podcasts below is free and distributed via iTunes, Apple's online music/video service.</p>
