<p>There are no products with Type B connectors, and there is no relationship between 1080p60 (148.5MHz speed) and Type B. None of the Primary or Secondary formats requires use of Type B.<img src="/images/articles/hdmi-mini-connector.jpg" alt="HDMI Mini Connector" align="right"> They can all be (and are) handled on Type A. Considering that HDMI 1.3 just raised the speed of HDMI Type A from 165MHz to 340MHz, there may never be a need for Type B and you will probably not see a Type B connector for many years.</p>

<p>The new Type C mini-connector (shown here) that is part of HDMI 1.3 contains the same number of pins as the Type A connector and targeted to the HDMI camcorders and digital still cameras.<br clear="all"></p>

