<h2>Dual Link</h2></p>

<p>Although the information released officially by HDMI does not indicate that a dual link version would be capable to double up the 10.2Gbps bandwidth capacity of 1.3 to 20.4 Gbps using the type B connector/cable (such as the original DVI and HDMI did with single at 4.95Gbps and double link at 9.9Gbps), it was informally confirmed that the potential exists, but there is no definition of a specific cross over frequency.</p>

<p>Furthermore, Joseph Lee explains, DVI specifies a maximum single link bandwidth of 4.95Gbps, and higher frequencies must implement the dual link configuration. DVI's dual link option has been generally viewed by the PC industry as a high cost solution as all cables & connector must be burdened with the extra pins & wires for dual link, yet it is at times difficult for the consumer to know whether a product is dual link capable or not.</p>

<p>Technically the Type B dual link solution could be implemented by a manufacturer. However, there has been little interest by the industry to use the Type B connector (in fact, this connector is not in production by any cable or connector manufacturers) since the HDMI single link solution with the Type A connector has more than adequate bandwidth for the vast majority for mainstream and high end CE & PC applications.</p>

<p>Both the HDMI & DVI specifications have no upper limit to maximum speeds when using the DVI or Type B dual link connectors, so the maximum bandwidth is dictated solely by the availability of electronics that can support higher bandwidths.</p>

<p>Therefore, it is possible from a specification point of view to have a 20.4Gbps or higher interface when using HDMI with a dual link connector, but this speed will be dictated by the availability of the semiconductor and other electronics. In addition, as the HDMI 1.3 press release mentions, the technology foundation has been set for HDMI to further increase the single link bandwidths to higher speeds in the future specifications.</p>

