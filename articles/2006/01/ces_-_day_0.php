				<blockquote>This is the first of 5 daily articles we will be distributing over the course of the 2006 Consumer Electronics Show (CES), which runs from Jan. 5th - Jan. 8th.</blockquote>

<p>Even though the CES doesn't officially start until tomorrow, the day before is typically a day of press conferences, and today was no exception. We did not have the opportunity to cover all of these conferences, but here are some items of note from those that we were able to take in:</p>

<p><br />
<b>Pioneer</b><br />
Pioneer announced dates and pricing for two Blu-Ray Disc (BD) players:</p>

<p>The BDP-HD1 will begin shipping in May of this year at a price of $1800, and is aimed primarily at the early adopter market. This first unit will support only the BD-ROM format, and will not support writable media. It will also not support any of the current CD or DVD read/write technologies.</p>

<p>The BDR-101A is the PC-based BD player, and will begin shipping in 1Q06 at a price of $995.</p>

<p><br />
<b>Panasonic</b><br />
Panasonic unveiled the largest plasma TV available to consumers at 103". No dates or pricing were provided.</p>

<p>They also announced a deal with Comcast in which they will deploy a new series of set-top boxes supporting the OpenCable Application Platform (OCAP). More on OCAP in another article.</p>

<p>The Panasonic BD player is currently scheduled for "summer" release, and of course with a date that far out ... price is not yet known. </p>

<p><br />
<b>Sony</b><br />
Sony is currently planning release of 20 titles to coincide with the release of their BD player in "early summer". And to this point, the Playstation 3 is still including a Blu-Ray drive for it's planned release "in 2006".</p>

<p>Sony has a line of Media PC's being marketed as the XL1 and XL2.  The XL2 includes an ATSC tuner and supports HD resolutions over both digital and analog outputs. The next model (the XL3?) will include Blu-Ray drive support.</p>

<p>I will have more on Sony in tomorrow's article as their press kits were not available today.</p>

<p><br />
<b>Toshiba</b><br />
Toshiba announced their HD-DVD player models and pricing today:</p>

<p>Both players will be released in March, the <a href="http://www.amazon.com/exec/obidos/ASIN/B000E21TY0/hdtvmagazine-20">Toshiba HD-XA1</a> will be priced at $799.99 and the <a href="http://www.amazon.com/exec/obidos/ASIN/B000E1PTGK/hdtvmagazine-20">Toshiba HD-A1</a> at $499.99. And by June they expect to have 200 titles available.  As of this writing, there are 20 <a href="http://www.amazon.com/exec/obidos/redirect?link_code=ur2&tag=hdtvmagazine-20&camp=1789&creative=9325&path=tg%2Fbrowse%2F-%2F16295741">HD-DVD titles</a> available.</p>

<p>The biggest (only?) down-side I see right now with this format is apparent lack of support for 1080p. I did like very much their support for "Managed Copy", where you could (through the menu system) save a legal copy of the entire DVD, just the HD movie, or a mobile version of the video for use with smaller screens (iPods, phones, etc).</p>

<p><b>Microsoft</b><br />
During the Bill Gates keynote/infomercial, there were several key announcements.</p>

<p>The first is that Windows Vista will support Digital Cable tuning (via CableCard).</p>

<p>The second is that XBox360 will have an HD-DVD drive accessory available within the next few months (March, if I recall correctly). They are also adding a third manufacturing partner to help catch up with demand and plan to have 50 titles available on the platform by June.</p>

