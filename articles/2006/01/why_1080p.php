				<p>What are 1080p manufacturers doing on their current 1080p sets?  Are they really implementing all that 1080p can and should do?  Do people need all that 1080p can do?  When?  How could one find out if a set is actually suited to be ready for near future 1080p media, such as Hi Def DVD coming in a few months? </p>

<p>I will cover all those subjects gradually in short articles, but first let us mention a couple of key points.</p>

<p>1080p resolution quality in displays, processors, players, recorders, pre-recorded media, etc. is rapidly becoming the next stage of this HDTV industry; the 1080p buzzword has been also loosely used to identify the "new breed of top quality HDTV sets."  In order to be actually ready for such level of quality throughout the HD system, digital display devices that claim 1920x1080p capabilities should be designed and suited to accept 1080p/24/30/60 fps signal from an external 1080p progressive source.   </p>

<p>Not accepting 1080p from an external source will force the source to supply a 1080i version to the TV which would do the 1080p upconversion job with its internal/proprietary de-interlacer circuitry, typically not as good as one should expect of equipment at this level of resolution. </p>

<p>Regarding deinterlacing, do these new 1080p sets deinterlace properly 1080i?  What happens when it is not properly done and you still want that TV?  One option could be to take that deinterlacing job outside the TV so a dedicated video processor can improve it.  However, if the TV does not accept 1080p, such limitation would preclude the use of a higher-quality 1080p video processor/scaler, which usually is expected to perform better 1080p upconversion, such as Faroudja, DVDO, Lumagen, or the Dragon Fly scaler/noise reduction implementing the new Silicon Optix "Realta" chip (a professional video technology originating from Teranex), among others.   </p>

<p>Most people would consider it irrational to spend $2000 on a 1080p video processor to feed a $3000 1080p HDTV just because the TV is weak in that area, but other people might consider the option of having 1080p inputs an important future proof feature that would allow the component approach for upgrading the overall quality of the HD system where and when it is needed.  </p>

<p>Separating the video processor from the display device to follow individual upgrade paths could be a good solution, especially for front projectors/large projection screens; the processor might be software upgradeable, while many HDTVs usually are not.  An owner of an otherwise good 1080p HDTV display might not like how the set handles the internal 1080p video processing that cannot be upgraded.  </p>

<p>The higher quality of 1080p opens the opportunity to sit closer to the image and open the angle of view, which would immerse the viewer into a cinematic experience by enhancing the peripheral vision without sacrificing resolution; it also provides the possibility for using larger screens for a home theater environment.  </p>

<p>However, viewing non-1080p content on a 1080p HDTV set that might have insufficient quality to properly upscale, deinterlace, and/or upconvert, could certainly produce a variety of video artifacts that would actually force the viewing position to be further back to avoid seeing them, which is the case of many of the first generation 1080p TV sets introduced over the last year; upgrading to a larger screen could accentuate the visibility of those artifacts.<br />
   <br />
Additionally, in many viewing situations the higher quality of 1080p resolution might not be noticed as an improvement by people accustomed to view the TV just as the typical TV box from far away; for those, a 1080i, or 720p, or even a 480p ED level DTV could be all they should need.  In other words, some people driven by the 1080p bug of "more is better, and I have to have it" might be paying extra for 1080p resolution they would never be able to see as an improvement on their room/viewing conditions.</p>

<p>Without changing the tutorial intention of this series of articles, the next part takes a look at an example of how some 1080p rear projection HDTVs are being implemented; in our first case we will step behind the technical curtain of Syntax-Brillian's new 1080p set.  </p>

