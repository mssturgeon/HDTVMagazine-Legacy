			<p>Plasma should not work!  At least it should not work as a TV display system.  At best, it should provide a nice, even light surface - suitable for decorative effect, and maybe, with a strong south wind, work as some type of test display.  That was the thinking about thirty years ago.  But today, "Plasma" (a.k.a. Gas Discharge) is one of two technologies presently being employed for flat panel TV displays - the other being LCD.  Although plasma displays have been around for several years, only relatively recently has this technology been applied to television.  Earlier Plasma uses were relegated to flat alphanumeric displays, but other, more efficient technologies such as LCD, LED et al have replaced Plasma in these applications.</p>

<p>Now, however, two display systems - Plasma and LCD - are in somewhat of a "race" to determine which will dominate the flat panel TV market. At this point in time both technologies have staked out their marketing territories. LCD is most economically applied to screen sizes below 40" in diameter (16x9). Panel costs and performance limitations above that size become prohibitive for CE applications, and Plasma becomes a viable alternative. Plasma, however, does not economically "scale down" as efficiently as LCD in screen sizes below about 40."  This is primarily because the plasma panel and driving electronics costs do not decrease in linear proportion to screen size.  Secondarily, large panel LCD displays suffer from uniform performance problems, negatively affecting production yield.  As a result, large LCD panels have a 20% to 25% cost disadvantage over Plasma.</p>

<p>Therefore, for the time being, Plasma is the most economic technology for larger flat panel HDTV displays.</p>

<p><img alt="fig1.jpg" src="http://www.hdtvmagazine.com/articles/Images/fig1.jpg" width="401" height="322" /> <br />
Figure 1</p>

<p>How plasma displays operate is quite interesting. You probably know the basic operation, but, if not, here is a quick review.  Figure 1 illustrates schematically a very basic plasma cell.  (Three cells, one for each primary color - Red, Green and Blue - comprise a "pixel.")  When a voltage (100 to 200 volts), called the "ignition" voltage, is applied across a glass cell containing Xenon gas, the gas ionizes, creating a stream of charged particles (Plasma).  This plasma discharge emits a wide spectrum of electromagnetic energy including ultraviolet light.  This ultraviolet energy, in turn, impinges on a phosphor coating, causing the phosphor to emit visible light, the color depending on the type of phosphor.  The arrays of electrodes connected to each cell are called "Display" and "Address" electrodes respectively.  Each cell is "fired" when the voltage between its respective display and address electrodes equally the ignition voltage.</p>

<p><img alt="fig2.jpg" src="http://www.hdtvmagazine.com/articles/Images/fig2.jpg" width="445" height="359" /> <br />
Figure 2</p>

<p>In actual application the applied cell voltage is AC not DC.  It was found in early plasma display development that AC pulses provided a much more efficient and consistent display for larger panels.  A diagram of the AC voltage pulses applied to the cells is shown in Figure 2.  The "Ignition" pulse quickly "fires" the cell; the AC "Sustaining" pulses maintain the plasma output; while the "Quenching" pulse provides for quick extinguishing of the plasma discharge.<br />
As shown, once fired, the light output from the cell is relatively constant until the quenching pulse is applied.  Note that a 1920x1080 HDTV plasma display panel contains over six million individual cells.</p>

<p>Now, if you become faint when being confronted with a somewhat involved technical discussion, please feel free to jump to the last paragraph of this article, and you can consider it having been read.  If you wish a more detailed discussion, albeit simplified, of the concept used to drive plasma displays, please read on.</p>

<p><img alt="fig3.jpg" src="http://www.hdtvmagazine.com/articles/Images/fig3.jpg" width="480" height="379" /> <br />
Figure 3</p>

<p><br />
Because the plasma cell is a bi-modal device, i.e. it is either "on" or "off," it cannot be modulated in the conventional analog practice of applying a varying voltage. Instead, the modulation process much be accomplished digitally.  Let's consider, for example, that the brightness value of each cell in each video frame can be represented by a four-bit digital "word," the least significant digit representing a relative brightness value of one, and the most significant digit representing a brightness value of eight. Now, let's divide each video frame into four "subfields," as illustrated in Figure 3, with each subfield representing one of the four significant digits of the four bit cell brightness value.  Note that the cell is fired for a fixed period of time for each significant digit - a relatively short time for the least significant digit (1) and a longer period for the most significant digit (8).  Since the amount of light emitted by the cell during any given period of time (e.g. one subfield interval) is directly proportional to the time the cell is "on" for that period of time, the total light output from the cell for each frame is the total output of each subfield.  </p>

<p>Note from Figure 3, that if the cell were fired for each subfield, the total brightness output would have a relative value of 15 (1+2+4+8).  This means that such a four-bit system would generate 64 different brightness levels and over &frac14 million different color values, assuming three cells per pixel.   In actual practice, each frame is divided into as many as 10 to 20 subfields in order to achieve much finer brightness gradients and improve linearity.  </p>

<p>Now, that wasn't so bad, was it?</p>

<p>Plasma panels have five distinct advantages:  first, and most important, is that the form factor is thin and flat, finally delivering the much desired "hang on the wall" large screen television display; secondly, Plasma generates its own light - no need for a separate backlight; third, the viewing angle is 180&deg; - providing fixed brightness with no distortion regardless of the position of the viewer; forth, there are no optical components such as lenses and prisms to reduce resolution - resulting in a very sharp display; and fifth, Plasma is a purely digital display - eliminating linearity distortions caused by digital to analog converters.</p>

<p>Plasma has overcome most of its earlier problems such as low brightness and contrast, poor black level performance, white compression and noise caused by digital artifacts.  In addition, plasma panel prices that have been prohibitively high are now within the range of a viable mass consumer product.  This is the best of all worlds, and it will get better.</p>

