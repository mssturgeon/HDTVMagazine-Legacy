			<p>The International Consumer Electronics Show (a.k.a. CES) certainly lives up to all of the superlatives attributed to it.  The CES is arguably the largest commercial trade exhibition in the world by any metric applied.  Virtually every consumer electronics device that may be marketed in the near future is displayed. It addition, and equally important, powerful commercial agreements are consummated, deals are brokered, and carriers and reputations are established or diminished.  It is a wonderful and wondrous example of international capitalism at work and in full bloom.</p>

<p>In my thirty-four consecutive years of attending CES, I have been actively involved in most all facets of the show from working booths to establishing business agreements. But the most exciting and fun is to try to ascertain the general technological trends revealed at the show - trends that will influence products and services in the years to come.  So, here is my take on the three most salient CES 2006 trends that will impact HDTV in the near future:</p>

<p> <strong>LED Technology for Display Light Sources</strong><br />
LED (Light Emitting Diode) technology has now achieved a level of performance and cost effectiveness that will find these devices being utilized in an increasing number of light-source applications, replacing the conventional filament or florescent lamp technology.  LED's provide the benefit of long life, an expanded color gamut and a wide system dynamic range, allowing bright whites and deep blacks. LED applications with single chip DLP systems allow the elimination of the mechanical color filter.</p>

<p><strong>Field Emission Devices (FED)</strong><br />
FED's may ultimately be the "winner" of the flat panel display technological contest currently being waged between plasma and LCD.  At the CES, Toshiba demonstrated FED monitors under the acronym SED (Surface-conductive Electron emitter Display).  FED's are essentially pixel sized vacuum cells consisting of a very small electron emitter (cathode) directing electrons to a phosphor-coated anode.  In essence it is a very small CRT without the grids and deflection apparatus.  FED's deliver the best of all display worlds - the performance of CRTs without the focusing and deflection-related problems, self-light generation, and a flat form factor.</p>

<p><strong>In-home Digital Networks</strong><br />
Driven by the paradigm shift to the availability of digital services from many different HDTV sources (i.e. cable, satellite, OTA, broadband, computer, games, disc, PVR etc.), the need to "ship" and control the various source signals to multiple displays becomes obvious.  To address this need, several manufacturers are addressing and demonstrating HDTV signal network systems.  Although all work well, unfortunately, they are proprietary, or being developed by different manufacturers' coalitions.  Only when a single standard is adopted will networking become ubiquitous.  (HDTV networking will be the subject of a future article.)</p>

<p>So, those were my most important observations relative to HDTV at the 2006 CES. One additional observation - can't call it a trend yet - was a demonstration of 3D-TV without the need for glasses. The pictures were crude, certainly not commercial, but the possibilities were obvious. Oh yes, another very important observation:  virtually all display systems at this CES were High Definition.  </p>

