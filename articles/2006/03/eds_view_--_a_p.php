				<p>In the vary wee days in television history, back in the late 1800's, one of the first concepts devised for a means to electrically transport images was via parallel wires.  In this scheme an image was focused on a small array of crude selenium sensors.  Each sensor represented one pixel.  The varying current caused by the changes in resistance of the each sensor when excited by light was coupled to a respective lamp at the receiving end.  Each pixel, therefore, had its own wire.  Obviously, an image with any reasonable degree of resolution would require at least several hundred very small sensors and lamps and a like number of wires. Clearly, this was not practical, and the "parallel pixel" scheme for television was abandon.  Then, first mechanical then electronic scanning was invented, and the rest is history.  (By the way, sequential scanning represents the first application of video compression, albeit in the time domain.)</p>

<p>Now comes a very interesting development by a group of scientists working at the University of Uzbekistan (located at Tashkent, Uzbekistan) that resurrects the old parallel transmitting concept to generate and transmit HDTV images.*  (Interestingly, Uzbekistan is one of the poorest countries in the Middle East, but evidently possesses one of the world's most powerful supercomputers - go figure.)  Essentially, this is how it works:</p>

<p>At the imager sensor side, each Red, Green and Blue cell that makes up an individual pixel is comprised not only of the sensor element itself, but also a very sophisticated nano-computer with associated memory.  This means that the sensor array consists of over six million of these teeny-tiny things!   Each of these miniature cell/computers digitizes, encodes and sub-modulates its respective individual sensor output.  Further, each cell encoder compresses its data using a loss-less compression system similar to Motion JPEG.  Sub-modulation uses statistical multiplexed TDMA.   To enable statistical multiplexing, each cell communicates with its neighbor to determine the most efficient data distribution throughout the cell array.</p>

<p>A process similar to QAM completes the modulation process, however, the symbols, in addition to amplitude modulating the carrier, also phase modulate it.  This is done in order to achieve high information density within a given bandwidth. However, even with these clever modulation techniques, the most complex motion scene requires a bandwidth of over 90Thz.  Therefore, the physical medium used to transmit the signal is fiber optic modulated with an ultraviolet laser. </p>

<p>Obviously, most of the system's technology required to successfully transmit this "parallel" HDTV scheme has yet to be fabricated, but with continued rapid advances in nano-machining processes, the inventors predict a working model within 15 to 20 years.  However, the system has been mathematically simulated and documented using that aforementioned supercomputer.</p>

<p>So, what are the advantages of this system?  Simply pure images, unblemished by any scanning or compression artifacts, heretofore achievable only with film (that, by the way, is also a parallel process).  So, stay tuned.  It really will get better.</p>

