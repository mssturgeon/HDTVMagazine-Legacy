				<p>If you have one of the new lamp-based microdisplays such as DLP, LCoS, SXRD, D-ILA or LCD it will definitely pay off to learn how to extend your lamp life. Lamp life varies by manufacturer design based on the application of the product and varies anywhere from 2000 to 8000 hours. Lamp replacements run from $200-$500 but most consumer rear projection displays are in the $200-$300 range and also lean more towards longer rather than shorter life design. The good news here is unlike any other display you have owned you can bring these back to brand new performance by simply replacing the lamp.</p>

<p>Lamp replacement is generally easy and comes in the form of a cartridge. It is considered a consumer replaceable device and does not require a technician to perform. Most manufacturers will provide a direct replacement when under warranty. Should you decide to replace the lamp yourself, <b>do not touch the face or glass of the lamp in the cartridge</b>. Like a halogen lamp, body oils on these surfaces will cause hot spots on the lamp surface and cause the lamp to explode or crack. Please check your owner's manual for further replacement details for your product.</p>

<p>While I prefer writing definitive articles, this will not be one of them. The following information represents what the industry has experienced and represented over the last decade. In two aspects that have been considered critical for lamp life, Toshiba has taken the opposite stance and I am unable to confirm if they are right. Nevertheless, that is how their products operate and also what they officially recommend so it has been included since not following their policy would also prevent you from having any legitimate claim on premature Toshiba lamp failure.</p>

<p><B>Heavy Vibration</B>: Kids jumping up and down on your floor, heavy footsteps and excessive volume from home theater system subwoofers can cause the display, and ultimately the lamp, to vibrate, inducing an instant failure.</p>

<p><B>Keep Power Cycles to a Minimum</B>: Lamps are arc based and turning them on, called striking the lamp, is the most destructive process and plays one of the biggest roles in lamp life deterioration. Try to keep this at 2-3 times per day at the most. Rather than turn it off for only a few hours, it is best to leave it on. This is the same recommendation given for our old CRT technology.</p>

<p><B>Proper Ventilation</B>: Be careful of applications where the product is buried in an enclosed environment without good ventilation. Air movement is essential for the exchange of outgoing warm air with incoming cool air.</p>

<p><B>Keep Filters Clean</B>: Not all products have filters. If they do, replacing them should be covered in the owner's manual and you must maintain them to prolong lamp life, keep light path cooling at peak efficiency and, with LCD projection, prevent debris from entering the light path degrading image performance.</p>

<p><B>Power Down Cycles</B>: Most displays feature a 10-60 second grace period or delay when initiating a power down sequence. This prevents unnecessary striking of the lamp to safeguard against unintentional power down commands. Some manufacturers, like Toshiba, have this as a menu item called "Instant Startup". Testing such a feature is easy: With the display on, press the power button. Within 10 seconds press power again and within a few moments the picture should return. If you find yourself waiting a minute or longer, or the power on command is being ignored, then the lamp was turned off and will not be turned on again until the sequence has completed. This could be due to an older display, in which case there is no solution, or like the Toshiba you may have a menu item that addresses this.</p>

<p><B>AC Surge Suppressor</B>: If there is anything with a motor that is plugged into the same AC outlet, or on an outlet on the same circuit, it will generate spikes which can upset the ballast in the TV, causing a burst of additional current to the lamp. Some people have reported lamps failing as window AC units or vacuum cleaners are turned on! The solution is to install a surge suppressor. If you also want to protect against lightning, you should read <a href="http://www.hdtvmagazine.com/forum/viewtopic.php?t=3497">AC Surge/Lightning Suppressors.</a></p>

<p><B>Loss of AC power</B>: You should not unplug or remove AC power from the unit to turn it off. Turning off requires a typical 2 minute process to cool the lamp. Many auxiliary products, such as a cable box or satellite receiver, offer a switched AC outlet to "conveniently" turn your TV on and off - <B>don't use it</B>! If your electric company has problems maintaining the power while you are watching TV, then you need an uninterrupted power supply (UPS), like you would use for a computer.</p>

<p>Toshiba engineering, on the other hand, claims this process is not necessary and that their products do not provide a cool down process; when the lamp turns off so does the fan.</p>

<p><B>Power Settings</B>: Many displays offer two power levels for the lamp. If you want to increase lamp life, set it for low power at the expense of light output and remember: Lamp based rear projection displays are brighter than necessary in nearly all cases, so this is not much of a penalty and slightly improves black levels. As the lamp ages, light output will drop and you will notice it does not seem to be as bright as it once was. When this happens, go back in the menu and switch it to high power. Ordering a replacement lamp at this time is not a bad idea. Light output will continue to drop, and at this point in the life cycle it will also start to change color, creating a yellowish overcast most evident in the whites. Once you notice that, replace it. As a videophile, be aware that you will lose 25% of your light output within the first 500 hours and by the time the lamp turns yellow, you are well past a loss of 75%. Replacing the lamp well before it has reached that point is in your performance imaging interest.</p>

<p>Again, Toshiba engineering has a differing view: They recommend you disregard the above and set the display for the high power setting because the lamp was designed and life span maximized for the higher power setting. While counterintuitive to what one would expect, that is exactly what Toshiba engineering claims based on comparisons of televisions owned by consumers and the televisions on display at the store, which run all day long in high power mode, receive one power cycle per day, and in some cases none. Toshiba found that dealer demo displays could get up to 7000-8000 hours out of a lamp. It is noteworthy that the same claim has been made for years with ordinary incandescent light bulbs used with a dimmer.</p>
