				<p>Depending on the age of your product and its options, you are either watching the viewing screen directly, or watching through a screen protector. The actual viewing screen will be grooved for CRT rear projection or flat textured for micro-display rear projection (such as DLP, LCD, etc.). Screen protectors are perfectly smooth and shiny like a piece of glass. Indeed it is a Plexiglas product that may also have an optical coating to reduce glare. Behind the protector (if present) and the viewing screen is another screen called the Fresnel. The Fresnel focuses the light into a cone shaped path to increase brightness and causes the decrease in brightness you observe at wide viewing angles horizontally or vertically.</p>

<h2>Damage</h2>
In general, screen protectors are built into a product and are not optional. For those that are optional, your owner's manual should include instruction for removal and installation. If it becomes damaged, your best bet is to call the manufacturer or a distributor, order it directly and install it. When the screen is not optional, then far more disassembly will be required, and hiring someone with experience can pay off in the long run. If this is the extent of your damage, you will find the screen in the neighborhood of $70-150 plus an easy $30-50 for the special shipping and packaging. Depending on your market, who you hire and what it takes to get to it, figure another $75-250 for installation.

<p>If the outside viewing screen is damaged, this can run a bit more for the part, but the installation price is roughly the same. The real question at this point is whether or not the inside viewing screen was also damaged. If this is due to a medium weight object with some good inertia, more than likely it is. If due to more of a shock-type incident from a light weight object, it may have just damaged the outer screen, causing cracks/splits, without damaging the inner. This is especially true with the grooved type lenticular on CRT RPTV. One big problem with the inner screen is that while it may not crack, the bending action of the trauma can fracture the structure of the screen. If you have ever bent a piece of plastic, you likely noticed the stress marks and damage at the bending point. As with a screen, that area becomes opaque, reducing the light output and creating a line or smear easily seen in most cases.</p>

<p>A pair of screens (inner & outer) can run anywhere from $350-800 installed depending on many circumstances. Sometimes it is only available as an assembly of both viewing screens or all three with protector. This kind of damage is expensive, which you clearly want to avoid!</p>

<h2>Maintenance</h2>
Regardless of screen, these materials are optical grade plastic and need to be treated as such. As mentioned above, there are two basic types of screens, and each must be cleaned in a different manner.

<p><b>Screen Protector and Outside Viewing Screen (Smooth)</b><br />
Clean with a mix of 1-2 tablespoons of liquid dish washing soap and lots of water using a soft cotton, lint free cloth. Do not spray on heavily or apply so much that it begins to drip down into the frame. This can leach into the layers via capillary action leaving an obvious spot on the screen and once it dries you will likely have a ghostly reminder of the error. <B>DO NOT</B> use Windex, 409 or any other product with chemicals. Even if it claims to be safe on glass or specifically for glass, don't use it. A vast number of these products have been tested and it is all marketing claims with no substance for real world optical cleaning and longevity. Chemicals will slowly but surely degrade the plastic causing it to become opaque over time. Those screen protectors with an optical coating will end up with that coating removed or create spotting where it has been removed.</p>

<p><b>Outside Viewing Screen with Grooves</b><br />
This is a lenticular screen used exclusively with CRT rear projector displays. The worst possible thing you can do with a screen like this is treat it like a piece of glass by spraying or applying a cleaning fluid and rubbing it all over with a cloth or even a dry cloth. All you are doing is packing the grooves with debris! That is the bottom part or trough of the ridges. The crest or top part of the ridge has an optical coating to block light and just like a screen protector chemical based cleaners and abrasive cloth or material can affect it over time. The best solution is to avoid touching it all together. Even body oils, over the life span of the product, will deteriorate the finish. To clean, use your household vacuum cleaner, not a Shop-Vac (too much suction), and the soft bristle attachment. Follow the grooves up and down to remove the debris from the screen. If you should get a spill, or similar damage, then use the same solution as discussed and gently, with the cloth and your finger nail, rub the grooved area to work the material out. If it has dried, put a paper towel below the spot to catch the excess and spray on the solution to soften up the material before trying to remove it. If you are still having trouble then use a chemical based cleaner such as Windex, 409 or similar products.</p>
