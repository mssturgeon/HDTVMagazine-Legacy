				<p>As of 2006, nearly all TVs sold in the US now use this updated internal tuning system for receiving DTV over the air (an FCC regulation) and all analog and digital cable channels without a cable box. This has added a new wrinkle to how your TV is setup and how it operates.</p>

<p>First thing you may note when you setup the TV or product, such as a DVR, is that it takes quite a long time (10-30 minutes) to perform an auto programming of all available channels when you are on a cable system. In the past, your TV or other product was limited to the analog only channels up to 125, but with most cable systems typically limited to channel 99 or lower, in which case you needed a cable box to receive the digital tier above that. With QAM, you can now receive that digital tier directly but that also adds another couple hundred more channels for which your product will search, hence the time required for a complete channel scan.</p>

<p>Once this is completed you are in for another surprise: You have channel numbers that you didn't know existed and that do not appear in the guide from your cable company. For example, you may find in scanning that you can receive the FNC channel as number 90-002 on your product, but the cable company channel guide states this channel is on 224. Furthermore, you may find that 90-003 is MTV which your cable guide states as being on 176. If your product supports a cable card, and you are going to get one for it, then you can skip to the end of this article. If you intend to get a cable box that will resolve all your tuning issues as well.</p>

<p>The reason for this channel discrepancy is that the actual transmission has nothing to do with the sequence or linear channel numbers shown on your product. This was a huge problem in the early 80s with the introduction of analog cable tuners on televisions that required the customer to properly setup and often times only allowed about 20 channels to be setup or stored. Manufacturers provided transmission to channel number conversion charts in the owners manual to assist, yet a great deal of effort was spent in the field helping customers setup their product. To recall that time, a much simpler time indeed, the sequential transmission of the channels was 2-6, 14-21, 7-13, 22 on up. Yes, 14 follows 6, 7 follows 21 and 22 follows 13! This was unexpected for many folks and difficult to wrap their brains around. Fortunately by the late 80s these manual tuners were replaced with digitally controlled tuners that removed this hassle and allowed the user to watch any channel they could receive just like having a cable box. Most have forgotten or never experienced this era of manual tuners.</p>

<p>QAM digital cable is far worse in this regard because there is no universal sequence like we had for analog cable. On top of that, many channels will be stored that will appear blank when you tune to them; those are the pay digital channels. You may also see channel numbers come and go. Those are Video-On-Demand (VOD) and Pay-Per-View (PPV) channels that are created on the fly for the customer and removed once the viewing has ended. Nobody can tell you how the raw channel numbers will be displayed for the cable company in your area unless one of your local citizens figures it out, documents it and makes that available on the internet. Many can appear between known analog cable channels, adding to the confusion.</p>

<p><a href="http://www.hdtvmagazine.com/forum/viewtopic.php?t=6884">Georgia, Atlanta - Comcast QAM HD channel list</a> </p>

<p>Despite the inconvenience, there is much to be gained, such as potentially free access to some digital channels and definitely any local DTV/HDTV channels (an FCC regulation) even for simple basic cable service. If your product does not support a cable card or you don't want or need one then you will need to use channel up and down and go through a lengthy process of recording the raw channel number your product is showing and determine what actual channel or program content that is. In effect you must create your own channel map for the digital channels. Once that is done you can manually remove the ones you can't receive, or don't want to show up, during channel scan.</p>

<p><strong>Cable Card</strong><br />
If the product supports a cable card, then getting one resolves all tuning problems since that is where the channel map information comes from for your cable company. A cable card will also allow you to subscribe to other digital channels or tiers of service for your system without having a cable box. Please note that current cable cards do not support VOD or PPV services, and those will require a cable box. For more information, see my recent article: <a href="http://www.hdtvmagazine.com/articles/2007/01/cablecard_basics.php">CableCARD Basics</a>.</p>

<p><B>Gotchya!</B><br />
When you are shopping, keep an eye out for displays that claim to be ATSC or QAM capable yet are limited to 480I output. For example, Hitachi's entry level CRT rear projection HDTVs. The reason for that conundrum is that the FCC defines that any display with a tuner is called a television, and all televisions are required by the FCC to include ATSC tuners to maintain universal compatibility with over the air broadcast systems. The FCC does not specify performance capability, only that it works. Manufacturers like Hitachi decide what performance level they will provide and if you consider that most viewers are using either a cable box or satellite system one can see why they might do that to reduce the sales price. If you move up to Hitachi's next tier, they include fully capable HD ATSC tuners with CableCard for those seeking those features.</p>
