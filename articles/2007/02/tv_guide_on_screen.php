				<p>TV Guide has become the new industry standard for providing the mass market with a universal guide system. It operates anywhere in the US using your local over the air broadcast stations, which are also carried on your cable system. QAM digital cable tuners are typically part and parcel of a product supporting TV Guide, often times including a cable card option. This review will help you navigate the potential problems that may arise in setting up this feature for your HDTV.</p>

<p>When you first install the TV, or other product with this feature, you will be prompted to setup the system by answering multiple questions. The system will then search out the cable system to locate the one or few other channels that carry the TV guide data. Typically this will be your PBS channel(s). After that has been accomplished, the next time you turn on the product you will be asked to select your cable or over the air tuning system. This creates the channel map for the product so the TV guide data matches the channel number you are watching. During the year there may be updates to the channel map. When this happens you will be prompted to select your system again the next time you turn on the product. Anytime you are asked to make this selection it takes another 24 hours to download and reconfigure the TV Guide function.</p>

<p>One important aspect of this free service is that the data is only downloaded when the product is turned off. Most DVRs using TV Guide provide an option to automatically turn off the unit sometime late at night when you are likely to be sleeping to insure your data is kept up to date for those who don't turn off the product for whatever reason.</p>

<p>While TV Guide data can provide up two weeks of scheduling, in practice, this will vary and is directly related to how many channels you have setup on the product and how long it is turned off. If you have too many channels you may not get a full week even with the product turned off for days. While you can remove channels to improve that, they will also be removed from your channel scanning which some may see as an inconvenience.</p>

<p>The length of available scheduling is typically only a concern for those with products that record TV, such as DVRs and DVD recorders. On that note, you should also know that the TV Guide system is not perfect, but not any more error ridden than other services. On occasion, it may slip up and record the wrong program or the wrong time or not at all. Also, on occasion, a change in the data or cable company services will force a new download disrupting your schedule until completed. Most of these products also provide a way to manually record a program which bypasses the TV Guide system altogether, which removes the hassles but also some convenience. We are now getting content that not only varies in day and time slot shown but length as well, such as Dancing With the Stars or American Idol, in which case you would have to reprogram the product regularly for manual applications. Our new TV world is becoming less and less compatible with that concept out-dating the use of a VCR and making data based programmable DVR products a modern necessity.</p>

<p><B>Personal Experience</B><br />
We have one Motorola Moxi DVR from Charter cable, 2 Panasonic DMRE85H DVD Player/Recorder/DVRs and one Sony DHGHDD250 OTA/cable HDTV STB/DVR. My wife calls the TV Guide and Moxi data services "the little people inside the box" and as noted, the "little people" sometimes get the schedule wrong. Her Panasonic has had more problems than mine with TV Guide updates trashing her scheduled recordings to the point where she exclusively uses the Moxi box. My Panasonic has hiccuped a few times as well but from the first incident I changed from TV Guide data recordings to manual resolving all future problems and fortunately for me those shows never change in length or time slot through out the year. The Sony is exclusively TV Guide driven, and so far no real complaints. But it is not used nearly as much my Panasonic or the Moxi products, which has created an unexpected problem with new TV Guide data; If I don't turn it on, I won't know this has occurred so the process will not advance until I set it up, which means nothing gets recorded. Getting the cable card setup for the Sony was an experience I would not want to repeat, nor wish on anyone else. And it should be noted that regardless of how many times they told me the Sony or my house cabling system was at fault, it took 2 months for them to finally get it working and all the problems were directly related to Charter.</p>

<p>If there is anything about the service that seems idiotic it is the TV Guide updates related to cable system changes. All systems I can receive have an internal ID number and I have to tell it which one is mine upon first setup, yet these updates for some reason require me tell it again and again which one is mine and that is the cause of failed recordings. The ID number does not change so I fail to understand why it can't just keep using that ID number, download the data and make necessary adjustments automatically without my input and confirm the next time I turn it on that my cable system has not changed. Those who are waiting for such updates can look at the new cable system(s) available and make a selection. Note that my Panasonic units are notorious for this problem while it happens far less with the Sony.</p>

<p>Recently my Charter cable company decided to dramatically change the channel line up. This knocked out the Moxi for about 24 hours with it showing no guide info at all during that time nor would it record the programs for that day. One end user called Charter and they sent out a service tech! Fortunately the Moxi recovered quickly yet the same could not be said of the Sony or Panasonic. It has now been about 45 days and the channel line up remains incorrect. Fortunately this has not caused a great problem for them due to what and how they are recording and I have yet to do an in depth analysis. This could easily be a problem though if I wanted to record American Idol or several other shows that require correct TV Guide data. </p>

<p><br />
<h2>Troubleshooting</h2><br />
TV guide does not support satellite services.</p>

<p>TV Guide products require a direct connection to the cable or antenna line: You cannot connect the antenna or A/V output of a cable box to a TV Guide enabled product and get data.</p>

<p><B>TV Guide never loads - empty grid:</B><br />
Due to how QAM digital cable tuners work and first time setup, it could take days for the product to identify which channel(s) out of hundreds have the TV Guide data. One trick for that is tune to one of your PBS stations and turn the product off, or in the case of a TV, set it for that channel before you go to bed and turn it off. If you are on the right channel then within 4-8 hours, next morning, you should finally see some TV Guide data appear in the grid. If PBS is getting you nowhere, then move on to the other local channels in your area; one of them has to have it or you are one of the unlucky few in the country that cannot receive the data. </p>

<p><a href="http://www.hdtvmagazine.com/articles/2007/02/atsc_cable_qam_tuners_-_cablecard_or_atsc_ready.php">ATSC Cable QAM Tuners - CableCARD or ATSC Ready</a></p>

<p>New cable card installations can cause problems if not done properly because the cable card provides the channel map and without it your product will be lost. To test for this problem, remove the cable card, setup the TV Guide again and see if the TV Guide data returns the next day. If so, call your cable company and be relentless if they tell you cable cards do not support TV Guide as that is false. The TV Guide data rides on the video signal from the station, and would require additional effort to remove it. Also,this would be illegal per the FCC; all signals are to be rebroadcast fully intact as transmitted by the local station(s). </p>

<p><a href="http://www.hdtvmagazine.com/articles/2007/01/cablecard_basics.php">CableCARD Basics</a></p>

<p><B>No TV Guide data for one or more channels:</B><br />
That is why there are TV Guide updates for your product. As to when such an error will be corrected is unknown, but after waiting over 9 months for the few I had nothing changed.</p>

<p>If you want to record one of these channels using the TV Guide data or have that schedule appear in the program guide you need to check your owner's manual for a feature that will allow you to re-map TV Guide data to a specific channel manually. I had to do this for my Sony on 2 stations where there was TV Guide data for them but was using the wrong channel number or none was specified. I have no idea if any of the updates fixed that or if it changed anything in the background without telling me; from my perspective everything appears to remain as it always was and continues to work.</p>

<p><B>Firmware Updates:</B><br />
If you are having intermittent or wacky TV Guide problems this is something to keep in mind. First and foremost I can only be very fuzzy on this issue. I have not received nor required the first one. On the other hand while there is quite a bit of standardization for manufacturers implementing the TV Guide feature for their product it is also obvious that there is some leeway for self expression and interfacing specific aspects of the service to the user and the unique design of a product. Manual recording, setting up a TV Guide recording, list of recordings and finding a program to record functions of the Panasonic and Sony are uniquely different in presentation and function. With that said, if all else fails, contact the manufacturer or your local authorized service center to find out if there is a firmware upgrade.<br />
