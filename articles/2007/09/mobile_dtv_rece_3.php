<li><a href="/articles/2007/09/mobile_dtv_reception_-_advanced-vestigial_side-band_a-vsb_-_the_implementation.php">Mobile DTV Reception - Advanced-Vestigial Side-Band (A-VSB) - The Implementation</a></li>
