				<p>CableCARD is a new feature that comes with many HDTV displays allowing you to eliminate the cable box from your system (and your bill), saving you some space and a little dough. Most cable cards rent for a few dollars a month. Depending on your cable company, you will be provided the card for you to install, a simple insertion on the back of the product, or they will send out a service rep. Once installed, the cable company must set up your account to activate it. If done right away, as in most cases, it should start working within minutes to possibly an hour.</p>

<p>CableCARDs use the same PCMCIA connection and slot that laptop computers provide for expansion. On a laptop, it is obvious which way the card goes in, but that is not the case for a cable card product. While this device is keyed it is possible to force it in backwards, damaging the card and/or receptacle on the product, in which case the product will need to be repaired and/or cable card replaced. If you are installing one it should slide in easily with a final 1/4 inch of effort to seat the card connector into the jack. If there is any effort to slide it in then either you are not lining up the card properly for insertion or it is backwards.</p>

<p>At this time cable cards have been implemented as one way communication devices only, meaning they do not support VOD (video on demand) or PPV (pay per view) services. If you want to receive these types of services, you must use a cable box. Cable Cards are inherently two way devices, but implementation has been delayed due to two reasons; 1) There remains considerable industry wrangling over what the 2 way standards should be, and 2) Technical problems in the field still lingering with the one way devices. It has been a very tough two years for the cable providers and manufacturing industries as they worked together resolving the problems of implementing universal standards for this system. Based on that experience, if you are having problems it is more than likely due to your cable company. It should be noted that some manufacturers decided to not provide the cable card feature for 2007 in part or all of their line due to the problems. Some have decided it is not worth the hassle.</p>

<p><b>Technical</b><br />
A CableCARD is actually a computer modem device that receives data from the cable company using a different and exclusive carrier on the cable system which is already there and required for their cable boxes. Non-functioning or intermittent CableCARDs have problems for only two reasons in most cases: either (a) the exclusive carrier is too noisy to function properly or (b) the cable company is not setting up the data right in their system to properly activate it.</p>

<p>A CableCARD receives the channel map from your cable company so you can find your channels exactly where they should be as listed and provided by the cable company for your QAM cable tuner. The CableCARD also determines what pay channels and services you will be allowed to view.</p>

