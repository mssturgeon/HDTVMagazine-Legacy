<p>Saturday's early game <b>(4:30pm EST, CBS 1080i)</b> pits the brash, trash-talking and hard-hitting Ray Lewis-led <b>Baltimore Ravens</b> against Peyton Manning and the <b>Indianapolis Colts</b> in the AFC. Lewis and other Raven defenders have already singled out poor Joseph Addai as their primary target. Geez, Addai never did anything bad to them. It has all the makings of a great strength vs. strength AFC Divisional match up.</p>

<p>In the nightcap, the <b>Philadelphia Eagles</b> try to unseat the <b>New Orleans Saints</b> at the rebuilt Louisiana Superdome <b>(8:00pm EST, Fox 720p)</b> in the NFC Divisional game. It's hard to root against either of these teams, which both finished in their respective division basements in 2005 (heck, the Eagles didn't even win an NFC East game, going 0-6). Now, both are reborn, and the winner would deserve the sentimental favorite tag going forward for obvious reasons.</p>

<p>On Sunday, <b>(1:00pm EST, Fox 720p)</b> the <b>Seattle Seahawks</b> swoop into Chicago's Soldier Field, looking to build on the magic (can you say, "Fumbled snap?") they used to edge the Cowboys. It's going to be interesting, considering the <b>Chicago Bears</b> have lost the "sure thing" mantle. If the Seahawks manage to upset the Bears, the Eagles-Saints winner will be licking their chops for next week's NFC title game (either would host against the Seahawks). But Bear fans expect otherwise.</p>

<p>In Sunday's late game <b>(4:30pm EST, CBS 1080i)</b>, the resurgent <b>New England Patriots</b> will pull out every defensive stop trying to confuse <b>San Diego Charger's</b> young QB, Philip Rivers, because the Pats won't be able to completely shut down All-World running back LaDainian Tomlinson. And it looks like Tom Brady has his incredible playoff mojo working on all cylinders. The Patriots are a scary opponent, especially on the road where they are 7-1 this season.</p>

<p>Of course, the NFL isn't the only game in HD town. Tonight (1/11), Labron James and the <b>Cleveland Cavaliers</b> invade the desert to take on the red-hot <b>Phoenix Suns (10:30pm EST, TNT 1080i)</b> in a battle of slam-dunk playoff teams.</p>

<p>For die hard college hoop fans, this Saturday night match up may be the perfect event for your HD DVR, as <b>Georgetown and Pittsburgh (9:00pm EST, ESPN-HD 720p)</b> will go head-to-head against each other, and the NFC playoff game (Eagles vs. Saints). The Hoya-Panther collision is always a physical, fun game on the Big East regular-season slate. Both teams are playing well, so this one be no different.</p>

<p>For soccer freaks, you have <b>Real Madrid vs. Zaragoza (2:58pm Worldsport-HD 1080i)</b> on Sunday afternoon, also going heads-up against the NFL. Again, there's always the DVR option.</p>

<p>Finally, the week wraps up with consecutive NBA marquee games. On Monday, the NBA champion (and Shaq-less) <b>Miami Heat</b> and SI Sportsman of the Year Dwayne Wade visit the left coast to take on Kobe Bryant and the <b>L.A. Lakers</b> (10:00pm TNT-HD 1080i).</p>

<p>Then, on Wednesday night, those same <b>Lakers</b> head for a key hookup with the <b>San Antonio Spurs (9:00pm , ESPN-HD 720p)</b> way down Texas way.</p>
