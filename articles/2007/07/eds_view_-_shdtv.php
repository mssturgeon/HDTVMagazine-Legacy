			<p><strong>SHDTV</strong><br />
(Part Unus)</p>

<p>It has been a long battle, but it has been won - big time.  HDTV is now de-facto, not only nationally but internationally.  The marketing "S" curve is approaching its steepest slope.  Indeed, it is getting hard to find a retail TV offering that is not HDTV capable.  HDTV programming, distribution options and sources are being augmented on an increasingly frequent basis.  (Of course, there can never be enough.) </p>

<p>But, is there another, higher level of home AV that can be attained and should be sought?  The answer is a profound yes - not as a replacement for our present ATSC based system, but as a high level supplement to achieve a truly pristine AV presentation in the home or at small venues.  But, "why," you ask?  Isn't our present system good enough?  For the most part, it is.  Viewing a well produced HDTV video disc movie on a well installed front projection home theater system requires no further convincing, but unfortunately these systems, as good as they are, cannot fully replicate the true theatrical AV experience.  And, they tend to exacerbate (i.e. magnify) compression artifacts found in broadcasted HDTV.</p>

<p>As an increasing number of consumers are opting for HDTV large screen front projection home theater systems, the demand for a greater variety of better quality content is sure to emerge.  Some of this demand will be satisfied by video games and downloaded HDTV program files (media players), but these may not be good enough.</p>

<p>What is needed is another, higher level of HDTV - a "super" high definition television system - SHDTV.  Yes, it will be expensive.  No, it will not replace our present HDTV standard, nor will it be compatible with it.  Yes, it will be global.  No, it will not require (thank God!) any government approval.  And, yes, it has 3D capability.  Best news of all is that the documented standard for SHDTV exists and is being deployed on a commercial basis (albeit somewhat awkwardly) as you read this.  Think of SHDTV as a small venue "IMAX" television system.</p>

<p>Essentially, most all of the technical issues have been addressed, but the economic case for a consumer based model has not.  In my next article on this topic, I will discuss how SHDTV is possible and how it could work as a business.  It is going to get a lot better.</p>

<p>Ed </p>
