<p>A-VSB is a DTV broadcast system for mobile purposes proposed to the ATSC in December 2005. During 2006 Sinclair Broadcast Group, Samsung Electronics, and transmitter manufacturer Rohde & Schwarz, joined efforts to successfully test DTV mobile reception at highway speeds.</p>

<p>A-VSB is expected to be included in the Advanced Television Systems Committee (ATSC) digital-TV standard by 1H07, and is backward compatible with 8-VSB the current DTV terrestrial system.</p>

<p>A-VSB, was previously simulated at NAB in April 2006, using forward-error-correction (FEC) "turbo-coding" for difficult signal environments, which used about one fifth of the transmitted bits for the actual video, the rest was to provide robustness so the signal is tuned well by the receiving device.</p>

<p>In other words, 1.5 megabits per second (Mbps) of transmitted signal would have only 375 kbps of actual video. That number of bits is considered sufficient for small devices such as cellphones and PDAs.</p>

<p>Sinclair's Buffalo digital station, WUTV-DT, received a temporary license for the join group to test A-VSB in a real-world environment, and it did successfully up to 150Mph using a Samsung YEPP portable digital media player to decode and display the MPEG-4 video carried within the turbo-coded streams transmitted from a server specially suited for the parallel transmission of 8-VSB and A-VSB.</p>

<p><br />
<B>CES 2007</B></p>

<p>At CES 2007, Samsung announced A-VSB and did a demonstration at the show.</p>

<p>According to Samsung:</p>

<p>"The A-VSB technology eases synchronization of broadcast signal timing of different towers in a Single Frequency Network (SFN). SFNs can improve broadcast quality with higher uniform signal strength throughout a service area, even in locations that normally would have their signals interfered with by obstacles such as hills or buildings."</p>

<p><br />
<B>SRS</B></p>

<p>"A broadcaster adds a specified Supplementary Reference Sequence (SRS) to the transmitted signal. A-VSB receivers can use the SRS in order to remain "locked in" to the transmission. This helps maintain reception of the main signal and extra 'turbo' signal(s) even when interference would normally disrupt a signal, like when the signal is reflected from moving objects near the receiver. A-VSB also enables the receiver to stay 'locked on' to the signal when the receiver itself is moving, such as when someone is walking with their portable TV."</p>

<p><img src="/images/articles/a-vsb.jpg" alt="A-VSB - Advanced-Vestigial Side-Band" /></p>

<p>"Broadcasters can implement A-VSB technology with no impact on legacy (non-A-VSB) digital TV receivers. Existing legacy receivers (e.g. TV receivers not A-VSB enabled) will ignore the added information in the signal while continuing to receive the main TV stream (e.g., high definition TV programming). In addition, as A-VSB technology helps broadcasters deploy SFNs to fill gaps in the coverage of their service area, owners of legacy receivers may find their reception quality is also improved."</p>

<p>"The upgrade to the current 8-VSB standard could be implemented by broadcasters at low cost, possibly with just a software upgrade", said John Godfrey, VP of government and public affairs for Samsung Information Systems America, a corporate R&D lab.</p>

<p>"One of the options available in the A-VSB standard, he added, would enable terrestrial broadcasters to reach homes and apartments whose over-air signals are currently blocked by tall buildings or mountains. The option would enable broadcasters to build additional towers whose signals could be synchronized with their main towers in much the same way that satellite-radio providers synchronize the signals from orbiting satellites with ground-based repeaters."</p>

<p><br />
<B>Single-frequency Network</B></p>

<p>"Another optional A-VSB technology is called "single-frequency network," a delay signal that broadcasters could insert into their transmission to synchronize the simultaneous transmission of a program on their assigned channel from multiple towers in a market. By filling in coverage gaps, the technology would further improve mobile and portable reception but also improve reception by legacy DTV sets in homes where over-air line-of-sight signals might otherwise be blocked. Synchronization is needed because the reception of two signals slightly apart in time would confuse the tuner and cause the screen to go black", he said.</p>

