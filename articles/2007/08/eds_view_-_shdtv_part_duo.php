			<p>By the end of 2007 more than 5000 North American movie screens will be capable of showing digitally distributed motion pictures, some of which are produced in 3D.  The distribution medium, however, remains mechanical, i.e. the actual digital data are stored as encrypted files on hard discs.  Downloading of the files via satellite has been successfully demonstrated internationally, and undoubtedly will replace the ferrying of hard drives soon.</p>

<p>The key to this high quality, economical motion picture distribution system is the establishment in 2002 of the Digital Cinema Initiative (DCI) specification by the seven giant motion picture studios - Disney, Fox, MGM, Paramount, Sony, Universal and Warner.  In short, the DCI standard is Super High Definition Television - SHDTV.  Now, this same consortium plus additional key players is studying ways to commercially expand DCI applications closer to the consumer marketplace - not only for newly released motion pictures and documentaries, but also for live television events, some produced in 3D.</p>

<p>The most straightforward economic model being considered by the DCI group involves the formation of a private distribution entity wholly owned by the seven (plus) DCI partners.  SHDTV content would be distributed via satellite to three venue groups:  private (home) installations, "small" venue theaters, and traditional theaters that have digital capability.  Content packages available to each venue group would be different.  Five "channels" would be offered initially, with expansion capability to ten simultaneous SHDTV programs.  Private venues would select and purchase content using a subscription/PPV model, similar to the PPV models being offered by DBS satellite and Cable.  Video-on-Demand (VOD) is not being considered.  </p>

<p>Receiving hardware for the private installations would be tightly controlled.  I am not sure what that means, but clearly the implication is that equipment would be offered only through licensed home theater installation outlets.  Lease or lease-to-buy, or buy packages are contemplated.  Obviously, this business paradigm is not intended to follow a mass-market CE product model, nor (I was asked to emphasize) is it not intended to replace, but to augment, our present terrestrial DBS and Cable HDTV ATSC based distribution systems.</p>

<p>Technically, as implied, the described SHDTV system is based on a subset of the presently deployed DCI specifications.  Essentially, most all system components are in the final states of design or are in-place except the electronic link i.e. the satellites themselves and the wideband RF receiver systems.  Transponder spectrum "slots" are not a problem, but the system is a bandwidth "hog."  There is nothing economical about it, nor is there intended to be.  </p>

<p>After analyzing an outline of the technical specifications available to me and doing some grade school mathematical extrapolations, the absolute value of 15 appears to be a good "paper napkin" approximation of costs, capability and technical demands.  That is, simply multiplying or dividing by 15 will give a reasonable estimate of the techno-economic demands of SHDTV.  Here is a summary of the contemplated technical specifications:</p>

<p><strong>Resolution</strong><br />
The SHDTV resolution is 4096 x 2160 pixels at 24fps. <br />
The highest resolution of the ATSC HDTV system is 1920 x 1080 pixels at 30fps; therefore, SHDTV has roughly four times the resolution (sometimes called 4K) as HDTV.  </p>

<p><strong>Aspect Ratio</strong><br />
The aspect ratio is 1.89:1. Further, the 4x structure will support 2.39:1 with bars. Our present HDTV aspect ratio is 1.77:1.</p>

<p><strong>Compression</strong><br />
The no-loss version of MJPEG 2000 is employed.<br />
This is a very inefficient, but very high quality compression system.  Essentially, each frame is individually compressed, eliminating motion estimating artifacts present in MPEG.  Also, bit errors translate into resolution errors, not blocking artifacts as with MPEG.</p>

<p><strong>Pixel Sampling</strong><br />
SHDTV employs 16 bits/color (48 bits/pixel) image sampling.<br />
Present HDTV imagers used for ATSC rarely sample above 24 bits/pixel. The higher the image sampling rate, the greater gamut (depth) of color available.</p>

<p><strong>Video Compressed Payload Bit-rate</strong><br />
The RF link supports a streaming payload of 250 Mbits/second. <br />
This is approximately 13 times the ATSC HDTV payload bit-rate. </p>

<p><strong>Audio</strong><br />
An uncompressed, 8 channels, 24 bits/sample, 48 kHz sampling rate system is employed.<br />
This provides "no compromise" CD quality audio.  There is no acoustical specification, only recommendations for each venue group.</p>

<p><strong>Security </strong><br />
The security system is based on IP delivered keys, metadata and conditional access using payload synchronized encrypted FTP sites.<br />
This is not part of the present DCI specification which is designed for file transfer, not streaming.  (Also, I'm not sure they didn't make this up, as I have no idea how it could operate.)</p>

<p><strong>3D System</strong><br />
DCI does not specify a 3D system per se, but probably the Real D solution will be employed.</p>

<p>Will this all work?  Technically, of course it will.  Commercially, I obviously believe so, although there is a very high lawyer to engineer ratio in play.  But when one considers that the "Hollywood" content moguls with the vast collective monitory resources available to them are driving this concept, it will happen.<br />
Want a preview?  Simply find one of the growing number of theaters showing digital movies and have a peak.</p>

