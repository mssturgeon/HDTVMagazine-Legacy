				<p class="editorial">Shortly after this article was published, I attended the annual CEDIA show in Atlanta, GA. While there I had the pleasure to meet Eric R. Lanham of Just Lamps who was trying to get the word out about counterfeit lamps. For more information on counterfeit and after-market lamps, please visit <a target="_blank" href="http://www.genuine-lamps.com/">http://www.genuine-lamps.com/</a>.</p>

<p>If you suspect lamp failure the first step is to check your owner's manual, which will tell you how to read/interpret the indicator lights on the front of your TV or on your front projector. If you do not have the owners manual, odds are very high you can find it on the internet and download it. Manufacturers often times provide these manuals on their web sites.</p>

<p>A lamp timer showing hours accumulated is typically not available for rear projection micro-display products via the customer menus and is found in the service menu, an area consumers are not supposed to access. HDTV Magazine does not support service menu access by consumers and suggests you research this aspect via a Google search if this is of interest to you. Front projectors on the other hand typically do provide this information, along with the ability to reset the timer, in the customer menu. Keep an eye out in your owner's manual for any filters that may exist and should also be inspected, maintained or replaced for your particular display. </p>

<p>There are a handful of displays that do not have lamp indicator lights. Sometimes a lamp failure will not trigger the lamp indicator. Remove the lamp cartridge and physically inspect it. Sometimes the lamp will shatter, making failure obvious. If not obvious, in the center is a glass rod that can crack along with a metal wire from the glass rod to the reflector around it which can melt and you will see the wire is missing a section in between.</p>

<p>The owner's manual will tell you how to replace the lamp cartridge, which will be located on the front, rear or side of the display and require the removal of a few screws to remove a cover and some more screws on the lamp cartridge. The owner's manual typically provides the part number of the lamp cartridge so you can order it. If the part number is missing you should contact the manufacturer to make sure you get the right lamp cartridge. A replacement lamp cartridge may be available locally and it is recommended that you acquire an OEM, Original Equipment Manufacturer, replacement. By following this route you can rest assured that the lamp is not counterfeit and replacement will be easy. Many manufacturers either provide a direct phone number and/or website for genuine replacement parts or a list of distributors that provide genuine replacement parts. Some lamp cartridges come with an additional dud or core deposit fee that will be credited upon the return of your old lamp cartridge.</p>

<p>Be very wary of using an internet search engine to find a lamp cartridge. You will find a ton of "bare" lamps along with some lamp cartridges. More than likely the lamp cartridge is not an OEM product but a recycled lamp cartridge where an outside source has provided their own bare lamp within. This is covered in more depth in the next section.</p>

<p>When handling the lamp cartridge do not touch the glass lamp surfaces with your hands because body oils can cause a hot spot on the surface and crack the glass due to the intense heat the lamp generates. If the lamp glass is inadvertently touched, clean fingerprints off with denatured alcohol (NOT RUBBING ALCOHOL) and wipe dry with a soft clean lint free cloth. Do not use cleaning rags or material that can leave a residue. When inserting the lamp cartridge it should simply slide into place with little effort and will resemble the same amount of effort it took to remove. Some models may have wires that need to be moved out of the way or even an exhaust housing to be removed in order to access the cartridge. With some models the cartridge does not line up quite right, getting stuck with only about an inch to go. This means the cartridge jack and cartridge housing plug are not lining up. Do not force the cartridge or you may find yourself merely forcing the cartridge plug right out of the cartridge housing, creating a repair. The key here is to wiggle the cartridge back and forth and side to side where it gets stuck so they will line up, allowing the cartridge to easily seat into place. The lamp cartridge screws need to be only snug - do not over-tighten.</p>

<p>This represents the official stance on lamp replacement by manufacturers. The lamp cartridge is consumer friendly and easily replaced by most owners. Most lamp cartridges run $150-250 for rear projection micro-displays. Front projection micro-display lamp cartridges are notoriously more expensive running $300-450. I wrote an article a while back about <a target="_blank" href="/articles/2007/02/hdtv_tlc_extending_the_lamp_life_of_your_hdtv_microdisplay.php ">Extending the Lamp Life of Your HDTV Microdisplay</a>, which has some useful tips  ...  definitely worth a read in this economy.</p>

<p><br />
<b>Bringing Down the Cost</b></p>

<p>In our industrious calculating world there are other ways to fix your lamp problem for less money by replacing the lamp contained within the cartridge. In searching for a lamp cartridge on the internet, more than likely you found a ton of results for purchasing a bare lamp.</p>

<p>While this approach is certainly valid on the surface you are also opening yourself up to counterfeit or improperly cross referenced replacement lamps. While replacing the lamp in some cartridges is straightforward, there are others that will require careful disassembly to avoid breaking anything because there is one part that is not available for your product; an <i>empty</i> lamp cartridge.</p>

<p>During the replacement use gloves when handling the new bare lamp so you do not get body oils on it, which can cause the lamp to crack due to the intense heat the lamp generates. As mentioned above, if the lamp glass is inadvertently touched, clean fingerprints off with denatured alcohol (NOT RUBBING ALCOHOL) and wipe dry with a soft clean lint free cloth. Do not use cleaning rags or material that can leave a residue.</p>

<p>It will be difficult, if not impossible, for you to determine if you are being sold a counterfeit lamp or an improper cross reference. I recommend buying a bare lamp that also comes with a warranty of 6 months or greater providing at least some measure of confidence that you are getting the real deal. In most cases the warranty will provide one replacement lamp. Print a copy of the web page you are viewing along with the statement of warranty and keep them during the warranty period. Order the lamp with a credit card so you have another avenue of consumer protection.</p>

<p>The shenanigans taking place over the sale of after-market bare lamps and lamp cartridges is overwhelming and frustrating. Some retailers actually go to sites such as this one, create an account posting about replacing a lamp, following that up by creating another account and posting the answer along with a link to their site all under the guise of a public member seeking advice and another public member sharing their positive personal experience with a bare lamp retailer. In short, be wary of trusting internet forums for lamp purchasing advice, particularly from users with few posts and no history or reputation on the site.</p>

<p>Some bare lamp retailers also provide lamp cartridges, and buyers will think they are getting an OEM lamp cartridge when what they are really getting is a recycled lamp cartridge where the retailer has replaced the lamp with their own bare lamp sources. Recycled lamp cartridges such as these are typically perceived by the consumer to be an OEM lamp and when asked OEM questions about the box and packaging answer in the affirmative. Upon arrival the service center finds out that while the box has the appearance of OEM packaging it isn't because it is missing the typical fonts and labeling the service center has experienced from the manufacturer, which nearly all consumers simply would not know. There are bare lamps that meet the electrical specifications yet miss entirely for color temperature - such as being far more yellow or have less light output than the OEM lamp.</p>

<p>Some OEM bare lamps are not available except from the manufacturer, such as the Mitsubishi Turbo series. This lamp design improves the focal pattern of the back reflector and turns the safety glass into a lens as well to capture typically wasted light improving efficiency thereby increasing light output for the same wattage of a generic lamp design. Bare lamp retailers will suggest a generic lamp instead for the Mitsubishi Turbo and while they may meet electrical requirements they clearly are not duplicating the light output capability of the OEM lamp.</p>

<p>Ultimately counterfeit lamps or incorrect cross references cause lots of trouble for the owner and the service center they are likely to call when either the new lamp does not strike, strikes intermittently or fails prematurely. In most cases the service center will either replace the lamp/lamp cartridge or request you purchase an OEM lamp cartridge to confirm you have a genuine service problem before contracting the service call. A common request from either the lamp retailer or the owner is to have the product inspected in case the problem is due to something other than the lamp. In most cases this service will increase your expense, generating a service call fee and possibly additional labor and likely ending up full circle right back to replacing the lamp again with a known quality source. Every lamp problem diagnosis typically starts with an OEM correct lamp to avoid chasing non-existent problems!</p>

<p><br />
<b>Extended Warranty</b></p>

<p>Most extended warranty policies cover at least one lamp replacement and you must call the insurance provider listed in your contract to request one. Cost cutting has become part and parcel of extended warranty insurance. As a result, it has become common over the last few years for your provider to send you a bare lamp kit rather than an OEM lamp cartridge. Insurance providers are under far more pressure to balance cost than a retailer is since they cannot charge you directly for the lamp to cover the cost of doing business, yet cannot afford premature failures and multiple lamp replacement. While you stand a good chance of getting the real deal keep in mind they have also suffered the same problem as lamp retailers, although on a smaller scale.</p>

<p>What you should know is you do not have to accept a bare lamp kit from them. All revolve around the original terms of service as provided by the manufacturer. Per the manufacturer, the product was designed for the owner to easily and conveniently replace the lamp cartridge; therefore you retain every right to request and expect a lamp cartridge be provided. On top of that, if you cannot perform this service you also retain the right to request it be done for you by a service center. You can also make the same request over a bare lamp kit although you will also likely have to wait until you can be scheduled; many would opt for the lamp cartridge under those conditions.</p>
