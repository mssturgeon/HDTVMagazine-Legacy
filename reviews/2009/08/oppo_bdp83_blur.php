<p>It was in September of last year that we first got wind that OPPO was developing a Blu Ray player. Since then we have received a boatload of emails asking us when it would become available. The good news for those who have asked is the answer is it is available today! The BDP-83 can be found online for $499.99 and is available at the HT Guys store.</p>

<p><br />
<h2>Features</h2></p>

<ul><li>Universal Blu-ray disc player providing playback for a myriad of video formats</li><li>Supports Blu-ray, SACD, DVD-Audio, DVDs, and CDs</li><li>24 Frames per second support</li><li>Two USB ports allow for playback of media stored on a flash drive</li><li>Uses award-winning video processing chip for a clear, true picture</li><li>Device measures 17.0 x 3.0 x 13.25 inches (WxHxD)</li></ul>

<p><br />
<h2>Setup</h2></p>

<p>It looks like OPPO has taken a page out of the Apple Playbook, minimalistic and elegant. OPPO includes a high quality HDMI cable with the product which is a nice touch. They want you to have a great out of the box experience. We connected power, Ethernet (required for automatic updates and BD Live capability), and HDMI. The HDMI was connected to our Pioneer receiver and we were off to the races. Our 65 inch Mitsubishi DLP TV is already properly calibrated so no tweaking was done to the player. But if you chose to you can adjust the player to dial in the picture.</p>

<p><br />
<h2>Blu Ray</h2></p>

<p>The first thing you notice is that the player loads discs faster than any other player we have owned or used. This is nothing to just brush off. The Samsung 1400 that the OPPO replaced took so long that you could go an pop some corn before the movie was on screen. As far as video quality goes, it was quite good, but we wouldn't say it was any better than than other players in its class. Same goes for the audio. Both audio and video quality are a function of the mastering of the disc. We can say that the OPPO player did not affect the quality adversely. The player will decode Dolby True HD and DTS Master Audio and send it to the receiver via HDMI in PCM format or through its 7.1 analog outputs. We chose to send a bitstream version of the audio to the receiver just because we like seeing "True HD" on the front of the receiver. If all things were equal vs other players we would recommend the OPPO based on load times alone. But there is more to love about this player. Keep reading.</p>

<p><br />
<h2>Up Converting Standard DVDs</h2></p>

<p>This is where the OPPO outshines its competition. OPPO is know for building great upconverting DVDs players so we had high expectations when this unit arrived. The BDP-83 did not disappoint! The upconversion was as good as their former top of the line player the DV-983H because OPPO is using the same Anchor Bay deinterlacing and scaling technology. The Player easily passed all the tests on the HQV Benchmark Disc. Subjectively the player did a great job with the random DVDs we threw at it. With most of our discs you could see a noticeable improvement in quality. There was a small number of discs where it was harder to tell.</p>

<p><br />
<h2>Media on External Devices</h2></p>

<p>Two USB 2.0 high speed ports are provided, one on the front panel and one on the back. That will allow you to play your high definition video, high resolution photos and music directly from the USB ports. Its as simple as plugging the drive into the USB port and navigating to the content. There was no album art displayed on the screen for audio files. And it was very simple to start a slide show with music playing in the background.</p>

<p><br />
<h2>Odds and Ends</h2></p>

<p>The OPPO Menus are very clean and easy to navigate. The remote is a little busy not no more so than any of the other Blu Ray player remotes out there. The player was easily integrated into the Harmony remote so like all our other remotes it was placed in storage in the office. We are not big fans of BD Live but if you are the player fully supports it and it does not require you to add and USB stick for the storage. The BDP-83 comes with 1GB of on board storage. Not that many of you would need this but the player will allow you to output HD on component and HDMI simultaneously. There is support for RS-232 control for custom installers.</p>

<p>For those of you who have invested in a high quality video processor the BDP-83 has something called "Source Direct Mode" In this mode the video on the disc is sent to the processor unaltered. This way your video processor is working on the content exactly as it was recorded to the media.</p>

<p><br />
<h2>Conclusion</h2></p>

<p>If you have a large investment in standard DVDs this player is a must for you. It will allow you to enjoy all your old DVDs with improved quality befitting your HD projector or large format TV. Plus its its a high quality Blu Ray player that supports the complete Blu Ray specification and plays SACD or DVD Audio discs. Add to that OPPO Digital's excellent customer service, you can't go wrong.</p>
