<p>Today we take a look at the <a href="http://www.samsung.com/Products/TV/DLPTV/HLS5687WXXAA.asp">Samsung HL-S5687W 56" Widescreen 1080p DLP</a> ($2100 at a Big Box Retailer)). The TV has the newer color wheel that is supposed to be faster, bigger, and quieter. According to Samsung this will provide a smoother picture, even with fast motion, with more accurate color.   The TV's main features are:</p>

<ul>
<li>1080p (via Wobulation)</li>
<li>10,000:1 Contrast Ratio</li>
<li>Faster, Bigger, Quieter color wheel</li>
<li>Dual HDMI inputs</li>
<li>Only 16.3 inches deep and 64 lbs</li>
</ul>

<p>One of the big knocks we have had against DLP technology is how it handles dark scenes. With a 10,000:1 contrast ratio we were hoping that we would see a major improvement in this area. We saw an improvement but we wouldn't call it major. There is still material that is not visible with this TV. Just so we are all on the same page we used chapter 22 of Blackhawk Down as out standard. We are both very familiar with this material and use it for our tests. We thought the colors weren't as vivid as the SONY SXRD but it was hard to say as we did not have the SXRD next to the Samsung during the test. We remember how the colors just popped off the screen with the SXRD and we did not get that from this DLP. Skin tones looked a bit washed out. This TV needs to be calibrated to get the best color out of it. Do not just buy it and leave it with the default settings. You will be very disappointed. After calibration the color was improved.</p>

<p>The TV does a good job with 480i/p, 720p, and 1080i. We though this TV had one of the best SD pictures we have seen. ESPN sports looked great but overly compressed sports looked worse on this TV. Los Angeles ABC is 720p and it did not look good on this TV. HDNET Hockey looked great! That proves what we have been saying all along. Sports at 1080i can be done but you need a high data rate.  Movies on 1080i channels looked better than we have seen. Detail on the actor's faces was highly visible and was a good as the SXRD. Detail in general was good on this TV.</p>

<p>As mentioned above Standard Definition looked great. This TV has a good scaler. Your standard DVDs will see an improvement just by connecting it to the TV.</p>

<p>Is the better color wheel all that it is cracked up to be? Well from the point of view of rainbows the answer is yes. Ara can see them all the time on his second generation DLP. He knows exactly what to do to make them happen. On this set there was nary a one. No matter how hard we tried we could not see a rainbow. Now we hate making statements like that because someone out there will say that they see them all the time. But it does not change the fact that we did not see them. Take that for what its worth. Samsung claims that the color wheel is quieter. Maybe it is but you can't hear it over the fan anyway. Also, this is a bulb based light system so plan on spending $250 a couple to three years on replacements.</p>

<p>The TV has a very nice looking cabinet with hidden speakers. The speakers do not add or detract from the TV both visually or sonically. The remote is basic but provides easy access to key features of your TV. The menus are easy to navigate. One issue we have with the TV is that you can not get to an input directly. The source button toggles through the inputs that have something connected to them. You can label each input with DVD, DVR, etc so its easy to find the input you are looking for.</p>

<h2>What we liked:</h2>
<ul><li>Great HD picture (for sports and movies)</li><li>One of the best SD pictures we've seen on a TV this size</li><li>No Rainbows</li><li>1080p</li><li>dual HDMI</li></ul>

<h2>What we disliked:</h2>
<ul><li>Color was not as vivid as SXRD but still pretty good</li><li>Some detail lost in dark scenes</li></ul>
