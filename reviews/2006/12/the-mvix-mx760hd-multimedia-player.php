<p>If you remember back in March of this year (Episode 76), we reviewed the Mvix 5000U multimedia player.  We really liked it, but were hoping for the release of a wireless version.  Well wait no longer, the wireless version has arrived.  But not only is it wireless, it also fully supports high definition, so it's right up our alley.  The basics are the same, you buy the new unit, the MX-760HD, add any 3.5" HD and you're set.  But that's where the two units start to diverge.  With the 760HD, because of the wireless (or wired) network connectivity, you don't even need the hard drive.</p>

<p>While the 5000U had composite, s-video and component video outputs, the 760HD adds a DVI output.  They both have stereo analog, digital coax and optical audio outputs.  In addition, the 760HD allows you to connect external USB devices to expand its storage capacity, or to temporarily connect another device, like a portable media player.  Then there's the network capabilities.  The 760HD has both wired and wireless ( 802.11g with WEP support) connectivity options.  So you can simply plug it in ... or not.</p>

<p>For file types the 760 HD will play back just about anything.  It supports: DivX<sup>&reg;</sup> (3/4/5), Xvid, MPEG 1/2/4, WMV-9, ASF(WMV9), DAT, DVD(IFO, VOB), ISO, HD-level TP, TS, TRP, MP3, WMA, AAC, OGG, PCM, AC3, DTS decoding including down-mixing, DTS pass through, BMP, JPEG/JPG, and PNG.  There really aren't that many formats out there that it won't play.  Of course, it won't playback protected content.</p>

<p>Setup is pretty simple.  To install the hard drive you just remove one screw, pop the drive in place, plug it in and put the screw back in.  It may be a little advance for some, but the instructions are pretty easy to follow.  Once the drive is in, you can connect it to your computer as a USB drive and transfer any files you want to store on it.  Setting up the wired network is as simple as plugging in the cat-5 cable, assuming you use an automatic network configuration (DHCP).  Setting up the wireless network isn't as easy because you have to type everything in - it won't discover the wireless networks for you.  But if you know the name of your wireless network, and your WEP key, it isn't very difficult.  That's it - you have access to all the files stored on the device, as well as all the files shared on your network.</p>

<p>It handled every file type we threw at it without problems, DivX HD, WMV HD, XviD, WMA, MP3, you name it.  The only time it struggled was with content streamed over the wireless connection.  It had trouble playing a DVD from a shared DVD drive on the network using wireless, it also struggled with WMV HD, 1080p was a complete failure and 720p stuttered.  But that's just a limitation with 802.11g, not the 760HD.  Using a wired connection, everything ran fine.  While connected to the wireless network, it was able to playback a compressed, backup copy of a DVD that was on an external USB hard drive connected to a laptop that was also connected to the network wirelessly.  Plain and simple, it just worked.</p>

<p>The NAS functionality isn't working yet, but will be enabled with a firmware upgrade in the very near future.  We also had a bit of trouble getting the 760HD to find an external USB hard drive we had connected to it.  This should be addressed in a firmware upgrade in the near future as well.</p>

<p>Overall the Mvix MX-760HD was a smashing success.  We can't wait to get the new firmware and try it out as a NAS device.  That should also allow us to update the files on the device itself without having to USB cable it to a computer.  Very cool feature.  With that enabled, one of these may work really well in the car as a mobile entertainment center.  It's really like a home theater Swiss army knife, and would fit well in just about anyone's stocking. </p>
