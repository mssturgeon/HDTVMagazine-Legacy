 </p><p><span style="color:black; font-family:Arial">The pads that go around the ear are made from the same material that's used in memory foam mattresses. This helps the headphones form a tight comfortable seal around your ears. But due to the tight fit you may experience some sweating and after about an hour or so you may find that your ears start to hurt.
</span></p><p>
 </p><p><span style="color:black; font-family:Arial">The ear pads are held on with magnets so if something were to happen to them they can easily be replaced. Removing the ear pad reveals a jack for the cable. The plug makes it easy to replace the cable should it fail over time. The cable comes with an in-line microphone and control for your iPhone. 
</span></p><p>
 </p><p><span style="color:black; font-family:Arial">The headphones come with two cables, one for the iPhone and a standard 3.5mm cable that can be used on any device. B&amp;W also include a two prong airplane adapter. Do any airlines use those anymore? The travel case is nice and worthy of the $300 headphones.
</span></p><p>
 </p><h3><span style="color:black; font-family:Arial; font-size:14pt"><a name="h.vuc4hn18jpxg"/>Performance:
</span></h3><p><span style="color:black; font-family:Arial">The P5s did a great job with all our source material. Music with a strong bass did quite well. Podcasts sounded a bit bass heavy however. We did find that the P5s didn't do as well with higher frequencies. We could barely hear the triangles in Beethoven's Ode to Joy. Pounding rock like Hole's Violet had a lot of punch and the live version of Van Halen's "You Really Got Me" put you in the concert! 
</span></p><p>
 </p><p><span style="color:black; font-family:Arial">Movies did really well too. Dialog was easy to understand and the noise isolation made it easy to hear at lower levels. One issue we have is that on airplanes the dialog can be hard to hear. With the P5s it's easier to hear because the noise from outside is reduced. Effects are where the P5s shined. No other headphones we used have sounded as good with special effects.
</span></p><h3><span style="color:black; font-family:Arial; font-size:14pt"><a name="h.6sprve1461y7"/>What we liked:
</span></h3><ul><li><span style="color:black; font-family:Arial">Deep rich bass
</span></li><li><span style="color:black; font-family:Arial">Good sounding dialog in movies
</span></li><li><span style="color:black; font-family:Arial">Noise isolation
</span></li><li><span style="color:black; font-family:Arial">Stylish design
</span></li><li><span style="color:black; font-family:Arial">Removable ear pads
</span></li><li><span style="color:black; font-family:Arial">iPhone support
</span></li></ul><p>
 </p><h3><span style="color:black; font-family:Arial; font-size:14pt"><a name="h.yle7l3n2ehcz"/>What we disliked;
</span></h3><ul><li><span style="color:black; font-family:Arial">High price
</span></li><li><span style="color:black; font-family:Arial">Ear pads will heat up your ears
</span></li><li><span style="color:black; font-family:Arial">High frequency playback
