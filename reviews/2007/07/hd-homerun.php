<p>Do you have a computer that is capable of displaying HD pictures but have no way to get an ATSC signal to the screen? The HDHomeRun now makes it possible to place a tuner anywhere in your house, as long as you have a network connection near by, and send the television picture to any or all computers on the network. The HDHomeRun is a small device a little bigger than a paperback novel. It has two ATSC/QAM tuners and a 100 baseTX Ethernet port. The concept is very straight forward. The digital signal is received by the tuners and than multi-cast on your network for all computers to receive. You can put more than one device on your network but when you use more than three you need a gigabit network to support all the data traffic.</p>

<p>The HDHomerun is compatible with:<ul><li>Windows Media Center:<ul><li>MCE 2005 32-bit</li><li>MCE 2005 64-bit</li><li>Vista MCE 32-bit</li><li>Vista MCE 64-bit</ul></li><li>MythTV - DVR for Linux</li><li>SnapStream BeyondTV - DVR for Windows</li><li>SageTV - DVR for Windows</li><li>MediaPortal - DVR for Windows</li><li>GB-PVR - DVR for Windows</li><li>Pluto - Home automation & media system</li><li>VLC - Multi-platform media viewer</li><li>TSReader - MPEG-2 transport stream analysis</li></ul></p>

<p>For Mac users we found out from the company that they are working with El Gato Systems to support this product. But for now you can download a nice application called <a href="http://yanoweb.com/HDHRControl.zip">HDHR Control</a> that will steam the content out on port 1234 and you can use the open source VLC application to watch the video.</p>

<p><strong>Setup</strong><br />
The setup is straight forward. You connect the antenna or cable source, plug the device into the network, and apply power. Then you are ready to scan for channels. You can do this automatically or manually. On the Mac the auto scan feature of HDHRControl was not functioning so we added the channels manually. The HDTVPub website was a lifesaver here. You put in your zip code and you get back all the channel numbers for digital TV in your area. We had some issues with the devices ability to pick up channels that our other digital tuners could. With the version of the firmware that came pre-installed we could only pick up about three channels. Our Tivo and EyeTV 500 was able to pick up more than 20 including some from San Diego (our test site is 55 miles from the LA towers and 90 miles from the San Diego towers). A quick scan of the forums and a call to tech support told us about a new version of the firmware that was supposed to help with this situation so a download later we were up and running with the same performance as the other tuners.</p>

<p>We also want to comment on Silicon Dust's customer support. These guys are great! They read posts on their forums and usually respond quickly to issues their users are having. You kind of get the feeling that you belong to a special group of users.</p>

<p><strong>Performance</strong><br />
The device does exactly what the company says it does. It streams HDTV over your network. With that said some things you should consider. We found that you need a pretty powerful processor to handle the data and forget about 802.11g (we didn't try 802.11n but it should probably work even if you only get 50% of the theoretical maximum data rate). All our dual core computers had no issues with the content but our Powerbook G4 couldn't keep up.</p>

<p><strong>What can I do with this Device?</strong><br />
If you think about what the HDHomeRun can do, it can become an extremely important part of any home theater network. With this device you no longer have to have your antenna connection next to your HTPC or any other computer for that matter. One antenna run can support the entire home. You can install DVR software like SageTV on all your computers and have DVRs all over the home. Sure you could do this without the HDHomeRun but you would need to run antenna cables to all your computers. When the time comes to upgrade your wireless to 802.11n you'll be able to watch your local OTA television anywhere you can take your laptop within the range of your WiFi connection. There limitations however, the device only works with OTA or unencrypted digital cable so you are restricted to watching and recording network TV. Also, the firmware was a bit particular. It would require the box to be reset every once in a while in order to tune in some of the channels and some of the multicast channels did not show up where they should have been. That may have been an issue with the HDHR Control software however.</p>

<p><strong>Conclusion</strong><br />
This is a nifty device and at $170 its the cheapest way to add two HD tuners to your computer. We did not get a chance to try it out with the MythTV box yet but from everything we read on the Silicon Dust forums it should work. This setup would have saved us about $150 off the total cost of our MythTV box. It can add HD capability of older PCs as long as the processor can keep up and you have a wired network. Maybe now Ara has a reason to drop a network connection in the master bathroom and buy a new laptop. What better way to watch the local news while getting ready in the morning? Don't laugh his wife already does this with the SlingBox but now she'll be able to watch the news in HD!</p>
