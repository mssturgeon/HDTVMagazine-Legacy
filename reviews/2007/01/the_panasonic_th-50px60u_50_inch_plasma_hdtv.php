<p>In a recent podcast (<a href="http://www.htguys.com/archive/2006/December292006.html">Podcast 132</a>) we both put together and HD starter system. Braden chose the <a href="http://www2.panasonic.com/webapp/wcs/stores/servlet/vModelDetail?storeId=15001&catalogId=13401&itemId=96291&catGroupId=24973&modelNo=TH-42PX60U&surfModel=TH-42PX60U&cacheProgram=11002&cachePartner=7000000000000005702">Panasonic TH-42PX60U</a> Plasma HDTV ~$1,300 US Street Price. Today we are going to take a look at its bigger cousin the <a href="http://www2.panasonic.com/webapp/wcs/stores/servlet/vModelDetail?storeId=15001&catalogId=13401&itemId=96292&catGroupId=24973&modelNo=TH-50PX60U&surfModel=TH-50PX60U&cacheProgram=11002&cachePartner=7000000000000005702">TH-50PX60U</a> 50" Diagonal Plasma HDTV ~ $2,000 US Street Price (<a href="http://www.htguys.com/shop.php?id=B000F4CTUK">Buy Now</a>). Other than the resolution of this TV, pretty much everything else we say about it applies to the 42 inch version. This TV come with built-in ATSC/QAM/NTSC Tuners, SD Memory Card Slot (for photo viewing). It has a contrast ratio of 10,000:1 and can display 29 billion colors. This is a 720p TV with a resolution of 1366x768 and has to HDCP compliant HDMI inputs.</p>

<p>The TV build quality is first rate. The only thing we didn't like about it was the silver finish. We have really started to take to the Piano Black finish that other manufactures are using. Another plus with this TV is that the speakers are mounted underneath the screen which makes the overall width of the TV smaller. The full dimensions of the TV are 31.6'' x 49.9'' x 5.5'' ( 80.26 x 126.75 x 13.97 CM) without the pedestal and its pretty light as far as Plasmas go weighing in at a hair under 95 pounds (43.2 Kgs).</p>

<p>The picture looks amazing with high quality HD material. The blacks are a black can be. Colors are vivid and accurate. The greens just popped off the screen. The nice thing about plasmas is the off angle viewing and this TV is no exception. Colors stayed true out to about 170 degrees. Vertical colors stayed true whether you were standing up or sitting on the floor. So gaming with the Wii should be no problem. The TV passed the detail test as well. It consistently displayed detail that was lost on other TVs that we have reviewed or own. Dark scenes are not an issue for this TV. We did pick up a lot of glare in these scenes and that is a problem with most plasmas. The glass is very reflective and because it is dual layer you get double the reflection. Its not an issue with bright scenes.</p>

<p>Not everything was good with the picture however. We found that it did not do well with overly compressed 1080i content. Most TVs don't do well with this type of signal but we found the Panasonic did worse. Heroes, which looks bad on Ara's DLP also, looked very bad. Forget about Sunday Night football. If you base it on NBC's HD you will be disappointed. The picture would pixelate at any motion. By contrast 1080i on CBS looked much better. Football looked like you were looking through a Skybox window. So with a good source the Plasma was amazing. With a poor source it made it difficult to watch.</p>

<p>The TV was more forgiving with 720p material. Even with highly compressed material the TV presented a clear and sharp picture. With a quality source like ESPN the picture was amazing! Movie sources like DVDs (both upconverting and standard) looked sharp. With a TV of this size we would recommend an upconverting DVD player. Standard DVDs looked good but it was easy to see the difference with the upconverting player. HBO, Showtime, and HD Net Movies looked great as well. Standard Definition TV looked OK in our opinion. Text was not very crisp so it may bother you when watching a news program with a ticker. But when Standard Definition was run through a set top box that upconverted the picture we found that it didn't really matter as the set top box cleaned up a lot of the issues. This would only be an issue if you were watching standard cable via this TV.</p>

<p>Menus are very clean and simple to navigate. The remote is basic and we recommend replacing it with a universal remote (but when have we not said that). The TV has a digital output that makes it possible to send the Dolby Digital audio track received over the air via the ATSC tuner to your Home Theater Receiver. The speakers as we mentioned before are underneath the screen and sound OK. The TV has a virtual surround mode that we found kind of useless. The audio was clear and easy to hear though.</p>

<p><strong>What we liked:</strong><ul><li>Deep Inky Blacks</li><li>Bright Vivid colors</li><li>720p picture second to none</li><li>Very wide viewing angle (both horizontal and vertical)</li><li>Digital Audio output</li></ul></p>

<p><strong>What we disliked:</strong><ul><li>Poor handling of highly compressed 1080i content</li><li>Standard Def viewing</li><li>Silver Cabinet</li></ul></p>

<p><strong>Conclusion:</strong><br />
Panasonic is the number one manufacturer of Plasma TVs today. When you consider that they are the most reasonably priced tier one manufacturer its a no brainer. If you watch a lot of NBC you may want to go to a retailer and ask them to turn on NBC HD one evening and see if you can live with it. </p>
