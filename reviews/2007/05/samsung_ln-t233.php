<p>There's an old adage that says "never shop at Costco when you're hungry."  If you do, you'll typically walk out of there with way too many snack foods.  We'd like to extend that adage to include "never shop at Costco when you've got an HDTV itch."  It's just way to easy to walk out of there with a new television.  That's exactly what happened to Braden a few days ago.  He was at Costco, because, well who doesn't want to go to Costco? And of course, needing a new HDTV, happened upon the <a href="http://www.samsung.com/Products/TV/LCDTV/LNT2332HXXAA.asp">Samsung LN-T2332H</a> 23" LCD HDTV.  Having passed finance committee approval (the finance committee was waiting in the car), the set has since made a great addition to the Russell family abode.  At a price of $499, how can you go wrong?</p>

<p>It was sitting right next to an Akai 26" LCD with a built-in DVD player for a mere $30 more, but knowing the aesthetics committee would like the sleek look of the Samsung, and armed with the knowledge of Samsung's solid reputation in the LCD space, Braden opted for the slightly smaller screen.  As far as specs go, it's a 720p set with ATSC, QAM and NTSC tuners, 3000:1 contrast ratio and 2 HDMI inputs.  On paper (or the Internet, or the side of the box, depending on how you do your research) it looks like it has potential to be a very nice TV.  In typical HT Guys fashion, we couldn't get a new HDTV without reviewing it in detail, that would almost be irresponsible.  When we compared it with our reference TVs, we noticed that it didn't quite match the detail of the other sets, although it was still very good.  Colors and black level seemed to be exactly what we'd expect of a 720p LCD at this size - nothing amazing, but certainly worthy of HDTV content.</p>

<p>To dive in a little deeper, the colors are every bit as good as other televisions we've reviewed in the same class. Off angle viewing held up very well.  Blacks were great, very dark and inky.  The high contrast ratio was great in dark scenes, it did every bit as well in that area as the rest of the TVs we compared it with. Of course, as is typical with flat panel LCD TVs, the bright scenes really looked the best.  It had trouble at times with very fast moving content, like hockey, but nothing that was overly distracting.  For other sports like baseball it did a perfect job.  Although tough to watch if you are a Lakers fan, basketball looked very good as well.  Movie watching is excellent because of the good contrast and great, vivid color.</p>

<p>Standard definition TV was decent - the set is small enough that it can minimize the typical "HD on an SD" issues.  The built-in speakers sounded really good, better than we expected;  the SRS mode helped a little.  The menus are easy to use and very responsive.  Setup was a snap, although it took a very long time to learn the channels.  The remote is a run of the mill universal - which is helpful if you have the TV in a secondary room that doesn't have a Hamony remote.</p>

<p><strong>Conclusion:</strong><br />
It still seems odd to say that a 23" TV will work really well as a secondary TV - especially if your kids just asked you how big the TV was that you had growing up.  But if you're in the market for an HDTV for a bedroom, loft, game room or gym, this Samsung is a perfect fit.  If you have a small viewing room, such as a dorm or apartment, this TV will do well for you there also.  For the price, it's a great buy.</p>

<p><strong>What we liked:</strong><ul><li>Price</li><li>Sleek design</li><li>Good color</li><li>Great contrast</li><li>ATSC/QAM Tuners</li><li></li><li>2 HDMI inputs</li></ul><br />
<strong><br />
We didn't like:</strong><ul><li>Ability to handle fast motion</li><li>Slow channel learning and channel tuning</li><li>Some assembly required</li></ul></p>
