<p><a href="http://www.jvc.com/product.jsp?modelId=MODL027825&pathId=125&page=1">JVC HD-61FN97 61" 1080p HD-ILA HDTV</a><br />
<strong><br />
Features</strong></p>

<p>    <ul><li>True 1080p 2 Million Pixel Structure 3-Chip DILA System (1920x1080)</li><li>ATSC/QAM and Digital CableCard Capable (Digital Cable Ready)</li><li>5th Generation D.I.S.T. 1080p (Digital Image Scaling Technology) + GENESSA Picture Processing</li><li>Advanced Super Cinema Mode (Optical Iris System)</li><li>Intelligent Noise Reduction Circuitry</li><li>Contrast ratio of 10,000:1</li></ul> </p>

<p><br />
We've talked about the JVC HD-ILA (<a href="http://www.htguys.com/shop.php?id=B000HE8JA2">Buy Now</a>)rear projection HDTVs for a long time.  In fact way back in Episode 11, on June 9 of 2005, we picked a 720p JVC as our favorite in a shootout between JVC, Mitsubishi and Samsung.  Those were the days.  TV technology has come a long way since then, but JVC is still a very solid performer, and one of our favorites.  In fact, Ara has mentioned that his brother has a couple of them.  We finally got one in our HT Guys testing facility - also know as our family rooms - to test it out for ourselves.  But would it live up to our expectations?</p>

<p>Out of the box the picture looks OK.  There's a dedicated button on the remote called 'Theater Pro' it switched you over to the "Theater" mode, and away from the default "Dynamic" mode.  This was a huge improvement and actually looked pretty good.  It seemed to lean a little on the yellowy side, but after calibrating the TV, everything looked great.  Black levels are what really set this TV apart from many others.  It can produce some of the deepest blacks we've seen on a rear projection set, and the contrast ratio is stellar.  No detail is ever lost in a dark scene; everything shows up with perfect detail.  Which leads us to the actually clarity and detail in the picture.  With HD content the TV looked perfect, DVDs looked as good as any other micro display we've used and standard definition held up pretty well.  We weren't able to get the colors calibrated to 100% using just the user menu options, but it was very close.  The green gave us a little trouble, but nothing a common viewer would ever notice.</p>

<p>As far as features go, the numerous inputs gave us the opportunity to plug in anything we wanted.  It has built in NTSC/ATSC and QAM tuners as well as a cable card slot.  The HDMI inputs are fully 1080p capable and it has a bunch of analog inputs that we didn't really play with that much.  The set also has a digital audio output, so that if you're using an HDMI input and your receiver doesn't support HDMI, you can just pull the audio from the TV.  Very convenient.</p>

<p>The remote is not very good and took a while to get used to.  The factory remote doesn't offer any way to select a specific input, so you have to go the old-school route of scrolling though all of them to get to the right one.  That can be solved with a good universal remote, but without it switching inputs is a real headache.  It also takes quite a while to move from one input to another.  The menu system is clunky and cumbersome to navigate.  After a while you can get pretty familiar with it, but it's not the greatest design.  From an aesthetics point of view the TV looks really nice. It has a small pedestal base with a long speaker grill just below the screen - no big ears on this TV.  The very thin frame around the TV practically disappears when you're watching something.  It measures 55 3/8" x 40" x 19" (WxHxD) and weighs a svelte 97 pounds.</p>

<p><strong>What we liked</strong><ul><li>Awesome HD picture</li><li>Amazing black levels</li><li>Great, real color</li><li>Excellent detail</li><li>Two HDMI inputs</li><li>Price</li></ul></p>

<p><strong>What we disliked</strong><ul><li>Remote control</li><li>Menu system</li><li>Input switching with the factory remote</li></ul><br />
<strong></p>

<p>Conclusion</strong><br />
The JVC HD-61FN97 is an excellent value.  It looks great, does a wonderful job with HD content, a great job with DVDs and a pretty good job with standard definition TV.  Blacks are good, contrast is solid, colors are excellent and detail is vivid.  We try to look for great values to help you (and us for that matter) get a little more out of each hard earned dollar. You'd be hard pressed to find a better looking 61" TV at its price. At an online street price of $2125 this is an awesome TV for the money.  It really helps bring the big screen home.</p>
