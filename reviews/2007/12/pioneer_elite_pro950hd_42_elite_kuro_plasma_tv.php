<p>We recently did a review of the <a href="http://www.pioneerelectronics.com/PUSA/Support/HomeEntertainment/PlasmaTVs+Monitors/EliteTVs/ci.PRO-150FD.Support">Pioneer Elite PRO-150FD</a> 60" Plasma TV back in November so when Pioneer offered us the 42 inch model we weren't sure that we wanted to review a TV that was so similar. Since the TV was 720p we decided that it was different enough to warrant a review. For this review it was setup in Ara's Master Bedroom and calibrated the same as the 60 inch we reviewed back in November. Then it was dialed in for the room. We are including the calibration settings at the end of the review. The TV had a DirecTV connection without OTA. Some critical viewing was also done with a Blu Ray player.</p>

<p>The TV measures 40-15/16"  (~104 CM) x 26-3/4" (~68CM) x 4-1/2" (11.5 cm) (WxHxD) and weighs 66.9 pounds (30.3 kg). As far as looks go it is as stunning as it's 60 inch cousin. The bezel is smaller on the sides as compared to the 60 inch model. The speakers on this model are on the bottom of the screen. Like all the plasmas in this years line the panel is very black. Be prepared to do a lot of dusting.</p>

<p><strong>Main Features:</strong><ul><li>720p (1024 x 768)</li><li>42" Diagonal / 16:9 Wide-Screen Aspect Ratio</li><li>4 Independent HDMI® 1.3 Inputs</li><li>Optical Digital Audio</li><li>Built-In CableCard™ Slot</li><li>SRS® WOW / FOCUS / TruBass Surround Sound Audio</li><li><a href="http://www.pioneerelectronics.com/pio/pe/images/portal/cit_3424/470838314PRO-950HD.pdf">Complete list here</a></li></ul></p>

<p><br />
The TV performed as good as the 60 inch in the way of color saturation and accuracy which is to say excellent. Plasma has the deepest blacks and this TV is no exception. An area where plasma excels is response time. Plasmas have instantaneous response at the pixel level. This makes for better performance with fast action. On this TV watching football on ESPN is breathtaking. We found that even 1080i sports looked better than the Mitsubishi DLP that Ara owns. The 950 did even better with compressed video  than the  sixty inch model. The TV also has the ability to adjust the lighting to day and night settings but an ISF calibration is required (more info here). We really like the ability to calibrate each HDMI input independently of each other. This really allows us to fine tune the settings for each source. If you go the ISF route make sure you ask the technician to optimize each input for the device you are connecting.</p>

<p>Movies played back smooth and had an amazing amount of detail, even in dark scenes. The TV did a great job with the night scope scenes of Blackhawk down. It was easy to see the detail that other TVs miss. Standard Definition looked very good (well as good as SD can). It was the best looking SD on a HD set we have seen. While watching SD the TV can auto size the picture so the black bars are removed or it can change the black bars to gray. This is done to prevent burn in. Regardless of what plasma manufacturers say, we see burn in all the time. Not so much from gaming but more from people watch mostly 4:3 content. With that said, by taking proper precaution you should be able to game and watch TV without burn-in issues. Just be careful.</p>

<p>About the only issue we have with the panel is the resolution. Since the TV has 1024 horizontal pixels the TV must scale all incoming images. But this is an issue with many 42 inch 720p plasmas. You still see everything its just that some resolution is lost.</p>

<p><strong>Odds and Ends:</strong><br />
The speakers sound quite good. They provided a rich stereo sound. While no substitute for a home theater receiver, we felt the speakers did a better job than most TVs that we have heard in the past.  The only other thing we didn't like about the TV was the menu structure. It is a bit deep and hard to navigate to what you are looking for.</p>

<p><strong>Conclusion:</strong><br />
Like its bigger cousin, the Pioneer Elite Kuro is a fantastic TV with one of the best pictures we have seen. At $2500 it is a quite a bit more expensive than a 720p Panasonic, and many of you may wonder is it $1100 better. If you want total control of each input with advanced calibration features (ISF) that produce one of the best pictures we have seen then the Pioneer is the way to go.</p>

