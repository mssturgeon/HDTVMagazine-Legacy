<p>We have both gone on record saying that we are going to wait out the next generation DVD format war. But Ara gave in and bought a HD DVD drive for his xBox 360 at Christmas. Braden is still holding out as are many people. So what are your alternatives. You can buy an upconverting DVD player that will supposedly take your standard DVDs and make them compatible with HD resolutions.</p>

<p>We have reviewed all three Oppo Digital DVD players in the past. Today, we are going to review a new player made by <a href="http://www.neodigits.com/">NeoDigits</a> called the <a href="http://www.neodigits.com/new/body/products/h4000/h4000.asp">Helios H4000</a> ($170 US <a href="http://www.htguys.com/shop.php?id=B000MF7R4K">Buy Now</a>). We'll have a review of their networkable player on a later podcast. The first thing you notice about this player is that it is thin and made out of plastic. But don't let that stop you. The player is well made! Another nice touch is that NeoDigits includes and HDMI cable to get you going right out of the box. Some of the H4000 features include:</p>

<p>    <ul><li>Playback format options:<br />
      DVD/SVCD/VCD/CD/HDCD/MP3/MP3/WMA</li><li>MPEG4(DivX, Xvid, MPEG1, MPEG2 and MPEG4) video file file playback.</li><li>1080p support via Component.</li><li>High-definition output options via Component interface in 720p,1080i and 1080p</li><li>High-definition output options via VGA/RGB-HV interface is 640x480,800x600,1024x768, 1280x1024, 480P,720P and 1080i.</li><li>High-definition output options via DVI(via HDMI to DVI cable) interfaces.</li><li>576i video output via HDMI for external video scalers.</li><li>NTSC 720P/1080i/1080p support at 60hz</li><li>PAL 720P/1080i/1080p support at 50hz</li><li>Output video via HDMI and component simultaneously.</li></ul></p>

<p>The DVD player performed as well as any of the other upconverting players we have reviewed. DVDs looked quite nice on this player. We ran through our typical suite of DVDs. The night scope scenes of Blackhawk down played back flawlessly. The Superbit version of Spiderman looked, in a word, super! Colors looked true and skin tones looked natural. There was detail present that was not noticeable with our standard DVD player. This was especially evident with our superbit DVD. This was true on 1080p and 720p TVs. One nice feature is that the H4000 upconverts over component cables so HDTV owners who have TVs without digital inputs can also use this player and enjoy improved picture quality. We tested component and HDMI simultaneously by switching inputs on the TV. While the best picture was available via the digital output we were quite pleased with the picture via component cables. There  really wasn't allot of picture degradation via component. The H4000 has optical and coaxial digital audio outputs and 5.1 analog outputs for connections to receivers that have 5.1 pass through inputs</p>

<p>When it comes to features the Oppo can play more audio and video formats than the H4000 but the H4000 has a few tricks up its sleeve. One feature that we really liked is called Smart Play. When enabled Smart Play skips past all the coming attractions and menus and goes right to the main feature. This works great but there were a couple of issues with it. We found that at times the movie would play with sub titles on. The remote has a dedicated button to turn sub titles off. So we would gladly trade a simple button press to turn off sub titles than all the buttons you have to press to get past previews and the menu. The other issue with this feature is when watching a DVD with both widescreen and standard the Smart Play feature picked standard (4:3 Aspect Ratio). Then it became a bigger hassle to use the menus to get to widescreen. NeoDigits has downloadable firmware support so this can be fixed with a simple patch in the future.</p>

<p>The only other thing we thought was odd was that the controls are on top of the player. So you can't stack anything on top of it. But that's really not possible anyway as the device is smaller than typical equipment in your system. You just have to make sure you can get your fingers on top of the player if you want to control the device at the player.</p>

<p>Overall the player was very easy to use. Setting up the device was simple and getting through the menus are straight forward. The remote is easy to use and has dedicated buttons for most of the features you'll use each time you watch a movie. So if you have a Harmony Remote you will have to put those buttons in your soft keys. After about ten minutes with the H4000 we were very comfortable using it. Now if your TV already comes with a good scaler or you have a dedicated scaler you can still find value in this player as it can output 480i and 576i from the HDMI output. This keeps the signal in the digital domain so that your TV or dedicated scaler can upconvert the exact signal that is encoded on the DVD. The last nice feature is that the H4000 is region free right out of the box.</p>

<p><strong>Who should consider the H4000?</strong><ul><li>You have an older HDTV without a digital input and you want to watch standard DVDs with greater clarity and detail</li><li>You want to watch your movie without watching previews or going through the menus</li><li>You have DVDs from other regions</li><li>You have a HDTV</li></ul><br />
<strong>What we liked:</strong><ul><li>Great looking upconverted picture 720p and 1080p</li><li>Upconverting via component cables</li><li>Smart Play</li><li>Region Free</li><li>Price</li></ul><strong>What we disliked:</strong><ul><li>Smart Play would activate subtitles</li><li>Smart Play did not handle DVDs with both widescreen and standard aspect ratio versions cleanly </li><ul></p>
