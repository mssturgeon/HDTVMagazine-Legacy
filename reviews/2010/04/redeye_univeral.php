				<p>If you have spent any time listening to our show you know how important we feel universal remote controls are to a home theater system. Our remote control of choice is the Harmony line of products made buy Logitech. The Harmony remote is an IR remote that needs a line of site to your equipment so that it can manage you activities like "Watching Movies", "Watching TV", or "Playing Games". If you are in another room with your remote you have to walk back to where the equipment is in order to control it. Today we look at a product that eliminates the need to be in the same room with your gear and will work with your iPod Touch or iPhone. We are talking about the RedEye Universal Remote Control. The RedEye is a universal remote control system for the iPhone and iPod Touch that allows users to control virtually any home entertainment device from any room in the home. The system requires a free download from Apple's iTunes App Store and the purchase of a the RedEye Base Station (MSRP $190). From this point forward we will only refer to the iPod but everything said also applies to the iPhone.</p>

<h2>Setup</h2>

<p>Setup is straight forward and is done using your iPod. Follow the clearly written instructions exactly as written! The first thing you do is get the base station connected to your wireless network. This process takes about 5 minutes if you complete every step. We had some pilot errors which required us to reset the device. Once we followed each step we were connected and ready to go. The next step is define your room using the ipod app. The iPod can control multiple rooms provided that you have multiple base stations. In each room you define your equipment and then you setup your activities. Setting up the room is an area we had issues with the device. What would be nice is if there was an option to define the system on a computer. Using the app is a bit clumsy and slow. The good news is that you only do this once.</p>

<p>The key to the system is the multi purpose base station.  The base station serves as an IR blaster and a iPod charger. The base station emits IR signals in all directions so it should be easy to find a location within the room that will control your system and allow for easy access. With that said, we specifically chose not to use the charging capabilities and instead placed the device in the equipment rack. In this configuration the devices blasts IR commands into the room which are reflected back to the gear. This has been reliable and not one IR command has been missed in the time we have been using the device.</p>

<p>You define your equipment like A/V Receiver, Satellite TV, DVD Player, etc. There is an area to enter model numbers but we couldn't tell if that did anything. Once your brand and type of equipment is entered you are presented with commands to test until you get a reaction from the devices. Once you confirm success the rest of the codes are downloaded and transferred to your iPod. The download takes longer than we would like and must be done for each device you have in a serial manner. It would be nice if you could define the other devices and then let all the codes transfer while you do something else. Some devices take longer than others and some of the commands are not available. This should get better as time goes on. ThinkFlood ( the parent company of the product) is actively working to improve the experience. For the commands that were not available it was a simple process to teach the base station about them. You put the base station into a learn mode and press the button on the remote that you are trying to learn and voila you are done. I don't know if the command is sent back to HQ for others to use like they are with the Harmony.</p>

<p>Now that you have all your gear defined next up is defining activities. This is where universal remotes really make our lives easier. You define an activity name like "Watch TV", "Play Game", or "Watch Movie" and then add the equipment that will be used in it. You can define a sequence of commands that are executed when you turn on and turn off the activity. The app puts some default buttons on the screen and for the most part they were most of the buttons you would normally use. However, there were a few buttons that we felt should be added. No worries, its a simple process to add them. In fact its very straight forward to modify the interface so it does exactly what you want. Another area we had an issue with the user interface is that the window is not as large as a dedicated remote so you need to scroll to get to some of your commands. But what you get in return is the ability to control you equipment without a line of site.</p>

<h2>Use</h2>

<p>Once the device was setup it worked as advertised. The device has faithfully executed every command we have given it. As we used the RedEye we kept finding ways to tweak the commands and activities until we had it doing exactly what we wanted. Expect to tweak it over a few days. One area that you will enjoy tweaking is the macro within an activity. You can define a sequence of commands and tie them to a button. Perhaps you have some favorite channels? With the Macro you can go to your favorite channels with one press of a button. Another thing we did was create a sophisticated mute command. Our command sends a mute to our AV Receiver and then puts the Satellite receiver into closed caption mode. Putting the Sat receiver into closed caption mode requires three button presses. All totaled it would take four button presses to make this happen. With the RedEye it takes one simple button press.</p>

<p>Being run on an iPod means you have a couple of compromises off the bat. The iPod will go to sleep and requires two actions to wake. So there is a delay from when you want to do something and when the remote is ready to accept your input. We also felt it would be nice if you could control the base station from your Mac of PC. It would then tie into many home automation software packages out there. This is where we think this device needs to eventually end up. You could build extensive macros on your computer, where it would be more convenient to do, and then attach a button to it on the remote. Customizing the GUI on the remote would be easier to do from a computer as well. Again, you only do this once so its not that big of an issue. We add gear all the time so we appreciate this type of function.</p>

<h2>Conclusion</h2>

<p>We have used a lot of remotes in our day and have pretty much settled on Logitech's Harmony Remote for our personal use. ThinkFlood's RedEye is the first remote solution that will be making us take a second look. The ability to use multiple remotes while only having to configure one of them is very appealing. Now no one has to fight over the remote. If you have an iPhone or iPod Touch you simply install the free application and turn your iPod into a powerful universal remote control. The RedEye is a quite impressive and will help you take back control of your home entertainment.</p>
