				<p>Pretty much since we have been doing the HDTV and Home Theater Podcast we have had listeners ask us about wireless solutions. We have been pretty happy with products from Rocketfish&trade; and AudioEngine. Today we take a look at the Aperion Audio Home Audio Link (HAL) which will transmit high quality uncompressed audio up to 100 feet.</p>

<h2>Features:</h2>

<ul><li>Send audio from your computer, MP3 player, or other audio source to any audio-video receiver or audio system</li><li>Wireless Subwoofer - Connect your powered subwoofer or powered speakers wirelessly</li><li>Audio input via USB or Audio-In Jack</li><li>Send music throughout your house, or even outside</li><li>No software needed, just plug and play</li></ul>

<h2>Connections</h2>

<p>With HAL you can transmit wireless audio from your laptop or desktop to your AV Receiver. Just connect the sender to the USB port on your PC. On the AV Receiver side you need to provide power to the HAL receiver. Aperion provides two power plugs which comes in handy if you are connecting mp3 players. We'll talk about that in a bit. Plug in the power adapter then connect the mini RCA plug to the HAL receiver's audio out. Then plug the RCA cables into the AV Receiver's audio input and your just about ready. Wait for the blue blinking lights on both the sender and receiver to become solid blue and then you are good to go.</p>

<p>Other connection combinations are MP3 players, Portable DVD Players, or Subwoofer Output from your AV Receiver to Powered Subwoofer, Powered Speakers, or AV Receiver Inputs. There are many combinations that you can come up with. In the case where you are connecting portable media or even the subwoofer output from your receiver you need to provide power to the sender unit. What's nice about the HAL is that Aperion includes power plugs for both the transmitter and receiver.</p>

<h2>Performance</h2>

<p>The HAL system works on the 2.4 GHz frequency band and transmits audio up to 100ft. We did not test beyond about 60 feet but found the HAL had no issues transmitting flawless audio during all our testing. We tested and iPod and subwoofer. We tested both MP3s and AAC files and did not hear any difference when compared to listening via headphones. An area that made us happy was connecting our subwoofer wirelessly. This makes it possible to place your subwoofer in the room's most optimal location without worrying about running wires. Your performance may vary, 2.4GHz devices can experience interference from cordless phones, microwaves, and WiFi networks so keep that in mind when considering a wireless solution.</p>

<h2>Wireless Surround Speakers</h2>

<p>You can use the HAL system to connect your surround speakers with the following caveat. You need to use powered speakers for your surrounds. While not and ideal way to hook up a surround system it will work great if you live someplace that you can't run wires. For this application we recommend the Audioengine A2 Powered Multimedia Speaker System.</p>

<h2>Whole House Audio</h2>

<p>The HAL system allows you to connect one sender to three receivers. Each receiver will run you an additional $70.</p>

<h2>Conclusion</h2>

<p>The Aperion Audio HAL System is the easiest way to extend your audio to additional listening zones without running wires or cables.</p>
