<p>Premiering on February 15, launch day for SI Swimsuit 2011, the 3D Swimsuit video (content will also be available in a 2D format) shot earlier this year will be exclusively available for rental or purchase on PlayStation&reg; Network's video delivery service via PlayStation&reg;3 (PS3&trade;) computer entertainment system, and for rental on "Video On Demand powered by Qriocity&trade;" via Sony's 3D-compatible and network-enabled 2010 and 2011 BRAVIA&reg; HDTVs and 2011 Blu-ray Disc&trade; players.  A free, three-minute sneak preview of the 3D Swimsuit video will be available on PlayStation Network's video delivery service and "Video On Demand powered by Qriocity" later this year. </p>

<p>"Just when you think the bar couldn't get any higher for the Swimsuit franchise, we've raised it once again with our partners at Sony," said Mark Ford, President of the SPORTS ILLUSTRATED Group. "Swimsuit in 3D has extraordinary potential and we're thrilled to deliver its millions of fans a new perspective through the exciting world of 3D video."</p>

<p>In addition to the 3D footage, users of PlayStation Network's video delivery service and "Video On Demand powered by Qriocity" can also rent or purchase more than twelve hours of Swimsuit video including the official, hour-long, behind the scenes Making of SPORTS ILLUSTRATED Swimsuit 2011 video, four new 30-minute videos focusing on the 2011 Swimsuit shoot locations, and the hour-long Making of SPORTS ILLUSTRATED Swimsuit videos shot during the last decade.  PS3 users can purchase exclusive "Dynamic PS3 Themes" based on iconic SI model photos from the 1990s, the 2006 All-Star Shoot, as well as SI model photos from 2010 and 2011, to customize their PS3 experience. </p>

<p>"The combination of SPORTS ILLUSTRATED Swimsuit brand with the amazing 3D capabilities of Sony's network-enabled devices makes for a great consumer entertainment experience," said Tim Schaaff, President, Sony Network Entertainment.  "We strive to deliver unique content to our users, and are delighted to offer this first-of-its-kind high definition 3D Swimsuit video."</p>

<p>The multiplatform cross-marketing agreement, builds upon a 2010 partnership between SPORTS ILLUSTRATED and Sony, which produced the most downloaded sports content of the year on the PlayStation Network— the Making of SPORTS ILLUSTRATED Swimsuit 2010 video.</p>

