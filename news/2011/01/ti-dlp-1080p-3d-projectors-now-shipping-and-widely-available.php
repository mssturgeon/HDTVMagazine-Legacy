<p>1080p from DLP brings bold contrast ratios, inky black levels, vibrant color and placement flexibility, all with the filter-free, consistent color, and unique mirrored chip design that has made DLP famous. One new application of this technology can be seen in the Mitsubishi 92" DLP HDTV being shown at CES this year. From this television, which is nearly 1/30 the size of a cinema screen, to devices that fit in the palm of your hand, to projectors that power IMAX&reg;, DLP continues to innovate and deliver the best in projection technology.</p>

<p>Last year, "Avatar" started the tidal wave of 3D viewing experiences that has since spilled into the classroom. Utilizing the same Academy Award-winning DLP projector technology for cinema productions, the company has extended its leadership in 3D cinema technology to projectors for schools as well. School districts across the U.S. and beyond are incorporating 3D learning into lessons, providing an engaging learning environment for teachers and students. The ability of DLP technology to provide both 2D and 3D images in a single projector offer enormous cost savings and opportunities to schools.</p>

<p>DLP technology's ability to fill large screens while still maintaining contrast ratios, brightness, and color quality, combined with the immersive experience that 3D provides, are reasons that now more than 400 3D-Ready projectors from 30 different DLP Products' manufacturers are available on the worldwide market. Adding further fodder to the prevalence of 3D adoption, Pacific Media Associates (PMA) notes the worldwide front projector market for 3D-enabled models will grow from about 1.0 million during 2010 to nearly 5.4 million in 2014 (via PMA, August 9, 2010: http://www.pacificmediaassociates.com/press/item.php?id=24).</p>

