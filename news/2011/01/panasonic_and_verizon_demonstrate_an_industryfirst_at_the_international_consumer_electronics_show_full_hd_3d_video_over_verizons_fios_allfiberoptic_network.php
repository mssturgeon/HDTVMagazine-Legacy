<p><strong>NEW YORK, Jan. 7, 2011 /PRNewswire/ -- </strong>Full-resolution high-definition 3D transmission via a premium TV service provider became a reality at this year's 2011 International Consumer Electronics Show. Verizon and Panasonic, a leader in Full HD 3D technology, are streaming Full HD 3D, currently the highest-possible resolution of 3D video, via Verizon's 100 percent fiber-optic FiOS TV service. </p>

<p>The first-of-its-kind demonstration (in the South Hall of the Las Vegas Convention Center Room S228) was made possible through a technical collaboration between the two companies, with content streaming over Verizon's future-proof network to a Panasonic Blu-ray 3D player. Engineers from both companies worked closely to co-develop the required network, software and user-interface enhancements that make Full HD 3D possible over the bandwidth-rich FiOS service. </p>

<p>(NOTE: To view a video a demonstration of the full-resolution HD 3D as shown in the Blogger Lounge of the CES, visit <a target="_blank" href="http://www.youtube.com/watch?v=9_MZb-7iOmQ/">http://www.youtube.com/watch?v=9_MZb-7iOmQ</a> . ) </p>

<p>"We're proud of our work with Verizon to develop this Full HD 3D streaming capability," said Eisuke Tsuyuzaki, chief technology officer, Panasonic Corporation of North America. "Panasonic has always believed that the best way to view 3D is via a Full HD, 1080p resolution image, but until now the only option available has been on Blu-ray Disc&trade; media. Over Verizon's high-bandwidth FiOS network, we've now shown that this kind of innovation can be accomplished by a premium television service like FiOS as well."</p>

<p>Unlike some competing technologies, Full HD 3D transmissions preserve the complete 1080p picture resolution that consumers have come to expect from their HDTVs. Other solutions degrade the 3D image, typically reducing resolution by half.  In a demonstration at the Verizon-sponsored Blogger Lounge, FiOS engineers showed a selection of 3D content streaming to a Panasonic Full HD Blu-ray 3D Disc&trade; player at a bit rate of up to 18 Mbps (megabits per second)  -- double the bit rate currently used by most cable providers. </p>

<p>Tony Melone, chief technology officer for Verizon, said, "Delivering full-resolution 3D content is a natural fit for Verizon's FiOS network.  Built with the future in mind, FiOS was designed with the bandwidth headroom to grow along with consumer demand for the latest technologies. Verizon continues to deliver the future of TV and is once again redefining the consumer's at home-entertainment experience."</p>

<p>Last year, Verizon televised the first National Football League game in 3D, the New York Giants versus the New England Patriots, as well as the first Major League Baseball games in 3D, between the New York Yankees and the Seattle Mariners.</p>

<p>Verizon continues to drive the future of TV, with more than 140 HD channels and next-generation interactive services like social networking, DVR management via broadband or mobile phone, and an interactive media guide.</p>

