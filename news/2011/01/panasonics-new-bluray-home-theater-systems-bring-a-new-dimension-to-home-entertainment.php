<p>Equipped with Panasonic's renowned Full HD 3D Playback, the new systems not only deliver powerful 3D images with dramatic effects, enhanced depth, luster and texture, but allow the user to tailor the image display as desired. The 3D Effect Controller adjusts the amount of the depth effect for more expansive images and enables the viewer to enjoy 3D movies with exactly the preferred level of 3D effects.</p>

<p>For space-saving elegance, the sleek, ultra slim main component measures only a mere 1.5 inches high. The systems are designed to ideally match a flat panel display. They are easy to install, and with the rear wireless speakers included on the SC-BTT770 and available on the SC-BTT370, there is no need for unsightly wires across the room.</p>

<p>The top two models SC-BTT770 and SC-BTT370 feature VIERA CAST&trade; with Skype&trade; a new function which allows users to connect with friends and family around the world on any compatible TV.  And when they are not home, a convenient Auto Answering Video Message feature answers incoming calls and records video voicemail messages. </p>

<p>Models SC-BTT770 and SC-BTT370 include a down-firing subwoofer, which achieves powerful bass by releasing the sound downward from the speaker unit and port and utilizes the sound reflected from the floor. These models are equipped with one HDMI output and two HDMI inputs with Standby Pass through for HD and 3D gaming and set-top box connections. Since they feature a Standby Pass Through function, signals from the connected devices can pass through the unit even when the home theater system is turned off.</p>

<p>All of the home theater systems feature Audio Return Channel (ARC*), which makes it possible to receive audio signals from the TV, on top of the preexisting HDMI function of sending audio/video signals to the TV with just one cable. This feature simplifies connection by eliminating the audio cable connection between the TV audio output and the main unit's audio input.</p>

<p>All of the new systems feature a Universal Dock for iPod/iPhone** which employs a digital connection to minimize sound degradation. This lets the user play music and video downloads and enjoy high quality sound from an iPod/iPhone.</p>

<p>The new models boast improved easy-to-use features, such as an internal wireless LAN system so IP content, such as VIERA CAST(2) and BD-Live, can be enjoyed without having a LAN cable*** connection. VIERA CAST has been further enhanced with CinemaNow and Vudu, allowing viewers to stream movies. Other content can also be accessed from the special VIERA CAST screen to check weather, stocks and other information.</p>

<p>(1)  Skype video calling requires access to a broadband Internet connection as well as a Skype-compatible camera available from Panasonic, sold separately, to make video calls.</p>

<p>(2)  Not all VIERA CAST features are available on both VIERA Connect-enabled VIERA&reg; HDTVs and VIERA CAST-enabled Blu-ray Disc&trade; Players due to specific technology requirements required to activate certain applications.  Specific app availabilities and compatibilities will be announced at a later date. Access to a broadband Internet connection is required to access VIERA CAST features. There is no fee to use the VIERA CAST functionality however some VIERA CAST services such as Netflix and Amazon VOD have a separate fee structure.</p>

