<p><strong>LAS VEGAS, Jan. 6, 2011 /PRNewswire/ -- </strong>Placing a display outdoors requires a certain confidence that it can operate and last in a variety of harsh environments, as well as unpredictable weather. You can now rest assured, thanks to the fully-sealed technology that sets a new standard for weatherproof flat panel TVs, featuring the greatest flexibility in outdoor screen placement on the market.</p>

<p>Ciil Technologies, LLC, provider of the market's only 100-percent, fully-sealed full 1080p HD flat panel TVs, is showcasing its full line of 32" thru 55" outdoor models in booth #22063 at CES 2011.</p>

<p>Combining innovative technology with state-of-the-art design and manufacturing techniques, Ciil Technologies has developed an outdoor flat panel display that sets a new standard of protection, against even the harshest environments.</p>

<p>"By providing a simple, seamless solution that outperforms any other outdoor TV, Ciil's fully-sealed flat panel displays are the definition of what outdoor displays should be," says Jack McKeague, General Manager, Ciil Technologies. "The unique design allows the presentation of an attractive flat panel display that is robust enough to handle the elements with ease. There has never been an outdoor TV that provides this level of protection from the elements with this attractive of a design."</p>

<p>Ciil flat panel TVs stand out from the competition because they go beyond "weatherproof" and are 100-percent sealed, according to McKeague. Competitor TVs, he notes, are built with vents and filters that can often lead to water, dust and insect damage over time. Ciil's unique designs have no vents or filters, making it impossible for moisture or microscopic dust to collect and get inside the display, creating an outdoor TV that can operate without fail under the harshest of conditions.</p>

<p>Not only do Ciil flat panel displays boast the highest waterproof (IP) rating and the highest dust proof (NEMA) rating, they have the widest operating range in their class.</p>

<p>In fact, Ciil's cutting-edge technology is so advanced that their TVs achieve an IP rating of up to 68. Ciil flat panel TVs can easily withstand pressurized washing from any angle.  Additionally, the outdoor TVs can be submerged while continuing to operate reliably.</p>

<p>Ciil's patented Fully-Encapsulated Dynamic Thermal Transfer&trade; System keeps internal components safely warmed in extreme cold and properly cooled in extreme heat all without vents, filters or exhaust fans. This system completely eliminates the possibility of water, dust, insects or air getting inside the display.</p>

