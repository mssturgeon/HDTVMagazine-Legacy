<p><strong>LAS VEGAS, Jan. 5, 2011 /PRNewswire/ -- </strong>Panasonic Corporation of North America, a major developer and contributor to the success of the Blu-ray format, today introduced an expanded Blu-ray Disc&trade; player lineup with three new Full HD 3D models – the DMP-BDT310, DMP-BDT210, DMP-BDT110 – and a new 2D model, the DMP-BD75.</p>

<p>The BDT310, BDT210 and BDT110 are all high-quality Blu-ray Disc players with 2D-3D Conversion, which can convert 2D images from DVDs and Blu-ray discs into 3D with natural depth perception. With the 3D Effect Controller the user can control the leaping effects of 3D images, as well as allowing one to adjust the amount of depth. This permits the user to view expansive images and enjoy 3D content with exactly the kind of 3D effects they want. Also contributing to higher picture quality is the new UniPhier chip, which, simultaneously lowers power consumption. Vertical color reference process has also been increased by 1.5 times, to express fine details and nuances in movie scenes with the Adaptive Chroma Processing. The HDMI Pure Audio improves sound quality, delivering pure and robust bass sound reproduction with minimal noise compared to previous models.</p>

<p>The newest addition to VIERA CAST&trade;, Panasonic's proprietary internet solution, on the BDT310, BDT210 and BDT110 is the video/voice communication service, Skype&trade;(1). With this new application and optional camera, users can engage in long distance video/voice conversations with family and friends right from their TV. Panasonic has made it even easier to access this through the Blu-ray Disc player with a devoted Skype button on the remote control. Other features of Skype include Standby Mode, Auto Answering Video Message, which allows users to create a personalized message when away, and Video Voice Mail Recording which automatically records messages left onto an SD card. These three models are also DLNA-certified, allowing users to enjoy content with their Blu-ray Disc player, from a computer or other DLNA compatible device.</p>

<p>VIERA CAST's popular sites, including Netflix&trade;, Amazon VOD&trade;, You Tube&trade;, Pandora, twitter, Bloomberg News, a weather channel and Skype continue on the 2011 models and are joined by a host of exciting features and apps, all optimized for the best possible user experience. Included in VIERA CAST's 2011 roster are such apps as Napster, CinemaNow, and access to popular sports sites including the NHL, NBA, MLB and MLS(2).</p>

<p>"Panasonic's 2011 Blu-ray Disc player lineup incorporates the successes of its 2010 line, while adding innovative features that meet the demand of consumers and new trends in technology," said Richard Simone, Vice President, Panasonic, Consumer Electronics Company, Merchandising, Imaging and Entertainment Products. "Features such as the Touch-Free Sensor, Home Screen Wallpaper and Skype allow consumers to easily personalize their entertainment experience to fit their lifestyle. And now the consumer can enjoy the benefits of Skype from any HDTV."</p>

<p>The BDT310, BDT210, BDT110 and BD75 feature a unique updated design, making operation simple with icons and text indications. They also have ultra-quick playback. The BDT310 and BDT210 feature a Touch-Free Sensor to open and close the disc tray for smooth operation, perfect for dark rooms. Additionally, each of the 3D Blu-ray Disc players works with an iPhone as a remote.</p>

<p>New networking capabilities are among the highlight features of the new 2011 Blu-ray Disc player lineup. All four players allow users to customize their own home screen using your favorite photo or wallpaper. Simply insert an SD card into the Blu-ray Disc player to transfer over the image. The BDT310 and BDT210 feature a built-in Wi-Fi System, while the BDT110 requires an optional wireless adaptor for local area network connections.</p>

<p>Energy efficiency and sustainability are also important to the overall design and functionality of these models. All four models have compact slim designs and packaging reduction (50% less from 2010 models), significantly reducing CO2 emissions. The BDT310, BDT210 and BDT110 have an energy-saving design which saves on electricity bills and natural resources with a 48 % power reduction.</p>

<p>The Panasonic DMP-BDT310, DMP-BDT210, DMP-BDT110 and DMP-BD75 will be available in the spring of 2011.</p>

