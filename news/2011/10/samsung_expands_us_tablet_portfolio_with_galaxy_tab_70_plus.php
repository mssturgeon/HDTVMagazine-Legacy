<p>Featuring built-in infrared capabilities, the Galaxy Tab 7.0 Plus can control the user's home theater/TV setup. The Peel integration on the Galaxy Tab 7.0 Plus goes beyond the Peel application available for download today by no longer requiring additional hardware or cables for TV control functionality. Peel allows users to control any home entertainment system regardless of manufacturer.</p>

<p>Peel displays personalized programming recommendations in an intuitive and content-driven graphical interface, completely eliminating the need to scroll through traditional channel-listing grids. The application's home screen displays colorful thumbnail images of "Top Picks," or favorite shows. Touch one of the thumbnails and the application displays what channel that show is on as well as a brief description of the episode that is playing. Simply tap "Watch On TV," and the Galaxy Tab 7.0 Plus will automatically change the channel to the selected program.</p>

<p>"The Galaxy Tab 7.0 Plus optimized with the innovative Peel application will enable users to connect seamlessly to view their favorite TV shows," said Dale Sohn, president of Samsung Mobile. "Our partnership with Peel further builds on Samsung's convergence strategy to create enhanced user experiences."</p>

<p>Peel combined with the Galaxy Tab 7.0 Plus can control the entire home entertainment system, including the TV, set-top box, DVD, Blu-ray player and AV audio system. Peel will provide Galaxy Tab 7.0 Plus users with a social aspect as well, connecting them directly to Facebook and Twitter to share what they are watching with their social networks.</p>

<p>"This partnership continues Peel's vision of eliminating the barriers between you and your favorite shows," said Greg Lindley, chief experience officer for Peel. "The Samsung Galaxy Tab 7.0 Plus – with its built in IR remote functionality – is a great platform for the Peel app and creates an ideal second screen experience for any TV lover."</p>

<p>The 16GB Galaxy Tab 7.0 Plus will be available nationwide through Best Buy, Amazon, Tiger Direct, Fry's and other fine retailers starting November 13th for $399.99. Pre-orders will begin October 23rd with select partners.</p>

<p>Samsung's relationship with Peel is part of Samsung's overall commitment to convergence, and the companies are working to integrate the Peel Smart Remote Application into future Samsung mobile devices.</p>

