<strong>Breakthrough Design Delivers Larger Screens and an Element of Luxury</strong></p>

<p>As design increasingly becomes a key differentiator, Samsung has further extended its design philosophy across its premium models. The company debuted its revolutionary Plasma+1 design through its entire line of new plasma TVs. This engineering breakthrough delivers a new narrow bezel design that adds up to one inch of viewable screen size over last year's products without increasing the outside dimensions of the set. With the larger screen, 3D content – whether movies or games – will almost literally jump out of the TV.</p>

<p>Samsung's commitment to design is also underscored by the introduction of eight ultra-slim plasma TV models that are 1.5 inches in depth. The plasma D8000 and D7000 Series TVs feature Samsung's signature brushed metal bezel design that was widely popular with the 2010 LED TV line, while the D550 series sports the trademark Touch of ColorTM design. New in 2011, Samsung's unique Quad Stand will be introduced to the plasma D8000 series to offer the elegance associated with a luxury product.</p>

<p><br />
<strong>New Smart Hub Makes TV Smarter</strong></p>

<p>Samsung expects 2011 to be a watershed year for smart TV. To meet consumer demand for more immersive and interactive content experiences, Samsung is introducing the new Smart Hub to select plasma models, including the D8000, D7000 and D6500 Series.</p>

<p><br />
<strong>Key features of Smart Hub include:</strong></p>

<p>Search, which allows users to easily search for content on the TV and via Samsung Apps or other online services.<br />
Your Video, which delivers recommendations based on a user's viewing history.<br />
Web Browser, which offers full web browsing right from your TV (available on the D8000 series).<br />
Samsung Apps, the world's first HDTV-based apps store, offers a range of paid and free apps that help people connect to their passions. Applications fall into several categories, including video, sports, information, games and lifestyle.<br />
For those seeking the ultimate smart TV experience, the D8000 series includes a remote that features a full physical QWERTY keyboard, making it easy to search and discover new content. New in 2011, the D8000 Series will also include built-in access to Skype, enabling owners to make video calls in high-definition from the comfort of their couch when paired with a compatible TV camera (sold separately).</p>

<p>Connecting to Smart Hub and the Internet is easy right out of the box. Built-in Wi-Fi is included across Samsung's ultra-slim plasma portfolio – the D8000, D7000 and D6500 Series.</p>

<p>Samsung has integrated more features to make the plasma line smarter in 2011. AllShare technology begins at the D550 Series, making it easier to connect and share content across multiple DLNA-enabled devices. The Plasma D550 Series is Wi-Fi ready with the addition of a wireless LAN adapter (sold separately) for enjoying DLNA-based networking with compatible devices and home media network drives.</p>

<p><br />
<strong>More 3D-Capable Models Bring Immersive Entertainment Home</strong></p>

<p>Building on its successful introduction of 3D last year, Samsung will include 3D in three-quarters of its plasma portfolio in 2011, making it easy to bring home a premium 3D experience at multiple price points.</p>

<p>The expanded range of 3D-capable models includes new technology to make the 3D picture quality more vivid and life-like than ever before. Samsung improved its 2D to 3D up-conversion feature, making it easy to customize the 3D viewing experience by adjusting the depth of the 3D images.</p>

<p>Watching 3D in the home has also become more comfortable. Samsung unveiled four new models of 3D active glasses, which are only compatible with Samsung's 2011 3D TVs. The new range of 3D active glasses is Bluetooth-enabled, offering a stable signal and more vivid, life-like 3D imagery for an optimal viewing experience. The company also created the world's lightest 3D active glasses (model SSG-3700CR). Sporting a completely redesigned frame, the SSG-3700CR model weighs approximately one ounce, delivering the most premium picture quality and comfort during extended wear.</p>

<p>As part of the company's ongoing commitment to bring premium content to consumers, Samsung announced that its new 3D Starter Kit, which includes of two pairs of 3D active glasses, would also include Blu-ray 3D versions of DreamWorks Animation SKG's Megamind and the complete Shrek collection at no additional cost.</p>

<p><br />
<strong>More Picture Enhancing Advancements Bring Deepest Blacks to Life</strong></p>

<p>Samsung is committed to delivering an unmatched viewing experience whether in 2D or 3D. This year's flagship plasma TV models produce the deepest blacks and most vivid colors with the addition of Samsung's proprietary Real Black Panel to the D8000 and D7000 series. Real Black Panel reduces onscreen glare and allows the viewer to enjoy the deepest blacks and sharpest images. Samsung has also introduced Local Contrast Enhancer (LCE) and the Cinema Black feature to the D8000 Series to further enhance black level performance versus last year's C8000 Series.</p>

<p>Samsung further integrated advanced picture quality technologies across the full plasma TV portfolio, with each model enjoying 600Hz Subfield Full HD Motion performance and .001 ms response time to generate smooth playback of any content. Building on the widely lauded inclusion of Cinema Smooth technology in the 2010 plasma line, Samsung integrated its new Crystal Full HD engine with Cinema Smooth into the new D8000 series, making blacks and moving image details as crisp and defined as possible.</p>

