<p>Interwoven throughout the opera's interludes will be a series of short films, directed by Figgis, that present the back story of Lucrezia and the Borgia family, behind-the-scenes interviews with Figgis and the cast, as well as Donzetti's original score. The 3D production of Lucrezia Borgia, a collaboration between Sky Arts and ENO, was filmed live on Feb. 23, 2011 at the London Coliseum and will be available on DIRECTV CINEMA beginning this April.</p>

<p>In addition, DIRECTV CINEMA (Ch. 104) is adding a variety of Hollywood movies in 3D to its lineup, including Piranha 3D (Now Playing), Jackass 3D (March 8), Tangled 3D (March 29), Tron: Legacy 3D (April 5), for $6.99 each.</p>

<p>"We are constantly looking for ways to provide our 3D fans with the most compelling lineup of 3D programming available," said Derek Chang, executive vice president, Content Strategy and Development, DIRECTV. "Mike Figgis' unique production of Donizetti's Lucrezia Borgia and Hollywood hits like Tangled and Tron: Legacy 3D are the perfect content to showcase 3D technology at its best."</p>

<p>n3D&trade;, powered by Panasonic (Ch. 103), the nation's first 24/7 3D network, is available at no additional cost to millions of DIRECTV HD customers. In addition to exclusive 3D coverage of special events such as the 2010 MLB All-Star Game and the 2010 U.S. Open Tennis Championship, the n3D channel also gives customers access to exclusive, original 3D programming such as DIRECTV's award-winning series "Guitar Center Sessions" and "Guy's Big Bite" in 3D. The 3D programming available both on n3D and DIRECTV CINEMA are all powered by Panasonic. DIRECTV also offers 3net and ESPN 3D as part of its 3D programming platform.</p>

<p>DIRECTV HD customers received a free software upgrade that enables them to have access to the 3D channels on DIRECTV. DIRECTV HD customers will need a 3D television set and 3D glasses to view 3D programming on DIRECTV. For more information on n3D&trade; powered by Panasonic or DIRECTV CINEMA&trade;, please visit <a target="_blank" href="http://www.DIRECTV.com/3D/">www.DIRECTV.com/3D</a> or <a target="_blank" href="http://www.DIRECTV.com/cinema/">www.DIRECTV.com/cinema</a>.</p>

