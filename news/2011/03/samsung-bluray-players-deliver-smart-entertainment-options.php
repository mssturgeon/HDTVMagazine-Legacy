<p>Building on the success of Samsung Apps in 2010, Samsung is delivering the Smart Blu-ray experience in 2011 through a new application interface that give consumers easy access to content and services. The new Smart Hub includes key features like:</p>

<ul><li><strong>Search</strong>, which allows users to easily search for content on the TV and via Samsung Apps or other online services.</li><li><strong>Your Video</strong> allows users to watch and preview video through a personalized recommendation service</li><li><strong>Samsung Apps</strong>, the world's first HDTV-based application store, now with more than 200 apps to download in the U.S. Samsung Apps offers a range of paid and free apps that help consumers connect to their passions – whether in sports, entertainment, information, games or social networking.</li></ul>

<p>The ability to search and share content across multiple devices is becoming increasingly popular with consumers. To accommodate this demand, Samsung built AllShare into its entire Smart Blu-ray player line. AllShare makes it easy to share multimedia content – videos, images, music and more – between DLNA-enabled devices such as a PC, camera, tablet or mobile phone. Once connected to the home network, the Samsung Smart Blu-ray player can easily play back content on other AllShare devices.</p>

<p>Samsung continues to create solutions that make it easier for consumers to access and enjoy their entertainment. All 2011 Smart Blu-ray players offer Samsung's new patented One Foot Connection feature, when paired with the Samsung wireless router1. Setting up a connection is hassle-free – users simply place the Blu-ray player within one foot of the router during setup to establish a connection. The player will then maintain this connection regardless of where it's placed in the home. One Foot Connection makes Internet setup easier than ever and allows users to effortlessly access their favorite Samsung Apps.</p>

<p>Further simplifying Internet connectivity out of the box, the majority of the Smart Blu-ray player line, including the BD-D5700, BD-D6500, BD-D6700, BD-D7000 and BD-D7500, has built-in Wi-Fi, while the BD-D5300 and BD-D5500 are Wi-Fi-enabled with the addition of a wireless LAN adapter (sold separately).</p>

<p><br />
<strong>2011 Portfolio Brings Home Premium 2D and 3D Entertainment</strong></p>

<p>Samsung's Smart Blu-ray players deliver the most immersive entertainment experience, whether in 2D or 3D. In 2011, Samsung built support for full HD playback with 3D into five of the seven new Blu-ray players, offering consumers greater choice in price and form factors.</p>

<p>The BD-D7500, BD-D7000 and BD-D6700 incorporate Samsung's new innovative 3D Converter technology to deliver exceptional 3D up-conversion of movies, pictures and streaming video at the push of a button. Samsung's proprietary Hyper Real Engine delivers cleaner, detailed picture quality by ensuring clarity, motion and color performance remain at optimal levels.</p>

<p>The 2011 line offers built-in support for Dolby True HD across the full lineup; DTS-HD is also integrated in the BD-D6500 and higher. Support for HD audio makes decoding high-resolution audio effortless – the uncompressed sound is always pure and crystal clear to deliver the total home entertainment experience that audio aficionados demand.</p>

<p>Beyond picture and audio quality, Samsung continues to improve the overall performance of its Blu-ray players. This year, the entire portfolio features the new Ultra Fast Play technology, which slashes the boot-up time by 80 percent to just three seconds.</p>

<p><br />
<strong>Samsung's New Design Identity Offers Options to Match Any Interior</strong></p>

<p>All of the 2011 Smart Blu-ray players embody Samsung's 3S concept design philosophy – symmetric, slim and slot-in. The units are designed as symmetric products, with all major functions placed in the middle so that using the device is easy and convenient. The slot-in design concept eliminates the need for moving parts and makes the unit quieter and more efficient.</p>

<p>This philosophy is best seen in the world's slimmest Blu-ray player, the BD-D7500. The wall-mountable unit is a slim 0.9-inch in height and features an elegant brushed metal finish that matches perfectly with Samsung's premium 2011 LED and Plasma TV models.</p>

<p>Samsung's design philosophy has also resulted in unique, yet practical form factors. The minimalist BD-D7000 personifies functionality. The player features a hidden slot for disc loading that pops up from the center of the player and a unique cube design with a stylish silver metal casing that wraps around the player to add sophistication.</p>

<p>Samsung's design innovation was widely recognized at CES 2011. The BD-D7500 was awarded a CES Best of Innovations Award, while the BD-D6500, BD-D6700 and BD-7000 each received CES Innovation Honoree distinctions.</p>

<p><br />
<strong>Integrated Blu-ray Portfolio Adds More Choice</strong></p>

<p>Bringing Blu-ray home has never been easier. For consumers who are looking for more than a standalone Blu-ray player, Samsung is introducing new Blu-ray home entertainment systems this month. The line includes the world's first 7.1 channel AV receiver system with Blu-ray playback, 3D viewing and Internet services in one integrated component, the HW-D7000.</p>

<p>For more information on the extended Blu-ray product line, please see the home entertainment system press release.</p>

