				<p class="prtitle">3M-Commissioned Research Shows Consumers Value Wide-Angle Viewing on Their LCD TVs</p>

<p><strong>ST. PAUL, Minn.--(BUSINESS WIRE)--</strong>A new study commissioned by 3M shows that American consumers want high brightness and quality no matter at what angle they view their LCD TVs.</p>

<p>The study was conducted by CBS Vision, the Las Vegas-based research division and facility owned by CBS Corporation. 3M is a leading technology company in high-quality consumer electronics.</p>

<p>The findings show that as TVs become central entertainment hubs for viewing, gaming and web connectivity, consumers are viewing their TVs from many different angles on a regular basis, and expect a consistently bright and crisp screen image. As consumers age, they place an even higher premium on wide-angle viewing, the study shows.</p>

<p>"We were pleased to team up with 3M to take a closer look at the fundamentals surrounding consumers' LCD television viewing experience," said David Poltrack, chief research officer, CBS Corporation and president, CBS Vision. "We learned that consumers don't always realize that the way they watch their LCD TV impacts the quality of what they see."</p>

<p>"We wanted to understand how important wide-angle luminance – a combination of off-axis viewing and brightness – was to consumers, since this is something 3M technology enhances. This study shows that wide-angle luminance is very important, even if consumers are not initially aware of the measurement," said 3M Physicist Dr. Dave Lamb, the scientific advisor on the study.</p>

<p>Studying nearly 600 consumers in three phases over a four-week period, the study found that 84 percent of respondents view their TVs from a variety of angles. Further, 69 percent of participants said wide-angle picture quality was very or extremely important. And yet, 44 percent initially were unaware of a difference in quality of many LCD screens when viewed from the side. Once they viewed two sets of varying quality side by side, however, 88 percent preferred the screen with better wide-angle luminance – a brighter, crisper screen at a variety of viewing angles.</p>

<p>Additionally, the research shows that 47 percent of consumers reported they are not satisfied with the home-mode settings of most LCD screens, and change these settings, increasing the amount of energy consumed.</p>

<p>The research reinforces previous studies conducted in Japan looking at consumer viewing habits[i] and luminance preferences[ii].</p>

<p>Key <strong>consumer behavior</strong> findings include:<br />
<ul><li>86% have a flat screen TV</li><li>15% definitely will buy a new TV this year; 60% find picture quality extremely important</li><li>46% typically view their primary TV off axis, defined as any viewing angle that is more than 15% from center, when watching alone; 67% do so when watching with other people</li><li>52% typically view their secondary TV off axis when watching alone; 65% do so when watching with other people</li><li>84% at times view their TV off axis when watching alone; 87% reported other people at times viewing their TV off axis</li></ul></p>

<p>Key <strong>consumer preference</strong> findings include:<br />
<ul><li>47% change the settings on their TVs to make them brighter (reducing the effectiveness of ENERGY STAR ratings)</li><li>44% were initially not aware of a difference in picture quality when viewed off axis</li><li>88% preferred the set with better wide-angle luminance in a direct comparison</li><li>83% of males 55 years of age and older would pay on average $200 more for the TV with better wide-angle luminance; 64% of females 55 years of age and older would do so, as well</li></ul></p>

