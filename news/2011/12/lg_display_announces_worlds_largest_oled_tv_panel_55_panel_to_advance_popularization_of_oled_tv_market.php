<p>"Our objective has always been to actively define and lead emerging display technology markets," said Dr. Sang Beom Han, CEO and Executive Vice President of LG Display. "Although OLED technology is seen as the future of TV display, the technology has been limited to smaller display sizes and by high costs, until now. LG Display's 55-inch OLED TV panel has overcome these barriers."</p>

<p><br />
<strong>Superior Image Quality in an Ultra Thin Design</strong></p>

<p>LG Display's 55" OLED TV panel produces remarkable image quality with no after image due to its high reaction velocity, as well as high contrast ratio of over 100,000:1 and wider color gamut than that produced by LCD panels.</p>

<p>OLED, a medium that controls pixels is a departure from LCD panels which utilize liquid crystals. The new technology allows light emitting diodes to self-generate light and features a reaction velocity to electric signals over 1000 times faster than liquid crystal.</p>

<p>The environmentally conscious will also appreciate LG Display's 55" OLED TV panel. While light sources in backlight units, like LCD panels, must always be kept on, the OLED panel allows diodes to be turned on or off which enables lower power consumption than conventional LCD panels.</p>

<p>With no need for a special light source, LG Display's 55" OLED TV panel is also able to utilize a simplified structure thinner than that of a pen (5mm), and lighter than LCD panels. The panel's minimalist structure also allows for the realization of unique design elements.</p>

<p><br />
<strong>Advancing the Popularization of OLED TVs</strong></p>

<p>Although industry watchers anticipate OLED as the future of TV display, to date, the technology has faced challenges due to limitations on the sizes of displays it can be applied to and a high level of investment required. LG Display has successfully addressed these issues with its 55" OLED TV panel.</p>

<p>The panel adopts an Oxide TFT technology for backplane which is different from a Low Temperature Poly Silicon (LTPS) type generally used in existing small-sized OLED panels. The Oxide TFT type that LG Display utilizes is similar to the existing TFT process, with the simple difference lying in replacing Amorphous Silicon with Oxide. Moreover, the Oxide TFT type produces identical image quality to high performance of LTPS base panels at significantly reduced investment levels.</p>

<p>Additionally, LG Display uses White OLED (WOLED). WOLED vertically accumulates red, green, and blue diodes. With white color light emitting from the diode, it displays screen information through color layers below the TFT base panel, which leads to a lower error rate, higher productivity, and a clearer Ultra Definition screen via the benefits of small pixels. Further, it is possible to realize identical colors in diverse angles via color information displayed through a thin layer. Lower electricity consumption in web browsing environments for smart TVs is another key strength of WOLED.</p>

