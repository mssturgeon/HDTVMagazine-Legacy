<p><strong>SECAUCUS, N.J.--(BUSINESS WIRE)--</strong>Panasonic Solutions Company, provider of collaboration, information-sharing and decision-support solutions for government and commercial enterprises, today announced the TH-65VX300U – the newest addition to Panasonic's family of HD Professional Plasma Displays. The 65" display's color reproduction approaches digital cinema standards making it ideal for both the home theater and post-production markets.</p>

<p>The display's ultra high-speed drive technology achieves clear and extremely detailed 3D video and also enhances 2D content. The advanced drive provides smoother gradation, which is double the smoothness of conventional models, resulting in richer gradation expression in a dark area of the screen allowing the viewer to see what is happening in extremely low-lit areas.</p>

<p>For home theater users, this makes images, such as those in sports and action films, crisp and clear. The display also features a scaler bypass function which allows for the use of an external scaler. With 3D images, the TH-65VX300U Professional Plasma Display features phosphor improvements and original lighting controls that deliver clear images with virtually no double images or crosstalk. The plasma display is housed in a durable, brushed aluminum frame, giving it a high-end look that matches virtually any room decor.</p>

<p>The TH-65VX300U is also equipped with multiple customizable functions for the post-production experience. These include a wide color gamut which can be selected from five setting types, an option to customize placement of RGB, as well as added adjustment menus such as five gamma curve options, white balance settings, and an advanced memory function that allows users to name and save equalized data. Furthermore, independent RGB ON/OFF function checks secondary colors or monochrome images, helping with individual color calibration. These features allow those in post-production to display the most accurate color representation. The display includes a waveform monitor to confirm the incoming signal which offers significant value for those using the TH-65VX300U in post-production.</p>

<p>"With the TH-65VX300U, we're introducing a professional plasma display solution that includes features critical to those in post-production and those who want to experience the best that home theater has to offer," said Rick Albert, VP Sales, Professional Display Solutions. "This new display fits two important markets, both of which demand the highest-quality technology and picture clarity available. The TH-65VX300U will meet and exceed their needs."</p>

<p>The TH-65VX300U features SLOT 2.0 for greater display convenience and system flexibility with standard HD-SDI and DVI-D terminals (optional) compliant network function.</p>

<p>The TH-65VX300U has a list price of $6,250 and will be available in October.</p>

