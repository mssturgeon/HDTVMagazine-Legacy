<center><i>New Survey Shows Majority of Consumers Say 3D is Better Than Regular TV</center></i><br />
<br />

<p>LOS ANGELES, CA (September 23, 2011) -- Consumers love 3D TV, according to a new study of the TV marketplace. Conducted by well-known independent research firm Frank N. Magid Associates for Panasonic during Disney's D23 Expo in Anaheim last month, researchers found that a vast majority of consumers believe that 3D TV significantly improves their television viewing experience.</p>

<p>"We've always said that, just as with HDTV, once consumers experience 3D TV, they will want it," said Eisuke Tsuyuzaki, Panasonic Corporation of North America's Chief Technology Officer. "This survey proves it. We couldn't be happier with the results."</p>

<p>D23: The Official Disney Fan Club provided the venue for the face-to-face study which queried more than 500 attendees at Disney's D23 Expo, the ultimate Disney fan event, which was held in Anaheim in August, and found that 99% of those surveyed who have seen 3D TV perceive it to be at least "somewhat better" than standard HDTV or "2D" TV.  Equally as impressive is the fact that of those surveyed, 71% said that 3D TV is "much better" or "dramatically better" than 2D TV.</p>

<p>Consumers responded with a wide range of superlatives when asked to describe their thoughts about 3D TV. "I wish I had this in my home," said 50% of those surveyed, while 34% agreed that it "brings things alive in a way I've never seen before." "Fabulous" was the word that 27% agreed with when asked to describe their sense of the 3D TV experience.</p>

<p>"These are very positive and impressive responses," said Mike Vorhaus, President of Magid Advisors, a unit of Frank N. Magid Associates. "When it comes to 3D TV, consumers clearly like what they see. Their feelings are very reminiscent of the public's response to HDTV in its early days."</p>

<p>Unlike HDTV, however, 3D TV is off to a much faster start, with multiple full-time 3D channels available on cable and satellite just one year after the technology's launch, They include DirecTV's n3D Powered by Panasonic, Comcast's Xfinity 3D Channel, ESPN 3D, and Discovery's 3Net. By contrast, HDTV channels from these major content carriers were not available until at least four years from that technology's 1998 introduction.</p>

