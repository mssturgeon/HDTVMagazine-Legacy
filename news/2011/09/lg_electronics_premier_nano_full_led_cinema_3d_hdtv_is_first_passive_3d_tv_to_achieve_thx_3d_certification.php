<p>This unique NANO FULL LED HDTV uses LG's film-pattern retarder (FPR) 3D screen technology making it the first 3D TV using flicker-free passive technology to achieve both THX 2D and 3D Display Certification. Joining an elite group of HDTVs, the 55LW9800 passed more than 400 THX tests evaluating left and right eye images for color accuracy, cross-talk, viewing angles and video processing performance. THX offers the only performance benchmark available today for 3D hardware.</p>

<p>"The milestone of being the first passive 3D HDTV to pass our rigorous testing and achieve 3D Display Certification is quite impressive," said Kevin Wines, Image Technology director, THX. "LG has created a product that meets the utmost standards for 2D and 3D picture quality, delivering movie experiences with the same stunning color and detail found in the filmmaker's studio."</p>

<p>THX provides the ultimate benchmark and performance criteria for CE manufacturers to deliver best-in-class entertainment products. THX 3D Display Certification confirms the 55LW9800 meets THX's qualifications for having the correct gamma, luminance and color temperature. These requirements in addition to low cross-talk and wide viewing angles result in superior 3D picture quality and performance.</p>

<p>The NANO FULL LED display employs a thin film incorporating a full array of LEDs, giving it more uniform light distribution and detailed local dimming from over two hundred addressable sectors. With more uniform lighting and improved localized dimming in both 2D and 3D modes, this model offers a greater range and life to colors. Add LG's TruMotion 480Hz refresh rate and the overall effect is a picture so smooth, sharp and realistic, it's as if the action is playing out right in viewers' living rooms. With NANO technology, superior picture quality meets stylish design, allowing for an incredibly narrow bezel and thin depth of just 1.08 inches.</p>

<p><br />
<strong>Next Generation 3D TV Technology from LG</strong></p>

<p>The 55LW9800 features LG CINEMA 3D technology, which lets people recreate the 3D movie theater viewing experience in their homes with lightweight eyewear, crisp, bright images and wide horizontal viewing angles. LG CINEMA 3D makes it easy to host family and friends for a sporting event or 3D movie night given the low cost of the glasses.</p>

<p>LG's FPR technology optimizes the separation of images for the left and right eye, which are then filtered through the glasses to give viewers a better 3D effect with minimal cross-talk. LG's 3D Light Boost, a thin film covering the screen, creates bright, crisp 3D images for a superior 3D viewing experience by helping to counteract dimness that can occur with other 3D systems. The 2D to 3D Conversion feature provides a ready supply of shows and movies in high quality 3D.</p>

<p>"The 55LW9800 provides the ultimate home theater experience for consumers who want great picture, immersive and life-like 3D, and best-in-class technical certification from THX," said Jay Vandenbree, senior vice president, home entertainment, LG Electronics USA. "The display experts agree with what consumers have already said— LG CINEMA 3D provides a top-notch 3D solution, hands down."</p>

<p><br />
<strong>Enhanced LG Smart TV</strong></p>

<p>To complete the package, the 55LW9800 incorporates the expanded LG Smart TV online content package, which offers easy access to thousands of movies, customized apps, videos, web browsing as well as simple multimedia file sharing within a consumer's home network*. New additions to LG Smart TV include content from Amazon Instant Video, Hulu Plus, MOG, as well as video conferencing with Skype (accessories sold separately), and numerous options in the LG App store, such as the new 3D Zone. All this content is organized in a simple to use interface controlled by LG's unique gesture-based Magic Motion Remote Control and easily accessed using the TV's built-in Wi-Fi.</p>

<p>The 55LW9800 is available in a 55-inch class size (54.6-inch measured diagonally) at a manufacturer's suggested retail price of $3,799.99.</p>

<p>LG has expanded the 2011 CINEMA 3D series to include 10 models. In addition to the new 55LW9800, they are:  the LW6500 series in 47-, 55- and 65-inch class screen sizes (47.0-, 54.6- and 64.7-inch diagonals, respectively), the LW5600 and the LW5700 series in 47- and 55-inch class screen sizes (47.0- and 54.6-inch diagonals, respectively), and the new LW5300 entertainment packages bundled with a 3D Blu-ray player in 47- or 55-inch class screen sizes (47.0- and 54.6-inch diagonals, respectively). While all LG CINEMA 3D models are bundled with four pairs of lightweight, 3D glasses and additional sets of glasses are available for affordable purchase.</p>

