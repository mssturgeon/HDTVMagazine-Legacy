<p>Mitsubishi Electric's new HC7800D home theater projector blasts an impressive 1600 lumens used to create high-brightness, high-contrast (up to 30,000:1 full on/full off, up to 700:1 ANSI contrast ratio) images that are smooth, dazzling and true to the original 2D and 3D content.</p>

<p>The HC7800D shows impressive native 3D images with virtually no crosstalk when using its high-performance proprietary active shutter glasses. The projector is also one of the few models in its category with one of the industry's best 2D-to-3D Frame Rate Conversion using Mitsubishi's own algorithms in calculating and interpolating multiple depth levels in a 2D image, resulting in a near-perfect simulation of a true 3D frame of vision. This new, high-speed frame reproduction technology crafts detailed, high-definition 3D images with minimum crosstalk or distortion so 3D content appears to literally jump off the screen, even in high speed action scenes.</p>

<p>Two of the latest HDMI&trade; version 1.4 inputs support 3D signals, as well as provide easy set-up options for multiple video inputs. The projector's RS232 support offers plug-and-play connectivity with third-party remote operations for easy installation and control.</p>

