<p><B>DENVER, Sept. 3 /PRNewswire/ -- (CEDIA Booth #600)</B> -- Sony continues to push the limits of display innovation and technology with today's introduction of two new BRAVIA(R) flat-panel LCD high-definition televisions appealing to the hard-core home theater enthusiast and design-conscious consumer alike.</p>

<p>The BRAVIA KDL-52XBR7 LCD TV features 240Hz high frame rate technology, delivering exceptional motion detail in movies, sports and video games. Meanwhile, the BRAVIA KLV-40ZX1M LCD monitor features a revolutionary slim design measuring just 9.9mm, or about the thickness of a Compact Disc jewel case.</p>

<p>"Sony continually pushes performance and design innovation beyond any other television manufacturer," said Jeff Goldstein, vice president of marketing for Sony Electronics' Home Product Division. "From the top to the bottom of our TV line, Sony offers unmatched performance and design."</p>

<p>The full HD 1080p 52-inch diagonal KDL-52XBR7 incorporates Sony's new Motionflow(TM) 240Hz technology delivering an exceptionally crisp and detailed image with natural motion.</p>

<p>The Motionflow algorithm goes beyond traditional 120Hz technology by quadrupling the frame rate of conventional LCD TVs and interpolating three new frames, producing remarkably crisp and natural motion.</p>

<p>Other picture enhancements include Sony's Advanced Contrast Enhancer (ACE), which helps deliver a dynamic contrast ratio of 80,000:1 and BRAVIA Engine(TM) 2, Sony's digital video processor that enhances all incoming signals to match the TV's 1080p resolution.</p>

<p>The model also is compatible with Sony's BRAVIA Link modules providing the ability to seamlessly add new features. Optional expansion modules include the BRAVIA DVD Link, the BRAVIA Wireless link, the BRAVIA Input Link, which will ship later this year, and the currently available BRAVIA Internet Video Link.</p>

<p>The BRAVIA Internet Video Link module attaches to the back of a selection of Sony's 2007 and 2008 BRAVIA LCD flat-panel television models. The service seamlessly streams on-demand entertainment including movies, TV programs, your favorite YouTube videos and a variety of other content not found on network or cable/satellite TV. The service connects to the Internet via your existing broadband Ethernet connection and streams content, much of which is available at no additional charge. Content is easily navigated with Sony's Technical 2007 Emmy(R) award-winning Xross Media Bar (XMB)(TM) user interface.</p>

<p>Rounding out the feature set is Digital Media Port (DMP) compatibility, which provides access to video and music from portable media devices like compatible Walkman(R) and iPod(R) players and other DMP accessories, which are sold separately. The models also can display digital photos and play digital music using a creative multi-plane 3D graphics slideshows from USB devices, as well as access photos from your PC in another room using Digital Living Network Alliance(R) (DLNA)(R) compliant devices via your home network.</p>

<p>Sony's new 3D Favorites Menu complements the XMB graphical user interface, which has also been enhanced with Sony-unique integration of TV Guide providing easy access and navigation of content and menus through colorful thumbnails and logically placed icons.</p>

<p>Inputs found on the KDL-52XBR7 include four 1080/60 24p HDMI(TM) connections (HDCP), two 1080/60p HD component inputs, a 1080/60p-capable PC input, and an Ethernet (RJ-45) port.</p>

<p>Sony is also introducing the 40-inch diagonal 1920 x 1080p KLV-40ZX1M flat panel LCD monitor. The revolutionary super-slim display measures just approximately 9.9mm deep -- about the depth of a Blu-ray Disc jewel case -- and weighs about 26 pounds.</p>

<p>The model features an edge-lit wide color gamut LED backlight delivering exceptional color reproduction and detailed contrast and Sony's Motionflow 120Hz technology for exceptional clarity and resolution when viewing film or video content with motion.</p>

<p>Other features include Sony's BRAVIA Engine 2, a single HDMI input and compatibility with Sony's BRAVIA Wireless Link allowing users to stream high-definition content wirelessly to the monitor from high-definition sources such as a set-top cable or satellite tuner or Blu-ray Disc(TM) player.</p>

<p>Other optional accessories include a flat-matching speaker bar with four full-range speakers and two tweeters and a wall-hugging bracket that completes the stunning package.</p>

<p>Both the BRAVIA KDL-52XBR7 and KLV-40ZX1M will ship this December. They will be offered at sonystyle.com and at Sony Style retail stores nationwide, as well as at authorized Sony dealers across the country.</p>

