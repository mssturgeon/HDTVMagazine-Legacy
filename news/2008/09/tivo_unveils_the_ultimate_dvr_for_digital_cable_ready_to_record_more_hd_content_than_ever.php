<p><B>ALVISO, Calif., Sept. 4 /PRNewswire-FirstCall/</B> -- TiVo Inc., the creator of and a leader in television services for digital video recorders (DVRs), announced today the launch of the TiVo(R) HD XL Digital Video Recorder. Available online today, the TiVo HD XL box offers more recording capacity than any other DVR available, be it satellite or cable. Boasting 150 hours of high definition television recording capacity, the HD XL has enough space to appease even the most devoted entertainment fans. The TiVo HD XL is also THX(R) Certified to ensure it delivers accurate and exceptional sound and video playback in your home theater.</p>

<p>"With so much HD content now available, we felt it was vital to offer consumers an easy way to record as much television programming as they'd like to watch at a later time without ever having to worry about capacity," said Andrew Morrison, Director of Product Platforms at TiVo. "What is great about the XL is it gives content lovers plenty of room for all the programming they love, saving them from having to decide if they need to prematurely delete a favorite movie or a big game memory when space gets tight. Satellite or cable DVRs simply can't match it."</p>

<p>On top of increased recording capacity, the TiVo HD XL DVR offers all the innovative broadband features that TiVo lovers have grown accustomed and addicted to. Users can download thousands of movies & TV shows directly to the TV, browse and watch endless YouTube videos, listen to thousands of songs from Rhapsody, or view hundreds of music videos from Music Choice.</p>

<p>Features exclusive to TiVo HD XL include the 150 hours of HD recording space, THX certification, a Series3 premium backlit remote control and an included HDMI cable.</p>

<p>Similar to TiVo HD, dual tuners allow subscribers to record two different shows in HD at the same time, while watching a third pre-recorded show. The TiVo HD XL is designed to fit seamlessly into the most discerning home theater systems, compatible with HD digital cable, analog cable and over-the-air digital HD (ATSC).</p>

<p>As with the TiVo HD, the TiVo HD XL box delivers the best in high definition entertainment, allowing the consumer to experience TiVo's acclaimed service features, such as Season Pass(TM) recordings, Universal Swivel Search and WishList(R) searches, in sharp, vivid high definition images. Extensive video analysis and performance testing by THX ensures content will always record and playback at the maximum quality and resolution.</p>

<p>"TiVo pioneered the DVR category, and they are maintaining that position with the new high performance, high capacity TiVo HD XL," said Dr. Michael Rudd, Chief AV Architect at THX. "As more consumers adopt high definition programming, they will expect their recorded content to reflect the same level of quality and consistency as the original broadcasts. With a Terabyte hard drive, the TiVo HD XL lets users enjoy more HD movies, sports and other programs in high definition than ever before, and THX certification ensures that the quality is always superb."</p>

<p>The TiVo HD XL box joins the existing TiVo product line, and is available online today for $599.99 at http://www.tivo.com/. Other retailers that will unveil TiVo HD XL as early as next week include Magnolia Home Theater, Amazon, and various other high-end retailers and customer installers.</p>

