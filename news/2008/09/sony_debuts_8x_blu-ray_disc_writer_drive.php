<center><i>Sub-$400 Model Leaps Ahead in Recording Speed; Includes Blu-ray Disc Movie Title 'Men In Black'</i></center><br />
<br />

<p><B>SAN JOSE, Calif., Sept. 23 /PRNewswire/</B> -- Sony Electronics today announced its third generation internal Blu-ray Disc(TM) (BD) writer for the computer aftermarket, which at about $400 achieves a new level of affordability for BD enthusiasts.</p>

<p>The new BWU-300S model burns single and dual layer BD-R media at up to 8X speed, recording a full 25GB disc in about 15 minutes and a full 50GB disc in about 30 minutes. The 8X recording speed is achieved using 6X compatible BD-R media. The drive also records DVDs at up to 16X, CDs up to 48X, and supports DVD-RAM recording, with an eye towards data backup, making it an excellent replacement burner for a standard DVD drive while offering all the benefits of Blu-ray Disc technology.</p>

<p>To provide consumers with the opportunity to experience high-definition movie playback first-hand, the new drive comes bundled with a "Men in Black" Blu-ray Disc from Sony Pictures Home Entertainment. "Men In Black" stars Will Smith ("Hancock") and Oscar(R)-winner Tommy Lee Jones ("The Fugitive") saving the world from a total intergalactic disaster in Barry Sonnenfeld's smash-hit sci-fi action comedy. The "Men In Black" high-definition Blu-ray Disc boasts advanced BD-Live enabled bonus features, including a multiplayer trivia game, an interactive Frank the Pug advice generator, an alien subtitle track and much more.</p>

<p>Also included with the drive is CyberLink's software suite for capturing, authoring, editing, burning and viewing high-definition personal content.</p>

<p>"Consumers are demanding a better experience," said Bob DeMoulin, marketing manager for branded storage products in Sony Electronics' IT Products Division. "Not only are we providing state of the art hardware, but also the industry's most complete software bundle and premium content."</p>

<p>"Sony's new 8X Blu-ray Disc writable drive significantly improves the BD recording speed, a key feature in the optical storage technology," said Wolfgang Schlichting, research director for removable storage at IDC. "The explosion of digital media usage by consumers, whether in the form of high- definition video, music or data, continues to grow at exponential rates. Innovative products such as this next-generation drive will help fuel the acceleration of Blu-ray adoption in the years ahead with more than 100 million drives shipping worldwide by 2011."</p>

<p>The BWU-300S drive can record up to 50GB of data for random access storage and backup on BD-R (write once) or BD-RE (rewritable) discs, or up to 230 minutes of high-definition HDV 1080i video on a BD-R/RE 50GB disc. It also supports recording on standard single layer 4.7GB DVD+-R/+-RW/-RAM discs, 8.5GB DVD+-R double/dual layer discs, and CDs.</p>

<p>The internal drive features a Serial ATA (SATA) interface and standard 5.25-inch form-factor for easy installation inside a desktop PC with Microsoft(R) Windows XP or Windows Vista(R) operating systems.</p>

<p>The new drive is fully supported by Adobe(R) Encore(R) CS3 software, now included with Adobe Premiere(R) Pro CS3, and Sony's Vegas Pro 8 and DVD Architect Pro 5 software, providing video production professionals with another option for outputting high-definition video on a Blu-ray Disc with MPEG-2 or H.264 compression.</p>

<p><br />
<B>Availability</B></p>

<p>The BWU-300S drive will be available through select retailers, resellers and directly at sonystyle.com starting next month. Pre-orders are now being accepted by Sony on the website.</p>

