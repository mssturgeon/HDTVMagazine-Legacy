<p><B>DENVER--(BUSINESS WIRE)</B>--Continuing its leadership position in developing the world's thinnest HDTVs, Hitachi Home Electronics (America), Inc. has unveiled the first Plasma Display Panel in its UltraThin "1.5" family. This gorgeous new plasma addition to Hitachi's 1.5 line - so named for its ultra thin 1.5-inch depth - will be offered in a 50-inch screen size, making it among the largest in the UltraThin category. In fact, it represents one of the world's thinnest, at approximately one-third the depth of other plasma displays.</p>

<p>This new product embodies an engineering milestone of major significance for Hitachi and the HDTV industry. The 50-inch 1.5 UltraThin PDP is expected to be a main attraction of the CEDIA Expo in Hitachi's booth (#925).</p>

<p><br />
<B>Hitachi Offers Full Range of Choice in UltraThin Displays</B></p>

<p>While a handful of companies, including Hitachi, have already developed UltraThin LCD models, Hitachi is at the forefront and among the first vendors to demonstrate an UltraThin plasma display. For a variety of technical reasons, the challenges in producing a thin plasma display greatly exceed those associated with developing a thin LCD, making Hitachi's achievements - 1.5-inch UltraThin models in both LCD and PDP - even more impressive. As a result, Hitachi has already captured an early lead in the rapidly emerging and commercially attractive emerging category of UltraThin Displays.</p>

<p>"The industry theme of 'Thin is In' continues apace and Hitachi was one of the first to propel this trend," said Daniel Lee, vice president of marketing for Hitachi Home Electronics (America), Inc. "Hitachi's goal is to offer consumers more choice and greater flexibility. That means LCD or plasma.</p>

