<center><i>Epson Builds Upon Leadership Position as Number-One Selling Projector Brand Worldwide With New High-Performance, High-Value 1080p PowerLite Home Cinema 6100</i></center><br />
<br />
 
<B>DENVER, Colo. - Sept. 4, 2008</B> - Continuing its long-established leadership role as the number one selling projector brand worldwidei, Epson today announced the introduction of its latest 3LCD 1080p front projector, the high-performance, and high-value PowerLite Home Cinema 6100. Redefining the price-to-performance equation, the Home Cinema 6100 provides full 1920 x 1080 progressive high definition resolution at an amazing $1,999 price point, bringing the big-screen high definition home theater experience to an even wider range of consumers.
 
"Our goal is to drive the growth of the home theater market in a wide range of customer segments, bring incredible big-screen experiences to first-time home entertainment consumers and to the most discerning AV elitists," said Rajeev Mishra, director, Projector Marketing and Development, Epson America. "The Home Cinema 6100 is especially ideal for home theater enthusiasts, delivering the optimal balance of quality, performance, ease-of-use, and flexibility at an outstanding value." 
 
At the heart of the Home Cinema 6100's optical imaging engine is Epson's latest-generation D7 high definition resolution LCD technology. Unlike projectors which use a spinning color wheel with a white segment, 3LCD technology delivers realistic, vibrant colors without the possibility of color break-up. This latest technology also provides substantially improved contrast, reaching an incredible 18,000:1 dynamic contrast ratio (a 50 percent improvement over earlier models) to deliver brighter and more accurate whites and darker blacks.
 
Another contributing factor to the Home Cinema 6100's increased contrast is its exclusive Dynamic Iris system, which allows light to be controlled precisely on a frame-by-frame basis.  This feature is especially ideal for projecting fast-action movies that involve quick changing scenes.  This is largely due to the Dynamic Iris system's ability to make automatic light output adjustments up to 120 times per second.  The projector also features Epson's exclusive Cinema Filter that delivers a larger color space for improved color accuracy and a more film-like image. Epson has also collaborated with Fujinon - the leading provider of precision optics to the digital film and HDTV camera industry - to develop this projector's unique OptiCinema&trade; multi-lens system.  This feature projects clean, precise edges with consistent image quality across the entire screen.  It also gives users more options and flexibility in terms of where they wish to install the projector.  
The Home Cinema 6100's light source uses a newly-updated E-TORL&reg; (Epson Twin Optics Reflection Lamp), an exclusive Epson design. Unlike off-the-shelf lamps, the ultra high efficiency E-TORL design provides optimum light uniformity and is rated at 200 watts (compared to 170 watts with earlier models). This enables the projector to deliver an incredible 1,800 lumens of white and color light output. It also allows the projector to be used with larger screen sizes (greater than ten feet diagonal), while still providing a bright, impressive picture.
 
A significantly improved airflow system in the Home Cinema 6100 contributes to more efficient use of power, reduced cool-down periods and lower fan speeds that result in quieter operation (only 22 db) than earlier models. The airflow system also takes advantage of an advanced air filtration system that achieves up to 98 percent efficiency which contributes to longer filter life.
The Home Cinema 6100 features numerous high definition inputs, including a high definition component video input as well as two HDMI version 1.3a digital inputs.  An S-video input and a composite video input are also provided, along with a VGA-type RGB input (D-sub 15) to accept a wide variety of computer resolutions including high definition, bringing the number of HD-compatible inputs to four.

<p>Stylishly designed, the Home Cinema 6100 features a white casing with silver accents and a reversible Epson logo on the front panel that can be reoriented for tabletop, shelf and ceiling mounting. An integrated cable hook ensures that connections always remain solid and secure, while an optional rear panel cable cover fully encloses the input panel to hide wiring.</p>

