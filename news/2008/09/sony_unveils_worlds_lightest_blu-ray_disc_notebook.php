<p><B>SAN DIEGO, Sept. 23 /PRNewswire/</B> -- Sony today took the wraps off the world's lightest computer with Blu-ray Disc(TM) technology -- the VAIO(R) TT Series notebook.</p>

<p>Housed in a lightweight carbon-fiber chassis, this new model weighs just 2.87 pounds and is less than 1-inch thin.</p>

<p>"This engineering marvel packs the power of HD technology into an ultra-light, ultra-portable notebook," said Mike Abary, senior vice president of VAIO product marketing at Sony Electronics.</p>

<p>Select models play Blu-ray Disc movies in full HD 1080p resolution when connected to a compatible HDTV. These units can also record, store and play back personal content on high-capacity BD media.</p>

<p>It features an 11.1-inch widescreen display (measured diagonally) with Sony's XBRITE-DuraView(TM) LCD technology, delivering 100 percent color saturation for a wide range of vibrant colors and true-to-life picture quality. This technology also produces a brighter screen thanks to an energy-efficient white LED backlight so you can view photos in crystal-clear resolution.</p>

<p>The display is ideal for Blu-ray Disc movies. Since many HD films are shot using a 16:9 aspect ratio, the unit's extra-wide LCD is constructed with the same dimensions. This minimizes the black bars that typically appear, letting you view movies in their intended format.</p>

<p>For those who prefer to watch content on a big screen television, the TT model also has an HDMI(TM) output connector so you can connect it to a compatible high-definition TV for a larger viewing experience (connector cable sold separately).</p>

<p>It is equipped with Intel(R) Centrino(R) 2 processor technology for powerful PC output and energy-conserving features that deliver long battery life.</p>

<p>Select VAIO TT notebooks feature a dual channel 256GB (128GB X 2) solid state drive (SSD) with RAID technology. The result is quicker boot-up times, faster application launches and overall enhanced performance.</p>

<p>The PC integrates wireless Wide Area Network (WAN) technology provided by the Sprint(R) Mobile Broadband Network and its latest mobile network technology, EV-DO Revision A. For this, a separate Sprint service subscription is required.</p>

<p>The notebook comes with the choice of Windows Vista(R) Home Premium, Vista Business and Vista Ultimate operating systems. Windows(R) XP Professional is also available on select models.</p>

<p>All models are ENERGY STAR(R) 4.0 compliant, hold an EPEAT Silver ranking and incorporates such eco-conscious features as a mercury-free LED backlit LCD.</p>

<p>The TT model starts at $2,000. The BD version will go for about $2,700, while the SSD model (128GB) for around $2,750. It is available in a premium carbon black, silk black, champagne gold and crimson red.</p>

<p>The VAIO TT notebooks will be available online at http://www.sonystyle.com/pr/tt. They will also be sold at Sony Style(R) stores, military base exchanges, and select retailers around the country starting this fall.</p>

