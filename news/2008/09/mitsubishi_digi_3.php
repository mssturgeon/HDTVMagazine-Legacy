<p><B>IRVINE, Calif.--(BUSINESS WIRE)</B>--Mitsubishi Digital Electronics America's Presentation Products Division, known for award-winning, high-quality, high-definition presentation and display products, is announcing its Diamond Series of projectors designed for the finest high-definition home theater environments.</p>

<p>Mitsubishi's new channel strategy for its 1080p HC7000U and HC6500U premium projectors signifies the quality and value of its products for end-users and profitability for its loyal channel partners. These new projectors are available exclusively through custom home theater systems integration and high-end retail channels.</p>

<p>The Diamond Series of projectors includes Mitsubishi's new flagship home theater projector, the HC7000U, and the HC6500U, both premiering at the CEDIA Expo. These HD projectors boast a new sleek and highly stylized design with a rich black cabinet and are also two of the quietest projectors on the market today, emitting only 17 dBa in low mode.</p>

<p>The flagship HC7000U HD projector uses polarization to create one of the highest contrast ratios available in a projector of this caliber. At 70,000:1, rich details, deep blacks, and great depth and dimension are obvious in dark scenes like those in classic film noir and action films.</p>

<p>Mitsubishi is also announcing its first ultra-bright 1080p HD projector designed for more exposed, brighter home theater environments.</p>

<p>When living spaces are intended to capture fantastic, breathtaking views, installing a home theater environment in those areas often requires closing the curtains. However, with Mitsubishi's new high-brightness HD8000, its 5000 lumens creates incredibly brilliant HD 1080p video images that don't need a darkened room so ocean, mountain and city lights views can be enjoyed alongside an HD movie during panoramic sunsets, lazy afternoons or early weekend mornings.</p>

<p>The HD8000 projector uses three robust 1.1 inch 3LCD inorganic panels and includes a DVI connector with an HDMI&trade;-to-DVI&trade; adapter for a wider range of HD connectivity options in a stylish black cabinet.</p>
