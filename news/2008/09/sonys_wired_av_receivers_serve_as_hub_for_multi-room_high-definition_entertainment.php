			<p class="prtitle">Sony's Wired AV Receivers Serve as Hub for Multi-Room High-Definition Entertainment</p>

<center><i>Can Also Connect to DLNA PCs and the Internet for Access to Photos, Music and Video</i></center><br />
<br />

<p><B>DENVER, Sept. 3 /PRNewswire/ -- (CEDIA Booth #600)</B> -- Sony today introduced two new ES A/V receivers with a CAT5e port, allowing them to provide high-definition video to a second room.</p>

<p>The STR-DA6400ES and STR-DA5400ES models offer second room high-definition video and audio distribution via CAT5e wiring. The CAT5e output shared by both models provides an inexpensive option in sharing HD video in a second room.</p>

<p>Additionally, the STR-DA6400ES features an extra CAT5e input and is Digital Life Network Alliance (DLNA) compliant. The combination makes the STR-DA6400ES Sony's first network A/V receiver. Now there is a Sony A/V receiver that can stream music, photos and video from a DLNA-compliant PC plus it can access online music content from Rhapsody(R) and Shoutcast(R) Internet Radio without a PC.</p>

<p>"High-definition and other digital content is no longer limited to the living room and Sony's new ES receivers have been designed to be the hub of this change in entertainment options," said Tyler Ishida, director of marketing for Sony Electronics' Digital Imaging and Audio Division. "Backed by 25 years of expertise, Sony's new ES products not only deliver high quality audio and video, but offer the ability to connect new types of entertainment while distributing them throughout the home."</p>

<p>Designed to provide the highest audio and video performance, the new receivers are fully compatible with Blu-ray Disc(TM) format by supporting 1080/24p video signals and the latest audio formats (Dolby(R) Digital Plus, Dolby(R) TrueHD, DTS(R) High Resolution Audio and DTS(R) HD Master Audio).</p>

<p>Both receivers add a second Faroudja DCDi Cinema(R) chip allowing standard definition video sources to be up-scaled to 1080p in the main room (zone 1) when connected via HDMI(TM). The second Faroudja DCDi chip upscales standard definition video content in a second room (zone 2) to 1080i. This latest chassis innovation insures an outstanding picture no matter where you are watching your content. Both receivers also support x.v.Color and Deep Color enabled sources.</p>

<p>The dual Faroudja DCDi Cinema chips also allow Sony's xross media bar(TM)-inspired graphical user interface to be shared in both the main plus a second room for easy navigation and control of content. The Faroudja chip can also blend the onscreen GUI over 1080p sources via HDMI and provide picture-in-picture monitoring of another room or second room (zone 2) source.</p>

<p>The models decode Direct Stream Digital (DSD) audio sources such as that from Super Audio CD players, and feature Sony's D.L.L. (Digital Legato Linear) audio scaler. The proprietary technology works much like a video scaler, analyzing standard definition (compressed) audio signals like MP3 audio files and upscales them to 192 KHz resulting in higher quality audio.</p>

<p>Dual Digital Media Ports adds control and connectivity options for music playback through more than one accessory, including a cradle for iPod(R), a Network Walkman(TM) cradle, a PC client device and a Bluetooth(R) adapter (each is sold separately). The models are also Sirius(R) and XM Connect-and-Play(TM) ready and offers RS-232C, 12 volt triggers and IR repeaters for custom installation solutions.</p>

<p>Other features include Sony's Digital Cinema Auto Calibration(TM) for simple surround sound setup and BRAVIA(R) Sync(TM) for Theatre for easy synchronization of compatible home theater components.</p>

<p>The STR-DA6400ES 7.1 channel receiver has a 120-watt power amplifier x 7 (8 ohms, 20 Hz - 20 kHz, 0.09 percent THD), six HDMI inputs (five rear, one front) with Direct Stream Digital and two HDMI outputs.</p>

<p>The model's Ethernet port allows it to connect DLNA-compliant PCs via CAT5e wiring. Not only does this connection allow users to stream photos music and video, it provides access to Shoutcast(R) Internet Radio and Rhapsody Music Service. Additionally, the Ethernet connection provides easy access to firmware upgrades and service.</p>

<p>The model also distributes HD video to a second zone via CAT5e wiring and offers audio distribution to three zones and picture-in-picture for monitoring of multi-zone output or an external video source.</p>

<p>The STR-DA6400ES also features Sony's High Quality Audio Transmission System (H.A.T.S.) that efficiently manages the robust digital signal insuring a consistent, high quality exchange.</p>

<p>The model will be available in October for $2,500.</p>

<p>The STR-DA5400ES 7.1 channel receiver has a 120-watt amplifier x 7 (8 ohms, 20 Hz - 20 kHz, 0.09 percent THD), six HDMI inputs with Direct Stream Digital and two HDMI outputs. The model's CAT5e port allows it to distribute high-definition video to a second zone. It also offers audio distribution to three zones and picture-in-picture for monitoring of multi-zone output or an external video source.</p>

<p>The model will be available in September for about $2,000.</p>

<p>Sony also announced a new Super Audio CD and compact disc player complementing the new ES receivers. The single-disc SCD-XA5400ES incorporates an uncompressed digital output for DSD signal via HDMI. Leaning on Sony's ES heritage, the model incorporates audiophile-grade discrete components such as twin R-Core power transformers and gold-plated outputs to maintain the utmost performance.</p>

<p>The SCD-XA5400ES will be available in October for about $1,500.</p>

<p>Both ES receivers and the SCD-XA5400ES are supported by a five-year limited manufacturer warranty and will be available online through http://www.sonystyle.com/, at Sony Style stores nationwide and at authorized Sony dealers across the country.</p>

