			<p class="prtitle">Sony Bridges Gap Between High-Definition Prosumer and Professional Video Production</p>

<center><i>One New Camera Brings Cinematic Film-Look for Amateur Videographers and Another Offers Advanced Production Capabilities for Directors of Photography</i></center><br />
<br />

<p><B>SAN DIEGO, Sept. 10 /PRNewswire/</B> -- Sony is expanding its industry leading line-up of high-definition video products with two new HDV(TM) cameras designed to meet the needs of professionals and prosumers.</p>

<p>With the HDR-FX1000 Handycam(R) camcorder, more adept consumer videographers gain access to cinematic features, including 24P scanning and advanced color settings for around $3,200. With the HVR-Z5U camcorder, professionals will appreciate its native 24P recording and other professional features -- all for less than $5,000 -- as well as tapeless recording capability through an optional CompactFlash(TM) adapter.</p>

<p>"The HDR-FX1000 is appealing to the amateur videographer shooting weddings or the aspiring cinematographer," said Kelly Davis, director of camcorder marketing at Sony Electronics. "The combination of film-like movie quality and advanced color settings makes it possible for prosumers to achieve the deep cinematic look they crave at a reasonable price."</p>

<p>The HVR-Z5U camcorder offers a "step-up" solution for professionals who desire a more advanced set of features.</p>

<p>"Professionals need features like balanced audio, XLR inputs, timecode and more," said Bob Ott, vice president of professional audio and video products at Sony Electronics. "They also need access to technical resources to help them with issues like integrating with non-linear editing systems. This is where a professional solution like the HVR-Z5U is an appropriate choice."</p>

<p><br />
<B>Enhanced Image Capture</B></p>

<p>Both models use three of Sony's ClearVid(TM) 1/3-inch CMOS sensor chips, which are designed to provide high sensitivity, deep resolution, high-speed reading, low noise and a wider dynamic range. The CMOS sensors capture full HD 1920 x 1080 resolution, resulting in better picture quality when recorded onto miniDV tape in the HDV format (1440 pixels x 1080 lines). Each of the three sensors is dedicated to one color -- red, blue and green -- for natural, more accurate color reproduction.</p>

<p>With a 45-degree rotated pixel layout, the ClearVid CMOS sensor system offers outstanding pixel surface area while maintaining high resolution. The Exmor(TM) technology features a unique column-parallel analog-to-digital conversion technique and dual noise canceling, resulting in digital signals with extremely low noise. The technologies combine to allow the new camcorders to perform significantly better in low-light environments with sensitivity of 1.5 lux.</p>

<p>Both cameras use Sony's XtraFine LCD(TM) (3.2-inch, 921,000 dots) and XtraFine electronic viewfinder (0.45-inch, 1,227,000 dots) for high-resolution and high-contrast images with remarkable color reproduction.</p>

<p><br />
<B>Ideal For Aspiring Cinematographers</B></p>

<p>The HDR-FX1000 is Sony's first Handycam camcorder to feature progressive scan at 1080/24p and 30p, giving video productions a film-like look. Using a two to three pull down, the 24P scanned image is converted to 60i for easy editing with user's existing software applications. CinemaTone Gamma(TM) and CinemaTone Color(TM) settings complement the 24P capabilities to create a rich dreamlike picture processing while three built-in neural density filters provide exceptional light control even in extremely bright environments.</p>

<p>Equipped with a refined level of optical performance, the HDR-FX1000 and the HVR-Z5U models are the first camcorders to have a Sony G lens with a 29.5mm wide-end viewing angle, extra-low dispersion glass and 20x optical zoom. The fixed lens is optimized to perfectly complement the cameras' advanced image sensor and image-processing technology.</p>

<p>The HDR-FX1000 model enables prosumers to define their own manual settings for iris, gain, white balance, shutter speed and focus for increased creativity and control. Use of any of the three manual rings for adjustments to zoom, focus and iris provides even more flexibility.</p>

<p><br />
<B>Professional Video Production</B></p>

<p>The HVR-Z5U camcorder offers the addition of several features specifically designed for professional video production, such as progressive scan shooting at 1080/24P and 30P, DVCAM(TM) recording, timecode support and two XLR balanced audio inputs.</p>

<p>Professionals can record the native 24P/30P signal on to the videotape used in the camcorder or to CompactFlash cards -- simultaneously or separately -- with the optional HVR-MRC1K recording unit. This unit attaches directly to the back of the camcorder, eliminates the need for cables and automatically synchronizes with the recording action of the camcorder.</p>

<p>The recording unit can be directly attached to the new HVR-Z5U camera, as well as to Sony's HVR-Z7U and HVR-S270U models. It will also work with other HDV camcorders using a supplied iLINK(R) (IEEE-1394) cable and shoe adapter.</p>

<p>The camcorder, and the HVR-MRC1K adapter will be compatible with Sony's Professional 306x CompactFlash card. The recording times on an 8 and 16 GB CompactFlash card in HDV, DVCAM and DV format are approximately 36 and 72 minutes, respectively.</p>

<p><br />
<B>Availability</B></p>

<p>The HDR-FX1000 camcorder will be available in early November at authorized dealers nationwide, Sony Style(R) retail stores and online through http://www.sonystyle.com/.</p>

<p>The HVR-Z5U professional camera is expected to be available in December for a suggested list price of $4950. The HVR-MRC1K recording unit should be out in October for a suggested list price of $940.</p>

<p>Source: Sony Electronics, Inc. </p>
