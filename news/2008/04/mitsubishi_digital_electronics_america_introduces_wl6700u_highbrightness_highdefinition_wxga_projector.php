<p>Blasting 5000 lumens with a 1000:1 contrast ratio, the WL6700U uses three robust 1.2 inch 3LCD inorganic panels. This projector is ideal for commercial venues such as sports bars, restaurants or hotel conference rooms as well as school auditoriums and corporate boardrooms that require wide-format, high-definition resolution HD video. Other applications include medical imaging, CAD/CAM designs, geo-spatial mapping and more. The WL6700U is available in a white outer cabinet and also features a DVI connector for a wider range of HD connectivity options.</p>

<p>"Our new WL6700U fits a perfect niche for those who need high brightness and wide format imaging," said Wayne Kozuki, product manager, Mitsubishi Digital Electronics America's Presentation Products Division.</p>

<p>The WL6700U can create side-by-side images for enhanced video conferencing applications that include a live video feed and simultaneous presentations on the same screen, perfect for large venues where ambient light can be a factor. It also offers RJ45 networking support for easy online management and control.</p>

<p>With a built-in motion-sensitive anti-theft alarm, Mitsubishi's WL6700U is designed to deter projector theft from public venues such as classrooms, auditoriums or other open-access conference room settings. The motion detector is built into the connector panel cover and is set manually by a key. Once the cover is installed and the safety key removed, the projector's alarm is automatically set; moving the projector will sound a 120-decibel high pitch alarm.</p>

<p>"Mitsubishi is committed to making wide screen projectors become more mainstream, thus we are offering a range of WXGA projectors that fit today's display requirements," said James Chan, director, product marketing, Mitsubishi Digital Electronics America's Presentation Products Division. "Some of our customers work only in wide screen formats; we listened and brought a new projector to market just for them."</p>

