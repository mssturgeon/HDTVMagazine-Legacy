<p>"With more and more consumers discovering and enjoying music videos online, we are confident that fans and artists will embrace the engaging product the PluggedIn team has put together," stated Rio Caraeff, Executive Vice President of Universal Music Group's eLabs. "This is the first time customers will be able to view our videos online at such high quality, and the difference is remarkable."</p>

<p>"There is no question that music remains a large part of our everyday lives and a key element to the online community experience," commented Jeff Somers, CEO of PluggedIn. "This strategic partnership is an ideal fit as it provides us and our customers with access to the resources of Universal Music, the world's largest producer of music programming."</p>

<p><br />
<B>About Universal Music Group</B></p>

<p>Universal Music Group is the world's leading music company with wholly owned record operations or licensees in 77 countries. Its businesses also include Universal Music Publishing Group, the industry's largest global music publishing operation.</p>

<p>Universal Music Group consists of record labels Decca, Deutsche Grammophon, Interscope Geffen A&M Records, Geffen Records, Island Def Jam Music Group, Lost Highway Records, MCA Nashville, Mercury Nashville, Mercury Records, Philips, Polydor Records, Universal Music Latino, Universal Motown Records Group, and Verve Music Group as well as a multitude of record labels owned or distributed by its record company subsidiaries around the world. The Universal Music Group owns the most extensive catalog of music in the industry, which is marketed through two distinct divisions, Universal Music Enterprises (in the U.S.) and Universal Strategic Marketing (outside the U.S.). Universal Music Group also includes eLabs, its new media and technologies division, Bravado, its merchandising company, and Twenty-First Artists, its full service management division.</p>

<p>Universal Music Group is a unit of Vivendi, a global media and communications company.</p>

<p><br />
<B>About PluggedIn</B></p>

<p>PluggedIn launched its beta service in April 2008, with the goal of changing the way consumers interact with and view premium entertainment content on the web. PluggedIn is an internet media company that offers streaming, free to consumer, HD and broadcast quality videos to fans everywhere. The entertainment site features over 10,000 HD and broadcast quality music videos and more than one million Artist Profiles, and is powered by an innovative new media player that supports high-definition full-screen video playback with no buffering and DVD like controls, a multimedia search engine and fan-centric community features. PluggedIn is based in Santa Monica, CA. The company was founded and is managed as a rare partnership between proven Internet entrepreneurs and successful music industry executives. The company's team includes Brett O'Brien, founder of Xdrive, which was sold to America Online (AOL)in 2005; Kevin Welk, CEO of Vanguard and Sugar Hill Records; Jeff Somers, former executive with Amazon and Zillow; JJ Aguhob, previously with Xdrive and AOL, and an early team member at MySpace; John Gaa, previously with Xdrive and Sony; and Nicola Marzolla, from Yahoo Music.</p>

