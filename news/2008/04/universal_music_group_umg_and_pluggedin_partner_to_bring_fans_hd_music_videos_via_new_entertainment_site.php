<p><B>LOS ANGELES, and NEW YORK, April 16 /PRNewswire/</B> -- Universal Music Group (UMG), the world's leading music company, and PluggedIn (http://www.pluggedin.com/), announced today an agreement whereby PluggedIn users will have access to thousands of high-definition quality videos from UMG's extensive roster of chart-topping artists covering every genre of music.</p>

