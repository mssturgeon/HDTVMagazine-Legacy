				<p><P class="editorial">Gary Shapiro, president of the Consumer Electronics Association in Arlington, VA., is sharpening his battle ax for the likes of Lou Dobbs. Dobbs is chief among those believers and campaigners against many elements of free trade, at least as practiced around the world today. Dobbs asserts that FT is hollowing out our advanced civilization and replacing it with a third-world-like existence--a bad deal for America. Shapiro holds a far different view and offered it on Dobbs afternoon CNN television program a few months ago. The recalcitrant Dobbs left Shapiro appearing as a well-spoken but one-sided representative of a foreign constituency rather than a noble upholder of the truth. Shapiro is widely acknowledged as being a savvy, but shoot-from-the-hip operator, and one of the most effective lobbying forces in all Washington. Shapiro said recently in a confident statesman-like address to the Detroit Economic Club that contrary to popular thinking the benefits of Free Trade are many and permits an embrace of innovative and standardized digital consumer electronics that can be on board the products of Detroit. "Detroit must and can compete in the new economy."<br /><br />To beef up his Free Trade arguments for the following report was commissioned for (and released today) by the CEA. __Dale Cripps</P></p>

<p><em>U.S. Consumer Electronics Industry Indirectly Impacts One-Tenth of U.S. GDP and Supports 15.4 Million American Jobs in Related Industries</em>.</p>

<p><strong>Arlington, Va., April 2, 2008</strong> - Fueled by international trade, the consumer electronics (CE) industry is poised to generate $1.4 trillion in direct business activity in 2008, while directly employing more than 4.4 million Americans, according to a new study released today by the Consumer Electronics Association (CEA)®.  Burgeoning international trade is helping grow the sector, driving 14 percent of the CE industry's total output and 16 percent of its total employment.  </p>

<p>The study, conducted by PricewaterhouseCoopers, LLP, defined the consumer electronics industry as the manufacture of electronics products, the creation of services and content for these products, and the distribution of these products, services and content throughout the economy.  Beyond its significant direct impact on the economy and job market, the CE industry also spurs billions of dollars in additional indirect economic benefits in the form of industry purchasing and consumer spending in related industries.  The CE sector also helps to support millions of additional jobs in related industries. Taken together, the CE industry will directly and indirectly produce $2.6 trillion in output, contributing $1.3 trillion to the economy in 2008 and supporting 15.4 million jobs in related industries, researchers estimated. In addition to tracking national trends, the study also assessed the impact of trade on a state-by-state basis. A copy is available at www.CE.org.  </p>

<p>"When America competes in the global marketplace, our nation's economy and workers win," CEA President and CEO Gary Shapiro said. "Upholding our national commitment to free trade goes far beyond simply ensuring that our industries can compete on a level playing field. This study demonstrates that supporting free trade is about nurturing an economic engine that contributes trillions of dollars to the economy and supports millions of workers." </p>

<p>The study found that international trade has played a major role in the CE industry's emergence as a powerful economic driver.  The impact from trade is largely a result of exports, with CE sector exports contributing more than 76 percent and 61 percent of the total impact from international trade for output and jobs, respectively. </p>

<p>"It's clear from the data that our longstanding national commitment to free trade has been an extraordinarily successful policy," Shapiro said. "Now it falls to Congress to build on that success by approving critical free trade agreements with Colombia, Panama and Korea."  </p>

<p><strong>Other key findings include:</strong></p>

<p>The CE sector directly contributes $1.4 trillion in output, $325 billion in labor compensation, $145 billion in tax payments, and 4.4 million jobs in the U.S. This economic activity means the CE sector directly contributes $585 billion to U.S. gross domestic product (GDP) - 4.6 percent of the national economy. <br />
Including indirect and induced effects in related industries, the CE industry contributes $2.6 trillion of output, $836 billion of labor compensation, $321 billion in taxes and 15.4 million jobs. This indirect and induced economic activity means that overall the CE sector contributes $1.3 trillion to U.S. GDP - 10.4 percent of the national economy. </p>

<p>Exports are an important component of U.S. economic activity in the CE sector. Goods and services account for roughly 10 percent of CE sector output. This translates into about 1.5 million U.S. jobs reliant on CE exports.  Tax payments of $6 billion are attributable to the sale of U.S. CE goods and services overseas. That number grows to roughly $30 billion when indirect and induced effects are included. </p>

<p>The study also found on a national basis the CE sector, including related industries, is 10.4 percent of GDP, 10.1 percent of labor compensation, and 9.1 percent of employment.  This not only illustrates the importance of the sector and related industries to the broader economy, but also that they provide above average compensation for American workers.   </p>

<p>The state-by-state analysis revealed that all 50 states have significant activity in the CE sector and reap the benefits in the form of overall economic output and job creation. California, Texas, New York, Florida and Illinois ranked the highest in the consumer and enterprise markets. Massachusetts and Minnesota are also among major exporters. </p>
