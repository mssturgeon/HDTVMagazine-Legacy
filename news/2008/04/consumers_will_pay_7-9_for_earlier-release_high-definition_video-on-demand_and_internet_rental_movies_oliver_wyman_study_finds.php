			<p class="prtitle">Consumers Will Pay $7-9 for Earlier-Release, High-Definition Video-on-Demand and Internet Rental Movies, Creating Billions of Dollars in Industry Growth, Oliver Wyman Study Finds</p>

<center style="display:table"><i><ul><li>$5 billion+ growth opportunity for U.S. movie industry, on base of $50 billion</li><li>DVD cannibalization minimal; more for rentals than sales</li><li>Internet rentals more promising than sales for now; consumers will pay up to $5 more for digital ownership with interoperability and Internet storage</li></ul></i></center><br />
<br />

<p><B>NEW YORK--(BUSINESS WIRE)</B>--A study of 2,000 U.S. consumers conducted by Oliver Wyman, an international management consulting firm, found that a price point between $7 and $9 is optimal for the next generation of video-on-demand (VOD) and Internet movie rentals: high-definition (HD) movies released on the same day as DVDs. This premium over today's $4 price for standard DVD or VOD movie rental would create substantial market growth by 2010.</p>

<p>Rollout of HD VOD and Internet movies on day-and-date of DVD release is a growth opportunity not only because consumers value them and will pay more, but also because this expanded availability will increase overall movie viewership. The Oliver Wyman study found that that these enhanced offers would lead U.S. consumers to watch and pay for an average of three more movies per year than they do today, creating a net annual increase in domestic consumer movie spending of more than $5 billion, from the current base of $50 billion.</p>

<p>Demand for Blu-ray discs was also tested in this study, and this new format will drive 6% growth of packaged media by 2010, even as VOD/Internet distribution grows.</p>

<p>The Oliver Wyman study further found that DVD sales will be only marginally cannibalized by enhanced VOD and Internet offers at these prices. In fact, retailers could charge an additional $2 for DVDs that include a portable e-copy of the movie for use on other devices.</p>

<p>Mark Teitell, a partner in Oliver Wyman's Media & Entertainment practice, said: "This research reveals a clear opportunity for the industry to introduce new offerings that tap unmet consumer demand, while fitting well with existing movie distribution channels. Ultimately, the consumer will benefit the most - and be willing to pay for those benefits - from the additional choice and consumption options."</p>

<p>For Internet movies, the Oliver Wyman study found that consumers prefer Internet rentals more than today's Internet sales offers, as they don't see digital ownership having comparable benefits to owning a DVD. However, if available, consumers will pay up to an additional $5 for advanced features that approximate DVD ownership: assurance that purchased movies will work on a wide variety of devices, the right to burn a DVD, and secure Internet-based storage to protect against loss of digital files.</p>

<p>Martin Kon, a partner and head of Oliver Wyman's Media & Entertainment practice, added: "This study shows that enhanced VOD and Internet offers will benefit the entire industry - studios, network operators, and retailers alike - to the tune of several billion dollars."</p>

<p><br />
<B>About the Study</B></p>

<p>This web-based study, conducted in Q4 2007 with 2,000 U.S. consumers, used advanced consumer research techniques to simulate actual buying decisions. The study focused on feature-length movies that consumers pay for (box office, DVD sales/rentals, pay-per-view and VOD, premium movie channels, and Internet sales/rentals). Research respondents:</p>

<ul><li>Completed a profile of their actual current video buying/rental behavior</li><li>Saw interactive, multimedia materials explaining anticipated and possible 2009-2010 offers spanning Blu-ray discs; hybrid offers combining DVDs and a digital file consumers can use on other devices; video-on-demand offers with expanded title availability, in HD and with early availability; and Internet sales/rental offers spanning PC, game console and set-top box models of Internet distribution</li><li>Responded to a series of simulated choices among new competing offers, indicating how their current buying/renting behavior will be different when new offers are available</li></ul>

<p>To make projections, Oliver Wyman's "pure" measurement of demand was calibrated to the real-world market. This included normalizing to actual historical sales, and imposing assumed constraints that will remain in the 2009-2010 market, ranging from projected adoption of required hardware to ongoing penetration of digital cable and broadband Internet, to limited consumer awareness that characterizes the marketplace.</p>

