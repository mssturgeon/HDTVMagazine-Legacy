<p><B>DALLAS, April 10 /PRNewswire-FirstCall/</B> -- Beginning this week, in addition to the standard DVDs lining its shelves, Blockbuster Inc. will be offering customers something extra -- Blu-ray movies, for rent and sale in all of its corporate stores in the U.S., as well as in Canada, and select domestic franchise locations. Blockbuster made news last July with its announcement that the company was making Blu-ray available in 1,700 of its stores. Now, less than a year later, the company is positioning itself to become the customer's Blu-ray headquarters for rental and retail product with this national launch.</p>

<p>To highlight the availability of Blu-ray in its stores, Blockbuster is installing Blu-ray kiosks in the center of its stores. Featuring a 42-inch high-definition TV with movies playing via a PLAYSTATION(R)3 (PS3(TM)) console, the Blu-ray kiosks will enable customers to experience the movie-viewing advantages of high-definition technology while also driving home the point that PS3 consoles double as Blu-ray players.</p>

<p>As for Blockbuster's by-mail service, in addition to the wide selection of Blu-ray titles it carries online, this week Blockbuster began offering online subscribers a Blu-ray preference setting so they can automatically indicate that they want to receive all available movies in the high-definition format.</p>

<p>"Blockbuster was the first national retailer to accurately recognize and react to consumers' preference for this format when we added Blu-ray discs to a large percentage of our stores last summer," said David Podeschi, Blockbuster Senior Vice President, Merchandising, Distribution and Logistics. "Now, with this national rollout, we believe Blockbuster is perfectly positioned to drive consumer adoption of this next generation DVD format and to become the customer's headquarters when it comes to renting or buying Blu-ray movies, whether in-store or online."</p>

<p>Podeschi continued, "Our mission at Blockbuster is to provide consumers with convenient access to media entertainment -- whether that's with Blu-ray or standard DVDs, retail or rental, through our stores, by mail and through new technologies."</p>

