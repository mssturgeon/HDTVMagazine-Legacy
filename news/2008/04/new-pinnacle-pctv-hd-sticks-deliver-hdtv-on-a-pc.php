<p><B>Mountain View, Calif., April 3, 2008</B> - Pinnacle Systems, Inc., the consumer division of Avid Technology Inc. (Nasdaq: AVID) , announced today the next generation of its Pinnacle PCTV&trade; HD Stick, and Pinnacle PCTV&trade; HD Pro Stick-the number one selling TV tuner for PCs in the U.S. retail market in 2007, according to NPD. In addition to delivering free digital HD and SD TV over-the-air (ATSC), these new Pinnacle PCTV HD and HD Pro Sticks now support unencrypted digital cable (ClearQAM) channels and include a next-generation tuner/demodulator with more sensitive reception of both analog and digital TV signals and, in the case of the PCTV HD Pro Stick, even FM radio.</p>

<p>About the size of a flash drive, the new Pinnacle PCTV HD Sticks provide consumers with the brilliant sharpness of digital HDTV with resolutions up to 1080i, by simply plugging the device into a USB port on their PC. The addition of ClearQAM support allows cable TV subscribers to enjoy their favorite over-the-air (OTA) digital channels with optimal quality by connecting the digital cable directly to their PC.</p>

<p>The affordable, easy-to-use Pinnacle PCTV HD and HD Pro Sticks are for laptop users, travelers and students, who want to experience HD-quality TV at home or on-the-go without having to pay expensive service fees. They are also compelling solutions for Windows Vista&trade; and Windows&reg;XP MCE owners who did not purchase a PC TV tuner with their systems.</p>

<p>"With the February 17th, 2009 shut down of analog television approaching, users are considering cost-effective alternatives to paying for cable and satellite TV or buying a new HD TV," said Tanguy Leborgne, Pinnacle Systems Vice President of Worldwide Marketing. "At just $99 U.S., the new PCTV HD Pro Stick can provide consumers with savings of up to $1,000 on their subscription fees and it even works as a Personal Video Recorder (PVR). All you need is your laptop or desktop computer."</p>

<p>The Pinnacle TVCenter Pro software bundled with the new tuners delivers fully functional PVR capabilities that make it easy to watch, TimeShift and record SD and HD TV. For added convenience, users have the option of viewing programs in full-screen mode or in a scalable window while using other applications. An integrated Electronic Programming Guide (EPG) is included to locate programs and schedule recordings. Shows can be recorded to the user's hard drive or direct to DVD for playback on a DVD player.</p>

<p>The new Pinnacle PCTV HD Pro Stick offers all of these features plus a broad range of additional capabilities ranging from stereo sound for both digital and analog TV, stereo FM radio reception and the ability to capture a video signal from a cable/satellite set-top box or camcorder with the A/V adapter cable provided. It also supports the DivX&reg; format and includes a trial version for MPEG-4 support which enables output to a PSP&trade; or iPod&reg;.</p>

<p>Pricing, Availability<br />
The Pinnacle PCTV HD Stick and the Pinnacle PCTV HD Pro Stick will be available through leading retailers and online resellers by April 6, 2008 with U.S. pricing at $69.99 and $99.99 respectively. Both devices are fully certified for Windows Vista&trade; and Windows&reg; Media Center.</p>

