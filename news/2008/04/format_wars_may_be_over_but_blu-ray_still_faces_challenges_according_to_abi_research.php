			<p class="prtitle">Format Wars May Be Over, but High-Definition DVD Still Faces Challenges, According to ABI Research</p>

<p><B>NEW YORK--(BUSINESS WIRE)</B>--Aided by the major motion picture studios, Sony's Blu-ray format has emerged as the undisputed technology for high-definition DVD video, but according to new market data released by ABI Research, Blu-ray cannot rest on its laurels. A bright future for high-definition DVD is not a foregone conclusion.</p>

<p>One of the primary challenges facing Blu-ray, says principal analyst Steve Wilson, is that many consumers are not fundamentally dissatisfied with the quality delivered by their conventional DVD players, when "upconverted" to play on high-definition TVs. "We are starting to see an increase in the number of DVD players with built-in upconverters, and the video processing is getting better with each new generation," he says. "Today about 35% of all DVD players sold include upconversion. ABI Research expects that figure to climb to about 60% by 2013."</p>

<p>Further, the state of the Blu-ray player market is not all that encouraging. The Blu-ray installed base today is heavily tilted towards Sony's Playstation 3. Says Wilson, "The studios better hope that people are playing movies on their Playstations. Otherwise there's very little installed base. In 2008 about 85% of the Blu-ray players in the market will be found in PS3s; the dedicated consumer electronics and PC-based types of Blu-ray players won't catch up in terms of market share until about 2013."</p>

<p>In an effort to spur the market, optical disc manufacturers are lowering prices and PC manufacturers are offering lower-cost configurations. Bare-bones PCs with Blu-ray players are arriving. "But," asks Wilson, "if you're only going to spend $500-600 on a PC, are you really going to spend 40% more for a built-in Blu-ray player?"</p>

<p>Meanwhile consumer electronics manufacturers are maintaining high prices for dedicated players. "The studios had hoped to have settled the war," Wilson concludes, "but I think they're going to be disappointed when they don't see the volumes of players going up they way they would have liked."</p>

