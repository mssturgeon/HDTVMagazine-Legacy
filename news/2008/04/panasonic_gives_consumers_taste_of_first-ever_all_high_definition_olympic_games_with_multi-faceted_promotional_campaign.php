<center><i>National Truck Tour, Appearances by Gold Medal Olympians and Sweepstakes Highlight Olympic Campaign</i></center><br />
<br />

<p><B>Secaucus, NJ (April 29, 2008)</B> - Panasonic, a market and technology leader in flat panel HDTV's and an Official Worldwide Partner of the Olympic Games, celebrated the 100 day mark to the start of the Summer Olympic Games with the launch of a nationwide promotional campaign designed to make sure consumers are ready to enjoy the upcoming Olympic Games - the first time the entire Games will be broadcast in High Definition. Panasonic VIERA series Plasma and LCD HDTV's are the official HDTV of the Olympic Games.</p>

<p>"The world's athletes are getting ready to come together and compete at the Olympic Games this summer and Panasonic is helping families get ready to come together and watch them," said Christine Amirian, Vice President, Consumer Marketing Group, Panasonic Consumer Electronics Company. "We are proud to be helping deliver the first ever Olympic Games to be shot and broadcast entirely in HD to consumers in the United States and around the world."</p>

<p><br />
<B>Olympic Truck Tour</B></p>

<p>At the center of Panasonic's Summer Olympic promotional campaign is a nationwide truck tour which features a fleet of four custom-built trucks, including a 53-foot flagship vehicle. Formerly know as the Living In High Definition Tour, the vehicles have been rebranded and redesigned with an Olympic theme and messaging, including "Get Your Family Ready For The First HD Olympics."</p>

<p>The tour will visit retailers around the country and feature autograph signings at select stops by U.S. Olympic icons, such as nine-time Olympic Gold Medalist swimmer Mark Spitz and Olympic Gold Medal gymnast Kerri Strug. Visitors will also receive limited edition Panasonic Olympic Games pins and have the chance to play Mario and Sonic at the Olympic Games and compete for prizes, including Panasonic VIERA HDTV's.</p>

<p><br />
<B>Get Your Family Ready Sweepstakes</B></p>

<p>Visitors to the Panasonic trucks can also enter the "Get Your Family Ready" sweepstakes which kicks off today - 100 days from the start of the Olympic Games - and runs through the end of the Games in August. The sweepstakes features a range of prizes including Panasonic VIERA HDTV's, Blu-ray Disc Players and a Grand Prize trip for four to the 2010 Vancouver Winter Olympic Games and a Panasonic VIERA HDTV and Blu-ray Disc Home Theater system.</p>

<p>Consumers can also enter the sweepstakes by visiting www.panasonic.com/olympics. The site also features tips for getting ready for the Olympic Games and information on Panasonic's involvement in the Games.</p>

<p><br />
<B>Bringing The Olympics To The World In HD</B></p>

<p>Panasonic will deliver the largest-ever supply of digital electrical technologies to the Games of the 29th Olympiad in Beijing, China. Beijing 2008 will be the first time in history that the Olympic international broadcasting signal will be produced entirely in High Definition, making Beijing the "First HD Olympic Games." As the official sponsor for the Olympic Games in the category of Video and Audio Equipment, Panasonic, through cooperation with the International Olympic Committee (IOC), the Beijing Organizing Committee for the Games of the XXIX Olympiad (BOCOG), and the Beijing Olympic Broadcasting Co., Ltd. (BOB), is providing a full line-up of professional HD equipment for the operation of The Games.</p>

<p>Panasonic will be providing digital broadcast-related equipment including the Panasonic P2 HD series, based on solid-state P2 memory recording, as well as studio-use Digital VCRs, system cameras and TV monitors to the International Broadcasting Center (IBC) and other broadcasters for Beijing 2008. Panasonic supplied broadcast equipment and maintenance support to the host broadcaster during Barcelona '92, Atlanta '96, Nagano '98, Sydney 2000, Salt Lake City 2002, Athens 2004 and Torino 2006. This year marks the 8th Olympiad for which Panasonic has provided equipment in the official recording format for the Games.</p>

<p><br />
<B>About Panasonic</B></p>

<p>Panasonic is proud to support the Olympic Movement - which is aimed at promoting world peace through sports - as an Official Worldwide Olympic Partner in the Video and Audio Equipment category for more than 20 years since The Olympic Partner (TOP) Program commenced for the Calgary Olympic Winter Games in 1988. Under the slogan "Sharing the Passion," Panasonic will contribute to the success of the Olympic Games through its technology. Panasonic recently renewed its partnership with the International Olympic Committee for a further eight years to 2016.</p>
