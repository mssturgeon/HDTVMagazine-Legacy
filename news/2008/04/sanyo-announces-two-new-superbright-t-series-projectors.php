<p>Offering a full 1400 x 1050 resolution and 10-Bit digital gamma correction, the PLC-ET30L makes it possible to project high-quality high definition images from virtually any location. At 4200 lumens this extremely bright projector is perfect for delivering a PC-based presentation with high quality graphics and images or displaying high-resolution video. The PLC-XT21/L is a value-priced, XGA (1024 X 768) resolution projector that is replacing the popular PLC-XT20.</p>

<p>"These projectors are capable of delivering extremely bright images in environments that require a certain degree of ambient light, such as conference rooms and educational facilities," said Mark Holt, Vice President and General Manager for SANYO's Presentation Technologies Division. "While both are considered high resolution projectors, the PLC-ET30L fills a specific niche as our only SXGA+ model in the 'T' Series line."</p>

<p>The projectors are easy to install using SANYO's exclusive Lens Center design that offers unlimited setup options to meet specific staging requirements with 360-degree position function. To further increase installation convenience, the Up/Down/Left/Right lens shift ensures flawless image projection even in challenging and unusual positions. The Whisper Quiet fan produces an amazing low noise level of only 35 dBA, which is a major advantage in small offices and classrooms.</p>

<p>Both are equipped with SANYO's exclusive PJ Network Interface for wired networking, a common feature among SANYO's extensive line of commercial projectors. The optional networking module (POA-PN03C) allows the monitoring of projector functions and operation from a remote location via a web browser.  This optional module (POA-PN03C) comes with a camera and the optional PJ Master Software (POA-PJM01) allow for control and administration of projectors via a network. Users can monitor the actual picture, check status and control projector functions via any web browser. A warning notification can be automatically sent to the registered user's email whenever the projector encounters warnings such as maintenance needs.</p>

<p>Each is outfitted with a sophisticated One-Way Flow System that effectively controls the airflow that cools the projector with a single intake and exhaust vent. A filter warning alerts users to clean clogged filters, ensuring maximum performance. For further maintenance the top plate can be flipped open to clean and replace the Prism Block system for proper maintenance of LCD panels to reduce artifacts in the projected images.</p>

