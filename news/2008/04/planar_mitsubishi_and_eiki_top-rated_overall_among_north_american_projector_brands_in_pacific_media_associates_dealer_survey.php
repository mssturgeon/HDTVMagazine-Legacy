<center><i>NEC tops in Quality/Reliability, Sanyo tops in Products, and Epson tops in After-Sale Support</i></center><br />
<br />

<p><B>Menlo Park, California, USA - April 22, 2008</B>. Planar, Mitsubishi, and Eiki earned the first three spots as the top front projector brands overall in the 12th annual survey of U.S. and Canadian projector dealers. Pacific Media Associates, the global market information experts on large-screen displays, conducted the survey at the end of 2007. The company's Annual Dealer Survey is the authoritative source of independent, unbiased ratings of large-screen displays manufacturers by dealers throughout North America.</p>

<p>"The market for front projectors was even more challenging during 2007 than in previous years. With all the competition, manufacturers have had to do more than just make good products. They had to provide outstanding sales, marketing, and technical support programs," said Michael Abramson, who directs Pacific Media's research on front projectors and was project manager for the Dealer Survey. "Many of the aspects dealers considered most important in the past continued to be significant in 2007, and will probably remain important going forward. The top three manufacturers had strong scores in many individual aspects, especially those considered most important by dealers. Mitsubishi has been among the top three brands for many years," added Abramson.</p>

<p>The survey ranks 25 aspects of marketing support, products, and after-sale support according to their importance to dealers. Dealers then rated their key suppliers on each of these aspects. Ratings were based on a scale of 1 (very poor) to 5 (very good). Manufacturers with high scores on the more important aspects posted higher overall composite scores than those who scored well on less-important aspects. The report includes numerical ratings for each manufacturer for each aspect. This data can help manufacturers learn whether efforts to improve certain aspects are yielding results, and to see where they lag behind their competitors.</p>

<p>For the 2007 Dealer Survey, PMA is giving awards to the three companies with the highest composite scores. These top-rated overall brands are:</p>

<p>* Planar</p>

<p>* Mitsubishi</p>

<p>* Eiki</p>

<p>In addition to these three awards, a special award is being given to the top-rated brand in Product Quality/Reliability, the most important of the 25 rated aspects, according to the dealers. This award goes to:</p>

<p>* NEC Display Solutions</p>

<p>Two more awards are being given to the companies with top ratings in the two most important groups of rated aspects:</p>

<p>* Products - Sanyo</p>

<p>* After Sale Support - Epson</p>

<p>The 2007 survey is the twelfth that Pacific Media has conducted. It covers a broad range of facts, figures, and opinions from 151 participating dealers, many of whom are among the largest dealers in North America.</p>

