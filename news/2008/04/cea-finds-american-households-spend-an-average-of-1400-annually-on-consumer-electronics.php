<p><B>ARLINGTON, Va.--(BUSINESS WIRE)</B>--The average U.S. household reports spending $1,405 on consumer electronics products in the past 12 months, $120 more than the year before, according to new research released today by the Consumer Electronics Association (CEA)&reg;. The 10th Annual Household CE Ownership and Market Potential Study shows that HDTVs will have the highest growth in household penetration rates this year.</p>

<p>"More than 50 percent of American homes already own a digital television and it looks like high definition, or HDTVs, have the potential to match that by the end of the year," said Chris Ely, CEA's senior analyst of market research. "With the transition to digital television coming on February 17, 2009, lower prices and an increased awareness of the benefits of high definition, many consumers are deciding to upgrade their televisions."</p>

<p>Cell phones, MP3 players, digital cameras and laptop computers are also helping drive growth in the industry. "Consumers are seeking portable consumer electronics products," Ely continued. "The ability to listen to music, check email and make calls while on the go is what consumers want."</p>

<p>Multi-functional devices are one reason why the average number of consumer electronics (CE) products is down slightly, from 25 products in 2007 to 24 in 2008. As devices combine functions, consumers are able to consolidate their products. "Consumers can now take pictures on their cell phones or watch DVDs using their portable GPS system," Ely explained. "Consumers also owned dual products for years, such as having a DVD player and a VCR. Now, consumers can transfer their content from one device to be used on another. Taking this into account, we estimate the number of CE products owned by each American household to be consistent with last year's number."</p>

<p>The demographics of a household also determine CE purchases. Households with three or more people report owning 32 devices compared to just 17 for smaller households. Men also tend to own more and spend more on CE products, on average, than women. The study shows the average man reports owning 25 CE devices and will spend over $1,000 on CE products in 2008 compared to the average women, who owns 21 devices and will spend $600. However, women are far less likely than men to consider CE products in the house "theirs personally." Women are also increasingly influencing their households' CE purchases. Roughly forty-five percent of all retail CE purchases in 2007 were made by women at the checkout counter. Consumers 45 years old and younger, those with children in the home and those with higher incomes tend to spend more on CE products than the average adult.</p>

<p>Despite uncertain economic times, the CE industry has held up well. With continued growth in several categories including flat-panel displays, PCs and video game systems, the industry is on pace to outperform last year's total of $161 billion in overall shipment revenues.</p>

