			<p class="prtitle">Onkyo Ratchets up Features on New TX-SR606 Receiver</p>

<p><B>UPPER SADDLE RIVER, NJ (4/21/08)</B> -- Onkyo has upgraded the features set of its most popular HDMI-1.3a-capable home theater receiver by adding 1080i video upscaling, two additional HDMI inputs to handle a total of four HDMI sources, Audyssey's new Dynamic EQ loudness compensation technology, and Onkyo's new Music Optimizer circuit. The new Onkyo TX-SR606 replaces the company's best selling TX-SR605.</p>

<p>The Onkyo TX-SR606 provides HDMI 1.3a inputs for up to four high-definition 1080p video sources, plus high definition surround sound processing all over a single HDMI connection. This version of HDMI has greater bandwidth for higher resolution, higher frame rates, and 36-Bit Deep Color. Onkyo's HDMI video upscaling technology converts standard definition signals to 1080i, and Faroudja DCDi Edge (Directional Correlational Deinterlacing) technology effectively eliminates video artifacts.</p>

<p>This receiver also has a powerful 90 watt-per-channel amplifier section, Remote Interactive control over HDMI (RIHD), Audyssey 2EQ automatic room correction, is Sirius Satellite Radio ready, and offers a full range of advance surround sound codecs, including Dolby TrueHD and DTS-HD Master Audio to provide lossless bit-by-bit audio identical to the master recordings.</p>

<p>"The TX-SR605 was the industry's first home theater receiver with HDMI 1.3a repeaters and a price tag in the $500 range," said Paul Wasek, Onkyo USA's marketing manager. "The marketplace welcomed it as an unbeatable value, and the new TX-SR606 builds on its success with two more HDMI inputs, and great new features such as 1080i video upscaling and Audyssey's new Dynamic EQ, which provides a greatly improved home theater surround sound experience at more normal moderate listening levels. It also has Onkyo's exclusive Music Optimizer for a solid improvement in the dynamics of the music when headphone-oriented sources like iPods are played over loudspeakers."</p>

<p>The Audyssey 2EQ automatic calibration employs an included calibration microphone to analyze the system's acoustical output at three unique positions in the listening area. The receiver sends test signals to each speaker in turn, then uses the inputs from the microphone to adjust channel level and time delay settings for each speaker. By taking readings in three different positions in the theater room, the receiver can be calibrated to the speakers and environment, delivering optimal response throughout the room rather than just at the 'sweet spot' directly in front of the screen.</p>

<p>This receiver is among the first products to employ Audyssey's Dynamic EQ algorithm, which adds moment-by-moment refinement to the receiver's frequency response and surround levels in order to compensate for volume-dependent deteriorations in the listening experience, particularly at low volume levels. When used in combination with the Audyssey 2EQ system, this feature tailors the receiver's output to correct for room acoustics, listening position, and playback-level distortions, delivering an overall experience that is a much closer match to what the audio production engineers originally intended.</p>

<p>The TX-SR606 also includes the company's new Music Optimizer software, which improves the quality of MP3 and AAC encoded audio source material. While these compressed audio formats sound quite acceptable over small headphones or PC speaker systems, when reproduced on a full-scale home theater system the loss of high-frequency information becomes much more apparent. The Music Optimizer employs sophisticated equalization and optimization algorithms to overcome these faults, and enhances the reproduction quality of digitally compressed music.</p>

<p>For sharp and accurate audio reproduction, the TX-SR606 employs 32-bit DSP processing and 192 kHz/24-bit digital-to-analog converters on all channels. Each includes 7.1-channel surround processing for Dolby Digital EX, Dolby ProLogic IIx, DTS-ES, DTS-96/24, and DTS Neo:6. The receivers also include a user-selectable eight-setting subwoofer crossover adjustment for ideal integration of any subwoofer/satellite speaker system.</p>

<p>The TX-SR606 also features Onkyo's Powered Zone 2 capability, which can be used to power stereo speakers in a second room while listening to 5.1-channel sound in the main zone thanks to a dedicated set of zone 2 L/R speaker terminals. The receiver is capable of processing separate multichannel and stereo sources simultaneously for the main and second zone, or processing a single source for both. There is also a zone 2 pre-out that can be used in conjunction with a dedicated zone amplifier or receiver. For those with main stereo LR loudspeakers that can be bi-amped, the back surround channels can also be reconfigured for this much more powerful operating mode.</p>

<p>The Onkyo TX-SR606's RIHD (Remote Interactive over HDMI) capability allows it to seamlessly integrate with other leading brand-name devices, including all Toshiba CE-Link equipment and selected Panasonic VIERA Link, Sharp, and Samsung products. The receiver is also compatible with Onkyo's RI (Remote Interactive) iPod dock/charger models.</p>

<p>The Onkyo TX-SR606 will be available in black or silver finish in April, and it will have a suggested retail price of $579.</p>

<p>Onkyo, which takes its name from the Japanese "On" meaning 'sound' and "Kyo" meaning 'harmony,' has been producing precision audio components for over a half-century. The company's philosophy is to deliver products that are superbly designed and built to a consistently outstanding standard of excellence. Today, Onkyo is at the forefront of the home theater and digital revolutions. For more information about this and other fine Onkyo products, visit www.onkyousa.com or call 800-229-1687.</p>
