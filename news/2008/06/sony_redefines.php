				<p class="prtitle">Sony Redefines LCD Picture Quality With New XBR HDTV Line</p>

<center><i>New Technologies Deliver Exceptional Color Reproduction and Black Levels</i></center><br />
<br />

<p><B>NEW YORK, June 5 /PRNewswire/ </B>-- Sony today introduced seven new BRAVIA(R) XBR flat-panel LCD high-definition televisions including models with TRILUMINOS(R) LED backlight and local dimming for outstanding black-level reproduction and unmatched contrast.</p>

<p>The new models expand the BRAVIA LCD line up to 30 models ranging in screen size from 19- to 70- inches measured diagonally.</p>

<p>The XBR models represent Sony's premium line, delivering the latest features and the pinnacle of picture quality.</p>

<p>"Critics consistently praise BRAVIA as the best HDTVs on the market, and the XBR badge indicates the best of the best," said Jeff Goldstein, vice president of marketing for Sony Electronics' television marketing group. "Consumers can now experience the quality of BRAVIA from small-sized models all the way up through our premium big screen XBR series."</p>

<p><br />
<B>XBR8-Series</B></p>

<p>Leading the line is the full HD 1080p 55-inch KDL-55XBR8 and 46-inch KDL-46XBR8 models (all measured diagonally). The models incorporate Sony's TRILUMINOS three-color LED backlight technology with local dimming coupled with 10-bit processing and 10-bit panel to deliver exceptionally deep black level and accurate colors.</p>

<p>Sony's TRILUMINOS LED backlight technology dramatically expands the TV's color range by aligning individual clusters of red, green and blue LEDs, significantly elevating color purity compared to traditional single white LED backlights.</p>

<p>Additionally, the sets offer the new Advanced Contrast Enhancer PRO (ACE PRO) technology. ACE PRO, which features Sony's own algorithm for local dimming, improves contrast and dynamic range by controlling the LED backlight level by area so that detail is maintained in the dark areas, while other areas are driven near peak brightness. The technology reduces unnecessary light emission resulting in true, deep blacks and reduced power consumption compared to conventional LED backlit models.</p>

<p>The models also feature BRAVIA Engine(TM) 2 PRO, which is Sony's latest high quality picture processing technology and the company's Motionflow 120Hz high frame rate technology.</p>

<p>Sony's Motionflow technology allows you to enjoy movies and prime-time TV (film-based content) with exceptional clarity and resolution in motion. The Motionflow algorithm identifies film content and removes "judder" resulting in a clearer picture with smoother motion during sweeping pans without a visible jerking or stuttering. Additionally, Motionflow 120Hz technology creates 60 unique frames between each of the existing 60 frames, doubling the frames displayed per second, further improving images for fast action sports and other programming.</p>

<p>Rounding out the picture enhancement suite in the XBR8 is x.v.Color compatibility. This technology expands the potential color data range of video by about 1.8 times, resulting in the display of more natural and vivid colors similar to what the human eye can actually see. This complements Sony's HD camcorder models and Blu-ray Disc players, which capture and display color range beyond what broadcasters currently deliver.</p>

<p>The models also feature Sony's Digital Media Extender (DMeX), providing the ability to seamlessly add new features. DMeX allows users to connect optional expansion modules such as the BRAVIA DVD Link, the BRAVIA Wireless link, the BRAVIA Input Link, which will ship later this year, and the currently available BRAVIA Internet Video Link.</p>

<p>The BRAVIA Internet Video Link module attaches to the back of a selection of the Sony's 2007 and 2008 BRAVIA LCD flat-panel television models. The service seamlessly streams on-demand entertainment including movies, TV programs, your favorite YouTube videos and a variety of other content not found on network or cable/satellite TV. The service connects to the Internet via your existing broadband Ethernet connection and streams content at no additional charge. Content is easily navigated with Sony's Technical Emmy(R) award-winning Xross Media Bar (XMB)(TM) user interface.</p>

<p>Rounding out the feature set is Digital Media Port (DMP) compatibility, which provides access to video and music from portable media devices like compatible Walkman(R) and iPod(R) players and other DMP accessories, which are sold separately. The models also can display digital photos using creative multi-plane 3D graphics slideshows from USB devices, as well as access photos from your PC in another room using Digital Living Network Alliance (DLNA) compliant devices via your home network.</p>

<p>Sony's new 3D Favorites Menu complement the XMB graphical user interface, which has been also been enhanced with Sony-unique integration of TV Guide providing easy access and navigation of content and menus through colorful thumbnails and logically placed icons.</p>

<p>Inputs found on the XBR8 models include four 1080/60 24p HDMI connections (HDCP), two 1080/60p HD component inputs, a 1080/60p-capable PC input, Ethernet (RJ-45) port and a RS-232C connection.</p>

<p><br />
<B>XBR7-Series</B></p>

<p>The full HD 1080p XBR7-series includes the 70-inch KDL-70XBR7 and 40-inch KDL-40XBR7 models. With WCG-CCFL backlight, 10-bit processing and 10-bit panel, and ACE (Advanced Contrast Enhancer circuitry), the models deliver outstanding picture quality and elegant style only BRAVIA can deliver.</p>

<p>The KDL-70XBR7 features BRAVIA ENGINE 2 Pro digital video processing, while the KDL-40XBR7 offers BRAVIA ENGINE 2 EX. The models both feature Sony's Motionflow 120Hz high frame rate technology and x.v.Color. Rounding out the feature set on these models is the new 3D Favorite Multi-plane graphics, XMB graphic interface with TV Guide, BRAVIA Sync, DMeX and DMP compatibility.</p>

<p>The XBR7 models also can display digital photos and play digital music from USB devices and photos from Digital Living Network Alliance (DLNA) compliant devices via your home network.</p>

<p>Inputs include four 1080/60 24p HDMI connections (HDCP), two 1080/60p component inputs, a 1080/60p PC input, Ethernet (RJ-45) port and a RS-232C connection.</p>

<p><br />
<B>XBR6-Series</B></p>

<p>Complementing the full HD 1080p 32-inch class (31.5 inch diagonal) KDL-32XBR6 and 37-inch KDL-37XBR6 models previously announced, the full HD 1080p 52-inch KDL-52XBR6, 46-inch KDL-46XBR6 and the 40-inch KDL-40XBR6 models were also introduced today (all screen sizes measured diagonally). The models offer a space-saving bottom speaker, floating-glass industrial design and all of the features found in the KDL-40XBR7 except the RS-232C connection and BRAVIA ENGINE 2 EX.</p>

<p>All of the new XBR series models also offer the option of additional speaker grille color accents including silver, red, brown and gold. The optional color grilles can be purchased separately. XBR8 and XBR7 models ship with a black grille cover and the XBR6 ships with a silver grille cover. Additional grille covers are sold separately.</p>

<p>All of the new BRAVIA models ship this fall and further details are available at http://www.sony.com/2008xbr. They will be offered at sonystyle.com and at Sony Style retail stores nationwide, as well as at authorized Sony dealers across the country.</p>

