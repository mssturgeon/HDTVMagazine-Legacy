<p><B>WASHINGTON, June 16 /PRNewswire-USNewswire/</B> -- On July Fourth, there's no place like our nation's capital for America's biggest birthday party. Featuring the most spectacular fireworks display anywhere in the nation, the 28th annual broadcast of A Capitol Fourth airs live in high definition and commercial free from the West Lawn of the U.S. Capitol. Hosted by Emmy and Golden Globe Award-winning actor Jimmy Smits, the star spangled party features special performances by Grammy Award-winning winning musicians Huey Lewis and the News, American Idol winner Taylor Hicks, Rock 'n' Roll Hall of Fame legend Jerry Lee Lewis, Tony Award-winning Broadway star Brian Stokes Mitchell, classical superstar Hayley Westenra and American soprano Harolyn Blackwell in performance with the National Symphony Orchestra under the direction of top pops conductor Erich Kunzel. New this year will be extended coverage of the most dazzling display of fireworks in the nation. The skyline of the nation's capital will come alive with vibrant and booming pyrotechnics, set against silhouettes of national landmarks the U.S. Capitol, the Washington Monument, the Lincoln and Jefferson Memorials. A Capitol Fourth will capture this stunning fireworks display from every vantage point with eighteen TV cameras stationed around the city -- including the U.S. Capitol, the White House, the Washington Monument and across the Potomac River. The multi-award winning event will be broadcast on PBS Friday, July 4, 2008 from 8:00 to 9:30 p.m. ET (check local listings), simulcast on National Public Radio and around the world to our troops on the American Forces Network. Capping off the show will be a rousing rendition of Tchaikovsky's "1812 Overture" complete with live cannon fire provided by the United States Army Presidential Salute Battery, an audience favorite and now A Capitol Fourth tradition.</p>

<p>"We heard from our viewers that they'd like to see more of the most amazing fireworks display in the nation. We are pleased to respond to our viewers' requests, not only with extended coverage of this year's fireworks, but we've also added more TV cameras that will capture these dazzling and colorful pyrotechnics in high definition from virtually every panorama. If you can't be in Washington, D.C. for our nation's birthday, watching A Capitol Fourth will truly be the next best thing to being there!" said executive producer Jerry Colbert of Capital Concerts.</p>

<p>In addition to the extended fireworks, A Capitol Fourth will include a special salute to the Olympic Games with figure skater and Gold medal winner Scott Hamilton. The musical tribute will include John William's "Olympic Fanfare" from the National Symphony Orchestra led by Erich Kunzel. Kunzel will also conduct the Cincinnati Pops at the Beijing Olympics this summer, the only American orchestra to perform in this year's Olympic games. The program will also feature performances by The Choral Arts Society of Washington, The U.S. Army Herald Trumpets, The U.S. Marine Drum and Bugle Corps, The U.S. Army Presidential Salute Battery, and an Armed Forces Color Guard provided by the Military District of Washington, D.C.</p>

<p>For A Capitol Fourth executive producer Jerry Colbert has assembled an award-winning production team that features the top Hollywood talent behind some of television's most prestigious entertainment awards shows. This includes Emmy award-winning producer Walter C. Miller, American's leading director and producer of live programs including the Grammy Awards and Country Music Awards; award-winning director Paul Miller whose credits include the Country Music Awards and Saturday Night Live; and veteran television writer Jon Macks, whose credits include the Tonight Show with Jay Leno, the Academy Awards and the Emmy Awards. The program is a co-production of Jerry Colbert of Capital Concerts and WETA, Washington, D.C.</p>

<p>For more than 25 years, Capital Concerts has produced the two major patriotic events at the U.S. Capitol. In 1981, Colbert presented the first PBS Fourth of July telecast with the National Symphony Orchestra and guest artists performing live from the West Lawn of the U.S. Capitol. In 1990, he introduced the National Memorial Day Concert. Since then, both holiday specials have been honored with over 55 awards including the New York Film Festival Award, the Telly Award, the Golden Cine Award, the Videographer Award, the National Education Association Award, the Aurora Award, the Christopher Award, the Communicator's Award, the AXIEM Award, the Omni Award and the Writer's Guild of America Award.</p>

<p>A Capitol Fourth 2008 is made possible by grants from The Boeing Company, the National Park Service, the Corporation for Public Broadcasting, the Department of the Army, the National Endowment for the Arts, PBS and public television stations nationwide. Air travel is provided by American Airlines.</p>

