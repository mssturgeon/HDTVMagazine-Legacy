<p>To facilitate the highest quality home theater experience and color reproduction, Samsung teamed up with Joe Kane Productions, a worldwide authority on visual imaging equipment and development. The result of this collaboration is a premium high-definition projector that reproduces astonishing flesh tones and natural colors. The SP800B allows users to freely select the color space for the three broadcasting formats (SMPTE-C, HDTV, and EBU) to deliver accurate projection regardless of format. In addition the projector has the capability of matching the gamma response curve of ultra-expensive studio video equipment.</p>

<p>"Basic technologies for HD projectors have drastically improved on superior performance capabilities and enhanced design functionality over the last several years. Samsung continues to maintain its performance standards within the marketplace by delivering the A800B," said Christopher Franey, VP Marketing and Commercial Sales, Samsung Electronics America, Information Technology Division. "The unique design and functionality of this high-end projector separate this from any in its class. By leveraging the experience of Joe Kane we deliver the ultimate cinematic visual experience with our high-class fully functional HD projector that displays clearer and crisper images."</p>

<p>The SP-A800B projector matches high-performance with high-design, incorporated in this highly functional design is the low-noise cooling system that supports and maintains quiet installations, making installations and placement practical without hindering the unit's functionality. The theater mode operates at just 25db enabling users to focus on the finest details without compromising excellence.</p>

<p>Like all Samsung projectors, the SP-A800B projector is backed by a two-year limited warranty on labor and parts as well as toll-free technical support for the life of the display.</p>

