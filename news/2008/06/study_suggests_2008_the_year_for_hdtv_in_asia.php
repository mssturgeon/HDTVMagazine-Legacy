<center><i>3/4 of Asian PayTV Operators surveyed expect HDTV offerings by end 2008</i></center><br />
<br />

<p><B>Kuala Lumpur and Paris, 17 June 2008</B> - MEASAT Satellite Systems Sdn. Bhd. ("MEASAT") and Euroconsult jointly announced today the results of a study into the development of High Definition Television ("HDTV") in the Asia-Pacific region. The study, which was conducted during May by Euroconsult, polled the rationale, benefits, challenges and expectations or HDTV amongst the regions' leading PayTV operators. 25 operators in 15 markets, collectively serving more than 24 million subscribers, were interviewed.</p>

<p>The study found that 75% of PayTV operators surveyed have, or were planning, to launch a High Definition Television ("HDTV") offering during 2008. It showed operators as generally bullish on the outlook for HDTV, with a majority expecting it to increase ARPU or profits on its own. HDTV, which most saw as "here to stay" and destined to become a "must have" offering, had been identified as a key strategic priority for their business. The study indicated that the rollout of HDTV is being spearheaded by newer PayTV platforms looking to differentiate their offerings from existing platforms. More established platforms were taking a slower approach to implementing HDTV.</p>

<p>Interviews conducted suggested that HDTV was seen as not particularly easy or difficult to introduce. The lack of substantial HDTV content - both local and international - was viewed consistently as the most important roadblock for developing the HDTV sector in the region.</p>

<p>"The results from this study are very interesting" said Paul Brown-Kenyon, Chief Operating Officer of MEASAT. "The insights will help us determine how best we can support our customers and partners in the development of this important segment."</p>

<p>"The study provides clear evidence of faster development of HD offerings in Asia than previously expected. Opportunity for growth and increasing competitive pressure are the primary factors driving pay-TV broadcasters to develop an HD offer" said Pacome Revillon, Managing Director of Euroconsult.</p>

