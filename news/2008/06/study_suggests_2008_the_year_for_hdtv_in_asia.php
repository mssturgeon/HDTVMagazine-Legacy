<p>MEASAT is a premium supplier of satellite communication services to Asia's leading broadcasters, DTH platforms and telecom operators. With the recent commissioning of AFRICASAT-1, the MEASAT fleet is able to provide satellite capacity over 145 countries representing 80% of the world's population across Asia Pacific, Middle East, Africa, Europe and Australia. The fleet will be further enhanced in 2008 with the launch of MEASAT-3a, providing additional capacity and in-orbit redundancy at the Company's key 91.5E orbital video slot.</p>

