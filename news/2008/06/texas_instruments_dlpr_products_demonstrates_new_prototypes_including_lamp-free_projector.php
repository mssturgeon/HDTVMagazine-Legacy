<B>About Texas Instruments</B></p>

<p>DLP Products DLP display technology from Texas Instruments offers clarity down to the most minute detail, delivering pictures rich with color, contrast and brightness to large-screen HDTVs and projectors for business, home, professional venue and digital cinema (DLP Cinema(R)). 50 of the world's top projection and display manufacturers design, manufacture and market products based on DLP technology. DLP is the only HDTV technology built from a foundation in the digital cinema where it set the industry standard demonstrated by the deployment of DLP Cinema technology in 6,000 theatres worldwide. At the heart of every DLP chip is an array of up to 2.2 million microscopic mirrors which switch incredibly fast to create a high resolution, highly reliable, full color image. DLP technology's chip architecture and inherent speed advantage provides razor-sharp images and excellent reproduction of fast motion video. Since early 1996, more than 16.5 million DLP subsystems have been shipped. For more information, please visit www.dlp.com.</p>

