<center><i>DLP unveils the world's first 3-D Front Projector and shows the first DLP Pico chipset product</i></center><br />
<br />

<p><B>LAS VEGAS, June 18 /PRNewswire/</B> -- Texas Instruments (TI) (NYSE:TXN) today at InfoComm DLP(R) Products introduced the industry's first home theater lamp-free projector that utilizes a PhlatLight(TM) LED light source and a BrilliantColor(TM) chipset. This technology demo delivers a superior 1080p picture for which DLP technology is known, while eliminating maintenance costs such as lamp replacements and filter changes required by some competing projector products. Multiple DLP customers have plans to develop DLP lamp- free LED-based projectors, including Optoma, with units expected to ship in late 2008. Similar to the deployment of DLP Product's now popular BrilliantColor technology, the solid-state, lamp-free innovation will first be incorporated into home theater units and proliferate through corporate and education product lines thereafter.</p>

<p>DLP also introduced the first 3-D front projector with Norwegian manufacturer, projectiondesign, and the brand new pico-projector stand-alone product with Optoma. The 3-D portable high-resolution active stereoscopic single-chip projector is designed for the demanding visualization, simulation and entertainment environments in applications that have not been able to achieve this level of performance in the past, while the pico product uses a pioneering DLP Pico(TM) chipset for mobile applications.</p>

<p><br />
<B>Benefits of Lamp-free</B></p>

<p>Due to the inherent switching speed of the DLP chip and advancements in LEDs from Luminus, a leader in LED manufacturing, consumers will benefit from the increased picture quality, reliability and value found in this new projector category. The reflective nature of the mirrors on the DLP chip allow more light to reach the screen resulting in a 50% increase in color gamut range producing more than 200 trillion colors and a contrast ratio in excess of 500,000:1. The proprietary combination of LED illumination, coupled with DLP technology elevates picture quality to a new level while eliminating the traditional projection lamp.</p>

<p>In addition to the expanded color and contrast performance, the illumination system has an incredibly long life and offers up to 30% lower power usage and, most significantly, hundreds of dollars in savings from lamp purchases.</p>

<p>Due to the sealed DLP optics, DLP projectors are inherently prepared to withstand dusty environments and unlike projectors based on other technologies; do not require a filter to protect the optics. Most DLP projectors are filter-free. This important value attribute will remain true with new lamp-free DLP projectors, eliminating potential costly filter cleaning and replacements required by other technologies.</p>

<p>DLP is leveraging strengths from its other leading product lines for the new lamp-free projectors. Since 2006, lamp-free DLP HDTVs with LED-based illumination systems have been available from Samsung. To date, nearly 150,000 of these units have shipped.</p>

<p>DLP Products is featuring other market leading innovations at InfoComm booth #C909, Central Hall, including</p>

<p>-- World's first DLP 3-D Front Projector Product</p>

<p>The F10 AS3D is designed for the demanding scientific visualisation, simulation and entertainment environments. A full 120 Hz refresh rate enables flicker-free 3-D image. The F10 AS3D features a resolution of 1,400 x 1,050 pixels, and it is fully compatible with 1080p inputs. It is also compatible with both IR transmitted and DLP(R) Link 3-D shutter glasses. The F10 AS3D can be found on the projectiondesign booth, N5541 at InfoComm.</p>

<p>-- World's first DLP Pico-Projector Product</p>

<p>Optoma has announced plans to build a miniature stand-alone projector using the DLP Pico(TM) chipset. Product is expected to be available in limited distribution in Europe and Asia in late 2008 with a worldwide launch planned for 2009. There will be a demo at the DLP booth of this hand-held projector displaying composite video from a mobile business device.</p>

<p>"DLP Products has a proven legacy of "firsts" in the market and the projectors being demonstrated this year are examples of that commitment to innovation and commitment to our customers," said Lars Yoder, vice president and business manager, TI's DLP Front Projection Business Unit. "DLP Products is proud to enable our customers, who are the leading projector manufacturers globally, to be the best."</p>

<p>For more information on DLP and DLP products please visit www.dlp.com or booth #C909, Central Hall at InfoComm.</p>

