<p>-- 1080p with 10,000:1 Contrast: Mitsubishi at InfoComm 08 will debut its new HC5500 3LCD projector, its latest 1920 x 1080 projector with automatic iris function for quicker black-to-light image shift and an incredible 10,000:1 contrast ratio. With an Emmy-award-winning HQV processor and 5000 hour lamp life, The HC5500 offers top-of-the-line functionality and image quality for an MSRP of $2495.</p>

<p>-- Ultra-Short Throw with Networking Capabilities: Sanyo at InfoComm is introducing the PLC-XL51 3LCD projector, an upgrade to the previous PLC-XL50 that offers the same unique short throw distance capable of projecting an 80- inch image from a distance of only 3-inches. The PLC-XL51 also includes added brightness at 2700 Lumens, a SD card slot for presentations without a PC, in addition to networking capabilities.</p>

<p>-- Something for Everyone: Sony will be showcasing its recently announced 3LCD projector line-up of incredible quality projectors, with MSRPs ranging from $900-$1400: two XGA (VPL-EX50 and VPL-EX5), SVGA (VPL-ES5) and WXGA (VPL- EW5). Features of this series include: short focal-length lens that allows large-screen projection from a very short distance, four-second power up and high level security to help prevent theft.</p>

<p>-- Budget-Friendly, Feature-Rich: Epson is also introducing a line-up of 3LCD multimedia projectors at sub-$800 pricing. The Epson PowerLite W6 projector ($799*), a WXGA resolution model delivering 2,000 Lumens of color and white output and offers HDMI connectivity for high-definition quality video. Epson will also debut the Epson PowerLite 78c ($649*) with 2,200 Lumens and XGA resolution, and the Epson PowerLite S6 ($549*) delivering 2,200 Lumens with SVGA resolution. All three models weigh and deliver 2000:1 contrast ratio to offer incredible image quality at competitive price points.</p>

