<p>-- Ultra-Bright, Ultra-Portable: Epson is unveiling its new line-up of ultra-bright, ultra-portable projectors for corporate and mobile presenters. The Epson PowerLite(R) 1720, 1725, 1730W, and 1735W deliver 3,000 lumens of color and white light output for bright, and vivid images in sleekly designed less than four pound projector. Epson PowerLite 1720 and 1725 ($1,299* and $1,499*, respectively) offer XGA resolution and PowerLite 1730W and 1735W projectors ($1,699* and $1,899*, respectively) weigh less than four-pounds and offer WXGA resolution and easy wireless connectivity.</p>

