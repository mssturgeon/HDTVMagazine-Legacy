<B>Blu-ray Content Opportunities</B></p>

<p>Consumers who purchased a BD set-top player cited "leading-edge technology" and a "superior viewing experience" as primary reasons for making the purchase. And they indicated a clear preference for BD content. In fact current BD set-top player owners expect that 80 percent of their upcoming purchases will be in BD rather than standard DVD. By comparison, 43 percent of PS3 owners use the BD capability in their consoles at least once a month; however, they do not view BD movies as often as set-top device owners do.</p>

<p>"The door is open for studios to feed the consumer's appetite for Blu-ray content, and we expect sales to increase, as prices for hardware and software moderate in the coming months," Crupnick said. "Even so it will take a concerted effort by manufacturers and retailers to ratchet awareness even further and convince all of those potential buyers of the superiority of Blu-ray Disc versus standard DVD."</p>

<p>Data note: Data was collected via online survey, which was fielded between March 10 and March 20, 2008. Final data for the nationally representative sample was weighted to represent the U.S. population of individuals age 18 and older.</p>

