<p><B>CHATSWORTH, CA and INFOCOMM, LAS VEGAS, NV. -- June 17, 2008</B> -- SANYO, one of the world's largest manufacturers of LCD and DLP projectors introduces their latest optical engine, called 4LCD, which adds a Color Control Device to conventional 3LCD (red/green/blue) systems. The first projector to launch this innovative new 4LCD engine is the PLC-XP200L. The additional Color Control Device in the 4LCD optical engine allows the PLC-XP200L to automatically control the amount of yellow light in the image, producing higher luminosity with improved color accuracy and clarity.</p>

<p>The demand for even brighter projectors continues to come from the field as systems integrators are asked to install video displays in extremely large venues such as convention halls, conference rooms, auditoriums and houses of worship. However, as brightness levels increase on 3LCD projectors, there is a reverse effect in color reproduction. Colors become noticeably washed out, lacking vibrancy and realism.</p>

<p>SANYO's innovative solution overcomes the limitations of 3LCD technology, opening the way for new projectors capable of extremely high luminosity without the trade off in color accuracy. The PLC-XP200L, the first projector to benefit from this new technology, is rated at an amazing 7000 lumens. Coupled with the impressive high contrast ratio of 2200:1, the PLC-XP200L is capable of generating clearer, richer and more beautiful images than was ever possible with high brightness 3LCD projectors.</p>

<p>SANYO developed a new high-speed image compensating LSI for the 4LCD engine. The combination of the 4LCD engine and the new LSI allows for up to 20% more color space than our conventional projectors. With the controlled yellow light, SANYO's Advanced Color Correction technology separates each color histogram for unparalleled color processing and correction, resulting in beautiful and naturally rich colors.</p>

<p>Additionally, the PLC-XP200L is equipped with a high-output, single lamp that is designed for exceptional light efficiency. Aside from generating sharper and brighter displays in large halls and meeting rooms, the 4LCD design is well suited for digital signage and advertising in brightly lit environments.</p>

<p>"This is just the first of many projectors we will release featuring our new 4LCD Engine. The increased luminosity and contrast ratio coupled with the dramatically improved color accuracy of this new design is going to revolutionize the capabilities of LCD projector solutions," says Mark Holt, Vice President and General Manager for SANYO's Presentation Technologies Division.</p>

<p>Minimal maintenance and repair was essential for the XP200L, so it was outfitted with SANYO's exclusive Active Maintenance Filter (AMF). AMF is a single filter cartridge that contains ten lengths of filtering material plus an airflow sensor to detect when airflow is obstructed by dust. The AMF system automatically advances a clean section of filter when needed. When the last section of filter material becomes obstructed an on-screen graphic appears telling the user to change the cartridge. Each filter lasts approximately 10,000 hours with a cartridge lifecycle of about 2 years (calculation based on 14 hrs/day projector use). The filters are easy to replace due to the side loading access on the projector. To further increase reliability and performance, the PLC-XP200L uses SANYO's unique Durable Inorganic Optical System (DIOS).</p>

<p>The SANYO PJ-NET ORGANIZER is available, allowing the PLC-XP200L to be connected to a wired network via Ethernet. Using the PJ-NET MASTER software all projector functions such as power status, lamp status, input mode, signal condition, lamp-use time, etc. can be monitored and controlled from a remote location.</p>

<p>For quick and easy installation the XP200L is outfitted with a motor driven vertical and horizontal lens shift. Up/Down/Left/Right lens shift ensures image projection at any angle of up to 360-degrees, allowing ceiling or floor image projection.</p>

<p>A special mechanical shutter is also placed behind the lens and activated by the remote control, allowing the presenter to close the lens and temporarily darken the screen.</p>

<p>There is an abundance of digital/analog video input terminals including a DVI-D (digital and analog video), component video and D-Sub15. The input signal compatibility includes UXGA, SXGA+, SXGA, WXGA, XGA, SVGA, VGA, and MAC. It is also compatible with HD resolutions including 1080i 50/60, 1035i, 720p as well as standard definition (480p, 480i, 575p, 575i).</p>

