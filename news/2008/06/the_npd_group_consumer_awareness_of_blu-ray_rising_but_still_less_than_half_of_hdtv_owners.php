			<p class="prtitle">The NPD Group: Consumer Awareness and Potential for Blu-ray Disc Devices Rising</p>

<center><i>Challenges Still Remain for Consumer Adoption of Next-Generation DVD Players and Content</i></center><br />
<br />

<p><B>PORT WASHINGTON, N.Y.--(BUSINESS WIRE)</B>--According to The NPD Group, a leading market research company, 45 percent of HDTV owners in the U.S. now claim to be familiar with Blu-ray Disc (BD), up from 35 percent in June 2007. And, while only 6 percent of all consumers surveyed said they plan to purchase a BD device, NPD found purchase intent to be higher among the growing population of HDTV owners, boding well for the future of the format.</p>

<p>NPD's "2008 Blu-ray Disc Report" reveals that 9 percent of HDTV owners plan to buy a BD-capable player in the next six months. "With HDTVs now in approximately 40 million US households, that percentage translates to a pool of almost 4 million potential BD player buyers," according to Russ Crupnick, entertainment industry analyst for NPD.</p>

<p>Nevertheless, manufacturers still face challenges. Although HD-DVD is no longer a competitive threat, many consumers are content with standard-definition DVD players and content. The leading reasons cited as barriers to purchase were a perceived high cost of BD players and a belief that standard-definition DVD is "good enough."</p>

<p><br />
<B>Blu-ray Content Opportunities</B></p>

<p>Consumers who purchased a BD set-top player cited "leading-edge technology" and a "superior viewing experience" as primary reasons for making the purchase. And they indicated a clear preference for BD content. In fact current BD set-top player owners expect that 80 percent of their upcoming purchases will be in BD rather than standard DVD. By comparison, 43 percent of PS3 owners use the BD capability in their consoles at least once a month; however, they do not view BD movies as often as set-top device owners do.</p>

<p>"The door is open for studios to feed the consumer's appetite for Blu-ray content, and we expect sales to increase, as prices for hardware and software moderate in the coming months," Crupnick said. "Even so it will take a concerted effort by manufacturers and retailers to ratchet awareness even further and convince all of those potential buyers of the superiority of Blu-ray Disc versus standard DVD."</p>

<p>Data note: Data was collected via online survey, which was fielded between March 10 and March 20, 2008. Final data for the nationally representative sample was weighted to represent the U.S. population of individuals age 18 and older.</p>

