<p>Taking advantage of HDMI&reg; 1.3a technology, Pioneer brings film aficionados to the frontier of next generation entertainment with the most cutting edge video processing available. Both players support 12-bit video digital-to-analog converter (DAC) providing exceptional analog video performance. 12-Bit Deep Color is implemented on both models to deliver an unprecedented range of hues and shades resulting in pristine, realistic imagery that was not possible with previous generations. For early technology adopters, both players are a great investment that will continually meet the advancements of HD home entertainment technology.</p>

<p>With Pioneer's 1080p / True 24 frames per second (fps) video output, the two models offer smooth performance of film based Blu-ray Disc movies that greatly reduce image judder. By preserving the feature film scene cadence in which Blu-ray Disc titles are authored and feature films are captured, viewers gain a natural, high quality movie viewing experience just as they would in the theater.</p>

<p>Pioneer has continued to enhance high performance DVD playback in the new players with the inclusion of the proprietary and advanced PureCinema Deinterlacer, which essentially eliminates lines that can negatively affect the viewing experience. DVDs can be scaled to a 1080p resolution for improved picture quality and compatibility with HDTVs.</p>

<p>Pioneer recognizes the vital importance that sound plays in creating an emotional home entertainment experience and for film aficionados who want to gain the full impact of high resolution movie soundtracks.</p>

<p>The new players are two of the industry's first to support all advanced audio formats, with the ability to decode Dolby&reg; TrueHD and Dolby Digital Plus, DTS&reg; HD* and DTS HD Master* high resolution audio formats, which also enables advanced connectivity that makes compatibility a minimal concern. Consumers will hear the subtle nuances and deep bass in their favorite films to bring an unprecedented listening experience that transcends what was previously thought possible in home theater.</p>

<p>Typically utilized by high end audio manufacturers and professional audio equipment, Pioneer selected the professional quality Wolfson Digital Audio Converters (DACs) in the new players to ensure the highest level audio performance that sound engineers intended audiences to experience.</p>

<p><br />
<B>Robust Build Quality</B></p>

<p>Pioneer's two BonusView Blu-ray Disc players feature a supreme build construction and attention to detail to ensure unrivaled content performance. The BDP-05FD and BDP-51FD define premium performance with high quality parts, a center loading tray which helps reduce vibration as well as dedicated audio and video boards for smooth operation and uninterrupted playback of discs.</p>

<p>The Elite BDP-05FD features gold-plated connection ports, capacitance touch key buttons and an aluminum front panel that will have audiophiles and videophiles eager to use and display within their high end home theater décor.</p>

<p><br />
<B>Pioneer Home Theater Synergy</B></p>

<p>Performing in concert with KURO displays and the upcoming Elite A/V receivers (SC-05 or SC-07), the new Blu-ray Disc players complete the home entertainment experience, allowing consumers to immerse themselves in stunning HD content.</p>

<p>Pioneer engineers developed unique performance settings in both players to ensure subtle details, vivid colors and deep shadows are accurately reproduced when shown on KURO displays. When selecting the "Pioneer PDP" in the video adjust mode, the new players will output the appropriate signal to a connected KURO and deliver the best possible image possible for viewers.</p>

<p>In line with the premium movie experience its products provide, Pioneer sought to create jitter-free playback and dynamic sound quality for music CDs. When connected to a new Elite receiver (SC-05 or SC-07) via HDMI, the BDP-05FD enhances CD playback with the proprietary Precision Quartz Lock System (PQLS). This advanced feature synchronizes music data coming from the Blu-ray Disc player to the receiver giving music fanatics a revolutionary high resolution listening experience far exceeding traditional methods.</p>

<p><br />
<B>Consumer Convenience</B></p>

<p>Due to the exclusive chip set design and build quality Pioneer is now utilizing, significant strides in speed performance have been made with the new players to now rival the rapid playback rate consumers have come to experience when using their DVD players. This platform greatly improves disc load, power on, power off and disc eject times.</p>

<p>With a continued focus on unifying the appearance and enhancing the operation of its home theater products, Pioneer has integrated the same graphic user interface found on its KURO displays and new Elite receivers. Through the player, users can customize their viewing experience via the A/V Selection menu, which provides a series of image modifications (LCD, PDP, Pioneer PDP, projector and professional) to optimize the picture displayed on a connected HDTV. Pioneer takes image quality a step further with the exclusive Picture Control Suite, which is comprised of an additional 13 video adjustments that allow viewers to fine tune small picture details of a film and deliver an experience that best suits a user's viewing preferences.</p>

