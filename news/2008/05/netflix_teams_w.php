<p class="prtitle">NETFLIX TEAMS WITH STREAMING MEDIA INNOVATOR ROKU ON PLAYER THAT INSTANTLY STREAMS MOVIES FROM NETFLIX DIRECTLY TO THE TV</p>

<center><i>Priced at Just $99.99 and Available Starting Today,
The Netflix Player by Roku&trade; is Compact,
Easy to Set Up and Intuitive to Use</i></center><br />
<br />

<p><B>LOS GATOS and SARATOGA, Calif., May 20, 2008 </B>- Netflix, Inc. (Nasdaq: NFLX), the world's largest online movie rental service, and Roku, Inc., an innovator in digital media streaming technology, today announced the introduction of The Netflix Player by Roku&trade;, a device that enables Netflix subscribers to instantly stream a growing library of movies and TV episodes from Netflix directly to the TV. Priced at just $99.99, the player is available for purchase starting today at www.roku.com/netflixplayer.</p>

<p>The player is simple to install, easy to use and gives Netflix members instant access to more than 10,000 movies and TV episodes.</p>

<p>"We're excited to bring the first Netflix ready device to the market, " said Anthony Wood, CEO and founder of Roku. "The seamless integration of the Netflix service into our player has resulted in true ease of use for the consumer. Now, streaming video isn't limited to people sitting in front of the PC; it's ready for the TV in the living room."</p>

<p>"The key breakthroughs of The Netflix Player by Roku are simplicity and cost," said Reed Hastings, chairman and CEO of Netflix. "First, it allows consumers to use the full power of the Netflix Web site to choose movies for their instant Queue, and then automatically displays only those choices on the TV screen. That's a major improvement versus the clutter of trying to choose from 10,000 films on the TV. Second, there are no extra charges and no viewing restrictions. For a one-time purchase of $99, Netflix members can watch as much as they want and as often as they want without paying more or impacting the number of DVDs they receive."</p>

<p><br />
<B>About The Netflix Player by Roku</B></p>

<p>The Netflix Player by Roku is surprisingly compact - roughly the size of a paperback book - and can integrate easily into any home entertainment system. All it takes is connecting the player to a TV and to the Internet. For homes with wireless Internet connectivity, the player is Wi-Fi enabled and offers the ultimate in placement flexibility.</p>

<p>From the Netflix Web site, members simply add movies and TV episodes to their individual instant Queues, and those choices are then displayed on the TV and available to watch instantly. With the player's accompanying remote control, members can browse and make selections right on the TV screen and also have the ability to read synopses and rate movies. In addition, they have the option of fast-forwarding and rewinding the video stream via the remote. In all, the Queue-based user interface creates a highly personalized experience that puts members in control.</p>

<p>Additional features of the product include optimization of the Netflix video streaming technology, which eliminates the need for a hard disk drive associated with video downloads, and built-in connectivity for automatic software upgrades, which will keep the device current with service enhancements.</p>

<p><br />
