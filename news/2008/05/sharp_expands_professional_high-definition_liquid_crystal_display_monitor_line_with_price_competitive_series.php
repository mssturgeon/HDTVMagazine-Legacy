<p> * The TL-M5200 is available now through Sharp authorized dealers and value-added resellers for a Manufacturer's Suggested List Price (MSLP) of $4,995</p>

<p> * The TL-M4600 will be available in June through Sharp authorized dealers and value-added resellers for a MSLP of $3,995</p>

