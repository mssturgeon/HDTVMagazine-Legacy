<p><B>MAWHAH, N.J.--(BUSINESS WIRE)</B>--Expanding its broad line of Professional Liquid Crystal Display (LCD) Monitors, Sharp today announces the new TL Professional LCD Monitor line, a full 1920 x 1080 two-megapixel high-definition (HD) resolution series. This series joins the high-end PN Monitor series, providing an affordable complement for display and presentation opportunities requiring accurate and precise image reproduction.</p>

<p>The new series, including the 52-inch class (52.03" diagonal) TL-M5200 and the 46-inch class (45.9" diagonal) TL-M4600, offers high image quality, features and performance at a very competitive price point. They are ideal for use in a wide range of settings including teleconferencing, CAD/simulation, digital signage, corporate, educational, training, hospitality, sports arenas, entertainment and house-of-worship.</p>

<p>"The large-format display market continues to evolve, with increased needs for advanced functionality and connectivity in a reasonably priced package," said Dan Wynne, senior director of marketing, Professional Display Division, Sharp Information and Imaging Company of America. "With the addition of this affordable monitor series, Sharp will reach a broader audience while offering superior image quality and improved compatibility, for reliability in a wider range of commercial applications."</p>

<p>The TL series features a new thin, lightweight cabinet design for easy installation as well as RJ-45 LAN Control for increased network connectivity. To ensure reliable operation and backlight life, Sharp has optimized the internal cooling with a unique fanless design and backlight system.</p>

<p><br />
<B>High Image Quality</B></p>

<p>The TL Monitor series has a full, two-megapixel 1920 x 1080 HD resolution for exceptionally accurate and precise image reproduction. Sharp's proprietary Advanced Super View (ASV) panel provides stellar picture quality for fast-moving video through its fast pixel response time of less than 6 ms, as well as high brightness and wide 176 degree viewing angles while maintaining exceptionally low power consumption. For a superior picture in practically any lighting condition, the monitors feature 1500:1 (TL-M4600) and 2000:1 (TL-M5200) contrast ratio, enabling viewers to discern details they might otherwise miss, particularly when viewing darker content. High image quality and color accuracy is ensured through Sharp's advanced signal processing technology, providing an unparalleled image for a professional presentation of information, data and images.</p>

<p><br />
<B>Enhanced Connectivity</B></p>

<p>The new TL monitor series has an array of input connectors to show all types of content, from DVD to varying PC resolutions from both analog and digital (DVI-D) sources for all types of presentations. The monitors include an HDCP compatible HDMI input for access to premium HD content, as well as a built-in Web browser. The monitors are designed for landscape mode use, and also offer an optional stereo speaker system, which attaches across the bottom of the display, for enhanced audio during presentations.</p>

<p>The new TL series complements the current "PN" series, which features Sharp's highest commercial design, with models available for both landscape and portrait modes. The PN series is recommended for extended-use 24/7 applications and is "trade compliant" (manufactured in Japan), and available on GSA (U.S. Government's General Services Administration) contract. The PN series comes with a 3-year on-site limited warranty covering parts, labor and backlight.</p>

<p>The TL-M4600 and TL-M5200 are supported with a 3-year on-site parts and labor limited warranty, including 3-year warranty on the backlight.</p>

<p><br />
