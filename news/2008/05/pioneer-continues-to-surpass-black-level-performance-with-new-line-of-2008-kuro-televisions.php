<B>Pioneer's Philosophy is Absolute Black</B></p>

<p>The philosophy behind Pioneer's Project KURO and the driving force is to achieve absolute, pure black. True, deep black creates a picture unlike any other that possesses finer detail, greater contrast, and more importantly, the ability to produce deeper colors not achievable before. This year, Pioneer pushes ever closer to their goal of absolute black by further reducing the idle luminance and improving black levels five times over the previous 2007 KURO models. This has enabled Pioneer to accurately reproduce deeper colors within the high-definition color spectrum and outdistance other display manufacturers.</p>

<p>Pioneer understands that color is a vital tool that creative professionals - from visual artists to film and television producers - use freely to evoke emotion and arouse our senses. With varying techniques from the most subtle to intense manipulation of color, artists can induce a very specific feeling within their audience. That feeling can be lost or diluted if a television cannot produce true, pure deep blacks and in turn reproduce an accurate color spectrum. The end result cannot be imitated and is beyond compare.</p>

<p><br />
<B>Evoking Emotion through Sound</B></p>

<p>Pioneer has incorporated six unique sound settings associated with each of the KURO video settings - standard, movie, sports, performance, game, dynamic - to ensure a customized listening experience that is specifically in tune with the type of programming on-screen.</p>

<p>The television employs an auto volume stabilization feature that further controls the television's volume level when switching between different types of programming; including network shows and commercials, broadcast channels or different input types to ensure each experience remains true and distinct from one another.</p>

<p>Pioneer has included the most advanced SRS&reg; WOW HD technology in the new KURO models by incorporating SRS Definition, a high frequency enhancement that provides finer control and adjustment to manage low, mid and high audio frequencies. The result adds to the virtual surround sound effect and produces clearer, more precise audio in mid to high frequency levels.</p>

<p><br />
<B>A Truly Intelligent Television</B></p>

<p>The KURO employs a unique automatic adjustment feature called Optimum Mode that simultaneously monitors video and room light conditions. The KURO then seamlessly adjusts the picture and sound settings by even the slightest variation to provide an experience specially tailored to each type of programming. The result is movies that reproduce a film-like quality, sports that feel like you're on the field and crisp clear narration from newscasts that focus on the reporter, not ambient background noise.</p>

<p>While many consumers will rely on this unique feature, the 2008 KURO models still have the ability to switch between six finely tuned pre-set modes including: standard, movie, sports, performance, game, dynamic for consumers who prefer the ability to manually adjust their KURO television according to their particular taste.</p>

