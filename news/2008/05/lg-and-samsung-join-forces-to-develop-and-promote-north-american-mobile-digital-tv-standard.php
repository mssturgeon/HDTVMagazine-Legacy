<p><B>Seoul, Korea, May 14, 2008</B> - LG Electronics (LG) and Samsung Electronics (Samsung), which together lead the global digital TV market, announced today that they will propose their jointly developed technology as the North American technology standard for mobile DTV.</p>

<p>Samsung and LG held a signing ceremony at Seoul Plaza Hotel in Seoul, Korea, on May 14, 2008. Executives from the two companies attended the event, including Woo Paik, LG's President and CTO, and JongWoo Park, President of Samsung Digital Media Business.</p>

<p>At the ceremony, the two companies agreed to cooperate in order to assure rapid adoption by the Advanced Television Systems Committee (ATSC) of a single common in-band mobile DTV standard.</p>

<p>Technology for the jointly proposed system will reflect the findings of the IDOV (Independent Demonstration of Viability) conducted by the Association of Maximum Service Television (MSTV) on behalf of the Open Mobile Video Coalition (OMVC). A report on IDOV will be submitted by the OMVC to the ATSC.</p>

<p>The jointly promoted mobile DTV solution uses the existing terrestrial digital TV broadcast bandwidth, with no impact on existing digital TV and with minimum broadcasting equipment investment.</p>

<p>"LG and Samsung are already world-class in digital TV and mobile communications, said LG President and Chief Technology Officer Woo Paik. "Through this collaboration, we also have an opportunity to lead the North American mobile DTV market."</p>

