<center><i>DMP-BD50 Continues Advancement of 1080p High Definition With Inclusion of BD-Live Function</i></center><br />
<br />

<p><B>SECAUCUS, NJ (May 6, 2008)</B> - Panasonic Corporation of North America, the principal U.S. subsidiary of Matsushita Electric Industrial Co., Ltd. (NYSE:MC), announces the introduction of the anticipated DMP-BD50, Panasonic's third generation Blu-ray disc player - the ultimate playback source for high definition 1080p content. Blu-ray media offers a wide range of functions that foster the transition to HD - including 1080p image quality, lossless Dolby&reg; TrueHD and DTS-HD Master Audio&trade; and versatile Picture-in-Picture applications. The BD50 adds the new BD-Live function, which uses the internet to further enhance the consumer's entertainment experience and employs VIERA Link,&trade; a technology that allows the consumer to operate VIERA Link equipped home theater components with a single remote. The DMP-BD50 will be available this spring and will have an SRP of $699.95.</p>

<p>BD-Live opens up a myriad of interactive possibilities for the consumer. In the future BD-Live will allow users to connect the DMP-BD50 to the internet to download such data as images and subtitles, and to join in multi-player interactive games that are linked to bonus movie content contained on Blu-ray discs.</p>

<p>For optimum image quality the DMP-BD50 features the PHL Reference Chroma processor and P4HD i/p conversion processor, which combine to create Uniphier&reg;, a precise digital video processor that produces sharp, crisp, natural colors that are extremely faithful to the original movie. Uniphier reflects the advance encoding and authoring technologies developed by Panasonic Hollywood Laboratory.</p>

<p>The true to the original source images are complimented by an exceptionally pure, accurate sound achieved through Audio Re-master and integrated decoders for the lossless Dolby True HD and DTS-HD Master Audio formats. Furthermore, the DMP-BD50 can be combined with a 7.1 channel amplifier and speakers for full 7.1 channel surround sound.</p>

<p>Networking is an essential product of the DMP-BD50. The included SD Memory Card slot allows for easy transferring of images from an HD camcorder or digital still camera via an SD Memory card. The consumer simply inserts the SD card into the BD50 and then can view the images on a large screen HD flat panel television with AVCHD format video images or JPEG stills in full 1920 x 1080 resolution. In addition the DMP-BD50 has been awarded the Energy Star certification.</p>

<p>"Panasonic was the first to bring a Blu-ray player with Bonus View (Final Standard Profile 1.1) to market and now with the DMP-BD50 we are again leading the industry with the inclusion of BD-Live," said Paul Sabo, Panasonic, National Marketing Manager Entertainment Group. "The beauty of the Blu-ray player is that we can now see movies the way the film maker intended, in glorious HD video and audio. The consumer can now combine the new generation DMP-BD50 with a VIERA flat screen televison to create a true living in high definition experience."</p>

