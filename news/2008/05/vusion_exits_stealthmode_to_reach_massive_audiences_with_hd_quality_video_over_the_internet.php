<p><B>SAN JOSE, Calif., May 5 /PRNewswire/</B> -- Vusion, Inc., providers of instant-on, full-screen, HD quality streaming video, today announced its formal company launch, leaving behind its stealth-mode name of 'Jittr Networks'. Vusion will deliver the industry's first end-to-end online video distribution service capable of providing the scalability and reach to serve true HD and DVD quality video to 95 percent of all broadband consumers.</p>

<p>The high bandwidth fees and limited reach of current content delivery technologies has made streaming video a loss leader for even the most highly trafficked web properties. Vusion's technology has been designed to answer the great demand among media companies and content providers for an end-to-end service to efficiently monetize assets through the delivery of high-quality video over the standard Internet.</p>

