<center><i>Advanced Television Systems Committee Celebrates 25 Years; Michael Dolan Receives 2008 Bernard Lechner Outstanding Contributor Award</i></center><br />
<br />

<p><B>WASHINGTON, May 8 /PRNewswire/</B> -- Paving the way for next-generation digital television (DTV) standards, the Advanced Television Systems Committee, Inc. celebrated its 25th Anniversary at the 2008 ATSC Annual Meeting today.</p>

<p>The Honorable Richard E. Wiley, former chairman of the Federal Communications Commission (FCC) and of the FCC's Advisory Committee on Advanced Television Service, was the keynote speaker at the event held at the Pentagon City Ritz-Carlton in Arlington, Va. Wiley, recognized as the "Father of HDTV," highlighted the amazing journey by literally thousands of industry participants in the ATSC's quarter-century of technology and marketplace leadership.</p>

<p>Past ATSC Executive Directors Dr. Richard Green, now President and CEO of CableLabs, and Dr. Robert Hopkins spoke to the audience using the organization's favorite medium, HDTV. Hopkins thanked the founders of HDTV for their vision, and Green commended the work of ATSC, emphasizing that "the best is yet to come." Setting the stage for the ATSC celebration was a 20-minute high-definition newscast, developed with the support of Gannett Broadcasting's WUSA-DT, and its anchor-reporter Mike Walter, a documentary newsreel featuring interviews with government leaders and industry luminaries discussing the past, present and future of ATSC DTV in the United States and around the world.</p>

<p>Featured speakers included David Donovan, President of the Association for Maximum Service Television (MSTV), who underscored broadcasters' key role in the nation's transition to DTV, and Brandon Burgess, President and CEO of ION Media Networks and Chairman of the Open Mobile Video Coalition (OMVC). Burgess discussed efforts to support ATSC's development of the DTV broadcast standard for mobile and handheld service (ATSC-M/H).</p>

<p>Also in the spotlight was the special luncheon guest speaker, Paula A. Kerger, President and Chief Executive Officer of the Public Broadcasting Service (PBS). Kerger told the audience, "We are taking a strong interest in two ATSC projects -- the work you're doing in mobile and handheld and non-real-time platforms. The M/H and NRT standards will allow PBS stations to provide innovative content to viewers when and where they want it. This ability is crucial to the future of broadcast television. We must go where our viewers go."</p>

<p>Speaking to the attendees in HDTV, Bill Jasper, President and CEO of Dolby Laboratories and John Eck, President NBC TV Network and Media Works praised the ATSC for its accomplishments and the importance of its ongoing work.</p>

<p>Distinctive honors were bestowed during the annual awards luncheon. Plaques were presented to the 16 organizations that have been 25-year participating members: ABC, CBS, CEA, IEEE, MSTV, NAB, NBC, NCTA, Panasonic, Philips, Sarnoff, SMPTE, Sony, Tektronix, Thomson and Zenith. Joseph Flaherty, Senior Vice President of Technology for CBS, was recognized for his 25 years on the ATSC Executive Committee and Board of Directors. William Miller of ABC was honored for his three years of service as chairman of the ATSC Technology and Standards Group.</p>

<p>A highlight of the luncheon awards ceremony was presentation of this year's Bernard Lechner Outstanding Contributor Award to Michael Dolan. Founder and President of Television Broadcast Technology, Dolan was recognized for his long service to ATSC and his commitment to the development of high quality technical documents. "He gives standards development and documentation the attention and care that it requires," said ATSC President Mark Richer. "Mike has consistently demonstrated that he cares deeply about helping to optimize our standards development process." Among other things, Dolan was a key contributor to the development to the ATSC's Data Broadcasting suite of standards, including A/90; and he co-authored the book Understanding the ATSC Data Broadcasting Standard (McGraw-Hill, 2001).</p>

<p>Morning and afternoon panels featured industry experts on a range of topics of keen interest to digital television stakeholders -- lively discussions commemorating the ATSC's Silver Anniversary, the organization's groundbreaking work over the years, and the ongoing activities focused on the future of DTV.</p>

<p>Peter Fannon, Panasonic Vice President and former head of the Advanced Television Test Center, chaired the panel, "HDTV, We've Come a Long Way," addressing HDTV's major progress since the 1980s, while CBS Vice President John Orlando chaired the "February 17, 2009 Perspectives" panel, discussing the final phase of the Nation's DTV transition.</p>

<p>NBC Universal Vice President and ATSC Chairman Glenn Reitmeier chaired the panel entitled, "ATSC Strategic Plan: Where are We?" looking at the exciting work under way on next-generation standards, including broadcasting to mobile and handheld receivers, file-based content delivery for on-demand consumer viewing and new capabilities for the next generation of large screen HDTV receivers.</p>

<p>"Twenty-five years after our first meeting, we are leading the effort to develop standards essential to the future of broadcasting," said Richer. "We are focused on the development of standards that will enable mobile and handheld service (ATSC-M/H), non-real-time program delivery (ATSC-NRT) and the next generation of services for fixed receivers (ATSC 2.0)."</p>

<p>Under the banner "ATSC at 25: The Digital Foundation for Broadcasting's Future," a fascinating display of historical artifacts included the original prototype Digital HDTV Grand Alliance modulator and demodulator equipment racks on loan from the Smithsonian Institution. The exhibit also showcased early HDTV receivers from ATSC member companies as well as photos and mementos from the Grand Alliance and others.</p>

<p>"This year's Annual Meeting included a fond look back at our accomplishments in the creation of digital television broadcasting and HDTV balanced with the enthusiasm for our ongoing work to enable exciting new digital television possibilities for broadcasters, receiver manufacturers and consumers" said ATSC Board of Directors Chair Glenn Reitmeier of NBC Universal.</p>

<p>Top supporters of the celebration were Silver Sponsors LG Electronics and Zenith, and Bronze Sponsors IEEE Broadcast Technology Society, Neural Audio, Samsung and VoiceAge. Other sponsors included CBS, Cox Television, Dolby, Gannett, Harris, the OMVC, Panasonic, PBS, Sony, TANDBERG Television and WUSA-9. High-definition displays were provided by ATSC members LG Electronics, Panasonic, Samsung and Sony.</p>

<p>The Advanced Television Systems Committee is an international, non-profit organization developing voluntary standards for digital television. The ATSC member organizations represent the broadcast, broadcast equipment, motion picture, consumer electronics, computer, cable, satellite, and semiconductor industries. ATSC creates and fosters implementation of voluntary Standards and Recommended Practices to advance terrestrial digital television broadcasting, and to facilitate interoperability with other media.</p>

<p>ATSC-M/H is being developed to support a variety of services including free (advertiser-supported) television and interactive services delivered in real-time, subscription-based TV, and Non-real-time content download for playback at a later time. The standard may also be used for transmission of new data broadcasting services such as real-time navigation data for in-vehicle use.</p>

<p>ATSC-NRT addresses the new reality that consumers are increasingly in control and want information and entertainment content, when and where they want it. By leveraging the low cost of storage in receivers, broadcasters utilizing the ATSC-NRT Standard will be able download content to a new generation of products.</p>

<p>ATSC-2.0 will define a complete suite of "Next Generation" services for the conventional fixed DTV receiver viewing environment.</p>
