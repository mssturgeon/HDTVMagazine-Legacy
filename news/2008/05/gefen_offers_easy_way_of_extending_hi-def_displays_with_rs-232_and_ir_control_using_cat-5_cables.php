<p><B>CHATSWORTH, CA</B> - When high definition video displays, touch screens and computer monitors need to be extended away from their source or mounted in a remote location, Gefen's HDMI RS-232 CAT-5 Extender enables a simple method of signal delivery. With RS-232 and an IR back channel delivered alongside HDMI, users can adjust their displays, change settings and access audio/video sources from up to 50 meters (150-feet) in distance. Long-distance source control through the display is ideal for digital signage installations where A/V equipment is located in rack-mounted spaces away from the viewing area.</p>

<p>Sender and receiver units connect the A/V source to the remote display using category-5 cables that transmit 1080p full HD resolutions as well as RS-232, IR back channel and HDCP-compliance. Up to 100 meters (330-feet) can support hi-def resolutions to 1080i.</p>

<p>"Entertainment venues, retail spaces and presentation rooms using HDMI sources and displays can use this product to deliver a hi-def source or computer to any location with real-time RS-232 control," said Hagai Gefen, president and CEO, Gefen Inc.</p>

<p>The Gefen HDMI RS-232 CAT-5 Extender (MSRP $599) is engineered to deliver flawless HDTV signals over CAT-5 cables by compensating for possible cable skews, ensuring hi-def video is delivered with zero signal loss.</p>

<p>Installation of the system is simple, requiring a local connection of the A/V and RS-232 equipment to the sender, and the display to the receiver. Source connection cables are included in the package.</p>

