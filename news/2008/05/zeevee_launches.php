				<p class="prtitle">ZeeVee Launches ZvBox, New Consumer Electronics Product for Broadcasting Any Internet TV or Computer Content to All HDTVs in Your Home</p>

<center><i>Available for preorder online at Amazon.com, ZvBox's pioneering ZvCast technology defines new 'localcasting' product category</i></center><br />
<br />

<p><B>LITTLETON, Mass., May 1 /PRNewswire/</B> -- Startup company ZeeVee Inc. announced today the launch of ZvBox(TM), a new consumer electronics product for watching any Internet TV, online video, or computer content on HDTVs at home. Available for preorder online <a href="http://www.hdtvmagazine.com/cgi-bin/ntlinktrack.cgi?http://www.amazon.com/gp/product/B0018L7NUA?tag=hdtvmagazine-20">exclusively at Amazon.com</a>, ZvBox will redefine television as we know it.</p>

<p>Until today, the explosion of Internet TV and movie downloads has been confined to the computer's small screen. Alternative solutions have failed to solve this problem, with drawbacks including limited content, added subscription fees, the need for a box at each TV, and the inability to show everything a computer can do with high-quality video and audio. ZeeVee's new ZvBox is the first device that allows consumers to watch anything they can get online or on their computers on all the HDTVs in their homes. ZvBox achieves this by simply connecting to the monitor output of the computer and turning it into a new high-definition (HD) TV channel called Zv, which is then broadcast across the existing cable wiring to all HDTVs in the home. As a result, ZvBox frees TV watchers from restrictive set-top boxes, rigid network schedules, and the strain of hunching over laptops to view online video.</p>

<p>ZvBox represents a new product category for consumer electronics called "localcasting," a breakthrough method for broadcasting anything a computer can do using the home's existing cable wiring and the TV tuners already embedded in HDTVs. As demonstrated by ZeeVee's own ZvCast(TM) technology upon which ZvBox is built, localcasting has several benefits which surpass alternative methods for watching Internet video on TV:</p>

<p> -- Lets you watch anything available online or on your computer, with no new subscription fees<br />
 -- Broadcasts the same great HD resolution that is displayed by your computer<br />
 -- Uses your existing cable wiring to reach all the HDTVs in your house with just one box<br />
 -- Eliminates the need for a receiving device near your HDTV<br />
 -- Experiences no wireless interference or performance problems<br />
 -- Allows you to start watching Zv in one room and finish in another</p>

<p>The best benefit of all is that ZvBox requires no change in consumer behavior. Because ZvBox localcasts its signal to an open TV channel, you only need to turn to that channel to watch Zv -- just like any other TV channel. And since ZvCast delivers such a crisp screen resolution, any computer application is accessible from the HDTV, including email, web browsing, photos, music, home movies, and of course the computer's own DVD player.</p>

<p>"ZvBox closes the huge gap that has existed between HDTVs, which have the best viewing experience, and the computer, which provides virtually unlimited content options and many applications already in use by consumers," said ZeeVee Co-founder and CEO Vic Odryna. "Instead of the walled garden world of set-top box solutions, ZvBox opens up the entire universe of Internet video and computer applications, where innovation usually happens first. And since ZvBox provides a duplication of what you see on your monitor, anything you can do on your computer you can now do on your HDTVs."</p>

<p>To enhance the Zv viewing experience, ZeeVee has also pioneered a new remote control, called ZvRemote(TM). ZvRemote controls your media playback and has an integrated touchpad which controls the computer's mouse and desktop interface from across the house - up to 150 feet away. The ZvKeyboard(TM) makes it even easier to compose email, surf the web, and type text for desktop applications. ZeeVee also provides a "widescreen guide" called Zviewer(TM) that is optimized for a 10-foot viewing experience on an HDTV.</p>

<p>According to Dallas-based research firm Parks Associates, premium online video streams and downloads (TV shows and movies) will grow from one billion in 2008 to more than 18 billion by year-end 2012. "Why should Internet video be exiled to the PC?" said Kurt Scherf, vice president and principal analyst at Parks Associates. "The Internet hosts an increasing treasure trove of high- quality video content, but it's been a difficult road for vendors to come up with a seamless solution that does not add clutter or complexity and does not limit the menu of content available. ZvBox solves a big problem for consumers eager to watch online shows from sites like Hulu and Joost. ZeeVee's straightforward approach eliminates thorny technical issues like competing encoding formats, APIs, and video player support."</p>

<p>ZeeVee Inc. is a startup funded by venture capital firms Alpond Capital and JLL Ventures.</p>

<p><br />
<B>Pricing and Availability</B></p>

<p>The ZvBox is being offered as a bundle including the ZvRemote and Zviewer and is now available for preorder <a href="http://www.hdtvmagazine.com/cgi-bin/ntlinktrack.cgi?http://www.amazon.com/gp/product/B0018L7NUA?tag=hdtvmagazine-20">exclusively at Amazon.com's Electronics store</a> for $499. ZvBox will be shipped to customers on June 30, 2008, its scheduled release date. "Our customers have come to expect breakthrough products to be available at Amazon.com first, and we're excited that ZvBox is available for preorder online exclusively at Amazon.com," said Paul Ryder, vice president of consumer electronics at Amazon. "ZvBox aims to fill a clear need for a simplified and flexible way to enjoy Internet content on HDTVs throughout the home. It's a fresh approach and a full solution for enjoying media and entertainment in new ways."</p>

<p><br />
<B>About ZeeVee</B></p>

<p>ZeeVee Inc., the creators of ZvCast(TM) technology for localcasting anything a computer can do to all the HDTVs in the home, is helping to redefine television as we know it. The company's ZvBox(TM) is liberating captive TV viewers from hardware, content and scheduling restraints, and opening the HDTV to the universe of Internet and computer video and applications. Through the creation of a new high-definition channel called "Zv," localcasted from ZvBox across the home's existing cable wiring, ZeeVee's technology allows for a more content-rich, interactive, and enjoyable entertainment experience -- all from the comfort of the couch. For more information, visit http://www.zeevee.com/.</p>

