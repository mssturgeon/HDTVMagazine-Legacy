				<p class="prtitle">Blu-ray Wins the Format Battle, but Consumers Don't Buy it</p>

<center><i>Few U.S. Adults are Likely to Purchase a Blu-ray Player within the Next Year</i></center><br />
<br />

<p><B>ROCHESTER, N.Y.--(BUSINESS WIRE)</B>--While many people expected sales of Blu-ray disc players to spike when Toshiba decided to drop out of the high-definition HD DVD market in February 2008, according to a new Harris Poll, it seems that the recently resolved high definition format war is not motivating consumers to purchase the advanced DVD players any time soon. The Harris Poll&reg; of 2,529 U.S. adults surveyed online between April 7 and 15, 2008 by Harris Interactive&reg; found that:</p>

<ul><li>Ownership of standard DVD players is practically ubiquitous (87%);</li><li>Few report owning Blu-ray disc players (4%), Sony PlayStation 3 (5%), HD DVD players (6%) and the HD-DVD drive for the Xbox 360 (1% have external drive while 9% have an Xbox 360);</li><li>Only nine percent of non-Blu-ray player owners report being likely to purchase a Blu-ray disc player within the next year, even when made fully aware that Blu-ray is considered to be the definitive technology for high definition DVD players going forward;</li><li>Two-thirds of consumers are familiar with the recently resolved high-definition format war (67%) and seven in ten of them have heard that Blu-ray is the unofficial winner (69%);</li><li>Nearly a quarter (23%) of those aware of the format war report that they had been waiting for the rivalry to play itself out before purchasing a high definition player, but by April they had yet to do so;</li><li>Although one-third of consumers report owning a high definition television set (HDTV; 35%), with incidence higher among males (41%) versus females (28%) and rising decidedly with household income (15% for those with less than $35K vs. 53% among those with $75K+), the percentage of HDTV owners likely to purchase a Blu-ray disc player is only 14 percent;</li><li>Current ownership of Blu-ray disc players among HDTV owners stands at 10 percent.</li></ul>

<p>According to Joan Barten Kline, Vice President of the Harris Interactive Media & Entertainment Practice, "Since Blu-ray disc player pricing averages more than $300, which is well above the cost for the latest generation of standard DVD players with up-converters, Blu-ray disc players may be encountering price sensitivity despite the advanced technology."</p>

<p><br />
<B>Internet Connectivity</B></p>

<p>Interest in a Blu-ray disc player with Internet connectivity expected to be out in the Fall in a higher price range is also lacking:</p>

<ul><li>U.S. adults are more likely to purchase a Sony PlayStation 3 that plays Blu-ray discs and has Internet access for $399 (11%) or an original Blu-ray disc player without connectivity for the same price (10%) versus a new Blu-ray disc player with Internet for $500-$650 (4%);</li><li>Not surprisingly, the under 40 crowd is most likely to opt for the PlayStation 3 as their Blu-ray capable device of choice - fully 23 percent of those in the 30-39 age group are likely to purchase this device in the next year (compared to 14% likely to buy an original Blu-ray disc player or the new Blu-ray disc player with Internet connectivity 5%)).</li></ul>

<p><br />
<B>What Will Become of the HD-DVD Player?</B></p>

<ul><li>Like the BetaMax loyalists of yore, almost half (45%) of those who currently own an HD DVD player say that they will just continue to use it and continue purchasing HD DVD's as long as they are available;</li><li>Another 14 percent of those who currently own an HD DVD player will continue to use it with the HD DVD's they have already purchased, but do not plan on buying any new ones;</li><li>An equal proportion of HD DVD player owners (15%) will continue to use it but also plan to invest in a Blu-ray disc player in the future.</li></ul>

<p><br />
<B>Methodology</B></p>

<p>The Harris Poll&reg; was conducted online within the United States between April 7 and 15, 2008, among 2,529 adults (aged 18 and over). Figures for age, sex, race, education, region and household income were weighted where necessary to bring them into line with their actual proportions in the population. Propensity score weighting was also used to adjust for respondents' propensity to be online. Because the sample is based on those who agreed to participate in the Harris Interactive panel, no estimates of theoretical sampling error can be calculated. A full methodology and data tables are available at www.harrisinteractive.com.</p>

