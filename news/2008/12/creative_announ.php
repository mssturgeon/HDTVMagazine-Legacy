				<p class="prtitle">Creative Announces Availability of the Vado HD Pocket Video Cam - See it, Shoot it in HD, Share it, Save it for a Lifetime, Watch it in True HD Quality on your HDTV</p>

<center><i>Output Your HD Video to Your HDTV in 1080i Resolution with HDMI Connection</i></center><br />
<br />

<p><B>MILPITAS, Calif., Dec. 8 /PRNewswire/</B> -- Creative(R) today announced availability of the Vado(TM) HD Pocket Video Cam, the ideal holiday gift. The thin, lightweight Vado HD is small enough to fit easily in a pocket, purse or the palm of your hand, and it captures video in 720p high-definition quality with just the touch of a button.</p>

<p>The Vado HD is the only Pocket Video Cam to feature HDMI connectivity and an included HDMI cable that provides 1080i output to an HDTV. It also features a precision glass lens for stunning video quality, and 8GB of built-in memory to carry up to two hours of HD video. The Vado HD has an estimated street price of US $229.99 and is available today in carbon black at Amazon.com and Creative.com.</p>

<p>"We designed the Vado HD so you can easily shoot all of life's spontaneous and fun moments, and then come home and watch your videos on an HDTV - all with true high-definition quality," said Steve Erickson, VP and GM for audio and video at Creative. "You can upload the videos to your PC, or what's really cool is to watch them on your HDTV in full HD quality. Some cameras such as the Flip Mino HD record HD video but don't let you output it in high definition to your HDTV. Even the New York Times laments, 'the Mino HD is a hi-def camcorder that can't play your movies in high def on a high-def TV.' The Vado HD delivers 1080i high-definition video to an HDTV, plus it offers the convenience of an HDMI connection."</p>

<p>The simplicity of the Vado HD makes it ideal for capturing video on a moment's notice. While your camcorder is stored away somewhere in a camera bag, the Vado HD is ready in seconds to capture clips that you can cherish and save for a lifetime in HD quality. With 8GB of built-in memory, the Vado HD can carry up to two hours of HD video, and it doesn't require you to carry tapes or DVDs with you. The removable, rechargeable battery provides up to two hours of recording and playback, and extra batteries are available as accessories so you can easily swap them to capture more video.</p>

<p>The Vado HD enables fast and easy sharing of video on YouTube(TM) and Box.net(TM). The Vado HD has a built-in USB connector so you can plug right it into your PC, just like you would with a thumb drive. The Vado HD includes the Vado Central(TM) software program built right into it that shows thumbnails of your video clips, which you can view on or copy to your PC. With one easy step, just click on the YouTube or Box.net buttons in Vado Central to easily post your videos. When you want to share your videos with selected friends and family, they can use Box.net to either view or download a copy of the video. Vado Central also enables capture of single snapshots or successive snapshots in burst mode. When you want to make and edit your video productions, just use the Muvee software that's included in Vado Central.</p>

