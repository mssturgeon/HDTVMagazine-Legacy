<p>For users in North America, Sony Computer Entertainment America (SCEA) will launch game themed high-definition virtual environments including the Uncharted: Drake's Fortune(TM) and Far Cry 2 spaces and the soon to be released Warhawk(TM), Resistance, Guitar Hero(R) and SOCOM spaces. In these environments, users will discuss specific games, plan strategies and access content and clues that will enhance their gaming experience. Through these virtual environments, publishers will be able to increase and extend consumer interest in their game titles via new mediums of game play. SCEA is partnering with Activision, Disney Eidos, Electronic Arts, Lucas Arts, THQ and UBISOFT, to develop virtual environments among other content for PlayStation Home.</p>

<p>"PlayStation Home is a social gaming service unlike anything else on the market and we are excited to be partnering with gaming and non-gaming partners to develop content that connects and entertains today's PS3 users like never before," said Susan Panico, Senior Director of PlayStation Network, SCEA. "PlayStation Home is a tremendous addition to the growing suite of entertainment services available only through PlayStation Network."</p>

<p>SCEA is announcing partnerships with some of the world's most respected lifestyle brands during open beta including Ligne Roset, a contemporary furniture designer, and Diesel, an international fashion design company. These partnerships will allow users to purchase customizable furniture for their personal apartments and designer clothes for their avatars, respectively.</p>

<p>A variety of studio partners including Sony Pictures Home Entertainment and Paramount Pictures will bring the PlayStation(R) community original intellectual property through dedicated spaces, sponsorship of in-world events, virtual items and exclusive media viewings in the PlayStation Home Theater. Sony Pictures Home Entertainment will use PlayStation Home to promote its latest films, offering exclusive video content, interviews and appearances from film talent. Paramount Digital Entertainment will bring to PlayStation Home virtual goods and video content based on its most relevant and popular franchises.</p>

<p>As the very first consumer brand space, Red Bull has created the Red Bull Island featuring an airplane racing game modeled after the Red Bull Air Race World Championship. The space is designed to facilitate interaction among the PlayStation community, creating opportunities to interact and take part in various Red Bull events and experiences. Expansion and completion of the island will follow in early 2009.</p>

<p>PlayStation Home is exclusive to PS3, free to download and easy to join. It's the ultimate online community - a place to meet friends, play the latest games together, dance to new music, watch videos in a social setting, and host parties in their personal apartments. With more spaces being created and partners like Diesel, Electronic Arts, and Red Bull coming on board, the PlayStation Home experience is just getting started.</p>

