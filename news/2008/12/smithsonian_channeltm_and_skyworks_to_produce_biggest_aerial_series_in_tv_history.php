<p><B>NEW YORK, Dec. 8 /PRNewswire/</B> -- A high definition "bird's eye view" of the visual splendor of each of the 50 states will be the focus of a new series, Aerial America, commissioned by Smithsonian Channel.</p>

<p>The channel is co-producing Aerial America with Skyworks, one of the world's top high definition aerial filming specialists, to profile the USA in 50 distinct one-hour programs. The series will be the most expansive aerial television series ever produced.</p>

<p>Aerial America will capture the wonders of the entire country as never seen before: Swoop over California's Hearst Castle, around Alcatraz and under the Golden Gate Bridge. Watch bears catching salmon in Alaska's rivers, surge over a mountain ridge and see one of the largest volcanoes on the North American continent. Covering every state in the union, Aerial America will also reveal fascinating stories seen in a whole new way from the air. Follow Bonnie and Clyde's escape route through the Ozarks of Arkansas, and find the unexpected home of the original London Bridge -- on a lake in Arizona. The variety of spectacles is never ending, and evocative music tracks and insightful commentary will complement the eye popping visuals.</p>

<p>Principal photography will be shot in a Smithsonian Channel-branded helicopter equipped with a gyro-stabilized Cineflex HD camera system, the same rigging used for "Planet Earth". The helicopter crew will criss-cross the nation on an epic journey, spending about 6 months airborne. By the end of their journey they will cover approximately 60,000 total miles, a distance comparable to two and a half trips around the planet.</p>

<p>"This show represents the biggest aerial series ever attempted and the most ambitious project the channel has produced. We are embarking on a voyage of discovery and revelation, and who better to show America our nation in a new way than Smithsonian Networks. Skyworks is a perfect partner for us on this," said David Royle, Executive Vice President of Production and Programming for the Smithsonian Channel.</p>

<p>Richard Mervyn, Founding Director, Skyworks, adds: "The idea of Aerial America is to tell the complex and intriguing history of the country but in a way never before attempted. Skyworks brings the expertise in capturing all the elements that makes this great story and from a view rarely before seen. This is a great commission for Skyworks and cements our relationship with the Smithsonian Network."</p>

<p>Aerial America is directed and produced by Richard Mervyn, founding director of the British-based Skyworks, and executive produced by Damian Keogh. The series is anticipated to premiere in summer 2009 on Smithsonian Channel.</p>

