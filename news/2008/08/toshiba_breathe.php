<center><i>XDE offers enhanced picture performance from standard DVDs</i></center><br />
<br />

<p><B>WAYNE, N.J., Aug. 18 /PRNewswire/</B> -- Toshiba America Consumer Products, L.L.C. ("Toshiba") today announces its new video enhancement technology for DVD with the introduction of the XD-E500. XDE, or "eXtended Detail Enhancement," is more than just DVD upconversion. XDE takes DVD picture quality to a whole new level. In addition to providing upconversion from 480i/p up to 1080p, XDE offers user selectable picture enhancement modes that allow for greater detail, more vivid colors and stronger contrast that bring standard DVD quality closer to the HD experience. XDE technology lets consumers enjoy their existing DVD libraries in a whole new way.</p>

<p>"Consumers have embraced the DVD format like no other technology and invested in large libraries of their favorite movies. As the market moves towards high definition, XDE lets them experience their existing DVD library and the tens of thousands of DVD titles in a whole new way," said Louis Masses, Director of Product Planning. "XDE offers consumers a simple solution to add on to their HDTV purchase. XDE works with existing DVDs to deliver a near HD experience with enhanced detail and richer colors. Toshiba is delivering to consumers what they want -- a high quality experience at an affordable price."</p>

<p><br />
<B>XDE Flexibility</B></p>

<p>In addition to upconversion from 480i/p to 1080p, XDE technology offers consumers the ability to customize their viewing experience to their liking with its picture mode settings. With these three selectable settings -- Sharp, Color and Contrast -- users can get the most out of their DVD movie-viewing experience on their terms.</p>

<p>-- Sharp Mode offers improved detail enhancement that is one step closer to high definition. Edges are sharper and details in movies are more visible. Unlike traditional sharpness control, XDE technology analyzes the entire picture and adds edge enhancement precisely where it's needed.</p>

<p>-- Color Mode makes the colors of nature stand out with improved richness. Blues and greens are more vivid and lifelike. Color Mode combines the improvement in color with the detail enhancement of Sharp Mode and is ideal for outdoor scenes.</p>

<p>-- Contrast Mode is designed to make darker scenes or foregrounds more clearly visible without the typical "washing out" that can occur with traditional contrast adjustment. Recommended for dark scenes where detail may be difficult to notice, Contrast Mode is also combined with Sharp Mode to provide a clearer viewing experience.</p>

<p>In an effort to reach a broad spectrum of consumers from around the world, Toshiba's new XDE technology and the exciting experience it delivers, will be featured in an extensive print and online advertising campaign. This includes placement on NBCOlympics.com, a site that signifies strength, performance, diversity and unity among many. A new Web site, http://www.toshibaxde.com/, will be launched to help educate consumers on the benefits of XDE technology and how it works so they can experience the best of what this new technology has to offer and enjoy their DVD movies in near HD quality.</p>

<p>XDE will be launched today onboard the XD-E500 1080p/24fps Upconverting DVD player. Featuring XDE technology, the XD-E500 also incorporates key features found on today's upconverting standard DVD players such as HDMI-CEC, DivX certification, JPEG capability,</p>

<p>MP3 and WMA playback and much more in a slim, high-gloss cosmetic design to complement today's HDTV.</p>

<p>The XD-E500 is shipping this month with an MSRP of $149.99 and can be found at authorized retailers nationwide. For more information on XDE please visit http://www.toshibaxde.com/ or http://www.tacp.toshiba.com/.</p>

<p><br />
<B>About Toshiba America Consumer Products, L.L.C.</B></p>

<p>Toshiba America Consumer Products, L.L.C. is owned by Toshiba America, Inc., a subsidiary of Toshiba Corporation, a world leader in high technology products with subsidiaries worldwide. Toshiba is a pioneer in DVD and DVD Recorder technology and a leading manufacturer of a full line of home entertainment products, including flat panel TV, combination products and portable devices. Toshiba America Consumer Products, L.L.C. is headquartered in Wayne, New Jersey. For additional information please visit http://www.tacp.toshiba.com/.</p>

<p><br />
<B>Important Notes</B></p>

<p>This product does not play HD DVD or Blu-Ray discs. It upconverts standard definition (480p) DVD content to HD (720p, 1080i or 1080p) to match the resolution of your HD display. Although near the picture quality, it does not produce or output native HD video content.</p>

<p>To display upconverted 720p, 1080i or 1080p video content, a 720p, 1080i or 1080p capable HDTV or HD Monitor (as applicable) with an HDCP capable HDMI or DVI input is required.</p>

<p>The effect of enhancements may vary depending upon disc content quality and display device capability/functionality/settings. Depending on the quality of the DVD disc, some video noise may be visible.</p>

<p>Some DVD-R/DVD-RW discs may be incompatible due to laser pick up and disc design. Some recordable media or recording formats may not be supported.</p>

<p>Compatibility with other HDMI-CEC products will vary by manufacturer. Some products may not be compatible at all or may only allow for limited functions.</p>

<p>Viewing 24 frames per second requires content created in 480p / 24 frames/sec and an HD display capable of accepting a 1080p/24Hz signal.</p>

