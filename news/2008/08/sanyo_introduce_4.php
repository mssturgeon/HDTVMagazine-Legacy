<p><B>CHATSWORTH, Calif., Aug. 25 /PRNewswire/</B> -- SANYO, one of the world's largest manufacturers of LCD and DLP presentation systems introduces a new Full HD LCD projector for popular residential applications, such as home theaters and media rooms. While the PLV-Z700 is SANYO's entry-level projector it is equipped with a state-of-the-art Full 1080p HD 3LCD panel, the most advanced lens-shifting technology in the industry, a new variable iris, and SANYO's 3D color management system. The PLV-Z700 will be shipping in October 2008 with a MSRP of only $1,995.00.</p>

<p>"Our entry-level Full HD projector addresses the increased interest in projection systems for home-based entertainment systems due to the rapid growth of high resolution material, from Blu-ray discs, HD game consoles and digital camcorders," says Mark Holt, the Vice President and General Manager for SANYO's Presentation Technologies Division. "SANYO recognizes this trend toward affordable higher quality video and the PLV-Z700 is capable of projecting large, beautiful images anywhere and now for more Americans."</p>

<p>The PLV-Z700 is one of SANYO's least expensive projectors designed for residential installations, offering a Full HD panel providing 1920 x 1080 resolution from high definition sources such as Blu-ray discs, HD camcorders, a wide variety of video on-demand services plus paid TV services from cable and satellite companies, in addition to terrestrial-based HD broadcasts.</p>

<p>Outfitted with an extremely versatile lens-shifting function, the PLV-Z700 can effectively adjust the equivalent of 3 screens vertically and 2 screens horizontally. Combined with the 2x zoom, which allows for an extremely long or short focus, it is possible to create a large screen projection virtually anywhere, even in small rooms such as dens or bedrooms.</p>

<p>The new variable iris offers rapid adjustments that control the amount of light projected on the screen every 1/60th of a second. By permitting ultra, fast-acting lens adjustment, the PLV-Z700 is capable of providing the most optimal light level at all times. Factor in a high contrast ratio of 10,000:1, along with the more advanced variable iris; this projector is capable of creating incredibly rich, and deep black color reproduction. The iris noise has been reduced to ensure greater enjoyment and cinematic-like immersion in quiet or silent scenes of a movie.</p>

<p>The PLV-Z700 also incorporates SANYO's 3D color management system that address changes in color phase and color level to obtain perfect color reproduction. This new color management system was designed to optimize the potential of Deep Color via the projectors two HDMI 1.3 inputs. Other features include an electronic shutter that protects the lens from dust when not in use and a whisper quiet fan, rated at only 21dB. Five video modes (Brilliant Cinema/Creative Cinema/Natural/Living/Dynamic) provide pre-calibration for various genres of video material.</p>

