<p><B>SOMERVILLE, Mass., Aug 25, 2008 (BUSINESS WIRE)</B> -- Farm Aid today announced that its Sept. 20 New England music festival will be broadcast live on DIRECTV's The 101 Network, which reaches more than 17 million viewers. This broadcast will mark the first time that Farm Aid's annual benefit concert airs live in HD.</p>

<p>The show will broadcast from Farm Aid 2008 Presented by Whole Foods Market and Horizon Organic at the Comcast Center near Boston. The show will feature performances by Farm Aid president and founder Willie Nelson; board members Neil Young, John Mellencamp and Dave Matthews; as well as Kenny Chesney. Coverage on The 101 Network will begin at 4 p.m. and end at 11 p.m.</p>

<p>Farm Aid also announced that The Pretenders, moe., Arlo Guthrie, Jerry Lee Lewis, Nation Beat, Grace Potter and the Nocturnals, Jakob Dylan and The Gold Mountain Rebels, Danielle Evin, Jamey Johnson, Jesse Lenat, Will Dailey and One Flew South will join previously announced performers Nelson, Young, Mellencamp, Matthews and Chesney.</p>

<p>"This year we are excited to bring the Farm Aid experience to homes across the country, inviting viewers who can't make it to the show to join our celebration of music, good food and family farmers," said Carolyn Mugar, Farm Aid's executive director. "The generosity of all of the musicians who donate their performances on behalf of family farmers is an inspiration to the many viewers at home who also want to show their support. DIRECTV is generously leading the way, offering to match its subscribers' gifts from Sept. 6 to Sept. 30 up to $50,000."</p>

<p>"We're giving our more than 17.1 million subscribers a front row seat to this legendary benefit concert while encouraging them to support such an important cause that affects us all on many levels," said Patty Ishimoto, vice president of DIRECTV Entertainment and general manager of The 101 Network. "The 101 Network is known for bringing its viewers quality programming that they can't get anywhere else and we're excited to add Farm Aid to our already robust fall lineup."</p>

<p>In addition to stage performances, the broadcast will feature interviews with artists, farmers and food activists, clips from the pre-concert press event, exclusive backstage coverage and footage from Farm Aid's unique, interactive HOMEGROWN Village, which showcases the direct connection between who is growing our food and what we eat every day. The 7-hour broadcast will be filmed entirely in High Definition and air in 5.1 surround sound.</p>

<p>The 101 Network broadcast will also include an interactive application that allows viewers to learn more about Farm Aid, artists performing at the show and how they can find good food from family farmers. Viewers can access the interactive application by simply pressing the red button on their remote control during the live broadcast.</p>

<p>The show will rebroadcast in its entirety four times, the first starting immediately following the end of the live broadcast and then three more times on the Sunday, Sept. 21st. Albert Spevak is executive producer of the Ambassador Entertainment production. Lawrence Jordan is directing, Philip Hack and Robert Katz are producers, and Susan Steiner is segment producer.</p>

<p><br />
<B>About Farm Aid</B></p>

<p>Farm Aid's mission is to build a vibrant family farm-centered system of agriculture in America. Farm Aid artists and board members Willie Nelson, Neil Young, John Mellencamp and Dave Matthews host an annual concert to raise funds to support Farm Aid's work with family farmers and to inspire people to choose family-farmed food. Since 1985, Farm Aid has raised more than $30 million to support programs that help farmers thrive, expand the reach of the Good Food Movement, take action to change the dominant system of industrial agriculture and promote food from family farms.</p>

