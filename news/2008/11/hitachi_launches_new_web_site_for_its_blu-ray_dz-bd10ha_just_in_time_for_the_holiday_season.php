<p>Several key features of the DZ-BD10HA include:</p>

<p>Three Format Hybrid Compatibility</p>

<p>The camcorder has the versatility of being able to record HD video onto three separate formats (Blu-ray Disc, Hard Drive, SDHC) and provides the flexibility and ease of playback and long recording time all in one camcorder.</p>

<p>7 Mega Pixel CMOS Image Sensor</p>

