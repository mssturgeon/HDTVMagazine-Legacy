<p class="prtitle">Comcast Announces That Viewers in South Florida Now Have More Than 1,000 HD Choices Available - the Most HD Content Anytime, Anywhere</p>

<center><i>HD Choices Increase Five-Fold This Year</i></center><br />
<br />

<p><B>MIRAMAR, Fla.--(BUSINESS WIRE)</B>--As High Definition (HD) Television viewing skyrockets, Comcast/South Florida, the area's leading provider of entertainment, information and communications services, announced today that it now offers more than 1,000 high definition viewing choices, delivering on the company's commitment to significantly increase HD programming by year's end. This announcement also marks a major milestone for Project Infinity, Comcast's initiative to provide consumers with the ability to watch any movie, television show, user generated content or other video that a producer makes available On Demand.</p>

<p>"In January of 2004, we began offering high definition television in South Florida. At that time we offered a total of 12 channels; today, less than 4 years later, we offer more than 1,000 HD OnDemand choices - five times more than last year! One thing we've learned is that it's not just about the volume of HD offerings, it's the quality of those choices, and we're providing the highest-quality content consumers really want, whether they choose to watch live or based on their own schedule," said Filemon Lopez, Comcast's regional senior vice president for South Florida. "We have the ability to deliver the best HD movies, top-rated HD shows and the hottest HD music all On Demand ... we're delivering the future of HD television, today. We not only offer tremendous quantity but also the excellent quality as well."</p>

<p>HD Explosion</p>

<p>With the availability of more than 1,000 HD choices, Comcast strengthens its industry-leading position of providing more choices on TV than anyone else, feeding the insatiable appetite consumers have for HD content. Recent HD trends include:</p>

<p>    * The proportion of viewing time spent with HD has increased nearly 50 percent in four years1.<br />
    * Over the next three years, the total number of HD households receiving HD service is expected to increase by 90 percent or 53 million households2.<br />
    * Of homes with HD cable, 27 percent now have two or more HD sets hooked up to cable HD3.</p>

<p>With 1,000 HD choices, Comcast is delivering the HD programming that aligns with what consumers want to watch and how they want to watch it; for example:</p>

<p>    * Live HD sporting events through all of the major local broadcasters: Comcast Sports South, ESPN and ESPN2, TBS, TNT, Versus, etc.;<br />
    * More than 200 HD movies from top movie providers; supporting recent findings that in spite of how many HD movies are already out there in HD, 65 percent of HD viewers want more4;<br />
    * Nearly 300 television shows including highly acclaimed television series like Mad Men, Weeds and the CSI series, available on linear and on HD On Demand the day after they air; and<br />
    * Hundreds of music offerings in the music category, one of the most popular categories currently On Demand.</p>

<p>Mirroring Comcast's content strategy, a recent independent study outlined that HD viewers listed their favorite things to watch in HD as: sports, movies, TV shows and music, respectively. And, when asked how they wanted to watch, respondents answered: sports live (78 percent); movies on their schedule (81 percent); TV shows on their schedule (65 percent) and music on their schedule (60 percent)5.</p>

<p>On Demand Usage Continues to Grow Exponentially</p>

<p>Every month, Comcast customers nationwide choose On Demand programming more than 300 million times. Currently Comcast's On Demand lineup offers more than 10,000 selections each month. In South Florida, On Demand is accessed more than 9 million times a month, and includes everything from movies, music and top TV shows to the most popular kids', sports and lifestyle programs - available anytime consumers want to watch them, with the ability to fast forward, rewind and pause selections.</p>

<p>About Comcast Corporation</p>

<p>Comcast Corporation (www.comcast.com) is the nation's leading provider of entertainment, information and communications products and services. With 24.4 million cable customers, 14.7 million high-speed Internet customers and 6.1 million Comcast Digital Voice customers, Comcast is principally involved in the development, management and operation of broadband cable systems and in the delivery of programming content.</p>

<p>Comcast's content networks and investments include E! Entertainment Television, Style Network, Golf Channel, VERSUS, G4, PBS KIDS Sprout, TV One, ten Comcast SportsNet networks and Comcast Interactive Media, which develops and operates Comcast's Internet businesses, including Comcast.net (www.comcast.net). Comcast also has a majority ownership in Comcast-Spectacor, whose major holdings include the Philadelphia Flyers NHL hockey team, the Philadelphia 76ers NBA basketball team and two large multipurpose arenas in Philadelphia.</p>

<p>Comcast's South Florida Region, which employs more than 2,200 people, encompasses Broward, Miami-Dade and Monroe Counties. Its regional offices are located in Miramar, FL.</p>

