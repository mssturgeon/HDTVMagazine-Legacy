<p><B>SECAUCUS, N.J., Nov. 25 /PRNewswire/</B> -- Panasonic, a market and technology leader in flat panel HDTV's, announced today that it will again offer consumers access to its Panasonic VIERA Concierge(TM) toll-free information service prior to "Black Friday" and through this holiday season. The Panasonic VIERA Concierge program, normally open exclusively to Panasonic VIERA Plasma and LCD HDTV owners, will be accessible to any consumer who would like to learn more about selecting a flat panel television from a live expert beginning today through February 17, 2009.</p>

<p>Panasonic first offered open access to its VIERA Concierge HDTV experts during the 2006 holiday season, again last year during the 2007 holiday season, as well as other key buying times including Father's Day.</p>

<p>"The quality and volume of calls our VIERA HDTV Concierge experts have received from consumers during our past open access periods underscored the fact that this effort has provided a valuable resource to people looking to buy a flat panel television," said Bob Perry, Senior Vice President, Panasonic Consumer Electronics Company. "The holidays are traditionally a time when many consumers consider buying a new television, and as we close in on the Digital TV transition this February 17, 2009, more and more consumers will be making the transition to High Definition television. Offering consumers access to our otherwise exclusive group of HDTV experts gives them a valuable resource to assist them in making educated decisions when purchasing a flat panel HDTV."</p>

<p>Panasonic's VIERA Concierge Program, which began in June 2006, offers VIERA HDTV owner members an exclusive range of free services, including live access to specialized HDTV consultants, a loaner program if a unit needs to be removed for repair, on-line chat capabilities and call staff that are empowered to resolve issues swiftly.</p>

<p>In addition to answering basic and technical questions, Panasonic VIERA Concierge experts will work with consumers to help them determine the type of flat panel television that best suits their needs by asking key questions about their TV-watching environment, viewing habits, room design/dimensions and other conditions.</p>

<p>Panasonic's Customer Call Center in Chesapeake, VA, which administers the Panasonic VIERA Concierge hotline, has been recognized as a Certified "Center of Excellence" by the Center for Customer-Driven Quality(TM) at Purdue University. This highly respected certification ranked Panasonic's Call Center in the top 10 percent of the 20,000 call centers studied throughout North America.</p>

<p>"As a maker of both Plasma and LCD flat panels, we know that, especially this time of year, many consumers are confused and often bombarded with information on the pluses and minuses of the various flat panel product offerings; some of this information may be outdated or inaccurate," said Mr. Perry. "Our goal in providing access to our VIERA HDTV Concierge experts is to empower and inform consumers so they can ultimately select the HDTV that best suits their needs."</p>

<p>Open access to the Panasonic VIERA Concierge service ends February 17, 2009. Consumers can access the service by calling 1-888-777-1170 Monday through Friday 9:00 a.m. to 9:00 p.m. ET and Saturday and Sunday 10:00 a.m. to 7:00 p.m. ET where they will be connected to a Panasonic VIERA HDTV expert. Consumers also can find tips, facts about flat panel televisions including a guide which highlights the ins and outs of shopping for a flat panel HDTV at www.panasonic.com/plasmacentral.</p>

