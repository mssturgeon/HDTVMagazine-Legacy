<p>The Nielsen Company estimates that 13 million households (12 percent) will be impacted by the switch to digital broadcast, so the nation's largest retailer has made specific plans to help customers from all cities and towns make an informed decision.</p>

<p>"Due to our many locations, we expect the majority of customers will come to us for making their digital transition plan, both for convenience and price," said Gary Severson, senior vice president of Home Entertainment, Wal-Mart Stores, U.S. "We've prepared for many months to ensure the coupon process will go smoothly, and will work with suppliers to continue to have available, affordable options in our stores for all customers."</p>

<p>In addition to close counsel and preparations with the NTIA (National Telecomunications and Information Association), Wal-Mart developed additional training for its associates and created a new platform for registers, so the $40 coupon card will work as easily as a gift card.</p>

<p>Wal-Mart now has the following digital television transition options available today in it stores:</p>

<ul><li>Purchase a digital converter box for $49.87 (with coupon, $9.87*) Digital converter boxes receive over-the-air digital TV broadcasts for viewing on TVs that do not have built-in digital tuners. Those looking to keep watching on their current analog TV sets must purchase a digital converter box. Wal-Mart stores nationwide will offer a Magnavox unit and add a new brand in the coming months.</li><li>Sign up for cable or satellite service, right in the store Customers can sign up for cable or satellite service at Wal-Mart stores for their current home TV or with the purchase of a new TV through in-store "kiosks" with the help of a Wal-Mart associate. Shoppers are able to view local service provider packages, with next day service available in most locations.</li><li>Purchase a digital or HDTV television Wal-Mart carries more than 40 types of digital TV and HDTVs across its stores, from $150 to $2,100* if customers choose to replace their TV. Over the last year, Wal-Mart has continued to increase its assortments and carries brands as well as training and in-store communication about digital TV selection and options.</li></ul>

