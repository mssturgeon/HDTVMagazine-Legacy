<center><i>Priced at $16,900 The Eidos 20 BD Embodies Goldmund's Signature High-Tech Refinement</i></center><br />
<br />

<p><B>LOS ANGELES, Feb. 26 /PRNewswire/ </B>-- Goldmund, makers of the world's most extravagant and technologically advanced systems for audio-video purists, introduced today the company's first Blu-ray player, the Eidos 20 BD. With the announcement of the Eidos 20 BD, Goldmund becomes the first high-end audio/video manufacturer to issue a Blu-ray player.</p>

<p>The Eidos 20 BD embodies the Goldmund high-tech refinement that has made the Swiss-based company a leader in the audiophile community for the last 30 years. Goldmund signature features found on the Eidos 20 BD include the "AC-Curator" power supply circuit which dramatically improves picture and sound stability and dynamics, and the "Mechanical Grounding" construction which removes from the player mechanism spurious vibrations blurring the video signal and increasing jitter. In addition, the new Eidos 20 BD uses the Goldmund "Magnetic Damper," a device lowering the reading errors, a feature that previously was exclusive to Goldmund's highest end devices.</p>

<p>"As a result of last week's news in regards to the format wars, Goldmund decided to launch the Eidos 20 BD earlier than we had originally planned to capture the attention of the industry that believes in the superior technological merits of the Blu-ray format," said Michel Reverchon, president of Goldmund. "The Blu-ray player is the perfect addition to our Goldmund Media Room, which requires high-definition playback and is the pinnacle of technological excellence."</p>

<p>Goldmund will begin taking orders for the Eidos 20 DB, which is priced at $16,900.</p>

<p>Additional information can be accessed by visiting the Goldmund website at http://www.goldmund.com/. The Goldmund Media Room in Los Angeles is available for select demonstrations by appointment.</p>

<p><br />
<B>About Goldmund</B></p>

<p>Based in Geneva, Switzerland, Goldmund has set the standard for ultra-luxury audiophiles worldwide. Founded in 1978, Goldmund's exceptional product design is matched by its industry-leading commitment to fundamental audio performance research. Employing a team of electro-acoustic engineering experts, Goldmund leads the industry in fundamental research and has developed and introduced industry firsts including home wireless music distribution, DVI output, mechanical grounding and thermal grounding. At the forefront of the international luxury audio/video marketplace, Goldmund recently introduced the "Reference II" turntable, priced at $300,000. The "Reference II," the world's most expensive turntable for the world's most demanding collectors of masterpieces, is also the most scientifically accurate, pushing the limits of physics and demonstrating the most advanced levels of technology. In 2007, Goldmund introduced the Goldmund Media Room, a revolutionary media room solution. For more information visit Goldmund online at http://www.goldmund.com/.</p>

