<center><i>New Models Feature Ethernet Port for Interactive Functionality and Easy Firmware Updates</i></center><br />
<br />

<p><B>LAS VEGAS, Feb. 26 /PRNewswire/</B> -- Sony updated its Blu-ray Disc player line today with two new models that will be capable of accessing advanced interactive features such as BonusView and BD-Live.</p>

<p>The BDP-S350 and BDP-S550 models both support BonusView (Picture-in-Picture) featured on some of the new Blu-ray Disc theatrical releases. The BDP-S350 model is BD-Live ready featuring an Ethernet port for an easy firmware update and access to Internet-based interactive content features. The BSP-S550 is BonusView and BD-Live capable when it ships.</p>

<p>Both models also feature an external port for local storage, so users can add optional storage device. The BDP-S550 ships with a 1GB storage device.</p>

<p>"Building on the exceptional picture and sound quality of previous players, Sony's next-generation Blu-ray Disc models bring exciting interactive features to life and offer consumers a ground-breaking experience," said Chris Fawcett, vice president of marketing for Sony Electronics' Home Product Division. "These new devices bring home movie experience beyond the cinema and into a whole new realm of entertainment."</p>

<p>The players feature 1080/60p and 24p True Cinema output. They are compatible with most standard DVDs and feature 1080p upscaling through an HDMI connection to capable HDTV sets, improving the picture performance of existing DVD libraries.</p>

<p>The models offer 7.1 channel Dolby(R) TrueHD and Dolby(R) Digital Plus decoding and bit-stream output, as well as dts(R)-HD High Resolution Audio and Master Audio bit-stream output. The BDP-S550 adds dts-HD High Resolution Audio and dts-HD Master Audio decoding as well as 7.1 channel analog audio output.</p>

<p>The players support AVCHD discs encoded with x.v.Color(TM) (xvYCC) technology, an international standard for wide color space reproduction. The standard expands the current data range of video by about 1.8 times, allowing the players to output more natural and vivid colors similar to what the human eye can actually see. The players also feature compatibility with an array of video formats, including BD-R/RE (BDMV and BDAV modes), DVD+R/+RW, DVD-R/-RW, CD, CD-R/RW (CD-DA format), and JPEG on DVD//CD recordable media.</p>

<p>The new models feature a slim design with reduced depth and height compared to previous models matching Sony's new home-theater-in-a-box systems, the HT-SS2300 and HT-CT100 T-SS2300, also announced today. Optimized for Blu-ray Disc(TM), the new component systems feature three 1080p compatible HDMI(TM) inputs making them the perfect match for a Full high-definition home theater when connected to a new Sony BRAVIA(R) 1080p HDTV.</p>

<p>The new BDP-S350 ships this summer for about $400 and BDP-S550 will be available this fall for about $500. They will be offered at Sony Style stores, online at sonystyle.com, at military base exchanges, and at authorized retailers nationwide.</p>

