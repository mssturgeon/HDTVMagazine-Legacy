<p><B>YONKERS, N.Y., Feb. 5 /PRNewswire-USNewswire/</B> -- There's no need to wait any longer to buy an HDTV. That's the advice from Consumer Reports. Tests of 101 plasma, LCD, and rear-projection TVs for the March issue yielded more sets with top scores for picture quality than in years past. CR also reveals that prices are down as much as 40 percent on some TVs, so consumers continue to get more bang for their buck.</p>

<p>How to Choose & What to Buy</p>

<p>Consumer Reports notes that there are three major considerations when buying an HDTV: the type - LCD, plasma or rear-projection, the size of the screen, and whether it's worth paying a premium to step up from 720p to 1080p resolution. CR recommends considering a 1080p model first, especially if price is not an issue.</p>

<p>But CR strongly advises that shoppers shouldn't automatically rule out a 720p set. Not all 1080p sets were superior in CR's tests, especially when selecting a smaller screen-size. CR found that on a 42-inch screen, the advantages of 1080p resolution aren't as apparent as on sets 50 inches or larger. Some of CR's top-rated TVs are 720p models. For example, the 40-inch Samsung [LN-T4053H], a $1,500 LCD set, was the top-rated model in its category. It has 720p resolution, sufficient for its screen size, and had deeper blacks than many LCD sets. Consumers interested in a 720p plasma set should consider the 42-inch Panasonic [TH-42PX77U], $1,300, a CR Best Buy for its combination of top picture quality and price.</p>

<p>CR also has several recommendations for shoppers looking for a larger screen. The top-rated 58-inch Panasonic [TH-58PZ750U], for example is a $5,000 1080p plasma model that has excellent picture quality, rich, vibrant colors, and deep blacks. Two 50-inch 1080p plasma sets from Panasonic, are among CR's Quick Picks. Other highly-rated 50-inch plasmas include sets from LG and Pioneer.</p>

<p>Among LCD sets, CR recommends models by Sony [Bravia KDL-52XBR4], $4,000, Sharp [Aquos LC-52D64U], $3,000, and Samsung [LN-T5281F], $4,500. All of these 52-inch 1080p models did well for picture quality, brightness, image detail, and color accuracy. Other recommended sets include 46-inch models by Sony, Samsung, and Mitsubishi. The 46-inch 720p Sony [Bravia KDL-46S3000], $1,900, a CR Best Buy, did very well for picture quality. However, its 1080p sibling, the Sony [Bravia KDL-46W3000], $2,500, had finer detail.</p>

<p>If price, rather than screen-size is the priority, CR has quite a few recommendations. For under $1,000, consumers can get very good picture quality from the 37-inch 720p LCD Olevia 537H, $800 or the Insignia [NS-LCD37], $750. The 32-inch 720p LCD Vizio [VW32LHDT], $600, had comparable performance at a lower price. The best 32-inch 720p LCD sets came from Sony, Panasonic, and Samsung, all cost more than $1000.</p>

<p>The report also includes ratings of 14 rear-projection models. However, CR notes that a growing number of manufacturers - including Sony, Toshiba, Hitachi, and Philips - have exited the category and have stopped making rear-projection TVs.</p>

<p><br />
<B>What it costs to run a big screen TV</B></p>

<p>One new feature in the latest HDTV report is energy consumption. CR's engineers determined the amount of energy used by typical LCD, plasma, and rear-projection TVs turned on for 8 hours a day, 365 days a year. Most sets didn't use significantly more energy than a 32- to 36-inch picture tube TV. One exception was 50-inch 1080p plasmas, which used twice-as-much energy as the biggest picture-tube set, and more than a comparably-sized LCD. Not surprisingly, bigger screens of all types consume more electricity than smaller ones. See the chart on the right to see CR's estimates on what it costs to run a TV annually.</p>

<p><br />
<B>TV Reliability & Extended Warranties</B></p>

<p>According to Consumer Reports' most recent product reliability survey, repair rates for LCD and plasma TV sets have been very low, an average of three percent overall, especially during the first three years of use - the time covered by many warranties. In the small number of cases where a set did need servicing, most repairs reported by respondents were free, presumably because they were covered by the manufacturer's standard warranty. The few respondents who paid for repairs spent an average of $264 to fix a flat-panel LCD, $395 for a plasma, and $300 for rear-projection sets.</p>

<p>The latest issue of Consumer Reports includes advice on how to handle repairs in warranty and out-of-warranty. CR also advises whether to repair or replace a TV depending on its type and age.</p>

<p>Consumer Reports' latest product reliability survey data also reinforces its long-standing advice to skip the extended warranty. Rear-projection TVs have been more repair-prone, but even for these sets, an extended warranty usually won't pay off. And, consumers may be able to get longer manufacturers' warranty coverage on their set without paying for it. Some premium credit cards add up to a year on the manufacturer's warranty at no cost if the TV is bought with their card. Also, Costco offers a free two-year warranty on sets purchased in its warehouse or on its Web site.</p>

