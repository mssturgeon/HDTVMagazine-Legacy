<center><i>Models Optimized for Latest HD Sources and Simple Connectivity</i></center><br />
<br />

<p><B>LAS VEGAS, Feb. 26 /PRNewswire/</B> -- Providing a simplified approach to high-definition home theater management, Sony today unveiled a line of four A/V receivers offering high-definition performance, easy set-up and control through a unique icon-driven menu system.</p>

<p>Each of the new models simplify home theater operation by serving as a central hub for audio and HD video home theater components, converging all sources to one HDMI(TM) output from the receiver to the display.</p>

<p>Designed for optimal high-definition home theater performance, the models include such features as 1080/24p True Cinema video pass-through, advanced audio codec support, and upscaling of all standard definition video sources to 1080p via HDMI when connected to a 1080p-capable HDTV set.</p>

<p>"Our new line of A/V receivers serve as the heart of any high-definition home theater system by synchronizing all audio and HD video sources to deliver a smooth, high quality home theater experience," said Brennan Mullin, vice president for audio products for Sony Electronics' Digital Imaging and Audio Division. "The new receivers offer an easy and affordable solution to complete the important second half of the high-definition equation -- cinematic surround sound that complements the picture."</p>

<p><br />
<B>Optimized High-Definition Support</B></p>

<p>The new STR-DG920 and STR-DG820 7.1 channel A/V receivers offer 110 watts of power per channel and are equipped to support the latest in high-definition formats with 1080/60p and 24p True Cinema video signal pass-through.</p>

<p>Featuring four HDMI(TM) inputs, the models support the latest audio formats -- Dolby(R) Digital Plus, Dolby(R) TrueHD, dts(R) High Resolution Audio and dts(R) HD Master Audio. The models also support x.v.Color(TM) technology (xvYCC) which offers a wider spectrum of colors from source to receiver to an x.v.Color-compliant HDTV.</p>

<p>Additionally, the STR-DG920 model supports Deep Color(TM) for greater color depth on compatible televisions and upscales standard-definition video content to 1080p via HDMI with a 1080p-capable HDTV set. The model features an icon-driven menu system for simple device and content navigation.</p>

<p>Also included is Sony's Digital Media Port. This adds networking and connectivity to the AV receivers for music playback from various sources with optional accessories, including audio cradles compatible with select Walkman(R) players and iPod(R) products, a PC client device and a Bluetooth(R) adapter. Once the accessory is connected, the device can be powered and controlled by the receiver for enhanced home theater experience.</p>

<p>An upgraded Portable Audio Enhancer improves the clarity and depth of any connected digital music player by adding information to the audio signal that had been removed during compression for an improved audio experience. Additionally, the units are XM Connect-and-Play(TM) ready with 5.1 Neural Surround Sound.</p>

<p>The models incorporate Digital Cinema Auto Calibration (DCAC) for simplified multi-channel surround sound setup. In about 20 to 30 seconds, the system automatically adjusts frequency, distance and level for optimal performance.</p>

<p>The STR-DG920 model will be available in June for about $600, while the STR-DG820 system will be available in May for about $400.</p>

<p><br />
<B>Full HD 1080p and HDMI Connectivity</B></p>

<p>The new STR-DG720 7.1 channel A/V receiver, with 105 watts of power per channel, features three HDMI inputs that support 1080/60p and 24p video signal pass-through, plus up to eight channels of uncompressed LPCM audio. It works with XM Radio and will be available in March for about $300.</p>

<p>At 100 watts, the STR-DG520 5.1 channel A/V receiver offers two HDMI inputs with 1080/60p and 24p video signal pass-through. It will be available in March for about $200.</p>

<p>Both models include Digital Cinema Auto Calibration (DCAC) technology, Digital Media Port, Digital Cinema Sound processing for studio quality reproduction, and Portable Audio Enhancer.</p>

<p>The new line of A/V receivers will be available through sonystyle.com, at Sony Style retail stores, at military base exchanges and at authorized dealers nationwide.</p>

