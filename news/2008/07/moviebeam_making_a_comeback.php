<p>"This acquisition is a strategic fit in our global expansion strategy for our Media and Entertainment practice. Through MovieBeam, Valuable will further establish itself as a leader in the media and entertainment space by allowing us to deliver content to homes and the hospitality industry worldwide," said Gaikwad.</p>

