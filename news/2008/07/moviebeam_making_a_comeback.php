<p><B>SEATTLE & LOS ANGELES & MUMBAI, India--(BUSINESS WIRE)</B>--The Valuable Group (http://www.valuablegroup.com), a leading Mumbai-based media and technology company, has completed a transaction to purchase the assets of pioneering video on demand (VOD) service, MovieBeam, including all trademarks, technology, and alliances. The announcement was made today by Sanjay Gaikwad, Founder and Managing Director, Valuable Group, who also led the deal.</p>

