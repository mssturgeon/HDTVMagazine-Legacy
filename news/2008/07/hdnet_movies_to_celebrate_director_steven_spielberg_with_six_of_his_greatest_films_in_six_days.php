<p><B>DALLAS, July 21 /PRNewswire/</B> -- This month, HDNet Movies presents a programming event to celebrate director Steven Spielberg as one of the most influential figures in cinema.</p>

<p>Beginning Monday, July 28, HDNet Movies subscribers will get a chance to sample some of the early work that helped solidify Spielberg's position as a top Hollywood director, including "E.T. The Extra-Terrestrial," "Close Encounters of the Third Kind," and "Jaws."</p>

