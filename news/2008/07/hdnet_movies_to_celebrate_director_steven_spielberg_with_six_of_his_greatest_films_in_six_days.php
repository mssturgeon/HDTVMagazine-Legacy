<p>Tuesday, July 29 at 8:00 p.m. ET is the drama "Empire of the Sun" starring a thirteen year-old Christian Bale, John Malkovich and Miranda Richardson. This film received Academy Award nominations for Best Cinematography, Best Film Editing, Best Sound, Best Art Direction - Set Decoration, Best Costume Design, and Best Music - Original Score, in addition to Golden Globe Nominations for Best Motion Picture - Drama and Best Original Score, Motion Picture.</p>

