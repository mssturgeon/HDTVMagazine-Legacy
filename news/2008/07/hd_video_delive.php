				<p class="prtitle">PLAYSTATION(R)Network's Video Delivery Service to Offer Movies and TV Shows for Purchase and Rental Through PLAYSTATION(R)3 and PSP(R) (Playstation(R)Portable)</p>

<center><i>New service to expand entertainment offering of PLAYSTATION 3 and PSP giving consumers downloadable content when and where they want it</i></center><br />
<br />

<p><B>FOSTER CITY, Calif., July 15 /PRNewswire/</B> -- Sony Computer Entertainment America (SCEA) today launches the company's new video delivery service on PLAYSTATION(R)Store for PLAYSTATION(R)3 (PS3(TM)) and PSP(R) (PlayStation(R)Portable) systems in the United States. Consumers will have the ability to download full-length movies, television shows, and original programming accessible through the PLAYSTATION Store on PLAYSTATION(R)Network. With nearly 300 full length movies and more than 1,200 TV episodes, many available in both standard-definition (SD) and high-definition (HD), PLAYSTATION Network's video delivery service makes PS3 the ultimate entertainment platform and enhances PSP's status as a portable entertainment marvel. PLAYSTATION Network's video delivery service will become available later this evening.</p>

<p>Sony Computer Entertainment Inc. (SCEI) will initially make available to consumers content for video rental and electronic sell-through from top movie studios including: 20th Century Fox, Lionsgate Entertainment, MGM Studios, Paramount Pictures, Sony Pictures Entertainment, Warner Bros. Entertainment as well as titles for rent from The Walt Disney Studios and a wide-ranging menu of popular titles from a variety of television partners.</p>

<p>"PLAYSTATION Network's video delivery service capitalizes on the superior value and entertainment potential of PS3 and PSP -- not only for gaming enthusiasts, but also for the millions of consumers looking to buy the best, most versatile solution for their home entertainment system," said Jack Tretton, president and CEO, Sony Computer Entertainment America. "The collaboration of Sony's film, TV and entertainment business units, coupled with our hardware and content offerings, provide consumers with entertainment experiences unlike any on the market."</p>

<p>The video delivery service will have full integration in the PLAYSTATION Network, utilizing the same login, wallet management, and user interface of the newly revamped PLAYSTATION Store. Video will be categorized, for example, by top rating, alphabetical order, television shows, and movies and content is also fully searchable, for example, by title, producer, studio and cast. In addition, PS3's progressive downloading means users can view content shortly after the downloading process begins. Background downloading is also a feature of PS3, allowing users to access other platform features such as gaming and other XMB(TM) (XrossMediaBar) content while a video is downloading to their consoles.</p>

<p>20th Century Fox's "Jumper", Lionsgate's "3:10 to Yuma", MGM's "Rocky", Paramount Pictures' "Cloverfield", Sony Pictures' "Spider-Man", and Warner Bros. Entertainment's "10,000 B.C." are a few of the titles available for electronic sell-through on the video service at launch. Disney's "Pirates of the Caribbean: Dead Man's Chest" will also be available for rent. Additionally, SCEI will be introducing original exclusive content such as</p>

<p>Xam'd: Lost Memories, an anime series developed by Sony Computer Entertainment Japan, delivered in SD and HD.</p>

<p>Consumers who rent a movie from the video delivery service have 14 days to watch the content. Once content playback is started, consumers have a full 24 hours to enjoy their rental. Pricing for rental movies at launch ranges from $2.99 to $5.99, and pricing for purchased movies ranges from $9.99 to $14.99. Sony has also adopted Marlin Digital Rights Management technology, an open industry standard for protecting and managing digital content, to provide consumers with flexible access to their content while ensuring digital rights are protected. Usage rules of the video download service will allow content for purchase to be shared on multiple activated devices including PS3 and PSP systems per PLAYSTATION Network account, depending on the type of content purchased by the user.</p>

<p>One of the biggest value propositions of PLAYSTATION Network's video delivery service is the ability to transfer digital content onto the PSP from the PS3. For the initial electronic sell-through or rental price, consumers can also transfer content onto multiple devices. The connectivity between PS3 and PSP platforms provides a seamless solution for those looking for entertainment experiences on their own terms -- on the go or in their living room -- all with a new-found freedom of not having to worry about TV schedules, movie listings or viewing on a desktop PC.</p>

