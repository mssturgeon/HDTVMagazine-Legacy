<p>To shorten recording times, the BAE-VX1000 offers an Auto Customize function. This can automatically detect parts of the picture that are difficult to encode, then perform multiple encoding using up to five possible bit rates set up in advance. When two-pass encoding of the entire title is finished, users can review these multiple versions and select the most suitable one based on its picture quality and disc size.</p>

<p><br />
<B>Frame-by-Frame Customization</B></p>

<p>Each encoding parameter can be customized frame-by-frame for best picture quality. The graphical user interface shifts to another color to indicate where the parameters have changed. After customization, segment encoding allows users to input the smallest range required for re-encoding. This delivers optimum picture quality in the shortest time by avoiding the need to re-encode the entire title.</p>

<p><br />
<B>Scalable Three-speed Configuration</B></p>

<p>Engineered to suit individual production needs, the BAE-VX1000 offers multiple settings to give Blu-ray Disc producers the most flexibility, while not compromising picture quality. An "Express" mode supports AVC real-time encoding with one PC, when encoding speed is the top priority. When using additional networked processors, "Fast" and "Quality" modes are also available to meet higher performance and quality requirements. The BAE-VX1000 also offers a built in real-time AVC elementary stream decoder that improves the efficiency of quality checking procedures.</p>

<p><br />
<B>Supports Single and Multiple PC Networks for Optimum Studio Flexibility</B></p>

<p>The BAE-VX1000 encoder can support a simple and affordable single PC configuration that can accomplish AVC encoding in real-time, which is ideal for smaller production houses. The encoder can also be easily expanded to a networked distributed processing configuration, offering large-scale studio encoding studios a new and affordable tool for greater operational flexibility.</p>

