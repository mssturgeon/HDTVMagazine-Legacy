<center><i>LG BD300 Network Blu-ray Disc Player to be Unveiled Tonight</i></center><br />
<br />

<p><B>NEW YORK, July 31 /PRNewswire-FirstCall/</B> -- Building on a groundbreaking technology partnership announced earlier this year, LG Electronics and Netflix, Inc. (NASDAQ:NFLX) today announced plans for the first Blu-ray disc player that will have the added benefit of being able to instantly stream a growing library of movies and TV episodes from Netflix directly to the TV.</p>

<p>Available this fall, the LG BD300 Network Blu-ray Disc Player will play high definition Blu-ray discs, up-convert standard DVDs to 1080p and allow Netflix subscribers to instantly stream more than 12,000 choices of movies and TV episodes from Netflix to the TV for no additional charge.</p>

<p>LG Electronics and Netflix will demonstrate the BD300 Network Blu-ray Disc Player for the first time tonight at LG's 2008 Summer Line Show at Morgan Library and Museum in New York City. (The event is open to invited media only.)</p>

<p>Instantly streaming content from Netflix to the TV via the LG BD300 Network Blu-ray Disc Player will rely on a wired broadband connection and Queue-based user interface. Netflix members will use the Netflix Web site to add movies and TV episodes to their individual instant Queues. Those choices will automatically be displayed on members' TVs and available to watch instantly through the LG player. Once selected, movies will begin playing in as little as 30 seconds. With the BD300's accompanying remote control, Netflix members will be able to browse and make selections right on the TV screen and also have the ability to read synopses and rate movies. In addition, they will have the option of fast-forwarding and rewinding the video stream.</p>

<p>"As Blu-ray player sales are expected to triple in three years, consumers are craving content and seeking a premium home entertainment experience," said LG Electronics USA President Teddy Hwang. "The BD300 is another LG industry first and provides consumers with an advanced high-def disc player with unparalleled flexibility and networked access for services such as Netflix."</p>

<p>Consumers craving more content will appreciate the BD Live feature, which provides real-time interactivity for movie enthusiasts seeking extras, new previews or special content while BonusView provides picture-in-picture access to Blu-ray disc special features. To further personalize and simplify the home theater experience, the BD300 includes LG's SimpLink(TM) technology, which allows users to control similarly equipped LG TV and AV products via convenient on-screen menus or directly from the product itself.</p>

<p>In January, prior to the 2008 International CES(R), LG Electronics and Netflix announced their technology partnership to provide a set-top box for consumers to stream movies and TV episodes from the Internet to the TV beginning in the second half of the year.</p>

<p>"LG Electronics is establishing itself as the innovation leader in consumer electronics, combining the best of broadband and Blu-ray connectivity," said Netflix Co-Founder, Chairman and CEO Reed Hastings. "LG Electronics was the first of our technology partners to publicly embrace our strategy for getting the Internet to the TV, and is the first to introduce a Blu-ray player that will instantly stream movies and TV episodes from Netflix to the TV."</p>

