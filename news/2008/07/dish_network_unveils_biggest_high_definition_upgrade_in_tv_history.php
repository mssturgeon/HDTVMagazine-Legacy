<B>ENGLEWOOD, Colo. - July 31, 2008</B> - DISH Network Corporation (NASDAQ: DISH) today set the bar for the next-generation HD standard by becoming the first in the pay-TV industry to offer high definition programming in 1080p, the highest and best HD resolution available. 

<p>This new functionality is part of DISH Network's latest and unprecedented expansion in HD services, which includes the rollout of TurboHD, the industry's first 100 percent, all-HD suite of programming packages. As previously announced, DISH Network will also launch 17 more national HD channels tomorrow, surpassing its goal of reaching 100 national HD channels five months ahead of schedule. DISH Network now plans to nearly double its national HD channel count in less than one year and offer up to 150 national HD channels by the end of 2008, made possible by the recent launch of Echo XI, the most powerful satellite in the company's fleet. </p>

<p>"Over the years, DISH Network has maintained a very competitive HD offering in the marketplace, providing customers with a premium HD product including the best technology, signal and experience - at the best value - that no other pay-TV provider can come close to matching," said Charlie Ergen, Chairman, CEO and President of DISH Network. "Our latest system upgrade coupled with the introduction of TurboHD further strengthens our position as the leader in digital television and high definition television, platforms we look forward to enhancing even more with mobile and portable options." </p>

<p>DISH Network's new HD services are supported by a proprietary "turbo-charged" system upgrade that, starting August 1, is being rolled out to all MPEG-4 HD and HD DVR receivers. The upgrade activates a unique feature of the set-top boxes, improving the current standard of HD delivery used by pay-TV providers such as the ability to output 1080p programming. By early August, all DISH Network customers with MPEG-4 HD and HD DVR receivers will have the only set-top boxes in the nation enabled to display 1080p content, allowing them to maximize the full potential of their 1080p-compatible HDTV sets.</p>

<p>To celebrate this new era in the HD viewing experience, DISH Network is offering subscribers a special deal in August to enjoy the unparalleled picture and sound of 1080p HD programming. Starting August 1, the recent blockbuster "I Am Legend" starring Will Smith will be available in Blu-ray&trade; disc quality 1080p resolution, only on DISH Network's VOD service, DISH On Demand, at a discounted price. Subscribers may order the movie on DISH Network Channel 501. This marks the first time in history a pay-TV provider offers movies in 1080p, the highest resolution format available for HD video enthusiasts. </p>

<p>Consumers can sign up for the best HD programming and service in the industry with DISH Network's new TurboHD programming packages, the only all-HD packages on the market, starting at $24.99 per month. TurboHD is available in three separate tiers and includes DISH Network's award-winning and industry-leading HD technology, advanced equipment enabled to display 1080p programming, and the most-watched HD channels that may be viewed on any TV - analog, digital or HD. </p>

<p>Current DISH Network customers with MPEG-4 HD and HD DVR receivers are being automatically upgraded and will have their systems "turbo-charged" by early August with all the features and benefits of TurboHD. DISH Network customers looking to add the industry's best HD experience can get a "turbo-charged" HD package for as little as $10 more per month. </p>

<p>The latest national HD channels added to DISH Network's programming line-up are: ActionMax HD (DISH Network Ch. 313), CBS College Sports HD (Ch. 152), Lifetime HD (Ch. 108), Lifetime Movie Network HD (Ch. 109), Planet Green HD (Ch. 194), Encore HD (Ch. 340), HBO 2 HD (Ch. 301), HBO Comedy HD (Ch. 307), HBO Family HD (Ch. 305), HBO Latino HD (Ch. 309), HBO Signature HD (Ch. 302), HBO West HD (Ch. 303), HBO Zone HD (Ch. 308), Starz Comedy HD (Ch. 354), Starz Edge HD (Ch. 352), Starz Kids & Family HD (Ch. 356), Starz West HD (Ch. 351).</p>

