				<p class="prtitle">Sony Announces Availability of Multi-Codec Video Encoder for Professional Blu-ray Disc Authoring</p>

<center><i>New Encoding Tool from Sony Creative Software Supports All Blu-ray Formats, Offers Customization and 30 Percent Faster Delivery over Previous Sony Encoder at a Competitive Price</i></center><br />
<br />

<p><B>MADISON, Wisc.--(BUSINESS WIRE)</B>--Sony Creative Software, a leading worldwide provider of professional video and audio production applications, today announced the availability of Sony's new multi-codec video encoder for Blu-ray Disc authoring developed in conjunction with Sony Electronics and Sony Pictures Entertainment. Originally announced by Sony Electronics at NAB 2008, the BAE-VX1000 encoder is priced to bring high-speed, high-quality Blu-ray Disc authoring within reach of smaller studios.</p>

<p>"As Blu-ray Discs become consumers' high-definition format of choice, industry demand for affordable and powerful studio encoding tools is rapidly expanding," said Dave Chaimson, Sony Creative Software vice president of global marketing. "The BAE-VX1000 encoder was designed to meet the changing needs of the growing professional encoder market. It can decrease total encoding time by up to 30 percent over the previous Sony BAE-VA700 solution through enhancements such as parallel capturing and pre-processing and increased encoding algorithm efficiency."</p>

<p><br />
<B>Multiple Format Compatibility</B></p>

<p>A multi-codec design enables BAE-VX1000 encoder compatibility with most common Blu-ray authoring applications, such as Sony Creative Software's Blu-print. It offers the option of using H.264 AVC or MPEG-2 technology to give production professionals more flexibility, depending on their project deadlines, client preferences or individual workflow requirements. MPEG-2 encoding for traditional DVD authoring is also available in the BAE-VX1000 encoder.</p>

<p><br />
<B>Auto Customize Function</B></p>

<p>To shorten recording times, the BAE-VX1000 offers an Auto Customize function. This can automatically detect parts of the picture that are difficult to encode, then perform multiple encoding using up to five possible bit rates set up in advance. When two-pass encoding of the entire title is finished, users can review these multiple versions and select the most suitable one based on its picture quality and disc size.</p>

<p><br />
<B>Frame-by-Frame Customization</B></p>

<p>Each encoding parameter can be customized frame-by-frame for best picture quality. The graphical user interface shifts to another color to indicate where the parameters have changed. After customization, segment encoding allows users to input the smallest range required for re-encoding. This delivers optimum picture quality in the shortest time by avoiding the need to re-encode the entire title.</p>

<p><br />
<B>Scalable Three-speed Configuration</B></p>

<p>Engineered to suit individual production needs, the BAE-VX1000 offers multiple settings to give Blu-ray Disc producers the most flexibility, while not compromising picture quality. An "Express" mode supports AVC real-time encoding with one PC, when encoding speed is the top priority. When using additional networked processors, "Fast" and "Quality" modes are also available to meet higher performance and quality requirements. The BAE-VX1000 also offers a built in real-time AVC elementary stream decoder that improves the efficiency of quality checking procedures.</p>

<p><br />
<B>Supports Single and Multiple PC Networks for Optimum Studio Flexibility</B></p>

<p>The BAE-VX1000 encoder can support a simple and affordable single PC configuration that can accomplish AVC encoding in real-time, which is ideal for smaller production houses. The encoder can also be easily expanded to a networked distributed processing configuration, offering large-scale studio encoding studios a new and affordable tool for greater operational flexibility.</p>

<p><br />
<B>Pricing and Availability</B></p>

<p>The BAE-VX1000 encoder is offered as a turn-key system priced at $55,000 U.S. The system is compatible with 64-bit operating systems on Microsoft Windows Server 2003, XP and Vista. For more information, please visit: http://www.sonycreativesoftware.com/products/bluprint.asp?page= otherencoders (Due to its length, this URL may need to be copied/pasted into your Internet browser's address field. Remove the extra space if one exists.)</p>

