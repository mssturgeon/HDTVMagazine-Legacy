<B>About Simplay Labs, LLC</B></p>

<p>Simplay Labs, LLC, based in Sunnyvale, Calif., is the leading solutions provider of technologies, testing programs, development tools, and interoperability and performance design standards for the high-definition (HD) consumer electronics industry. The Simplay HD(TM) Testing Program is comprised of leading consumer electronics manufacturers and technology providers focused on delivering fully compatible products for consumers. As a result, consumers making home theater component purchases can be confident that Simplay HD verified systems exhibit the highest levels of interoperability performance and are ready to receive and play premium digital content, regardless of manufacturer. Simplay Labs is a wholly-owned subsidiary of Silicon Image, Inc. (NASDAQ:SIMG) .</p>

