<center><i>Major expansion of the Simplay HD Testing Program to accelerate product throughput and ensure optimal interoperability and performance for HDMI- enabled products</i></center><br />
<br />

<p><B>SUNNYVALE, Calif., July 1 /PRNewswire/</B> -- Simplay Labs, LLC, the leading solutions provider of technologies, testing programs, development tools, and interoperability and performance design standards for the high-definition (HD) consumer electronics industry, today announced that Samsung Electronics Co., Ltd. (SEC) will be implementing a pilot program of Simplay HD testing and verification at Samsung's facilities. Administered by both companies, this program will expand Samsung's participation in the Simplay HD Testing Program by increasing product throughput, extending the range of products tested, and accelerating time to market.</p>

<p>This is the first-of-its-kind self-testing initiative for Simplay Labs and the result of a collaborative effort between Samsung and Simplay Labs to define and develop a program that supports Samsung's increased use of the Simplay HD Testing Program.</p>

<p>"We understand the importance of delivering fully interoperable products with optimized performance to our retailers and customers, and the best way to ensure this is by utilizing the expertise of Simplay Labs and its Simplay HD Testing Program," said ChanHo Youn, assistant manager of the Customer Satisfaction Management Center at Samsung Electronics. "Samsung has used Simplay Labs testing extensively on a variety of consumer electronics devices and, as we expand our Simplay HD participation, the self-testing program will help streamline the process."</p>

<p>The Simplay HD Self-Testing pilot program will include on-site Simplay testing equipment installation, technician training and certification, quality control, collaborative test specification reviews, and integration with product development and supply chain processes.</p>

<p>"We are thrilled to expand our longstanding relationship with Samsung by rolling out the Simplay HD Self-Testing pilot program to support one of our major partners," said Joseph Lias, president of Simplay Labs, LLC. "Working closely with Samsung in defining the parameters of the Simplay HD Testing Program continues to provide consumers the peace of mind that their HD components will work together to deliver a great HD experience."</p>

<p>The Simplay HD Testing Program takes the guesswork out of shopping for HDMI-enabled components such as set-top boxes (STBs), digital televisions (DTVs), digital video disk (DVD) players, cables and audio/video (AV) receivers. Components bearing the Simplay HD logo have demonstrated that they will work together to provide a "plug-and-play" user experience. Consumers can be assured that when they see the Simplay HD logo, the device has passed the industry's most rigorous HD interoperability and performance testing regimen. Service and content providers, retailers and product manufacturers can expect HD equipment compatibility resulting in reduced returns and the satisfaction of their end users.</p>

