<p>A growing library of more than 10,000 movies and TV episodes will be available from Netflix when it launches on Xbox LIVE in late fall, with more choices added over time. Through this agreement, along with the existing Xbox LIVE Marketplace Video Store, Xbox 360 will be home to more movies and TV shows on demand than any other device connected to the TV. Xbox LIVE quickly and easily connects consumers and their friends to the entertainment they want -- with no PC required for viewing.</p>

<p>Netflix on Xbox 360 is an important component of the new Xbox experience, a new generation of games and entertainment experiences that will be available on Xbox 360 consoles this fall. The new Xbox experience, also announced today at the E3 Media and Business Summit, represents the first time in history that a mass-market consumer electronics device has been re-invented through free software, giving people more fun and intuitive ways to interact, play and enjoy entertainment content.</p>

<p>"Watching movies at home will never be the same. Netflix on Xbox 360 is an entertainment first, and we are bringing friends together with the best in entertainment content like no other device in the living room," said John Schappert, corporate vice president of Interactive Entertainment LIVE, Software and Services Business at Microsoft. "We are creating a completely new social entertainment experience, and Xbox 360 will be the only video game system where you can access your library of instantly streamable movies from Netflix and turn any room into a virtual movie theater."</p>

<p>From the Netflix Web site, members simply add movies and TV episodes to their individual instant Queues. Those choices will be automatically displayed on the TV screen via Xbox 360 and available to watch instantly. Once selected, movies will begin playing in as little as 30 seconds. In addition to instantly streaming movies to the TV, Xbox LIVE Gold members can fast-forward, pause and rewind, all using either their Xbox 360 Controller or Media Remote. In all, the user interface creates a highly personalized experience that puts viewers in control.</p>

<p>"Netflix and Xbox 360 are a perfect combination, the leading online movie rental service and the leading games and entertainment system joining forces to create an all-in-one entertainment experience with content for everyone," said Reed Hastings, chairman and CEO of Netflix. "For Netflix, it represents an important step forward in making instantly streaming movies on the TV more broadly available to our members."</p>

<p>The library of movies and TV episodes that will be available for instant streaming from Netflix via Xbox 360 includes scores of Academy Award winners and nominees, episodes from a number of popular, currently running and classic TV shows, and 24 of the movies rated by the American Film Institute as the greatest ever.</p>

<p>Today, Xbox LIVE members can also download movies and purchase TV shows from the industry-leading Xbox LIVE Marketplace Video Store, currently packed with content from more than 45 networks and studios. The Xbox LIVE Marketplace Video Store offers more than twice the high-definition content than the nearest cable provider and more than 6,000 hours of TV shows and movies.</p>

