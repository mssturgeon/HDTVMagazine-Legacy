				<p class="prtitle">New KODAK Theatre HD Player Transforms Living Rooms into Personal Home Theatres</p>

<center><i>An Innovative, High-Definition TV Viewing Solution Debuts; KODAK Theatre HD Player Inspires Consumers to Interact Freely with Their Memories and Share the Stories of their Lives</i></center><br />
<br />

<p><B>ROCHESTER, N.Y., July 10 /PRNewswire-FirstCall/</B> -- Eastman Kodak Company (NYSE:EK) today unveiled the KODAK Theatre HD Player, a High Definition (HD) media player that enables consumers to interact more freely and creatively with their most valuable possessions -- their memories.</p>

<p>Harnessing Wi-Fi and HD technologies, a wide array of organizational and display features and access to online content through unique partners, the KODAK Theatre HD Player turns consumers into the directors of their own show with a wireless remote control pointer in-hand. The device will roll out in stages, with a market trial commencing in September 2008.</p>

<p>"The proliferation of HDTV technology has created a demand for HD content beyond standard television programming," said John Blake, General Manager Digital Capture and Devices, Vice President, Eastman Kodak Company. "With the KODAK Theatre HD Player, consumers will relive the most cherished moments of their lives on their HDTV -- the largest and highest quality display device in their home. Consumers will have the ability to do more than ever with their pictures, music and videos with easier and more interactive access to their personal content, as well as content from family and friends from around the globe."</p>

<p><br />
<B>KODAK Theatre HD Player</B></p>

<p>Revolutionizing the way images and videos can be enjoyed in HD*, the KODAK Theatre HD Player is an interactive device displaying personal content -- pictures, video, podcasts, music -- and web-based content on a HDTV, while wirelessly connecting to a household's private Wi-Fi network.</p>

<p>The remote-operated KODAK Theatre HD Player lets consumers relive their favorite, and even forgotten, memories in customized slideshows, incorporating their personal music and video collections, Internet Radio, plus online video- and photo-sharing sites. Consumers can also edit and upload images and videos to popular online content sharing sites on their HDTV from the comfort of their living room.</p>

<p> *Able to display HD still images (16:9 Aspect Ratio) and videos (720p).</p>

<p><br />
<B>KODAK Theatre HD Player Partnerships</B></p>

<p>Through unique partnerships with pioneers in photo sharing, such as KODAK Gallery and Flickr(TM), the KODAK Theatre HD Player provides consumers with features that help them achieve new levels of interactivity while viewing, sharing and managing pictures.</p>

<p>Additional alliances with YouTube(TM) and RadioTime allow for access to more than just imaging content, offering an interactive and engaging multimedia experience. The KODAK Theatre HD Player can also source and display imaging content from USB Jump Drives and SD memory cards.</p>

<p><br />
<B>Pricing and Availability</B></p>

<p>The KODAK Theatre HD Player will retail for US $299.99 (MSRP) from September 2008 at select Best Buy stores, Kodak.com and Amazon.com.</p>

