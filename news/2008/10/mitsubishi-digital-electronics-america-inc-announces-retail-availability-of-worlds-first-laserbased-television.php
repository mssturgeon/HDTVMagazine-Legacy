<p>"The consumer demand for LaserVue has simply exceeded our expectations and the product is a terrific example of Mitsubishi's technology leadership within the home entertainment market. Bringing laser TV to market is a significant industry accomplishment and we're very proud to be the only TV manufacturer to date that has delivered on the promise of a laser-driven TV," said Frank DeMartin, vice president, marketing, at Mitsubishi Digital Electronics America. "With operating power at approximately 135W, LaserVue is environmentally friendly, consuming approximately one-third the power of today's LCD TVs, and one-fourth of plasma TVs. Living in today's green-conscious environment, consumers can enjoy this color-brilliant, ground-breaking home entertainment product while being mindful of energy consumption at the same time."</p>

<p>LaserVue's technology is unparalleled; laser beams provide an extensive range of rich, complex colors, along with truly distinct clarity and immersive depth of field. Precise and focused, the purity of laser light far surpasses current high-definition technologies. LaserVue has demonstrated a reproduction of color gamut in excess of 200 percent of BT.709, delivering two times the color of many of today's HDTVs. Brightness has been demonstrated at approximately 500 nits. Additional features for LaserVue include Smooth 120Hz(TM), x.v. Color(TM) and 1080p with an Ultra Thin Frame.</p>

<p>LaserVue is also equipped with 3D-ready(3) viewing capabilities, demonstrating Mitsubishi's foray into bringing a true "Hollywood" entertainment experience to the consumer. At 10 inches thin, LaserVue TV has been designed for both floor stand and wall-mount applications and features a full stereo range of sound capabilities with integrated speakers.</p>

<p>"Consumers are now coming to equate LaserVue with the industry's best performing high-definition television, and we are confident that HDTV enthusiasts everywhere will want to quickly get their hands on one," continued DeMartin.</p>

