<center><i>Based on Microsoft Silverlight, New Player Features Enhanced Dynamic Streaming, First-Time Use for Macs and Breakthrough Navigation for Fast-Forward and Rewind</i></center><br />
<br />

<p><B>LOS GATOS, Calif., Oct. 27 /PRNewswire-FirstCall/</B> -- Netflix, Inc. (NASDAQ:NFLX) , the world's largest online movie rental service, today announced it has begun the deployment of Microsoft Silverlight to enhance the instant watching component of the Netflix service and to allow subscribers for the first time to watch movies and TV episodes instantly on their Intel-based Apple Macintosh computers. The deployment, which will initially touch a small percentage of new Netflix subscribers, is the first step in an anticipated roll-out of the new platform to all Netflix subscribers by the end of the year.</p>

<p>Silverlight is designed for delivery of cross-platform, cross-browser media experiences inside a Web browser. It is expected that Netflix members who watch movies and TV episodes instantly on their computers will enjoy a faster, easier connection and a more robust viewing experience with Silverlight, due to the quality built directly into the player. Among the viewing enhancements with the new player is a breakthrough in timeline navigation that vastly improves the use of fast-forwarding and rewinding. The new Netflix player takes advantage of PlayReady DRM, which is built into Silverlight, for the playback of protected content on both Windows-based PCs and on Macs. That had not been possible with previous generation technologies.</p>

<p>"Silverlight with PlayReady offers a powerful and secure toolkit for delivery of dynamic streaming, which offers faster start-up, and higher quality video, adapted in real time to users' connection speeds," said Netflix Chief Product Officer Neil Hunt. "Members who enjoy watching movies and TV episodes from the growing library of choices that can be instantly streamed at Netflix will be thrilled with this next generation improvement of access and quality, on a broader range of platforms, including Intel Macs and Firefox."</p>

<p>"Instantly streaming from Netflix directly addresses the needs and wants of today's Web users by providing on-demand, high-quality online video," said Scott Guthrie, corporate vice president of the Developer Division at Microsoft Corp. "By using Silverlight, Netflix can deliver to its subscribers a higher quality video experience on the Web, on more platforms."</p>

<p>Silverlight was tried and proven this summer as NBCOlympics.com streamed thousands of hours of live and on-demand online video for the 2008 Beijing Olympics.</p>

<p>For Macintosh users, the Silverlight player will work only on Intel-based Macs, which currently account for roughly three-fourths of Mac units operated by Netflix subscribers.</p>

<p>The Netflix instant watching catalog of more than 12,000 choices continues to grow with significant new titles from CBS, the Disney Channel and Starz Play, which the company announced recently. In addition to watching instantly on the PC and Mac via Silverlight, Netflix members can enjoy the same movies and TV episodes on their television with a Netflix ready device such as the Netflix Player by Roku, which was introduced in May, the LG Electronics BD300 Blu-ray disc player and the Samsung BD-P2550 and BD-P2500 Blu-ray disc players, which are on sale now at retailers nationwide, and, soon, the Microsoft Xbox 360.</p>

<p><br />
<B>About Netflix, Inc.</B></p>

<p>Netflix, Inc. is the world's largest online movie rental service, with more than eight million subscribers. For one low monthly price, Netflix members can get DVDs delivered to their homes and can instantly watch movies and TV episodes streamed to their TVs and PCs, all in unlimited amounts. Members can choose from over 100,000 DVD titles and a growing library of more than 12,000 choices that can be watched instantly. There are never any due dates or late fees. DVDs are delivered free to members by first class mail, with a postage-paid return envelope, from 55 distribution centers nationwide. More than 95 percent of Netflix members live in areas that generally receive shipments in one business day. Netflix is also partnering with leading consumer electronics companies to offer a range of devices that can instantly stream movies and TV episodes to members' TVs from Netflix. For more information, visit http://www.netflix.com/.</p>

