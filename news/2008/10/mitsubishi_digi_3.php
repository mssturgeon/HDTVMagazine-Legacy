				<p class="prtitle">Mitsubishi Digital Electronics America Announces FL6900U High Brightness 1080p Projector for Commercial and Education Applications</p>

<p><B>IRVINE, Calif.--(BUSINESS WIRE)</B>--Mitsubishi Digital Electronics America's Presentation Products Division, known for award-winning, high-quality, high-definition presentation and display products, introduced its FL6900U projector designed for commercial and education installations. At a manufacturer's suggested retail price of only $9,995, Mitsubishi continues to lead the market for high-brightness 1080p projectors at lower price points than most with similar specs.</p>

<p>"Mitsubishi consistently offers high brightness and robust features at price points that are well below the competition, and our FL6900U is no exception," said Wayne Kozuki, product manager, Mitsubishi Digital Electronics America's Presentation Products Division. "It's designed for budget-conscious people who need high brightness and high definition at a reasonable price."</p>

<p>Mitsubishi's FL6900U offers a combination of 4000 lumens with full 1080p high-definition (1920 x 1080 pixels) resolution for commercial venues with high ambient lighting such as sports bars, restaurants, hotel conference rooms, school auditoriums and corporate boardrooms.</p>

<p>The projector provides RS232 support for compatibility with third-party control systems. Installation is straightforward and efficient, with remote-controlled automated horizontal and vertical lens shift, automated zoom and focus and digital keystone correction. Optional lenses (short, long, tele-zoom and rear-projection) allow this projector to be easily installed in a wide variety of venues and applications.</p>

<p>Using three robust 1.1 inch 3LCD inorganic panels that are durable and long-lasting, the FL6900U operates quietly at an approximate 29 decibel level (in low mode) so the audience can concentrate on a presentation rather than listen to a loud projector. It also provides estimated lamp life of up to 4000 hours (in low mode).</p>

<p>The FL6900U can create side-by-side images for enhanced video conferencing applications that include a live video feed and simultaneous presentations on the same screen, making presentations more captivating and dynamic. Blasting 4000 ANSI lumens, the projector is also perfect for large venues where ambient light can be a factor. It offers RJ45 networking support for easy online management and control.</p>

<p>With a built-in motion-sensitive anti-theft alarm, Mitsubishi's FL6900U is designed to deter projector theft from public areas such as classrooms, auditoriums or other open-access conference room settings. The motion detector is built into the connector panel cover, and is set manually by a key. Once the cover is installed and the safety key removed, the projector's alarm is automatically set. If the projector is moved, a loud (estimated 120 decibels), attention-grabbing alarm will sound to deter projector thefts.</p>

<p>The projector also uses a menu password lock for additional security as well as a splash screen to show ownership or location.</p>

<p>"Mitsubishi strives to fit the needs of our dealers and our end-users," said James Chan, director, product marketing, Mitsubishi Digital Electronics America's Presentation Products Division. "Adding the FL6900U to our product line-up provides even more flexibility for installations that require high brightness 1080p performance."</p>

<p><br />
<B>Pricing, Availability, Warranty</B></p>

<p>Mitsubishi's FL6900U will be available this month at a suggested retail price of $9,995 through authorized Mitsubishi dealers. The projector comes with Mitsubishi's three-year limited warranty on parts and labor plus a one-year limited warranty on the original lamp.</p>

