<center><i>2008 Fall Meet Will Be Available in Both Standard Definition and HD</i></center><br />
<br />

<p><B>LOUISVILLE, Ky.--(BUSINESS WIRE)</B>--Churchill Downs will become the first racetrack in the United States to offer simulcasting in high definition ("HD") when it opens its 2008 Fall Meet on Sunday, Oct. 26. The HD signal will be rolled out progressively to select off-track betting locations ("OTBs") and racetracks across the nation, as well as on-track in a variety of public areas.</p>

<p>"Churchill Downs is delighted to take the lead on this innovation and bring to our customers across the country the unparalleled quality and clarity that high definition provides," said Tom Jenkins, vice president for Churchill Downs Incorporated. "From the day this technology upgrade was proposed, our goal was to focus on the end-user experience. We wanted to ensure that our customers, whether on-track or at simulcasting outlets, could enjoy the experience of high-definition racing from Churchill Downs, and that goal will become a reality on opening day of our 2008 Fall Meet."</p>

<p>Churchill's high-definition simulcast will present live racing in full 16:9 HD format, offering customers a larger and clearer view of the race itself. In addition, on-screen graphics and racing information will be presented in high definition within the 16:9 format, allowing for additional and enhanced wagering information for both the on-track and simulcasting customer. More than 100 HDTVs on-track at Churchill Downs will benefit from the high-definition signal. Those televisions will be spread throughout the facility in both luxury seating locations and areas open to the general public. Locations include the Silks and Champions Club Lounges near the ITW area, the Jockey Club and first-floor Jockey Club, the Turf Club, Gold Rooms 2 and 6, the Finish Line Suites lobby, and the Directors, Stakes and Aristides Rooms inside the clubhouse. The televisions will be marked with signage to help customers identify and enjoy the HD experience.</p>

<p>Churchill Downs is also working with select OTBs and racetracks across the country to provide the technology needed to take advantage of high-definition simulcasts. Installation of the necessary components is currently underway, and a full list of locations offering the Churchill meet in HD will be forthcoming.</p>

<p>The 2008 Fall Meet at Churchill Downs will also be offered in a typical standard-definition format for facilities without HD technology in place.</p>

<p>"Today's announcement is just the first step in what we hope will be a continuing process of HD upgrades, expansions and improvements for our customers," Jenkins added. "We're also open to any interest from other simulcast outlets that may want to offer the Churchill Downs signal in high definition. We're looking forward to receiving and acting upon feedback from our customers to continue improving their experience at the races."</p>

<p>For nearly a year, Churchill Downs has worked with several technology providers to make its high-definition transition possible. Key among those is Roberts Communications Network, which helped devise a system to deliver HD simulcasts to OTBs in a manner that works with their existing television infrastructure. Two other major providers are International Sound Corp., which will provide the new high-definition graphics package with enhanced wagering information, and Thomson Grass Valley, which was chosen to provide the Kayak digital video production switcher and LDK 4000 mk II high-definition camera.</p>

<p>Churchill Downs, the world's most legendary racetrack, has conducted Thoroughbred racing and presented America's greatest race, the Kentucky Derby, continuously since 1875. Located in Louisville, the flagship racetrack of Churchill Downs Incorporated (NASDAQ Global Select Market: CHDN) also operates Trackside at Churchill Downs, which offers year-round simulcast wagering at the historic track. Churchill Downs will conduct the 135th running of the Kentucky Derby on May 2, 2009. The track's 2008 Fall Meet runs from Oct. 26 through Nov. 29. Churchill Downs has hosted the Breeders' Cup World Championships a record six times, and will host the international racing event again on Nov. 5 and 6, 2010. Information about Churchill Downs can be found on the Internet at www.churchilldowns.com. </p>
