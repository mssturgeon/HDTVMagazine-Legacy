<p><B>LOS GATOS, Calif. and RIDGEFIELD PARK, N.J., Oct. 23 /PRNewswire-FirstCall/</B> -- Netflix, Inc. (NASDAQ:NFLX) , the world's largest online movie rental service, and Samsung Electronics America, a market leader and award-winning innovator in consumer electronics, today announced a broad partnership to offer consumers the ability to instantly stream movies and TV episodes from the Netflix Web site directly to their living rooms via Samsung's BD-P2500 and BD-P2550 Blu-ray disc players. The companies also said they are collaborating to enable Samsung to integrate instant streaming from Netflix into a range of home entertainment products.</p>

<p>The BD-P2550 and BD-P2500 are currently available at $399.99. Consumers who already own one of these Samsung players can upgrade their device at no additional cost to enable instant streaming from a growing library of more than 12,000 movies and television episodes from Netflix. The upgrade is available at http://www.samsung.com/bluraysupport.</p>

<p>Instantly streaming movies and TV episodes from Netflix on the BD-P2550 and BD-P2500 is done through a wired broadband connection and a Netflix Queue-based user interface. Netflix members visit the Netflix Web site to add movies and TV episodes to their individual instant Queues. Those choices will automatically be displayed on members' TVs and available to watch instantly through the Samsung players. Once selected, movies will begin playing in as little as 30 seconds. With the players' accompanying remote control, Netflix members will be able to browse and make selections right on the TV screen and also have the ability to read synopses and rate movies. In addition, they will have the option of fast-forwarding and rewinding the video stream.</p>

<p>Samsung's Blu-ray players offer Full HD 1080p playback and feature the award-winning HQV(TM) processing chip for the highest quality viewing of Blu-ray discs and astounding upconversion of standard DVDs. The players also provide a truly immersive HD home theater experience with capabilities to decode high-resolution multi-channel digital audio soundtracks and 7.1-channel analog audio outputs.</p>

<p>"Samsung has been at the forefront of innovation in consumer electronics and has established a market leadership position in Blu-ray and digital television," said Netflix Co-Founder and Chief Executive Officer Reed Hastings. "We're excited about the upgraded Blu-ray disc players. Moreover, we look forward to working with Samsung in the years to come to deliver a variety of outstanding products on which consumers can watch movies delivered over the Internet from Netflix."</p>

<p>"In its new form, Samsung Blu-ray players become the ultimate content delivery box, combining on-demand access to movies and jaw-dropping Full HD viewing," said Reid Sullivan, Vice President of Marketing, Audio/Video & Imaging at Samsung Electronics America. "Samsung presents a new value proposition for Blu-ray players by positioning it as a portal to a world of engaging digital content, be it Blu-ray discs, movies from Netflix or other online content."</p>

