<p><B>Taipei, Taiwan----October 13, 2008</B>----CyberLink Corp. (5203.TW), innovative solution provider for the connected digital lifestyle, today announced the release of CyberLink Media Server 2 and CyberLink SoftDMA 2, home networking applications for remotely accessing and sharing high-definition videos, photos, and music throughout the digital home.</p>

<p>Media Server turns a home PC into a network server for digital video, photo, and music content, which can be accessed and played by media players-such as SoftDMA-that are connected across a DLNA/UPnP network. Media Server, which is certified for the DLNA 1.5 logo, supports file transcoding, features admission controls, and includes quality of service (QoS) technology for optimizing playback quality.</p>

<p>SoftDMA allows the streaming of digital video, photo, and music content by automatically locating media servers connected to a user's network. New features allow the downloading of files across a network to the local hard drive, as well as the playback of high-definition content.</p>

<p>"CyberLink's digital home strategy is about allowing consumers to access their content remotely: anywhere and anytime they like," said Alice H. Chang, CEO of CyberLink. "The latest versions of Media Server and SoftDMA improve the quality of the experience, through support for high-definition video, by allowing the downloading of files, and by incorporating Quality of Service technology to deliver the best performance for available bandwidth."</p>

<p>CyberLink Media Server 2:<br />
Media Server is an application that enables streaming of media over a digital home network. Key features include:</p>

<p>    * Automatic detection of players connected to a home network<br />
    * Streaming of high-definition video content across a network<br />
    * Quality of Service (QoS) technology to optimize playback quality for the available bandwidth<br />
    * Transcoding of video formats to make the most of available bandwidth and ensure compatibility with a wide selection of players<br />
    * Access control for denying unauthorized access to media files<br />
    * Admission controls to avoid overloading the network with too many media players requesting access to content<br />
    * DLNA 1.5 logo certification ensures compatibility with media players including CyberLink SoftDMA, Sony&reg; PLAYSTATION&reg; 3, and Microsoft&reg; Xbox 360&reg;.</p>

<p>CyberLink SoftDMA 2:<br />
SoftDMA is a software-based digital media adapter (DMA) for playing media files streamed across a digital home network. Key features include:</p>

<p>    * Automatic detection of media servers connected to a home network<br />
    * Playback of high-definition video, photo and audio formats streamed across a network, including MPEG-4 H.264 (AVC) video and AAC audio<br />
    * Compatibility with DLNA certified servers, including CyberLink Media Server, Windows Media Connect, and Windows Media Player 11<br />
    * Downloading of content from a network server to a local hard drive for playback on the go<br />
    * Quality of Service (QoS) technology to deliver the best playback performance for available bandwidth (working with CyberLink Media Server 2)<br />
    * Remote operation as a Digital Media Renderer (DMR) when controlled by a Digital Media Controller (DMC).</p>

<p>CyberLink SoftDMA 2 and Media Server 2 are currently available in 9 languages as OEM products. For more information about SoftDMA, Media Server, or CyberLink's full range of software, please visit www.cyberlink.com .</p>

