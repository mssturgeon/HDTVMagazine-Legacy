<p><B>NEW ORLEANS, Oct. 15 /PRNewswire/</B> -- This week at its annual Fall Member Meeting in New Orleans, La., Internet2 together with several collaborators will showcase the first uncompressed high-definition videoconference application over revolutionary dynamic circuit networks (DCN). The demonstrations will highlight the promise of DCN and high-definition video technology to create the ultimate collaboration environment that can support new innovation in science, research, the arts, telemedicine and beyond.</p>

<p>"The Internet2 community is deploying dynamic circuit networks to empower its users with the ability to self-provision dedicated point-to-point optical circuits on demand for applications that require very reliable high capacity connections for short intervals of time," said Rob Vietzke, Internet2 executive directornetwork services. "Uncompressed high-definition video is a natural fit for DCN as it requires about 1.5 gigabits of dedicated capacity to create a real-life, real-time visually stunning video experience."</p>

<p><br />
<B>iHDTV(TM) Demo</B></p>

<p>On October 15, Ed Seidel, director of the office of cyberinfrastructure at the National Science Foundation (NSF) will host a live tour of the Large Hadron Collider (LHC) Control Center in France and will moderate a virtual Q&A with Jim Virdee, spokesperson for the LHC's CMS detector - one of six detectors at the LHC; Jim Strait, Accelerator Physicist at Fermi National Accelerator Laboratory and Harvey Newman, professor of physics at the California Institute of Technology.</p>

<p>Also known as the "Big Bang Machine," the LHC, located in Geneva, Switzerland is the world's largest particle accelerator. It will produce over 15 million gigabytes of data annually, which scientists around the world hope will yield valuable insights into the origins of mass and matter. The LHC community was a primary driver for the development of DCN services and is actively deploying the technology in anticipation of their massive data transfer needs when the LHC begins operation in 2009.</p>

<p>The demo will showcase the use of iHDTV(TM) software. Developed by the ResearchChannel and the University of Washington, iHDTV will be used to stream uncompressed 1080i high-definition video between the conference floor in New Orleans and LHC's Control Center at CERN in Prevessin, France. The technology interoperates internationally across three DCN network domains including the Louisiana Optical Network Initiative (LONI), Internet2 and US LHCNet.</p>

<p>"New dynamic networking, as well as advanced video technology being pioneered by the research and education community, will play a critical role in supporting the next wave of scientific collaboration and discovery," said Dr. Ed Seidel, director of the office of cyberinfrastructure for the National Science Foundation. "I'm gratified to see such an impressive display of video technology using advanced dynamic circuit networks -- both of which are important to our nation's cyberinfrastructure in providing a truly collaborative foundation for new discovery."</p>

<p>The session will be netcast and archived for worldwide viewing: http://events.internet2.edu/2008/fall- mm/sessionDetails.cfm?session=10000236&event=911 (Due to length of URL, please copy and paste into browser).</p>

<p>A video explaining the importance of cyberinfrastructure to supporting LHC, can be viewed via: http://www.internet2.edu/lhc.</p>

<p><br />
<B>UltraGrid demo</B></p>

<p>On October 16, Internet2 and its partners will highlight the use of UltraGrid high-definition video technology. Initially developed via a NSF grant to University of Southern California/Information Sciences Institute, the UltraGrid application has is now primarily developed by the Laboratory of Advanced Networking Technologies at Masaryk University in Brno, Czech Republic and is supported by CESNET.</p>

<p>The technology will link Louisiana State University Professor Thomas Sterling to students located in Brno, Czech Republic to showcase how advanced virtual collaboration technology can revolutionize the global educational environment. The video will also utilize international DCN connections across multiple circuit domains including LONI, Internet2 and the GEANT2 AutoBAHN networks.</p>

<p>"Next-generation high-definition videoconferencing provides an impressive environment to connect students from around the world to subject matter experts they may not otherwise have access to at their home institution," said Charlie McMahon, Deputy CIO for Research Enablement, LSU. "While we have been using video technology for some time over IP networks, the use of dedicated facilities via dynamically switched networks provides us the capacity we need to make the visual experience that much more life like."</p>

<p>The data for the UltraGrid demo will be distributed by application-level modular programmable UDP packet reflectors that have been developed over the past five years by CESNET and Laboratory of Advanced Networking Technologies. This technology allows for independence on network-native multicast, while it is possible to process the data in per-user specific way.</p>

<p>The session will be netcast and archived for worldwide viewing: http://events.internet2.edu/2008/fall- mm/sessionDetails.cfm?session=10000237&event=911 (Due to length of URL, please copy and paste into browser).</p>

<p>Both iHDTV and UltraGrid technologies are under active development by the research and education community. Through the iHD DevCore partnership, the community is currently investigating how to create interoperability between these platforms to enable more widespread adoption of uncompressed high- definition video technology.</p>

<p>The Internet2 community extends a special tribute to the recently deceased Michael Wellings of the ResearchChannel at the University of Washington. Michael was a pioneer in developing the advanced iHDTV technology used for the October 15 demo and inspired the research and education community to imagine broad use of high-definition video as a fundamental enabler of advanced research collaboration.</p>

