				<p class="prtitle">PANASONIC ANNOUNCES ARRIVAL OF FIRST TRU2WAY&trade; HDTVs AT RETAIL</p>

<center><i>Consumers In Chicago And Denver Will Be First To Experience Comcast's Video On Demand Without A Set-Top Box

<p>Panasonic Tru2way-Enabled VIERA Plasma HDTVs To Go On Sale In Late October At Abt Electronics, Ultimate Electronics and Circuit City Stores</i></center><br /><br />
<br /></p>

<p><B>CHICAGO, IL (October 15, 2008)</B> - Panasonic (NYSE: PC), the consumer electronics industry leader in the development and application of tru2way technology, and Comcast Corporation (NASDAQ: CMCSA, CMCSK), the nation's leading provider of entertainment, information and communications today announced the arrival of the first tru2way VIERA HDTVs at Abt Electronics in Glenview, IL and officially declared the tru2way platform active in Chicago and Denver. </p>

<p>Tru2way technology is being used to create a common software platform that will enable cable companies, consumer electronics companies, content developers, network programmers and others to extend interactivity to the TV set and other kinds of devices.  The new Panasonic VIERA HDTVs are built with tru2way technology inside, enabling consumers to access two-way digital cable programming, like video on demand, without a cable operator-supplied set-top box.  Panasonic and Comcast have worked together to lead the development and deployment of tru2way technology and related products which are based upon specifications developed by CableLabs&reg;, the industry's research and development arm. </p>

<p>"The arrival of the first tru2way HDTVs at retail combined with Comcast's activation of its first tru2way head ends are among the most significant milestones in the cable industry and are a huge win for consumers," said Dr. Paul Liao, Chief Technology Officer, Panasonic Corporation of North America.  "At the May 2008 Cable Show, we stated with great confidence that the first tru2way HDTVs would be available for consumer purchase at retail by fall 2008.  We are especially delighted to have partnered with Comcast and CableLabs to make good on that promise and bring the benefits of open networks to cable subscribers."</p>

<p>Comcast customers in the Chicago and Denver areas will be the first in the U.S. to have access to tru2way digital cable service with additional cities expected to go live in the coming months. The tru2way VIERA HDTVs will be available in the Chicago area at Abt Electronics in Glenview and at Circuit City locations as well as at Ultimate Electronics and Circuit City stores in the Denver area.</p>

<p>"We see tru2way technology as the gateway for our customers to experience the next generation of interactive television, and our work with Panasonic to develop and support the first fully digital-cable-ready HDTVs is an important first step in making that happen," said Mark Hess, Comcast's Senior Vice President of Video Product Development.  "This common platform also will let us develop an exciting array of interactive services and applications that we can deliver on our advanced fiber network to a variety of consumer electronics devices."</p>

<p>Added Dr. Richard R. Green, President and CEO of CableLabs, "We are delighted to see the arrival of Panasonic tru2way products in the marketplace.  As tru2way technology is adopted by operators like Comcast nationwide, consumers can be confident that exciting new interactive digital cable products and services from innovative companies such as Panasonic will work seamlessly with any cable network that supports OpenCable specifications nationwide."</p>

<p>Panasonic's first tru2way enabled VIERA Plasma HDTVs will be offered in 42-inch class and 50-inch class sizes with integrated tru2way cable receiver capability within the set's chassis. </p>

<p>The TH-42PZ80Q and TH-50PZ80Q will be extensions of Panasonic's critically acclaimed VIERA PZ80 series of 1080p Plasma HDTVs.  The TH-42PZ80Q will have an SRP of $1,599.95 and the TH-50PZ80Q will have an SRP of $2,299.95.  These tru2way HDTVs will allow consumers to access all digital cable services such as electronic program guides and the full range of interactive and video-on-demand programming - all accessible directly via the television's remote control - without the costs or clutter associated with a traditional external cable set-top box. </p>

<p>In addition to tru2way technology, the VIERA TH-42PZ80Q and TH-50PZ80Q feature 480Hz Sub-field Drive for sharp motion image focus, 1,000,000:1 Dynamic Contrast Ratio, VIERA Link and a built-in SD Memory Card reader for playing back digital photos. VIERA Link allows the consumer to operate all VIERA Link equipped components with a single remote. </p>

