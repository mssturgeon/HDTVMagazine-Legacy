<p><B>Santa Clara, CA, October 2, 2008</B> -- VUDU Inc., a leading provider of digital technologies and services that deliver Internet entertainment to consumers' HDTVs and Home Theaters, today unveiled HDX, a groundbreaking video format that for the first time enables the viewing of Internet-delivered movie content in full High Definition 1080p format that is optimized for 40 inch and larger HDTVs and Home Theaters.</p>

