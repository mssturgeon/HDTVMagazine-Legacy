<p><B>IRVINE, Calif., Oct. 28 /PRNewswire/</B> -- Mitsubishi Digital Electronics America, Inc. today announced the beginning of the laser era and the immediate availability of the world's first, laser-powered television. The Mitsubishi LaserVue(TM) 65" model is now being sold for $6,999 at select specialty retailers nationwide. After months of anticipation, many consumers nationally have already purchased LaserVue and have had the rare opportunity to experience the amazing breadth and depth of color that laser television offers. LaserVue has been introduced as the most energy efficient large-format, high-definition television available on the market today. LaserVue not only delivers two times the color(1) of many of today's HDTVs, but it also uses exponentially less power(2) than LCD and plasma TVs.</p>

