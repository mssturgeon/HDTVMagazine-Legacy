<p>LaserVue is also equipped with 3D-ready(3) viewing capabilities, demonstrating Mitsubishi's foray into bringing a true "Hollywood" entertainment experience to the consumer. At 10 inches thin, LaserVue TV has been designed for both floor stand and wall-mount applications and features a full stereo range of sound capabilities with integrated speakers.</p>

