<p><B>Santa Clara, CA, October 2, 2008</B> -- VUDU Inc., a leading provider of digital technologies and services that deliver Internet entertainment to consumers' HDTVs and Home Theaters, today unveiled HDX, a groundbreaking video format that for the first time enables the viewing of Internet-delivered movie content in full High Definition 1080p format that is optimized for 40 inch and larger HDTVs and Home Theaters.</p>

<p>HDX delivers the highest quality available from any Internet, broadcast, cable, or satellite on-demand service, offering consumers a true cinematic experience with a vividly detailed and virtually artifact free picture accompanied by high-resolution, immersive sound. HDX movies are available today to all VUDU customers and the new HDX format does not cost VUDU viewers a penny extra - since HDX films are offered at the same price as standard HD titles.</p>

<p>VUDU has already compiled a library of more than 50 films available now in the new HDX format and will be offering every newly released HD title in the new format. VUDU will also be encoding into HDX many of the HD movies in the existing VUDU catalog, offering consumers a quickly growing library of  HDX content.  With this new offering, VUDU is the only Internet movie delivery service offering consumers a choice between an instant-start HD experience and a high quality HD download version.</p>

<p>"VUDU HDX truly raises the bar on picture quality for HD movies delivered on demand, over the air, satellite or Internet and across the entire video landscape," said Mark Jung, CEO of VUDU. "Accelerating consumer adoption of large screen HDTVs has fueled strong demand for the kind of viewing experience and picture quality only HDX can deliver."</p>

<p>VUDU HDX is being introduced at a time when technology advances and rapidly declining prices have driven explosive growth in the larger than 40 inch HDTV segment. The same forces have led to rapidly increasingly penetration of 1080p full high definition TVs.  Consumers who buy these large screen HDTVs and Home Theaters are demanding higher and higher picture quality and want the convenience of Internet delivery. </p>

<p>HDX displays content in the true cinematic gold standard of 1080p at 24 frames per second. Content in HDX is displayed at twice the resolution of other Internet HD formats and offers an ultra-detailed and virtually artifact free picture on any size screen. HDX also offers the best available surround sound quality for Internet delivered movies with immersive, high resolution sound at a 40 percent higher bit-rate than standard surround sound DVD's.</p>

<p>VUDU's unique TruFilm&trade; technology is at the core of the HDX's groundbreaking picture quality. TruFilm technology optimizes the encoding, transmission, and display of HDX movies on HDTVs and larger Home Theater screens using the following technologies:</p>

<ul><li><b>Psychovisual Processing</b> - Improves picture quality by enhancing details in dark areas of the picture, virtually removing the dark area artifacts typical of Internet movies.</li><li><b>Film Grain Preservation</b> - Improves the cinematic experience by ensuring that the displayed picture remains true to the fine optical texture of the original film.</li><li><b>Statistical Variable Bitrate</b> - Ensures optimal video quality throughout the film by allocating a higher encoding budget to high detail and high motion segments of the film, while preserving the ability to stream it over the Internet.</li><li><b>Color Gradient Processing</b> - A unique technology used to tune the picture for optimal display on modern LCD and Plasma televisions.</li></ul>

<p>HDX movies are available to rent at the same price as VUDU's instant HD movies.   Consumers can order HDX movies directly on their VUDU or online at www.vudu.com/movies with delivery times expected to take a few hours, depending on content.  VUDU will continue to offer HD titles in both HDX and instant HD formats, affording consumers the choice of ordering ahead the highest available quality movie or renting HD movies that are delivered instantly to their TV. </p>

