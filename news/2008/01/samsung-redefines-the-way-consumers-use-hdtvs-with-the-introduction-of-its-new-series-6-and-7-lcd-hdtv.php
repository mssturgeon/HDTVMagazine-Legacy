<p>Samsung's LCD HDTV lineup will be on display at Booth #11033 during the International Consumer Electronics Show held at the Las Vegas Convention Center, January 7 through 10.</p>

<p>"With the application of TOC design to the Series 6 and 7 HDTVs, Samsung is truly changing the look of TVs and introduces a visual appeal that will make it the centerpiece of any living room," said Jonas Tanenbaum, vice president of Flat Panel Marketing at Samsung Electronics America. "Featuring multifunctional connectivity, the Series 6 and 7 deliver an experience that goes well beyond traditional content viewing. Users can now connect and utilize the data stored on a variety of digital devices, turning their HDTV into a media hub. It is a whole new way of seeing and using HDTVs."</p>

<p><br />
<B>Series 6 Full HD LCD TV</B></p>

<p>Samsung's Series 6 marks the first appearance of TOC (Touch of Color) design in the 2008 LCD HDTV line-up. Inspired by designs from the automotive and fashion industries, Samsung's new molding process creates a clean, smooth finish infused with a hint of a translucent color during the manufacturing process.</p>

<p>Utilizing the award-winning technologies found in all Samsung HDTVs, the Series 6 delivers unparalleled picture quality. Samsung's Super Patterned Vertical Alignment (SPVA) panel provides a 178-degree viewing angle from all four axes as well as overall picture improvements in LCD panel technology. Samsung's Full HD (1080p) panel uses a new high-speed liquid crystal to cut response time to 4ms. The fast response time, coupled with Samsung's Auto Motion Plus 120Hz&trade; motion blur reduction technology dramatically reduces motion blur and judder-making the set ideal for playing video games and watching action sports.</p>

<p>Additionally, the Series 6 features the latest version of Samsung's breakthrough super clear panel technology, making colors appear more vibrant and blacks even deeper. With the addition of enhanced films, glare is reduced and off-angle viewing has been optimized. The total package gives gamers, sports fans and movie buffs superb viewing quality for the applications they demand and use most.</p>

<p>To make the Series 6 a true entertainment hub for any home, Samsung has incorporated advanced HD connectivity and networking capabilities that expand the HDTV's functionality. A wide variety of multimedia devices can be connected to the set through any one of the four Simplay compliant HDMI 1.3 inputs (including one on the side). Once connected, users can easily access device menus and manage and display content through the newly redesigned Wheel Key Remote control and the HDTV's sophisticated content management interface.</p>

<p>The Series 6 Full HD LCD TVs will be available in March of 2008 in the following sizes: 40-inches, 46-inches and 52-inches (Model numbers LN40A650T, LN46A650T, LN46A650T and LN52A650T).</p>

<p><br />
<B>Series 7 Full HD LCD TV</B></p>

<p>Building on the superior technologies and features found in the Series 6, the Series 7 takes networking and multimedia management to a whole new level. Consumers can easily enjoy MPEG and JPEG files stored on external devices by connecting through a side-mounted USB 2.0, turning their LCD into a full-scale home viewing gallery, or connect their MP3 players for a dynamic audio experience.</p>

<p>Additionally, the Series 7 features internal flash memory loaded with premium content to enjoy right out of the box, as well as an integrated woofer for an enhanced audio experience.</p>

<p>The 750 LCD HDTVs will be available in May of 2008 in the following sizes: 40-inches, 46-inches and 52-inches (Model numbers LN40A750T, LN46A750T and LN52A750T).</p>

