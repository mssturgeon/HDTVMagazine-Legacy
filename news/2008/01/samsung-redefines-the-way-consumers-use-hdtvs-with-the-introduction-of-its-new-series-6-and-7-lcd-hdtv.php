<p><B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics, the market leader in HDTV design and innovation, is redefining the role HDTVs play in the home with its forward-looking LCD HDTV Series 6 and 7. Not only is picture quality dramatically enhanced, but an elegant new design born from Samsung's extensive R&D in the automotive and fashion industries brings a never-before-seen "Touch of Color" to any living room or home theater. Samsung's TOC (Touch of Color) design features a hint of amber color naturally blended into Samsung's traditional piano black bezel frame.</p>

