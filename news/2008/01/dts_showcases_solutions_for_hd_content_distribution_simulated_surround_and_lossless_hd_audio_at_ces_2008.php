<p><B>AGOURA HILLS, Calif.--(BUSINESS WIRE)</B>--DTS, Inc. (NASDAQ: DTSI) returns to main floor of the 2008 Consumer Electronics Show (CES), January 7-10, Booth # 21913, South Hall, Las Vegas Convention Center, with breakthrough demonstrations of its new DTS Surround Sensation&trade; simulated surround sound technologies, innovative high definition content distribution partnership news with XStreamHD&trade;, as well as new developments in its highly regarded DTS-HD Master Audio&trade; technology (common to both Blu-ray Disc and HD DVD next generation optical disc standards). At CES, the company will be showcasing its offerings for the consumer electronics, personal computing, and digital content distribution marketplaces including live A/B demonstrations of DTS Surround Sensation headphone technology. The company will also distribute its new Blu-ray Disc and HD-DVD movie / music discs featuring DTS-HD Master Audio&trade; throughout the show.</p>

<p>"Our first year on the CES show floor last year was an overwhelming success, and this year we are pleased to be highlighting our ever-widening array of audio solutions for the consumer electronics marketplace," said Brian Towne, Senior Vice President & General Manager, Consumer Division at DTS. "DTS will underscore the rapid expansion of DTS-HD Master Audio into mainstream AV products, and celebrate its entry into the digital content distribution space. Additionally, the launch of DTS Surround Sensation will set a new bar for high performance surround experience in a wide variety of entertainment products. This is a very exciting time for DTS."</p>

<p>At CES 2008, DTS will feature:</p>

<p> * Next generation A/V receivers, as well as HD DVD and Blu-ray Disc players featuring lossless DTS-HD Master Audio, from Pioneer, Onkyo, Denon, Samsung, Yamaha and others.<br />
 * Live "A/B" demonstrations of DTS' new Surround Sensation headphone technology (simulated surround sound via two-channel speaker sources.)<br />
 * Prototype PC software products featuring DTS Surround Sensation technology.<br />
 * XStreamHD for digital delivery of movies and music featuring lossless 7.1-channel DTS-HD Master Audio with HD 1080p-quality video.<br />
 * New PC software products featuring DTS-HD Master Audio.<br />
 * DTS point-of-sale and informational videos.</p>

<p>DTS will also distribute its new 2008 Blu-ray Disc and HD DVD demonstration discs. Available only to CES attendees at the DTS booth, the discs feature select movie and music clips that showcase DTS-HD Master Audio, and are produced in stunning 1920 x 1080p high definition video resolution. The demo discs include several tracks featuring DTS-HD Master Audio in 7.1 channels, as well as feature film clips including Hairspray, Night At The Museum and The Italian Job, and music videos from BT, Black Crowes, Pixies and The Who.</p>

