<B>About XStreamHD</B></p>

<p>XStreamHD is leading an HD revolution, setting a new standard for the delivery and distribution of Full HD entertainment throughout the home. Privately funded and five years in the making, XStreamHD is led by George Gonzalez, a recognized pioneer in broadband and satellite communications. Mr. Gonzalez's previous company, iDirect, developed the world's premier bi-directional satellite broadband router. XStreamHD's executive team and board of directors include veterans of the Fortune 500 who have been instrumental in shaping the television, entertainment, telecom, and consumer markets. At CES 2008, XStreamHD will unveil the first-ever transport network to deliver Full HD video and 7.1 channels of lossless audio directly to the home via satellite, offering unprecedented quality and convenience. For more information, visit www.XStreamHD.com or call +1 (703) 852-1300.</p>

