<p><B>LOS GATOS, Calif. and ENGLEWOOD CLIFFS, N.J., Jan. 3 /PRNewswire-FirstCall/</B> -- Netflix Inc. (NASDAQ:NFLX) , the world's largest online movie rental service, and LG Electronics, a global consumer electronics leader, today announced they are joining forces to develop a set-top box for consumers to stream movies and other programming from the Internet to HDTVs -- bypassing the need to use a personal computer.</p>

<p>The collaboration is expected to deliver a compelling new online home entertainment service via technology embedded in an LG networked player planned for the second half of 2008. Today's announcement sets the stage for next week's 2008 International Consumer Electronics Show (CES(R)), which will emphasize digital content as well as hardware solutions.</p>

<p>"Consumers crave compelling and immediate content, and the Netflix online streaming movie feature can provide instant gratification. This alliance underscores LG's goal of developing smart technologies that deliver flexibility, convenience and control to consumers," said KI Kwon, President of the Consumer Electronics Division of LG Electronics USA, Inc.</p>

<p>The technology collaboration supports the Netflix core strategy of offering a multi-dimensional, or "hybrid," service that gives its more than 7 million members a variety of ways to receive movies and TV series for one, low monthly fee.</p>

<p>With the availability of the networked LG product planned for later this year, Netflix subscribers can watch movies streamed from the Netflix Web site on their large-screen home theater HDTVs, in addition to the current capability to watch movies instantly on their PCs.</p>

<p>On top of its rich catalog of more than 90,000 titles on DVD delivered fast through the mail, a growing selection of more than 6,000 familiar movies and TV episodes delivered instantly over the Internet to Netflix members' personal computers or TVs will even more strongly position Netflix in online movie rentals, which it pioneered in 1997.</p>

<p>"Internet to the TV is a huge opportunity," said Netflix Founder, Chairman and CEO Reed Hastings. "Netflix explored also offering its own Netflix-branded set-top boxes but we concluded that familiar consumer electronics devices from industry leaders like LG Electronics are a better consumer solution for getting the Internet to the TV."</p>

<p>In all, today's announcement enhances LG Electronics' position as a top-tier player in the U.S. digital television marketplace and advances the Netflix goal of making electronic delivery -- including future high definition content -- a meaningful addition to its existing DVD delivery platform and a valued enhancement to the Netflix subscriber experience. Netflix took its first step in that direction in 2007 when it enabled members to instantly watch movies and TV series on their personal computers.</p>

