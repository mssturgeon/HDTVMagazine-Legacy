				<p class="prtitle">AMD Unleashes the ATI Radeon&trade; HD 3400 and ATI Radeon&trade; HD 3600 Series, Delivering Leading-Edge Graphics Technology With Full Support for DirectX&reg; 10.1, PCI Express&reg; 2.0 and DisplayPort&trade;</p>

<center><i>Both Next-Generation Series of Graphics Processors Built on 55nm Process Technology, Available for Under $100 SEP</i></center><br />
<br />

<p><B>SUNNYVALE, Calif.--(BUSINESS WIRE)</B>--AMD (NYSE:AMD) today announced the introduction and availability of the ATI Radeon&trade; HD 3400 and ATI Radeon&trade; HD 3600 series, the leading-edge entry-level and mainstream graphics processors (GPU) in the ATI Radeon&trade; HD 3000 series. Ranging in price from USD $49-$65 suggested e-tail pricing (SEP) for the ATI Radeon HD 3400 series and USD $79-$99 SEP for the ATI Radeon HD 3600 series1, the new graphics solutions deliver unmatched value to the consumer. Both series continue to advance AMD's leadership by delivering display connectivity through DisplayPort&trade; integrated into the GPU2, allowing AMD to exceed current manufacturing expectations in the industry. As part of the first family of graphics cards built using 55nm process technology3, both series provide exceptional performance-per-watt for a quiet and power-efficient experience at unbelievable price points.</p>

<p>Blu-ray or HD DVD disc playback can be enjoyed in full HD glory (1080p)4 thanks to AMD's proprietary unified video decoder (UVD) technology found on the ATI Radeon HD 3400 and ATI Radeon HD 3600 series, ensuring movies play back smoothly and with incredible detail. Immersive home theater environments can be created using the built-in support for six-channel (5.1) Dolby Digital&reg; surround audio transmission through HDMI. In addition, the ATI Radeon&trade; HD 3450 will support fully silent (passive) cooling, delivering the ideal solution for home theater PCs.</p>

<p>"With the ATI Radeon HD 3400 and ATI Radeon HD 3600 series, AMD is delivering outstanding graphics performance to the mainstream," said Rick Bergman, senior vice president, AMD Graphics Products Group. "AMD is leading the industry by delivering top-to-bottom DirectX&reg; 10.1 support with modular graphics capabilities for easy upgradeability. It's part of our commitment to deliver The Ultimate Visual Experience&trade; to more users than ever before."</p>

<p>AMD continues its display leadership with both series by offering the world's first GPUs with integrated DisplayPort support. DisplayPort offers twice the bandwidth of DVI, and is poised to deliver low-cost high resolution and bit-depth panels.</p>

<p>"Dell and AMD have been leaders in driving the DisplayPort standard since its inception," said Bruce Montag, office of the CTO, Dell. "AMD is demonstrating its technology leadership with the introduction of dual integrated DisplayPort capability in the ATI Radeon HD 3400 and ATI Radeon HD 3600 series graphics."</p>

<p>Gamers looking for graphics processors that allow for further scalability will find that both series boast ATI CrossFireX&trade;, which delivers the option of multi-GPU upgradeability. ATI Hybrid Graphics will allow users to combine an ATI Radeon&trade; HD 3400 GPU with a compatible AMD 7-Series chipset to provide exceptional 3D performance as part of the upcoming AMD mainstream high-definition "Cartwheel" codenamed desktop platform, adding further value to the gaming experience. With support for Microsoft&reg; DirectX 10.1 support, gamers can play the top HD games with life-like 3D graphics, stunning realism, and great shading effects. Full support for PCI Express&reg; 2.0 technology allows for twice the throughput of current PCI Express cards5, which means gamers will be ready for demanding graphic applications.</p>

<p>The ATI Radeon HD 3400 and ATI Radeon HD 3600 series have already enjoyed broad customer adoption and are designed into a significant number of major OEM mainstream and entry-level PCs scheduled to be shipped in 2008.</p>

<p>The official launch event, highlighting both series in depth, will be held in Beijing, China on Wednesday, January 23, 2008.</p>

