				<p class="prtitle">HANA Demonstrates Integrated Home HD Networking at CES 2008</p>

<center><i>Consumers Benefit from Simple "One Cable / One Remote" Networking Solution</i></center><br />
<br />

<p>2008 International CES<br />
North Hall Meeting Rooms N119/N120</p>

<p><B>BEAVERTON, Ore.--(BUSINESS WIRE)</B>--The High-Definition Audio-Video Network Alliance (HANA) announced today that it will host a four-room "HANA Home" demonstration of its HD home networking solution at the 2008 International Consumer Electronics Show, January 7-10 in Las Vegas. Along with the demo, HANA also announced that Firecomms Ltd. and Newnex Technology Corporation have joined HANA as adopter members. The HANA Home is located in the North Hall Meeting Rooms N119/N120.</p>

<p>HANA will showcase the HANA Home, a four-room demo that will simultaneously distribute five wireless HD content streams throughout the home over in-home coax cabling. Using the HANA network, consumers can access HD content on any device in the house, and watch it on any networked device in any other room.</p>

<p>"HANA is delivering on the promise of a standards-based home networking solution that we envisioned when we launched two years ago," said Jack Chaney, HANA Technical Work Group Chair. "With a sole focus on HD content, we are committed to combining simplicity with premium quality and content protection. The HANA one remote - one cable solution makes it easy for anyone, regardless of their level of technical prowess, to immediately enjoy HD in any room in their house."</p>

<p>The HANA home demo partners include Cablevision, Firecomms, IntellaSys, Newnex, Pulse~LINK, Samsung, Texas Instruments and VividLogic.</p>

<p>In the four-room HANA Home, audiences will walk through various real-life scenarios of sharing content from one room to another during a typical day. They will experience firsthand how using HANA technology enables them to connect all their media devices through a single wire that once connected creates a wireless network controlled by a single remote. Another key advantage of HANA is a friendly graphical user interface (GUI) that features automatic device discovery that enables the simplicity that consumers want from their entertainment systems.</p>

<p>In the HANA Home, consumers will be able to watch TV, time-shift their viewing, record live TV and push content from room to room within the home by using the HANA menus on any wired to wireless connected HDTV - all with guaranteed 400 Mbps guaranteed quality of service. The demo will illustrate how HANA uses whatever cabling they have in their home, be it coax, CAT5 or plastic optical fiber (POF), to interconnect their entertainment systems. Additionally, HD content will be transmitted wirelessly via a Wireless HDMI solution - with no loss of quality and full use of the HANA menus.</p>

<p>The HANA Home at CES is sponsored by Samsung, Pulse~LINK, Oxford Semiconductor, Newnex, Firecomms and the 1394 Trade Association. These companies will showcase their home networking technology during the show.</p>

<p>"With the explosive growth of HD devices in the home, consumers are looking for a simple and inexpensive way to view their HD content when and where they want around the home," said Dan Friedman, Pulse~LINK Vice President of Marketing. "With Pulse~LINK CWave UWB Technology enabling more than 400 Mbps of application layer throughput with guaranteed QoS over various physical media, HANA is addressing this market demand by providing consumers an intuitive user interface with plug and play ability for whole-home networking of these HD devices over existing in-home cabling and wireless connectivity. We are excited to demonstrate this capability in the HANA Home at CES."</p>

<p>Oxford Semiconductor, a leading supplier of high performance storage controllers and connectivity/bridging solutions for consumer devices, will showcase two technologies key to HANA. First, it will demonstrate high performance RAID storage with greater than 240Mbytes/s throughput and hardware encryption. Oxford Semiconductor will also demonstrate a HANA over MoCA (Multimedia Over Coax Alliance) system showing media content playback. This system was developed with Entropic Communications using its c.LINK home networking products and is the first demonstration leveraging a MoCA Phy with HANA devices.</p>

<p><br />
<B>HANA Unveils 2008 Plans</B></p>

<p>HANA will be hosting a reception, sponsored by Pulse~LINK, on January 8 from 4:30 p.m. to 6:30 p.m. in the HANA Home. During the reception, HANA will share its 2008 roadmap and attendees will get a first look at product plans. The reception is open to all CES attendees.</p>

<p><br />
<B>New Members Join HANA</B></p>

<p>HANA is pleased to welcome two new members, Firecomms Ltd. and Newnex Technology Corporation. Both companies will be demonstrating their home networking technology as part of the HANA Home demo. Firecomms is a compound semiconductor company that develops high-speed light sources in visible range wavelengths. Its red laser and LED-based transceivers will create new opportunities for simple, low cost optical data communications in home networking. Newnex is a leading developer of interconnection products, which are designed with cutting-edge technologies, such as USB and IEEE1394.</p>

<p>"Firecomms is committed to enabling the transmission of HD content throughout the home," said Lawrence Thorne, Firecomms' VP of Sales & Marketing, The Americas. "Coupling Firecomms' innovative transceiver designs with Plastic Optical Fiber (POF) from Mitsubushi Rayon, Firecomms will be demonstrating an easy to install, consumer friendly solution for the streaming of HANA 1394 with no loss of quality."</p>

<p>"In the HANA Home we will be demonstrating our new 400 Mbps FireNEX-CAT5-S400 repeater to network content throughout the four room demonstration, using a CAT5 or CAT6 cable that already exist is installed in many homes and offices," said Sam Liu, President, Newnex. "It operates seamlessly in a HANA 1394 network where users have the ability to change any recorded video in any room with the push of a button."</p>

<p>Visit the HANA Home at CES to view the demonstration and learn about HANA's 2008 plans. For more information about HANA or its member companies, visit www.HANAalliance.org.</p>

<p><br />
<B>About HANA</B></p>

<p>Launched in December 2005, HANA is a cross-industry collaboration of members addressing the end-to-end needs of connected, HD, home entertainment products and services. The membership includes leading companies from the four industries most impacted by the HD revolution: Content Providers, Consumer Electronics, Service Providers and Information Technology. HANA is working to create design guidelines for secure high-definition audio-video networks that will speed the creation of new, high quality, easy to use HD products. HANA membership is open to all companies involved in the digital entertainment industry. Additional information is available at www.HANAalliance.org.</p>
