<B>WirelessHD 1.0 Spec Launches with Widespread Industry Support</B></p>

<p>The WirelessHD special interest group made several significant announcements this week. Most importantly, WirelessHD announced the availability of the WirelessHD 1.0 specification, the world's first consumer-based application of 60GHz for wireless video area networks (WVANs). Also as part of the announcement, WirelessHD announced Digital Transmission Content Protection (DTCP) as its content protection method. In addition, WirelessHD announced its collaboration with the Motion Picture Association of America (MPAA) and major content providers including Hollywood movie studios that have stringent requirements for secure content transmission. The WirelessHD specification will be made available to those companies who become WirelessHD Adopters.</p>

