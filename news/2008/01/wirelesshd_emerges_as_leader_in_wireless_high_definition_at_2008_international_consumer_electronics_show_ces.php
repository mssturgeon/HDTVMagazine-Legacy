<p><B>Las Vegas, Nevada - January 9, 2008</B> - At the 2008, International Consumer Electronics Show (CES), SiBEAM, Inc., a leading innovator of millimeter wave (mmWave) solutions and developer of high-speed wireless communications platforms, along with other WirelessHD Promoters, Toshiba and Panasonic, are showcasing the World's First WirelessHD-based solutions which are poised to revolutionize the wireless high-definition multimedia experience. WirelessHD experienced a triumphant introduction at CES this year and has established itself as the choice of major global consumer electronics manufacturers for delivery of true uncompressed, lossless delivery of high definition content.</p>

