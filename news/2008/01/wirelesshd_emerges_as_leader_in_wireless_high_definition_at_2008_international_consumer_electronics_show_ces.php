<p>Adding to the momentum, WirelessHD welcomed Intel as the newest member and Promoter of WirelessHD, answering the industry need for PC/CE convergence in home entertainment.</p>

<p>SiBEAM Makes Available First WirelessHD-Based Chipsets and Development Kit</p>

<p>Among the many WirelessHD news items, SiBEAM announced the world's first WirelessHD Chipset Solutions, built in affordable CMOS. These chipsets are the first to deliver true, lossless uncompressed A/V at 1080p, the preferred choice of consumer electronics manufacturers. The WirelessHD specification simplifies the set-up and management of a WVAN which can consist of a variety of WirelessHD-enabled devices including a high-definition television, high-definition disc player, digital video recorder, digital video camera, digital A/V player and more, by using only one A/V controller.</p>

<p><B>WirelessHD-based SiBEAM Technology Awarded "Best of Innovations" at CES 2008</B></p>

<p>Further, standing out among a myriad of wireless technology entries, SiBEAM's WirelessHD-based chipsets, which include the company's trademark OmniLink60 technology, were awarded the CES 2008 Best of Innovations Award in the Enabling Technology category. SiBEAM is the only provider of wireless high definition solutions to win this prestigious award.</p>

<p>"Our award-winning chipsets are unique in that they are the only solution available that enables true, lossless, uncompressed wireless transmission of HD video content among a complete range of home entertainment components - HDTVs, DVRs, DVD players, HD video cameras and PC Media Centers," said John LeMoncheck, SiBEAM CEO. "We're excited to join other WirelessHD Promoters in showcasing the industry's first WirelessHD-based solutions that will change the way CE manufacturers develop and market devices, as well as reshape how consumers interface with these products."</p>

<p><B>Panasonic Announces WirelessHD Products Powered by SiBEAM Technology</B></p>

<p>During the CES opening keynote presentation on Monday, January 7, Panasonic AVC Networks Company President, Toshihiro Sakamoto, unveiled a wireless 1080p full HD transmission system powered by SiBEAM's WirelessHD-based chipsets. In his keynote, Mr. Sakamoto demonstrated SiBEAM's revolutionary "beam steering technology" which provided an uninterrupted display of HD content despite an obstruction such as a person walking through the wireless connection path. Panasonic is also demonstrating this wireless solution on the show floor.</p>

<p><B>Toshiba Demonstrates WirelessHD Products Powered by SiBEAM Technology</B></p>

<p>Toshiba is demonstrating a WVAN using WirelessHD on an HD-A35 HD-DVD player to wirelessly display uncompressed, lossless video and to control a Toshiba Regza 42LX177 LCD TV.</p>

