				<p class="prtitle">Sling Media Unveils Top-of-Line Slingbox PRO-HD</p>

<center><i>First of Its Kind Slingbox Will Stream HDTV Content</i></center><br />
<br />

<p>2008 International CES<br />
Sling Media booth, #73106</p>

<p>Sling Media, Inc., a leading digital lifestyle products company, today announced its next generation Slingbox&trade; PRO-HD, a revolutionary new product that is capable of streaming HD content from a home television source, including over the air HD digital signals, HDTV cable or satellite receivers, or HD DVR's, to a laptop or desktop computer in and around the house. In addition, when paired with Sling Media's new SlingCatcher, Slingbox PRO-HD will transmit the HD signal to another TV in the house. In fact, customers who have a high speed broadband connection that features upload speeds of 1.5 - 2 Mbps or higher, Slingbox PRO-HD can even stream in HD outside the home to the office, to a hotel room or even to a remote TV when using SlingCatcher.</p>

<p>As part of the Slingbox PRO-HD product, Sling Media is also announcing SlingStream 2.0, a major improvement to the company's proprietary SlingStream&trade; technology. SlingStream 2.0 allows the Slingbox PRO-HD to adaptively stream high quality television content across virtually any network connection. With SlingStream 2.0, audio/video quality is noticeably improved for remote clients operating in a low bitrate environment as well as high definition players on a home network.</p>

<p>"Millions of customers are purchasing HDTVs, signing up for HD service and enjoying the benefits of HD quality picture creating a huge market for new products like Slingbox PRO-HD. With Slingbox PRO-HD, our customers will have the ability to placeshift their HD programming without sacrificing the quality of the picture," said Blake Krikorian, co-founder, chairman and CEO of Sling Media. "Slingbox PRO-HD marks a giant leap forward in hardware and software development from Sling Media including the powerful encoding enhancements that are a part of SlingStream 2.0. Because of this, Slingbox PRO-HD will deliver a picture quality, regardless of the resolution, that is truly amazing."</p>

<p>The Slingbox PRO-HD sets itself apart from the existing Slingbox family, including the Slingbox SOLO and the Slingbox PRO, as it is the first and only Slingbox product that is capable of streaming HD content. While the Slingbox PRO and Slingbox SOLO down-convert HDTV sources to EDTV resolutions, the Slingbox PRO-HD preserves the original resolution of the feed and delivers it to a HD-compatible laptop or desktop computer or secondary TV when paired with a SlingCatcher.</p>

<p>Slingbox PRO-HD is designed to meet the varied requirements of today's multi-faceted TV-viewing households. The product includes standard (4:3) and widescreen (16:9) video support and features multiple integrated sets of audio-video inputs and outputs (ATSC/QAM HDTV Tuner, S-video, composite video, component video and either analog or multi-channel, 5.1 surround, digital audio) and features integrated looping outputs for each input. Slingbox PRO-HD transforms PCs, laptops, Macs and a variety of smartphones (including the just announced RIM BlackBerry&reg;) into personal, portable TVs and builds upon the goals of the original Slingbox - to give consumers the freedom to view their home cable, satellite or DVR programming on a wide range of devices anywhere they can access the Internet.</p>

<p>Sling Media will demonstrate the Slingbox PRO-HD in the Sling Media booth, #73106, Sands Convention Center, at next week's International Consumer Electronics Show in Las Vegas, January 7th-10th. Slingbox PRO-HD will be available for purchase in Q3 2008 for a suggested retail price of $399.99.</p>

<p>In addition to the Sling Media booth Sling Media products can be found in several other partner booths at the Consumer Electronics Show including EchoStar Communications, Central Hall Las Vegas Convention Center (LVCC), booth 9021 and Microsoft, Central Hall LVCC, booth 7144. Sling Media products and services will also be on display at the Digital Experience press event on Sunday night at Caesar's Palace.</p>

<p><br />
<B>About Sling Media</B></p>

<p>Sling Media, Inc., a wholly owned subsidiary of EchoStar Holding Corporation (NASDAQ:SATS), is the world's leading digital lifestyle company offering consumer services and products that are a natural extension of today's digital way of life. Sling Media's product family includes the internationally acclaimed, Emmy award-winning Slingbox&trade; that allows consumers to watch and control their living room television shows at any time, from any location, using PCs, Macs, PDAs, and smartphones. For more information on Sling Media or the Slingbox, visit www.slingmedia.com.</p>
