				<p class="prtitle">Toshiba Deploys New HD DVD Marketing Initiatives Based on Strong Fourth Quarter Unit Sales</p>

<center><i>Mass Market Acceptance Confirms that HD DVD is the Consumer's Choice for Next Generation High Def Entertainment</i></center><br />
<br />

<p><B>WAYNE, N.J., Jan. 14 /PRNewswire/</B> -- Toshiba America Consumer Products, L.L.C. ("Toshiba") today announced that it is stepping up its successful marketing campaign for HD DVD as it experienced record-breaking unit sales in the fourth quarter of 2007. Major initiatives, including joint advertising campaigns with studios and extended pricing strategies will begin in mid- January and are designed to spotlight the superior benefits of HD DVD as well as the benefits HD DVD brings to a consumer's current DVD library by upconverting standard DVDs via the HDMI(TM) output to near high definition picture quality.</p>

<p>As Toshiba achieved the #1 sales volume in the next generation DVD category with an approximately 50 percent market share in 2007, HD DVD is proven to be the format of choice for consumers. Coupled with an 80 percent plus market share of all next generation DVD equipped notebooks for the 4th quarter 2007, the HD DVD format has already paved the way to a high definition digital AV solution by eliminating the boundaries between the consumer's living room and on the go.</p>

<p>HD DVD not only creates the ultimate high definition entertainment experience, leveraging all of the promise of the format such as superior audio/video performance, Web-enabled network capabilities and advanced interactive features - it also has a high-level of compatibility with DVD. With DVD upconversion via the HDMI output, HD DVD players instantly make a movie lover's existing DVD library look better than ever.</p>

<p>"HD DVD is the best way to watch movies in high definition," said Jodi Sally, Vice President of Marketing, Toshiba's Digital A/V Group. "Our HD DVD players not only play back approximately 800 HD DVD titles available worldwide and deliver an entirely new level of entertainment but also enhance the picture quality to near high definition on legacy DVD titles by all studios. In short, we added high def to DVD which already is the de facto standard format created and approved by the DVD Forum that consists of more than two hundred companies."</p>

<p><br />
<B>New Marketing Strategy for Mass Market Adoption</B></p>

<p>Taking the holiday season sales based on promotional prices into full consideration, these new manufacturer's suggested retail prices (MSRP) are designed to meet the potential demand for HD DVD players in the U.S. market. Effective on January 13, 2008 the MSRP of the entry-model HD-A3 will be $149.99, the HD-A30, with 1080p output, $199.99, and the high-end HD-A35, $299.99.</p>

<p>"While price is one of the consideration elements for the early adopter, it is a deal-breaker for the mainstream consumer," said Yoshi Uchiyama, Group Vice President Digital A/V Group. "Consumer sales this holiday season have proven that the consumer awareness of the HD DVD format has been elevated and pricing is the most critical determinant in consumers' purchase decision of the next generation HD DVD technology. The value HD DVD provides to the consumer simply cannot be ignored."</p>

<p><br />
<B>Extended Advertising Campaign</B></p>

<p>Toshiba plans to execute an extended advertising campaign that will further enhance consumer awareness of the benefits of HD DVD and drive sales to retail among potential consumers. Advertising strategies will include television, print and online media channels. Toshiba will also work with its dealers and studio partners on joint marketing and promotional initiatives to promote HD DVD. Current promotions include "The Perfect HD Offer" - a mail-in offer allowing consumers to select five HD DVD titles for free from a selection of 15 with the purchase of any Toshiba HD DVD player.</p>

<p><br />
<B>Consistent Viewing Experience and More</B></p>

<p>With advanced interactivity and Web-enabled network capabilities built into every HD DVD player through a dedicated Ethernet port as mandated by the specifications approved by the DVD Forum, Toshiba delivers on the promise of a consistent entertainment experience through firmware updates as studios launch new applications. HD DVD allows studios to flex their creative muscle in ways never before seen. The latest of these new experiences is online streaming. Now, when consumers connect their HD DVD player to the Internet, they can stream new content or trailers, as available, directly from a movie studio's server.</p>

<p>Universal Home Video, Paramount Pictures and DreamWorks Animation SKG have reported that an average of 30 percent of HD DVD owners have accessed Web- enabled network features and continue to do so regularly.</p>

<p><br />
<B>Ongoing Customer Commitment</B></p>

<p>In order to ensure that its customers will receive complete satisfaction from their new players, Toshiba introduced the "HD DVD Concierge" earlier this month. Consumers can now call 1-888-MY HDDVD (1-888-694-3383) for answers to general questions about HD DVD, for operational assistance or for assistance with various promotions.</p>

<p><br />
<B>About Toshiba HD DVD Players</B></p>

<p>With the HD DVD format, select HD DVD players allow consumers to experience true high def 1080p for extraordinary resolution that matches the latest state of the art 1080p HDTVs. These same players display images at 24 frames per second, the same frame rate used by directors when using film to create motion pictures, for a smoother, more film-like, viewing experience.</p>

<p><br />
<B>Important Notes:</B></p>

<p>HD DVD with high-definition content required for HD viewing. Up- conversion of DVD content will result in near HD picture quality. Viewing high-definition content and up-converting DVD content may require an HDCP capable DVI or HDMI input on your display device. 1080p capable display required for viewing content in 1080p. Firmware update may be required for some interactive features depending on content, which may also require an always-on broadband internet connection. Some features may require additional bandwidth. To take advantage of web-enabled network content, installing the latest firmware (ver.2.4 for HD DVD player models HD-XA1, HD-A1, and HD-D1; ver.2.7 for HD-XA2, HD-A2, HD-A2W, HD-D2, HD-A2C, and HD-A20; and ver.1.3 for HD-A35, HD-A30, and HD-A3) is required. Web-enabled network features require an always on broadband connection along with specific movie titles that include this form of content. For 24p output, content that was created in 1080p/24 frames/sec is required. Viewing 24p output requires an HD display capable of accepting a 1080p/24Hz signal. Use of REGZA Link, which is a feature based on HDMI-CEC, requires an HDMI-CEC compatible display device. Depending on the specifications of your TV, some or all REGZA Link functions may not work even if your TV is HDMI-CEC compatible. Dolby(R) Digital Plus, Dolby(R) TrueHD and DTS(R) support for up to 5.1 channels (DTS HD(R) support for DTS(R) core only). MP3/WMA audio files not supported. HDMI audio output requires connection to a PCM capable device. Because HD DVD is a new format that makes use of new technologies, certain disc, digital connection and other compatibility and/or performance issues are possible. This may, in rare cases, include disc freezing while accessing certain disc features or functions, or certain parts of the disc not playing back or operating as fully intended. If you experience such issues, please refer to the FAQ sections of www.toshibahddvd.com or www.tacp.toshiba.com for information on possible work- around solutions or the availability of firmware updates that may resolve your problem, or contact Toshiba Customer Solutions. Some features subject to delayed availability. While every effort has been made at the time of publication to ensure the accuracy of the information provided herein, product specifications, configurations, system/component/options availability are all subject to change without notice.</p>

