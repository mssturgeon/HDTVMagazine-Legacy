				<p class="prtitle">ViewSonic Unveils Industry Leading Color Performance and Improved Pixel Density for Desktops, Living Rooms and Home Theaters at CES 2008</p>

<center><i>Company's Heritage, Leadership and Vision Reflected in Wide Range of Offerings</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 7 /PRNewswire/</B> -- ViewSonic(R) Corp., a leading global provider of visual display products, has once again expanded its display technology innovations from the desktop to any room in the home with ease, style and affordability. In conjunction with the Consumer Electronics Show (CES), the company will showcase more than a dozen new displays that push the boundaries of color reproduction and image quality, including industry- leading, stylish desktop LED and LCDs; a broad line of true high definition (HD) 1080p HDTVs, a complete line of digital photo frames and a high-end home theater projector.</p>

<p>With new designs and enhanced feature sets, ViewSonic continues its heritage of display technology leadership. The VLED221wm, a 22-inch widescreen desktop monitor, leads the pack with the world's first 12000:1 dynamic contrast ratio in a LED desktop display. In addition, the Pro8100 home theater projector -- the first in ViewSonic's Precision Series -- combines a proprietary image enhancement technology with leading-edge video processing for the highest quality and performance available in the market.</p>

<p>"Our history as a desktop display leader has established the ViewSonic brand as an industry benchmark for innovation and performance," said Alan Chang, managing director of ViewSonic Americas, Europe and Asia Pacific regions. "This legacy is helping drive ViewSonic's success across its wide range of display product categories in the home, office or beyond."</p>

<p>ViewSonic has extended choices to consumers through new display sizes, feature sets and price points, including:</p>

<p><B>LCD TVs</B><br />
* The 90 Series includes the 26-inch N2690w, 32-inch N3290w, 42-inch N4290w, 47-inch N4790w and 52-inch N5290w, which are just the right size for home theatres and living rooms. All five of the TVs deliver consistent, high-quality digital video pictures with features such as built-in ATSC/NTSC/QAM TV tuner with precision 3D comb filter, motion adaptive de-interlacing, HDMI 1.3 and digital noise reduction. In addition, the 90 Series TVs up to 47-inchs feature a swivel base so that the screen can be easily adjusted and viewable from more angles.<br />
* The widescreen 30 Series, which includes the 15.6-inch N1630w, 19- inch N1930w and 22-inch N2230w, is ideal for consumers seeking dual- purpose HDTV/PC displays for smaller living spaces such as the kitchen, office, den or RV. Additionally, the 19-inch and 22-inch feature super HD panel resolution, delivering up to 68 percent more pixel performance than traditional high definition LCD TV resolution. The LCDs deliver high-definition digital video content through an integrated ATSC/NTSC/QAM TV tuner, and comprehensive inputs including component video "S," composite video and a DVI-compatible HDMI port.<br />
* Answering the demand for premium HDTV entertainment at more affordable prices, ViewSonic introduced the big screen 47-inch N4785p and 42-inch N4285p LCD HDTVs. The new 47-inch N4785p is priced below $1,600, delivering brilliant images with 1920X1080p resolution for true 1080p capability and boasts a 6.5ms response time for extreme clarity in fast-action movies and sporting events.</p>

<p><B>Desktop Displays</B><br />
* The 22-inch widescreen VLED221wm desktop monitor with LED backlight provides color experts, such as graphic designers, multi-media editors and gamers with color precision and reproduction never before seen in an LED monitor. In addition to offering 12000:1 dynamic contrast ratio and providing premium color reproduction of 118 percent of the NTSC color gamut, the VLED221wm addresses environmental concerns by removing harmful mercury used in traditional displays.<br />
* The new VP 50 Series includes up to 110 percent NTSC OptiColor(TM) Technology for better accuracy and more detailed images in any viewing environment. These displays offer up to 3000:1 dynamic contrast ratio dynamic contrast ratio (typ), the widest tonal range and largest color gamut, making them ideal for both creative and business professionals.<br />
* The stylish VX 62 series delivers industry-leading color performance and 6000:1 dynamic contrast ratio (typ) in a unique, multiuse design to enhance the PC entertainment experience on the desktop.<br />
* The 26-inch VX2640w boasts 3ms video response time, 4000:1 dynamic contrast ratio (typ), 1080p full HD native resolution and color saturation nearly 25 percent better than traditional displays, and is ideal for multimedia enthusiasts, gamers and graphic artists.</p>

<p><B>Digital Photo Frames</B><br />
* The company's first digital frames -- the widescreen 7-inch DP701W4, widescreen 8-inch DF88W and traditional 8-inch DF87G -- are affordable, stylish and versatile, providing a high-quality display for consumers to show off digital photos that may have never seen the light of day.</p>

<p><B>Projectors</B><br />
* The Pro8100 home theater projector combines ViewSonic's Precision Color System and the latest design to offer full HD 1080p resolution, 13,000:1 contrast ratio (typ), 1000 lumens of brightness, auto iris, and full HD optics for the custom installation and specialty retail channel.</p>

<p><br />
For more ViewSonic product information or to locate an authorized ViewSonic dealer, visit www.ViewSonic.com or call 800.888.8583.</p>

