				<p class="prtitle">Toshiba Third Generation Players Deliver on the Promise of the HD DVD Format</p>

<center><i>State-of-the-Art Performance, Successful Promotions and Affordable Pricing Result in Strong Consumer Acceptance of Third Generation Players</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 6 /PRNewswire/</B> -- CES -- Demonstrating strong consumer acceptance for the HD DVD format, Toshiba America Consumer Products L.L.C. ("Toshiba") today announced that the rollout of its third generation HD DVD players has been the most successful to date. With their unrivaled performance including real-world Web-enabled networking capabilities, consumers have chosen Toshiba's third generation HD DVD players for their ultimate high def entertainment experience, resulting in the strongest quarter of unit sales to date and solidifying Toshiba's market share leadership position.</p>

<p>"We are pleased with the consumer acceptance of our HD DVD players in the market," said Jodi Sally, Vice President of Marketing, Toshiba's Digital A/V Group. The combination of HD DVD's state of the art audio/video performance and unrivaled interactive capabilities along with exciting consumer promotions and affordable pricing in 2007 marked significant accomplishments for the HD DVD format.</p>

<p><br />
<B>An HD DVD World</B></p>

<p>As it has become established in the market, HD DVD has delivered on the promise of next generation entertainment in the home, which has led to the expansion of high definition in all areas of the consumer experience.</p>

<p>"Because HD DVD is a standardized format and meets the spec guidelines mandated and approved by the DVD Forum, it provides a consistent platform for all applications of next generation high definition video such as mobile entertainment and makes it possible to enjoy HD DVD in a multitude of lifestyle settings," said Yoshi Uchiyama, Group Vice President America Digital A/V Group. "Whether as a standalone player for a home theater as a companion drive to the Xbox 360(TM) gaming machine or as an HD DVD-ROM drive for computers, HD DVD will be in many facets of consumers' lives. As part of our vision for transitioning movie lovers to high definition, our goal is to extend HD DVD beyond the traditional home entertainment experience."</p>

<p><br />
<B>Fulfilling the promise of HD DVD</B></p>

<p>Toshiba also announced its commitment to enhancing the consumer's HD DVD player purchase with the introduction of the "HD DVD Concierge," a new 800 number offering dedicated assistance to purchasers of HD DVD players. Consumers can now call 1-888-MY HDDVD (1-888-694-3383) for answers to general questions about HD DVD, for operational assistance or for assistance with various marketing initiatives. Trained service agents will provide the latest information on HD DVD enabling consumers to get the most from their purchase.</p>

<p><br />
<B>Toshiba delivers a richer interactive experience-now</B></p>

<p>With interactivity built into every HD DVD player as a mandatory spec, and with the reality of Web-enabled network capabilities, Toshiba delivers on the promise of a totally new experience. HD DVD allows studios to flex their creative muscle in ways never before offered or not currently available on any other format. 2007 saw the introduction of online polling, ringtones and online shopping to name a few, all from the HD DVD player itself and from the comfort of one's own home. The latest of these new experiences is online streaming. Now when consumers connect their HD DVD player to the Internet via the standard Ethernet port on every player, they can stream new content or trailers, as available, directly from a movie studio's server. "It's exciting to see the studios bring HD DVD to life through new interactive features and Web-enabled network capabilities," said Uchiyama. "By consistently delivering unique entertainment experiences, we're changing the world of movie watching and giving meaning to the HD DVD experience." Consumers have spoken, and data from Universal Home Video and Paramount and DreamWorks Animation SKG shows that an average of 30 percent of HD DVD owners have accessed Web-enabled network features and continue to do so regularly.</p>

<p><br />
<B>About Toshiba HD DVD Players and Third Generation Line</B></p>

<p>HD DVD was designed from the outset to be the evolution of the DVD format; every Toshiba HD DVD player is designed to play back DVDs and CDs. Toshiba's HD DVD players will not only play DVD but will instantly make a movie lover's existing DVD library look even better than it ever did with upconversion via the HDMI(TM) output. With the HD DVD format, consumers can experience true high def 1080p resolution for extraordinary detail that matches the latest state of the art 1080p HDTVs. Select Toshiba HD DVD players display images at 24 frames per second, the same frame rate used by directors when using film to create motion pictures, for a smoother, more film like, viewing experience.</p>

<p>Toshiba's third generation family starts with the entry level HD-A3 player featuring 1080i output capability. The other two new models, Toshiba's HD-A30 and HD-A35, output 1080p resolution (1920 x 1080p), the highest HD signal currently available. Both models are capable of outputting signals at 1080p/24 frames per second so consumers can enjoy movies in their native frame rate. The HD-A30 and HD-A35 models also feature "REGZA(R) Link" (HDMI(TM)-CEC), allowing two-way control between the HD DVD player and a TV through an HDMI connection.</p>

<p>All Toshiba HD DVD players also feature twin video processors and advanced audio to deliver an immersive home theater experience with features such as picture-in-picture video and audio commentary. Thanks to the Ethernet port and flash memory built into every Toshiba HD DVD player, movie lovers also can enjoy the benefits of Web-enabled network connectivity. Plus, Toshiba's third generation players have a new slim design cabinet that is approximately 1/4- inch slimmer than second generation models.</p>

<p><br />
<B>HD DVD's Commitment to Green</B></p>

<p>Toshiba is committed to not only making its products consumer friendly, but friendly to the environment as well. Its products, including the third generation HD DVD players, meet Toshiba's voluntary environmental standards and ongoing efforts to bring eco-conscious products to market and comply with the company's strict environmental policies. Environmental management is promoted both from the standpoint of improving products themselves and renewing manufacturing processes, which not only calls for the restriction of the use of hazardous substances in products, but also to avoid using such substances in any manufacturing process.</p>

<p>For example, Toshiba HD DVD players are compliant with the EU RoHS Directive, a European Union environmental directive that restricts the use of six hazardous substances, including lead, mercury and cadmium. Also, for energy conservation, all third generation players meet the Energy Star standard. Toshiba will place the Toshiba Group Earth Protection mark on its third generation players' catalogs and manuals. The Toshiba Environmental Standard for granting the Toshiba Group Earth Protection mark is on Toshiba America Consumer Products, L.L.C.'s official website.</p>

<p><br />
<B>Pricing and Availability:</B></p>

