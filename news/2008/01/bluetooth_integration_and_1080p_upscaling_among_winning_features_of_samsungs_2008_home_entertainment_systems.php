<p>New for 2008, Samsung has integrated Bluetooth 2.1 technology in select models in its home entertainment line including the A100, A105, X710, X715 and X810, offering consumers more freedom to enjoy their digital devices than ever. From MP3 players to cell phones, Samsung's 2008 home entertainment models work seamlessly with compatible Bluetooth-enabled devices and expands wireless audio listening capabilities even further. Additionally, all of the models in the lineup offer 1080p upconversion, which ensures consumers can enjoy the best quality sound with the best quality picture.</p>

<p>Adding to the superior audio output capabilities, Samsung's Smart Volume function featured on a select number of home entertainment systems, continuously monitors and adjusts the volume levels of content coming through the system to ensure the consumer hears even, yet accurate sound reproduction without over-saturation. Many models, such as the HT-Z410, also offer auto calibration in order to ensure consumers will have the best possible surround sound regardless of where they place their speakers.</p>

<p>Select models in Samsung's 2008 home entertainment lineup easily connect to other digital peripherals through an HDMI 1.3 port with CEC for expanded color delivery and easy home theater control. Additionally, a convenient USB port lets users enjoy DivX, MP3, WMA and JPEG files without having to access a PC-all that's needed is the remote and a TV.</p>

<p>Sporting an elegant piano-black finish and smooth contour design, Samsung's home entertainment line looks as good as it sounds. Knowing consumers are looking to integrate their home electronics into their décor, Samsung has paid special attention to each product's design to make sure it fits flawlessly together with other Samsung HDTVs or Blu-ray/HD-DVD players.</p>

<p><br />
<B>Z510 Series</B></p>

<p>Samsung offers three models in this 5.1-channel Home Theater series that include wireless out-of-the-box speakers with 5.8 GHz technology. Consumers do not have to go through a complicated set-up but can immediately begin enjoying the freedom of wireless home audio speaker. Z510 Series consists of the HT-Z510, which features four satellite speakers; the HT-Z512, which features two satellites and two tallboys; and the HT-Z515, which has four tallboys. In addition to the connectivity and next-generation technology detailed earlier, each includes a five-disc, 1080p-upconverting DVD player and Auto Sound Calibration to deliver exceptional sound in any type of room. The HT-Z510 delivers 400 watts of power, while the HT-Z515 doubles that, in addition to featuring wireless-ready rear speakers for added convenience.</p>

<p>The HT-Z510, HT-Z512 and HT-Z515 will be available April 2008.</p>

<p><br />
<B>X710 Series Compact Home Theater-In-a-Box Systems</B></p>

<p>With a compact, dual-layout chassis and a clean, modern design, the 2.1-channel HT-X710 and the 5.1-channel HT-X715 easily integrate into most any home theater. Bluetooth capability makes it easy to connect and control. 5.8GHz wireless-ready functionality on the HT- X715 offers the opportunity of upgrading to convenient and clean wireless home theater system. Additionally, the HDMI-CEC and 1080p upconversion features optimize the viewing experience.</p>

<p>The HT-X710 and HT-X715 will be available in May 2008.</p>

<p><br />
<B>HT-BD2 Blu-ray Home Theater-In-a-Box System</B></p>

<p>A CES 2008 Innovations Honoree and the industry's first home theater-in-a-box to integrate Blu-ray playback, this comprehensive 7.1-channel Home Theater system delivers 1,100 watts of surround sound and full HD 1080p Blu-ray playback. Consumers will also love its HDMI 1.3 output with CEC and 1080p upconversion of DVDs. With an Ethernet port, consumers are able to receive the latest firmware updates as they become available, making the HT-BD2 a device that evolves with the industry's latest technologies. This system features an active subwoofer and an expanded center channel, combined with four tower speakers and two satellite rear speakers-all with wireless-ready capability-for theater-like audio output in almost any environment. The HT-BD2 also decodes Dolby Digital Plus, DTS-HD, Dolby TrueHD, MP3 files and more, bringing high-definition sound no matter the format.</p>

<p>The HT-BD2 is available now.</p>

