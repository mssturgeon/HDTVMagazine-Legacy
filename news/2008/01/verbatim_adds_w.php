				<p class="prtitle">Verbatim Adds World's First 2x-Speed HD DVD Recordable Media to Industry's Broadest HD DVD Media Product Line</p>

<center><i>Provides One-stop Shopping for Highest Speeds, Highest Capacities, Highest Quality</i></center><br />
<br />

<p>2008 International CES<br />
Booth #S4-36249, South Hall</p>

<p><B>LAS VEGAS--(BUSINESS WIRE)</B>--Verbatim&reg; Americas, LLC announced today that it will begin shipping the world's first 2x-speed HD DVD-R (recordable) and HD DVD-RW (rewriteable) discs this quarter. By adding the new HD DVD recordable media to its current offerings, Verbatim now offers the industry's broadest range of premium-quality HD DVD media products. The complete HD DVD media product line, including Verbatim's 2x HD DVD R/RW media and its 1x HD DVD-R DL media will be showcased at Verbatim's CES Booth #S4-36249 in the South Hall this week.</p>

<p>Verbatim 2x-speed HD DVD-R/RW Media -- At 2x-speed Verbatim's new recordable and rewriteable HD DVDs slash the time required to fill a 15GB HD DVD disc to about 30 minutes, compared to about 1 hour at 1x speed. HD DVD media supports the Advanced Access Content System copy-protection technology.</p>

<p>To achieve the higher performance required for 2x write speeds, Mitsubishi Kagaku Media (MKM), Verbatim's parent company, leveraged its proven dye technology to develop a new highly sensitive recording layer. The recording characteristics of Verbatim HD DVD-R discs are further enhanced by the disc's physical attributes. Features such as a uniform groove shape, consistent substrate thickness and flatness of the disc have been proven to optimize the performance and longevity of Verbatim media. These characteristics are achieved using a new mastering process, ultra-precise molding technology and advanced bonding techniques developed by MKM. To achieve the narrow track pitch of the HD DVD format, MKM also developed a stamper with a precise groove shape.</p>

<p>Verbatim's single-sided, dual layer HD DVD-R Media has been available in Japan since July of 2006 and began shipping to its North American customers when compatible hardware became available in Q1 2007. Verbatim's HD DVD DL media supports the Advanced Access Content System copy-protection technology.</p>

<p>To achieve the best balance of reflectivity, transmission and absorption for both recording layers, MKM developed a new highly sensitive recording dye. The high recording sensitivity plus the wider power margin of the new recording layer ensure a low error rate, regardless of drive power fluctuations or smudges on the disc surface. Highly resistant to sunlight and heat, the media provides ultra-stable recording characteristics for a lifetime of high performance -- even after long periods of storage -- for both recorded and unrecorded media.</p>

<p>Verbatim/MKM is a general member of the HD DVD Promotion Group and a charter member of the DVD Forum.</p>

