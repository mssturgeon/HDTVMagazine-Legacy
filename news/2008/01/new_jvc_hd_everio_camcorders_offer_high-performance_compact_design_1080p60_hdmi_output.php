<p><B>LAS VEGAS, Jan. 30 /PRNewswire/</B> -- JVC today announced a pair of new high definition Everio hard disk camcorders that offer industry-leading picture quality in a dramatically reduced size. The new JVC GZ-HD6 and GZ-HD5 HD camcorders are 45 percent smaller than JVC's previous top-end HD camcorder, the GZ-HD7, without any sacrifice in image quality.</p>

<p>To provide the best possible quality, both new HD camcorders feature a FUJINON HD lens, a progressive scan 3CCD imaging system and JVC's HD Gigabrid engine that delivers 1920 x 1080 Full HD recording. In addition, they offer 1080p 60 frame per second output via HDMI 1.3 with x.v.Color(TM). Collectively these technologies capture and maintain optimum image quality for videos and stills through every stage, from the lens on through to recording.</p>

<p>Both camcorders offer a long recording time in 1920 x 1080 Full HD -- 10 hours for the 120GB GZ-HD6 and five hours for the 60GB GZ-HD5. They record up to 24 (GZ-HD6) or 12 (GZ-HD5) hours in the 1440 LP mode. Recordings are stored on either the built-in hard disk drive or on an inserted microSD card (optional). Both models also offer a microphone input and a wide range of manual controls. The black GZ-HD6 also features a lens hood and headphone jack. The smaller silver GZ-HD5 weighs just 1 lb 3.9 oz with battery.</p>

<p>The GZ-HD6/HD5 also come supplied with a full set of Windows(R) applications for editing and authoring to DVD and Blu-ray disc, as well as plug-in software to facilitate data import into various Macintosh applications. And to make it easy to share and archive recordings, JVC will continue to offer the CU-VD40 Everio SHARE STATION for HD which enables one-button burning of video data to DVD.</p>

<p>To preserve the Full HD quality, the HD Everios feature optical image stabilization, avoiding the signal degradation caused by electronic image stabilization, which might be particularly noticeable in HD footage. In short, HD Everio matches its high-definition recording capability with a proven HD lens section that has proven its value in the broadcast industry.</p>

<p>While HD Everio camcorders offer fully automated operation for point-and- shoot simplicity, they also offer a wide range of manual controls. These include a manual focus ring, manual white balance, exposure control, shutter priority mode, aperture priority mode and sharpness control. In addition, a Focus Assist function displays the edge of the in-focus elements in color while the rest of the image is black-and-white, making it easy to check which image elements are in focus. And a Zebra function displays a striped pattern across highlight areas on the image in the LCD monitor, making it easier to manually set the exposure.</p>

<p>The JVC GZ-HD6, offered in black, and the GZ-HD5, offered in silver, will be available in March for $1,399.99 and $1,199.99, respectively.</p>

