				<p class="prtitle">Apple Premieres iTunes Movie Rentals With All Major Film Studios</p>

<center><i>New Apple TV Software Lets You Rent Movies Directly from Your Widescreen TV</i></center><br />
<br />

<p><B>MACWORLD SAN FRANCISCO, Jan. 15 /PRNewswire-FirstCall/</B> -- Apple(R) today announced iTunes(R) Movie Rentals featuring movies from all the major movie studios including 20th Century Fox, The Walt Disney Studios, Warner Bros., Paramount, Universal Studios Home Entertainment, Sony Pictures Entertainment, Metro-Goldwyn-Mayer (MGM), Lionsgate and New Line Cinema. Users can rent movies for as low as $2.99 and watch them on their Macs or PCs, all current generation iPods*, iPhone(TM) and Apple TV(R). iTunes Movie Rentals launches today and will offer over 1,000 titles by the end of February, including over 100 titles in stunning high definition video with 5.1 Dolby Digital surround sound which users can rent directly from their widescreen TV using Apple TV. iTunes Movie Rentals are priced at $2.99 for library titles and $3.99 for new releases, and high definition versions are just one dollar more with library titles at $3.99 and new releases at $4.99.</p>

<p>"iTunes Movie Rentals instantly brings great movies from all the major studios directly to your iPod, iPhone, TV or computer -- without having to drive to the video store or wait for DVDs to arrive in the mail," said Steve Jobs, Apple's CEO. "Movie lovers can now discover and enjoy movies as simply and easily as music lovers discover and enjoy music today on iTunes."</p>

<p>"Apple has created an incredibly easy and innovative way to rent and enjoy movies," said Jim Gianopulos, chairman and chief executive officer of Fox Filmed Entertainment. "Millions of movie lovers will be able to watch wonderful movies from Fox and the other major studios whenever and wherever they want, be it on their computer, TV, iPod or iPhone."</p>

<p>iTunes Movie Rentals feature iTunes' legendary ease of use, which makes discovering and enjoying movie rentals as simple and easy as buying music on iTunes has always been. Once a movie is rented, it starts downloading from the iTunes Store directly to iTunes or Apple TV, and users with a fast Internet connection can start viewing the movie in seconds. Customers have up to 30 days to start watching it, and once a movie has been started customers have 24 hours to finish it -- or watch it multiple times.</p>

<p>The all new Apple TV software delivers an entirely new user experience centered around iTunes Movie Rentals, allowing movie fans to rent and watch movies right from their widescreen TV, with no computer required. Users can also view photos from their computers, Flickr and .Mac Web Galleries on their widescreen TV as slideshows or screen savers, and anytime photos are updated on Flickr or .Mac they are automatically updated on Apple TV. Apple TV users can now browse and enjoy the iTunes Store podcast directory of over 125,000 video and audio podcasts, view over 50 million originally created videos from YouTube, or choose from a selection of six million songs, over 600 TV shows and 10,000 music videos to purchase directly from their Apple TV. Purchases downloaded to Apple TV are automatically synced back to iTunes on the user's computer for enjoyment on their computer, iPod(R) or iPhone.</p>

<p>Apple TV easily connects to a broad range of widescreen TVs and home theater systems and comes standard with HDMI, component video, analog and optical audio ports. Using high-speed AirPort(R) 802.11 wireless networking, Apple TV now automatically plays all of your iTunes content without setup or management**.</p>

<p><br />
<B>Pricing & Availability</B></p>

<p>Movie rentals from the iTunes Store for Mac(R) or Windows require iTunes 7.6, available as a free download immediately from http://www.itunes.com/. iTunes Movie Rentals require a valid credit card with a billing address in the country of purchase. iTunes Movie Rentals are available in the US only and are $2.99 (US) for library titles and $3.99 (US) for new releases, and high definition versions are priced just one dollar more with library titles at $3.99 (US) and new releases at $4.99 (US).</p>

<p>The new Apple TV software will be available as a free automatic download to all Apple TV customers later this month. Apple TV, which includes the Apple Remote, is available from the Apple Store(R) (http://www.apple.com/), Apple's retail stores and Apple Authorized Resellers for a suggested retail price $229 (US) for the 40GB model, and for $329 for the 160GB model. Apple TV requires an 802.11g/n wireless network or 10/100 Base-T Ethernet networking, a broadband Internet connection and a high definition widescreen TV. iPod games will not play on Apple TV.</p>

<p>*Movie rentals work on iPod classic, iPod nano with video and iPod touch.</p>

