<p>Extenders for Windows Media Center allow viewers to enjoy digital entertainment, including live and recorded HDTV, Internet TV, music, movies and photos, from their PC running Windows Vista Home Premium or Windows Vista Ultimate on any TV in the house through wired or wireless home networks.</p>

