<p>Microsoft also announced Extender product availability and ship dates from initial partners D-Link Corp.; Linksys, a division of Cisco; and Niveus Media Inc. These devices allow people to extend their entertainment experience from their Windows Vista-based PC with Windows Media Center to any TV in the house.</p>

<p>"People want to bring digital entertainment from the PC to a big-screen HDTV, and with the addition of popular consumer companies such as Samsung to the growing list of Extender partners, Windows Media Center makes that possible for an even wider audience," said Enrique Rodriguez, corporate vice president of the Connected Television Division at Microsoft. "Such growing industry support validates Microsoft's approach of using Extender for Windows Media Center technology to deliver the ultimate connected entertainment experience."</p>

