<p>Designed for high-end home entertainment enthusiasts and available for purchase today through select custom audiovisual installers, the Niveus Media Extender - EDGE offers a high-fidelity experience, uncompromised 1080p video, digital audio and the same amazing 3-D user interface found on the award-winning Niveus Media Center. In addition, the Niveus Media Extender - EDGE is built with the Niveus Glacier Passive Cooling System for near-silent operation in a sleek and stylish form factor.</p>

<p>D-Link announced the January 2008 availability of its DSM-750 MediaLounge HD Media Center Extender at an estimated retail price of $329.99 (U.S.). Housed in a sleek, 17-inch, black aluminum chassis, this device connects to a home network using Ethernet or dual-band 802.11n networking, which makes it easy to enjoy the Windows Media Center experience with friends and family on any TV in the house. The DSM-750 lets customers enjoy high-definition videos with resolutions of up to 1080i and includes a USB 2.0 port for instant access to music, photos and videos stored on removable USB flash drives or hard drives.</p>

