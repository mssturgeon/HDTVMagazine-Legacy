<center><i>The World's First Wireless Transmission System Based on WirelessHD Standard Realizes Greater Layout Flexibility</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 6 /PRNewswire-FirstCall/</B> -- Panasonic today announced that it has developed the world-first wireless High Definition (HD) Audio/Video transmission system based on the "WirelessHD(TM)" standard, in partnership with SiBEAM, Inc. (SiBEAM) of the United States. The system enables HD video transmission in uncompressed format between a television and other AV equipment like a Blu-ray Disc player without quality deterioration. Panasonic will debut this system at the 2008 International Consumer Electronics Show (CES) which will be held from January 7-10, 2008 in Las Vegas, Nevada. Panasonic's lineup of featured products and technologies will be on display at booth #9405.</p>

<p>Unlike conventional wireless transmission technologies, this system uses a 60 GHz-band millimeter wave radio to provide robust transmission connectivity, since uncompressed HD video requires a large bandwidth. The WirelessHD system consists of a Plasma television with a receiver and a movable rack housing video sources with a transmitter such as a Blu-ray Disc player and HD digital camcorder. Without the clutter of connecting cables, users can enjoy greater freedom in positioning and design of their home theater. For example, a user can hang an HD Plasma on their wall while keeping their Blu-ray Disc player apart from the Plasma, without worrying about running cables or other wires between the products.</p>

<p>SiBEAM's beam steering technology enables this system to maintain stable connectivity when there is an obstacle, such as a person, between the wireless transmitter and receiver. When the system detects an obstacle interrupting the beam, it immediately finds another path to maintain a stable link and provide uninterrupted signal transmission. Therefore, users can enjoy their wireless High Definition Plasma viewing without having to worry about signal interference just as with conventional cable-connected systems.</p>

<p>Panasonic's newly announced VIERA Link feature is available with this system. VIERA Link is an audio/video operation system developed and promoted by Panasonic that uses a single remote to operate an entire home entertainment system connected via High Definition Multimedia Interface (HDMI(TM)) cable.</p>

<p><br />
<B>About Panasonic</B></p>

<p>Based in Secaucus, NJ, Panasonic Corporation of North America markets a broad line of digital and other electronics products for consumer, business and industrial use. The company is the principal North American subsidiary of Matsushita Electric Industrial Co., Ltd. (NYSE:MC) of Japan, and the hub of Panasonic's U.S. branding, marketing, sales, service and R&D operations. Information about Panasonic and its products is available at www.panasonic.com. Additional company information for journalists is available at www.panasonic.com/pressroom.</p>

<p><br />
<B>Overview of WirelessHD Consortium and Standard</B></p>

<p>WirelessHD standard is specified by the WirelessHD Consortium, comprising Intel Corporation, LG Electronics Inc., Matsushita Electric Industrial Co., Ltd (Panasonic), NEC Corporation, Samsung Electronics Co., Ltd, SiBEAM, Inc., Sony Corporation and Toshiba Corporation. A data throughput of 4 Gbps is achieved within 10 m range indoor and uncompressed HD audio/video/data can be transmitted. For more information on WirelessHD, please visit www.wirelesshd.org</p>

