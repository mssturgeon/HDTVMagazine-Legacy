<center><i>Media Friendly System Boasts Blu-ray, SD Memory Card Slot, iPod Dock</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 6 /PRNewswire/</B> -- Panasonic Consumer Electronics Company today announced the launch of its first home theater in a box (HTiB) system with an integrated Blu-ray Disc player. The new model, SC-BT100, is the perfect complement to a flat panel, large screen TV.</p>

<p>The new model epitomizes Panasonic's emphasis on media friendly capabilities. It is made for iPod* and features an advanced integrated dock which not only recharges an iPod but plays music or video through the home theater system, displays audio tracks and menus on the TV screen and operates with the supplied remote control. Its SD Memory Card slot offers simple playback of digital images or original video footage in either standard or High Definition AVCHD format. The optical input offers simple digital audio connection for set-top box, digital video recorder and game system.</p>

<p>"The Panasonic SC-BT100 home theater system is the best of both worlds," says Paul Sabo, national marketing manager for Panasonic Home Audio. "It combines the installation ease and user-friendly operation of an HTiB plus the features and performance of high-end audio/video components, including full High Definition 1080p resolution Blu-ray video, wireless rear speakers and 7.1channel or multi-room/multi-source upgradeability."</p>

<p>The SC-BT100 can be upgraded to wireless full 7.1 channel sound with the optional purchase of two side speakers and a transceiver. It is compatible with all new audio codecs and is equipped with Viera Link(TM) HDAVI control, HDMI digital A/V connectivity for one-touch operation of all the components including a Panasonic TV.</p>

<p>The Blu-ray Disc player boasts the Final Standard Profile for advanced functions such as Picture-in-Picture and Audio Mixing, which allows the consumer to switch the sound between the main and sub windows.</p>

<p>In addition to superb video, this system delivers advanced state-of-the- art audio. The Kelton-design subwoofer features a passive radiator and a driver anchored to the cabinet to reduce vibration and noise while delivering more dynamic bass. All speakers, including the center channel speakers, are made with a bamboo diaphragm which provides a tightly intertwined fiber to deliver greater rigidly and accuracy. To allow viewers to enjoy surround sound effects without disturbing others, the system even has Whisper-mode Surround(TM), which dynamically boosts bass and surround-channel levels as the volume is turned down to provide a full surround effect even at low volume.</p>

<p>The SC-BT100 is scheduled to ship in May 2008. Suggested retail pricing has not been announced.</p>

