				<p>El Segundo, Calif., Jan. 22, 2008-After two lackluster quarters, Plasma Display Panel (PDP) shipments rebounded during the third quarter of 2007 due to increased consumer demand driven by rapid price declines, according to iSuppli Corp.</p>

<p>Global shipments of PDPs, which are used mainly in televisions, in the third quarter reached 3 million units, up 27.1 percent from 2.4 million in the second quarter of 2007, and up 15 percent year on year. In contrast, PDP-TV shipment growth in the second quarter was an anemic 4.5 percent, following a sequential drop of 16.6 percent in the first quarter. The first half of 2007 saw no growth compared to the equivalent period in 2006.</p>

<p>"The attractive pricing of plasma television sets has captured the attention of consumers, especially for the 50-inch and larger sizes, boosting the market prospects for PDPs," said Riddhi Patel, principal analyst for television systems and plasma panels at iSuppli.</p>

<p>"However, the rise in consumer attention presently isn't making any of the leading panel makers rejoice-and it isn't convincing them to add any capacity at this time as they remain cautious," Patel added.</p>

<p>iSuppli believes a balanced supply situation is likely to prevail in 2008 and beyond for PDP makers as they retain their cautious attitude toward adding capacity. Furthermore, plasma will maintain its stronghold in the large-screen market-50-inches and larger diagonally-as TV makers continue to offer less-expensive televisions with larger screen sizes.</p>

<p><strong>Slow but steady pace keeps plasma in the race</strong></p>

<p>Although competition from Liquid Crystal Displays (LCDs) has had a dramatic impact on the plasma market in the consumer and business segments, PDP shipments are continuing to grow at a slow but steady pace. PDP suppliers continue to work on improving their technology and cutting costs to remain competitive, adopting new technologies and techniques, including:</p>

<p>• Single-scan technology</p>

<p>• Lower power consumption</p>

<p>• Improved materials</p>

<p>"These improvements are helping panel makers to reduce production costs," Patel said. "This will make PDP television sets more attractive to buyers that are comparing plasma sets with LCD-TVs-not only based on resolution-but also on price. While profitability is still a worry, price declines are inevitable due to the severe competition from the LCD market as well as from microdisplay-based rear-projection sets."<br />
 <br />
<strong>Flat revenue growth-but fat unit growth</strong><br />
Global PDP market revenue is expected to amount to $7.64 billion in 2011, virtually unchanged from $7.63 billion in 2006. On the other hand, units will double to 20.1 million by 2011, rising at a Compound Annual Growth Rate (CAGR) of 14.9 percent from 10 million units in 2006. This will be due to a decline in per-panel Average Selling Prices (ASPs) to $380 by 2011, down from $761 in 2006.<br />
 <br />
<strong>Matsushita in the lead for panel makers</strong></p>

<p>Looking at the big-three suppliers of PDPs, Matsushita (Panasonic) maintained its lead in the third quarter of 2007 with a 30.2 percent share of unit shipments, followed by Samsung SDI with 29.1 percent and LG Electronics with 28.9 percent.</p>

<p>The Top-3 plasma panel makers in the third quarter accounted for 88.1 percent of total production and are likely to maintain this commanding position in the market for the next five years, according to iSuppli.</p>

<p>For PDP suppliers, the main challenges continue to be the cost of panel production and the slower uptake in the end markets. With revenue expected to remain flat during the next five years, these problems aren't likely to solve themselves, iSuppli believes. </p>

