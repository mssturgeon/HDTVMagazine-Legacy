<center><i>Mitsubishi Raises the HD Bar with Low-Cost, 5000-Lumen Full HD Projector for Commercial, Home Theater and Education Applications</i></center><br />
<br />

<p><B>IRVINE, Calif.--(BUSINESS WIRE)</B>--Mitsubishi Digital Electronics America's Presentation Products Division, known for award-winning, high-quality, high-definition presentation and display products, introduced the FL7000U, its first ultra bright 1080p HD projector for commercial, home theater and education installations. At a cost remarkably lower than similar projectors of the same caliber that are available today, Mitsubishi continues to lead the projector industry by offering this combination of high brightness and high definition at an unprecedented price.</p>

<p>Blasting 5000 lumens with a 1000:1 contrast ratio, the projector uses three robust 1.1 inch 3LCD inorganic panels. This projector is ideal in larger home theaters or commercial venues such as sports bars, restaurants or hotel conference rooms as well as school auditoriums and corporate boardrooms that require full high definition (1920 x 1080 pixels) for HD video or applications such as medical imaging, CAD/CAM designs, geo-spatial mapping, and others. It includes a DVI connector with an HDMI-to-DVI adapter for a wider range of HD connectivity options, and is available in a black or white outer cabinet.</p>

<p>"With a suggested price of $14,995, our new FL7000U offers the best-valued 5000 lumen projector in the full HD market," said Wayne Kozuki, product manager, Mitsubishi Digital Electronics America's Presentation Products Division. "We're very proud to bring a projector this extraordinary to market and show our commitment to a full line of commercial and consumer 1080p projectors."</p>

<p>The FL7000U can create side-by-side images for enhanced video conferencing applications that include a live video feed and simultaneous presentations on the same screen, perfect for large venues where ambient light can be a factor. It also offers RJ45 networking support for easy online management and control.</p>

<p>With a built-in motion-sensitive anti-theft alarm, Mitsubishi's FL7000U is designed to deter projector theft from public venues such as classrooms, auditoriums or other open-access conference room settings. The motion detector is built into the connector panel cover, and is set manually by a key. Once the cover is installed and the safety key removed, the projector's alarm is automatically set. If someone moves the projector, a loud, attention-grabbing beep will sound a 120-decibel high pitch alarm, foiling a potential projector heist.</p>

<p>"The Mitsubishi FL7000U represents a breakthrough in the full high-definition front-projection product space in terms of brightness, resolution and most importantly, affordability," said James Chan, director, product marketing, Mitsubishi Digital Electronics America's Presentation Products Division. "Mitsubishi continues to lead the market in offering the best value for excellent quality products. There are plenty of manufacturers selling projectors at aggressive prices, but ours come with the known quality and innovation that makes our so brand popular."</p>

<p><br />
<B>Pricing, Availability, Warranty</B></p>

<p>The suggested price of Mitsubishi's FL7000U is $14,995 and will be available this month through authorized Mitsubishi dealers. The projector comes with Mitsubishi's three-year limited warranty on parts and labor plus a 90-day limited warranty on the lamp.</p>

