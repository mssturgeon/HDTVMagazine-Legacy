<p><B>LAS VEGAS, Jan. 9 /PRNewswire-FirstCall/</B> -- New Medium Enterprises (NME) (BULLETIN BOARD: NMEN) today at International CES 2008 announced HD VMD players are shipping into the U.S. market. HD VMD is delivering maximum-HD 1080p high-quality players to consumers for a groundbreaking MSRP of $199 via PCRush.com and NMEStore.com. All orders for HD VMD players in January will come with two complementary titles, "Mother Ghost" starring James Franco and cult hit "Cutting Room."</p>

<p>Shipping since December, HD VMD discs and players stand to revolutionize the high-definition disc market, providing consumers with the best possible HD experience. HD VMD's ground-breaking innovation is its patented multi-layer disc, which allows for the utilization of proven red laser technology to provide high definition, versus blue laser technology that competitors are forced to use due to disc space limitations. With only one laser (red), HD VMD players can upconvert existing DVD collections for better viewing quality, as well as play true high definition content.</p>

<p>"We are excited to be delivering upon our promise to deliver high quality, affordable high definition to consumers," said Alex Potter, director of U.S. operations, NME. "We remain committed to delivering great HD products and compelling content to the global consumer market."</p>

<p>NME also this week announced its worldwide distribution deal with SFM Entertainment for the release of rare and classic film and TV titles never before seen in HD on NME's disc format. NME HD VMD players are also currently shipping to Australia and Europe.</p>

<p>HD VMD combines the best industrial opto-electronics and disc technologies, bringing together established DVD red-laser production infrastructure and break-through multilayer discs technology to deliver its maximum-HD picture. HD VMD red laser multilayer disc plans include storage of up to 30 GB of content on a single side disc.</p>

<p>NME is a U.S. publicly listed company headquartered in London with Offices worldwide including Los Angeles.</p>

