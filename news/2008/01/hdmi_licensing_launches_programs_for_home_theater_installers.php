<p><B>LAS VEGAS, Jan. 5 /PRNewswire-FirstCall/</B> -- At the 2008 International Consumer Electronics Show (CES), HDMI Licensing, LLC, the agent responsible for licensing the High-Definition Multimedia Interface(TM) (HDMI(TM)) specification, today announced the launch of a suite of tools and educational programs specifically designed to help the installer community more effectively install home theater systems that are connected with HDMI. The new tools and programs include a dedicated web-based installer area on the HDMI Licensing website, featuring new webinars hosted by HDMI Licensing developed specifically for installers, and a new, easily accessible Knowledge Base that provides installers with tips and answers to help solve installation issues and questions. The new installer section can be found at: http://www.hdmi.org/installers/.</p>

<p>HDMI is the leader in digital connectivity for high-definition consumer electronics, including HDTVs, set-top boxes, DVD players and A/V receivers. Installing with HDMI creates new challenges to installers accustomed to working with analog connections. To help installers with issues of audio and video distribution and with the migration from older analog to best-in-class performance with HDMI connectivity in home theater systems, HDMI Licensing has created a resource to provide installers with the most current technical and "how-to" information with contributions from recognized leaders in the installer community such as Jeff Boccaccio, president of In-Visions Technology, Inc. and Joel Silver, president and founder of Imaging Science Foundation, Inc. Boccaccio and Silver provide their own perspective and tips on installing HDMI.</p>

<p>"The installer community represents a critical part of the HD services ecosystem and they are facing a fundamental change in the technologies they use to provide the highest quality entertainment experience," said Leslie Chard, president of HDMI Licensing. "HDMI is an essential to this new technology offering. As the agent responsible for HDMI and the most direct source of information regarding HDMI, we recognize the need to provide installers with resources that will help them."</p>

<p>"HDMI is now a necessary part of any home theater system to achieve the highest quality HD entertainment experience consumers demand," said Jeff Boccaccio, president of In-Visions Technology Inc. "Installers can look to HDMI Licensing to help them transition from previously analog-driven systems to today's new all-digital world and meet the needs of our customers who are seeking the highest quality HD home theater experience."</p>

<p>"HDMI Licensing continues to deliver innovative programs and educational opportunities for the installer community as we work with HDMI more and more," said Joel Silver, president and founder of Imaging Science Foundation, Inc. "Having a partner that understands the real-world issues we face and that is committed to working with the installer community to tailor educational programs for us is a huge asset to our ability to develop our business and remain competitive. We are excited to contribute to HDMI Licensing's programs to bring helpful information to the installer community."</p>

<p>Included in the new installer section of the website are content areas designed specifically for the installer community. For installers who are new to digital connections, there are introductory sections that outline the benefits of digital connectivity as well as webinars and existing online training modules that earn CEDIA credits. Installers working with HDMI will be able to find information covering topics such as why move to a digital connection, cable length recommendations and interoperability questions, among others. One of the key new features of the HDMI Licensing installer resource is a section of case studies of home theater installation stories directly from installers describing their first-hand experiences with HDMI. The case studies provide tips, lessons learned, recommended products, techniques and other important information for installers, and professionals are encouraged to submit their own HDMI case studies for publication on the site.</p>

<p>Another critical component of this new resource area is an HDMI Knowledge Base. This major contribution to the installer community is a frequently updated database of tips and answers to major issues that arise during installation of HD home theater systems and topics of interest. The Knowledge Base is a keyword searchable collection of questions and answers, organized by major categories ranging from Cables and Connectors, HDMI features, interoperability and HDMI 1.3. For example, the Cables and Connectors section includes a discussion of HDMI and cable length, options for long cable runs, and how to read eye-diagrams. Installers are encouraged to ask new questions as this Knowledge Base will continue to grow and more and more questions are answered.</p>

