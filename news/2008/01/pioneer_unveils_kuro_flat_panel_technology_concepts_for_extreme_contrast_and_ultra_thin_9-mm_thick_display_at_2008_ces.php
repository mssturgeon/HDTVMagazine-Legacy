<p><B>TOKYO--(BUSINESS WIRE)</B>--Pioneer Corporation (TOKYO:6773)(ISIN:JP3780200006) (President and Representative Director: Tamihiko Sudo) today unveils concepts for future plasma display technologies under the code name "Project KURO" at the Consumer Electronics Show in Las Vegas. After a year where it was proved that its award-winning plasma technologies are leagues above the rest of the HDTV industry in picture quality, Pioneer engineers preview future Project KURO concepts for extreme contrast and advanced design. The extreme contrast concept realizes the reproduction of absolute black, and the advanced design concept becomes the world's thinnest 50-inch display(1) at only nine millimeters (mm) thick.</p>

<p>- Project KURO extreme contrast concept</p>

<p>The extreme contrast concept is the industry's first plasma that can achieve absolute black with no measurable light emitting from the display, when reproducing black. Contrast ratio is defined as the ratio of the luminosity of the brightest color (white) to that of the darkest color (black). A high contrast ratio is desirable to recreate ideal picture quality. In televisions, the truer the black, the more accurate the color.</p>

<p>Exploiting the advantages of self-emitting displays, Pioneer has succeeded in reproducing absolute black by achieving zero-idling luminance in more than six million cells. Ultimately, the KURO extreme contrast concept has a contrast ratio that is literally beyond measurement, rendering the debate of contrast ratio irrelevant.</p>

<p>- Project KURO advanced design concept</p>

<p>At nine millimeters (mm) thick - the world's thinnest in 50-inch class(1), this groundbreaking Project KURO technology results in a picture that appears to be floating on a wall, creating an experience for consumers where the television becomes simply a canvas for great entertainment. In addition, its extremely light weight (18.6 kg/41 lbs) allows the television to easily be wall-mounted, contributing handsomely to interior decor.</p>

<p>The Pioneer future Project KURO concepts - part of Pioneer's true engineering passion to deliver an emotional entertainment experience - will be showcased at the 2008 International CES in Las Vegas (CES Booth #9827) from January 7 to 10.</p>

<p>(1) According to Pioneer survey, as of Jan. 7, 2008.</p>

