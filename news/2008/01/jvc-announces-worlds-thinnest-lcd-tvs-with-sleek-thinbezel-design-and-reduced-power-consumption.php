The slim design was made possible through the use of a new JVC-developed slim panel backlight unit and power supply substrate, or chassis. The new slim LCD panel backlight unit is 40 percent smaller in depth and bezel width compared to a conventional LCD backlight, measuring just 0.79 inches (20mm) deep and 0.51 inches (13mm) wide. In addition, the unit weighs only 26.4 lbs (12kg) and consumes a mere 145W.</p>

<p>Efforts to reduce the depth of an LCD panel backlight result in uneven hot spots appearing on the LCD screen surfaces because CCFL light sources are brought closer to the liquid crystal panel. To overcome this problem, either light-diffusing plates are applied or more CCFL tubes are used. But the former approach can result in lower brightness, while the latter approach can be costly and increases power consumption.</p>

<p>JVC's display engineering team succeeded in developing a new, slimmer backlight unit by optimizing the light-diffusing plates and light-reflection sheets, as well as improving its overall composition. This provided uniform light-diffusion at all the corners and edges without the addition of more CCFL tubes, while maintaining adequate luminance to ensure that the screen always remains bright.</p>

<p>JVC also developed a slimmer yet efficient power-supply substrate and employed a direct-mount configuration for it on the LCD panel backlight unit with a fan-less heat dissipation system to further reduce power consumption.</p>

<p>Both models will be VESA compliant for easy wall mounting, but JVC will also offer its own mounting solution - a wall mount designed to position the slim TV closer to the wall than does a standard mount.</p>

<p>*with built-in tuners as of January 6, 2008, according to a JVC survey</p>

<p>The new JVC super-slim LT-42SL89 and LT-46SL89 will be available in early summer. Prices will be announced at that time.</p>

