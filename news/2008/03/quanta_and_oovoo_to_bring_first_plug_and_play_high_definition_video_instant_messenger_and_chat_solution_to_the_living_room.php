<p><B>NEW YORK, March 24 /PRNewswire/</B> -- Quanta Research Institute, the advanced technology research center of Quanta Computer Inc. (www.Quantatw.com), and ooVoo (www.ooVoo.com), the leader in providing high-quality, real-time video communication over the Internet, today announced a technology partnership that will for the first time turn any high-definition television (HDTV) or laptop computer into a simple high definition, multi person video instant messenger and chat screen.</p>

<p>The agreement between Quanta, the world's largest laptop manufacturer, and ooVoo, one of the leading innovators of video conversation on the internet, calls for the creation of an advanced video-based chat system that brings real-time, face-to-face high definition communications to living rooms, laptops and offices. The technology promises to deliver true HDTV quality through a dedicated box or laptop that can be set up anywhere there is a common broadband internet connection and an HDTV display with the same ease as plugging in a webcam and launching a chat with a group of friends.</p>

<p>"The world is just beginning to realize the promise of high definition video as more and more HDTV sets are sold and more HD programming and content becomes available," said CC Leung, vice chairman and president at Quanta Computer. "Quanta is delivering the highest-performing computer hardware platforms since 1988. We are now looking to the day when the benefits of high definition will move from a passive, entertainment-driven technology to one where connecting with friends and collaborating with colleagues is possible in HD. Whether at home, work or on the go, the promise of high definition video opens new possibilities when it is put in a social context. HD video chat is just the first step."</p>

<p>"Quanta and ooVoo are now creating the next frontier in video communication over the Internet," said Philippe Schwartz, CEO of ooVoo. "The promise of this technology is similar to the transition from standard television to high definition television- not only vastly improved quality, but the potential for delivering a totally new experience and service for consumers and businesses through their TVs and laptops. This partnership is a true reflection of ooVoo's mission of enabling deeper, more meaningful and highest quality communication experiences between individuals and groups."</p>

<p>The benefits of HD video conversations range from witnessing the smallest details of a friend's newly renovated kitchen, or seeing the beauty of new grandchild come home for the first time to collaborating with colleagues on the finest details of a circuit board engineering project. When brought together in high definition, the possibilities for connecting with all kinds of social networks in new ways are far reaching.</p>

<p>Quanta plans to leverage its partnership with ooVoo along with its substantial manufacturing resources and global relationships in the computing and consumer electronics industries to develop the technology into a commercially viable product in 2008.</p>

<p><br />
<B>Inside The Technology</B></p>

<p>The Quanta and ooVoo system combines the latest in video compression/decompression technologies to deliver HD in a multipoint environment. The technology for HD video communication utilizes a high- throughput H.264 codec, with a minimum of only 512kbps bandwidth is required for one-way 720p video transactions at 30 fps. This low transaction data rate requirement makes true HD video chat possible for consumers, small and larger businesses with no need for a dedicated lease line.</p>

<p>The incorporation of ooVoo's innovative software allows the Quanta/ooVoo technology to deliver a high quality multi-party video chat experience with low latency associated with video and voice over the internet and can provide improved quality of service, better lip synchronization, reduced video delay and clear audio.</p>

<p><br />
<B>About Quanta</B></p>

<p>Established in 1988, Quanta Computer today is the largest notebook computer ODM company in the world. With leading technology and strong R&D, Quanta has become a leader in hi-tech markets. Besides continuous high growth, high quality and high value creation in notebook computers, Quanta has extended its businesses into enterprise network systems, home entertainment, mobile communication, automotive electronics and digital home markets. With the dedication to technological innovation and education, Chairman Barry Lam launched a new US$200 million R&D center, Quanta R&D Complex (QRDC), in Taiwan. The facility has 2.2 million square feet of floor space, and a capacity to house up to 7,000 engineers. For more information about Quanta, please visit http://www.quantatw.com/ .</p>

<p><br />
<B>About ooVoo</B></p>

<p>ooVoo provides a high-quality video communication service that delivers a more meaningful way for people to call and connect over the Internet. ooVoo's technology enables people to experience a face-to-face conversation and share a full range of emotions as if they are in the same room together, whether they are across the street or across the globe from each other. ooVoo's superior quality video and audio is available to anyone with a computer, broadband connection and a web camera, for real-time video calls with up to six friends, relatives and colleagues simultaneously. ooVoo's high quality video chat service includes video conversation recording, telephony, video messaging, instant message chat and file sharing amongst other capabilities. ooVoo is privately held and headquartered in New York, NY. You can learn more and download free ooVoo software at http://www.oovoo.com/ .</p>

