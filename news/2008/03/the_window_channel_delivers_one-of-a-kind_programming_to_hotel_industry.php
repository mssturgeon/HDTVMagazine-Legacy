<p><B>EDMONDS, Wash.--(BUSINESS WIRE)</B>--The Window Channel creates an exclusive library of High Definition programming for hotel operators offering guests a customized window on the world.</p>

<p>Hotel operators can choose from a wide variety of existing content or work with The Window Channel to produce custom content that promotes the property and the brand.</p>

<p>"The Window Channel brings the world to life in the unparalleled clarity of High Definition with footage from across the street and across the world to create very real scenes that transport you to the location," said Jim Wilmer, partner in The Window Channel. "We can help any hotel create a branded production that not only sells their property's amenities, services and outlets but can also boost incremental revenue and brand loyalty."</p>

<p>"With its relaxing, captivating imagery, The Window Channel has become a critical component of our conversion to our HD television offerings," said Craig Sundell, General Manager of The Westin Stonebriar Resort, recently named Starwood Hotels and Resorts' North American Property of the Year. "From the favorable guest comments we've received, clearly, we have elevated our guest experience to new levels, while enhancing our overall brand promise of rejuvenation and renewal."</p>

<p>"We have footage as diverse as the sunrise from 10,000 feet at Haleakala Creator in Maui to sitting in a crowd at an outdoor café along the Champs-Elysées in Paris," said Mark Knight, partner in The Window Channel. "Our format has a completely immersive feel to it."</p>

<p>The Window Channel, headquartered in Edmonds, Wash. is a production company that produces long-play, ambient and scenic footage shot in High Definition. Each video "window" is at least five minutes in length and is photographed from a single "locked down" shot. The video also contains the ambient audio recorded in 5.1 High Definition Surround Sound from the location. Mark Knight and Jim Wilmer bring a combined 40 years of marketing and hospitality experience to the team. For more information please visit www.thewindowchannel.com.</p>
