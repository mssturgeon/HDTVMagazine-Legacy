				<p class="prtitle">Plextor Announces New Internal Blu-Ray Drives</p>

<p><B>MILPITAS, Calif.--(BUSINESS WIRE)--</B>Plextor&reg; LLC, a leading developer and manufacturer of high-performance digital media equipment, today announced two new multifunction disc drives that combine next-generation Blu-Ray and HD DVD technologies.</p>

<p>The internal PX-B920SA drive features 4X BD-R write speed and a Serial ATA (SATA) interface for fast data throughput, up to 150 Mbits/sec. This drive is ideal for PC OEMs, systems integrators, enterprises, professionals, and high-end consumer markets where people want HD DVD playback along with Blu-Ray recording and playback.</p>

<p>The new PX-B920SA is a Blu-Ray burner that also plays HD DVD discs and supports high-speed reading and recording of DVD and CD media formats, including DVD-RAM, Dual Layer DVD, Double Layer DVD, DVD&plusmn;R/RW, and CD-R/RW.</p>

<p>The new PX-B300SA multifunction drive is capable of playing both Blu-Ray and HD DVD media. The internal drive also reads and records DVD and CD media formats with recording speeds of 16X DVD&plusmn;R, 24X CD-RW, and 40X CD-R. The PX-B300SA, which includes a SATA interface for high performance, is designed for PC OEMs, systems integrators, enterprises, professionals, and mid-market consumers who want to playback both Blu-Ray and HD DVD discs and record on DVD and CD media.</p>

<p>"With the recent end of the DVD format wars, these new combos drives from Plextor still offer customers the freedom to view high-definition video media they prefer to use, whether Blu-Ray or HD DVD," said Amber Wang, director of new business development and marketing at Plextor. "According to Home Media, more than 1.5 million HD DVD movies have been sold in the United States to date. Our new drives give customers the ability to play HD DVD movies as well as Blu-ray discs."</p>

<p><br />
<B>PX-B920SA Multifunction Disc Drive</B></p>

<p>The PX-B920SA drive supports fast Blu-Ray recording speeds of 4X BD-R (18 MB/sec transfer rate) and 2X BD-RE (9 MB/sec transfer rate) on single layer and double-layer media. Playback is 4.8X for Blu-Ray BDMV (movie) discs and 3X for HD DVD Video discs.</p>

<p>For DVD, the PX-B920SA delivers 16X DVD&plusmn;R on single-layer media, 4X DVD&plusmn;R on Double-Layer and Dual-Layer (DL) media, and 5X DVD-RAM. The drive also supports 8X DVD+RW, 6X DVD-RW, 6X max DVD-ROM, 40X CD-R, 24X CD-RW, and 40X CD-ROM. The PX-B920SA drive features a 4MB data buffer. The drive is LgihtScribe enabled for direct disc laser printing.</p>

<p>The PX-B920SA drive comes bundled with a single rewritable 25GB BD-RE media disc and a complete package of application software, including InterVideo WinDVD 8, Ulead MovieFactory 5.5 SE, and Burn.Now 4.5 SE.</p>

<p><br />
<B>PX-B300SA Multifunction Disc Drive</B></p>

<p>The PX-B300SA drive offers 4.8X BDMV and 3X HD DVD reading. For DVD, the drive delivers 16X DVD&plusmn;R on single-layer media, 4X DVD&plusmn;R on Double-Layer and Dual-Layer (DL) media, and 5X DVD-RAM. The drive also supports 8X DVD+RW, 6X DVD-RW, 6X max DVD-ROM, 40X CD-R, 24X CD-RW, and 40X CD-ROM. The PX-B300SA drive features a 4MB data buffer. The drive is LgihtScribe enabled for direct disc laser printing.</p>

<p>The PX-B300SA drive comes bundled with a complete package of application software, including InterVideo WinDVD 8, Ulead MovieFactory 5.5 SE, and Burn.Now 4.5 SE.</p>

<p><br />
<B>Pricing and Availability</B></p>

<p>Plextor will ship the PX-B920SA drive to distributors in North and South America in late March 2008, with a Manufacturer's Suggested Retail Price (MSRP) of $599.99 USD. Plextor will ship the PX-B300SA drive to distributors in North and South America in late March 2008, with a Manufacturer's Suggested Retail Price (MSRP) of $499.99 USD.</p>

<p>All retail packages include one-year full warranty and unlimited toll-free technical support.</p>

