<center><i>Four new AMD Phenom&trade; X4 Processors Pair with AMD Enthusiast Platform to Propel the Ultimate Visual Experience</i></center><br />
<br />

<p><B>SUNNYVALE, Calif.--(BUSINESS WIRE)--</B> AMD (NYSE: AMD) today announced immediate availability of four new high-performance AMD Phenom&trade; X4 processors for PC users in search of the Ultimate Visual Experience. Led by the AMD Phenom X4 9850 Black Edition processor, each CPU features true quad-core design, and when matched to AMD 790 series chipsets supports up to four award-winning ATI Radeon&trade; HD 3800 series graphics cards. This enthusiast PC platform, codenamed "Spider," energizes the latest PC gaming titles, speeds high-definition video playback, and delivers amazing performance for advanced productivity and multi-tasking.</p>

<p>"These new AMD Phenom X4 processors unlock even greater visual computing performance to showcase the unparalleled scalability of the AMD enthusiast platform," said Mario Rivas, executive vice president, computing solutions group, AMD. "Based on AMD's advanced true quad-core architecture, these processors are loaded with powerful performance features like next-generation HyperTransport&trade; 3.0 and energy-efficient innovations like Cool'n'Quiet&trade; 2.0 technology."</p>

<p>Featuring the best quad-core desktop CPUs AMD has offered, these AMD Phenom X4 quad-core processors can improve performance for gaming and multi-threaded applications. The AMD Phenom X4 9850 Black Edition is the top performer in the new line-up, with Clock Multiplier Control(1) for tunable performance that gives gamers and enthusiasts scalability and customizable performance levels to run multiple processor-intensive applications simultaneously.</p>

<p>"As the worldwide leader in the PC industry, HP is pleased to be offering our customers the choice of AMD Phenom X3 and X4 based systems in our consumer desktop PCs," said Thi La, director of marketing, North America Consumer Computing, HP. "We are seeing a strong market demand for increased performance and multi-core capabilities."</p>

<p>Consumers are now rapidly adopting quad-core processor-based desktops, as usage models expand to HD entertainment applications and gaming. AMD has responded with innovations like the AMD Phenom X4 processor and the "Spider" quad-core enthusiast platform, which commands both a high-performance and energy efficient market position at a compelling price.</p>

<p><br />
<B>AMD Phenom X4 9000 Series Quad-Core Processors</B></p>

<p>The AMD Phenom quad-core processor is the world's most advanced desktop PC processor, commanding four natively integrated processor cores to break system bandwidth barriers and turbo-charge high definition (HD) platform performance. Customers can implement AMD Phenom X4 processors 9550 (2.2GHz) and 9650 (2.3GHz), or experience an enhanced multi-tasking experience with two higher frequency processors: the AMD Phenom X4 9750 (2.4GHz) and AMD Phenom X4 9850 Black Edition (2.5GHz) processors.</p>

