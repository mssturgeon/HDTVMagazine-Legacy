<p><B>KNOXVILLE, Tenn.--(BUSINESS WIRE)</B>--Scripps Networks' HGTV and Food Network will simulcast their respective standard-definition and high-definition feeds to cable and satellite affiliates beginning March 31, 2008. This means that the rapidly growing number of HD-enabled households will be able to watch their favorite Food Network and HGTV programs in high-definition at the same time the shows air on the standard-definition channels.</p>

<p>Since launching in 2006, HGTV-HD and Food Network-HD have carried a number of popular programs in high-definition on a separate schedule.</p>

<p>"We are moving from a wheel format to a full-blown simulcast because of affiliate and viewer demand," said Hal Rosenberg, senior vice president, affiliate sales at Scripps Networks. "The programming simulcast is not only great news for Food Network-HD and HGTV-HD viewers, it also gives our affiliates a new tool to help drive HD upgrades."</p>

<p>The move will be popular as well with advertisers, whose commercials will have presence on both SD and HD channels at the same time.</p>

<p>The popular lifestyle programming on both networks lends itself to presentation in high-definition. As two of the most visually-appealing networks, HGTV-HD and Food Network-HD enhance the viewer experience of favorites like Food Network's Throwdown with Bobby Flay, and House Hunters on HGTV, among the programs produced in native high-definition. Moreover, Food Network plans to ramp up its production of high-definition programs and is upgrading its Chelsea Market studios in New York to full high-definition capability.</p>

<p>Distribution of HGTV-HD and Food Network-HD combined exceeds 25 million households, and is growing rapidly. "We have agreements in place with every major affiliate," Rosenberg says.</p>

<p>Scripps Networks is comprised of the lifestyle television brands HGTV, Food Network, DIY Network, Fine Living Network and country music network Great American Country (GAC). Scripps is the leading developer of lifestyle-oriented content for television and the Internet, where on-air programming is complemented with an array of broadband video, social media areas and e-commerce components on companion Web sites.</p>

<p>In addition, Scripps Networks has launched HGTV and Food Network in high definition and is aggressively developing its emerging media platforms for broadband and video on demand. Scripps Networks also acquired popular recipe Web site Recipezaar.com and Incando Corp. to deepen its user-generated content capabilities. Scripps Networks' brands collectively are available in more than 175 countries and territories on all seven continents. </p>
