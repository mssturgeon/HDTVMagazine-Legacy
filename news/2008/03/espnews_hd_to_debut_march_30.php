<p class="prtitle">ESPNEWS HD To Debut March 30</p>

<center><i>Debut to be Simulcast on ESPN HD<br />New Look, New Graphics, New Music & More</i></center><br />
<br />

<p>ESPNEWS, the nation's only all-sports news television network, will debut a new high-definition studio and an entire new look on Sunday, March 30 at 8 a.m. ET with the first hour simulcast on ESPN HD. In addition, twice later that day - at 11:30 a.m. and at 11:30 p.m. - ESPNEWS HD will be simulcast for 30 minutes on ESPN2 HD.</p>

<p>One notable innovation in the 16x9 HD delivery of ESPNEWS is the "HD Sideline" graphic. This latest incarnation of the traditional "BottomLine" will now wrap around the top, left and bottom of the screen for HD viewers. This will allow for additional real-time information - news, scores, stats, headshots, standings, and more - to be imparted, while still delivering 16x9 HD video in the remaining space. The familiar "BottomLine" on ESPNEWS' standard definition presentation has also been redesigned to convey additional text, headshots and graphics. It will continue to reside at the bottom edge of the screen.</p>

<p>The new studio environment is larger and more versatile than the one it replaces. There are two primary desks, seating up to four and five people, respectively, allowing for interviews, debates and more. A new area has been designed for anchor "stand-ups," giving ESPNEWS HD much more flexibility in its presentation. The backdrop of the set is ESPN's new multimedia newsroom, just as the former set was positioned in the old newsroom, which only served the company's television outlets. For downloadable images of the new ESPNEWS set and "HD Sideline" graphic, please click here.</p>

<p>In addition, viewers will also notice changes to both the network's look and sound. The current orange and red color scheme is being replaced by shades of steel blue supplemented by yellow and red. The animation package, including show opens and other signature elements, has been redesigned. The graphics package has been fully reinvented and features real-time automation which populates ESPNEWS HD with the latest up-to-the-second scores and statistics. All of these elements together are intended to express the notion that ESPNEWS HD is the center of the sports information universe. The music has also been freshened, with the network's familiar theme now featuring a more modern and full orchestra sound.</p>

<p>"March 30 will be a special day for ESPN and sports fans," said Bryan Burns, ESPN vice president of strategic business planning and development. "The launch of ESPNEWS HD comes on the fifth birthday of ESPN HD, which jump started the move to high definition television in the United States. Everyone involved with ESPNEWS has worked very diligently over the last year to prepare our first service that provides information not available on its standard definition counterpart. This is a milestone concept at ESPN, and one we believe our affiliates and consumers will rapidly label as a "must have."</p>

<p>The debut of the new set, graphics and music will coincide with that night's start of the Major League Baseball season as the Washington Nationals unveil their new stadium, playing the Atlanta Braves on ESPN2 HD at 8 p.m. ESPNEWS HD will also feature extensive coverage of that day's NCAA Men's Basketball Tournament Regional Finals.</p>

<p><br />
<B>ESPN's HD Networks</B></p>

<p>ESPNEWS HD joins ESPN HD and ESPN2 HD as the country's leading high-definition offerings for sports fans. ESPN HD was launched March 30, 2003, and reaches almost 17 million subscribers; it is available to almost 94 million homes. ESPN2 HD debuted January 5, 2005. It reaches more than 12 million subscribers and is available to more than 81 million homes.</p>

<p>In 2008, ESPN HD and ESPN2 HD will deliver more than 12,000 hours in high definition including all of ESPN's NASCAR coverage, NBA telecasts, MLS telecasts, MLB telecasts, college football telecasts, National Hot Rod Association races and coverage of NFL Monday Night Football. All of ESPN and ESPN2's Bristol-based studio programming originates in high definition, including SportsCenter, NFL Countdown, NFL Monday Night Countdown, NFL Live, Monday Night Countdown, Baseball Tonight, Mike & Mike in the Morning and First Take. In addition to live sports programming, ESPN HD and ESPN2 HD produce individual programs, movies and series.</p>

<p>In addition to ESPNEWS HD, ESPN will launch two additional high definition services in 2008 - ESPN HD Australia (mid 2008), and ESPNU HD (August 28).</p>

