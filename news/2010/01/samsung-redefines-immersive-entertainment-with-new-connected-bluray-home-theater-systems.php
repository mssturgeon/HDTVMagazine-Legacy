<p>“Samsung has always prided itself on delivering thoughtfully-designed immersive experiences to every type of home theater enthusiast,” said Sung-Ho Jun, Senior Vice President of Visual Display Division at Samsung Electronics. "This year we’re kicking it up a notch by greatly enhancing the systems’ audio quality and adding unprecedented connectivity, enabling consumers to access a diverse range of entertaining content.”</p>

<p><br />
<strong>Samsung HT-C6730W: Recipient of the CES “Best of Innovations 2010” Award</strong></p>

<p>The 1330W HT-C6730W was designed for the ultimate home theater aficionado and is the most powerful audio system Samsung offers with lifelike 7.1-channel surround sound which fully immerses viewers in their entertainment experience. The system introduces a built-in digital signal processor (DSP) that allows for realistic vertical 3D surround sound experience. Boasting 1080p video playback for both Blu-ray discs and standard DVDs, the unit supports the Dolby Digital Plus™, Dolby TrueHD™ and DTS-HD Master Audio high-definition audio formats. The system includes eight speakers; a wide center channel speaker, a large subwoofer, two tower speakers and four surround speakers, including wireless rear satellite speakers. </p>

<p>The HT-C6730W comes in a dark black, high gloss finish for a distinct elegance that matches the quality of the sound.</p>

<p><br />
<strong>The Samsung HT-C7530W: Perfect Balance of Design and Performance</strong></p>

<p>Samsung’s 800W HT-C7530W takes home theater component design to new heights. Featuring a nature-inspired Touch of Color™ (ToC™) design, the HT-C7530W matches modern interior design aesthetics while also complementing Samsung’s stylish HDTVs. Suggesting high-end furniture rather than high-end acoustics, the receiver’s cabinet has a wood-grain texture and is encased in a luxurious translucent material. The 5.1-channel system consists of two tall satellite speakers, 2 wireless rear speakers, a center unit and an active subwoofer.  </p>

<p><br />
<strong>Samsung HT-C6500: Impressive Features in a Small Package</strong></p>

<p>The 1000W HT-C6500 delivers the perfect home theater experience for small spaces. The system features built-in Wi-Fi, 1GB of built-in storage, 5.1 channel surround sound and advanced auto sound calibration in a compact package that doesn’t sacrifice audio or picture quality.</p>

