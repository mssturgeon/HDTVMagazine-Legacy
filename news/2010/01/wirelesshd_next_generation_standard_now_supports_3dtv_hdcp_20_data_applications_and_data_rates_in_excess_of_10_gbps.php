<p><b>Sunnyvale, California and Las Vegas, Nevada  – January 5, 2010</b>  – The WirelessHD&reg; Consortium, the first and largest 60 GHz initiative worldwide and the only wireless standard that provides wireless lossless A/V support, today announced a major enhancement to the WirelessHD 1.0 specification. The next generation of the WirelessHD specification will enable HDTVs, Blu-ray disc players, PCs and portable devices to transmit, share and display content in billions of colors with unprecedented vividness and accuracy as well as instantaneously transfer large multi-gigabyte media files among a variety of devices.  The WirelessHD standards group also announced its new authorized self test house (ASTH), extending the WirelessHD Compliance Test Program capabilities.</p>

<p>Panasonic has developed a WirelessHD Authorized Self Test House. They now have an internal facility where they will be able to test WirelessHD products for protocol compliance and interoperability in early 2010.</p>

<p>The WirelessHD specification, the de facto standard wireless digital interface for high definition consumer electronics, is currently supported by almost 50 global technology industry leaders. Products with the updated technology, which is the only 60 GHz specification that is included in the Institute of Electrical Engineering (IEEE) 802.15.3c global standard, will be backward compatible to those products using WirelessHD 1.0 that have been shipping since early 2009.  The update reflects the determination of the WirelessHD founders to ensure WirelessHD continues extending its utility and evolving ahead of future consumer demands.</p>

<p><br />
<strong>New WirelessHD specification capabilities include:</strong></p>

<ul><li><strong>Highest data rates</strong>: The next generation spec increases the data rate to 10 – 28 Gbps, an unprecedented level of wireless bandwidth. This will support the demands of future high definition display devices, such as higher resolutions, Deep Color™ and high frame rates, as well as high speed data applications.</li><li><strong>3D over WirelessHD</strong>:  The new specification will define common 3D formats and resolutions for WirelessHD-enabled devices.</li><li><strong>4K resolution support</strong> enables devices to support HD resolution four times beyond the resolution of 1080p. This feature allows the WirelessHD interface to transmit content at the same resolution as many digital theaters.</li><li><strong>Data support</strong>: Connected devices that include this feature supports sync’n go file transfers at 1Gbps for portable and fixed devices. This new specification also provides for IP connectivity for Internet access and networking of WirelessHD devices.</li><li><strong>Portable device support</strong>: The scalability of WirelessHD technology has been extended to support lossless video streaming plus 1Gbps data connectivity in low-power portable devices such as portable media players, netbooks and smartphones.</li><li><strong>HDCP 2.0 content protection over WirelessHD</strong>: In addition to DTCP, both the current and future versions of WirelessHD will include support for HDCP 2.0 content protection.  WirelessHD is the only standard to support both streaming and copying of multimedia content.</li></ul>

<p>"WirelessHD is an established cornerstone for the High Definition TV industry and we are extremely pleased to see such significant improvements in this new version,” said John LeMoncheck, President and CEO of SiBEAM, Inc. “We look forward to continuing to work with other WirelessHD Founder companies to extend the scope of WirelessHD across new devices and applications, while remaining entirely committed to ensuring full backward compatibility with existing products." </p>

<p>“The dramatic increase in maximum speed achieved in the next generation of the WirelessHD specification will enable WirelessHD to stay far ahead of the bandwidth demands of future high definition source and display devices,” said John Marshall, Chairman of the WirelessHD Consortium. “As the de facto standard digital interface for the high definition and consumer electronics markets, WirelessHD is implementing the most innovative technologies today to fulfill the demands of tomorrow’s consumers.” </p>

