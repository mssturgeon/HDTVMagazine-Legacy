				<p class="prtitle">SONY UNVEILS NEW SOLID STATE CAMCORDERS</p>

<p><strong>LAS VEGAS (CES Booth 14200) Jan. 6, 2010</strong> – Sony Electronics is expanding its line of solid state camcorders with two new models designed to broaden the shooting capabilities for professionals and consumers. The company is introducing its first professional camcorder that implements the AVCHD format, the HXR-NX5U, as well as a consumer AVCHD model, HDR-AX2000.</p>

<p>The professional HXR-NX5U model is part of Sony’s NXCAM family of video products for professionals. It features Sony’s Exmor™ CMOS sensor with ClearVid™ array, to deliver full high-definition resolution and low light sensitivity with low noise. The camcorder will record AVCHD up to 24Mbps, delivering 1920x1080 high definition images with both interlace and progressive modes along with native 1080/24P, 720/60p and MPEG-2 standard definition recording. Only the professional NX5U camcorder includes both HD-SDI and HDMI™ outputs, as well as two-channel linear PCM audio capabilities.  Other unique features for the professional NX5U camcorder include 720/60P recording, built-in GPS function, SMPTE Time Code I/O and an upgrade option for 60i/50i switchable.</p>

<p>AVCHD technology has been widely adopted in Sony’s consumer camcorder line. In the professional market, Sony has already introduced one AVCHD-based model: the compact point-of-view (POV) camera and solid-state recorder combination, model HXR-MC1.</p>

<p>According to Sony, AVCHD is a highly efficient long-GOP codec based on MPEG-4 AVC/H.264 Long-GOP image compression, a member of the MPEG family of codecs. This approach is consistent with Sony’s current line-up of MPEG professional camcorders, including the HDV™, XDCAM® HD optical and XDCAM EX™ series.</p>

<p>The new NXCAM model also shares the 20x optical zoom G lens used in Sony’s HVR-Z5U professional camcorder. The camcorder uses two types of consumer media along with an optional HXR-FMU128 128GB Flash Memory Unit for more than 11 hours of recording time at 24 Mbps. The HXR-FMU128 unit can be easily removed and simply powered through a computer’s USB connection, to make file downloading or editing easier and faster. Besides the Memory Stick PRO Duo™ media, users are also able to record HD content on class 4 or higher SDHC cards. </p>

<p>The new HXR-NX5U will be available this month, at a suggested list price of $4,950, which is the same as Sony’s highly successful HVR-Z5U.  The HXR-FMU128 unit will also be available this month, at a suggested list price of $800.  It can only be used with the professional model HXR-NX5U, not with the HDR-AX2000.</p>

<p><br />
<strong>For High-end Prosumers</strong></p>

<p>With both the HXR-NX5U and the HDR-AX2000 Handycam® camcorders, professionals and more adept consumer videographers can achieve a deep cinematic look with film-like movie quality and advanced color settings.</p>

<p>Recording full 1920x1080/60i high-definition video at up to 24Mbps, the HDR-AX2000 features progressive scan at 1080/24p and 30p, giving video film-quality motions for brilliant scene reproduction. Sony’s new prosumer camcorder delivers HD broadcast-quality images with the convenience of a non-linear recording format to Memory Stick PRO Duo™ media for editing and playback. CinemaTone Gamma™ and CinemaTone Color settings complement the 24P capabilities by providing the color and gamma range for an even more high-end feel and extra control over image expression.</p>

<p>The model uses three 1/3" Exmor™ CMOS Sensors with Exmor derived technology to improve the color reproduction of video recordings and capture sharp, detailed images even in less than perfect lighting situations. Noise reduction is accomplished via the unique column-parallel analog-to-digital conversion technique and grid arrangement of the photo diodes, which are designed to provide high sensitivity, deep resolution, high-speed reading, and a wider dynamic range. The Exmor technologies combine to allow the new camcorders to perform significantly better in low-light environments with sensitivity of 1.5 lux.</p>

<p>The EIP processor is able to rapidly process the vast amounts of pixel data read from the three 1/3” Exmor CMOS Sensors, and record beautiful HD and colorful video. The Exmor CMOS Sensors were developed using some of the most advanced technologies in the semiconductor industry. They handle video data in 1920 x 1080p and 4:2:2 color space for high-quality signal processing before recording it to the dual Memory Stick PRO Duo media. Together, the EIP and Exmor CMOS Sensors imaging system allows both HXR-NX5U and the HDR-AX2000 camcorder to provide extremely high image quality with smooth gradation and detailed image reproduction. </p>

<p>The new camcorder uses Sony’s 3.2” (16:9) (measured diagonally) Xtra Fine LCD™ screen (921K) and Xtra Fine LCD electronic viewfinder (0.45-inch, 1,227,000 dots) for high-resolution and high-contrast images with remarkable color reproduction. </p>

<p>Equipped with a refined level of optical performance, both HXR-NX5U and the HDR-AX2000 also have a 29.5mm Wide-Angle to 590mm Telephoto G-Lens, extra-low dispersion glass and 20x optical zoom. The fixed lens is optimized to perfectly complement the cameras’ advanced image sensor and image-processing technology.</p>

<p>Optical SteadyShot™ image stabilization with Active Mode improves on existing Optical SteadyShot image stabilization by allowing the camera lens to shift over a greater range of motion allowing the camera to compensate for greater degrees of camera shake and deliver a stunning level of image smoothness. </p>

<p>Both models features three built-in neutral density filters for adjusting the amount of light entering the image sensor through the lens and enables prosumers to define their own manual settings for iris, gain, white balance, shutter speed and focus for increased creativity and control. Use of any of the three manual rings for adjustments to zoom, focus and iris provides even more flexibility and makes it possible to fine-tune the settings. This allows users to conveniently assign features used often to shortcut buttons so they can be accessed quickly without going through a menu.</p>

<p>Since professional quality video requires professional quality audio, both models feature dual XLR 3-pin audio jacks for +48V phantom power to external microphones.  Additionally, the grounded connection allows insertion/removal of connectors in live equipment without picking up external signals.</p>

<p>The HDR-AX2000 camcorder is scheduled to be available in March for about $3,500 at authorized dealers nationwide, Sony Style® retail stores and online through <a target="_blank" href="http://www.sonystyle.com/">www.sonystyle.com</a>.</p>
