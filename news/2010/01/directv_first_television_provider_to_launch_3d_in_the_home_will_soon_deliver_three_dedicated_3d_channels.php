<p><strong>LAS VEGAS, Jan 06, 2010 /PRNewswire via COMTEX News Network/ -- </strong>DIRECTV, the world's most popular television service, and Panasonic, a world leader in HDTV and digital electronics, announced today a strategic relationship that, for the first time, will bring 3D TV, the next frontier of television entertainment, to the largest audience nationwide. Beginning in June 2010, millions of DIRECTV HD customers will receive a free software upgrade enabling them to have access to three dedicated 3D channels through their 3D television sets, such as Panasonic's VIERA Full HD 3D TVs.</p>

<p>Panasonic will be the exclusive presenting sponsor of DIRECTV's new HD 3D channels, which will deliver movies, sports and entertainment content from some of the world's most renowned 3D producers. DIRECTV and Panasonic will leverage current relationships with programming partners and movie studios to obtain new and existing 3D content. DIRECTV is currently working with AEG/AEG Digital Media, CBS, Fox Sports/FSN, Golden Boy Promotions, HDNet, MTV, NBC Universal and Turner Broadcasting System, Inc., to develop additional 3D programming that will debut in 2010-2011. The sponsorship will feature Panasonic branding on all DIRECTV 3D channels for a one-year period.</p>

<p>"We led the way with HD and we are excited to do the same with 3D," said Eric Shanks, executive vice president, DIRECTV Entertainment. "Adding the most HD channels to our lineup gave customers a viewing experience that was incredibly lifelike; adding 3D to the mix will take that one step further allowing them to become part of the cast as the picture comes to life in their living rooms. We are taking a technology that at one time could only be seen in a theater and bringing it into the living rooms of the largest audience in the United States. By partnering with Panasonic, we are bringing together two industry leaders to deliver the most advanced television technology available today and together we are continuing to set the standard for the best television viewing experience available."</p>

<p>"Panasonic has been developing 3D standards for television for several years, and we believe it represents a fundamentally new experience in home entertainment because it adds the immersive nature of real life," said Yoshi Yamada, chairman &amp; CEO of Panasonic Corporation of North America. "Our relationship with DIRECTV is a core component of our 'end-to-end' strategy of building out an entire 3D entertainment ecosystem. From leading the development of the Full HD 3D standard for Blu-ray Disc to launching Full HD 3D stereoscopic prosumer camcorders; to now supporting broadcast of 3D content by DIRECTV; to introducing a broad line of Full HD 3D VIERA televisions and a Full HD 3D Blu-ray player in 2010; our commitment to 3D is unquestioned in the industry."</p>

<p>At launch, the new DIRECTV HD 3D programming platform, powered by Panasonic, will offer a 24/7 3D pay per view channel focused on movies, documentaries and other programming, a 24/7 3D DIRECTV on Demand channel and a free 3D sampler demo channel featuring event programming such as sports, music and other content.</p>

<p>In addition, Panasonic is working to make available 3D production tools, such as Full HD 3D camcorders, professional monitors and related production technology assistance.</p>

<p>Panasonic will showcase its suite of Full HD 3D VIERA televisions and home theater system products tuned to a dedicated DIRECTV 3D channel with exclusive content from the motion picture, "AVATAR" and other sports, entertainment, documentary and music footage at its booth (Las Vegas Convention Center, Central Hall, #9405) at the 2010 Consumer Electronics Show in Las Vegas.</p>

<p>For more information on Panasonic's Full HD 3D Technology, visit <a target="_blank" href="http://www.panasonic.com/3D/">www.panasonic.com/3D</a>.</p>

