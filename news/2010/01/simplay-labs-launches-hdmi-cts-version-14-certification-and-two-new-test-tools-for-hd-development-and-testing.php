<p>As manufacturers quickly develop and release HDMI Version 1.4-enabled products, Simplay has launched HDMI Authorized Test Center (ATC) support for the latest specification. Products recently certified will release in the consumer marketplace in early 2010. In addition to standard ATC testing services manufacturers can also leverage the technical support of Simplay Labs consulting resources which provide system-level application engineering and design integration services.</p>

<p><br />
<strong>Fourth Anniversary of Simplay Ushers in The Enhanced Simplay HD&trade; Certification Program</strong></p>

<p>Since its inception in January 2006, Simplay Labs has steadily grown to include 105 partnerships and a testing portfolio of almost 500 products certified for Simplay HD. Products that have passed certification are distinguished by their performance and interoperability, ease of use, and consumer satisfaction. The enhanced Simplay HD certification program for 2010 accounts for the new HDMI Specification Version 1.4 features, and new cables and devices enabled with HDMI Version 1.4 will go through this unique and robust test regimen to ensure optimum performance and quality.</p>

<p><br />
<strong>New Locations Expand Simplay’s Reach and Manufacturer Support</strong></p>

<p>In the fourth quarter of 2009 Simplay opened upgraded facilities in both Shenzhen and Shanghai China, and expanded into new markets by opening the only authorized ATC in Korea. Along with its Sunnyvale, California facility, Simplay operates 4 HDMI Authorized Test Centers globally and is the only non-consumer electronics manufacturer ATC testing facility.</p>

<p><br />
<strong>New CEC Explorer&trade; Recommended as Official Test Tool for HDMI Compliance Test Specification</strong> Version 1.4</p>

<p>The Simplay CEC Explorer SL 309 Development Tool has been officially recommended as a compliance test tool in the HDMI CTS Version 1.4. The tool helps design engineers develop, simulate and debug all aspects of CEC (Consumer Electronics Control)/CDC (Capability, Discovery and Control) functionality in real time, and includes a powerful GUI (Graphical User Interface) that allows engineers to interface with their own product prototype by exercising and monitoring CEC/CDC performance. The Explorer is the only tool officially recommended for CDC and the only tool that tests for both CEC and CDC. It also enables the testing for HDMI Ethernet Channel and Audio Return Channel through its CDC and CEC capabilities.</p>

<p><br />
<strong>Simplay Announces the Universal Test System (UTS)</strong></p>

<p>Continuing the pace of expanding capabilities of HD-enabled devices, Simplay’s release of the Universal Test System will serve a unique need in the marketplace. This multi-technology and human behavior scoring test tool solution enables all HDMI features performance and consumer experience testing. The complexity of new HD features across multiple technologies requires new product quality testing techniques and approaches. Product quality metrics are evolving from simple single standards support to more complex “use case” support.</p>

<p>The new tool features a modular design and integrated human-perception modeling technologies which allow testing and service organizations to customize the solution for their specific requirements as well as add test functions as needed.</p>

