				<p class="prtitle">Technicolor Brings 3D to the Home and Beyond</p>

<center><i>Company Launches Innovations to Accelerate Proliferation of Quality 3D Experiences to Consumers</center></i><br />
<br />

<p><strong>LAS VEGAS--(BUSINESS WIRE)--</strong>Technicolor (Euronext Paris: 18453; NYSE: TMS) today announced several innovations to support the consumer electronic industry’s migration to 3D, including new technologies for Blu-ray 3D, broadcast 3D, 3D subtitling, and auto-stereoscopic 3D delivery to mobile handsets.</p>

<p>“Theatrical 3D is the gateway to in-home 3D,” said Frederic Rose, Chairman and Chief Executive Officer, Technicolor. “The revival of 3D movies at the multiplex has overwhelmingly engaged and intrigued consumers who now want immersive entertainment experiences in the comfort of their homes. From theatrical to the living room and beyond, wherever advancement in the entertainment experience goes, Technicolor goes. ”</p>

<p><strong>Technicolor will demonstrate the following at CES:</strong><br />
<ul><li><strong>Blu-ray 3D</strong>: Already a leader in the content preparation and replication of DVDs and Blu-ray discs, Technicolor has developed the first advanced compression and authoring solution to bring the recently released Blu-ray 3D specifications to production reality. Technicolor has expanded its capacity in anticipation of increased demand for Blu-ray 3D authoring.</li><li><strong>Broadcast 3D</strong>: Technicolor has built the first independent 3D broadcast facility located at its London broadcast location at Chiswick Park. The 3D channel is capable of transmitting both live and pre-recorded 3D content using a conventional HD channel. The solution is currently delivering content to a Technicolor HD set-top-box. The company is now ready to offer this service to its network service provider and broadcast clients.</li><li><strong>Automated 3D Subtitling Creation</strong>: Subtitles in 3D introduce unique challenges due to the number of various depths at which objects appear on the screen, thus creating limitations on where subtitles can be placed. Technicolor has developed a production tool that automatically recommends the best placement of subtitles to minimize disruption to the creative intent of the content.</li><li><strong>Auto-stereoscopic Content Delivery on Mobile</strong>: Technicolor will be showcasing its extensive authoring and compression expertise to deliver auto-stereoscopic (glasses-free) 3D experiences to mobile handsets.</li><li><strong>Theatrical Technicolor 3D Solution</strong>: In addition to the demonstrations listed above, Technicolor will be providing updates regarding deployment of its 3D on Film solution which was announced last year in September.</li><li><strong>Technicolor Alliance with Samsung and DreamWorks to Deliver 3D Blu-Ray to the Home</strong>: Technicolor also announced today an exclusive global alliance with Samsung Electronics America, Inc., and DreamWorks Animation SKG for the delivery of a complete 3D home entertainment solution to homes in 2010. The three companies have joined forces to accelerate the worldwide deployment of in-home 3D to mainstream consumers. The solution includes a broad line-up of 3D-capable HDTVs from Samsung, Samsung’s new 3D Blu-ray disc player, and an exclusive promotion that includes a feature-length, 3D Blu-ray version of DreamWorks Animation’s 2009 release, MONSTERS VS. ALIENS to be created and produced by Technicolor.</li><li><strong>Technicolor Connect</strong>: Demonstrating its continued leadership and vision of tomorrow’s networked residential ecosystem, Technicolor will also showcase its new line-up of advanced set-top-box and gateways at CES.</li></ul></p>

<p><br />
<strong>Technicolor at CES</strong></p>

<p>Technicolor will demonstrate the company’s “Technicolor Genuine 3D” innovations by appointment only at CES booth #13219 Central Hall. Technicolor will also be in the CES 3D Tech Zone, Central Hall booth #14448. Media requests for demonstrations and executive interviews should be made by emailing press contacts noted in this release.</p>

<p><br />
<strong>About Technicolor</strong></p>

<p>Headquartered in Hollywood, Calif., with more than 95 years of experience in entertainment innovation, Technicolor serves an international base of entertainment, software, and gaming customers. The company is a leading provider of production, postproduction, and distribution services to content creators, network service providers and broadcasters. Technicolor is the world’s largest film processor; the largest independent manufacturer and distributor of DVDs (including Blu-ray Disc); and, a leading global supplier of set-top boxes and gateways. The company also operates an Intellectual Property and Licensing business unit managing more than 40,000 patents. For more information: http://<a target="_blank" href="http://www.technicolor.com/">www.technicolor.com</a>.</p>
