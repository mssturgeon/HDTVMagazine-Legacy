				<p class="prtitle">Haier Introduces Ultra-Slim LED HDTV Line Today at 2010 CES</p>

<center><i>-- Plus the debut of a full line of LCD HDTVs with Key Feature Introductions --</center></i><br />
<br />

<p><strong>LAS VEGAS (CES Booth #10427), Jan. 7, 2010</strong> – Today at CES, Haier is launching its ultra slim LED TV lineup. The company's first generation of LEDs is available in 46", 40", 32", 24", 22" and 19" screen sizes. The 19" and 22" models are shipping in January and the other sizes shortly after. The 46" and 40" measure in at just 1.2" thick and the TV cabinets are available in a high gloss piano black cabinet for a smooth, sexy look or a high gloss white cabinet for a modern luxury appearance. Haier's Edge-lit LED technology paired with full HD 1080p and 120Hz Full Motion refresh rate, offers amazing picture quality with true-to-life colors without motion blur. In addition, SRS TruSurround XT technology gives any movie a live-performance quality that makes any movie night, a night to remember.</p>

<p>"With the introduction of our ultra slim LED HDTV's and the full assortment of our LCD HDTV product lines, Haier now offers a full array of TV products ranging from fun, colorful models for kid's rooms, elegant designs for the kitchen, to the home theater centerpiece," said Michael Jemal, Chairman of the Board for Haier America. "Haier always strives for more environmentally friendly products, and we are proud that the 24", 22" and 19" LED's are rated ENERGY STAR&reg; 4.0."</p>

<p>One of the new technologies available in 2010 is Haier's USB TimeShift function. This exciting addition allows users to have complete control of their viewing experience. Pause, rewind, or fast forward the program you are watching. Simply connect a USB drive to the USB input – different size USB memory will give you different time length to playback. Easily pause to get a snack, fast forward through commercials and press play.</p>

<p>Haier's LED line will be available the first quarter of 2010 with the following model numbers:<br />
- 46" HL46XSL2 (Black), HL46XSLW2 (White)<br />
- 40" HL40XSL2 (Black), HL40XSLW2 (White)<br />
- 32" HL32XSL2 (Black), HL32XSLW2 (White)<br />
- 24" HL24XSL2 (Black), HL24XSLW2 (White)<br />
- 22" HL22XSL2 (Black), HL22XSLW2 (White)<br />
- 19" HL19SL2 (Black), HL19SLW2 (White)</p>

<p><br />
The 2010 Haier CES introductions for television include the following series:</p>

<p><br />
<strong>K-Series</strong></p>

<p>The 55" K-Series is the largest screen Haier has ever offered in the US. The impressive 55" 1080p 120Hz LCD TV has all the features you would need for a full-time entertainment system, without the bulk. Go from video games, to pictures from your computer, to an action movie with just your remote.</p>

<p>The centerpiece of Haier's K-Series is the 42" HL42XZK42 flat-screen LCD TV that boasts the fastest refresh rate in the Haier line with 240Hz Full Motion. Along with the precise picture, the hidden Sound Chamber speaker includes SRS TruSurround XT and has an Auto Volume Leveler with distortion control, so you are hearing clear sound, without background noise.</p>

<p><br />
<strong>LCD and LED HDTV Combos</strong></p>

<p>Haier is also introducing several new combo units. The K-Series 32" LCD TV with Blu-ray /DVD combo, HLB32XK2, is the ultimate in entertainment. The Blue-ray combo has the ability to play DVD or Blue-ray discs, and features a built-in wifi connection and Adobe&reg; Flash&reg; for the Digital Home to support streaming movies in HD or DVD quality directly from pre-installed applications built with Adobe Flash technology like Netflix and Pandora, all powered by Broadcom's chipset.</p>

<p>Haier's LED TV Combos come in 24", 22" and 19" screen sizes. Get all the pluses of the LED line, including a built-in DVD player for space saving and convenience for you.</p>

<p><br />
<strong>F-Series</strong></p>

<p>The Designer F-Series LCD 22" screen is perfect for any bedroom, office, dorm room or kitchen. The unique teardrop design with compact cabinet offers space-saving style that fits comfortably into smaller areas Available in stylish high gloss cabinet colors - black, white and pink</p>

<p><br />
<strong>D-Series</strong></p>

<p>Ranging from family room sized 42" to space-saving 19" screens; the D-Series is perfect for the budget conscious consumer who wants to upgrade their TV experience with all the bells and whistles of a high-priced flat-screen. With extras like HDMI input, component input, PC and USB hook-ups as well as AV input, you can get a whole range of entertainment possibilities with one TV.</p>

<p>Haier's Key Technologies on select 2010 models include:</p>

<p>Haier's LED LCD TV is slim enough to be mounted to a wall just like a picture frame. The thin cabinet design measures less than 1/8" across the front bezel edge of the TV, and about 1.2" at the thickest part of the television. And since the televisions bezel has a rounded smooth finish, you get a picturesque sleek and slim look - like a piece of art hanging on your wall.</p>

<p>120Hz Full Motion refresh rate creates smoother motion during fast action scenes for a more natural and fluid picture. This technology reduces blurring of fast-moving objects by doubling the frame rate. It's perfect for sports and action movies.</p>

<p>Allows people to enjoy watching TV programs without the annoying volume fluctuations when switching between channels or when the program changes to a commercial. Simply set the volume to your preferred listening level and let the TV automatically adjust the sound leve</p>

<p>SRS TruSurround XT solves the problem of playing 5.1 or 6.1 multi-channel content over two speakers on your TV.  When receiving multi-channel content, SRS TruSurround XT virtualizes the channels, creating "phantom" speakers that appear to extend all around the listener. In addition, when receiving mono or stereo content, SRS TruSurround XT creates an expansive three-dimensional sound field.</p>

<p>4-HDMI allows you to connect all of your entertainment gadgets. Conveniently, switch to each device so everyone can have an enjoyable multi-media experience.</p>

<p>USB TimeShift allows users to have complete control of their viewing experience. Pause, rewind, or fast forward the TV program you are watching. Simply connect a USB drive to the USB input – different size USB memory will give you different time-length to playback. Easily pause to get a snack, fast forward through commercials and press play!</p>

