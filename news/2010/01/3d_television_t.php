				<p class="prtitle">3D TELEVISION TO TAKE CENTER STAGE AT 2010 INTERNATIONAL CES </p>

<center><i>Guide to 3D@CES is Comprehensive Resource</center></i><br />
<br />

<p><strong>LAS VEGAS, January 4, 2010</strong> – 3D TV is expected to dominate the show floor at the 2010 International CES this week with an abundance of products on display ranging from television displays and Blu-ray DVD players to end-to-end 3D solutions. A focal point of 3D exhibits at CES is the Experience 3D TechZone located in Central Hall of the Las Vegas Convention Center (LVCC) where more than 10 companies will showcase their products and technologies.</p>

<p>Some highlights at CES include:<br />
<ul><li>3D displays in all formats: flat screen (in a variety of sizes--mostly large screen), video projector and computer monitors</li><li>3D movies demonstrated via the just finalized Blu-ray 3D standard on prototype 3D Blu-ray players</li><li>3D games demonstrated on all popular videogame console formats</li><li>3D authoring software for Blu-ray</li><li>End-to-end 3D solutions encompassing everything from image capture through distribution and display</li><li>3D still images that do not require glasses to view</li><li>2D-to-3D real-time and offline video processing</li><li>Technology for converting a live high definition broadcast to 3D including live capture in HD of show attendees with 3D viewing</li><li>Accessories such as active shutter 3D glasses and 3D-optimized projector screens</li></ul></p>

<p>Specifics on these 3D developments and other news from 30 CES exhibitors will be included in a “Guide to 3D@CES”, developed by the 3D@Home Consortium. The Guide gives show attendees and the media a road map to 3D exhibits and provides a comprehensive overview of 3D technology. The Guide can be downloaded on Thursday, January 7 from the Consortium website: http://www.3dathome.org and is also available at the 3D@Home booth in the Experience 3D TechZone.</p>

<p>The 3D@Home Consortium will hold an open meeting on Friday, January 8 from 7:30 – 11:30 a.m. in Rooms 1 and 2 at the Las Vegas Hilton. At this meeting, the consortium Steering Teams and various standards organizations around the world that are looking at defining 3D requirements will provide updates. The meeting will conclude with a roundtable discussion on the direction of 3D, where the challenges lie and the opportunities for overcoming them. Pre-registration is required! To reserve a seat, please contact: Heidi@3Dathome.org.</p>

<p>A series of conference sessions on 3D will be held on Thursday, January 7: </p>

<p>Entertainment Technology@CES will take place from 10:00 am to 4:30 pm in room N260, in the North Hall of the LVCC, and is presented by The Entertainment Technology Center at USC. This program brings together the major Hollywood studios, consumer electronics and technology/services companies to collaborate on solutions for next-generation content delivery. </p>

<p>3D Hope or Hype will be held from 1:30 – 2:30 p.m. in N256 in the North Hall of the LVCC and will discuss 3D in the home including competing technologies, and whether today’s 3D is different from the 3D fads of the past.</p>
