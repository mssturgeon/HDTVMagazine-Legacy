				<p class="prtitle">DISH NETWORK&reg; INTRODUCES TV EVERYWHERE&trade;</p>
 
<center><i>New Products on Display at CES Include TV Everywhere Adapter<br />
<br />
World’s Smallest Slingbox Adds Sling Technology to DISH Network HD DVR Receivers</center></i><br />
<br />

<p><strong>LAS VEGAS, Nev. – Jan. 6, 2010 – </strong>DISH Network L.L.C., America’s fastest growing pay-TV provider, today introduced TV Everywhere&trade; – a unique suite of integrated products designed to maximize the convenience and ease of watching TV anytime and anywhere.<br />
 <br />
“DISH Network is proud to introduce the first and only comprehensive solution for consumers to pay once for content and then remain connected to their TV everywhere,” said Ira Bahr, Chief Marketing Officer for DISH Network. “DISH Network customers will be able to enjoy their favorite live and recorded shows throughout their home and on the go, using the same program guide, menu and navigation they are familiar with on their home TV.”<br />
 <br />
TV Everywhere&trade; from DISH Network provides customers with access to all their live and recorded programming on a laptop, mobile device, or anywhere in the home wirelessly. Key components of TV Everywhere&trade; include the TV Everywhere Adapter; the award-winning ViP&reg; 922; the new DISH Network WiFi HD Monitor; and the newly-released DISH Remote Access App.<br />
 </p>

<p><strong>Add TV Everywhere&trade; with the TV Everywhere Adapter – the World’s Smallest Slingbox</strong></p>

<p>Developed in partnership with EchoStar Technologies L.L.C. and its affiliate Sling Media, Inc., the TV Everywhere Adapter adds Slingbox technology to existing DISH Network HD DVR receivers such as the ViP&reg; 722k. The TV Everywhere Adapter is a sleek, ultra-slim device that easily connects to compatible set-top boxes via a single USB cable, removing the need for additional wires or a separate power supply. Once activated, the TV Everywhere Adapter provides DISH Network customers with the freedom to watch their favorite TV programming anytime and anywhere on laptops and mobile phones.<br />
 </p>

<p><strong>Watch Your TV Everywhere&trade; with the Award-Winning ViP&reg; 922</strong></p>

<p>DISH Network’s award-winning HD DuoDVRTM ViP&reg; 922 with TV Everywhere&trade;, the world’s only DVR with built-in Slingbox technology, allows customers to watch and control their favorite programs anytime and anywhere on their laptop or mobile device. The ViP&reg; 922 features a 1 TB hard drive with up to 1,000 hours of recording time – the largest hard drive in the industry.<br />
 </p>

<p><strong>Enjoy TV Everywhere&trade; in Your Home with the DISH Network WiFi Monitor</strong></p>

<p>The DISH Network WiFi Monitor, a lightweight, portable, high-definition monitor developed by Sling Media, is the only free-standing monitor available today that can wirelessly transmit an HD video signal from a set-top box to anywhere in the home via a WiFi network. Designed as a companion product to the TV Everywhere Adapter and the ViP&reg; 922, the WiFi Monitor offers a 16 x 9 widescreen format that displays 720p HD quality and controls all features of a connected DISH Network HD DVR receiver, including viewing live TV as well as viewing and managing DVR recordings.<br />
 </p>

<p><strong>Manage Your TV Everywhere&trade; with the DISH Remote Access Mobile App</strong></p>

<p>DISH Network continues to lead the industry in offering fully-featured remote DVR scheduling technology. The DISH Remote Access App, compatible with most SD and HD DISH DVR receivers, is the first and only app that offers satellite TV customers complete control of their TV everywhere. Users can set and delete timers on multiple receivers; browse and search nine days of shows; and manage their DVR library by setting recording priorities, resolving recording conflicts and deleting programs they have already watched. An added bonus, the DISH Remote Access App also includes a unique feature that transforms an iPhoneTM or iPod touch&reg; into a remote control for televisions connected to compatible DISH Network receivers.  Customers without an iPhone or iPod touch can still enjoy all DISH Remote Access benefits through the web browser on their PC or mobile device.<br />
 <br />
The DISH Remote Access App is now available for free for both the iPhone and iPod touch and can be downloaded from the App StoreSM. DISH Network expects to launch the TV Everywhere Adapter, the ViP&reg; 922 and the WiFi Monitor in the second quarter of 2010.<br />
 <br />
DISH Network will provide demonstrations of all TV Everywhere&trade; products at the Consumer Electronics Show in Las Vegas, Jan. 7-10. DISH Network’s booth, #9021, is located at the front of the Central Hall.</p>

