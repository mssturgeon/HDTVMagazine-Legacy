<p><strong>PORTLAND, Ore.--(BUSINESS WIRE)--</strong>InFocus® Corp., the industry pioneer in digital projection technology, is debuting five new projectors in its IN2100 and IN3100 series that create a new standard in high brightness and rich features for entry-level priced projectors. Increased zoom capabilities, true-to-life colors, and 3000-3500 lumens ensure a crisp, brilliant image under any classroom or meeting room lighting condition. The IN2100 series also introduces the first InFocus projector to offer networking functionality for less than $1000 (US).</p>

