<p>Sony Corporation of America, based in New York, NY, is a U.S. subsidiary of Sony Corporation, headquartered in Tokyo. Sony is a leading manufacturer of audio, video, communications, and information technology products for the consumer and professional markets. Its motion picture, television, computer entertainment, music and online businesses make Sony one of the most comprehensive entertainment companies in the world. Sony's principal U.S. businesses include Sony Electronics Inc., Sony Pictures Entertainment Inc., Sony Computer Entertainment America Inc., and Sony Music Entertainment, one of the largest recorded music companies in the world. Sony recorded consolidated annual sales of approximately $78.9 billion for the fiscal year ended March 31, 2009, and it employs 171,300 people worldwide.</p>

