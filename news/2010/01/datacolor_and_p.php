<center><i>New System Automatically Calibrates TVs Using Integrated Software</center></i><br />
 <br />

<p><strong>LAS VEGAS, NV -- January 4, 2010</strong> -- Datacolor&reg;, a global leader in digital color management technology, along with its product development partner, Portrait Displays, Inc., announced they will demonstrate an incredible breakthrough in TV calibration with their new Spyder3HDMI&reg; calibration system.  The companies will display the new TV color calibration technology at their booth located inside the HDMI TechZone in the South Hall of the Las Vegas Convention Center during the Consumer Electronics Show (South Hall, Booth #20309)<br />
 <br />
Spyder3HDMI automatically calibrates any digital TV using an HDMI connection, eliminating the need for a computer or cumbersome third party solution that requires OSD adjustments.  The software, including all dialogs and color targets, is embedded directly into the TV for easy calibration.  With Spyder3HDMI professional color adjustments are no longer proprietary to only sophisticated users or installation technicians but available to everyone.  Anyone can now benefit from properly calibrated color to maximize their viewing experience.  The built-in, step-by-step process calibrates the color of each TV to its specific environment.<br />
 <br />
"Consumers are making significant investments in their home theater systems but often lack the knowledge or proper tools to get their big screen TVs to perform at optimum levels," says Christoph Gamper, Vice President, Consumer Business Unit, Datacolor.  "Spyder3HDMI takes the frustration and guesswork out of calibrating your TV and simplifies the process by embedding the software and step-by-step instructions directly into the TVs operating environment.  Once calibrated, consumers will see an amazing difference in the viewing experience, as well as a reduction in their energy consumption because a calibrated TV is more energy efficient." Mr. Gamper added.<br />
 <br />
TV manufacturers, Original Design Manufacturers (ODMs) and Original Equipment Manufacturers (OEMs) are invited to visit Datacolor and Portrait Displays at the HDMI TechZone to learn how easy it is incorporate the color calibration software into their TV product line.  Calibration set-up instructions can be designed to match each manufacturer's On-Screen Display (OSD) for a seamless, customized look.<br />
 </p>

