				<p class="prtitle">CableLabs&reg; Develops 3D Test Support, Opens Laboratory for 3D TV Technology</p>

<p><strong>LOUISVILLE, Colo.--(BUSINESS WIRE)--</strong>CableLabs&reg; has expanded support for development of 3D television technology. This effort results from the positive responses of the consumer electronics and programming industries.</p>

<p>CableLabs is providing testing capabilities for 3D TV implementation scenarios over cable. These capabilities cover a full range of technologies including various frame compatible, spatial multiplexing solutions for transmission. Examples of the systems were shown publicly at a CableLabs-organized 3D TV Pavilion demonstration held in Denver as part of the Society of Cable & Telecommunications Engineers (SCTE) Cable-Tec Expo in October.</p>

<p>Based upon an RFI issued by CableLabs in March 2009, CableLabs opened its test facilities for development and support to vendors and TV designers to explore interoperability with 3D cable delivery systems.</p>

<p>As a result of these investigations, CableLabs has determined that many of the digital set-top boxes deployed by cable operators are capable of processing 3D TV signals in frame-compatible formats. Today’s new generation of 3D TV receivers is expected to support these formats using an HDMI video connection. It was through this testing that CableLabs played an influential role in the recently announced changes to the HDMI 3D specifications to add support for the "Top/Bottom" format and enable legacy STBs to signal 3D carriage.</p>

<p>A "frame-compatible" 3D format is one that carries separate left and right video signals within the video frame used to convey a conventional (2D) high-definition signal by squeezing them to fit within the space of one picture. The advantage of such a format is that it can be delivered through existing plant and equipment as if it were a 2D HDTV signal.</p>

<p>While the frame-compatible formats will enable support for stereoscopic 3D signaling almost immediately, work continues on an effort to define a long-term solution that will enable support for 3D content that can be delivered at resolutions and frame rates as high as 1080p60 for both eyes.</p>

<p>“We’ve found today’s cable system is a flexible system that enables delivery of 3D TV signals with little to no change in cable’s existing video on demand and switched digital video infrastructure to existing set-top boxes,” said CableLabs President and CEO Dr. Paul Liao. “This system will deliver a high-definition 3D image to today’s new generation of 3D TVs regardless of their native display technology,” he added.</p>

<p>“As with 3D cinema, the viewing of 3D TV in the home will require special glasses. Cable delivered 3D video works equally well with displays using active shutter glasses and with displays using passive polarized glasses,” said David Broberg, Vice President of Consumer Video Technology at CableLabs.</p>

<p>Cable’s VOD and SDV systems can deliver the 3DTV signals to those subscribers who have upgraded to new 3DTVs, while simultaneously delivering a 2D variation of the program to existing subscribers with only a small fractional increase in bandwidth needed.</p>

<p>The importance of cable delivery of 3D video was underscored in a recent Quixel Research survey of consumers who own HDTVs. The survey found 46% of respondents had a strong interest in viewing 3D TV in their homes over a cable or satellite distribution system versus other distribution means such as Blu-ray. A summary of the research is available at the following Web site: http://<a target="_blank" href="http://www.quixelresearch.com/pdfs/Quixel_3D_Study_2009_Overview_ZZZ.pdf/">www.quixelresearch.com/pdfs/Quixel_3D_Study_2009_Overview_ZZZ.pdf</a>.</p>

<p>Working with content owners, cable equipment manufacturers, consumer electronics companies and 3D technology companies, CableLabs actively supports work in standards bodies such as SCTE, Consumer Electronics Association (CEA) and the Society of Motion Picture and Television Executives (SMPTE) to standardize technologies that enable distribution of 3D TV content over cable systems.</p>

