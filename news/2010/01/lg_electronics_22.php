				<p class="prtitle">LG ELECTRONICS TO UNVEIL BROADBAND HDTVs WITH EMBEDDED SKYPE CAPABILITY</p>
 
<center><i>Skype Software Allows Users to Make Video and Voice Calls Directly on New LG HDTVs with NetCast Entertainment Access™</center></i><br />
<br />

<p><strong>LAS VEGAS, Jan. 5, 2010</strong> – LG Electronics and Skype today announced that LG’s 2010 HDTVs with NetCast Entertainment Access™ will feature embedded Skype™ software* allowing Skype users to make voice and high-definition video calls directly from their family room without a PC. Skype on the new LG HDTVs will be demonstrated this week at the International Consumer Electronics Show (Central Hall Booth #8205).</p>

<p>“Embedding the Skype software in our broadband HDTVs enriches the user experience, allowing consumers to connect with family and friends from the comfort of their family room without a PC,” said Peter Reiner, senior vice president, marketing, LG Electronics USA. Skype on LG HDTVs will give our customers another flexible option in allowing them to communicate using Skype, as well as access content directly through their HDTV.”</p>

<p>Beginning this spring, Skype will be available on 26 new LED, LCD and plasma HDTVs planned for 2010. The application takes video calling beyond the computer to the technology at the heart of the home, the television. By purchasing a separate camera with an integrated microphone, consumers can conduct HD video and voice calls by accessing Skype through the NetCast on-screen menu. The new LG HDTVs will also deliver familiar Skype features including:<br />
<ul><li>Free Skype-to-Skype voice and video calls to other Skype users</il><li>Calls to landline or mobile phones at Skype’s low rates</il><li>The option to receive inbound calls via a user’s online Skype number</il><li>Skype voicemail, if it is set up</il><li>Being invited to participate in voice conference calls with up to 24 other parties</il></ul></p>

<p>“We know that Skype users are increasingly interested in conducting video calls away from their computers. With Skype, consumers of LG’s NetCast HDTVs will now be able to participate in rich, real-time video conversations from the comfort of their couch,” said Josh Silverman, CEO of Skype. “A hallmark of Skype is the ability to bring people together. Together with LG, we have created an all new user experience with amazing video quality and audio clarity.”<br />
 </p>

