<p>The 3D Experience Tour will highlight Mitsubishi's fourth generation of 3D-capable TVs and introduce local consumers to demonstrations of fully immersive entertainment that rivals going to the movie theater, sitting on the sideline of a game or being a character inside a video game. Mitsubishi has spearheaded the 3D movement into the home, selling 3D-capable TVs since 2007, being first to demonstrate 3D TV at retail and also showcasing 3D directly to consumers for over two years.</p>

<p>"3D is moving quickly into broadcast, theatrical and gaming content as consumers seek to immerse themselves in the games, movies, and sports programming they love," says Max Wasinger, executive vice president of sales and marketing, Mitsubishi Digital Electronics America. "The Mitsubishi 3D Experience Tour brings this experience to towns and cities across America so that consumers can experience for themselves the eye popping, jaw dropping difference our cinema-quality DLP technology makes in 3D entertainment. This year represents the third consecutive year that we have used our mammoth big-rig Mobile Marketing Showroom to tour the U.S. and demonstrate 3D TV as it would be experienced in the home. We're excited to again hit the road and introduce our unparalleled 2010 lineup of large screen, immersive 3D DLP Home Cinema TVs to America."</p>

