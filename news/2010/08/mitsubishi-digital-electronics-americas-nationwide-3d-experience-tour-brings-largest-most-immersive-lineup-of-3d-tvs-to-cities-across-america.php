<p><strong>IRVINE, Calif.--(BUSINESS WIRE)--</strong>Mitsubishi Digital Electronics America, Inc. (MDEA) today announced the launch of its nationwide 3D Experience Tour, which will introduce its unparalleled lineup of theater-like immersive 3D* DLP&reg; Home Cinema Televisions to U.S. consumers. The tour packs Mitsubishi's latest and greatest 3D TV technology into Mitsubishi's Mobile Marketing Showroom, a 995 sq. ft. 18-wheeled home theater experience that gives viewers across the country the chance to experience the industry's largest and broadest lineup of 60-inch plus large-screen 3D-capable TVs available today.</p>

<p>The tour will showcase Mitsubishi's full lineup of very large 3D DLP Home Cinema TVs, including an 82-inch behemoth which offers more than three times the viewing area of a 46-inch screen. All 3D DLP Home Cinema TVs use the same core DLP technology as the vast majority of 3D movie theaters to deliver a cinema-quality 3D sensory experience at home.</p>

<p>Sharing the stage will be Mitsubishi's flagship 3D LaserVue&reg; TV, one of the world's most energy efficient large screen TVs, bettering EnergyStar&reg; by 50 percent. LaserVue is the only TV that uses advanced laser technology to deliver true cinema-like color, approximately doubling the spectrum of color available in any other TV.</p>

<p>Engadget, the acclaimed technology blog, recently called LaserVue, "…the best looking consumer-level set we've ever laid eyes on."*</p>

<p>For consumers who want fully immersive, cinema-quality 5.1 Dolby&reg; Digital surround sound without the hassle of extra wires and speakers, Mitsubishi's 3D Experience Tour will include the Unisen&trade; Immersive Sound LED TV series. The Unisen series integrates up to 18 intelligent speakers that use an advanced algorithm to delay and project perfectly balanced, independent sound waves that bring concert-quality audio to the viewing experience, without the clutter of separate audio components.</p>

<p>Mitsubishi will tweet from all locations throughout the tour, including the cities below. Follow the Mitsubishi Mobile Marketing Showroom on Twitter to find out when it will visit your area at <a target="_blank" href="http://www.twitter.com/Mitsubishi3D/">www.twitter.com/Mitsubishi3D</a>.</p>

