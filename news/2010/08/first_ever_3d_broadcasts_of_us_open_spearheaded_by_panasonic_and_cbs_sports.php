<p><strong>FLUSHING, N.Y., August 25, 2010 – </strong>The USTA today announced that consumer electronics giant Panasonic has become an official sponsor of the US Open in a new three-year agreement.</p>

<p>Working with CBS Sports, the USTA and Panasonic will spearhead the first-ever 3D broadcasts of the tournament.  CBS Sports will produce 3D versions of all the Arthur Ashe Stadium matches that it broadcasts in High Definition on Labor Day Weekend and on Finals Weekend, September 10-12.  These matches will be made available nationwide via DirecTV's exclusive dedicated 3D entertainment channel, "n|3D Powered by Panasonic" (DirecTV channel 103).</p>

<p>On-site at the 2010 US Open, Panasonic will have three 3D viewing galleries--a 3D Panasonic Showcase located in the former International Tennis Hall of Fame Gallery on the floor level of Louis Armstrong Stadium, and another in SmashZone, the US Open's interactive tennis experience for fans and families located in the state-of-the-art indoor facility and one more in the South Plaza area.  Panasonic and DirecTV also will provide the US Open semifinal and final matches live in 3D to hundreds of TV retail outlets nationwide, including scores of Best Buy stores, as part of the September 10-12 "National 3D Demo Days" organized by the Consumer Electronics Association.   </p>

<p>"We are very pleased to enter a new era of sports production with a new partner, Panasonic, and our long-time partner, CBS," said Lucy S. Garvin, USTA Chairman of the Board and President.  "We continually explore new innovations for the US Open, and new ways to present our tournament to tennis fans.  3D technology is the wave of the future, and once again the US Open will be on the cutting edge."</p>

<p>"Panasonic is proud to support the US Open, on site and in homes throughout the country, by bringing live match action to tennis fans in immersive 3D," said Joseph M. Taylor, Chairman and CEO of Panasonic Corporation of North America. "Panasonic consumer and professional 3D displays will show the Arthur Ashe Stadium matches to spectators on site in Flushing Meadows, viewers nationwide can see them via DirecTV's exclusive 3D channel, "n|3D powered by Panasonic," and our professional 3D camcorder will be used to shoot interviews and other footage in 3D for CBS's production."</p>

<p>"CBS Sports is looking forward to using this groundbreaking technology during our coverage of the U.S. Open Tennis Championships," said Harold Bryant, Vice President, Production, CBS Sports.  "With the court-level camera positions that will make viewers feel like they are right on the court, and the resonant sounds of the game and the spectators, tennis will be a spectacular sport to see in 3D."</p>

<p>The 3D broadcasts will use a separate production team and equipment from the traditional HD broadcasts of the tournament.  Plans call for six camera rigs (each holding two high definition cameras), two special 3D production trucks, and a unique 3D-dedicated CBS Sports broadcast team. CBS has designed the 3D camera placements lower to the court than traditional TV locations, in order to capture the close-up and personal, athletic dimension of tennis that make 3D such a powerful experience.</p>

<p>Panasonic also will reach out to viewers with advertising geared to the new 3D technology during the CBS Sports broadcasts of the US Open.  In order to view the US Open in 3D, fans must have 3D televisions and 3D eyewear and be subscribers to DirecTV.</p>

<p>The Panasonic sponsorship also include sponsorship of Arthur Ashe Kids' Day, the US Open's tennis and entertainment spectacular that serves as the unofficial opening to the tournament.  In addition, Panasonic will have new, digital signage in the three stadiums and at most of the outer courts at the US Open.</p>

