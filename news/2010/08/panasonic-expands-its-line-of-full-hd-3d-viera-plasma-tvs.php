<p>The VIERA GT25 Series features 42-inch class (41.6" measured diagonally) and 50-inch class (49.9" measured diagonally) screen sizes. The TC-P42G25 will have an MSRP(3) of $1699.95 and the TC-P50GT25 will have an MSRP of $2099.95. Both models will be available in late August 2010. Active Shutter 3D Eyewear required for viewing 3D content is sold separately. Complete technical specifications for the GT25 Series are now available at <a target="_blank" href="http://www.panasonic.com/">www.panasonic.com</a>.</p>

<p>The VIERA GT25 series augments Panasonic's VT25 series (named Best in Show at the 2010 International Consumer Electronics Show) of Full HD 3D Plasma TVs providing consumers with a broader product line which now ranges from 42-inch class through 65-inch class screen sizes. Panasonic also markets 85-inch class, 103-inch class and 152-inch class professional Full HD 3D Plasma models.</p>

<p>"From the beginning, Panasonic has led the charge into the immersive world of 3D home entertainment by offering end-to-end 3D home entertainment solutions including Full HD 3D VIERA Plasma TVs, 3D Blu-ray Disc Players, professional and consumer 3D camcorders, the nation's first suite of 3D TV channels with partner DIRECTV, and the authoring of 3D Blu-ray movies in cooperation with the Hollywood studios," said Henry Hauser, Panasonic Vice President, Merchandising, Display Group. "The debut of our VIERA GT25 Series of Full HD 3D TVs further expands our portfolio of 3D offerings and makes it even easier for consumers to join the immersive world of Full HD 3D for the home."</p>

<p>While the VIERA&reg; GT25 Series represents a new price point, the models include many of the same innovative features found on the critically-acclaimed VIERA VT25 models including Panasonic's proprietary IPTV functionality, VIERA CAST(TM) which features USB connectivity, allowing for the addition of a wireless LAN adaptor, keyboard and USB memory. VIERA CAST now includes such favorite entertainment sites as Amazon Video-on-Demand(TM), Netflix(TM), Google's YouTube(TM), Picasa(TM) Web Album, Bloomberg, Pandora, Twitter and a weather service, as well as Skype(4)(TM) on Your VIERA TV. With ease of use as a major focus, VIERA CAST's interface implements quick keyword input (like a cell phone) to help retrieve favorite content faster and easier.</p>

<p>Another prominent feature of the GT25 series that is also found in the VT25 series is VIERA Link(TM), which allows Panasonic owners to control their VIERA Link compatible audio and video products with just one remote. This feature also affords the consumer the opportunity to add a network camera to the mix. And THX&reg; Certified Display certification insures that every Panasonic Full HD 3D TV displays motion pictures and television content with the quality and color palette that the director intended.</p>

<p>Like its VT25 counterpart, the GT25 series also features 600Hz Sub-field Drive; 1080p Full HD resolution; 1080 lines of moving picture resolution; VIERA Image Viewer (for viewing of digital still images), 24p Cinematic Playback and new fast switching phosphors.</p>

<p>The GT25 Series also includes 2D to 3D conversion which can convert a 2D image or video to 3D.</p>

<p>Panasonic's range of Full HD 3D VIERA Plasma HDTVs, when coupled with Panasonic's 3D Blu-ray Disc players (DMP-BDT100, DMP- BDT300, DMP-BDT350) bring a new era of immersive visual entertainment into consumers' homes, by creating a 3D experience that easily rivals the best that can be seen in cinemas. In addition, Panasonic and DIRECTV recently ushered in a new age in the rapid growth of 3D entertainment for the home with the launch of n3D(TM) powered by Panasonic - a DIRECTV channel dedicated exclusively to 3D programming. n3D powered by Panasonic is now available at no additional cost to millions of DIRECTV HD customers and features a range of sports and entertainment programming exclusively in 3D. Panasonic is the exclusive presenting sponsor of DIRECTV's n3D channel, one of three 3D TV channels from DIRECTV that deliver movies, sports and entertainment content from some of the world's most renowned 3D producers.</p>

<p>All Panasonic VIERA&reg; Full HD 3D TV models are also Full HD TVs that display pristine 1080p content in two dimensions (2D) for conventional HD viewing.</p>

<p>For more information on Panasonic's Full HD 3D technology, visit <a target="_blank" href="http://www.panasonic.com/3D/">www.panasonic.com/3D</a>.</p>

