<p>"Sixteen years ago, Onkyo created a revolution in home theater with its introduction of the world's first THX Certified AV receiver, the TX-SV919THX," said Paul Wasek, Onkyo's marketing manager. "Onkyo's engineers have worked closely with THX to maximize the home theater experience for consumers. Now we are introducing a trio of high-end component separates. Their build-quality, market-leading features, and THX-Certified performance will ensure that Onkyo will quickly become a major factor in this higher realm of the AV marketplace."</p>

<p>Onkyo's flagship PR-SC5508 is a THX-Ultra 2 Plus certified, network-capable, 9.2-channel audio-video controller will function as the brains of the worlds most advanced in-home home theater systems. It has a 3D-Ready HDMI-1.4a interface, HQV Reon-VX video processing, ISF Video Calibration, and a long list of top-of-the line audio and video features unmatched in other products.</p>

<p>The networking features offer DLNA 1.5 and Windows 7 compatible connection to PC audio and internet radio. The system is configured for Pandora, Rhapsody, Mediafly, Slacker, Napster, VTuner, and Sirius Internet Radio. The PR-SC5508's component circuitry is at the far edge of the technology envelope, both in terms of sound and video quality and processing. Superior video performance comes in the form of HQV Reon-VX processing, 1080p upscaling, and individual ISF calibration capability for all video sources. This THX-Ultra 2 Plus certified system offers exceptional surround sound, height channels, setup calibration, and state of the art processing from Dolby, THX, DTS, and Audyssey, including the latter's new MultEQ XT 32. The PR-SC5508's extensive connectivity options includes 8 HDMI inputs, dual USB's, two balanced line-level XLR audio inputs, and nine XLR preamp outputs to drive the matching PA-MC5500 nine-channel power amplifier.</p>

<p>The Onkyo PA-MC5500 is a powerful nine-channel THX-Ultra2 Plus certified analog power amplifier that is 8-ohm rated at 150 Watts per channel, and up to 400 Watts dynamic power into 3 ohms. It utilizes Onkyo's exclusive WRAT (Wide Range Amplifier Technology) design philosophy, which proscribes low negative feedback, low distortion, extended frequency response, and a power supply with high instantaneous-current capability. To achieve all this, the PA-MC5500 uses large, custom output transistors in push-pull configuration and massive power supply consisting of a large toroidal power transformer and two 22,000 µF storage capacitors. Despite all this power, the PA-MC5500 preserves the subtle details of the sound with a three-stage inverted Darlington circuit to remove distortion and the use of professional balanced line-level XLR inputs for the optimal interface with its ideal companion, the Onkyo PR-SC5508. The 51-lb PA-MC5500 has a rigid, anti-resonant chassis, gold-plated inputs and outputs, plus multi-zone and bi-amp capability to allow full utilization of all channels no mater what the system configuration.</p>

<p>The Onkyo BD-SP808 is a THX Certified and DLNA 1.5 Certified Blu-ray Disc Player with a full array of state of the art technology, including Video On Demand, premium Marvel Qdeo&trade; video scaler, and studio-master quality Dolby&reg; TrueHD and DTS-HD Master Audio&trade; sound. Its superior build quality provides a robust and versatile playback solution for Blu-ray, DVD, and CD. Harmful vibrations are minimized thanks to the highly rigid chassis construction and a balanced, center-mounted drive mechanism. An Ethernet port enables interactive Profile 2.0 BD-Live features such as picture-in-picture and web-sourced firmware updates. An SD card slot allows playback of downloaded web content or stills and video from a digital camera. In HDMI Source Direct mode, the player can output the video signal in its native resolution for optional external processing.</p>

<p>These products will begin shipping to dealers in September. The PR-SC5508 will have a suggested retail price of $2,199, the PA-MC5500 will be $1,699, and the BD-SP808 will have a suggest retail price of $599.</p>

