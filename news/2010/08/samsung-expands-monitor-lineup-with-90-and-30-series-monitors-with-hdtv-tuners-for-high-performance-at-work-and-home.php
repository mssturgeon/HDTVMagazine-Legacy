<p>"People are looking to do more in smaller areas and multi-function monitors are a great way to maximize the functionality of a single device," said Young Bae, director of display marketing Samsung Enterprise Business Division. "Samsung continues to expand our multi-function offerings and these two new lines – the 30 and 90 series – provide a new range of options and value for our customers."</p>

<p><br />
<strong>Unique features for work and home</strong></p>

<p>Both the 30 and 90 series monitors can be used as a small TV with full HD resolution and also feature Picture in Picture (PiP) so multi-tasking users can simultaneously use their computer and watch TV without the need for a second monitor or additional connections.</p>

<p>The monitors come equipped with two HDMI inputs for easy connection to multiple HD devices – cable boxes, video game consoles, Blu-ray players, etc. Samsung's Connectshare feature adds even more multi-media capabilities allowing users to instantly view and listen to music, movies and photos on the monitor from a memory stick, portable media player, or digital camera through a plug-and-play USB connection.</p>

<p>For additional enhanced viewing options and productivity, the 30 and 90 series monitors are equipped with Samsung's MagicAngle, which ensures users see full brightness and color range when viewing the monitor from above, below or to the side. Additional Magic Suite 2010 options included are Magic Eco, Magic Return, Magic Color, MagicTune and Magic Bright3.</p>

<p><br />
<strong>Sleek Design</strong></p>

<p>The new 30 and 90 series monitors are contemporary and elegant designs. The 24 inch LED 90 series is marked by a Touch of Color Mystic Brown finish accented with a chrome-coated quadruple stand. As with all Samsung LED technologies, the new 90 series monitors consume up to 40 percent less energy than non-LED displays.</p>

<p>The 30 series, available in 21.5, 23 and 24 inch screen sizes, is finished in a sleek black with a clear acrylic bar along the bottom bezel. Additionally, the 30 series features a rear wave pattern that makes it attractive for those sitting on either side of a desk or table.</p>

