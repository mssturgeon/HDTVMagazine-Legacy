<p>Samsung also introduced three additional standalone Blu-ray players and three new Blu-ray Home Theater Systems that deliver crystal-clear picture and sound quality with new features that will excite both the first-time owner and the audiophile.</p>

<p>"Blu-ray has raised the bar for video and audio quality that consumers expect to see at home. We led the way in 3D TVs and are excited to do the same for 3D Blu-ray players and Home Theater Systems. With the industry's broadest line-up of 3D capable home entertainment products, there is a product to suit every home and wallet," said John Revie, senior vice president of Home Entertainment at Samsung Electronics America Inc.</p>

<p><br />
<strong>Expanded Range of 3D-Capable Blu-ray Players Helps Future-Proof Entertainment Options</strong></p>

<p>Samsung's latest Blu-ray players bring the wonder of 3D entertainment into the home. The Samsung BD-C7900 Blu-ray player is designed for the HD guru. With two HDMI outputs, the BD-C7900 makes it easy to connect multiple HD sources to experience a full 1080p picture and digital surround sound. The two HDMI outputs also allow for support of legacy receivers so there is no need to upgrade to a new HDMI 1.4 receiver; the user can simply connect their receiver to the HDMI 1.3 output for rich, life-like surround sound audio. This sleek and stylish device offers built-in Wi-Fi for seamless connectivity to Samsung Apps. It also features Samsung's proprietary AllShare&trade;, which allows people to wirelessly sync digital devices so that they can enjoy music, movies and photos directly from their DLNA certified PC, camera and mobile devices to their Samsung TV screen.</p>

<p>For those looking for a versatile home entertainment experience, Samsung's BD-C6800 Blu-ray player includes built-in Wi-Fi, enabling it to wirelessly receive web-based content via Samsung Apps and playback media files from DLNA certified devices via Samsung's AllShare&trade;. The entry-level BD-C5900 is designed for those looking for a high-performing yet affordable 3D Blu-ray player.</p>

<p>All Samsung Blu-ray players support a wide range of media formats and access to an expanding library of applications through Samsung Apps, the first HDTV-based applications store. These new 3D Blu-ray players deliver a premium experience with both 2D and 3D content and allow consumers to future-proof their living rooms for when they are ready to purchase a 3D HDTV.<br />
