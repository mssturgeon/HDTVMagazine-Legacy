<p><strong>Powerful New Blu-ray Home Theater Systems Deliver Immersive 3D Experience</strong></p>

<p>The Samsung HT-C9950W is the ultimate combination of beauty, design and performance. It features a modern metallic finish and is the perfect complement to Samsung's award-winning 9000 series LED TV. It delivers jaw-dropping home theater picture quality, and engaging, life-like and immersive entertainment experience that will please anyone looking for the best in home cinema. The HT-C9950W is as feature-rich as it is stylish – with slot-in disc loading, organic touch control buttons and a premium volume wheel. The 7.1 channel 3D surround sound system consists of four floor-standing speakers, two satellite speakers, one center channel unit, an anti-vibration subwoofer, iPod/iPhone dock, two HDMI inputs, and it comes with a dongle for wireless Internet connectivity so that you can easily access new content everyday via Samsung Apps, or use Samsung's AllShare&trade; to watch content from your DLNA certified devices on the TV.</p>

<p>With the introduction of the HT-C6900W and HT-C6600, Samsung brings together the unsurpassed picture quality of 3D Blu-ray players with vibrant surround-sound audio, all in the perfect home theater package for small spaces.</p>

<p>The Samsung HT-C6600 offers an impressive slate of features – a Blu-ray player with built-in 3D, support for HDMI 1.4, access to Samsung Apps and Wi-Fi dongle for wireless connectivity. In addition, the HT-C6600's patented, high-performance Crystal Amp Pro technology dramatically enhances sound quality through its multi-variable feedback technology to deliver a complete immersive audio experience. The Samsung HT-C6900W offers all the features of the HT-C6600, plus wireless rear speakers, built-in Wi-Fi, and a two-way center channel speaker for enhanced sound quality.<br />
