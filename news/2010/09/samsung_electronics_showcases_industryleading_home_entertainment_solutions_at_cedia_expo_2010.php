<p>To create the ultimate home cinema system that delivers a solid audio visual experience with sleek, cutting-edge design, Samsung offers the LED 9000 Series 3D HDTV and the HT-C9950W Home Theater System.</p>

<p>At 0.31" thin, the award-winning ultra-slim LED back-lit 9000 television features Real 240Hz Clear Motion, 1080p resolution, a 6,000,000:1 Mega Dynamic Contrast Ratio and HDMI version 1.4. It includes a built-in 3D processor and auto-conversion technology that renders 2D content into 3D in real time. The LED 9000 Series features Samsung Apps, which gives viewers access to an expanding library of content and services such as Hulu Plus, Netflix, Facebook, Google Maps, ESPN Next Level, and more. This 3D TV also offers a premium accessory package, which includes a Samsung Linkstick&trade; to connect easily to a Wi-Fi network, a slim Wall-mount, and a Wi-Fi capable touchscreen remote which features a 3" display that streams the same content that is being viewed on the TV to the remote.</p>

<p>The HT-C9950W home theater system boasts the same modern styling and metallic finish that perfectly complements the LED 9000 series. This 3D-capable Blu-ray home theater system features slot-in disc loading and a premium volume wheel that is also home to the touch panel controls. The 7.1 channel surround sound system pushes out up to 1400 watts and consists of four floor-standing speakers, two satellite speakers, one center channel unit, an anti-vibration subwoofer, iPod/iPhone dock, two HDMI inputs, Samsung Apps, AllShare&trade; and a dongle for wireless Internet connectivity.</p>

<p><br />
<strong>Samsung TVs: Crystal clear picture and personalized entertainment experience</strong></p>

<p>With its sleek 65-inch screen, the new Samsung UN65C8000 is the largest Full HD 3D LED back-lit TV available for the home today. It features Samsung's built-in 3D processor, Real 240Hz refresh rate technology, dynamic 8,000,000:1 contrast ratio, Samsung Apps, and proprietary Precision Dimming technology. It also supports Skype&trade; via Samsung Apps. This means that users can make calls right from their TV, turning it into a huge video screen and bringing an almost life-like quality to video calls.</p>

<p>Featuring a slim brushed titanium bezel with hints of Samsung's Touch of Color&trade; (ToC&trade;) design, the Samsung Plasma 8000 Series TV offers a mega dynamic 7,000,000:1 contrast ratio, built-in 3D technology, Real Black Filter, 600Hz Subfield Motion and a Motion Judder Canceller (MJC). The television is also equipped with Samsung's CinemaSmooth&trade; technology for playback of 24fps, two USB ports, 4 HDMI (3 rear/1 side), Samsung Apps, and AllShare&trade;.</p>

<p>In addition to these featured models, Samsung will have a wide range of it 2010 lineup on display at the event.</p>

<p><br />
<strong>Samsung AV Receivers: Outstanding audio clarity and value</strong></p>

<p>The HW-C500 AV Receiver is a versatile home entertainment system that delivers up to 500 watts of audio power through 5.1 channels. The Samsung HW-C700 AV Receiver offers advanced 7.2 channel surround sound to deliver an impressive audio experience. Available in silver and black, designers can create a home entertainment system that delivers peerless audio quality without sacrificing style. The premium Samsung HW-C900 includes all of the features of the HW-C500, as well as video up-scaling, video up-conversion, and multi-zone functionality.</p>

<p>Samsung's 2010 line of AV Receivers offers Crystal Amplifier Pro technology, including multi-variable feedback circuitry and Intelligent Power to deliver accurate sound reproduction. Multi-Variable Feedback Circuitry filters sound distortion and noise to provide pure sound performance and Intelligent Power delivers power to the amp when listening to music with high volume variance to avoid clipping. In addition, Samsung's line of receivers comes with 4 HDMI inputs and supports HDMI 1.4 for 3D as well as an iPod/iPhone dock.</p>

<p><br />
<strong>Samsung Soundbar and Portable Blu-ray Player: Bringing Immersive Entertainment to Any Room</strong></p>

<p>Slim and compact, the Samsung HW-C450 Sound Bar can be wall mounted, while the 5.8 GHz wireless subwoofer allows users to place it anywhere in the room. The slim design means that it requires minimal space and wiring, allowing installers to add big sound to any TV, even in limited space. The unit features an alluring new prism ToC&trade; design, 280 watts of 2.1 channel virtual surround sound, Dolby Digital, DTS, one audio input, and 2 optical inputs.</p>

<p>The Samsung BD-C8000 portable Blu-ray player with 3D capability is the perfect way to bring a rich home entertainment experience to a home office or bedroom setting. The Samsung BD-C8000 delivers true 1080p HD video output and features a brilliant 10.1-inch screen. It includes built-in Wi-Fi for easy access to advanced connectivity features, including an expanding library of content and applications via Samsung Apps. It even offers HDMI 1.4a support to enable 3D playback when connected to a 3D-capable TV and used with 3D glasses.</p>

