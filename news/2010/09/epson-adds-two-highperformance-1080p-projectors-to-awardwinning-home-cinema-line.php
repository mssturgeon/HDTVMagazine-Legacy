<p><strong>ATLANTA, Sept. 23 /PRNewswire/ -- (</strong>CEDIA Expo 2010, Booth 2406)– Epson America today expanded its award-winning line of 3LCD&trade; home theater projectors with the announcement of the PowerLite&reg; Home Cinema 8350 and 8700 UB. These two projectors offer native 1080p resolution and Epson's latest 3LCD&trade; technology with C2Fine&reg; chip sets for amazing color and detail, high contrast ratios and road-tested reliability. The value-packed Home Cinema 8350 and 8700 UB also include Epson's award-winning customer service and support, delivering an outstanding and affordable viewing experience for home entertainment and AV enthusiasts.</p>

<p>As the number-one selling projector brand worldwide(i), Epson has priced the Home Cinema 8350 and 8700 UB in the sub-$1,300 and sub-$2,200 categories, respectively, offering consumers two options for affordable high-definition home entertainment. Both projectors feature state-of-the-art image quality and performance in each of their respective categories with deep blacks and bright images with contrast ratios of up to 50,000:1 and 200,000:1.</p>

<p>"Epson has packed its latest Home Cinema line of projectors with a number of value-add features and technologies in order to deliver high-performing 1080p solutions to the home theater and AV enthusiast market," said Marge Ang, senior product manager, Epson America. "We are committed to leading the market in terms of performance and value, and these models clearly demonstrate that consumers can get outstanding image quality at affordable price points."</p>

<p>The Home Cinema 8350 offers a high-quality, affordable big-screen entertainment at home, featuring Epson's C2Fine chip set for higher contrast of up to 50,000:1 and higher brightness of up to 2,000 lumens color and white light output(ii). It also has an exclusive Dynamic Iris system that contributes to the enhanced contrast by controlling light on a frame-by-frame basis at up to 60 times per second.</p>

<p>Adding a host of technology enhancements, the Home Cinema 8700 UB offers home theater AV enthusiasts an incredible 1080p big screen experience. With a dual-layered auto-iris to effectively control light reduction rates, as well as Epson's D7 chip set and UltraBlack&trade; technology, the projector delivers superb black levels and vivid images. It also features brightness of 1,600 lumens color and white light output for deep blacks and crystal clear detail.</p>

<p>Also offered with the Home Cinema 8700 UB is Epson's Super-resolution technology for enhanced picture quality and FineFrame&trade; technology for smoother frame interpolation, sharper video quality and the elimination of judder. It also includes a built-in Silicon Optix HQV Reon-VX video processor and PW390 scaler to ensure a smoother picture. New to the Home Cinema line, the Home Cinema 8700 UB now features pre-set color space selection to set color gamut according to geography and source material. In addition, the projector comes equipped with anamorphic lens mode to enable anamorphic viewing without an external processor for true 2.35:1 and 2.40:1 widescreen images without the black bars above and below the picture(iii). For added value, the projector includes a voucher for a replacement E-TORL lamp ($299.99).</p>

<p><br />
<strong>Additional Shared Features of the Home Cinema Line</strong></p>

<p>Epson's Home Cinema projectors share a range of features including:</p>

<p>    * Advanced, three-chip optical engine for brilliant color and image quality without color break-up<br />
    * Cinema Filter feature delivers larger color space for improved color fidelity<br />
    * Outstanding video image quality with Fujinon OptiCinema&trade; Multi-Lens Optics System (2.1 zoom ratio); projects clean, precise edges with consistent image quality across the entire screen<br />
    * Real color reproduction feature delivers more natural and precise colors<br />
    * Epson's exclusive 200W E-TORL&reg; (Epson Twin Optics Reflection Lamp) for up to 5,000 hours of lamp life(iv)<br />
    * Features two HDMI 1.3 connections with Deep Color support, high definition component video input, S-video input, composite video input, and VGA-type RGB input (D-sub 15)<br />
    * Five Color Modes to easily adapt to different viewing environments<br />
    * Manual zoom, focus and lens shift (47.1 percent horizontal and 96.3 percent vertical) ensure a range of installation options and flexibility<br />
    * Stylish, sleek design featuring white casing and reversible Epson logo on the front panel allow the projector to be reoriented for tabletop, shelf and ceiling mounting</p>

