<strong>Availability and Industry-Leading Service and Support</strong></p>

<p>Both projectors will be available in late-September and can be purchased through authorized Epson projector dealers and select retail outlets. Ranking as the number one Home Video company in the annual "Supplier Loyalty Report" by the consumer electronics industry publication inside track for three consecutive years, Epson offers its industry-leading customer service and support with the Home Cinema 8350 and 8700 UB. Both projectors come with a two-year limited warranty with toll-free access to Epson's PrivateLine(SM) priority technical support, 90-day limited lamp warranty, and free two-business day exchange with Extra Care(SM) Home Service.</p>

