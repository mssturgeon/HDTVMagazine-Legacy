<p>Viewing widescreen 2.35:1 aspect ratio films is easy with the HC4000 projector, thanks to its anamorphic lens support.  Users simply position an anamorphic lens in front of the HC4000 lens and select the appropriate Anamorphic Mode 1 or Mode 2, either 2.35:1 or 16:9 aspect ratios, for the corresponding movie format.  It's a simple and economical design that saves time and effort while providing the ultimate home theater viewing experience.</p>

<p>Mitsubishi's HC4000 offers low cost of ownership with an estimated 5000-hour lamp life* in low conservation mode.  It's filter-free design and advanced semi-sealed construction helps makes the HC4000's optics resistant to dust, dirt and other micro particles within its light path. Periodic maintenance is greatly reduced, making the projector more economical over time, and allowing users to enjoy their home theater longer.  The HC4000 also has a convenient and simple top-access lamp design for easy lamp exchanges.</p>

<p>Subdued scenes are easy to hear with the HC4000's quiet engine that has an ultra-hushed noise level rated at 25dBA in low mode. The projector includes a native digital HDMI&trade; input for true high-definition connectivity, and at less than eight pounds can be taken almost anywhere.  With its built-in 1.5x-zoom ratio lens as well as a digital keystone correction, set-up is easy and more flexible for various room configurations.</p>

