<p>MTV Networks International (MTVNI), owned by Viacom Inc. (NYSE: VIA, VIA.B), today announced plans to significantly expand the company's high definition services across brands through next year with the launch of new channels and programming. The announcement underscores MTVNI's commitment to providing audiences and cable/satellite operators with premium content and innovative entertainment experiences.</p>

