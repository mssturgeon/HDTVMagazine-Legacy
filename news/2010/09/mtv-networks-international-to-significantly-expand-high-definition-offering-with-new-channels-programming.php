<p>MTVNHD is operated by MTVNI's Emerging Markets Group, which produces and broadcasts the channel 24 hours a day from its Warsaw hub. The group will also oversee the launch of the international Nickelodeon HD channel starting next year. Drawing on the company's global talent pool, HD programming is also produced by MTV Networks' creative teams in South Europe, Latin America, the UK and US.</p>

