<p>Mike Darcey, Sky's Chief Operating Officer, comments: "We're delighted to announce the addition of Nickelodeon HD to Sky+HD, the UK's leading high definition service. Sky remains committed to delivering customers the best HD service available, and this means continuing to work with high-quality content partners to launch outstanding channels right across the schedule. With the best of free and pay TV now in HD, there's never been a better time to embrace HD."</p>

<p>Nickelodeon puts kids first in everything it does. The network, which is seen more than 345 million households via 52 channels in 111 countries, showcases a broad array of critically acclaimed animated and live action shows for kids and families. Popular animated series to be seen in HD include Fanboy &amp; Chum Chum and The Penguins of Madagascar. Live action shows in HD include the sitcoms iCarly and Victorious, along with the musical comedy Big Time Rush and action comedy The Troop, among others. The company has built a diverse, multi-platform business that also includes consumer products, online, events, recreation and feature films.</p>

<p>In the UK, Nickelodeon is a joint venture between MTV Networks and BSkyB. Launched in 1993, it is a top performing commercial kids TV network comprised of seven award-winning entertainment channels for kids aged 2-12: Nickelodeon, Nickelodeon HD, NickToons, NickToons Replay, Nick Jr, Nick Jr 2 and Nick Replay. The Nickelodeon network now reaches more than 10 million UK viewers a month and is available in 12.7 million cable and satellite homes. Nickelodeon HD in the UK will be produced and broadcasted by the company's local operation and will be available to all Sky HD customers that currently take the Kids pack as part of their SD subscription package. Additional carriage deals will be announced in the future.</p>

