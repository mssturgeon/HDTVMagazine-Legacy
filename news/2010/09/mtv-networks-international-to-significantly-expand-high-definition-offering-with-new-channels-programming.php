<p>With the launch of Nickelodeon HD next month, the company's first international high definition service MTVNHD, will no longer broadcast a weekend block of Nick programming and will focus exclusively on music-related content. MTVNHD will continue to expand distribution and is expected to be available in 30 countries across four continents by the end of this year. The 24-hour service, which debuted in 2008, is currently available in more than 7 million households with recent launches in Bulgaria and Malta. MTVNHD will expand its library of diverse music programming to more than 1,000 hours by end of 2011, including original and acquired live performances, documentaries and world-class events. Additional carriage deals and programming announcements for MTVNHD will be made in the coming months. For more information, visit http://www.mtvnhd.com.</p>

