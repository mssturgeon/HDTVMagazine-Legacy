<p><strong>CONCORD, N.C.--(BUSINESS WIRE)--</strong>Continuing a tradition of innovation and fabulous firsts, Speedway Motorsports Inc. (NYSE: TRK) Chairman and Chief Executive Officer O. Bruton Smith and Charlotte Motor Speedway officials announced a partnership with Panasonic to revolutionize the fan experience at motorsports events with the creation of the world's largest high-definition video board.</p>

<p>Panasonic will also become the founding sponsor of the video board and a Speedway Motorsports Inc. alliance partner around its broad portfolio of advanced technologies.</p>

<p>At an incredible length of 200 feet wide, standing 80 feet tall and weighing 165,000 pounds, the video board will cover an expansive 16,000 square feet and be located between Turns 2 and 3 along the backstretch of the legendary superspeedway. Fans seated throughout the frontstretch from Turn 4 to Turn 1 will have clear viewing angles of the gigantic board that will feature 720P high-definition visuals illuminated by more than nine million light emitting diode, or LED, lamps.</p>

<p>"Charlotte Motor Speedway continually establishes itself as a pioneer when it comes to one-of-a-kind, over-the-top facility enhancements that change the game for motorsports fans," said Smith. "Fans will see this like a gigantic television that will elevate the NASCAR experience in ways they have never dreamed. It will give them a view of the on-track action on the world's largest high-definition screen. The fans will feel closer than ever before to the cars and stars of NASCAR at each event."</p>

<p>In addition to the live race coverage, the video board will provide fans with interactive entertainment, continuous leaderboard updates, sponsor information and instant replays.</p>

<p>"Panasonic is proud of our efforts to bring this spectacular new high-definition scoreboard to Charlotte Motor Speedway," said James Doyle, president, Panasonic Enterprise Solutions Company. "This amazing example of industry-leading technology and engineering speaks volumes about our strong relationship with Charlotte Motor Speedway as we work together to bring innovative concepts to life and enhance the fan experience.</p>

<p>"Panasonic worked closely with Charlotte Motor Speedway to design the end-to-end system from the control room to this massive HD video board," Doyle added. "We are confident that the new Panasonic HD video board system will leave fans awestruck and make their entire Charlotte Motor Speedway experience that much more enjoyable and memorable."</p>

<p>Construction will begin on the video board following the Oct. 13-16 Bank of America 500 Week at Charlotte Motor Speedway and is scheduled to be complete by April, 2011.</p>

<p>Panasonic is now the exclusive audio/video provider of Charlotte Motor Speedway with category exclusivity inclusive of camera, camcorder, television, display, and Blu-ray.</p>

<p>The creation of the video board is the latest in a tradition of trend-setting innovations and fabulous firsts at Charlotte Motor Speedway during its 51-year history. Other notable firsts include:</p>

<p>    * 600-Mile Race. In 1960, Charlotte Motor Speedway became the first and only track to host a 600-mile NASCAR-sanctioned event. Now known as the Coca-Cola 600, the race is still the longest and one of the most prestigious on the NASCAR Sprint Cup Series schedule.    </p>

<p>    * Luxury Condominiums. Charlotte Motor Speedway became the first sports facility in America to offer year-round living accommodations in 1984 when it released 40 condominiums for sale high above Turn 1. Twelve additional condominiums were added in 1990.      </p>

<p>    * The Speedway Club. Opened in 1988, The Speedway Club was the first exclusive members-only private club to be constructed at a motorsports facility. The club features restaurant seating for 240 people overlooking the frontstretch and expansive ballroom and boardroom banquet facilities. Members enjoy a champagne toast with the race winner after each Coca-Cola 600 and Bank of America 500.                                               </p>

<p>    * Night Racing. Charlotte Motor Speedway became the first modern speedway to offer night racing in 1992 after installing a $1.7-million, 1,200-fixture permanent lighting system. The system was different from any installed at other tracks in that it used a system of adjustable mirrors surrounding the inside of the track to moderate the light aimed at the drivers.</p>

