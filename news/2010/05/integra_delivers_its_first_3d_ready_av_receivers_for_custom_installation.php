<p><img src="http://www.hdtvmagazine.com/news/images/integra-dtr-30.2.jpg" alt="Integra DTR-30.2" height="225" width="300" class="keyimg"><strong>UPPER SADDLE RIVER, NJ  (5/13/10) -- </strong>Integra, the premier brand of audio-video components specifically engineered for custom installation, has introduced two 3D-video-ready THX Select 2 Plus certified home theater receivers. These include advanced technology that allows home theater owners to take full advantage of all the available dimensions of video and sound.</p>

<p>The new Integra DTR-30.2 and DTR-20.2 use the latest HDMI 1.4a A/V interface. This allows them to pass 3D video signals from a player to a 3D video display, and to simultaneously extract uncompressed full-definition studio-master-quality sound tracks using Dolby True-HD or DTS-HS Master Audio.  These new receivers are also compatible with the mandatory formats for 3D broadcast content of "Side-By-Side (Half)" and "Top-and-Bottom" 3D video formats. Both have five rear HDMI inputs and one output, and the DTR-30.2 also has a convenient front panel HDMI input. Both support Audio Return Channel and offer a new feature called HDMI Through, which allows TV viewing even when the receiver is in standby mode.</p>

<p>The powerful Integra DTR-30.2 delivers 100-watts to each of seven loudspeakers that can be arranged for a variety of different surround modes, surround plus height, stereo bi-amping, or powered Zone 2 configurations. When used with included Audyssey DSX or Dolby ProLogic IIz processing, additional speakers mounted above front speakers can add height ambience to the sound above the listener. For those with more limited speaker needs, the DTR-20.2 has five power amplifier channels rated at 90 watts each.</p>

<p>These receivers include advance technology systems designed to ensure the best possible video and sound. Faroudja DCDi Cinema offers video upscaling to 1080p, and PLL jitter-cleaning technology ensures a clear sharp picture even with older video sources. On the audio side, there are premium Burr-Brown PCM-1690 192 kHz / 24-bit DACs for all channels. The power amplifiers use the company's premium Wide Range Amplifier Technology (WRAT) with three-stage inverted Darlington circuits. Both receivers include Audyssey 2EQ automatic room correction, and Audyssey's Dynamic Volume and Dynamic EQ processing. There are four DSP Gaming modes for rock, sports, action, and role-playing games; a Music Optimizer for compressed digital music; and a Theater Dimensional processer for sound-bar virtual surround.</p>

<p>Custom installers will appreciate the many "little" features on these receivers: three DC triggers, two IR inputs and one output, bidirectional RS-232, PC-input, Zone-2 capabilities, separate dealer settings for quick system restore, RiHD, Universal Port for connection optional iPod dock and HD-Radio modules, and optional rack mounting kit.</p>

<p>The Integra DTR-30.2 and DTR-20.2 are now available with manufacturer's suggested prices of $800 and $600 respectively.</p>

