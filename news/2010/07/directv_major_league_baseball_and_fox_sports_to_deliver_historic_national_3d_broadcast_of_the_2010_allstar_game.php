<p><strong>EL SEGUNDO, Calif., Jul 09, 2010 (BUSINESS WIRE) -- </strong>DIRECTV, Major League Baseball and FOX Sports, continuing to lead the industry in sports programming innovation, will offer the 2010 MLB All-Star Game in 3D exclusively on DIRECTV's new 3D channel, n3D (TM) powered by Panasonic (Channel 103).</p>

