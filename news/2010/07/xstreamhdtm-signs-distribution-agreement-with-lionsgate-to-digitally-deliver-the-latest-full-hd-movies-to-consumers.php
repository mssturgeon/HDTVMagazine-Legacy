<p>XStreamHD's ground-breaking whole-home HD entertainment system delivers Full 1080p HD video and up to 7.1 channels of lossless DTS-HD Master Audio(TM) directly to the home via satellite, enabling consumers to enjoy the very latest entertainment, in uncompromised Full HD, exceeding the quality of physical media. Additionally, every XStreamHD customer has exclusive multi-room access to Pre-Fetched Entertainment (PFE), which provides unparalleled convenience by automatically delivering just-released HD entertainment directly to each user's personal library based upon their individual user preferences and advance title selections.</p>

<p>"Our partnership with XStreamHD presents us with a new opportunity to distribute our content in the digital marketplace," said Lionsgate Executive Vice President of Distribution and Digital Jon Ferro. "Our decision to distribute our titles through XStreamHD reflects our commitment to offer consumers the highest quality home entertainment and access to our enormous library of titles."</p>

<p>"We are excited to provide our customers with access to Full HD digital cinema, on the DVD release date, from the Lionsgate library of daring, original and high quality titles," stated George Gonzalez, president and CEO of XStreamHD. "Our customers will enjoy unparalleled digital quality, access and convenience to HD entertainment without the hassles associated with slow Internet downloads or limited retailer inventory."</p>

<p>Consumers can pre-order either XStreamHD's FAST Start or PRO Start packages to receive priority shipment of the first release systems at <a target="_blank" href="http://www.XStreamHD.com/">www.XStreamHD.com</a>. The XStreamHD FAST Start package includes one HD Media Server with 1TB storage, one HD Media Receiver, RF One Remote Control, and all of the accessories, including one 3m High-Speed Cat2 certified HDMI cable and two 3m Cat5e Ethernet cables. The PRO Start package includes all of above plus customers will receive an upgraded HD PRO Media Receiver, which replaces the HD Media Receiver. The FAST Start package is priced at only $399 while the Pro Start package will be offered for $499. 2TB and 4TB storage configurations are also available with both starter packages.</p>

