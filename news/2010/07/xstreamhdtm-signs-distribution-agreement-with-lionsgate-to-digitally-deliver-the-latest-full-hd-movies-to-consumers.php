<p>XStreamHD is leading the HD revolution, setting a new standard for the delivery and distribution of Full HD entertainment throughout the home. XStreamHD provides the first-ever transport network to deliver high-definition movies and music directly to the home via satellite - offering Full HD (1080p) video and up to 7.1 channels of lossless audio. With XStreamHD, consumers can build a customized, unique, and unparalleled in-home entertainment network and enjoy the content they want most including movies, music, electronic games, broadcast HDTV, and more--when it's most convenient, anywhere in the home, and at the quality today's home theaters were designed to support. XStreamHD is based in McLean, Virginia. For more information, visit <a target="_blank" href="http://www.XStreamHD.com/">www.XStreamHD.com</a>.</p>

