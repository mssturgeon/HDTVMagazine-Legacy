<p><img src="http://www.hdtvmagazine.us/news/images/onkyo-ht-s7300.jpg" alt="Onkyo HT-S7300" height="115" width="161" class="keyimg"><strong>UPPER SADDLE RIVER, NJ, 7/7/10 -- </strong>Onkyo, a brand renowned worldwide for quality home entertainment technology, has added two premium 3D-Ready packaged 'home theater in a box' systems (HTiB).</p>

<p>The Onkyo HT-S6300 and HT-S7300 both have 3-D Ready HDMI-1.4a inputs, 1080p video upscaling, lossless Dolby &amp; DTS high definition audio, Dolby height processing, Audyssey automatic room equalization, and numerous other high performance features typically not found at these price points. Both packages include seven home theater loudspeakers, subwoofer, audio-video receiver, Audyssey calibration microphone, and an outboard dock for iPod/iPhone.</p>

<p>The Onkyo HT-S6300 and HT-S7300 are each equipped with four 3D-Ready HDMI 1.4a input connectors that are fully compatible with state-of-the-art HD video players and TVs, including all the latest 3D technologies. They are compatible with the mandatory formats for 3D video broadcast content of "Side-By-Side (Half)" and "Top-and-Bottom" formats.</p>

<p>All video inputs can be upscaled to 1080p, regardless of native resolution, via the Faroudja DCDi Cinema&trade; processor. This also removes the 'jaggies' during the video signal deinterlacing process, resulting in smooth progressive-scan video images.</p>

<p>Both systems include Audyssey 2EQ room acoustics correction technology, Audyssey Dynamic EQ and Audyssey Dynamic Volume processing. Dolby ProLogic IIz height channel processing allows the back surround speakers to be re-tasked as front height speakers.<br />
Onkyo's proprietary Universal Port is provided for connection of the included UP-A1 dock for iPod/iPhone and an optional HD Radio tuner. All new models use Onkyo's new overlaid graphical OSD for seamless adjustment of settings while still viewing the program in the background. They also include Onkyo's HDMI Thru feature, which provides automatic HDMI switching when the receiver is in the standby mode, and allows children to enjoy programs using the TV's built-in speakers without turning on the AV receiver.</p>

<p>The most obvious visual difference between the two systems is that the HT-S7300 features a stunning pair of black, 41-inch tall floor-standing speakers, each with dual, vertically arrayed woofers. The center channel uses the same drivers as the stereo speakers to ensure timbre consistency. Four compact surround speakers can be used for the side, back, or height channels. The HT-S6300 speaker system consists of six, 1-foot-tall bookshelf speakers and horizontal center speaker. All seven speakers use the same 4-inch, two-way driver compliment for a very consistent surround-soundstage.</p>

<p>Both systems include a powerful 290-watt subwoofer that works with the receiver's seven 130-watt, 6-ohm power amplifiers to drive these systems to full Hollywood sound effects levels.</p>

<p>The Onkyo HT-S6300 and HT-S7300 are now available with suggested retail prices of $749 and $899 respectively.</p>

