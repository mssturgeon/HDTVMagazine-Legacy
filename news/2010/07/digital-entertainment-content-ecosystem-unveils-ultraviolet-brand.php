<p>Complementing the physical DVD and Blu-ray home entertainment markets, UltraViolet will allow consumers to watch their digital entertainment across multiple platforms, such as connected TVs, PCs, game consoles, smartphones and tablet PCs, in an easy, consistent way. Since all UltraViolet offerings will work together, consumers will be able to select which products and devices they prefer from a spectrum of familiar companies – ranging from major studios to consumer electronics companies to cable, web and other service providers. In addition, the UltraViolet name and logo will help identify entertainment products and services designed to work together seamlessly.</p>

<p>"The introduction of the UltraViolet brand is another important step towards the consumer launch of UltraViolet products and services," said Mitch Singer, DECE president and CTO of Sony Pictures Entertainment. "Our goal is to firmly establish UltraViolet as the symbol for digital entertainment – one that gives consumers the freedom of access wherever they are, the confidence of knowing how it will work and the broadest choice of content, stores and devices."</p>

<p>The UltraViolet experience will be powered by a cloud-based UltraViolet Account, which will include a Digital Rights Locker and account management functionality. Consumers will be able to create an UltraViolet Account, free of charge, via one of the many participating UltraViolet service providers or through the UltraViolet website. Once created, this Account will allow consumers to easily access and manage all of their UltraViolet entertainment, regardless of where it was purchased.</p>

<p>Technical specifications and licensing details for companies who wish to offer UltraViolet content, services and devices, are expected this year.</p>

<p>DECE also announced the addition of LG Electronics, LOVEFiLM and Marvell Semiconductor, Inc. to the consortium. These companies join DECE's already strong group which include world leaders across a wide range of industries.</p>

<p>About Digital Entertainment Content Ecosystem (DECE) LLC</p>

<p>The Digital Entertainment Content Ecosystem (DECE) LLC is a cross-industry initiative developing the next generation digital media experience based on open, licensable specifications and designed to create a viable, global digital marketplace. The DECE is currently made up of Adobe, Alcatel-Lucent, Ascent Media Group, Best Buy, Blueprint Digital, BT, CableLabs, Catch Media, Cineplex Entertainment, Cisco, Comcast, Cox Communications, CSG Systems' Content Direct, Deluxe Digital, DivX, Dolby Laboratories, DTS, ExtendMedia, Fox Entertainment Group, HP, Huawei, IBM, Intel, Irdeto, LG Electronics, Liberty Global, Lionsgate, LOVEFiLM, Marvell Semiconductor, Inc., Microsoft, MOD Systems, Motorola, Movie Labs, Nagravision, NBC Universal, NDS, Netflix, Neustar, Nokia, Panasonic, Paramount Pictures, Philips, Red Bee Media, RIAA, Rovi, Roxio CinemaNow, Samsung Electronics, Secure Path, Sony, SwitchNAP, Tesco, Thomson, Toshiba, Verimatrix, VeriSign, Warner Bros. Entertainment, Widevine Technologies Inc. and Zoran. DECE's new digital media specifications, logo program and interoperable digital rights locker will enable consumers to purchase digital video content from a choice of online retailers and play it on a variety of devices and platforms from different manufacturers.</p>

