<p><img src="http://www.hdtvmagazine.us/news/images/samsung-hmx-e10.jpg" alt="Samsung HMX-E10 HD Camcorder" height="108" width="144" class="keyimg"><strong>RIDGEFIELD PARK, N.J.--(BUSINESS WIRE)--</strong>Samsung Electronics Co., Ltd., a global leader in digital media and digital convergence technologies, today added to its point-and-shoot camcorder lineup with the introduction of the innovative HMX-E10. Offering full-HD resolution, the Samsung HMX-E10 is highlighted by a versatile, 270-degree swiveling lens that enhances consumers' creativity and allows them to add their own unique views to their video by being able to record from just about any angle. The HMX-E10's swiveling lens also brings a new sense of fun to recording video, and gives consumers the ability to step out from behind the camcorder and put themselves in the frame with their friends and family.</p>

<p>Samsung has also strived to simplify the way consumers share content with others through the HMX-E10, with the innovative built-in USB port function. The USB feature enables users to connect the camcorder directly to any computer without added attachments like a USB cable, allowing consumers to share important moments wherever they are. The USB connection can also be used to charge the battery.</p>

<p>"Samsung is focused on introducing features to its camcorders which address unmet needs and take the video recording experience to new levels for consumers," said Sangjin Park, President of the Digital Imaging Business, Samsung Electronics. "The HMX-E10 offers the image quality, ultra-compact design and built-in USB technology that consumers expect from this class of camcorder, but goes a step beyond, offering features such as a swiveling lens, versatile LCD screen and a range of smart filters, which give users the ability to do more and express their creativity."</p>

<p><br />
<strong>Easy Connectivity and Sharing</strong></p>

<p>Samsung designed the HMX-E10 to help simplify the way consumers share their content with others. The camcorder features a built-in USB connection that gives users the ability to connect the camcorder to any computer without having to worry about always carrying around a separate USB cable. In addition, the HMX-E10 is also loaded with Samsung's play-edit-sharing program, called intelli-studio. This intuitive program gives users the ability to edit and play their video from any computer without having to install supporting software. This is extremely useful when traveling or when consumers are away from the own personal computers.</p>

<p>An interactive and onscreen "upload" button on the HMX-E10 also makes uploading footage to the Web effortless. When connected to a computer with an internet connection, the one-touch "upload" button links directly to a specified content sharing Web site, such as YouTube&trade;, and reduces the number of steps needed to successfully upload and share video.</p>

<p><br />
<strong>High-Performance Sensor and Versatile Display</strong></p>

<p>At the heart of the HMX-E10 is a large, high-performance 1/3.2 inch CMOS sensor that captures impressive 1920x1080 full HD resolution video (30p / H.264) as well as eight mega-pixel digital still images. On the back of the camcorder is a versatile, 2.7-inch wide, touch-screen LCD that is set vertically. When recording video, the HMX-E10's LCD screen is divided into two sections; the top displays the live view showing what is currently in the frame and the bottom displays a series of touch-screen controls, including record, stop and play. Consumers can even rotate the swivel lens to utilize this screen to put themselves in the frame, allowing them to step out from behind the camcorder and become part of the action. When reviewing footage, consumers hold the HMX-E10 horizontally, so that they can leverage the entire display to view their video in widescreen.</p>

<p><br />
<strong>Creative Controls</strong></p>

<p>The HMX-E10 is packed with a full range of fun controls which encourage consumers to get creative with their videos. Consumers can take advantage of several Smart Filters which adjust the HMX-E10 to produce unique lens and color effects. The camcorder's lens effects include miniature, which produces the tilt and lens shift effect, and vignetting, which produces the lomo effect. Color effects include defog, which mimics the use of a CPL filter, and sketch, which gives video a pencil drawing feel.</p>

