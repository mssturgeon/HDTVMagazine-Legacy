				<p class="prtitle">JVC TO INTRODUCE GY-HM790 PROHD CAMCORDER AT NAB 2010</p>

<center><i>Innovative Design Offers Flexibility for Studio Applications, ASI Output Module Simplifies Live HD Reports from the Field</center></i><br />
<br />

<p><img src="http://www.hdtvmagazine.com/news/images/jvc-gy-hm790-prohd-camcorder.jpg" alt="JVC GY-HM790 ProHD Camcorder" height="69" width="96" class="keyimg"><strong>WAYNE, NJ (April 5, 2010) – </strong>JVC Professional Products, a division of JVC U.S.A., will introduce the new flagship of its ProHD camcorder line, the GY-HM790, at the 2010 NAB Show in Las Vegas, Nev., April 12-15 (Booth C4314). With an innovative modular design and a full complement of accessories, the new camera supports multicore or fiber-based production. Plus, as a shoulder-mount camcorder, it delivers outstanding ENG and sports production performance with more features than ever.</p>

<p>The GY-HM790 features three 1/3-inch CCDs, which allow a lighter, more compact form factor for better maneuverability in the field and more flexibility with robotic camera control systems in the studio. It produces 1920x1080 images and can record in 1080i, 720p, and even SD (480i) for operations that have not yet made the move to HD. The camera records at 35 Mbps (HQ mode/variable bit rate) or 19 Mbps/25 Mbps (SP mode/constant bit rate). The camera ships with a Canon 14x zoom lens or without lens, as accommodates a variety of lenses with its 1/3-inch bayonet lens mount.</p>

<p>Adopting the successful tapeless workflow introduced in the GY-HM700 camcorder, the GY-HM790 features a dual card slot design that records to low-cost, non-proprietary SDHC Class 6 or 10 solid-state media cards. JVC's native file recording technology allows recording in ready-to-edit file formats for Apple Final Cut Pro (.mov) and other major NLE systems (.mp4) that are compatible with Sony XDCAM EX workflow.</p>

<p>An optional ASI output module provides a direct feed from the camera to a satellite uplink or microwave transmitter via BNC – no "black box" interfaces required – for live HD video from the field. Other ENG features on the GY-HM790 include an analog SD pool feed input, 4.3-inch LCD screen, and a high-resolution, 1.2 megapixel LCOS viewfinder. Two XLR inputs with phantom power offer uncompressed LPCM audio recording with manual level controls.</p>

<p>"The excellent image quality of the GY-HM790, coupled with its versatility for both studio and ENG use, makes it an attractive camcorder for broadcasters in any DMA," said Craig Yanagi, manager of marketing and brand strategy. "Plus, our optional ASI module makes it easier than ever to produce true HD reports from the field. The GY-HM790 does more than shoot great pictures, it literally changes the way live news reports can be produced."</p>

<p>With its HD/SD-SDI port, the GY-HM790 provides an uncompressed 4:2:2 full HD signal for live monitoring, and a FireWire port provides output of SD signals or the HDV transport stream, so footage can be backed up economically with an HDD recorder. An optional SxS media recorder module attaches directly to the camcorder and allows simultaneous recording to SDHC cards and SxS media.</p>

<p>The new GY-HM790 also builds on the studio capabilities of JVC's popular GY-HD250 camera with its improved picture quality and cleaner studio integration. Its redesigned studio adapter sled incorporates a modular approach to multicore or fiber connectivity for a cleaner interface. Modules connect directly to the camera without external cabling, so they can be used either with the studio sled or handheld. Plus, JVC's modular approach allows the creation of additional modules to accommodate future technologies.</p>

<p>Other new features for studio or multi-camera use include built-in time code in/out and genlock. JVC also offers a full complement of accessories, including a remote camera control unit, remote shader panel, 8.4-inch studio viewfinder, and multi-input special effects generators.</p>

<p>The GY-HM790 will be available this summer with an MSRP starting at $11,995, including the Canon 14x HD ENG lens.</p>

<p>A specially configured low light version of the camera, the GY-HM790LL, has JVC's patented LoLux function that provides ENG users with image capture in an extremely low light environment. The LoLux version will be available to broadcast direct customers beginning in the Fall of 2010.</p>

