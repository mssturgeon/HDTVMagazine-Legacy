				<p class="prtitle">FIFA and Sony to Launch First Ever Global 3D Experience of the FIFA World Cup(TM)</p>

<center><i></center></i><br />
<br />

<p><strong>LONDON, April 8, 2010/PRNewswire/ --</strong></p>

<ul><li>Schedule of the 25 games in 3D announced</li><li>Sony to Release the Official 3D FIFA World Cup(TM) Film on Blu-ray Disc in 2010</li><li>Sony to Produce and Show 25 Exclusive Promotional Trailers for the Official 3D Film Featuring Images of the FIFA World Cup in 4,000 Retail Stores Globally</li><li>3D Live Broadcast and Public Viewing to be Made Available at Selected Locations Globally</li><li>Sony 3D Technology as the Provider of Cutting-Edge Next-Generation 3D Solutions</li></ul>

<p>Following the initial joint announcement to make the world's first FIFA World Cup(TM) available in 3D, FIFA and Sony Corporation today unveiled insights into what the football fans around the globe can expect from this innovative undertaking to add a third dimension to the football viewing experience. Coinciding with the rapidly growing consumer interest in 3D fuelled by the release of blockbuster movie titles in 3D and impending launch of 3D TV sets for the home, the first ever FIFA World Cup(TM) in 3D will further capture the excitement for millions of football fans around the globe.</p>

<p>With a total of seven pairs of Sony's professional HDC cameras on rigs at every match (model: HDC-1500), the action on the pitch will be captured in a stunning 3D quality enabled through its proprietary multi-image processor (model: MPE-200) and 3D Outside Broadcast truck. Sony's cutting-edge processor, the only one in the market to date, makes an end-to-end workflow possible in the production process and automatically adjusts the depth-of-field to ensure an unprecedented and optimal 3D viewing experience around the world. Starting from the FIFA Confederations Cup last year in South Africa, Sony has been working on enhancing the 3D capturing of fast-moving football action and has since conducted a number of 3D filming trials in Europe.</p>

<p>3D filming will be realised at five out of the 10 FIFA World Cup stadiums: Soccer City and Ellis Park in Johannesburg, Durban, Cape Town and Port Elizabeth. 25 matches in total will be filmed and broadcast in 3D, which will include a carefully chosen selection of those games expected to attract most public attention, including the opening game on June 11 at Soccer City (South Africa vs Mexico) and the crowning final game on July 11 also in Johannesburg. Other games to be captured in 3D are:</p>

<p>   <br />
    1.  June 11  16:00h  RSA v MEX<br />
    2.  June 12  16:00h  ARG v NGA<br />
    3.  June 13  20:30h  GER v AUS<br />
    4.  June 14  13:30h  NED v DEN<br />
    5.  June 15  20:30h  BRA v PRK<br />
