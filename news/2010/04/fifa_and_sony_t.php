    25. July 11  20:30h  Final</p>

<p><br />
"The 3D feed from these 25 matches will be made available for broadcast on 3D channels, which can be enjoyed by consumers on their 3D-compatible TV sets in the comfort of their home, almost as if they were in the football stadium themselves," said Niclas Ericson, Director of FIFA TV. "Whilst discussions with major broadcasters are ongoing, I am very pleased to announce the first confirmed partners for the 3D live broadcast, who are ESPN in the US and Sogecable in Spain. We expect further announcements to be made shortly," he added.</p>

<p>In line with FIFA's and Sony's endeavour to make this new exciting 3D viewing experience available to as many football fans as possible, a dedicated global 3D public viewing project will debut at this year's FIFA World Cup. Eight matches will be fed live to digital cinemas and selected venues in 3D HD quality around the globe. To this end, FIFA has appointed Swiss-based Aruna Media AG to manage the exclusive 3D cinema and entertainment venue rights for live games in 3D. Aruna plans to broadcast live 3D coverage of matches to around 26 countries and is in advanced discussions with several major markets.</p>

<p>Reaffirming its leading position at the forefront of the emerging 3D market, Sony is the key technological enabler of this new viewing experience and enhances the excitement of football fans, either watching a football match live in the stadium or enjoying a new 3D experience through 3D TV channels or at the public viewing events around the world. "Sony has long standing credentials in the creation of professional 3D technology and content for theatrical use," said Hiroko Saito, Deputy General Manager of Global Sponsorships, Sony Corporation. "True to our strategy 'From the lens to the living-room', we are actively involved at every stage of the 3D value chain and proudly draw on the strengths of the '3D World created by Sony', which encapsulates our expertise in professional solutions, consumer electronics, movie making and gaming alike. We are very excited to capitalise on these strengths and to be able to complement our compelling 3D proposition by bringing an entirely new viewing experience to the world of football through our partnership with FIFA," Saito added.</p>

<p>Complementing the 3D live broadcast and public viewing activities, the general public will also be able to exclusively enjoy the 3D promotional trailers shown on Sony 3D BRAVIA TVs in around 4,000 Sony-affiliated retail stores worldwide, including 200 Sony flagship stores (total number of Sony-affiliated retail stores: 1,500 in North America, 1,300 in Europe, 500 in Japan, 200 in Asia, 200 in Latin America, and 30 in South Africa). Furthermore, Sony Pictures Home Entertainment today unveiled plans to produce and distribute the official FIFA film in 3D on Blu-ray Disc this year.</p>

