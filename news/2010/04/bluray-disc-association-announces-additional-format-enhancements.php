<p><strong>LOS ANGELES--(BUSINESS WIRE)--</strong>The Blu-ray Disc Association (BDA) today announced two new media specifications that use Blu-ray Disc technology to provide targeted functionality for commercial and consumer applications. The specifications for BDXL&trade; (High Capacity Recordable and Rewritable discs) and IH-BD (Intra-Hybrid discs) are expected in the next few months.</p>

<p>The BDXL specification, which is targeted primarily at commercial segments such as broadcasting, medical and document imaging enterprises with significant archiving needs, will provide customers with write-once options on 100GB and 128GB capacity discs and rewritable capability on 100GB discs. The discs reach these capacities by incorporating three to four recordable layers. A consumer version of BDXL is also expected, particularly in those regions where BD recorders have achieved broad consumer acceptance.</p>

<p>"Professional industries have expressed a desire to find optical disc solutions that enable them to transition away from magnetic media for their archiving needs," said Victor Matsuda, Blu-ray Disc Association Global Promotions Committee chair. "Leveraging Blu-ray Disc to meet this need provides professional enterprises with a compact, stable and long term solution for archiving large amounts of sensitive data, video and graphic images using a proven and widely accepted optical technology."</p>

<p>The Intra-Hybrid Blu-ray Disc (IH-BD) incorporates a single BD-ROM layer and a single BD-RE layer so as to enable the user to view, but not overwrite, critical published data while providing the flexibility to include relevant personal data on the same physical disc. This allows for consumer specific applications where combining published content with related user data on a convenient, single volume is desirable. Both the ROM and the RE layers on IH-BD discs provide 25GB of capacity.</p>

<p>Because both BDXL and IH-BD are specially designed formats with specific market segments in mind, newly-designed hardware is required to play back or record BDXL or IH-BD media. However, because the new media specifications are extensions of current Blu-ray Disc technology, future BDXL and IH-BD devices can be designed to support existing 25GB and 50GB Blu-ray Discs.</p>

<p><br />
<strong>About Blu-ray Disc</strong></p>

<p>Blu-ray DiscTM is the next-generation optical disc format for high definition audio-video and high-capacity data software applications. A single-layer Blu-ray Disc holds up to 25 gigabytes of data and a double-layer Blu-ray Disc holds up to 50 gigabytes of data.</p>

