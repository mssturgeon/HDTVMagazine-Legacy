<ul><li>Color: White/Silver and Personalized</li><li>Recording Time:  Up to four hours</li><li>Storage Time: Up to 12 Hours</li><li>Memory: 16GB</li><li>Screen: 3-inch wide transflective touch screen</li><li>Video Resolution: High Definition; 1280x720 (30fps)</li><li>Video Format: H.264, MP4</li><li>Battery: Internal Li-ion rechargeable</li><li>Battery Life: Up to two hours</li><li>TV Output: HDMI Widescreen</li><li>Zoom:  2x digital</li><li>Audio: Stereo speakers, headset jack</li></ul></p>

