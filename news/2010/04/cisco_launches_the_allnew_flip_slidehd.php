<p>With SlideHD, anyone can capture an event and then relive the moment with immediate playback as friends gather around. In addition, with up to 12 hours of storage, SlideHD makes it easy for people to bring their videos and photos with them as they travel or meet up with friends or family. It's like having a portable life book for spontaneous viewing anywhere. SlideHD's 3-inch widescreen playback makes it ideal for many occasions such as entertaining the kids with their own personal video show or fine-tuning a tennis serve.</p>

<p>The Flip SlideHD is the first Flip Video camera that lets consumers shoot up to four hours of HD video or store up to 12 hours of videos, photos, and content from Flip channels(TM). SlideHD is also the first Flip to enable real-time video sharing on a stunning 3-inch widescreen with a unique slide-up design. SlideHD's simple touch screen and innovative slide strip make it easy and fun to quickly navigate through your library to locate a video or photo.</p>

<p>Like Flip's popular and stylish Mino line, SlideHD lets users design their own camcorder to make it uniquely their own. Users can also choose from thousands of designs from artists, leading design firms, celebrities, and iconic brands, or they can easily upload their own image to create a one-of-a-kind camcorder.</p>

<p>The new Flip SlideHD joins the popular Flip Video family which includes the Flip Ultra(TM) and Flip Mino(TM) lines. Like all Flip models, the SlideHD is pre-loaded with the proprietary FlipShare(TM) software that allows consumers to easily organize, create and share their videos. Using a PC or Mac, Flip video content can be instantly uploaded, both privately and publicly, and ready for one-click sharing. From social media sites - Facebook, MySpace and YouTube -- to email, mobile devices, Flip Channels, and the TV; FlipShare is the easiest solution for consumers to share their videos.</p>

<p>Since the debut of the Flip Video family of video cameras in 2007, more than four million have been sold and millions of videos have been shared using FlipShare software.</p>

