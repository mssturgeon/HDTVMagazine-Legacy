<p><strong>HORSHAM, Pa., April 12 /PRNewswire-FirstCall/ -- </strong>The Mobile Devices and Home business of Motorola, Inc. (NYSE:MOT) announced today software enhancements for its industry-leading DCX line of set-tops that represents a breakthrough in 3D video processing, providing consumers with an exceptional and seamless 3D TV experience in their home. By enabling 3D content to be processed in the set-top before delivery to the 3D-capable television, consumers will no longer be confused by having to use remote controls and access on-screen menus to configure the set-top and television set every time a channel change involves switching between 2D and 3D video. Furthermore, all of this is done while maintaining the visual integrity of emergency broadcast messages, closed captioning or on screen displays while 3D video is playing.</p>

<p>"Motorola has been developing 3D technology for more than 10 years, leading the industry with innovative solutions that support the deployment of 3D TV to the home," said John Burke, senior vice president, Motorola Mobile Devices and Home. "The development of this 3D software enhancement gives our service provider customers a straightforward solution for deploying high-quality 3D TV services today using their existing video delivery infrastructure. By focusing on the customer's viewing experience Motorola has taken 3D TV to the next level and helped our industry to bring the experience of 3D from the theater into the living-room"</p>

<p>With many service providers having already announced their intent to broadcast select 3D programming, there are several challenges to overcome to deliver 3D signals to the home using currently deployed infrastructure and devices. Although frame-compatible 3D content can be passed through deployed set-tops and viewed on 3D TVs today, accessing the set-top on-screen guide and menu while watching 3D content provides an unsettling experience for the consumer. Motorola addresses these deployment challenges and maintains its leadership position in 3D TV by integrating 3D signal processing software into the set-top. Specifically, the new 3D TV-enabled set-tops provide the following functionality:</p>

<p>  --  3D format detection: The 3D TV processing software automatically<br />
      detects the presence of 3D content and identifies the type of 3D<br />
      format used to ensure proper delivery and display on the 3D TV. As a<br />
      result, the consumer will be able to seamlessly switch between 2D and<br />
      3D channels. Additionally, the set-tops support 3D TV over both MPEG-4<br />
      and MPEG-2 and are capable of 1080p24/30 output.<br />
  --  Content reformatting: Upon detection of 3D content, the set-top<br />
      automatically reformats all on-screen text and graphics to match the<br />
      incoming 3D format so that they can be correctly displayed by the 3D<br />
      TV set. The 3D processing software supports all on-screen displays<br />
      such as closed captioning, emergency alerts, application graphics and<br />
      text overlays, as well as existing EPGs and applications.</p>

<p></p>

<p>3D TV is becoming a hot new viewing format and participants across the ecosystem are targeting home viewing. Momentum is building, and IDC survey data shows that consumers that have experienced 3D in the movie theaters express a greater willingness to pay for 3D-capable devices," said Greg Ireland, IDC Consumer Markets research manager. "Motorola is successfully demonstrating its ability to support 3D TV and continues to be one of the leading providers of 3D TV solutions."</p>

<p>"Motorola's portfolio supports the end-to-end delivery of frame-compatible 3D signals today, making it easier for service providers to deploy 3D services," continued Burke. "The fact that service providers are starting to embrace 3D TV will only increase consumer interest and further drive demand for 3D programming and services. Motorola is committed to continued innovation for 3D TV to help our customers be successful deploying this exciting new service."</p>

