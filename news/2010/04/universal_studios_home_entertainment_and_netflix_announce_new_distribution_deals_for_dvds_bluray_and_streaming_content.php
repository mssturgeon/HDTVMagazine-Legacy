<center><i>New Release DVD and Blu-ray Titles Will Be Made Available After a 28-Day Window; Film Streaming License Expanded</center></i><br />
<br />

<p><strong>UNIVERSAL CITY, Calif. and BEVERLY HILLS, Calif., April 9 /PRNewswire-FirstCall/ -- </strong>Universal Studios Home Entertainment and Netflix, Inc. [Nasdaq: NFLX] today announced agreements covering the distribution of Universal new release DVD and Blu-ray titles at Netflix while providing an expanded selection of the studio's movies that can be streamed instantly from Netflix to TVs and computers.</p>

<p>New release titles on DVD and Blu-ray will be made available to Netflix members after a 28-day window, giving Universal a dedicated time period for sales of its physical and digital offerings. Netflix receives the benefits of reduced product costs, significantly more units and better in-stock levels four weeks after street date. At the same time, a license for Universal streaming content allows Netflix to provide its more than 12 million members more movies they can watch instantly.</p>

<p>"As the home entertainment market continues to evolve, we're exploring new and creative approaches to distribution with our key studio partners," said Ted Sarandos, chief content officer for Netflix. "Our intent is to forge agreements that make sense for the companies involved and that, on the whole, improve the consumer experience and the movie ecosystem. We believe the Universal deals accomplish that."</p>

<p>"We're extremely pleased to have reached this mutually beneficial arrangement that will allow Netflix subscribers to continue enjoying Universal's film content on DVD and Blu-ray," said Craig Kornblau, president of Universal Studios Home Entertainment.</p>

<p>The first release covered under the new agreement is the comedy "It's Complicated," which will be available to Netflix subscribers 28 days after its April 27 street date. New releases will continue to represent an important component of the Netflix service, and deals such as these with Universal will allow Netflix to be better in stock on new releases after a brief window while continuing to enhance the scope and attractiveness of the streaming content Netflix members receive.</p>

