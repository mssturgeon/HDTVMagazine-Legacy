<p><strong>BUENA PARK, Calif.––</strong>Yamaha Electronics Corporation, the innovator in home theater and digital audio and video reproduction, today introduced five new HTIB (home-theater-in-a-box) systems that offer advanced features, such as ample HD source connectivity and HD Audio decoding, ideally suited for integration with Blu-ray players, flat panel displays, HD services, game consoles and portable audio/video devices. The new line includes the YHT-893 (7.1 channel, 730W Total Power, MSRP: $849.95), YHT-693 (5.1 channel, 625W Total Power, MSRP: $649.95), YHT-593 (5.1 channel, 625W Total Power, MSRP: $549.95), YHT-493 (5.1 channel, 600W Total Power, MSRP: $449.95) and YHT-393 (5.1 channel 600W Total Power, MSRP: $399.95).</p>

<p>Each system in the line boasts advanced features normally associated with higher end separate components, including 1080p-compatible HDMI repeaters (4 in/ 1 out) with 3D support for the Side-by-Side (Half) and Top-and-Bottom formats that broadcasters are adopting, as well as for current 3D Blu-ray content (via upcoming firmware update). All units also have Burr-Brown 192 kHz/24-bit DACs for all channels, Deep Color (30/36bit), x.v.Color, 24Hz refresh rates and Auto Lip-Sync compensation to ensure the picture and sound match up perfectly without requiring the manual adjustment of complex settings.</p>

<p>Leading the line, the YHT-893 features a 7.1 channel 3D-Ready AV receiver* with HD Audio decoding (Dolby TrueHD, DTS-HD Master Audio; Dolby Digital Plus and DTS-HD High Resolution Audio), HDMI Audio Return Channel support, analog video upscaling to full HD 1080p and a high-performance 2-way 7-channel speaker package with a 10-inch 100W subwoofer. The YHT-893 also includes the new Yamaha iPhone/iPod-compatible YDS-12 dock and an on-screen display to easily navigate control features and entertainment content.</p>

<p>The YHT-593, YHT-493 and YHT-393 systems have 5.1 channel receivers and speaker packages with 8-inch 100W subwoofers. The 5.1 channel YHT-693's speaker package includes a powerful 10-inch 100W front firing subwoofer to drive low-end bass.</p>

<p>All five systems offer iPod/iPhone compatibility via a Yamaha dock accessory (YDS-12) that is included in the YHT-893, YHT-693 and YHT-593 systems (and can be purchased separately for the others for MSRP $99.95). Bluetooth device compatibility is possible with the optional Yamaha YBA-10 wireless audio receiver (MSRP: $129.95). A front panel mini-jack makes it easy to connect portable audio players. Yamaha's proprietary Compressed Music Enhancer improves the sound of "ripped" music files stored on portable devices.</p>

<p>Offering seamless operation with high AV performance, all systems feature Yamaha's SCENE modes, a series of four buttons that allow users to instantly ready the system for any entertainment experience by powering the unit and selecting the correct input and surround sound combination. Yamaha's proprietary Cinema DSP (17 programs) with HD Audio decoding enable users to adjust the sound to best suit music, movies, sporting events and other programs. Adaptive DRC (Dynamic Range Control) automatically increases the volume of softer dialog passages when overall system volume is set low.</p>

<p>The top three systems feature Yamaha's proprietary YPAO technology that allows users to automatically set up their speakers for optimized sound.</p>

