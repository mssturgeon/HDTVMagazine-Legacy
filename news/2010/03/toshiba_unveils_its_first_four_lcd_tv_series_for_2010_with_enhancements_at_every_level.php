<p>Underscoring Toshiba's commitment to stellar picture quality, as well as elements that enhance consumer's overall television viewing experience, these new LCD televisions feature several key picture quality and convenience technologies. DynaLight(TM) monitors the brightness level of each video frame and automatically adjusts for deeper black levels, creating higher dynamic contrast for a more realistic picture. Photo Frame capability allows these sets to act as both a TV and a Digital Photo Frame. Consumers can now showcase their favorite memories as a clear, crisp slide show on the high-resolution television screen, all controlled with just the TV remote. Additionally, Gaming Mode takes the gaming experience to a new level by reducing game control delay, thus giving the player improved reaction time and a more realistic playing experience. This is great when used with popular gaming consoles, or with PC games using the TVs PC Input.</p>

<p>"We have enhanced our 2010 TV Line-up from top to bottom" said Scott Ramirez, VP, TV Marketing. "For 2010, both LED and LCD are important TV categories, and we have ensured that our new LCD models get enhancements that make them compelling values for our consumers. With features like DynaLight, Photo Frame capability, Gaming Mode, and the new Horizon design, these models will become must haves in their category."</p>

<p><br />
<strong>G300 Series - Fast Action, Fast Connectivity</strong></p>

<p>For sports enthusiasts and action movie fans alike, the G300 boasts ClearFrame(TM) 120Hz which doubles the video frames from 60 per second to 120 per second, designed to virtually eliminate motion blur without decreasing image brightness. Whether watching a football player angling toward the end zone, or eagerly following a high speed movie chase, the picture is crisp and clear regardless of image motion.</p>

<p>The G300 series is available in 40-inch, 46-inch, and newly offered 54.6-inch measured diagonally.</p>

<p><br />
<strong>E200 Series - Great Picture, Great Looks</strong></p>

<p>Enjoy a stunning picture bursting with color and clarity with 1080p Full HD, offered on the E200. With twice the pixel resolution of 720p HD models, Full HD is the pinnacle in picture quality. Using Full HD, there's no need to scale down a 1080 signal. This series also comes fully equipped with convenient connectivity benefits such as 4 HDMI Digital Inputs with InstaPort(TM) and REGZA-LINK, and a Hi-Res PC Input. To compliment these features, the E200 also adds a subtle luminance to the logo, furthering the stylish appeal of the television.</p>

<p>The E200 series is available in 31.5-inch, 37.6-inch, and 40-inch screen sizes measured diagonally.</p>

<p><br />
<strong>C100 Series -Features at Your Fingertips</strong></p>

<p>Toshiba's new C100 series is a feature packed 720p high-def TV providing high quality and value for the discerning consumer. The C100, available in four different screen sizes, and coupled with the attractive Horizon design, allows this television to complement virtually any room of the house including bedrooms, dens, and kitchens where the Photo Frame capability is especially useful.</p>

<p>The C100 Series is available in 18.5-inch, 21.6-inch, 26-inch, and 31.5-inch screen sizes measured diagonally.</p>

<p><br />
<strong>CV100 Series - Eliminate the Wires</strong></p>

<p>Toshiba's CV100 series combines the television picture quality and basic design of the C100 series, but also adds the convenience of a built-in DVD player. This all-in-one entertainment series is a great fit for any room of the house, even when there are space constraints.</p>

<p>The CV100 series is available in 18.5-inch, 21.6-inch, 26-inch screen, and 31.5-inch screen sizes measured diagonally.</p>

<p><br />
<strong>Pricing and Availability:</strong></p>

<p>The G300, E200, C100 and CV100 will be available to purchase starting in March 2010.</p>

