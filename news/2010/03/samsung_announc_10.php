<p>"Our commitment to innovation has always been strong. We're not only delivering elegant design and eco-friendly energy consumption, but we're adding a new dimension to superior home entertainment through a broad lineup of 3D LED TVs," said John Revie, vice president of Home Entertainment for Samsung Electronics America. "We are passionate about this year's LED TV lineup as we once again raise the bar on technology innovation by delivering a superior TV experience and leadership in the HDTV space."</p>

<p><br />
<strong>Built-in 3D</strong></p>

<p>This year's premium LED TV models, the C7000, C8000 and C9000, feature Samsung's Real240Hz&trade; refresh rate technology and Samsung's proprietary built-in 3D processor that is compatible with major 3D format standards. While the TVs are optimized for viewing 3D content, the built in 3D processor lets you render 2D content into 3D in real time.</p>

<p>Combined with the company's 3D Blu-ray player or home theater system (BD-C6900 and HT-C6930W), and unique Samsung-designed 3D Active Glasses, Samsung offers a total 3D solution for home entertainment. To further kick-start the 3D experience, consumers, for a limited time, will receive a free 3D Starter Kit with the purchase of a Samsung 3D HDTV and either the Samsung BD-C6900 3D Blu-ray Player or the HT-C6930W 3D Home Theater System. Included in the kit is a 3D version of "Monsters vs. Aliens"&reg; and two pairs of Samsung 3D Active Glasses.</p>

<p><br />
<strong>Unsurpassed Picture Quality with Precision Dimming</strong></p>

<p>Samsung's LED C8000 and C6800 include Samsung's Precision Dimming technology that merges the advantages of LED edge-lighting with the control of local dimming technology in directly back-lit LED televisions. Precision Dimming uses an array of special LEDs that create diamond-shaped areas of light to illuminate objects on the panel. These areas can vary in size and shape according to the light required, and an algorithm calculates where the light should be targeted to intensify contrast. The result: higher contrast ratios, deeper blacks, vibrant colors and enhanced energy efficiency.</p>

<p><br />
<strong>Connected TV and Samsung Apps</strong></p>

<p>The LED 6500, 6800, 7000, 8000 and 9000 come with Internet@TV connectivity which includes Samsung Apps, allowing users, with internet access or a wireless network with our Link Stick* (or similar), to download and view applications on their TV screens. Samsung Apps provides consumers with a broad selection of content and applications from leading services like The Associated Press, Netflix, Pandora, Twitter, USA TODAY, and VUDU. More than 20 apps should launch by the end of March, with more to come.**</p>

<p>Also included is Allshare&trade; for wireless connectivity and multimedia sharing across DLNA&reg; Certified devices, allowing consumers to wirelessly transfer photos, movies and music from PCs, mobile phones and digital cameras to their TV for big screen viewing at home with friends and family.</p>

<p><br />
<strong>Focus on Design</strong></p>

<p>In 2010, Samsung builds on its tradition of innovative design by introducing narrower bezels and brushed metal frames in silver and black – pushing the limits beyond the familiar black bezels of many HDTV's. The LED TVs are very slim, with the 7000 Series measuring one-inch, and LED C8000 measuring 0.9 inches and the LED C9000 measuring a pencil thin 0.3 inches. For select models, Samsung also developed a groundbreaking four-legged quad stand that makes the TV look more like furniture and a new "mystic earth" Touch of Color&trade; (ToC&trade;) design scheme with chrome edging to better match a living room's décor. The new LED TVs match Samsung's 2010 line of Blu-ray players and home theater systems.</p>

<p><br />
<strong>Green Efficiency</strong></p>

<p>All these functionalities are delivered without compromising on the energy efficiency that Samsung LED TVs are known for and meet even higher standards of sustainability. They all exceed the more stringent EnergyStar&reg; 4.0 guidelines, and are slimmer and lighter for easier shipping and storing. The 2010 LED TVs are the highest performing and most eco-conscious HDTV products Samsung has ever released.</p>

<p><br />
<strong>The Touch Screen Remote Control</strong></p>

<p>The C9000 Series come equipped with a premium 3-inch color touch-screen remote control – which features a live feed of the channel you're currently watching. For the C9000 only, the easy to use, full touch-screen remote control comes complete with an earphone jack and Twin View, which lets you watch TV or Blu-ray DVD titles on the remote or TV at the same time. The remote includes Allshare and a QWERTY keyboard for the LED C7000, C8000 and C9000, and at 2.4 Ghz, its integrated Wi-Fi and infrared technology controls the TV, STB and AV devices with on-screen buttons. The touch screen remote is available as an accessory for the LED C7000 and C8000, as well as select LCD and Plasma Series.</p>

<p><br />
<strong>Accessories</strong></p>

<p>The LinkStick makes it easy to connect to online content and acts like a thumb drive. When connected to a USB 2.0 port, it allows for online connectivity, offering easy access to Samsung Apps and InfoLink&trade; RSS data.</p>

<p>Samsung's innovative ultra-slim wall-mount solutions enhance Samsung's latest ultra-thin televisions by reducing the gap between the TV and the wall to a mere 0.6 inches, making the experience similar to hanging a picture frame. They feature a unique cord system to help you stay untangled for a neat and organized appearance. The wall mounts come in two versions that support various TV models.</p>

