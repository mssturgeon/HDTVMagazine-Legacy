<p><img src="http://www.hdtvmagazine.us/news/images/xpand-logo.jpg" alt="XpanD Logo" height="57" width="120" class="keyimg"><strong>BARCELONA, Spain--(BUSINESS WIRE)--</strong>Underscoring the innovation leadership of XpanD's active 3D technology platform for cinematic, television and gaming applications, the company today announced a partnership with Philips to provide consumers with co-branded iterations of its award-winning, patented pi-cell active 3D glasses with Philips' 3D television sets. In doing so, XpanD and Philips will provide consumers with the most advanced, most comfortable and highest-performing 3D technology that couples Philips' heritage in bringing truly immersive cinematic viewing experiences into the home with XpanD's advanced active 3D technology.</p>

<p>Commenting on the agreement, XpanD Chief Executive Officer, Maria Costeira noted, "Few manufacturers in today's high-tech marketplace can draw from the same depth of innovation and market experience that Philips Electronics puts into each and every one of its products. We are very pleased to partner with Philips to provide consumers with the best 3D technology and we look forward to working with the Philips team to explore new dimensions in consumer entertainment."</p>

<p>Echoing this sentiment, Ami Dror, XpanD Chief Strategy Officer stated, "XpanD's active 3D technology can be scientifically proven as superior to competitive offerings in the active realm and simply obliterates passive 3D on every level imaginable. It is gratifying that Philips recognizes our commitment to superior 3D and I am confident that today's announcement will serve as an important first step in a long and successful journey together."</p>

<p>XpanD debuted its range of consumer 3D glasses at the 2010 Consumer Electronics Show (CES) earlier this year. The company is the global leader for active 3D glasses for cinema, with an estimated 90-percent 3D market share in Asian cinemas and a share of more than 50-percent in Europe with 75-percent share of the 3D sector in France, Europe's largest cinema market. Leveraging this market position and technology experience into the consumer space, XpanD launched three new series of glasses at CES and gained widespread acknowledgment for technology performance, comfort and robustness.</p>

<p>"In many respects, the cinema market represents an endurance test for the glasses: our glasses are required to perform beautifully multiple times a day, many days a week and they must also be comfortable, easily cleaned and robust," Costeira explained. "Having proven our technology in the cinema sphere, we're addressing the consumer market by adding extra style to designs, making available new colors, entering OEM partnerships with great companies such as Philips and also pursuing our own retail strategy to support consumers who need additional glasses."</p>

