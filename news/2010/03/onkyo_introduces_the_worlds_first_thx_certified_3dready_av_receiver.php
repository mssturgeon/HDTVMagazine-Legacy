<p><img src="http://www.hdtvmagazine.us/news/images/onkyo-tx-sr608.jpg" alt="Onkyo TX SR608" height="225" width="300" class="keyimg"><strong>UPPER SADDLE RIVER, NJ, (3/9/10) -- </strong>Onkyo USA has announced March deliveries of its first 3D-Ready home theater receivers and home theater in a box (HTiB) systems. The new models consist of three A/V receivers and three HTiB systems ranging in price from $299 to $599, and all of them support the new HDMI v1.4 connectivity standard for new 3D video displays and Audio Return Channel capabilities. All are exceptionally well equipped to provide a superior music, home theater sound and video experience, with high build-quality and offering excellent value.</p>

<p>For Onkyo, a name that translates roughly to 'sound harmony' in Japanese, sound quality is preeminent. All these new receivers and HTiBs now decode lossless Dolby TrueHD and DTS-HD Master Audio bitstreams, and include new 192-kHz/24-bit Burr-Brown PCM1690 DAC's that are highly resistant to clock jitter and provide a remarkable 113-dB dynamic range. The lineup includes Onkyo's new easy-to-setup overlaid onscreen graphical display that lets the user watch the program in the background while using the function menus. Additionally, all 2010 HDMI v1.4 models include a new feature call HDMI Thru. HDMI Thru allows content to pass through to the TV when the receiver is in a standby state.</p>

<p>The new TX-SR608 7.2-channel THX-Select2 Plus certified receiver has new power amplifier section that uses three-stage inverted Darlington output topology, and a power boost from 90 to 100 watts. Audyssey DSX dimensional sound processing has been added to its predecessor's Dolby PLIIz capabilities. Additionally, all video sources, including those using the new PC input, and regardless of source resolution, can be upscaled to big and beautiful 1080p via HDMI and Faroudja DCDi Cinema&trade;. The TX-SR608 will also include a front HDMI input, a feature first introduced by Onkyo in 2009. The TX-SR608 will be available in April at an MSRP of $599.</p>

<p>The 5.1-channel TX-SR308 and 7.1-channel TX-SR508 round out this initial announcement of A/V Receivers from Onkyo. The TX-SR308 will be available in March with an MSRP of $299, a followed by the TX-SR508 in April for $399.</p>

<p>The HTiB package systems, which each consist of a receiver, speakers and a subwoofer, are the 5.1-channel HT-S3300 and 7.1-channel HT-S5300; the latter also includes an iPod dock. Thanks to the HDMI interface and the use of advanced Dolby and DTS codecs, all of these receivers and systems are also capable of decoding lossless Dolby TrueHD and DTS-HD Master Audio. The HT-S3300 will ship in March with an MSRP of $379, followed by the HT-S5300 in April for  $599.</p>

<p>A third packaged system departs from the traditional HTiB form factor and uses a combination subwoofer and 3D Ready A/V receiver plus two front speakers. It uses Onkyo's own Theater-Dimensional processor to create an immersive and convincing surround effect through just 2.1 channels. The HTX-22HDX has three HDMI v1.4 inputs, handles HD audio formats from DTS and Dolby; offers four distinct audio modes for gaming; and outputs for additional speakers. The HTX-22HDX will ship in May with a $349 MSRP.</p>

<p>"Onkyo's 2010 entry-level product line represents a significant jump over last year's line," said Paul Wasek, Onkyo USA's marketing manager. "We are excited to deliver this first wave of 3D capable products. By upgrading to 1.4, even on the least expensive HTiB, we have eliminated all HDMI pass-through products and allowed HD audio formats to be used across the line. The fact that consumers can now buy a THX-Certified receiver with 1080p upscaling, Burr-Brown DACs, PC input and more for under $600 shows Onkyo's clear commitment to delivering performance and value to consumers."</p>

<p>All of Onkyo's receivers offer exceptional connectivity options with as many as six HDMI inputs, plus component and composite video, numerous stereo input jacks,  optical/coaxial digital inputs, and the popular front-panel connections on many models. Two models include Sirius Radio connections, and all these receivers incorporate Onkyo's proprietary Universal Port (U-Port) connector which simplifies connections to optional HD Radio tuners and iPod Docks (included with the HT-S5300). </p>

