				<p class="prtitle">Toshiba Introduces the New UX600 Series LED TV, Blending High Picture Quality with Internet Capability That is Fun and Easy</p>

<center><i>Slim and easy to use, the UX600 with included Wi-Fi(R) adapter delivers digital entertainment on demand</center></i><br />
<br />

<p><strong>WAYNE, N.J., March 22 /PRNewswire/ -- </strong>Toshiba America Consumer Products L.L.C. ("Toshiba"), a market leader in LCD TVs, today announced the availability of the new UX600 LED TV, offering breakthrough picture quality with advanced interactive features for non-stop entertainment.</p>

<p>Entertainment on-demand is taken to new levels with the UX600's NET TV(TM) capabilities. Net TV includes a wide variety of applications that broaden the definition of "TV Content" and enrich the overall user experience. VUDU(TM) Movies offers true 1080p HD, 5.1 surround sound and gives viewers access to over 3,000 HD movies on demand. NET TV also streams audio applications such as Pandora(R) and creates personalized "Channels" of the music users enjoy. Viewers can also keep in touch while watching TV through social networking applications like Facebook(R) and Twitter(R). Additionally, video and photo services such as YouTube(TM), Flickr(R), and Picasa(TM) Web Albums let users share content with friends and family wherever they live. News services including the New York Times(R), AP, National Weather, and more, provide up to the minute information about the world around you. And, the customizable "Ticker" available at the bottom of the screen allows you to keep up to date with information from Twitter, News, Weather, or Stocks, automatically.</p>

<p>In order to provide consumers with simple and instant access to the Internet, the UX600 also comes equipped with its own Wi-Fi adapter. Unlike some other Internet capable televisions, the UX600 is ready to deliver the latest content right out-of-the-box. The included WPA Wi-Fi adapter eliminates the need to purchase additional accessories, and simplifies the set-up process.</p>

<p>"This is a high quality LED TV that is both simple and fun!" said Scott Ramirez, VP, TV Marketing. "We have packed amazingly deep LED picture quality, robust Internet capability, and a long list of key Toshiba features, into our new slim Air Lagoon(TM) design, and included a Wi-Fi Adapter to make it a total pleasure from day one. This is a package people will be excited to own."</p>

<p>Available in 40 , 46 and 55 sizes (measured respectively at 40.0 , 46.0 and 54.6 diagonally), the UX600 is packed with a number of cutting-edge picture quality features. The stunning 3M:1 dynamic contrast ratio LED produces a clearer, crisper image. To ensure consistent contrast levels, the UX600 benefits from Toshiba's CrystalCoat(TM) high contrast screen coating to keep contrast high in bright rooms, AutoView(TM) which analyzes ambient room light and the incoming video signal to automatically create the optimal picture in all lighting conditions and DynaLight(TM) automatically adjusts the backlight intensity based on the incoming video signal. All this is combined with the Pixel Pure(R) 5G engine, whose superior processing enhances the quality of high definition and standard definition images. Fast-paced action video also achieves the ultimate clarity with Toshiba's ClearFrame(TM) 120Hz technology which doubles the video frames from 60 per second to 120 per second to reduce any motion blur that may occur when watching sports or action movies. The superior picture quality is matched by superior sound quality as Dolby(R) Volume ensures a consistent volume level, even during commercials or when changing channels.</p>

<p>Going above and beyond an ordinary television, the UX600 also boasts many other features designed to enhance the consumer experience. Photo Frame capability lets consumers effortlessly view photos in an automatic slide show, allowing the TV to act as both a TV, and a digital photo frame. Gaming Mode is designed reduce game controller delay, giving the player improved reaction time and a more realistic playing experience. With the UX600, these, along with a list of other advanced features, transform television viewing.</p>

<p>The UX600 heralds a new luxurious appearance for Toshiba's LED range, featuring a slim, gorgeous Air Lagoon(TM) design less than 2 in depth. As efficiency is also important, the UX600 also meets ENERGY STAR(R) 4.0 requirements.</p>

<p><br />
<strong>Pricing and Availability:</strong></p>

<p>The 40UX600, 46UX600 and 55UX600 will be available to purchase from March 2010 at a</p>

<p>Suggested Retail Price of $1,399.99, 1,699.99 and $2,499.99 respectively.</p>

<p>For full product details and more information on the UX600 as well as other television products, please visit http://www.tacpnewsroom.com/ or http://www.toshibatv.com/.</p>

