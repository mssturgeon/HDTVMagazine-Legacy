<p><strong>PRINCETON, N.J.--(BUSINESS WIRE)--</strong>With its 3D-ready satellites and teleports serving as the distribution backbone, SES WORLD SKIES, a division of SES S.A. (Paris:SESG)(LuxX:SESG), today announced it plans to join leading broadcasters, programmers, TV makers and technology providers in a series of extensive tests aimed at accelerating the delivery of 3D TV.</p>

<p>Planned for this spring, the trials are expected to bring together eight major 3D TV components that will be tested under real-life scenarios in an end-to-end platform. Participants in the high learning environment will include innovators in content production, formatting, encoding, uplinking and transmission, headend reception, network distribution and display. SES WORLD SKIES' teleports in Vernon Valley, New Jersey and Manassas, Virginia will provide encoding, uplinking and delivery.</p>

<p>"This is a clarion call to anyone doing 3D TV. We have the platform for a whole new dimension of collaboration focused on doing 3D TV right," said Bryan McGuirk, Senior Vice President of Media Solutions for SES WORLD SKIES. "While stereoscopic formats are being debated, the test platform allows everyone from content producers and cable operators to the makers of TVs and 3D glasses to identify firsthand any compatability issues with existing satellite-based video distribution systems."</p>

<p>"There is a lot of work being done in the areas of 3D production and screens, but no one was considering the end-to-end chain and how to distribute 3D TV over the existing infrastructure in the U.S.," explained Alan Young, SES WORLD SKIES' Chief Technology Officer. "New advancements in encoding, encryption, modulation and compression make satellite an extremely relevant player in the delivery of 3D TV."</p>

<p>SES WORLD SKIES will pull on its deep HD expertise as it embarks on a new 3D TV initiative. Together with sister company SES ASTRA, SES WORLD SKIES delivers more HD channels than anyone in the business, and the firm's advanced satellites and HD-PRIME neighborhood have become the defacto home for leading HD content.</p>

<p>"We're focused on accelerating the adoption of 3D TV," said Steven Corda, Vice President of Market Development for SES WORLD SKIES. "No question 3D TV in some capacity is going to become a big part of the at home entertainment experience. We want to make sure it's a long-term commercial success."</p>

