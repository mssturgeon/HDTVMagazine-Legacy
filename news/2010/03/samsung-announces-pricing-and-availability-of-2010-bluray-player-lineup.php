<p>The Samsung BD-C7500 offers a multimedia experience that goes well beyond traditional Blu-ray players. A CES 2010 Innovations Honoree in the Video Components product category, the BD-C7500 is Samsung's slimmest Blu-ray player on the market at 1.1 inches. The super-slim, stylish device features an elegant nature-inspired wood design coated with jewel-like gloss. It is designed to be wall-mounted, or comes with a wedge stand and can be placed on a 40-degree angle or placed flat. It includes a motorized front panel, wireless dongle, 1GB of embedded memory, and two- channel analog out.</p>

<p>The BD-C7500 features improved disc load and boot up times, while the 1080p playback reproduces movie images at 24 fps without need for up-conversion, resulting in a natural on-screen motion.</p>

<p><br />
<strong>Liberating Content with 3D Playback: BD-C6900</strong></p>

<p>With the BD-C6900, entertainment enthusiasts can enjoy 3D content on their Blu-ray player, enhanced with multi-channel HD surround sound. Samsung provides consumers with a way to immerse themselves in the entertainment experience and watch their favorite 3D titles from the comfort of their homes. The player is compatible with Samsung's new 3D HDTVs, liberating content for the TVs by adding a new dimension to home entertainment.</p>

<p>True in its commitment to elegant design, Samsung delivers the BD-C6900 in a slim form factor and a transparent cover that allows the consumer to see the disk spin as it plays. It includes built-in Wi-Fi, 1GB embedded memory, 1 USB port, and 7.1 channel analogue out.</p>

<p><br />
<strong>Fast Performance, Quality Entertainment: BD-C6500</strong></p>

<p>With fast 15-second disc loads boot-up times, the BD-C6500 is one of the quickest Blu-ray players in the market giving consumers more time to relax and enjoy their favorite movies in high-definition. Another CES 2010 Innovations Honoree, the player features enhanced Blu-ray disc playback using Samsung's Adaptive Servo Technology (AST). All of this is packaged in a slim and sleek design and includes built-in Wi-Fi ability, 1GB embedded memory, 1 USB port, and 7.1 channel analogue out.</p>

<p><br />
<strong>Affordable, High Performing: BD-C5500</strong></p>

<p>The BD-C5500 is designed for those who want a high-performing Blu-ray player with advanced multimedia features at an affordable value. It includes a turbo engine for fast booting and loading and is Wi-Fi ready (separate purchase of Samsung Wi-Fi USB dongle required) providing consumers with access to apps based content services so they can surf the content of their DLNA devices or the diverse entertainment options via Internet@TV. It also includes two USB ports and Full Screen, which allows you to expand HDTV images from 21:9 formats to 16:9 screen size at the touch of a remote button.</p>

<p><br />
<strong>Connected TV and Samsung Apps</strong></p>

<p>With a focus on connected entertainment, the BD-C6500 and models above include built-in Wi-Fi support. Consumers are also able to access Samsung's upgraded Internet@TV feature for the first time on all Samsung Blu-ray players via their wireless/broadband connection, even if they do not have a Samsung HDTV. New for Internet@TV this year is Samsung Apps, providing consumers with an expanded, easy to navigate selection of content and applications from leading services like The Associated Press, Netflix, Pandora, Twitter, USA TODAY, and Vudu. Applications can be downloaded and viewed all while watching TV. More than 20 will launch by the end of March free of charge, with more to come.</p>

<p><br />
<strong>Greater Energy Efficiencies</strong></p>

<p>Consistent across all of the 2010 Blu-ray player models is a commitment to green technology. Each player has improved energy efficiency through technologies such as loader duty control, low voltage spindle motor, and analog video detect, which contribute to a reduced power consumption of 13W during disc playback, and just 0.1W in stand-by mode. The players are all compliant to EnergyStar&reg; 2.0 guidelines.</p>

