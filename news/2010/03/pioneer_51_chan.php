				<p class="prtitle">Pioneer 5.1 Channel A/V Receivers Deliver Expanded iPhone Experience to the Home Theater</p>

<center><i>Two New Models Feature Bluetooth&reg; Audio Streaming and High Definition Connectivity with 3D Ready Feature</center></i><br />
<br />

<p><img src="http://www.hdtvmagazine.us/news/images/2010-03-01_pioneer_vsx_820_k_iphone_certified_a_v_receiver.jpg" alt="Pioneer VSX-820-K iPhone Certified A/V Receiver" height="69" width="144" class="keyimg">Pioneer Electronics (USA) Inc. today unveils a new line of 5.1 channel A/V receivers that deliver a dynamic music experience to the living room. For the first time, the Pioneer VSX-520-K and VSX-820-K feature wireless Bluetooth&reg; transfer of audio content allowing users to enjoy their music directly from their Bluetooth&reg;-enabled device to their home theater system and are 3D Ready with the latest HDMI, version 1.4, providing more high definition connectivity options for the Blu-ray 3D specification. The VSX-820-K also features "Works with iPhone" certification, providing a seamless user experience for iPhone owners. Pre-orders of the VSX-520-K and the VSX-820-K are currently available at Amazon.com.</p>

<p>"Pioneer continues to innovate the A/V receiver category with expanded compatibility for iPhone users. The addition of Bluetooth audio streaming allows consumers to keep their phones close to them to answer calls or select their next song without limitations of a wired connection to the receiver," said David Bales, marketing manager of audio products for the home entertainment division of Pioneer Electronics (USA) Inc. "Additionally, by equipping all models with HDMI 1.4, consumers can be assured that their Pioneer receiver is ready for future 3D home theater experiences."</p>

<p><br />
<strong>Enhanced iPhone&trade; Functionality &amp; Bluetooth Audio Streaming</strong></p>

<p>The new models feature expanded iPhone&trade; functions including an iPhone&trade; Control Button and Bluetooth Audio Streaming for portable media devices.<br />
<ul><li><strong>"Works with iPhone" Certification</strong> – Pioneer was the first in the industry to introduce "Works with iPhone" certified A/V receivers which allow for playback of content on an iPhone&trade;, iPod&reg; and iPod&reg; Touch. The VSX-820-K features this certification and allows users to listen to their music, watch downloaded as well as stream audio and video such as YouTube and Rhapsody music services all while charging their Apple devices when connected to the receiver.</li><li<strong>>iPhone&trade; Control Button</strong> – Adding to the ease-of-use expected by Apple users, the VSX-820-K additionally features a front panel iPhone Control button that transfers iPod&reg; navigation control and on-screen display from the A/V receiver's remote control back to the connected Apple device so users can easily and quickly navigate through their library of media files directly on the device.</li><li><strong>Bluetooth Audio Streaming</strong> – Expanding on the iPhone&trade; user's experience, both new models feature wireless Bluetooth transfer of audio content from any Bluetooth-enabled iPhone&trade;, iPod&reg; Touch, Android, Smart Phone or personal computer with an optional Bluetooth adaptor. The Pioneer branded AS-BT100 ($99) Bluetooth Adaptor allows consumers to keep the phone close to them while they enjoy music through their home theater system.</li></ul></p>

<p><br />
<strong>3D Ready Features</strong></p>

<p>Both new Pioneer A/V receivers are 3D Ready with the latest HDMI version 1.4 and feature the new Dolby ProLogic IIz decoder for HD audio formats.<br />
<ul><li><strong>HDMI 1.4</strong> – HDMI 1.4 allows for passage of the high data transfer rate required by the Blu-ray 3D specification as well as a new 3D specific command protocol.</li><li><strong>Dolby ProLogic IIz Decoding</strong> – All new Pioneer receivers are equipped to decode new HD Audio formats including Dolby True HD&reg; and DTS Master&reg; now with the new Dolby ProLogic IIz height channel. Dolby ProLogic IIz distinguishes background sounds and adds them to additional front height speakers for an enhanced front surround sound experience. Creating the depth and dimension of a lifelike soundstage, this speaker configuration is ideal for gamers and may also complement a 3D video experience. The new technology provides new speaker placement options for consumers as well as easier installation solutions. Additionally, Pioneer's proprietary Front Wide Mode adds versatility and dimension to a 7.1 speaker arrangement.</li></ul></p>

<p><br />
<strong>Pioneer's Proprietary Audio Enhancements &amp; Room Calibration</strong></p>

<p>The new 5.1 channel A/V receivers feature Pioneer's proprietary audio enhancement and room calibration technologies that elevate the sound quality experience of compressed audio including:<br />
<ul><li><strong>Advanced Sound Retriever</strong> – ASR enhances compressed audio files by restoring critical data from iPhone, iPod and other portable media players as well as satellite radio devices, delivering a robust music experience that is near CD quality.</li><li><strong>Auto Level Control</strong> – ALC technology ensures consistent listening from all entertainment by equalizing fluctuating volume levels across digital audio tracks, television channels and commercials that can cause unexpected disruptions to the entertainment experience.</li><li><strong>Multi-Channel Acoustic Calibration</strong> – Featured in the VSX-820-K, MCACC analyzes the room's speaker configuration then optimizes each one to balance out any room-induced acoustic inaccuracies to provide an optimal, customized audio experience in any home theater room.</li></ul></p>

<p><img src="http://www.hdtvmagazine.com/news/images/2010-03-01_51_chanel_receivers_at_a_glance.png" alt="5.1 Chanel Receivers - At a Glance" height="287" width="430"></p>

<p>All models are finished with premium glossy, black and will be available at national and regional retailers in March 2010.</p>

