<p>"Samsung has raised the bar for the plasma TV marketplace by providing exceptional picture quality in a slim and energy efficient package," said John Revie, senior vice president of Home Entertainment for Samsung Electronics America. "With our 2010 select models which include 3D capabilities and Web-enabled multimedia access through Samsung Apps, we are delivering on our promise to create products that evolve with the needs and desires of our customers."</p>

<p><br />
<strong>Samsung Plasma HDTV 8000 Series</strong></p>

<p>The Samsung Plasma HDTV 8000 Series delivers stunning performance in a deeper dimension and optimized design quality. Built-in 3D technology provides a striking depth of dimension for in home television viewing and uses a full color spectrum to deliver a rich, more immersive viewing experience. Innovations like Real Black Filter and Motion Judder Canceller (MJC) deliver our best picture quality. The Real Black Filter reduces onscreen glare caused by ambient light, so blacks and shadow details are as crisp and defined as possible, while MJC reduces motion judder commonly found in fast-paced action scenes in film-produced content. The TVs also feature a slim brushed titanium-colored bezel with hints of Samsung's signature Touch of Color&trade; (ToC&trade;) design. Additionally, the TVs are equipped with Samsung's CinemaSmooth&trade; technology for playback of 24fps Blu-ray content mirroring the quality of the latest movie theaters.</p>

<p><br />
<strong>Samsung Plasma HDTV 7000 Series</strong></p>

<p>The ultra-slim 7000 Series is equipped with a wealth of immersive viewing and picture enhancing technologies in a slim, brushed black bezel designed with affordability in mind. Samsung's proprietary, built-in 3D processor is compatible with major 3D formats. The processing can also be applied to broadcast TV, gaming content and legacy DVDs to automatically convert 2D viewing into 3D in real time. Couple this with Samsung's 3D Blu-ray player (BD-C6900) and 3D active glasses, and consumers can bring the complete 3D theater experience home.</p>

<p>The 7000 Series also includes Samsung's Clear Image Panel technology, which delivers clear images from every angle without the blurring dual images typically found with conventional panels. It also features Internet@TV connectivity to delight entertainment enthusiasts. The 58" class model received a 2010 CES "Innovations Honoree" Award.</p>

<p><br />
<strong>Samsung Plasma HDTV 6500 Series</strong></p>

<p>The Plasma HDTV 6500 Series is Samsung's opening price point ultra-slim Plasma HDTV. The TV comes with Samsung's Wide Color Enhancer and Clear Image Panel to achieve the highest picture quality available at the best value on a plasma TV. Its exterior features the company's signature ToC design. The 6500 Series also provides expansive access to entertainment options with the updated Internet@TV feature.</p>

<p><br />
<strong>Connected TV/Samsung Apps:</strong></p>

<p>The upgraded Internet@TV feature now includes Samsung Apps, providing consumers with an expanded, easy to navigate selection of content and applications from leading services like The Associated Press, Netflix, Pandora, Twitter, USA TODAY, and VUDU. Applications can be downloaded and viewed all while watching TV. More than 20 applications will launch by the end of March free of charge, with more to come. Premium apps will be available for purchase via the platform's transactional interface in the second half of 2010.</p>

<p><br />
<strong>Ever More Efficient</strong></p>

<p>Samsung's 8000, 7000 and 6500 Series Plasma HDTVs feature a high-efficiency panel that lowers the TVs power consumption to meet the more stringent Energy Star&reg; 4.0 guidelines.</p>

