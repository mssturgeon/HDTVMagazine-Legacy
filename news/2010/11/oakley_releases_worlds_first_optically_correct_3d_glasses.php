<p>"This is a landmark moment in 3D entertainment," said Oakley CEO Colin Baden. "We began with a single goal: to set the standard for optical performance in 3D. No one has ever engineered optically correct 3D glasses. We collaborated with industry partners and utilized the DreamWorks facility for testing. For OAKLEY 3D GASCAN, we achieved unparalleled visual clarity while extending the wearer's peripheral viewing angle and providing truer alignment of 3D images. This is a technological breakthrough that sets a new standard for 3D," Baden concluded.</p>

<p>It should be noted that "optically correct" does not refer to prescription correction. Conventional non-prescription lenses that are designed and manufactured with inferior technologies may cause visual distortion due to deficiencies including refractive power, optical astigmatism and prismatic power. A variant of the company's High Definition Optics&reg; (HDO&reg;), Oakley HDO-3D technology addresses these deficiencies, allowing the company to offer the first optically correct 3D glasses on Earth.</p>

<p>With HDO-3D, Oakley 3D lenses virtually eliminate the ghosting or "crosstalk" between images that reach each eye from one moment to the next, a potential problem with inferior 3D glasses. Lens curvature is another issue with conventional 3D glasses. Greater curvature around the eyes provides a wider field of view, but without highly precise optics, even a mild curve can cause visual distortion. Oakley technology maintains optical clarity so the wearer can enjoy a wide field of sharp vision. The curvature of Oakley 3D lenses has the added benefit of minimizing distractive glare.</p>

<p>This premier release of Oakley 3D Eyewear is a special rendition of a popular Oakley frame design. OAKLEY 3D GASCAN will be released this month in two optional frame finishes: Polished Black and Polished White. The new 3D glasses will be available for U.S. $120 at select Sunglass Hut locations, Oakley Stores, <a target="_blank" href="http://www.Oakley.com/">www.Oakley.com</a> and <a target="_blank" href="http://www.Zappos.com/">www.Zappos.com</a>.</p>

<p>OAKLEY 3D GASCAN is designed with a proprietary Three-Point Fit to retain the lenses in precise optical alignment. The fit optimizes comfort by eliminating the unbalanced pressure points common with ordinary frames. Oakley's durable yet lightweight frame makes contact only at the sides of the head and bridge of the nose, and it does not hook the ears like conventional frames made with curved earstems.</p>

<p>Oakley 3D lenses were developed to deliver a prime entertainment experience in cinemas that utilize passive polarization, the technology found in most 3D theaters. Oakley is also pursuing partnerships with manufacturers of home 3D systems that utilize passive polarization technology. This will allow consumers to use the same glasses for home and cinema 3D entertainment.</p>

<p>Oakley 3D glasses are optimized for indoor cinema application and are not intended for outdoor use. Due to their transmission profile (light and UV), glasses utilizing 3D polarization technology are not ideal for normal daily outdoor use and will not provide the same level of protection as sunglasses.</p>

