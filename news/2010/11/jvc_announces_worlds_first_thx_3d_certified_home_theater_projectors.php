<p><strong>WAYNE, NJ, November 9, 2010 – </strong>Four new JVC home theater projectors are the world's first to gain THX&reg; 3D Display Certification.  The four projectors, announced at CEDIA Expo in September while undergoing THX testing, will be available later this month.</p>

<p>The new THX 3D Certified projectors are the Reference Series DLA-RS60 and DLA-RS50, to be marketed by JVC's Professional Products Company, and the Procision Series DLA-X9 and DLA-X7, to be available through JVC U.S.A.</p>

<p>During the THX 3D certification process, more than 400 laboratory tests are conducted, evaluating color accuracy, cross-talk, viewing angles and video processing to ensure the high quality 3D and 2D display performance that home theater enthusiasts demand. The JVC projectors have simple, one button solutions for optimized playback of 3D and 2D movies – THX Cinema Mode to ensure that color reproduction, luminance, blacks, gamma and video processing matches what the filmmaker intended, and THX 3D Cinema Mode, which extends this same level of accuracy for 3D broadcasts and Blu-ray Discs. THX 3D Cinema Mode is designed to deliver highly accurate color in 3D, while minimizing sources of cross-talk and flicker.  For further fine-tuning, all THX Modes on JVC projectors can be accessed by THX Professional Calibrators.</p>

<p>For 3D content, each projector includes two HDMI 1.4a ports and supports side-by-side (broadcast), frame packing (Blu-ray Disc), and above-below 3D transmissions. An external 3D Signal Emitter (PK-EM1) syncs the projected image with JVC's Active Shutter 3D Glasses (PK-AG1). The external 3D signal emitter ensures solid signal transmission to the 3D glasses for a superior 3D experience, no matter what type of screen is used or how the home theater has been configured.</p>

<p>The new flagship projectors, the DLA-RS60 and DLA-X9, are built using hand-selected, hand-tested components and provide a 100,000:1 native contrast ratio. For 3D display, both models come with two pairs of 3D glasses along with a PK-EM1 3D Signal Emitter. Both projectors also have a three-year warranty.</p>

<p>The DLA-RS50 and DLA-X7 offer 70,000:1 native contrast ratio, come with a two-year warranty and are compatible with JVC's PK-AG1 Active Shutter 3D Glasses and PK-EM1 3D Signal Emitter (sold separately) for 3D presentations.</p>

<p>All four projectors feature three 0.7" 1920 x 1080 D-ILA devices and are designed around JVC's third generation D-ILA High Dynamic Range optical engine that is optimized to provide exceptional native contrast ratios without a dynamic iris to artificially enhance contrast specifications.  A directed light integration system and wire grid polarizer ensures optimum light uniformity and minimal crosstalk in the light path.  A 4-step lamp aperture is combined with a 16-step lens aperture to allow more precise management of lamp output, which further improves black level and native contrast.<br />
With a new short arc gap, lamp brightness has been increased from earlier JVC models to 1,300 ANSI lumens.  To reduce motion blur, JVC's double-speed 120Hz Clear Motion Drive technology uses a newly developed LSI for frame interpolation black frame insertion.</p>

<p>These same four models also include a new seven-axis color management system (R, G, B, C, M, Y and orange) that allows precise color tuning, especially in skin tones, and a choice of color profiles, including Adobe RGB, DCI and sRGB/HDTV.  They have also been designed for ISF certification and will include an ISF C3 mode for professional calibration. Ninety-nine screen correction modes match the projector to 99 specific types of projection screens.</p>

<p>All four models share a completely new design, with a center-mounted lens and rear power, signal and control connectors for improved cable management and more versatile positioning and mounting options. Rear-to-front airflow also allows more placement flexibility while reducing thermal concerns.</p>

