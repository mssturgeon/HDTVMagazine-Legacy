<p><strong>YONKERS, N.Y., Nov. 1, 2010 /PRNewswire-USNewswire/ -- </strong>In its first-ever ranking of 3D performance, Consumer Reports evaluated 14 3D TV models and found that plasma TVs are better at displaying 3D images than LCD sets, primarily because they exhibit less ghosting, or double images that appear even when wearing 3D glasses. Three plasma models from Panasonic exhibited the best 3D picture quality and the least ghosting of all the sets tested. The report appears in the December Annual Electronics issue and online at <a target="_blank" href="http://www.ConsumerReports.org/">www.ConsumerReports.org</a>.</p>

<p>"It remains to be seen whether 3D TV is just a novelty or a new product category in the consumer electronics space," said Paul Reynolds, electronics editor for Consumer Reports. "But, our tests show that there are some fine 3D TV sets out there for those consumers eager for a new experience."</p>

<p>Using exclusive 3D test patterns developed in-house, as well as 3D Blu-ray movies and recorded 3D sports broadcasts, Consumer Reports engineers found that all the 3D TVs were capable of creating impressive three-dimensional depth; however, the overall quality of 3D varied quite a bit among the 14 models that were evaluated.  Consumer Reports found that attributes that affect regular picture quality also affect 3D, including black level, brightness, image detail, and viewing angle.  Ghosting, which is technically called "crosstalk," also plays a big part in 3D quality.</p>

<p>Panasonic plasma sets exhibited the least ghosting of any of the 3D TVs Consumer Reports tested, followed by plasma TVs from LG and Samsung, which had slightly more.  Sony's LCD TVs came closest to the plasmas: ghosting was minimal, but only when the viewer's head was kept level; ghosting became severe when the viewer's head was titled even slightly.  On the LG and Samsung LCD TVs, images had satisfying three-dimensional depth, but ghosting, which was significant in a wide variety of content, was distracting when apparent. All the tested 3D TVs, with one exception, performed very well with regular 2D programs.</p>

<p><br />
<strong>Things to Consider Before Buying a 3D TV</strong></p>

<p>Glasses required.  Some TVs come with one or two pairs of active-shutter glasses, which are required for viewing 3D content, but other models don't include any.  And some Sony TVs require users to additionally purchase an optional "sync transmitter," which synchronizes the glasses to the TV. Viewers must use compatible glasses that are sold by each TV manufacturer; although the first "universal" glasses have just become available. Consumer Reports found varying levels of comfort among the different 3D glasses, so viewers might want to try them on in a store before buying.</p>

<p>3D isn't for everyone.  Some people might have trouble seeing 3D images or find that they develop headaches or eyestrain from watching 3D. Consumer Reports advises consumers to heed any warnings from the TV manufacturer as the potential effects of long-term 3D viewing are still being studied.</p>

<p>There's not much content. Although some 3D Blu-ray movies have been released, they require a new 3D Blu-ray player to play back in 3D.  And many of the early releases have been tied to special "bundle" deals with a specific manufacturer. There are also some 3D broadcasts, from ESPN 3D and DirecTV's n3D full-time 3D channel, but 3D programming is still quite limited. Consumer Reports expects that more 3D movies and programs will be available later in 2011.</p>

<p>Buy or wait?  Buying a 3D TV right now makes the most sense for early adopters who want to experience 3D in their homes, or for someone who's currently in the market for a new TV and thinks they'd like to have 3D capability in the near future. Consumer Reports suggests they choose a set that did well in the full TV Ratings, then consider 3D quality.  Those who wait will have more models to choose from, possibly at lower prices, and more 3D content to watch.</p>

