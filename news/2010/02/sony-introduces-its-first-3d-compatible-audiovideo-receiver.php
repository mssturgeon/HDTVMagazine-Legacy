<p><strong>SAN DIEGO, Feb. 18 /PRNewswire/ -- </strong>Sony today announced its first A/V receiver capable of supporting 3D audio and video.</p>

<p>Featuring HDMI(TM) 1.4 3D pass-through technology, ample high definition connectivity and compatibility with all of the latest Blu-ray Disc(TM) audio formats, the new STR-DN1010 A/V receiver is designed to create a simple solution for controlling any high definition or 3D capable home theater.</p>

<p>"It's important for consumers to understand the role that audio plays in the in-home 3D experience," said Neal Manowitz, director of Sony's Home Audio and Video division. "By streamlining connectivity and supporting 3D hardware and software, the STR-DN1010 receiver will provide a simplified approach to 3D home theater control and performance, ensuring the best possible user experience."</p>

<p>The 7.1 channel STR-DN1010 A/V receiver (110 watts power per channel @8-Ohms, 1kHz, 1% THD) features full high definition 1080/24p support and seven HD inputs in total (four HDMI and three component) allowing for connection to a wide variety of HD devices. The receiver's HDMI 3D pass-through technology supports 3D video from connected devices and passes them through to a 3D compatible high definition television, while decoding high-resolution audio codecs.</p>

<p>The receiver also features an icon-driven menu system for simple device and content navigation and has the ability to upscale analog video sources to 1080p resolution via HDMI. The model also boasts a sleek piano black gloss design that matches Sony's line of Blu-ray Disc players and televisions.</p>

<p>The STR-DN1010 is compatible with all advanced audio codecs, including Dolby&reg; TrueHD, dts&reg;-HD Master Audio and features wireless 2nd zone capabilities through Sony's S-AIR&reg; wireless technology. With the addition of an S-AIR transmitter (model EZW-T100) and separate S-AIR speakers (sold separately), the receiver can also drive wireless audio in up to 10 additional rooms.</p>

<p>The STR-DN1010 A/V receiver also features a Digital Media Port (DMP) input for simple connection to external sources including an iPod&reg; and iPhone&reg; (compatible DMP accessories required and sold separately) and is compatible with both Deep Color(TM) and x.v.Color(TM).</p>

<p>The STR-DN1010 A/V receiver will be available this June for about $500.</p>

