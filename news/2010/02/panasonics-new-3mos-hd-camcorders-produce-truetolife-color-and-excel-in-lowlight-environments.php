<p>"For video enthusiasts looking for a feature-rich, high-performing, yet affordable High Definition Camcorder, Panasonic's new TM700 and HS700 3MOS models will be a hit this year," said Chris Rice, Product Manager, Imaging, Panasonic Consumer Electronics Company. "Last year's TM300 was extremely popular and won several honors and awards for its video quality and performance, so with the improvements we have made with the TM700/HS700, including extended zoom, wider-angles and a more advanced image stabilization system, we are excited to give consumers the ideal tool they need to capture their memories with superb quality."</p>

<p>The high-sensitivity 3MOS system provides an effective video image pixel count of 7,590,000 pixels (2,530,000 pixels x 3) and separates the light received through the lens into the three primary colors - red, green and blue - processing each independently. The sensor shoots 14.2-megapixel still images (in Still Image mode) and 13.3-megapixel still images from recorded video. Even with this high pixel count, newly developed technology increases sensitivity and reduces noise by one-half to achieve vivid images with minimal noise. As a result, Panasonic's 3MOS system enables excellent color reproduction, high resolution, rich gradation, and lets the user capture vividly colored images in bright or darkly-lit places.</p>

<p>The Panasonic HDC-TM700 and HDC-HS700 HD camcorders feature the newly designed, large-diameter F1.5 (46mm) Leica Dicomor lens, which provides the superb image rendering and not only suppresses ghosts and flare, but also minimizes the distortion and degradation of contrast and resolution. In addition, its 35mm** wide-angle capability makes it ideal for many different shooting situations, such as self-portraits, group photos, and landscape shots.</p>

<p>Both models feature a 12x optical zoom lens, which is further enhanced by Intelligent Resolution Technology to extend the zoom to an 18x Intelligent Zoom. The Intelligent Zoom corrects image degradation in ordinary digital zooming, extending the camera's zoom ration to approximately 1.3x, while maintaining the image quality, thus delivering stunningly clear full-HD images***.</p>

<p>Both models feature a 3.0" touch-screen LCD that allows users to navigate by selecting icons on the display. These models also have a manual ring allowing creative flexibility, so users have intuitive control of the zoom, focus, aperture, shutter speed and white balance. An Electronic View Finder, earphone terminal and microphone terminal allow for even more control. The HDC-HS700 records to its 240 GB HDD, which can store 102 hours of recording (in HE mode). When combined with Panasonic's new 64 GB SDXC Memory Card, the camcorder provides an additional recording time of 27 hours and 30 minutes. The HDC-TM700 has a 32 GB built-in memory for 13 hours and 40 minutes of recording (in HE mode).</p>

<p>Other features of the Panasonic HDC-HS700 and HDC-TM700 include:</p>

<ul><li>Power O.I.S. (Optical Image Stabilization) - Uses gyro sensors to detect hand-shake to reduce blurring. When the camcorder is held, it moves at low frequency due to the breathing of the operator or other slight movement.  POWER O.I.S. corrects even the slightest movement approximately five times more effectively than the previous version.</li><li>iA (Intelligent Auto) - Function that automatically selects the most suitable shooting mode at the press of a button, and this year iA adds Face Recognition, which finds the faces of registered people and automatically optimizes the focus and exposure for them. In addition, the camcorder continues to track this subject as the person moves anywhere within the LCD frame. Up to six faces can be registered.</li><li>Smile Shot - Feature that automatically takes a still photo during video recording when it detects a smiling face.</li><li>5.1-Channel Surround Sound System with Zoom Microphone - Uses five microphones so when voices/sounds recorded from front, right, left and back are played back on a 5.1-channel home theatre system, viewers are surrounded by clear, detailed sound.  The Zoom Microphone lets users zoom the sound only to hear the subject while continuing to record a wide-angle shot.</li><li>Wind Noise Canceller - An evolution from the previous wind noise reduction system, this advanced function automatically detects and suppresses wind noise only, to ensure only the natural sounds of the shooting environment remain.</li><li>Auto Power LCD - Automatically adjusts the brightness of the LCD screen according to the shooting environment. In dark places, the screen brightness is reduced to 1/3 the normal level to minimize the possibility of disturbing nearby people. In bright outdoor places, the screen brightness is increased to twice the normal level.</li></ul>

