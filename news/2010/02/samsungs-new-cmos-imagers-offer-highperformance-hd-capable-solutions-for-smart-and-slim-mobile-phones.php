<p><strong>SEOUL, Korea &amp; BARCELONA, Spain--(BUSINESS WIRE)--</strong>Samsung Electronics, a world leader in advanced semiconductor solutions, today announced that it has developed two new CMOS image sensors – the S5K4E2 and the S5K5CA – for the mobile phone market. Designers and manufacturers of high-end smart phones and slim mobile handsets can now integrate one of these high-performance, cost efficient, small form factor imagers into their next generation design.</p>

<p>"Consumers want a more feature rich experience when using their mobile handsets," said Dr. Dojun Rhee, vice president, System LSI marketing, Samsung Electronics. "To meet the diverse needs of the mobile phone market, we've expanded our product line-up to include imagers that support HD video capabilities while fitting into an ever decreasing module space."</p>

<p><br />
<strong>The S5K4E2 CMOS Image Sensor</strong></p>

<p>Using its proprietary pixel technology SEES (Samsung Enhanced Energy Steering), Samsung's new S5K4E2 imager is an ultra-sensitive 1/4-inch, 1.4 micron, 5Mpixel chip with an integrated extended depth of field (EDoF) IP for crisp, sharp images. The EDoF enables in-focus range from 15cm to infinity with optimum image quality. The new functionality supports the barcode and business card scanning features available in mobile operating systems. In addition, Samsung's new 5Mpixel imager can capture clear video images at up to 15 frames per second at full resolution. The SEES pixel, integrates more light into an optimized pixel structure to present clear, high resolution images. Advanced noise removal logic is also used to further improve image performance.</p>

<p>Designed to fit into a 6.5mm x 6.5mm module with a height dimension of 4.5mm, the S5K4E2 imager is suitable for ultra slim smart phones and other imaging applications which require cost and size competitiveness compared to conventional auto-focus solutions. The S5K4E2 also supports 1.2V digital power supply voltage for low power consumption and has a four-channel anti-shading correction feature for image enhancement processing.</p>

<p><br />
<strong>The S5K5CA SoC Imager</strong></p>

<p>Samsung's new S5K5CA is a 1/5-inch, 1.4 micron, 3Mpixel imager that combines both the image signal processor (ISP) with the CMOS image sensor into a single system-on-chip (SoC) solution. In doing so, Samsung is able to reduce the overall module size by 25 percent over its preceding 3Mpixel SOC imager, the quarter-inch 1.75-micron 3Mpixel solution. This SoC is ideal for 6.5mm x 6.5mm fixed focus camera modules; the current small form factor requirement for slim mobile handsets.</p>

<p>The S5K5CA's embedded ISP performs sophisticated image processing functions to enrich user experience with outstanding image quality on par with 1/4-inch, 3Mpixel 1.75 micron imager as well as 720 progressive high definition (HD) video capabilities. The S5K5CA also offers a 10 percent improvement in signal-to-noise ratio (SNR) for better color precision against the previous 3Mpixel imaging solution.</p>

<p>By including a new JPEG rotation feature that reduces frame buffer memory needed to rotate images, users can save JPEG runtime up to two seconds.</p>

<p><br />
<strong>Availability</strong></p>

<p>Samsung's new S5K4E2 is currently sampling and will be in mass production by the end of the first quarter 2010. Samsung's S5K5CA is in volume production for many of the world's top handset manufacturers today with products on the market expected later in 2010.</p>

