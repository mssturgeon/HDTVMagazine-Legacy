<p><strong>NEW YORK, Feb. 12 /PRNewswire-FirstCall/ -- </strong>Panasonic, a worldwide leader in high definition technology and the Official Worldwide Olympic Partner in the Audio and Visual Equipment category for the Vancouver 2010 Olympic Winter Games, has been selected to provide its 152-inch Plasma Display Panel to NBC during the network's studio coverage of the Vancouver Winter Games from Vancouver, February 12-28. The announcement was made today by Randy Raddatz, Vice President, Sourcing and Production Logistics, NBC Olympics and Andrew Nelkin, President, Panasonic Professional Display Company.</p>

