<p>"Our manufacturing facilities are in full production ensuring that we keep pace with this overwhelming demand for the new Christie Series 2 projectors," said Craig Sholder, Vice President of Entertainment Solutions at Christie. "With the spectacular success of 3D movies like Avatar, exhibitors realize that digital cinema is no longer an option, it is a strategic imperative. The Solaria Series is the most practical, cost-effective solution today, based on time-tested, highly reliable DLP Cinema technology."</p>

<p>Manager Vince Butler of CLACO Equipment and Service Inc. (a specialist in new cinema installations, upgrades, and maintenance of both the projection booth and auditoriums) observed, "In order to remain competitive, exhibitors have to be proactive when deciding which projector to buy today, and upgradeability to the right 4K technology is important. The main advantage of Christie DLP 4K vs. LCOS 4K is its light output capabilities. The DLP chip can handle the heat build-up better. LCOS technology does not allow for extreme heat to be dissipated, and this can affect the light output in larger venues."</p>

<p>Integrity Entertainment Systems, LLC, an authorized digital-cinema reseller for Christie, placed hundreds of orders for the new Solaria Series 2 projector, which it will install throughout the United States. Integrity president Gary Engvold wanted to provide his customers with the largest selection of 2K and 4K cinema projectors on the market. He also wanted to ensure that his customers' technology investment is future-proof.</p>

<p>"Some of our customers specifically requested Christie's next generation of cinema projectors because they offer a 4K upgrade option," remarked Engvold. "It's inevitable that 4K is the future of cinema, but I truly believe that Christie DLP Cinema projectors are the best choice for our industry because they produce more light with less energy. In fact, the energy and lamp savings from using Christie versus the LCOS technology over a ten year period is huge. It's almost enough to pay for the projector itself."</p>

<p>Engvold added: "You can tell Christie put a lot of thought into this new product. In addition to offering a 4K upgrade option, they also made a lot of other improvements to the new Series 2 platform. The units are much easier to service and simpler to operate. For me it's a 'no-brainer:' Christie really did listen to what their customers wanted and needed. The Solaria line is the only way to go."</p>

<p>"It's all about choice," said Craig Sholder. "With Christie Series 2 projectors, exhibitors can choose from the widest range of components, including external or integrated media blocks, to complete their systems. They can also create a top-of-the-line 3D solution using any of the leading 3D technologies on the market. Christie is committed to supporting its customers and protecting their technology investment."</p>

<p>In addition to the Christie CP2220, the new Solaria Series of 4K-ready digital cinema projectors also includes the Christie CP2210 and the Christie CP2230.</p>

