<p>The adoption of MPEG-2 Full HD (MPEG-2 4:2:2P@HL compliant) compression enables the recording of 1,920 x 1,080-pixel full high-definition video. Additionally, compared with the 4:2:0 profile format used in HDV and other standards, 4:2:2 color sampling offers twice the volume of color data, providing double the level of color resolution.</p>

<p><br />
<strong>Maximum 50 Mbps data recording</strong></p>

<p>With approximately twice the data volume of HDV, the new codec supports higher resolution and increased color data to enable the recording of high-quality video.</p>

<p><br />
<strong>Industry-standard MXF*2 file format</strong></p>

<p>MXF (Material eXchange Format) is a widely supported open source file format for the recording of video and audio and metadata, developed to suit the latest editing systems used by broadcasters.</p>

<p><br />
<strong>Canon partners with major editing and processing software developers</strong></p>

<p>To support the swift adoption of its new MPEG-2 Full HD (4:2:2) file-based recording codec, Canon is working in cooperation with Adobe Systems Incorporated, Apple Inc., Avid Technology, Inc. and Grass Valley to ensure compatibility with major editing and processing software programs widely used within the video imaging industry. Additionally, at future industry events, Canon intends to demonstrate the overall video-production workflow, from initial video capture to clip-trimming and final editing, with video clips stored in a file-based recording system and using industry-standard software applications.</p>

<p><br />
<strong>Advantages of File-Based Recording</strong></p>

<p>File-based recording enables video and audio data to be managed and stored by file, much in the same way as computer data. It supports efficiency throughout the production process, from initial video capture to final editing through the entire workflow. Additionally, file-based recording provides users with the flexibility to utilize different editing environments and workflow solutions without the restrictions associated with some other video recording formats, helping to reduce investment costs.</p>

