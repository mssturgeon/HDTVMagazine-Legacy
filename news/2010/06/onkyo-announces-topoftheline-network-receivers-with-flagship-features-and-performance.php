<p>Each of these models features eight HDMI&reg; 1.4a inputs, with compatibility specified for an Audio Return Channel and 3D video. Both mandatory video formats for 3D broadcasting—"Side-By-Side (Half)" and "Top-and-Bottom"—are supported. With 3D content on the rise, users will be able to take advantage of the unique visual dimensions made possible by this dynamic new format.</p>

<p>Dual HDMI outputs are also provided on these models, allowing users to connect two high-definition displays simultaneously. In conjunction with HDMI, HQV-Reon VX enables 1080p upscaling of all video inputs, regardless of source resolution. Both also feature advanced ISF video calibration, which allows users to make fine-grained, independent adjustments for each video source.</p>

<p>Audio networking and internet radio are common to both models. A rear-side Ethernet port enables easy firmware upgrades and links the receiver/controller directly to the internet or to a home PC. Users can access streaming internet radio through Pandora, Rhapsody, Napster, Slacker, Mediafly, Sirius Internet Radio, and vTuner, or play back a wide variety of PC-based audio files, including FLAC, MP3, WAV, Ogg Vorbis, WMA, WMA Lossless, AAC, and LPCM. The receivers are also Windows&reg; 7 compatible and DLNA 1.5 certified to ensure optimal compatibility with other network-enabled equipment in the home.</p>

<p>With 9.2 audio channels, users have a great deal of flexibility in how they set up their home theater. The 9-channel configuration allows users to take advantage of the expanded surround dimensions of Audyssey DSX&trade; or Dolby&reg; Pro Logic&reg; IIz. The former adds extra height or width channels for greater spatial ambience, while the latter provides the option of extra height channels.</p>

<p>Naturally, support is also provided for Dolby&reg; TrueHD and DTS-HD Master Audio&trade;, the popular lossless codecs found on Blu-ray Disc. Furthermore, compatibility with DSD Direct means that users will be able to enjoy their SA-CD collections in all their pristine clarity. High-quality Burr-Brown DACs allow these Onkyo models to handle the heavy demands of multi-channel audio processing.</p>

<p>In a modern home theater, matching audio output to the acoustic characteristics of the room is all-important. Both receivers include a full suite of Audyssey room-correction and equalization technologies. These work to optimize audio performance, regardless of room shape and volume level. Audyssey MultEQ&reg; XT, for example, uses information from up to 8 positions throughout the room to calibrate speakers for optimal audio balance.</p>

<p>Flexibility is the byword when it comes to multi-room set-ups. The TX-NR5008 and TX-NR3008 let users play a 5.1-channel source in the main room, along with fully powered stereo audio of two different sources in Zone 2 and Zone 3. On top of that, users also have the option of Zone 2/3 pre outs and Zone 2 video output.</p>

<p>The TX-NR3008 features a front-side USB port, while the TX-NR5008 has USB ports front and rear. As well as handling audio content from flash memory devices, the USB ports let users play music—and display album art—from a connected iPhone/iPod.</p>

<p>Build quality is highlighted by gold-plated audio inputs and PLL jitter-cleaning circuit technology on all models. These A/V receivers feature separate transformers for audio and video processing, with the TX-NR5008 also adding a massive toroidal transformer and 22,000 uF capacitors, a feature more typical of separate component amplifiers.</p>

<p>Other convenient features shared by both models include an analog RGB input for video content from a connected PC; a backlit and customizable remote controller; HDMI Thru allows children to still watch programs when the receiver is not turned on; and Onkyo's new overlaid graphical OSD for seamless adjustment of settings during a viewing session.</p>

<p>These new releases keep Onkyo at the forefront of high-end integrated home entertainment, and demonstrate the company's ongoing commitment to providing maximum performance at every level of the home theater market.</p>

<p>The Onkyo TX-NR3008 and TX-NR5008 will be available in August with suggested retail prices of $2,099 and $2,699 respectively.</p>

