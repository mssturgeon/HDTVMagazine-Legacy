<p>The latest innovation from a pioneer in cinema sound, Dolby Surround 7.1 improves the spatial dimension of soundtracks and enhances audio definition. The result: full-featured audio that better matches the visual impact of movies.</p>

<p>With the ability for content creators to mix in a discrete 7.1 format, Dolby Surround 7.1 provides four surround zones to better orchestrate audio channels in a movie theatre environment. The four surround zones incorporate the traditional Left Surround and Right Surround with new Back Surround Left and Back Surround Right zones. The addition of the two Back Surround zones enhances directionality in panning 360 degrees around the theatre.</p>

<p>Dolby Surround 7.1 format comprises eight channels of audio and has the following channel layout: Left, Center, Right, Low-Frequency Effects (LFE), Left Surround, Right Surround, Back Surround Left (new), and Back Surround Right (new).</p>

