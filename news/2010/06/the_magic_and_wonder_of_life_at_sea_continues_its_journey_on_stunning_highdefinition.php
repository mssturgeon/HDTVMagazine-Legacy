<p>Disneynature OCEANS is helping to conserve more than 35,000 acres of coral reef in The Bahamas on behalf of moviegoers who went to see the film during its theatrical opening week. In continued efforts, Disneynature has committed to carry on the "See OCEANS, Save Oceans" initiative by contributing a portion of sales to The Nature Conservancy through Disney's Worldwide Conservation Fund for every Disneynature OCEANS Blu-ray Combo Pack or DVD purchased between October 19 and 25. As one of the world's leading conservation organizations, The Nature Conservancy is widely recognized for its efforts to protect vital marine habitats.</p>

<p>OCEANS on Blu-ray Hi-Def will take viewers on a breathtaking and unprecedented high-definition journey to discover nature's mysteries, showcasing creatures captured on film for the first time and state-of-the-art imagery of the colorful symphony that lives under the sea. With crystal clear picture, and theater-quality sound, OCEANS puts audiences in the very heart of the action, racing along amid a school of traveling tuna, leaping with dolphins and swimming shoulder-to-fin with whales that will entertain kids and parents alike.</p>

<p>Directed by Jacques Perrin (two-time Academy Award&reg; nominee for Best Documentary, Features for Winged Migration in 2003; Best Picture for Z in 1970) and Jacques Cluzaud (Winged Migration, Les Ailes de la Nature), the two filmmakers venture in, on and around our seas to discover photogenic oddities and endangered wonders. OCEANS dives deep into the very waters that sustain all of mankind--exploring the playful splendor and the harsh reality of the weird and wonderful creatures that live within. These two directors capture mesmerizing footage using the most technologically-advanced equipment that has allowed them to bring this to true high-definition powers.</p>

<p>OCEANS is narrated by Pierce Brosnan (The Ghost Writer, Percy Jackson and the Olympians, and Mamma Mia) who has long been affiliated with environmental causes and campaigns including programs such as the International Fund for Animal Welfare's "Save the Whales Again!" campaign.</p>

<p><br />
<strong>About "See OCEANS, Save Oceans":</strong></p>

<p>By purchasing a Blu-ray Combo Pack or DVD of Disneynature OCEANS between October 19 and 25, viewers can help conserve our world's oceans and the species that depend on them for survival. In honor of each Blu-ray and DVD purchased during that period Disneynature, through the Disney Worldwide Conservation Fund, will help establish new marine protected areas in The Bahamas with The Nature Conservancy, one of the largest conservation organizations in the world. In The Bahamas, The Nature Conservancy and its local partners, including the Bahamian government, are establishing a new marine protected area along the west side of Andros Island. Currently, new marine protected area boundaries are being defined that will expand the park from 300,000 acres to over 1 million acres. These areas will contain miles of vital coral reefs that provide natural habitat, nurseries and feeding grounds for hundreds of marine species. For more details on Disney's collaboration with The Nature Conservancy, please visit: <a target="_blank" href="http://www.disney.com/oceans/">www.disney.com/oceans</a>.</p>

<p><br />
<strong>About The Nature Conservancy:</strong></p>

<p>The Nature Conservancy is a leading conservation organization working around the world to protect ecologically important lands and waters for nature and people. The Nature Conservancy and its more than 1 million members have protected nearly 120 million acres worldwide. Visit The Nature Conservancy on the Web at www.nature.org.</p>

