<p><img src="http://www.hdtvmagazine.us/news/images/onkyo-tx-nr1008.jpg" alt="Onkyo TX-NR1008" height="129" width="267" class="keyimg"><strong>UPPER SADDLE RIVER, NJ, 6/1/10</strong> -- Onkyo, a world-renowned name in quality home entertainment, announced the release of three new mid- and upper mid-range network A/V receivers for 2010: the TX-NR1008, TX-NR808, and TX-NR708. Each of these models is THX&reg; Select2 Plus&trade; certified and offers the latest processing and user-friendly features to support multi-room set-ups, network audio streaming, iPhone&reg;/iPod&reg;-compatible USB, and fully immersive 3D capable home theater with multidimensional surround sound to match.</p>

<p>All of these models have seven of the latest HDMI&reg; 1.4a connections, specifying compatibility with the new 3D video formats, which promise to bring an exciting new dimension to movies and games in the home. These new receivers are also compatible with the mandatory formats for 3D broadcast content of "Side-By-Side (Half)" and "Top-and-Bottom" 3D video formats.</p>

<p>HDMI is also the conduit for 1080p video upscaling of all video inputs, regardless of native resolution, via Faroudja DCDi Cinema&trade;. On all three of the new Onkyo receiver models, DCDi Cinema works to remove jaggies during the video signal deinterlacing process, resulting in smooth progressive-scan video images.</p>

<p>Each of these network receivers includes a rear-panel Ethernet port that links it directly to the internet or to a home PC. Users can then enjoy superior fidelity from a wide range of audio file types, including MP3, WMA, WMA Lossless, FLAC, WAV, Ogg Vorbis, AAC, and LPCM. They can also access a range of different streaming Internet radio services, from Pandora&reg;, Rhapsody, vTuner, and Sirius Internet Radio&reg;, and newly expanded services from Napster, Mediafly&trade;, and Slacker&trade; internet radio.</p>

<p>The Ethernet connection brings the added convenience of easy firmware upgrades, which enhance the unit's functionality going forward. Each receiver is also Windows&reg; 7 compatible and DLNA 1.5 certified to allow audio streaming from other network-enabled equipment throughout the home.</p>

<p>Audio processing on all three models includes the studio master-quality of the industry's two leading lossless codecs, Dolby&reg; TrueHD and DTS-HD Master Audio&trade;. Complementing these are the expanded surround dimensions of Dolby&reg; Pro Logic&reg; IIz and Audyssey DSX&trade;. The former provides the option of adding extra height channels for improved ambience, while the latter adds either height or width channels. With the 7.2-channel TX-NR808 and TX-NR708, these extra channels replace the surround rear channels. Meanwhile, with the 9.2-channel TX-NR1008, users have a host of different speaker configurations to choose from.</p>

<p>This flexibility extends to multi-room set-ups. Onkyo's new A/V receivers open the door to distributed audio in up to three rooms in the home. With the TX-NR708, users can take advantage of a powered Zone 2 or a Zone 2 line out. Meanwhile, the TX-NR808 provides a powered Zone 2, along with pre-outs for Zones 2 and 3. Finally, the TX-NR1008 can deliver 5.1-channel surround sound in the main room, plus fully powered stereo audio of two different sources in Zone 2 and Zone 3.</p>

<p>Along with the two extra amplifier channels and one extra HDMI output, the TX-NR1008 offers further advantages over its two siblings. It is equipped with advanced ISF video calibration controls for independent optimization and fine-grained adjustments of every video source. And it sports an extra 192 kHz/24-bit Burr Brown DAC to handle the heavy demands of multi-channel audio processing.</p>

<p>Each of the three Onkyo models includes a full suite of Audyssey equalization and room-correction technologies to ensure optimal audio performance in any environment and at any volume level. Chief among these is Audyssey MultEQ&reg;, which corrects for time and frequency-response problems caused by room acoustics, and which calibrates speakers for optimal audio balance throughout the listening space.</p>

<p>All three receivers have an iPhone&reg;/iPod&reg;-compatible front-side USB port that allows on-screen display of album art and navigation via the included remote. Other noteworthy features shared by this trio include an analog RGB input for video content from a connected PC; PLL jitter-cleaning circuit technology; and Onkyo's new overlaid graphical OSD for seamless adjustment of settings during a viewing session.</p>

<p>The TX-NR1008 and TX-NR808 include Onkyo's bi-directional and customizable preprogrammed remote control to simplify the process of programming all the components in the system.</p>

<p>With these latest releases, Onkyo looks to consolidate its position as a provider of the most up-to-date home entertainment features backed by rock-solid performance and intelligent design.</p>

<p>The Onkyo TX-NR708 and TX-NR808 will be available at the beginning of July with suggested retail prices of $899 and $1,099 respectively. The TX-NR1008 will ship to dealers at the end of July and will have a suggested retail price of $1,399.</p>

<p>Since 1946 Onkyo has been passionately committed to developing audio products that deliver uncommon performance, quality and value. Bundling proprietary technologies and innovations with other sound-enhancing exclusives, Onkyo continues to created award winning products that are lauded by many of the industry leading audio publications. The company's philosophy is to deliver products that are superbly designed and built to a consistently outstanding standard of excellence. Today, Onkyo is at the forefront of the home theater and digital revolutions. For more information about this and other fine Onkyo products, visit <a target="_blank" href="http://www.onkyousa.com/">www.onkyousa.com</a> or call 800-229-1687.</p>
