<p><strong>MCLEAN, Va. and ENGLEWOOD, Colo., June 29 /PRNewswire/ -- </strong>XStreamHD, an emerging leader in the delivery and distribution of Full HD entertainment directly to the home, announced that it has entered into a long-term satellite service agreement with EchoStar Satellite Services L.L.C., a subsidiary of EchoStar Corporation (NASDAQ:SATS) . XStreamHD is using satellite capacity from the EchoStar-leased AMC-16 satellite that is centrally located at 85 degrees west longitude. This enables XStreamHD to offer exceptional coverage across North America. Under the terms of the agreement, XStreamHD will increase its capacity on the AMC-16 satellite as the company's transport needs grow over time. The two companies have been working together for the past two years as XStreamHD completed the operational testing of its revolutionary transport technology.</p>

<p>XStreamHD offers HD entertainment in a 1080p format, the highest quality viewing experience, delivered via satellite directly to homes. Its patent-pending technology enables XStreamHD to deliver a higher standard of digital entertainment that is equivalent to the quality of physical media. Utilizing Fixed Service Satellite (FSS) capacity from the AMC-16 satellite, XStreamHD transports multiple streams of Pre-Fetched Entertainment (PFE) to a subscriber's sophisticated XStreamHD Media Server. With PFE, consumers enjoy a better level of entertainment convenience by having access to a customized storefront of movie titles that are automatically placed in their media server's personal library based upon their unique user preference and distinct title selections.</p>

<p>"EchoStar is pleased to support new HD content services, like XStreamHD, utilizing our available FSS capacity," said Dean Olmstead, president of EchoStar Satellite Services. "We look forward to playing a vital role in the launch of XStreamHD's entertainment service."</p>

<p>"EchoStar has been helpful throughout our development cycle as we perfected our patent-pending transport technology," stated George Gonzalez, president and CEO of XStreamHD. "Having completed a rigorous set of test protocols, we are excited to launch our advanced whole-home HD entertainment solution this summer. XStreamHD will introduce consumers to a new standard of quality and convenience, unlike any other digital entertainment service."</p>

<p><br />
<strong>About XStreamHD</strong></p>

<p>XStreamHD is leading the HD revolution, setting a new standard for the delivery and distribution of Full HD entertainment throughout the home. XStreamHD provides the first-ever transport network to offer Full HD (1080p) video and up to 7.1 channels of lossless audio of movies and music delivered directly to the home via satellite. With XStreamHD, consumers can build a customized, unique, and unparalleled in-home entertainment network and enjoy the content they want most including movies, music, electronic games, broadcast HDTV, and more--when it's most convenient, anywhere in the home, and at the quality today's home theaters were designed to support. XStreamHD is based in McLean, Virginia. For more information, visit <a target="_blank" href="http://www.XStreamHD.com/">www.XStreamHD.com</a>.</p>

<p><br />
<strong>About EchoStar Satellite Services</strong></p>

<p>EchoStar Satellite Services L.L.C. is a wholly owned subsidiary of EchoStar Corporation (NASDAQ:SATS) and provides a reliable network for aggregation and distribution of video, audio and data domestically and internationally. EchoStar also offers IPTV solutions through its ViP-TV platform. EchoStar represents a significant source of Ku-band and Ka-band satellite capacity and spacecraft operation services with access to 10 satellites, ground-based teleport facilities, and 24-hour Satellite Access Centers. Visit www.EchostarSatelliteServices.com or email SatelliteServices@echostar.com.</p>

