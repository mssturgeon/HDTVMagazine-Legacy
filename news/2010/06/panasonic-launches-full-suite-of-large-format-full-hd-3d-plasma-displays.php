<p>Panasonic Solutions Company is also announcing the TH-103VX200U and TH-85VX200U, 3D versions of its premium 103-inch and 85-inch plasma displays. These products will ship in December 2010, at suggested list prices of $65,000 and $45,000, respectively. The TH-152UX1 is targeted to be available in January 2011.</p>

<p>Ideal for a broad spectrum of cutting-edge applications, the three new Full HD 3D large-format plasmas are designed for utilization in corporate environments (e.g., for 3D CAD proposals, where life-sized 3D simulations could improve design accuracy and flexibility); in commercial applications (e.g., car showrooms or real estate offices for virtual-reality customer demos); healthcare (where the ultra-large panels and Full-HD display performance could be used to supply high-level medical solutions in advanced healthcare environments and teaching hospitals); in home theatres and screening rooms; for digital signage in public facilities; in education and in entertainment staging.</p>

<p>Several breakthrough technologies enable the 3D displays' Full-HD images and even improve 2D performance. Panasonic's 3D ultra high-speed drive technology and new motion prediction technology eliminate crosstalk (ghosting) between left and right images to produce super fine crisp images, and facilitate an overwhelming, near-infinite contrast ratio of 5,000,000:12, around twice the tone gradation of conventional models3, as well as excellent color reproduction. A 30-bit Color Processing Engine provides super-accurate color reproduction and a color management system that features high-precision pixel conversion and color signal-processing technology, high definition broadcast-compliant color reproduction, and professional picture quality adjustment that allows the displays to be set up to suit their viewing environments perfectly. The result is studio monitor-like performance with reproduction of the detail and texture of the original images with near perfection.</p>

<p>The three displays also incorporate video processing technology to allow for the crisp, smooth playback of images originally recorded in 24p, such as movies recorded on film. This raises the video reproduction performance of the plasma display panels allowing for true-to-life reproduction of colorful, high-precision content in either 3D or 2D.</p>

<p>Addressing diverse customer needs, the displays have been outfitted with a SLOT 2.0 function whereby different terminal boards may be inserted, providing compatibility with interfaces such as DVI4 and HD-SDI4, and facilitating use in a wide array of professional operating environments.</p>

