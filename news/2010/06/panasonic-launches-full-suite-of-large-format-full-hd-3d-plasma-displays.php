<p>On June 3, Panasonic established the Panasonic 3D Innovation Center, a contact point for customers working in the 3D business. The professional 3D business has seen growing demand for a wide range of 3D system solutions to meet the needs of the customers as fully as possible. Panasonic will use this Center to develop closer relationships with customers, and will offer total solutions with even more compelling 3D technologies and services.</p>

<p>Panasonic aims to accelerate 3D-based innovation within global professional markets, so that the company may lead a 3D industry revolution by creating new home viewing environments and a new video industry based around 3D plasma displays.</p>

