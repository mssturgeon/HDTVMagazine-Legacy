<p><strong>LOS GATOS, Calif. and SAN FRANCISCO, Oct. 14 /PRNewswire/ -- </strong>Netflix, Inc. (Nasdaq: NFLX) and Dolby Laboratories, Inc. (NYSE: DLB) today announced that Netflix has selected Dolby&reg; Digital Plus to deliver 5.1-channel surround sound for TV shows and movies streamed instantly over the Internet.  Beginning October 18, the PlayStation&reg;3 (PS3&trade;) computer entertainment system from Sony Computer Entertainment, Inc. will be the first consumer electronics device to support 5.1-channel surround sound on movies streamed from Netflix.  Netflix said more devices would be added over time to support streaming digital surround sound. </p>

<p>"Netflix is committed to delivering an unparalleled experience to its members who watch TV shows and movies streamed instantly over the Internet," said Greg Peters, Netflix vice president of product development.  "Netflix required an audio solution that could efficiently deliver an outstanding surround sound experience for a wide range of consumer devices.  Dolby Digital Plus proved to be the best solution to meet our needs and the needs of our device partners."</p>

