<p>RAVE HD has secured the exclusive U.S. high definition rights to 18 episodes of the BBC music series, Later ... with Jools Holland, through an exclusive agreement brokered by UK based distributor 3DD Entertainment on behalf of the broadcaster. A staple of the BBC for the past decade, the Later ...  studio is a "must visit" for musicians passing through London.  World-class talent like Santana, Coldplay, The Foo Fighters, Burt Bacharach and Arcade Fire are among the 2006 line-up.  Hosted by recording artist Jools Holland, a noted solo artist and founding member of Squeeze, each episode blends an eclectic range of artists, designed to appeal to a broad category of music lovers.  For example, a single upcoming episode features Elton John, Keane, Interpol, Bloc Party, Ray Lamontagne, Old Crow Medicine and an interview with Pink Floyd's Nick Mason.  </p>

<p>The deal required that the enormously popular ten year-old series move from standard-definition production into HD, with LoCurto's team providing collaboration on the shift.  The move also feeds the broadcaster's recently announced upgrade to high-definition programming.  </p>

<p>"Later ...  has always been about getting the best artists in the world-legendary, brand new, cult and classic-and putting them together in a room with the very best lighting, sound and camerawork, all introduced by a musician and ringmaster, the one and only Jools Holland.  The deal with RAVE HD has taken Later ...  into the contemporary quality world of HD, producing a state-of-the-art music show designed for immediate fun and for longevity," said Mark Cooper, Creative Head, BBC Music Entertainment.   Adam Wakeling, 3DD's Head of Co-Production added, "We're anticipating wonderful results from this series and look forward to continuing and growing our relationship with RAVE HD and the US audience."</p>

<p>BEAUTIFUL NOISE:  </p>

<p>RAVE HD has also entered into a production venture with Toronto-based Original Spin Media to create the music network's first original series, Beautiful Noise. RAVE HD has given a 13-episode commitment for the hour-long music performance series, taped in front of a live studio audience in a dramatically lit, converted gothic-style church.  Production will begin this month.  According to LoCurto, "The show scouts up-and-coming artists, along with established 'hidden gems.'  It gives you a chance to discover this music, and to learn a little about these great musicians."  </p>

<p>Slated to premiere on RAVE HD in 3Q 2006, Beautiful Noise will feature blues rock guitarist Jeff Healy, alternative country singer/songwriter Kathleen Edwards, Canadian singer/songwriter Ron Sexsmith, country blues rockers The North Mississippi All Stars, indie songstress and former punk-band front woman Feist, and country-folk-influenced singer Sarah Harmer. </p>

<p>SOUNDSTAGE:</p>

<p>RAVE has also inked a deal to become the exclusive high-definition home to the seminal concert series Soundstage. Part of the RAVE HD line-up since 2004, airing of the series has, until now, followed the broadcast premiere on PBS.  But beginning in 2006, new episodes will debut nationally on RAVE HD before hitting the public airwaves.  The new deal is for 14 episodes of the hour-long concert series, including performances by classic rocker Robert Plant, pop rockers Garbage and alternative rock stars Fountains of Wayne.  The pact was made with Joe Thomas, who heads the Chicago-based production/distribution company HD Ready.  Soundstage is a co-production of WTTW National Productions and HD Ready.    </p>
