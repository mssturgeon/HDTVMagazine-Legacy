				<p><em>Majority Of Shows Also To Be Presented In 5.1 Surround Sound For The First Time</em><br />
 </p>

<p><strong><em>UPN To Present All Primetime Scripted Shows in HDTV For Second Year In A Row</em></strong><br />
 </p>

<p>For the seventh consecutive year, CBS will present its scripted primetime entertainment programming in HDTV, the network announced today. In addition, the majority of that line-up will be presented in 5.1 surround sound, the most advanced sound system available on digital television. CBS, the first network to offer prime time programming in HD, will present 17 hours of primetime entertainment programming in high definition programming each week. In addition, CBS will present daytime television's #1 dramatic serial, THE YOUNG AND THE RESTLESS, in HDTV each weekday.</p>

<p>"Adding 5.1 surround sound to our programming significantly enhances the viewing experience even beyond HDTV," said Martin Franks, Executive Vice President, Planning, Policy and Government Relations, CBS. "This is the most advanced sound system available to television, offering the industry's most dramatic range, whether it's the sound of cars and planes literally racing around the viewer, or the rumbles of an explosion. Additionally, 5.1 can magnify even the quietest of sounds, further immersing the viewer into our programming. CBS has been the leader in HDTV programming, and bringing 5.1 Surround Sound more fully into our schedule advances us even further." </p>

<p>Among the CBS shows featuring 5.1 surround sound will be COLD CASE, THE KING OF QUEENS, HOW I MET YOUR MOTHER, OUT OF PRACTICE, CSI: MIAMI, NCIS, CLOSE TO HOME, STILL STANDING, YES DEAR, CRIMINAL MINDS, CSI: NY, CSI: CRIME SCENE INVESTIGATION, GHOST WHISPERER, THRESHOLD, NUMB3RS and the CRIMETIME SATURDAY block. Additionally, select CBS SUNDAY MOVIES will also feature 5.1.</p>

<p><em>UPN for the second consecutive year </em>will also present the majority of its line-up in HDTV, including a record six hours of primetime programming, including critically-acclaimed series "Veronica Mars," its popular Monday night comedy line-up and the new season's most anticipated series "Everybody Hates Chris." UPN began broadcasting select programming in HDTV in 2003, and began offering its entire scripted line-up in digital last year.</p>

<p>CBS broadcasts, on average, 34 hours per week of original High Definition programming, more than any other broadcast network, and more original HD programming per week than any other network, broadcast or cable or satellite. One hundred and eighty-nine of CBS's owned and affiliated stations are currently broadcasting in digital, covering approximately 99 percent of the nation. </p>

