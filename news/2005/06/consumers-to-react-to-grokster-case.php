				<p>Washington, DC - Leading consumer rights organizations will hold a call-in press conference at 1:00 pm EDT on Monday, June 27, 2005, to react to Supreme Court decisions to be announced that morning on the MGM v. Grokster and FCC v. Brand-X cases. The groups filed in both cases because the outcome will determine whether the Internet remains an open, competitive and consumer friendly environment that fosters innovation, or becomes dominated by a handful of companies that act as gatekeepers.</p>

<p>The ruling in the Grokster case will directly impact the fundamental proposition established in the Sony Betamax case that inventors of technologies with substantial legal uses cannot be held liable for copyright infringement by users. The groups maintain that peer-to-peer networks are an efficient form of data exchange made possible by the Internet, not copyright piracy schemes as the recording companies and Hollywood studios maintain.  The industry campaign against peer-to-peer networks represents an effort by the film and music industry to constrict and control modes of distribution, preventing artists from reaching out directly to their fans and forcing consumers to buy overpriced CDs instead of digital singles.    </p>

<p>The Brand-X case will be a critical determinant of whether communications networks will be available to all service providers and consumers on a nondiscriminatory basis, as they historically have been. The groups argued in their briefs that the decision of the Federal Communications Commission (FCC) to exempt advanced telecommunications services that are used to deliver cable modem-based high-speed Internet services, from the obligation of nondiscrimination was a grave error, both harming consumers and stifling entrepreneurial innovation. Allowing cable operators to act as gatekeepers on the flow of information has slowed technological progress and adoption of broadband.  </p>

