<p>Colorado Springs, Colo. - The CEA CEO Summit lived up to its name today when leaders of three top CE manufacturers - Yoshi Yamada, chairman/CEO of Panasonic; Tom Haga, chairman/CEO of Pioneer Electronics; and D.J. Oh, president/CEO of Samsung Electronics - shared their views in a roundtable moderated by CEA's president/CEO Gary Shapiro. </p>

<p>The roundtable, billed "Top Trends for the Digital Home," was the key event at the Summit held at the Broadmoor Hotel, here, where sales trends, profitability, investments in new technology, product complexity and consumer education were only some of the issues discussed. </p>

<p>On a day where Wall Street was concerned about $60 a barrel oil prices the three executives were uniformly bullish on the CE industry's prospects. Haga said, "I believe that second half will be very strong this year. Higher ticket [CE] products are popular and driving the industry. [But] prices of those products are coming down." Samsung's Oh noted that higher oil prices and increasing industry rates will have "no dramatic impact on CE sales in the U.S. market." </p>

<p>Concerning the fourth-quarter CE sales in the United States, all three executives had distinct opinions on where growth will come from. Panasonic's Yamada said, "There will be very strong sales in plasma TV and big-screen LCD. We see triple the sales [vs. the same time last year], drastic increases. We are seeing some of those trends now.' He added that demand for DVD recorders will be "very strong" too and that the entire CE market is "very exciting from that standpoint." </p>

<p>Samsung's Oh reiterated that the U.S. economy "should be strong enough" to sustain good CE sales in the quarter and that "HDTV and MP3 players" will drive the market. In HDTV there will be "a variety of choice and affordable pricing." In cellular phones there should be a "higher penetration rate" with a "higher rate of replacement" coming. </p>

<p>But the overall concern of all three executives is the increasing rate of price erosion and the ability of leading manufacturers to invest their margins to make next-generation products. Haga of Pioneer said that price erosion is his biggest worry. "We are talking about maturing engineering of a variety of categories. There are a lot of things we can do for the future, but it is not free. Can we recoup our investments in technology? Two or three years from now we can make better products, but can we make the investment?" </p>

<p>Yamada of Panasonic noted, "My background is being in the computer industry for 20 years. The situation in CE with flat-panel TVs, for instance, is nothing compared to PC." Still, with CE products "rapidly switching from analog to digital, CE prices are going down faster" than ever before. </p>

<p>Oh said that the "most important thing in the digital era" to combat lower prices and margins is "product differentiation, which is hard to achieve. We think about how we can differentiate our products. Our company struggles with that. We have come to the conclusion that you must speed new technology to the market, with products that have style and fashion, and have a good relationship with your retail partners." </p>

<p>Haga added that Pioneer has seen "the PC industry and we know that [digital CE product] prices are coming down. I just wish it was a little slower. We know it if we can't make profit our retail partners can't make a profit. In the past two years my company has had to analyze our business model, cut costs and keep costs down. And it is still not enough. We need to do more." </p>

<p>Manufacturer relationships with retailers and how distribution channels are managed are key ways both CE manufacturers and retailers can build sales and profits. Samsung's Oh said that his company's two main goals are "market share and profit" although in this type of market "our retailers are struggling with that." Since other types of technology companies such as "HP, Motorola and others" are now competitors "market dynamics have been set up, but who will be the winner? I think our positioning is a little better than others and that we are very adaptable, in any case." </p>

<p>Yamada said that that while "profit is very important" if a key device in a product goes down $100 another key factor is "how quickly can we convey that to the end user? We manufacturers have inventory. Retailers have eight to 10 weeks of inventory." </p>

<p>When compared to a PC marketer such as Dell can do it a lot quicker. Yamada stressed that "inventories must be reduced. That is the only way to survive in coming years." </p>

<p>Haga agreed that controlling inventories is vital especially when you consider "how distribution channels have changed in the past two or three years." And while major chains control more of the market than ever before the future retail winners will be "focused on which channels can communicate to consumers efficiently. Retailers and manufacturers must communicate more effectively over the next few years. That is very, very important. You can't just put products on the shelf. I don't care if it is a Web site or a store, whatever type of retailer communicates better in explaining products to the consumer will win. The more complex the product, more education is required." </p>

<p>With his roundtable colleagues shaking their heads in agreement, Haga added, "If consumers want 'plug-and-play products it must be 'plug-and-play,' literally! The technology is out there but most consumers don't know how to put together a home networking system, entertainment system with HDTV, etc. With convergence and home networking how much education can [manufacturers] do on our own? We can't. We need [retailers'] help!"</p>

