				<p>CEA'S SHAPIRO STANDS FIRM ON INTELLECTUAL PROPERTY ISSUES AS SUPREME COURT READIES FOR GROKSTER RULING<br />
<em>Voices Opinion on IP, Grokster Case in 2005 Digital Media Conference Keynote</em> </p>

<p>Arlington, Virginia 6/20/2005 </p>

<p>"Perhaps the biggest threat to democratized creativity comes from intellectual property policy - the increasing narrowing of fair use rights, restrictions on technology and increasing penalties for copyright violators," said Gary Shapiro, president and CEO of the Consumer Electronics Association (CEA) in a keynote address at the 2005 Digital Media Conference held Friday in McLean, Virginia. <br />
Shapiro's remarks are part of an ongoing effort on behalf of CEA and its members to redefine the language at the heart of the intellectual property debate and combat measures taken by the content community to restrict consumers' fair use rights and put a stranglehold on innovation. </p>

<p>"For too long, the technology industry, the media and policymakers, have given the content community a free hand in defining the issues of how technology affects creativity," Shapiro said. "The content industry has been flexible, clever and ruthless in defining the terms of the debate to meet their legislative objectives." </p>

<p>In his keynote, Shapiro contended that although digital technology has threatened current distribution models, it has created a renaissance in innovation and democratized creativity so anyone is free to create, produce and distribute creative content. He also reiterated that access to content should be protected as fair use rights under the First Amendment, so long as it is used for non-commercial purposes. </p>

<p>Shapiro took a firm stance against those using the umbrella of intellectual property laws to protect existing business models at the expense of technological innovation. </p>

<p>"The content industry has it wrong here. Instead of trying to enforce new legislation or overturn a 20-year-old Supreme Court ruling, content creators should focus their considerable funding and energy on finding business models that incorporate new technologies, rather than shunning them. </p>

<p>"I am less concerned about protecting anyone's old business model, than I am about not harming our future," he continued. "We have a digital destiny." </p>

<p>Shapiro's remarks came just days before the Supreme Court is expected to reach a decision in the MGM v. Grokster case. While on the surface the Grokster case is about peer-to-peer file sharing, in reality the case has much broader implications. An adverse decision could overturn the standards set in the landmark 1984 Betamax case in which the Court deemed a product legal if it has significant non-infringing uses even if the product can be used to infringe copyright. </p>

<p>"To CEA and our members, as well as millions of technology lovers across the United States, this is the most important case before the Supreme Court since Betamax," Shapiro said. "We will continue to respond appropriately to Grokster to make sure the voice of the technology industry is heard." </p>

