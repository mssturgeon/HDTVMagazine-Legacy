<p>HDFEST 2005 Los Angeles is presented by Intel. Premiere Level Sponsors of the event include Dolby Laboratories, DALSA Digital Cinema, DivX, Kappa Studios, Film and Video Magazine and Production Update Magazine. The HDFEST 2005 World Tour is also sponsored by Goldcrest Post Productions, Video Gear Source, RGB Communications, Midtown Video, Royalty Free HD, SYPHA, ProductionHub, Guardian Entertainment, and BBC Post Production.</p>

<p>"Intel does more than make the chips that are fueling today's personal computers, we're keenly interested in supporting creative digital artistic expression worldwide," said Ralph Bond, consumer education manager for Intel Corporation. "HDFEST and Intel working together makes sense. We're excited about showcasing high definition video playback on the latest consumer entertainment PCs and Intel® Centrino® mobile technology based laptops, and HDFEST is taking the lead in showcasing the creative talents of some of the best digital film creators on the planet."</p>

<p>Dolby Laboratories is a Premiere Level sponsor of the HDFEST 2005 World Tour and has been a major supporter of HDFEST since the festival's inception in 2000. Dolby Laboratories staff will be on hand to ensure that all HD films are shown with the best possible multichannel sound.</p>

