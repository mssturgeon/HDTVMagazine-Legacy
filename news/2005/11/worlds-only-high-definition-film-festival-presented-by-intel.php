<p>The feature comedy Bachelorman, directed by John Putch, will also be screened. The film stars Missi Pyle (Charlie and the Chocolate Factory, Dodgeball a True Underdog Story) and David Deluise (Stargate SG1). David Deluise's character Ted Davis is a playboy who meets his match when Heather a mysterious brunette, moves next door and refuses to fall for anything in Davis' very deep bag of tricks.</p>

<p>Advanced Technology Presentations</p>

<p>In addition to 2K festival screenings and panel discussions on HD technology, HDFEST 2005 Los Angeles will also include cutting-edge presentations on recent high-def developments. The festival will present a series of short movies presented in DivX HD as well as special presentations by DALSA Digital Cinema, Intel and JVC.</p>

