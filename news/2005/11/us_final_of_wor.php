<p>DALLAS, TX and SEOUL, KOREA - Nov 10, 2005 - Move over, poker. Competitive video gaming, known as "e-Sports", is poised to become the next spectator sport when it debuts on HDNet this week. For the first time in the United States, HDNet will broadcast ground breaking coverage of the 2005 World Cyber Games US Final, premiering Thursday November 10, 2005 at 8pm EDT. </p>

<p>Featuring games for Xbox and PCs, the show will focus on the country's best Halo 2 players as they battle for cash prizes and the right to represent the United States in Halo 2 against elite Xbox gamers from 67 countries in Singapore later this month. The 2005 US Final will also take a close-up look at the world of the popular PC game Counter-Strike and its unique culture. For sports fans, the World Cyber Games US Final will also feature the country's best FIFA soccer players. </p>

