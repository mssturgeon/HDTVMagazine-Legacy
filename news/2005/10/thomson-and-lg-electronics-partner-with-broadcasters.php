WASHINGTON, DC - The Association for Maximum Service Television, Inc. and the National Association of Broadcasters have selected LG Electronics Inc. and Thomson, SA to each develop prototype high quality, low cost Terrestrial Digital Converter Boxes to receive digital signals on conventional analog televisions.</p>

<p>Jointly funded by MSTV and NAB with development support from Thomson and LG Electronics, these prototypes will serve as blueprints for future products from manufacturers to ensure that the more than 70 million analog TVs relying exclusively on terrestrial broadcast signals will continue to receive free over-the-air TV service when all-digital broadcasting begins.</p>

<p>MSTV President David Donovan explained that today's announcement follows an extensive evaluation over the past several months of more than a dozen proposals submitted by leading electronics and integrated circuit manufacturers from around the world in response to a Request for Quotation released by NAB and MSTV on June 20. </p>

<p>"No viewer should be left behind when this nation converts to all-digital signals," said Donovan. "Developing a high-quality, low-cost digital-to-analog converter box ensures that all Americans will be able to receive emergency information and their favorite TV shows using existing analog television sets. We are delighted to be working with these companies, both leaders in the consumer electronics industry. This collaborative effort benefits all consumers. Also, it comports with Congressional efforts to subsidize quality converter boxes that provide an alternative for consumers that want to keep their current analog equipment."</p>

<p><br />
NAB President Eddie Fritts observed, "There are 21 million homes and 73 million receivers relying exclusively on antennas to receive local television signals. Disenfranchising these viewers would present a significant problem for broadcasters, the government and consumers. This project demonstrates a willingness by both broadcasters and two of the world's leading electronics companies to ensure that all Americans have affordable access to local television signals both during and after the transition to digital."</p>

<p>"LG Electronics is honored to be selected by the NAB and MSTV, and we're enthusiastic about joining forces with broadcasters to develop the next-generation of DTV reception technology," said Dr. Jong Kim, vice president, research, LG Electronics. "As a long-time participant in the digital television transition, LG and our Zenith subsidiary look forward to working with the broadcasting industry to develop this important product, which we expect to set the performance benchmark against which others should be measured to assure consumer satisfaction with digital reception. As I testified before a Congressional committee earlier this year, this kind of product is a key to the digital TV transition."</p>

<p>"We are delighted to be working with the broadcast television industry to develop a new digital to analog converter box platform," said Barb Birnbaum, director of business development for Thomson's Access Platforms & Gateways business. "We know that Congress desires an inexpensive digital-to-analog converter box in order to ensure consumers are not disenfranchised when analog broadcasts cease, and we believe there will be a market for a variety of digital-to-analog conversion products. Thomson has a long history of providing top quality receiving devices and we look forward to working collaboratively with the broadcast industry to help meet Congressional expectations."</p>

