<p><em>Exclusive North American HD Telecast to Feature Behind-the-Scenes Coverage of Astronauts' Pre-flight Activities, Launch and Landing</em></p>

<p>DALLAS - July 6, 2005 - HDNet will take viewers on an exclusive high-definition adventure with complete coverage of NASA's historic Return to Flight, as the Space Shuttle Discovery and its seven-member crew embark on mission STS-114, currently scheduled for July 13.</p>

<p>Utilizing up to 14 cameras positioned throughout the Kennedy Space Center, HDNet's extensive live coverage on the launch date will begin at 11:00 a.m. EDT with behind-the-scenes access to the astronauts and their families as they eat breakfast, suit up, board the shuttle, and complete their pre-launch routine inside the crew module.  Then viewers will witness the countdown, launch, and follow the shuttle as it reaches far into the earth's atmosphere. </p>

<p>HDNet's cameras will also be live on location for the shuttle's landing, currently scheduled for July 25 at 11:01 a.m. EDT.  In keeping with HDNet's practice of delivering live world news raw and uninterrupted by outside commentary, the network will be broadcasting the natural sounds of the launch complemented by NASA's commentary, allowing the HDNet audience to receive 100% of their information directly from mission control.</p>

<p>"NASA is pleased to work with HDNet to provide the world's viewing audience live pictures of the launch of Space Shuttle Discovery in high-definition TV," said Mike Rein, Chief, Media Services at NASA's Kennedy Space Center.  "These will undoubtedly be the highest quality pictures ever broadcast of a Space Shuttle launch."</p>

<p>"Once again, HDNet is leading the way with innovative and exclusive programming for our viewers," said Mark Cuban of HDNet. "While other networks are beholden to business as usual, only HDNet will bring launch-to-landing coverage of the Shuttle Discovery, without annoying talking heads interrupting this historic return to space."</p>

<p>Cuban continued: "HDTV is a completely new entertainment medium and only HDNet tailors programming to the advanced resolution, sound and widescreen picture HD offers. The launch of the Shuttle Discovery will be a thrilling experience on HDNet and we are proud to be partnering with NASA to present it exactly as those at the launch pad will see it."</p>

<p>Extensive Equipment and Technology Required to Produce Complex Telecast The complex task of producing a live, multi-camera, switched high-definition telecast of an historic event such as this requires extensive equipment and technical support.  HDNet is installing 1080i cameras in various locations ranging from inside the "firing room" where engineers and administrators direct the countdown, to right on the launching pad itself.  Close-up views of the exterior of the shuttle itself and of the astronauts once they are inside the crew module will appear courtesy of several NASA cameras.</p>

<p>HDNet will be deploying a special Canon DIGI SUPER 86 TELExs lens capable of a 2,322mm focal length to enable a 1080i camera situated at one of the tracking sites to follow Discovery at least 176,000 feet, or 33 miles into the earth's atmosphere. The network is also using a pan and tilt robo head at the launch pad from Eagle Pan Tilt, and is installing the Grass Valley Kalypso(TM) HD Video Production Center switcher, which is switchable between SD and HD productions inside NASA's TV control room.<br />
