<strong>PROPOSED NEW DTV TUNER MANDATE SCHEDULE WILL RAISE TV PRICES AND DISRUPT MARKET, SAY CEA AND CERC </strong></p>

<p><em>New Burdens on Smaller Sets Would Penalize Lower Income Consumers</em></p>

<p>Arlington, Va., July 27, 2005 - Accelerating and expanding the Federal Communications Commission's (FCC) digital television tuner requirements will sharply raise prices on smaller sized television sets causing disruption in the marketplace and harming low-income consumers, said the Consumer Electronics Association (CEA) and the Consumer Electronics Retailers Coalition (CERC) today.  The organizations expressed their concerns in comments filed today with the FCC in response to the Commission's Further Notice of Proposed Rulemaking (FNPRM) on digital television (DTV) receiving capability.  <br />
      <br />
In the FNPRM issued on June 9, 2005, the Commission proposes to accelerate the current mandated timetable for the inclusion of a DTV tuner in television sets of all sizes from July 1, 2007 to a completion date of no later than December 31, 2006.  It further proposes to extend the digital tuner requirements to receivers with screen sizes of less than 13-inches.<br />
      <br />
In their filing, CEA and CERC cautioned that the accelerated date would be extremely difficult for manufacturers to meet.  They added that if implemented, such a requirement likely would cause a sudden jump in prices, thereby putting smaller sets out of reach of Americans with low or fixed incomes.  <br />
        <br />
  "By contrast, the current and anticipated July 2007 date allows time for economies of scale to develop fully.  This will lessen the sticker shock for consumers, allowing these products a chance to compete against less expensive, tuner-less alternatives." <br />
      <br />
In their comments, CEA and CERC explained that there is insufficient basis for the Commission to depart from the existing July 1, 2007 date pertaining to TV receivers with screen sizes of 13 to 24-inches.  This date has been relied upon in the product and resource planning of manufacturers and in the merchandising and marketing plans of retailers.  Moreover, a change in this date to a date any earlier than March 1, 2007, would be not only unwarranted; it would be infeasible for the general population of TV receiver manufacturers, who require a minimum of 18 to 24 months to plan, develop and deploy new equipment.  Even if manufacturers were able to meet a foreshortened production schedule, a date any earlier than March 2007 could result in a complete inability for many manufacturers to produce products in this category, and cost increases for those that do become available, that the marketplace would be unlikely to sustain.</p>

<p>"This development would defeat the purpose of the tuner mandate itself," said Shapiro.</p>

<p>CEA and CERC noted that current market forces and the regulatory regime to date have proven successful.  CEA forecasts that the industry will this year sell 9 million DTVs with an integrated over-the-air (OTA) digital tuner, 16.7 million in 2006, 27 million in 2007 and 33 million in 2008.  By 2009 CEA projects that 97 million DTV tuners will have been sold, translating to 86 percent U.S. household penetration of OTA tuners.  <br />
      <br />
With respect to new receivers with screen sizes less than 13-inches, CEA and CERC explained that since the deadline on sets 13- to 25-inches has not taken effect it would be difficult to know at present, the feasibility and practicality of including DTV tuners in TVs under 13-inchs.  They noted that it currently appears that the cost and development burdens on manufacturers, and the impact on consumers, would outweigh any possible benefits.</p>

<p>While the FNPRM did not address the issue of product labeling and the need for manufactures and retailers to clearly label new TV sets to indicate whether they can receive over-the-air DTV signals or only off-the-air analog signals, CEA and CERC noted that, "TV receivers with digital tuning capability are, by and large, clearly identified as such in advertising and point of display materials. The main issue is not if labeling is occurring but whether consumers can determine for themselves under what circumstances they will need a tuner for digital OTA signals."</p>

<p>"CEA will continue to work closely with the FCC as further actions are taken to help complete the successful transition to DTV," concluded Shapiro.  </p>
