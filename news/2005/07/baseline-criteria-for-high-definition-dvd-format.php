				<p><strong>Baseline Criteria for High Definition DVD Format</strong></p>

<p>(From the Retail Perspective)</p>

<p><strong><u>Presented by the Video Software Dealers Association, July 20, 2005 </u></strong></p>

<p>As consumer electronic manufacturers, duplicators, and motion picture studios prepare for the launch of a DVD format capable of storing high definition video, retailers are carefully evaluating their merchandising alternatives.</p>

<p>As of this writing, two formats, each capable of storing high definition movies on DVD, are planned for release into the market.  Retailers uniformly agree that the concurrent distribution of more than one format is likely unsustainable, and that the launch of a single format is preferable to a format war which could confuse the public and lead to reluctance to embrace either format. </p>

<p>The Video Software Dealers Association (VSDA) believes that consumers, retailers, consumer electronic developers, and content providers would benefit from clarification of the baseline criteria needed for a high definition DVD format to gain acceptance and widespread support among the broadest spectrum of market participants, especially consumers.  </p>

<p>For these reasons, VSDA presents the following list of criteria, with the expectation that it will facilitate discussion and fulfillment of these requirements and therefore assist retailer and consumer acceptance of the next generation of DVD. </p>

<p><strong>Full Disclosure of Features and Specifications </strong></p>

<p> It is in the best interests of consumers and retailers to be as well informed as possible with respect to the relative benefits of any new formats. To that end, every feature, specification and capability of a new format that distinguishes it from the existing DVD format and from any competing new format should be fully disclosed. Such disclosures should include not only the feature sets active at launch, but also any latent features capable of being implemented in the future, and any features that are available at the option of the publisher, including those on a title-by-title or copy-by-copy basis.  They should be presented in a manner that facilitates format comparison and detailed evaluation of each value proposition. </p>

<p><strong>Robust Copy Protection</strong></p>

<p>Piracy is of paramount concern to the retail home video industry.  The most advanced copy protection available should be employed on high definition DVDs, while respecting the rights afforded consumers and retailers to sell, trade, gift, rent and loan these products.  </p>

<p>Copy protection needs to be robust and dynamic, and needs to impede both digital and analog copying.[1]  Watermarks which withstand digital-analog conversion must be incorporated, but must not violate the privacy of consumers.  Renewable security should be employed in a framework that does not require disclosure of the identity of retailers' customers nor require consumer activation for unlimited playback by the person in lawful possession. </p>

<p><strong>Consumer Value</strong></p>

<p>The consumer value of DVD purchasing and renting has encouraged rapid industry growth and has helped to dampen consumer interest in motion picture piracy, online and through other means.  Consumer value will continue to be critical to the acceptance of a new format such as high definition DVD.  </p>

<p>The perception of value is a result of several factors, including product quality, functionality and price.  While retailers make no recommendations regarding pricing, it is crucial that the right of retailers to develop creative business models and competitive retail-level pricing beyond the control of the copyright holder be maintained.</p>

<p>The video and audio quality of high definition DVD must offer a bottom-line experience to the consumer which is no less than that available today (and projected to be available in the near future) via high definition satellite and cable offerings.  </p>

<p>However a single disc must contain sufficient viewing time, with quality as defined below, for a feature length motion picture and bonus material.</p>

<p><strong>Product Quality</strong><br />
 <br />
Motion pictures encoded onto high definition DVDs must be capable of offering the consumer with appropriate equipment the best quality viewing experience, with a maximum resolution of no less than 1920x1080.  Any compression techniques should be employed without creating noticeable pixilation or artifacting during high action sequences on even the largest high definition television screens currently in production.  </p>

<p><strong>Product Dimensions</strong><br />
 <br />
Due recognition should be given to retailers' concerns for product dimensions.  The diameter of a single high definition DVD ought to be 120mm, exactly the same as standard DVDs and CDs.  Thickness, including any protective layer, meeting the existing DVD standard of 1.2mm +.03/-.006, should ensure compatibility with legacy playback and automated vending equipment.  Weight ought not to exceed .6 ounces (or the maximum weight capable of enjoying the lowest tier of first class postage in effect at launch date) to contain supply chain costs, including those of internet-based distribution.</p>

<p><strong>Durability</strong><br />
 <br />
Consumer satisfaction increases with the durability of a product.  The more damage-resistant high definition DVDs are, the more consumers will accept the format, and the more widely available they will become in aftermarkets accessible to persons unwilling or unable to purchase new copies.  Also, in light of the triennial rulemaking to consider exceptions to the prohibition against circumvention of access controls, increased durability will undermine efforts to excuse or gain legal authorization for the circumvention of copy protection measures for the purpose of making so-called "back-up" copies to guard against degradation or damage.  In addition, durability is critical to the rental model where consumers often do not use the same care in handling product as with owned product.  However, disc cartridges or caddies are not recommended, considering consumer experience with current optical disc products.</p>

<p>A protective coating should be applied to each disc to protect against abrasions resulting from ordinary use and stains/oils/ink without increasing rigidity that might make the disc more susceptible to cracking than standard DVDs.</p>

<p><strong>Differentiated Packaging & Labeling</strong><br />
 <br />
Retailers' racks have been constructed to accommodate the width of standard DVDs and, in many cases, their height.  Distribution systems have been developed around case and pallet packs based on standard DVD dimensions.  Packaged dimensions of high definition DVD product must accommodate the merchandising and distribution vehicles in use for standard DVDs.  Thickness of the package should be no greater than that of a standard DVD package and no less than the thickness of a CD jewel case.</p>

<p>However, to avoid consumer confusion, high definition DVD packaging must be easily distinguished from standard DVD packaging via a standard color scheme, labeling scheme, or other easily recognized unique feature(s), and the discs themselves should also be easily distinguishable.</p>

<p>Additionally, packaging should include uniformly represented and placed descriptors of all unique product features (including ratings), and uniform UPC placement and size.</p>

<p><strong>Ability to Meet Consumer Demand</strong><br />
 <br />
While initial demand for high definition DVD players and software may be limited to early adopters, it is essential that sufficient replication capacity be in place at or near launch to satisfy demand as it grows, and to ensure that supply doesn't fall short causing the rationing of product.</p>

<p>Verification tools appropriate for a broad range of (or all readily available) DVD players should be developed and employed, prior to shipment, to ensure that high definition DVDs will have an insignificant failure rate due to defectives or player incompatibility.</p>

<p><strong>Marketing Support</strong><br />
 <br />
The launch of a new optical video disc format will require substantial, comprehensive, and multi-faceted consumer marketing support.  Hardware manufacturers and content providers are anticipated to fund such an effort.  Consumers need information and education to assist them in clearly understanding the benefits of such a new format and the value proposition.</p>

<p>As well as mass media promotional support, in-store marketing and consumer-educational material will also help stimulate acceptance and growth.</p>

<p><strong>Freedom to Develop New Business Models </strong><br />
 <br />
To ensure the widest possible dissemination of motion pictures and other entertainment products and the most compelling consumer propositions, in every case superior to those offered by unlawful and infringing enterprises as well as casual non-commercial infringement, retailers must retain unrestricted freedom to develop and maintain their own customer relationships, create their own business models, and adapt to new challenges and opportunities presented through technological evolution.  </p>

<p>To that end, the new format should enable copyright owners to fully protect and exploit any and all of the six exclusive rights granted to them in the Copyright Act while preserving the freedom of retailers to continue to engage in unrestrained non-infringing activities to the fullest extent of the law, and to develop and exploit lawful business opportunities to the limits of technology and the exercise of their entrepreneurial skill. </p>

