				<p>The July issue of Projection Monthly is now in the hands of our readers, and like the June issue, our normal projection component and large-area display coverage is augmented with extensive industry show coverage.  This month we include the events of the two-day Projection Summit produced by Insight Media and McLaughlin Consulting Group and the Infocomm conference and exhibition that ran from June 4-10.  That, together with some late SID reports added almost fifty pages to the July issue.  </p>

<p> This year promised to be a good summit and the presenters really delivered.  As a co-producer of the Projection Summit, Insight Media gained a unique outlook on the two-day event and we cover the highlights of all seven sessions with plenty of back-up material and screen shots from the presentations.  By the way, the full proceedings are now available on CD for $495 at: <a href="https://special.mags.net/mdreport-ssl/cart/carthtml/56.html">https://special.mags.net/mdreport-ssl/cart/carthtml/56.html</a><br />
  </p>

<p><strong>The Projection Summit </strong>was kicked-off with the popular electronics review session.  This began with a comprehensive talk by Pete Putman that set the tone for the rest of the presenters.  Putman took a cold, hard, look at the image quality trade-offs in moving from CRT technology to brighter, larger and higher resolution displays, starting with decoding and deinterlacing SD and HD video images.  Image scaling vs. native pixel resolution, bandwidth and imaging detail plus accurate grayscales and color shading issues round out the "big four" display image trade-offs identified by Putman.  </p>

<p>He showed that converting SD video can require no less than seven separate processes including decoding composite to component, converting interlaced to progressive, correcting for inter-frame motion artifacts &etc.  Examples of test patterns of good and poor decoding were shown.  Unfortunately, Putman sees an industry trend where analog video quality is becoming an afterthought in many new products. </p>

<p>On the deinterlacing side, as digital resolutions grow in density from 480p to 720p (768p) to 1080p the problem of displaying a standard 480i source can bring unacceptable results.  Putman said most 1080i processors do not convert both interlaced fields, only one.  The result, a 540p processed signal is scaled up to display on a 720p native set with a bit of "fudging".  However, this trick doesn't work when scaling to a native 1080p display.  Even the untrained eye will spot problems with the image - with results that hit everyone's bottom line.  </p>

<p>Putman reminded the group that the number one cause of consumer returns on 720p HD RPTVs is poor SD video performance.  To put it simply, the customer said their old CRT image looked better than the new HD set when watching "regular TV".  To bolster his point, Ron Csermak from Silicon Optix said in a later presentation, that 85% of the content is not the native resolution of the display and they have found that customers want a better-all-around viewing experience, not just HD.  </p>

<p>In his presentation, Csermak agreed with Putman's assessment that scaling and video processing are key elements to good image processing and went on to say lack of processing resources was the primary cause of image artifacts.  For example, in the Silicon Optics pixel-by-pixel processing solution, up to 100 input pixels are needed to produce 1 output pixel.   In geometric pixel-by-pixel image mapping the input pixels increase by an order of magnitude -  1000+ input pixels are used to produce 1 output pixel.  </p>

<p>Looking at the problem another way, Pixelworks Mike Fullman showed how original MPEG-2 source content is encoded at 4Mbps, decoded at 165 Mbps, and scaled to 1080p for display at 2900 Mbps -- generating what he called 94% filler from the original source.  To get this right according to Fullman, you need to own the pipeline: signal processing, front-end processing, image processing and post processing.  </p>

<p>Dan Turow of Gennum Corp also referenced the Putman talk regarding HD deinterlacing and the traditional short-cut method (what Putman called "fudging") to get to 720p/60 via 540 interlaced images scaled up.  Gennum's approach to reach 720 progressive lines is to move 540 lines through an adaptive 1080i to 1080p process, creating a 1080p/60 image, and from there, scale down to 720p.  Gennum offered a host of solutions to display artifacts based on 10 bit data path processing and asserted that 1080p is required to take full advantage of 720p display technologies.  </p>

<p>The illumination session consisted of a look at traditional lighting approaches with offerings of incremental improvements in NSH (Ushio), UHP and new low cost approaches like VIDI technology (Philips) in development.  The new kids on the block to projection illumination included LED (Osram) and Laser projection technology (Novalux).  Wolfgang Schnabel's LED talk included an illustrated review of the process Osram went through to achieve light output breakthroughs increasing the efficiency for InGaAIP thin-film LEDs up to 75%.</p>

<p>For the thin-film technology, OSRAM builds LED chips similar to conventional AlInGaP and InGaN wafers, except they add an artificial layer under the epi layer.  The wafer is then inverted and bonded to a germanium carrier with a highly reflective metal mirror surface.  Next, the original substrate is removed by lift-off.  The compound wafer is finished using conventional metallization processes, and then sliced into LED chips and packaged.  The resulting die has an emission layer less than 10 microns thick with no side emissions, and is thus highly efficient.</p>

<p>Greg Niven of Novalux perhaps portended the competitive phase the illumination side of the industry is about to enter with some pretty caustic statements about the competition.  In one fell swoop he rendered UHP lamps void of any (major) improvements going forward, and dismissed LED technology as too little, too late in adequately addressing the needs of projection.  The laser advantages in projection were rattled off in a litany of slides with the most impressive being an etendue chart.  Here, laser illumination showed a flat line for coupled energy efficiency at 95% for any MD size, against the traditional UHP lamp curve topping out at 60% on large etendue systems.  </p>

<p>It was the cost savings review that really captured the interest of the audience beginning with the promise that the lasers themselves will be cheaper than a traditional UHP lamp.  But that's just the beginning according to Novalux.  Lasers will enable completely new light engine designs eliminating major components in a traditional DLP system.  </p>

<p>According to Niven, a laser illumination system in quantities of 1M/year will be < $75.  Designers can use a single or separate RGB lasers depending on 1 or 3 panel systems and the lower etendue allows for cheaper projection optics.  An RGB module for a 3 panel system eliminates the color wheel and cooling fan, is more efficient than a lamp, and since each color is "on" only 33% of the time, they yield longer life than traditional lamps.  That's compelling technology, not going unnoticed by the industry. </p>

<p>The Microdisplay Engine Review at the Projection Summit focused on the issue of projection products finding ways to cope with 15 to 20% annual price reductions over the next few years to keep competitive with flat screen offerings.  </p>

<p>While MD's of all stripes were represented in this session with presentations from Epson (HTPS LCD), Sony (SXRD-LCOS), TI (DLP) and engine maker Zeiss, it was the TI presentation by Peter van Kessel that focused on combating the PDP nemesis in the large display space.  van Kessel reported on plasma price reductions putting pressure on the whole industry by compressing margins but noted that even with all the price reductions, PDPs have gained little market share in the US.  </p>

<p>Microdisplays offer a cost advantage in the +40-inch segment over PDP displays, particularly as display size grows.  As PDPs get larger they take a cost per inch hit.  To illustrate this, van Kessel put up a revealing Microdisplay vs. Plasma cost per inch chart.  The data from TSR, showed 42- and 50-inch plasma sets at $70 and $90/inch in 2005 while the MD based RPTVs came in substantially lower hovering in the sub-$50/inch range.  2006 and -07 numbers for MD's were $40 and $30/inch respectively while PDPs were at $60 and $55/inch for the 42-inch size and $70 and $65/inch for the 50-inch plasmas in that same time frame.  The over 60-inch PDP models slated for 2006 were off the chart - well above the $150/inch price range at introduction with expected pricing at $120/inch by 2007--three times costlier than the +60-inch MD-RPTVs forecasted.  </p>

<p>TI then reported on some focus group studies that went beyond the HD flat screen mantra. Their findings included clear segmentation in the large screen market with screen diagonal, image quality and styling all factoring in to the mix along with thin displays.  TI drove the point home with a US Market Share Gains chart based on data from NPD Techworld. It showed that MD-TV market share continues to outstrip PDP by >2:1.  </p>

<p>But to continue the microdisplay advantage, developers need to keep pace with the rapid price declines of PDP and LCD-TVs.  To this point, van Kessel unveiled details of its new Fast Track Pixel architecture.  This is a essentially a simplified MEMS structure for the mirrors that eliminates some layers to reduce cost.</p>

<p>There's more coverage on the other four sessions of this year's Projection Summit including our Screen review session, LED/Laser based projection session, a new session on the Investment community's take on the projection industry, and the popular Analysts debate bringing together the major projection analysts to explain/defend their forecasts going out to 2009.  </p>

<p>And, there's our usual coverage with 140+ timely stories, all organized into over 30 sub-sections for easy review and reference.  We've even added some new categories like MD-TV, Plasma and LCD Watch sections and this month includes a special China Retail Pricing report.  If you are a subscriber, you can build a library of past issues that is key word searchable -- a very valuable business intelligence reference tool.</p>

