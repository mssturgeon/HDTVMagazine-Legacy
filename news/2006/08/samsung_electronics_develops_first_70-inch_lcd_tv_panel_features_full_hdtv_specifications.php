<p><img src="/images/bulletins/samsung-70-lcd.jpg" alt="Samsung 70&quot; LCD" align="left"><b>Seoul, Korea - August 21, 2006</b>: Samsung Electronics Co., Ltd., the world's largest provider of thin-film transistor, liquid crystal display (TFT-LCD) panels, has developed the first 70-inch LCD panel for use in the consumer TV market. Currently, the largest LCD TV screen size is 65 inches. The company will unveil its 70-inch LCD HDTV at the International Meeting on Information Displays (IMID) 2006, which will open in Daegu, Korea on August 23.</p>

<p>Executive Vice President Kim Sang-Soo of Samsung Electronics said, "Our new 70-inch LCD is not only significantly larger, but also sets a new benchmark of excellence in terms of video image reproduction, viewing angle and image quality. We've designed it to dramatically enhance the large screen LCD TV user's viewing experience. "</p>

<p>Samsung's latest LCD panel boasts full high-definition resolution (1080p) and a conical viewing angle of 180 degrees for multi-viewing audiences. In addition, its video signal is reproduced at 120Hz, compared to a video signal of 60 Hz for a conventional Full HD LCD panel, enabling rapidly moving video images to be reproduced with crystal clarity.</p>

<p>Samsung will begin producing the new 70-inch LCD during the first half of 2007, bolstering its position in the ultra-large-screen TV segment. With the introduction of the 70" LCD TV, the company will be in a position to compete head-to-head with PDP (plasma display panel) and projection TV makers.</p>

