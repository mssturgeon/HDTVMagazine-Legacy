<b>Terminology</b></p>

<p><b>Full High Definition (FHD)</b>: The FHD requirement for a wide screen (aspect ratio of 16:9) is 1,920 pixels across by 1,080 rows high (the highest resolution available).</p>

<p><b>Polarizer</b>: A multi-layered optical film is placed at the front and back of the LCD panel as a filter that only allows light waves of a certain rotation to pass through.</p>

<p><b>Nit</b>: An abbreviation for the measure of brightness properly called candela per meter square (cd/m2).</p>
