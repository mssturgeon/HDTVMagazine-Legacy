				<p>HD World Conference & Exposition Announces Broadcast Veterans Dan Rather and David Hill as Keynote Speakers for 2006 Event; Premiere Event Filled with Influential Speakers, Timely Sessions and Extensive Networking Opportunities</p>

<p><strong>HD World Conference & Exposition 2006</strong><br />
TRUMBULL, Conn.--Aug. 23, 2006--Dan Rather, Global Correspondent for HDNet, and David Hill, Chairman and CEO for Fox Sports Television Group and President of Entertainment for DirecTV Inc., will be the featured speakers at the inaugural HD World Conference & Exposition (www.hdworldshow.com), November 29-30, 2006 at Jacob K. Javits Convention Center in New York. Held in conjunction with the SATCON event (www.satconexpo.com), HD World is recognized as the premier event of its kind for industry professionals to gain insight into the field of high definition television, video, audio and broadcast applications.</p>

<p>"We are pleased to have Dan Rather and David Hill as keynote speakers at our HD World conference," said Michael Driscoll, event director for HD World. "Attendees will have the opportunity to listen to two influential industry leaders and gain insight into where an already popular form of broadcast technology will be headed in the future. HD World is definitely the place to be to hear from these dynamic media leaders who will continue to impact the field of broadcast as we know it."</p>

<p>Both industry mavens will address an audience of executives from some of the most technologically advanced industries gathered to educate themselves on practical applications and solutions for professionals interested in high definition technology. Hill will speak on November 29 during the opening-day address with a speech titled "Why HD is the Road to Financial Nirvana." Rather will address HD World attendees on November 30.</p>

<p>Content for the conference was developed by the HD World Council, and stems from real-world challenges and case studies involving the adoption of high definition technology. This esteemed group of senior management represents major broadcast and cable networks and solution providers, including ABC, CBS, Discovery, ESPN, Fox, Grass Valley, Harris, HBO, HDNet, NBC, Panasonic, PBS, TBS and Warner Brothers.</p>

<p>HD World's topics and sessions are designed to explore the challenges of integrating HD production, acquisition, origination and distribution systems for media companies, as well as managing the transition of the television process from SDTV to HDTV, and improving the consumer experience as the end result.</p>

<p>Several topics will be addressed at the 2006 HD World conference, including:</p>

<p>-- Newsgathering -- The Cost Complexity Multiplier</p>

<p>-- HD Sports from the Field -- Origination, Production, Editing, Broadcast Center Studio Integration and Transmission</p>

<p>-- Real World Challenges of Delivering Surround Sound for Digital Television Technical Challenges in HD Content Production and Distribution</p>

<p>-- Advertising and HD -- the Advertisers' Responsibility. Where are all the HD Ads?</p>

<p>-- HDTV -- Creating Efficient and Affordable Models for Single Distribution</p>

<p>-- Technical Challenges in HD Content Production and Distribution</p>

<p>Speakers currently confirmed for HD World come from a variety of media companies such as ABC, Ad Age, CBS, DG FastChannel, Dolby, ESPN, Fox, Gannett, Grass Valley, Harris/Leitch, HBO, HDNet, JWT, Linear Acoustic, NBC, PBS, Saatchi & Saatchi, Sony, TBS, Turner Sports, Warner Brothers, Vyvx, WRAL and YES - Yankee Entertainment Sports, among others.</p>

<p>"High definition has already become very popular among entertainment-savvy consumers, but the challenges media companies are facing as they migrate to all HD in the next few years are substantial," said Driscoll. "HD World explores those issues and offers solutions, both from innovative broadcasters who are paving the way, as well as solutions providers who are showing new technologies and services that were not around even six months ago."</p>

<p>A complete speaker roster, session details and event/registration information can be found at http://www.hdworldshow.com/.</p>

<p>About Dan Rather</p>

<p>Dan Rather has covered virtually every major event in the world in the past 50 years. His resume reads like a history book, from his early local reporting in Texas on Hurricane Carla to his unparalleled work covering the assassination of President John F. Kennedy; the civil rights movement; the White House and national politics; wars in Vietnam, Afghanistan, the Persian Gulf, Yugoslavia and Iraq. From his first days as the Associated Press reporter in Huntsville, Texas, in 1950, Rather has more than earned his reputation as the "hardest working man in broadcast journalism." Now the anchor and managing editor of DAN RATHER REPORTS, which starts broadcasting on HDNet in October 2006, Rather has regularly landed the biggest interviews with the world's most important and compelling figures, from the famous to the infamous. He has dedicated himself to delivering to the American public coverage that is fair and accurate, no matter the size and scope of the story. </p>
