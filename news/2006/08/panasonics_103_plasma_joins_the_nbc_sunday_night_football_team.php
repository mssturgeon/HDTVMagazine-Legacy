<p>The 103" plasma displays will be located on each side of the on-air talent desk on the newly-constructed set at 30 Rockefeller Plaza in New York and will be an integral part of NBC's "Football Night in America" studio. In addition, four Panasonic 50" TH-50PH9UK high definition plasma displays will team with the 103" plasma in the studio to offer pristine, stunning visuals of the season's game action.</p>

<p>"We're very excited to join forces with NBC Universal as the nation's weekly marquee football game shifts to Sunday night. These super-size high definition displays will allow NBC to present viewers with an even more in-depth understanding of the sport's fast-paced action," said John Baisley, President of Panasonic Broadcast & Television Systems Company. "'Football Night in America' provides a terrific showcase for our 103" plasma. We have received tremendous interest from organizations nationwide who would like to make this stunning display the ultimate centerpiece of their facility."</p>

<p>"'Football Night in America' will be the essential destination show for NFL fans, providing the first complete look at all of the NFL highlights and stories of the day. These amazing 103" hi-def screens will add a fabulous visual element to the game action and storyline breakdowns that we'll be bringing to our viewers each week," said David Neal, Executive Producer, NBC Sports and Executive Producer, "Football Night in America."</p>

<p>"NBC Sunday Night Football," the premier primetime game of the week, will be preceded by the "Football Night in America" studio show, which kicks off NBC's regular season coverage each Sunday at 7 p.m. NBC's unprecedented six-year NFL deal includes innovative flexible scheduling, and continues through the 2011 season with Super Bowls in 2009 and 2012. Following the completion of the deal, NBC assembled the most honored broadcast team ever. Joining Al Michaels, the commentator called "TV's best play-by-play announcer" by the Associated Press, and John Madden, the most honored NFL broadcaster of all time with 15 Emmy Awards, are: Bob Costas, the most honored studio host of all time with 19 Emmy Awards, who will host NBC's "Football Night in America" studio show alongside co-host Cris Collinsworth, the most honored studio analyst in history with six Emmy Awards; and analysts Sterling Sharpe, a five-time Pro Bowler and Jerome Bettis, one of the most popular players in recent NFL history. "NBC Sunday Night Football" coverage also includes sideline and feature reporter Andrea Kremer, whom the Los Angeles Times has called "the best TV interviewer in the business of covering the NFL." Peter King, who covers the NFL for Sports Illustrated and is considered one of the country's foremost NFL reporters, will serve as a reporter for the "Football Night in America" studio show. Both "Football Night in America" and "NBC Sunday Night Football" will be broadcast in high definition.</p>

<p>The TH-103PF9UK is designed to produce breathtaking-quality images and features a Super Cinema Mode and new image-enhancing technologies to reproduce crisp, film-like motion images in native 1920 x 1080 progressive resolution. Its new Real Black Creation color-enhancing feature produces high-contrast and rich, deep blacks resulting in an impressively high contrast level (5000:1). Included in its outstanding features are a Contrast Management system that optimizes the contrast for each individual portion of the image displayed and a high-precision Motion Pattern Noise Reduction circuit that adjusts the image to optimize picture quality by detecting motion patterns that generate noise.</p>

<p>The TH-103PF9UK can display 1080/60p/50p, 1080/60i/50i/24p/24sF/25p/30p, 1080/50i, 720/60p/50p 480/60i/p, and 575/50i/p video signals. As the largest member of Panasonic's high-performing professional plasma display family, the TH-103PF9UK features three interchangeable, multi-function slots (in the back panel) which allow users to add and update their panel with different combinations of optional terminal boards for a variety of applications. The 103" plasma display comes standard with the TY-FB9DD DVI board (compatible with UXGA input), TY-42TM6A analog component board, an integrated D-sub15 PC input, and an integrated D-sub9 RS232C interface. Optional plug-in boards assure expanded connectivity, including HD-SDI and DVI, as well as a variety of advanced functionality including monitor control, networking, running of internal applications and data storage, and remote signal playback.</p>

<p>The 103" plasma display will be available in November 2006 at a suggested list price of $69,999.95. Panasonic Broadcast is accepting orders for the TH-103PF9UK and users can call 1-800-528-8601 to receive additional information.</p>

