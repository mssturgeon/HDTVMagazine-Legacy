<p><br />
SECAUCUS, NJ (August 31, 2006) - Panasonic, the market and technology leader in Plasma displays, today announced that it is supplying NBC Universal with two 103" full high definition professional plasma displays (TH-103PF9UK) to be integrated into the set of NBC's "Football Night in America" studio show, premiering Sunday, September 10 at 7 p.m. ET. The Panasonic TH-103PF9UK, which recently made its worldwide debut, is the world's largest plasma television available. NBC Universal is the first commercial customer to purchase the 103" plasma display.</p>

<p>With industry leading 16-bit color reproduction, the super-size TH-103PF9UK provides stunning widescreen progressive display featuring full HD pixel resolution of 1,920 horizontal x 1,080 vertical, a contrast ratio of 5,000:1, and 4,096 equivalent steps of color gradation, delivering clear, crisp and impactful fast action video images. This 1080p display's screen resolution, which amounts to about 2 million pixels, equals twice the resolution of high-definition televisions that are commonly available today and boasts an effective display area of approximately 89" wide by 50" high, which is equivalent in size to four 50" Panasonic plasma displays.</p>

