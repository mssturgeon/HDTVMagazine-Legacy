<p>"As a maker of both plasma and LCD flat panels, we know that many consumers are confused and often bombarded with information on the pluses and minuses of each product offering, some of which may be outdated or inaccurate," said Mr. Nelkin.  "By opening access to our Plasma Concierge Service, our goal is to empower and inform consumers.  Whether from home, work or a retail store, consumers can contact our experts to ask questions and gather facts, to ultimately select the HDTV that best suits their needs."</p>

