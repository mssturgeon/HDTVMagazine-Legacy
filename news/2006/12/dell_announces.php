				<p class="prtitle">Dell Moves beyond High Definition with Blu-ray Enabled Multimedia Notebook</p>

<p><img src="/images/bulletins/Dell-XPSM1710.jpg" lt="Dell XPSM1710" align="left" /><b>ROUND ROCK, Texas--(BUSINESS WIRE)</b> -- Dell (NASDAQ:DELL) today introduced Blu-ray Disc technology into its product line, offering the next-generation optical disc format as an option on the extreme-performance XPSTM M1710 consumer notebook computer.</p>

<p>This enhancement furthers Dell's strategy to offer customers PCs that can function as a single platform for a compelling digital entertainment throughout the home.</p>

<p>Blu-ray Disc technology offers significant advancements for customers requiring high-definition content and storage for archiving large amounts of data and digital content. For instance, a Blu-ray Disc supports playback of high-definition feature-length films and offers the highest optical disc capacity - up to 50GB, - or more than five times the capacity of a dual-layer DVD.</p>

<p>Configured with Blu-ray technology, the XPS M1710 supports read/write capabilities across CD, DVD and Blu-ray Disc media. Using Blu-ray Disc technology, M1710 users can burn up to 50GB of data or author up to 50GB of theater-quality video on a single piece of media.</p>

<p>"Blu-ray optical drive technology has gained broad industry support and we believe it will become the optical drive standard of the future," said Alex Gruzen, senior vice president, Dell Product Group. "We continue to see PCs - both desktops and notebooks - functioning as the entertainment and productivity hub in the home and on the road with their versatility, power, connectivity, and vibrant high-definition displays. We believe high-definition video powered by Blu-ray Disc technology will be a significant part of that entertainment experience," he added.</p>

<p>As a founding member of the Blu-ray Disc Association, Dell is actively involved in developing and advancing Blu-ray Disc technology. To date, the Blu-ray Disc format has generated wide support - more than 170 major companies - from a variety of industries including consumer electronics, computers video games, recording media, music and movies. Seven of eight major Hollywood studios support the format with over 100 feature titles announced as of the dates of this release.</p>

<p><br />
<b>Key Benefits of the Dell XPS M1710 Blu-ray-enabled Notebook</b><br />
<ul><li>High picture quality at 48 Mbps and up to 1,080p high-definition resolution</li><li>Offers up to 7.1 channels of uncompressed surround sound and options for up to 32 audio streams for cinematic sound</li><li>Backwards compatibility with CD and DVD, which enables DVD and CD movie playback, DVD and Blu-ray Disc (BD) authoring and CD, DVD and BD data burning</li><li>First Blu-ray Disc system to meet logo requirements for NVIDIA® PureVideoTM technology which delivers the ultimate HD experience on a PC</li><li>Intel Core 2 Duo T7600 and Intel Core 2 Duo T7600G (2.33GHz, 4MB L2 Cache, 667 MHz FSB) processors</li><li>Superior NVIDIA GeForce Go 7950 GTX graphics processing unit with 512MB delivers vivid realism in the latest games at extreme HD</li><li>Up to 4 GB1 667 MHz DDR2 memory</li><li>Serial ATA hard drive up to 160 GB2</li><li>Personalized XPS service with dedicated sales, specially trained technicians and designated phone queue</li></ul></p>

<p><br />
<b>Pricing and Availability</b><br />
This holiday season, customers worldwide can purchase Dell XPS M1710 notebooks configured with Blu-ray technology. Pricing starts at approximately US$3,699.</p>

