<p>"Just over a year ago, Sling Media delivered to consumers a ground breaking product that has now been incorporated into their daily lives," said Blake Krikorian, co-founder and CEO of Sling Media. "With our new products, we are setting an even higher standard by incorporating industry-leading video quality and streamlined setup all at price points we feel will make the Slingbox an ideal holiday gift. Our mission has and will remain the same - to create the best possible consumer experience with innovative products that our customers simply love."</p>

<p><b>Which Slingbox is Right for Me?</b></p>

<p>With the three new Slingbox models, Sling Media has created a product that fits the needs of every consumer, no matter how basic or sophisticated their home TV setup. </p>

<p><b>Slingbox PRO</b><br />
The Slingbox PRO is designed for the consumer who has multiple A/V devices or has made an investment in high definition TV. The Slingbox PRO features four sets of audio-video inputs and outputs including the optional HD component connection for HD set-top box customers making for seamless integration into current A/V systems. Other new features include widescreen (16:9) support, high quality programmable video compression, easy connection to set-top boxes (e.g. digital cable, satellite, DVR) and remote control of A/V devices.</p>

<p>The optional cable for HD component set-top boxes is called the Slingbox HD Connect and it includes all the necessary cables to connect HD component video and audio to the Slingbox PRO. This accessory will be available later this fall. Customers who wish to seamlessly connect their HD receiver to the Slingbox PRO using the component connection will need to purchase this accessory.  </p>

<p><b>Slingbox AV</b><br />
The Slingbox AV gives consumers who watch TV using a standard definition cable set-top box, satellite receiver or DVR, the ability to connect their Slingbox AV seamlessly to their set-top box. Slingbox AV features the ability to watch and control TV from any Internet connected PC/Mac/laptop or Windows-based mobile device, widescreen (16:9) support and high quality programmable video compression.</p>

<p><b>Slingbox TUNER</b><br />
The Slingbox TUNER is ideal for customers with cable who want to easily view their line-up of television channels and do not require access to a set-top box, satellite receiver, DVR or other AV device. The Slingbox TUNER easily connects adjacent to a cable modem or basic coaxial connection even without a TV present. This allows the Slingbox TUNER customer to view their cable channels without impacting another family member watching TV anywhere else in the home.</p>

<p><b>New Level of Customer Care</b><br />
With this product launch, Sling Media is introducing a new customer support capability aimed at providing first-time customers with easy installation. Technology embedded in Sling Media's setup wizard allows "live" chats between customers and Sling Media technical support representatives when the customer is going through the installation process. In addition to this "live" chat support, a Sling Media technical support representative can remotely control a customer's PC (with the customer's explicit permission) to assist in real time with the installation.  </p>

<p>"Our focus on simple installation - including the ability to have live interaction with a technical support representative or allowing the technical support representative to remotely control a customer's PC to make any necessary adjustments - raises the bar, setting a new standard in the industry that is unmatched today," continued Krikorian. "Sling Media has taken a huge step forward with this product launch demonstrating our commitment to customer support as we continue to make "place-shifting" a household word." </p>

