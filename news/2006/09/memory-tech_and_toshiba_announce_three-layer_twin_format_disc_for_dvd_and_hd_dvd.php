			<p class="prtitle">Memory-Tech and Toshiba Announce Latest Advance in Single-Sided, Three-Layer TWIN Format Disc for DVD and HD DVD; New Disc Supports High Capacities of Both Standard DVD and HD DVD on a Single Disc</p>

<p>TOKYO--(BUSINESS WIRE)--Sept. 11, 2006--Memory-Tech Corporation and Toshiba Corporation today announced the latest advance in DVD disc technology: a jointly developed, single-sided, three-layer ROM disc supporting high capacity storage and playback of both DVD and HD DVD formats.</p>

<p>The newly announced disc is the latest addition to the DVD TWIN format, discs that support both DVD and HD DVD content and that are fully compatible with both formats. The new disc boosts capacity and expands versatility with a three-layer structure offering support for two HD DVD layers and one DVD layer or two DVD layers and one HD DVD layer. Memory-Tech and Toshiba will propose the new disc to the HD DVD Forum, the industry body that defines DVD standards.</p>

<p>In a two-layer HD DVD configuration, the new TWIN disc has a 30GB HD DVD capacity, plus 4.7GB of standard DVD capacity. Configured to maximize standard DVD content, the disc can support 8.5GB on two layers, plus 15GB of HD DVD content on the third layer. DVD content can be played back on a standard DVD player, while HD DVD players can play back both formats.</p>

<p>Memory-Tech and Toshiba together proposed the DVD/HD DVD TWIN to the DVD Forum in 2004, as a transitional format able to support both standard DVD and HD DVD content. The single-sided, dual-layer TWIN disc was adopted as part of the HD DVD specifications, and has found wide application since HD DVD players and PC drives were launched in the Japanese and North American markets in March this year. One advantage is its ability to support both standard definition and high definition versions of a movie, allowing users to play it back now on present DVD players, and to enjoy the high definition version once they upgrade to an HD DVD player.</p>

<p>The only drawback with the first generation TWIN disc was its limited capacity: support for 15GB of HD DVD content and 4.7GB of DVD content. The new 3-layer disc meets demand from movie studios and software companies in North America and Japan for a capacity boost, and offers double the maximum capacity for each format.</p>

<p>The new disc also maintains two defining features of the HD DVD format: a low cost and highly efficient manufacturing process. Memory-Tech has developed a new disc manufacturing procedure that adds an additional process to form the third layer, but does so on the same disc replication machines that can be used for DVD and HD DVD mass production.</p>

<p>Major content companies have welcomed the new format.</p>

<p>"We have been releasing TWIN Format titles since April," said Mr Hideki Oyagi, General Manager, Visual Entertainment Department, PONY CANYON INC. "We are getting very positive feedback from the market, and our TWIN Format titles are selling better than anticipated. The new 3-layer TWIN Format will allow us to develop even more products and I am sure it will accelerate acceptance of the HD DVD format in the market. We welcome the fact that the new format will be accepted as part of HD DVD family format in the near future."</p>

<p>"We offer our congratulations on the announcement of the new 3-layer TWIN Format," said Mr Kazuo Sakai, Program Vice President, Digital Entertainment Partner Program, Microsoft Corporation. "We're hoping the new format finds wide acceptance and supports content development, and promotes consumer adoption of HD DVD."</p>

<p>Memory-Tech and Toshiba will propose the new format to the DVD Forum and develop reliable disc manufacturing process together. Memory-Tech and Toshiba will introduce the new format to content providers and develop new business opportunities together with studio partners.</p>
