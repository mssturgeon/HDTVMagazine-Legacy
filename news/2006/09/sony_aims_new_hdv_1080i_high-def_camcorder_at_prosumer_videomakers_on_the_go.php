			<p class="prtitle">SONY AIMS NEW HDV 1080i HIGH-DEF CAMCORDER AT PROSUMER VIDEOMAKERS ON THE GO</p>
	
<i>New Handycam Camcorder is the World's First 1080i HDV High-Def Camcorder With Three-Chip ClearVID CMOS Sensor Technology</i>

<p><b>SANDIEGO, Sept. 7, 2006</b> - Sony is expanding its high-definition camcorder line with the introduction of the HDR-FX7 1080i HDV camcorder, a model with three-chip ClearVID&trade; CMOS Sensor technology to deliver exceptional high-def video and the utmost in creative control.</p>

<p>For videographers on the move, the new model sports a compact body design, weighing in at about three pounds. It is approximately 40 percent smaller and 25 percent lighter than Sony's first prosumer HDV model.</p>

<p>Like previous HDV models, the HDR-FX7 can record and playback both 1080i HDV and standard definition DV video on standard miniDV tapes. Recorded HDV video can be conveniently edited with a choice of available HDV, non-linear editing software. Its HDMI interface offers simple, one-cord connection to compatible display devices so you can just plug and play into instead of struggling with multiple cables.</p>

<p>"Our ClearVID CMOS sensor is one of the core technologies used to ensure that customers enjoy the full 1080 HD experience," said Linda Vuolo, director of marketing for camcorder products. "Advanced camcorder users will be impressed with the richer, more natural-looking video shot with the HDR-FX7 camcorder, especially when shooting outdoors, improved handheld shooting, and long recording times."</p>

<p><b>The Power of 3ClearVID CMOSSensor Technology</b></p>

<p>The primary benefits of Sony's ClearVID CMOS sensor are high-speed data transfer rates and lower power consumption, which is a real boon when handling data-rich, high-def video.</p>

<p>The new camcorder's three-chip configuration combined with Sony's originally-developed Enhanced Imaging Processor results in higher video resolution, greater light sensitivity with minimal picture noise, and more accurate color reproduction than previous Sony models. These combined technologies also bring added functions.</p>

<p>The HDR-FX7 camcorder has a smooth slow record function. With its three sensors, the HDR-FX7 model can capture a six-second burst of video and play it back in 24 seconds as slow motion video. The model's dual record function allows users to capture 1.2-megapixel still images and shoot video simultaneously, with the press of a button.</p>

<p>Fueled by the Sony InfoLithium&reg; L Series battery with STAMINA&reg; technology, the model is highly power-efficient. Users can expect up to eight hours of continuous recording time with the optional largest capacity battery.</p>

<p><b>Get The Shot You Want At Any Angle</b></p>

<p>The HDR-FX7 camcorder sports a high-resolution viewfinder to accurately check composition, focus and image color. It also features a high-resolution, 3.5-inch SwivelScreen&trade; LCD screen with Clear Photo Plus LCD&trade; technology for superb contrast and accurate color reproduction.</p>

<p>Ideal for the mobile videomaker, the LCD can be tilted out and swiveled for comfortable viewing in any shooting position. Both the viewfinder and LCD screen can be turned on independently or simultaneously.</p>

<p><b>Zoom In and Out Like A Pro</b></p>

<p>The HDR-FX7 features a Carl Zeiss&reg; Vario-Sonnar&reg; T* lens with a 20x optical zoom range, equivalent to 37.4 - 748mm (35mm equivalent) in 16:9 widescreen mode. With its new digital extender function, the camcorder can magnify video footage 1.5 times greater, realizing a 30x optical zoom without significant degradation of picture quality.</p>

<p>To compensate for the HDR-FX7 model's substantial zoom capability, Sony incorporated an extra-low dispersion lens glass in order to reduce color distortion. Its built-in Super SteadyShot&reg; optical image stabilization helps to reduce shaky footage, even when shooting handheld at high zoom settings.</p>

<p>In addition to its superb high-def picture quality, the HDR-FX7 provides extensive manual controls for zoom, focus, shutter speed, white balance, iris, and gain.</p>

<p>Independent manual zoom and focus rings provide a high degree of manual control. Conveniently positioned directly behind the zoom ring, the model's selectable exposure dial now adds iris, along with exposure and auto-exposure shift functions, so that users can easily adjust both gain and shutter speeds.</p>

<p>The HDR-FX7 will be available in October for about $3,500. Options will include a full line of accessories, including lights, lenses, microphones, InfoLithium&reg; batteries, chargers and cables.</p>

<p>Both models will be available online at Sonystyle.com, at Sony Style&reg; retail stores (www.sonystyle.com/retail), and at authorized dealers nationwide. Pre-orders will begin on Friday, Sept. 8 at www.sonystyle.com/handycam.</p>
