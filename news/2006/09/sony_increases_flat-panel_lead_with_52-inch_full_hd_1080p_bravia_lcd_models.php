<i><center>Two 720p Models Also Added to Line</i></center>

<p><img src="/images/bulletins/sony-kdl-52xbr3.jpg" alt="Sony KDL-52XBR3" align="left"><b>DENVER (CEDIA Booth #150), Sept. 13, 2006</b> - Continuing to stretch performance and design boundaries, Sony Electronics today announced its largest BRAVIA&trade; flat-panel LCD televisions: the 52-inch KDL-52XBR2 and KDL-52XBR3 models.</p>

<p>Both feature native 1920 x 1080 full high-definition resolution panels, HDMI&trade; inputs with 1080p capability, and Sony's unique floating glass design.</p>

<p>The company also added two new 1366 x 768 resolution models, KDL-40S2400 and KDL-32S2400, to the BRAVIA line.</p>

<p>As for Full HD 1080p models, the BRAVIA family now includes eight of them with screen sizes ranging from 40 to 52 inches. The complete line, including 1080p and 720p models, now features 16 models from 23 to 52 inches.</p>

<p>"Introduced only a year ago, BRAVIA quickly gained critical acclaim and the number one share at nearly 30 percent of the flat-panel LCD market," said Philip Abram, vice president of marketing for Sony's television group in the U.S. "BRAVIA is becoming the new standard for LCD and flat-panel HDTV sets in general."</p>

<p>According to Abram, the new BRAVIA models feature advanced technologies that are exclusive to Sony.</p>

<p>One of the new improvements is Sony's Advanced Contrast Enhancer (ACE). With real-time image processing and optimization of backlight levels, ACE technology builds on the already excellent on-screen contrast ratio of 1300:1 and delivers a dynamic contrast ratio of up to 7,000:1, translating to blacker blacks and better shadow detail.</p>

<p>Like the previously announced BRAVIA XBRs, the new 52-inch models include Sony's BRAVIA Engine Pro&trade; full digital high-definition video processing system. Optimizing the video signal path, the system leverages Sony's Digital Reality Creation Multi Function Version Two Point Five (DRC-MFv2.5) with increased computing capabilities to up-convert not only standard-definition signals to 1080p with detailed image that traditional interpolation video scaling cannot achieve, but also high-definition signals for a consistently crisp, detailed image.</p>

<p>Sony's Live Color Creation technology, featuring Wide Color Gamut Cold Cathode Fluorescent Lamp (WCG-CCFL) backlight system, is also featured in the new 52-inch models. WCG-CCFL's color spectrum coupled with chroma signal processing allow for a wider, more realistic range of colors enhancing the picture.</p>

<p>Rounding out the XBR feature package is a built-in ATSC tuner; three HDMI inputs with 1080p compatibility (two rear, one side), a PC input; two high-definition component, one S-video and three composite inputs.</p>

<p>The KDL-52XBR3 model features a high-gloss piano black bezel finish, while the KDL-52XBR2 features a silver bezel. They both ship in November for about $6,800 and $6,500, respectively.</p>

<p><b>BRAVIA S2400 Series</b></p>

<p>Also new to the BRAVIA line is the 40-inch KDL-40S2400 and 32-inch KDL-32S2400 models. Both feature 1366 x 768 screen resolution and are equipped with ACE technology for optimized dynamic contrast ratio of up to 5,000:1 (the on-screen contrast ratio is 1300:1). Additionally, Sony's BRAVIA Engine&trade;, delivers a clear, sharp picture from any source material.</p>

<p>The models' narrow, picture frame black bezel incorporates invisible bottom speakers with SRS TruSurroundXT&trade; and BBE Digital Enhancement technology. Other features include a built-in ATSC tuner, HDMI and PC inputs, as well as two high-definition component, two S-video and two composite inputs.</p>

<p>The KDL-40S2400 and KDL-32S2400 models will be available next month for about $2,600 and $1,700, respectively.</p>

<p>All of the new BRAVIA televisions are being offered direct at www.sonystyle.com and at Sony Style retail stores nationwide, as well as at authorized dealers around the country.</p>

<p>More information on these models can be found at www.sony.com/CEDIA2006.</p>
