<p>IBC 2006</p>

<p>AMSTERDAM, Netherlands--(BUSINESS WIRE)--Sept. 8, 2006--Blackmagic Design Inc. today announced Intensity, an ultra low cost HDMI capture playback card. For the first time, low cost consumer cameras with HDMI video connections can move beyond the quality limits of HDV compressed video to a new world of uncompressed editing and design. Intensity can be seen on Blackmagic Design's IBC 2006 stand located at #7.526.</p>

<p><img src="/images/bulletins/intensity-card_150.jpg" alt="Intensity HDMI Capture/Playback Card" align="left">Intensity is an incredibly small HDMI capture and playback card that instantly switches between 1080HD, 720HD, NTSC and PAL video standards. Once Intensity is plugged into compatible PCI Express Windows or Mac OS X computers, users get the amazing quality of uncompressed video via HDMI from cameras, decks and set top boxes, enabling them to playback to any HDMI big screen television or video projector for video editing, in SD or HD, and with real time effects.</p>

<p>"For the first time, customers don't need expensive SDI based cameras to access uncompressed quality," said Grant Petty, CEO, Blackmagic Design Inc. "We hope Intensity finally allows videographers on a tight budget to afford full resolution HDTV post production that goes well beyond HDV quality limits."</p>

<p>Using the same Blackmagic Design technology as used in the latest Hollywood feature films, Intensity is designed to allow people with consumer level cameras to benefit from uncompressed video quality, allowing direct-from-CCD recording for the highest uncompressed quality. Users can capture to disk arrays for high speed uncompressed video, or when disk speed and space is tight, choose from a range of professional compressed codecs that go well beyond HDV for quality.</p>

<p><img src="/images/bulletins/intensity_300.jpg" alt="Intensity HDMI Hookup" align="right">Customers recording to HDV tape also benefit from HDMI uncompressed capture and editing. Once the HDV footage is recorded uncompressed via HDMI, and graphics and effects are placed, the edited video will retail full HD resolution and color depth. This high quality editing can be viewed in real time via the Intensity HDMI video output on large screen televisions or video projectors. Because Intensity's media files are fully compatible with Blackmagic Design's DeckLink and Multibridge capture cards, users can even play-out to broadcast take decks by moving content to a DeckLink or Multibridge based system.</p>

<p>Intensity is fully compatible with Adobe Premiere Pro(R), Apple Final Cut Pro(TM), Adobe After Effects(TM), Adobe Photoshop(TM) and any DirectShow(TM) or QuickTime(TM) based software application. Intensity works with almost any video software.</p>

<p>When live performance events need to be captured, Intensity features Blackmagic Design's popular On-Air 2.0 software. Two HDMI video cameras can be connected for live mixing, when used with two Intensity boards plugged into the same computer. On-Air 2.0 supports auto-sync of video inputs, so users don't need expensive cameras that feature genlock. On-Air 2.0 features "genlock-less" operation so any camera with HDMI outputs will work as an incredibly low cost solution.</p>

<p>Product Features</p>

<p>-- HDMI in for capture from HDMI video cameras and HDMI HDV decks</p>

<p>-- Uncompressed video capture and playback</p>

<p>-- Edit with Apple Final Cut Pro on Mac OS X or Adobe Premiere Pro on Windows</p>

<p>-- Professional Compression codecs</p>

<p>-- True 64 bit 1 lane PCIe support</p>

<p>-- Instantly switches between HDTV 1080i/59.94, 1080i/50, 720p/59.94, 720p/60, 720p/50, NTSC and PAL video standards</p>

<p>Availability and Price</p>

<p>Intensity has a recommended retail price of only US$249 and will be available beginning October 15th from all worldwide Blackmagic Design authorized resellers.</p>

