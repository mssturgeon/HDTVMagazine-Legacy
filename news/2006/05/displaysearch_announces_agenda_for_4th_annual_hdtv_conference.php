<p>HD Content Outlook - The View from Movie Studios, Networks and Game Developers This session will address the plans of movie studios, broadcast/cable/satellite networks and game developers to expand their HD offerings. It will examine the outlook for HD content by native format. In addition, it will discuss the impact of alternative HD delivery models and how to maximize HD broadcast quality. <br />
Distributing HD Content - New Models, Markets, Challenges and Opportunities This session will examine the opportunities and challenges associated with distributing HD content via conventional (OTA, cable and satellite) and alternative distribution models such as IPTV, iTunes, DivX, BitTorrent, etc. What advances are coming? How can quality be improved? </p>

<p>Lessons from Retail - View from National, Regional, Online and Warehouse Club Channels Leading retailers from all channels will discuss how they are taking the confusion out of the HDTV shopping experience and why they are well positioned to benefit from the growth in HDTV sales. Other discussion topics include their outlook for 1080p TVs, high definition DVD players and flat panel vs. projection. </p>

<p>Also under discussion are how they position LCDs vs. PDPs and whether they intend to build awareness of the analog cut-off. </p>

<p>Outlook for High Definition DVD Players - What Does the Adoption Curve Look Like? Leading DVD manufacturers will discuss the outlook for the HD-DVD/Blu-ray DVD player market covering products, configurations, price points, shipment targets, penetration and market sizing. </p>

<p>The Digital Home - The Future of Home Networking, Media Centers and the Set Top Box This session will discuss the future of the digital home and home networking. Is home networking a near term reality? Are media center PCs the right solution? What happens to the set top box? Which solutions will allow for remote access? Can this become plug and play? </p>

<p>TV Brand Keynote - TV Market/Technology Outlook Senior executives from the leading TV manufacturers will discuss their HDTV technology, product, sales and marketing strategies. Also under discussion is how they are positioning the different TV technologies and the outlook for 1080p TVs. </p>

<p>Flat Panel TVs - Will They Dominate All Categories? This session will examine whether the future of the TV is flat. Can LCD and PDP TVs dominate all categories? Can they coexist? Is one better than another or does it depend on the application? Where are LCDs and PDPs improving? How much capacity is being added? Where are costs and prices going? </p>

<p>Rear Projection TV Outlook Will the arrival of LED and laser based light sources boost the outlook for MD RPTVs? While lifetimes will increase, how will performance improve and will costs fall? Is it sufficient to offset the flat panel migration to larger sizes? How fast is the 1080p transition happening in MD RPTVs? </p>

<p>Display Electronics - Maximizing Performance While Cutting Costs This session will discuss the evolution of display electronics, likely configurations for mainstream and high-end applications and how display electronics suppliers are improving performance while cutting costs. </p>

<p>Mobile TV - How Prevalent Will It Become? Digital broadcasting will enable mobile TV to become the next wireless "killer app", driving revenues and device sales and ushering in a wide range of products and services. Mobile TV will have at least 3 different transmission standards and a host of delivery systems and devices. The session will address the wireless technology (terrestrial and satellite), carrier strategies, adoption rates and experience of other countries to date.<br />
