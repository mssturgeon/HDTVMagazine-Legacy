<p><B>MINNEAPOLIS--(BUSINESS WIRE)</B>--By year's end, it's estimated more than 52 million households in the US will own a high-definition television1. A recent study by Best Buy found that owning an HDTV (high-definition television) doesn't always mean people are getting an HD experience. In fact, 41%2 of HDTV owners said they understand little to nothing at all about HDTV.</p>

<p>As the leading consumer electronics retailer, Best Buy is committed to helping consumers understand that HDTV is about more than just the television. That's why Best Buy has launched the HD Done Right campaign, which includes education and resources in stores and online, as well as no-cost phone support. This educational campaign will help consumers understand how to get the true HDTV experience they are looking for, and how to properly budget for the right home theater for their needs.</p>

<p>The Best Buy survey found consumer misconceptions regarding HDTV range from not understanding it at all (32%) to moderate understanding (56%), with only 11% of consumers in general and 19% of HDTV owners feeling they have a complete understanding of HDTV. The limited understanding of HD technology has created some confusion for shoppers, who aren't aware of the components and costs involved in creating a full HD experience in their homes. Consumers are typically only budgeting for the HD-ready TV - 52% of consumers plan to spend 75-100% of their budgets on the TV, even though the components needed to experience HD programming can account for as much as 50% of the cost of an HDTV system.</p>

<p>To fully experience high definition technology, which significantly improves the picture and sound quality, Best Buy recommends understanding the four main HDTV components, which include: the HD-ready TV, an HD programming source, surround sound, and proper installation including HD ready cables.</p>

<p>"As more and more people invest in new high-definition televisions and expand their home theaters, Best Buy wants to ensure our customers fully appreciate what's needed to get the most from their purchases," said Mike Vitelli, senior VP & general manager for Home Solutions. "We want to serve as a trusted resource to our customers, by helping them understand the necessary components and how to make the right budgeting decisions so they can have a truly outstanding HD experience in their home."</p>

<p><br />
<B>Best Buy's HD Done Right Survey Findings</B></p>

<p><B> * Continued Confusion On High Definition Technology</B></p>

<p>Almost all consumers (89%) feel they lack complete understanding of HDTV technology-how it works and what it takes to get the full HDTV experience. in fact, four in ten people (39%) don't even identify an HD ready TV as necessary for the experience. Six out of ten people expressed a need for aids like a budgeting tool, definitions for each component and online resources.</p>

<p><B> * Budgeting Confusion Is An Issue for Many</B></p>

<p>Beyond the TV, many consumers don't understand that additional components such as access to HD programming or an HD antenna (44%), HD cables (52%), and an audio system (62%) are necessary to get the most out of the HDTV experience, and are not likely to be budgeting appropriately for these components. More than half (52%) of the survey respondents said they would spend 75-100% of their home theater budget on the TV alone. Best Buy home theater specialists say depending on your specific needs additional HDTV costs can account for as much as 50% of the HDTV system.</p>

<p><B> * Consumers Are Reluctant to Admit Gaps In HDTV Knowledge</B></p>

<p>While 41% of HDTV owners admit to knowing little to nothing at all about HD, they would not want to admit that to friends and family. Half (52%) of HDTV owners say it would be difficult to admit that an HDTV wasn't set up right after they had shown it off to friends.</p>

<p><br />
<B>Best Buy HDTV Educational Offerings: Online, Hotline and In-Store Resources</B></p>

<p>In response to survey findings, Best Buy has created tools to assist consumers through the HD purchasing process, available on AskABlueShirt.com.</p>

<p> * <B>Are you Experiencing HDTV?</B> 5 Questions to Ask leads consumers through a step by step questionnaire to determine whether or not they are currently enjoying the full HD experience in their homes. The questions also help explain the importance and necessity of each step.<br />
 * <B>What is HD Done Right</B> breaks down each of the four components of the HD experience - HD-ready TV, programming source, sound and installation.<br />
 * <B>Planning and Budgeting for HDTV</B> offers a budgeting pie chart that provides a good baseline of advice for consumers who are planning to purchase an HDTV.<br />
 * <B>HDTV Glossary</B> decodes HDTV jargon to help aid in an overall understanding of the technology and benefits of each.</p>

<p>Best Buy is also offering an HD Done Right Hotline. HDTV owners or consumers planning for an HDTV purchase can call (888) BestBuy and ask for "HD Troubleshooting" to speak with a home theater specialist about how to make sure they are getting a full HD experience. In addition, Best Buy home theater specialists are available in more than 800 stores across the country and are equipped to aid consumers through the HDTV budgeting process, or to help HDTV owners who aren't sure if they're getting a full HD experience.</p>

<p>Still available to consumers are Best Buy's Magnolia Home Theater in-store audio rooms to experience the sights and sounds of home theater items before the purchase. Similarly, in-home consultations from Geek Squad Home Theater Specialists are a great way to get a personal, home theater consultant to provide the customized experience depending on a specific need. These home theater installation professionals can provide insight and make suggestions of what might fit each customer's needs and lifestyle. Most consumers make a considerable investment when purchasing a home theater system and Best Buy wants to make sure it is done right.</p>

