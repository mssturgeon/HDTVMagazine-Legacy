<p><B>DENVER--(BUSINESS WIRE)</B>--Sharp introduces the new slim-profile AQUOS&reg; BD player, model BD-HP20U, the company's first offering in the U.S. market and first U.S. product outside of the Sharp LCD suite to carry the AQUOS name. Combining full digital 1080p video output with an AQUOS HDTV Liquid Crystal Television, the BD-HP20U allows consumers to view the latest high-definition films as well as enhanced definition titles in stunning high-definition quality.</p>

<p>"Consumers have become comfortable watching high-definition programming, and now they want to transform their entire home theater experience into high-definition," said Bob Scaglione, senior vice president and group manager, Product and Marketing Group, Sharp Electronics Corporation. "Our new Blu-ray disc player produces a breathtaking and vivid picture with enhanced audio quality that closely mimics a true cinematic experience."</p>

<p>The BD-HP20U player lets consumers realize the powerful next generation of home entertainment enabled by the high-definition Blu-ray format. The user-friendly player features a built-in HDMI&trade; 1.3 digital inputs AV interface that can be connected to an AQUOS LCD HDTV, allowing consumers to watch a Blu-ray disc in complete digital 1080p high-definition with high-quality picture and high fidelity audio.</p>

<p>Reflecting Sharp's strategy of creating great products from great devices, the key components of the AQUOS BD player were all built by Sharp, including the Blu-ray laser, the pick-up beam, and the driver unit.</p>

<p>The BD-HP20U also includes several innovative convenience features. Through the HDMI cable connection, users can experience AQUOS LINK&trade;, which enables integrated and seamless operation between the Blu-ray disc player and AQUOS LCD TV. With the AQUOS LINK feature, HDMI-connected products can be controlled through the AQUOS screen with a single TV remote. The remote also provides simultaneous Power On/Off, which allows the user to power on/off both the Blu-ray disc player and the AQUOS TV together.</p>

<p>The BD-HP20U can output 1920 x 1080 24 fps (frames per second) high-definition video, which is the highest resolution possible via an HDMI connection. In addition to an HDMI output, the player has component video output for those consumers who have an HDTV without HDMI. The unit's Quick Start feature allows the user to begin enjoying gorgeous Blu-ray video with a touch of a button in less than 10 seconds*. Additionally, the player offers multi-channel audio output via HDMI by decoding Dolby&reg; TrueHD. Dolby TrueHD lossless audio technology delivers sound that is identical to the studio master, for a true high-definition experience on next-generation discs. It also decodes Dolby&reg; Digital Plus, providing optimum surround sound to an appropriately equipped receiver. In addition, via HDMI, the player outputs 7.1 Channel digital audio.</p>

<p>The BD-HP20U provides outstanding versatility and is compatible with a wide variety of formats including BD-ROM/RE/R, DVD Video, DVD-RW/R, DVD+RW/R, and Audio CDs. Additionally, the BD-HP20U is compatible with standard DVDs and is capable of upscaling them via HDMI to 1080p, improving the picture performance of an existing DVD library.</p>

<p>The BD-HP20U will be available in a piano black finish with one of the slimmest designs in the industry, making it a perfect match with a high-definition AQUOS HDTV.</p>

