<p>The new HC6000 provides two HDMI connectors allowing for a true digital-to-digital link between the projector and its image sources. The 1000 ANSI lumens projector offers a powered lens shift and powered zoom for easy installation and set-up, making it perfect for installed home theater environments.</p>

<p>Unlike other 1080p projectors, Mitsubishi incorporates the Emmy&reg; award-winning HQV (Hollywood Quality Video) high-performance video processor inside the projector, for a more streamlined form factor.</p>

<p>Reon-VX's HQV processing delivers sharp, detailed HD images by utilizing features such true 1080i-to-1080p HD deinterlacing and a sophisticated multidirectional diagonal filter that helps ensure video that is free from jagged edges. HQV also makes standard definition material approach HD quality by employing advanced scaling, per-pixel detail enhancement and noise reduction technology that removes noise and artifacts caused by compression.</p>

<p>The projector's 3LCD technology delivers unbelievable color, amazing detail and road-tested reliability. Using an advanced three-panel design, Mitsubishi's HC6000 produces both rich and vibrant colors with extraordinary details for outstanding picture quality.</p>

<p>Mitsubishi's HC6000 is designed with inorganic LCD panels that are durable and provide a more color-consistent, even-toned image than previous generation LCD panels. Mitsubishi is also offering an accessory air filter that can be applied over the air panel for an even cleaner projector environment.</p>

<p>With up to 5000 hours of lamp-life (in low mode), HC6000 owners won't have to change lamps often, but when it's necessary the new projector offers a design that makes replacement quick and easy. Through an easily accessed lamp housing, users simply switch the lamps without taking the mounting structure apart and physically handling the projector.</p>

<p>"Mitsubishi is committed to making high quality 1080p home theater projectors more affordable," said James Chan, director, product marketing, Mitsubishi Digital Electronics America's Presentation Products Division. "We're excited to offer so many advanced features for a suggested price under $4000."</p>

