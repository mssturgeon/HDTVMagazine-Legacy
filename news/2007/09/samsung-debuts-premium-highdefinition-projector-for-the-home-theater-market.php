<p><B>DENVER--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a world-leading manufacturer of professional LCD and PDP display products, today unveiled the SP-A800B projector, a premium projector that enhances the home theater experience by delivering film-like picture quality in high-definition 1080p. A selection of Samsung's home theater offerings, including the SP-A800B, will be on display at the CEDIA Expo 2007, in the Samsung booth, SR-10, at the Colorado Convention Center, September 5-9.</p>

<p>With the SP-A800B, home theater enthusiasts are able to watch their favorite films in the comfort of their own living and media rooms without compromising on picture quality. The SP-A800B leverages an advanced 1080p DLP engine to deliver a level of color and image quality that is traditionally only found in studio-grade monitors and commercial movie theaters. In addition to its native resolution of 1920 x 1080, the SP-A800B features an impressive 95% aperture ratio and a fast 16 microsecond (0.016 millisecond) response time to further facilitate accurate and natural motion graphics. Furthermore, the SP-A800B projector features a contrast ratio of 10,000:1, providing for darker shades of blacks and achieving an image closer to what is originally intended by the filmmaker.</p>

<p>To facilitate the highest quality home theater experience and color reproduction, Samsung teamed up with Joe Kane Productions, a worldwide authority on visual imaging equipment and development. The result of this collaboration is a premium high-definition projector that reproduces astonishing flesh tones and natural colors. Matching the gamma response curve of ultra-expensive studio video equipment, the SP800B allows users to freely select the color space for the three broadcasting formats (SMPTE-C, HDTV, and EBU) to deliver accurate projection regardless of format.</p>

<p>Further pleasing home theater purists, the SP-A800B delivers a film mode with a frame rate of 24 frames per second, the same frame rate found in commercial movie theaters.</p>

<p>"As a global leader in the home cinema industry, Samsung is equipped to leverage its technology prowess to deliver an unparalleled home theater experience," said Chris Franey, Samsung Electronics America. "With the SP-A800B, Samsung has created the ultimate solution for the growing body of consumers that seek premium cinematic viewing within the comforts of their own home."</p>

<p>"With its Texas Instruments DLP light engine and Samsung's state of the art electronics engineering, the Samsung projectors are the only non CRT display devices I am aware of that mirrors the performance of a broadcast grade monitor," said Joe Kane. "It is these broadcast monitors that are used by directors and cinematographers to create their art. With Samsung's ability to reproduce this, the viewer at home is able to see exactly what was intended," Kane added.</p>

<p>The SP-A800B projector matches high-performance with high-design. Sleek and stylish, the projector creates a mystical effect, delivering soft blue lighting and a "dolphin-like" design. The SP-A800B also provides quiet operation with a low noise fan. The theater mode operates at just 25db enabling users to focus on the finest details without missing a word in the quietest of scenes.</p>

<p>Like all Samsung projectors, the SP-A800B projector is backed by a three-year limited warranty on labor and parts as well as toll-free technical support for the life of the display.</p>

