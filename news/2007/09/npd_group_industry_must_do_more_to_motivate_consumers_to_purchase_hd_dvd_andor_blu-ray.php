			<p class="prtitle">High-Definition Discs and Video Players: Industry Must Do More to Motivate Consumers, but Opportunity for Growth is Abundant</p>

<center><i>The NPD Group examines consumers' intent to purchase and awareness of high-definition video players and video content</i></center><br />
<br />

<p><B>PORT WASHINGTON, N.Y.--(BUSINESS WIRE)</B>--The NPD Group reported today some reasons for the slower than expected start of high-definition video players and high-definition content sales (i.e., HD DVD and Blu-ray Disc). NPD's new High Definition Video Report Series examines consumer awareness, ownership, usage patterns, and intent to purchase high-definition players and content, since these new technologies were introduced last year.</p>

<p>Among those who currently own HDTVs, half (52 percent) are familiar with the availability of high-definition DVD players, but only 11 percent expressed strong intentions to buy one in the next six months. Seventy-three percent of HDTV owners reported that their current traditional-format DVD player still works well for them, so they do not need to replace it; while 62 percent said they are waiting for the prices of high-definition players to fall.</p>

<p><br />
<B>The format battle rages on</B></p>

<p>According to NPD, consumers' knowledge of the HD DVD format is more prevalent than for the Blu-ray Disc format. While 29 percent of respondents were aware of HD DVD, just 20 percent had heard of Blu-ray Disc. Consumers who purchased a Blu-ray Disc player reported that they did so because they believed it was superior to HD DVD; while those who purchased an HD DVD player did so because the price was lower than a Blu-ray Disc player.</p>

<p>"As HDTV penetration continues to grow, manufacturers and studios will need to do a better job imparting the benefits of these formats to a consumer base that still reports a high satisfaction with the current DVD standard," said Ross Rubin, director, industry analysis, consumer electronics.</p>

<p>Familiarity with the latest formats is primarily coming from exposure to marketing - especially television commercials. Forty-one percent of consumers who say they are familiar with Blu-ray Disc players and content gained awareness through ads and commercials. The same is true for HD DVD (42 percent). Nearly one-in-five consumers reported learning about the devices from friends and family.</p>

<p><br />
<B>The high-definition DVD content conundrum</B></p>

<p>Difficulty in communicating the high-definition message is compounded by the relatively small amount of available content in either of the two formats. NPD's research shows that the overwhelming majority of DVDs purchased by high-definition owners are standard definition (64 percent); however, the primary reason consumers reported buying a traditional DVD was that the high-definition disc was not available.</p>

<p>"Early adopters aren't choosing to evangelize high-definition players to others, in large part because they are unhappy with the available selection," said Russ Crupnick, vice president and senior entertainment industry analyst. "The good news is that the industry can address this concern by releasing HD DVD and Blu-ray Disc titles more aggressively."</p>

<p>One encouraging signal for the industry is that existing HD DVD and Blu-ray Disc consumers are trading up from standard definition. According to NPD, early adopters plan to replace nearly a quarter (23 percent) of their current collections with high-definition format DVDs (either HD DVD or Blu-ray Disc), and there is an appetite for more.</p>

<p><br />
<B>Methodology</B></p>

<p>For NPD's High Definition Video Player Report Series, more than 5,500 adults were surveyed between June 18 and June 28, 2007. Among the sample were 542 pre-identified owners of high-definition players and high-definition capable video game consoles.</p>

