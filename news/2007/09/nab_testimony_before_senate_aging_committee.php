<p>Thank you, Mr. Chairman and Members of the Subcommittee. My name is Marcellus Alexander and I am Executive Vice President for Television at the National Association of Broadcasters. I appreciate this opportunity to testify today. </p>

<p>Local broadcasting is a vital part of everyday life with local news, weather, emergency information and programming. The switch to digital broadcasting holds great promise. It is of particular significance to older Americans. Research suggests that older Americans are among the groups who will be disproportionately affected by the transition. In fact, adults ages 55 and older spend more time watching broadcast TV than other TV services. It is critical that we maintain their access to local news, emergency information and entertainment.</p>

<p>For close to 20 million households, their choice and time spent watching TV are with local broadcast stations. I have managed television stations in Baltimore and Philadelphia, and I can tell you that broadcasters do not want to lose any viewers - period. And, they will do what it takes to ensure they don't. Local broadcasters have a social and community responsibility to ensure that television viewers understand what they need to do to continue to receive their local television. It also makes good business sense.</p>

<p>Let me be clear - DTV consumer education is the number one priority of NAB's Television Board. </p>

<p>In July, NAB President David Rehr sent a letter to every member of Congress outlining our efforts on the digital transition. One of these is the DTV Transition Coalition, started by NAB and seven other organizations. It now has grown to include over 160 members. This coalition includes AARP and the cable channel, Retirement Living Television (RLTV). These organizations will help give specific focus to reaching the older American population.</p>

<p>AARP has taken a leading role in the Coalition and is able to review and help shape the materials that the Coalition sends out to its members. In May, NAB participated in a DTV transition-themed and televised town hall meeting. RLTV will be promoting these meetings across the country in the upcoming months</p>

<p>Our partnerships can't end there, however. Recently, we have reached out to the National Council on Aging and sent letters to the aging agencies of all 50 states. </p>

<p>I am fortunate and blessed to have both parents still living. So I look at the transition through their eyes and can see first hand some of our challenges. Mom and Dad, who live in Texas, still like to watch local news and Dad doesn't like to miss the Dallas Cowboys play...in spite of my advice on better teams!</p>

<p>So we will reach my Mom and Dad's eyes and ears with information from a variety of sources: public service announcements, news stories, information crawls, speakers' bureaus, seniors publications and Web sites. </p>

<p>Additionally, I am pleased to share that early next week NAB will announce the next phase of our comprehensive media strategy to deliver information across multiple media platforms, and to grow consumer awareness across the country.</p>

<p>Many individual stations are already running DTV transition public service announcements. Raycom Media is running a series of PSAs under the theme of "The Big Switch". Other companies, like Capitol Broadcasting, Post Newsweek, Bonneville, Freedom, and Dispatch Broadcast Group, are also already running DTV PSAs. Many others have aired news stories on the subject.</p>

<p>Today, I am also pleased to announce that NAB has developed and sent to stations yesterday, a video package that includes interview sound bites for use in newscasts. And yes, it includes English and Spanish language public service announcements as one part of our overall communications strategy. These PSAs are closed captioned and include a 1-800 phone number.</p>

<p>Now, what can members of Congress do? NAB has sent a DTV toolkit to every Member of Congress suggesting ways in which you might help reach your constituents with education and information about the transition. We are pleased that this Committee's Web site includes a link to DTV information. NAB encourages all Members to include access to this information on their office Web sites.</p>

<p>Mr. Chairman, the NAB and the Coalition efforts are well underway. We hope we can work together to ensure that all consumers, including older Americans, maintain access to free over-the-air television. </p>

<p>Thank you very much.</p>
