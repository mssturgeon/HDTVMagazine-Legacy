<p><B>CEDIA EXPO -- DENVER, CO - Sept. 5, 2007</B> -- SANYO, one of the world's largest manufacturers of projectors introduces the PLV-Z2000 1080p LCD projector during CEDIA EXPO this week in Denver, CO. The PLV-Z2000 features a new 3D color management system with a high contrast ratio of 15,000:1, along with an advanced lens shifting function and the industry's quietest fan system. The PLV-Z2000 will be available in the U.S. in October 2007 with a MSRP of $2,995.99.</p>

<p>Offering a full 1920 x 1080 high definition resolution, the PLV-Z2000 delivers rich, deep and accurate colors due to SANYO's exclusive Topaz Real HD technology, a 3D color management system that addresses changes in color phase and color level to obtain perfect color reproduction. The PLV- Z2000's color management system provides 1110 times more color combinations than SANYO's 720p PLV-Z5, a total of approximately 216 billion possible color combinations. This new color management system was designed to optimize the potential of Deep Color via the projectors two HDMI 1.3 inputs.</p>

<p>Rated at 1200 lumens, the PLV-Z2000 is capable of an incredible 15,000:1 contrast ratio for superlative black levels, even in ambient light. Plus a newly developed, high efficiency lens that maximizes image details for exceptional optical performance.</p>

<p>The PLV-Z2000 uses a Durable Inorganic Optical System (DIOS), which includes the projector's LCD panels and polarizing film. This highly advanced optical engine increases the overall reliability and performance of the PLV-Z2000 many times over traditional 3LCD projectors.</p>

<p>The PLV-Z2000 is outfitted with the industry's most advanced lens shifting function. When coupled with the projector's short throw capability and 2x zoom, the PLV-Z2000 can create a large screen image in any size room and from virtually any location. The lens shifting function allows wide-range shifting up or down to three screen sizes and left to right to two screen sizes. The throw design of the PLV-Z2000, is capable of projecting a 100-inch diagonal image from 10 to 20 feet away, which makes it extremely suitable for small to mid-size home theaters.</p>

<p>A 1200 lumen projector generates a tremendous amount of heat and requires a high quality fan to protect it. At this level of brightness, the fan is 'on' most of the time and the noise can be extremely loud and disruptive, especially in smaller home theaters where the projector and the audience are in the same vicinity. To promote greater enjoyment of the film and to reduce noise levels during quiet passages of a film, the PLV-Z2000 is equipped with the industry's quietest fan, a large aperture, low noise Sirocco cooling fan that never rises above 19dB in the economy mode.</p>

<p>"The PLV-Z2000 offers home theater users a high performance, cost-effective solution for 1080p projection, "says Mark Holt, the Vice President and General Manager for SANYO's Presentation Technologies Division. "The flexibility of installation due to our unique lens shifting system and the short-throw distance makes the PLV-Z2000 an excellent choice for home theater viewing. HDMI 1.3 and Full 1080p HD makes it a wise investment in the best in home theater for year's to come."</p>

