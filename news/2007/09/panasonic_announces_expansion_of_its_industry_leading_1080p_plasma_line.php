<p><img src="/images/products/panasonic-th-42pz77.jpg" alt="Panasonic TH-42PZ77" align="left" /><B>DENVER, Sept. 6 /PRNewswire/</B> -- Panasonic, the market and technology leader in Plasma HDTVs, announced today at the opening of the 2007 CEDIA convention, that it has expanded its already industry leading line of 1080p High Definition Plasma TVs, to include two new, more affordable models -- the TH-42PZ77 and the TH-50PZ77. Scheduled to ship this month, the new 42-inch and 50-inch class Plasmas have SRPs of $1799.95 and $2799.95 respectively.</p>

<p>The introduction of the PZ77 series increases Panasonic's already deep line of 1080p Plasmas to eight -- the widest selection of Plasma TVs in the industry -- and further demonstrates Panasonic's industry leadership and cutting edge technology in big screen Plasma entertainment. The two new 1080p TVs join the critically acclaimed 700 and 750 series providing consumers with a wide selection of Plasmas with the highest, to date, possible resolution. Panasonic's top rated Plasmas are available in 42-inch, 50-inch, 58-inch and 65-inch class models, all of which include the unique SD memory card slot, a feature that allows consumers to view images from an SD Memory Card on the big screen Panasonic Plasma, rather than the camera's small screen or a computer monitor.</p>

<p>"CEDIA is the perfect environment to introduce Panasonic's expanded line of 1080p Plasmas," stated Dennis Eppel, Vice President, Panasonic Display Company. "Custom installers are a very important part of our business and with this in mind we are confident that the depth and outstanding picture quality of Panasonic's Plasmas will meet and exceed the installer's requirements. In the end, Panasonic's commitment to providing the highest quality ensures that we will continue to meet consumer desire for a High-Definition lifestyle."</p>

<p>The TH-42PZ77 and TH-50PZ77 feature more than two million pixels and have a resolution of 1920 x 1080, with a contrast ratio of 10,000:1. The two latest additions to Panasonic's 1080p Plasma line also feature an anti-glare screen coating and a jack pack that includes two HDMI inputs, three S-video inputs, three composite video inputs and two component video inputs. The PZ77 series also incorporates an automatic pixel wobbling function -- as does the entire 2007 Plasma line -- for anti-image retention. The PZ77 series also features EZ-Sync(TM), a technology that links Panasonic consumer home entertainment and video products to allow seamless control of the entire system using only one remote and the unique SD Memory card slot.</p>

<p>"Panasonic's 2007 line of 1080p Plasmas produces crisp, clear images with a wide viewing angle so that the superb picture can be seen from any seat in the home environment," added Eppel. "We've been the market leader for the past three years and as the saying goes -- the proof is in the pudding. Quite simply, Panasonic's Plasmas produce beautiful pictures and with our recent announcement of an extended life span of 100,000 hours to half brightness, these 1080p TVs are the perfect technology for a variety of entertainment options, from gaming to viewing sports and movies."</p>

