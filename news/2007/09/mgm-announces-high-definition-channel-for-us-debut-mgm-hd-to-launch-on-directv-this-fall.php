<p><B>LOS ANGELES, Sept. 18 /PRNewswire/</B> -- Taking advantage of the new opportunities created by the recent growth in high definition broadcasting, Metro-Goldwyn-Mayer Studios Inc. (MGM) will launch its first wholly-owned channel in the United States, achieving its long-time goal of breaking into the channel business in the world's largest marketplace. The announcement was made today by Harry E. Sloan, Chairman and Chief Executive Officer at MGM.</p>

<p>In a breakthrough agreement, MGM HD, a new 24/7 linear network delivering a robust library of classic and contemporary films in high definition, will launch this fall on DIRECTV, Inc., the nation's leading satellite television service provider. While the MGM HD channel heralds the studio's first foray into domestic channel operations, the MGM channel is currently available in nearly 120 countries across the globe, including an MGM HD channel in Poland which launched last year.</p>

<p>MGM HD will provide consumers with the ultimate home viewing experience in the fast growing high definition market. MGM HD's tagline -- "the way movies were meant to be seen" -- accentuates the consumer proposition that high definition gives to films. MGM HD will feature a plethora of movie genres that will appeal to a growing and diverse audience craving to watch quality movies in high definition. Among its initial high definition screenings will be Academy Award(R)-winning films such as "The Black Stallion," "Usual Suspects," "Leaving Las Vegas," and "West Side Story" as well as audience favorites "Hotel Rwanda," "Throw Momma From The Train" and "RoboCop."</p>

<p>Backed by the world's largest modern film library, consisting of more than 4,100 film titles and winner of 209 Academy Awards(R), MGM HD will have a distinct advantage over the competition in the expanding HD marketplace. In addition to classic MGM theatrical hits, MGM HD will be the ultimate resource for serious movie fans, offering viewers an array of original programming and new content. Audiences can look forward to exclusive behind the scenes coverage of red carpet events, sneak peeks at new films in production, seasonal promotions and world premieres of newly re-mastered hits from the MGM library.</p>

<p>MGM HD will evolve into a strategically valuable asset for the studio as it will provide a "touch point" for the MGM brand, allowing cross promotional and advertising opportunities as well as programming synergies among all divisions of the company.</p>

<p>"The growth of the MGM library and the further expansion of the MGM channels worldwide are the studio's primary objectives," said Sloan. "By converting MGM's sizable library to high definition, we've developed a sustainable business model for an MGM HD Channel in the U.S. We are also fortunate to have Doug Lee, our digital media executive, who also has extensive channels experience, to spearhead the HD opportunity for us. We believe that as these new technologies and platforms emerge, they will be instrumental in adding overall value to the studio."</p>

<p>Sloan, who came to the studio Chairmanship after more than a decade in global television, is one of the few studio heads to have significant experience in creating worldwide broadcast platforms. Building SBS Broadcasting, S.A. from a single TV station in Scandinavia to a pan-European media empire, Sloan has hands-on knowledge of channel operations and the opportunities made possible through digital and high definition broadcasting. With the launch of MGM HD, Sloan is positioning MGM to participate in technology changes that shape the new landscape in the media world.</p>

<p>The U.S. launch of MGM HD was spearheaded by Jim Packer, Co-President, Worldwide Television and Douglas A. Lee, Executive Vice President, Worldwide Digital Media, MGM.</p>

<p>In commenting on the launch, Packer stated: "The response from cable, satellite and telco companies to the MGM HD channel has been resoundingly positive. Given the breadth and depth of our library, there are many unique programming opportunities that we can bring to movie lovers all over the U.S. Our programming vision is to grow the channel's breadth beyond our film library with original and unique HD content."</p>

<p>Lee added: "Given the importance of the MGM HD initiative, we are very pleased to have DIRECTV as our initial launch partner and look forward to announcing additional carriage agreements in the near future. As for the growth potential of the channel, MGM HD will become a significant brand extension and allow us to develop fantastic synergies with the studio's yearly slate of movies."</p>

<p>Derek Chang, Executive Vice President, Programming and Strategy, DIRECTV stated: "With the launch of up to 100 HD channels by the end of this year, DIRECTV is taking HD to a level that can't be found on any other multichannel provider in the country, MGM's brand recognition and entertainment assets will bring incredible value and we are excited to have them as a part of our HD lineup."</p>

<p>MGM predicts that as cable and satellite operators in the US drive penetration of HD services, MGM HD is in position to secure increased carriage from overall growth in the HD universe. Industry reports estimate that the HD universe will reach in excess of 40 million homes by 2012.</p>

<p>Over the last several years, MGM has focused on growing its channel business in the global marketplace. Currently, there are nearly 20 separate feeds of MGM channels outside the U.S., in various languages, reaching scores of markets across the Latin America, Europe, the Middle East, Africa, Asia and the Pacific Rim. Just last October, MGM launched its first HD channel internationally in Poland. With extensive experience in programming and marketing these channels, MGM is ready to capitalize on the opportunities in new emerging HD market in the US marketplace.</p>

