<B>Beautiful Picture Quality with Improved Clarity</B></p>

<p>The PT-AE2000U model comes equipped with Panasonic's new optical system that's designed to display beautifully detailed images with a captivating brightness of 1,500 lumens. Careful craftsmanship is incorporated into each individual optical system by highly skilled technicians to fully optimize the image for full high definition (HD) resolution. The projector's new Detail Clarity Processor analyzes frequency characteristics of each frame in three dimensions (horizontal, vertical, and along the time axis) and applies necessary sharpness at varying degrees to create natural, life-like images with exceptional clarity.</p>

<p>"Continuing our close collaboration with leading Hollywood colorists and image experts, we've taken our projector technology to the next level to meet the growing demand for high-definition home entertainment content," said Thomas Zitelli, president of Panasonic Projector Systems Company. "For home theater connoisseurs and audio video professionals who desire the richest colors and the best image quality, our new PT-AE2000U LCD projector enables viewers to easily enjoy movie theater-quality entertainment at home."</p>

<p>The PT-AE2000U projector reproduces Hollywood movies, independent films and other entertainment with exceptional color accuracy. Its enhanced unique Pure Color Filter Pro uses optical adjustment to achieve a higher purity level of the three primary colors; it also helps displays deeper, purer blacks. The color space has been extended even more to match the approximate level specified in the digital cinema industry.</p>

<p>The new projector also incorporates Panasonic's well-known Smooth Screen technology that reduces the black lines between pixels that mar picture quality. The technology has been tuned together with the new full-HD optical unit, allowing consumers to enjoy vibrant, smooth images found in commercial movie theaters. In addition, Panasonic's original Dynamic Iris has also been improved for further stability and response by controlling the iris speed at finer increments to help reproduce darker blacks and brighter whites.</p>

<p>The image processing system has been improved dramatically, with a maximum of 16 bit digital signal processing making it possible to reproduce subtle hues and brightness variations faithfully with greater smoothness. Furthermore, the projector also incorporates next-generation, full high definition LCD panels (C2Fine D7TM)1, which are characterized by inorganic alignment layer and vertically aligned liquid crystals for enhanced black level performance.</p>

<p><br />
<B>Professional-Level Features</B></p>

<p>The new LCD projector also comes equipped with professional-level features that let users personalize the images they see on the screen. First, the projector's Split Adjust mode allows users to split the screen into two halves, one to make picture adjustments and one to see those adjustments as a baseline reference. Second, the PT-AE2000U's waveform monitor - seen mostly on professional video and film equipment - measures the level of brightness output from a given video signal source. This feature also now automatically verifies that the source device is outputting at full dynamic range, and quickly makes adjustments to optimize it for your home theater setting. Users can easily see a graphical representation of any changes made to the unit's color settings.</p>

<p>In addition, the Cinema Color Management feature helps color correct approximately 1,070,000,000 different colors for a more refined, customized control of individual colors - closely representing the process used by Hollywood's motion picture color correction specialists. The PT-AE2000U also incorporates picture modes demanded by film production studios to help them with production and post-production activities. You can now store up to eighteen personalized settings with customized names.</p>

<p><br />
<B>Ease of Use</B></p>

<p>The PT-AE2000U is now equipped with three HDMI inputs2, so you can connect multiple HD sources without a HDMI switcher. Set-up and installation are a snap with the PT-AE2000U projector's 2x powered zoom and its wide lens shift range. Thanks to both features, the new model can cast a 120-inch diagonal image from as little as 3.6 meters (about 11 feet) to 7 meters (24 feet) from the screen. The new projector's lens shift capability enables full, 100 percent vertical adjustment and 40 percent horizontal adjustment so that viewers can suspend the projector close to the ceiling in a stylish fashion, or conveniently place the projector on a book shelf.</p>

<p>The projector's lens-centered design and maintenance features, such as the replaceable side filter and top lamp, make the ceiling mount very easy to install. The PT-AE2000U's jet black color and sleek cabinet design also fit well in home theater environments, and its universal remote control enables viewers to easily control their entire home theater system from one device.</p>

