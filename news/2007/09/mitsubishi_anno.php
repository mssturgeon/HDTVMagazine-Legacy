				<p class="prtitle">Mitsubishi Announces Newest 1080p HC6000 Projector at CEDIA 2007</p>

<center><i>Successor to Award Winning HC5000 Offers Improved Features, Lower Price</i></center><br />
<br />

<p>CEDIA EXPO 2007</p>

<p><B>IRVINE, Calif.--(BUSINESS WIRE)</B>--Mitsubishi Digital Electronics America's Presentation Products Division, known for award-winning, high-quality presentation and display products, today introduced its newest true 1080p (1920 x 1080) resolution HC6000 home theater projector. Improving upon and replacing Mitsubishi's outstanding HC5000, the HC6000 offers enhanced features at under $4000, performing seamlessly with the latest Blu-ray or HD DVD technology.</p>

<p>"Last year we took the high definition home theater market by storm with the HC5000," said Wayne Kozuki, product manager, Mitsubishi Digital Electronics America's Presentation Products Division. "The HC6000 continues the trend of the highest quality 1080p performance at an affordably low price."</p>

<p>Mitsubishi has improved the HC6000's auto iris function for quicker black to light imaging and increased its contrast ratio to 13,000:1. This combination allows for dynamic and smooth transitions between light and dark scenes and sharper overall details in dark areas, even in fast action spaceship scenes or classic film noir.</p>

<p>The new HC6000 provides two HDMI connectors allowing for a true digital-to-digital link between the projector and its image sources. The 1000 ANSI lumens projector offers a powered lens shift and powered zoom for easy installation and set-up, making it perfect for installed home theater environments.</p>

<p>Unlike other 1080p projectors, Mitsubishi incorporates the Emmy&reg; award-winning HQV (Hollywood Quality Video) high-performance video processor inside the projector, for a more streamlined form factor.</p>

<p>Reon-VX's HQV processing delivers sharp, detailed HD images by utilizing features such true 1080i-to-1080p HD deinterlacing and a sophisticated multidirectional diagonal filter that helps ensure video that is free from jagged edges. HQV also makes standard definition material approach HD quality by employing advanced scaling, per-pixel detail enhancement and noise reduction technology that removes noise and artifacts caused by compression.</p>

<p>The projector's 3LCD technology delivers unbelievable color, amazing detail and road-tested reliability. Using an advanced three-panel design, Mitsubishi's HC6000 produces both rich and vibrant colors with extraordinary details for outstanding picture quality.</p>

<p>Mitsubishi's HC6000 is designed with inorganic LCD panels that are durable and provide a more color-consistent, even-toned image than previous generation LCD panels. Mitsubishi is also offering an accessory air filter that can be applied over the air panel for an even cleaner projector environment.</p>

<p>With up to 5000 hours of lamp-life (in low mode), HC6000 owners won't have to change lamps often, but when it's necessary the new projector offers a design that makes replacement quick and easy. Through an easily accessed lamp housing, users simply switch the lamps without taking the mounting structure apart and physically handling the projector.</p>

<p>"Mitsubishi is committed to making high quality 1080p home theater projectors more affordable," said James Chan, director, product marketing, Mitsubishi Digital Electronics America's Presentation Products Division. "We're excited to offer so many advanced features for a suggested price under $4000."</p>

<p><br />
<B>Pricing, Availability and Warranty</B></p>

<p>The manufacturer's suggested price of Mitsubishi's new HC6000 is under $4000 and will be available in October through authorized Mitsubishi dealers. The projector comes with Mitsubishi's two-year limited warranty on parts and labor plus a 90-day limited warranty on the lamp.</p>

<p><br />
<B>About Mitsubishi Digital Electronics America Presentation Products Division</B></p>

<p>Mitsubishi Digital Electronics America's Presentation Products Division markets an extensive line of professional presentation, front-projection high definition home entertainment, and rear-projection video wall cube display systems and digital signage monitors that are designed with DLP&reg; or LCD technology, and is known for its award-winning, high-quality, accurate color reproduction technology. Products are sold through authorized distributors, resellers, retailers and system integrators throughout the United States and Mexico. Mitsubishi Digital Electronics America is located at 9351 Jeronimo Road, Irvine, Calif., 92618. For more information, please call 888-307-0312 or visit http://www.mitsubishi-hometheater.com.</p>

