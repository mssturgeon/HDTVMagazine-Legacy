				<p>AUSTIN, TEXAS, Sept 26, 2007-According to DisplaySearch Q2'07 video processor, MPEG video processor and de-interlacer/scalar unit shipment growth was 12% Q/Q and 51% on a Y/Y basis. Overall revenues, however, declined 3% Q/Q due to ASP margin declines in the quarter that were faster than unit shipment growth but showed a 8% Y/Y increase. A large percentage (65%) of all IC units shipped were video processors without MPEG decoding and required a separate MPEG decoder, with de-interlacing and scalar-related functions merged in either of the two remaining categories of video processors (those with/without) MPEG decoding. </p>

<p>According to Vish Nayak, Vice President of Display Electronics at DisplaySearch, "Revenue for TV IC manufacturers was slightly below expectations because TV semiconductor suppliers faced tremendous margin pressure from high volume, low cost brands like Vizio, which became the #1 selling brand in the North American market in Q2'07. These low cost TV market pricing pressures caused a corresponding ASP decline for quarterly pricing demanded by TV OEMs from their IC suppliers." </p>

<p>Nayak added, "Revenue and units are expected to pick up in 2H'07 due to aggressive promotional plans and inventory build-up by TV OEMs for the traditionally strong year-end holiday quarter and normal seasonal effects of a technology transition from analog to digital TVs by consumers. The overall outlook for 2H'07 is very positive with an aggressive shift continuing toward flat panel TV purchases, as consumers look forward to replacing their analog TVs with DTVs during the peak holiday and football seasons." </p>

<p>DisplaySearch latest report introduces coverage of the 120 Hz shipments and rolling forecasts for eight quarters. It also forecasts 1080p/720p semiconductor differential pricing for TVs offering these resolutions. </p>

<p>Most mid-tier and high-end TVs had two-chip solutions. Single integrated SOC solutions were targeted at cost sensitive TV markets where performance was not as much a premium. The overall 2007 revenue market forecast is $1.27B, up a small 2% Y/Y, due to faster ASP declines on unit volume growth. MPEG2-based video processors had the largest Q/Q unit and revenue growth. </p>

<p>Q2'07 highlights include </p>

<p>Total revenue in Q2'07 fell to $298.7M. Continued revenue growth is expected through 2007 in the IC market. </p>

<p>Trident Micro Systems was the overall DTV Market share leader with an overall 27% share of the DTV total market for Q2'07 with 20% Q/Q unit growth due to increased shipments of their SOC video processors that incorporate advanced ME/MC circuitry and 120 Hz technology into a single IC to the top four DTV brands. </p>

<p>IC suppliers are turning their attention to the fast growing European market for DVB-T. The DVB-T TV market is forecasted to be 9.4M units in 2007, and is expected to rise to 23.8M units by 2011. ST Microelectronics led the Q2'07 IC market with stand-alone MPEG2 processors shipping into DVB-T TVs.<br />
 <br />
AMD/ATI led the MPEG-2 video processor market with around 2M units shipped in Q2'07. Zoran was a distant second with 0.9M units shipped on a worldwide basis. </p>

<p>Trident leads the IC supplier market with a 27% share, followed closely by Genesis Microchip. Trident saw the fastest growth of the top five IC suppliers with 20% Q/Q unit shipments growth.</p>

