<center><i>Launch of CNN HD Is First U.S.-based 24-Hour News Network in High Definition</i></center><br />
<br />

<p>CNN Worldwide this week launched the first 24-hour domestic news network in high definition, marking the company's global commitment to provide more news and information in that format for years to come.</p>

<p>CNN HD, which was made available on Saturday, Sept. 1, stands as a separate high-definition signal offering a programming line-up identical to the CNN/U.S. channel broadcast in the standard-definition format. As part of its initial entry into high-definition television, CNN will produce all of its New York-based programs, select documentaries and special events, including CNN Presents: Planet in Peril and presidential debates, in high definition.</p>

<p>The launch of CNN HD is part of a continued rollout of high-definition offerings and innovations. CNN Worldwide's high-definition plans go beyond upgrades of studios and production centers and include a significant investment in equipment in the field to ensure that its journalists can gather news in high definition. For example, crews will be equipped with a combination of HD cameras, laptop editors, trucks and fly-aways and the CNN Election Express, the network's mobile HD production unit.</p>

<p>"As part of our strategic growth we are aggressively investing in our newsgathering efforts worldwide to bolster CNN's delivery of news and information across all available platforms and services," said Jim Walton, president of CNN Worldwide. "Our move into HD is one of many significant ventures we have undertaken this year to increase CNN's edge as the world's news leader."</p>

<p>For CNN HD, programs produced in high definition will include American Morning, Lou Dobbs Tonight, Anderson Cooper 360&deg;, Lou Dobbs Weekend, Your $$$$$ and Open House. High-definition programming also includes CNN Presents: Planet in Peril, a sweeping four-hour documentary featuring Anderson Cooper, Dr. Sanjay Gupta and Animal Planet's Jeff Corwin. Filmed in high definition across four continents and 13 countries, Planet in Peril will air over two nights on CNN/U.S. on Tuesday, Oct. 23, and Wednesday, Oct. 24, from 9 p.m. to 11 p.m. (ET/PT).</p>

<p>Another upcoming program in high definition includes the CNN: Special Investigations Unit documentary Fed Up: America's Killer Diet featuring Gupta, CNN's chief medical correspondent. It will air on Saturday, Sept. 22, and Sunday, Sept. 23, at 8 p.m. and 10 p.m. (ET). CNN's next two presidential debates - a Nov. 15 Democratic debate co-sponsored with the Nevada Democratic Party in Las Vegas and a Nov. 28 Republican debate co-sponsored with YouTube in Florida - will both be shot and produced in a high-definition format for live broadcasts.</p>

<p>CNN Worldwide, a division of Turner Broadcasting System, Inc., a Time Warner Company, is the most trusted source for news and information. Its reach extends to nine cable and satellite television networks; one private place-based network; two radio networks; wireless devices around the world; CNN Digital Network, the No. 1 network of news Web sites in the United States; CNN Newsource, the world's most extensively syndicated news service; and strategic international partnerships within both television and the digital media.</p>

