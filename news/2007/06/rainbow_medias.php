				<p class="prtitle">Rainbow Media's VOOM HD Networks to be Carried on Cablevision</p>

<center><i>VOOM's 15 High Quality, High Definition Niche Channels Provide an Immediate and Significant Increase in MSO's Consumer HD Offering</i></center><br />
<br />
<B>JERICHO, N.Y.--(BUSINESS WIRE)</B>--Cablevision will now carry Rainbow Media's fifteen channel suite of VOOM HD Networks, it was announced today by Joshua Sapan, Rainbow President and Chief Executive Officer. The VOOM HD Networks will be available to Cablevision subscribers beginning July 1, 2007.

<p>"Cablevision's addition of the fifteen VOOM channels to its HD lineup reinforces our long held view that consumer demand for more and better HD programming offers MSOs a compelling business opportunity," said Sapan. "Cablevision continues to lead the industry with its vision and its products, and they have recognized that VOOM provides a compelling opportunity to respond to consumer demand with a quality product designed to appeal to a wide breadth of interests.</p>

<p>"We believe that consumers with new HDTV sets consistently look for programming of interest in HD before they settle for SD programming. This has far-reaching implications for the television business in general, but it offers the cable industry an incredible and timely opportunity to respond quickly and competitively to the shifts in the marketplace."</p>

<p>Cablevision subscribers will now be able to watch the VOOM HD Networks (www.voom.com), television's largest and most diverse suite of high-definition channels. Fifteen commercial-free, wide-screen channels, all delivered in true 1080i HD and 5.1 Dolby Ditigal surround sound, VOOM offers an extraordinary breadth of movies, sports, fashion, music, travel, lifestyle and adventure programming.</p>

<p>VOOM HD Networks' robust suite of 15 channels provides an HD tier that hits both a multi-cultural audience and a multi-generational household. The programming offers something for everyone in the family crossing a broad spectrum of content. With the expectation of the growing population of HDTV households, VOOM fills a void in the marketplace for the shortage of high-caliber HD programming in the home.</p>

<p>VOOM's original programming has been building an audience and gaining popularity. From the star studded VOOM Robert Wilson Portraits, which attracted some of today's biggest stars, to the current high- definition documentation of an historic Mount Everest expedition, VOOM offers a wide variety of compelling original programming for every interest with stunning, eye-popping HD clarity.</p>

<p>Recent VOOM programming highlights include the VOOM PORTRAITS BY ROBERT WILSON, an artistic venture of over 30 high-definition video portraits, created by the celebrated theater icon and visual artist Robert Wilson. Gallery HD will feature the works as well as a behind the scenes documentary on air in October. The PORTRAITS feature celebrity subjects including Brad Pitt, Winona Ryder, Johnny Depp, Monaco's Princess Caroline of Hanover, Mikhail Baryshnikov, Robin Wright Penn, Juliette Binoche, Isabelle Huppert, Isabella Rossellini, Jeanne Moreau, Steve Buscemi, Alan Cumming and Willem Dafoe.</p>

<p>Coming in 2008, VOOM HD Networks and British production company, Altitude Films will debut The Altitude Everest Expedition 2007, a major multi-platform documentary film that follows a team of the world's leading high altitude climbers as they retrace the last steps of British climbing legend George Mallory on Mount Everest. Globally, VOOM and Altitude launched ueverest.com, an online portal that allows audience is able to follow the progress of the expedition on a fully interactive web portal, to be launched earlier this month.</p>

<p>The fifteen VOOM HD channels are:</p>

<p><B>ANIMANIA HD</B></p>

<p>Eye-popping animation from the newest groundbreaking series, specials and cutting edge anime produced in stunning high definition to favorite cartoon classics re-mastered into HD. This is animation like you've never seen before.</p>

<p><B>EQUATOR HD</B></p>

<p>The first high-definition channel dedicated to exploring the world's most intriguing people and amazing places with intelligent programs about global adventure and green living, and cultural programs. Hear people of the world in their own words, and visit extraordinary landscapes that speak for themselves.</p>

<p><B>FAMILY ROOM HD</B></p>

<p>Movies, series and specials suitable for all ages - with movies like March of the Wooden Soldiers and The Muppets Take Manhattan, and series like Flipper and Thunderbirds.</p>

<p><B>FILM FEST HD</B></p>

<p>FILM FEST HD is a virtual revival house with a breadth of genres curated in HD. With restored classics, sleeper hits, retro favorites, docs, indies and even midnight cult movies, FILM FEST HD feels like a landmark movie house, it's a non-stop film festival with films re-mastered in high definition.</p>

<p><B>GALLERY HD</B></p>

<p>Gallery HD is the first and only HD channel that defines the most talked-about artists of today and tomorrow. This channel is dedicated to visual art and the artistic process, catering to a wide array of art lovers. Through visually stunning imagery and compelling storytelling, GALLERY HD is the first and only HD channel that showcases stunning imagery and stories from the front line of the art world.</p>

<p><B>GAMEPLAY HD</B></p>

<p>Enter the virtual worlds of video gaming for the first time in HD. The intensity of the video game comes alive on GAMEPLAY HD. Watch live video game tournaments and get tips on playing strategies from the creators of everything from the newest games to the arcade classics.</p>

<p><B>KUNG FU HD</B></p>

<p>Welcome to the Wild, Wild East! KUNG FU HD offers intense fights, amazing cinematography and lush colors in a line-up of all your favorite martial arts stars - from Bruce Lee to Jet Li, KUNG FU HD is all martial arts action, all the time!</p>

<p><B>HD NEWS</B></p>

<p>The first and only 24/7 national news source in high definition, HD NEWS offers news headlines, sports highlights, in-depth features and national weather reports supported by 5 news bureaus across the nation.</p>

<p><B>MONSTERS HD</B></p>

<p>TV's first all horror channel. The masters of movie horror in terrifying HD clarity. Monster movies are brought to life like never before on MONSTERS HD. From Frankenstein to Freddy, Godzilla to Jason, this monstrous mix of horror features blood-curdling clarity and spine-tingling sound.</p>

<p><B>RAVE HD</B></p>

<p>RAVE HD is the first music channel dedicated to delivering a larger than life concert experience in crystal clear hi-definition and 5.1 Dolby digital surround sound. Live music has a whole new experience.</p>

<p><B>RUSH HD</B></p>

<p>Life on the edge with adrenaline junkies of adventure sports, RUSH HD takes you to the heart of adventure sports, from B.A.S.E. jumping and kayaking to big-wave surfing, snowboarding and more.</p>

<p><B>TREASURE HD</B></p>

<p>The first channel dedicated to the over 70 million Americans who share a passion for collecting. TREASURE HD also carries exclusive live coverage of prominent sales from the world's preeminent auction houses. Original, innovative, entertaining, it's a Hi-Definition look at what people treasure in life, from antiques to adventures.</p>

<p><B>ULTRA HD</B></p>

<p>Immerse yourself in the worlds of fashion, beauty and style. ULTRA HD delivers coverage of the hottest fashion, the coolest styles and insight into the 'luxe' life from around the world. From shopping to cuisine to interior design, ULTRA HD is devoted to stylish living.</p>

<p><B>WORLD CINEMA HD</B></p>

<p>TV without borders. WORLD CINEMA HD provides American audiences with a passport to explore the best HD imports, featuring award-winning movies and stars from around the globe.</p>

<p><B>WORLDSPORT HD</B></p>

<p>WORLDSPORT HD delivers a wide variety of top sporting events from around the globe, including live HD coverage of the Spanish Premier Soccer League and the Canadian Foot League, and other sporting events from premier arenas around the globe</p>

<p><B>About VOOM HD Networks</B></p>

<p>VOOM HD Networks is the largest suite of high-definition channels available anywhere, produced exclusively in high definition for distribution in the United States through satellite and cable operators. The VOOM HD Networks carry programming in categories as diverse as sports, movies, fashion, music and art. Today, the VOOM HD Networks are available nationally on Echostar's DISH Network. The VOOM HD Networks were developed by Rainbow Media to meet the growing demand for quality high-definition programming, building on Rainbow Media's history of original programming innovation.</p>

<p><B>About Rainbow Media Holdings LLC</B></p>

<p>Rainbow Media Holdings LLC is a subsidiary of Cablevision Systems Corporation (NYSE: CVC). Rainbow Media is a leading producer of targeted, multi-platform content for global distribution, creating and managing some of the world's most compelling and dynamic entertainment brands, including AMC, IFC, WE tv, Rainbow Sports Networks managed FSN Bay Area and FSN New England, LIFESKOOL, SPORTSKOOL, and VOOM HD Networks. Through its IFC Entertainment division, Rainbow Media also owns and manages the following: IFC Films, a theatrical feature film distribution company; IFC First Take/IFC in Theaters, a day and date theatrical feature film/VOD initiative; the IFC Center in New York City; IFC Productions, a feature film production company; and IFC Entertainment, which owns and operates a film library. Rainbow Media also operates Rainbow Advertising Sales Corporation, its advertising sales division, and Rainbow Network Communications, its full service network programming origination and distribution company.</p>
