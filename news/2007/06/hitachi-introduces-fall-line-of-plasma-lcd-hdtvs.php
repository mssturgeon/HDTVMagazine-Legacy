<B>Hitachi's Exclusive Reel60 Technology: A Breakthrough in Film Processing</B></p>

<p>Hitachi R&D today unveiled a technology breakthrough called Reel60&trade;, which is a key feature in its Full HD 1080 50-inch HDTV (model P50V701) and its Director's Series Full HD 1080 HDTVs in both 50-inch (model P50X901) and 60-inch (model P60X901) screen sizes. With Hitachi Reel60, a technique is applied that accurately and automatically eliminates the jittery or stuttering visual effect called "judder" which results from outdated methods for 3:2 pulldown correction (i.e. converting from 24 frames used in film to 60 frames used in television). By applying a motion interpolation technique that creates new frames based on the original film images, Hitachi's Reel60 processing technology smoothes out the movement and precisely matches the original motion. The result is extremely smooth, pure motion, whether it's a passing vehicle or a camera pan from across the screen or side-to-side. (Editor's Note: Complete details on Hitachi's Reel60 technology can be found in a separate release entitled: "Innovative Film Processing Technology from Hitachi Overcomes a 50-year Problem in Television," dateline: June 28, 2007)</p>

<p><br />
<B>Elegant Details Make the Difference</B></p>

<p>In all of its new models, Hitachi provides elegant details that enhance convenience and make a real difference in the viewing experience. For example, in some models, Hitachi's Power Swivel capability allows viewers to alter the angle of the display 30 degrees right to left, in seconds, all with a simple press of a remote control button. Additionally, in its V-Series and Director's Series models, the remote control includes glow-in-the-dark keys, another convenience feature for consumers, particularly since the displays are often viewed in dimly lit or dark rooms, as consumers seek to replicate the theater environment at home.</p>

