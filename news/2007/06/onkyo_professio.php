				<p class="prtitle">Onkyo Professional Debuts its First Multichannel Surround Processor</p>

<center><i>PR-SC885P features HDMI 1.3a Switching, Reon-HQV&trade; HD video scaling, HD radio, Ethernet and RS232 connections, Neural-THX Surround&trade;, and more</center></i><br />
<br />
<img src="/images/products/onkyo-prsc-885p.jpg" alt="Onkyo PR-SC885P" align="left" /><br />
<img src="/images/products/onkyo-prsc-885p-rear.jpg" alt="Onkyo PR-SC885P" align="left" /><B>ANAHEIM, CA (6/19/07)</B> -- Onkyo Professional introduced its first surround processor model designed for commercial and professional studio applications at the InfoComm 2007 event here today. The Onkyo Pro PR-SC885P is a THX-Ultra2 Certified 7.1-channel A/V processor that delivers state-of-the-art features and performance for the most technically sophisticated installations, including HDMI 1.3a compatibility, comprehensive upconversion of all sources to HD video with Reon-VX HQV video processing, and a wide array of connection options to accommodate any system. The rack-mounted unit is built around a massive toroidal transformer power supply with two separate power transformers for audio and video processing, and includes professional XLR balanced pre-outs for all channels.

<p>The PR-SC885P features HDMI v1.3a switching for single-cable transmission of HD video and audio signal, single-cable pure-digital audio and video transfer from HDMI sources, including 1080p and Deep-Color&trade; capability. Four HDMI inputs and two outputs are included to accommodate extensive combinations of high definition sources and display devices.</p>

<p>Onkyo Professional's PR-SC885P is among the first A/V preamplifier/processor available to include Silicon Optix's acclaimed Reon-VX HQV&trade; video processing. This sophisticated IC chip-based technology provides the processor with the highest-quality video scaling and deinterlacing currently available, including upscaling of all video sources to 1080p high definition video for output over the HDMI connection. Additionally, all video sources are also upconverted to HD output via the unit's component video outputs to accommodate displays lacking an HDMI input.</p>

<p>Ideally suited for large-scale installations, the PR-SC885P includes a wide range of integration features, including an ethernet port for easy integration with both AMX (via Device Discovery) and Crestron (via e-control) control systems. There is also a bidirectional RS-232 port, as well as IR in/out and dual 12-volt trigger jacks to round out the unit's extensive integration capabilities. Finally, it includes Onkyo's RIHD (Remote Interactive over HDMI) system control capability, which allows for integration of many system control functions via the HDMI connection between compatible components from Onkyo as well as many other manufacturers.</p>

<p>The Onkyo Pro PR-SC885P also includes a flexible array of multi-source/multi-zone capabilities, including processing for two separate audio and video sources in up to three individual zones. By using the 2.1-channel Zone 2 and Zone 3 pre-outs to connect to amplifiers in two other rooms, the main zone can still maintain full 7.1-channel playback. Power on/off, maximum volume, and balance controls for both additional zones can be controlled independently with the included preprogrammed/learning remote control, and there are separate tone controls for Zone 2.</p>

<p>The PR-SC885P is also highly adept at processing audio signals, with internal decoding for nearly every sound format currently in use, including Dolby Digital Plus, Dolby TrueHD, and DTS-HD Master Audio. Processing is accomplished with three advanced Texas Instruments 32-bit DSP chips, and digital-to-analog conversion on all channels is handled by superior-quality Burr Brown 192 kHz/24-bit DACs. For precise setup, the unit includes Audyssey Multi-EQ room acoustics correction, the most powerful built-in solution available for countering room distortion. By incorporating measurements at up to eight positions, rather than just one, Audyssey Multi-EQ provides both frequency response and time domain corrections throughout the entire listening area.</p>

<p>The Onkyo Professional PR-SC885P features HD Radio reception, as well as compatibility with both XM and Sirius satellite radio systems. It is among the first components available to feature Neural-THX Surround&trade; decoding for broadcasts and gaming. This new surround sound technology allows for broadcast content to be transmitted in a two-channel format, and later decoded for up to 7.1 discrete audio channels, as well as enabling 7.1-channel audio support for many modern video gaming consoles.</p>

<p>The Onkyo Professional PR-SC885P will be available in August at a suggested retail price of $1,800.</p>

<p>Onkyo Professional is a division of Onkyo USA devoted to providing high quality audio/video components designed for use in commercial and professional venues such as broadcast facilities, schools, stores, hotels, churches, etc. and semi-pro applications such as DJ usage. For more information about this and other fine Onkyo Professional products, visit www.onkyopro.com or call (201) 785-2600.</p>

<p>Onkyo, which takes its name from the Japanese "On" meaning 'sound' and "Kyo" meaning 'harmony,' has been producing precision audio components for over a half-century. The company's philosophy is to deliver products that are superbly designed and built to a consistently outstanding standard of excellence. Today, Onkyo is at the forefront of the home theater and digital revolutions.</p>
