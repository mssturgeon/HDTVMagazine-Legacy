				<p class="editorial">I've done a small amount of research here. Specifically, this release is announcing that those DIRECTV customers who own their HD DVR HR20 can connect to their PCs and view pictures or listen to music. This must mean that the ethernet port on the back of the unit, formerly "for future use", is now enabled. Let's hope this is just the beginning of PC connectivity.</p>
<p class="prtitle">DIRECTV and Intel Bring Connectivity to TV, PC</p>

<p><CENTER><I>Intel, DIRECTV Customers Can Now Play Music and View Pictures on</p>

<p>Their TVs from Their Intel(R) Viiv(TM) Technology-Based PCs Via Their</p>

<p>                        DIRECTV Plus(R) HD DVRs<br />
</I></CENTER></p>

<p><b>LAS VEGAS--(BUSINESS WIRE)--Jan. 10, 2007</b>--DIRECTV, Inc., the nation's leading satellite television service provider, announces that the DIRECTV Plus(R) HD DVR has been verified with Intel(R) Viiv(TM) technology. With this certification, DIRECTV becomes largest supplier of Viiv-verified digital media adapters (DMAs).</p>

<p>DIRECTV customers who have a DIRECTV Plus(R) HD DVR can now access and enjoy their pictures and music on their TVs directly from Intel Viiv technology-based PCs. The DIRECTV Plus(R) HD DVR is the world's first digital set-top box with integrated DMA functionality verified to work with Intel Viiv technology.</p>

<p>"We announced our alliance with Intel at the 2006 Consumer Electronics Show and we are happy to be here today, one year later, to show you the fruits of our labor," said Romulo Pontual, executive vice president and CTO, DIRECTV, Inc. "The way people consume media is rapidly evolving and connectivity between digital devices is becoming an essential part of the home ecosystem. DIRECTV understands this evolution and is delivering innovative solutions to make sure our customers stay connected."</p>

<p>"Today's announcement marries the millions of Intel Viiv technology-based PC owners with DIRECTV's high-definition TV viewers in a way that has never been done before," said Kevin Corbett, vice president, Intel's Digital Home Group and general manager of its Content Services Group. "DIRECTV's product exemplifies what a digital or connected home is all about where PCs, TVs and CE devices all work in concert together and consumers enjoy their entertainment on a variety of screens and devices when and where they want to."</p>

<p>Photos and music are just the beginning. The Viiv functionality is already available as a public beta trial to all DIRECTV Plus HD DVR customers. Later this year, DIRECTV plans to enhance the photo and music experience, as well as provide the ability to stream video from Intel Viiv technology-based PCs via DIRECTV Plus HD DVRs.</p>

<p>Delivering the ability to record and view 200 hours of standard definition content or 50 hours of MPEG 4 high-definition programming, the DIRECTV Plus(R) HD DVR receiver verified with Intel Viiv technology enables consumers to access and enjoy new experiences that combine the best of the TV with the best of the PC.</p>

<p>DIRECTV has established a dedicated location on the DIRECTV Web site to help customers understand the new connectivity options available to them. For more information and support customers can visit www.directv.com/viiv.</p>

