<p><img src="/images/bulletins/eva8000.jpg" alt="EVA8000" align="left" /><b>LAS VEGAS - January 7, 2007</b> - NETGEAR&reg;, Inc. (Nasdaq: NTGR), a worldwide provider of technologically advanced, branded networking products, today announced an ongoing collaboration and agreement with BitTorrent, Inc. to promote video downloads streamed to high-definition televisions (HDTVs) through the new NETGEAR Digital Entertainer HD (EVA8000) media receiver. BitTorrent, home to the world's leading peer-assisted digital content delivery platform, will work with NETGEAR on marketing and technology initiatives to deliver the highest quality and fastest distribution of media files over home networks.</p>

<p>Debuting this week at the Consumer Electronics Show in Las Vegas, the Digital Entertainer HD is a sleek set-top media receiver that connects to a home-theater system to stream digital media from computers, network storage and USB media players. The receiver automatically discovers, organizes and plays high-definition movies, TV shows, music files and personal photos - as well as Internet-based video, news feeds, weather reports and radio programs. The receiver's high-definition multimedia interface (HDMI) port displays video resolution up to 1080p on big-screen TVs and optical digital audio output (TOSLINK) transmits full digital surround sound to a digital audio receiver.</p>

<p>Responsible for almost 40 percent of all Internet traffic worldwide, BitTorrent is the most efficient platform for transferring large, high-quality files over the Internet to PCs and storage devices. BitTorrent, which has partnerships with more than 20 leading entertainment studios and TV networks, plans to offer a comprehensive library of downloadable digital entertainment content, including HD movies and TV shows. NETGEAR will market BitTorrent's online marketplace in collateral for the Digital Entertainer HD and at www.netgear.com. The marketplace is slated to launch in February 2007. BitTorrent will promote the Digital Entertainer HD at www.bittorrent.com.</p>

<p>"Our customers' growing appetite for quality HD content is well-served through NETGEAR routers, adapters, media receivers and storage devices," said Patrick Lo, NETGEAR's chairman and chief executive officer. "Even with broadband connections, however, the experience is only as good as the technology delivering the content over the Internet and to the HDTV screen. The audio and video quality of the Digital Entertainer HD - combined with the speed, simplicity and security in BitTorrent's delivery technology - offers exactly the type of experience our customers demand."</p>

<p>"BitTorrent provides the most sensible content delivery platform for high-definition entertainment on the Internet," said Ashwin Navin, president and co-founder of BitTorrent. "We are pleased to add NETGEAR to our family of innovative hardware manufacturers as we continue to expand BitTorrent's delivery capabilities beyond the PC."</p>

