				<p class="prtitle">LG Electronics Launches Industry's First Dual-Format High-Definition Disc Player</p>
<center><i>Player with Blu-ray Disc and HD DVD Playback Capabilities Introduced for First Quarter 2007 Availability</center></i>

<p><b>LAS VEGAS, Jan. 7 /PRNewswire-FirstCall/</b> -- Blending the latest technologies and offering unprecedented flexibility to consumers seeking the convenience of playing both Blu-ray Disc and HD DVD high-definition content, LG Electronics (LG), a leader in consumer electronics and mobile communications, today launched the groundbreaking "Super Multi Blue" Player at the 2007 International CES&reg; (Booth #8214, Central Hall, Las Vegas Convention Center).</p>

<p>Launching in the United States during the first quarter of 2007, this advanced dual-format high-definition disc player, LG model BH100, will be the first player on the market with the capability to play both next-generation disc formats, addressing the challenge of the current format war. The new player is ideally suited to LG's expanded lineup of Full HD 1080p plasma and LCD HDTVs, delivering best video possible in the highest display resolution format.</p>

<p>"We've developed the Super Multi Blue Player to end the confusion caused by the current competition between Blu-ray Disc and HD DVD. Customers are no longer forced to choose between the two formats," said Dr. Hee Gook Lee, president and chief technology officer of LG Electronics. "As Full HD TV is already gaining ground, we are hoping that the Super Multi Blue Player will play the trigger role in expanding and advancing both Full HD TV and high- definition DVD market volume together."</p>

<p>LG Electronics also offers flexibility to consumers in next generation optical disc drives for personal computers. (See separate news release) The GGW-H10N, also available in the first quarter of 2007, is compatible with both Blu-ray Disc and HD DVD formats. The Super Multi Blue 50GB drive is compatible with Blu-ray Disc, DVD, CD read/write and HD-DVD-ROM (read), offering the most universal unit available.</p>

<p>"We know our customers want high-definition content for their HDTVs. We also know a format war keeps people on the sidelines," said Mike Vitelli, senior vice president of merchandising at Best Buy. "With this new dual-format player, LG is offering a viable solution to this dispute. This is the kind of customer-focused approach that Best Buy looks to bring to our customers." Warner Home Video President Ron Sanders added, "We enthusiastically welcome LG's introduction of the Super Multi Blue high-definition disc player. This is a great first step towards resolving consumer confusion and uncertainty due to the two high-definition formats. The Super Multi Blue Player will allow studios to better meet consumers' growing demand for high-definition content in both the Blu-ray Disc and HD DVD formats."</p>

<p>"By providing a high-definition player that supports both Blu-ray Disc and HD DVD discs, LG is delivering a product that puts the customer first," said Randy Wick, senior vice president and general merchandise manager of consumer electronics at Circuit City Stores, Inc. "We applaud the LG customer-friendly approach, as it will serve to alleviate customers' confusion about the two formats."</p>

<p>Michael Ahn, president and CEO of LG Electronics North American Headquarters, echoed comments from Hollywood and leading retailers in support of LG's dual-format approach. "The American consumers' love affair with HDTV is now even stronger thanks to LG's marriage of Blu-ray Disc and HD DVD. What's more, our player upconverts standard DVDs to 1080i resolution, providing compatibility with consumers' existing movie libraries while improving the picture quality of those discs, too."</p>

<p>In addition to offering Full HD 1080p picture quality from high-definition discs, the player incorporates interactive functions based on BD-Java, which allows advanced menus and functions to be displayed over the video of Blu-ray discs. And, while the same level of advanced menu interactivity is not available while playing HD DVD discs, the powerful combination of Blu-ray Disc and HD DVD audio-video playback technologies is like no other on the market.</p>

<p>The unit supports various A/V formats, including MPEG-2, VC-1, H.264 video, MPEG1/2 audio, Dolby Digital, Dolby Digital+, DTS and DTS-HD audio, and includes multiple inputs/outputs such as HDMI out, component/composite video outputs, and optical/coaxial/discrete 5.1 channel audio outputs, among others.</p>

<p>The strikingly designed unit incorporates elegant and easy-to-use backlit touch sensor buttons along with an ergonomic remote control that delivers an effortless command of the next-generation home entertainment experience.</p>

<p>LG's Super Multi Blue Player (BH100), available to U.S. consumers during the first quarter of 2007, is expected to sell for about U.S. $1,199.</p>

