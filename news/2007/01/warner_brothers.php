				<p class="prtitle">Warner Home Video 2007 High Definition Slate Best Films of 2006 and 2007 and Classic Favorites on HD DVD
2007 International CES</p>

<p><b>LAS VEGAS--(BUSINESS WIRE)</b>--In 2007 Warner Home Video (WHV) will offer consumers a dynamic slate of titles on HD DVD including the critically acclaimed and highly anticipated Martin Scorsese gangster drama <I><B>The Departed</B></I> on February 13. <B><I>The Departed</I></B> is the proud recipient of six Golden Globe&trade; nominations this year including Best Motion Picture, Best Actor (Leonardo DiCaprio), Best Supporting Actor (Jack Nicholson, Mark Wahlberg), Best Director (Martin Scorsese) and Best Screenplay (William Monahan). <B><I>The Departed</I></B> will be available on HD DVD Combo for $39.99 SRP.</p>

<p>Since the inception of the format in April 2006, WHV has released 53 titles on the HD DVD format and has six of the top 10 selling HD DVDs for 2006 including the #1 selling title, <I><B>Superman Returns</B></I>.</p>

<p>Also coming to HD DVD will be the riveting thriller <B><I>The Wicker Man</I></B> which will be available on January 30 and includes an alternate ending not seen in theaters. The slapstick comedy <B><I>Beerfest (Unrated)</I></B> from the Broken Lizard comedy group will also arrive to stores on the 30th. Both HD DVD titles will be available for $28.99 SRP. All bonus materials on the standard DVD version will be included on the high definition versions.</p>

<p>Warner Bros. recent theatrical hit <B><I>Happy Feet</I></B> and the critically acclaimed films <B><I>Blood Diamond</I></B> and <B><I>We Are Marshall</I></B> will make their HD DVD debuts in 2007. Dates and specifics for these titles will be announced soon.</p>

<p>WHV will be opening the vaults and bringing out fan favorites and top franchises for all genres. Planned releases for 2007 include <B><I>The Matrix</I></B> franchise, all of the <B><I>Harry Potter</I></B> films and <B><I>Oceans 11</I></B> and <B><I>Oceans 12</I></B>. Other classic titles to be released in the first quarter of 2007 include <B><I>Bullitt</I></B> and <B><I>The Getaway</I></B> (1972) starring Steve McQueen. Also being released in 2007 is <B><I>Alexander Revisited: The Unrated Final Cut</I></B>.</p>

<p>Warner Home Video, which has the largest film library of any studio, will continue to release a wide variety of the most successful titles from its collection on HD-DVD and Blu Ray Disc to bring the high definition viewing experience home to more consumers than ever before. In 2006, Warner Home Video released <I>The Forbidden Planet Ultimate Collector's Edition HD DVD</I> and will continue to release Ultimate Collector's Edition HD DVDs and Blu-ray Discs to meet high definition and collector consumer needs.</p>

<p>Warner Home Video HD DVDs offer resolution six times higher than standard definition DVDs, as well as extraordinarily vibrant contrast and color and beautifully crisp sound. HD DVDs also provide a higher level of interactivity, with instant access to extra features via a seamless menu-bar where viewers can enjoy features without leaving or interrupting the film.</p>

<p>With operations in 90 international territories, Warner Home Video, a Warner Bros. Entertainment Company, commands the largest distribution infrastructure in the global video marketplace. Warner Home Video's film library is the largest of any studio, offering top quality new and vintage titles from the repertoires of Warner Bros. Pictures, Turner Entertainment, Castle Rock Entertainment, HBO Home Video and New Line Home Entertainment.<br />
