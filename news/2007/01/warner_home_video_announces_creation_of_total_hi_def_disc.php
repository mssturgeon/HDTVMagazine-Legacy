<p><I><CENTER>Home Video Leader Introduces Single Disc that Plays Both HD DVD and Blu-ray at Consumer Electronics Show in Las Vegas</CENTER></I></p>

<p><B>BURBANK, Calif.--(BUSINESS WIRE)</B>--Warner Home Video (WHV), distributor of the largest film library of any studio, today unveiled its groundbreaking "Total Hi Def" disc, which plays the HD DVD format on one side and the Blu-ray Disc format on the other, at a presentation hosted by Warner Bros. Entertainment Chairman and CEO Barry Meyer at the Consumer Electronics Show in Las Vegas.</p>

<p>"Warner Bros. has a history of embracing and promoting new technologies, from producing the first sound movies to being early pioneers in 1950s television to the creation and proliferation of DVDs," Meyer said. "We understand the benefits to our business-and to consumers-that technology affords us."</p>

<p>While consumers rave about the quality of high definition when they see it, a confusing format dilemma will result in slower consumer adoption of HD technology. Until now, consumers have been forced to choose one high-definition format-not knowing if their favorite titles would be produced in their specific format or how long that specific format would survive.</p>

<p>"The Total Hi Def disc is about giving consumers complete choice, providing creators and artists the greatest possible distribution of their work, and helping retailers thrive in the marketplace," said Kevin Tsujihara, President of Warner Bros. Home Entertainment Group. "By eliminating potential apprehension over formats, we believe this new disc could help consumers fully embrace the greatest home entertainment experience available."</p>

<p>If broadly adopted by the industry, the Total Hi Def disc would eliminate consumer confusion by including both formats on a single disc. Tested with leading manufacturers and replicators, the Total Hi Def disc would also simplify point of sale issues for retailers by reducing the shelf space required to carry two versions of the same content.</p>

<p>"The research clearly shows that people are thrilled with high-definition devices and the stunning home entertainment experience they provide," said Ron Sanders, President, Warner Home Video. "Now Total Hi Def provides the complete package with all the benefits of HD DVD and Blu-ray on a single disc."</p>

<p>Warner Bros. announced that discs in Total Hi Def will be available in the second half of 2007, and titles will be announced in a time frame consistent with the company's standard trade announcements for home entertainment titles. The physical structure of the disc is 1.2 mm the same as DVDs, HD DVD and Blu-ray discs. The Total Hi Def disc has the ability to contain both single layer and dual layers for both formats enabling either 15 GB or 30 GB on the HD DVD side and 25 GB or 50 GB on the Blu-ray side.</p>

