<p><b>LAS VEGAS, Jan. 7 /PRNewswire/</b> -- JVC today unveiled its 2007 line of digital entertainment products in conjunction with the 2007 International Consumer Electronics Show (CES). For 2007, JVC will field a line that positions the company at the forefront of advanced-technology design and engineering, delivering expanded performance capabilities, operational versatility, and unmatched ease of use to consumers.</p>

<p>JVC's 2007 display product line-up reflects its 10 years of HD-ILA technology innovation. Among its many product highlights, JVC will introduce two new Slim HD-ILA Rear Projection HDTVs and a full HD D-ILA home theater projector that delivers the industry's highest native contrast ratio. JVC will also debut its newest innovation in home audio, its networked Sophisti Home Entertainment Systems. JVC will expand its Everio hard drive camcorder lineup with the debut of the HD Everio, a new high definition hard drive camcorder that provides full HD video quality combined with the convenience of hard drive recording. In addition, JVC will also showcase additions to its Made for iPod(R) audio products, as well as new DVD recorders and players.</p>

<p>JVC expands its award-winning Everio hard drive camcorder family with the addition of the HD Everio GZ-HD7, a new high definition camcorder that provides up to five hours of full HD 1920x1080i recording onto a built-in 60GB hard drive. Designed to enable consumers to conveniently capture and share their memories in high definition without the need for removable tapes or discs, the HD Everio offers consumers the simplicity of a point-and-shoot camcorder combined with the features, technology and manual controls that appeal to the serious videographer.</p>

<p>JVC brings a new profile to the rear projection TV category with two new sets in its HD-ILA line that features dramatically reduced cabinet depth. Two screen sizes will be offered, 58 and 65 inches, with cabinet depths of 10.7 and 11.6 inches, respectively. The new shallow cabinet is made possible by the development of a new optical engine, which will be offered in two new HD-ILA televisions -- the 58-inch HD-58S998 and the 65-inch HD-65S998.</p>

<p>Both sets each use three native 1080p JVC D-ILA devices, LCOS (liquid crystal on silicon) technology developed by JVC that is renowned for its close pixel spacing, which delivers a bright, high contrast, smooth image. These devices are used in a new JVC-developed optical engine that combines a new concave mirror with the refracting lens to create a projection angle approximately 138 degrees wider and about 1.5 times greater than previous JVC technology. The wide projection angle reduces the projection distance by about 40 percent, allowing JVC to slim down the set considerably.</p>

<p>The new DLA-HD1 is a full HD front projector with a native contrast ratio of 15,000:1 -- the industry's highest native contrast ratio and a level that ensures outstanding black reproduction without sacrificing picture brightness since there is no iris mechanism.</p>

<p>The high native contrast ratio is achieved through the combined use of a new 0.7-inch full HD (1920 x 1080 pixels) D-ILA device and a new optical engine. Like all D-ILA-based JVC front projectors and rear projection televisions, the DLA-HD1 uses three D-ILA devices -- one each for red, green and blue color reproduction.</p>

<p>JVC is fielding a pair of networked home entertainment systems for 2007. JVC's Sophisti line includes two models, the DD-8 and the DD-3. Each feature a Network Media Player that serves as the nerve center of the home entertainment set up, allowing consumers to retrieve music files, movies, digital images and other digital files stored on their computer. Both also offer USB Host, allowing a wide range of digital devices to be connected directly to the system, including flash audio players, USB drives, digital cameras and card readers. The player is also DLNA (Digital Living Network Alliance) certified, which means that files can be accessed from other DLNA- compliant devices. The main unit also includes a DVD player, and built-in decoding of Dolby Digital, DTS and Dolby Pro Logic II soundtracks.</p>

