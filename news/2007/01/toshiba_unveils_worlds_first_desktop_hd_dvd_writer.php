<p>In addition, HD DVD provides massive data back-up capabilities for commercial applications. This functionality is ideal for archiving graphic, legal, financial and technical data, which require reliable, high-quality back-up solutions.</p>

<p>Featuring six times better resolution than standard DVD, the HD DVD format delivers an enhanced viewing experience with brighter colors and greater detail, using the same physical structure of standard DVD technology. As a result, the SD-H903A allows PC and CE manufacturers to make a smooth and affordable transition to high-definition offerings from existing DVD platforms. The SD-H903A features a Serial ATA (SATA) interface for superior performance.</p>

<p>Experts anticipate rapid growth in the high-definition market in the coming year. Since Toshiba launched the world's first HD DVD player in April 2006, more than 1.5 million HD DVD movies have been sold, reflecting the growing adoption of this format. Major movie studios have announced 400 titles worldwide in the HD DVD format. HD DVD has also been adopted by seven of the top 10 PC OEMs for high-performance notebook and desktop PCs.</p>

<p>"Toshiba is leading the transition to next-generation DVD technologies with an easy-to-use, low-cost solution for professionals and consumers looking to create and enjoy high-definition content, while still offering access to current audio CD and DVD libraries," said Scott Maccabe, vice president and general manager, Toshiba Storage Device Division. "HD DVD adoption is growing rapidly in all applications - from gaming to A/V editing. With its remarkable resolution, higher storage capacity and interactive offerings, HD DVD brings a superior media experience to consumers. Toshiba's new writer will greatly transform current PC offerings."</p>

<p>Toshiba's SD-H903A integrates a blue-violet laser diode to read and write HD DVD-R discs and supports high-density HD DVD-ROM discs, including high-definition movie and video images.</p>

<p>Toshiba will showcase its HD DVD offerings for IT and CE manufacturers Jan. 8-11 during the 2007 International Consumer Electronics Show (CES) at the Las Vegas Convention Center (booth 12832). For information on Toshiba's announcements and events at CES, please visit www.toshibastorage.com. Volume shipments of the SD-H903A are scheduled to start in February with OEM sampling in January.</p>

