<p>But the Play Big IN82 doesn't stop there. With video optimized brightness of 1,500 Max ANSI lumens - nearly twice as bright as most other home theater projectors are capable of - the IN82 is bright enough to deliver film-standard, D65K color accuracy in nearly any home theater, even with ambient light during a daytime movie or sporting event. The InFocus Color Gamut Calibrator and ISF Day & Night presets even allow installers to "lock in" optimized calibration settings for consumers, adding to the projector's incredible ease-of-use.</p>

<p>In addition, the Play Big IN82 full HD 1080p projector comes with integrated Pixelworks&trade; DNX&trade; 10-bit video processing technology and future-proof HDMI 1.3 with Deep Color&trade; support providing 1.07 billion colors, so every scene is vibrant, crystal clear images, allowing consumers to be immersed in the total experience of an amazingly smooth picture.</p>

<p>The Play Big IN82 is versatile, and accommodates any home entertainment environment with easy connectivity to nearly any consumer electronic device including: HD media players, HD cable and satellite receivers, and broadcast receivers, DVD players, computers and video game consoles.</p>

<p>"InFocus is known for its product innovation and dedication to delivering excellent, home entertainment projectors to our customers," said InFocus Vice President and acting Chief Operating Officer, Joseph O'Sullivan. "We are excited to introduce the Play Big IN82 1080p projector to our already impressive, award-winning line-up."</p>

