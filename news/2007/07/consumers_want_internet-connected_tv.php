<p><br />
El Segundo, Calif., Jul. 11, 2007-Nearly two-thirds of consumers want their televisions to link to the Internet, a sentiment that will help propel rapid sales growth for network-enabled consumer electronics devices in the coming years, according to iSuppli Corp.  </p>

<p>In line with consumers' desires, home networking is migrating beyond its PC-centric beginnings to incorporate a variety of entertainment-oriented consumer-electronics devices, including DVD recorders, cable modems, Digital Televisions (DTVs), multi-room Digital Video Recorders (DVRs), digital media adapters, set-top boxes and video game consoles. Shipments of these network-equipped devices, along with consumer PCs and home network bridges and gateways, are expected to rise to 732.9 million units by 2011, more than triple the 225.3 million that were shipped in 2006, according to iSuppli.</p>

<p> "The awareness and demand for media home networking is growing rapidly among consumers," said Steve Rago, principal analyst, networking/optical communications for iSuppli. "According to iSuppli's first-quarter 2007 consumer-demand survey, 61 percent of respondents 'agreed' or 'strongly agreed' that they wanted the ability to network the Internet to their televisions. Male respondents were even more favorable, with a 71 percent 'agreed' or 'strongly agreed' response."</p>

<p>The figure below presents iSuppli's unit shipment forecast for network-equipped consumer-electronics and related products.</p>

<p>By 2011, Wi-Fi will be the most common network physical interface for such products, followed by Cat 5, power line and coax. The interface technology of choice will be significantly influenced by geographic region.</p>

<p>By the end of 2006, 76 million home LANs were deployed worldwide. Yet, there is plenty of room for growth left in this market, with only 3 percent of global homes now having a LAN.</p>

<p>iSuppli also found:</p>

<p> </p>

<p>·          Internet Protocol Television (IPTV) and multi-room DVR demand is driving cable, satellite and telecom operators to consider a variety of new high-speed home networking technologies, ranging from coax (Moca, HPNA, Hana), to power line, to Wi-Fi (802.11n).  </p>

<p>·          Makers of televisions and other consumer electronics devices are incorporating Internet Protocol (IP)-based connectivity to enable access to both user-created content and to new Internet-based media portals.</p>

<p>·          Emerging regions, including India and South America, will experience only a slight expansion of home networking usage, despite having strong broadband growth. When deployed, home networking in this region will primarily be used to link notebook PCs to broadband gateways.</p>

