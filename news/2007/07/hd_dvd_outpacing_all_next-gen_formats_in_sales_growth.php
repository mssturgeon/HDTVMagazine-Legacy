<center><i>Promotional Group announces record HD DVD hardware and software sales increases from Q1-Q2 2007</center></i><br />
<br />

<p><B>LAS VEGAS, July 17 /PRNewswire/ </B>-- At the Entertainment Merchants Association (EMA) Home Media Expo 2007, the North American HD DVD Promotional Group today announced that overall HD DVD hardware sales were up 37 percent from Q1 to Q2 2007, while software sales experienced a 20 percent increase in growth. The data is based on NPD reports, Nielsen Netratings reports and point of sale data from the studios. During the same time-frame, overall Blu-ray hardware sales saw a 27 percent decline from Q1 to Q2, and Blu-ray software sales were down 5 percent.</p>

<p>Driven by major spring marketing efforts which brought standalone HD DVD players down to an industry first $299, dedicated HD DVD CE players experienced an astounding 183 percent quarterly increase. There are currently more than 180,000 dedicated HD DVD CE players in the market.</p>

<p>"The numbers are clear -- HD DVD is steadily gaining momentum and market share," said Ken Graffeo, executive vice president of HD strategic marketing for Universal Studios Home Entertainment, and co-president of the HD DVD Promotional Group. "With HD DVD CE players now at MSRP prices starting at $299 and with strong marketing campaigns around new HD DVD titles with web-enabled interactive features, we're continuing to raise the bar for the consumer experience."</p>

<p>Recent studies(1) have shown most consumers are basing their purchasing decisions on pricing. Benefiting from more than a decade of DVD technology advancements and improvements, HD DVD hardware pricing has already dropped from $499 to $299 since the first players were introduced last year as a result of manufacturing efficiencies, while still maintaining a consistent consumer experience.</p>

<p>"With the total number of titles available for each format differing by only 20-30 titles at this time, the real-world gap in content between the two formats is in actuality not as large as many would perceive," said Paul Erickson, market analyst with IMS Research. "Consumers in the US and Europe continue to show the greatest sensitivity to price, rather than content or branding, in their purchase decision for standalone high-definition players."</p>

<p>With titles like "300" coming later this month from Warner Home Video and "Heroes: Season 1" to be released in August from Universal Studios Home Entertainment, HD DVD owners will have close to 1,000 titles worldwide to choose from by the holidays.</p>

