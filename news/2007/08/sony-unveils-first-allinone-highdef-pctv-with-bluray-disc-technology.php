<p>The model features a built-in 1.3 megapixel camera and an echo-cancelling microphone for crystal-clear video messaging-great for staying in touch with family and friends. A broadband connection is required.</p>

<p>"The LT model has everything you need- it's a PC and HDTV set in one breathtaking device," said Mike Abary, senior vice president of VAIO product marketing at Sony Electronics. "It's the ultimate showstopper for media lovers who appreciate high-def performance and cutting-edge technology in a saving space design."</p>

<p>The unit packs a powerful punch. With an Intel(R) Core(TM) 2 Duo processor, 2GB of RAM and a discrete graphics card, it can run demanding applications simultaneously such as graphics-intensive games and HDTV.</p>

