<p>Featuring a floating glass design, the VAIO(R) LT HD PC/TV serves as a computer entertainment center, where you can watch and record analog, digital and cable television programming, including premium HD channels. A Cable CARD(TM) is required.</p>

<p>Part of a series, the new LT PC/TV comes in multiple configurations, including a standard and an HD model. The high-definition version features a Blu-ray Disc(TM) optical drive so you can enjoy high-definition movies, as well as record, store and play back personal content on high-capacity BD media (up to 50 GB on a single disc).</p>

<p>The unit features a 22-inch diagonal WSXGA+ widescreen display, with Sony's XBRITE-HiColor(TM) LCD technology. It displays images in razor-sharp detail, whether watching TV, enjoying family photos or simply surfing the web.</p>

<p>The LT PC/TV is ideal for anywhere space is at a premium. A unique feature in a PC, the LT model has a mounting capability that allows users to attach a VESA-compatible mount (sold separately) to the unit and hang it on the wall of your bedroom, kitchen, office or attach to your desk.</p>

<p>Since the LT PC/TV can be used for television viewing as well as computing functions, an A/V power button lets you shut down the TV function, while your PC continues to run in the background. This lets you quickly turn the TV off and on without waiting for the PC to shut down or boot up.</p>

<p>The model features a built-in 1.3 megapixel camera and an echo-cancelling microphone for crystal-clear video messaging-great for staying in touch with family and friends. A broadband connection is required.</p>

<p>"The LT model has everything you need- it's a PC and HDTV set in one breathtaking device," said Mike Abary, senior vice president of VAIO product marketing at Sony Electronics. "It's the ultimate showstopper for media lovers who appreciate high-def performance and cutting-edge technology in a saving space design."</p>

<p>The unit packs a powerful punch. With an Intel(R) Core(TM) 2 Duo processor, 2GB of RAM and a discrete graphics card, it can run demanding applications simultaneously such as graphics-intensive games and HDTV.</p>

<p>It also ships with a roomy hard drive and allows for expandable hard drive capacity, providing plenty of space for HD recording. The unit comes pre-installed with Genuine Windows Vista(R) Ultimate.</p>

<p>For a tidy interior design, the new model incorporates built-in wireless 802.11n LAN technology. You can position it virtually anywhere in your home without worrying about messy network cables, and then access the internet, your email and your home network with greater wireless speed and range than before.</p>

<p>A wire organizing tab on the back of the chassis ensures that wires are discreetly routed, while ample ports are conveniently located on the sides. Wired connections are further minimized with the included fold-up wireless keyboard, mouse and remote control.</p>

<p>The LT standard model will start at about $1,900, while the LT HD model with a Blu-ray Disc(TM) optical drive will go for around $2,900. The VAIO LT series will be available online at http://www.sony.com/pr/lt. They will also be sold at Sony Style(R) stores, as well as at military base exchanges and select retailers around the country starting in October.<br />
