				<p><strong>DisplaySearch Reports July LCD TV and LCD Monitor Panel Shipments Establish Record Highs</strong><br />
 <br />
AUSTIN, TEXAS, August 28, 2007--DisplaySearch today released its July LCD panel shipments results. Specifically, the firm announced that LCD TV panel shipments hit an all-time high with 7.2 million units shipped, up 6% M/M and 72% Y/Y. Although LCD monitor panel shipments have been growing in single digits on a sequential basis since April, July results established a record high of 16.1 million units, up 1% M/M and 35% Y/Y. </p>

<p>"Despite worries that US consumer spending might decline due to weakness in the housing market and recent credit crunch, July was a strong month for the LCD industry-indicating that there is still a strong demand for LCD TVs and notebook PCs," noted Jin Kim, DisplaySearch's Director of TFT LCD Market Research. "While there were concerns of LCD TV set inventory build-up in June and July, LCD TV panel shipments continued to post strong growth in July. Overall, most producers involved in the three large-area LCD applications supply chain, including panel suppliers, OEMs and major brands, expect strong retail demand to continue for large area LCDs into the holiday shopping season," Kim added.</p>

<p>In terms of overall large panel shipments in July, Samsung Electronics (SEC) regained the #1 position on a shipment basis with a 20.6% share in July 2007. SEC had fallen to the #3 position in June due to weak notebook panel shipments, but in July led the notebook segment, displacing LG.Philips LCD (LPL) who led for 14 consecutive months. AUO (AU Optronics) edged out LPL for the #2 position with a unit market share of 19.8%, while #3 LPL closely chased the leaders with 19.7% unit share.</p>

<p><strong>July LCD TV Panel Shipment Highlights and Outlook</strong><br />
LCD TV module shipments increased 72% Y/Y in July due to strong growth in large LCD TV sizes. The most popular LCD TV module size continued to be 32", with a 36.2% shipment share in July, followed by 26" at #2 with 13.0% shipment share. Rounding out the top three was 37" with 11.3% unit share. Of note, since April 2004, 40" has led the battle against 42", but the tide has recently turned. Beginning in June 2007, the 42" share of LCD TV module shipments beat 40", 8.3% to 6.7%, respectively. In July, that gap slightly widened with 42" at 9.0%, versus 7.3% for 40". The reason is due to the success of second tier TV brands such as Vizio, who captured the #1 spot with 12.1% market share in North America in LCD TV unit shipments in Q2'07 (based on the recently announced Quarterly Global TV Shipment and Forecast Report, Q3'07 Datatables). Growth was most impressive for 52" up with 2476% Y/Y growth, followed by 47" up with 1204% Y/Y growth. </p>

<p>AUO captured the #1 position for LCD TV panel shipments, with a 22.1% share followed by LPL and Samsung with shares of 21.3% and 18.9%, respectively.</p>

<p>AUO recorded the fastest growth at 147% Y/Y, CPT grew a significant 100% Y/Y and CMO grew 88% Y/Y. Almost all LCD TV module suppliers recorded double-digit Y/Y growth including AUO, BOE, CMO, CPT, LPL, Samsung and Sharp. The top five suppliers (AUO, LPL, Samsung, CMO and Sharp) continued to maintain a 90% shipment share, which began in December 2006.</p>

<p>Looking forward, DisplaySearch has upgraded its annual outlook as the result of strong performance in June and July and a robust August outlook as LCDs continue to take share from competing technologies. DisplaySearch now expects LCD TV panels to rise 48% Y/Y in 2007 to 80.4M panels.<br />
 </p>

<p><strong>July LCD Monitor Panel Shipment Highlights and Outlook</strong><br />
LCD monitor panel shipments were up 2% M/M and 35% Y/Y to a record-breaking 16.1 million units. Since April, LCD monitor panel shipments have been growing at only single-digits sequentially, but have experienced robust growth Y/Y. SEC was the largest supplier of LCD monitor panels in July capturing 17.3% unit share, followed by AUO with 16.5% and LPL rounding out the top three with 13.9%. All three of the top suppliers experienced M/M declines in July, while suppliers such as BOE, Chi Mei Optoelectronics (CMO), Chunghwa Picture Tubes (CPT), InfoVision and Innolux posted high single-digit gains. 17.0" LCD monitor panels took the #1 position with 27.5% of unit shipments in July, followed by 19" Wide with 23.9% and 19.0" with 14.6% unit share. Gaining considerable momentum was 22" Wide; a 5.0% unit share in January more than doubled to 11.2% in July.</p>

<p>"Typically, back-to-school sales have had a positive impact on LCD monitor panel shipments in July and August. The trend of purchasing a desktop PC with an external LCD monitor is waning and instead is shifting toward purchases that include a notebook PC with an external monitor," Kim concluded.</p>

<p>LCD monitor panels are expected to rise 24% Y/Y in 2007 to 174M panels, although Q2'07 may prove to be the peak quarter as a number of panel suppliers divert capacity in 2H'07 to seasonally stronger TV panels or higher margin notebook panels.</p>

<p>DisplaySearch tracks monthly TFT LCD shipments, which are available in the Monthly TFT LCD Shipment Database. A free information service, PanelTrack, can also be viewed at www.displaysearch.com/free/paneltrack. </p>
