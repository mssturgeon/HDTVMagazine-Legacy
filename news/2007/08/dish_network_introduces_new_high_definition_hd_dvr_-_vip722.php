<p><B>ENGLEWOOD, Colo., Aug 16, 2007 (PrimeNewswire via COMTEX News Network)</B> -- EchoStar Communications Corporation (Nasdaq:DISH) and its DISH Network(r) satellite TV service today announced the introduction of its newest high definition (HD) DVR, the ViP722(tm). The ViP722 is an advanced version of the company's award-winning ViP622 DVR(tm) and complements DISH Network's extensive lineup of HD programming, which was expanded to 38 national channels earlier this week.</p>

<p>"Over the years, DISH Network has maintained a leadership position in the pay-TV industry by designing and manufacturing cutting-edge, sought-after products that offer unique benefits to our customers, and the ViP722 HD DVR is no exception," said Mark Jackson, president of EchoStar Technologies Corporation. "Our industry-leading DVRs, combined with our affordable DishDVR Advantage Package, allow our customers to control their TV viewing experience and choose when and how they want to enjoy their favorite shows -- and that's what makes our customers so satisfied."</p>

<p>Similar to the ViP622, the ViP722 is a dual-tuner DVR receiver that powers two rooms, one in HD and the other in standard definition (SD). Compared to HD DVRs offered by other pay-TV providers, the ViP722 features expansive storage capacity (500 GB hard drive) and the option of recording 55 hours of HD programming in MPEG4, 350 hours of SD programming, and more than 100 hours of movies and shows with DISH On Demand -- for a total of up to 500 hours of programming. The receiver supports Dolby Digital 5.1 surround sound, and along with the ViP622 is the only DVR in the industry with a true 30-second skip feature -- allowing subscribers to watch television commercial-free. It also includes an IP call-back feature ideal for customers who don't have a phone line, but still want the ability to order Pay-Per-View programming, among other functions.</p>

<p>Those looking for additional DVR recording capacity just in time for football season and fall season premieres can take advantage of the external hard drive feature now available on the ViP722 and ViP622. The external hard drive feature allows customers to expand their DVR recording capacity and create a virtually unlimited library of favorite TV shows, movies and sports programming. By connecting an off-the-shelf hard disk drive (up to 750 GB) to the DVR through one of two USB 2.0 ports, customers can transfer, store and play HD and SD content saved to the external hard drive. Earlier this year, the DVR video archiving feature was awarded an International CES Innovations 2007 Design and Engineering Award on behalf of the Consumer Electronics Association.</p>

<p>The ViP722 is available for free to qualifying new DISH Network customers, and the external hard drive feature has a one-time household activation fee of $39.99.</p>

<p>The ViP722 and external hard drive feature complement DISH Network's industry-leading DishHD, which the company continues to enhance with channels that exemplify the top-quality HD programming consumers enjoy. DISH Network is the first pay-TV provider to offer Discovery Channel HD, TLC HD, Animal Planet HD and The Science Channel HD, which DishHD customers now have access to in addition to MHD and Golf/Versus HD. With these exciting additions -- plus more planned for September including The History Channel HD on Sept. 5 -- DISH Network will continue to offer the largest national HD lineup in the United States, now available free for six months to new DishHD subscribers.</p>

<p>For more information about DISH Network, HD programming or the ViP722, call 1-800-333-DISH (3474), visit www.dishnetwork.com, or visit your local DISH Network retailer.</p>

