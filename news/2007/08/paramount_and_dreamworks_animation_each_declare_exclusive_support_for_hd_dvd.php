<p><B>Los Angeles, CA, August 20, 2007</B> - Paramount Pictures, a unit of Viacom Inc. (NYSE: VIA and VIA.B) and DreamWorks Animation SKG (NYSE:DWA), each announced today that they will exclusively support the next-generation HD DVD format on a worldwide basis. The exclusive HD DVD commitment will include all movies distributed by Paramount Pictures, DreamWorks Pictures, Paramount Vantage, Nickelodeon Movies and MTV Films, as well as movies from DreamWorks Animation, which are distributed exclusively by Paramount Home Entertainment.</p>

<p>The companies each said that the decision to distribute exclusively in the HD DVD format resulted from an extensive evaluation of current market offerings, which confirmed the clear benefits of HD DVD, particularly its market-ready technology and lower manufacturing costs. Paramount Home Entertainment will launch its exclusive HD DVD program with the release of the blockbuster comedy hit "Blades of Glory" on August 28th and follow with two of the biggest grossing movies of the year "Transformers" and "Shrek the Third". These three titles alone represent more than $1.5 billion in box office ticket sales worldwide.</p>

<p>"The combination of Paramount and DreamWorks Animation brings a critical mass of current box office hits to consumers with a line-up of live action and animated films that are perfect for HD DVD," stated Brad Grey, Chairman and CEO of Paramount Pictures, which is currently the leading studio in domestic box office. "Part of our vision is to aggressively extend our movies beyond the theater, and deliver the quality and features that appeal to our audience. I believe HD DVD is not only the affordable high quality choice for consumers, but also the smart choice for Paramount."</p>

<p>"We decided to release "Shrek the Third" and other DreamWorks Animation titles exclusively on HD DVD because we believe it is the best format to bring high quality home entertainment to a key segment of our audience - families," stated DreamWorks Animation CEO, Jeffrey Katzenberg. "We believe the combination of this year's low- priced HD DVD players and the commitment to release a significant number of hit titles in the fall makes HD DVD the best way to view movies at home."</p>

<p>With the rapid increase of HD TV screens in households, and audiences wanting to enjoy the total entertainment experience, HD DVD has emerged as the most affordable way for consumers to watch their movies in high definition. In addition to pristine quality, HD DVD also offers consumers the chance to personalize the movie-watching experience, to interact with their movies and even to connect with a community of other fans.</p>

<p>Paramount Home Entertainment will issue new releases day and date as well as catalog titles exclusively on HD DVD. Today's announcement does not include films directed by Steven Spielberg as his films are not exclusive to either format.</p>

