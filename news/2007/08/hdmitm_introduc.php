				<p class="prtitle">HDMI(TM) Introduces First-Ever HDMI Developers Conference to Educate Engineers and Product Designers</p>

<center><i>HDMI Teams with China Video Industry Association to Educate Consumer Electronics and PC Manufacturers in China, Japan, Korea and Taiwan</i></center><br />
<br />

<p><B>SUNNYVALE, Calif, Aug. 20 /PRNewswire/</B> -- HDMI Licensing, LLC, the agent responsible for licensing the High-Definition Multimedia Interface(TM) (HDMI(TM)) specification, today announced that it has teamed up with the China Video Industry Association (CVIA) to sponsor the first-ever HDMI Developers Conference in Shenzhen, China on September 12, 2007. CVIA members include China's largest manufacturers of digital televisions, digital movie/broadcasting, high-definition optical disc, set-top box and information technology equipment and components.</p>

<p>The continued rapid adoption of HDMI as the de facto standard connector for high-definition consumer electronics (CE) devices, including TVs, set-top boxes, DVD players and A/V receivers, has created a demand for a developers conference that will help existing and new CE and personal computer (PC) manufacturers to successfully implement advanced HDMI features and establish best practices. Attendees -- design engineers and product planners from the largest CE and PC manufacturers in China, Japan, Korea and Taiwan -- will learn how to successfully implement HDMI 1.3-enabled features into their product lines.</p>

<p>"We worked closely with the CVIA to develop a curriculum that will help manufacturers gain valuable insight into the HDMI specification," said Les Chard, president of HDMI Licensing. "We are thrilled that leading companies have agreed to participate in this important conference and know that attendees will gain the knowledge to successfully implement HDMI functionality into all levels of their CE and PC product lines."</p>

<p>Sessions in the morning will focus on market and business trends pertaining to HDMI, and will feature presentations from executives from the CVIA, HDMI Licensing, LLC, Sino-Market Research, Ltd, Best Buy Corporation and TCL Corporation. Afternoon sessions will focus on technical topics from Platinum Sponsors of the conference. Platinum sponsors include: Agilent Technologies, Inc. Digital Content Protection, LLC, Quantum Data, Silicon Image, Inc. Simplay Labs, LLC, and Tektronix. Sessions in the afternoon are designed to help manufacturers bring products to market with the most advanced HDMI features and capabilities possible, including many of the features enabled by version 1.3 of the HDMI specification.</p>

<p>For more information about the HDMI Developers Conference, or if you are interested in becoming a sponsor please visit http://www.hdmi.org/devcon/</p>

<p><br />
<B>About HDMI Licensing, LLC</B></p>

<p>HDMI Licensing, LLC, a wholly owned subsidiary of Silicon Image, Inc., is the agent responsible for licensing the HDMI Specification, promoting the HDMI standard and providing education on the benefits of HDMI to retailers and consumers. The HDMI specification was developed by Hitachi, Matsushita (Panasonic), Philips, Silicon Image, Sony, Thomson and Toshiba as the digital interface standard for the consumer electronics market. The HDMI specification combines uncompressed high-definition video and multi-channel audio in a single digital interface to provide crystal-clear digital quality over a single cable. For more information about HDMI, please visit http://www.hdmi.org/</p>

