				<p class="prtitle">Nielsen Releases High Definition TV (HDTV) Household Estimates for Total U.S. and Local People Meter Markets</p>

<center><i>DMA Media Related Universe Estimates Also Reported</i></center><br />
<br />

<p><B>NEW YORK, Oct. 30 /PRNewswire/</B> -- The Nielsen Company today announced that 13.7% of TV households in the U.S. are equipped with an HD television and HD tuner capable of receiving signals in HD (HD Capable), while 11.3% are equipped with an HD television and HD tuner and receive at least one HD network or station (HD Receivable).</p>

<p>Los Angeles has the highest penetration of HD Capable homes (20.4%) and New York has the highest penetration of HD Receivable homes (17.5%). Nielsen also reports that among U.S. Hispanic or Latino households, 10.4% are HD Capable and 8.2% are HD Receivable. Among African-American households, 8.1% are HD Capable and 6.9% are HD Receivable.</p>

