<center><i>Only Blu-ray Player to Feature Final Standard Profile</i></center><br />
<br />

<p><B>LOS ANGELES CA (October 30, 2007)</B> - Panasonic, a leader in High Definition technology, announced today the introduction of the DMP-BD30, the next generation High Definition 1080p Blu-ray Disc player. The DMP-BD30 is the first Blu-ray player to be introduced with Final Standard Profile, which adds a variety of new and enhanced features to the Blu-ray arena and one that separates the Panasonic Blu-ray player from the rest of the field. Also unique to the DMP-BD30 is the inclusion of an SD Memory Card slot for playback of High Definition content recorded in the AVCHD format. The SD slot also allows for viewing of digital still images recorded to an SD Memory Card.</p>

<p>Final Standard Profile is an advanced function added to the Blu-ray standard, which opens the door to new functions such as Picture-in-Picture (which displays a second image in a sub window) and Audio Mixing (allows the consumer to switch the sound between the main and sub windows).</p>

<p>"The DMP-BD30 will contribute greatly to Blu-ray's mounting lead over the competing format," said Gene Kelsey, Vice President, Panasonic Entertainment Group. "Panasonic's adoption of the Final Standard Profile adds a whole new dimension to the entertainment experience. For example, when the added value features inherent to the Final Standard Profile are incorporated into a Blu-ray movie, the viewer could have a myriad of entertainment options. One of the more intriguing aspects of the Final Standard Profile is the Picture-in-Picture feature that would allow the movie fan to access a variety of entertainment enhancements, such as having the director or an actor pop up to discuss a scene you are watching, or with an animated movie, you might see the actor performing their character's voice over, all while still watching the movie. Not only do these features give Panasonic a strong advantage in the high definition market, but they provide the movie community with numerous opportunities to embellish the viewing experience with additional creative elements."</p>

<p>With an SRP of $499.95, the DMP-BD30 also features a myriad of technology advances, including Deep Color Compatibility, and HDMI 1.3B, that bumps the step gradation from 8-bit 256 all the way up to 12-bit, 4,096 step gradation. To further enhance the viewing experience, the DMP-BD30 also provides 1080/24p playback, so the consumer can enjoy the same 24-fps (frames per second) reproduction as the original movie. This eliminates the need to utilize 3.2 pull down, a process to convert 24-fps images to 60-fps, resulting in a smoother picture.</p>

<p>The inclusion of a multi-function SD Card slot is another new addition to the Panasonic Blu-ray player. Coupled with the AVCHD codec, the DMP-BD30 allows for images recorded on a high capacity HD SD card to be outputted directly from the player's HDMI terminal in their original 1080p form. To further benefit the user, the DMP-BD30 provides an AVCHD Direct Navigator function that makes it easy to search for particular scenes. The player can also play back JPEG still images on an SD card, such as those recorded with a Panasonic Lumix digital camera. The DMP-BD30 converts the images to 1920x1080 resolution, ideal for viewing on a1080p HD Plasma and output them through the HDMI terminal.</p>

<p>Like its predecessor, the DMP-DB30 features the EZ-Sync&trade; HDAVI Control that allows the consumer to operate their Panasonic home theater system with one remote. With one touch of the EZ-Sync button, all the components turn on, the correct TV input is chosen, the TV's built-in speakers are muted and the home theater starts playback.</p>

<p>"Panasonic's commitment to excellence in entertainment and technology is evident in the establishment of Panasonic Hollywood Labs, where a great deal of research went into the development of Blu-ray," added Kelsey. "PHL has become one of the major centers for the authoring of Blu-ray titles and works closely with studio engineers in developing High Definition compression technologies."</p>

