<p>"As families gather together this holiday, it's the perfect time to launch a new low-priced, high-value Xbox 360 that plays games, TV shows and music for everyone to enjoy," said Jeff Bell, corporate vice president of global marketing, Interactive Entertainment Business at Microsoft. "In addition to offering an incredible all-in-one package for families to get right into the fun, the Xbox 360 Arcade system features the industry-leading Family Settings, which allow parents to control what their kids are watching and playing - and we know how important that control is to families around the world."</p>

<p>Karen Dodge, senior vice president and chief merchandising officer at Toys "R" Us, added, "We are excited to offer this new gaming experience to our customers -- children and families -- who can now enjoy the fun of Xbox 360 together. Many of this holiday season's hottest items provide Internet connectivity, and with the online entertainment options available through Xbox LIVE(R), Xbox 360 Arcade offers families a great mix of online content and traditional gaming in one console."</p>

<p>The news of Xbox 360 Arcade comes as part of a broader initiative by Microsoft to bring the Xbox 360 experience to families everywhere. Microsoft also announced today that it is significantly expanding its catalog of high- and standard-definition family fun content that is available on demand direct to the consumer's living room. This includes the addition of everyone's favorite characters such as Bugs Bunny and Daffy Duck from Warner Bros., which will be delivering the first ever "Looney Tunes" cartoons for download on Xbox 360, starting today. In addition, Nickelodeon is adding three new shows to its already large library of more than 300 episodes of TV shows on Xbox LIVE, Microsoft's premier online gaming and entertainment service, with the inclusion of "Blue's Clues," "The Backyardigans" and "iCarly." "SpongeBob SquarePants Underpants Slam(TM)" (THQ Inc.) and "SHREK-N-ROLL(TM)" (Activision) games will also be available exclusively on Xbox LIVE Arcade, the place to download games for Xbox 360 over Xbox LIVE, adding more fun for everyone in the family.</p>

<p>Microsoft's commitment to family entertainment is complemented by the largest next-generation library of "E"- and "T"-rated games, more than 200 in all, available at retailers nationwide this holiday, including "BEE MOVIE(TM) GAME" (Activision), "Guitar Hero III(R): Legends of Rock" (Activision), "Naruto: Rise of a Ninja" (UbiSoft Entertainment), "Scene It? Lights, Camera, Action" and "Viva Pinata(R): Party Animals."</p>

