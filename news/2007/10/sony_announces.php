<p><B>FOSTER CITY, Calif., Oct. 18 /PRNewswire-FirstCall/</B> -- Sony Computer Entertainment America Inc. (SCEA) today announced plans to introduce a new 40GB model of its PLAYSTATION(R)3 (PS3(TM)) computer entertainment system. Beginning November 2nd, to further enhance the HD entertainment experience, the new 40GB PS3 model will come bundled with the blockbuster movie Spider-Man(TM) 3 Blu-ray Disc(TM) (BD) from Sony Pictures Home Entertainment, and will be available in North America for a suggested retail price of $399 (USD/CND). The company also announced that effective immediately, the current 80GB PS3 model will be available in North America for $499 (USD/CND), $100 below the original launch price.</p>

