				<p class="prtitle">HDMI Licensing Introduces HDMI Trademark and Logo Usage Guidelines for Advanced Consumer Electronics Features</p>

<center><i>Trademark and Logo Usage Guidelines Provide Manufacturers with Common Language to Communicate Advanced Features</i></center><br />
<br />

<p><B>SUNNYVALE, Calif., Oct. 17 /PRNewswire/</B> -- HDMI Licensing, LLC, the agent responsible for licensing the High-Definition Multimedia Interface (HDMI) specification, today announced the release of Trademark and Logo Usage Guidelines creating a consistent way for manufacturers to describe the HDMI-enabled functionality of their products. By providing a consistent set of terminology for HDMI-enabled features, the Trademark and Logo Usage Guidelines provide manufacturers with effective ways to communicate these features to consumers, giving consumers consistency and clarity of information when making an HD purchase decision.</p>

<p>To ensure that consumers are given the product information that they want and need, manufacturers are now required to include specific HDMI features enabled in their product along with the HDMI version number (e.g. as "HDMI 1.3"). This enhancement is necessary because an HDMI version number does not require functionality, but specifies a list of optional features for manufacturers to select depending on their target market. Consumers will now have the necessary descriptive Information they need to understand HDMI functionality of specific products that take advantage of the capabilities of specific HDMI versions.</p>

<p>In addition, for each of the features, the guidelines establish minimum functionality that the device must deliver to the user, thus ensuring that consumers buying these products will receive a consistent, high-quality experience. With these guidelines, manufacturers, retailers and installers will be able to more accurately convey to consumers HDMI-enabled features -- such as Deep Color functionality, x.v. Color(TM) extended color gamut, and advanced audio formats -- available in high-definition consumer electronics (CE) and PC devices.</p>

<p>With the new Trademark and Logo Usage Guidelines, consumers will find it easier to build home theater systems that deliver the latest features. Manufacturers will share a more consistent terminology to communicate their products' HDMI features. Retailers will have a consistent and understandable sales message for their customers and sales associates. Installers will have a simple way to specify feature-compatible components for high-definition home theater installations.</p>

<p>"Our goal with the release of the HDMI Trademark and Logo Usage Guidelines is to provide the CE industry with a common language to explain HDMI functionality, and to ensure that the new terms will clearly describe the performance of each feature to the consumer," said Les Chard, president of HDMI Licensing. "To further support manufacturers, retailers and installers in helping consumers make better informed decisions, we have created a map of HDMI features with terminology that is easy to communicate. With the new guidelines, the industry now has the means to do that more effectively."</p>

<p>Each revision of the HDMI specification has added new capabilities, but these are typically optional, giving manufacturers the ability to best match features with consumer demand. The Trademark and Logo Usage Guidelines state that manufacturers must specify which HDMI features are enabled when referencing the version such as "Supports HDMI 1.3" or "HDMI 1.3 compliant." An acceptable use, for example, is "HDMI (V.1.3 with Deep Color, x.v.Color)."</p>

<p>For each feature, the guidelines specify a minimum level of functionality that must be met by the device in order to use the terminology. For example, a display device described as supporting Deep Color must be capable of accepting a Deep Color signal (i.e., >8 bit color depth), processing the signal such that the resulting stream is greater than 8 bit color depth upon delivery to the display, and having a display that renders color bit depth of greater than 8 bits per color.</p>

<p>HDMI Adopters are required to implement the Trademark and Logo Usage Guidelines on all products that are initially shipping after October 17, 2008, and are instructed to use "commercially reasonable efforts" to comply with the guidelines as of October 17, 2007.</p>

<p>The HDMI Trademark and Logo Usage Guidelines document and additional information are available on the HDMI Licensing Web site Branding Resource Center at http://www.hdmi.org/manufacturer/trademark_logo_pub.aspx.</p>

