<B>Methodology</B></p>

<p>Nielsen Media Research conducted a telephone survey with 511 respondents from June 28, 2007 until July 10, 2007 to learn how satisfied HD owners are with their TV set as well as the HD programming they receive. Respondents were previously identified through a telephone omnibus survey as HDset owners who also receive HD content.</p>

