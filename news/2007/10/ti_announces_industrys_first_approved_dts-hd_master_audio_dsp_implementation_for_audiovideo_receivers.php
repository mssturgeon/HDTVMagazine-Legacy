-- "Onkyo takes advantage of TI's complete software and hardware solutions, which includes the industry's first HD decoders required to support next-generation DVD formats, so we can concentrate on developing differentiated features to deliver unique, compelling AVR products," said Miwa Mori, software design manager, Onkyo.<br />
-- "TI continually improves its audio DSP solutions with the highest performance and fully certified decoder software, empowering Yamaha to quickly bring to market our flagship RX-Z11 AVR, the first AVR capable of decoding 192 kHZ DTS-HD master audio," said Akihiro Muramatsu, department manager, Yamaha.</p>

