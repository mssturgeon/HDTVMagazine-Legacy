<p>"We're pleased to offer the consumer a lower price point without sacrificing the core technology components that make PS3 the most advanced high-definition entertainment system available. Every PS3 comes with a Blu-ray drive, HDMI output, an integrated Wi-Fi connection, Cell Broadband Engine and a built-in hard-drive," said Jack Tretton, President and CEO, SCEA. "This holiday season we'll be able to offer attractive retail pricing with a broad portfolio of outstanding games including Ratchet & Clank(R) Future: Tools of Destruction(TM), THE EYE OF JUDGMENT(TM), Uncharted: Drake's Fortune(TM), Heavenly Sword(TM), Call of Duty(R) 4: Modern Warfare, Assassin's Creed(TM), Haze(TM) and RockBand(TM)."</p>

<p>The new 40GB PS3 will no longer play PlayStation(R)2 titles, reflecting the availability of a more extensive line-up of PS3 specific titles. Consumers looking for backwards compatibility can take advantage of the limited PlayStation 2 backwards compatibility of the 80GB PS3.</p>

