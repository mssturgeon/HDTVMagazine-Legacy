<p><B>CHARLOTTE, N.C.--(BUSINESS WIRE)</B>--SPEED will make its move to High Definition in 2008, beginning Feb. 7 with 100 hours of NASCAR on SPEED HD from Daytona Speedweeks.</p>

<p>"With the Gatorade Duel 150's on SPEED, the NASCAR Craftsman Truck Series race, NASCAR RaceDay and all of the other programming SPEED will deliver surrounding the 50th Anniversary of the Daytona 500, this is one of our most visible times of the year for the network and the perfect time to launch our move to HD," said SPEED President Hunter Nickell. "SPEED already offers some of the most action-filled programming on television and the move to HD in 2008 enhances all of it exponentially."</p>

<p>Topping the 70-million U.S. household mark and coming off four consecutive years of ratings growth in 2007, the move to High Definition is the next step in the evolution of a network that has added more than 30 million homes since being fully acquired by Fox Cable Networks in 2001.</p>

<p>"SPEED is now one of the most important and popular of all the national cable sports networks, so it's somewhat inevitable that we provide our many partners and their customers with this HD companion," said Michael Biard, Senior Vice President of Affiliate Sales and Marketing for Fox Cable Networks.</p>

<p>In addition to its season-long, at-track coverage of NASCAR, with programs including NASCAR RaceDay, Trackside, NASCAR Victory Lane, Tradin' Paint, NASCAR Live!, NASCAR Performance and Go or Go Home, SPEED also will explore opportunities to bring other racing series and special events to viewers in HD in 2008.</p>

<p>"Over the course of the 2008 season, SPEED will be transitioning all of its event programming to HD," said Rick Miner, SPEED Senior VP of Production and Network Operations, who is shepherding the project. "We already are in discussions to design and commission the development of remote HD production facilities that will be in full use in 2008."</p>

<p>In addition to its HD programming surrounding the 50th Anniversary of The Great American Race from Daytona, SPEED also will be ready to launch new seasons of its popular automotive and motorcycle lifestyle programming in HD, including PINKS, PINKS All Out and Super Bikes!</p>

<p>In a move that began earlier this summer, SPEED programming is now commissioned in true 16:9 HD.</p>

<p>In addition to the bold moves on the television side, SPEED's interactive division will raise the bar as well, with a re-launch of a completely re-tooled SPEEDtv.com slated for early February. The new site will feature dramatic across the board improvements in depth and timeliness of motor sports news and information, delivered through a new wide-screen format that is optimized for easy navigation, interactivity with mobile and other applications, social networking and customization. Registered SPEED Insiders (www.insider.speedtv.com) will get a sneak peek at the new SPEEDtv.com in early in January.</p>

