<p class="prtitle">RADIOSPIRE NETWORKS ANNOUNCES AVAILABILITY OF ITS AIRHOOK&trade; CHIPSET FOR IN-ROOM WIRELESS HD</p>
 
<center><i>Breakthrough Technology Provides the Highest Bandwidth Available Today for Delivering the Best Quality HD at the Lowest Cost</i></center><br />
<br />

<p><b>Hudson, MA - October 23, 2007</b> - Radiospire Networks today announced the availability of its AirHook&trade; chipset, the industry's highest bandwidth wireless HD connectivity solution. The AirHook chipset allows display manufacturers to achieve uncompressed wireless HD at the lowest cost, making it the obvious platform for wireless connectivity and the best choice for today's home theater and gaming accessories, including cable replacement dongles, HDTVs, DVD players, game consoles, and other consumer electronics products.</p>

<p> </p>

<p>Radiospire is the first company to break the bandwidth barriers that have inhibited other wireless solutions from achieving the same high-quality HD video that A/V cables provide. The AirHook chipset utilizes the widest bandwidth (1.7 GHz of unlicensed spectrum) and delivers the highest throughput (1.6 Gbps) of any product on the market, allowing for the transmission of pure, uncompressed audio and video.  </p>

<p> </p>

<p>"Radiospire's unique approach to wireless HD connectivity has the potential to deliver the highest bandwidth at the lowest cost," said Brian O'Rourke, principal analyst at In-Stat, a leading provider of market analysis and forecasts for end-user devices and semiconductors. "This value proposition may prove very compelling for the consumer electronics market, where this technology has the most potential in providing differentiation and allowing display and other CE manufacturers to capitalize on the fast-growing HDTV market."</p>

<p> </p>

<p>Radiospire's AirHook technology is setting a new quality standard for wireless HD connectivity.  Compared with 802.11n and WiMedia-based Ultra-Wideband (UWB) solutions, which have been repurposed for wireless HD connectivity, AirHook technology was purpose-built to deliver high-definition video with unlimited scalability. Based upon a 1.7 GHz radio link, the AirHook chipset delivers completely pure audio and video without the use of companion compression chips, which often degrade picture quality and unnecessarily introduce latency. The inherent bandwidth also allows AirHook-based products to achieve HD throughputs without having to resort to multiple antenna techniques that invariably add to system cost, complexity and size.  </p>

<p>   </p>

<p>"Radiospire is redefining the wireless home entertainment landscape with a new class of wireless chipset products designed specifically for high-definition applications," said Paul Powers, CEO of Radiospire Networks. "Our innovative approach has allowed us to not only solve the difficult challenge of delivering cable-like quality without the wire, but to do it in a way that is easiest and most cost-efficient for the manufacturer." </p>

<p> </p>

<p>As the first and only purpose-built wireless HD connectivity solution, the AirHook chipset efficiently and cost-effectively satisfies consumer demand for 1080p and can scale to meet future industry requirements. AirHook technology is designed for use in any wideband unlicensed spectrum, including 3.1 - 4.8 GHz and 57-66 GHz, and supports all major worldwide video formats. </p>

<p> </p>

<p>AirHook chipsets are in production and ready for use today in consumer electronics products. For more information, visit www.radiospire.com.</p>
