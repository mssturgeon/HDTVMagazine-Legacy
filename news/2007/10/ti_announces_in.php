				<p class="prtitle">TI Announces Industry's First Approved DTS-HD Master Audio DSP Implementation for Audio/Video Receivers</p>

<center><i>TI's DA7xx Audio DSPs Enrich Audio Quality for Consumers Watching HD DVDs and Blu-ray Discs</i></center><br />
<br />

<p><B>HOUSTON, Oct. 31 /PRNewswire/</B> -- Committed to innovations that provide the highest performance audio quality, Texas Instruments Incorporated (TI) (NYSE:TXN) today announced that its audio digital signal processors (DSPs) are the first embedded implementation approved with DTS-HD master audio at 192 kHz for unparalleled audio quality in home theater systems. Audio/video receivers (AVRs) based on TI's award-winning DA7xx generation of DSPs have the power to fully support eight channels of 192 kHz lossless audio that is bit-for-bit identical to the original audio source, which allows home theater systems to sound exactly as the filmmaker intended. With the full certification of DTS-HD Master audio and DTS-LBR (Low Bit Rate), DA7xx DSPs are the first audio processors approved for both DTS-HD and Dolby TrueHD, and can support all audio formats present on next-generation HD DVD and Blu-Ray discs. For more information please visit http://www.ti.com/pa6.</p>

<p>"The consumer electronics industry continues to demand the highest quality surround sound in home theater systems," said Brian Towne, senior vice president and general manager, DTS. "With TI's DSP-based A/V receivers that are DTS-HD certified, consumers will now have unprecedented audio that matches high-definition video images for a truly all-encompassing HD home theater experience."</p>

<p><br />
<B>Cost-Effective Performance</B></p>

<p>Decoding the highest quality DTS-HD master audio streams, eight channel/192kHz lossless audio and all essential post-processing can be handled on a single DA7xx DSP. By supporting DTS-HD master audio in a cost-effective, single-chip solution, manufacturers can incorporate crisper, fuller and more dynamic audio quality into lower-priced home theater systems. TI integrated the new DTS-HD audio decoders into the existing DA7xx software solution and system framework, allowing manufacturers to get DTS-HD products to market quickly without any compatibility problems.</p>

<p>TI's audio framework enables original equipment manufacturers (OEMs) to easily plug in differentiating post-processing modules from TI or TI third parties, including Audyssey MultEQ XT, Neural-THX Surround, SRS Circle Surround II and THX Ultra 2.</p>

<p><br />
<B>The Aureus Engine</B></p>

<p>TI's DA7xx DSPs or Aureus processors target a wide range of home theater and automotive products requiring multi-channel decoding and high-speed encoding. TI's Aureus product line consists of a 32/64-bit floating-point programmable DSP and a comprehensive software solution, enabling multi-channel decoding applications.</p>

<p>TI offers a wide range of complementary high-performance analog and DSP products for home entertainment audio, including audio data converters, Class-D and PurePath Digital(TM) audio amplifiers and audio clocks. TI provides the silicon, software, systems expertise and support for the entire audio signal chain, enabling customers to get to market quickly. For more information see the Audio Solutions Guide at http://ti.com/audio.</p>

<p><br />
<B>Customer Accolades</B><br />
-- "TI was the first audio DSP vendor to provide an approved Dolby TrueHD implementation for AVRs and is now again at the forefront of the industry with the first implementation with DTS-HD," said Masao Kimura, general manager, Marantz Brand Company, D&M Holdings Inc. "This offering made TI's DA7xx audio DSP as the obvious choice for Marantz's first HD audio/video receiver."<br />
-- "Onkyo takes advantage of TI's complete software and hardware solutions, which includes the industry's first HD decoders required to support next-generation DVD formats, so we can concentrate on developing differentiated features to deliver unique, compelling AVR products," said Miwa Mori, software design manager, Onkyo.<br />
-- "TI continually improves its audio DSP solutions with the highest performance and fully certified decoder software, empowering Yamaha to quickly bring to market our flagship RX-Z11 AVR, the first AVR capable of decoding 192 kHZ DTS-HD master audio," said Akihiro Muramatsu, department manager, Yamaha.</p>

<p><br />
<B>Availability and Packaging</B><br />
 <br />
The 32-bit floating point DA7xx HD decoder solutions are currently available in production volume in a 256-ball BGA package and 144-pin TQFP package through select TI regional third party providers. TI's audio DSPs and the accompanying software solution and system framework are in production today and supported by TI's Code Composer Studio(TM) development tools.</p>

