<p>Women were slightly more positive about HD picture quality than men. There was no difference among cable vs. satellite subscribers. Respondents, in general, were less happy with the actual number of HD channels they receive, as fewer than 40 percent were somewhat or very satisfied with the amount or selection of HD programming. Women and older respondents - ages 50+ - were most positive, while those with an HD-DVR unit were least satisfied with the HD channel selection.</p>

<p>"Nielsen's High Definition Survey shows that HD technology is outpacing content, although a few networks do score high in consumer satisfaction," said Steve McGowan, Nielsen Senior Vice President Client Research Initiatives. "Television owners clearly feel that HD viewing is a more intense experience than standard television and there are early indications that the acquisition of an HD television can, initially at least, stimulate the type of television that is viewed."</p>

<p><br />
<B>Reported TV Viewership</B></p>

<p>Sports and movies are the categories most frequently watched in HD with only twelve percent of respondents indicating that they never watch movies in HD at home. Music and reality shows are the least frequently watched HD content (See Table 3). ESPN HD was the most popular sports channel, Discovery HD was the most watched channel for documentaries and HBO HD was the most watched channel for movies (See Table 3).</p>

