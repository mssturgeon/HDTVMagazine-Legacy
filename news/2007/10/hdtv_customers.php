<p>Other highlights of the study include:</p>

<p> -- There was no runaway winner in terms of which network provides the "best picture," but among HD networks, Discovery HD Theater ranked first (12.7%). CBS HD and NBC HD tied for second.</p>

<p> -- Nearly one-fifth (19.7%) of respondents reported that they watch more TV since they got their HD set.</p>

<p> -- Consumers continue to embrace television as an entertainment platform and many are investing in sophisticated home theater centers, with a HD television as the centerpiece. Nearly three-fourths of respondents placed a set in the family/living room (74%).</p>

<p> -- Far more than one-half (60%) of respondents get their HD signals from a cable provider and nearly another one-third (31%) from a satellite provider. Only about six percent reported receiving HD signals via an antenna or over the air. Comcast, DirecTV and Time Warner were the three largest distributors reported among participants.</p>

<p> -- Over one-third of respondents report getting at least one premium pay channel, led by HBO, Showtime and Starz!</p>

