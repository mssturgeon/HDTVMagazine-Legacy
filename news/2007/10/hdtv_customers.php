				<p class="prtitle">HDTV Customers Are Happy With Picture Quality, Less Enthusiastic About Programming Options, Nielsen Finds</p>

<center><i>Discovery HD Perceived Having Best Picture</i></center><br />
<br />

<p><B>NEW YORK, Oct. 3 /PRNewswire/</B> -- High definition (HD) television owners are much more satisfied with the picture quality of HD television than they are with the amount or selection of HD programming, The Nielsen Company reported today.</p>

<p>According to Nielsen Media Research's 2007 High Definition Survey, 85 percent of HD owners gave a 4 or 5 rating (with 5 meaning "excellent" and 1 meaning "poor") for picture quality but only 39 percent provided the same rating for programming selection.</p>

