<p><B>HOUSTON, Oct. 31 /PRNewswire/</B> -- Committed to innovations that provide the highest performance audio quality, Texas Instruments Incorporated (TI) (NYSE:TXN) today announced that its audio digital signal processors (DSPs) are the first embedded implementation approved with DTS-HD master audio at 192 kHz for unparalleled audio quality in home theater systems. Audio/video receivers (AVRs) based on TI's award-winning DA7xx generation of DSPs have the power to fully support eight channels of 192 kHz lossless audio that is bit-for-bit identical to the original audio source, which allows home theater systems to sound exactly as the filmmaker intended. With the full certification of DTS-HD Master audio and DTS-LBR (Low Bit Rate), DA7xx DSPs are the first audio processors approved for both DTS-HD and Dolby TrueHD, and can support all audio formats present on next-generation HD DVD and Blu-Ray discs. For more information please visit http://www.ti.com/pa6.</p>

<p>"The consumer electronics industry continues to demand the highest quality surround sound in home theater systems," said Brian Towne, senior vice president and general manager, DTS. "With TI's DSP-based A/V receivers that are DTS-HD certified, consumers will now have unprecedented audio that matches high-definition video images for a truly all-encompassing HD home theater experience."</p>

