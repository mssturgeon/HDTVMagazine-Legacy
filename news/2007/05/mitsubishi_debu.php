				<p class="prtitle">Mitsubishi Digital Electronics America Debuts Eight Thin Frame&trade; 1080P LCD Flat Panel HDTVs</p>

<center><i>Sleek, Modern Design Allows for More Screen in Less Space</i></center><br />
<br />
<B>NEW YORK--(BUSINESS WIRE)</B>--Mitsubishi Digital Electronics America, Inc., maker of award winning high-definition home theater products, today rolled out eight top-of-the-line, premium 1080p LCD flat panel HDTVs with unique thin frame, ultra-compact designs. All of these new 1080p flat panel HDTVs are designed, engineered and built in North America.

<p><B>New Models at a Glance</B></p>

<p>The 133 Series 1080p LCD flat panel HDTVs include the 40-inch LT-40133 (Suggested Value Price $2699), 46-inch LT-46133 (Suggested Value Price $3399) and 52-inch LT-52133 (Suggested Value Price $4499) and offers a high contrast picture with x.v.Color&trade;, PerfectColor&trade;, Easy Connect&trade;, and three rear HDMI&trade; 1.3 Inputs. The 40-inch 134 Series LT-40134 (Suggested Value Price $2899) includes PerfectColor&trade; and PerfecTint&trade;, and adds NetCommand&reg; and a side HDMI&trade; 1.3 input. The 144 Series which includes the 46-inch LT-46144 (Suggested Value Price $3899) and 52-inch LT-52144 (Suggested Value Price $5099) offers PerfectColor&trade; and component side input and adds Smooth120Hz&trade; for true 120Hz 1080p LCD flat panel performance. Smooth120Hz&trade; enables the display of more fluid and smoother fast-moving images, free from motion blur. The Diamond LT-46244 (Suggested Value Price $4499) and Diamond LT-52244 (Suggested Value Price $5699) round out the new models and feature the full complement of 133 Series features plus Smooth120Hz&trade;, PerfecTint&trade;, a CableCARD&trade; slot, TV Guide Daily&reg;, NetCommand&reg; and a side HDMI&trade; input.</p>

<p><B>Larger screens in less space with low-profile, modern design</B></p>

<p>Each 40-inch, 46-inch and 52-inch 1080p LCD flat panel HDTV features Mitsubishi's super Thin Frame&trade; with high-quality hidden speakers for more picture in a smaller space than ever before. The Mitsubishi Thin Frame&trade; measures about an inch, which is less than half typical LCD flat panel frame widths, resulting in a space savings of over two inches in cabinet width compared to most flat panels. Each 40-inch model is only 37 inches in width and 23.9 inches in height (without base); each 46-inch model is 42.3 inches wide and 26.9 inches tall (without base), and each 52-inch model is 48 inches in width and only 30.4 inches high (without base). The 133 Series is presented in Platinum Black with a Platinum Metallic accent. Both the LT-40134 and the 144 Series products are finished in Platinum Black with a Platinum Black accent. Diamond models are presented in a sleek high-gloss Black Pearl accented by a Diamond Blue light.</p>

<p><B>More color, for a more colorful image</B></p>

<p>Mitsubishi takes color to a new level on each member of its 2007-2008 1080p LCD flat panel Lineup with a suite of color features led by x.v.Color&trade; support and Mitsubishi's Full Spectrum Color&trade;. x.v.Color&trade; is the new standard in high definition color. Its wide color palette provides up to 80 percent more color than standard HDTV for breathtaking realism and vivid, natural colors. x.v.Color's wide color palette is complemented by Deep Color on HDMI&trade; 1.3 inputs, enabling additional color resolution for smooth transitions between different shades of color.</p>

<p>Mitsubishi's Full Spectrum Color&trade; results in 25 percent more color than standard LCD. Reds and yellows become more vivid and there are more available shades of green, cyan and blue, resulting in a more vivid, more realistic image. Additionally, each model comes with Mitsubishi's new Color 4D Noise Reduction system that takes advanced noise reduction technology to the world of color. Color 4D Noise Reduction adds an extra dimension to picture performance by looking horizontally, vertically, within and between frames of video and additionally analyzing color to filter video noise. The result is noise-free images and clean, clear colors.</p>

<p>PerfectColor&trade; allows for advanced individual 6-color adjustment. The 134 Series and Diamond models also include PerfecTint&trade; where the viewer can fine tune the tint of each of the six colors for each input separately. The end result of Mitsubishi's full suite of unique color features is maximum color control and breathtaking realism with vivid, yet natural color without compromise.</p>

<p><B>Lots of connections, made easy</B></p>

<p>All eight models offer superior connectivity and convenience. Mitsubishi leads the industry with three rear HDMI&trade; 1.3 inputs, two rear component inputs, and a side component input on every set for maximum HD connectivity with HD cable and satellite boxes, Blu-ray Disc&trade; or HD DVD&trade; digital disc sources and the latest in HD gaming consoles. All HDMI&trade; inputs are version 1.3 and are additionally SimplayHD&trade;-certified to make sure all your HD components work together properly. Additionally, a USB input for up to five mega pixel pictures lets you easily connect a USB thumb drive or USB card reader for easy large screen digital photo viewing in stunning HD clarity.</p>

<p>Mitsubishi's Easy Connect&trade; makes set-up and operation simple, the 134 Series, 144 Series and Diamond models add NetCommand&reg; to Easy Connect&trade; for a true one-remote control home theater system. NetCommand&reg; combines the control and conventional IR-products and adds HDMI&trade; with consumer device control to create an easy-to-use on-screen guide.</p>

<p>Additionally, the 134 Series and Diamond models add a side HDMI&trade; 1.3 input for easy access wiring of an HD camcorder or HD gaming console, and even include TV Guide Daily&reg; for additional convenience. Diamond models even go one step further to include an RS232C input for advanced home installation and are Digital Cable Ready with a CableCARD&trade; slot for cable box free operation.</p>

<p>In separate announcements, Mitsubishi Digital Electronics America detailed its latest advancements in high-definition color and introduced nine new 1080p DLP&reg; HDTVs, each with a Mitsubishi Exclusive 6-Color Light Engine.&trade;</p>

<p><B>Mitsubishi Digital Electronics America, Inc.</B></p>

