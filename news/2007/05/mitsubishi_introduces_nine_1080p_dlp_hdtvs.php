<p>Three Diamond models, available in the 57-inch WD-57833 (Suggested Value Price $3399), the 65-inch WD-65833 (Suggested Value Price $3999) and the 73-inch WD-73833 (Suggested Value Price $5899), offer the ultimate HDTV experience. The 833 Series includes some key features above and beyond the 734 Series including Smooth120Hz&trade; for more fluid and smoother moving images free from motion blur; TV Guide On Screen&reg; 9.0; Game FX - 3D game capability; IEEE1394; and an RS232C input.</p>

<p><B>Larger screens, not larger spaces with sleek, elegant design</B></p>

<p>Each 57-inch, 65-inch and 73-inch 1080p DLP&reg; HDTV features Mitsubishi's super Thin Frame&trade; that delivers more picture in a more compact space than ever before. In addition, each model is at least 25 percent less deep, with the most drastic changes to the three 73-inch models. This year, Mitsubishi's 73-inch models get their most efficient designs ever with a 65.2-inch width and 43.6-inch height, and less depth than last year's 57-inch 1080p DLP&reg; HDTVs. The 733 Series and 734 Series are presented in Platinum Black while the 734 Series also includes a Brushed Black accent. The Diamond models sport a rich Black Pearl high-gloss finish with a Soft Blue light. These are the sleekest, most modern and compact designs ever from Mitsubishi, enabling more picture in less space for the most immersive experience available.</p>

<p><B>More color, for a more colorful image</B></p>

<p>Mitsubishi takes color to a new level on each member of its 2007-2008 1080pDLP&reg; HDTV Lineup with a suite of color features led by x.v.Color&trade; the new standard in high-definition color, which delivers up to 80 percent more color than standard HDTV for breathtaking realism and vivid, natural colors. x.v.Color's wide color palette is complemented by Deep Color on HDMI&trade; 1.3 inputs by enabling additional color resolution for smooth transitions between different shades of color.</p>

<p>Mitsubishi applied over two decades of optical experience in the design of its proprietary 6-Color Light Engine&trade;. This unique Mitsubishi light engine generates yellow, cyan, and magenta directly rather than by combining red, green, and blue. This more efficient process results in a wider range of colors, brighter individual colors and purer whiter whites. The resulting picture quality adds realism to yellow sunlight, blue skies and crimson sunsets.</p>

<p>Additionally, each model comes with Mitsubishi's new Color 4D Noise Reduction system that takes advanced noise reduction technology to the world of color. Color 4D Noise Reduction adds an extra dimension to picture performance by looking horizontally, vertically, within and between frames of video and additionally analyzing color to filter video noise. The result is noise-free images and clean, clear colors. In addition to PerfectColor&trade;, which allows for advanced individual 6-color adjustment, the 734 Series and Diamond models also include PerfecTint&trade; that allows the viewer to define the tint of each of the six colors for each input separately, providing maximum color control. The end result of Mitsubishi's full suite of unique color features is breathtaking realism with vivid, yet natural color without compromise.</p>

<p><B>Lots of connections, made easy</B></p>

<p>All nine models offer superior connectivity and convenience. Mitsubishi leads the industry with three rear HDMI&trade; 1.3 inputs, two rear component inputs, and a front component input on every Mitsubishi 1080p DLP&reg; HDTV for maximum HD connectivity with HD cable and satellite boxes, Blu-ray Disc&trade; or HD-DVD&trade; digital disc sources and the latest in HD gaming consoles. All HDMI&trade; inputs are not only version 1.3, they are also SimplayHD&trade;-certified to make sure all your HD components work together properly. Additionally, a USB input for up to five mega pixel pictures lets you easily connect a USB thumb drive or USB card reader for large-screen digital photo viewing in startling HD clarity.</p>

<p>The 734 Series and Diamond models enhance Easy Connect&trade; with NetCommand&reg;. NetCommand&reg; enables a true one-remote control home theater system, combining the control of conventional IR-products and adding HDMI&trade; with consumer device control to create an easy-to-use on-screen guide. Additionally, the 734 Series and Diamond models add a front HDMI&trade; 1.3 input for easy access connection of an HD camcorder or HD gaming console. The Diamond models even include TV Guide On Screen&reg; 9.0 for additional convenience, an RS232C input for advanced home installation and an IEEE1394 interface for FireWire&reg; playback and recording.</p>

