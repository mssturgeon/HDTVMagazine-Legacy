				<p class="prtitle">DIRECTV Launches NHL Network</p>

<center><i>24-Hour Hockey Network Now Available In Both SD and HD on DIRECTV</i></center><br />
<br />

<p><B>EL SEGUNDO, Calif., Nov 01, 2007 (BUSINESS WIRE)</B> -- DIRECTV hockey fans now will have access to the ultimate hockey sports lineup with the launch of the NHL Network(TM) in both SD and simulcast in HD on DIRECTV. NHL Network will broadcast 50 live regular-season games this season all in HD in addition to its daily live signature show, NHL on the Fly, classic games, documentaries, instructional shows, highlights and more.</p>

<p>NHL Network is now available to DIRECTV customers subscribing to DIRECTV(R) CHOICE XTRA(TM) and above programming packages, as well as those with a subscription to NHL(R) CENTER ICE(R).</p>

<p>"Our loyal DIRECTV hockey fans have been asking for more quality hockey content and the addition of the NHL Network in both SD and HD will give them all of the games they have been waiting for," said Derek Chang, executive vice president, Content Strategy and Development, DIRECTV, Inc. "As the undisputed HD leader, DIRECTV is now enabling fans to get up close and personal with their favorite NHL team and see every face off, body check, and slap shot in crystal-clear HD."</p>

<p>"DIRECTV has been a great partner of the NHL since the launch of NHL CENTER ICE over a decade ago," said Jody Shapiro, senior vice president, Distribution, NHL. "Having DIRECTV offer NHL Network through their CHOICE XTRA(TM) package and above gives the majority of DIRECTV customers the chance to watch great hockey programming 24-hours a day."</p>

<p>With the addition of NHL Network HD, DIRECTV now offers 74 full-time national HD channels, including 18 sports networks in HD, significantly more than any other television provider. DIRECTV will continue to expand its national HD lineup throughout the rest of the year and is expected to have up to 100 national HD channels by year-end.</p>

<p>NHL Network in SD and HD will be available on DIRECTV viewer channel 215. NHL Network is the first network dedicated to the NHL, giving viewers an unprecedented 24-hour all-access pass to the most comprehensive hockey coverage, both on and off the ice, with live games, daily highlight shows, up-to-the-minute hockey news and exclusive hockey programming and special events.</p>

<p><br />
<B>About DIRECTV</B></p>

<p>DIRECTV, Inc., the nation's leading satellite television service provider, presents the finest television experience available to more than 16.3 million customers in the United States, through exclusive content, industry-leading customer satisfaction (which has surpassed cable for seven years running) and superior technologies***. Each day, DIRECTV subscribers enjoy access to over 250 channels of 100% digital picture and sound, exclusive programming and the most comprehensive collection of sports programming available anywhere, including NFL SUNDAY TICKET(TM) and MLB EXTRA INNINGS(R). DIRECTV (NYSE:DTV) also leads the digital television technology revolution with exclusives such as NFL SUNDAY TICKET SuperFan(TM), US Open Interactive and YES Network Interactive and will soon have the capacity to offer over 150 national HD channels. For the most up-to-date information on DIRECTV, please visit directv.com.</p>

<p><br />
<B>About NHL Network</B></p>

<p>As the definitive hockey destination, NHL Network offers viewers a 24-hour all-access pass to complete hockey coverage both on and off the ice, including live NHL games featuring stars such as Sidney Crosby and Alexander Ovechkin. The network's daily signature show - NHL On The Fly - offers fans exclusive live look-ins to NHL games, goals, complete shootouts, extended highlights, stellar saves, features, interviews, pre- and post-game reports, team press conferences, expert analysis from a variety of hockey insiders and former players, plus special event coverage from the NHL All-Star Game, NHL Stanley Cup(R) Final and NHL Entry Draft. Additional NHL Network programming includes international and amateur hockey, player profiles, interview shows and youth-oriented programs. NHL Network is operated out of Canada and is available in the United States by contacting digital cable or satellite providers.</p>

<p><br />
<B>About the NHL</B></p>

<p>The National Hockey League, founded in 1917, is the second-oldest of the four major professional team sports leagues in North America. Today, the NHL consists of 30 Member Clubs, each reflecting the League's international makeup, with players from more than 20 countries represented on team rosters. According to a Simmons Market Research study, NHL fans are younger, more educated, more affluent, and access content through digital means more than any other sport. The NHL entertains more than 100 million fans each season in-arena and through its partners in national television (VERSUS, NBC, TSN, CBC, RDS, RIS, NASN, NHL Network and HDNet) and radio (Westwood One and XM Radio). Through the NHL Foundation, the League's charitable arm, the NHL raises money and awareness for Hockey Fights Cancer(TM), Hockey's All-Star Kids and NHL Diversity(TM), and supports the charitable efforts of all NHL players. For more information on the NHL, log on to NHL.com.</p>

