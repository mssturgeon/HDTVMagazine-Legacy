<p><B>SANTA CLARA, Calif., Dec. 19 /PRNewswire/</B> -- VUDU Inc., the company that brings instant access to video entertainment to the living room, announced today that they will offer a free VUDU box to customers who purchase select models of the AQUOS high definition televisions through Vudu.com over the holidays.</p>

<p>The free VUDU box will be offered through January 5, 2008 on purchases of Sharp AQUOS televisions with 42" or larger screens. (visit http://www.vudu.com/sharp.html for details)</p>

<p>"This holiday offer guarantees that new owners of the finest high definition product in the world will have direct access to lots of great content with superior picture quality," said Bob Scaglione, senior vice president and group manager, Product and Marketing Group, Sharp Electronics Corporation. "Through this offer, new AQUOS owners will be able to instantly enjoy thousands of movie titles, television content and more on a pay as you go basis."</p>

