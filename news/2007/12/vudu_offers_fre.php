<p>"We're adding loads of HD quality content to the VUDU service so AQUOS owners will have thousands of new and classic movies, TV shows and more from which to choose. HD movies will be lighting up high definition screens everywhere across America this holiday season," said Tony Miranz, VUDU's Co-founder and EVP of Sales and Business Development.</p>

<p>The company is also currently offering a limited number of television programs that are available on demand at a per-episode price. VUDU plans to expand its offering of television content in 2008 as well.</p>

