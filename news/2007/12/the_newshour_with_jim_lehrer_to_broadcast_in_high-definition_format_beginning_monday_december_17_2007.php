<p><B>ARLINGTON, Va., Dec. 11 /PRNewswire-USNewswire/</B> -- THE NEWSHOUR WITH JIM LEHRER has built its reputation by insisting on the highest standards in journalism for more than 30 years. The program's commitment to depth and clarity takes on new dimension as it launches a high-definition broadcast beginning on Monday, December 17, 2007. The new format will deliver superb video resolution and higher-quality audio, and will result in a richer experience for the increasing number of viewers who watch the program on an HD television set.</p>

<p>The transition of the NEWSHOUR to a high-definition digital broadcast furthers the goal of the Public Broadcasting Service (PBS) to deliver the majority of its national programming schedule in HD. The NEWSHOUR will contribute an additional 260 hours of national programming toward that objective.</p>

<p>To enable the transition, WETA, the flagship public television station serving the Washington, DC, area and a co-producer of the NEWSHOUR, built a new state-of-the-art control room, constructed a new set optimized for HD and installed all new cameras and related digital editing equipment. The conversion to HD is made possible in part by a grant to WETA from the United States Department of Commerce's National Telecommunications and Information Administration (NTIA) under the Public Telecommunications Facilities Program.</p>

<p>Beyond the series' regular evening broadcast, the NEWSHOUR and PBS will produce approximately 24 hours of live, HD primetime coverage of the 2008 Democratic National Convention from Denver, Colorado (August 25-28) and the Republican National Convention from St. Paul, Minnesota (September 1-4).</p>

<p>"This transition is an exciting development for the NEWSHOUR, WETA and PBS," remarked Linda Winslow, executive producer of the NEWSHOUR. "While all this change is challenging, we look forward to this new HD format as a way to make the NEWSHOUR even more engaging and to serve our viewers better. But while we may look a little different, viewers can expect the same in-depth reporting and balanced discourse they have always gotten from the NEWSHOUR."</p>

<p>"The NEWSHOUR's move to HD will double PBS' general audience HD hours from the previous year," said John Boland, PBS Chief Content Officer. "Long-form films such as THE WAR and other transitions to HD by acclaimed series including NATURE, ANTIQUES ROADSHOW, AMERICAN EXPERIENCE, NOVA and FRONTLINE, hasten PBS' already exponential growth in new HD programming and support the plans to transition public television to a full HD service by February 2009."</p>

<p>Until the national conversion to digital television in February 2009, PBS will offer local PBS stations simultaneous feeds of both an HD and standard-definition NEWSHOUR broadcast. The standard-definition NEWSHOUR feeds will be down-converted from HD by PBS and will therefore appear to viewers of analog channels in a "letterbox" format.</p>

<p>THE NEWSHOUR WITH JIM LEHRER airs five nights a week on more than 315 PBS stations across the country (check local listings) and is also available online, via public radio in select markets and podcast. The program is produced by MacNeil/Lehrer Productions in association with WETA Washington, DC, and Thirteen/WNET New York. Corporate funding for the NEWSHOUR is provided by the new AT&T, Chevron and Pacific Life, along with major funding from the Atlantic Philanthropies, the William and Flora Hewlett Foundation, the National Science Foundation, the Corporation for Public Broadcasting and public television viewers.</p>

