			<p class="prtitle">Sony Gives Back to Consumers and the Environment With TV Trade-Up Offer and Electronics Recycling Program</p>

<p><B>SAN DIEGO, Dec. 18 /PRNewswire/</B> -- On the heels of its launch of the first national electronics recycling initiative, Sony Electronics today announced a program to further encourage consumers to recycle their old television sets.</p>

<p>Sony will be offering, until March 15, 2008, a $100 coupon towards the purchase of a new Sony BRAVIA high-definition TV at Sony Style stores, online at sonystyle.com and through Sony Style telesales at 1-877-865-SONY for every old set recycled through the Sony Take Back Recycling Program, which kicked off September 15.</p>

<p>To help consumers recycle and dispose of electronic devices in an environmentally sound manner, the Sony Take Back Recycling Program was established with Waste Management Recycle America, to offer customers free recycling of any of their unwanted Sony products. Consumers can bring Sony-branded products, as well as other manufacturers' electronics products that may include a recycling fee, to 79 eCycling centers throughout the U.S. Those customers who drop-off their television, no matter what brand, to a participating collection site for recycling between now and March 15, 2008 will receive a coupon good towards $100 off the purchase of an HDTV from Sony Style retail (stores, online and telesales) through March 31, 2008.</p>

<p>"By layering our Take Back Recycling Program with offers like the TV Trade Up promotion, Sony expects to reach its goal of recycling one pound of old product for every pound of new product sold," said Mark Small, vice president of environment, safety and health for Sony Electronics. "With the next wave of high definition technology, we anticipate many HDTVs to replace analog television sets and Sony is providing customers with end-of-life solutions for those unwanted items."</p>

<p>"We value Sony as a partner and are excited to be expanding our partnership to reward responsible consumers who seek waste management services for their old electronics," said Patrick DeRueda, president of WM Recycle America. "The take back program has been a huge success since its inception, gathering more than 530 tons of electronic waste to date, and we anticipate the TV Trade Up promotion to further encourage people to recycle."</p>

<p>The amount of e-waste is on the rise and the issue is becoming increasingly crucial as the FCC-mandated switch to all digital TV signals in February 2009 nears. This imminent transition will create demand for digital televisions -- as well as the need for a responsible, efficient way to manage the disposal of obsolete analog TV sets. The Consumer Electronics Association expects at least 30 million digital televisions to be sold in the U.S. this year alone.</p>

<p>By recycling old electronics products, useful materials -- such as glass, plastic and metals -- can be collected and re-used in the manufacture of other products. Recycling not only minimizes the amount of waste disposed, it also minimizes the extraction of new raw materials from the earth and resources required for processing, saving energy and reducing greenhouse gases in the process.</p>

<p>The Sony TV Trade Up and Take Back Recycling Programs are part of the company's broader global commitment to environmental stewardship, which spans product design, recycling, facilities management and energy conservation across all categories. This is the first national recycling initiative in the U.S. to involve both a major electronics manufacturer and a national waste management company.</p>

<p>Sony TV Trade Up coupons will be distributed, on a first come-first serve basis, at 79 Waste Management eCycling drop-off centers taking part in the Sony Take Back Recycling program nationwide. The number of participating eCycling drop-off centers is growing, as Sony and Waste Management are aiming to open enough drop-off locations in all 50 states so there is a recycling center within 20 miles of 95 percent of the U.S. population. A complete list of WM Recycle America eCycling drop-off centers can be found at http://www.wm.com/sony/ or by calling 1 877 439 2795. More information about the Sony Take Back Recycling Program is available at http://www.sony.com/recycle.</p>

