			<p>AUSTIN, TEXAS, December 12, 2007-TVs, next-generation DVD formats, notebook PCs and other consumer electronic devices were highlighted in last week's Black Friday Webinar held by DisplaySearch. Featuring an analysis of holiday sales results for consumer electronics through Thanksgiving weekend, expert analysts from DisplaySearch, The NPD Group and Current Analysis West provided a closer look at the results for the first week of the 2007 holiday shopping season and how this activity will translate into results for the remainder of the holiday selling season. The webinar also addressed the latest sell-through, sell-in, channel inventory, product inventory and panel inventory results for all major display applications including TVs, notebook PCs and DVD players, as well as the 2008 outlook. </p>

<p>Below is a summary of the Black Friday webinar highlights:</p>

<p>Black Friday Overview, Stephen Baker, Vice President, Industry Analysis, NPD</p>

<p>During his presentation, Baker noted that Black Friday sales volume was weak, but transactions were strong, with an increase in the average dollar spent per transaction. Price wars in 2007 have been non-existent to date. Sales in key categories such as LCD TVs, GPS, digital picture frames, camera accessories and D-SLR were as expected, with GPS growing 237% Y/Y. Despite this, many other segments showed decline in revenues from 2007. In his 2008 outlook, Baker also indicated that the industry is pushing toward bundles, add-ons and accessories-focusing on selling for profit versus for volume. Furthermore, retailers are making service and support a priority to provide a better experience in the store and at home, and ultimately access new profit opportunities.</p>

<p>Black Friday Retailer Promotion Summary, Sam Bhavnani, Director of Research, Computing, Storage & Consumer Technology, Current Analysis West</p>

<p>The CE channel held its position in the Black Friday spotlight this year, with LCD TV promotions the most prevalent, plasma TVs declining significantly and a focus on 1080p full HDTVs. LCD TVs led in the 40-49" segment, while plasma focused on 50" and above. Also of note was the increase of online-only promotions, such as Toshiba's laptop promotion.</p>

<p>TV Results and Q4 Outlook, Paul Gagnon, Director North American TV Market Research, DisplaySearch</p>

<p>Gagnon noted that Black Friday TV unit sales this year barely surpassed 2006, which could impact Q4 results. LCD TVs sales grew 61% Y/Y in units and 83% Y/Y in revenues on a 14% improvement in average selling price-attributed to the adoption of 1080p and less competition from CRT. PDP growth not as strong as last year, but new 1080p models have had a positive impact on sales. He also discussed LCD and PDP ASP results, top selling TVs, how the Black Friday TV sales will impact Q4'07 results and the outlook for 2008. </p>

<p>DVD Results and Q4 Outlook, Paul Erickson, Director of DVD and HD Market Research, DisplaySearch</p>

<p>On Black Friday, HD DVD led in overall unit sales share, while Blu-ray Disc led in revenue share. Erickson also reported that HD DVD drove the majority of week/week unit and revenue growth. He also discussed the importance of pricing for both next generation DVD solutions, as well as the success CE retailers had in bundling discounts and the top vendors in next-generation DVD sales.</p>

<p>Notebook PC Results and Q4 Outlook, John Jacobs, Director, Notebook Research, DisplaySearch </p>

<p>Jacobs provided an overview of the key Black Friday notebook trends, indicating that notebook sales have grown in the past few years from advertisements of a few low-priced models at traditional computer retailers to a wide range of brands and notebook sizes at an ever-growing list of retailers. Black Friday notebook volume increased 29% Y/Y. He also highlighted a comparison of weekly Y/Y brand results and notebook ASPs, concluding with a 2008 forecast.</p>

