				<p class="prtitle">Worst Cable TV Horror Story Will Win a 42" Plasma HDTV and Antenna from Antennas Direct&trade; Plus $1,000 for Stress Counseling</p>

<center><i>Best verified story wins TV first prize; nine other winners of antennas to be selected.</i></center><br />
<br />

<p><B>St. Louis, MO (PRWEB) December 20, 2007</B> -- As reported a few days ago by the Bridge Data Group, overall customer satisfaction with cable TV stands at only 58%. The 75 year-old hammer wielding grandmother who "attacked (http://www.cepro.com/article/75_year_old_woman_takes_hammer_to_comcast_office/)" a Comcast payment center in Virginia might be considered to be in the other 42%.</p>

<p>Richard Schneider, President of Antennas Direct said, "We hope this is an isolated incident, but we know that cable TV has lost 1.1 million subscribers recently. At the same time, our new Terrestrial Digital brand of antennas are doubling in sales about every 180 days. We first thought that these dramatic sales increases were the result of recognition of improvements in our Off-Air (OTA) antenna technology and design. But then, we began hearing more and more cable TV horror stories from our new antenna customers. They told us they were dumping Cable TV because they'd had enough of higher costs, billing add-ons, service outages, contact difficulties, aggravating half-day in-home service waits and no-shows. And from posts on blogs, we also know that cable TV subscribers have had even worse experiences. So we decided we'd see just how bad it is out there, short of the use of hammers."</p>

<p>To that end, Antennas Direct is having a contest to find the ten worst cable TV horror stories. The best of the worst verified story teller will receive a 42" Plasma HDTV and a Terrestrial Digital&trade; Off-Air antenna, selected to allow them to receive the most digital Off-Air stations for their location. Schneider continued, "And to help them get over their feelings of anger and frustration, the winner will also receive $1,000 for stress counseling." Nine other winners will get an Antennas Direct Terrestrial Digital HDTV digital antenna. All the stories will be posted on the Antennas Direct web site.</p>

<p>It's not only basic problems with cable TV (or even Satellite DBS) providers that have caused this dramatic OTA antenna sales increase. Because local digital TV broadcasts are now everywhere, a meaningful percentage of new antenna buyers are adding an OTA antenna to other signal reception sources. Cable subscribers that want access to all their favorite local broadcasts or all available HD local broadcasts free, but can't get them from their present service provider, are buying OTA antennas. And how hot is HD? High Definition Televisions bumped digital cameras out of the top spot for the most desired CE product for 2007.</p>

<p>Bandwidth limitations mean that cable providers may not carry all local channels in many areas or may not offer all the high definition available. While not a horror story, contract disagreements between local cable operators and local broadcasters can mean that major networks may not be available via cable TV in some areas. And with the right antenna, OTA viewers may even be able to receive several out-of-town broadcasts, which may carry blacked out sports programs, network broadcasts not available in their home town or their favorite show in HD, free. Schneider added, "They can purchase an HD antenna for a one-time fee that's probably the same as, or less than, just one month's cable bill."</p>

<p>For lower income families, an OTA antenna may be the only alternative. Those viewers are going to want to be able to receive all the local digital broadcasts that the right Off-Air antenna can deliver after the digital change-over.</p>

<p>As an added benefit, an OTA antenna provides back-up reception options for local cable or satellite signal loss due to equipment failure or rain, snow and ice fade or to smaller TVs and second sets in homes not wired for whole-house signal distribution. Also, there is only so much room on cable bandwidth in which to squeeze signals, so data is compressed to fit, resulting in a somewhat "soft" picture.</p>

<p>Research projects that 15 percent of TV households and 23 percent of TV sets in U.S. homes don't receive cable or satellite TV. That represents more than 70 million TV sets that only receive OTA broadcast television. An OTA signal is the gold standard in digital reception because it's completely uncompressed and also free; good news for those 70 million homes not using cable or satellite.</p>

<p>Cable Horror Stories should be submitted to cablehorror @ antennasdirect.com by January 20, 2008. Submissions may also be made on antennasdirect.com. Antennas Direct will post all stories on their website and announce the lucky verified winners on January 26, 2007. Rules and eligibility information is available at antennasdirect.com.</p>

