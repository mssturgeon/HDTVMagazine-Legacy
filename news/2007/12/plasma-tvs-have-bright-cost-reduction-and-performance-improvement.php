				<p> <em><strong>Plasma TVs Have Bright Cost Reduction and Performance Improvement Outlook According to DisplaySearch's 2007 Plasma Technology Report</strong> </em><br />
 <br />
AUSTIN, TEXAS, December 12, 2007-DisplaySearch believes the outlook for plasma TV cost reductions and performance improvements are closely tied to improvements in luminous efficacy as outlined in its recently introduced 2007 PDP Technology Report. Luminous efficacy can be simply expressed as the relationship between luminance (brightness) and power consumption. As luminous efficacy improves, higher brightness can be achieved at the same power levels, and lower power can be achieved at existing brightness levels. DisplaySearch's new report goes into great detail explaining how higher luminous efficacy levels can be increased, when they are likely to occur and quantifies the anticipated impact on cost reduction and performance improvements. </p>

<p>According to DisplaySearch's YS Chung, Director of FPD Material and Technology and Analysis and co-author of this new report, "It will be critical for plasma manufacturers to increase luminous efficacy to improve their competitive position with LCD TV manufacturers who continue to target larger and larger sizes where the plasma share is highest. We believe a doubling of luminous efficacy to 5.0 lm/W will happen this decade and can reduce plasma panel manufacturing costs by 9-11% vs. 2.5 lm/W costs primarily due to reductions in address and sustain voltage levels and resulting increases in circuit integration. In addition, further improvements in luminous efficacy to 10 lm/W could reduce costs by as much as 40%." </p>

<p><br />
Chung also pointed out in the report that improvements in luminous efficacy are not just limited to brightness, power and cost, but will have far reaching effects in contrast ratio, gray scale, design tolerances, EMI, heat reliability, lifetimes, power suppliers, optical filters, mechanical designs, panel designs, circuit designs and number of process steps.</p>

<p>DisplaySearch's 200+ page 2007 PDP Technology Report begins with an overview of the history of plasma TV, materials, costs, the manufacturing process, current technology, future technology advances, the impact of higher luminous efficacy on costs and performance, and company profiles, concluding with DisplaySearch's outlook on the PDP market. It also profiles five leading PDP manufacturers including Matsushita/Panasonic, Samsung SDI, and LG Electronics. </p>

<p>The report also shows additional insights into R&D activities that can significantly improve the performance of PDPs, while bringing the cost of manufacture down and allowing the technology to compete head-on with LCDs. Matsushita, Pioneer, Hitachi, Samsung SDI and LG Electronics all have a heavy stake in the success of PDP and are investing and researching feverishly toward improving PDP performance today.</p>

<p>Other report highlights include </p>

<p>At 10 lm/W, plasma panel brightness is expected to reach 800-1000 cd/m² for full screen brightness while power consumption is expected to be just 150W at 800 cd/m² for a 42" HD PDP. These improvements would give plasma the upper hand in brightness and power consumption vs. LCDs. </p>

