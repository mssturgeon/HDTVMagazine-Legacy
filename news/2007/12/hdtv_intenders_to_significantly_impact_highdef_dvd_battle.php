<p><B>December 10, 2007 (Dallas, TX)</B> - According to research from The Diffusion Group, close to one-third of non-HDTV households are interested in purchasing a new HDTV in the next six months - a very encouraging sign for HDTV manufacturers and, by relation, high-def DVD manufacturers. More interesting, perhaps, is that the same research found that the characteristics of these "HDTV Intenders" vary widely from that of current HDTV owners. HDTV Intenders tend to be younger, single, more ethnically diverse, and have lower annual household incomes than current HDTV owners - in many respects more characteristic of mainstream consumers than the early adopters who today own an HDTV.</p>

<p>While this trend could in theory benefit either Blu-ray or HD DVD, the data suggests otherwise. Among HDTV Intenders who are likely to purchase a new high-def DVD player in the next six months, 43% prefer HD DVD, 27% prefer Blu-ray, and 30% are undecided.</p>

<p>"The strength of this preference and its correlation to mainstream attributes are notable," states Michael Greeson, president and principal analyst with The Diffusion Group. "Today's high-def DVD owner is likely an early adopter with a knack for power gaming; most certainly tech-sophisticates not at all mainstream in temperament. The next wave of buyers is comprised of early mass-market consumers, a much larger segment with a focus on practical considerations such as price. It is TDG's opinion that the format which can best address the needs of mainstream consumers will emerge as the winner of this format war."</p>

<p>TDG's research confirms this conclusion. When asked to characterize their own "status" as technology consumers, High-Def DVD Owners are five times more likely than Non-Owning High-Def DVD Intenders to see themselves as early adopters. Conversely, Non-Owning High-Def DVD Intenders are almost twice as likely as High-Def DVD Owners to view themselves as early mass-market buyers.</p>

<p><img src="/images/bulletins/PR_HD.jpg" alt="" align="center" /></p>

<p>As is the case with the diffusion of most new technologies, TDG believes there will be several "waves" of high-def DVD buyers, each of which will be motivated by different factors. The most immediate wave, which is expected to be exhausted by early 2008, is comprised of the remaining early adopters who have yet to buy a high-def DVD player and which (not surprisingly) show a preference for Blu-ray. The second (and more sizable) wave will consist of early mass-market consumers who, while less enthusiastic about technology per se and very price sensitive, are more likely to favor HD DVD (a conclusion grounded in TDG's latest primary research).</p>

<p>TDG recently fielded two separate primary research studies focused on consumer interest in next-generation media platforms: the first, an October 2007 survey of 1,500 U.S. adult Internet users; the second, a November 2007 survey of 2,000 U.S. adult broadband users. This larger study is now being offered for purchase by contacting Andy Tarczon at 469-287-8060.</p>

