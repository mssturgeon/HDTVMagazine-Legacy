<p><B>LOS ANGELES (March 28, 2007)</B> - The top studios backing HD DVD, including Universal Studios Home Entertainment, Warner Home Video, Paramount Home Entertainment, The Weinstein Company, Genius Products, and Eagle Rock Entertainment today announced more than 70 specific titles and release windows through July 2007. With movie titles like Smokin' Aces, The Complete Matrix Trilogy, and DreamGirls, HD DVD continues to deliver on promises made to fans of high definition. Additional titles for the remainder of 2007 will be announced this summer.</p>

<p>With attach rates that still far exceed other high definition formats, HD DVD movies continue to sell briskly at retail to a growing consumer base. The 2007 title line-up from the core HD DVD studios, combined with a strong HD DVD title and hardware presence in North America, Europe and Asia, showcases the format's global appeal and unmatched technology features. Effective April 1st, Toshiba is implementing strategic retail price reductions on its full line of HD DVD players for the U.S. market. The entry level HD-A2 will have a suggested retail price of $399.99; and the new HD-A20, with 1080p output, will be introduced at $499 (available in stores in April). The top of the line HD-XA2 was already repositioned to $799.99 on March 1st.</p>

<p>"The spring is ramping up well for HD DVD, with an incredible list of movies and the best priced hardware on the market," said Ken Graffeo, executive vice president, HD Strategic Marketing, Universal Studios Home Entertainment. "Our consumer base continues to buy movies at rates that outpace DVD in its early years, which shows the willingness of consumers to make the transition to high definition."</p>

<p>"HD DVD continues to perform exceptionally well for Warner Home Video, and we see this continuing as more titles from the HD DVD studios roll out and more hardware hits the market," said Steve Nickerson, senior vice president of market management for Warner Home Video. "Fans of high definition have a lot more to choose from with the release of long-awaited blockbusters like The Complete Matrix Trilogy on HD DVD."</p>

