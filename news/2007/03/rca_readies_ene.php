				<p class="prtitle">RCA READIES ENERGY-EFFICIENT DTA800
DIGITAL TV ADAPTER FOR RETAIL CUSTOMERS</p>

<center><i>Final Digital TV Transition Product Fully Complies with Coupon
Eligibility Requirements Just Issued by U.S. Department of Commerce</center></i><br />

<p><img src="/images/products/rca-dta800.jpg" alt="RCA DTA800" align="left" /><B>March 12, 2007 -- Indianapolis, IN</B> - Now that the federal government has issued final eligibility rules for Digital Television Adapters, RCA is readying the DTA800, a low-cost and energy-efficient converter that will insure reception of favorite broadcast TV programs even when analog TV signals are turned off.</p>

<p>At the stroke of midnight at the end of February 17, 2009, analog TV broadcasts are scheduled to end in the United States in favor of digital over-the-air broadcasting. Millions of consumers rely on terrestrial broadcast TV for news, information, and entertainment, and each will need a digital TV receiver or converter before the end of analog broadcasting. The ideal answer for the end of the transition is the RCA DTA800, designed to be an affordable, high-quality set-top receiver for terrestrial digital TV broadcasts that will be fully compliant with the consumer coupon requirements of the U.S. government.</p>

<p>"The final rules from the Department of Commerce insure that manufacturers will offer high-quality and energy-efficient Digital TV Adapters to meet the needs of millions of consumers. We"re very pleased that all households in America will initially qualify to receive up to two $40 coupons to defray the cost of products like our RCA DTA800, which we are now discussing with retailers for consideration in their upcoming assortments," said Dan Collishaw, Chief Operating Officer of Thomson's Americas Audio/Video business.</p>

<p>Designed for consumers who have a favorite analog TV, or perhaps one built into a custom-made cabinet, the DTA800 receives terrestrially broadcast digital TV signals and converts them for display on a conventional analog TV.</p>

<p>With the Consumer Electronics Association estimating that more than 20 million analog televisions rely on terrestrial signals for local channel reception, the RCA DTA800 Digital TV Adapter will play an important role in the completion of the digital TV transition.</p>

<p>With an antenna input, digital reception and analog conversion electronics, and analog outputs, the DTA800 will easily receive over-the-air ATSC standard-definition and high-definition terrestrial broadcasts and comes equipped with a remote control unit. Analog viewers will have several new features with the RCA DTA800, including on-screen program information sent by broadcasters, digital parental control options, closed captioning, and a SmartAntenna interface for use with specialty antenna products that optimize reception in hard-to-reach areas.</p>

<p>"We anticipate a market for several million Digital TV Adapters beginning with the availability of Digital TV Adapter coupons in January 2008. The RCA DTA800 will be the ideal resource for consumers who want to keep watching their old TV set - either in the main entertainment room or another room in the home. And now that the final eligibility requirements have been made public, we"re ready to meet the demand from our retail customers," Collishaw said.</p>

<p>Retail availability and suggested retail pricing will be dependent on retailer interest in this new product category.</p>

