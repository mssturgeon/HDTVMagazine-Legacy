The TX-SR605 is Onkyo's first A/V receiver to include the company's RIHD (Remote Interactive over HDMI) communication protocol. This feature allows for automatic integration of many system control functions between compatible components via the HDMI connection. Common functions include one-button system on/standby control, volume control punch-through from display remote control to the A/V receiver, and a 'direct change' function to automatically select the correct receiver input and begin playback for RIHD source components.

<p>In addition to its two HDMI inputs, the Onkyo TX-SR605 includes three component video, five S-Video, and five composite video inputs to accommodate other sources. There is upconversion of all composite and S-video inputs to both HDMI and HD-quality component video to eliminate the need for multiple redundant video connections to modern video displays. For displays that are not compatible with 480i video, the receiver also provides Faroudja DCDi de-interlacing circuitry to convert 480i signals to progressive scan. There are a total of five digital audio inputs, as well as five A/V and two audio-only analog inputs. Front panel A/V inputs, including optical digital jack, allow easy connection of A/V or audio devices such as a camcorder or portable mp3 player.</p>

<p>The TX-SR605 includes the Audyssey 2EQ automatic speaker calibration feature that provides remarkable improvements in performance by calibrating the home theater system to its acoustical environment. With this system, the included calibration microphone is used to analyze the system's acoustical output at two unique positions in the listening area. By taking readings in two different positions in the theater room, with the included microphone in the listening position, the receiver sends test signals to each speaker in turn, then uses the input from the microphone to adjust channel level and time delay settings for each speaker.</p>

<p>The Onkyo TX-SR605 makes it easier than ever to bring Satellite radio into the living room, featuring compatibility with both XM and Sirius satellite radio programming. The addition of an optional tuner system for either network enables consumers to subscribe to and receive hundreds of channels of commercial-free music, news, talk, and entertainment programming. The receiver even includes onboard Neural Surround processing for reception of multichannel XM HD surround programming. Finally, there is also a high quality terrestrial radio tuner, and the TX-SR605 features 40 presets for AM, FM, XM, or Sirius stations.</p>

<p>Onkyo has also designed the receiver to take complete advantage of the company's optional Remote Interactive iPod dock/charger units. With the iPod placed in the dock, it becomes a source component for not only audio playback, but also for photography stored in iPod photo units. Basic iPod controls such as play, pause, stop, skip, and random / repeat functions can all be operated via the TX-SR605's preprogrammed learning remote control.</p>

<p>The TX-SR605 amplification modules benefit from Onkyo's exclusive WRAT (Wide Range Amplifier Technology) and Optimum Gain Volume Circuitry, delivering 90 watts per channels into 8 ohm loads. There are sturdy five-way binding posts for all seven full-range channels, and the rear surround channels can also be employed to provide a second set of Front L/R channels for speaker bi-amplification.</p>

<p>The TX-SR605 also features Onkyo's Powered Zone 2 capability, which can be used to power stereo speakers in a second room while listening to 5.1-channel sound in the main zone thanks to a dedicated set of zone 2 L/R speaker terminals. The receiver is capable of processing separate multichannel and stereo sources simultaneously for the main and second zone, or processing a single source for both. There is also a zone 2 pre-out that can be used in conjunction with a dedicated zone amplifier or receiver.</p>

<p>The Onkyo TX-SR605 will ship in May in both black and silver finishes, at a suggested retail price of $599.</p>

