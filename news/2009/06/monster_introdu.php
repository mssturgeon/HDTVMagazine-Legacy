				<p class="prtitle">Monster Introduces Breakthrough "SuperThin Cable&trade; for HDMI&trade;"</p>

<center><i>Developed in Collaboration With RedMere, New Powered SuperThin Cables for HDMI Are Ideal for </i></center><br />
<br />Elegant Flat-Panel TV Installations and Use with Mobile HD Devices

<p><B>NEW YORK--(BUSINESS WIRE)</B>--Monster, the world's leading manufacturer of cables, AV accessories, and power conditioning products, today announced the introduction of a new line of "Powered" SuperThin Cables&trade; for HDMI&trade; Cables specifically designed for use with a wide variety of electronics devices, ranging from today's super-slim flat-panel TVs to digital video cameras, home theater systems, gaming systems or portable computers. The new Monster SuperThin Cables for HDMI are the first fruits of a recently announced collaboration with RedMere, a leader in advanced silicon chip development. Monster Super Thin Cable for HDMI products will be available in 4-, 8-, and 16-foot versions in the DigitalLife line of products (DL HDMI HSMI-4, DL HDMI HSMI-8, DL HDMI HSMI-16). Monster's Core line of cables for HDMI will also offer a SuperThin cable design in 1, 2, 4 and 5 meter lengths.</p>

<p><br />
<B>HD Signals Are Boosted in the Cable Itself</B></p>

<p>With the introduction of SuperThin Cable for HDMI, Monster is continuing to follow through on its commitment to provide consumers with a comprehensive range of high-quality, reliable connectivity solutions for every need and budget. The key innovation that made the creation of Monster SuperThin Cables for HDMI possible is the RedMere&trade; MagnifEye&trade; Active technology. Requiring no external power supply the technology enables industry-leading data speeds and ultimate-quality performance by boosting the HD signals directly in the SuperThin cable itself. This eliminates the need for heavy-gauge copper, making the cables extremely light, thin and portable. SuperThin cables measure just 3.5 mm in diameter, approximately 65% thinner than normal HDMI cables.</p>

<p><br />
<B>"Super-Slim TVs Need Monster SuperThin Cables"</B></p>

<p>Monster's new SuperThin cables for HDMI are poised to usher in a new era of convenience and elegance in high-performance cable management, both at home and on-the-go. Featuring a built-in LED indicator that instantly lets users know they are active, the virtually invisible cables are ideal for use in aesthetically designed home theater installations utilizing flat-panel TVs. Consumers can literally hide the cables away in plain sight, as well as fit them into any tight corners for a new level of installation flexibility. Additionally, the compact and lightweight cables, which include handy cable ties, are ideal for taking on the road with camcorders or other mobile digital devices. Their easy portability provides users with a fast and convenient way to connect camcorders or other digital devices to notebook computers or other display. For total reliability and performance, the new cables feature corrosion-resistant 24k gold contacts.</p>

<p>Noted Noel Lee, the Head Monster: "Monster built our reputation on thick, heavy gauge high-quality cables with unequalled performance capabilities. Now, thanks to our alliance with RedMere and the leading-edge MagnifEye Active technology, we're able to provide our customers with the same level of Monster quality and reliability in a brand new type of 'magically thin' cable. The difference is immediately apparent - SuperThin cables are much smaller and lighter, matching the sleek appearance of the consumer electronics products they connect. Whether you want a totally clean-looking virtually invisible installation option for your HDTV or you just want a much better and more convenient way to access HD content while on-the-go, there's never been anything like our new super-thin cables."</p>

<p>Digital Life&trade; SuperThin High Speed Powered Cable for HDMI (SRP) 4ft. $89.95, 8ft. $99.95 and 16ft. $119.95.</p>

