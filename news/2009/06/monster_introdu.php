<B>About Monster</B></p>

<p>Monster is celebrating its 30th anniversary in 2009. The company was founded by Head Monster Noel Lee with a commitment to creating products under the Monster Cable&reg; brand to literally "make music sound better." Today, Monster has grown and diversified to become the world's leading manufacturer of connectivity solutions for high-performance audio, video, car audio, computer, console and computer gaming, as well as a leading innovator in the field of iPod&reg; and iPhone&trade; accessories and professional audio and sound reinforcement. Additionally, under its Monster Power&reg; brand, the company is the leading manufacturer of high-performance AC power line conditioning and protection products for audio/video systems. Explore the world of Monster at www.monstercable.com.</p>

<p><br />
<B>About RedMere</B></p>

<p>RedMere is the leading provider of chip and cable technology solutions for the next generation of compact, lightweight cables for Synchronization, Imaging, Home Theater, Gaming and Enterprise Networking applications. Whether on the move, at home or at work these new cable systems deliver the ultimate in compact digital connectivity over HDMI, DisplayPort and USB for Video and Still Cameras, Smartphones, HDTV, Blu-Ray DVD, PS3 and Xbox, as well as enterprise solutions using Infiniband and PCI Express. RedMere provides cable-embedded semiconductors and advanced cable reference designs to cable industry leaders and manufacturing partners. RedMere is a private company with lead investors Celtic House Venture Partners and EdgeStone Capital Partners.</p>

