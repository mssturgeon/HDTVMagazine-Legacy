<p><B>ENGLEWOOD CLIFFS, N.J., June 11 /PRNewswire/ </B>-- Building on its 18-month alliance with Netflix, Inc. (NASDAQ:NFLX) , LG Electronics has introduced yet another industry first with two new series of Full HD 1080p HDTVs with Netflix instant streaming software embedded directly in the TV and requiring no external device.</p>

