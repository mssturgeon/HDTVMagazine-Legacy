<p>The collaboration between LG and Netflix burst on the scene in 2008 with the world's first Network Blu-ray Disc Player to offer consumers the ability to instantly watch thousands of movies and TV episodes streamed from Netflix. Since that time, LG has introduced two additional Network Blu-ray Players and two Network Home Theater Systems that incorporate the Netflix instant streaming capability.</p>

<p>"With 2.5 million North American households looking to purchase a networked TV,(1) incorporating broadband connectivity into our new HDTVs became a natural progression of our partnership with Netflix," said Peter Reiner, senior vice president, marketing and strategy, LG Electronics USA, Inc. "Both LG and Netflix are committed to offering consumers easy access to entertainment on demand and LG's newest HDTVs make it easier than ever to access thousands of movies and TV shows instantly."</p>

<p>Ideal for movie enthusiasts, LG's LH50 and PS80 series provide access to the Netflix library of more than 12,000 movies and TV episodes available to watch instantly, with hundreds available in HD. Without the need for an external device, the LH50 and PS80 provide consumers access to more content and video on their big screen. Netflix members pay as little as $8.99 per month for unlimited instant streaming to the LCD or plasma in addition to unlimited DVD and Blu-ray rental from a catalogue of more than 100,000 titles.</p>

<p>Instantly streaming content from Netflix to the LG HDTVs requires a broadband connection and relies on a Queue-based user interface. Netflix members can add movies and TV episodes to their individual instant Queues, via the Netflix Web site. Those choices will then automatically be displayed on the TV screen and can be viewed instantly through the HDTV. Once selected, titles begin playing in as little as 30 seconds.</p>

<p>Using the accompanying remote control, Netflix members can effortlessly browse and make selections right on the TV screen and also have the ability to read synopses and rate movies. Additionally, consumers have the option of fast-forwarding and rewinding the video stream.</p>

<p>"Our partnership with LG Electronics is less than two years old, but remarkable achievements have been made in that time," said Bill Holmes, Netflix vice president of business development. "LG was the first manufacturer to embrace Netflix as an instant streaming partner. LG was the first to introduce a Netflix ready Blu-ray Disc Player and LG was the first to announce a Netflix ready HDTV. Netflix is enthusiastic about continuing our innovative partnership with LG and pursuing our joint commitment to provide ground-breaking entertainment options to our customers."</p>

<p>In addition to the LH50 and PS80 series, LG's full Netflix-enabled product line includes two Blu-ray players (models BD370, BD390) and two Blu-ray home theater systems (models LHB953, LHB977) that are Netflix ready to stream instantly. LG's BD390 Blu-ray player, with Wi-Fi capability, makes it easier than ever to connect content on demand. By connecting to an 802.11n wireless home network, the BD390 delivers Netflix instant streaming to rooms where wired broadband connections ordinarily can't reach.</p>

<p>Ideal for home theater enthusiasts, the LHB953 and LHB977 Blu-ray home theater systems not only offer consumers Netflix instant streaming, but they also ensure an exceptional full HD 1080p video experience and advanced surround sound capabilities.</p>

