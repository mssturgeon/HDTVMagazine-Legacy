<center><i>FCC Assists Consumers to Ease Transition</i></center><br />
<br />

<p><B>Washington, D.C. </B>- The nation's historic switch to digital television by 971 full-power stations Friday prompted hundreds of thousands of consumers to call for assistance but caused no widespread disruption of free, over-the-air television broadcasts.</p>

<p>A record 317,450 consumers called the FCC's toll-free help line, 1-888-CALL-FCC, for a total of almost 700,000 from June 8 through 12. Of the calls handled by live FCC help line agents, nearly 30% concerned the operation of digital converter boxes.  Most of those calls were resolved when consumers were instructed to "re-scan" their converter boxes in order to receive the digital channels that had moved to new frequencies.  Over 20% of the calls handled by live agents dealt with reception issues.</p>

<p>Reports from the 200-plus FCC staff stationed across the country as part of the Commission's extensive outreach effort reflected similar concerns.  At DTV transition events held across the country, consumers routinely sought information on the government converter box coupon program and raised concerns about reception.  FCC field staff also worked closely with local broadcasters, cable operators and satellite providers to identify and address issues that arose, and to serve as a liaison with FCC headquarters in Washington.</p>

<p>"I am pleased with the way our FCC team responded to the technical challenges that arose throughout the course of the day," said Acting FCC Chairman Michael Copps.  "But our job is far from over.  This transition is not a one-day affair.  We have known about re-scanning and reception issues for some time and have been doing our best to get the word out. We will continue to work with every consumer who needs assistance in making this important and necessary transition."</p>

<p>The largest volume of calls per TV household among markets registering 1,000 or more calls came from the Chicago media market, followed by the Dallas-Ft. Worth, New York, Philadelphia, and Baltimore markets.</p>

<p>Despite extraordinarily high call volume, average wait time on the help line was 4.6 minutes overall and 1.8 minutes for Spanish-speaking calls.  Periodic call spikes slowed response time for limited intervals, but staffing by 4,000 agents throughout the day permitted the call center agents to take the time and care necessary to walk each consumer through the necessary steps to get DTV-ready.  Agents on average spent over 8.4 minutes per call.</p>

<p>Inside the Commission building, two DTV transition command centers were staffed day and night to monitor call center activities and maintain contact with field staff, broadcasters and electronics manufacturers and retailers.  The FCC and the Commerce Department's National Telecommunications and Information Administration also continued to coordinate activities and promote the NTIA's converter box coupon program. </p>

<p>Chairman Copps and FCC Commissioners Jonathan Adelstein and Robert McDowell spent the morning getting out the word about the steps consumers need to take to make the transition, conducting over 25 national and local live television and radio interviews across the country.  The Chairman and commissioners also were in close contact with Commission staff throughout the afternoon and evening to monitor call center and field operations.   </p>

<p>The FCC's Media Bureau monitored technical problems reported by broadcasters and granted requests to adjust power and other needed accommodations while fixes were made.  Problems included the failure of a shared transmitter in one market that affected four channels.  The stations were back on the air in a few hours.</p>

<p>In addition, the FCC's Office of Engineering and Technology monitored and analyzed reception problems involving specific stations and markets to identify solutions.</p>

<p>The Commission's Consumer and Governmental Affairs Bureau monitored supplies of DTV converter boxes and antennas through industry sources, while staying in touch with field staff working with consumers and broadcasters in markets across the nation.  While anecdotal reports of antenna shortages surfaced, industry officials reported that supplies were adequate in most markets.</p>

<p>The bureaus also worked with the cable and satellite industries to monitor and resolve any problems.  Reports included various stations that had initial problems moving digital channels, and instances of satellite providers momentarily losing broadcast station feeds.</p>

<p>The digital deadline prompted consumers across the nation to enlist the services of vendors working under contract with the FCC to provide free in-home installation of converter boxes. Vendors scheduled thousands of visits Friday, many through the FCC's toll-free help line.</p>

<p>While unprepared consumers lost television service when analog signals were turned off, their TVs still provided helpful information in many markets.  Analog "nightlight" service informing viewers that analog signals have been terminated and providing them with the FCC's 1-888-CALL-FCC number and other transition information was provided by 121 stations in 87 markets, including 45 of the 49 markets designated by the government as "hot spot" markets needing special attention in the transition.  These analog nightlight stations will also broadcast urgent news and emergency information.</p>
