				<p class="prtitle">Panasonic Introduces the World's Lightest* High Definition Camcorders</p>

<center><i>New HD Camcorders Weigh 0.5 LB, Packed with Easy-to-Use, Advanced Features</i></center><br />
<br />

<p><B>SECAUCUS, N.J., June 8 /PRNewswire-FirstCall/</B> -- Panasonic today announced the release of two of the world's lightest*, High Definition (HD) camcorders -- the HDC-SD10, which uses an SDHC/SD Memory Card as recording media, and the Twin Memory Type HDC-TM10, which records onto both an 8 GB** Built-in Memory and an SDHC/SD Memory Card. Each model weighs just 0.5 LB, yet its compact body design has a high-powered 16x optical zoom capabilities and advanced features to produce beautiful 1920 x 1080 Full-HD videos.</p>

<p>The 16x optical zoom of the HDC-SD10 and HDC-TM10 is supported by the Advanced O.I.S. (Optical Image Stabilizer) function -- an essential element to achieve clear zooming, as it minimizes the hand-shake that often impairs video quality while zooming. Panasonic's Advanced O.I.S. detects and corrects for hand-shake around 4,000 times per second and works with the high-powered optical zoom to produce clear, stable zoom shots. The new Active mode also extends the hand-shake correction range to allow the shooting of clear, crisp images while walking or moving.</p>

<p>"We recognize that users are looking for camcorders that capture high-quality, High Definition video, but they also want something lightweight that has advanced, yet easy-to-use functions," said Chuck Kirkman, Senior Product Manager, Imaging, Panasonic Consumer Electronics Company. "With the SD10 and TM10, we've made it easier to record HD video with features such as Advanced O.I.S., Face Detection, Intelligent Scene Selector and the Pre-Rec function, all which maximize shooting results and minimize common issues like blurring."</p>

<p>As with most Panasonic camcorders, the HDC-SD10 and HDC-TM10 both feature the iA (Intelligent Auto)*** function, which automatically sets the most suitable Scene mode according to shooting conditions. These include Advanced O.I.S., Face Detection, which adjusts the exposure so faces are captured perfectly; Intelligent Contrast Control, which helps ensure proper contrast; and Intelligent Scene Selector, which determines the shooting conditions and automatically selects the Scene setting that will provide optimal results. Both camcorders are also equipped with AF/AE Tracking (Auto Focus/Auto Exposure Tracking), which automatically tracks a moving subject for consistently beautiful images. This feature maintains the focus and exposure even if the subject moves or turns to one side.</p>

<p><B>Other features of the HDC-SD10 and HDC-TM10 include:</B></p>

<ul><li>SDHC/SD Memory Card Recording - The SDHC/SD Memory Card not only brings significant advantages to smaller and lighter camcorders, but it also differs from a hard-disk drive in that it has no transport mechanism, making it highly shock-resistant and enabling faster recording starts.</li><li>Twin Memory Recording - Relay Recording (HDC-TM10 Only) - The HDC-TM10 records Full-HD images onto the built-in memory or an SDHC/SD Memory Card (optional), and features a Relay Recording function. When the built-in memory is full, this function automatically switches the recording media to the SDHC/SD Memory Card to provide uninterrupted recording. Video data that is recorded using both media types can  be merged inside the camcorder and saved to an SDHC/SD Memory Card.****
</li><li>Touch Screen and Handy Function Buttons - Both models feature a touch screen that lets users operate a variety of functions by simply touching an icon displayed on the LCD. This allows intuitive operation without having to look away from the subject.</li><li>1.9-sec Quick Power-On - The power turns on and off by opening and closing the LCD. This start-up allows users to save battery power by keeping the power turned off when the camcorder is not in use, while making sure that unexpected shooting opportunities are not lost. The power-saving Eco mode***** automatically turns the power off when the camcorder is not in use for five minutes.</li><li>Pre-Rec - To avoid missing critical shooting opportunities, when the Pre-Rec function is on, the camcorder continuously records three seconds of images into an internal buffer memory.  When the Record button is actually pressed, the three seconds immediately prior are added to the beginning of the clip.</li><li>Auto Power LCD - This feature automatically adjusts the brightness of the LCD screen according to the shooting conditions.</li><li>Built-in Video Light and Flash - Both the HDC-SD10 and HDC-TM10 are equipped with a video light and flash for convenience when shooting in dimly lit places.</li><li>Highlight Playback - This function is for users who want to view recorded images quickly, as "highlights" can be created and played back according to a set time interval.</li><li>One-Touch Copy of Videos to DVD and Easy Playback with the BN1 DVD Burner - To avoid the two-step process previously required to save Full-HD videos from an SDHC/SD Memory Card or built-in memory onto a DVD for playback, the HDC-SD10 and HDC-TM10 feature a one-touch function that makes this process easier.</li></ul>

<p>The HDC-SD10 and HDC-TM10 are both compatible with Panasonic's VIERA Link to allow quick and easy viewing of Full-HD video content, as well as with the VIERA Image Viewer function on a VIERA HDTV. This allows users to play videos on a large screen by simply inserting a recorded SDHC/SD Memory Card into the SD Card slot of a Panasonic VIERA HDTV******. It provides instant playback of video clips recorded in the AVCHD format in Full-HD quality. Similarly, video recordings can be easily played by using a Panasonic Blu-ray Disc(TM) player.</p>

<p>The suggested retail prices of the HDC-SD10 and HDC-TM10 are $549.95 and $599.95 respectively. The TM10 will be available in black and silver models, while the SD10 in black only. All models will be available in September 2009.</p>

