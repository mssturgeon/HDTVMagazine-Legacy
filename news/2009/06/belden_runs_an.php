				<p class="prtitle">Belden Runs An Unamplified 1080p/60 Digital Video Signal Over 100ft of Connectorized HDMI Cable</p>

<p><B>ORLANDO, Fla., June 16 /PRNewswire-FirstCall/ </B>-- Belden (NYSE:BDC) , a world leader in the development of signal transmission products for enterprise, industrial, building management, broadcast, and security applications, demonstrates the unique cable performance properties of their HDMI cable by running an unamplified 1080p/60 digital video signal 100 feet from a generic Blu-ray Disc player to a generic 1080p/60 display. This demonstration will be featured live throughout the InfoComm/NSCA tradeshow in Orlando, Florida June 17-19, 2009.</p>

<p>"All HDMI cables are manufactured offshore in Asia, with one exception: the HDMI cable made by Belden," states Steve Lampen, Product Line Manager at Belden. He continues, "However, this is just raw bulk cable. To be turned into assemblies, our partner Blue Jeans Cable (<a target="_blank" href="http://www.bluejeanscable.com">www.bluejeanscable.com</a>) sends our bulk cable to China where it is cut and assembled with connectors. We currently make this raw cable in two gauge sizes, 23.5 AWG and 28 AWG, of which the 23.5 AWG is being demonstrated here at InfoComm, running what many say is impossible: a crystal clear 1080p/60 digital video signal over 100 feet."</p>

<p>The secret behind these Belden HDMI cables is the patented Bonded-Pair(R) technology. Belden has used this technology for over sixteen years in Category 5, 5e, 6 and now Category 6A 10 gigabit (10GBASET) data cables. Bonded-Pairs attach the two insulated wires of each pair together, without any glue or bonding agent. This makes the most stable pair ever made, providing unequalled impedance tolerance. Even when the cable is flexed or bent, the conductor-to-conductor spacing remains constant. That means that the impedance also remains constant, and the problems of regular twisted pairs, such as impedance variations, are minimized. Impedance variations cause signal reflection ("return loss"). These variations also allow the signal to radiate off the cable (egress) and to pick up noise from other sources (ingress). Reducing these effects allows cables made this way to run farther, with less signal loss, and less noise, than regular twisted pairs.</p>

<p>While Belden makes bulk cable with Bonded-Pairs, we also make standard Nonbonded-Pair HDMI cables as assemblies in our factories in China. We believe these to be the highest quality Nonbonded-Pair HDMI cables, so our customers have a choice of Bonded-Pair or Nonbonded-Pair cables (HD2001-2007). All of these exhibit legendary Belden quality, performance, consistency, and reliability.</p>

<p>For more information about bulk HDMI Cable with Bonded-Pair technology from Belden, contact Belden, at P.O. Box 1980, Richmond, Indiana 47375, 1.800.BELDEN.1. FAX: 765.983.5294. Or visit our Web site: <a target="_blank" href="http://www.belden.com">www.belden.com</a>.</p>

