<p><B>SECAUCUS, NJ (April 14, 2009)</B> -  Panasonic Corporation of North America, a market and technology leader in High Definition consumer and digital electronics products, announced today a major expansion of its Nationwide Recycling Program.  The expansion will initially add more than 30 drop-off sites to Panasonic's Nationwide Recycling Program in the Southeastern United States including Florida, Georgia, North Carolina, South Carolina, Tennessee and Virginia with plans to add additional locations in the Southeast throughout the Spring.</p>

<p>"We appreciate Panasonic's commitment to Product Stewardship and welcome their recycling expansion into the state of Florida," said Mary Jean Yon, Director of the Division of Waste Management in the Florida Department of Environmental Protection.  </p>

<p>Panasonic's Nationwide Recycling Program, which began in November 2008, was created to provide consumers convenient and easy recycling of their Panasonic branded TVs and other consumer electronics1. By January 2009, the program had 280 drop-off locations covering all 50 states.  Included as drop-off sites in the program are Panasonic's North American headquarters in Secaucus, NJ, as well as their corporate facilities in Chesapeake, VA and Rolling Meadows, IL. Today's announced expansion brings the current number of drop-off locations to 310 nationwide.</p>

<p>"At the 2009 Consumer Electronics Show in January, Panasonic announced plans for an aggressive expansion of our nationwide recycling program through 2011," said Yoshi Yamada, Chairman and CEO of Panasonic Corporation of North America.  "We are ahead of our projected timing to reach 400 drop-off locations by December 2009, and plan to continue expanding this program with a goal of having more than 800 drop-off sites participating in the program by 2011."</p>

<p>"Panasonic's program has a dual focus; consumer convenience and environmentally sound recycling," said Richard Vernam, who heads Panasonic's Recycling Office.  "Consumers can drop off their Panasonic products free of charge and the program will help to divert these end-of-life consumer electronics out of the common waste stream and help ensure they enter a separate and environmentally responsible recycling stream."</p>

<p>Panasonic is also working collaboratively with other consumer electronics manufacturers. A significant part of Panasonic's recent recycling expansion stems from a new relationship between Electronic Manufacturers Recycling Management Company, LLC (MRM) - a joint venture established in 2007 by Panasonic Corporation of North America, Sharp Electronics Corporation and Toshiba America Consumer Products, LLC.  -- and Creative Recycling Systems, Inc. (CRS) which operates collection facilities in the Southeast and Midwest regions of the United States.  Day-to-day management of the Panasonic's Recycling Program is contracted to MRM.  The MRM venture was created to address America's e-waste recycling needs most efficiently by bringing the electronic product manufacturing community together into a unified, voluntary effort.</p>

<p>For a list of all Panasonic Nationwide Recycling Program drop-off sites, please visit www.MRMrecycling.com.</p>

<p><br />
<B>About Panasonic's Eco Ideas Initiatives</B></p>

<p>By continuing to work with environmental stakeholders, Panasonic expects to increase public awareness of the convenience, ease and reliability of its electronics recycling program in the U.S.  In fact, promoting employee and public awareness of environmental responsibility is one central element of Panasonic's worldwide environmental initiatives.  Other key elements include the global company's pledges to reduce annual CO2 emissions by 300,000 tons on a global basis over the three year period between fiscal 2008 and 2010 despite growth in production and to introduce products which are easier to recycle and increasingly more energy efficient.  These actions are part of Panasonic's ongoing, global 'Eco Ideas' campaign to help achieve an environmentally sustainable future.  </p>

