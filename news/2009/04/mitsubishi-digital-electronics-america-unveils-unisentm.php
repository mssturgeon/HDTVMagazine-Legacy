<B>How Unisen Works</B></p>

<p>Conceived and built with Mitsubishi Digital Electronics America expertise and precision, this revolutionary immersive sound television features 16 intelligent speakers that direct perfectly balanced audio waves beside and behind the user to reproduce 5.1 surround sound and create an unparalleled entertainment experience. Through the use of an advanced algorithm, the sound technology delays the sound beams and projects them independently from the 16 speakers at varying intervals, to create fully immersive surround sound.</p>

<p>Consumers who value both their space and time will find that Unisen's built-in 16 speaker immersive sound technology delivers high quality sound quickly and completely, with simple setup and ongoing user-friendly operation. Upon initial set-up, the user can enter specific room dimensions into the on-screen graphical interface, or simply utilize the calibration microphone to calculate and set the sound beams for optimal sound within the specific room environment. The user can also adjust the direction, location, and sound levels for each of the five surround channels. The output level for the sub woofer is also directly controllable from the remote control.</p>

<p>With a simple user interface and audio supported by both HDMI and digital audio inputs, Unisen is designed to deliver optimal sound in typical room settings and supports easy connection to DVD and Blu-ray players.</p>

<p><br />
<B>Product Features</B></p>

<p>Mitsubishi Unisen TVs combine ultra compact design and advanced video performance to deliver a gorgeous picture, in a beautifully crafted display. Each model features a New UltraThin Frame(TM) design delivering a frame measuring less than one inch, advanced Smooth 120Hz Film Motion for viewing of fast and slow moving programs and Enhanced Color. Every model features wide color gamut backlight technology to reproduce approximately 25 percent more color than most LCD-TVs. All Unisen models are EnergyStar(TM) 3.0.</p>

