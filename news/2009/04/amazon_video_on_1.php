<center><i>Customers can now purchase HD TV shows from Amazon Video On Demand and rent HD movies from compatible devices including those from Roku, TiVo, Sony, and beginning today, Panasonic</i></center><br />
<br />

<p><B>SEATTLE--(BUSINESS WIRE)</B>--Amazon.com, Inc. (NASDAQ: AMZN) today announced that customers can rent box-office favorites and purchase top TV shows in HD from Amazon Video On Demand. Customers can select from more than 500 HD TV shows and movies from major studios and networks including Warner Bros. Entertainment Inc., Sony Pictures, Paramount Pictures, Metro-Goldwyn-Mayer Studios Inc., Universal Studios Home Entertainment and Showtime Networks. Top titles available now in HD on Amazon Video On Demand include new-release movies such as "Frost/Nixon," "Twilight" and "Yes Man" and hit TV series including "Californication," "The Tudors," "Smallville," and "Gossip Girl."</p>

<p>"Our customers have been asking us for two things: HD and the ability to watch movies and TV shows instantly on their television," said Bill Carr, Amazon vice president Music and Video. "Today we are thrilled to begin offering HD and to add the distinctive Panasonic VIERA CAST&reg;-enabled HDTV lineup to the growing number of televisions and devices supported by Amazon Video On Demand. We plan to continue making it easier than ever for customers to instantly enjoy their favorite TV shows and movies in HD from the comfort of their living rooms."</p>

<p>With movies and TV episodes in HD, Amazon Video On Demand is providing customers with even more choices for entertainment. Customers can now order and watch movies and TV shows in HD on their televisions through compatible devices including: the Roku digital video player, TiVo Series3, HD, and HD XL DVRs, and the Sony Bravia Internet Video Link. Starting today, Amazon Video On Demand's entire library of 40,000 titles, plus HD titles, are also available on Panasonic VIERA CAST&reg; enabled HDTVs. Using these devices, customers can now rent HD movies for $3.99 - $4.99. Customers can also purchase and watch HD TV shows online on MACs or PCs, through compatible devices, or download them to their PC for offline viewing for $2.99.</p>

<p>"Panasonic is thrilled to be working with Amazon's Video on Demand service, an association we see as another step in providing the ultimate entertainment experience for the consumer. Both Panasonic and Amazon are extremely consumer centric and this functionality will provide the consumer with a myriad of entertainment choices," said Merwan Mereby, Panasonic vice president of New Business Development. "It's fitting that Panasonic and Amazon have joined creative forces to create this unique entertainment vehicle. Panasonic's VIERA CAST HDTVs have garnered numerous best of awards, while Amazon is a pioneer in transforming in-home movie entertainment. The consumer will have access to a vast selection of movie and TV entertainment at their finger tips with just a click of a button."</p>

<p>"The addition of Amazon's HD offerings to the Roku digital video player is a tremendous enhancement for our customers," said Tim Twerdahl, vice president of consumer products at Roku. "Amazon's vast selection of high-quality content is the perfect complement to Roku's instant delivery of top movies and TV shows directly to the TV. The combination of Amazon Video On Demand and the $99 Roku player is an incredible value to customers."</p>

<p>"This is a great day for our customers because our best-in-class HD offering just became even better with HD movies and TV shows now being offered by Amazon Video On Demand," said Tara Maitra, vice president and general manager of Content Services and Advertising Sales at TiVo Inc. "Adding HD content from Amazon Video on Demand to an existing vast library of options shows once again that with a TiVo remote you truly can have it all. Consumers can access Amazon Video On Demand HD movies and TV shows, all with the simplicity people have come to expect from TiVo."</p>

<p>"Striving to deliver high-quality content directly to customers, Sony is excited to have HD movies and television shows from Amazon Video On Demand delivered directly to BRAVIA televisions," said Jeff Goldstein, vice president of TV Marketing for Sony Electronics.</p>

