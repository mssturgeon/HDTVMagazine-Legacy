<p>With Samsung's innovative use of white LEDs as a backlight source, the 8500 Series is capable of a stunning 7,000,000:1 dynamic contrast ratio for extreme detail and image depth. Its Wide Color Enhancer Pro ensures that colors are consistently vibrant, while Samsung's Ultra Clear Panel works to improve image clarity and brightness regardless of a room's ambient lighting. The 8500 Series is also compliant with the latest Energy Star® v3.0 ratings, and includes an optimized energy savings mode that adjusts the backlight and picture quality, without sacrificing the overall viewing experience. Additionally, its "Natural" mode optimizes picture settings to model the brightness advantage of LCD displays and the cinema-like richness of plasma displays with any content.</p>

<p>The 8500 Series incorporates an ultra-quick 2ms panel response time, combined with Samsung's latest version of its Auto Motion Plus&trade; frame interpolation technology that has a true 240Hz refresh rate to significantly improve playback of fast-paced content. Going beyond the three standard Auto Motion Plus&trade; presets, users can also separately adjust the levels of judder and motion blur reduction for superior picture control.</p>

<p><br />
<strong>Connectivity and Content</strong></p>

<p>The new 8500 Series features Samsung's Medi@2.0&trade; suite, allowing users to access content from more sources than ever before. The Internet@TV - Content Service, developed in association with Yahoo!, provides onscreen access to popular web-based content from Yahoo! (Flickr, Video, News, Weather, and Finance), USA Today (Sports), Twitter, YouTube, and others. The widgets-based interface and scrollbar are activated with the push of a button, and run along the bottom of the screen for easy browsing of the latest programs and content available.</p>

<p>Even after purchase, consumers will be able to use a growing library of widgets, as the widget development kit is available for other content providers to develop new offerings. Samsung's Medi@2.0&trade; suite provides wired and wireless DLNA compatibility to enjoy photos, music and videos from a networked PC right on the television. Pre-loaded photos, artwork, games, and recipes are also included for entertaining, and two USB 2.0 connections can be used for playing a plethora of video, photo, and audio files from portable devices, including external hard memory.</p>

<p><br />
<strong>Designed to Stand Out</strong></p>

<p>Measuring at just 1.6 inches deep and featuring Samsung's Touch of Color&trade; (ToC&trade;) bezel, the 8500 Series provides consumers with style and flexibility in an HDTV. Additionally, both the 46-inch and 55-inch models come with a built-in tuner and an array of multimedia connections. Samsung's innovative, ultra-slim wall-mount solution (sold separately) makes installation akin to hanging a picture frame, by reducing the gap between the TV and the wall to a mere 0.6 inches - a major improvement over traditional mounting systems.</p>

