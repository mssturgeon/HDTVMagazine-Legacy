				<p class="prtitle">Sony Unveils New Flash Memory Camcorders With Advanced Optics, New Technology</p>

<p><B>SAN DIEGO, July 7 /PRNewswire/ </B>-- Sony today announced its new HDR-CX520V and HDR-CX500V Handycam(R) camcorders, which capture full 1920x1080 high-definition video and up to 12-megapixel photos on a 64GB or 32GB internal flash memory, respectively, offering up to 25 hours of HD video (LP mode).</p>

<p>"These models combine the best in digital imaging technology, strengthening Sony's industry leadership and meeting demand for both quality camcorders and HD video," said Kelly Davis, director of the camcorder business for Sony Electronics. "Expanding our lineup to include Handycam camcorders with large capacity embedded flash memory allows us to offer consumers flexible recording solutions concentrated in a very portable, compact body."</p>

<p><br />
<B>Advanced Features and Performance</B></p>

<p>For optimal playback, the HDR-CX520V and HDR-CX500V camcorders feature 60p output, which automatically converts content to 60 progressive frames per second when connected to a compatible high-definition television.</p>

<p>Another notable feature, Optical SteadyShot(TM) with Active Mode (which allows a moveable lens element to shift with greater range of motion during camera shake) now offers 3-Way Shake Canceling. This feature reduces hand shake in three directions - vertical and horizontal shake corrected by optical image stabilization and the third, by way of electronic image stabilization, facilitates correction for lateral-roll shake. By employing a wider camera shake correction angle and improved compensation algorithms, blur caused by rolling wrist movements is reduced so users can shoot smoother movie footage on the move.</p>

<p><br />
<B>Prime Functionality</B></p>

<p>Sony's powerful BIONZ(TM) imaging processor is adding a Face Touch function. With Face Touch, users can select a person to be prioritized by the camcorder simply by touching a detected face on the screen. The camcorders prioritize and optimize focus, skin color, and brightness for the selected individual, even if they leave the scene, for the entire recording session. This new feature is a function of Face Detection, which also incorporates Smile Shutter(TM) technology to capture candid smiling photos while simultaneously recording video. When Face Touch is activated, the Smile Shutter feature only activates automatically in response to the smiles of the selected person.</p>

<p>These models also have a back-illuminated "Exmor R" CMOS sensor to provide stunning low light performance with approximately twice the sensitivity compared to Sony's existing front-illuminated CMOS sensor at F2.0. The sophisticated G lens fuses advanced optics and low dispersion aspheric glass elements for accurate color reproduction and sharp, detailed images. A six-blade aperture produces circular "bokeh" defocus effects for creative shooting possibilities.</p>

<p>To effortlessly track your destinations on a map, the camcorder's built-in GPS antenna and NAVTEQ(R) digital maps geo-tag your videos and photos. Geo-tagged content is marked by a virtual push pin at each shot location and can be played back on the camcorder map index display on the three-inch (measured diagonally) wide touch panel LCD.</p>

<p>Introducing new technology to down-convert from AVCHD(TM) to MPEG2, Sony eliminates the need for a PC and allows for simple DVD creation with the optional DVDirect Express (VRD-P1) DVD writer.</p>

<p>When the camcorders are connected to the DVDirect Express (sold separately for around $150) via a USB cable, they will instantly burn HD video footage onto a DVD. The camcorder can even down-convert content and burn DVDs in standard-definition picture quality, providing familyographers a way to "future proof" their memories. The down conversion feature allows owners of standard-definition players to capture video in the highest quality and have the option of playing in standard-definition now or saving HD content for when they upgrade to a Blu-ray disk player at a later time.</p>

<p>Other powerful features include a built-in zoom microphone with Dolby(R) Digital 5.1-channel surround sound and an instant power-on feature when the LCD is opened that lets you capture the moment without delay. The camcorders' advanced user interface features a new operation bar, which allows scroll searching for all menu items, and a customizable shortcut menu. Improving upon the Highlight Playback feature that personalizes video footage by generating a video slideshow with theme transitions and background music, Sony introduces Highlight Scenario, which saves up to eight highlight scenes for viewing again later. These models also include Picture Motion Browser software to easily view, edit, organize and upload images to many major video and photo sharing Web sites. Mac users can transfer AVCHD recorded data and edit video clips in HD image quality using iMovie software.</p>

<p>In addition to built-in flash memory, the models can record content to optional Memory Stick PRO-HG Duo(TM) HX media (currently sold separately in capacities up to 16GB, a 32GB card will be available in September). Using Sony's PRO-HG Duo HX format, consumers can transfer nearly two hours of full high-definition video to a PC in approximately 13 minutes (using supplied adapter).</p>

<p>Price and Availability</p>

<p>The HDR-CX500V and HDR-CX520V, will be available in September for about $1,100 and $1,300 respectively. They will be available at Sony Style(R) retail stores, online through <a target="_blank" href="http://www.sonystyle.com">www.sonystyle.com</a> and at authorized dealers nationwide.</p>

