<p><strong>UPPER SADDLE RIVER, NJ (8/24/09) -- </strong>Onkyo has introduced three network- and internet-radio-capable, 9.2-channel THX Ultra2 Plus certified A/V receivers that deliver all the power, processing, and features to support cutting edge home theater and whole-house entertainment. The three new models, the Onkyo TX-NR1007, TX-NR3007, and top-of-the-line TX-NR5007, will all be shipping to dealers before the end of September.</p>

<p>"With nine amplifier channels, dual independent subwoofer outputs, and up-to-the-minute networking and AV processing, the flexibility of the 'double-0' series is unprecedented," said Paul Wasek, Marketing Manager, Onkyo USA. "You can have a full-tilt 9.2-channel theater using Audyssey DSX or Dolby ProLogic IIz, or a great five-channel theater with added power to the main speakers or to additional stereo zones - the list of possibilities is a long one. These receivers take home theater to the current frontiers of networking, audio, and video performance."</p>

<p>All three new receivers include a rear-panel Ethernet port, and provide advanced networking capabilities with streaming for Pandora, Rhapsody, vTuner, and Sirius Internet Radio services. Each receiver is Windows 7 compatible, and carries DLNA (Digital Living Network Alliance) 1.5 certification, ensuring optimal compatibility with other network-enabled equipment throughout the home.</p>

<p>The two top models in Onkyo's TX-series AV receivers, the TX-NR5007 and TX-NR3007, feature eight and seven HDMI 1.3a inputs each, respectively, including one on each front panel. Video processing, including upscaling of all video inputs to 1080p/24, is handled by an advanced HQV Reon-VX chipset. The less expensive TX-NR1007 features a total of six HDMI inputs on the rear panel, and 1080p upscaling via Faroudja DCDi Cinema processing. All three models include dual parallel HDMI outputs, allowing for display of current programming on dual monitors, simultaneously or independently, for increased setup flexibility. These models also include powerful ISF Certified Calibration Controls (ISFccc) for independent optimization and fine-grain adjustments of a full range of video sources, including day, night, and custom modes for each input.</p>

<p>Audio processing duties in each new model is handled by a trio of TI Aureus &trade; DSP chips, and is compatible with every major surround format currently in use. Premium quality Burr Brown DACs-32-bit in the case of the TX-NR5007--in conjunction with Onkyo's exclusive VLSC (Vector Linear Shaping Circuitry) are employed for digital-to-analog conversion. In addition to audio decoding, the receivers include a full suite of acoustic setup and optimization technologies from THX (Loudness Plus) and Audyssey (MultEQ XT, Dynamic EQ, and Dynamic Volume) that custom tailor audio output to ensure optimal system performance in any environment and at any listening level. Additionally, the TX-NR5007 and TX-NR3007 are the first Onkyo Receivers to include Dolby Volume, which maintains listening volume at a consistent level regardless of changes in the source material, such as commercials, or when switching from one source to another, such as TV to DVD.</p>

<p>The nine power amplifiers can be configured for a variety of different purposes. One option is for a full 9.2-channel theater system that includes independent left and right subwoofers, and two additional 'height' or 'stereo-wide' speakers when using Audyssey DSX or Dolby's Pro Logic IIz processing. The system can also be configured to power two independent stereo zones in addition to a five-channel theater set-up. Two channels can also be combined with the front left/right channels to increase power to the main speakers via bi-amplification or, in the case of the TX-NR5007 and TX-NR3007, in a bridged configuration. Finally, in the TX-NR5007 two channels can be tasked to power a second pair of main speakers for dedicated two-channel listening, allowing for independent 7.2-channel home theater and stereo audio speaker setups in a single room.</p>

<p>The TX-NR5007 is rated at 145 watts per channel, and its power supply features a massive toroidal transformer and a pair of 22,000 microfarad storage capacitors to handle even the most dynamic source material. Both the TX-NR5007 and the 140-watt-per-channel TX-NR3007 feature separate power supply transformers for audio and video processing and reproduction. All three receivers, including the 135-watt-per-channel TX-NR1007, feature a push-pull amplification topology, with three-stage inverted Darlington circuitry and the company's highly regarded WRAT (Wide Range Amplifier Technology) for highly dynamic and linear response throughout the audible spectrum.</p>

<p>The TX-NR5007, TX-NR3007, and TX-NR1007 each include Onkyo's exclusive Universal Port, allowing for one-cable expansion with the company's HD Radio tuner and/or iPod dock unit. Each model is firmware updatable via Ethernet or (on the TX-NR5007 and TX-NR3007) front panel USB port. All three include Onkyo's new bidirectional and customizable preprogrammed remote control that dramatically simplifies the process of programming all the components in your system.</p>

<p>The Onkyo receivers will be available in September at suggested retail prices of $2,699 for the TX-NR5007, $2,099 for the TX-NR3007, and $1,599 for the TX-NR1007.</p>

