<p><B>Santa Clara, CA, FEBRUARY 24, 2009</B> - VUDU, Inc., a leading provider of digital on-demand entertainment products and services, today announced it has achieved another industry milestone by becoming the first on-demand service to offer high definition  movies for download to own on its popular 1080p Internet Movie Player. HD movies are available for purchase today to all Vudu owners.</p>

