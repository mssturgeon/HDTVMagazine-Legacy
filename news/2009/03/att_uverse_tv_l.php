				<p class="prtitle">AT&T U-verse TV Lineup Expands To 100 Or More High Definition Channels In Every U-verse TV Market</p>

<p><B>DALLAS, March 2 /PRNewswire-FirstCall/</B> -- For viewers who want more High Definition (HD) channels at a great value, cable isn't even a question. AT&T* today announced that AT&T U-verse(SM) TV now offers 100 HD channels -- exceeding the HD channel lineups offered by the local cable providers in every U-verse TV market.</p>

<p>With recent expansions to the U-verse TV HD lineup, customers can now enjoy ABC Family HD, Disney Channel HD, Disney XD HD, ESPNews HD and ESPNU HD as part of their existing HD service subscription, depending on their programming package. With the additions, U-verse TV offers 100 or more HD channels in every U-verse TV market.</p>

<p>"In this economy, consumers are turning to home entertainment to save money and get better value, and they should pick a provider that offers them more HD bang for their buck. That's U-verse TV," said Dan York, executive vice president of content and programming, AT&T Converged Services. "These great HD additions from the Walt Disney Company help us with important strategic content initiatives and allow us to deliver an even bigger HD lineup to customers. With spectacular picture quality, HD-ready equipment included in every U-verse TV package, and the ability to watch your favorite HD recordings when and where you want with Total Home DVR - you can't beat the U-verse TV HD experience."</p>

<p>AT&T U-verse TV has two HD subscription options. HD service is included with the U450 programming package and available for $10 a month with any other U-verse TV programming package. U-verse HD customers can get even more HD-exclusive channels with the HD Premium package for an additional $5 a month. All U-verse TV packages include HD-ready equipment, and most packages include an HD-ready Total Home DVR, which gives you the ability to record your HD programs from a single DVR and watch them on any connected TV.</p>

<p>AT&T U-verse TV is the only 100 percent Internet Protocol-based television (IPTV) service offered by a national service provider, making AT&T U-verse one of the most dynamic and feature-rich services available today. AT&T U-verse TV ranked "Highest in Residential Television Service Satisfaction in the North Central, South, and West Regions," according to the J.D. Power and Associates 2008 Residential Television Service Provider Satisfaction Study(SM).</p>

<p>For additional information on AT&T U-verse -- or to find out if it's available in your area -- visit http://uverse.att.com/. Customers can get more information about U-verse TV programming and television events by visiting http://uverse.att.com/uconnect.</p>

