<p class="prtitle">LG Electronics, Samsung Electronics, Sony Pictures Entertainment and Valens Semiconductor to Launch the HDBaseT&trade; Cross-Industry Alliance</p>

<center><i>Companies Invite Key Players to Join the Newly Formed Alliance

<p>HDBaseT&trade; Technology Enables the Whole-home Distribution of Uncompressed HD Multimedia Content to Address the Needs of Home Entertainment and Related Commercial Applications</center></i><br /><br />
<br /></p>

<p><strong>Seoul, Korea; Culver City, CA; Hod-Hasharon, Israel (December 15, 2009) - </strong>LG Electronics, Samsung Electronics, Sony Pictures Entertainment and Valens Semiconductor announced today that they intend to launch a cross-industry alliance to promote and standardize the HDBaseT&trade; technology for whole-home distribution of uncompressed HD multimedia content.</p>

<p>The HDBaseT Alliance will engage key players across the consumer electronics and the content industries. Working together, they will create a global standard for advanced digital media distribution. The Alliance’s standardization activities will cover the entire value chain of the digital media ecosystem and the various market segments: TV sets, projectors, professional AV equipment, home theater, content providers, IT companies and more.</p>

<p>As the consumption of and demand for high quality HD content increases, so does the interest of the end user in extending their entertainment experience to their entire home. Consumers are looking for a way to connect TVs and other display equipment with entertainment devices, such as a Blu-ray DVD player, for in-home converged distribution of HD multimedia content. Some of the existing technologies are limited in terms of bandwidth and cannot support uncompressed video. The demand for in-home converged distribution of HD multimedia content and the lack of adequate existing technologies are driving the industry toward an HD digital connectivity standard such as HDBaseT, which increases distance of uncompressed HD multimedia content transfer, expands distribution, simplifies installations and lowers overall system cost.</p>

<p>"As the demand for high-quality HD content distribution in the entire home is already huge, we are hoping that HDBaseT will play the trigger role in advancing this market, since HDBaseT enables simultaneous multi-room distribution of uncompressed HD Multimedia as well as data, control and power over a single CAT5e cable," said ByungJin Kim, research fellow, LG Electronics.</p>

<p>“HDBaseT is an advanced solution for securely delivering high definition video content within the home network,” said Mitch Singer, CTO, Sony Pictures Entertainment.</p>

<p>“We firmly believe that in today’s industry a standard must have broad consensus and support from the major players in the industry.  For this purpose, we are actively working with such leading companies across the value chain to assure broad support and active participation in the newly formed HDBaseT Alliance,” said Dror Jerushalmi, CEO, Valens Semiconductor.</p>

<p>Key players in the consumer electronics industry have been introduced to HDBaseT technology and it is expected that other global market leaders will join the HDBaseT Alliance and together work to finalize the standard.</p>

<p>The four founding companies say that the Alliance is expected to release new details about more global leaders joining the Alliance in the upcoming weeks. The HDBaseT Alliance plans to attend the 2010 International Consumer Electronics Show held January 7-10 in Las Vegas, Nevada.</p>

