<p><strong>DALLAS, Dec. 14 /PRNewswire-FirstCall/ -- </strong>AT&amp;T* today announced several additions to the AT&amp;T U-verse(SM) TV channel lineup, including five new High Definition (HD) channels and new international programming channels for Filipino and Cantonese viewers.</p>

