				<p class="prtitle">DIRECTV Partners With HDNet and HDNet Movies to Offer On Demand Programming</p>

<center><i>Top satellite service now offers 20 hours of HDNet programming and over 25 movies from HDNet Movies each month to its HD subscribers</center></i><br />
<br />

<p><img src="http://www.hdtvmagazine.com/news/images/2009-11-04_hdnet.jpg" alt="HDNet" height="68" width="192" class="keyimg"><strong>DALLAS, Nov. 3 /PRNewswire/ -- </strong>HDNet, the independent network delivering all of its programming in true high definition, announced today a deal in which DIRECTV, the nation's No. 1 satellite service, now offers more than 20 hours of HD programming from HDNet, and more than 25 movies from its sister network HDNet Movies, on a video on demand basis every month.</p>

<p>"HDNet is excited to partner DIRECTV on their VOD offering," said Mark Cuban, chairman and co-founder of HDNet. "Now, HD subscribers will have access to HDNet's critically acclaimed movies, in-depth news, provocative originals and exciting MMA coverage not only on our linear channels but also on a video on demand basis."</p>

<p>"HDNet has been a part of the DIRECTV platform since its debut in 2001 and we are excited to continue to grow our relationship with the launch of its new on demand service," said Dan Hartman, senior vice president of Programming for DIRECTV, Inc. "HDNet's line up of unique movies and sports programming is a perfect addition to the DIRECTV On Demand platform, which offers more than 5,000 titles for customers to choose from."</p>

<p>DIRECTV HD customers will be able to experience the unique and provocative brand of content that HDNet offers, including blockbuster concerts, in-depth news from "Dan Rather Reports", exciting Mixed Martial Arts events from around the globe," "Ring of Honor Wrestling, "New York Confessions," and of course, the exotic travel locals and beautiful women of "Get Out!" and "Bikini Destinations."</p>

<p>The agreement allows DIRECTV customers with HD Access to enjoy HDNet's great, original programming, much of which will be available within 24 hours of its network premiere.</p>

<p>DIRECTV customers who subscribe to the HD Extra Pack will also have access to more than 25 movies from HDNet Movies' slate of top performing, critically acclaimed feature films and box office hits - each and every month. As always, these films will be presented in their original aspect ratio, uncut, unedited and delivered in true high definition.</p>

<p>DIRECTV subscribers can see great films including, "Lost in Translation" starring Bill Murray, "21 Grams," starring Naomi Watts, classics like "Hoosiers" starring Gene Hackman and "Waterworld," starring Kevin Costner, comedies such as "The Nutty Professor" starring Eddie Murphy, and thrillers like "Darkman," starring Liam Neeson and "The Illusionist," starring Edward Norton and many, many more.</p>

<p>The programming provided by HDNet and HDNet Movies on DIRECTV will be refreshed on a weekly basis.</p>

