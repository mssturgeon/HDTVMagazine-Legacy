<center><i>Enhancements Include Networking, Audio Return Channel, 3D Capability, Improved Performance and New Connectors</i></center><br />
<br />

<p><B>SUNNYVALE, Calif.--(BUSINESS WIRE)</B>--HDMI Licensing, LLC, the agent responsible for licensing the High-Definition Multimedia Interface&reg; (HDMI&reg;) specification, today announced the features that will be incorporated in the upcoming HDMI 1.4 specification. This latest version of the HDMI specification will, among other advancements, offer networking capabilities with Ethernet connectivity and will add an Audio Return Channel to enable upstream audio connections via the HDMI cable. The HDMI specification 1.4 will be available for download on the HDMI LLC website no later than June 30, 2009.</p>

<p>The HDMI 1.4 specification will offer the following enhanced functionalities:</p>

<p><br />
<B>    * HDMI Ethernet Channel</B></p>

<p>The HDMI 1.4 specification will add a data channel to the HDMI cable and will enable high-speed bi-directional communication. Connected devices that include this feature will be able to send and receive data via 100 Mb/sec Ethernet, making them instantly ready for any IP-based application.</p>

<p>The HDMI Ethernet Channel will allow an Internet-enabled HDMI device to share its Internet connection with other HDMI devices without the need for a separate Ethernet cable. The new feature will also provide the connection platform to allow HDMI-enabled devices to share content between devices.</p>

<p><br />
<B>    * Audio Return Channel</B></p>

<p>The new specification will add an Audio Return Channel that will reduce the number of cables required to deliver audio upstream for processing and playback. In cases where HDTVs are directly receiving audio and video content, this new Audio Return Channel allows the HDTV to send the audio stream to the A/V receiver over the HDMI cable, eliminating the need for an extra cable.</p>

<p><br />
<B>    * 3D Over HDMI</B></p>

<p>The 1.4 version of the specification will define common 3D formats and resolutions for HDMI-enabled devices. The specification will standardize the input/output portion of the home 3D system and will specify up to dual-stream 1080p resolution.</p>

<p><br />
<B>    * 4K x 2K Resolution Support</B></p>

<p>The new specification will enable HDMI devices to support high-definition (HD) resolutions four times beyond the resolution of 1080p. Support for 4K x 2K will allow the HDMI interface to transmit content at the same resolution as many digital theaters. Formats supported include:</p>

<p>    * 3840x2160 24Hz/25Hz/30Hz<br />
    * 4096x2160 24Hz</p>

<p><br />
<B>    * Expanded Support For Color Spaces</B></p>

<p>HDMI technology now supports color spaces designed specifically for digital still cameras. By supporting sYCC601, Adobe RGB and AdobeYCC601, HDMI-enabled display devices will be capable of reproducing more accurate life-like colors when connected to a digital still camera.</p>

<p><br />
<B>    * Micro HDMI Connector</B></p>

<p>The Micro HDMI Connector is a significantly smaller 19-pin connector that supports up to 1080p resolutions for portable devices. This new connector is approximately 50% smaller than the size of the existing HDMI Mini Connector.</p>

<p><br />
<B>    * Automotive Connection System</B></p>

<p>The Automotive Connection System is a cabling specification designed to be used as the basis for in-vehicle HD content distribution. The HDMI 1.4 specification will provide a solution designed to meet the rigors and environmental issues commonly found in automobiles, such as heat, vibration and noise. Using the Automotive Connection System, automobile manufactures will now have a viable solution for distributing HD content within the car.</p>

<p>"The HDMI specification continues to add functionality as the consumer electronics and PC industries build products that enhance the consumer's HD experience," said Steve Venuti, president of HDMI Licensing, LLC. "The 1.4 specification will support some of the most exciting and powerful near-term innovations such as Ethernet connectivity and 3D formats. Additionally we are going to broaden our solution by providing a smaller connector for portable devices and a connection system specified for automobiles, as we see both more and different devices adopting the HDMI technology."</p>

<p>Consumers will also see new HDMI cables introduced to the market. In order to take advantage of the HDMI Ethernet Channel, consumers will need to purchase either a Standard HDMI cable with Ethernet, or a High Speed HDMI cable with Ethernet. Consumers connecting an external device to an in-vehicle HDMI-enabled HD system will need the new Automotive HDMI cable. Consumers can expect to see new HDMI 1.4 cables introduced to the market when new HDMI 1.4 devices are available.</p>

<p>Consumers will have a choice of the following HDMI cables:</p>

<p>    * Standard HDMI Cable - supports data rates up to 1080i/60;<br />
    * High Speed HDMI Cable - supports data rates beyond 1080p, including Deep Color and all 3D formats of the new 1.4 specification;<br />
    * Standard HDMI Cable with Ethernet - includes Ethernet connectivity;<br />
    * High Speed HDMI Cable with Ethernet - includes Ethernet connectivity;<br />
    * Automotive HDMI Cable - allows the connection of external HDMI-enabled devices to an in-vehicle HDMI device.</p>

<p>The HDMI standard continues to grow in the marketplace with now over 850 adopters worldwide. The growing adoption of the HDMI specification by both consumer electronics and PC manufacturers further strengthens its position as the worldwide standard for high-definition digital connectivity. According to market research firm In-Stat, over 394 million HDMI-enabled devices are expected to ship in 2009, with an installed base of 1 billion devices. By the end of 2009 100% of digital televisions are expected to have at least one HDMI input.</p>

<p>The HDMI specification 1.4 will be available for download at http://www.hdmi.org no later than June 30, 2009.</p>

