<p><B>RIDGEFIELD PARK, N.J.--(BUSINESS WIRE)</B>--Samsung Electronics America, a subsidiary of Samsung Electronics Corporation, the number one worldwide brand of LCD display products, today announced the release of its 70 Series Monitors: the P2070, P2370 and P2370HD. These slim LCD monitors, with screen depths of 30 mm (1.18 inches) for the P2070 and P2370 and 65.5mm (2.58 inches) for the P2370HD and Touch of Color (ToC&trade;) design, are the latest release of Samsung's high performance displays.</p>

