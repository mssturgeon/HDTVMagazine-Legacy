<p>The P2370 offers full HD 1080p resolution (1920x1080) for optimized viewing of HD content. For full HDTV capability, the P2370HD builds on the 1080p capabilities of the P2370 with the addition of a HDTV tuner, integrated speakers with SRS TruSurround HD(r) and remote control. In addition, the P2370HD also has HDMI and component inputs for additional connections such as Blu-Ray, set-top boxes and game consoles providing users with a display that is ready for work and play.</p>

