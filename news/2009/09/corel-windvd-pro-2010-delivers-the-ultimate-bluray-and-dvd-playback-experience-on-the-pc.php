<p>Whether you're watching a Blu-ray Disc&reg; or an AVCHD&trade; or SD home movie, WinDVD Pro 2010 provides the life-like video quality that people expect from an HD experience. Increased format support lets you watch popular video formats, even direct from your camera or camcorder. New support for BD-Live gives access to bonus features and exciting new ways to interact with your disc content. The software is also designed for the latest technologies in Windows&reg; 7, giving users hands-on control when used with Windows Touch enabled hardware.</p>

<p>"With more than 200 million units sold around the world, WinDVD is widely recognized as the industry's best DVD and Blu-ray playback software and with the latest version we wanted to take our users' experiences with the software even further. Every enhancement in WinDVD Pro 2010 was designed to provide the best possible PC movie experience. Thanks to the new performance enhancements, actions across the entire application are faster, fine details and special effects are clearer and users can now have full access to interactive content. And it is all delivered through a clean and easy-to-use interface that supports Windows 7 and Windows Touch," said Nick Davies, Senior Vice President of Product Management and Product Marketing at Corel.</p>

<p><br />
<strong>New to Corel WinDVD Pro 2010</strong></p>

<p>Outstanding Blu-ray Playback<br />
    * Experience high-definition Blu-ray movies with stunning 1080p sharpness and next-generation surround sound<br />
    * Discover amazing extras, bonus features and exciting ways to interact with content through new support for BD-Live, an interactive Blu-ray feature</p>

<p>Advanced HD Upscaling for Standard-Definition DVDs<br />
    * Experience a new, innovative GPU-based solution or the latest Trimension&trade; All2HD technology to upscale SD video to near-HD quality. Enjoy DVD playback that is smoother than ever before</p>

<p>Superior Speed and Performance<br />
    * Enjoy an experience that's faster than ever. Thanks to optimization for new CPUs and GPUs, WinDVD Pro 2010 outpaces the competition, providing quick, clear Blu-ray and DVD playback<br />
    * Make your battery last the whole movie! New battery optimization delivers optimal performance to extend the battery life on Windows Vista&reg; and Windows 7 without comprising video quality</p>

<p>Windows 7 Touch Control<br />
    * Explore new Windows 7 features, including Windows Touch, Jump Lists and Taskbar integration<br />
    * Access WinDVD controls with the touch of a finger on Touch-enabled hardware</p>

<p>Refreshed Look and Feel<br />
    * Enjoy a clean and easy-to-use new interface that offers faster access to controls</p>

<p>Incredible Surround Sound<br />
    * Discover amazing surround sound and effects with Dolby&reg; Digital Technology and DTS Neo:6&trade;<br />
    * Experience an authentic surround sound effect, even through headphones, with WinDVD Virtualization technology</p>

<p>Comprehensive video support<br />
    * Format Support: BD-ROM (BonusView&trade;, BD-Live), BD-R/BD-RE, AVCREC&trade;, AVCHD&trade;, MPEG2 PS/TS, Windows Media&reg;*, QuickTime&reg;<br />
    * Video Codec: MPEG2, VC1, MPEG-4/AVC (H.264)<br />
    * Audio format support: Dolby&reg; Digital/Dolby Digital Plus/Dolby TrueHD, DTS&reg;/DTS-HD&trade; Master Audio&trade;<br />
    * Audio Technology: Dolby Headphone, Dolby Virtual Speaker, Dolby Pro Logic IIx and DTS Neo: 6<br />
    * Hardware: GPU optimization support for NVIDIA&reg;, ATI&reg; and Intel&reg; hardware</p>

<p>Extensive Windows Support<br />
    * Enjoy WinDVD Pro 2010 on Windows&reg; XP, Windows Vista and Windows 7</p>

<p><br />
<strong>Pricing and Availability</strong></p>

<p>Corel WinDVD Pro 2010 is now available globally in English, Chinese Traditional, Dutch, French, German, Italian, Polish and Spanish as an electronic software download (ESD). In the US and Canada, the product is available at the suggested retail price of $99.99. English, Chinese Traditional and German versions of Corel WinDVD Pro 2010 will also be available at leading retailers around the world starting later this month.</p>

<p>For customers who don't require Blu-ray support, but want to enjoy HD (AVCHD) video playback and advanced SD upscaling, Corel also offers WinDVD 2010 standard edition for $49.99 (USD and CDN) available exclusively from Corel or as part of the new Corel&reg; Digital Studio&trade; 2010 suite.</p>

