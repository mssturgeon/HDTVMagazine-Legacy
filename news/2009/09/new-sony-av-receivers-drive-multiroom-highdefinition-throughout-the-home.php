<p><strong>ATLANTA, Sept. 9 /PRNewswire/</strong> -- (CEDIA Booth #1409) - Sony today introduced two new "Elevated Standard" (ES) audio/video receivers, including its first to offer control over an IP network, the STR-DA5500ES.</p>

<p>Both the STR-DA5500ES and new STR-DA3500ES are designed as easy-to-use solutions for expanding high-definition entertainment to multiple rooms of the home.</p>

<p>"For over 25 years, ES has represented the most technologically advanced products Sony has to offer," said Neal Manowitz, director of Sony's home audio and video business. "By adding features like Control4 certification and enhanced multi-room HD support, Sony continues to raise the bar in the high-definition digital home business."</p>

<p>The new STR-DA5500ES model features IP network control, allowing installers to easily integrate into Control4 home automation systems. It will also support special Control4 developed and certified IP network applications, such as advanced configuration and diagnostic tools for dealers, email and text alerts, and more.</p>

<p>Additionally, the receiver is the company's first to feature Automatic Phase Matching (APM), which corrects for phase differentiation between front, center, and surround speakers, ensuring an ideal sound stage regardless of speaker type.</p>

<p>Also new, the STR-DA5500ES A/V receiver features Sony's innovative new HD Digital Cinema Sound . Developed in consultation with Sony Pictures Entertainment, the new technology was designed to transform and replicate both the sound quality and acoustics of a movie theater in the home environment, creating an unmatched viewing experience for both Blu-ray Disc(TM) and DVD(TM).</p>

<p>The network capabilities of the STR-DA5500ES model also allow users to easily view photos and access digital music and videos from a Digital Life Network Alliance(TM) (DLNA) compliant source within a home broadband network when connected via an Ethernet cable. Additionally, the connection provides access to both Shoutcast Internet Radio and Rhapsody Music Service and functions as the source for easy firmware upgrades.</p>

<p>The STR-DA5500ES model offers a 120-watt power amplifier x 7 (8 ohms, 20 Hz - 20 kHz, .09 percent THD) and a variety of high definition connections, including six HDMI inputs (five rear, one front) and two HDMI outputs.</p>

<p>The model supports 1080/24p video signals and x.v.Color(TM) and Deep Color(TM) video codecs, as well as all the latest audio formats (Dolby Digital Plus, Dolby TrueHD, DTS HD, DTS ES, Dolby Digital EX, Dolby Pro Logic IIx and 8 channel Linear PCM).</p>

<p>The STR-DA5500ES also offers Faroudja chip up-scaling of all sources to 1080p in the main zone and 1080i in a second zone, ensuring a consistent, sharp picture. Further, each connected video zone has a high-grade, icon-driven menu system that allows for simple device and content navigation. Audio can also be expanded into a third zone.</p>

<p>The model features Sony's Digital Media Port(TM) for simple connection to iPod and other digital music players, and is both XM and Sirius ready.</p>

