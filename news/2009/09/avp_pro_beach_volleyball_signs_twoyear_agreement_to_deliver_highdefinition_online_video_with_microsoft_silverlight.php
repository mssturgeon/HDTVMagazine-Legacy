<p><strong>LOS ANGELES, Sept. 15 /PRNewswire/ -- </strong>AVP Pro Beach Volleyball announced today they signed a two-year agreement with Microsoft Corp. to use Microsoft Silverlight 3 to deliver high definition (HD) live streaming video of professional beach volleyball matches to fans around the world. AVP will utilize its new AVP.com HD Video Player application powered by Silverlight 3 and Internet Information Services (IIS) Live Smooth Streaming to bring worldwide professional beach volleyball fans a new and unique option for watching their favorite sport.</p>

<p>"Silverlight is the premium platform for online streaming in the market today," said Jason Hodell, CEO, AVP Pro Beach Volleyball. "We are eager to enhance our streaming video capabilities to bring our beautiful sport to a larger audience online. We intend to cover both outer court and stadium action to bring fans an authentic game day experience."</p>

<p>Microsoft worked with the AVP to develop the Silverlight AVP HD Video Player and will license AVP adequate license right to deploy it on AVP and any AVP partner websites. Additionally, AVP and Microsoft will share web presence on each company's respective website.</p>

