<strong>Epson Home Cinema 8100</strong></p>

<p>The value-packed Home Cinema 8100 features an improved contrast ratio of up to 36,000:1 (double that of previous models) and higher brightness - 1,800 lumens color and white light output(ii) - for outstanding image quality in dark or lighted rooms. The projector's exclusive Dynamic Iris system contributes to the dramatic contrast improvement, allowing light to be controlled on a frame-by-frame basis at up to 60 times per second, making it ideal for fast-action movies with frequent scene changes. Designed for home entertainment and AV enthusiasts on a budget, this projector offers high-quality home entertainment for enjoying movies, video games, sports, and more.</p>

<p><br />
<strong>Epson Home Cinema 8500 UB</strong></p>

<p>Along with the latest D7 chip set, this high-quality projector adds Epson's C2Fine and UltraBlack(TM) technology for superb black levels and vivid images. Further boosting black levels, the Home Cinema 8500 UB includes brightness of 1,600 lumens color and light output and new dual-layered auto iris technology, allowing for an impressive contrast ratio of up to 200,000:1. As a result, the projector controls light intensity more effectively, causing dark images to appear even darker and blacks to appear even richer and deeper.</p>

<p>The projector also features Epson's new Super-resolution(TM) technology to create a sharper, more detailed picture resolution ideal for broadcast signal noise reduction or enhancing the quality of poor DVD transfers. Super-resolution technology improves the resolution of a blurred image, allowing consumers to fully enjoy high-definition quality at all times. Epson has also added new real color reproduction capabilities, which delivers more natural and precise colors, allowing viewers to experience the true-to-life colors filmmakers intended.</p>

<p>To ensure sharp, clear images, the projector features Epson's 12-bit 3LCD driver technology and a built-in Silicon Optix HQV Reon-VX scaling and de-interlacing video processor. This processor reduces mosquito and block noise and augments multi-level contrast enhancement to further improve picture quality. The Home Cinema 8500 UB also features enhanced FineFrame(TM) technology resulting in smoother frame interpolation, sharper video quality and the elimination of judder.</p>

<p>Shared Features of the Home Cinema Line - The Home Cinema 8100 and 8500 UB share features designed to improve image quality and total cost of 3LCD projector ownership, including:</p>

<ul><li>Cinema Filter: Delivers larger color space for improved color fidelity.</li><li>Fujinon OptiCinema(TM) Multi-Lens Optics System: Projects clean, precise edges with consistent image quality across the entire screen, expanding installation flexibility.</li><li>Pre-set Color Modes: Features seven color modes (Dynamic, Living Room, Natural, Theatre, Theatre Black 1, Theatre Black 2, x.v.Color) for optimal viewing in any environment.</li><li>E-TORL  (Epson Twin Optics Reflection Lamp): Provides optimum light uniformity and increased light output for screen sizes larger than ten feet with exclusive 200 watt high efficiency design; uses less energy for up to 4,000 hours of lamp life(iii).</li><li>Advanced Dust Filtration System: Ensures efficient power use, reduced cool-down periods, lower fan speeds, quieter operation (only 22 db), and 98 percent efficiency for longer filter life.</li><li>Input Options: Features two HDMI 1.3a inputs with Deep Color support, high definition component video input, S-video input, composite video input, and VGA-type RGB input (D-sub 15).</li></ul>

