<strong>Pricing and Availability</strong></p>

<p>The Seagate FreeAgent Theater+ HD media player is available immediately via Seagate.com and other online retailers. It comes as a stand-alone unit for use with any USB storage device for a manufacturer's suggested retail price (MSRP) of $149.99, or bundled with a 500GB FreeAgent Go drive for a manufacturer's suggested retail price (MSRP) of $289.99. The FreeAgent Theater+ Wireless Adapter is expected to be available in October as a separate accessory through Seagate.com for $69.99.</p>

