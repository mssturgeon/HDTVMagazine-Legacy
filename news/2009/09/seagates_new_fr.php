				<p class="prtitle">Seagate's New FreeAgent Theater+(TM) HD Media Player Enhances the Enjoyment of Digital Home Movies and Photos</p>

<center><i>Bring Your Digital Media to Life with True HD and Dolby(R) Digital Surround Sound Technology</center></i><br />
<br />

<p><img src="http://www.hdtvmagazine.com/news/images/2009-09-15_seagate_freeagent_theater_hd_media_player.jpg" alt="Seagate FreeAgent Theater+ HD Media Player" height="123" width="192" class="keyimg"><strong>SCOTTS VALLEY, Calif., Sept. 15 /PRNewswire-FirstCall/</strong> -- Seagate (NASDAQ: STX) , the worldwide leader in hard disk drives and storage solutions, today unveiled its new FreeAgent Theater+(TM) [Plus] HD media player, the next generation home theater solution designed to instantly and easily connect your digital media library to your home entertainment system.</p>

<p>The FreeAgent Theater+ HD media player leverages a docking system unique to Seagate FreeAgent Go(TM) portable drives and accessories, providing a quick and easy way to connect your external hard drive to your television or home entertainment center. After loading the drive with your favorite movies, videos, music and pictures from the home PC, simply slide it into the FreeAgent Theater+ dock to get instant access to your digital media library. With the FreeAgent Theater+ player, you can just sit back, relax, point, click and enjoy as digitally captured memories and your favorite movies come to life in 1080p HD video, DTS(TM) 2.0 + Digital Out, or Dolby Digital technology. The interface is easily navigated with the included remote control, and you can choose from video, photos or music with the up/down arrows on the remote to make your selection.</p>

<p>The Seagate FreeAgent Theater+ HD media player includes two additional USB ports for connecting other USB attached storage devices. Also incorporated into FreeAgent Theater+ is an Ethernet port for network connectivity, which allows access to digital media through your home network. Seagate intends to launch a USB Wireless Adapter in October to enable this same access with 802.11n wireless connectivity to a home network. Enjoy it all, with the included new and improved remote control, from the comfort of your couch.</p>

<p>"There is so much media that is now being captured and created through various methods and stored on the PC, yet the computer is not the ideal way to enjoy these photos and videos," said Terry Cunningham, senior vice president, Seagate Branded Solutions. "The FreeAgent Theater provides the easiest way to view and enjoy video and photos on your HDTV. Simply load up a Seagate FreeAgent Go(TM) hard drive and drop it into the FreeAgent Theater+ HD media player dock. It's a behavior we've all been familiar with for years with VHS and DVDs, but now with digital HD enjoyment."</p>

<p>The new FreeAgent Theater+(TM) HD media player solution includes:<br />
  --  HDMI with 1080p HD video playback for high-definition content viewing<br />
  --  Dolby  Digital and DTS(TM) 2.0 + Digital Out audio support surround sound where available.<br />
  --  Unique docking system eliminates fumbling with cables and connections<br />
  --  Ethernet connection for accessing shared content on your network or streaming of content from the Internet<br />
  --  The optional wireless connectivity feature, expected to be available in October, will allow you to access stored content on any networked computer in the home at your fingertips<br />
  --  Two additional USB ports and one front-mounted port for digital cameras and additional storage devices<br />
  --  Simple sync software for PC and Mac  computers<br />
  --  Intuitive user interface with DVD-style navigation<br />
  --  Support for Windows  XP, Windows Vista , Windows  7, and Mac OS  X operating systems, as well as NTFS, FAT, FAT32, HFS+ file support<br />
  --  Component video and Composite video support<br />
  --  Optical S/PDIF audio and Stereo RCA sound options</p>

<p>The software included with FreeAgent Theater+ HD media player is a rich media-specific synchronization application that enables the automatic transfer and organization of all photo, music, video and movie files stored on your computer.</p>

<p><br />
<strong>Technical Specifications</strong></p>

<p>The Seagate FreeAgent Theater+ HD media player now supports even more Audio/Video and sound formats including MPEG-1, MPEG-2 (VOB/ISO), MPEG-4 (DivX /Xvid formats), DivX HD, Xvid HD, AVI, MOV, MKV, RMVB, AVC HD, H.264, WMV9, VC-1, M2TS, TS/TP/M2T, JPEG files up to 20 megapixels, BMP, GIF, PNG and TIFF. Audio formats supported include 5.1 channel surround sound, where available, and popular digital audio formats including: AAC, MP3, Dolby Digital, DTS, ASF, FLAC, WMA, LPCM, ADPCM, WAV and OGG. The FreeAgent Theater+ player also offers support for SAMI (smi), SRT and SUB subtitles. To download and transfer content to a Seagate FreeAgent Go portable drive using a Windows XP, Windows Vista or Windows 7 operated PC, a 256MB RAM and an available USB port is required. Mac computer users must be running Mac OS X 10.4.11 or 10.5.6 or later and have an available USB port. FreeAgent Theater connects to any TV with composite, component video or HDMI connection and stereo, optical S/PDIF or HDMI audio connection</p>

