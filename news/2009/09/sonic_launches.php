				<p class="prtitle">Sonic Launches BD PowerStation</p>

<center><i>Complete Blu-ray Disc Production Suite for Professional Videographers</center></i><br />
<br />

<p><strong>NOVATO, Calif., Sept. 4 /PRNewswire-FirstCall/ -- </strong>Sonic Solutions (NASDAQ:SNIC) today released the Sonic BD PowerStation(TM), a new cost-effective Blu-ray Disc (BD) production suite for professional videographers that's built on Sonic's Hollywood-standard CineVision HD video encoding and Scenarist authoring products, which have been used to create millions of DVD and BD titles worldwide.</p>

<p>Configured and priced to meet the needs of professional videographers, independent film and corporate video producers, Sonic BD PowerStation includes a special version of CineVision featuring multi-codec and segment controls, as well as DVDit! Pro HD for authoring BD and DVD titles and Scenarist QC(TM) Studio, a specialized BD emulation system that provides a detailed title proofing step during the authoring process. The result is the world's first truly focused BD authoring solution for desktop video professionals that delivers the ease of use, quality, speed and the dependability required for meeting tough production schedules.</p>

<p>Priced at $2,499.00, the Sonic BD PowerStation breaks the financial barrier-to-entry and immediately expands the availability of high-quality HD title creation solutions to a broader range of post-production facilities and specialized content owners looking to enter the Blu-ray Disc market. In concert with the recent reduction in AACS-LA licensing costs, Sonic's introduction of the BD PowerStation is perfectly timed to energize a hungry high-definition content creation industry and initiate a new wave of BD title production beyond the traditional Hollywood community.</p>

<p>"Sonic's BD PowerStation is the perfect combination of technology, product and price positioning that independent producers and small production houses have been waiting for to start offering BD production services. Until now, producing reliable replication-ready BD masters has been financially out-of-reach of most businesses," said Gary Bettan, VP of Business Development at Broadfield Distributing a leading distributor of desktop production solutions. "Sonic is the standard in Hollywood and since BD PowerStation is based on that same proven technology we feel confident that this is going to be a very important product for our market."</p>

<p>The Sonic BD PowerStation leverages the same exclusive video encoding and title multiplexing engines used in Sonic's industry-leading products for high-end facilities, which are responsible for the vast majority of commercially released BD titles. Capabilities include: support for MPEG-2 HD, VC-1 encoding with segment re-encoding that provides significant video encoding image quality controls; simple-to-learn and use authoring application that offers HD motion menus and interactive navigation programming without the need to understand the BD specification; and detailed title proofing based on Sonic's BD and DVD navigation engine that is used by leading CE vendors worldwide for set-top and in-car playback devices.</p>

<p>"BD PowerStation is another example of Sonic's unprecedented tradition of constant development and investment in the growth of the professional content production and delivery industry. We've combined our expertise in video encoding, authoring and playback with our clear understanding of 'what's important' to content owners, videographers and producers and delivered an amazing new suite to jump-start their BD title production," said Rolf Hartley, senior vice president and general manager, Sonic's Premium Content Applications Group. "With tried-and-true technology and break-through-pricing, BD PowerStation makes it possible for post-production facilities, independent and specialized film creators, event and corporate videographers to increase their services and use BD to showcase HD content."</p>

<p>Sonic will be demonstrating the Sonic BD PowerStation at the IBC convention, Hall 7, Stand 7.J38, September 11 to 15, Amsterdam, The Netherlands. The Sonic BD PowerStation is available now from Sonic's professional products reseller network and appointed distributors. For more information visit: <a target="_blank" href="http://www.sonic.com/go/bdpowerstation/">www.sonic.com/go/bdpowerstation</a>.</p>

