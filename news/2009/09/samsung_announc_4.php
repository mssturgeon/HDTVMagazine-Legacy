				<p class="prtitle"> Samsung Announces New Addition to the LCD TV Line Up at CEDIA EXPO 2009</p>

<center><i>Innovative Features and Design Unite with 65" LCD 650 Series Living Room Centerpiece; Samsung Showcases Its Latest Innovative TV and Home Theater Solutions for Enthusiasts</center></i><br />
CEDIA EXPO 2009<br />

<p><strong>ATLANTA--(BUSINESS WIRE)--</strong>Today at CEDIA EXPO 2009 (Booth #925) Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, announced availability for its latest CCFL-backlit LCD TV- the 65" LCD 650 Series (LN65B650) with 1080p resolution. The latest entry in the LCD 650 Series TVs will deliver Auto Motion Plus&trade; 120Hz refresh rate, fast 4ms response time for motion clarity and high dynamic contrast ratios for deeper, more natural blacks. The LN65B650 will also include expansive networking and connectivity capabilities including Samsung's Medi@2.0 Suite, the unique Touch of Color&trade; design, and it will meet the latest Energy Star® qualifications.</p>

<p>The Samsung booth will also showcase additional products designed for the true HD and home entertainment aficionado at the show, including the recently announced 8500 Series LED TV. In addition, CEDIA attendees can check out the latest line of Samsung Blu-ray players (BD-P1600, BD-P3600 and BD-P4600) that feature Netflix, Pandora, and YouTube&trade; streaming capabilities, as well as the new HT-BD8200 Blu-ray Soundbar, the latest Blu-ray Home Theater Systems (HT-BD7200, HT-BD3252 and HT-BD1250), and the HT-WS1 Soundbar. Samsung is located at Booth #925 at CEDIA EXPO 2009, just inside Main Entrance #3 in Building C.</p>

<p>"We are excited to showcase a variety of our offerings this year at CEDIA, which we feel are ideal for the custom installer or enthusiast looking to build the ultimate HD experience," said Tim Baxter, co-president of the Consumer Electronics Division, at Samsung Electronics America. "From our new 65" LCD 650 Series TV and latest LED TV's, to our Blu-ray players with network streaming capabilities and Blu-ray Home Theater Systems, we're aiming to set a high bar for delivering innovative technologies along with sleek design."</p>

<p><br />
<strong>65" LCD 650 Series</strong></p>

<p>Product Availability and Pricing</p>

<p>-- Price: LCD 650 Series - 65-inch class: $5,999.99<br />
