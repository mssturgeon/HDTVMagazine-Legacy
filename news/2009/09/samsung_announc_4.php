 <br />
Enhanced Picture Quality</p>

<p>The newest member of the LCD 650 Series TV family will utilize Samsung's proprietary Auto Motion Plus&trade; 120Hz frame-interpolation technology, partnered with a quick 4ms response time, to reduce blurring caused by fast movement shown onscreen. Advanced users can also customize how Auto Motion Plus handles judder and motion blur to suit their taste. The LN65B650's Ultra Clear Panel technology creates a vibrant picture by enhancing colors and reducing glare, even in rooms with a lot of ambient light. The Wide Color Enhancer 3 ensures accurate reproduction of colors with shows, movies, games and more, regardless of the viewing environment.</p>

<p>Connectivity and Content</p>

<p>The 2009 LCD 650 Series TVs (40-inch class and larger) come equipped with the new Samsung Medi@2.0 suite of multimedia features. Ready for both wired and wireless connectivity, the LCD 650 Series TVs offer access to a breadth of content via the Internet@TV - Content Service, built-in Content Library, DLNA and USB 2.0 ports to play movies and more. Internet@TV delivers access to Internet content from Yahoo!, Flickr, YouTube, and more while watching TV via easy-to-use TV widgets. The smart, user-friendly USB 2.0 interface makes it easy to share and view media files on your TV from a digital camera, MP3 player, or even a thumb drive.</p>

<p>A New Touch of Color&trade;</p>

<p>The LN65B650 further distinguishes itself with a Touch of Color, or ToC&trade;, design, which is produced through a dual-injection molding process that luxuriously coats a translucent surface over the frame for a premium look. The 65" includes a two-tone gradation of a stylish gray tone color along the curve of the bottom edge, with transparent color finishing along the bezel's outer edges.</p>

<p>Energy Friendly In Any Home</p>

<p>As with all of Samsung's LCD 650 Series TVs, the LN65B650 features low power consumption, meeting Energy Star® v3.0 efficiency guidelines and saving energy and money for the consumer. Additionally, the dual-injection process used to create the unique ToC bezel design is done so without the need for sprays, paints or dyes, which typically release Volatile Organic Chemicals (VOCs).</p>

<p>Samsung Electronics America's press releases, video content and product images are available at <a target="_blank" href="http://www.samsung.com/newsroom/">www.samsung.com/newsroom</a>.</p>

