<p><strong>BOULDER, Colo. and MENLO PARK, Calif., Sept. 23 /PRNewswire-FirstCall/ -- </strong>Silicon Mountain Holdings, Inc., (OTC:SLCME) (BULLETIN BOARD: SLCME) , a technology company specializing in high-performance interactive computing solutions, today announced their second generation all in one Allio LCD HDTV-PC products.</p>

<p>Like their first generation predecessors, Allio 2.0 products will be available in 42-inch and 32-inch high-definition LCD form factors, supporting a broad range of integrated PC configurations. The second generation Allio release comes less than a year after the initial launch. Introduced in November, 2008, response to the Allio all-in-one LCD HDTV PC concept was very strong. Allio products received major attention at the 2009 CES in Las Vegas, where Allio was praised for its pioneering innovation.</p>

<p>Demand for the first generation Allio HDTV PCs was so strong that inventories are completely sold out before the introduction of the new models. Allio and its resellers will be taking pre-orders in September, with the first units scheduled to ship by October 1st, 2009. "The response to Allio has been extraordinary," said Tre' Cates, President and CEO of Allio. "Strong sales in our first generation resulted in some excellent customer feedback on usability, functionality and use cases. We will be incorporating this priceless knowledge into our new models, and look forward to delivering an even better product to the market."</p>

<p>Like the first generation Allio models, two series are available: all in one Allio Lite and Allio Media Center. Improvements were made to both families.</p>

<p>Allio Lite integrates an Intel Atom based PC architecture into the HDTV for a cost-effective point-of-entry into the converged PC TV experience. These basic models offer processing power similar to a netbook and are perfect for surfing the web or performing other lightweight Windows-based computing tasks while watching TV, all at the same time, from the same interface. In addition to the low-cost entry level model, an all-new more powerful version of Allio Lite HDTV PC was also announced, which adds Blu-ray support and an integrated nVidia GeForce 9400 chip for better graphics performance.</p>

<p>The all in one Allio Media Center family of configurations takes convergence to another dimension by delivering a full-featured Intel multi-core PC. Video performance was also upgraded on Allio Standard models, where nVidia's GeForce 9300 mGPU provides plenty of horsepower for graphics and gaming. In addition to dual core skus based on Intel's PDC E6300 and Core2Duo E8400, Allio Standard now offers the powerful Core2Quad Q8400 as an option, making the all in one Allio a dream rig for online games like World of Warcraft.</p>

<p>Aesthetics and usability were also major considerations in the second edition. The matte finish on the first all in one Allio HDTV PC is now replaced with a shiny new piano black bezel and both models are thinner and lighter than their predecessors, making them ideal for wall mounting. The tray loading DVD/Blu-ray player is replaced by an elegant slot loading solution. A third HDMI port and a second set of AV and audio inputs were added and placed on an all-new side access panel for easy connection to a gaming console or other high-def peripheral. Four USB ports and an Ethernet port were also conveniently placed on the side panel to simplify expansion.</p>

<p>The LCD specifications were also upgraded. Both the 42-inch and 32-inch Allio offer an improved contrast ratio of 3000:1 and brightness of 450 cd/m-squared for better viewing. Prices range from $1299 for the entry-level 32-inch Allio Lite to $2999 for the fully loaded 42-inch quad-core all in one Allio Media Center with Blu-ray.</p>

<p>Pre-orders for all in one Allio 2.0 can be placed now at alliotv.com, or from resellers like Amazon, TigerDirect and Visionman. These new models will ship starting October 1, 2009.</p>

