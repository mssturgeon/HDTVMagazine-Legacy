				<p class="prtitle">Sony Introduces New Full HD Home Theater Projector</p>

<center><i>BRAVIA SXRD Model Features High Contrast and Exceptional Performance</center></i><br />
<br />

<p><strong>ATLANTA, Sept. 9 /PRNewswire/ --</strong> (CEDIA Booth #1409) -- Sony today announced a new high-contrast, high-definition projector, adding more options for those looking for a true cinematic home theater experience.</p>

<p>The new VPL-VW85 projector features a full HD 1920 x 1080 progressive Silicon X-tal Reflective Display (SXRD(TM)) and 24p True Cinema(TM) technology, delivering a true film-like performance. The new model also has an exceptionally high dynamic contrast of 120,000:1 and brightness of 800 ANSI lumens.</p>

<p>Specifically designed with the custom installation market in mind, the VPL-VW85 has a motorized, fully adjustable, 'lens shift' function that offers more options in terms of installation and projector placement, without any image distortion. Additionally, the lens offers a 1.6x motorized zoom with horizontal and vertical adjustment, making it easy to set up in a variety of environments.</p>

<p>The VPL-VW85 projector also adds Sony's Motionflow(TM) 120Hz with black frame insertion technology, providing exceptional clarity and resolution for fast moving images. The model also features Sony's Anamorphic Zoom Mode that, when paired with an external anamorphic lens (sold separately), allows users to enjoy a true big screen home theater experience.</p>

<p>The new projector also offer RS-232C control, as well as two HDMI inputs, single component and composite inputs, and a PC input. In addition, the VPL-VW85 includes access to a dedicated CEDIA certified technical support hotline for all troubleshooting and is eligible for Sony's Advance Exchange program. This minimizes downtime for exchanges if a customer experiences any problems within 90 days of original purchase.</p>

<p>The VPL-VW85 will be available in October for about $8,000, and will be offered direct at Sony Style retail stores nationwide and authorized installation dealers around the country.</p>

<p>For those looking to upgrade their home theater at a value, Sony also introduced the VPL-HW15 SXRD projector. The full HD 1080p model features 24p True Cinema(TM) technology, a 60,000:1 dynamic contrast ratio and a brightness of 1,000 ANSI lumens. It offers RS-232 control, two HDMI inputs and single component and composite inputs, as well as a PC input.</p>

<p>This VPL-HW15 projector will also be available in October for about $3,000, and will be offered direct at Sony Style retail stores nationwide and authorized installation dealers around the country.</p>

