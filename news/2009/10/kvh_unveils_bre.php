				<p class="prtitle">KVH Unveils Breakthrough Marine HDTV Antenna with Simultaneous Tracking of Three Satellites</p>

<center><i>New Ka/Ku-band TracVision HD7 uses exclusive TriAD technology to track and receive signals from all three of DIRECTV's primary satellites at the same time; eliminates need to switch satellites and provides full support for HDTV DVRs</center></i><br />
<br />

<p><strong>MIDDLETOWN, R.I., Oct. 29 /PRNewswire-FirstCall/ -- </strong>There's a new definition for satellite television at sea and it's called the TracVision&reg; HD7 from KVH Industries (NASDAQ:KVHI) . Unveiled today at the 2009 Ft. Lauderdale International Boat Show, the TracVision HD7 is a breakthrough in maritime satellite TV design, offering boaters a DIRECTV&reg; high-definition TV experience exactly like they enjoy at home thanks to simultaneous reception of two DIRECTV Ka-band satellites and one Ku-band satellite.</p>

<p>"With the TracVision HD7, you enjoy complete, uninterrupted access to all of the great TV entertainment offered by DIRECTV's satellites thanks to our revolutionary TriAD(TM) technology, which simultaneously delivers programming from DIRECTV's three primary Ka- and Ku-band satellites," explained Martin Kits van Heyningen, KVH's chief executive officer. "In addition, boaters will be able to enjoy full support for DVRs because no satellite switching will be required, along with our best-ever in-motion tracking. What does this mean? HDTV at sea with no compromises, now and in the future. You, your family, and your friends can watch whatever you want, when you want, on whatever TV you want, because TracVision HD7 tracks all three satellites at once, just like home!"</p>

<p>The 24-inch diameter TracVision HD7 is the world's most advanced maritime satellite television system, incorporating patent pending technology and features that provide a unique entertainment experience and unmatched simplicity in operation and installation, including:</p>

<ul><li>KVH's Tri-Rod Antenna Design (TriAD) technology - this patent pending new design simultaneously receives broadcasts from three separate DIRECTV satellites. These signals are concentrated by the tuned subreflector before reaching the unique tri-rod dielectric feed. Multi-axis dynamic tracking then allows the system to stay locked on even in the roughest seas.</li><li>IP-enabled Antenna Control Unit (ACU) - KVH's new Internet Protocol (IP)-enabled antenna control unit, with its Ethernet connection, and built-in WiFi interface, makes system setup as easy as opening a web browser.</li><li>The TracVision iPhone&reg; application - For the most convenient connection to the TracVision HD7 satellite TV, simply download KVH's free TracVision iPhone app from Apple's iTunes App Store for your iPhone or iPod&reg; touch. Then use it to check signal strength, switch to secondary satellites, download and automatically install antenna software updates, and send information directly to KVH technical support. It doesn't get any easier!</li><li>Single Wire Multiswitch (SWM) - TracVision HD7 includes a built-in single wire multiswitch that supports up to eight high-definition tuners with just a single cable and allows boat owners to run just a single wire to a dual-tuner DVR, making installation simpler than ever.</li><li>USB Flash Port - If the boat owner or dealer does not have Internet access or the TracVision iPhone app, updating antenna information is as simple as inserting a USB flash drive loaded with the latest KVH software into the ACU's USB Flash Port to update the system.</li><li>New optional Tri-Americas(TM) Ka/Ku-band LNB - The TracVision HD7 offers an optional configuration that includes KVH's new Ka/Ku-band Tri-Americas LNB that eliminates the need to change antenna hardware when switching between DIRECTV HD and Galaxy/DIRECTV Latin America as the boat travels from the U.S. to the Caribbean, Central America, and South America.</li><li>Easy installation - Installation is simple with only one dome and the same cabling and mounting design as KVH's popular TracVision 6/G6 and M7 models so upgrading is a breeze.</li><li>Rock-solid in-motion tracking - The TracVision HD7 offers the best tracking ever available in a KVH satellite TV product thanks to enhanced tracking algorithms and a stainless steel bearing construction to ensure outstanding performance and uninterrupted entertainment even on sportfishers and tuna towers.</li></ul>

<p><br />
The TracVision HD7 is designed to overcome the challenge raised when DIRECTV moved its HDTV programming to new Ka-band satellites incompatible with existing maritime satellite TV systems. Adding to the complexity, HDTV programming is broadcast on the 99 degrees W and 103 degrees W Ka-band satellites while the program guide and all non-HD channels are broadcast by DIRECTV's original 101 degrees W Ku-band satellite.</p>

<p>"We wanted to offer boat owners an experience just like home, which requires the ability to watch all three satellites at once, a challenge overcome by our TriAD technology," commented Brent C. Bruun, KVH's vice president of sales and business development. "Other solutions, like the use of multiple antennas or a home dish inside a 4-foot diameter dome, are impractical for most boat owners due to cost, size, and installation space.</p>

<p>"Antennas that only view one satellite at a time and rely on the antenna or LNB to switch among the Ka- and Ku-band satellites raise a host of other problems for boaters, including receiver lockups, reboots, or lengthy satellite searches due to expired program guides or receivers looking for the wrong satellite. And do you really want to run the risk of missing the big game because ESPN HD is broadcast on the 99 degrees W satellite and your kids want to watch Animal Planet HD broadcast on 103 degrees W? The TracVision HD7 eliminates all of these issues and allows you all to watch DIRECTV's programming, whether live or on the DVR, exactly like you do at home."</p>

<p>Visit <a target="_blank" href="http://www.kvh.com/HD7/">http://www.kvh.com/HD7</a> for complete details about this groundbreaking new approach to satellite TV at sea.</p>

