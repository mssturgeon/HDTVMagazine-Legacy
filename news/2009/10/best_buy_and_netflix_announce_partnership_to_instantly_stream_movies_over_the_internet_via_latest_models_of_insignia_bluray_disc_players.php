<strong>About Netflix, Inc.</strong></p>

<p>Netflix, Inc. (NASDAQ:NFLX) is the world's largest online movie rental service, with more than 10 million subscribers. For only $8.99 a month, Netflix members can instantly watch unlimited movies and TV episodes streamed to their TVs and computers and can receive unlimited DVDs delivered quickly to their homes. There are never any due dates or late fees. Netflix members can exchange DVDs as often as they want using a postage-paid return envelope. Members can choose from a vast selection of DVD titles and a growing library of movies and TV episodes that can be watched instantly. Netflix is partnering with leaders in consumer electronics to bring to market a range of devices that can instantly stream movies and TV episodes from Netflix directly to members' TVs. These devices currently include Blu-ray Disc Players and new Internet TVs from LG Electronics; Blu-ray Disc Players from Samsung; the Roku digital video player; Microsoft's Xbox 360 game console; TiVo digital video recorders; and, soon, Internet TVs from Sony and VIZIO. For more information, visit <a target="_blank" href="http://www.netflix.com//">http://www.netflix.com/</a></p>

