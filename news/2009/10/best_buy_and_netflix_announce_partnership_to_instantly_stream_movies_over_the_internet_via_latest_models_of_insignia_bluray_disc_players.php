<p><strong>MINNEAPOLIS and LOS GATOS, Calif., Oct. 20 /PRNewswire/ -- </strong>Insignia, a Best Buy Co., Inc. (NYSE:BBY) exclusive brand, and Netflix, Inc. (NASDAQ: NFLX) , the world's largest online movie rental service, today announced the availability of two new Insignia Blu-ray Disc Players that enable Netflix members to instantly watch movies and TV episodes streamed from Netflix over the Internet to their televisions.</p>

<p>The new Insignia Advanced Series Blu-ray Player (NS-WBRDVD) and the Insignia Connected Blu-ray Player (NS-BRDVD3) are now on sale for $249.99 and $179.99, respectively, at all Best Buy retail stores and <a target="_blank" href="http://bestbuy.com/">bestbuy.com</a>. Both models are Internet ready, giving Netflix members on an unlimited plan access to a growing library to watch instantly on their TV. The Insignia Advanced Series model uses built-in Wi-Fi to connect to the Internet while the Insignia Connected player uses an Ethernet connection. The ENERGY STAR-certified players feature Dolby TrueHD to deliver exquisite high-quality sound and use up conversion to display standard DVDs with crisp clarity and precision.</p>

<p>Netflix members on an unlimited plan can use the Insignia Blu-ray Disc Players to instantly watch thousands of titles streamed from Netflix, including popular current season and older television shows, classic movies, documentaries, foreign films, independent movies, some new releases and more. They can watch as much as they want, any time they want. Members can manage their Netflix instant Queue on the Insignia Blu-ray Disc Player, including browsing titles by genre from personalized lists, adding movies to their instant Queue or pushing "Play" to start instantly watching a movie or TV episode. As with all other Netflix ready devices that instantly stream from Netflix, the Insignia Blu-ray Disc Players allow Netflix members to start and stop movies, go back or fast forward as much as they like at different times.</p>

<p>"Best Buy customers appreciate dependable performance at reasonable prices," said Nigel Waites, CTO of Best Buy's Exclusive Brands. "The ability to instantly watch movies streaming from Netflix via the Insignia line of Blu-ray Disc Players will appeal to Best Buy shoppers who seek unsurpassed convenience, selection and value in a Blu-ray disc player."</p>

<p>"Best Buy is a terrific place to shop for TVs, Blu-ray disc players, computers and other technology products that entertain and suit the lifestyle needs of millions of consumers," said Netflix Chief Executive Officer Reed Hastings. "We're proud to see Insignia models that instantly stream movies from Netflix on Best Buy shelves. Or, better yet, seeing customers buy them off the shelves."</p>

<p><br />
<strong>About Best Buy Co., Inc.</strong></p>

<p>With operations in the United States, Canada, Europe, China and Mexico, Best Buy is a multinational retailer of technology and entertainment products and services with a commitment to growth and innovation. The Best Buy family of brands and partnerships collectively generates more than $45 billion in annual revenue and includes brands such as Best Buy; Audiovisions; The Carphone Warehouse; Future Shop; Geek Squad, Jiangsu Five Star; Magnolia Audio Video; Napster; Pacific Sales; The Phone House; and Speakeasy. Approximately 155,000 employees apply their talents to help bring the benefits of these brands to life for customers through retail locations, multiple call centers and Web sites, in-home solutions, product delivery and activities in its communities. Community partnership is central to the way business is done at Best Buy. In fiscal 2009, Best Buy donated a combined $33.4 million to improve the vitality of the communities where its employees and customers live and work. For more information about Best Buy, visit <a target="_blank" href="http://www.bestbuy.com/">www.bestbuy.com</a>.</p>

<p><br />
<strong>About Insignia</strong></p>

<p>Insignia is a Best Buy Exclusive Brand designed to provide our customers with affordable, well-designed technology. Best Buy listens to its employees' and customers' feedback then leverages these insights to develop a broad range of quality solutions in Insignia products, all at a great value. The Insignia line features a wide selection of consumer electronics including HDTVs, Blu-ray players, home theater solutions, GPS, audio products and more. The Insignia Advanced Series Televisions feature clear picture quality, richer sound and are backed by an industry leading two-year warranty. Insignia products are available exclusively at all Best Buy retail locations and online at <a target="_blank" href="http://www.bestbuy.com/">www.bestbuy.com</a> and <a target="_blank" href="http://www.insigniaproducts.com/">www.insigniaproducts.com</a>.</p>

