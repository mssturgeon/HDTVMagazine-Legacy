<p>The all-new Flip MinoHD camcorder offers a stylish new look with brushed metal finish. True to its heritage, the new MinoHD can be personalized with one of thousands of designs or can be custom designed by the user at <a target="_blank" href="http://theflip.com/">theflip.com</a>. The sleek device now has a slightly rounder design, responsive touch-sensitive buttons, and a durable brushed metal finish. Along with great new looks, the second generation Flip MinoHD includes double the memory for up to two hours of recording capacity, a bright two-inch transflective screen for no-glare viewing even in direct sunlight, and an HDMI jack for direct input to HD televisions with an HDMI cable. The new Flip MinoHD is priced at $229, while the original Flip MinoHD -- with one hour of recording time -- is priced at $199 and the standard Flip Mino sells for $149.</p>

<p><br />
<strong>New FlipShare Software</strong></p>

<p>Like all Flip Video camcorders, the new Flip MinoHD includes FlipShare, the pre-loaded software that leads consumers seamlessly through the process of organizing, editing and sharing videos. The new version of FlipShare software, available soon, has been upgraded across the line to include the easiest way to instantly upload video to Facebook, in addition to YouTube and MySpace. The latest FlipShare software will also include a number of new organization tools and user controls, and debuts Magic Movie, a fun feature that automatically trims and arranges a user's selected video content into their own movie.</p>

