<center><i>Technology provides most accurate view inside human body</center></i><br />
<br />

<p><strong>ATLANTA, Oct. 27 /PRNewswire-USNewswire/ -- </strong>Doctors at the annual meeting of the American Society for Reproductive Medicine got a glimpse into the future of women's health with the presentation of endoscopic gynecologic surgery performed for the first time using "4K" technology.</p>

<p>Steven F. Palter, MD, an obstetrician, gynecologist, reproductive endocrinologist and fertility specialist performed the world's first 4K super high-definition (HD) laparoscopy at Syosset Hospital, part of the North Shore-LIJ Health System, and presented images from that surgery on October 20 at the 65th annual meeting of the American Society for Reproductive Medicine (ASRM) at the Georgia World Congress Center in Atlanta.</p>

<p>"The images are the sharpest, most detail-rich and color-correct endoscopic images ever created anywhere," Dr. Palter said. "There is not a more accurate view inside the human body."</p>

<p>Produced in conjunction with RED Digital Cinema Camera Company; Sony Electronics, Inc., an ultrahigh definition projector company; and the University of Southern California Cinema Arts School, the diagnostic images were presented in a specially built digital theater with a projector designed to run "ultra-HD" movies in high-end movie theatres. "It's a prime example of how Hollywood film technology can be used to transform medicine by enabling doctors to see more accurately inside the body to study and treat disease," Dr. Palter said.</p>

<p>Ultra-high resolution digital cameras are transforming the art of cinema. Leading Hollywood directors such as Peter Jackson and Stephen Soderbergh are filming the next generation of cinema blockbusters using cameras with "4K" resolution, four times the resolution of HD with 4,096 lines of resolution to give audiences unprecedented realism.</p>

<p>"Through the use of this digital technology, Hollywood is moving from observation to immersion -- you're not just watching something, you are there," said Dr. Palter, medical and scientific director of Gold Coast IVF in Syosset, NY, who presented the plenary presentation, Film and Medicine: The Technological Transformation of Medicine. "In this session we showed how tomorrow's film technology can apply to laparoscopic surgery, which is all performed using video techniques."</p>

<p>Dr. Palter joined with the Red Digital Cinema Camera Company that manufactures the 4K Red One system to create Hollywood movies of tomorrow, and Sony, the leading ultra-HD theatrical projector company, to perform laparoscopic surgery using the Hollywood camera system.</p>

<p>During the film presentation, the 3,500 reproductive medicine specialists in attendance were able to visualize the surgery as if they were standing in the operating room. However, by combining unprecedented resolution and magnification, the surgical images were beyond what a surgeon would see in traditional surgery. The progress from regular surgical film technology is like comparing sitting in an HD home theater to watching a video on a cell phone," said Dr. Palter.</p>

<p>"Dr. Palter's research and vision of surgery's technological future opened the eyes and minds of the audience to fantastic treatments beyond what can be done today," said R. Dale McClure, MD president of ASRM.</p>

<p>The session also included a projection of the largest HD three-dimensional (3D) surgical images ever. Using the same system as 3D blockbuster Cloudy With a Chance of Meatballs, surgeons felt as if they could "reach out and conduct the operation." These images were enabled by converting Sony's 4K and 3D theatrical systems to show medical footage of what Dr. Palter has called "futurevision." To obtain the images, Dr. Palter and researchers from USC Cinema Arts created a method to attach the Red One 4K camera to a laparoscope. Offhollywood, a leading movie production company converted these images into a 4K digital cinema movie that was projected on $200,000, 700-pound Sony SRX-R220 projectors back to back with 4K Hollywood images of such stars as Tom Cruise, Julia Roberts and Will Smith. RealD 3D lenses projected HD 3D surgery as well as Hollywood images from 3Ality of movies, sports and the rock music band U2.</p>

<p>Dr. Palter has been honored for his prize-winning work on the development of autofluorescent endoscopy. He frequently shares his vision for the impact of future technology on medicine via his blog <a target="_blank" href="http://www.docinthemachine.com/">www.docinthemachine.com</a>.</p>

