<strong>Pricing and availability</strong></p>

<p>All three Roku players are available immediately at <a target="_blank" href="http://www.roku.com/">www.roku.com</a> and <a target="_blank" href="http://www.amazon.com/">www.amazon.com</a> and include free shipping for a limited time.</p>

