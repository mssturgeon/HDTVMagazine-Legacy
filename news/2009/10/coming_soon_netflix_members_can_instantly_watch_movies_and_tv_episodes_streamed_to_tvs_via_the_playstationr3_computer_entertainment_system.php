<p><img src="http://www.hdtvmagazine.com/news/images/2009-10-26_netflix_ps3.jpg" alt="Netflix-PS3" height="174" width="192" class="keyimg" /><strong>FOSTER CITY, Calif. and LOS GATOS, Calif., Oct. 26 /PRNewswire-FirstCall/ -- </strong>Sony Computer Entertainment America Inc. (SCEA) and Netflix, Inc. (NASDAQ: NFLX) today announced that they are joining forces to make thousands of movies and TV episodes from Netflix available to be streamed instantly to TVs via the PlayStation&reg;3 (PS3(TM)) computer entertainment system. Netflix expects to begin streaming via the PS3 system next month at no additional cost to Netflix members in the United States who have a PS3 system.</p>

<p>Today's announcement pairs two of the most popular and fastest growing home entertainment brands in the U.S. The PS3 system's installed base has reached close to 9 million units in the United States, and Netflix recently reported 11.1 million U.S. subscribers as of September 30.</p>

<p>The partnership further solidifies the PS3 system as the most complete home entertainment hub on the market today, enabling consumers to play high-definition games, watch Blu-ray movies, listen to music, view photos, browse the Internet, and download content from PlayStation&reg;Network - from exclusive games to blockbuster movies and popular TV shows. PS3 system owners will soon enjoy an unparalleled experience watching their favorite movies and TV shows streamed instantly from Netflix, downloading from the PlayStation Network or watching Blu-ray/DVD media. The Netflix offering expands on the entertainment experience delivered to PS3 system owners via PlayStation Network.</p>

<p>For only $8.99 a month, Netflix members can instantly watch unlimited movies and TV episodes streamed to their TVs and computers via Netflix ready devices such as the PS3 system and can receive unlimited DVDs delivered quickly to their homes.</p>

<p>"The PlayStation 3 system has always been about more than just gaming, and it will soon be the only platform in the industry to offer consumers such a variety of convenient options for enjoying movies and TV shows," said Jack Tretton, president and CEO, SCEA. "Whether you want to watch content on Blu-ray disc and DVD, download it from the PlayStation Network's video delivery service, or stream videos instantly from Netflix, the PS3 system is the only solution that offers it all."</p>

<p>"As instantly watching movies and TV episodes streamed from Netflix becomes an increasingly popular way to enjoy the Netflix service, our goal is to rapidly expand the devices that stream to our members," said Netflix CEO and co-founder Reed Hastings. "As a leading game console and Blu-ray disc player, bringing Netflix to the PS3 system is a real win for both Netflix members and PS3 system owners."</p>

<p>Initially, watching movies instantly streamed from Netflix via the PS3 system will be enabled by a free, instant streaming Blu-ray disc that is being made available to all Netflix members. The free instant streaming disc leverages Blu-ray's BD-Live(TM) technology to access the Internet and activate the Netflix user interface on the PS3 system, which must be online via Wi-Fi or Ethernet.</p>

<p>Netflix members simply slide the disc into their PS3 systems to reveal movies and TV episodes that can be watched instantly. These titles are conveniently organized into a variety of categories based on members' personal preferences, popular genres, new arrivals and members' individual instant Queues. Members can use the Netflix Web site or navigate directly on their PS3 systems to add movies and TV shows to their Queues. With the PS3 system's Wireless Controller, members can choose a movie to watch from their instant Queues or just play directly from any of the lists. They also have the ability to read synopses and rate movies. In addition, they have the option of fast-forwarding and rewinding the video stream via the Wireless Controller.</p>

<p>Netflix members and PS3 system owners can now reserve a free instant streaming disc for PS3 systems by going to <a target="_blank" href="http://www.netflix.com/ps3/">www.netflix.com/ps3</a>. Upon availability, the instant streaming disc will be delivered for free by first-class mail, generally one business day after members request it.</p>

