<B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, today unveiled the world's first wall-mountable Blu-ray player, the BD-P4600, as well as the new standard for Blu-ray performance and versatility, the BD-P3600. A 2009 CES "Best of Innovations" Award Winner, the BD-P4600 unites a plethora of multimedia features in a svelte, first-in-class package. The enthusiasts' choice, the BD-P3600 promises top-notch video playback, comprehensive audio decoding, and unprecedented networking capabilities for an immersive, theater-like experience. Both players set a new direction for the Blu-ray category with wireless networking, access to video and music streaming services, such as Netflix and Pandora, as well as sleek designs. Samsung's new Blu-ray players will be on display at Booth #11033 during the International Consumer Electronics Show, which will be held at the Las Vegas Convention Center, January 8 -11, 2009.</p>

<p>"Samsung is heralding a new direction for the Blu-ray industry with the BD-P4600 and BD-P3600," said Reid Sullivan, vice president of Audio/Video and Digital Imaging Marketing at Samsung Electronics America. "The BD-P4600 makes it easier than ever to bring Blu-ray into the living room with its unique, wall-mountable design, while the BD-P3600's comprehensive specs place it on the short list of even the most discerning home theater consumers."</p>

<p>The BD-P4600 and BD-P3600 include BD Live&trade; (Profile 2.0) and Bonus View (Profile 1.1) support, Full HD 1080p Blu-ray playback with DVD upscaling, and total HD soundtrack support. Standard CD playback, with support for JPEG photos and DivX videos, ensure even more entertainment value with the BD-P4600 and BD-P3600.</p>

<p><br />
<B>A New Era of Functional Design</B></p>

<p>Samsung's newest Blu-ray players continue the trend of stylish and décor-friendly electronics, with new versions of Samsung's groundbreaking Touch of Color&trade; (ToC&trade;) design and touch sensitive controls. The BD-P3600's traditional set-top form is just over two inches tall, and comes encased in deep black with charcoal grey highlights curving along the outer edges. The wall-mountable BD-P4600 is just 1.5 inches thin with a piano black design infused with ruby highlights, and finished with clear, prism-like edging. If wall-mounting is not an option, an integrated stand lets the BD-P4600 be placed on a table at a 25 degree angle.</p>

<p><br />
<B>Cutting Wires Without Cutting Back on Entertainment</B></p>

<p>Both the BD-P4600 and BD-P3600 can wirelessly connect to the latest Blu-ray features when the included 802.11b/g/n Wi-Fi dongle is connected to one of the players' two USB 2.0 ports, or via the traditional wired Ethernet connection. The two players can also instantly stream more than 12,000 movies and TV episodes from Netflix and Pandora music services (subscriptions required), to deliver an ever-expanding library of entertainment into the living room without having to leave the house. And with 1GB internal flash memory, both players can access the latest BD Live&trade; and Bonus View Blu-ray features out of the box, leaving the USB 2.0 ports for wireless networking and memory expansion duties when needed.</p>

<p><br />
<B>Speedy Control and Upgradeability</B></p>

<p>Samsung's newest Blu-ray players improve traditional disc loading time to begin fast playback and can eject a disc in a single second. The players' touch sensitive controls help to create a seamless experience that is pleasing to see, hear, and ultimately, use. To keep consumers updated with the latest features and improvements, Samsung's BD-P4600 and BD-P3600 also can easily access upgrades wirelessly via the included 802.11b/g/n Wi-Fi dongle, through the wired Ethernet connection, by connecting a USB drive, or with a CD / DVD / BD.</p>

<p><br />
<B>Total Full HD 1080p Video and HD Soundtrack Support</B></p>

<p>Samsung's BD-P4600 and BD-P3600 promise Full HD 1080p playback of Blu-ray discs and crisp upconversion of standard DVDs through the HDMI 1.3 connection. For a true, Hollywood-quality experience, both players can internally decode the latest high-resolution digital multichannel audio soundtracks, including Dolby Digital Plus&trade;, Dolby TrueHD&trade; and dts-HD HR / MA&reg;. The BD-P3600 can also output any of the soundtracks as a bitstream through its 7.1-Channel analog audio outputs, or as an uncompressed PCM signal, for consumers desiring the best cinematic sound with an older A/V receiver.</p>

