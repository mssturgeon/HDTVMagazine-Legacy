<B>Ultra Short Throw LCD Projector And Large Venue Projector</B></p>

<p>Hitachi will exhibit the CP-A100 3LCD projector at CES. This revolutionary model features a very short throw distance, eliminating the problem of presenters obstructing the projected image by standing in front of the screen. Additionally, the CP-A100 offers networking capabilities, allowing multiple projectors to be controlled and monitored from a single location. Hitachi will also showcase the CP-X10000 3LCD Professional Series projector. The CP-X10000 projector is the first model in Hitachi's new 3LCD Professional Series, offering a brightness of 7,500 ANSI lumens and up to six lens options.</p>

