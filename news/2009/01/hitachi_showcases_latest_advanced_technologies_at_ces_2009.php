<p>Hitachi Home Electronics (America), Inc. continues to introduce state-of-the-art consumer electronics with its next-generation Blu-ray Disc Hybrid Camcorder with the ability to record onto the next generation HD format, Blu-ray. This camcorder has the versatility of being able to record HD video onto three separate formats (Blu-ray Disc, Hard Drive, SDHC) and provides the flexibility and ease of playback and long recording time all in one camcorder.</p>

