<B>Gesture Control TV Interface</B></p>

<p>The TV interface prototype with gesture control interface allows users to operate a television by simply moving the hand without using a remote control unit. The embedded camera sensor spontaneously reacts to hand motion to turn TV on and off, scroll channels, control volume, and is also expandable to control home network such as air-conditioning and lighting.</p>

<p><br />
<B>Super-Resolution Technology</B></p>

<p>Hitachi has developed Super-Resolution technology to create high definition images of various resolutions. In contrast to conventional technology, which transforms video of a given resolution to a pre-determined level of high definition image, Hitachi's new technology uses original signal processing technology to transform video of various resolution levels to the optimal level of high-resolution image.</p>

<p>As a result, it is possible to create high-definition images from video containing images of various resolutions on the same display such as in television broadcasts. In additional to transforming SD video to near HD video, this technology also enhances full HDTV (1920x1080 pixels) resolution images to provide even more beautiful, crisp high-definition images.</p>

