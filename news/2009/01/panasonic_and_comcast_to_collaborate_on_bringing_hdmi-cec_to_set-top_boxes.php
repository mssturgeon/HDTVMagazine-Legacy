<center><i>Ongoing Collaboration Between Industry Leaders Continues To Develop Ease-of-Use Solutions for Cable Subscribers, Including the Arrival of the First tru2way HDTVs at Retail</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 7 /PRNewswire-FirstCall/</B> -- On the heels of the successful retail launch of the first tru2wayTM -ready VIERA(R) HDTV, Panasonic, the market and technology leader in HDTV, and Comcast Corporation (Nasdaq: CMCSA; CMCSK), the nation's leading provider of entertainment, information and communications, today announced that they are collaborating to bring HDMI-CEC technology to the latest generation of digital cable set-top boxes.</p>

<p>HDMI-CEC is the technology underlying Panasonic's VIERA LinkTM technology, which enables single remote operation of Panasonic VIERA HDTVs and connected home entertainment components, such as Blu-ray Disc Players and Home Theater Systems. Panasonic and Comcast are working to integrate HDMI-CEC technology with tru2way enabled set-top boxes that will enable non-tru2way HDTVs and other consumer electronics devices to interact with the set-top boxes via the use of a single TV remote control and a single user interface. Integrating the HDMI-CEC protocol with Comcast's on-screen program guide will allow set-top boxes to automatically configure connected home theater devices for optimal viewing and audio experiences and will enable intelligent interactive features, including auto input select and auto power on/off of all components. HDMI-CEC is already standard in all 2009 Panasonic VIERA HDTVs and select Comcast set-top boxes. The companies are currently working with CableLabs(R) on the standardization to adopt HDMI-CEC for next generation digital set-top boxes.</p>

<p>"Panasonic and Comcast are both committed to enhancing the user experience by enabling consumers to control all of the functions of their home entertainment systems with a single remote and user interface," said Dr. Paul Liao, Chief Technology Officer, Panasonic Corporation of North America. "This collaboration also highlights Panasonic's strong focus on delivering consumer-friendly solutions and the value that our VIERA Link technology brings to the consumer electronics industry."</p>

<p>Mark Hess, Senior Vice President of Video Product Development, Comcast Cable said, "When the consumer electronics and cable industry work together, the consumer is the real winner. We're pleased to continue our collaborative work with Panasonic to develop products that will seamlessly connect consumers' home entertainment experiences with all of the features and services they want and expect from cable."</p>

<p>Panasonic and Comcast have led the development of tru2way technology and related products, which are based upon specifications developed by CableLabs(R). Making good on a promise made at CES 2008, Panasonic and Comcast announced the arrival at retail of the first-ever tru2way HDTV -- the Panasonic VIERA TH-42PZ80Q and TH-50PZ80Q 1080p Plasma HDTVs -- and the activation of tru2way head ends in Chicago and Denver in October 2008. Additional cities are expected to go live in the coming months.</p>

