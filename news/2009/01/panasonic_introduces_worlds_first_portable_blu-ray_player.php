<center><i>Innovative Player Features BD Live and VIERA CAST(R) Internet Accessibility</i></center><br />
<br />

<p><B>LAS VEGAS, Jan. 7 /PRNewswire-FirstCall/</B> -- Panasonic, a major developer and contributor to the success of the Blu-ray format, introduced the world's first portable Blu-ray Disc player at the 2009 Consumer Electronics Show. The DMP-B15, designed to provide the ultimate high definition Blu-ray experience for those on the go, features a high quality 8.9-inch WSVGA LCD screen and includes the unique VIERA CAST(R) internet accessibility and BD Live functionality. The DMP-B15 will be available in May.</p>

<p>The DMP-B15 provides all the technology found in its stand alone brethren, the DMP-BD60, DMP-BD80 and the VHS-Blu-ray dual player DMP-BD70V. Image quality is of the highest level, thanks to PHL Reference Chroma Processor Plus technology developed in collaboration with Panasonic Hollywood Laboratory.</p>

<p>"As a pioneer in the development of DVD and Blu-ray expertise, Panasonic has always been in the forefront of cutting edge, consumer friendly technology. Panasonic was the first company to bring to market a portable DVD player and stand alone Blu-ray players to feature Bonus View and BD Live," said Richard Simone, Director, Entertainment Group, Panasonic Consumer Electronics Company. "Blu-ray technology came together with HDTVs to bring exciting High Definition viewing into the living room. With the introduction of this unique portable Blu-ray Disc player, the consumer can take this HD entertainment experience when they travel."</p>

<p>The PHL Reference Chroma Processor Plus is a high quality image-processing technology that precisely processes each pixel of the Blu-ray Disc(TM) video signal in the vertical direction. It reproduces color data with twice the accuracy of conventional systems, resulting in faithful and sharp colors.</p>

<p>Ease of use is an important element in Panasonic's products and the DMP-B15, with a three hour rechargeable battery, is designed with that in mind. In addition to its use as a portable player, the consumer can connect it to an HDTV via HDMI cable, and use it as a standalone Blu-ray Disc player. The player can also be connected to an HD-Audio compatible AV receiver with a home theater speaker system and enjoy movies with outstanding surround sound. To accommodate the traveler, the DMP-B15 offers an optional headrest mounting bracket for in-car use. Like all Panasonic Blu-ray players, the B15 features an SD Memory Card slot that allows the consumer to view and share digital photos, as well as HD video recorded on a SD card.</p>

<p>For 2009, Panasonic's entire line of Blu-ray players includes VIERA CAST functionality. This unique application gives the consumer access to select entertainment sites, including Amazon Video-on-Demand, a streaming video service that gives the consumer access to more than 40,000 titles; YouTube(TM); Google Picasa Web Album; Bloomberg and a weather channel.</p>

