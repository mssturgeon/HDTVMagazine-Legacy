<p><B>LAS VEGAS--(BUSINESS WIRE)</B>--Today, Toshiba Corporation (TOKYO:6502) announced a major product initiative that will reinforce its collaboration with Intel Corporation and Microsoft Corporation respectively and allow users to quickly and easily access and enjoy a diverse range of high quality content and information services in the home.</p>

<p>The full potential of digital convergence, can only be achieved through the integration of key software platforms. Toshiba is taking the lead in attaining this goal by launching AV devices including LCD TV, LCD TV/DVD Combo, and standalone network player, that support the Widget Channel applications framework promoted by Intel and Yahoo! and include Extender for Windows Media Center technology. Toshiba will bring the new products to the U.S. market in the second half of 2009, and will exhibit and demonstrate a concept system at the 2009 Consumer Electronics Show in Las Vegas.</p>

<p>The combination of TV Widgets and Extender for Windows Media Center technology deliver on the long promised, simple to use superior solution that consumers expect from a network device. Until now, devices have been dedicated to software implemented by the manufacturer. With TV Widgets and Extender for Windows Media Center technology, the consumer will have the greater flexibility to customize and enhance their entertainment experience. Each of Toshiba's line of network devices will act as the hub for content delivery into the entertainment space of the home.</p>

<p>TV Widgets which run on the Widget Channel applications framework developed by Intel and Yahoo! and driven by Intel's consumer electronics media processors, allow viewers to access rich content library over the Internet (the latest movies, music and sports programs) and information services (stock prices, weather forecasts, on-line communities) via a user-friendly interface that appears on their TV screen. While some TV Widgets will be pre-installed on the devices, consumers will have access to a growing universe of TV widgets as they become available.</p>

<p>By integrating Extender for Windows Media Center technology, the new Toshiba AV devices including LCD TV, LCD TV/DVD Combo, and standalone network player, will be able to access a wide range of digital content from Windows Media Center on the PC through their big screen TV using the home network. Included in every copy of Windows Vista Home Premium and Ultimate, Windows Media Center, with the addition of a TV tuner, turns the PC into a powerful DVR. Windows Media Center also delivers an extensive amount of Internet TV and movie content, plus photos, music, home videos and more. Toshiba's network player solution will be developed to be compatible with Windows Vista Home Premium, Windows Vista Ultimate and Windows 7.</p>

<p>Toshiba's new line-up of AV devices including LCD TV, LCD TV/DVD Combo, and standalone network player, will feature the company's picture enhancement technologies, allowing viewers to enjoy a wide range of content at near HD picture quality.</p>

<p>Eric B. Kim, Senior Vice President and General Manager, Digital Home Group, Intel Corporation, says, "Intel's consumer electronics platform, including the Intel&reg; Media Processor CE 3100 and Widget Channel, provide performance, flexibility and Internet compatibility, which help Toshiba to develop a new generation of connected devices. These new services will extend the Internet into the TV viewing experience, and transform the way consumers enjoy personal entertainment."</p>

<p>"Innovation is changing the definition of TV -change powered by software and web services. People now want to easily find and enjoy their PC and Internet-delivered content on all their screens," said Enrique Rodriguez, Corporate Vice President, Connected TV Division at Microsoft. "Toshiba's integration of Extender for Windows Media Center technology in their products will deliver rich experiences including the aggregation and intuitive navigation of content or the blending of information and services from the Web."</p>

<p>Yoshihide Fuji, Toshiba Corporate Senior Vice President and President and CEO of the Digital Media Network Company, said: "By strengthening our collaboration with Intel and Microsoft, Toshiba can deliver the new experience of the connected digital home, allowing consumers to enjoy content, anytime and anywhere. This is a paradigm shift that will establish the TV as an essential gateway to emerging entertainment content. We look forward to providing our customers, around the world, with advanced platforms that will allow them the flexibility to enjoy diverse content on their TVs at home." </p>
