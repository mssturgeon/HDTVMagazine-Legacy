<p><B>LAS VEGAS - CES - Jan. 6, 2009</B> - Say goodbye to complicated lists and long explanations about how to use your home-entertainment system. Today at the Consumer Electronics Show, Logitech (SIX: LOGN) (NASDAQ: LOGI) introduced the Logitech&reg; Harmony&reg; 1100 advanced universal remote control, delivering powerful home-entertainment control through a customizable, 3.5-inch full-color touch screen. Logitech's newest remote provides a touch-screen interface that lets you put the commands you want, where you want them. The Harmony 1100 remote has received the CES 2009 Design and Engineering Award: Best of Innovations in the Home-Entertainment Accessories category - the second consecutive year a Logitech Harmony remote has been honored with this award.</p>

<p>"The Harmony 1100 is a natural extension of the Harmony promise - to simplify today's complex home-entertainment systems," said Ashish Arora, vice president and general manager of Logitech's Harmony business unit. "As more and more people get the bulk of their entertainment at home, the Harmony 1100 will help people get more out of their home-entertainment experience - for a fraction of the price of traditional custom-installed remotes."</p>

<p>With a single touch, the palm-sized Harmony 1100 remote puts the power to control your home-entertainment in your hands. With its fully redesigned software, the 3.5-inch touch-sensitive screen - which features QVGA resolution - gives you a brilliant base from which to control your system. Using the new Harmony software, you can select the commands you use most and put those features on the screen. If you love to watch movies, for example, and are always using the Play and Pause buttons, you can tell the Harmony 1100 to make those commands immediately available on the screen once you start your movie.</p>

<p>In addition to the customizable touch screen, the Harmony 1100 offers simple details that also make it easy to use, such as tactile guides, which are located around the touch screen and help position your fingers so that you choose the right command. The brushed-black aluminum top case and soft-touch bottom case make it comfortable to hold - as well as a stylish complement to your living room. And the Harmony 1100 is rechargeable, so you never have to replace the batteries.</p>

<p>To help you beautify your home, the Harmony 1100 is equipped with RF capability. A Harmony&reg; RF Extender (sold separately) combined with the Harmony 1100 remote lets you control devices that are behind the closed doors of your entertainment cabinet or even in another room (from up to 100 feet).</p>

<p><br />
<B>One Touch to Your Entertainment</B></p>

<p>The Harmony 1100 delivers the renowned benefits common to the Harmony family of universal remotes, including its exclusive one-touch activity-based control system powered by the world's largest A/V-control database of entertainment equipment, as well as its convenient online setup process. The Harmony 1100 remote simplifies your entertainment with one-touch activity-based control. The whole family, your friends, and even the babysitter can simply select what they want to do by choosing the appropriate on-screen icon - such as "Watch TV" - and the Harmony 1100 remote does the rest. The remote will turn on the TV, the DVD player, the A/V receiver and any other necessary devices. There's no need to control components individually - the Harmony 1100 remote manages everything.</p>

<p><br />
<B>Guided Online Setup</B></p>

<p>Logitech's Internet-based setup makes getting the Harmony 1100 up and running as easy as possible. With its intuitive setup wizard guiding the process, the Harmony 1100 online interface allows you to enter your components' make and model numbers. Then, this information is automatically matched to the characteristics, discrete codes and infrared commands of the more than 225,000 devices from more than 5,000 manufacturers contained in Logitech's online database. Any devices that aren't in the database can be quickly added. When you want to add a device to your living room, you can be confident that the Harmony 1100 remote will work with the devices you own today, and the ones you'll buy in the future.</p>

<p><br />
<B>Pricing and Availability</B></p>

<p>The Harmony 1100 is expected to be available in the U.S. and Europe beginning in February for a suggested retail price of $499.99 (U.S.). </p>
