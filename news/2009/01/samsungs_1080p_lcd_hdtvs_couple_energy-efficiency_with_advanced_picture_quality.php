<p><br />
<B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, today unveiled its next-generation LCD HDTV lineup with CCFL backlighting. The LCD HDTV line-up is led by the Series 7, which is the company's first CCFL-backlit LCD TV with a 240Hz refresh rate. Samsung's line of LCD HDTVs will be on display at Booth #11033 during the International Consumer Electronics Show, which will be held at the Las Vegas Convention Center, January 8 -11, 2009.</p>

<p>"We are proud and excited to deliver consumers Samsung's first CCFL-backlit 240Hz LCD HDTV to consumers," said Jonas Tanenbaum, Vice President of LCD HDTV Marketing at Samsung Electronics America Inc. "Samsung continues to push the envelope in terms of technology and design innovation, and consumers will experience even better clarity, more vibrant colors and unprecedented networking capabilities available on Samsung's newest line-up of LCDs."</p>

<p>The Series 7 features a fast 240Hz refresh rate, a speed twice that of current 120Hz sets, and quadruple that of standard HDTVs. The refresh rate and a faster panel work together with Samsung's proprietary Auto Motion Plus&trade; 240Hz frame interpolation technology, to eliminate motion blur and judder with fast-action material, for stunning motion detail.</p>

<p>Both the Series 7 and Series 6 650 (32-inch and larger) LCD HDTVs impress with Samsung's improved Ultra Clear panel, a polarizer that reflects room light to produce deeper, darker black tones and bolder colors. By enhancing the performance of the new polarizer, the reflection rate is decreased significantly from previous versions, making blacks even darker, regardless of the ambient lighting conditions in the room. Both Series also feature Samsung's adaptive contrast picture setting, called "Natural" mode, which combines the brightness advantage of LCD displays and the cinema-like viewing experience of plasma displays. The result is a new level of video richness perfect for viewing films.</p>

<p>Additionally, both the Series 7 and 6 feature low power consumption, thus saving energy and money for the consumer. They meet the more stringent Energy Star&reg; v3.0 efficiency guidelines.</p>

<p>Recognizing the need for HDTVs to not only be technologically advanced, but also aesthetically pleasing, the HDTVs all feature Samsung's new Touch of Color&trade; (ToC&trade;) design. The unique ToC&trade; frame is produced by using dual-injection molding technology to luxuriously coat a translucent surface over the chassis.</p>

<p><br />
<B>Series 7</B></p>

<p>Superior Picture Quality</p>

<p>The 240Hz Series 7 LCD HDTV offers an excellent option for home theater enthusiasts who are focused on high-performance LCD picture quality and innovative product design. The HDTV's swift 240Hz refresh rate and Auto Motion Plus&trade; technology, Samsung's proprietary frame-interpolation technology, work in tandem to produce viewing quality comparable to that of the best CRT displays.</p>

<p>Samsung's exclusive Wide Color Enhancer 3 technology maps source colors to the panel's color space. This results in exceptionally vibrant, yet natural-looking images faithful to the director's original intent.</p>

<p>Advanced Design</p>

<p>In addition to the new ToC&trade; design, the Series 7 also sports a transparent bar that runs across its bottom bezel. The bar clearly divides the TV from the speaker compartment which houses a pair of down-firing speakers. It further serves to highlight the glass-like quality of the set's frame while giving the illusion that the display floats in mid-air. With a stand constructed using transparent reinforced glass, this stunning look is heightened even more.</p>

<p>Connectivity Features</p>

<p>Equipped with impressive networking skills, Series 7 LCDs feature Samsung's new Internet@TV - Content Service. Powered by the revolutionary Yahoo! Widget Engine, users will be able to access widget-based content from a wide array of Yahoo! Internet sources including Flickr, News, Weather and Finance along with future 3rd party providers as they become available. For added flexibility, the Series 7 goes beyond its built-in wired Ethernet connection, and supports 802.11a/b/g/n wireless networking capabilities via a wireless USB dongle. What's more, the Series 7 is DLNA certified and supports wireless connections allowing viewers to easily enjoy their PC-based music, video, and pictures from any room in their home.</p>

<p><br />
<B>Series 6</B></p>

<p>Auto Motion Plus&trade; 120Hz</p>

<p>Available on all Series 6 models 32-inches or larger, Samsung's proprietary Auto Motion Plus&trade; 120Hz frame-interpolation technology virtually eliminates motion blur and judder. Furthermore, the advanced panel has a fast pixel response time to produce razor sharp images even with fast-paced motion in action scenes.</p>

<p>Touch of Color&trade;</p>

<p>Further reinforcing Samsung's commitment to innovative design and high performance, the Series 6 distinguishes itself with a ToC&trade; design reminiscent of a beautifully blown wine glass. Taking a cue from the popular Bordeaux series, Samsung carries this fashion-forward look further by applying transparent color to the TV's four edges. A two-tone gradation of transparent ruby color yields a much softer, glassier look for the deeper and wider curve at the bottom of the bezel. The color does not appear from the front but at the sides, resulting in a lighter and unobtrusive design compared to previous ToC&trade; models.</p>

<p>A Multimedia Hub</p>

<p>Just like Series 7 sets, the 2009 Series 6 650 (40-inch and larger) HDTVs also feature the Yahoo!-driven Internet@TV - Content Service. Made possible with a collaboration with Yahoo!, Internet@TV - Content Service is widget-based and delivers a whole new level of connectivity by providing access to Internet-based multimedia content from Flickr and other Yahoo! services. With a click of the remote control, these widgets are easily accessed via a bar-style graphic user interface which sits on the bottom of the screen. Using an optional wireless dongle, the Series 6 is also wireless DLNA compliant allowing for simpler access to multimedia stored on household computers.</p>

<p>The Series 7 ranges in panel sizes of 40, 46, and 52 inches. Series 6 sizes, on the other hand, extend much more broadly. 19, 22, 32, 37, 40, 46, and 55. Both the series 7 and 6 will be available by the 1st half of 2009.</p>

