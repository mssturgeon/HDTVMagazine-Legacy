<p><B>LAS VEGAS, January 7, 2009 </B>- HDMI Licensing, LLC, the agent responsible for licensing the High-Definition Multimedia Interface&trade; (HDMI&trade;) specification, today announced an overview of the capabilities and features of the next version of the HDMI specification which will be launched in the first half of 2009.</p>

<p>"HDMI has reached an installed base of more than 600 million devices and now touches almost every consumer device that plays HD content.  We want to give the industry a preview of where the HDMI specification is headed as we continue to innovate and meet the needs of this dynamic marketplace," said Steve Venuti, president of HDMI Licensing, LLC. </p>

<p>Our goal is to address 5 key industry trends in the coming spec:</p>

<ul><li>- Networking - Consolidation of HD video, HD audio and now high speed data with the addition of Ethernet in the HDMI cable.</li><li>Audio Return Channel - Elimination of a S/PDIF cable by allowing a TV to send audio streams upstream to an A/V receiver for processing and playback over the HDMI cable</li><li>Performance - 4kx2k and 3D are high performance features to be met by increasing the upper limit of the HDMI link</li><li>HD in your Car - New connector specification for the auto industry as worlds' largest auto makers move to digital HD video and audio for 21st century cars with HDMI</li><li>Smaller connector - New smaller 19-pin connector</li></ul>

<p>As a testament to the success and proliferation of the HDMI standard over the past six years, the National Academy of Television Arts & Sciences (NATAS) has presented the HDMI founders with the Technology & Engineering Excellence Emmy&reg; Award on January 7, 2009, for their contribution to the development and implementation of the HDMI technology standard.</p>

<p>The HDMI standard continues to grow in the marketplace with now over 850 adopters worldwide. The growing adoption of the HDMI specification by both CE and PC manufacturers further strengthens its position as the worldwide standard for high-definition digital connectivity. According to market research firm In-Stat, over 394 million HDMI-enabled devices are expected to ship in 2009, and by the end of 2009 100% of digital televisions will have at least one HDMI input.  For more information on the HDMI standard please visit http://www.hdmi.org.</p>

