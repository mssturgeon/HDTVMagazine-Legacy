			<p class="prtitle">Celeno and Cavium Networks Collaborate to Offer Whole-Home 1080p60 HDMI Connectivity over Wi-Fi&reg;</p>

<center><i>Solution to be demonstrated by partners at CES 2009</i></center><br />
<br />

<p><br />
<B>LAS VEGAS--(BUSINESS WIRE)</B>--Celeno Communications, a leading provider of semiconductors for multimedia Wi-Fi home networking applications, today announced a collaboration with Cavium Networks (NASDAQ: CAVM), the leader in super low latency, full-HD H.264 video codecs to fulfill the demand for a robust, low latency and long range wireless HDMI solution. The joint reference design meets the demand for in-room HDMI cable replacement applications as well as whole-home full-HD video content sharing, using standards-based Wi-Fi networking technology. The solution enables consumer electronics manufacturers to develop products that support various digital home connectivity use cases. Examples include: eliminating the need for unattractive audio/video HDMI cables to connect thin full-HD TV panels; watching DVR recordings anywhere in the home; and using gaming applications in any room regardless of the console's location.</p>

<p>Consumer electronics (CE) vendors and service providers are seeking standards-based Wi-Fi home networking solutions for HD video distribution to enable consumers to easily stream video content between CE devices, set top boxes (STBs) and personal computers (PC). The combination of Celeno's OptimizAIR&trade; Wi-Fi HD home networking technology with Cavium's Super Low Latency H.264 codec technology meets the demanding capacity, reach and latency requirements for whole-home full-HD uncompressed video content streaming. In contrast to proprietary short distance wireless solutions, the joint standards-based solution enables easy interoperability between any digital media server device and any digital media player device, helping to create a seamless DLNA-Connected home environment.</p>

<p>According to market research firm iSuppli, by 2012 the market for A/V CE equipment will grow to over 830 million annual units shipped, with semiconductor revenues in those products to surpass $37 billion. "With growing interest in networked CE devices and especially DVR sharing application, iSuppli expects to see wireless A/V streaming functionality adoption increase significantly over the next few years," said Randy Lawson, senior analyst of display electronics for iSuppli. "Wi-Fi wireless technology enables video streaming over longer distances, and, since it is standards-based, allows for seamless interoperability between CE devices. The combination of Celeno's unique Implicit Beam Forming technology with Cavium's Super Low Latency video compression technology offers a compelling solution for the whole-home A/V equipment networking application."</p>

<p>The joint reference design is based on the Cavium PureVu Video Processor CNW3602 and the Celeno CL1300 HD-grade Wi-Fi System-on-Chip (SoC). It delivers compressed 480p/720p/1080p60 video over long distances while achieving sub-frame latency and perceptual lossless video quality.</p>

<p>"Leveraging standards based, Wi-Fi technology is key for interoperability in multi-device and multi-room use cases," said Lars Herlitz, GM Multimedia group Cavium Networks, "Celeno OptimizAIR&trade; Wi-Fi technology offers extra range while maintaining reliable bandwidth and special interference immunity. This will enable CE manufacturers to provide wireless display connectivity with best-of-breed video quality and practically zero latency at an extremely attractive price points."</p>

<p>Celeno's CL1300 is the first solution of its kind to use 802.11 4x4 Implicit Beam Forming MIMO transmission technology to boost range and robustness independent of the receiving side Wi-Fi chipset technology (even single stream, single antenna Wi-Fi clients). This truly open architecture means that CE manufacturers can build digital home networks that accommodate future plug & play of any Wi-Fi enabled TV screen. TV manufacturers can flexibly embed any 802.11n Wi-Fi technology on the TV screen, which helps to drive down costs due to the 802.11n mass-market silicon price curve. Service providers can offer customers advanced applications such as Multi-room DVR and Connected TV services, with future proof implementation - maintaining performance without dependence on the TV's Wi-Fi flavor.</p>

<p>"Celeno is delighted to partner with Cavium Networks. Together we can offer a wireless HDMI solution which provides full coverage of large homes using standards based H.264 and Wi-Fi," said Lior Weiss, VP Marketing at Celeno. "Cavium Super Low Latency Technology&trade; (SLL Technology&trade;) enables 1080p60 perceptual lossless compression with extremely low bit rates."</p>

<p>Celeno and Cavium will be demonstrating the joint full-HD video streaming solution at International CES 2009 in Las Vegas. The demo will use a Sony Playstation&reg;3 to show distribution of low-latency interactive gaming applications and Blu-ray&trade; Disc 1080p content over long distances. The demonstration will take place at the International CES 2009 in Las Vegas on January 8-11, 2009 in the South Hall #4, booth #35853.</p>

<p>About Celeno</p>

<p>Celeno is a leading provider of high performance Wi-Fi chips for HD multimedia and entertainment home networking applications. Powered by Celeno's system-on-chip (SoC) and its OptimizAIR&trade; technology, home gateways, multi-room DVRs and media servers can distribute multiple and simultaneous HD video streams to standard set-top boxes, PCs, television sets and other Wi-Fi enabled consumer devices. Founded in 2005, the company has offices and representatives in EMEA, the US and Asia-Pacific and is backed by blue chip investors including Cisco Systems, Greylock Partners and Pitango Venture Capital. www.celeno.com </p>
