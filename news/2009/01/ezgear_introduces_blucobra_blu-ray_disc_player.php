<p><B>Las Vegas, NV - CES 2009</B> - ezGear, a leading marketer of state of the art audio and video products, -announces the introduction of the BluCobra EZ3000 video player for Blu-ray Discs.  The EZ3000 is the first in the new BluCobra line of products from ezGear.  BluCobra Blu-ray players include a full host of features you get with higher end models at an affordable price.</p>

<p><br />
<B>Formats</B></p>

<p>The BluCobra EZ3000 is a multi-format player that supports DVD, SACD and Blu-ray with full 1080p/24Hz output.  For TVs that support lower resolutions, the player will also provide output in 1080i, 720P, and 480i.  Composite video is also supported.  The EZ3000 supports BD Profile 1.1 (Bonus View) and BD-ROM as well.</p>

<p><br />
<B>Video Outputs</B></p>

<p>The EZ3000 provides a full range of outputs so you can connect the player to the most popular TVs and audio systems.  Output connections include HDMI 1.3 output, Component Video output, composite video and S-Video outputs.</p>

<p><br />
<B>Audio Formats and Output</B></p>

<p>Multiple audio formats are supported by the EZ3000, including Digital Dolby. MPEG-2 Audio, Dolby TrueHD (lossless) and DTS-HD Master Audio.  The EZ3000 can be connected to virtually any audio device.  Two (2) channel downmix audio is provided to connect directly to your stereo TV or stereo hi-fi system.  Analog 7.1 audio is supported for stereo Hi-Fi with analog inputs.  You can also get a state of the art audio experience with full 7.1 Digital audio connections.  Both Optical and Coaxial digital audio is supported.</p>

<p>According to Charlie Bernstein, President of ezGear "With the conversion to HDTV almost complete, the demand for affordable Blu-ray players is growing everyday.  To date, full-featured Blu-ray players have been too expensive for many consumers.  With the economic challenges facing everyone, ezGear believes American consumers are looking for Blu-ray products they can afford.  With an affordable price and the flexibility of the EZ3000 to connect to virtually any TV or Stereo, ezGear is making it easier for consumers to adopt digital television in 2009."</p>

<p><br />
<B>Availability</B></p>

<p>The BluCobra EZ3000 will be available in the Spring of 2009.  The Manufacturer's Suggested List Price of the EZ3000 is expected to be $399.99 or below.</p>

