<p>The tournament season kicks off Thursday with the exclusive telecast of the Mercedes-Benz Championship from the picturesque Plantation Course in Maui, Hawaii, which will air for the first time in high definition. GOLF CHANNEL will then stay in the islands for the PGA TOUR's Sony Open in Hawaii, the Champions Tour's Mitsubishi Electric Championship at Hualalai and the LPGA Tour's SBS Open at Turtle Bay, all shown in HD for the first time.</p>

