<center><i>LED Technology Brings Higher Contrast Ratios, Slimmer Designs and Improved Energy Efficiency to the Living Room</i></center><br />
<br />

<p><B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, raises the bar for flat-panel TVs everywhere with the launch of an entirely new line-up of advanced LED HDTVs. Samsung's latest HDTVs will be on display at Booth #11033 during the International Consumer Electronics Show, which will be held at the Las Vegas Convention Center, January 8 -11, 2009.</p>

<p>The new 8000, 7000 and 6000 Series build upon the success of Samsung's first and second generation LED HDTV models. These cutting-edge TVs use LEDs as their primary light source, rather than traditional Cold Cathode Fluorescent Lamps (CCFL). Benefits of using LEDs include ultra-high contrast ratios, slim depths that allow for more artful designs, plus increased energy savings. In addition, a variety of state-of-the-art networking features give the ability to adapt to how consumers view and experience with shows, movies, games and other multimedia at home.</p>

<p>"Samsung has proven LED technology is a viable choice for consumers desiring the best picture possible from an LCD television. Samsung's latest LED televisions redefine the standards for viewing quality, energy-efficiency and home entertainment décor," said Jonas Tanenbaum, Vice President of LCD HDTV Marketing at Samsung Electronics America. "Samsung stays committed to developing technology and products that go beyond current expectations of value, quality and innovation. And, we are excited to be a part of this exciting point in TV evolution."</p>

<p><br />
<B>Top-Notch Picture Quality</B></p>

<p>Each of the three Samsung LED HDTV Series for 2009 boast high dynamic contrast ratios, complements of Samsung's ground breaking LED light source. Compared to a traditional CCFL, LEDs produce darker blacks that appear endlessly deep to the eye. Whites also remain crisp and bright with vivid colors. The result is picture quality that measures up to the natural beauty of life. For instance, Samsung's Wide Color Enhancer Pro feature lets consumers enjoy a broader color palette. The Ultra Clear Panel further allows the preservation of every detail even in brightly-lit, imperfect viewing conditions. This is done by effectively allowing more light to pass through the screen and simultaneously reducing reflections from ambient light. And with an adaptive "Natural" mode, Samsung's LED HDTVs can combine the recognized brightness advantage of LCD displays with the cinema-like viewing experience of plasma displays by automatically optimizing picture settings.</p>

<p>Samsung's entire LED HDTV line-up incorporates a number of innovative features to reduce the motion blur and image judder, which traditionally plague LCD HDTVs when displaying fast movement. All three series boast Samsung's acclaimed Auto Motion Plus&trade; frame interpolation technology. The 8000 Series uses a swift refresh rate of 240Hz - four times the rate of other TVs - that nearly eliminates the ill effects of displaying quick, action-packed motion. The 7000 and 6000 Series, with an also-quick 120Hz refresh rate helps ensure crisp, easy viewing of sports, video games and movies.</p>

<p><br />
<B>Expansive Networking and Entertainment Possibilities</B></p>

<p>In 2009, Samsung plans to redefine what it means to watch television with "Internet@TV - Content Service" Developed with Yahoo!, the Internet information interface will be available on a number of 2009-model Samsung HDTVs. Using either a wired or wireless Ethernet connection included in the 8000 and 7000 Series, "Internet@TV - Content Service" lets consumers access content onscreen from Yahoo!, Flickr, YouTube and more with the push of a button. The widgets-based interface and scrollbar run along the bottom of the screen for easy browsing of the latest programs and content. Even after purchase, consumers will be able to enjoy a growing library of widgets, as the widget development kit will be open to content providers willing to create new offerings. The 6000 Series includes access to Samsung's InfoLink&trade; RSS service, which can instantly display updated news, sports, weather and stocks information with a touch of the remote.</p>

<p>Beyond online entertainment, Samsung's LED HDTVs can also connect to a variety of other devices and content with ease. Included USB ports make viewing videos and photos from a camcorder, playing music from a media player or accessing multimedia files from a portable drive simple.</p>

<p><br />
<B>Lighting the Way for Functional Design</B></p>

<p>Samsung's new LED HDTVs offer not only a lifelike viewing experience and a portal to the latest entertainment, but break free from the conventional limits of integrating a television into a room's décor. By using LEDs, Samsung has been able to shave all three series down to ultra-thin depths. At just over an inch thick, the sets remain trim without cutting back on connectivity options, nor foregoing an ATSC tuner.</p>

<p>To further complement the svelte design of the new LED HDTVs, Samsung created an ultra-slim wall-mount solution - reducing the gap between the TV and the wall to around 0.6 inches, down from the two inches of bulkier solutions. The ultra-thin LED HDTV depth coupled with the new wall-mount solution allows for a simple installation akin to hanging a picture frame.</p>

<p>In 2008, Samsung created its unique Touch of Color&trade; (ToC&trade;) design, which uses dual-injection molding to coat a translucent, colored surface to achieve an attractive crystalline appearance. The latest evolution of Samsung's ToC&trade; design begins with a deep piano black bezel that fades into distinct chrome that finishes as a clear prism along the outer edges (8000 Series) or light ruby (7000 and 6000 Series) highlights. The intensity of the color subtly changes depending upon the viewing angle, and further accentuates these TV's slim bezels.</p>

<p><br />
<B>Going Greener</B></p>

<p>Lit by LEDs the Samsung 8000, 7000 and 6000 Series all meet the more stringent Energy Star&reg; v3.0 guidelines by cutting power consumption to significantly new lows. LEDs are also mercury-free, which adds another degree of environmental friendliness and safety compared with other currently available backlight technologies. Energy consumption is reduced by 40%+ versus traditional LCD HDTVs of similar size. The LED HDTVs also include an optimized energy savings mode that adjusts the backlight and picture quality while continuing to produce smoother, more natural images.</p>

