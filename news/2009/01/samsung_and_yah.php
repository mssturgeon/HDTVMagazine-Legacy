				<p class="prtitle">Samsung and Yahoo!&reg; Bring the Best of the Web to Television</p>

<center><i>Internet@TV - Content Service to Open a Whole New World of TV Interactivity for Consumers</i></center><br />
<br />

<p><br />
<B>SEOUL, Korea & SUNNYVALE, Calif.--(BUSINESS WIRE)</B>--Samsung Electronics Co., Ltd., a market leader and award-winning innovator in consumer electronics, and Yahoo! Inc., a leading global Internet company, today announced a new Internet-based service to Samsung televisions available in the spring of 2009. Select models in Samsung's 2009 flat-panel HDTV line-up will be powered by the Yahoo! Widget Engine, a fifth-generation applications platform that enables TV watchers to interact with and enjoy a rich set of "TV Widgets." TV Widgets make it easy to interact with Internet content and services to complement and enhance the traditional TV viewing experience. The lightweight Javascript and XML applications bring content, information and community features available on the Internet within easy reach of the remote control. The new televisions will be displayed at CES 2009 in Samsung's booth located at Central Hall, Booth #11033.</p>

<p>Select models in Samsung's 2009 flat-panel HDTV lines will support the new TV Widget service, called "Internet@TV - Content Service." The service, which adapts the Yahoo! Widget Engine, enables users to engage in a variety of experiences that traditionally could only be enjoyed on a PC. Not only will users be able to track their stock portfolio and stay on top of headline news, but they may also browse through videos, share photos and interact with friends. Users can access the service by connecting the HDTV to a home network via the built-in Ethernet port or using an optional Wi-Fi USB dongle.</p>

<p>The suite of TV Widgets range from a host of Yahoo! properties, including Flickr&trade;, Yahoo! News, Yahoo! Weather and Yahoo! Finance, to third-party content from well-known brands, including USA TODAY&reg;, YouTube&trade;, eBay&reg; and Showtime Networks&reg; among others. The content and services offered will grow to include video streaming and other popular internet services.</p>

<p>Developers worldwide will be able to develop and deploy TV Widgets for the television by using the open-platform Widget Development Kit (WDK). At the same time, Samsung will continue to provide high-performing TV hardware so that developers can easily deploy widgets on Samsung HDTVs. Samsung and Yahoo! will expand their collaboration further to bring more developers to the Internet@TV -Content Service and build an open ecosystem where more developers can create various TV Widgets for consumers to enjoy on their televisions.</p>

<p>"Samsung has been a proven innovator in Internet-enabled TV technology for some time now, offering the ground-breaking InfoLink service last year in 2008. There's no denying that the easy-to-use, one-touch of the remote control service successfully provides information simply and effectively," said Boo-Keun Yoon, Executive Vice President of the Visual Display Division at Samsung Electronics. He continues, "The collaboration with Yahoo! lets viewers go one step further. This new interface allows them to interact and connect with many of their favorite Web services on a personal level. It's frankly way beyond just passively watching broadcasts and is no doubt the future of TV."</p>

<p>"As a leader in developing innovative technology platforms to provide indispensable Internet services to millions of users, Yahoo! is excited to be working with Samsung to enhance consumers' television viewing experience by bringing the best of the Web to their televisions," said Patrick Barry, vice president of Connected TV at Yahoo! "Through this partnership, we can combine the Internet benefits of user choice and personalization with Samsung's leading product innovation and global reach to deliver a new experience to users around the world."</p>

<p>Samsung HDTVs with the Yahoo! Widget Engine and TV Widgets will be available in 13 countries in 2009 including the U.S, Canada, Mexico, United Kingdom, Germany, France, Italy, Spain, The Netherlands, Denmark, Norway, Sweden, and Finland. This provides publishers and developers the opportunity to create exciting TV Widget experiences that will reach and engage millions of Samsung TV viewers.</p>

<p>About Samsung Electronics</p>

<p>Samsung Electronics Co., Ltd. is a global leader in semiconductor, telecommunication, digital media and digital convergence technologies with 2007 consolidated sales of US$105.0 billion. Employing approximately 150,000 people in 134 offices in 62 countries, the company consists of four main business units: Digital Media Business, LCD Business, Semiconductor Business, and Telecommunication Business. Recognized as one of the fastest growing global brands, Samsung Electronics is a leading producer of digital TVs, memory chips, mobile phones and TFT-LCDs. For more information, please visit www.samsung.com.</p>

<p>About Yahoo!</p>

<p>Yahoo! Inc. is a leading global Internet brand and one of the most trafficked Internet destinations worldwide. Yahoo! is focused on powering its communities of users, advertisers, publishers, and developers by creating indispensable experiences built on trust. Yahoo! is headquartered in Sunnyvale, California.</p>

