<center><i>Blu-ray Technology is Even Easier to Enjoy with Samsung's Trio of Home Theater Systems</i></center><br />
<br />

<p><B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, today debuts its new line of award-winning home theater offerings, including the HT-BD8200 Blu-ray Home Theater Sound Bar, HT-BD7200 Blu-ray 2.1 channel Home Theater System, and the HT-BD1250 5.1 channel Blu-ray Home Theater System. The HT-BD8200 and HT-BD7200 are 2009 CES "Best of Innovations" Award winners, while the HT-BD1250 Blu-ray Home Theater System is a CES 2009 Innovations Design and Engineering Award honoree. Samsung's home entertainment lineup, available in the first half of 2009, will be on display at Booth #11033 during the International Consumer Electronics Show, which will be held at the Las Vegas Convention Center, January 8 -11, 2009.</p>

<p>"Focused on packaging powerful audio performance, the latest connectivity options and clean, yet sophisticated design, Samsung's 2009 home theater line-up offers a true variety of options to meet unique consumer preferences," said Reid Sullivan, vice president of Audio/Video and Digital Imaging Marketing at Samsung Electronics America. "As a recognized leader in technology innovation, Samsung delivers an unrivaled home theater experience with its award-winning Home Theater Systems."</p>

<p><br />
<B>HT-BD8200 Blu-ray Home Theater Sound Bar</B></p>

<p>The Samsung HT-BD8200 is the first home theater sound bar equipped with a Blu-ray player and wireless subwoofer, which delivers a streamlined, HD surround sound solution built to expand the prowess of any home theater. It features a fully integrated Blu-ray player with Full HD 1080p playback and virtual 5.1-channel surround sound for a lifelike audio presence.</p>

<p>As a self-contained, wall-mountable home theater sound bar, the HT-BD8200 is designed to fit in with today's contemporary décor and lifestyle. It is only 2.6 inches deep and accented with Samsung's Touch of Color&trade; (ToC&trade;) design, for a classy, yet cutting-edge look. The included wireless subwoofer provides a superior blend of effective audio performance and interior design flexibility just about anywhere in the home.</p>

<p>The HT-BD8200 is also equipped with Samsung's "Smart Volume" technology for volume level adjustments on-the-fly for superb listening levels without the need to continually pick up the remote. It also offers seamless playback of video, photos, or music from digital devices such as media players, mobile phones, and digital cameras, using either the built-in USB port or Bluetooth&trade; wireless connectivity. Multimedia disc playback and an included iPod dock add even more versatility to the system's cachet.</p>

<p>Equipped with wireless networking via an 802.11 b/g/n and optional USB dongle, the HT-BD8200 is compatible with BD-Live (Profile 2.0) interactive features and can access Netflix for instant streaming video or Pandora music.</p>

<p><br />
<B>HT-BD7200 Blu-ray Home Theater System</B></p>

<p>The Samsung HT-BD7200 2.1-channel Blu-ray home theater is ideal for consumers seeking sophisticated décor, superior performance, and comfort in their home theater solutions. Its compact design can fit into even the smallest rooms, making it more practical for deploying a full-sized multi-speaker home theater system.</p>

<p>The HT-BD7200 is a self-contained device that only appears diminutive. The system pumps out an impressive 400W output and simulated 5.1-channel surround sound using just two speakers. To enhance audio fidelity, it features an improved amplifier engine designed to minimize amplifier and power supply noise. The speaker unit itself is constructed from kelp, a natural material providing more audio clarity compared with conventional paper cone units. The system is also equipped with wireless networking via an optional 802.11 b/g/n USB dongle for additional convenience, and a speedy boot up time that is 2x faster than the industry standard.</p>

<p>The HT-BD7200 is dressed in Samsung's latest ToCTM treatment, providing a luxurious charcoal grey coating to the black bezel of the system.</p>

<p><br />
<B>HT-BD1250 Blu-ray Home Theater System</B></p>

<p>Samsung's HT-BD1250 Blu-ray Home Theater System offers consumers an affordable opportunity to discover the crisp picture and powerful audio performance brought by Blu-ray without compromising space. Boasting 1,000 watts of output and 5.1-Channel sound, the HT-BD1250 produces rich, lifelike audio and is capable of decoding high-definition formats including, Dolby Digital Plus&trade;, Dolby TrueHD&trade; and DTS-HD Master Audio&reg;. Similar to the HT-BD7200, the speaker cones are constructed using sea kelp rather than the traditional, chemically-treated paper pulp, for natural and improved sound reproduction. This model is also WiFi ready and also features the new amplifier technology as mentioned in the HT-BD7200.</p>

