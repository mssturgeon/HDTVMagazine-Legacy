				<p class="prtitle">Verizon Now Offers 100 or More High-Definition Channels in all FiOS TV Markets</p>

<center><i>FiOS Leads in HD, With More HD Channels, Pure HD Picture-and-Sound Quality, More Interactive Features -- Delivered Over the Network Built for High Definition</i></center><br />
<br />

<p><B>NEW YORK, Jan. 8 /PRNewswire/</B> -- Verizon FiOS TV now provides 100 or more channels of high-definition (HD) television in every market where the TV service is offered, delivering Verizon's promise to provide the ultimate high-definition home-entertainment experience by surpassing all of its cable competitors in the number of HD channels it offers. FiOS TV also offers superior picture-and-sound quality because it is delivered over the nation's most advanced all-fiber-optic network, straight to customers' homes.</p>

<p>"There's HD on FiOS and then there's everything else," said Shawn Strickland, vice president of FiOS products for Verizon. "The immense capacity and superior quality of our advanced all-fiber-optic network give customers the best HD experience with more channels, pure HD picture-and-sound quality, and interactive features old-fashioned cable only dreams of."</p>

<p>Verizon's HD leadership extends beyond the number of HD channels offered to also include:</p>

<p>  --  Superior picture-and-sound quality -- There is less pixilation or other digital distortion with FiOS TV than with cable or satellite. Also, unlike some cable providers, Verizon does not add additional compression that can degrade quality in delivering FiOS TV to customers.</p>

<p>  --  Technology innovation -- FiOS TV offers a multi-room DVR that allows subscribers to use one DVR to record standard- and high-definition programming that can be watched on up to six other sets in the home. This includes viewing up to three separately recorded programs simultaneously on different sets and the ability to pause recorded programming on one set and continue watching it on another.  Customers who subscribe to FiOS TV's Home Media DVR can program their DVRs and set their parental controls remotely - either through Verizon's FiOS TV Central Web site (www.verizon.com/fiostvcentral) or via select Verizon Wireless handsets.</p>

<p>  --  Service quality -- FiOS TV scored highest in J.D. Power's 2008 Residential Television Service Satisfaction Study for the East Region. A leading consumer magazine gave FiOS TV the top rating in its most recent survey of television service, with top marks in all six categories it measured:  channel choice, image quality, sound quality, reliability, value and support.</p>

<p><br />
Verizon is making it easier than ever for people to discover the FiOS TV HD difference, with a new promotional offer. New customers who subscribe to FiOS TV between now and Feb. 21 will receive their choice of free use for six months of either a high-definition (HD) digital video recorder (DVR) or an HD Home Media DVR. Customers who take advantage of this offer will save between $95 and $119 during the first six months, depending upon the DVR customers choose.</p>

<p>More than 1.6 million customers currently subscribe to the all-digital service, which is available for sale to more than 8.2 million homes and small businesses in 14 states. FiOS TV offers a broad collection of programming, with more than 500 all-digital channels and 14,000 video-on-demand titles each month - including more than 1,200 HD VOD titles per month.</p>

<p>For more information on FiOS TV, consumers can visit www.verizon.com/fiostv or call their local Verizon sales office or 888-438-3467.</p>

<p>Verizon Communications Inc. (NYSE:VZ) , headquartered in New York, is a leader in delivering broadband and other wireline and wireless communication innovations to mass market, business, government and wholesale customers. Verizon Wireless operates America's most reliable wireless network, serving nearly 71 million customers nationwide. Verizon's Wireline operations include Verizon Business, which delivers innovative and seamless business solutions to customers around the world, and Verizon Telecom, which brings customers the benefits of converged communications, information and entertainment services over the nation's most advanced fiber-optic network. A Dow 30 company, Verizon employs a diverse workforce of more than 228,000 and last year generated consolidated operating revenues of $93.5 billion. For more information, visit www.verizon.com.</p>

