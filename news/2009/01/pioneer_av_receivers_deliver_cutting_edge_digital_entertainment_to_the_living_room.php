<B>Premium Home Theater Digital Entertainment Connectivity</B></p>

<p>As the central hub for all home entertainment components, Pioneer's top three new models are designed as the most dynamic solution to connect and improve playback performance for the 174 million iPod and 13 million iPhone devices purchased to date.* With a multi-format front panel USB port that can handle an array of MP3 music files, consumers can seamlessly navigate and choose personalized playlists using just the receiver's remote control and a dedicated OSD.</p>

<p>The VSX-919 and VSX-1019AH transcend music selection capabilities and add a touch of style to the traditional mobile device experience with full-color artwork from a selected song or album that can be displayed on a connected HDTV.</p>

<p><br />
<B>Compressed Audio Restored for Surround Sound Performance</B></p>

<p>Pioneer continues to integrate its industry-leading Advanced Sound Retriever (ASR) and Auto Level Control (ALC) audio improvement technologies across all four new models to elevate the sound quality experience of compressed media beyond one's earphones. In the VSX-919AH and VSX-1019AH models, engineers utilize updated versions of these features to deliver fuller, more natural surround sound across various content.</p>

<p>    * Pioneer's ASR - Greatly enhances sound reproduction of iPhone, iPod and other portable media players as well as satellite radio devices by restoring the critical audio data that is often removed from a compressed audio file. When played back on a home theater system, audiences gain robust music that is near CD quality. The VSX-919AH and VSx-1019AH also feature ASR-multi, which restores compressed multi-channel legacy audio formats including Dolby&reg; Digital and DTS&reg; 5.1, often found on DVD movies and satellite or cable television programming.<br />
    * Pioneer's ALC - Recognizing that volume levels can fluctuate across digital audio tracks (i.e. MP3 and iPod), input sources and even television channels and commercials to cause disruptive entertainment, ALC is utilized to equalize these inconsistent volume levels. By restoring the gap in recorded and playback volume without diminishing audio quality, ALC ensures consistent listening from all entertainment. The VSX-919AH and VSx-1019AH also feature ALC3e-multi, which delivers multi-channel digital audio quality even in low volume listening.</p>

<p><br />
<B>Outfitted for the High Resolution Entertainment System</B></p>

<p>To fulfill the high resolution demands of audiophiles, Pioneer's top three models support Dolby TrueHD and DTS-HD high resolution audio formats from Blu-ray Disc&reg; feature films. The VSX-919AH and VSX-1019AH models also incorporate proprietary Hybrid Amplifier Technology II (P.H.A.T.) to ensure powerful, high quality, multi-channel sound performance at greater efficiency levels.</p>

<p><br />
<B>Audio Integration for Entire Home</B></p>

<p>Dedicated to providing a premium, customized audio entertainment experience throughout the home, Pioneer's new A/V receivers offers home integration features including:</p>

<p>    * Multi-Zone Audio - Pioneer's new models serve as the entertainment showpiece of up to two audio zone in the house. Users can even enjoy 2nd zone full-color OSD for Sirius as well as iPod album artwork (VSX-1019AH).<br />
    * Precision Quartz Lock System (PQLS) - Pioneer's engineers developed unique settings in its A/V receivers to harmonize audio performance with jitter-free playback and dynamic sound quality for music CDs. When connected to a new Blu-ray Disc player via HDMI, the VSX-919AH and VSX-1019AH utilize a proprietary PQLS technology that synchronizes data between the player and receiver.<br />
    * Multi-Channel Acoustic Calibration (MCACC) - Pioneer's exclusive high resolution sound tuning feature MCACC gives users finely tuned sound performance for their movies and music. MCACC room calibration takes inventory of a room's speakers then digitally optimizes each one to balance out any room-induced acoustic inaccuracies. With the top three models listeners gain extremely accurate, robust sound that reaches the ear at precisely the right time, sound level and equalization. The VSX-919AH and VSX-1019AH receivers allow users to make additional subtle adjustments as well as save room tuning settings.</p>

