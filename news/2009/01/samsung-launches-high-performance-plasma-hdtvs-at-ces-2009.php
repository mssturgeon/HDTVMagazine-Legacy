<p><br />
<B>Luxurious Design</B></p>

<p>Measuring just over an inch in depth, Samsung's Series 8 Plasma HDTVs is the world's slimmest 1080p resolution plasma sets to feature built-in ATSC tuners.</p>

<p>Featuring a New ToC&trade; treated chassis, the Series 8 sports a chrome-like translucent surface, which encases the bezel. This unique treatment contrasts the TV's black bezel to enhance its ultra-slim depth. Additionally, the outer edges of the bezel resemble a prism, magnifying light in such a way that its color intensity changes depending on the viewing angle.</p>

<p>In the case of the Series 6, a specially-designed, semi-transparent rose black hue lends a seductive hint of color to the TV's glass-like frame. Each of the HDTV's gracefully curved edges is transparent, creating the illusion of a display floating in mid-air. Further enhancing the design, the sets are also supported by a clear, reinforced glass stand giving it a "barely there" appearance.</p>

<p><br />
<B>Breathtaking Picture Quality</B></p>

<p>Despite their slim design, Samsung's Plasma HDTVs harness the latest display technology to produce unmatched picture performance and deliver the ultimate in HDTV viewing experience.</p>

<p>These advancements include an extremely high dynamic contrast ratio along with Ultra FilterBright technology, which uses arrays of black-coated color enhancement film to minimize glare and maximize contrast. Additionally, Samsung's Ultra Filter Bright Plus reduces the luminance in black levels by 50 percent over previous models for one of the darkest blacks ever seen on an HDTV.</p>

<p>And Samsung's exclusive Wide Color Enhancer 3 maps HD or SD signals to the panel's native color space, which covers 110 percent of the HD specification, helping the set portray hues in lifelike brilliance.</p>

<p><br />
<B>Sophisticated Multimedia and Networking Skills</B></p>

<p>The Series 8 and 6 plasma HDTVs are also equipped with the Internet@TV - Content Service platform that brings the best of the Web to the television. Powered by the innovative Yahoo! Widget Engine, Samsung's Internet@TV - Content Service enables users to access internet based multimedia content from their favorite Internet sources. They'll not only be able to take care of everyday tasks like tracking stocks and staying on top of headline news, but users can also browse videos, share photos and interact with friends. The suite of services ranges from a host of Yahoo! properties (Flickr, News, Weather and Finance) to third-party content from well-known names including USA Today, YouTube and eBay.</p>

<p>Samsung's newest plasma displays are among the first TVs to be wireless DLNA-compliant, allowing consumers to enjoy their entire library of media content that may exist in various locations around the house without the hassle of extra cabling. Additionally, users can connect storage and mobile devices to the USB 2.0 port to play a variety of multimedia files via USB 2.0 Movie. An expanded list of supported codecs, which will also include 3GPP, MKV, WMV9 and DivX, gives consumers even more freedom to easily access and share nearly all forms of digital content.</p>

<p><br />
<B>The Greenest Plasmas Yet</B></p>

<p>Samsung has gone to great lengths to make all the new Plasma HDTVs the most eco-friendly plasma line yet. Engineered with high-efficiency panels, these sets intelligently conserve power and as a result meet the stringent Energy Star&reg; 3.0 efficiency standard. In addition, these HDTVs are constructed using lead-free materials, making them even more environmentally friendly than the competition.</p>

