<B>LAS VEGAS--(BUSINESS WIRE)</B>--Samsung Electronics America, Inc., a market leader and award-winning innovator in consumer electronics, today unveiled two series of advanced plasma HDTVs. Delivering full HD 1080p resolution, increased energy efficiency, breath-taking design and deeper levels of black performance, Samsung's latest plasma line sets a new standard of excellence in the Plasma HDTV category.</p>

