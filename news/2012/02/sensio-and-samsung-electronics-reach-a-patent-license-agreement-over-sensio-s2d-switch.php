The proprietary SENSIO&reg; S2D Switch, which is protected by US and international patents, enables users to switch viewing mode of a 3D feed from 3D to 2D or between different 3D view modes. It supports the most popular frame-compatible formats covered by HDMI 1.4a, and is used by service providers supporting 3D today: side-by-side (SbS), top-and-bottom (TaB), checkerboard and SENSIO&reg; Hi-Fi 3D.</p>

