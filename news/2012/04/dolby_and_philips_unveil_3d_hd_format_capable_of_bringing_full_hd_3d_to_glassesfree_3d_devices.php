<p><img src="http://www.hdtvmagazine.us/news/images/2012-04-13_Dolby_3D_color.jpeg" alt="Dolby 3D" height="67" width="120" class="keyimg"><strong>LAS VEGAS--(BUSINESS WIRE)--</strong>Dolby Laboratories, Inc. (NYSE: DLB) and Royal Philips Electronics (NYSE: PHG; AEX: PHI) today unveiled Dolby&reg; 3D, a 3D HD format and suite of technologies designed to deliver full HD 3D content to 3D-enabled devices, including glasses-free displays. Dolby 3D is being demonstrated at the NAB Show&reg; (April 16–19, 2012) at booth SU1212.</p>

<p>The two leading companies have undertaken the joint project to improve the 3D viewing experience on displays of all sizes, including smartphones, tablets, PCs, and televisions. Dolby 3D is a complete system designed to work throughout the chain to deliver clear glasses-free 3D content that operates over existing distribution systems.</p>

<p>"Philips&reg; has a long history in 3D technologies and video innovation, and Dolby has a proven track record of enabling technologies to enhance entertainment experiences. Together, we identified a business need where we could bring a unique offering to the market that improves the end-user experience," said Ruud Peters, Chief Intellectual Property Officer at Philips. "By unveiling Dolby 3D, we introduce a 3D HD format capable of powering glasses-free 3D displays of any size, enabling broadcasters, operators, content aggregators, and device manufacturers to deliver HD-quality 3D on any device."</p>

<p>Ramzi Haidamus, Executive Vice President, Sales and Marketing, Dolby Laboratories, stated: "We believe that Dolby 3D can help drive the adoption of 3D—creating a comfortable, customizable, truly enjoyable glasses-free 3D viewing experience while enhancing 3D display performance. Armed with the innovative glasses-free 3D display technology from Philips, based on years of extensive research and development in the field, we plan to bring the same philosophy to 3D that Dolby has brought to the audio space—integrating our technologies and strengths throughout the entire content chain. Consumers will know that when they see Dolby 3D content on a 3D-enabled device, it will look its very best."</p>

<p>"Dolby and Philips are committed to taking the 3D experience to the next level and delivering a high-quality solution for all 3D display devices, including today's glasses-based devices and tomorrow's glasses-free displays. Working on cutting-edge technology with two leading companies is very exciting, and I'm thrilled to lead this unique joint effort," said Guido Voltolina, General Manager of the joint project.</p>

<p>The focus of the project will be to work with original equipment manufacturers of display panels and entertainment devices to enhance the performance of 3D consumer devices to make viewing of 3D content just as convenient and appealing as viewing of 2D content on a high-quality screen is today. This project is uniquely positioned to enable the industry's adoption of 3D by working on standardization and licensing of the technology.</p>

<p>The Dolby 3D experience will seamlessly integrate into the use cases and viewing patterns of consumers on the go and in the home, making the use of 3D devices an enjoyable daily experience. Content owners and broadcast operators have the unique opportunity to differentiate their offerings by encoding 3D titles in Dolby 3D for maximum fidelity on Dolby 3D enabled devices while maintaining compatibility with existing 3D products. The system will enable a 3D HD format, including tools for 3D content creation and real-time 3D content conversion.</p>

