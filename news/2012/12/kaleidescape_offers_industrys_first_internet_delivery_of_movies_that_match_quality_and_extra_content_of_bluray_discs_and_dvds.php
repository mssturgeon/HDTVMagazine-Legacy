<p><img src="http://www.hdtvmagazine.com/news/images/kaleidescape-blu-ray.jpeg" alt="Images/Kaleidescape blu ray" height="675" width="328" class="keyimg"><strong>SUNNYVALE, Calif., Dec. 11, 2012 /PRNewswire/</strong> -- Kaleidescape, Inc. today announced an industry-first service that enables the digital delivery of movie purchases over the Internet with video and audio quality equal to Blu-ray Disc&trade; and DVD. The new service is initially backed by a multi-year license agreement with Warner Bros. Digital Distribution and marks the first agreement that enables the electronic delivery of digital movies containing all of the extra content found on physical Blu-ray Discs or DVDs.</p>

<p>Customers can now purchase and download movies directly to their Kaleidescape Systems from the newly launched Kaleidescape Store that is designed exclusively for online movie sales.  This makes it easier than ever for Kaleidescape customers to expand their film libraries. Once a customer's system is linked to an account on the Kaleidescape Store website, the titles of their current movie collection are automatically cataloged and kept up to date.  This makes it simple to discover movies missing from a collection and avoid duplicate purchases.  In addition, the Kaleidescape Store provides the ability to buy multiple movie titles by a favorite actor or director, all available Academy Award&reg; winning titles, and more with a single mouse click.</p>

<p>Warner Bros. Digital Distribution is the first to license content for sale through the new Kaleidescape Store, providing nearly 3,000 premium films and over 8,000 television episodes.  To ensure Kaleidescape System owners have access to their movies on their mobile devices, Kaleidescape has also licensed UltraViolet rights for inclusion with the purchase of most titles.  Future plans will enable the consumer to add movies already purchased on disc to their UltraViolet Collection for a small fee.</p>

<p>"This new distribution deal dramatically improves the way customers buy movies which, until now, has remained virtually the same for the past 15 years," said Ralph Tarnofsky, Founder and President of Professional Audio Consultants in Millburn, NJ. "Now, multiple inconveniences in the purchasing process are completely eliminated.  Customers no longer need to keep track of titles already purchased, wait for discs to arrive, or spend time organizing the discs.  Until now, the conveniences of digital delivery also meant compromising on quality and special features. Now Kaleidescape customers – who are avid movie collectors – can enjoy a 'no compromise' buying experience."</p>

<p>"The potential represented by the Kaleidescape System and the new Kaleidescape Store is, in many respects, similar to the role the iPod&reg; played in kick-starting online music purchases," said Michael Malcolm, Founder, Chairman and CEO of Kaleidescape.  "Our movie servers enable customers to consolidate their film libraries – whether from disc or download – for immediate playback. We believe that this consolidation is a pre-requisite for mass adoption of electronic movie purchases.  By introducing the Kaleidescape Store in conjunction with the Warner Bros. deal, we are simplifying how movies are purchased and enjoyed at home."</p>

<p><br />
<strong>How it Works</strong></p>

<p>Movies purchased on the Kaleidescape Store website can be downloaded and enjoyed on Kaleidescape movie servers through the newly released kOS 5.0 operating system.  Downloads take full advantage of the system's award-winning user interface that makes it easy for customers to find and select the film to enjoy from any television in the home. Movies can be viewed directly from the beginning without advertisements, trailers and extraneous menus. Thanks to bookmarks in the exclusive Kaleidescape Movie Guide, users can jump directly to the most memorable scenes in a movie, or to any song in a concert.</p>

<p>Kaleidescape's high definition downloads will feature audio and video that equals Blu-ray Disc quality. This includes video resolution up to 1080p, Dolby TrueHD and DTS-HD Master Audio lossless soundtracks, and 24 frame-per-second progressive scan video. Standard definition downloads feature audio and video that precisely matches DVD quality. The extra content such as director's commentary, alternate endings, deleted scenes, and documentaries found on a disc are included in the download.</p>

<p><br />
<strong>Pricing and Availability</strong></p>

<p>The Kaleidescape Store is now live in the United States. For additional information on an invitation to use the service, availability of movie titles, or pricing, please visit https://store.kaleidescape.com.</p>

