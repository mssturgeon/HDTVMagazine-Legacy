<p>Kaleidescape is pioneering the development of movie servers that redefine how film enthusiasts purchase, organize and enjoy their movie collections.  Featuring a breakthrough user interface that gives viewers unprecedented flexibility and control over the movies they watch, the Kaleidescape system makes it easy for customers to select and enjoy films from their entire collection of DVD, Blu-ray and downloaded movies from any television in the home.  Founded in 2001 and headquartered in Sunnyvale, California, Kaleidescape sells its products through custom installation dealers and distributors throughout the world. For more information, please visit <a target="_blank" href="http://www.kaleidescape.com/">www.kaleidescape.com</a>.</p>

