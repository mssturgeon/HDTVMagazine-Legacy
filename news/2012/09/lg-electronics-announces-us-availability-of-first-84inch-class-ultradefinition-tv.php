<p><strong>INDIANAPOLIS, Sept. 7, 2012 /PRNewswire/</strong> -- LG Electronics today announced U.S. availability for its enormous 84-inch (84.04 inch diagonal) LED display, boasting a native "ultra definition" (UD) screen resolution of 3840 x 2160 to match its impressive size*.</p>

<p>The gigantic 84-inch screen quadruples the level of detail from full 1080p HD resolution to a massive 8 million pixels. Even before so-called "4K" content is available, LG's proprietary Resolution Upscaler Plus delivers higher detail from current HD/SD external sources. A major step forward for the display industry, ultra-definition TV makes use of the screen real estate available with today's largest-size flat panels, much like the jump from 720p to 1080p years ago. The LG UD 84LM9600 is expected to be available in October at an MSRP of $19,999.99.</p>

<p>Gary Yacoubian, chairman of the Consumer Electronics Association's 4K Working Group and president and CEO, Specialty Technologies/SVSound, said, "I couldn't be more excited about ultra-definition 4K technology and its potential to energize our entire industry; 4K is the next big thing in television, literally. First there was analog, then digital - standard-definition, then high-definition (HDTV). Now, with four times the pixel resolution of today's HDTVs, ultra-HD technology promises to transform the home entertainment experience on giant displays, truly recreating the movie theater in your living room." </p>

<p>"Ultra-definition television will transform the giant-screen viewing experience in the years ahead, and LG is proud to bring this new technology to market so that discerning U.S. consumers can enjoy a fully immersive home theater experience," said Jay Vandenbree, senior vice president, home entertainment, LG Electronics USA, Inc. "Beyond just the ability to produce gigantic screens, it's important that LG offers its consumers a feature-rich TV packed with Smart TV, 3D capability, a 2.2 channel built-in speaker system and the remarkable detail of 4K. The 84LM9600 epitomizes LG's design and innovation prowess."</p>

<p><br />
<strong>Under the Hood</strong></p>

<p>Beyond the 84-inch screen, this model features LG's CINEMA 3D technology, which provides a comfortable 3D viewing experience similar to what consumers experience in the theater. LG CINEMA 3D utilizes polarized technology, with lightweight, inexpensive and shutter free glasses (six included in the box). For ultimate comfort, consumers can customize the 3D effect to their preference with 3D Depth Control.</p>

<p>Also included is LG Smart TV, which offers users access to thousands of proprietary apps, premium content services including Netflix, Hulu Plus and more**. LG Smart TV features LG's "3D World," where users can access blockbuster 3D content. Users can easily browse and navigate through the Smart TV ecosystem using LG's four-mode Magic Remote, which acts as an air mouse with point and click, gesture commands, a scroll wheel and voice recognition. LG's proprietary dual-core L9 processor chipset offers ultra-fast processing speeds for shorter load and lag time when streaming content.</p>

<p>LG's new UD 3D TV includes a wealth of connectivity options to make access to content even easier. In addition to built-in Wi-Fi, it supports Intel's Wireless Display (WiDi) technology, which enables easy and quick connectivity between TVs and PCs without the need for cables or Internet access. With Smart Share Plus, users can access content stored on external devices such as PCs, tablets and smartphones through a portal on the TV. This model supports the Mobile High-definition Link (MHL) standard, for easy content sharing between the TV and mobile devices and the ability to charge devices via the connection. Finally, the 84LM9600 includes a portal to the LG Cloud, so consumers can access their personal content, such as pictures, home video and music libraries uploaded to the LG Cloud. </p>

<p>*No "ultra definition" or "4K" content is currently available.  No broadcast or other standard currently exists for "4K" or "ultra definition" television, and the 84LM9800 may or may not be compatible with such standards if and when developed.</p>

<p>**Internet connection and certain subscriptions required and sold separately. Content and services vary by product and are subject to change without notice.</p>

<p>For a small percentage of the population, the viewing of stereoscopic 3D video may cause discomfort such as dizziness or nausea. If you experience any of these symptoms, discontinue using the 3D functionality and contact your health care provider.</p>

