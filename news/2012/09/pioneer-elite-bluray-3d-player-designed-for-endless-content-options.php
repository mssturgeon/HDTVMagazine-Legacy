<p><img src="http://www.hdtvmagazine.com/news/images/BDP-62FD.jpeg" alt="BDP-62FD" height="255" width="480" class="keyimg"><strong>INDIANAPOLIS--(BUSINESS WIRE)--CEDIA Show Booth #719</strong> - Pioneer Electronics (USA) Inc. continues to enhance the home theater experience with the release of its new Elite&reg; BDP-62FD Blu-ray Disc&trade; player. The BDP-62FD offers new features including expanded high-resolution file format playback, Marvell Qdeo&reg; video processing technology, dual HDMI&reg; output, and iControlAV2012 app control for additional convenience.</p>

<p>"The BDP-62FD is a great addition to any home theater system and can actually replace other devices because of all the network and audio features that are built into the player," said Chris Walker, director of AV product planning and marketing for the Home Electronics Division of Pioneer Electronics (USA) Inc. "And, with its audio and video quality, the BDP-62FD will enhance your overall home theater experience."</p>

<p>Pioneer's new Elite Blu-ray Disc player is designed with expanded playback capability to offer consumers more source material options for their music and movies. The BDP-62FD supports many of today's most popular video and audio file formats including Flash Video (.flv), used by many online video sites, and high-quality audiophile FLAC files, made possible through DLNA&reg; certification that allows music content to be shared from a PC via the user's home network. The player supports DTS-HD&reg; Master Audio&trade;, Dolby&reg; TrueHD, DVD-Audio, and Super Audio CD&reg; high-quality audio formats on disc. Many of the BDP-62FD compatible file formats can be stored and retrieved from a USB thumb drive, USB hard drive (NTFS formatted) or via a home network. For convenience and custom installation flexibility, the BDP-62FD offers full IP and RS232 support including wake-up on LAN.</p>

<p>DLNA certification of the BDP-62FD enables the player to work as a DMP/DMR (Digital Media Player/Digital Media Renderer), allowing the user to push content directly from a portable source, such as a compatible smartphone. Through a network connection via Ethernet or the optional AS-WL300 wireless network adapter, the BDP-62FD provides access to popular entertainment network services including Pandora&reg;, Netflix&reg; and YouTube&reg;. It's even easier for users to search for and select videos to play through the player with a recent update from YouTube: its YouTube Leanback feature, available on the BDP-62FD.</p>

<p>The BDP-62FD is built with Marvell's award-winning Qdeo&reg; technology, offering high quality video processing for maximum performance and flexibility to produce a more vivid, superior image. Qdeo also captures, processes and renders a wider variety of video signals ranging from high definition Blu-ray Disc to content from portable video sources such as smartphones, for a truly immersive viewing experience. The new player offers 3D video output with the latest HDMI 1.4a connectivity, allowing for passage of the high data transfer rate required by the Blu-ray 3D format. Additional features to enhance video performance include support for HDMI 1080p/24 Hz output, 36-Bit Deep Color for accurate color reproduction, as well as Pioneer's Stream Smoother and three separate noise reduction circuits to decrease video noise that can distort images and degrade video reproduction.</p>

<p>For added convenience, the new player is equipped with dual HDMI outputs allowing users to push content to two different displays such as a TV and projector simultaneously. The BDP-62FD also offers simplified control with Pioneer's iControlAV2012 App that enables Apple's iPad&reg;, iPhone&reg; or iPod touch&reg; to act as a basic remote control for the player when connected via a wireless router. The app is available for download at no charge from the App Store or at <a target="_blank" href="http://www.itunes.com/appstore/">www.itunes.com/appstore/</a>. The iControlAV2012 for Android smartphones is available on Google Play&trade;.</p>

<p>The Pioneer BDP-62FD Blu-ray 3D player will be available in September with a suggested retail price of $399.</p>

