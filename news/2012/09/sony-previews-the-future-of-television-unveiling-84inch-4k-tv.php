<p><img src="http://www.hdtvmagazine.us/news/images/XBR-84X900.png" alt="XBR-84X900" height="219" width="297" class="keyimg"><strong>New York, August 29, 2012</strong>– Sony Electronics announced its first TV capable of displaying 4K images, raising the curtain on the next wave in innovation from a company that knows a thing or two about television. The new 84-inch set, model XBR-84X900, is equipped with a 4K (3840 x 2160) LCD panel that delivers an image four times the resolution of Full HD and creates an immersive viewing experience previously unavailable from a TV. The new XBR 4KTV will arrive in Sony Stores and select retail locations in North America later this year.</p>

<p>"From Trinitron to HD, 3D and now 4K, Sony has led the way, innovating TV since 1968. This new model redefines what consumers should expect from their television's performance," said Brian Siegel, vice president of Sony Electronics' TV Group. "Our professional division continues to see the migration toward 4K content creation with major film and broadcast productions. Armed with this knowledge and expertise, only Sony continues to push the television experience with innovation and immersive products."</p>

<p>Incorporating proprietary upscaling technology including the 4K X-Reality PRO picture engine, the new TV is designed to ensure that every frame looks clear and crisp, with a 4K resolution regardless of the content source. Viewers can now watch video on the large screen of this XBR TV and not see any the degradation of image quality traditionally associated with larger screen sizes. High-resolution processing powers a 3D viewing experience that exceeds Full HD resolution. The accompanying 3D glasses use a light and comfortable passive design, allowing viewers to enjoy 3D footage on an impressive large screen the same way they would in a movie theater.</p>

<p>In addition to unmatched picture quality, Sony's XBR-84X900 4K TV ensures that a full cinema-like experience is delivered to the living room with an immersive, full-bodied and rich sound. The 4K TV incorporates a 10 Unit Live Speaker system which is optimized for this large-sized screen. Drawing on Sony's storied sound signal-processing technology, these speakers envelop the viewer in virtual 5.1 surround sound. The side speakers are also detachable,allowing consumers to connect to an existing home theater system.</p>

<p>The XBR-84X900 4K TV not only delivers a great viewing experience; it also offers consumers a new way to enjoy digital photographs. By simply connecting a digital camera, digital photos can be displayed on the large screen at 4K resolution, allowing viewers to browse scenic pictures that are reminiscent of colorful, large posters, or enable viewing of life-sized pictures of their family and friends. PlayStation&reg;3 software such as PlayMemories Studio can be used to easily manage and playback photographs at 4K resolution.</p>

<p>The XBR 4K TV also has full network connectivity, allowing consumers control of their viewing experience via a tablet or smartphone with the downloadable Media Remote App. With built-in WiFi they can access movies, TV shows, and online video and music through the Sony Entertainment Network suite of services including Music Unlimited, Video Unlimited, Netflix, Pandora, Yahoo! Broadcast Interactivity and more than 50 other popular internet entertainment providers.</p>

