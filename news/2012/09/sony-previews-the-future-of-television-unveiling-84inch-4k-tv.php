<strong>4K – A New Way to Feel the Beauty</strong></p>

<p>Sony leads the way in all aspects of the 4K workflow, from both the professional and consumer perspective. More than 12,500 of the company's 4K digital cinema projectors are in use at movie theaters throughout the world, and Sony is also leading the way in true 4K content creation with its flagship F65 CineAlta 4K camera. With several 4K movies in production, the first broadcast TV shows beginning to shoot in 4K and Taylor Swift's release tomorrow of the world's first-ever 4K music video the content evolution has begun. Also part of Sony's 4K line-up in the home is the VPL-VW1000ES, the first 4K home theater projector, which was announced last year and is available through custom installers.</p>

