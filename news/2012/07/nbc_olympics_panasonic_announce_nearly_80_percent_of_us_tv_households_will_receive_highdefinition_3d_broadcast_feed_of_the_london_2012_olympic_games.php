<p><strong>SECAUCUS, N.J., July 20, 2012 /PRNewswire/</strong> -- NBC Olympics, a division of the NBC Sports Group and Panasonic Corporation of North America today announced that the first-ever 3D coverage of the Olympic Games, beginning in London later this month, will be available to subscribers of MVPD's (multichannel video programming distributors) representing nearly 80% of U.S. TV households.  The daily 3D programming, which will be shown on next-day delay, will be carried by many cable, satellite and telco providers such as such as Armstrong, AT&amp;T, Blue Ridge, Bright House Networks, Cablevision, Comcast, Cox Communications, DIRECTV, Insight, Mediacom, RCN, Suddenlink, Time Warner Cable, Verizon, and  WideOpen West.</p>

<p>These carriers will distribute roughly 242 hours of the 3D broadcasts via the Media Center. Panasonic is NBC Olympics' exclusive Flat-Panel HDTV and Blu-ray Disc Player advertiser for the London Olympic Games.</p>

<p>"We are pleased that nearly 80 percent of U.S. TV households will receive the incomparable clarity and performance of the first-ever 3D production of the Olympic Games," said Joseph M. Taylor, Chairman &amp; CEO, Panasonic Corporation of North America. "Panasonic's 3D technology and NBC Olympics' superb, moment-by-moment coverage of the Games will make the events more engaging to viewers as they watch their favorite athletes compete."</p>

<p>The 3D broadcasts will be produced by Olympic Broadcasting Services (OBS) and will include some of the most-anticipated events of the Games, including:</p>

<ul><li>Opening and Closing Ceremonies</li><li>Men's and Women's gymnastics</li><li>Extensive coverage from the Aquatic Center, including both diving and swimming</li><li>Bicycle racing (cycling) from the Velodrome</li><li>Full coverage of track &amp; field from the Olympic Stadium</li></ul>

<p>NBC Olympics will provide 12 hours of U.S.-oriented 3D programming every day, introduced by Bob Costas and featuring both competitive highlights from the previous day as well as the best moments of the Games to-date.  Viewers who watch the award-winning primetime coverage on NBC will have the opportunity to go back and relive their favorite events as never before – in Full HD 3D.</p>

<p>Olympic Broadcasting Services will capture the Games using Panasonic's state-of-the-art 3D production technologies and fully-integrated twin-lens Full HD 3D camera recorder products.  A taste of what's in store can be sampled at retail outlets everywhere, where Panasonic 3D televisions will be displaying amazing 3D footage of the memorable Opening and Closing Ceremonies of the Beijing 2008 Olympic Games.</p>

