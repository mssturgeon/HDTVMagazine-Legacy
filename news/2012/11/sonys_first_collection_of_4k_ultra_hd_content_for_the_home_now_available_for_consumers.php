<p>"Sony is a company of firsts, and this introduction of the first 4K technology platform continues that pioneering, innovative spirit," said Phil Molyneux, president and chief operating officer of Sony Electronics. "We were the first to introduce 4K projectors to cinemas in 2005, the first to introduce a 4K projector designed for the home in 2011, and the first to offer a 4K upscaling Blu-ray Disc player earlier this year. Now, we're the first to begin closing the content loop, offering native 4K content for the home and delivering the most immersive, awe-inspiring entertainment experience yet."</p>

<p><br />
<strong>Delivering Exclusive 4K Ultra HD Content for the Home</strong></p>

<p>Sony, as a total entertainment company encompassing movies and TV production, music, games and electronics, is uniquely positioned to be first to market in delivering 4K Ultra HD solutions. The 4K Ultra HD Home Experience includes the 84" 4K LED TV, the Video Player, and  an Xperia&trade; Tablet S that serves as a remote control through an easy-to-use app. Pre-loaded onto the Video Player will be the following first ever collection of 10 full-length feature films presented in native 4K for the home:</p>

<ul><li>The Amazing Spiderman</li><li>Total Recall (2012)</li><li>The Karate Kid (2010)</li><li>Salt</li><li>Battle Los Angeles</li><li>The Other Guys</li><li>Bad Teacher</li><li>That's My Boy</li><li>Taxi Driver</li><li>The Bridge on the River Kwai</li></ul>

<p>"Sony Pictures leads the industry in building a library of new releases and restored classics mastered in 4K, so it is both exciting and appropriate that we can provide the first 4K movies that consumers will be able to experience in their homes," said Chris Cookson, president, Sony Pictures Technologies.</p>

<p>In addition to the full length features, the Video Player will come pre-loaded with a gallery of 4K video shorts, including Red Bull Media House's exclusive 4K videos The Athlete Machine: Red Bull Kluge and four acoustic performances of songs from Red Bull Records' Heaven's Basement's new record, "Filthy Empire." Additionally, Sony's 4K Ultra HD delivery solution is designed to be updated with additional 4K titles and video clips. More delivery solutions will continue to evolve rapidly, with further product and content announcements coming shortly.</p>

<p>"Sony is committed to delivering the finest 4K Ultra HD entertainment experiences to customers," added Mike Lucas, senior vice president for Sony Electronics' Home Division. "The launch of the 4K Ultra HD Home Experience is another world first for Sony, and will wow consumers with 4K Ultra HD content. It's a proof point of our leadership in all things 4K, and the first step in creating a full, complete 4K Ultra HD solution for the home."</p>

