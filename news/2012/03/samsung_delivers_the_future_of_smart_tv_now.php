<p>Also new in 2012, the Smart Touch Remote – included with the LED ES7500, LED ES8000 and Plasma E8000 – makes navigating content and channels effortless. The built-in touchpad makes web-surfing a pleasure, while channel and volume buttons are on the edge for easy access. The Smart Touch Remote Control also has a built-in microphone for Smart Interaction commands when the viewer is too far from the TV's built-in microphone.</p>

<p>For those looking for even greater flexibility and control of their Smart TV experience, Samsung's new Smart Wireless Keyboard (sold separately) features a standard-sized keyboard along with touch pad. The keyboard utilizes Bluetooth to connect to the TV and also has an IR emitter to support TV functions. The Smart Wireless Keyboard can also be used with the Galaxy Tab or other mobile devices.</p>

<p><br />
<strong>Dramatically Improved Picture Quality</strong></p>

<p>Samsung's 2012 line of Full HD LED and Plasma TVs continue to raise the bar in 2D and 3D picture quality. Samsung's world-class motion clarity lets viewers read the name on the jersey of a player running at top speed, detect tiny details in a rapid-fire video game and capture every bit of the action in the most dynamic car chase.</p>

<p>Samsung's Micro Dimming contrast enhancement will be extended to significantly more LED models this year, beginning with the LED ES6600. Micro Dimming Pro adds color and detail enhancements to the LED ES7500 for superior color and sharp detail. Micro Dimming Ultimate, available on the LED ES8000, analyzes the picture in hundreds of pieces to optimize the LED backlight and video signal for each piece in real time. This leads to a noticeable increase in brightness, richer colors and higher contrast ratio.</p>

<p>All Samsung Plasma TVs will have Samsung's proprietary Real Black Filter, previously only available in premium models, to deliver improved black levels and color contrast. In the higher-end E6500, E7000 and E8000 models, Samsung will incorporate the new Real Black Pro to deliver even better black levels. The technology has an unprecedented ability to absorb external light reflections through an increased wedge depth, which leads to "blacker" blacks, more-realistic pictures and higher color contrast.</p>

<p>With the wealth of user-generated content on video streaming apps like YouTube and Vimeo, Samsung Smart TVs also offer De-Blocking and De-Mosquito picture filters that significantly improve the viewing experience for low resolution video.</p>

<p><br />
<strong>Stunning Designs, a New LED Line and the best in entertainment experience</strong></p>

<p>Samsung's 2012 line of Full HD TVs continue to raise the bar in design and picture quality.</p>

<p>The ES8000 LED TV features the ultra-slim ONE Design bezel first introduced by Samsung in 2011; it is complemented by a new U-shape stand that makes the TV look almost weightless. The ES8000 will also be available in even more screen sizes, up to 60 inches.</p>

<p>Samsung's PNE80000 Plasma TV sports a new ultra-slim Plasma+1 bezel design in brushed metal black with a crystal-like border. The gap between the bezel and the screen content is significantly reduced so consumers can get more screen real estate without increasing the size of the TV.</p>

<p>New in 2012, the EH line of LED TVs is ideal for consumers who value the picture performance and energy efficiency of LED technology, in Samsung's most affordable LED TV offering yet. This line delivers richer colors and sharper images than a traditional LCD, even in fast moving scenes, yet consumes half the power. Samsung EH LED TVs also sport Samsung's signature narrow bezel design so consumers can have a larger screen without increasing the overall size of the TV.</p>

<p>From the new line, Samsung's EH5300 LED TV is a great TV for consumers looking to embrace a Smart TV experience. Thanks to the TV's built-in WiFi, consumers can use Samsung Smart Hub to easily access a wide range of apps on Samsung Apps or browse the web; it also supports Skype and Samsung AllShare. The EH5300 offers a narrow bezel design and 1080p resolution for sharper pictures and brighter colors, a key improvement compared to traditional LCD TVs.</p>

<p>In 2012, Samsung will extend 3D capability to even more LED and Plasma TV models. As the volume of 3D broadcast and video content increases, consumers will be able to get closer to the action with breathtaking, immersive 3D entertainment on their Samsung LED and Plasma TVs. All Samsung 3D TVs will ship with at least 2 pairs of active 3D glasses – higher-end TVs will ship with four pairs – so it is even easier for family and friends to enjoy the ultimate in 3D viewing together.</p>

<p><br />
<strong>AllShare Play – The Future of Sharing, Today</strong></p>

<p>AllShare Play, premiering in 2012, lets consumers easily share their content exactly how they want through a variety of new features. In addition, consumers can browse any website from their mobile device and, with a single tap on their mobile screen, redirect and launch that site on their Samsung Smart TV.</p>

<p>With Remote Play, content can be seamlessly shared between supported mobile devices, PCs and a Samsung Smart TV – whether they are in the same room or on opposite sides of the world.</p>

<p>Consumers will also have access to 5GB of free cloud-based storage for images and videos, accessible through compatible Samsung Smart TVs, PCs and mobile devices.</p>

<p><br />
<strong>Television Evolved</strong></p>

<p>The need to quit each app to start a new one ends now. Thanks to the Samsung dual-core processor in the LED ES7000 series and up and the Plasma E8000 series, consumers can toggle between active apps with ease.</p>

<p>In addition, Samsung's Smart Hub user interface has been redesigned for faster performance and improved convenience with a cleaner, more intuitive interface in Full HD. Users can open multiple pages at a time using the tabbed web browser built using the powerful Webkit engine, and easily track recently accessed content via the new History Bar.</p>

<p>Samsung is also giving consumers an easy way to keep their TV up-to-date on technology improvements with Smart Evolution. Beginning in 2013, consumers will be able to purchase evolution kits to add new hardware and software enhancements to their 2012 TV.</p>

<p><br />
<strong>New Signature Services – Exclusively on Samsung TVs</strong></p>

<p>Three new signature services will be available on all Samsung 2012 Smart TVs and Smart Blu-ray Players.</p>

<p>Family Story allows consumers to chronicle and share their lives with up to 20 family members in a private network. They can organize photos and enjoy slide shows on the big screen, and share memos, activity calendars and reminders anywhere they are via the phone, tablet, PC or TV.</p>

<p>Fitness gives consumers a convenient way to stay healthy. They can connect their Samsung TV to a Samsung smartphone via a mobile Fitness app, or connect to a WiFi-enabled scale to manage their weight goals. They can also use the TV's built-in camera to create a virtual mirror to monitor their exercise routines.</p>

<p>Finally, Kids offers a wealth of infotainment and games in a kid-friendly interface that parents can control and monitor.</p>

