<strong>The Ultimate in Picture Quality and Design</strong></p>

<p>Samsung's Super OLED TV represents the culmination of Samsung's latest engineering technologies, and marks a new era of minimalistic design.</p>

<p>It features unmatched vivid and true-to-life picture quality in both 2D and 3D, with significantly improved color accuracy compared to conventional LED TVs. Since light output on the Super OLED is controlled on a pixel-to-pixel basis, the truest blacks and purest whites can be achieved.</p>

<p>Further, the Samsung Super OLED offers faster response times than LED, virtually eliminating motion blur even in the fastest-moving scenes.</p>

<p>Because Super OLED technology features self-emitting RGB sub-pixels which do not require a backlight, the TV weighs significantly less than a standard LED TV.</p>

<p>The design of the Samsung Super OLED is an engineering feat that provides a breathtaking form factor that blends into any environment. The Super OLED was also recognized by the Industrial Designers Society of America (IDSA) for its flawless design.</p>

<p>When powered on, a bright, vibrant picture illuminates the screen from edge to edge. When turned off, the TV appears like a framed piece of luxurious floating glass; when hung on the wall, it more closely resembles a work of art than an electronic device.</p>

<p><br />
<strong>Intuitive Controls and a Camera with Smart Interaction Technology</strong></p>

<p>Consumers can use Samsung's new Smart Interaction technology to easily manage their TV experience. By using Voice Control, Motion Control and Face Recognition features to complement the remote control, users can turn the TV on or off, adjust the volume or activate selected apps through speech. They can also use voice to activate the search function in the web browser and "tell" the TV what they are searching for.</p>

<p>The Super OLED's built-in camera recognizes movement in the foreground to enable intuitive control, and two unidirectional array microphones recognize voice at an incredibly accurate rate. Noise cancellation technology helps to separate any background noise from the users' commands.</p>

<p><br />
<strong>Richer Content for Outstanding Entertainment</strong></p>

<p>The Samsung Super OLED TV is equipped with Samsung's new dual core processor, which allows users to run multiple apps simultaneously for a faster, uninterrupted experience, as well as a smoother web browsing experience.</p>

<p>The Super OLED TV also offers the latest improvements to Smart Hub, Samsung's integrated destination for access to all types of content from a single screen. The interface has been updated for easier navigation and faster performance. With a new tabbed web browser, users can conveniently open multiple pages at a time for an improved web experience.</p>

<p>Additional first-of-its-kind signature services such as Family Story, Fitness and Kids will allow users to get more out of their TV experience, and help foster closer connections between friends and family members.</p>

<p>Samsung's AllShare Play offers a seamless way for users to access, manage and share content through cloud storage and access that content on supported smartphones, tablets, cameras, computers or TVs, regardless of their location.</p>

