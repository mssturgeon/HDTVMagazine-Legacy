<strong>Improved content sharing with Disc to Digital</strong></p>

<p>The Disc to Digital feature is a boon to consumers with a library of DVDs. They can now register their ownership of physical DVDs, and access the same movie content on a variety of devices, virtually anytime and anywhere—even from multiple locations at once. Once digital copies have been created and added to the consumer's UltraViolet collection, the content will be made available through the Flixster application on Samsung's Smart Hub, as well as on a broad range of connected devices such as smart phones, tablet, PCs and Smart TVs. Consumers also have the option to purchase HD quality versions of these movies, and can share digital library content with other members under the same account.</p>

<p><br />
<strong>Innovative Blu-ray Features in a Sophisticated Form Factor</strong></p>

<p>Consumers can look forward to innovative design without sacrificing performance with Samsung's new stylish 3D Blu-ray line. The units are designed as symmetric products with convenient centralized controls for easy access and management, and Samsung's premium players also come with a centralized slot-in mechanism. The line-up's lack of mechanical parts also makes for a smoother and quieter loading experience, with a boot time of less than one second.</p>

<p>Consumers now have an easy way to enhance and upgrade their current TV experience with the latest services and content options through Samsung's Blu-ray players. The premium 3D Blu-ray line-up provides access to Samsung Smart Hub, a simple way to access, search and explore Samsung Apps. New in 2012, Samsung Blu-ray players will offer a full web browser and the ability to experience rich content. They also have built-in WiFi for convenient access to a variety of web-based content and connectivity options.</p>

<p>Sharing content across devices is made even easier with the new DLNA-certified Blu-ray line. In addition, 2012 Blu-ray players will be supported by WiFi Direct, which allows WiFi devices to be connected directly and easily without a wireless access point.</p>

<p>Regardless of the source material's original resolution, the 2012 3D Blu-ray line's powerful video processor can up-convert DVDs, older non-HD content and even low-resolution streaming video to pristine Full HD 1080p. It also supports an array of audio formats including Dolby&reg; Digital Plus / TrueHD and DTS-HD Bitstream Outputs. No matter what the experience, the 2012 lineup's BD Wise Plus feature automatically adjusts the TV setting to provide optimal picture for each scenario.</p>

<p><br />
<strong>Compact Blu-ray Player</strong></p>

<p>Only slightly larger than a Blu-ray disc, the versatile Samsung BD-ES6000 3D Blu-ray player packs the latest video technologies and connectivity features into a compact form factor. This balance of technology and high design makes it a perfect addition to any room where space is at a premium, but outstanding video playback is desired.</p>

<p>Taking minimalism to the max without sacrificing performance, the BD-ES6000 sports a cubic form factor and features a stylish multi-layered pattern design on the top of its cabinet.</p>

<p><br />
<strong>3D Blu-ray with Dual HDMI Inputs</strong></p>

<p>Bringing Hollywood even closer to home, the slim and stylish Samsung BD-E6500 3D Blu-ray player delivers breathtaking 2D and 3D content playback. With 2 HDMI inputs, it streamlines connections to the TV by allowing more than one component, such as a set-top box and game console, to be hooked up to BD-E6500 and connected to the TV via only one HDMI output. This minimize the number of wires required so that the home entertainment area may be free of clutter an also maintain a minimalist look-and-feel to the room.</p>

<p>The BD-E6500 features a two-tone design that accentuates its slimness. The top of the player features an elegant piano-black finish, while the bottom has the look and feel of high-grade metal. A bright but unobtrusive Mystic Blue lighting feature serves as an elegant accent to unite the two parts together.</p>

<p><br />
<strong>Reinventing the Multi-Screen Experience</strong></p>

<p>Samsung is introducing a new remote control app that can be downloaded onto an Android or Apple smartphone. Previously only available for Samsung TVs, the 2012 remote control app enhances how users control and search for content on their Blu-ray players. The app's MovieNote feature also offers instant access to detailed information on movies they are currently watching, including plot synopsis, actor and director biography information.</p>

<p>When the smartphone is connected to the same home network as a Samsung Blu-ray player, users can control their Blu-ray player with ease and use the QWERTY keyboard on their devices for easy information input.</p>

<p>Parents will also be able to use Samsung's Kids service to access a variety of educational video-on-demand content across several categories – Communication, Exercise, Arts &amp; Play, Science, Social Activity and Math, and reward children with virtual stickers or other awards for a fun and interactive learning experience.</p>

