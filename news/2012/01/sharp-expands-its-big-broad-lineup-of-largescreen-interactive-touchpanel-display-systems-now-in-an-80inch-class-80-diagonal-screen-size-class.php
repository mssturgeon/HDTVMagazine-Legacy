<p>The 80-inch class AQUOS Board combines a high-performance interactive display with a well-designed, comprehensive system for uniquely collaborative sessions – and continues to set a new standard in price-performance for touch-screen displays. This latest addition to Sharp's evolving family of state-of-the-art, 60-inch class (60 1/32" diagonal), 70-inch class (69-1/2" diagonal) and 80-inch class display tools allows organizations to operate in a visual and truly collaborative way, creating a dynamic and interactive workplace experience.</p>

<p>This incredible display is produced by Sharp's state of the art, Gen-10 LCD manufacturing facility in Sakai City, Japan. The AQUOS Board interactive display replaces traditional, static projection solutions with spectacular performance, delivering the high-definition quality we've come to expect in our homes.</p>

<p>"Similar to what our innovative and industry-leading large-screen TVs are doing for the home, Sharp's large-screen interactive touch-panel display systems are revolutionizing the workplace," said Doug Albregts, president, SIICA. "The 80-inch class AQUOS Board provides endless collaboration, information and entertainment options and is a welcome addition to Sharp's family of solutions designed to improve our workplace lives."</p>

<p>Designed to optimize and integrate a wide range of applications companies need in order to think big and disseminate information on a global scale – such as work group collaboration, video conferencing, interactive signage and video walls – the AQUOS Board delivers more than double the screen area of a 55-inch class display. It is ideal for any setting that requires large-scale collaboration, information and/or entertainment options, including meeting rooms, office lobbies, schools, airports, malls, exhibit halls and hotels.</p>

<p>The AQUOS Board PN-L802B will be available in late February through Sharp's network of dealers, distributors and VARs for $13,795 MSRP.</p>

<p><br />
<strong>Features and Capabilities</strong></p>

<p>Further facilitating global collaboration, the AQUOS Board offers business users seamless integration with presentation and video conferencing technologies, including WebEx&trade;, GoToMeeting&trade; and Skype&trade;. Additionally, the system will be fully compatible with a full array of familiar Microsoft&reg; products (Microsoft Office Suite&reg;, Microsoft Windows 7&reg; and Microsoft touch Pack for Windows 7&reg;).</p>

<p>In addition to the PN-L802B stand-alone display, which comes with a three-year onsite parts and labor limited warranty, customers also have the option of purchasing a bundled solution. The bundle – PN-L802B-PKG –includes the AQUOS Board 80-inch class, full-array, LED backlit, interactive touch-panel display, the PN-TPC2W7 Compact Whiteboard PC and rolling cart floor stand. The whiteboard PC connects easily to the rear of the display; utilizes an Intel&reg; Pentium&trade; dual-core 2.5 GHz processor and comes pre-loaded with Microsoft Windows 7, Sharp Pen Software&trade; and touch-screen drivers, and is sold with a HDMI&reg; connecting cable for easy system set-up.</p>

<p>The AQUOS Board 80-inch class LED touch-panel, with full HD 1920 x 1080 resolution, is equipped with Sharp's UV2A photo alignment and Full Array LED backlight technologies to create an energy-efficient screen that is easy to read in most environments, regardless of ambient light.</p>

<p>Users can make meetings more interactive by drawing and taking notes directly on-screen, and saving new versions to their PC or printing them to a connected Sharp Multifunction Product (MFP). The intuitive software also lets users select pen colors and eraser functions easily, with a click of the touch pen button. Furthermore, existing images can be easily scanned and displayed by connecting to a networked Sharp MFP via the pen software.</p>

<p>The AQUOS Board is engineered for commercial 24/7 use, uninterrupted worry-free operation and comes with a three-year onsite parts and labor limited warranty. It can also function separately of the bundled solution, as a versatile LED-LCD information display.</p>

