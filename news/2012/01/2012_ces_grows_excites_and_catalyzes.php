<p>Technology innovations generated excitement across the 2012 CES showfloor including the launch of dozens of ultrabooks, OLED TVs, Android 4.0 tablets, next generation smartphones and 3D printers.</p>

<p>The 2012 CES was a star-studded event with numerous Hollywood celebrities in attendance including Eliza Dushku, who served as the Official Ambassador for the CES Entertainment Matters program, as well as Justin Timberlake, Justin Bieber, Ludacris, 50 Cent, Wil.i.am, Wayne Brady, Jillian Michaels, LL Cool J, Ryan Seacrest, Will Smith and Kelly Clarkson.</p>

<p>The 2012 International CES featured government leaders from the U.S. and around the world including FCC Chairman Julius Genachowski, Nevada Governor Brian Sandoval, Senator Ron Wyden (D-OR), Senator Dean Heller (R-NV), Representative Marsha Blackburn (R-TN), Representative Gerry Connolly (D-VA), Representative Darrell Issa (R-CA), Representative John Shimkus (R-IL), Representative Cliff Stearns (R-FL), Representative Lee Terry (R-NE) and FCC Commissioners Mignon Clyburn and Robert M. McDowell. Also, several ministerial level officials and commissioners from Canada, Columbia, Egypt, Iraq, Jordan, Korea, Lebanon and Oman also attended CES.</p>

<p>This week, more than 2,000 news articles profiling the innovations at the 2012 CES have appeared in the news media, and increase in media coverage of more than a third over 2011.</p>

<p>2012 CES Catalyzes</p>

<p>"The 2012 CES was the most phenomenal show in our history, generating more energy and excitement across every major industry touching technology than ever before," said Gary Shapiro, president and CEO of CEA, owner and producer of the International CES. "CES is the change agent, the catalyst, that brings executives from a wide range of industries together and helps them create better ways of doing business together. The breadth and depth of the 2012 CES, which featured more innovative technology products than anywhere else on Earth, is a testament to the dynamic and innovative global consumer technology industry, which will reach $1 trillion globally this year."</p>

<p>Industries with increased presence at the 2012 International CES include healthcare, automotive, entertainment, advertising and marketing.</p>

<p>Each CES attendee has an average of 12 business meetings that enable them to accomplish a significant amount of networking and business with professionals from a range of industries around the world.</p>

