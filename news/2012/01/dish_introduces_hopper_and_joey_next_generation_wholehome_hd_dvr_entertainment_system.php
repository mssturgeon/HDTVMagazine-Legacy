<strong>The Hopper -- Endless Entertainment Options</strong></p>

<p>The Hopper's new, unparalleled feature, PrimeTime Anytime&trade; allows customers, with one click, to record using a single tuner all of the primetime TV programming from ABC, CBS, FOX and NBC -- the networks that deliver the most popular shows during primetime. Once activated by a customer, PrimeTime Anytime records network programming in high definition, where available, every night and stores them for eight days after they have aired. This creates an on-demand library of approximately 100 hours of primetime TV shows, and makes it easy to catch up on episodes from last night and last week's airing.</p>

<p>The Hopper can record up to six TV shows at once (two live programs and four PrimeTime Anytime shows) while allowing viewers to watch up to four different recorded or on-demand shows in four rooms of the house, simultaneously. This gives a family a variety of options to control or view their recordings and to watch shows in any room from a single Hopper.</p>

<p>The Hopper's on-demand capabilities give access to DISH's Blockbuster @Home&trade; for $10 per month which is now enhanced with more than 10,000 total titles streaming to the TV.</p>

