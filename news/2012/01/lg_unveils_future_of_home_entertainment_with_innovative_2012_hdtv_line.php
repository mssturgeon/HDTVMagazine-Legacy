<p>LG reaffirmed its commitment to the connected TV movement by offering an upgraded Smart TV package in 60 percent of its 2012 LCD TV line. In addition to premium content from providers like Netflix, Hulu Plus, VUDU and others, new content options this year include a one-stop-shop for 3D content (via the 3D Zone) and almost 1,200 total applications in the LG App store. LG also enhanced the user Web browsing experience by incorporating HTML 5 and Flash so it can now function as a full internet browser with video support.</p>

<p>Select series (LM9600 and LM8600) will feature the LG Dual Core chipset, which powers faster loading speeds and enables voice recognition technology on the new 4-mode Magic Remote**. The new Magic Remote simplifies navigation with additional functions including Voice Recognition, Wheel, Magic Gesture and Pointing (see separate release). Consumers can also access online content easily through a built-in Wi-Fi connection. With Mobile HD Link (MHL), consumers can connect (hardwire) compatible mobile devices to the TV to charge and play its content (launch apps, games or access multimedia files) on the big screen using the Magic Remote to navigate. Finally, this year's Smart TV dashboard will be customizable so consumers can navigate and personalize their interface by putting their favorite content options on the main page.</p>

<p>Complementing its broad Smart TV line, LG also introduced two LED series featuring LG Smart TV with Google TV (LMG860 and LMG620). Consumers can navigate through LG's TV-centric home dashboard, or via the standard Google TV interface using a special remote control that combines the simplicity of the Magic Remote with an integrated QWERTY keyboard to access the broad array of Google content, including services and TV applications from the Android Market.</p>

<p><br />
<strong>CINEMA 3D is Here to Stay</strong></p>

<p>Due to its success in 2011, CINEMA 3D technology has been expanded to seven new series of LED HDTVs, all told 25 models. LG CINEMA 3D employs the revolutionary Film Patterned Retarder (FPR) technology to give viewers a great 3D effect and uses glasses that don't flicker like active shutter glasses. It also virtually eliminates cross-talk to help provide a more comfortable 3D viewing experience. The 3D glasses are battery-free, affordable and don't shutter open and closed so both eyes receive an image simultaneously. With new 3D Depth Control, viewers can optimize 3D content to their personal preference by adjusting the amount 3D effect applied to the content. 3D Sound Zooming offers users a maximized 3D experience with sound effect changing in accordance with the movement of on-screen objects. Upgraded 2D to 3D Conversion with improved depth effect enables any 2D content to be seen in immersive 3D.</p>

<p><br />
<strong>Getting Interactive</strong></p>

<p>LG's Dual Play function takes gaming to new levels of excitement. Many multi-player video games rely on a split-screen to show each player's perspective. However, Dual Play enables each player to enjoy a full screen view (in 2D) simultaneously through two different sets of polarized glasses.</p>

<p>Also on display will be the LG PenTouch plasma TV (PM6900). Particularly useful for families and businesses, the PenTouch plasma TV allows users to draw and write directly onto the display panel. Using a newly designed touch pen, users can do so through a variety of applications, including those for illustrations, photo editing and PowerPoint presentations.</p>

