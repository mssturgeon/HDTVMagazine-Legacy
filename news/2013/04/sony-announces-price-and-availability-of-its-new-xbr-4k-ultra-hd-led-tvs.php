<p>"These new models will be arriving in homes just before the summer and are sure to bring the enhanced viewing experience of 4K TV to a whole new audience," said Mike Lucas, senior vice president, Sony Electronics Home Division. "Our TVs deliver a vibrant and natural picture that is four-times clearer than high definition. As for content, these new sets enhance all of the video people are watching today, and this summer our 4K media player,  followed in fall by the video distribution service will demonstrate how Sony continues to lead in bringing the 4K entertainment experience to viewers."</p>

<p>Starting today, six Sony Store locations (Century City, Calif.; Costa Mesa, Calif.; Houston; Las Vegas; New York and Palo Alto, Calif.) will be the first to feature the XBR-55 &amp; 65X900A 4K TVs, offering consumers in-store demonstrations of true 4K and enhanced (upscaled) video.      </p>

<p>This summer, consumers of Sony's 4K UHD TVs can purchase the FMP-X1 4K Media Player bundled with 10 feature films and video shorts in true 4K resolution for $699. In the fall of 2013, users of the same 4K Media Player will be given access to a fee-based video distribution service offering a library of 4K titles from Sony Pictures Entertainment and other notable production houses. The feature films included with purchase of the 4K Media Player are Bad Teacher, Battle: Los Angeles, The Bridge on the River Kwai, The Karate Kid (2010), Salt, Taxi Driver, That's My Boy, The Amazing Spider-Man, The Other Guys and Total Recall (2012).</p>

<p>With a variety of options already available for the home theater, only Sony can bring true 4K content to consumers. Last November, in another first, Sony gave native 4K movies and video to consumers who purchased the XBR-84X900, Sony's first and biggest 4K Ultra HD TV. Making good on its promise to periodically update and add content to the system, Sony recently began delivering new 4K content to 84-inch XBR owners with the home server. Along with a slew of new 4K video shorts, the classic film Lawrence of Arabia has been added to their libraries, which was recently remastered in 4K resolution by Sony Pictures Colorworks. Owners of the first generation video server will be able to exchange that device for the FMP-X1 4K Media Player, once the distribution service launches in the fall.</p>

<p>To coincide with the availability of Sony's new 4K Ultra HD TVs, Sony Pictures Home Entertainment is also bringing to market a lineup of "Mastered in 4K" Blu-ray&trade; Discs. With 1080p high definition picture that's derived from the highest quality 4K source materials with new expanded color, consumers will enjoy a dynamic and vibrant picture that's both optimized for the 4K Ultra HD TVs and plays back on all existing Blu-ray&trade; players and HDTVs. As an added bonus, consumers who purchase the XBR-55X900A or XBR-65X900A 4K Ultra HD TV will also receive Spider-Man (2002), Ghostbusters and Angels &amp; Demons "Mastered in 4K" Blu-ray Discs (while supplies last).</p>

<p><strong>NEW SONY UHD 4K TV MODELS- KEY FEATURES:</strong></p>

<ul><li>Images become lifelike with a resolution of four-times that of Full HD TV (3840 x 2160) delivers lifelike images</li><li>All content is viewed at the highest resolution possible with enhanced images reaching near 4K with Sony's proprietary two-chip  4K X-Reality PRO picture engine</li><li>All colors, including difficult blues, greens and reds, are delivered naturally and accurately through TRILUMINOS&trade; Display</li><li>An immersive picture draws in viewers with blacker blacks and excellent contrast produced with dynamic edge-lit, LED backlighting</li><li>Amazing sound from the integrated 65 Watt, front-facing, magnetic fluid speaker system complements the stunning picture</li><li>A cinematic experience is brought to life through Full HD 3D and passive glasses</li><li>Entertainment choices are endless with WiFi&trade; connectivity, including access to the full Sony Entertainment Network suite of services</li></ul>

<p>Pre-orders for 4K UHD TVs begin April 21, 2013 at Sony Stores and select retailers nationwide. The 4K Media Player will be available this summer.</p>

<p>Beginning April 17, Sony will kick off a year-long partnership with The Tribeca Film Festival to promote 4K video production and distribution among amateur and professional film makers. During the festival in New York, Sony will showcase 4K technologies for use from lens to living room.</p>

<p>For more information, visit <a target="_blank" href="http://www.sony.com/4ktv">www.sony.com/4ktv</a> High resolution images and complete specification provided upon request.</p>

