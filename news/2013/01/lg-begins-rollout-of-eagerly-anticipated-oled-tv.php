<p>More than 1,400 LG retail stores in South Korea will begin accepting orders from consumers for KRW 11 million (approximately US $10,000) TVs starting Jan. 3 with delivery to commence the first week of February. As the first and only company to announce availability of the next-generation TV technology, LG is prepared to ramp up quickly to take the lead in the OLED segment that is expected to grow to 7.2 million units by 2016, according to DisplaySearch.</p>

<p>"We are extremely pleased to be able to make this announcement at the start of the new year because we believe that OLED will usher in a whole new era of home entertainment," said Havis Kwon, President and CEO of LG's Home Entertainment Company. "Not since color TV was first introduced 60 years ago has there been a more transformational moment. When high definition TV was first introduced 15 years ago, the public's reaction was 'wow!' but when customers see our razor-thin OLED TV for the first time, they're left speechless. That's a clear indicator as any that OLED TV is much more than just an incremental improvement to current television technology."</p>

<p>Only 4 millimeters (0.16 inches) thin and weighing less than 10 kilograms (22 pounds), LG's OLED TVs produce astoundingly vivid and realistic pictures thanks to its superior WRGB technology. LG's unique Four-Color Pixel system features a white sub-pixel, which works in conjunction with the conventional red, blue, green setup to create the perfect color output. LG's exclusive Color Refiner delivers even greater tonal enhancement, resulting in images that are more vibrant and natural than anything seen before. The 55-inch OLED TV also offers an infinite contrast ratio, which maintains optimal contrast levels regardless of ambient brightness or viewing angle.</p>

<p>Even before its launch, LG's OLED TV was turning heads all over the world. In addition to being named Best of Show at CES 2012, the influential Industrial Designers Society of America recognized the TV with a coveted IDEA Award. Meanwhile, LG received the European Display Achievement 2012-2013 Award from the European Imaging and Sound Association (EISA). And to cap it off, LG's OLED received Korea's Good Design President Award in October.</p>

