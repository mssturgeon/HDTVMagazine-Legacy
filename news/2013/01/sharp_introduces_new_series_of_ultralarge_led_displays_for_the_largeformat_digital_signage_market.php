<p>"This new series of LED displays makes a dramatic impact in any retail or public space with their seamless and slim design that can display full-scale images in both landscape and portrait orientations," said Steve Brauner, Senior Product Manager for the PN-R Series displays.  "All units are built to withstand the rigors of 24/7 operation, making them ideal for retail or customer establishments that require around-the-clock operation, seven days a week."</p>

<p>The most impressive of the new series, the PN-R903 LED display, features a high-impact 90" class screen (90-1/16" diagonal), big enough to showcase life-size images.  At 6' 8" tall, the new PN-R903 is the first professional LED display that can display people at real height in portrait view, making it an ideal fit for the fashion and retail industries. Large enough to seamlessly replace a 2x2 46" panel video wall, the PN-R903 offers easy set-up and installation, with much less wiring, computer support, and virtually no calibration requirements.</p>

<p>"Sharp has long been a leader in display technology, and this new series of professional,  large-format displays continues to deliver ground-breaking functionality," said Mike Marusic, Senior Vice President of Marketing and Business Solutions Group, Sharp Imaging and Information Company of America.  "With the breathtaking size, impact, and durability of these leading-edge displays, applications are almost unlimited in indoor digital signage environments."</p>

<p>Aside from variations in display size, the models utilize different technologies to achieve high contrast ratios and lower energy consumption. Uniquely available on the PN-R903, full-array LED backlighting with Local Dimming Technology enables the PN-R903 to produce up to 1,000,000:1 contrast ratio, deep rich blacks and superior energy efficiency.  The PN-R603 60" class (60-1/16" diagonal) and PN-R703 70" class (69-1/2" diagonal) incorporate edge lit LED backlighting technology resulting in an ultra-slim and sleek format and a significant reduction in energy consumption, making them ideal for LEED-compliant installations.</p>

<p>The PN-R903 and the PN-R603 are ready to ship February 1, 2013, followed by the PN-R703 which will be available later in February.  Please contact your Authorized Sharp Pro AV Dealer or Distributor for complete product information and pricing.</p>

