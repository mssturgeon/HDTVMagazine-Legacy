<p><strong>CHICAGO--(BUSINESS WIRE)</strong>--NEC Display Solutions of America, a leading provider of commercial LCD display and projector solutions, announced today the addition of the 55-inch V552 and 65-inch V652 to its commercial-grade V Series. The high-performance, full HD panel makes these models ideal for extended operation times, including retail stores, restaurants, indoor venues, training facilities and corporate boardrooms.</p>

<p>NEC's V552 and V652 utilize LED backlighting to reduce the product's depth, weight and power consumption when compared to their predecessors. Each also features built-in 10-watt speakers and an Open Pluggable Specification (OPS)-compliant expansion slot. This future-proofs the display and allows for the seamless integration of a computer or other NEC/third-party accessories. Additionally, video, RS-232 control and power are passed internally from the display to the accessory, allowing the elimination of additional cabling and simplifying installations.</p>

