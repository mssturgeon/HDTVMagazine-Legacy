<p><strong>CULVER CITY, CALIF. (January 7, 2013)</strong> – To compliment the electronics industry's launch of 4K Ultra HD Televisions, Sony Pictures Home Entertainment (SPHE) is proud to leverage its growing 4K asset library to present "Mastered in 4K" Blu-ray&trade; titles. While maintaining the studio's commitment to the highest possible quality Blu-ray releases, the "Mastered in 4K" offering takes these efforts even further.</p>

<p>"Mastered in 4K" Blu-ray releases will feature titles—such as The Amazing Spider-Man&trade;, Total Recall, The Karate Kid, Battle: Los Angeles and The Other Guys—sourced from pristine 4K masters and presented at high-bitrate 1080p resolution, with expanded color showcasing more of the wide range of rich color contained in the original source. When upscaled via the Sony 4K Ultra HD TVs, these discs serve as an ideal way for consumers to experience near-4K picture quality. SPHE also plans to utilize available high quality 4K masters for select upcoming new release Blu-ray titles.  "Mastered in 4K" Blu-ray Discs can be played on all existing Blu-ray Disc players.</p>

<p>"The electronics industry's groundbreaking launch of 4K Ultra HD TV has given us reason to even further elevate our Blu-ray offering," said David Bishop, President, SPHE. "This spring, Sony Pictures Home Entertainment is excited to deliver a complementing lineup of 'Mastered in 4K' Blu-ray titles, offering consumers the best possible picture and sound quality to be experienced on the latest HDTVs."</p>

<p>Leading the adoption of 4K content in cinema, home entertainment and broadcast, Sony Pictures builds on its renowned professional equipment expertise along with the company's wealth of knowledge in both 4K acquisition and home entertainment. These "Mastered in 4K" Blu-ray titles—paired with the native 4K titles for Sony's 4K video distribution service, which is planned to be launched in summer 2013 in the US—demonstrate Sony Pictures' holistic commitment to 4K and to the launch of this exciting new hardware into the market.</p>

<p>SPHE will release this initial wave of more than 10 "Mastered in 4K" titles starting in Spring 2013, with rollout to select international territories soon thereafter.</p>

<p>Visit Sony Home Entertainment on the Web at <a target="_blank" href="http://www.SonyPictures.com/">www.SonyPictures.com</a>.</p>

