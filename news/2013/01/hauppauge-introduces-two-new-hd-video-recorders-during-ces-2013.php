<p><img src="http://www.hdtvmagazine.us/news/images/HD-PVR-2-gaming-unit.png" alt="HD PVR 2 GE Plus" height="218" width="400"><strong>LAS VEGAS, Jan. 9, 2013 /PRNewswire/</strong> -- Hauppauge Digital, Inc. (Nasdaq: HAUP), the world's leading developer and manufacturer of TV tuners and HD video recorders, has launched two new models in their line of high definition video recorders. One model is geared toward home media enthusiasts, while the other is designed for advanced gamers.</p>

<p>The new model for home media users is called HD PVR 2 model 1512. HD PVR 2 users can create a library of their favorite cable TV or satellite TV programs in HD. HD PVR 2 has a built-in high definition video recorder plus an IR blaster to control channel changing on a set top box. HD PVR 2 is connected to both a set top box with supplied component video cables and to a PC, using the PC's disk drive for storing the recordings. With the supplied Hauppauge WinTV v7.2 application, the HD PVR 2 can be programmed to change the channels on the set top box using the IR blaster at a designated time. HD PVR 2 is also compatible with Windows Media Center from Windows 7 and Windows 8.</p>

<p>The new model for advanced gamers is the HD PVR 2 GE Plus. The HD PVR 2 GE Plus adds SPDIF and full surround sound audio to game recordings. Designed to be used with Xbox 360, PS3 and PC game systems where SPDIF and surround sound audio are used, HD PVR 2 GE Plus can record the surround sound audio along with the game play in HD. For gamers who use home theater A/V systems for an incredible audio/video experience, the HD PVR GE Plus also has full surround sound audio pass-through. HD PVR 2 GE Plus also is bundled with Hauppauge's StreamEez video streaming application which allows game play to be streamed via Justin.TV and U-Stream.</p>

<p>Both new models will be available beginning February 1, 2013 and will be distributed through retailers in North America and Europe.</p>

<p>The original HD PVR 2 Gaming Edition was introduced at the gamescom2012 gaming show in Cologne, Germany in August 2012. All features from the HD PVR 2 Gaming Edition are included with the two new models:</p>

<ul><li>A built-in HD video encoder that was designed for the TV broadcast industry. All recordings are in H.264, which is the video format used to make HD Blu-ray discs.</li><li>High definition HDMI and component video recording at up to 1080p30.</li><li>HDMI "no delay pass-through" so gamers can record their game play while playing the game on a TV monitor.</li><li>A built-in record button for simple manual starting and stopping of recordings.</li><li>StreamEez for streaming game play using Twitch and Ustream.</li><li>The Personal Logo inserter, for adding a digital inserter logo to recordings.</li></ul>

<p>With higher performance, easy installation and unparalleled quality, the HD PVR 2 family of game recorders is the best available today. Find out more at <a target="_blank" href="http://www.hauppauge.com/">www.hauppauge.com</a>.</p>

