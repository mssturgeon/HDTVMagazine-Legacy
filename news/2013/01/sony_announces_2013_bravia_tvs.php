<p><img src="http://www.hdtvmagazine.us/news/images/Sony-KDL-50R520.jpeg" alt="Sony KDL-50R520" height="300" width="400"><strong>LAS VEGAS, Jan. 7, 2013 (CES Booth #14200)</strong> –  Sony is unveiling an impressive line-up of new BRAVIA TVs, with new 4K Ultra HD models at sizes and prices that put 4K within reach of a wider audience, and new LED sets that complement superb picture quality with features like WiFi&trade; and NFC. With these new TVs, Sony's goal is clear: deliver the most immersive home entertainment experience, with the highest picture quality, regardless of the content or source.</p>

<p>Following the successful launch of its 84-inch 4K LED TV in September 2012, Sony is expanding its 4K UHD XBR LED TV line by adding 65-inch and 55-inch screen sizes to the X900A series of 4K Ultra HD TV, with four times the resolution of Full HD (3,840 x 2,160 pixels). Also on display at CES are the W and R series of HD LED TVs which deliver an incredible home viewing experience.</p>

<p>"The 2013 BRAVIA line continues our acclaimed commitment to delivering the best picture quality at every model segment and with two new sizes, the amazing 4K TV experience will now be within reach of many more consumers," said Mike Lucas, senior vice president of Sony Electronics' Home Division. "The 84-inch XBR 4K LED TV is an impressive sight and a status symbol for sure, but these new sizes mean that the beauty of Sony 4K can be experienced in any home environment."</p>

<p>The XBR-X900A series of 4K LED TVs employ many technological advances to achieve their stunning picture. For example, the 4K X-Reality PRO&trade; picture engine reduces visual noise and corrects image shapes. TRILUMINOS Display LED backlighting is used in the XBR 4K LED TVs to present rich, authentic color with subtle tones while also replicating bold colors including hard-to-reproduce reds and greens. By integrating QD Vision's Color IQTM* optical component with Sony's unique display technologies, these televisions achieve significantly wider color gamut and provide a far more natural and vivid viewing experience with a heightened sense of depth. This wider color gamut also enriches and improves picture quality of personal content captured on compatible Sony digital cameras and camcorders compatible with TRILUMINOS Color, which contains wide-color gamut information in its content.  Furthermore, Sony offers Blu-ray Disc players compatible with TRILUMINOS Color, allowing consumers to fully enjoy Blu-ray content shot in wide and rich color.</p>

<p>Along with offering  its best-ever picture quality, the XBR-X900A series, 4K UHD LED TVs offer a better sound experience by incorporating an end-to-end Sony audio solution. Utilizing a Signal-to-Sound Architecture, these TVs incorporate Sony's own magnetic fluid speakers and unique digital signal processing technology to deliver smooth midrange, lower vibration and deep bass. The front facing speakers on XBR 4K LED TVs extend Sony's new design concept to match the exterior aesthetic of some of the other 2013 models for the home with a striking, angular, faceted outer cabinet – incorporating the Sense of Quartz design concept.</p>

<p>All XBR-X900A models are Wi-Fi&reg; enabled and offer a wide range of internet connected services including Sony's smart connect solutions, enabling cross-device connectivity between mobile devices and their TV. With features such as One-touch mirroring and TV SideView&reg;, the X series TVs provide greater control and additional content options by interconnecting media sources across the home and mobile entertainment ecosystem.</p>

<p>The X series of 4K LED TVs will be available in Spring 2013 at Sony Stores and select electronics retailers nationwide. Also available in Spring will be a lineup of Mastered in 4K Blu-ray discs from Sony Pictures' Colorworks Studio. The first titles to be available include The Amazing Spider-Man&trade;, The Karate Kid and Taxi Driver. Sourced from pristine 4K masters and presented at high-bitrate, full HD resolution, these discs showcase more of the wide range of rich color contained in the original source content. When upscaled via the Sony 4K Ultra HD LED TVs, these discs serve as an ideal way for consumers to experience near-4K picture quality.</p>

<p>Sony's commitment to bring 4K content to the home does not stop there, as launching this Summer will be the first 4K Ultra HD Video distribution service in the U.S. Consumers will be able to enjoy native 4K content such as feature length movies from Sony Pictures as well as other productions with stunning picture and sound. At that time Sony will also introduce a dedicated 4K Media Player to bring this service to the home.</p>

<p><br />
<strong>Great Picture Quality Does Not Stop With 4K Ultra HD</strong></p>

<p>In addition to the new XBR-X900A, 4K LED TV models, Sony is debuting two new series of LED TVs, which will also arrive in stores this Spring, and created for consumers looking for an amazing high definition experience. The W series of LED BRAVIA televisions includes the KDL-W650A, KDL-W802A and KDL-W900A. All models are Wi-Fi enabled, with the W900A TV incorporating NFC features of the X-series, TRILUMINOS display, X-Reality PRO&trade; picture engine and active 3D capability. The KDL-W900A LED HD TV leverages the highest level of Motionflow&trade; XR for the best experience when viewing fast-moving action. The W900A integrates a unique long duct speaker cabinet design. The long 1.2m speaker duct is cleverly folded into a compact unit that's hidden neatly behind the TV screen. Though the speakers are hidden, the newly-designed speaker cabinet reproduces rich bass and lower midrange sounds, adding extra punch and depth to action movies, music and dialogue. This is means they produce the bass extension of a much bigger, bulkier speaker.</p>

<p>The R series BRAVIA LED HD TVs includes several options for consumers looking for feature rich TVs with incredible picture quality. The KDL-R550A LED HD TV with 3D is Wi-Fi connected enabling consumers to wirelessly access  a full array of Sony Entertainment Network services; as well as being RVU compliant, meaning DirectTV&trade; customers with Genie&trade; Whole-Home HD DVR can access their set-top box, DVR and on-demand services right from the KDL-R550A TV without the need for additional equipment. With passive 3D (including four pairs of glasses) the model is available in 70-inch, 60-inch and 50-inch sizes representing new sizes and performance from Sony. Also available with the same feature-set, in 60 and 70-inch sizes, minus 3D capability is the KDL-R520A. Additionally, the KDL-40R450A LED HDTV and KDL-32R400A will debut offering excellent picture and a bevy of features, including One-touch Mirroring, representing a great value for consumers.</p>

<p>For more information on the 2013 BRAVIA range, including product images please visit <a target="_blank" href="http://Sony.com/CES/">Sony.com/CES</a>.</p>
