<p>Pre CES media events kicked off Sunday night with CES Unveiled: The Official Press Event of CES. Seventy-four exhibiting companies drew one of the highest media crowds in Unveiled history with companies such as 3M Touch Systems, Body Media, Canopy Co., Chevrolet, Fitbug, Goal Zero, HAPI Labs, House of Marley, Hz0, Liquid Image, Matrix Audio, Parrot, Synaptics and Urban Hello. Major trends included ultra-HDTV, hybrid tablets, flexible touch screen display, apps and mobile solutions.</p>

