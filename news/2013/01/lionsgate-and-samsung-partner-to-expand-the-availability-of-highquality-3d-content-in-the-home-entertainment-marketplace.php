<p><strong>SANTA MONICA, Calif. and LAS VEGAS, Jan. 9, 2013 /PRNewswire/</strong> -- Lionsgate (NYSE: LGF), a leading global entertainment company, and Samsung Electronics Co., Ltd., are partnering to expand the availability of popular theatrical titles in 3D for the home entertainment market, the two companies announced today from the Consumer Electronics Show (CES) in Las Vegas, Nevada.</p>

<p>Utilizing Samsung's proprietary 3D image processing technology, the two companies will kick off the partnership by delivering new 3D versions of the Lionsgate action films GAMER, CRANK, and BANGKOK DANGEROUS as well as the horror/thriller hit THE DESCENT.  In addition to these popular films, a number of other theatrical titles are in the pipeline for 3D conversion and release. The companies are launching their initiative with popular titles that have already demonstrated success on DVD, Blu-ray Disc, EST and VOD platforms.</p>

<p>"The home entertainment market is ripe for a premium technology like 3D, and consumers have consistently demonstrated their willingness to pay for added value," said Lionsgate President of Worldwide Television and Digital Distribution Jim Packer.  "Lionsgate is committed to being an innovator in enhancing the quality of the home entertainment experience for our consumers, and Samsung is an ideal partner to help us fill the release pipeline with commercially exciting films in the best 3D picture quality."</p>

<p>"As an innovative market leader in TV, Samsung continues to invest in building a robust 3D home entertainment ecosystem that appeals to consumers who enjoy high-quality 3D in their homes," said Senior Vice President Kyungshik Lee of Visual Display Business, Samsung Electronics. "Lionsgate's vast, high-quality content library, coupled with Samsung's advanced 3D image processing technology, will provide the best 3D viewing experiences to Samsung Smart TV consumers."</p>

<p>The announcement was made against a backdrop of rapid 3D growth in the consumer home entertainment marketplace, with three times as many 3D enabled Blu-ray Disc releases in 2012 than in 2011 and 3D television households nearly doubling from 3.5 million in 2011 to an estimated 6.4 million in 2012.</p>

<p><br />
<strong>ABOUT LIONSGATE</strong></p>

<p>Lionsgate is a leading global entertainment company with a strong and diversified presence in motion picture production and distribution, television programming and syndication, home entertainment, family entertainment, digital distribution, new channel platforms and international distribution and sales.  The Company has built a strong television presence in production of primetime cable and broadcast network series, distribution and syndication of programming and an array of channel assets.  Lionsgate currently has 23 shows on 16 networks spanning its primetime production, distribution and syndication businesses, including such critically-acclaimed hits as the multiple Emmy Award-winning Mad Men, Weeds and Nurse Jackie, the new comedy Anger Management, the network series Nashville, the syndication successes Tyler Perry's House of Payne, its spinoff Meet the Browns, For Better Or Worse, The Wendy Williams Show, Are We There Yet? and the upcoming Orange Is The New Black, an original series for Netflix.</p>

<p>Its feature film business has been fueled by such recent successes as the blockbuster first installment of The Hunger Games franchise, the 13th highest-grossing North American release of all time, The Twilight Saga Breaking Dawn – Part 2, which has grossed more than $800 million at the worldwide box office, The Expendables 2, The Possession, Sinister, The Cabin in the Woods, Tyler Perry's Madea's Witness Protection and Arbitrage.  With the January 2012 acquisition of Summit Entertainment, the Company has now added the blockbuster Twilight Saga, which has grossed more than $3.3 billion at the worldwide box office, to its current slate, giving the Company the two premier young adult franchises in the world.  Recent Summit hits include Red, Letters to Juliet, Knowing, the Step Up franchise and the Academy Award-winning Best Picture, The Hurt Locker.</p>

<p>Lionsgate's home entertainment business is an industry leader in box office-to-DVD and box office-to-VOD revenue conversion rate. Lionsgate handles a prestigious and prolific library of approximately 15,000 motion picture and television titles that is an important source of recurring revenue and serves as the foundation for the growth of the Company's core businesses.  The Lionsgate and Summit brands remain synonymous with original, daring, quality entertainment in markets around the world.</p>

