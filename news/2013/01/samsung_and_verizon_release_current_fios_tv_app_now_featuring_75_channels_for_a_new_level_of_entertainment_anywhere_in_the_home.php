<p>The app, initially released in July on the Samsung Smart Hub platform, now lets Verizon's FiOS TV and FiOS Internet subscribers watch 75 live FiOS TV channels and more than 25,000 FlexView on-demand movies and TV shows on these TVs and Blu-ray players without requiring a set-top box. This furthers both Samsung's and Verizon's commitment to developing ways to help consumers enjoy "TV Everywhere."</p>

<p>FiOS subscribers that have FiOS TV and FiOS Internet subscriptions can easily download the free FiOS TV app on their compatible Samsung Smart devices without requiring a secondary set-top box. For those who already have installed the app it will automatically update when launched.</p>

<p>The expanded channel lineup included CNN, Comedy Central, Disney, Fox Business, Cinemax, MTV, Spike, HBO, TBS, TNT, Food Network and HGTV, based on the subscribers' current FiOS TV package.</p>

<p>"In July, Samsung became the first TV platform to offer FiOS TV, giving consumers the flexibility to watch their favorite FiOS channels from any TV in the home – without requiring a set-top box," said Eric Anderson, vice president of content and product solutions, Samsung Electronics America. "Today we deliver on our commitment to providing the best home entertainment experience as we offer more channels than ever."</p>

<p>"Verizon's mission is to break down technology barriers so that our customers can enjoy the best possible viewing experiences on multiple devices that they already own," said Maitreyi Krishnaswamy, director of product development for FiOS TV. "By continuing to upgrade and improve the FiOS app for Samsung TV, we are providing more ways for our customers to enjoy their FiOS TV experience on their own terms."</p>

<p>The FiOS TV application has parent friendly features such as parental PIN options to restrict mature content as well as a purchase PIN requirement for authorization of any rental and purchases of On Demand content through the application. The application also offers traditional features such as closed captioning, help and FAQs.</p>

<p>For more information on the FiOS app on Samsung devices, please visit <a target="_blank" href="http://verizon.com/fiostv/">verizon.com/fiostv</a>.</p>

