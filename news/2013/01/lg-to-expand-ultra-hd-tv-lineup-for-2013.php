<p>LG's newest Magic Remote allows the user to navigate the Ultra HD TV's smart onscreen interface using gestures and voice recognition. The company's Smart TV ecosystem now includes approximately 1,400 apps and access to a growing collection of premium content services, such as 3D World and Game World**. SmartShare Plus connects users to even more media and entertainment options. This feature set offers a range of connectivity options such as Wi-Fi and Intel's Wireless Display (WiDi), which enable content to be transferred from compatible portable devices such as laptops, mobile phones, tablets and other devices.</p>

<p>LG has equipped its Ultra HD TVs with CINEMA 3D technology, bringing 3D entertainment into the Ultra HD arena. Astounding screen resolution, in combination with 3D effects and 3D Sound Zooming, gives consumers a true sense of being "in the action." 3D Depth Control allows viewers to fine-tune the perceived distance between objects on the screen for a customizable 3D experience. 3D Sound Zooming analyzes onscreen objects to generate sound in accordance with their virtual location and movement. In addition, the Dual Play feature allows opponents playing multiplayer games to simultaneously see different images on the same screen* – effectively making split-screen gaming a thing of the past.</p>

<p>LG's Ultra HD TV also features a 2.2 Sound System. Consisting of two 10W speakers and two 15W woofers, the sound system produces a lush audio experience that perfectly complements the extraordinary onscreen visuals; creating a theater-like experience in the home.</p>

