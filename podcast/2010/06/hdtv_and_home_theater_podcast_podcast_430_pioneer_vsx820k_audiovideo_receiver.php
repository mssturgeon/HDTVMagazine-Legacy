<p>The first thing you notice is that the unit is light, it weighs just  under 20 pounds (9 Kg) . Like all receivers you connect your speakers,  input sources, power and turn it on. This unit does not have an Ethernet  connection so there are no network setup steps involved. Our system  came with the optional <a title="AS-BT100 Bluetooth Adapter ($100)" href="http://www.htguys.com/shop?id=B002RAOCPK">AS-BT100 Bluetooth  Adapter ($100)</a> for connecting Bluetooth enabled sources like cell  phones, iPods and even iPads. To use these devices you have to pair your  device with the receiver and that step took us about 10 minutes &#8211; eight  minutes to try and figure it out without a manual then an additional  two once we gave in and read it.</p>
<p>The auto calibration was quite  simple to use. Plug in the included mic to the front of the receiver  and then place it where you want the audio optimized, hit go and wait.  We found the calibration to be accurate however we like our surrounds a  bit hotter than standard so we went into the manual settings and  increased the gain a bit. One irritation we have with the unit is that  the onscreen display is not visible with HDMI. You need an analog  connection to the TV for onscreen feedback. As a result we stuck with  the front panel. Note: Banana plugs are your friend!</p>
<h4>Performance</h4>
<p>The 820 did a great job reproducing Dolby True HD and DTS Master  Audio. Actually we were pleasantly surprised how good the audio sounded  when mated to our Aperion speakers. For most home applications (not  theater rooms) this receiver will be all that you need. There is plenty  of power to fill any family or living room. The 820 does support Dolby  Pro Logic IIz but you&#8217;ll need an additional stereo amplifier.  This is  one way Pioneer was able to cut costs on the device. Its actually a  smart move. Most of us won&#8217;t use the additional speakers. Your other  option is to move up to the 7.1 <a title="920" href="http://www.htguys.com/shop?id=B0039XQL44">920</a> which will cost  about $100 more than the 820.</p>
<p>The 820 also comes with a cable to  integrate your iPod Touch, iPhone, and even your iPad. The cable has a  USB and RCA video connector on one end, which connects in the front of  the unit, and 30 pin dock connector on the other. Typically when you  dock your iPod like this, say in a car, you can not control the iPod  from the device itself. Control is passed to your car stereo. When  connected to the 820 you still control the iPod through the iPod  interface which makes selecting your music simple. You can play videos  through the 820 as well but only through an analog connection to the TV.  The 820 does not convert analog to digital or vice versa. Your input  and output must match to see anything on screen.</p>
<p>If you want to  free yourself from cables you can use the Bluetooth adapter to play  music off your idevices, as long as you are in range of the Bluetooth  receiver. The operation is similar to other Bluetooth devices like the  Ford Sync system. Audio sounded good and we could not notice any  degradation in quality when compared to the wired connection. Our range  was decent, pretty much anywhere in the media room (15 X 25 feet). Once  we went beyond that the audio quality degraded quickly.</p>
<h4>Conclusion</h4>
<p>The pioneer VSX-820-K is now our new go to receiver for value. But  don&#8217;t let the word value scare you, the 820 is very capable and will  fill any family room with glorious HD audio. The iPod connection cable  is a great touch and if you want to go wireless the Bluetooth adapter is  a nice feature. The only complaint we have is that there is no onscreen  menu and no video from your iPod if all you have is a digital  connection to your TV.</p>
