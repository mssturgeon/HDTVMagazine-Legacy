<h4><strong>Background  on TV display settings</strong></h4>
<p>Most of you probably already knew  that the four main display  settings on your HDTV: brightness, contrast,  tint, and sharpness,  originated with the analog NTSC color TVs of  yesteryear, dating back to  the 1950&#8242;s.  Most of those settings had  specific meanings back then,  and for the most part, they don&#8217;t apply  anymore.</p>
<p>Back then Brightness was really an  adjustment of the bias of the unit.  Bias  is an adjustment of how many  electrons are hitting the phosphors of  the screen.  It&#8217;s a negative  offset, so zero bias is full brightness  and adjusting the bias will  eventually result in no phosphors hitting  the screen or total  blackness.  Contrast controlled a gain factor  applied to the color  signals shot at the screen, adjusting the overall  luminance of the  picture.  So, in essence, contrast was a brightness  adjustment as well.</p>
<p>The  other two are very technical, so in Dr. Soneira&#8217;s words  (because we  couldn&#8217;t find better ones of our own): &#8220;<em>tint controlled  the phase of  the color subcarrier, and sharpness performed analog  high-frequency  peaking to compensate for the limited video bandwidth of  the old vacuum  tube amplifiers.</em>&#8220;  But ultimately, the bottom line  is that none of  these controls are necessary for or relevant to the  digital signals and  televisions we use today.</p>
<h4><strong>Settings to Avoid</strong></h4>
<p>Almost  all of the settings you see listed as &#8220;special&#8221;  technologies on the  brochure or the side of the TV box should be turned  off immediately.  In  most cases, it&#8217;s difficult to determine what  those settings actually  do.  And in many cases they actually decrease  picture quality.  These  settings come by dozens of different names and  acronyms, many of which  are listed in the article.  A few that stood  out to us were: Dynamic  Contrast, Black Level, Gamma, White Balance,  Digital NR, DNIe, Detail  Enhancer, Edge Enhancer, and Film Mode.</p>
<h4><strong>Contrast  Ratio</strong></h4>
<p>Contrast ratio, or the ratio of brightness between  full white and  full black on screen can be a very revealing number.   Since most sets  can go full white, it really tells you how black a set  can get.  Keep  in mind that really good contrast ratios only matter if  you&#8217;re watching  very dark content, like you see in some movies.  Most TV  viewing never  gets into the full black range.  Contrast ratio can also  be canceled  out by the ambient light in the room.  No matter how dark  the picture  gets, it can always be washed out if you can&#8217;t control the  light that  doesn&#8217;t come from the screen.</p>
<p>Possibly  the worst misuse of a spec is the so-called dynamic  contrast ratio.  We  have talked about this on the show before.  It is a  measurement of the  ratio of white when the full screen is white to  black when the full  screen is black.  Many televisions can actually  reduce or turn off the  light source entirely if the screen goes full  black, producing an  incredibly high ratio.  The problem, however, is  that the sets cannot do  this if they&#8217;re actually displaying a picture,  so you never see  anything that dark and the spec is completely  useless.  What&#8217;s worse is  that many manufacturers are leaving the word  &#8220;dynamic&#8221; off the spec  sheet, claiming contrast ratios in the  millions.  That just isn&#8217;t  accurate.</p>
<h4><strong>Response Times</strong></h4>
<p>This was a huge  eye opener when we first read about it a while  ago.  It turns out that  LCD response times, a spec we always thought  was very important, is  somewhat meaningless these days. First of all,  it would take about a  16ms refresh rate to support 60 fps video.  Most,  if not all, LCD TVs on  the market today are significantly below that  threshold.  Secondly, in  Dr. Soneira&#8217;s test, the actual measured  response time was significantly  higher than the published spec.  An 8ms  SONY LCD had a measured response  time of about 65ms, and it was the  best performer in the group.</p>
<p>Another  equally useless spec that is somewhat related is refresh  rate.  In an  independent test, many viewers were able to see  improvements (reduction  in) blur on 120Hz televisions over 60Hz sets if  they were shown a still  image moving quickly across the screen.  The  same people saw no  different when watching actual video content.  Since  what we watch on TV  is very rarely a still image moving quickly across  the screen, it  stands to reason that there is little if any benefit  for normal use, of a  120Hz TV over a 60Hz model.  Of course the 120Hz  sets tend to be newer,  with newer electronics, so it&#8217;s entirely  possible that they have better  picture quality &#8211; but not due to the  refresh rate alone.</p>
<h4><strong>Color  Gamut</strong></h4>
<p>The article goes on to discuss color gamut and how  manufacturers  reaching to give you a &#8220;wider&#8221; color gamut are just  playing specmanship  with you.  This also applies to Sharp and their new  quattron or quad  pixel technology.  According to the article, you won&#8217;t  get any benefit  from that extra yellow in the color array.  The content  you&#8217;re watching  is balanced for the RGB sets most people own, which  already include  yellow.</p>
<p>The article was very  informative and gave us some really good food  for thought.  Our main  takeaway was that your eyes are all that  matters when it comes to TV  picture quality.  Regardless of what specs  are published, what you see  on screen is what counts.  Find a TV that  works for you, and buy it.  So  what if someone else has a higher  dynamic contrast ratio, faster  response time or a wider color gamut.   Odds are, nobody can tell the  difference anyways.</p>
