<p>Its  no secret that we both love our whole house audio systems.  Judging from  the email we get its pretty clear our listeners like whole  house audio  as well. Braden uses the Logitech <a href="http://www.htguys.com/shop?id=B0013IWYHU">Squeezebox</a> setup and I use Apple’s <a href="http://www.htguys.com/shop?id=B0015YJOK2">Airport Express</a>. We tested and really like <a href="http://www.htguys.com/shop?id=B002S53LJ2">Sonos</a> as well.  So when Apple introduced their latest sharing technology called <a href="http://www.apple.com/itunes/airplay/">Airplay</a>, we were intrigued to see what it offers over existing technologies.</p>
<h4>Audio</h4>
<p>Airplay  is a wireless technology that lets you stream your music  from iTunes  (Mac or PC) to speaker docks, A/V receivers, and Airport  Expresses. So  what’s the big deal you may ask? I’ve been doing that for  years. With  Airplay, Apple has licensed the technology to third party  developers so  you’ll be able to build whole house audio systems by  doing nothing more  than plugging in power and joining your local  network.</p>
<p>By  licensing the technology you’ll be able to mix and  match components to  match the characteristics of your room. That way  you can go cheap in  your garage and high end in your media room. Denon,  iHome, JBL, and  Marantz have announced products that are compatible  with the technology.</p>
<p>AirPlay  does more than just stream your  music to external speakers however. It  streams information about your  music, too. Airplay compatible devices  will be able to display meta  data about the music you are listening to  including Song titles,  artists, album names, elapsed and remaining time,  and album artwork all  appear on AirPlay-enabled speakers with graphical  displays. Previous  remote speaker capability simply streamed the music  without any id3  data.</p>
<p>You  will be able to control your music from your iPod  Touch, iPhone and  iPad. That much is not new. What’s cool is that you  will also be able to  send audio from these devices to the remote  speakers as well. No longer  will need to leave you computer on to  listen to your library. It will  also be possible stream music from  other applications like Pandora or  Last.FM right from your portable  device.</p>
<p>This  frees Apple from having to create agreements with  content providers.  Essentially, Airplay comes with support from  thousands of content  providers on day one. Every radio station that has  an app in the iTunes  store is a content provider for streaming audio  to an AirPlay connected  device.</p>
<p>The  possibilities are pretty  cool if we think about it. You come home from a  run listening to some  great music and don’t want to stop. Simply press a  button on your  iDevice and your music is now blasting through the house  without  missing a beat! Have you been to a party and the host has lousy  music?  Get on his local network and send your own playlist to the whole  house  audio system and your friend will thank you for saving the party!</p>
<h4>Video</h4>
<p>Airplay  also has a video component that is very intriguing to us. If  you have  an AppleTV you will be able to send video from your iPod,  iPhone, or  iPad directly to the AppleTV. Until AppleTV supports apps  this is the  next best thing. What’s not clear yet is if the  applications need to  explicitly support this feature or if its  automatic with any video.</p>
<p>Imagine  sitting together and finding  funny videos on Internet and then sending  them to the AppleTV. No Hulu +  on AppleTV no worries. Just launch it  from your iPod and send it to  the AppleTV. Since the iPhone 4 has an  “HD” video recorder you can  easily share videos that you shot with your  friends and family. All you  need to do is jump on the local network and  you’re ready to go. Want  to share vacation photos with friends and  family? Its just a button  push away. We are hoping that Apple will allow  this technology to work  for videos stored on your computer as well.</p>
<p>At  this point in  time only the AppleTV supports video streaming from  iDevices, however,  we feel confident that TV manufactures will either  license the AirPlay  technology or perhaps build in AppleTV. Maybe Apple  will even  manufacture an actual HDTV that we keep hearing about.</p>
<h4>Conclusion</h4>
<p>While  other manufacturers have wireless whole house solutions this  is the  first time that you can bridge a single technology across  different  manufacturers with zero configuration. Competition should  spur creative  solutions and multiple price points. Tie all of them  together with  Apple’s revised Remote Control app and you have a sexy  solution that is  affordable and can grow with you.</p>
