<p>We’ve  been doing this show for going on six years. During that  period we’ve  seen the Home Theater world go through a lot of changes.  Technologies  have been announced and have either  completely failed or  never lived up  to their potential. We’re looking at you SED, HD DVD,  and MoCA. To be  fair MoCA is the closest to being a reality but its  taking a long time.</p>
<p>For  today’s show we are going to take a look  at what the future of Home  Theater was back in 2005 and see how its  panned out and then we’ll talk  about what we’d like to see five years  from now.</p>
<h4>Future of Home Theater circa 2005:</h4>
<p><strong>Laser Video Projectors</strong> &#8211; These are video projectors  that modulate a laser beam in order to  project a raster-based image.  While not a reality yet there are laser  based DLPs from Mitsubishi.  This technology is still a future technology  in 2010.</p>
<p><strong>HDTV everywhere</strong> &#8211; This  is pretty much a reality today, at least in the US. Satellite  and cable  companies used to send out press releases when they added new  channels.  Today we seldom get these. Many systems are giving HD  service away.  Finally, when commercials are in HD its safe to say HDTV  is more or less  everywhere.</p>
<p><strong>Enhanced Interactive Television</strong> &#8211; We are seeing this with Yahoo widgets and the forthcoming Google TV.   Many TVs are now connected to the Internet and soon most of them will   have this option.</p>
<p><strong>Holographic Front Projection</strong> &#8211; We really haven’t seen any Holographic Projection yet. This is still a future technology in 2010.</p>
<p><strong>Carbon Nanotube Displays</strong> &#8211; The dream of bendable screens has many applications from advertising   to wallpaper thick screens that can cover walls and make projectors   obsolete. We’re still waiting on the future for this.</p>
<p><strong>XBOX 360</strong> &#8211; We’d like to add PS3 and Wii to this and say that its here today. For   many their gaming consoles are more than a box to play games on. With   Netflix, Movie Rentals, and Media Streaming our gaming consoles are   Media Centers that anchor our home theaters.</p>
<p><strong>SED Displays</strong> &#8211; RIP</p>
<p><strong>IP Everything</strong> &#8211; Think about how many devices in your home have IP connections. TVs,   Receivers, Set Top Boxes, Music Players, and the list goes on. Safe to   say the future is here.</p>
<p><strong>DTS-HD and Dolby Digital Plus</strong> &#8211; While these were futuristic technologies in 2005 they have been improved upon with Dolby True HD and DTS Master Audio. Check!</p>
<p><strong>HD-DVD and or Blu-ray high definition DVD’s</strong> &#8211; HD DVD RIP, Blu Ray pretty much everywhere. Check!</p>
<h4>Future of Home Theater circa 2010:</h4>
<p>So  back in 2005 someone created this list and just five years later  six of  the ten are a reality, one has no chance of making it to the  market and  were still waiting for three. Now let’s look at where we see  Home  Theater going in the next 5 to ten years:</p>
<p><strong>Convergence</strong> &#8211; One box to do everything. Why not make a box that is your receiver,   tuner (ATSC and Cable Card), Blue Ray Player, Video Server, and Game   Console. Essentially we are talking about building a HTPC with   receiver/amplifier built in. Sure if it goes out your in the dark but   think how simple it would be to connect one box and be done.</p>
<p><strong>Wireless Home Theater</strong> &#8211; If you can’t have one box to do everything why not connect them   wirelessly. It would need to be as simple as placing the components next   to each other and putting them into a discovery mode. The units would   find each other and auto detect capabilities. This would extend to   speakers as well. You may have to designate the channel but other than   that you just plug in power.</p>
<p><strong>Interoperability/Control</strong> &#8211; This ties into the previous point. We’d like to see interoperability   between components of all manufacturers. We’re not talking just   connecting a Samsung Blu Ray player to a Yamaha receiver and watching a   movie but more about having the components identify themselves and  their  capabilities. In our world the remote would auto configure and  create  basic macros based on what type of components you have.</p>
<p>Want   to watch a Blu Ray? Just hit Watch a Blu Ray and the receiver would   switch to the appropriate inputs and turn on the Blu Ray player. In this   case the Remote is dumb. It doesn’t need to know the commands to send.   The receiver stores all the commands. The remote just sends what  button  was pressed and allows the receiver to determine what to do.   This way  you can add a new remote and all the macros and commands are  added to it  by the receiver. Go one step further, since everything is  IP based your  smartphones and mp3 players can act as a remote as well.</p>
<p><strong>Cloud</strong> &#8211; The cloud will be big in the future. It may be a private cloud where   your content is stored on your own server or a public one where your   content is stored in a digital locker. Either way if you have an   Internet connection you will have access to your content. In our vision   you will be able to sync between multiple locations, devices and even   your automobile.</p>
<p>Once  LTE networks get rolled out it will be  feasible to have reliable access  to music, videos, and personal media  anytime, anywhere. Imagine buying a  CD and ripping it to your car  jukebox. The ripped music complete with  id3 tags will sync via your 4G  connection to your connected devices  including your HTPC or A/V  Receiver. If you don’t have a good connection  on the road it syncs when  you pull into your driveway via WIFI.</p>
<p><strong>OLED TV</strong> &#8211;  This ties in with Nanotube technology from the 2005 list. While we   feel that OLED may never make it as a traditional TV technology it does   have a shot for large format use. Perhaps this technology may make  front  projection obsolete.</p>
<p><strong>Automation</strong> &#8211; This is  technology that’s already here. So why is it on the list? Our  vision  is that, like the remote control, it becomes dead simple to  integrate.  You add devices and the system recognizes them. Simple macros   pertaining to rooms are automatically generated, others, like activity   based macros, are created in a turbo tax style question and answer   mechanism. This eliminates the need for any real programming skills and   makes it possible for anyone to create a sophisticated automation   system.</p>
<p><strong>Ultra High Definition</strong> &#8211; Well this is  just the next progression of HD. Who wouldn’t want  higher resolution?  This UHD content may come from satellite, Internet,  or disc based  delivery systems before its available over the air. TVs  that support  will come well in advance of content. Look for an  upconverting Blu Ray  player from Oppo right after UHD TVs become common.</p>
<p><strong>3D</strong> &#8211;  Its no secret that we are not big fans of 3D. Actually, we’re not  the  only ones. The biggest issue we have is that you need expensive  glasses  to enjoy 3D and that experience requires a large screen to  fully  appreciate. In our vision we’re talking about 3D that doesn’t  require  glasses and the experience is the same regardless of where you  are  sitting. This may be the forerunner for Holographic projection.</p>
<p>That’s   our list. Chime in and comment on what you think the future of Home   Theater is. We’ll talk about it on a follow up to this show.</p>
