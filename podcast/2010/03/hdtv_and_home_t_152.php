				<h2>Today&#8217;s Show:</h2>
<h3>Switched Digital Video</h3>
<p>Last week Braden wrote that Cablevision is planning on rolling out network DVR (<a title="Cablevision To Roll Out RS-DVR In April" href="http://www.htguys.com/news/2010/2/25/breaking-news-cablevision-to-roll-out-rs-dvr.html" target="_blank">Cablevision To Roll Out RS-DVR In April</a>) functionality in April. This technology has got us excited because it shows that Cable is pushing itself to compete with Satellite, FiOS and U-Verse. One area that cable still falls a little short when compared to these other services is the number of HD channels they offer. A new technology called Switched Digital Video is being deployed that will allow cable companies to increase the number of HD channels they offer. But not every is happy about it.</p>
<h4>What is Switched Digital Video?</h4>
<p>Switched video sends programming to customers in an efficient manner so that bandwidth is freed up on the system. Its not that the head end of the cable system can&#8217;t receive hundreds or even thousands of channels, its that it can&#8217;t send them all down the line. So if only one person wants to watch Lifetime it needs to be sent to everyone.</p>
<p>The new system uses fiber optics to send all the content out to nodes throughout the service area. The fiber optic network has much higher capacity however most neighborhoods do not have fiber to the home. As a result something has to be done to get the video from the node to the home. Each node services anywhere from 1 to about 2000 homes.</p>
<p>Only the video being watched is actually sent to the homes. So if all 2000 homes are watching the same show then only one video stream is sent. The cable company has years of data suggesting that 2000 people will never watch 2000 unique channels. They are counting on the load balancing to offer more content which include more HD, Video on Demand, and Network DVRs.</p>
<p>When a home requests a channel from the distribution hub it checks to see if someone is already watching it, if not the hub creates a new QAM channel and sends it down the line. This new virtual channel number is mapped to the number that your cable system uses. So the one person who wants to watch Lifetime simply selects channel 225 to watch, even though it may be transmitted on channel 613. There must be two way communication for this system to work. Therefore you will have to use a cablebox. This has some people upset.</p>
<h4>What about my Tivo and HTPC?</h4>
<p>If you have a Tivo or HTPC with a cable card there are storm clouds on the horizon. When your cable system deploys SDV you will no longer be able watch and record your favorite programs. As stated earlier SDV needs to be able to communicate with the node in order to request the channel number for the programming. Since Tivo and current cable card don&#8217;t know how to talk to the node your tuners will no longer be able to lock onto your favorite channels.</p>
<p>The FCC has a mandate to the cable companies requiring them to open up their systems to third party devices. That&#8217;s how we got the CableCARD. Tivo uses the CableCARD and and Internet connection to provide a DVR experience that is better than the cable company&#8217;s. And that is probably the main reason cable is dragging its feet on this. They want to be the only source for your DVR service. If you have an HTPC then you are out of luck too. You don&#8217;t pay for Tivo but with Media Center software you have probably the best TV experience and the cable companies can&#8217;t charge you a premium for that.</p>
<h4>When will I get Switched Digital Video?</h4>
<p>Cable companies started rolling out the technology in 2008 to about 25 million homes, by 2009 that number rose to 35 million. Time Warner is rolling out SDV in three markets (Los Angeles, New York City, and Dallas) that will add another 6 million homes. Comcast and Cablevision also have plans for a roll out this year. Analysts are predicating that 90 million homes with be served by SDV by 2012.</p>
<p>From an investment angle BigBang Networks Inc sells SDV equipment to Time Warner and have installed switches in 28 million homes. When Comcast goes SDV then take a look at Cisco and Motorola since they provided equipment for Comcast&#8217;s trial with SDV. Aris Group Inc and Harmonic Inc also provide equipment for the technology.</p>
