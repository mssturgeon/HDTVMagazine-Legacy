				<h2>Today&#8217;s Show:</h2>
<h3><strong>Front Projector Technologies</strong></h3>
<p>We have to admit, we got a  little giddy when we got an email from  Jason asking us to go over the  various technology options available for  front projector home  theaters.  With rear projection television fading  into the sunset, we  don&#8217;t often get the opportunity to talk about the  various merits of LCD,  DLP, and LCoS projection technologies anymore.   It&#8217;ll be like the good  old days.</p>
<p>We&#8217;ve seen many technologies  come and go since Episode 1  of the podcast.  We&#8217;ve had a great time  over the years explaining and  analyzing the pros and cons of CRT  displays, LCD projection, DLP TVs and  even a brief love affair with  LCoS technology.  Anyone remember  Brillian?  Although it seems  everything is flat panel these days, many  of these technologies live on  as front projectors.</p>
<h4><strong>LCD</strong></h4>
<p>The  earliest digital projectors were based on Liquid Crystal Display  (LCD)  technology.  We have podcast episodes in the archives all about  it, but  most of them were lost in the transition to our new website.   Bottom  line, LCD is a tried and true technology.  It typically has very  vibrant  color and provide a very sharp, crisp picture.</p>
<p>On the   downside, LCD&#8217;s vibrant color and crisp picture tends to produce video   that doesn&#8217;t looks quite as real or lifelike as other technologies.    Many describe it as looking more digital.  It also doesn&#8217;t have the   contrast capabilities of the other technologies, which is critical to   home theater applications.  For the office, LCD is great, for the home   theater, it hasn&#8217;t quite won the hearts and minds of the masses.</p>
<h4><strong>DLP</strong></h4>
<p>Digital  Light Projection (DLP) is a Texas Instruments invention that  uses  millions of tiny mirrors to reflect the light your see onscreen.    Historically, it has been one of the more controversial and debated   technologies on the show.  When you&#8217;re feeling nostalgic, go ahead and   do a Google search for wobulation. ; That&#8217;ll bring back some memories.</p>
<p>On   the upside, DLP produces better contrast and black levels than LCD.    This makes it ideal for home theater applications.  On the downside, it   isn&#8217;t quite as sharp as LCD and has suffered from all sorts of crazy   screen artifacts like rainbows, silk screen effect and others.  Ara has  two DLP rear projection sets that he is quite fond of.</p>
<h4><strong>LCoS</strong></h4>
<p>Liquid  Crystal on Silicon (LCoS) comes in several variants.  JVC  markets it as  D-ILA; Sony markets it as SXRD.  LCoS uses liquid  crystals like LCD,  but they are reflective (almost like mirrors)  instead of transmissive.   At a really high level, the technology almost  feels like the perfect  marriage of the other two.</p>
<p>Of the  projectors we&#8217;ve seen and used,  the LCoS models tend to come out on  top.  They produce a great, vivid  picture and excellent contrast  ratios.  We were big fans of SXRD and  D-ILA rear projection TVs (Braden  owns a JVC) when they were out, and  have always been impressed with  their front projector variants as well.   Early on DLP had an edge in  contrast ratios, but that no longer holds  true.</p>
<p>Of course, LCoS  doesn&#8217;t come without a price.  The Sony and  JVC projectors tend to be  more expensive than their DLP or LCD  competition, with JVC edging Sony  slightly in the bang for your buck  department.</p>
<h4><strong>Conclusion</strong></h4>
<p>Bottom line, LCD projectors are  bright, vivid and inexpensive.  DLP  projectors are darker, provide  better contrast and don&#8217;t cost as much.   LCoS projectors probably give  the best picture, but they cost a lot.   You have to weigh the pros and  cons for yourself and see what your  budget will allow.  In the end,  though, no matter what you choose,  there&#8217;s no denying that a 120&#8243; screen  is pretty darn cool.</p>
