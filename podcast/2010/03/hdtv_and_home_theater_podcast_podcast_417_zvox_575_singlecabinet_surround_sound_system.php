Simply open the box and place the unit on  your TV stand, connect power, and connect the analog audio from the  source to one of the two audio inputs, and power on. That&#8217;s it! OK, so  the simplicity of setup is also a weakness of the unit. It does not take  digital audio but that doesn&#8217;t matter. We&#8217;ll talk more about that when  we talk about performance. The 575 has a nice aesthetic feature as well.  Its designed to be used as a stand to place your TV on top of. The  Z-Base 575 is 36 ” wide by 16.5 ” deep by 5 ” high and supports up to  146 pounds (66.2 Kgs). This is a great space saving feature and when you  place your TV on the unit it just looks like it belongs there.</p>
<p>There is no calibration of the 575. Instead the remote control is used  to adjust the Subwoofer, Treble, and Volume. There is also a PhaseCue  function that adjusts the virtual surround. Logitech has all the IR  codes for the 575 so we were able to setup our Harmony remote to control  the system.</p>
<p><strong>Performance</strong><br />
As far as surround goes don&#8217;t expect  the 575 to perform like your dedicated home theater system. After all,  it does not have digital inputs. All that aside we were quite pleased  with how the unit sounded. Dialog was clear and and had texture. Music  was wide and full. Sporting events seemed to be live. The 575 has a  built in subwoofer which gave punch to whatever we watched. The  subwoofer is what seals the deal on this unit.</p>
<p>There is some  surround imaging that you get out of the 575 and your mileage will vary  based on the room you put the unit in. We had mixed results depending on  what we were watching. The remote has two buttons to adjust the level  of surround, Phasecue+ and Phascue-. There are 8 levels of virtual  surround. What we found is for listening to music setting it to the max  gave you a wide sound image. The max setting for movies drowned out the  dialog when there was affects of music. We found that for most movies a  setting of 5 or 6 produced the best compromise. Not once did we feel  that there were sounds coming from behind us. It was more about the  front and how wide it sounded.</p>
<p>Don&#8217;t get us wrong. We felt there  was a big improvement over the speakers on the TV. The subwoofer helped  add an additional dimension to the sound. When watching movies on the  TV&#8217;s speakers the big boom effects are lost. They were loud and clear on  the 575.</p>
<p><strong>Conclusion</strong><br />
The ZVOX 575 is a good solution for  those who want more than a TV&#8217;s speaker for watching movies and  listening to music. Its a perfect device for an apartment dweller, den,  or a bedroom because its so dead simple to setup. If you don&#8217;t need the  power of the 575 you can step down to the <a title="ZVOX 550" href="http://www.htguys.com/shop?id=B001MA2AYG" target="_blank">ZVOX 550</a> and save yourself $300.</p>
