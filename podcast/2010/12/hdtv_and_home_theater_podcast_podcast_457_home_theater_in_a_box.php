<p>For the Blu Ray player we are going with the <a href="http://www.htguys.com/shop?id=B004BLK24S">OPPO BDP-93</a>.   Priced high ($499) for a Blu Ray by today’s standards but its one of   the best Blu Ray players on the market today.  This player is not yet   released but will be soon. Features include, Ethernet/wireless   networking, DVD audio and video are supported, and it&#8217;ll play Super   Audio CD (SACD) in stereo or multi-channel, USB/eSATA connectivity with   support for DVD, audio CD, HDCD, Kodak Picture CD, AVCHD, MP4, DivX,   MKV, FLAC, WAV and other audio/video/picture files on recorded discs.   Finally, there is support for Netflix and Blockbuster on demand.</p>
<p>For the speakers we are recommending the <a href="http://www.aperionaudio.com/product/Intimus-5B-Harmony-SD,118,71,271.aspx">Intimus 5B Harmony SD</a> ($1750). Its a 5.1 system that includes the <a href="http://www.aperionaudio.com/product/Intimus-5B-Bookshelf-Speaker,108,20,250.aspx">5B bookshelf speakers</a> combined with the<a href="http://www.aperionaudio.com/product/Intimus-5C-Center-Channel-Speaker,109,29,253.aspx"> 5C vertical array center</a> to provide the all-encompassing sound, and together with the massive rumble of the<a href="http://www.aperionaudio.com/product/Bravus-8D-Dual-8-Powered-Subwoofer,104,66,241.aspx"> Bravus 8D subwoofer</a>. Ara has Aperion speakers in his media room and he is a big advocate of the line.</p>
<p>Total   cost for the components is $4050. Incidentally Ara and Braden’s first   HDTVs, which are still in use today, were purchased for roughly the  same  price!</p>
