<p><a href="http://www.htguys.com/shop?id=B003LVZYNI">Denon AVR-3311CI 7.2 Channel Network Home Theater Receiver (Street Price $1200)</a><br />
We   are big fans of Denon products and the 3311CI is a real powerhouse  that  we highly recommend! The 3311CI supports Audyssey DSX surround   processing, Audessey MultEQ automatic room acoustic measuring and   correction system. Support for next generation audio, 3D and Anchor Bay   ABT-2015 upconversion and deinterlacing are included. At 125 watts per   channel the 3311 will fill almost any room with high quality audio!</p>
<p>For the Blu Ray player we are going with the same model as our less than $5000 system the <a href="http://www.htguys.com/shop?id=B004BLK24S">OPPO BDP-93</a>.</p>
