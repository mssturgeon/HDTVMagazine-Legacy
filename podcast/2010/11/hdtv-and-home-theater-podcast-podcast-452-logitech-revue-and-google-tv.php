<p>Google  TV literally combines a search engine with your TV. Google TV  lets you  search across every channel,  application, and the Internet  to find  exactly what you are looking for. It combines the power of  applications  like Pandora, Twitter, Netflix, and many others with the  Internet to  enhance how you watch TV. You can create a custom homepage   that gives  you access to your favorite apps, channels, and websites.  You can easily  switch between the web and TV or even combine the two  with picture in  picture. It takes the concept of Internet connected TVs  to the next  level by integrating the experience.</p>
<h4>About the Revue</h4>
<p>The  Logitech Revue is a small box you connect to your TV via HDMI.   In many  ways it is quite similar to the other streaming options out  there like  the Apple TV, Roku and Boxee Box.  With a retail price of  $299 (<a href="http://www.htguys.com/shop?id=B0040QE98O">buy now</a>),   it is a bit more expensive than the competition, so you’d assume it   comes with a few extras to differentiate itself.  And it does, but we’ll   get into those later.  We’ll leave it up to you to decide if the  extras  are worth the cost.</p>
<h4>Setup and Use</h4>
<p>In  addition to the HDMI output that you connect to your TV, the  Revue has  an HDMI input as well.  This allows you to plug in your TV  source  directly to the Revue so Google TV can interact with live  television.   That’s differentiator number one.  The competition devices  stream  content to your TV, the Review does that and can interact with  your live  TV content.  You can pull up a browser right on top of the TV  program  to do an IMDB search without having to switch boxes.</p>
<p>If you happen to be a <a href="http://www.dishnetwork.com/">Dish Network</a> subscriber, the integration goes even further.  This is where you   really start to see the power of what Google TV will offer as the   solution matures.  The Revue has the ability to connect to your Dish DVR   and access all of your recorded programs.  It can also see what’s   available for On Demand or Pay Per View viewing.  So when you do a   search on the Google TV for something to watch, not only do you get   online content, but you get your own local content as well.  It’s   awesome.  It really gives you one interface for all of your   entertainment options.</p>
<p>So  we’ve mentioned you can do full  browser searches and can search your  media content with the Revue.   That sounds like something that would be  difficult with a standard  remote control.  Differentiator number two,  the Revue comes with a full  keyboard controller with built-in touch pad.   It’s a bit large, but it  has buttons for media control like a remote  would, has a full keyboard  to make typing a breeze and even a touch pad  to allow you mouse around  to wherever you want to go.  You get hooked on  using it pretty  quickly.  We sure did.</p>
<p>And  of course, it’s from Logitech so you  expect some sort of Harmony style  universal control.  That brings us to  differentiator number three.  The  Revue actually uses HDMI CEC the way  it was intended to be used.  It  allows you to turn your TV on and off  and adjust volume.  It will change  channels on your video source.  If  you have a receiver for surround  sound, you can plug it into the Revue  instead of plugging your TV source  directly and control it as well.   Finally a good use of HDMI CEC to  actually control all your home  theater devices.</p>
<p>Of  course the Revue allows you to get access to  all the usual online  suspects: Netflix, NBA.TV, Pandora, Twitter,  Amazon OnDemand.  It’s all  in there.  It also has a built-in DLNA  player so you can stream all of  your backed-up movies to it.  We’ve  heard the CODEC support is limited,  but we use mostly mpeg4 video  variants and it played all of them just  fine.  Word on the street is  that Google is going to open app  development to the masses in the near  future.  This could be where  things really take off.</p>
<p>And,  of  course, as a Google based product you can imagine there’s an Android   app to control it.  This isn’t really a differentiator, but the app is   pretty cool.  It connects to the Revue via WiFi and lets you do just   about anything the keyboard allows, albeit not quite as easily.  But it   is convenient to have that controller in the palm of your hand for a   quite adjustment or something.  We’re expecting this integration between   Android and Google TV to grow in the future and perhaps become more of  a  differentiator.  Would be nice if you could watch whatever was  playing  on the Revue on your Android phone anywhere in the world.</p>
<h4>Conclusion</h4>
<p>We  had a ton of fun playing with the Revue and Google TV.  While it  does  carry a hefty price tag, it has a few bells and whistles that set  it  apart from the competition.  And we see tremendous opportunity for   innovation in this platform.  If you’re a Dish network subscriber,   you’ll love it.  If you aren’t, the Revue might make you want to sign up   with Dish just to get the integrated content all in one place.</p>
