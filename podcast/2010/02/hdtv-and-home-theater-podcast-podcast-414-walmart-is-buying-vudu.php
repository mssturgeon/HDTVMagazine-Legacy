If Wal-mart is one thing, it&#8217;s main stream.  You can&#8217;t throw a rock without hitting one.  That means Vudu is now instantly main stream as well.  Hopefully Wal-mart will change the name of the service.  Let&#8217;s face it, &#8216;Vudu&#8217; doesn&#8217;t really make most people think of instant access to new release movies.</p>
<p>When the Vudu service gets Wal-mart-ized, you can bet it will be simple, straightforward and super easy to use.  It will have to hit the setup and use requirements of other electronics sold at Wal-mart.  Not that Vudu was all that challenging, but Wal-mart knows their shoppers.  If it&#8217;s easy to use and easy to understand, they&#8217;ll sell a ton of boxes making downloaded/streamed movies commonplace in thousands of homes.</p>
<p>Wal-mart also has a little bit of pull with electronics manufacturers.  They could begin to demand that Vudu technology appear in the Wal-mart versions of TVs and Blu-ray players, extending the availability of the service even more.  It isn&#8217;t too far fetched to believe that in the near future every Blu-ray player from Wal-mart would include Vudu technology.  If it&#8217;s built into the Wal-mart models, it might make economic sense to just build it into the rest of them you can buy from Amazon, Best Buy or Costco as well.</p>
<p><strong>Pricing</strong><br />
Wal-mart has long been known as the store that sells cheap stuff for really cheap.  Lately they&#8217;ve made a move to carry higher quality merchandise but maintain the low pricing.  Wal-mart is big enough that they can dictate a lot of terms.  You can bet they&#8217;ll want to beat the competition like Apple and Amazon on price.  And they&#8217;ll probably be able to.</p>
<p>Wal-mart sells enough DVDs that they have quite a bit of pull in Hollywood.  We wouldn&#8217;t be surprised if they got some special terms from the studios, be it pricing or availability.  Imagine Wal-mart threatening to stop selling, or delay selling, a studio&#8217;s DVDs.  We&#8217;re pretty sure the studios would be able to &#8220;work something out.&#8221;</p>
<p><strong><span style="text-decoration:underline;">The Bad and the Ugly</span><br />
Been there, done that</strong><br />
Wal-mart has tried this before and it failed miserably.  They tried to get into the streamed movie rental business a few years back by partnering with HP and that failed to ever get off the ground.  Maybe the concept was still too new at the time, but we&#8217;re really big fans of Vudu HDX, so we&#8217;d hate to see it driven into extinction.  Hopefully this time around it works out for Wal-mart.</p>
<p><strong>Competition</strong><br />
For the most part, Wal-mart isn&#8217;t a big fan of competition.  Like most big companies, they don&#8217;t mind driving others out of business if it helps the bottom line.  In this particular market, competition is both a good and a bad thing.  Because all the competitors have different content contracts, you can&#8217;t always find everything you want at one particular service.  One service with everything would be great.</p>
<p>But, and it is a big but, competition is also what pushes these companies to provide a better service.  It&#8217;s how we got HDX quality from Vudu, 5.1 audio from Netflix and 1080p video from Microsoft.  Without competition there&#8217;s really no incentive to innovate or push the limits on quality and viewing experience.  Of course, HDX is really good, so maybe Wal-mart won&#8217;t need too much innovation.  At least not in the short term.</p>
<p><span style="text-decoration:underline;"><strong>The Dream</strong></span><br />
<strong>All-you-can-eat Vudu</strong><br />
What we&#8217;d really like to see is Wal-mart going head to head with Netflix, not Apple or Amazon.  Get away from the per-movie rental fees and move to a subscription based, all-you-can-eat model.  If they can find a way to pull that off, we&#8217;d be huge, huge fans.  Sure maybe it means the movies aren&#8217;t available for streaming at the same time, or you can only watch one or two every few days, depending on your subscription rate.</p>
<p>But in either case, we&#8217;d have to think long and hard about the possibility of switching over.  We think there are a lot of people out there who would do the same thing.  And at the very least it would open the door for Netflix to do something similar.  And like we said before, sometimes a little competition is a very good thing.</p>
