				<p><br /><h2>Today&#8217;s Show:</h2><br />
<div><br />
<h3>VIA: Vizio Internet Apps</h3><br />
</div><br />
<div>If you happened to watch the Super Bowl and paid attention to the commercials, there were some really good ones.  Bud light had a few, Doritos had a couple, but there also might have been a few that didn&#8217;t make much sense to you.  One of those could have been the Vizio add for their newly refreshed Vizio Internet Apps offering.</p><br />
<p>The commercial featured a robot arm throwing Beyonce and a bunch of other random stuff into a pit.  Somehow all these things, among which were Internet staples such as Twitter, Flickr, and Facebook, became the VIA (Vizio Internet Apps) product.  Apparently Vizio has added some of their own widgets to the standard Yahoo! TV Widgets.</p><br />
<p>We&#8217;re on record as saying that 3D won&#8217;t move the needle this year, could widgets be a better option for manufacturers?</p><br />
<p><strong>Models</strong><br /><br />
Vizio has three models available for presale.  They should become available on Monday Feb 15.</div><br />
<div><br />
<ul><br />
<li><a id="whjh" title="55” VF552XVT" href="http://www.htguys.com/shop?id=B0036DDHRQ">55” VF552XVT</a> for $1999</li><br />
<li><a id="c8w3" title="42” SV422XVT" href="http://www.htguys.com/shop?id=B0036DDHSA">47” SV472XVT</a> for $1549</li><br />
<li><a id="glcx" title="47” SV472XVT" href="http://www.htguys.com/shop?id=B0036DDHSU">42” SV422XVT</a> for $949</li><br />
</ul><br />
<p><strong>Features</strong></p><br />
<ul><br />
<li>Direct lit LED-backlit LCD HDTV with full 1080p HD resolution (1920 x 1080 pixels)</li><br />
<li>240Hz refresh rate</li><br />
<li>Connect to the Internet via Wireless-N Wi-Fi or Ethernet to stream video, audio and news content from VIZIO Internet Apps (VIA)<br />
<ul><br />
<li>Apps available: Amazon Video on Demand, Flickr, Netflix, Rhapsody, VUDU, Yahoo! TV Widgets (includes Blockbuster, CinemaNow, YouTube, USA Today, eBay, Facebook, CBS, Showtime, Twitter, MySpace)</li><br />
</ul><br />
</li><br />
<li>Smart Dimming intelligently controls LED blocks to produce 2,000,000:1 contrast ratio</li><br />
<li>Inputs: 5 HDMI, 1 component, 1 composite, 1 S-Video, 1 PC, 1 RF, 1 Ethernet, 1 optical digital audio output</li><br />
<li>Bluetooth remote with slide-out QWERTY keyboard which also uses IR to control your other home theater gear</li><br />
</ul><br />
<p><strong>Our take</strong><br /><br />
If you look at the 55&#8243; set, it costs $1999.  The equivalent set from Vizio without the Internet Apps and fancy remote (Direct lit LED, local dimming, 240 Hz), the <a id="s5.i" title="VF551XVT" href="http://www.htguys.com/shop?id=B002JPEWOO">VF551XVT</a>, costs $300 less at $1699.  At a $300 premium, you&#8217;re probably pushing the limit of how much the apps are worth.</p><br />
<p>By far the best app available on the TV is Vudu.  If you plan to use the Vudu service, the $300 is pretty good, considering the <a id="jvlp" title="Vudu box" href="http://www.htguys.com/shop?id=B000VEMJFY">Vudu box</a> itself costs $199.  So in this case you pay an extra $100 for all the other apps and a pretty cool remote.  The convenience of having everything in one unit is probably worth it.</p><br />
<p>If you don&#8217;t want Vudu, you can get movies from Netflix and Amazon, saving you $100 for a <a id="shfn" title="Roku box" href="http://www.htguys.com/shop.php?id=B001PIBE8I">Roku box</a>.  The rest of the apps are either very specific to a select audience: Facebook, Twitter, MySpace, or probably seldom used: eBay, YouTube, Flickr.  So the premium may be worth it for some (we both Tweeted during the Super Bowl), but maybe not to others.</p><br />
<p>But &#8220;having everything in one unit&#8221; is a little misleading.  You&#8217;ll still need a receiver for surround sound, a set top box for regular TV viewing, and probably a Blu-ray player because although HDX is really good, you just can&#8217;t beat Blu-ray right now.  If that&#8217;s true, and you can get Netflix and Vudu in your Blu-ray player for less than a $300 premium, perhaps VIA is overpriced.</p><br />
<p><strong>Conclusion</strong><br /><br />
Bottom line, we do think Internet Apps are more compelling than 3D.  Will they sell more TVs?  That will probably require a little more education on the part of manufacturers like Vizio.  Something tells us a strange commercial with robot arms throwing stuff in a pit doesn&#8217;t quite convey the power of what the Apps can provide.</p><br />
<p>That said, we&#8217;re still really excited to try them out for ourselves.  We can&#8217;t wait to get our hands on one of these Vizio units to see how it all comes together.</p></div><br />
