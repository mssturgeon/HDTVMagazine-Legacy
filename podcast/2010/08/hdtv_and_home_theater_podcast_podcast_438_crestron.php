<h4>iThing Support</h4>
<p>Crestron fully supports Apple’s iPhone, iPad, and iPod Touch. <a href="http://www.crestron.com/solutions/apple_mac_iphone_ipod_ipad_control/" target="_blank">Crestron Mobile</a>™  keeps you connected to the home or office via the internet. You can  view alarm status, adjust lights and room temperature from anywhere in  the world as long as you have internet connectivity. <a href="http://www.crestron.com/solutions/apple_mac_iphone_ipod_ipad_control/" target="_blank">Crestron Mobile Pro</a>®  provides even greater power and flexibility to control your whole  house, including pre-set audio and lighting scenes, home entertainment  and more. Both apps are compatible with the iPad, iPhone 4, iPhone 3G,  iPhone, and iPod touch.</p>
<h4>Cost</h4>
<p>As you can see the Crestron system is quite impressive and powerful.  This is not just for anyone. You can’t just go to a store buy the gear  and set everything up your self. Crestron integrators are highly  trained  and will work with their clients to define a system that meets  their needs. But in order to get this level of support you can expect to  pay quite a bit of money.</p>
<p>Crestron does not advertise pricing so  its hard to estimate prices. We checked eBay for new Crestron products  to get an idea of what the hardware costs. But this is now where near  what the final price would be since you have to pay someone to install  and configure it. Here are just a few components. The used prices will  be denoted below:</p>
<p>Adagio® Media System AMS-AIP Media System APAD CSSTK 3 AMFM $10,000<br />
Crestron TPMC-8X Isys i/O 8.4 WiFi Touchpanel $1900<br />
Crestron Adagio Audio Server AAS-2 $2000 (Used)<br />
NEW CRESTRON CP2 CONTROL PROCESSOR HOME AUTOMATION $650<br />
Crestron C2N-DAP8RC 7.1 Surround Sound Processor $2100<br />
CRESTRON DVPHD-PRO HIGH DEFINITION VIDEO PROCESSOR $8500<br />
CRESTRON CNX-PVID8X3 CAT5 Video Distribution Switcher $999 (Used)</p>
<p>Remember  that most custom integrators will start to with MSRP or close. You are  not only paying for the product when you buy an item, you are paying  them for their knowledge in selecting the right product for your needs.</p>
<p>In  general Crestron customers don&#8217;t price shop, at least not most of them.  They look for the Integrators they like the most and go with them. They  don&#8217;t have time to research, design, and implement a system.</p>
<h4>Low(er) Cost Solution</h4>
<p>If you really like Crestron, and why wouldn’t you cost not  withstanding, the have a solution that may fit your budget. Crestron has  developed a new line of product called <a href="http://www.crestron.com/solutions/prodigy_affordable_home_automation/" target="_blank">Prodigy</a>.  Again we had to go to eBay for pricing but a 4 ZONE package with 12  lighting controls (6 Dimmers and 6 Switches , 4 audio keypads, ipod  dock, am/fm/ sirius/XM tuners, amps, Touchpanel, Touchpanel Remote and  Thermostat is going for $5700 on eBay. The system is expandable and can  be installed by a somewhat qualified DIYer.</p>
<h4>Final Thoughts</h4>
<p>We all want the coolest smartest house! Its no doubt that with  Crestron you would have just that. Unfortunately, most of us who read  this won’t be able to afford a home automation system that uses Crestron  components. But it sure is something we can dream about for when we  make it big!</p>
