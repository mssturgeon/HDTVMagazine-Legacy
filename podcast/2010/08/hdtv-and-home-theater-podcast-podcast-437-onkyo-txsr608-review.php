<p>If you’ve already upgraded to a receiver and TV with HDMI, you know  how easy it is to setup a home theater these days.  If you haven’t,  you’ll be amazed at the simplicity.  Simply connect one HDMI cable from  your television source (cable/satellite box) to the receiver, another  from your Blu-ray player to the receiver, and one from the receiver to  the TV.  And you’re done.  Of course if you have more sources, you’ll  need a cable for each of those, and you need to connect speakers and a  subwoofer.  But all in all, you’re looking at about 5 to 10 minutes of  wiring.</p>
<p>To setup this particular model, you can use the included  microphone and allow it to run the Audyssey auto-calibration.  It takes a  while, so be patient.  For most people, it’ll get things dialed in  pretty well.  For more advanced users you may want to tweak it after, or  just skip it altogether.  One really convenient feature is that all  on-screen displays, including menus, are available on the HDMI output.   That isn’t always true of the budget units, but it make setup much, much  easier.</p>
<h4>Performance</h4>
<p>As a home theater receiver, this unit performs very, very well.  We  compared it with Braden’s older Denon 3806, which cost quite a bit more  back in its day, and the Onkyo outperformed it in just about every  aspect.  You’d be surprised how much the newer electronics add to the  experience.  Dialog is crisp and very clear, effects are pronounced, not  muddled like you sometimes hear, and the Onkyo really uses the  subwoofer &#8211; so much we actually ended up turning the sub itself down.   Is there such thing as too much sub?</p>
<p>But we didn’t really buy it  to be just another run of the mill 5.1/7.1 receiver.  We bought it for  the 9.1 channel options.  Because the unit has built-in amplification  for 7 channels, with the SR608 you have your choice of how you want to  use the 2 extra speakers.  If you want to go beyond 7.1, and use a 9.1  setup, you’ll need an external amplifier.  If the receiver you’re  replacing with the Onkyo happens to have discrete 5.1 inputs, you could  use it pretty easily to run your extra 2 channels, saving the cost of  buying a new stereo amplifier.</p>
<p>We found all three modes, Pro  Logic IIz, DSX wide and DSX height, to be extremely subtle.  The wide  speakers were tough to place in our room, so we listened to it, but  didn’t find enough benefit from it to justify putting the extra speakers  in.  Watching HDTV there were very few scenes that actually seemed to  take advantage of the two speakers.  Blu-ray movies, which tend to have a  better discrete mix, fared slightly better.  Occasionally we’d hear  something as if it was further off in the distance, but for the most  part, the wide channels didn’t do much for us.</p>
<p>From the wide  speakers, we tried to compare the two height modes, Pro Logic IIz vs.  DSX.  Again, both were very subtle.  We found that with some content the  Dolby processing was better, while with other content content the DSX  seemed to do a better job.  It’s very subjective, but it felt like Dolby  did better with falling objects and like rain or falling rocks while  the DSX did a better job with stuff flying overhead like airplanes and  arrows.  Again, this is really subjective and both effects were quite  subtle.  We struggled to hear anything when using basic HDTV content as  the source.</p>
<p>In addition to the 9.1 surround options, the SR608  also includes Audyssey’s volume levelling technology.  You can combine  Dynamic EQ, which is intended to level out the EQ at lower volume levels  so you don’t lose subtle effects, and Dynamic Volume, the one that  actually keeps volume levels consistent from scene to scene in a movie.   Dynamic Volume automatically includes dynamic EQ, so you don’t have to  dial them both in.  You can run Dynamic Volume in 3 different modes:  Light, Medium and Heavy.  Light worked well to keep things level and not  change the mix too much.  In some cases Medium was perfect, in others  it emphasized surround effects too much and we lost the dialog in the  noise.  The Heavy setting seemed too aggressive for us and we didn’t  enjoy it.</p>
<h4>Odds and ends</h4>
<p>The remote included with the SR608 is fine.  Use a universal remote  and put it in a drawer.  Having the on screen display over HDMI is  awesome.  It doesn’t have a network interface, so you can’t stream music  with it directly, you need an external source, like a Squeezebox, for  that.  It can control an iPod and do Sirius and HD Radio, but only if  you buy extra parts or adapters for them.  It doesn’t have bluetooth  support, nor can you buy an extra bluetooth module to add it.</p>
<h4>Conclusion</h4>
<p>Overall, the Onkyo will meet or exceed most expectations.  It has  enough power to fill just about any average sized home theater, and has  the features you need for serious home theater entertainment.  If you  want to go to 9.1 surround, just to say you have it, the SR608 can make  it happen.  It lacks some of the newer network/digital audio features  were starting to see on receivers, but as a dedicated home theater  receiver, it’s a great choice for the money.</p>
