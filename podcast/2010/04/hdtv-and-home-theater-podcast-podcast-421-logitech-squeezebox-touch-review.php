<h3>Logitech Squeezebox Touch Review</h3>
<p>Sure it&#8217;s the HDTV and  Home Theater Podcast, but we like to dabble a  little in the peripheral  edges of home theater from time to time.  One  such area is whole house  audio.  Braden has a whole house system based  on <a id="dl7s" title="Logitech Squeezebox" href="http://www.htguys.com/shop?id=B000VZL9C2">Logitech Squeezebox</a> devices and their  Squeezbox Server software.  Logitech recently  released a new <a id="gbd0" title="Squeezebox Touch" href="http://www.htguys.com/shop?id=B002LARRDA">Squeezebox Touch</a> player, so of course, we  wanted to try it out.</p>
<h4>Background</h4>
<p>Long time fans of the  show will no doubt remember the original  Squeezbox players.  We  originally reviewed them years ago when they  were made by a company  called Slim Devices, before Logitech bought  them.  The device was cool,  and it can still rock, but by modern  standards it&#8217;s a bit dated.  The  Touch really feels like a 2010 update  of that classic player.</p>
<h4>Specs</h4>
<p>Size  wise, it&#8217;s almost identical to the original player.  It is  about 6&#8243;  wide by roughly 4&#8243; tall.  It will connect to your home network  via WiFi  (802.11) or wired Ethernet (100 Mbps) and has three audio  output  options: Stereo analog (RCA), digital optical, and digital  coax.  It has  a USB port to connect a storage device (more on that  later) and an SD  card slot as well.</p>
<h4>Setup</h4>
<p>In our review of the <a id="ngx6" title="Squeezbox Radio" href="http://www.htguys.com/shop?id=B002LARRDK">Squeezbox Radio</a> on <a id="ll9h" title="Episode 397" href="http://www.htguys.com/podcasts/2009/10/30/podcast-397-logitech-squeezebox-radio-review.html">Episode  397</a>, we went into a little  more detail on how Braden has his  Squeezboxes deployed.  Today we&#8217;ll  focus on the Touch, but no matter  what, you&#8217;ll want a server to house  all your music and control multiple  players so you can have a whole  house system.  That&#8217;s where Squeezebox  Server comes in.  It&#8217;s a free  piece of software that ties it all  together.  For the iTunes lovers out  there, it will import your iTunes  library.</p>
<p>Since we had the  benefit of adding the Touch to an  existing system, it took less than 3  minutes to pull it out of the box,  plug it into the wall and get it  connected to the Squeezebox Server  software.  Another minute or so later  and it was blasting out tunes  synchronized with every other zone in the  house.  You should budget  about 15 to 20 minutes if you need to get the  server software up and  running first &#8211; longer if you have a lot of  music to index.</p>
<h4>The good</h4>
<p>The Squeezebox music system is  incredibly easy to setup and use.   Multiple zones can play in sync, or  each zone can play its own music.   You can use any zone to control any  other zone, or pretty much any  device with a web browser on it.  And it  isn&#8217;t just a local music  player, it can connect to Internet radio  stations, Pandora, and a bunch  of other audio sources like Podcasts.</p>
<p>The  Touch interface is  very easy to use and responsive.  The screen is  bright and vibrant.   When not in use, the Touch can display a few  different clock options,  making it a great alarm clock for your  bedroom.  Yes, it can set alarms  and you can even snooze them.  It has  an ambient light sensor to  automatically adjust display brightness  according to the environment  and an infrared proximity sensor to detect  presence and automatically  wake it from sleep mode.</p>
<p>If you don&#8217;t  want to use it as an alarm  clock or a clock radio, you can use the USB  or SD slots to turn it  into a digital photo frame when it isn&#8217;t in use.   That&#8217;s one of the  coolest features of the Touch.  You typically want to  have music in  every room, but you don&#8217;t want some big eyesore sitting  on a table or a  shelf.  With the Touch, you have a bunch of little  picture frames  around the house that also happen to be your whole house  audio zones.</p>
<h4>The not-so-good</h4>
<p>While the touch screen on  the unit is very bright, responsive and  easy to use, it does leave some  room for improvement in the navigation  area. There are very few  dedicated buttons always present on the  screen.  Those lacking most  noticeably are a power button and a home  button.  If you want to turn it  off quickly, you have to navigate all  the way back to the home screen,  which could be quite a few clicks of  the back button, before the power  button appears.</p>
<p>That pretty  much illustrates why you need a  dedicated home button as well. To be  fair, the remote that comes with it  does include those buttons, but in  our case, since it&#8217;s a touch device,  we&#8217;d really rather put the remote  in a drawer and control the whole  unit from the screen.  After all,  isn&#8217;t it called the &#8216;Touch&#8217;?   Hopefully a firmware update will come out  to address this issue.</p>
<p>The  touch has three audio output  methods, but doesn&#8217;t include a built in  speaker.  In many cases, this  is fine, you run it into a home receiver,  an amplifier or a pair of  powered speakers and you&#8217;re all set.  But in  some cases you just want  the unit itself to play the music.  You don&#8217;t  want the hassle or  unsightliness of speakers and wiring.  This is really  more of something  we thought we should point out.  If you want a unit  with built in  speakers, check out the <a id="a7eb" title="Squeezbox Radio" href="http://www.htguys.com/shop?id=B002LARRDK">Squeezbox Radio</a> or  the <a id="thxt" title="Squeezebox Boom" href="http://www.htguys.com/shop?id=B001DJ64D4">Squeezebox Boom</a>.</p>
<h4>Cost</h4>
<p>And  then there&#8217;s the cost.  We&#8217;ve long been fans of the Squeezebox  audio  system because it represented an inexpensive way to get your  whole house  rockin&#8217; with music.  But at $299 for the player, not  including  speakers, is that still the case?  It&#8217;s certainly still less  expensive  than some alternatives, and has actually stayed pretty  steady.  The  classic Squeezebox v3 had the exact same MSRP, $299, back  in April of  2006.  So 4 years later you&#8217;re getting a much better  product for exactly  the same price.  Not bad.</p>
<h4>Conclusion</h4>
<p>The Squeezebox  Touch is an elegant, inexpensive way to add music to  any room in your  home.  It can disappear as a digital clock or a  digital photo frame and  actually enhance the aesthetic of a room.  For  $299, it&#8217;s absolutely  worth taking a look at.</p>
