<p>Setup was fairly straight forward. We are all HDMI so it was as  simple as connecting power, keyboard, mouse, Ethernet and HDMI to the  Pioneer receiver and turning the thing on. Once you get through the  initial boot-up you are greeted to a Windows 7 desktop. Since the Zino  does not come with a tuner you&#8217;ll have to provide your own. Since its  the same story with the Mac Mini, Ara has an <a title="HD Homerun" href="http://www.htguys.com/shop?id=B0010Y414Q">HD Homerun</a> already  installed on his network. We downloaded the drivers for Windows 7,  scanned for digital channels and were up and running in about 15  minutes. Since we already had the receiver setup up for a Blu-ray player  the entire setup process took about 45 minutes. We literally removed  the Blu-ray player and placed the Zino in its place.</p>
<h3>Use</h3>
<p>We have already reviewed media center so we won&#8217;t be deep diving into  its use. Instead we&#8217;ll focus on what was not available when we did our  original review. The biggest new feature is that this device support  Blu-ray. That&#8217;s the good. The bad is that its not well integrated into  Media Center. When you play a Blu-ray disc PowerDVD is launched and  unlike playing a regular DVD its obvious that it is not Media Center.  The other issue we had was that we repeatedly tried to upgrade Power DVD  from within Media Center to no avail. It wasn&#8217;t until we launched  PowerDVD from the desktop that we could do the upgrade. It seemed like  some of the free software included on the Zino was preventing the  installation from within Media Center.</p>
<p>As far as playback of  Blu-ray movies go, it was OK. We would get stuttering frames every so  often. In general we felt that the hardware was underpowered to support  Blu-ray. DVDs and Backed up DVDs played fine. The latest version of  Media Center does a great job of finding meta data and cover art for  ripped discs that have VIDEO_TS folders in them. It makes the Windows  plug-in &#8220;MyMovies&#8221; unneeded. But for completeness we did download and  install MyMovies. While it include more features than Windows it did not  rock our world. Prior to this version of Windows 7 MyMovies would have  been a requirement. With this version not so much.</p>
<p>TV played  nicely even being upconverted to 1080p. Windows Media Center has a nice  built in tuner/DVR package. There is also a Netflix watch it now feature  that is easy to navigate and use. We were able to add our account and  select movies in a matter of minutes. The picture looked good but Ara  still feels that the best video quality of &#8220;Watch it Now&#8221; is on the Xbox  360 (of course, Braden would argue that it&#8217;s the PS3).</p>
<h3>Audio</h3>
<p>Since we used HDMI we were able to get 5.1 audio out of DVDs, OTA HD  and Blu-ray movies. One thing that dissapointed us was that we could not  get Dolby True HD or DTS Master Audio out of the Blu-ray discs. We  can&#8217;t tell if this is an issue with PowerDVD or the Zino. We&#8217;ve read on  some forums that PowerDVD does not support Dolby True HD. You can get  5.1 out of the Zino without HDMI but you need make sure you upgrade to  the ATI Radeon HD 4330. The audio sounded great but we&#8217;d expect nothing  less with the receiver we were using.</p>
<h3>Picture Quality</h3>
<p>DVD looked nice, ATSC looked even better and as you would imagine  Blu-ray looked the best. But when compared side by side with the Oppo  dedicated Blu-ray player we prefered the image quality of the Oppo.   However, since we were going through our receiver we had and issue with  underscan. We could not figure out a way to get the image to stretch  from side to side and top to botton. There was about an inch of space  all around the picture. There is probably a setting to fix this but we  could not find it. If you have a solution please post it to the comments  section.</p>
<h3>Odds and Ends</h3>
<p>Hard to believe that this computer that has so many features designed  to be used as a HTPC (Dell does not call it a HTPC however) does not  come with a remote control. In fact we couldn&#8217;t find any reference to an  IR Port on the Zino. That means if you really want to use this as a  HTPC you&#8217;ll need to buy a USB remote control. They go for about <a id="lhz5" title="$15 to $30" href="http://www.htguys.com/shop?id=B00224ZDFY">$15 to $30</a>. The Zino  is pretty quiet and it definitely won&#8217;t be heard while watching TV.  However, when everything is off it does make sound. Enough that it could  keep lighter sleepers awake at night. The Zino comes with plenty of  ports for expansion including an eSATA port so that you can add hard  drives to store all your movies.</p>
<h3>Our Recommendation</h3>
<p>The Dell Zino is a good device for basic HTPC use, watching TV (with  and external tuner), ripped movies, music, and photos. But when it comes  to Blu-ray you&#8217;d be better served with a stand alone Blu-ray player or a  more powerful HTPC. Save your money and go for a Zino without Blu-ray  player.</p>
