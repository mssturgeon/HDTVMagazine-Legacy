				<h2>Today&#8217;s Show:</h2>
<h3><strong>Surround Sound &#8211; The New Formats</strong></h3>
<p>We came across an article  at Home Theater Magazine about the various  7.1 speaker configurations  available today.  It got us thinking.  Do  we take the standard 7.1  configuration: 3 in the front, 2 on the sides,  2 in the back, for  granted?  If we could put the speakers anywhere we  wanted to, where  would they go?</p>
<h4><strong>5.1 to 7.1</strong></h4>
<p>Traditional 5.1 surround  sound systems place three speakers in front  of the listening position, a  left speaker, a center speaker and a  right speaker.  The additional 2  speakers were meant to add sound  around you, and were traditionally  placed immediately to your left and  right, maybe slightly behind the  listening position.  The 7.1 speaker  configuration added two more rear  surrounds, they are meant to be  behind you to the left and right.</p>
<h4><strong>Hearing  is Important</strong></h4>
<p>So with 7.1 setups, you have more speakers off to  the sides and  behind you than you do in front of you.  The human ear is  very accurate  at pinpointing sounds when they&#8217;re in front of you, that  accuracy  diminishes quickly as the sound wraps around behind you.  You  may be  off by a couple degrees in front, but as many as 20 degrees  behind.</p>
<p>Couple  that with the fact that there is almost no 7.1  content available  today.  DVDs max out at 5.1, so they&#8217;re off the  table.  According to  the website <a id="yc5g" title="blu-raystats.com" href="http://www.blu-raystats.com/Stats/Stats.php">blu-raystats.com</a>,  roughly 7% of the  available discs include a 7.1 soundtrack, only 162  of almost 2300. So if  you can&#8217;t really hear it, and there really isn&#8217;t  anything to hear  anyways, how important are those extra 2 channels?   That&#8217;s exactly what  the folks at Dolby and Audyssey would like you to  think about.</p>
<h4><strong>New  Options</strong></h4>
<h4><strong>Dolby Pro Logic IIz</strong></h4>
<p>We&#8217;ve mentioned Dolby&#8217;s new <a id="htcu" title="Pro Logic IIz" href="http://www.dolby.com/consumer/understand/playback/dolby-pro-logic-iiz.html">Pro  Logic IIz</a> format before.  The  main takeaway is that it adds height  channels to your home theater.  To  do that they move 2 of your 7.1  speakers from the back to the front, and  raise them up above the  listening position, pointed down.  Obviously  it&#8217;s easier to run a few  more wires in the front than it is to run them  all the way to the rear  of the room, so that&#8217;s one plus right away.</p>
<p>Since  there aren&#8217;t  any movies mixed in IIz, the Pro Logic technology fills  those two  height speakers with ambient sounds from other channels in the  track.   Pro Logic can create the IIz effect from a 2 or 5.1 channel  source.   Eventually it will support a 9.1 configuration, the standard  7.1 plus  the two height speakers.  The results of the Pro Logic  processing are  mixed.  A reviewer from <a id="c83." title="Home Entertainment Magazine" href="http://www.hemagazine.com/Dolby_Pro_Logic_IIz_vs_Audyssey_DSX">Home  Entertainment  Magazine</a> loved the effect, whereas the reviewers at <a id="xw6h" title="CNET" href="http://news.cnet.com/8301-17938_105-10230238-1.html">CNET</a> were  underwhelmed.</p>
<h4><strong>Audyssey DSX</strong></h4>
<p>Another  entrant in the modified 7.1 arena is <a id="nsi6" title="Audyssey's DSX" href="http://www.audyssey.com/technology/dsx.html">Audyssey&#8217;s DSX</a> technology.  In addition to  the height channels, DSX adds additional  width channels to the front of  the room.  A additional speaker is  placed on each side of the room,  wider than the existing front left and  front right speakers.  Audyssey  believes the extra width is more  important than height, so they&#8217;d tell  you to add those first.</p>
<p>Like  Dolby IIz, there isn&#8217;t any content  encoded to take advantage of the  new channels, either width or height,  available in DSX so you have to  rely on Audyssey processing to fill them  with sound.  We haven&#8217;t  reconfigured our setups yet, so we can&#8217;t  comment on how well it works.   In addition to the 7.1 with new width or  height setups DSX will  support 9.1 to use both, or either in conjunction  with a standard 7.1  system, and of course there will be an 11.1 system  that has them all.   DSX requires a 5.1 source track.</p>
<h4><strong>Our  Thoughts</strong></h4>
<p>This is a rare dilemma.  First off, we can&#8217;t really hear  that stuff  behind us very well, so it makes sense to move the speakers  up to the  front of the room.  Secondly, there really isn&#8217;t much content  taking  advantage of those speakers, so it makes sense to move the  speakers up  to the front of the room.  That said, there&#8217;s absolutely  nothing  encoded in IIz or DSX, so you have to rely on the processing to  get  anything from those speakers.  How well it works is something your  ears  will have to tell you.</p>
<p>We don&#8217;t think content will be coming   out anytime soon that supports the new height or width channels.  Movie   theaters are reluctant to add new speakers and new processing, so the   cinema mixes won&#8217;t include them.  If the cinema mixes don&#8217;t include   them, odds are the home mixes won&#8217;t either.  For the short term, it&#8217;s   really up to you: leave the speakers behind you and enjoy the 7% of   movies that use them, or move them to the front and hope the processing   works well enough to make a difference.</p>
<p>But in dream land, where   would we put the speakers?  We&#8217;ve always liked the idea of multiple   center channel speakers like Sony uses in <a id="kl1z" title="SDDS" href="http://www.sdds.com/">SDDS</a>.  Screens are getting so big these   days, it make sense to put dialog on either side.  We&#8217;d use 2 in the   center.  The we&#8217;d take the 7th speaker, the one we have left over, and   finally implement the often whispered about &#8220;god&#8221; speaker.  Mount it   right above your head.  That really gives you a sense of height and the   feeling that things are falling on you or flying over you.</p>
<p>That,   of course, won&#8217;t happen anytime in the foreseeable future, but that&#8217;s   how we&#8217;d do it.</p>
