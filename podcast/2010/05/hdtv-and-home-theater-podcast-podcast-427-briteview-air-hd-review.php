<p>Looking  around, however, you may come across the <a id="cnp9" title="brite-View  Air  HD" href="http://brite-view.com/air_hd.php">brite-View Air HD</a>.   The first thing you&#8217;ll notice is that prices  are dropping.  It has an  MSRP of $399 US, but it is on sale right now  for only $279.99.  The  last wireless HD solution we tried, the <a id="pbdt" title="Gefen  Wireless HDMI Adapter" href="http://www.htguys.com/podcasts/2009/3/24/gefen-wireless-hdmi-adapter-ext-whdmi-review-podcast-365.html">Gefen  Wireless HDMI  Adapter</a>, was selling for $999 at the time.  We had  decent success  with the Gefen unit, but our hopes were high for the  brite-View.</p>
<h4><strong>Setup</strong></h4>
<p>Setting  up the Air HD is trivial.  You plug your source equipment  into the  transmitter, plug your display device in the receiver, and  you&#8217;re done.   The two units find each other automatically, link up and  work with  minimal intervention.  You can transmit IR over the same link  using the  included IR sensor plugged into the receiver and IR blasters  plugged  into the transmitter.</p>
<h4><strong>Specs</strong></h4>
<p>According to the brite-View  website, the unit supports:</p>
<ul>
<li>Uncompressed HD quality audio  and video</li>
<li>Up to 1080i@60Hz &amp; 1080p@24Hz HD picture  quality/30Hz HD  quality</li>
<li>Less than 1ms latency for playing video  game console</li>
<li>Long transmission distance: 65 feet with Line of  Sight, 32 feet  without</li>
<li>Multiple inputs: 2 HDMI, 2 Component  &amp; Composite</li>
</ul>
<h4><strong>Performance</strong></h4>
<p>We tested using  Blu-ray, HD-DVD and HDTV.  With a good signal, the  video quality was  perfect.  We couldn&#8217;t tell the difference between the  HDMI cable and the  Air HD.  That said, we couldn&#8217;t get a good signal  at 65 feet.  At that  distance, even with Line of Sight, there was some  noise in the picture  and some strange audio artifacts.</p>
<p>At first,  the picture was  pretty rough even at 50 feet, but the Air HD allows  you to switch  channels in case other equipment in your home is causing  interference.   After switching the channel we were able to get perfect  transmission at  around 50 feet with Line of Sight and 27ish feet  without.  In addition,  IR commands were transferred instantly.  There  was no perceptible delay  with button presses.</p>
<h4><strong>Value</strong></h4>
<p>At $999 a wireless HDMI unit  would need to blow you away to make it  worth it, but at $279, it enters  the realm of possibility for many more  of us.  A 50 foot HDMI cable  will set you back about <a id="ekap" title="$15" href="http://www.htguys.com/shop?id=B000QKKAPE">$15</a>,  to  upgrade to an in-wall rated cable will cost closer to <a id="jd0v" title="$30" href="http://www.htguys.com/shop?id=B002HKGUT6">$30</a>.    At that point it really depends on how much wall damage and repair work   you have to do to exceed the total $279 cost.</p>
<p>Keep in mind that   the Air HD only supports up to 24 frames per second in 1080p.  That   means it won&#8217;t allow you to run 1080p/60 from a Blu-ray disc and won&#8217;t   support the 120 fps you&#8217;d need to get 3D.  If your primary use for the   projector is TV, since the ATSC spec only goes up to 1080i/60 and   1080p/30, you won&#8217;t miss a thing.  If you want support for the latest   and greatest Blu-ray has to offer, you may want to go with a fixed cable   solution, even if it&#8217;s a bit more expensive and less convenient.</p>
<h4><strong>Conclusion</strong></h4>
<p>There  are so many more uses for the Air HD than just front  projectors.  It&#8217;ll  work really well for backyard and outdoor theaters.   You could use it  to stream TV to a room in the house that doesn&#8217;t have  Coax, like a  bathroom, workshop or garage.  If you have a TV that&#8217;s  constantly moving  based on what&#8217;s happening at home, you&#8217;d only ever  need to plug it into  the wall to get great quality HDTV on it.</p>
<p>At  $279 we&#8217;ll leave it  up to your imagination to decide the best use for  it, but in our tests  it worked really well.  We didn&#8217;t get it to live  up exactly to the full  advertised specs, but when the signal was solid,  the audio and video  were solid and it was a cinch to get setup.</p>
