<p><a href="http://www.life-ware.com/products/lifecontroller.php" target="_blank"><em>Life|Controller</em></a> &#8211; The Life|Controller is a  computer with embedded version of Windows XP. This Life|Controller comes  with 8 RS-232 ports for support of third party hardware and is  available in a rack mount or desktop version. The Life|Controller is the  brains behind your home automation system</p>
<p><a href="http://www.life-ware.com/products/lifelink.php" target="_blank"><em>Life|Link</em></a> &#8211; converts a home automation controller&#8217;s programming interface (such  as a security system) or a device (such as a light or audio switcher)  into a Web Services device and implements it via Ethernet connection to a  network.</p>
<p><a href="http://www.life-ware.com/products/lifemedia.php" target="_blank"><em>Life|Media</em></a> &#8211; If you go the Life|Ware route you have an option to use their Media  Server called the Life|Media. Essentially its a Windows 7 box that is  designed for AV use. The unit comes with a DVD drive, ATSC tuner,  CableCard Slot, and Dolby Digital Decoding.</p>
<p><a href="http://www.life-ware.com/products/lifevision.php" target="_blank"><em>Life|Vision</em></a> &#8211; A distribution solution for digital and analog television,  Life|vision™ offers instant access to television entertainment anywhere  in the home via Life|point® touch panels. Surf up to four channels  simultaneously just by tapping on the stream that grabs your interest.</p>
<p>Life|ware  installs are easy for the Integrator, according to Michael McNamee of <a href="http://www.securedgenetworks.com/" target="_blank">Secure Edge  Networks</a>, a Life|Ware Integrator, because its easy to create  templates and do cookie cutter installs. Michael explained that other  automation solutions require complicated programming even when the rooms  are very similar. According to McNamee, technically savvy consumers can  do their own installations but from what we can tell, if you don’t  understand basic programming its probably something that’s better left  to a professional.</p>
<h4>Cost</h4>
<p>Pricing will vary but for a typical home, say 2500 square feet you  can count on equipment costs of $10K if you use Life|Ware servers and  controllers. Cut it in half if you use your own gear. You still will  need to buy light switches, thermostats, bridges, etc. Programming will  run you about $3000 in addition to the gear.</p>
<p>For that $8K to $13K  you will have a completely automated home that will be the envy of your  friends. While Life|Ware costs more than Insteon it provides a bit more  polish and does it for less than higher end systems out there.</p>
