&#8220;<em>ivi,   Inc., today releases its revolutionary live television application   enabling anyone with an Internet connection to “cut the cord” and watch   live broadcast television anywhere in the world, anytime. The   easy-to-use, over-the-top (OTT), online cable system, is the first   traditional television experience available on the Internet.</p>
<p>Upon   launch, ivi offers more content than Hulu and a 30 day free trial to   watch major broadcast channels including ABC, NBC, CBS, Fox, The CW,   PBS, and others from a growing number of local affiliates, all available   via a downloadable app at ivi&#8217;s website,</em> <a href="http://www.ivi.tv/"><em> ivi.tv</em></a><em>.</em>&#8220;</p>
<p>The   site bills itself as an online cable company, so you aren’t exactly   cutting the cord, but you are saving quite a bit of money.  The basic   service costs only $4.99 per month.  You can upgrade to the premium   service, called ivi Pro, for only 99 cents more per month.  The Pro   service give you DVR functionality, allowing you to record, rewind,   fast-forward, pause, and the ability to access additional premium and   PPV content for a nominal charge.</p>
<p>Through  ivi you can currently  access 26 different live TV channels, including  ABC, NBC, CBS, FOX and  CW affiliates in New York and Seattle.  They also  have channels like  PBS, Univision, Telemundo, and Universal Sports.   It’s basically like  having a SlingBox installed in New York and Seattle  that you can access  whenever you want.</p>
<h4>How do they make it work?</h4>
<p>According to the company:<br />
&#8220;<em>ivi  operates in good faith and  intends to help broadcasters and cable  operators realize new revenue  streams by making TV more accessible to  more people, anytime and  anywhere. Every single broadcaster gets paid.  ivi, Inc. fills out the  &#8220;United States Copyright Office Statement of  Account Form SA1-2&#8243; in  accordance to US Copyright Law, and that clearly  calculates royalty  payments for retransmissions.</p>
<p>An  important distinction to keep  in mind on the legal side is the historic  EchoStar precedent. Cable and  the broadcasters battled EchoStar and  fought the satellite erosion of  their hallowed ground.  They lost that  battle.  As history repeats  itself, they will lose this one as well, we  believe.</em>&#8220;</p>
<h4>So how good is it?</h4>
<p>The  service isn’t purely web based, you install an application on  your  computer to watch TV.  The application runs on Windows, Mac and  Linux.   It’s easy enough to install and quite easy to interact with.  The guide  provides much of the same functionality you get from a Cable  or  Satellite DVR.  Overall installation and usage are fairly trivial.</p>
<p>Quality   still leaves something to be desired.  Most of the content looks like   the old school streaming content from days gone by.  There’s lots of   macroblocking and quite often audio sync issues.  Although we’re sure   they have high definition in New York and Seattle, we’re yet to see it   in ivi.tv.  Which also means we’re yet to get any 5.1 surround sound.    Overall quality issues left us less than satisfied.</p>
<p>Lastly,   perhaps the biggest drawback is that the application is purely computer   based for now.  In an age where Netflix is available on every consumer   electronics device imaginable, we’re rapidly moving away from the need   to have a computer in your family room.  With that in mind, <a href="http://ivi.tv/">ivi.tv</a> really needs to get off the computer and into home theater devices.  They know this and claim to be working on it.</p>
<h4>Conclusion</h4>
<p>Although we wouldn’t give up high definition for the sub-par quality of <a href="http://ivi.tv/">ivi.tv</a> just yet, we are quite intrigued by the service.  Assuming they can fix   the video issues and give us something akin to what we’re used to from   Hulu or Netflix, the idea of paying $5 a month for TV service sounds   great.  Of course a set top box of some sort would need to be in the   mix.  They’d also need to beef up the available channels to include   stuff like ESPN and Fox Sports.  Monday Night Football simply isn’t   optional.</p>
