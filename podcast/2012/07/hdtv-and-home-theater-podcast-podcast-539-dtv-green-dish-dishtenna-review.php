<h4>The Dishtenna</h4>
<p>The DTV Green Dish, or Dishtenna, is a small, digital broadcast antenna that resembles a satellite dish for use with DirecTV or Dish Network. It is much smaller than other antennas that claim a similar range. The website claims the Distenna will pick up broadcasts that are within a 75 &#8211; 100 mile radius. The antenna costs $299, which includes professional installation. It is available in four different colors to match your home (Army Green, Grey, Sand or White).</p>
<h4>Installation</h4>
<p>Even if you consider yourself an enthusiast, you’ll want to have the Dishtenna professionally installed. An installer will have the right gear to make sure the unit is pointed exactly right for the highest possible signal. Both Braden and Ara had to have their demo units professionally installed to get the most out of them. The Dishtenna can’t simply be pointed in the direction of the broadcast towers. In Braden’s case, the antenna is actually pointed west of the broadcast tower to get the best signal.</p>
<p>Another installation issue we ran across was the the cables we had run from the antennas on our roofs to the inside of our homes didn’t work with the Dishtenna and needed to be replaced. The professional installer should already know the specs of the cable you need to get the signal all the way into your home. Braden’s first cable didn’t work at all, the second and third both transmitted most of, but not all of, the channels coming in on the antenna. By the fourth cable, everything was just fine. Ara had the same issue, but his installer had learned the cable specs and got him set up on day one.</p>
<h4>Use</h4>
<p>Using the Dishtenna is no different from any other over-the-air antenna you may have used or could be familiar with. One the installation is complete, you run the signal into your TV or other tuner device, let it scan for channels, and you’re off to the races. The website claims that one Dishtenna can be split out to up to 8 different televisions. We didn’t get a chance to test this limit, but if you have more than 8, simply invest in another Dishtenna for the rest of them.</p>
<h4>Performance</h4>
<p>Where the HT Guys live is quite far from our local Los Angeles broadcast towers on Mount Wilson. In Braden’s case, <a href="http://antennaweb.org/">antennaweb.org</a> reports that there is no known antenna capable of picking up any channels over the air. The exact quote is: “Due to factors such as terrain and distance to broadcasting towers, signal strength calculations have predicted no television stations may be reliably received at this location.” A quick check at <a href="http://www.tvfool.com/">tvfool.com</a> shows that most stations are beyond reach, with those that are available being listed in red (barely attainable). Ara previously had to put up a  Yagi Antenna with a 9 foot boom to get his over-the-air channels to work.</p>
<p>Once the professional installation was done at both HT Guys locations, we were shocked and amazed to see how many channels we were picking up. At Braden’s house we were able to get all the red stations from <a href="http://www.tvfool.com/">tvfool.com</a> as well as a couple of the gray ones.</p>
<p>Ara had some geographical issues that made reception difficult. He had a small hill with a house directly in the line of sight of the towers. Still with this limitation the Distenna was able to pick up most of the UHF channels. But the main reason Ara was interested in the antenna was to pick up ABC and Fox which reverted to VHF after the analog shutdown. The installer was able to tweak the antenna to pick up ABC (VHF 7) which shocked Ara, but that caused many of the other channels to disappear.</p>
<p>Feeling that he would never get all the major networks regardless of technology in a last ditch effort, Ara swung the Dishtenna around almost 180 degrees towards the sunny and beautiful city of San Diego more than 90 miles away! Bam! All the San Diego channels, including one with a transmitter in Mexico, came in. Here’s the weird thing, the Dishtenna started picking up LA ABC and Fox! Not all the time but the 9 foot Yagi never picked them up ever!</p>
<p>Ara did feel bad about losing his LA channels but then he thought the two antennas are pointing in different directions why not combine them. For that he used a <a href="http://www.amazon.com/gp/product/B00006JPEA?ie=UTF8&amp;camp=213733&amp;creative=393177&amp;creativeASIN=B00006JPEA&amp;linkCode=shr&amp;tag=hdtvandhometh-20&amp;redirect=true&amp;ref_=oh_details_o02_s00_i00">Channel Plus 2512 DC + IR Passing 2-Way Splitter/Combiner</a> it goes for about $10. And now Ara gets San Diego and LA OTA channels</p>
<p>The last install detail for Ara is that he runs the output of the splitter/combiner into a 4-way splitter that feeds his HD Homerun (two tuners), Slingbox, and Panasonic Plasma TV.</p>
<p>This performance only comes after a couple hours of getting the antennas installed and replacing the cables running into the house. But once all the hard work is done, you can sit back and watch one of hundreds of different stations (if you like multi-cast stations).</p>
<h4>Conclusion</h4>
<p>We were skeptical about how well the Dishtenna would work for us and were amazed at how well it exceeded our expectations. The professional installation is a must because the unit tends to be a bit fussy if you don’t have it set up just right. If you’re looking for a way to get free over-the-air television without installing a 9 foot antenna on your roof, the dishtenna could actually do the job for you.  It did for us.</p>
