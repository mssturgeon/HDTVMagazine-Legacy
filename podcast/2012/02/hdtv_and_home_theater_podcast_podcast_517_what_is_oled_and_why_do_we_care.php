<h3>What is OLED and why do we care?</h3>
<p>One of the big hits at CES this year were the Samsung and LG OLED displays. Sure we’ve seen OLED TVs in the past, but they were 55” screens this year, and they looked great. But why all the hype? Why do we even see references to AMOLED in cell phone commercials? Is OLED really that big of a deal?</p>
<h4>What is it?</h4>
<p>We’ve talked about this before, but a quick refresher might be in order. OLED stands for Organic Light-Emitting Diode. It is an emissive display technology meaning that, like plasma and CRT, it doesn’t require a light source. Instead the organic compound itself is actually a semiconductor that will emit light in response to an electric current.</p>
<p>We talk about OLED so much that we tend to forget that it is a variety of LED, the same acronym/technology used to light the latest and greatest generation of LCD displays. So what makes the organic variety so much better than the ones used in LCD TVs? It’s the fact that the OLED combines the functions of the LED and the LCD into one. It is both the light source and the pixel itself (color, intensity, etc.).</p>
<p>Each OLED is actually a sandwich of several different layers of materials. The color of light produced by an OLED depends on the material used in the emissive layer. By arranging the organic films when the screen is being produced, manufacturers can create OLED groupings to form pixels for color displays. The intensity of each pixel is determined by the amount of electrical current passed into it.</p>
<h4>Advantages and Disadvantages over LCD</h4>
<p>The main advantage of OLED over LCD it that in an OLED display, each pixel produces its own light. If a pixel should go completely dark, or totally black, the display can achieve that by not applying any electrical current to it. With LCD the best you can do is dim a portion of the screen to make some areas darker (local dimming), but you can’t turn off the light source for an individual pixel. As far as contrast goes, OLED is much better.</p>
<p>One often quoted advantage that OLED has over LCD is thickness, or perhaps thinness in this case. Because the OLED combines the function of the LCD and the light source, it can be much thinner. Until the TV can be rolled up, it’s going to be mounted on a wall somewhere. Whether it comes off the wall one inch or one centimeter probably won’t make too much difference in your overall home theater viewing experience. This “advantage” probably won’t change your life too much.</p>
<p>The biggest debate about OLED and its viability in the market is cost. Right now OLED TVs cost much more to manufacture that LCD for two reasons. First, the fabrication of the substrate itself is costlier right now. And secondly, LCD has a tremendous head start in economies of scale. There are many LCD plants around the world cranking out thousands of LCD screens. It will take quite an investment to match that capacity for OLED displays. On the other hand, in theory OLED TVs will be able to be manufactured with a technology as simple as an inkjet printer. If that can scale, the TVs could be quite cheap.</p>
<h4>Advantages and Disadvantages over Plasma</h4>
<p>If the biggest advantage OLED has over LCD is the fact that it is emissive and can produce dramatically better contrast ratios, what advantage does OLED have over plasma, which is also an emissive technology? Theoretically, OLED will offer advantages in color reproduction and contrast and brightness because the organic (carbon based) materials are easier to manipulate that the noble gasses used in plasmas. Both technologies will be somewhat matched in terms of refresh rates and viewing angles.</p>
<p>The real killer for plasma will be energy efficiency. Although plasma manufacturers have been hard at work to optimize their screens and make them much more energy conscious, it is believed OLED displays might be the most energy efficient of all display technologies when they finally make it to store shelves. They’ll need to be much more efficient, we’re talking thousands of dollars a year, to justify the early price premium, though.</p>
<h4>Other Considerations</h4>
<p>There main factor really hindering the mass release of OLED TVs into the market is the color blue. You could say that the continued success of LCD and Plasma has been brought to you by the color blue and the number 14,000. That’s the number of hours a blue OLED has before it drops to half brightness. That is well below the 25,000-40,000 hours you expect to get from and LCD or Plasma. The blue material also degrades more rapidly, impacting color balance as much as brightness.</p>
<h4>Conclusion</h4>
<p>From what we’ve seen, OLED looks amazing. From what we can gather, it could be the best looking display technology, slightly edging out plasma in color and contrast, and also the most energy efficient, slightly edging out LED LCD. If the theory that they can be made by inkjet printers becomes reality, they could be the cheapest display as well. Who knows, in the future you might be able to go to your local printer and have them crank out a new screen for you that’s just the exact right size to fit in that niche or cabinet you’ve got.</p>
