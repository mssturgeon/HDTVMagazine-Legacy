<p>The first thing you notice when you open the box is the beautiful fit and finish of the subwoofer. It has a high WAF. It comes in two finishes, charcoal black vinyl or for $30 more you can get a polished piano black finish that matches most TVs made in the past few years. The next thing is the size, it measures a little more than a cubic foot. That means you can easily find a place for the subwoofer to fit in your family room. We placed it just to the left of the TV in the front of the room a few inches from the wall. We reran the calibration on the Harman-Kardon 2650 and began a three week listening test.</p>
<h4>Performance</h4>
<p>During the three weeks we listened to movies, television, and music. The SB12 did a great job with all of them. What really impressed us was how good it sounded even at low levels. You still had feel that a subwoofer was in the room but without overpowering everything else. This is especially good if you have people in the house that are sleeping or you live in an apartment with neighbors above or below you. Make no mistake however, when you turn up the volume on the sub it will rattle your walls.</p>
<p>We decided to put the SB12 through its paces with the train crash scene in Super 8 and the final boxing match in Real Steel.  In Real Steel when the champ jumps into the ring the thud the subwoofer makes goes through your body and into the bone. You can feel each crushing punch as the robots fight. You begin to want the robots to move around so you can feel their footsteps reverberate through the room. In Super 8 the explosions were quite deep and loud. The SB12 put you right in the middle of the action. We ended up watching the scene twice!</p>
<p>Music was a big surprise for us. We have listened to a few subwoofers that muddy everything else. Not so with the SB12. We found the bass deep and crisp. Even in tracks that don’t have that real deep bass tone. Some audio tracks are about the booming bass others like classical music are about all the instruments. The SB12 added enough bass so you could enjoy it but not so much that in overpowered the rest of the instruments. However, if you want more of that deep penetrating sound, you can always turn up the volume. Even at higher levels we found the bass was clear but we recommend that for movies. Somehow watching the news is still not good even with an awesome sounding subwoofer.</p>
<h4>Conclusion</h4>
<p>If you are ready to improve the subwoofer that came with your HTIB and move into a more mid-tier unit without breaking the bank, or if you want big sound from a subwoofer that doesn’t take up too much space, the SVS SB12-NSD should be high on your list. The deep clean bass the SB12 produces will improve the listening experience of just about anything you listen to!</p>
