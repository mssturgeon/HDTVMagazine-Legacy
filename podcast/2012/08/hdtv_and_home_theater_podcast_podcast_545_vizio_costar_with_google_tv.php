<h3>Review: Vizio Co-Star with Google TV</h3>
<p>The Vizio Co-Star may have the Logitech Revue to thank for the uphill battle it faces in convincing consumers that Google TV is the right choice for their living room. When we<a href="http://www.htguys.com/podcasts/2010/11/12/podcast-452-logitech-revue-and-google-tv.html">reviewed the Revue</a> almost two years ago, there were some aspects of it we really liked. But it never quite caught on with the masses. Vizio is hoping that the Co-Star can change expectations; and at a price of only $99, it sure is a lot easier for many of us to at least check it out.</p>
<p>&nbsp;</p>
<h4>What is Google TV</h4>
<p>Originally, Google TV was a mash-up of search, web based content, apps and live video from your DVR or set top box. It still is. Recent incarnations makes the interface more intuitive and easier to use that when it first came out, but it is basically the same functionality under the covers. Google TV lets you search across every channel in your television, local apps, and the Internet to find exactly what you are looking for. It combines the power of applications like Amazon, Twitter, Netflix, and many others with the Internet to enhance how you watch TV. You even get a full browser for surfing the web.</p>
<p>&nbsp;</p>
<h4>About the Co-Star</h4>
<p>The Vizio Co-Star is a small box roughly the same size as an Apple TV or a Roku. You connect your DVR to it in the HDMI input and run the HDMI output to your TV or AVR. Other than the live video integration, it is quite similar to all the other streaming options out there. With a retail price of $99, it plays in the same ballpark as well. Like most of the others, you can connect it to the Internet and your local network with a wired Ethernet connection or using WiFi.</p>
<p>&nbsp;</p>
<h4>Setup and Use</h4>
<p>Setting up the Co-Star is quite trivial, but it does feel like it drags on for an extended amount of time. First you do some small tweaks like screen size and such, then you log into your Google account for access to everything you have stored in Google’s cloud. Then you go through the somewhat tedious process of adding all your devices. The Co-Star wants to be the one box and remote that will control your whole theater, so you add each device, TV, Receiver, DVR, etc. one by one. We lost some hair in this process. After that you get it on your network so it can download and install an update and if you’re still awake, you should be ready to watch something amazing.</p>
<p>Using the Co-Star should be very, very easy. Unfortunately we found it to be the exact opposite. The interface itself is quite intuitive and simple to navigate. The problem is getting the interface to respond to anything you do. It is just sooo slow and sluggish much of the time.  Often a button press on the remote takes so long to respond, we didn’t think anything happened, so we hit it again, then a few more buttons, and so on. Eventually the Co-Star would respond and all those queued up commands would fire, causing it to do a bunch of things we didn’t really want.</p>
<p>To make matters worse, (we might have a bad unit, but) ours won’t playback any sound at all. No sound from live TV using the Dish DVR, no sound from Netflix, no sound from Amazon, just peaceful silence. We tried to become super skilled at the art of lipreading, but were unsuccessful. If we connected the DVR directly to the Receiver, sound was restored. Somehow the Co-Star was gobbling up all those wonderful digital audio bits and not letting them go. This produced, let’s just say, a less than ideal viewing experience.</p>
<p>The Co-Star has most of the usual suspects available as apps: Amazon, Netflix, YouTube, etc. We couldn’t locate a Hulu Plus app and the Hulu.com sight blocked access to videos when we browsed to it with the standard Chrome browser. It does include the OnLive game app, which would be cool if OnLive hadn’t just <a href="http://articles.chicagotribune.com/2012-08-20/business/sns-rt-us-onlive-restructuringbre87j0w9-20120820_1_onlive-ceo-steve-perlman-gaikai">laid off half their staff</a> last week. Other than that, there’s not much to note in the apps department.</p>
<p>If you can get past the sluggish interface and the lack of audio, is the Co-Star worth the $99 price tag? Probably not. For $99 there are so many options available to you that will function better out of the box. The one big differentiator that the Co-Star has is the ability to integrate live TV into the mix, so you don’t have to switch between devices and inputs if you want to jump between TV, an app or a website. But that convenience factor isn’t enough to outweigh the sub-par user experience.</p>
<p>&nbsp;</p>
<h4>Remote</h4>
<p>You might also think that one saving grace for the Co-Star is the super cool remote that features all your standard remote buttons plus a track pad on one side and a full qwerty keyboard on the back side, but we weren’t impressed. The idea is excellent, and having a full keyboard comes in very handy at times, but having buttons on both sides of the remote makes it quite challenging to use. We would inevitably hit a button on the bottom of the remote when we squeezed it to press something on the top, frustrating our user experience even more. Eventually we adopted the Apple “just hold it a different way” mentality and were able to get it to work &#8211; most of the time.</p>
<p>&nbsp;</p>
<h4>Conclusion</h4>
<p>We aren’t ready to put the nail in the Google TV coffin just yet, but after 2 devices that have underwhelmed us and the general populus, things aren’t looking too good.  The price tag is close to the competition, but too close to make it a no-brainer decision. If Google decided to give them away to try to sell you more movies, music and apps from the Google Play market, we might have a different opinion. People tend to be more forgiving of a free product. But at the same price as an Apple TV, you expect it to perform as well or better. It simply doesn’t.</p>
