<p>We love looking for speakers that make whole house audio simple and provide high quality sound. There are plenty of choices out there, but few can fill a large room with sound and deep bass all from a package that measures 10.75&#8243; (27cm) x 7&#8243; (18cm) x 7.75&#8243; (20cm). We are talking about the Audioengine A5+ (<a href="http://www.htguys.com/shop?id=B005OA3BSY">Buy Now $399</a>) powered speakers.</p>
<h4>Features</h4>
<ul>
<li>Built-in power amplifiers, 50 watt per channel RMS</li>
<li>Compatible with any computer (Mac or PC)</li>
<li>Custom Kevlar woofers and silk tweeters</li>
<li>Improved thermal management</li>
<li>Remote control, 1/8&#8243; and RCA inputs, USB power, all cables included</li>
