<p>The speakers look fantastic and are built well. They look beautiful in full view but are small enough to be put almost anywhere so hiding them is easy. The A5+ comes in three finishes, Satin Black, Hi-Gloss White and Solid Carbonized Bamboo. The Bamboo option will run you an additional $70. The left speaker, the one with the amplifier in it weighs in at 15.4 lbs (7 kg) and has a hefty heat sink on the back. The right speaker is only 9.6 lbs (4.4 kg) and simply has speaker wire connections on back.</p>
<p>The left speaker also has a USB port for charging your portable media player if that’s what you have connected to the speakers. Missing, however, is the AC power plug that made using an Airport Express so convenient in the original A5s. Not a big deal to overcome but it was a nice feature on the older model. There is also a volume control and an IR port for the remote control on the left speaker.</p>
<p>If you plan on using the remote make sure the left speaker is visible so it can see the IR commands. The remote is basic and provides: Sleep, Mute, Volume Up and Down functionality. In our case we set the volume and then used the iPhone volume control.</p>
<h4>Setup</h4>
<p>The A5+ speakers are trivial to setup and start using. Connect the left speaker to power and a sound source, either by a 3.5 mm stereo connector or left and right RCA cable, then connect the right speaker to the left speaker with regular speaker wire and you’re done! All the cables you need are included in the box so that you are literally listening to your new speakers in minutes! For our testing we connected the speakers to an Apple Airport Express and sent them music from the iPad, iPhone, and iTunes. You can connect any source to these speakers including a Sonos amp if you have one.</p>
<h4>Sound</h4>
<p>The sound was fantastic. Rich bass and nice highs. Midrange was good but almost get lost with the low end with some content. We listened to classical, rock and pop music. Everything we played sounded great. Ara’s wife even commented on how good everything sounded. And it will only get better. The speakers need to be broken in. We’ll try to revisit the listening test after we have a few hundred hours on the speakers.</p>
<p>We were amazed at how good the low end sounded on the original A5. The new A5+ keeps that great bass but cleans it up a bit. If you like the deep bombastic lows, like I (Ara) do, you will love these speakers! We don’t know if you are a fan of the movie “Desperado” with Antonio Banderes, but that movie has an excellent soundtrack. Much of our listening was done with it. It has intricate guitar work both acoustic and electric that really comes through with these  speakers. There is rock, blues, and mariachi as well. Everything sounded crisp, shiny, and deep!</p>
<h4>Conclusion</h4>
<p>The Audioengine A5+ is an excellent follow on to original A5s. Their rich deep bass and shimmering highs bring new life to your music library. At $400, the A5+ may be a bit on the expensive side for some, but for those who want to fill a large room with music they’re just the ticket!</p>
