<h4>Setup</h4>
<p>Setup couldn’t have been easier. Plug in the Roku stick, power, and turn it on. Well there are a few more steps than that. You have to wait about a minute for the stick to boot up and then you need to connect to a wireless network so you can update the firmware. The projector even supports the 5GHz frequency so you can have a better experience if your network supports it. Once the firmware update is complete you either sign into your current Roku account or create one. Then you add channels and you are good to go! The whole process took about twenty minutes.</p>
<p>There are minimal user settings you can make to the projector. You can put the lamp into eco mode which extends the battery life but dims the output. Use this when its dark and you want max use from your projector. You can invert the image and select a softer or sharper focus and that’s about it. There is a focus wheel on the outside of the projector as well.</p>
<h4>Performance</h4>
<p>The DLP based 3M streaming projector will not compete with any full sized projector so don’t think that you can have a home theater for $300. But what it can do is project a large image at decent quality that is perfect for the traveler, dorm dweller, or family that wants to have a big screen movie night.</p>
<p>We watched movies from our Netflix queue and were pleasantly surprised at how good it looked in a darkened room. The projector is rated at 60 lumens so don’t expect much in a fully lit room. It has built in speakers that are OK but you will want to use external speakers. Even cheap PC speakers will sound better than the built in ones. The quality of the picture is about as good as the EDTVs of the early 2000’s. Completely acceptable for the projector’s intended use.</p>
<p>The Roku Streaming Stick (<a href="http://www.amazon.com/gp/product/B009CL6DUE?ie=UTF8&amp;camp=213733&amp;creative=393177&amp;creativeASIN=B009CL6DUE&amp;linkCode=shr&amp;tag=hdtvandhometh-20&amp;qid=1352226475&amp;sr=8-1&amp;keywords=roku+streaming+stick">$100</a>) essentially turns the projector into a Roku player. Makes you think that 3M should offer the player without the stick for less money as an option. To use the Roku stick 3M implemented the HDMI port with MHL (Mobile High Definition Link) functionality. Which means that the projector will work with other devices that use this protocol which should future proof the unit. Conversely, you can use the Streaming Stick in any TV that supports the MHL protocol.</p>
<p>Another aspect of the projector we liked was that you can plug anything into the projector’s HDMI port. So if you have an iPad or iPhone with and HDMI cable you now can project iTunes content. If you are a road warrior you can connect your laptop, provided it has an HDMI port and use the device for presentations. The projector even has the ability to be connected to a standard photographer’s tripod so you can optimize the picture.</p>
<h4>Odds and Ends:</h4>
<ul>
<li>The projector comes with a credit card sized remote. You can also use the Roku remote app for your iOS and Android devices.</li>
<li>The 3M™ Streaming Projector is compatible with the Roku® Game Remote for Streaming Stick™</li>
<li>There is almost no documentation with this projector. It is extremely straightforward for tech savvy users. If you are thinking of giving this as a gift to a friend or family member that isn’t as tech savvy as you, be prepared to help them get up and running. You can download a PDF version of the manual if you so desire.</li>
<li>No WiFi means no Roku player. There is no Ethernet connection on the device. You’ll be limited to projecting content from HDMI connected sources.</li>
<li>There are no adjustments for keystone or lens shift so you need to get the projector as square with the viewing surface as possible for the best experience.</li>
</ul>
<h4>Conclusion</h4>
<p>While the 3M Streaming Projector will in no way replace a dedicated home theater projector, it is still a great little unit! Its rated up to 120 inches but a truly acceptable range would be about 60 to 80 inches in a reasonably darkened room. To us its main use would be for those who want a large screen experience in an area that makes it difficult to bring in a large screen. Its also a great unit for those on the go. The only drawback we see for these scenarios are cost, at $300 its a bit pricy, and sound, the speakers don’t project out enough sound.</p>
