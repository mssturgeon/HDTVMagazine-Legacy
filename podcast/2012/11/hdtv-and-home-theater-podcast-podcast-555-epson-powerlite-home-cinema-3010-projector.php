<p>Unfortunately the two projectors, although both manufactured by Epson, both in the same product line and bearing the ‘PowerLite Home Cinema’ name, look nothing alike. Sure they’re both white with silver accents, but other than that, they bear no resemblance. And there’s the whole issue of 3D functionality on the 3010 that wasn’t there on the 8100. So not only was this an experiment in trying out a new projector, it was also a grand experiment to see if the finance committee would notice the change.</p>
<h4>About the Projector</h4>
<p>Epson makes very good home theater projectors. They may not be the absolute best projector you can buy, but they are quite often the best projector you can buy for the price. Epson is consistently rated high across multiple review websites when compared with other projectors of similar price. The 3010 is no different. It is highly regarded by professionals and enthusiasts and it has a near perfect 4 ½ star rating at <a href="http://www.amazon.com/gp/product/B005VONPT8/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B005VONPT8&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Amazon</a>. It’s currently priced just over $1300 at $1338.</p>
<h4>Features:</h4>
<ul>
<li><strong>A true cinematic experience</strong> — 2D &amp; 3D Full HD 1080p technology puts you right in the middle of exciting, lifelike adventures</li>
<li><strong>Super bright and saturated colors</strong> — 2200 lumens of color brightness, 2200 lumens of white brightness, and contrast ratio of up to 40,000:1</li>
<li><strong>Advanced 3D technology</strong> — Epson&#8217;s Bright 3D Drive for enhanced brightness in 3D mode</li>
<li><strong>Rich, vibrant color and reliable performance</strong> — 3LCD, 3-chip technology</li>
<li><strong>Captivating sound</strong> — two built-in 10 W stereo speakers for amazing audio</li>
<li><strong>Sleek design</strong> — fits in any setting</li>
<li><strong>Split screen feature</strong> (not available in 3D mode) — project two images side-by-side from two different sources</li>
<li><strong>Outstanding support</strong> — two-year limited warranty; two-business-day replacement with free shipping</li>
<li><strong>3D glasses</strong> — includes two pair of active shutter 3D glasses</li>
</ul>
<h4>Impressions</h4>
<p>Pardon the pun, but brightness is where the 3010 really shines. It is a light cannon. We’re convinced it could be used as the Bat signal if needed. Most of the time you can ignore manufacturer brightness specs, in the real world you won’t even get half of the value they report. But that isn’t true for the 3010. We observe with our eyes, but <a href="http://www.projectorreviews.com/1080p-projector/performance.php">others that have measured</a> the output have found the 3010 to kick out 1925 lumens in its brightest mode (Dynamic) and an astounding 1424 lumens in its best mode (called Cinema on the 3010). The Epson is brighter in Cinema than many equivalently-priced projectors are in Dynamic.</p>
<p>The 3010’s claim to fame is brightness, but it does a great job in other areas that matter as well. Colors are very good and very accurate. Sharpness and image detail are excellent, not the best we’ve seen, but still very good. The biggest knock on the projector is in contrast and black levels. The projector is quite good, but not quite as good as some of the DLP and LCOS projectors we’ve seen. But again, for the price, it’s comparable to just about anything on the market.</p>
<p>3D technology works best on a large screen, and the 3010 actually does a pretty good job pulling you into the action. It uses active shutter glasses, so eye fatigue is still an issue for us after extended use, but the projector performs very well for as long as we could watch it. You get the benefit of the extreme brightness in 3D, making the picture quite a bit more vivid than other, not as bright, projectors. 3D works better at night or in a darkened room, but the Epson was bright enough to hold up to daytime viewing as well. The glasses remained in sync consistently.</p>
<p>Our biggest issue with the projector is the lack of lens shift. With lens shift, the projector would be almost perfect, nearly unbeatable for the price. Without lens shift we had to rely on keystone and trickery to get the image on screen, leaving us with a less than desirable outcome. It’s tough to guess at why Epson would omit lens shift from the 3010. It does have built-in speakers, leading to the idea it may not be targeted as an installed projector. But everything else about it would make you believe it should be mounted in your family room.</p>
<h4>Conclusion</h4>
<p>Unfortunately the lack of lens shift ultimately did us in. Braden has already sent the projector back, and that’s really the only reason he didn’t get the opportunity to try the other experiment with the finance committee. But now that he’s dipped his toe in the new projector waters, and now that <a href="http://www.dragonflyscreens.com/">Dragonfly</a> screen has tasted 3D, odds are the return will become an exchange and we’ll be talking about a different projector in a couple weeks.</p>
<p>But if you’re in the market for a projector under or around $1500 and want to put it in a somewhat bright room and plan to use it during the day, you want the Epson 3010. Not only is it amazingly bright, it also does very well with color, detail and contrast. It could be a little better with contrast, but for just over $1300, you’ll love it. To get better black levels and lens shift functionality from Epson, you have to pay an additional $1000 to step up to the <a href="http://www.epson.com/cgi-bin/Store/jsp/Product.do?sku=V11H398020">5010</a> (<a href="http://www.amazon.com/gp/product/B006JGHF70/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B006JGHF70&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now</a>).</p>
