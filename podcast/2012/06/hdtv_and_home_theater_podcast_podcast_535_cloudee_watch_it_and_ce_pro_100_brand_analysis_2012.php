<h3>CE Pro 100 Brand Analysis 2012</h3>
<p><a href="http://www.cepro.com/">CE Pro</a>, the magazine for professional consumer electronics installers, puts out a <a href="http://ww.cepro.com/slideshow/image/10028">survey</a> every year to determine what brands dealers, integrators and resellers offer the most.  It’s an interesting list to take a look at.  Typically a reseller will have a few different reasons for choosing a favorite brand than the rest of us, like profit margins or marketing support, but often the reasons are the same.  They want products that please their customers and are reliable.</p>
<h4>Freestanding Speakers</h4>
<p>The top three brands were unchanged from last year. B&amp;W is in the top spot with 34%, followed by Klipsch at 23% and Paradigm at 21%.  Rounding out the top five were Monitor Audio and Triad Speakers, both at 9%.  KEF made the list with 7%.  Of course you wouldn’t expect a brand like Aperion to make the list since they don’t sell through dealers, they sell direct.</p>
<h4>A/V Receivers</h4>
<p>Integra dominated this segment with a outrageous 60%. Number two on the list was Denon all the way down at 31% followed by Marantz at 23%.  Pioneer made a strong showing with the stock Pioneer brand registering a 23% and the Pioneer Elite brand coming in at 20%.  Sony was also pretty high up the list with 20%.  Other notable HT Guys goto brands on the list were Yamaha with 15%, Onkyo at 11%, and Harman Kardon in the basement with a meager 1%.</p>
<h4>Media Servers</h4>
<p>The Media Server category was quite interesting. Despite the legal trouble, Kaleidescape crushed the competition with a whopping 50%. Number two on the list, falling all the way down to 16% was Apple. Of course this comes as no surprise to use. We’ve been talking about using a Mac Mini as a Video Server for half a decade. Rounding out the top five were ReQuest at 15%, Crestron at 14% and Autonomic with 8%. All brands we’ve heard of, but don’t have very much experience with.</p>
<h4>Projectors</h4>
<p>The consummate champion, Runco again led the pack in 2012 with 46%.  But there are also a few brands on the list that the rest of us can afford. Number two, coming in with an excellent showing at 37% was Epson. Braden was quick to point out that he’s been trying to tell everyone what an amazing value these projectors are. At least the dealers are listening. Also on the list were Digital Projection at 34%, JVC at 34% and Sony at 33%. Panasonic made the list, but not very convincingly, with only 6%. CE Pro credits the shift from dedicated theaters to more cost-effective media/great room installations for Epson’s noticeable surge.</p>
<h4>Flat-Panel TVs</h4>
<p>Just like in the world we all live in, Samsung was the big dog in this year’s survey as well.  Samsung with an almost jaw-dropping 88% increased its edge over second place contender Sony weighing in with a solid 54%.  Rounding out the top five were Sharp (41%), Panasonic (36%) and LG (26%).  CE Pro mentions the Elite brand as a reason why Sharp may have had the success they did.  If they can continue to make TVs that look that good, and somehow bring the price down, they might be able to move up the list.</p>
<h4>Bluray Players</h4>
<p>Samsung with 63% and Sony with 54% took this category as well. LG placed third with 20%, followed by OPPO Digital at 17% and Integra at 16%. The magazine believes that Oppo’s emergence into the top of the category is due to custom installers who need Blu-ray disc players that provide a high level of performance without costing an arm and a leg. Other that the OPPO Digital player, the rest of them are basically the same.  Blu-ray players have become somewhat commoditized these days.  Who knows why dealers would choose one over the other? It could simply be ease of ordering. or maybe better discrete IR codes for universal remotes.</p>
<h4>Mounts</h4>
<p>If you need to mount a flat panel to the wall or a projector to the ceiling, these are the brands the pros use.  Hopefully that means if you choose them, you won’t have too much stuff falling when you slam a door.  Of course the quality of the installation could be a factor in that as well.  The most offered brands by dealers in 2012 were Chief (67%), Sanus (42%), OmniMount (31%), SnapAV (20%) and Peerless (17%).  Premier, Braden’s goto choice in the past, barely made the list with only 2% of the vote.</p>
<h4>Computers</h4>
<p>In the retail and corporate world, the Windows based PC is king.  But in the custom installation world Apple dominates, hitting the number one spot with 39%.  This is most likely due to how well the iPad functions as a home theater/home controlling device.  The list also includes a few PC makers, though, like Dell (27%), HP (8%), and Lenovo (4%).  Of course, since there’s only one Apple, the entire rest of the list is PC makers like Acer (2%), Sony (2%) and Toshiba (2%).</p>
