<h3 id="internal-source-marker_0.4731481859629908">Movie and TV Piracy</h3>
<p>This is not a typical topic for the HT Guys but recently we received a lot of emails about the fact the HBO series “Game of Thrones” is the most pirated show today. We stated that if the show was available for download at a reasonable price it wouldn’t be pirated as much. A listener wrote us and gave us his take (<a href="http://www.htguys.com/news/2012/6/20/pirating-american-tv-programs-a-view-from-outside-the-us.html">Pirating American TV Programs</a>) on why show are pirated outside the US.</p>
<p>For today’s episode we wanted to take a deeper look into movie piracy and what if anything can be done to combat it.</p>
<h4>Dollars and Cents</h4>
<p>When <a href="http://judiciary.house.gov/hearings/pdf/112%20HR%203261.pdf">Stop Online Piracy Act</a> (SOPA) and<a href="http://leahy.senate.gov/imo/media/doc/BillText-PROTECTIPAct.pdf"> Protect IP Act</a> (PIPA) bills were working their ways through Congress arguments stated that not passing these laws would cost the motion picture industry between $200 and $250 billion per year, and a loss of 750,000 American jobs. The question is: how could something cause a loss of jobs that is equal to more than twice the current number of people employed by the movie industry? A $250 billion dollar loss is about $800 for every man, woman and child living in the US. The numbers don’t seem to make sense.</p>
<p>A different study by the GAO (<a href="http://www.gao.gov/products/GAO-10-423">Observations on Efforts to Quantify the Economic Effects of Counterfeit and Pirated Goods</a>) suggests that the loss would be closer to $60 billion and that study may be double or triple counting which would inflate the actual loss.</p>
<h4>Why Do People Pirate?</h4>
<p>Studios need to understand that the main reason people pirate movies is availability and cost. In the case of our friends outside of the US it&#8217;s mostly availability. They want the same content as we have here in the states and they don’t want to wait weeks, months, or even years to get it. Then there’s cost. Do the studios really think a Blu-ray version of a 1980’s flop is worth $20? Many don’t think last year&#8217;s blockbuster is worth $20. The studios understand this so they create a disc with a ton of features that no one wants simply to justify the price. Bottom line, charge what the market is willing to pay not what you think the market should be willing to pay.</p>
<h4>What Can Be Done?</h4>
<p>Since Piracy is already illegal it is unlikely that more legislation will do anything. Pirates are already breaking the law so why would they decide to start to obey a different law? It may cause the casual person to think twice about downloading something that is illegal, but for the most part it won’t even stop them. Its just too easy to download the next episode of Game of Thrones. Those who would argue differently can just look at ten years of illegal downloads and ten years of aniti-piracy measures that didn’t do a thing. Every roadblock that was put up gets taken down, costing millions legal fees and encryption schemes. Here is what we think would work for everyone:</p>
<ul>
<li>Release TV shows and movies worldwide simultaneously &#8211; This eliminates people who download just because they can’t wait for the content. This is no longer a technological issue. With digital transmission, movies and TV shows can be sent around the world in hours or even minutes. Yes some distribution agreements will have to be modified but that’s much cheaper than fancy encryption schemes and legal fees.</li>
<li>Allow an all you can eat plan from Netflix, iTunes, Amazon, or whoever &#8211; Reduce the price of streams down to a few pennies per view. Newer content could be reduced to perhaps 10 cents a view. The studios would make it up in dramatic increases in volume. Imagine a TV show that has worldwide distribution available for streaming at 10 cents. if 50 million people watched the episode it could make the studio 5 million dollars. More shows would be created and many shows that would be canceled in the US now become viable on a worldwide basis.</li>
<li>Reduce the price of disc based content &#8211; So you’re not a fan of streaming? You&#8217;re not alone. Disc based content has higher quality picture and sound. But there is still no reason it needs to cost a more than $5. Offer a basic no frills disc of the movie. The studio can create the disc for far less cost and thus increase the bottom line. If given the option of a high quality disc for $5 and flaky download most will opt for the disc.</li>
<li>Shorten the time after a movie exits the theater and is available as a download/disc &#8211; If a movie is available 15 to 30 days after it stops playing in a theater people will buy it. We know, cinema owners will cry foul. To them we say: lower your prices and create a better experience that would make people want to see the movie in your establishment. We’ll do a feature on how cinema owners can get people out of their home theaters and into the cinema on another show.</li>
<li>Offer DRM Free Downloads of Movie and TV &#8211; It worked for the music industry. There is research (<a href="http://server1.tepper.cmu.edu/Seminars/docs/DVessay_1October27.pdf">Digital Music Set Free: The Flip Side of DRM</a>) that suggests:
<ul>
<li><em>Consumers enjoy unrestricted, DRM-free, digital products more and thus are willing to pay more for an unrestricted product. The impact of DRM technology on consumers’ willingness to pay has not been taken into account sufficiently in previous research, which simply assumes that DRM protection unambiguously decreases piracy. Instead, the present research demonstrates that this assumption might not hold. </em></li>
</ul>
</li>
<li>Understand that no matter what, there is a segment of society that will always pirate &#8211; Yes there are people in society that don’t want to pay for anything. It’s not right but it’s a very small group. Frankly you won’t be able to sell them a movie at any price. But don’t punish the vast majority because of those few. Go after them and throw them in jail. But don’t lump people in who would gladly pay you for your content if it were available at a fair price.</li>
</ul>
<h4>Final Thoughts</h4>
<p>Digital content is not like, say, a computer or a car. It’s hard for someone in South Africa to steal a laptop or car in Southern California. Anyone with a computer can steal a digital file. But it doesn’t have to be. It comes down to a fair price and availability for digital content. If you make your product available to the masses and at a fair price people will buy it.</p>
