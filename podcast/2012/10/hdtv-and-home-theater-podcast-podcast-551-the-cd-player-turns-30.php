<h4>The Beginning</h4>
<p>Many of us remember our first CD player. It was, more than likely, your first introduction to a digital music format. Some of us are old enough to remember our first record player, our first 8 track or our first cassette player, but the CD was something special. There was something magical about the digital format you didn’t have to rewind. The format that allowed you to jump from track to track instantly. It was like living in the Jetsons.</p>
<p>Sony introduced the first CD player in 1982. The CDP-101 sold for $674 in its day. That amount alone would be expensive for any media player today. But adjusted for inflation, the only player on the market would cost you over $1600 in today’s dollars. The first thing you have to ask yourself is, I wonder whatever happened to the CDP-100? What fundamental flaw did it have that forced Sony to come up with the CDP-101? We’ll probably never know.</p>
<p>But the second question you probably ask yourself about the CDP-101 is, “how much content was available for it?” That’s the question we all ponder whenever a new format comes out. We struggled with it when HDTV first arrived, then Blu-ray. Back in 1982 there were a whopping 50 discs to choose from, ranging from classical music to show off the fidelity of the format, to contemporary music people wanted to buy, like Billy Joel, Pink Floyd, and Journey. Discs cost around $15 then. Not bad, until you realize that would be $35 if you wanted to buy one today.</p>
<h4>The Market</h4>
<p>In 1982 the average household was much, much different than it is today. Technology didn’t play nearly the role in everyone’s lives that it does now. Technology uptake was a much more gradual affair. According to a study by UC Irvine (Braden’s alma mater, btw), only 7.9 percent of American households owned a personal computer in 1984. There were a few popular game consoles, but by and large America had not gone digital. The CD was poised to change all that and become the first digital device most American consumers would own.</p>
<p>Due to the high cost of the player and the discs, many believed the new format would be relegated to a very small niche market. It would find its way into the homes of the very rich or the extreme audiophile; average consumers simply wouldn’t want or need it. Unfortunately, many audiophiles weren’t big fans. They expressed concerns about the loss of fidelity when converting analog to digital and clung to their record players as the one true source of good music.</p>
<p>But the vast majority of consumers didn’t share that concern. The audio quality was excellent, especially compared to cassette tapes, and the convenience of the format was undeniable. As prices came down, uptake accelerated quickly. By 1988 the CD had passed the vinyl record in total units sold. It overtook the cassette tape soon after in 1992. By that time prices had come way down and the benefits of the format spoke for themselves.</p>
<h4>More than just Music</h4>
<p>But the CD as a digital storage format had a life that was so much bigger than just the music industry. The CD-ROM first hit the market (in non-consumer applications) in 1985. To this point, the primary means for storing and transporting digital information was floppy discs or tape drives.  A single CD-ROM was capable of holding the equivalent of nearly 2400 floppies on one disc. That was mind blowing. Even more mind blowing than putting the headphone jack on the bottom of the iPhone 5.</p>
<p>We can all remember the discussions we had about the CD-ROM and how it was going to revolutionize everything we could possibly imagine. Does anyone remember quotes like “You can fit the entire Library of Congress on a single disc” or “Your entire life, and the lives of your entire family can be stored on there &#8211; what if it falls into the wrong hands?” The CD-ROM represented limitless opportunity and a new giant leap in the digital revolution.</p>
<p>It wasn’t long before the two formats, Music and Data, would merge. Audio discs that included special bonus features like games or screen-savers or video clips, began popping up on store shelves everywhere. Who could forget the infamous Sony root-kit fiasco in 2005 when Sony tried to protect their music from piracy by taking over your computer. That was a less than popular use of the merged technology that Sony soon regretted.</p>
<h4>To Infinity and Beyond</h4>
<p>But no good thing can last forever and eventually the CD gave way to new distribution methods for digital audio, namely digital downloads. In 2011 annual music download sales surpassed physical media sales for the first time. But the CD should be remembered for much more than that. The CD introduced laser-based disc storage, a technology that spawned the DVD, DVD-Audio, SACD and eventually HD-DVD and Blu-ray. As home theater enthusiasts, we owe a lot to the CD.</p>
<p>And we can see a lot of parallels between the life of the CD and current disc based technologies. In the early years, Blu-ray struggled with price issues and content availability. Even now we ask how long it will take for digital downloads to surpass DVD and Blu-ray in total sales. When will Blu-ray see a demise similar to that of the CD?  That’s hard to answer.  Early on, digital downloads didn’t have nearly the audio quality of a CD, but they’ve become pretty darn close. Right now digital downloads don’t have the quality of a Blu-ray movie, but eventually, we’re sure they’ll get pretty darn close as well.</p>
