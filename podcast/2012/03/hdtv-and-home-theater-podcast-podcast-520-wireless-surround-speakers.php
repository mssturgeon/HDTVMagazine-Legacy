<p><strong><a href="http://www.polkaudio.com/homeaudio/fx/">Polk audio F/X Wireless Surround Sound</a> (<a href="http://www.htguys.com/shop?id=B0049Z89MS">Buy Now $290</a>)</strong><br />
The F/X is a unique product. Think of it like a soundbar for your surrounds. The entire unit is contained in one cabinet. The 2.4 GHz transmitter is connected to your home theater receiver and communicates with the F/X loudspeaker which can be placed on the floor, a table or a shelf. The whole thing sets up in a snap. Out of all the solutions this is the easiest to setup. Plug in the transmitter, place the speaker behind the couch and provide power. That’s it! We have no experience as to how good it works. We’ll try to get one for demo.</p>
<p><strong><a href="http://shop.panasonic.com/shop/model/SH-FX71">Panasonic SH-FX71 Wireless Rear Speaker System</a> (<a href="http://www.htguys.com/shop?id=B003DKEILG">Buy Now $100</a>)</strong><br />
The Panasonic SH-FX71 is a classic wireless transmitter, it has a transmitter and receiver. The receiver base is a box measuring 9.00&#8243; h x 6.00&#8243; w x 10.00&#8243; so you need to find a place for it behind the couch. Connect your speaker wires and power and you are good to go. The system works on the 2.4Gz frequency.</p>
<p><strong><a href="http://www.jbl.com/estore/jbl/us/product/productDetails.jsp?pid=WEM-1">JBL WEM-1 50-Watt Wireless Amplifier and Expansion Module</a> (<a href="http://www.htguys.com/shop?id=B001GXQOUU">Buy Now $329</a>)</strong><br />
The JBL WEM-1 kit contains a transmitter that wirelessly transmits a signal up to 70 feet. The receiver includes a 50W amplifier that receives the wireless signal and can drive any pair of loudspeakers with plenty of power. The transmitter connects to the source using either line or speaker level inputs. The receiver/amplfiier also offers equalization settings for several speakers. A local input allows the user to hook up a portable device as well. At $329 this is one of the more expensive solutions on the market.</p>
<p><strong><a href="http://kef.com/html/us/innovation/wireless/index.html">KEF Universal Wireless System</a> (<a href="http://www.htguys.com/shop?id=B000U6XE7U">Buy Now $499</a>)</strong><br />
