<p>You may be thinking the same thing we were, “Do we need another paper thin antenna?”. If so, “What makes the HD Blade worth buying?”.  Solid Signal, the makers of the HD Blade, claim that it is one of the most powerful indoor antennas and one of the reason is:</p>
<p><em>The HD Blade has real silver elements embedded between two thin sheets of industrial grade plastic.   The design of the elements mimic that of a long range outdoor antenna, but for the first time technology has allowed us to print metal elements on to a sheet.</em></p>
<p>So we compared it to the leaf. Since the HT Guys live about 70 miles away from the TV towers for Los Angeles our tests we performed in Fresno CA. Ara’s in-laws live 20 miles from the TV towers which is right in the sweet spot of the antenna’s performance range.</p>
<h4>Performance</h4>
<p>Our HD Blade came with a six foot coax cable. And like the leaf it is important that the cable run towards the ground. Solid Signal includes a quick tips pamphlet that helps with placement and positioning of the antenna. We placed the antenna behind the TV, which limits reception but is acceptable to the aesthetics committee, and then we connected the cable to the TV’s antenna jack and hit scan.</p>
<p>For our performance measure we will compare the number of digital channels picked up by HD Blade, Mohu Leaf and Mohu Leaf Plus. The plus is an amplified version of the Mohu Leaf. We reviewed it on <a href="http://www.htguys.com/podcasts/2012/4/27/podcast-528-mohu-leaf-plus-amplified-indoor-hdtv-antenna.html">Podcast #528</a> back in April.</p>
<p><strong>Number of Digital Channels Received:</strong></p>
<ul>
<li>Mohu Leaf &#8211; 31</li>
<li>Mohu Leaf Plus &#8211; 38</li>
<li>Solid Signal HD Blade &#8211; 42</li>
</ul>
<p>This is an improvement over both leaf antennas. The HD Blade found a few more than the Leaf Plus but it was very close. There may have been other factors involved since these tests were not performed at the same time. Bottom line is we can say that the blade performs as good if not better than the Mohu Leaf Plus at a lower price. Plus the HD Blade does not need amplification so its easier to install.</p>
<h4>Conclusion</h4>
<p>There are a few options out there to pull in HD signals over the air, and if you live less than 30 miles from the towers its never been easier to do so. The HD Blade from Solid Signal works well and at less than $40 is no brainer for those who wish to cut the cord or simply want a good backup for when the cable goes out.</p>
