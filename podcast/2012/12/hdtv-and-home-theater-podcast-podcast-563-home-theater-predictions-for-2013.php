<p><strong>Product Placement will be big</strong> - With so many DVRs out there advertisers are looking for a way to put their brand in front of you. This year I am saying that it won’t be subtle but more in your face. Rather than just seeing the product look for dialog about how good the product is. There have been a few examples of this with Toyota and Bones. Look for the cell phone companies to talk about communications on any action/cop show.</p>
<p><strong>Apple will enter the home automation market</strong> - Since 2012 was the year of home automation <img src='http://s1.wp.com/wp-includes/images/smilies/icon_wink.gif' alt=';-)' class='wp-smiley' />  Apple will make 2013 the year of plug and play automation. They are rumored to be interested in id8 Group R2 Studios Inc which is a startup company developing home media and automation technology. Look for Apple to tie your entertainment, lighting, and security together in a neat easy to setup package. So does this make 2013 the year of home automation?</p>
<p><strong>We’ll see a “True” smart TV</strong> - I’m not talking an Internet connected TV but more of a TV that truly has some brains. Something that can sense who is in front of it and configure itself for that viewer. If more than one person is in front of the TV then maybe go into family mode or something like that. It will be voice activated. Actually it will be a cross between GoogleTV, AppleTV and a computer. Look for Samsung to develop the first True Smart TV.</p>
<p><strong>Movie Studios will eliminate DRM from their content</strong> - Following the lead of the music industry, the movie industry will see the err of their ways and make it easy for all of us to freely create video servers with legally owned content. This is my Hail Mary pass prediction. Probability of success&#8230; less than 1%</p>
<p>&nbsp;</p>
<h4><strong>Braden’s Predictions:</strong></h4>
<p><strong>Adios Mother Plasma</strong> - Although plasma may have given birth to the flat screen revolution, the technology will be forced into early retirement in 2013. The glory days of plasma are long gone; the technology has been holding on for dear life for too long. 2012 saw the death of rear projection, 2013 will do the same for plasma as the last few stalwarts are forced to cut losses and retool manufacturing for LCD or maybe “the next big thing” &#8211; whatever that is.</p>
<p><strong>I’ll buy that for $300</strong> - The average selling price for a 42” 1080p LCD TV will be $300 by the end of the year, down from $480 in 2012. Due to the lack of enthusiasm in 3D and the difficulty they’ll have convincing consumers to upgrade for 4K, manufacturers will be forced to drive prices down even further to entice more sales. By the end of the year, prices across the board will be down and the 42” TV will move to the standard “entry level” screen size. We’ve already seen Black Friday deals on 40-42” TVs for under $200. As we approach the end of the year, that will be closer to the norm than the crazy door buster.</p>
<p><strong>Let’s be more than friends</strong> - As the economy continues to struggle and the price of electronics continues to plummet, 2013 will see at least one, maybe a few large mergers or acquisitions in the consumer electronics/home theater industry. The industry is ready for a little consolidation or contraction. Perhaps Samsung and LG will merge to become an unstoppable force in total world electronics domination. Or in an attempt to hold off pressure for China and Korea, Sony might make a play for Panasonic. Who knows, maybe Apple will try to buy a smaller TV company like Sharp or Vizio to legitimize its entry into the television market.</p>
<p><strong>Stream it to me</strong> - This year will see new release available via streaming in an all-you-can-eat subscription package. For whatever reason, the movie studios seem to hate Netflix, so odds are it won’t be a Netflix package. More than likely the deal will come from Amazon, Vudu, Google, DirecTV or Dish via Blockbuster@Home. The package cost may be ridiculously high, probably too high to be worth it for most people, but it will be available.  The cost will be roughly equivalent to renting 10 movies per month, or $50, possibly more for the “high def” option.</p>
<p><strong>You can take it to grandma’s house</strong> - In 2013 someone will show the prototype for a truly portable tablet computer. Not something thinner and lighter but still 10 inches by 8 inches, but something that either rolls up or folds up so you can very easily take it with you anywhere. Flexible screens will meet the tablet computer revolution and produce something truly revolutionary. How cool would a tablet that can roll up be? Or a tablet that could fold up to the size of a standard smartphone (perhaps just a little thicker)?</p>
