<h4>Background</h4>
<p>Typically the chemical composition of a material determines the color of light it will produce, whether you‚Äôre talking about CRT, LCD, LED or Plasma. ¬†But scientist have found that size matters as well. When you‚Äôre dealing with very, very small semiconductors, less than 10 nanometers, their size can actually determine what color they produce. ¬†The tiny semiconductors are called Quantum Dots and by varying the size of the dot, you can actually produce different wavelengths of light.</p>
<p>Quantum dot light emitting diode (or QLED) technology is being pioneered by Massachusetts company QD Vision, a spin-off from the Massachusetts Institute of Technology. ¬†Together with technology partners such as LG, QD Vision is trying to pioneer the new technology they claim will surpass OLED in price, performance, quality and power consumption. ¬†They claim their QLEDs will be ‚Äúa reliable, energy efficient, tunable color solution for displays and lighting that is less costly to manufacture [than inorganic LEDs] and that can employ ultra-thin, transparent or flexible substrates.‚Äù</p>
<h4>How it Works</h4>
<p>A quantum dot made from Cadmium selenide will produce light in the red region of spectrum from a 5 nm diameter dot and the violet region from a 1.5 nm dot, and anywhere in between. The energy that determines the color of the fluorescent light produced is inversely proportional to the square of the size of dot. In other words, the emitted light changes as the dot size changes. By producing dots of varying sizes on a single substrate, a manufacturer can create any wavelength of light they want. ¬†QLEDs can be tuned over the entire visible spectrum, from 460 nm (blue) to 650 nm (red).</p>
<h4>Pros and Cons</h4>
<p><a href="http://en.wikipedia.org/wiki/Quantum_dot_display">Wikipedia</a> has a great collection of Pros and Cons for the emerging technology:</p>
<p><strong>Pros</strong></p>
<ul>
<li><strong>Color range:</strong> Nanocrystal displays should be able to yield a greater portion of the visible spectrum than current technologies&#8230;QD Vision calculates as much as 30% more of the visible spectrum would be available using QDs in a QD-LED vs. a CRT TV.</li>
<li><strong>Low power consumption:</strong> QD Vision estimates its nanocrystal displays could use 30 to 50% less electrical power than an LCD, in large part because nanocrystal displays don&#8217;t need a backlight.</li>
<li><strong>Color accuracy:</strong> Nanocrystal displays would yield more purity in colors than other types of display technologies. Some display technologies, such as LCDs, can‚Äôt create a pure red, green, or blue for the display; instead, they need to add a few other colors to those three to display pure colors. Quantum dots, on the other hand, create pure red, green, and blue to create all other colors.</li>
<li><strong>Brightness:</strong> 50~100 times brighter than CRT and LCD displays ~40,000 cd/m2</li>
<li><strong>Added flexibility:</strong> QDs are soluble in both aqueous and non-aqueous solvents, which provides for printable and flexible displays of all sizes, including large area TVs</li>
<li><strong>Improved lifetime:</strong> QDs are inorganic, which can give the potential for improved lifetimes when compared to alternative OLED technologies. However, since many parts of QD-LED are made of organic materials, further development is required to improve the functional lifetime.</li>
</ul>
<p>Other advantages include better saturated green, manufacture ability on polymers, thin display, same material used to generate difference colors, and higher resolution.</p>
<p><strong>Cons</strong></p>
<ul>
<li><strong>Less saturated blue:</strong> Blue quantum dots are difficult to manufacture due to the timing control during the reaction. A blue quantum dot is just slightly above the minimum size, where red to green can be easily obtained. Sunlight contains roughly equal luminosities of red, green and blue. So in order to display an acceptable range of colors, a display needs to be capable to produce approximately equal luminosities of blue as of red and green (even though in order to achieve the same brightness as perceived by the human eyes, blue needs to be about 5 times more luminous than green; have 5 times more power).</li>
</ul>
<p>Commercialization of quantum dot display is yet to come. Compared to LCD and OLED, the manufacturing cost of QD-LED is relatively high and development of novel and more cost-efficient fabrication process is desired in future.</p>
