<h3>Google Chromecast review</h3>
<p dir="ltr">There was a lot of buzz a couple weeks back when Google announced the release of a new HDMI device called the Chromecast (<a href="http://amzn.to/1dsPVCx">buy now, $35</a>). We weren’t immune to the curiosity, so we ordered one. The popularity made them tough to get, but when ours finally arrived, we couldn’t wait to see if it would live up to expectations. We’ll admit, we set our own expectations. Google didn’t do much to hype it up. They simply said, here it is, at a very reasonable price, have at it.</p>
<h4>Unboxing</h4>
<p dir="ltr">The Chromecast itself is a small HDMI dongle, a little bigger than the typical USB flash drive. On one end is an HDMI connector, and on the other a micro-USB port for power. Inside the box you also get a short HDMI extender, in case the dongle doesn’t exactly fit where your HDMI ports are, a USB power cord and a standard plug adapter for it. There’s also a small setup guide, but we instantly discarded it.</p>
<h4>Setup</h4>
<p dir="ltr">You don’t need the instruction manual to know that you plug the Chromecast into an open HDMI port on your TV or receiver, and give it power. If you have an open USB port handy, you can use it to power the Chromecast, if not, you can use the included standard plug adapter to plug into wherever your TV gets its power from. Once that’s done, you switch your TV to the HDMI input you just plugged the Chromecast into and you’re greeted with a very simple setup screen.</p>
<p dir="ltr">The setup screen will tell you to point your browser to a particular URL to get the Chromecast ready for use. You can do that, or if you’ve installed the Chromecast app on your phone or tablet, you can use it instead. If you choose to go the browser route, you’ll want to use Chrome, after all, it is called the Chromecast. Setup is as simple as connecting to it, providing your WiFi password and giving it a name. When that completes, which may take a minute or two, you’re ready to start casting.</p>
<h4>Performance</h4>
<p dir="ltr">The Chromecast has two basic modes of operation. You can stream content to it from a supported app on your smartphone or tablet, or you can share a tab from your Google Chrome browser. Both worked seamlessly for us. From an iOS device you can cast Netflix and YouTube, from an Android device you can cast Netflix, YouTube and Google Play Music or Movies/TV. From the Chrome browser on any OS it runs on, you can cast any tab you want, but some tabs (websites) work better than others.</p>
<p dir="ltr">Casting from a portable device is easy and works very well. The streams coming to the Chromecast are actually direct connections back to NetFlix or Youtube, they don’t get routed through your phone, so the quality is as high as you’d expect to get from any other set top streamer like a Roku or Apple TV. In both cases the content looked as good as any other device we’ve used to stream those services. And the same goes for the Google Play apps from an Android device.</p>
<p dir="ltr">Casting from the browser is a different story. In most cases, casting from the browser is a screen sharing session streamed from your computer to the Chromecast. Even with a beefy laptop, you’re subjected to video stutters and a somewhat low quality stream. You can stream any audio or video file you can get Chrome to open, but we wouldn’t claim it’s the best way to play your files on your big screen. But you can get access to some of the apps you like, Pandora, etc. If you need to.  We found that the video apps, like Amazon or Hulu, wouldn’t cast video to the Chromecast.</p>
<p dir="ltr">One cool feature of casting from the browser is how it treats Netflix and YouTube. If you cast a tab from one of those services, it’ll work just like your phone does. It’ll send the video directly to the Chromecast, providing you with the same, high quality experience you get from your phone. You even get the full control interface in the browser, no change to how it looks there, but just the high quality video on your TV. One oddity was that the subtitles in Mission Impossible, Ghost Protocol actually showed twice, once overlaid in the video itself and another time below it in the black space below the video.</p>
<p dir="ltr">Before you get the idea that Chromecast may work to mirror your browser on a larger display for working on items like Google Docs or Spreadsheets, you might have to think again. We tried it, and it doesn’t work. Chrome doesn’t appear to stream any Javascript or AJAX changes to the Chromecast, so unless you refresh the page, you don’t get any updates. You can type all day on your Google doc and not see a single letter on your Chromecast. The text resolution for reading browser pages and such is also pretty bad.</p>
<p dir="ltr">Perhaps the best feature of the Chromecast is that it isn’t tied to and single Netflix or Google account. Anyone connected to the WiFi network can stream to it. If you have movies or music in your Google Play account you want to share with friends, you’re all set. If you saw a funny video on YouTube and want to share it, you just pull it up on your phone and cast it to the TV.  Same goes for Netflix. Of course you have to have those apps installed and configured on your phone first.</p>
<h4>Conclusion</h4>
<p dir="ltr">All in all, the Chromecast did great with YouTube, Netflix and Google Play, and was a so-so experience from the browser. At one third the cost of many other streaming devices, it has a lot of potential. We’re hearing a lot of chatter about “developers working on more native apps” for it, and as they come the value of the Chromecast will continue to improve. All it needs is Amazon, Hulu, Vudu and Pandora and it’ll cover just about any service you’re into. And with the rumors that Google is looking into live TV streaming, this little dongle could become the cord cutters’ set top box.</p>
