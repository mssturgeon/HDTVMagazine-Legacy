<h3>DirecTV Genie</h3>
<p dir="ltr">It’s hard to believe that only about 5 years ago most of us had to watch TV when the Networks wanted us to. Our first DVRs were so liberating because it allowed us to watch television on our own terms. No more missing programs because they conflicted with another show or were on late at night. The only real issue was that when DVRs first came out you had to watch in one room, typically the family room.</p>
<p dir="ltr">As DVRs became more prevalent many of us added one to the bedroom or theater room which allowed for more content but you still were chained to a specific room depending on which DVR your show was recorded on.  Enter the Genie from DirecTV. Genie unchains you from watching your recorded programs in specific rooms, and with its five tuners, eliminates recording conflicts, keeping peace and harmony in the home.</p>
<h4>Features:</h4>
<ul>
<li>Record up to 5 shows in HD simultaneously</li>
<li>Additional rooms can use the Genie Mini which is a fraction of the size of a typical cable or satellite receiver.</li>
<li>With Samsung and Sony TVs that support RVU, you don&#8217;t even need an the Genie Mini. These HDTVs can access the Genie HD DVR without any additional equipment at all.</li>
<li>Start programs at the beginning even if you tune in late.</li>
<li>Picture in Picture on the main Genie Unit.</li>
<li>Genie recommends shows based on what you have watched in the past and will even record them for you without using any of the recording space.</li>
<li>Record up to 200 hours of HD content. That’s more than 8 full days of HD programming!</li>
</ul>
<h4>Setup</h4>
<p dir="ltr">Ara was told that all he had to do was remove his old DVRs and connect the new Genie and Genie Minis. Unfortunately that wasn’t true. Ara’s home was missing a Single Wire Module (SWM) which is required for the Genie to work. A quick call to DirecTV to schedule an appointment and one week later a fantastic installer showed up at his door.</p>
<p dir="ltr">It took the installer about four hours to get everything set up. But in the process he convinced Ara to skip the Genie Minis and keep the DVR in the theater and receiver in the master bedroom. The reason is that it allows the Genie to use all five tuners for itself and the older equipment can still see what is recorded on the Genie and play it back. As a result Ara has eight tuners and there is no chance that there will EVER be a recording conflict in his house. Plus, with the DVR in the theater room, the kids are banished to using that for their recordings which adds about 50 more hours of HD recording time to the entire system.</p>
<p dir="ltr">The other thing the installer did was add a device to bridge the network over the satellite cables. Not really a big deal but now only one unit is connected to network and the other units get their network connection through that unit. This frees up Ethernet ports which may or may not be a big deal.</p>
<h4>Performance</h4>
<p dir="ltr">The Genie is much more responsive than the DVR it replaced. The two and a half minute skip seems faster as well. In general you can say the Genie system does everything in the blink of an eye <img src='http://s1.wp.com/wp-includes/images/smilies/icon_wink.gif' alt=';-)' class='wp-smiley' />  Watching recorded content on the older receiver/DVR from the Genie is about the same as it was with a standard DVR.</p>
<p dir="ltr">Where the Genie outperforms its predecessors is in tuners. For fun we recorded 5 shows at the same time and had no issues. This really wasn’t an issue for us in the past. A bigger problem was recording two shows at the same time and watching a third live program. With the Genie we also recorded four shows and watched a fifth live. Its quite nice. If you do use the Genie Mini be aware that watching something live with those units will use a tuner on the Genie and reduce the capability of recording more shows simultaneously. That’s why we recommend using a standard set top box to add more tuners to your system.</p>
<p dir="ltr">Another nice feature of the Genie is Picture in Picture (PIP) which is only available on the main unit. The feature is turned on by bringing up a menu and then navigating to it.  Once there you can select where you want the secondary screen on the main screen. We found the most useful orientation is Side by Side. To turn it off you use the same sequence of button presses. To toggle between the screens you press the down button. It would be great if there was a discrete command to turn the feature on and off. Regardless, this feature will be getting a lot of work this football season!</p>
<h4>Genie Recommends Too</h4>
<p dir="ltr">Genie has a feature that will recommend TV shows and movies based on your viewing habits. It will record an episode and you can immediately watch the recommendation if you chose. This program does not cut into your 200 hour capacity. If you like what you see you can tell Genie to record the entire season. If you don’t like a recommendation you can tell Genie that you are not interested and it will modify its recommendations.</p>
<p dir="ltr">One evening we were sitting on the couch and there was nothing on the DVR that the family could agree on so we decided to give Genie a try. One of the recommendations was a show on Discovery Channel about repossessing airplanes. Since Ara works in the aircraft industry for his day job he hit play even though everyone else in the family objected. Long story short, Ara told Genie to record the series. BTW, Ara’s daughters reluctantly admitted that they like the show.</p>
<h4>GenieGo</h4>
<p dir="ltr">The GenieGo feature requires an additional box formerly known as the Nomad. With the box you can select shows to be converted to a portable format for viewing on a smartphone or laptop at a later time without connectivity. But a nice aspect of the feature is that you can watch the content online once you have connectivity. Kind of like a Slingbox lite. No live content but you can view something that is currently recording as long as it was already selected for the GenieGo.</p>
<p dir="ltr">The DirecTV iPad app lists the shows that are recorded on your Genie and it looks like it can play something that is in the GenieGo format. We have not confirmed this but the interface looks like it supports it. We’ll check this out and report back.</p>
<h4>Conclusion</h4>
<p dir="ltr">If you are a DirecTV subscriber the Genie is a great upgrade. Be sure to keep any current set top boxes in the other rooms as this will increase the number of tuners available to your household. If you have cable consider switching over to DBS TV because in our opinion they have better equipment and picture quality. If you are a Dish subscriber, well enjoy your Hopper! No need to switch.</p>
