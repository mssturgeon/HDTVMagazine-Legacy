<h3>Wireless HDMI Options</h3>
<p>We have reviewed a handful of wireless HDMI systems in the past, and have been impressed each time at how much better they’re getting and how quickly the prices have fallen. An unfortunate incident in the Russell home recently required a replacement wireless HDMI setup, kicking off a new round of research into what is available on the market now.</p>
<p>Wireless HDMI has long promised an amazing solution for those who wanted to run a front projection home theater, but couldn’t run a hard wire to the projector itself. Or the situation where you really want to put a TV on a particular wall, but that doesn’t happen to be the wall where your cable outlet is. We can think of several uses for them all around the house. Braden may even have a need for a couple of them at work.</p>
<p>All Wireless HDMI systems consist of two parts, a transmitter and a receiver. Both the transmitter and the receiver will require power, so they aren’t completely without wires. But since you have to power the devices you’ll connect to them, like a Blu-ray player on one end and a TV on the other, finding a power outlet shouldn’t be terribly difficult.</p>
<p>One other key feature of a wireless HDMI system is line-of-sight. Many require that the transmitter have a clear line of sight to the receiver, so they won’t work through walls or cabinet doors. Some of the highest quality systems we’ve used in the past have required line of sight, but the requirement can get very annoying, very quickly. You’ll lose TV when someone accidentally or unknowingly walks through the beam, and then it can take a while &#8211; what usually feels like a very long while &#8211; for the transmitter and receiver to resync and for picture to be restored.</p>
<p>&nbsp;</p>
<p><strong><a href="http://www.belkin.com/us/F7D4515-Belkin/p/P-F7D4515">Belkin ScreenCast AV4 &#8211; 4 Port Wireless HDMI Adapter</a> (<a href="http://www.amazon.com/gp/product/B005NYPC1U/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B005NYPC1U&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now $240</a>)</strong></p>
<p>At $240 the Belkin ScreenCast AV4 is at the higher end of the price range in our list.  But unlike several other models, it has 4 HDMI inputs, so you can switch between and wirelessly beam one of several devices using the same transmitter. The ScreenCast also works through walls, so you shouldn’t have to worry about line of sight issues. The receiver is wall mountable, so it should pair well with a wall mounted flat panel TV.</p>
<p>One interesting note is that the ScreenCast AV 4 actually uses Wi-Fi to transmit audio and video signals from your AV devices to your TV using the same 5 GHz wireless technology you may be using for your home network. The 5 GHz band is good, so it should ensure high-fidelity, transmission, but you never really know if other bits on the same band could get in the way. It supports 5.1-channel surround sound and is compatible with 2D and 3D video resolutions up to 1080p.</p>
<p>Belkin quotes a line-of-sight maximum distance of 100 feet, for those really, really large home theaters. They don’t provide a maximum distance through walls, but they do state that it is less than 100 feet. It also has the ability to transmit IR signals and has an IR blaster, so if you have source equipment in a different room or behind a cabinet door, you’ll still be able to control it as if it was right in front of you.</p>
<p>&nbsp;</p>
<p><strong><a href="http://www.iogear.com/product/GW3DHDKIT/">IOGEAR Wireless 3D Digital Kit with Full HD 1080P</a> (<a href="http://www.amazon.com/gp/product/B00630WKGI/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B00630WKGI&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now $189</a>)</strong></p>
<p>On paper, the IOGEAR unit sounds like the one to buy. The price is at the lower end of the spectrum, without being so low that you know there has to be a catch. And feature-wise is seems to have it all. It operates up to 100 feet apart, including through walls, uses the 5 GHz band, has 2 HDMI inputs and does IR transmission as well.</p>
<p>We haven’t used it, but if we were shopping based purely on specs, the IOGEAR would top our list. To be completely open and honest, we’ve never seen a wireless HDMI system go 100 feet through walls, maybe 30 or 40, but never close to 100. So don’t count on 100 feet through walls. We’ve also seen that the signal quality can degrade if you try to get too crazy with the number of walls or the distance, but we have no proof the IOGEAR would exhibit the same behavior.</p>
<p>This unit also supports a local HDMI pass-thru, which can open up a whole world of possibilities. You could run a second screen anywhere you want, just for the heck of it. Something like that would come in really handy at a Super Bowl party or anytime you want to create a sports bar like environment. You could even run a second TV somewhere, like a garage, without the need for an additional tuner, just beam out whatever is on an existing TV in the house.</p>
<p>&nbsp;</p>
<p><strong><a href="http://www.brite-view.com/product.php?P=8">Brite-View Air SyncHD Uncompressed 1080p Wireless Transmission Kit</a> (<a href="http://www.amazon.com/gp/product/B0043BPZWA/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B0043BPZWA&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now $189</a>)</strong></p>
<p>Brite-View is a company we’re very familiar with, we have reviewed a few of their systems in the past and, in fact, the system Braden needs to replace is made by a Brite-View. Of the wireless HDMI units we’ve reviewed in the past, the Brite-View had, by far, the best picture quality. This model supports 1080i at 100 feet or 1080p at 66 feet. We couldn’t get that kind of range out of it, but when it was in range it looked awesome.</p>
<p>The biggest issue we have with the Brite-View is that is does require line of sight. It has the annoying habit of losing signal when someone happens to wander through the beam. The Air SyncHD is also a one HDMI input system, so you’ll have to rely on a separate switch, or your receiver, if you have more than one HDMI source. If you have line of sight and an existing method for switching HDMI inputs, the Brite-View should look really, really good for you.</p>
<p>There are other units out there, but they all tend to fall in the same categories as the ones we’ve already looked at. For example, the VIZIO XWH200 Wireless HD Video Kit (<a href="http://www.amazon.com/gp/product/B004M18AYG/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B004M18AYG&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now $194</a>) is quite similar to the Brite-View Air Sync HD. It requires line of sight and while it adds support for 3D, its range is only 30 feet. One distinctive feature the Vizio has going for it, however, is that it operates at 60 GHz frequency so it shouldn’t interfere with other Wi-Fi devices. The Actiontec My Wireless TV WiFi / HDMI Multi-Room Wireless HD Video Kit (<a href="http://www.amazon.com/gp/product/B005L9ZZ32/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B005L9ZZ32&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Buy Now $199</a>) is in a class all its own, but almost feels too good to be true. It claims 3D 1080p at 150 feet through walls and is the same price as the rest of the systems in our list. If it can do that, we’ll take it!</p>
<p>&nbsp;</p>
<h4>Conclusion</h4>
<p>There are plenty of ways to make whatever your home theater dreams happen to be into reality. Whether you finally want to take the plunge and try a front projector, or you want to mount a huge 65” LCD on that one wall over there that you can’t run cable to, or you simply want to put a TV in your garage, wireless HDMI is now at a price where we can all give it a shot. The aesthetics committee may have told you, sure, you can get a bigger TV, if you put it over there&#8230;and now you can.</p>
