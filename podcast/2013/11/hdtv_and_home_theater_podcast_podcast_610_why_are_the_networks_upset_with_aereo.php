<h3>Why are the networks upset with Aereo?</h3>
<p dir="ltr">We have been covering the <a href="http://www.aereo.com/">Aereo</a> story for a few months now. Aereo is a service that allows you to watch and record live television from anywhere within you home coverage area via an Internet connected device.  What Aereo does is connect you to a dedicated antenna that pulls in OTA TV signals and then sends it to you via the Internet so long as you are physically in your local network coverage area.</p>
<p dir="ltr">The networks are all in a huff about this service. They are sueing Aereo claiming that the service is infringing on their copyrighted material. So far the courts have upheld Aereo’s rights to provide the service. The fight will probably end up in the Supreme Court. But this got us wondering why its such a big deal? We understand that the networks make money on retransmission fees but what if this is the beginning of something that will generate even more money? People, and businesses, hate change. Here is our view on what Aereo could mean to the networks.</p>
<h4>Over the Air TV is Free isn’t it?</h4>
<p dir="ltr">There is no reason to pay for network TV since it comes over the air anyway. Anyone can put an antenna on their roof and pick up pristine HD broadcasts. If you are lucky enough to live close to the TV transmitters this can be done with some very cool indoor antennas like the<a href="http://www.htguys.com/podcasts/2011/7/29/podcast-489-mohu-paper-thin-hdtv-antenna.html">Mohu Leaf</a> or <a href="http://www.htguys.com/podcasts/2012/9/28/podcast-550-solid-signal-hd-blade.html">Solid Signal HD Blade</a>. Otherwise you will need a larger outdoor antenna but you will still be able to watch your networks. The networks make their money by selling ads on TV programming and that’s how it was for years and years. Then in the 80’s cable TV systems sprouted up everywhere and you no longer needed an antenna. Plus you got a bunch of other networks that were only available on cable. In the 90’s Direct Satellite Broadcast systems also came on the scene and suddenly the country no longer needed over the air TV. In the transition the networks latch on to a new revenue source in the form or retransmission fees.</p>
<p dir="ltr">If HD had never been invented no one would care about OTA broadcasting. Standard Definition broadcasts had all kinds reception issues that degraded the picture quality. Cable and Satellite TV really improved the experience and thus dramatically reduced the number of people watching over the air. With HD on the other hand, if you get the signal locked you have a perfect picture. In many cases better than cable and satellite. Fast forward to today and you see more and more people getting their signals over the air.</p>
<p dir="ltr">With some viewers switching to Aereo there would be no net losses in viewers of network television. In fact there may even be an increase at certain times of the day. The networks should be able to charge the same amount for ads. The only potential loss would be the retransmission fees. But better to lose the fees than viewers. Losing viewers is what’s happening now. People are cutting the cord and watching their content online via legal and illegal sources. Why not allow a new means to view the content with those who have or will soon cut the cord?</p>
<h4>How Many of Aereo’s Viewers do not have Cable TV</h4>
<p dir="ltr">We’re not convinced that all of Aereo’s subscribers do not also subscribe to pay TV. In this case the networks get to double dip! They get the retransmission fees and the added eyeballs.</p>
<h4>Better Metrics</h4>
<p dir="ltr">Since Aereo is digital, the networks can get accurate and up to the second metrics about who is watching and what they are watching. This would allow the networks to insert targeted advertisements that would in theory command higher revenues. That sounds like a win for the networks.</p>
<h4>Larger Audiences</h4>
<p dir="ltr">Being able to watch network programming while you are out and about is a good thing. Whether its your kids watching children’s programming while you do the grocery shopping or a husband watching football while he goes shopping with his wife. Aereo can provide a larger audience to the networks. Larger audiences mean more ad revenue. That sounds like another win for the networks.</p>
<h4>Keep Cord Cutters in the Fold</h4>
<p dir="ltr">For the most part its cord cutters who are using the Aereo service and those eyeballs are lost to advertisers. If you block the service its unlikely that they will go back to cable. At least with Aereo you still have a chance to count their viewership and better yet sell directly to them. Cord cutters are going to cut the cord with or without Aereo. Might as well keep them in viewership counts. This is a break even for the networks. You might even say its a win since they don’t lose viewership.</p>
<h4>Keep People from Pirating your Content</h4>
<p dir="ltr">This is inline with keeping cord cutters in the fold. If people want your content and its not easily obtainable via legal means they will simply download it from the Internet. I (Ara) hate admitting this but I used to download music from Napster. My rationalization was that I had already paid for it on vinyl or cassette so why should I pay for it again in mp3 form. With that said I would have gladly paid 99 cents to buy only the tracks I liked. At the time nothing like that existed. Once you could buy music I stopped using Napster and bought my music. I even went back and bought tracks that I had already pirated. I liked the higher quality of the iTunes store. The exact same thing is playing out with TV and movies and the TV and movie industry are the only ones who don’t see it.</p>
<h4>Conclusion</h4>
<p dir="ltr">When it comes to TV, the content is already free with ads, so why does it matter whether those ads are coming over the air or over the Internet? It doesn’t! What matters to the networks is that they get their fees from the cable companies. That’s the real issue. If DirecTV decides that what works for Aereo also works for DirecTV, then the networks may be out a lot of money. Sure they can take their content off the air and onto pay cable or even open up their own streaming solution but that will take time and money. With all the competition for our eyeballs the networks are having a hard time understanding that they will be making less money. The only thing that can really stop the loss is creating great content and making easily available to everyone across the globe at the same time. Companies like Aereo are going to force this issue regardless of what the networks do. The networks should steer into the skid and embrace it or they will find themselves obsolete.</p>
