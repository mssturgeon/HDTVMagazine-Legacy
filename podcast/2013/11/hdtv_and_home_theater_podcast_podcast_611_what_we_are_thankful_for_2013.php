<h3>What we&#8217;re thankful for &#8217;13</h3>
<p dir="ltr">Thanksgiving is a time to, well, to give thanks.  So that&#8217;s what we&#8217;re going to do; give thanks for everything we have in our lives.  The things we&#8217;re most thankful for: our families, our health, our friends, and our wonderful listeners, don&#8217;t make good topics for a show about HDTV and Home Theater. So as is tradition over the last few Thanksgivings, on today&#8217;s show we give you our list of consumer electronics things we are thankful for.</p>
<p dir="ltr"><strong>Aereo</strong> - While neither of us actually use the service, nor will we be able to anytime soon from the list of cities they’ve announced, we love the concept. We’re thankful for what the service represents, change and choice for the consumer. And we’re thankful that Aereo hasn’t folded like Superman on laundry day under the mounting pressure. They’ve stood their ground.</p>
<p dir="ltr"><strong>Netflix</strong> - With Netflix there is literally always something to watch. In days gone by, you could sit for hours channel surfing, only to wind up watching the second half of the<br />
Matrix for the umpteenth time or a rerun of the Golden Girls. Not only does Netflix always have something to watch, we love the fact that they’re moving into original programming, bringing a new dimension to the service and possibly, like Aereo, shaking things up a bit.</p>
<p dir="ltr"><strong>Insteon</strong> - Insteon happens to be our flavor of choice for DIY home automation, so we’re thankful for it, and for how easy it is. But Insteon represents the ability for common guys like us to automate our homes without having to spend a fortune. It is a fun hobby and provides tremendous reward. Nothing makes a house into your house like custom automation. It doesn’t make it a home, but it makes it pretty darn cool.</p>
<p dir="ltr"><strong>The DVR</strong> - This little device has probably made our list every time we’ve done a Home Theater Thanksgiving show. No single device has changed  the way we watch TV and gather together as a family quite like the DVR. We’re thankful for the easy and convenience, for the ability to skip commercials, and most of all, for how much more family time we get because we can watch shows on our schedule, not the broadcasters’.</p>
<p dir="ltr"><strong>High Speed Internet</strong> - Most of the goodies and gadgets we’re thankful for require some sort of Internet access. It wasn’t too long ago, ok maybe it was a long time ago, but it doesn’t feel like too long ago that we had to use dial-up modems to access an Internet of static pages. Now we have always connected, blazing fast Internet that delivers movies, music, TV shows, and even packages (thanks Amazon!) instantly.</p>
<p dir="ltr"><strong>4K TV</strong> - One thing that never made out list was 3D TV. It isn’t gone, but the big push from all the manufacturers has disappear thanks to, in large part, the new push to 4K UltraHD TV. Anything that got us off the 4D kick deserves our thanks and gratitude. But beyond that, 4K could be great. The demos we’ve seen are awesome. We are thankful for those who move technology in the right direction, and 4K is certainly doing that.</p>
<p>And of course we have our listeners to be thankful for.  You make doing the show fun and, in a lot of cases, easier.  Thank you for your news leads, story ideas, email, voicemail, everything you send that we get to turn right around and use as show content. And thank you so much for keeping us going by supporting our sponsors, shopping at our store and feeding our caffeine addiction! You rock!</p>
