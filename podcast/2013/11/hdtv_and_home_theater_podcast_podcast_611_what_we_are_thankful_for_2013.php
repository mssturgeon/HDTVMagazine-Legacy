<p>Just wanted to say, I am swapping out all of my Airplay speakers and switching to Sonos Play 1 speakers, the $199 version.</p>
<p>I have long been one to &#8220;poopoo&#8221; the expensive Sonos system. &#8220;Hey, I&#8217;m better off with Airport Expresses, attached speakers, and Airfoil&#8221;.  Well, I have to admit, I was wrong.</p>
<p>The $199 speakers sound very good, but the integration with the Sonos controller on iPad and iPhone and Mac, is pretty amazing.  I purchased one, just to test them, with full expectation that I would bring it back after testing it for a week or so. Boy, was I wrong. I&#8217;ve started converting my other AE stations and will replace all of them eventually.</p>
<p dir="ltr">The speaker is small, but sounds great, especially for background listening while I work around the house. They come in black or white, which is cool.  One thing that convinced me that Sonos has seriously put some thought into this system, is the ability to shut off all lights on the speaker via your iPhone or iPad. I abhor bright, useless lights, so although this seems a small insignificant feature, it went far to convince me that these people are serious. I mean, I like sleeping in the dark.</p>
<p dir="ltr">I also like the physical size and minimal cords.  There is simply a well integrated power cord. No Airport Express hanging out the outlet with its green light, no cord from the AE to the speaker, and no big, stupid looking power bricks like many speakers have.  Just a simple power cord. In fact, I&#8217;m thinking about mounting them on the wall using a simple $49 bracket from Amazon.</p>
<p dir="ltr">The ability to group speakers into sets via software like downstairs and upstairs is useful. Being able to make two single speakers into a paired set is also cool. Playing Pandora or Spotify, or podcasts through the Sonos controller, something I was convinced would be awkward, is actually great. I didn&#8217;t realize it, but the Sonos device streams many services directly from the web (think Chromecast) and not your iPhone or iPad.  Start a playlist and it will just play in the background, even without an active app on your iPhone.</p>
<p dir="ltr">I can play Spotify, Pandora, iTunes libraries over the network, from my computer, iPhone, or iPad. I can even play your podcast! Also, thousands of radio stations, formatted in a very easy to use application.</p>
<p>I am a person who doesn&#8217;t mind paying a premium for a good product. This is one of them, and I am hooked into Sonos for the long haul.</p>
