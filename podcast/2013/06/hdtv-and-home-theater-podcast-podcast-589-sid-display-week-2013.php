<h3>SID Display Week 2013</h3>
<p dir="ltr">The <a href="http://sid.org/">Society for Information Display</a> held their annual Display Week conference in Vancouver, British Columbia, Canada last month from May 19 &#8211; 24.  The show came and went without so much as a mention on the HDTV Podcast, but in our reading and research since the show, it turns out some very cool innovations were on display. Next year’s show will be in San Diego, we might have to make a day trip out of it.</p>
