<h4>Flexible OLED</h4>
<p dir="ltr">LG had several panels on display at the conference. Among them was a <a href="http://www.engadget.com/2013/05/21/lg-5-inch-oled-display-hands-on/">5&#8243; flexible, unbreakable OLED screen</a>. Unlike the screens we’re used to on smartphones and tablets, this LG screen is made of plastic, not glass. Not only does that make it much more durable and difficult to break, it also makes it flexible. You can actually bend, twist and beat on the screen. It looks amazing.</p>
<p dir="ltr">Using plastic substrates instead of glass reduces manufacturing costs, so there’s an obvious benefit to those creating and selling smartphones and tablets. And the benefits for the consumer are obvious, who hasn’t had a screen crack on them at some point? According to<a href="http://www.engadget.com/about/editors/sarah-silbert/">Sarah Silbert</a> of engadget, LG was encouraging attendees to hit the screen with a hammer and twist it in whatever way they wanted. She reports the screen having a feel like a thick film strip.</p>
<p dir="ltr">Various internet reports have mentioned the screen will need to be brighter and have better resolution, when the screen does make it to market, but LG is confident they’ll be able to do that, as well as scale the technology to smaller and bigger sizes, in the near future. There’s no word on when it will be available, but you’ve got to think a technology like that will send shockwaves through the portable device market.</p>
<p>&nbsp;</p>
<h4>Quantum Dot</h4>
<p dir="ltr">We talked about Quantum Dot potentially being the &#8220;next big thing&#8221; in display technology on<a href="http://www.htguys.com/podcasts/2012/5/18/podcast-531-quantum-dot-display-technology.html">Episode 531</a> a little over a year ago. It looks like 3M and Nanosys would like to make that a reality very soon. The companies have announced that they will begin shipping samples of their Quantum Dot Enhancement Film to LCD manufacturers by the end of this quarter. They report that QDEF will produce a 50% wider color gamut than existing backlight technologies, while also consuming less power.</p>
<p dir="ltr">The QDEF technology is a drop-in replacement for existing backlight technologies in use in LCD manufacturing, so according to 3M and Nanosys, will represent zero additional cost in the actual creation of an LCD TV itself. So you’ll get colors that rival OLED using the existing LCD fabrication facilities. Sounds like a win-win for manufacturers and consumers. Of course the new Quantum Dot technology itself is more expensive to produce now than the current LED or CCFL light sources, but as the technology scales, it should come down in price.</p>
<p dir="ltr">While 3M and Nanosys are promising to ship qualification samples by the end of this quarter, and hoping products will be on the shelves within 6 months, Sony already has a few devices with Quantum Dot technology from QD Vision on the market, including a Vaio tablet and an Xperia smartphone and the &#8220;Triluminous&#8221; TV screens we saw at CES this year. Look like the &#8220;Triluminous&#8221; Quantum Dot technology has made it into the 4K TVs <a href="http://store.sony.com/webapp/wcs/stores/servlet/CategoryDisplay?catalogId=10551&amp;storeId=10151&amp;langId=-1&amp;identifier=S_4KTV">Sony is currently showing off</a> at their website. We aren’t sure why Sony hasn’t made a bigger splash with this.</p>
<p>&nbsp;</p>
<h4>Flexible Plasma</h4>
<p dir="ltr">Unlike the flexible OLED that LG showed off at 5&#8243;, Japan&#8217;s Shinoda Plasma Co. demonstrated a flexible, full size plasma display panel at the conference. For their efforts, they were able to garner the &#8220;Best Prototype at Display Week&#8221; award. When we first read about it, we thought it had to be a typo. How can the big, rigid, glass panels we all know as &#8220;plasma&#8221; be transformed into a flexible, bendable screen?</p>
<p dir="ltr">Turns out its no typo. But it’s not quite as flexible as the OLED either. The screen itself can be rolled up, but not bent or twisted. It works like a pull down front projection screen. It can only be rolled in one dimension, and really only in one direction in that dimension. So you can’t roll it up sideways or decide you want to roll it up backwards. In fact, the technology is a lot like a wooden or bamboo shade you might use to cover a window.</p>
<p dir="ltr">They call it &#8220;Luminous Array Film,&#8221; or LAFi. It uses thousands of tiny glass tubes that measure one millimeter in diameter. When rolled out, the individual tubes form the equivalent of the one large glass surface we’re used to seeing in a plasma screen. The prototype panel was three feet wide and can be rolled up into a cylinder less than four inches in diameter. Sure this doesn’t seem as amazing as plastic OLED, but imagine being able to pull a 100” screen down from the ceiling, with performance equivalent to a VT60, even in a bright room, no projector required. Could be pretty great.</p>
