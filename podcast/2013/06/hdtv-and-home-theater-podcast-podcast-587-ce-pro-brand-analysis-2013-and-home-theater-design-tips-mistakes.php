<p dir="ltr">Integra dominated this segment again this year with the same outrageous 60%. Hanging in at number two on the list was Denon down to 27% from 31% last year.  Marantz hangs onto the number three spot with 24%, but had to share it this year with Sony, who jumped up to 24% from 20% last year. Rounding out the list are Pioneer at 23% and Yamaha at 18%. This is the first time Yamaha has made the top five. The Pioneer Elite brand was at 20% last year but dropped out of the top this year completely.</p>
<h4>Projectors</h4>
<p dir="ltr">Oh how the mighty have fallen, the consummate champion, Runco dropped from its almost historic run at number 1 all the way to a tie for fourth place with JVC at 34%. Runco had a substantial lock on first place last year with 46%. The new number one for 2013 is Epson with 47%. Braden has been trying to tell you. The list also includes Sony at number two with 40% and Digital Projection at number three with 37%. SIM2 rounds out the top brands with 11%.</p>
<h4>Flat-Panel TVs</h4>
<p dir="ltr">Unlike Runco’s dramatic fall from number 1 to number 4 in projectors, Samsung, who crushed the competition last year with 88% hangs onto the top spot this year with 87%. Sony has lost the second place spot to Sharp with 51%; Sony has 47%. Rounding out the top five were LG (33%) up from number five last year, and Panasonic (30%). While they didn’t make the list, CE Pro also points out that Runco took a beating in flat panels as well, dropping from 21 dealers to only 8. Value was the big theme in this years survey; evidently Runco isn’t seen as a value brand.</p>
<h4>Other</h4>
<p dir="ltr">If you have time to peruse the full report, we’d encourage you to. The survey covers everything from architectural speakers to outdoor speakers; audio servers, video servers, wireless audio systems; lift mounts and racks; whole house automation, lighting control and universal remotes. You name it, they have a category for it. If you want to know what the pros are installing, this survey is a great starting point.</p>
<p dir="ltr">
<h3>Home Theater Design Tips &amp; Mistakes</h3>
<p dir="ltr">This <a href="http://www.cepro.com/whitepapers/details/home_theater_design_tips_mistakes/">CE Pro White Paper</a> starts off by making the point that “A great home theater is more than just a big screen and a nice projector.” The authors then go on to explain several concepts in home theater to introduce some tricks of the trade and warn you against some of the more common pitfalls encountered in designing and building a home theater. Most of the tips revolve around what to sell and how to sell it, and focus primarily on seating, audio design and lighting.</p>
<h4>Material Matters</h4>
<p dir="ltr">One point made by Gerry Lemay, founder of the Home Acoustics Alliance (HAA), is something we’ve probably never mentioned before, and may be new to some listening. He advises installers to use cloth seats, not leather, when designing a home theater. He believes that the reflective nature of leather is less desirable than cloth seating. Cloth makes perfect sense from a sound absorption perspective, but so many home theater chairs are leather, you’d almost assume the leather was just as good.</p>
<p dir="ltr">We don’t have any measurements or even anecdotal evidence to prove or refute Mr. Lemay’s claim, so we’re simply passing it along. Intuitively it does seem to make sense that leather would be more sound reflective than cloth. On the other hand, the percentage of chairs and seating you find at typical furniture stores marketed as home theater seating that’s made of leather is very high. How could the whole industry be so wrong? Unless they’re simply making and selling what the customer wants, and nobody is educating the customer on the pros and cons.</p>
<h4>Where do you sit at the Movie Theater?</h4>
<p dir="ltr">John Caldwell of Motif Grace distribution advises dealers to ask their customers where they like to sit when they visit the movies, assuming the theater isn’t too crowded and they can actually select their favorite spot. So we’ll ask you now, take a second and think about where you like to sit. Are you a front row person, a front third of the theater viewer? Do you like to sit near the middle or just slightly behind middle? Or maybe you like to sit all the way to the back &#8211; and please assume for this activity that you’re there to watch the movie and not engage in other extracurricular activities.</p>
<p dir="ltr">Depending on how you answer, it could help you decide where to put your seats, as well as ideal screen size and other options. According to Mr. Caldwell, the standards and formulae we use for viewing angle and seating distances were developed to match the experience in the last row of a commercial movie theater.  That’s where we get the minimum seating distance numbers that range from 1.3 to 2 times the screen width. He advises changing those values and instead using something like 0.9 for those who like to sit in the middle third of the theater and 1.0 for those who like to sit in the first third of the commercial movie theater.</p>
<h4>Show me ‘Paint the Fence’</h4>
<p dir="ltr">Apologies for the Karate Kid reference, especially since it doesn’t even really even apply, but just as painting the fence was essential to young Daniel’s success in martial arts, painting the walls and even the ceiling, could be very important to your home theater. We’ve talked about selecting the right color and paint finish several times before, but it isn’t a topic we deal with often, so it bears repeating. Movie theaters are painted dark for a reason. Light or bright walls are a bad idea in a theater.</p>
<p dir="ltr">Dark, neutral or earth tones tend to work best in a home theater. Light reflecting off a red or blue or green wall will tint the image on screen and upset your calibration. And before you ask, this reflection is nearly impossible to “calibrate away” because the amount of reflected light is never constant. Since most people don’t want to feel like they’re living in a cave, so you have to make compromises. If you have to give in on the color, stay firm on the sheen. Sure glossy paint is easier to clean, but even glossy darks still reflect some light. Matte or flat paints reflect much less.</p>
