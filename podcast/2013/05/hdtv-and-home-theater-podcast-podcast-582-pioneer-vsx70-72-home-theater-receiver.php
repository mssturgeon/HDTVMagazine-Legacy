<p>&nbsp;</p>
<h4>Performance</h4>
<p>We’ll look at video performance first. The unit has a 4K scaler and pure cinema video processing. We don’t have a 4K TV so we can’t comment on the 4K scaling but we can comment on the pure cinema video processing. We turned it off. It just looked off and motion was choppy. Once we turned it off and let the signal go through to the TV everything was fine.</p>
<p dir="ltr">Audio had better results, after we tweaked the calibration a tiny bit. We weren’t happy with the subwoofer as it was turned way down by the auto calibration. A quick entry into the iControl app to turn up the gain on the subwoofer and we were back in business with booming bass. For our listening tests we listened to 256Kbps AAC audio, Blu-ray, and ATSC TV. We also played some music from Pandora which is built into the VSX-70. We have the premium 192Kbps Pandora so the audio is of decent quality.</p>
<p dir="ltr">Our iTunes and Pandora sound great! Well as great as those formats would allow but considering our environment, that of a typical home, most people will find the audio reproduction of their libraries quite nice. We did throw some CDs, yes we still have some laying around, and some lossless aac files and as expected they too sounded great. We struggled to hear the difference but when listening to classical music its was apparent, especially in the higher frequencies. Mate this receiver up to a good set of speakers and you will not be disappointed!</p>
<p dir="ltr">For movies we had a lot of listening experience from the Blu-ray reviews that we do and were able to go back into our notes and compare. In all cases the VSX-70 sounded as good or better than the older Elite we use to review our Blu-rays. We still get a kick out of the train crash scene in Super 8. Some of the best demo material out there and the VSX-70 was true to the sound designer. There was plenty of power and we were able to go up to ear pain levels without any distortion. The audio had a tight and solid feel.</p>
<p>&nbsp;</p>
<h4>Odds and Ends</h4>
<ul>
<li>iControlAV2013 Remote Control App for some Android devices and iOS. The app is nice and has more info and functionality than most people will need or use. For the power user it provides detailed infor about your room calibration and allows for tweaks with the flick of a finger. For typical users the app will do everything the physical remote does but available from your tablet or phone. Quick tip, take the unit out of eco mode if you want to turn it on via WiFi.</li>
<li>Airplay and HTC Connect - We streamed music from our iOS devices to the VSX-70 via Wifi with no issues. We did not have an HTC device so we weren’t able to test the HTC connect feature. You can also plug an iPhone into the USB port on the front of the panel and control it from a full color GUI.</li>
<li>DLNA &#8211; If you have Windows 7® you can stream your content using DLNA, you can also use Pandora®, or finally you can vTuner® to stream Internet Radio from all over the world. Even with these features we found it simpler to find what we want on our portable device and just send it to the receiver via Airplay.</li>
<li>Adapters &#8211; Both Bluetooth and Wireless adapters are available if you do not have a hardwired connection.</li>
</ul>
<p>&nbsp;</p>
<h4>Conclusion</h4>
<p dir="ltr">The VSX-70 is a solid receiver that is packed with loads of features. Most of which you will like! Full two way control via IP is a great feature especially if you are using a tablet based controller like <a href="http://iruleathome.com/">iRule</a> or <a href="http://www.roomieremote.com/">Roomie</a>. Sound quality is fantastic and will really draw you into a movie or let you drift away listening to your music. At $750 it costs more than budget receivers but does so much more. You can buy VSX-70 even though you may not need all the features but its nice to know that you will have room to grow.</p>
