<h3>Rec. 2020: UHD Decoded</h3>
<p dir="ltr">There’s a lot of buzz in the home theater industry around the forthcoming Ultra High Definition, or UHD televisions, sometimes called 4K TVs. It turns out the UHDTV specification, often referred to simply as Rec. 2020, gives us quite a bit to be excited about, quite a bit more than just a bump in resolution. When we’ll ever get content for it, or whether or not televisions will really be able to take advantage of it anytime soon remains to be seen. But the spec looks good.</p>
<h4>The Specification</h4>
<p dir="ltr">The formal name for Rec. 2020 is ITU-R Recommendation BT.2020; you may also hear it referred to as simply BT.2020.  It was posted on the ITU (International Telecommunication Union) website just under one year ago, in August of 2012.  Rec. 2020 defines all of the specifics of what the rest of us call Ultra High Def television (UHD) including the one most talked about, display resolution,as well as the lesser discussed items such as bit depth, color space, frame rate and chroma subsampling.</p>
<p dir="ltr">Like the ATSC specification, Rec. 2020 defines multiple possible resolutions.  While ATSC, in the US at least, via ATSC A-53,included three-ish: 480 (480 x 640 and 480 x 704), 720 (720 x 1280) and 1080 (1080 x 1920), Rec. 2020 includes only two: 3840 × 2160 (what we call 4K) and the massive 7680 × 4320 (often simplified to 8K). Both resolutions are 16:9 format and use square pixels.</p>
<p dir="ltr">With Rec. 2020, interlaced scanning is a thing of the past; it only provides progressive scan frame rate options. It has been so long since we’ve discussed the topic of processive scan, you almost start to forget what that “p” in 1080p stands for. While ATSC topped out at 1080p/30 or 720p/60, the UHD specification covers all the standard rates like 23.976p, 24p, 25p, 29.97p, 30p, 50p, 59.94p and 60p and does you one better. UHD has 120p built into the spec, at either of the two ridiculously large resolutions.</p>
<p dir="ltr">In addition to resolution and frame rate improvements, UHD will also give you better colors than you’ve ever had. Rec. 2020 defines color representation at 10 or 12 bits per color. The color scale for the current HDTV format we’re used to watching is defined in Rec. 709 and uses 8 bits per channel. According to <a href="http://informationdisplay.org/IDArchive/2012/NovemberDecember/FrontlineTechnologySuperHiVisionasNextGen.aspx">InformationDisplay.org</a>, the Rec. 2020 color space covers 75.8%, the Digital Cinema reference covers 53.6%, Adobe RGB covers 52.1%, and Rec. 709 covers only 35.9%.</p>
<h4>What does it mean to us?</h4>
<p dir="ltr">So that’s a lot of numbers and fancy math to say that UHD is more than just better resolution. That kills the argument that UHD doesn’t matter on smaller screens because all screens can benefit from the options made available by the improved frame rates and expanded color gamut. While it may not make sense to jump into a UHD set simply for the better resolution &#8211; because you’ll never be able to see it, there is a possibility you’ll see benefit from other aspects of the specification.</p>
<p dir="ltr">To throw some more numbers in the math soup we’ve already created, our current TVs based on Rec. 709 can show just under 17 million unique colors. Using the 12 bit color option in Rec. 2020, UHD sets should be able to show almost 69 billion colors. Yes, billion with a “b” (and yes, 69 dudes). While this is possibly the most exciting part of the spec, it is also likely to be the slowest adopted. A change of that magnitude would require changes in the entire video pipeline, from camera to editing to encoding/mastering and broadcast, then into decoding and playback. Without all the required changes upstream, there’s no telling what a TV show or movie would look like on your new UHDTV.</p>
<p dir="ltr">We’ve talked about how well some of the 4K demos we’ve seen have been able to upconvert pristine 1080p content into crystal clear 4K that looks amazing. Imagine trying to do something similar, but mapping 17 million colors into 69 billion. You think TVs were hard to calibrate before? And you thought the colors might be a bit off on your in-law’s TV? You ain’t seen nothing yet. OLED can handle the new color space, but since most manufacturers won’t want to deal with the potential issues, thus eliminating the need for the better colors, they’ll skip it in LCD/LED displays. They’ll wait until there is content that requires it.</p>
<h4>Bottom line</h4>
<p dir="ltr">Ultimately the adoption of UHD will be driven by content. If content is readily available and the difference is dramatic enough, UHD could be the next HDTV revolution manufacturers have been searching for. But if you can’t get content, or if when you do, the difference is so minor you don’t really notice it &#8211; due to compression or simply limitations of the human eye &#8211; the TVs will trickle off the shelves until they ultimately become the standard and you end up buying one by default. Hopefully we’ll get the content.  First the 4K, then the 8K!</p>
