<h4>OLED</h4>
<p dir="ltr">We all know OLED has been an incredibly slow moving technology. We’ve been talking about it on the HDTV Podcast for nearly five years, and there still aren’t any OLED TVs available, at least not here in the US. That lack of progress over such an extended amount of time scares us a little. It makes you think that even when the TVs do start to ship, they’ll have quite a few kinks left to work out before they’re really ready for prime time.</p>
<p dir="ltr">But OLED promises an amazing home theater experience. The OLED technology, even at existing 1080p resolutions, provides a strikingly better visual experience than either of the two present formats, LED and Plasma. It is a brand new technology, offering markedly better color and contrast performance. Viewing content on an OLED screen is amazingly vivid and almost appears 3D, even with 2D content. And OLED, on average, consumes less power than LED or Plasma.</p>
<p dir="ltr">Prices for OLED have come down from early reports, but they’re still up there. LG is selling a 55” OLED in Korea for the equivalent of $10,000 US and their curved OLED should be available later this year for close to $13,500.</p>
<h4>4K (UHD)</h4>
<p dir="ltr">Of the two technologies, the one that is within the closest reach has got to be 4K, also known as UHD or Ultra High Definition. While a 55” OLED will cost over $10,000 when you can eventually get your hands on one, there are 4K TVs availble right now at <a href="http://www.htguys.com/amazon">Amazon.com</a> for much more affordable prices.</p>
<ul>
<li><a href="http://www.amazon.com/dp/B00BXF7I9M/?tag=hdtvandhometh-20">Seiki Digital SE50UY04 50-Inch 4K UHD 120Hz LED HDTV, $1445</a></li>
<li><a href="http://www.amazon.com/dp/B00BSREPRS/?tag=hdtvandhometh-20">Sony XBR-55X900A 55-Inch 4K Ultra HD 120Hz 3D LED UHDTV, $4998</a></li>
<li><a href="http://www.amazon.com/dp/B00BSREQI6/?tag=hdtvandhometh-20">Sony XBR-65X900A 65-Inch 4K Ultra HD 120Hz 3D LED UHDTV, $6998</a></li>
</ul>
<p dir="ltr">The move from 1080p to 4K, or roughly 4 times the resolution, is great. Content will be clearer, more crisp and better defined. You’ll be able to watch content while closer to the screen or on a much larger screen without having to worry about seeing any pixels. The UHD demos we saw at CES were great, especially when paired with 4K content, or very high quality 1080p content upconverted to 4K. Both were very impressive.</p>
<p dir="ltr">But the upgrade from 1080p to 4K is just that, a resolution upgrade, nothing more. You’re still watching on the same LED TV technology that your neighbor has in his (or her) 1080p TV. You get the same color representation, the same contrast performance and all of the same drawbacks like off-angle viewing and potentially even motion blur or ghosting. It’s roughly equivalent to upgrading from the old 480p EDTVs of yesteryear to a modern 1080p TV. Sure the TV looks sharper, but otherwise there’s not much difference.</p>
<p dir="ltr">Then there’s the whole issue of content. There is no over-the-air or free-to-air specification for 4K, so you’re looking at years, possibly decades, before that will happen. The current Blu-ray spec tops out at 1080p/24 or 1080i/60, so it’s no good for 4K either. That leaves Cable / Satellite or streamed / downloaded. Both of which are viable, but probably not in the short term. Bandwidth needs to improve, or the Cable and Satcasters need to do a serious equipment upgrade first.</p>
<h4>So which is it?</h4>
<p dir="ltr">So which one wins? Is it the technology that is available now for only a slight premium that looks great in some ways, but looks the same in others and has no content, or the technology that will be available {hopefully} soon for a significant price premium that offers a completely different viewing experience, but at the same resolution you’re used to? For our money, we say neither.  Wait until the prices come down on OLED and maybe by then they’ll have the kinks worked out and be available in 4K as well.</p>
<p dir="ltr">But as of today, unless you’re in the market for a TV anyways, and the 4K is only a slight premium over the 1080p TV you like, we advise you hold off on the UHD technology as well. There’s no content for it (of course we heard that with HD back in the day, but that’s a different story) and odds are unless your screen is huge or you’re sitting right next to it, you won’t even see much of an improvement.</p>
<p dir="ltr">Save yourself some money and buy a <a href="http://www.amazon.com/dp/B00BC4SN9S/?tag=hdtvandhometh-20">1080p Panasonic Plasma</a> instead.  It’ll look amazing and last for as long as it takes for OLED to hit reasonable prices, 4K content to become readily available, or some other technology, like Quantum Dot, to come out of nowhere and kill them both.  For all we know, OLED could be the next Laserdisc.</p>
