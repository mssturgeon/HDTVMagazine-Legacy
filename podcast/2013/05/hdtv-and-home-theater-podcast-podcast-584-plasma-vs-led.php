<p dir="ltr">We have been talking about the demise of plasma for at least three years. But with each passing year manufacturers come out with plasma TVs that are simply the best TVs on the market. In a CNET article titled <a href="http://reviews.cnet.com/flat-panel-tvs/panasonic-tc-p60vt60/4505-6482_7-35566958.html">Best HDTVs Overall</a>, the top 5 TVs were plasma, and that doesn’t even include the forthcoming Panasonic ZT60 which won best of show at CES. In the following paragraphs we’ll try to compare and contrast the plasma and LED LCDs and see if there is a real reason why LEDs are putting plasma out of business.</p>
<h4>Room Type</h4>
<p dir="ltr">Let’s start out by looking at the type of room the TV is going to be in. If its a bright room with minimal or no light control you are probably going to want an LED. LEDs are brighter than plasma and their screens typically are more glare resistant. Although that is changing because for some reason more manufacturers of LEDs are going to glossy screens. Plasmas aren’t dim by any stretch but they are not as bright as LEDs. We have a plasma in our family room and an LED in our den. Both are viewed during daylight hours and we do have to control the light in the family room. It has never been an issue in the den. However, at night when the lights are low the plasma has a much better picture.</p>
<h4>Light Uniformity and Black Levels</h4>
<p dir="ltr">Edge lit screens can have issues with light uniformity. Terms like Clouding , Backlight bleeding, halo, and flashlight are used to describe various issues with LED lit screens. Its more of an issue with edge lit TV than direct lit. These anomalies are mostly affect dark scenes with bright spots. Think credits. It can really take away from the picture. We reviewed a direct light LED from Vizio that we really liked because it produced better blacks but a halo was clearly visible in the darker scenes, or when we were watching a letterboxed movie.</p>
<p>Plasma on the other hand have the best blacks bar none. You won’t see clouding or flashlight effects on a plasma panel. With these deep blacks, plasmas can achieve high contrast ratios, the ratio of the darkest part of an image and the brightest part. High contrast ratios screens seem more lifelike and have more depth.  There are some LEDs that can achieve deep blacks and high contrast ratios but we’re talking Elite screens that cost two or three times that of a plasma.</p>
<h4>Color</h4>
<p dir="ltr">Plasma is typically more faithful in reproducing color that is more vivid and lifelike. Some LEDs have approached the same level but they typically cost more and are still matched in performance by mid tier plasma TVs. A plasma can control the brightness and hue of each pixel more efficiently than an LED so its color is more saturated and richer.</p>
<h4>Image Retention</h4>
<p dir="ltr">A big issue with plasma televisions is a concept called Image Retention. That’s where a portion of the screen retains an image that has been on screen for an extended period of time. This can be an issue for gamers or someone who watched a lot of news. While a big issue with earlier plasmas the issue has been reduced with new panels. In many cases image retention can be reversed by displaying white noise (snow) on the screen until the image is eliminated. You will typically notice some retention long before you have an issue with Burn in. LEDs can also have retention issues but its less likely.</p>
<h4>Everything Else</h4>
<ul>
<li><strong>Viewing Angles</strong> - Plasma’s picture does not degrade when viewed off angle. In-Plane Switching (IPS) helps LEDs but it does so at a cost of contrast.</li>
<li><strong>Weight</strong><strong> </strong>- Plasmas weigh more than LEDs. If you plan on mounting a TV on the wall you still can with a plasma it just may be slightly more difficult. Once installed weight is really not an issue any longer.</li>
<li><strong>Size</strong><strong> </strong>- If you want to go larger than 65 inches LED is really the only option.</li>
<li><strong>Energy Consumption</strong> - LEDs use less energy but total yearly savings will be less than $50.</li>
<li><strong>Lifespan</strong><strong> </strong>- Both should get you 15 to 20 years under typical use.</li>
<li><strong>Price</strong><strong> </strong>- Its hard to match the value of a plasma when you consider  size/price and quality/price.</li>
</ul>
<h4>Bottom Line</h4>
<p dir="ltr">Its hard to find a reason not to pick plasma. Better color, contrast, and the deepest black levels make it the perfect TV right? Well, maybe for some. About the only reason we would not pick plasma is if you want a screen bigger than 65 inches or you are constantly gaming. Its hard to get a good side by side comparison in a big box retailer. You’ll have to go to a friend who owns a plasma and look at their screen. Of course there won’t be an LCD right next to it for comparison. Or you can take our word for it, buy a plasma and enjoy some of the best TV you have ever seen.</p>
