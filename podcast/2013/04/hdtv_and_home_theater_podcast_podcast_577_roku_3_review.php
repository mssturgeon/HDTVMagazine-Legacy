<h4>Setup:</h4>
<p dir="ltr">The physical setup is no different than any other streaming player, plug it in, connect HDMI and you’re done.  There’s an Ethernet port if you want to go hard-wired, but you don’t need it if you plan to use it with WiFi. It took longer to pull it out of the box than it did to get it installed. Setting up a wired connection takes seconds, configuring WiFi takes about as long as it takes to type in your WiFi password. This is where you start to notice the new, faster hardware.</p>
<p dir="ltr">The next step is the obligatory firmware update on first boot. Considering we got ours almost immediately after it was announced, we didn’t really expect a firmware update, but there it was waiting for us nonetheless. Such a quick turnaround on firmware can either be really good or really bad &#8211; either the box is full of bugs and they shipped it too soon or they’re aggressively pushing out new features and making even better.</p>
<p dir="ltr">But the firmware update is another instance where you really notice the updated hardware. It might have been the fastest firmware update of any home theater device we’ve reviewed. Most devices give you plenty of time to go get a snack, grab something to drink, walk the dog, read a novel&#8230;but the Roku 3 was done before we could get our lazy butt of the couch.  It was impressive.</p>
<p dir="ltr">The Roku channels &#8211; 750 and counting &#8211; are what have classically set the Roku apart from every other device. You can get all the usual suspects, Netflix, Hulu, Vudu, Blockbuster, Pandora, along with a ton of others. Some could be great, depending on what you’re into, like the MLB or MLS channels, and some are ridiculously obscure. Adding and configuring channels is what takes the lion’s share of the setup time. you have to visit each one and enter your username and password.</p>
<h4>Use:</h4>
<p dir="ltr">As far as the standard channels go, the Roku isn’t much different than all the others. It supports up to 1080p and 5.1 surround which is better than some of the older streamers, but on par with the modern ones. The content didn’t look any better or worse on the Roku than it did on the WD TV Play we reviewed a few weeks ago, or pretty much any other streamer out there. The standard apps aren’t what set the Roku 3 apart.</p>
<p dir="ltr">The first thing that sets the Roku 3 apart is the speed. The interface is ridiculously responsive. Where we’ve gotten used to other streamers “sticking” on certain options or logos when you try to navigate menu and options, the Roku 3 never did. It was effortless to get to anything you wanted, and typing, which can be a nightmare on other boxes, was perfect on the Roku 3. We never accidently pushed the arrow button too many times because it didn’t respond the first time, only to overshoot the letter and accidently enter the wrong one, then have to navigate down to the delete key&#8230;sound familiar?</p>
<p dir="ltr">The next true differentiator is the actual navigation. Roku has gone out of their way to make navigation very simply and quick. Almost all menus and icon style options will automatically cycle back to the beginning when you reach the end of a list, so you don’t get stuck at the bottom and have to scroll all the way back to the top again. Scroll up and down to see more options in the current category, or right drill deeper into an option or left to pull up a level higher.  It is very simple. As simple as they should all be.</p>
<p dir="ltr">The channel options on the Roku 3 are great. It doesn’t matter what you’re into, foreign content, horror movies, sports, sci-fi, anime, there’s a channel for that. You can use the Plex channel to stream your own movie collection to the Roku 3. Everything is at your fingertips. Hot on the heels of our WD TV Play review, the one channel we found lacking is the absence of a Slingplayer for your Slingbox. Why they don’t have one is still a puzzler to us. it seems like such an obvious fit. Without it, we felt a great potential is lacking on the Roku platform.</p>
<p dir="ltr">But the true killer app on the Roku 3 is the new unified search. The Roku 3 will search your installed and configured channels for the movie or TV show you want to watch. Then it will give you the options for where you can see it, how much it will cost you, and whether or not it is available in HD at each provider. You can even search by actor, director, etc. We found what appears to be a bug where content that is only available for purchase from Vudu didn’t appear in the search, but everything else came up just fine. And the searches are fast. Lightening fast.</p>
<p dir="ltr">The remote is pretty cool. You can use it to play games, like Angry Birds, on the Roku 3 just like you could on the higher end Roku 2 devices. The included headphone jack is great for late night viewing. It automatically mutes the output of the Roku box, so it doesn&#8217;t matter if you’re using a TV or a surround sound receiver, it will work the same with both. We couldn’t find a way to use the headphone jack as a supplement to the standard output. For us it was only one or the other.</p>
<h4>Conclusion:</h4>
<p dir="ltr">The Roku costs the same as all the other streaming players out there, but has some very compelling features that they don’t have. Other than the lack of a Slingplayer, there’s really nothing bad to say about it. Is it enough to convince a die hard Apple fan to swap out their Apple TV, probably not. Odds are there isn’t a device made that could do that. But if you aren’t entrenched in the iTunes ecosystem, you’ll find the Roku 3 will meet or exceed any expectations you have for a streaming player.</p>
