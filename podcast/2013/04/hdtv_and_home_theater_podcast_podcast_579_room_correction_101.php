<h4>The Background</h4>
<p>Your home theater has a unique personality, a unique character that determines how music, movies and television sound. The acoustics of the room are influenced by the size and shape of the room, walls or lack of walls in some cases, wall height, wall material, windows, acoustic treatments, floor material, furniture, and the list goes on. All these factors influence how sound travels in the room, ultimately making some frequencies louder and making others softer, or even cancelling them out altogether.</p>
<p>Some of these personality quirks can be overcome by changing speaker or subwoofer locations or directions. Others can be overcome by adjusting furniture or adding window coverings, wall treatments or rugs. But some of the more advanced corrections come in the form of Digital Room Correction (DRC), sometimes also referred to as room equalization or EQ. Leveraging the power of modern digital technology and Digital Signal Processing (DSP) can transform an average listening room into a sensational audio experience.</p>
<h4>Where to Start</h4>
<p>The first step in Room Correction is that little microphone that came with your receiver. If yours didnâ€™t come with one, youâ€™ll need to get a bit more advanced for your first step. There are software packages you can buy for your computer, and even some you can get for tablets and smartphones, that will analyze room acoustics and recommend EQ changes. But those packages are beyond the scope of our discussion.</p>
<p>For today weâ€™ll stick with the DRC/EQ mic that came with your receiver. If you didnâ€™t get one and were looking for an excuse to upgrade, youâ€™re welcome. They all run in pretty much the same manner. You plug the mic into the front of the receiver, place it at your regular listening position, then start the dynamic EQ process from the menu options. Depending on the receiver you have, the whole process can take between five and twenty five minutes.</p>
<h4>How Does it Work?</h4>
<p>The DRC process works by playing a set of known tones or signals through each speaker and recording the output using the microphone. The microphone is able to measure the magnitude of each frequency in the test tone, the receiver then compares that with a target magnitude or volume level, and makes the proper adjustments until the measured value matches the desired value. Once those adjustments have been made for each speaker at each of the measured frequencies, you have a custom EQ specific to your home theater.</p>
<h4>Why Do It</h4>
<p>First of all, why not? If you have the mic anyways, why not plug it in and see what happens? There will be cases where the dynamic EQ may not sound any better to you, or might even sound worse, but itâ€™s at least worth giving it a try. In the early days of DRC, we prefered to do it ourselves and dial in our own settings to our own listening preferences. In recent years however, with the advancements weâ€™ve seen in the technology, especially by companies like Audyssey and others, digital room correction has become quite good and well worth the twenty minutes.</p>
<p>All rooms suffer from something called room modes, and typically more than one mode exists in every room. A room mode, also called a standing wave, can wreak havoc on your listening experience by amplifying or eliminating certain frequencies at your listening location. Room modes can cause a room to sound very different to two listeners in different places in the room. Room correction can be very effective at reducing the impact of room modes on your listening experience. Audyssey will have you take multiple measurements with the microphone in an attempt to address more issues throughout the room and not just in the main listening position.</p>
<p>Room Correction is one tool in your toolbox you can, and should, use to improve the sound quality of your home theater. Combined with correct speaker placement, acoustic treatments and other wall and windows coverings to reduce reflections, DRC can transform a ho-hum room into one that really hums. It canâ€™t fix everything, but if you know the gear you invested in should be sounding better than it does, it is a great place to start.</p>
