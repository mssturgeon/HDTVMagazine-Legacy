<p dir="ltr"><strong>Product Placement will be big</strong> - <em>With so many DVRs out there advertisers are looking for a way to put their brand in front of you. This year I am saying that it won’t be subtle but more in your face. Rather than just seeing the product look for dialog about how good the product is. There have been a few examples of this with Toyota and Bones. Look for the cell phone companies to talk about communications on any action/cop show.</em></p>
<p dir="ltr"><strong>Not Really</strong>. Still about the same as 2012.</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>Apple will enter the home automation market</strong> - <em>Since 2012 was the year of home automation <img src="http://s1.wp.com/wp-includes/images/smilies/icon_wink.gif" alt=";-)" class="wp-smiley" />  Apple will make 2013 the year of plug and play automation. They are rumored to be interested in id8 Group R2 Studios Inc which is a startup company developing home media and automation technology. Look for Apple to tie your entertainment, lighting, and security together in a neat easy to setup package. So does this make 2013 the year of home automation?</em></p>
<p dir="ltr"><strong>Fail</strong>. Maybe next year?</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>We’ll see a “True” smart TV</strong> - <em>I’m not talking an Internet connected TV but more of a TV that truly has some brains. Something that can sense who is in front of it and configure itself for that viewer. If more than one person is in front of the TV then maybe go into family mode or something like that. It will be voice activated. Actually it will be a cross between GoogleTV, AppleTV and a computer. Look for Samsung to develop the first True Smart TV.</em></p>
<p dir="ltr"><strong>Fail</strong>. Didn’t quite happen yet.</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>Movie Studios will eliminate DRM from their content</strong> - <em>Following the lead of the music industry, the movie industry will see the err of their ways and make it easy for all of us to freely create video servers with legally owned content. This is my Hail Mary pass prediction. Probability of success&#8230;. less than 1%</em></p>
<p><strong>Fail</strong>. Still waiting.</p>
<p dir="ltr"><strong>Total score: 1/5 for a whopping 20%.</strong></p>
