<h4>Braden’s Predictions:</h4>
<p dir="ltr"><strong>Adios Mother Plasma</strong> - <em>Although plasma may have given birth to the flat screen revolution, the technology will be forced into early retirement in 2013.</em></p>
<p dir="ltr"><strong>Success</strong>! Panasonic, the stalwart supporter of plasma technology for the last few years announced they will be exiting the plasma business for good. While plasma will remain in stock for a while, Panasonic&#8217;s exit spells the end for a great technology. The technology that started the flat screen revolution. <a href="http://www.techradar.com/news/television/hdtv/panasonic-s-plasma-tv-exit-is-the-end-of-a-brilliant-era-1195314">Panasonic&#8217;s plasma TV exit is the end of a brilliant era.</a></p>
<p>&nbsp;</p>
<p dir="ltr"><strong>I’ll buy that for $300</strong> -<em> </em><em>The average selling price for a 42” 1080p LCD TV will be $300 by the end of the year, down from $480 in 2012.</em></p>
<p dir="ltr"><strong>Fail</strong>. Pricing stayed pretty flat, driven by advanced features and a push into LED technology. If the prices moved downward, it was only slightly, certainly not into the $300 range.</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>Let’s be more than friends</strong> - <em>As the economy continues to struggle and the price of electronics continues to plummet, 2013 will see at least one, maybe a few large mergers or acquisitions in the consumer electronics/home theater industry.</em></p>
<p dir="ltr"><strong>Fail</strong>. Microsoft acquired Nokia otherwise nothing. Zip. Zero. Zilch. Bummer.</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>Stream it to me</strong> - <em>This year will see new release available via streaming in an all-you-can-eat subscription package.</em></p>
<p dir="ltr"><strong>Fail</strong>. Lo and behold, this prediction still didn’t happen. Yet I continue to make it every year. It’ll be right eventually, you just watch. Sure you can get <a href="http://primacinema.com/about_prima_cinema.php">Prima Cinema</a> in your home now, so maybe I should get partial credit here. But I just can’t see taking partial credit on a system that costs $35,000 and $500 per movie.  If it was $3500 and $50 per movie, maybe.</p>
<p>&nbsp;</p>
<p dir="ltr"><strong>You can take it to grandma’s house</strong> - <em>In 2013 someone will show the prototype for a truly portable tablet computer. Not something thinner and lighter but still 10 inches by 8 inches, but something that either rolls up or folds up so you can very easily take it with you anywhere.</em></p>
<p dir="ltr"><strong>Fail</strong>. We got thinner and lighter, but still nothing flexible or foldable. Thinner and lighter is nice, but it’s an incremental change, I was looking for the game changer here, and came up empty.</p>
<p><strong>Total score: 1/5 for a whopping 20%.</strong></p>
