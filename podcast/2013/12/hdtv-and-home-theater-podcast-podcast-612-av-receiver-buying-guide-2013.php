<h4>$500 &#8211; $1000</h4>
<p dir="ltr"><a href="http://www.amazon.com/dp/B00CALM12W/?tag=hdtvandhometh-20">Denon AVR-X3000 7.2-Channel 4K Ultra HD Networking Receiver with AirPlay $900</a></p>
<p dir="ltr">Hard to believe this is what we would call mid-tier but its true. Some may say that a $900 receiver is not mid-tier, but in the larger scope of products out there, X3000 is right in the middle based on price. How about based on features? Well in that regard we would agree that it leans more towards the higher end units. It has 7 HDMI inputs, you know in case you have three Blu-ray players <img src="http://s1.wp.com/wp-includes/images/smilies/icon_wink.gif" alt=";-)" class="wp-smiley" />  It also has two HDMI outputs for multiple zone viewing. The X3000 comes with <a href="http://usa.denon.com/us/resources/pages/audysseytier.aspx">Audyssey’s Gold</a> package so you can get your sound exactly the way you want it. The unit is Airplay and Windows 8 compatible and comes with Denon Remote app for mobile devices. Honestly there are many more features that we can’t list here. This is a very capable receiver and will last you for years.</p>
<p>&nbsp;</p>
<p dir="ltr"><a href="http://www.amazon.com/dp/B0087KGNBA/?tag=hdtvandhometh-20">Yamaha RX-A2020 9.2-Channel Network AVENTAGE AV Receiver $1000</a></p>
<p dir="ltr">This receiver is at the limit for the range but is a bargain at the price. The A2020 is all about audio quality. Sure it has the same bells and whistles of other receivers in its class but this unit differentiates itself by using the highest quality parts get the most out of the sound. Yamaha also spent time in the design layout like laying out the left and right channels so that the crosstalk is minimized. Yes it supports Airplay, Network Audio, and comes with a mobile app for setup and control. Yamaha includes the YPAO auto calibration system with Reflected Sound Control for easy setup and optimization. Like the Denon, there are so many features we can’t list them all here. The A2020 is also a receiver that will do the job for years to come!</p>
<p>&nbsp;</p>
<p dir="ltr"><a href="http://www.amazon.com/dp/B007O5ATGO/?tag=hdtvandhometh-20">Pioneer VSX-1122-K 630W 7-Channel A/V Receiver $600</a></p>
<p dir="ltr">Our last mid-tier receiver is also the best bargain. At $600 its will probably be in the entry level range by summer. The VSX-1122 is certainly not a entry level receiver in terms of capability. It too is a 7 channel receiver that supports Airplay, iPad and iPods. For those with Windows it is certified to works with Windows 7 and DLNA 1.5. With an Internet connection you can stream Pandora and radio stations from around the world. Pioneer has their own auto calibration feature which will have you enjoying surround sound in no time. The iControlAV app gives you ultimate control of the settings on this receiver. So much easier than doing everything from the front panel. The 1122 will be the hub around which your home theater experience will center.</p>
<p>&nbsp;</p>
<h4>Greater than $1000</h4>
<p dir="ltr"><a href="http://www.amazon.com/dp/B00CS4X8S2/?tag=hdtvandhometh-20">Marantz SR7008 9.2-Channel 1080P and 4K Ultra HD Pass Through $2000</a></p>
<p dir="ltr">Our first unit is quite a bit more than the $1000 entry point for this tier. The reason for that is the mid tier really has about all the features you would want even for a greater than $1000 receiver. The SR7008 definitely has features. Its a 9.2 channel receiver that can be controlled with a mobile device. It supports Airplay and will upconvert video to 4K. There is Internet connected features like Pandora. It has seven HDMI inputs and three outputs! So why then would you want to spend a thousand dollars more than the mid-tier receivers? Its the sound. Don’t buy this receiver if you don’t have an equal amount in investment in speakers. To get the most out of it you will want speakers that can reproduce sound as precisely as the SR7008 can. With the Audyssey MultEQ XT32 your subwoofer will produce the bang for all the bucks you spend. This is a serious receiver for serious home theater lovers!</p>
<p>&nbsp;</p>
<p dir="ltr"><a href="http://www.amazon.com/dp/B00965J7J0/?tag=hdtvandhometh-20">Sony STR-DA5800ES 9.2 Channel 4K AV Receiver with Automation $2100</a></p>
<p dir="ltr">This is another receiver for serious home theater lovers. Along with similar features sans Airplay, the 5800 sports: nine HDMI inputs, you know for those of you with four blu-ray players, three HDMI outputs (supports multi room HD video distribution), a four port Ethernet switch (thank you!!!), Control4 automation support, special parts selected for their audio quality, and so much more!! This is a super receiver with high quality sound and more bells and whistles than you would ever imagine!</p>
