<h3>HDMI 2.0 Announced</h3>
<p dir="ltr">When it comes to movie sequels, 2.0 is rarely better than 1.0. In fact, we struggled to think of a single instance where a 2.0 movie was better than the 1.0. But in technology, we crave the latest and greatest, and the next version of anything gets our heart rates up. When the HDMI licensing group announced HDMI 2.0, we could hardly contain our enthusiasm.</p>
<p dir="ltr">According to the <a href="http://www.hdmi.org/manufacturer/hdmi_2_0/hdmi_2_0_faq.aspx#136">HDMI 2.0 FAQ</a> at <a href="http://www.hdmi.org/">hdmi.org</a>, “HDMI 2.0, which is backwards compatible with earlier versions of the HDMI specification, significantly increases bandwidth up to 18Gbps and adds key enhancements to support market requirements for enhancing the consumer video and audio experience.” What exactly is HDMI 2.0?</p>
<p>&nbsp;</p>
<h4>Increased bandwidth to 18Gbps</h4>
<p dir="ltr">This is a spec nobody using the cable really cares about, it’s really more of an “under the covers / how we make things work” type of spec.  This increase was required to support the rest of the features we’ll talk about in the 2.0 spec. For comparison, HDMI 1.3 and 1.4 support up to 10.2Gbps, so the new format is capable of supporting almost twice as much simultaneous information on the same cable.</p>
<p>&nbsp;</p>
<h4>Resolutions up to 4K@50/60 (2160p), which is 4 times the clarity of 1080p/60 video resolution</h4>
<p dir="ltr">Here’s the big reason for the jump in bandwidth. HDMI 1.4 supports 4K, but only at 24, 25 or 30 Hz. HDMI 2.0 will see your 4K and raise you 60 frames per second, nearly doubling the amount of video information on the cable. It isn’t a one to one correlation, but obviously the bandwidth would need to increase to support the increased data rate associated with 4K/60.</p>
<p>&nbsp;</p>
<h4>Up to 32 audio channels</h4>
<p dir="ltr">Talk about surround sound. We’ve already put in budget requests with the finance committee for the additional 25 speakers we’re going to need to upgrade our measly 7.1 surround sound systems.  Talk about a multi-dimensional immersive audio experience. Where would you even place that many speakers?</p>
<p>&nbsp;</p>
<h4>Up to 1536kHz audio sample frequency</h4>
<p dir="ltr">Sample frequency, for those who aren’t familiar, is a rough way to gauge the quality of a digital audio stream. The more samples you take, the better the music or soundtrack will sound. Of course the codec and compression factor in as well, but it’s a good measure for simplicity. HDMI 1.3 and 1.4 support 192kHz &#8211; the 1536kHz jump in HDMI 2.0 is a huge improvement.</p>
<p>&nbsp;</p>
<h4>Simultaneous delivery of dual video streams to multiple users on the same screen</h4>
<p dir="ltr">Since nobody can ever agree on what to watch, now you can watch two movies or TV shows simultaneously &#8211; both in 4K quality, over the same cable.  Or maybe 2 football games?</p>
<p>&nbsp;</p>
<h4>Simultaneous delivery of multi-stream audio to multiple users (Up to 4)</h4>
<p dir="ltr">This may be where the 32 audio channels really start to make some sense. in this scenario, you can get four separate 8 channel audio streams running at once. We still aren’t quite sure how this could be used, and it’s odd that you can do 4 audio streams but only 2 video streams, but we imagine someone will find a clever use for it.</p>
<p>&nbsp;</p>
<p dir="ltr">The new spec has a few more goodies, like</p>
<ul>
<li>Support for the wide angle theatrical 21:9 video aspect ratio</li>
<li>Dynamic synchronization of video and audio streams (dynamic auto lip-sync)</li>
<li>CEC extensions provide more expanded command and control of consumer electronics devices through a single control point</li>
</ul>
<p>&nbsp;</p>
<p>Like all the previous revisions to HDMI, from 1.1 to 1.4,  HDMI 2.0 will continue to be fully backward compatible with all previous versions. In fact, according to the FAQ, HDMI 2.0 is built on top of HDMI 1.x and any device that wants to implement HDMI 2.0 must first implement HDMI 1.x as a baseline requirement.</p>
<p>HDMI 2.0 will continue to use the same connectors as the 1.x versions and will even work on existing cables. Some of the higher bandwidth features, such as the 4K/60 video format, will require the existing Category 2 cables, also called High Speed HDMI cables.  So although you’ll need new source equipment, a new receiver and a new TV to take advantage of the new spec, at least you’ll be able to use the same cables you already have.  You’ve got that going for you, which is nice.</p>
