<p dir="ltr"><strong><em>RedEye Remote</em></strong>¬†- Redeye is closing its doors and will still be available for a little while longer. If you want to go this route you may want to look into the¬†<a href="http://www.iruleathome.com/">iRule</a>. It is a more powerful solution at roughly the same cost. Both of these solutions consist of an app that runs on the tablet and a network connected IR emitter/blaster for communication with your equipment.</p>
<p dir="ltr"><strong><em>DirecTV Tablet App</em></strong>¬†- The app is not required but it has some nice features that make it worth installing. The ideal solution would be to have one app that does all the control and the Redeye (and iRule) do that. But the DirecTV app has the ability to directly communicate with the satellite box. It can obviously change channels and pull up the guide but it also can bring up the playlist of all your recorded shows on the tablet. This way you can browse recorded shows without interrupting what‚Äôs on the screen.</p>
<p dir="ltr">There is also a currently watching panel that displays detailed information about what is on screen. IMDB type information is also available to help you remember where you have seen an actor before. Speaking of IMDB, make sure you load that app as well. Its a great resource when you need info about a movie that isn‚Äôt covered in the DirecTV app.</p>
<p dir="ltr"><strong><em>AppleTV/Roku/Boxee Remote App</em></strong>¬†- ¬†For Ara‚Äôs experiment he used an AppleTV but just about everything applies to the remote apps for almost any streaming box. ¬†The Redeye remote faithfully reproduces all the commands of the physical remote for the AppleTV. But who wants to enter letters into a search field with the D-pad. The dedicated remote app on the tablet makes entering data far easier. Plus you can select a movie off your server right on the tablet. No need to go into the menus on the streamer. These apps are not required but they sure to make navigating your stream much easier.</p>
<p dir="ltr"><strong><em>Automation</em></strong>¬†- Just about every automation system has a tablet app. We dimmed the lights and went into movie mode with a simple touch of the screen.</p>
<p dir="ltr"><strong><em>All other apps</em></strong>¬†- Being a tablet means you can install any app you want. CBS has a cool second screen app that allows you to watch with others and communicate via social networks. You can check twitter, facebook, email, or browse the web during sporting events or shows that don‚Äôt require your full attention.</p>
<h4>Actual Experience</h4>
<p dir="ltr">It would be great if we could definitely state that the experiment was a smashing success. Unfortunately that is not the case. In some cases there is an absolute benefit to this type of setup. Mostly in the sense that the remote (tablet) does not have to be pointed at the TV. You can be in the kitchen and still have control. Heck, you can control the system over the internet if you have your router configured properly. Having the ability to have other media related apps on the same device is also pretty cool. Beyond those examples the advantage is for a hard button remote.</p>
<p dir="ltr">The biggest disadvantage the family had was requiring a button push, a swipe, and then a visual identification of the button you wished to press. There was no way to reach over raise the volume simply by feel. Sure you can leave the Redeye app open which prevents the tablet from sleeping but you still need to look at what you are pressing. Repeat functions like volume up work but not always. More than a few times you would have to lift your finger off the screen and make contact to register a volume up command.</p>
<p dir="ltr">You can use the Redeye app to switch activities and then use the DirecTV or AppleTV remote apps as the remote control but those apps will eventually go to sleep requiring a button push and swipe to skip your program forward. In the end, the whole family decided that the tablet remote would not replace our Harmony One no matter how hard we tried.</p>
<h4>Final Solution</h4>
<p dir="ltr">Even with all the issues of the remote we decided that we didn‚Äôt want to let go of the Redeye. We came up with a use case that seems to work for the Derderian family anyway. The Harmony remote is still the primary remote. It will be used to turn on the system and used for volume control, Skip, and anything else that requires immediate control. The Tablet will be used for the DirecTV app which is still the best way to see what you have on the DVR or what‚Äôs on other channels. Likewise for the Apple Remote, it is the best way to navigate the apple TV or send music to the multiple music zones throughout the house.</p>
<p dir="ltr">The Redeye still has value for anyone working in the kitchen since it doesn&#8217;t need line of sight to control the system. Our experience is that a tablet remote will add far more functionality than a hard button remote but for simple things like raising the volume or skipping forward which is done constantly its inconvenient and thus a deal breaker. As a supplemental remote it works well but the cost make it deal breaker. Bottom line, we still haven‚Äôt found a replacement for our Harmony!</p>
