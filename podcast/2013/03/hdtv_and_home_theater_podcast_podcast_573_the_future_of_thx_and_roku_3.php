<p>Roku may not be the number one seller in the dedicated streaming set top box market, but it is among the best, and certainly one of the most innovative. At the time of this writing (3/5), Roku held 4 of the top 12 products in Amazon’s Best Sellers for all <a href="http://www.amazon.com/gp/bestsellers/electronics/1266092011/?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;linkCode=ur2&amp;tag=hdtvandhometh-20">Television &amp; Video Products</a>. The Roku 3 hadn’t quite cracked the top yet, but we didn’t expect it to be too far off. We’ve already ordered ours. News Flash! The Roku 3 is the number one bestseller as of 3/7/2013</p>
<p>The <a href="http://www.amazon.com/gp/product/B00BGGDVOO/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B00BGGDVOO&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Roku 3</a> will retail for $99 and comes in as a replacement for the Roku 2 XS.  You’ll still be able to order the Roku 2 XD ($79), the Roku HD ($59) and the Roku LT ($49). The <a href="http://www.amazon.com/gp/product/B009CL6DUE/ref=as_li_ss_tl?tag=hdtvandhometh-20">Streaming Stick</a> is also still available ($99). According to the Roku Blog, The Roku 3 is available now in the U.S. through Roku.com, <a href="http://www.amazon.com/?_encoding=UTF8&amp;tag=hdtvandhometh-20">Amazon.com</a> and several other leading online retailers. It will be available at major retail chains beginning in April./p&gt;</p>
<p>The Roku 3 has a slightly modified look; is it a bit more sleek and rounded than its predecessor. But it’s more than just a cosmetic upgrade, the new model has some additional horsepower as well. The Roku 3 clocks in at over 5 times faster than previous models. So if you’ve ever experienced sluggish performance with your existing Roku, that should be a thing of the past, provided you buy a new one. Some Roku apps, when you’re scrolling through a lot of data or movies, can get a bit cumbersome in the 2 line. We can’t wait to see how they perform with the 3.</p>
<p>But that’s not even the best part, the killer app we’ve all been waiting for in a set top streamer is unified search.  Samsung showed it on some devices at CES a couple years ago, but it never made it to store shelves. The new Roku 3 has it.  There’s a Video on the blog post <a href="http://blog.roku.com/blog/2013/03/05/introducing-roku-3-video/">Introducing Roku 3</a> that demonstrates it, and it looks great. You can search for a movie or TV show and Roku will show you what apps have it and how much it costs. Simple as that. You can even search by actor or browse by various categories.</p>
<p>While we can’t wait to get our hands on the Roku 3 to try it ourselves, if you’re a current Roku owner, you’ll be happy to know that the new interface will automatically roll out as a free software update in April to all Roku 2 models, Roku HD (model 2500), Roku LT and the Roku Streaming Stick. Hopefully the performance will be just as snappy, even with the older hardware.</p>
<p>Last, but not least, is the headphone jack on the remote we’ve all been hearing about. In fact, this little feature may be the biggest buzz generator of the whole product release. The Enhanced Remote has an integrated headphone jack makes it easy to enjoy TV without bothering anyone else. Just plug in the included in-ear headphones and Roku instantly switches audio to the headphones while muting your TV speakers. We aren’t sure how it will work if you’re running audio through a receiver, but we’ll let you know. Even if you have to mute the receiver manually, eliminating the dedicated wireless headphones &#8211; or not having to buy them at all &#8211; is a huge plus.</p>
<p>All-in-all, Roku continues to push the envelope in set top streamers. With over 750 channels to choose from, the content is as varied and diverse as you can imagine. And with the new interface, it looks like it will be even better.  We’re salivating for the chance to try it out. If you ordered yours on prime and get it before we post a full review, let us know what you think.</p>
