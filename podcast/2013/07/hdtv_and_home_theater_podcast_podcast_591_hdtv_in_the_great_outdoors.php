<p>We’ve talked about the Dish Tailgater before, but this bundle at Amazon brings the whole experience together (<a href="http://www.amazon.com/gp/product/B008BQI7WI/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B008BQI7WI&amp;linkCode=as2&amp;tag=hdtvandhometh-20">buy now $449</a>). The bundle includes the Tailgater antenna, a ViP211K receiver and all the cables you need to connect them and get to watching some HDTV.</p>
<p>Although it looks big and bulky, the Tailgater is actually quite portable and lightweight; it only weighs 10 pounds and is about the size of a rolled up sleeping bag. At that size and weight, it might not make an exceptional backpacking accessory, but it is easy to move around at a campsite. The Tailgater antenna connects to the ViP 211k receiver using a single coax cable and actually draws power from the receiver through the coax cable.</p>
<p>According to Dish, it only takes 15 minutes for the Tailgater to automatically locate DISH satellites and get you up and running with live HDTV. The beauty of the system is that you don’t have to try to point and align a manual satellite antenna. You just plug the Tailgater into the ViP 211k, plug the ViP 211k into your TV or projector, give it anywhere from 12 to 15 minutes and you’re done. All the comforts of HDTV in the tent or by the campfire.</p>
<p>You can even turn the ViP 211k into a DVR, adding the ability to record and pause live TV by connecting your own external USB hard drive to the USB port on the back of the receiver. For a reason we don’t quite understand, a one-time $40 service fee will apply. The external hard drive will need its own power supply cable and must have at least 50 GB of storage, and can go up to 1 TB maximum. The power implications for recording TV may not make sense, but the ability to pause what you’re watching is always a good thing.</p>
<h4>What if I don’t have Dish?</h4>
<p>Dish customers can watch the same programming packages they have at home by simply adding the receiver to their account for a $7 monthly fee. But if you’re not a Dish customer, that’s not a problem either. For Tailgater-only customers, Dish has something called the Pay-As-You-Go plan that allows you to start and stop service without penalty. To restart service, simply log into your account on the web. There&#8217;s no monthly contract and you pay only for the months you use. When the season is over, simply log in and stop your service without penalty.</p>
<p>If you are in the same area as your billing address you will be able to use the Tailgater to view your local channels as well. But if your outdoor vacation takes you outside of your home area, you would need to connect an over-the-air antenna to the receiver to try to pick up the local channels from that area. That may be a challenge depending on how remote you go. However, for a $5 monthly fee, if you camp in an RV, you can subscribe to the Dish Distant Network service and watch nine channels from LA and NY local networks and national PBS. This requires RV vehicle declaration and Distant Networks service authorization forms.</p>
<h4>Powering the System</h4>
<p>Of course you’ll need to power the ViP 211K receiver, and your TV or projector, both of which will probably need 120 V AC power outlets. The Dish receiver does, and odds are your TV will as well. For that you can use a <a href="http://www.amazon.com/gp/product/B004MDXS0U/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B004MDXS0U&amp;linkCode=as2&amp;tag=hdtvandhometh-20">power inverter</a> from your vehicle&#8217;s DC power supply. They only cost around $20 and you can find a plethora of options at <a href="http://www.htguys.com/amazon">Amazon</a>. If you’re watching TV from your car battery for more than a few hours, you’ll want to periodically turn your car on and run it to maintain battery life.</p>
<p>For extended use, Dish recommends you get a portable power generator, power pack, or alternative accessory battery. If you want to preserve the environment you’ve set out to enjoy, you may want to consider a <a href="http://www.amazon.com/gp/product/B0015398OU/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B0015398OU&amp;linkCode=as2&amp;tag=hdtvandhometh-20">portable solar panel system</a>. These will add significantly to the cost of your portable HDTV rig, and will also make it much harder to tote with you, but you’ll have the power you need to run your TV and other AC appliances anytime day or night without the noise or fuel costs of a generator.</p>
<h4>Porting a Big Screen</h4>
<p>The simple option for HDTV by the campfire is a small <a href="http://www.amazon.com/Best-Sellers-Electronics-Televisions/zgbs/electronics/172659/?_encoding=UTF8&amp;camp=1789&amp;creative=390957&amp;linkCode=ur2&amp;tag=hdtvandhometh-20">LCD TV</a>. They’re getting thinner and lighter all the time, have low power consumption requirements and provide built-in speakers. But for those who want to get a bit more exotic and embrace the vast expanse of the great outdoors, why not hang a white sheet over a rope tied between two trees or two tents? Use that as the screen for a portable projector. Your only issue then is sound, and if you get a projector with built in speakers, like the <a href="http://www.amazon.com/gp/product/B0046SQFZG/ref=as_li_ss_tl?ie=UTF8&amp;camp=1789&amp;creative=390957&amp;creativeASIN=B0046SQFZG&amp;linkCode=as2&amp;tag=hdtvandhometh-20">Epson 85HD MovieMate</a> for $779, you can have a portable movie theater right in the campsite.</p>
