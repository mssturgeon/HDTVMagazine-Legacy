<h3>Is Blu-ray a Dead Format?</h3>
<p>Ask anyone who knows something about home theater what is the highest quality audio and video available to mere mortals today and they will tell you Blu-ray. Blu-ray video is stunning and the audio is simply amazing. But we don’t have to tell you that. So does Blu-ray have a future? The following are some reasons why Blu-ray may not be around for too much longer.</p>
<h4>Convenience</h4>
<p>Its pretty clear that the mass audience for content couldn’t care less about quality. Our own children are completely happy watching crap video on Youtube in mono. When today’s youth get their own place many don’t even buy a HDTV but rather opt for a computer to watch their cat videos.</p>
<p>Beyond Youtube there are plenty of places to get higher quality content. Companies like Apple, Amazon, Netflix, HBO and many more are happy to stream movies that are better than DVD at a moment’s notice. The experience is quite enjoyable and for some movies, mainly dramas without much action, preferable to buying a blu-ray. As bandwidth and processing power increases it is quite logical to expect Blu-ray quality from streaming.</p>
<p>The last thing to consider for convenience is that most services have some sort of virtual locker. You don’t even have to download the movie to watch it when you want. This is great since you may get a 4Mbps version now but when bandwidth improves you may get a 10Mbps version with the latest compression technology.</p>
<h4>BD-Live</h4>
<p>When DVDs first came out many of us were excited about the extras that came along with the main feature. Blu-ray was supposed to take it to the next level with BD-Live. Do you remember how BD-Live was supposed transform the way we watch movies? When they developed BD-Live, tablets weren’t even on the radar. Tablets make it far easier to interact with others or the studios while watching our movies. There is no need to buy a Blu-ray disc for the consumer to get in on the “Community” aspect of watching a title. The whole concept of BD-Live was to draw diehard fans of a movie to buying the disc. Now you can search twitter hashtags and get all the community you want.</p>
<h4>Other Media</h4>
<p>Blu-ray isn’t the only format for storing large amounts of data. Secure Digital (SD) cards can now store more content than Blu-ray discs and they are faster too! A <a href="http://www.amazon.com/dp/B00B7ID9CU/?tag=hdtvandhometh-20">64GB SD card</a> with a 40MB per second transfer rate is $40. Within a year it will be less than $10. Now imagine a Kiosk at Wal-Mart or Target where you insert your own card and download your movie in a couple of minutes. No distribution costs for the studios and quality that is equal to or better than blu-ray without the need for a disc. This scenario does assume that studios wake up and realize that DRM is not worth it and the vast majority of people would be willing to pay a fair price for this type of content.</p>
<p>Even if our fantasy of downloading an open file at a Kiosk is far fetched there is nothing stopping manufacturers from developing a new SD card that acts exactly like a Blu-ray disc. Once written the device can’t be written again. Even with this option, studios would see that most people don’t care about the fancy packaging. Virtual points of sale would pop up and in a faction of the space retailers would be able to store every movie available on disc format today. Who would be interested in this option? Those few people who streaming is either not possible or the quality is not good enough.</p>
<h4>Time to Bury Blu-ray?</h4>
<p>Its probably too early to put the last nail in the Blu-ray coffin right now. There needs to be one or two more paradigm shifts before Blu-ray goes away. The first is the studios realizing that DRM is more hassle than it is worth. Once this hurdle is crossed in-store Kiosks or online downloads will soar. Prices will come down and the world will be saved from all that plastic be created. The second is a jump in online speeds. Once gigabit Internet is ubiquitous there will be a shift to storing content in online lockers and again the world will be saved. The big question is when? Based on what we are seeing we are betting on within 5 years.</p>
