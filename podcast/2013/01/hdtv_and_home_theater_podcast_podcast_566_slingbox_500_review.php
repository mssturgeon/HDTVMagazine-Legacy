<h3>Slingbox 500 Review</h3>
<p>We have had slingboxes for the past 5 years and they have come in quite handy! There have been plenty of Sundays where the Slingbox has allowed us to keep up with our favorite football team. In general the Slingbox is life saving device for those of us who spend some time on the road. Today we take a look at the latest Slingbox, the Slingbox 500. It has a street price of $288 and is available now (<a href="http://www.amazon.com/dp/B009FU8BR0/?tag=hdtvandhometh-20">Buy Now $288</a>).</p>
<h4>Features:</h4>
<ul>
<li>Supports 1080p HD.</li>
<li>Connects to your DVR, cable set-top box or satellite receiver via HDMI and component or composite sources.</li>
<li>New simple setup on your TV screen</li>
<li>Built-in Wi-Fi</li>
</ul>
<h4>Setup:</h4>
<p>Dish has done a good job of making setting up a Slingbox simple. The 500 has some cool features that should make getting up and running as straightforward. With the 500 they have added support for HDMI. You connect the output of your source to the Slingbox and then connect the Slingbox to the display, or in our case the receiver. When you are not watching the Slingbox the signal is passed through.</p>
<p>You will still want to connect analog sources since the HDMI won’t sling a channel that is protected&#8230; HBO, Showtime, etc. When you want to watch one of those channels the player will switch over to analog for the source. If you don’t have any analog connections you will see a message on screen telling you that the content is protected.</p>
<p>In addition to the HDMI and Component connections we connected power, Ethernet, and the IR Emitter Cable and were on screen in no time. The Slingbox 500 allows you to setup and configure it on your TV with an included remote control. You select your provider, device, and wifi network (if applicable). When its all done you are ready to go.</p>
<p>Our first slingbox required us to get into the router and open up ports to allow streaming over the Internet.  This one didn’t ask whether we wanted to sling via the Internet. It communicated with our router and did everything for us automatically. If you have an older router that doesn’t support universal plug and play you may have to manually select a port to stream over the Internet.</p>
<p>We already had Slingplayer on our portable devices as well as on our computer. If you don’t you will have download the software and log into your account. Once there you will be slinging your local TV signals to anywhere in the world without restriction.</p>
<h4>Performance:</h4>
<p>Like everything over the Internet your experience will vary depending on your network connection. In this case there are two limiting factors, upstream and downstream speed. If you have an Internet connection that limits your upload speed to 500Kbps then it doesn’t matter how fast your download speed on the other end is because you won’t get a better stream that your upload. But with that said, even at 500Kbps the picture is watchable, especially for typical movie or TV show content. Sports is a bit harder to watch at that data rate. We have a 2Mbps upload speed and found the picture quality to be quite good even for sports. There has been such an improvement on picture quality over the years.</p>
<p>Watching on your home network is even better! With data rates at 8Mbps the picture quality is better than anything you would stream over the Internet. We’re not going to tell you that the picture is as good as the original or even close. But when you are stuck at your in-laws and they don’t have the football package the picture quality is completely acceptable.</p>
<p>We also watched on portable devices and found similar results. The smaller screen was more forgiving with lower data rates. The picture looked fantastic on an iPad with the Retina Display. If you want to add a small tv in a bathroom or kitchen buy a used iPad and a slingbox. You will get so much more out of the setup!</p>
<p>There were a couple of things we didn’t like. When someone connected to the slingbox there would be a blanking of the screen for a couple of seconds. When we were testing my kids thought something starting to fail. The issue was when the network bogged down and the iPhone lost connection the TV would blank every time it lost the connection and then do it again when it reconnected. This is only an issue if someone is watching at the same time. The other issue was when the system did a firmware update it took control of the TV signal so all you could see was the update which took a few minutes. Not a big deal since the firmware isn’t continually being updated.</p>
<h4>Odds and Ends:</h4>
<ul>
<li><strong>Guest Account</strong> - You can invite a guest to use your slingbox. You enter your friend’s email and then Sling sends them a registration email. You can revoke it at anytime as well. It makes it better than having to give someone your username and password.</li>
<li><strong>Sharing Pictures</strong> - This is kind of like Apple’s Airplay. From within the Slingplayer app you can beam pictures and videos to the Slingbox 500. You can only do this when the phone is on the same network as the slingbox.</li>
<li><strong>SlingSync</strong> - This feature, when available, will allow you to store content on a hard drive and connect it to the slingbox for viewing anywhere you have an Internet connection;</li>
</ul>
<h4>Conclusion:</h4>
<p>Without a doubt the Slingbox 500 is still the best way to watch your local content anywhere in the world. The improvements in setting up and addition of built in WiFi make the Slingbox 500 a product that pretty much everyone can install and make work easily.</p>
