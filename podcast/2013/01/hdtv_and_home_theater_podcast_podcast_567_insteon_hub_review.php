<h3>SmartHome Insteon Hub Review</h3>
<p>To take full advantage of an automation system, you need a server running that can take action based on events that may occur, these are often called “triggers.”  You can run a software package on a computer you leave on 24/7 or you can buy a dedicated device for it. If you’re like us and have Insteon devices in your home, one option to look into is the <a href="http://www.insteon.net/2242-222-insteon-hub.html">Insteon Hub</a> from SmartHome.</p>
<h4>About the Hub</h4>
<p>You can buy the hub from <a href="http://click.linksynergy.com/fs-bin/click?id=w2Z/veGBaPc&amp;offerid=173671.10000217&amp;type=4&amp;subid=0">SmartHome.com</a> for $129.99. That’s a lot less than you’d pay for a dedicated computer if you don’t have an old one sitting around that you can use. And it is about as much as you would pay for a software package like SmartHome’s own HouseLinc for Windows or Indigo from Perceptive Automation for the Mac. It is a small, self contained unit that allows you to take control of your automation system without much cost or effort.</p>
<p>The device itself is a small white box with connections for power and Ethernet.  Both cables are included in the box, along with a quick start guide. The Hub should fit pretty easily into any space where you can get a dedicated Ethernet connection, like right next to your router or by a computer. The only difficult piece in that scenario is finding somewhere to plug it in. The Hub needs to be plugged into the wall directly, you can’t plug it into an existing power strip.</p>
<p>&nbsp;</p>
<h4>Setup</h4>
<p>Once you have the hub itself plugged into the wall and your local network, you simply download the app for your smartphone or tablet, both iOS and Android are supported, and you’re ready to go. The app will find the Hub on your network and attempt to configure it and your router to allow you to access your automation system while away from home. If the automatic setup doesn’t work with your router, you may need to set a static IP and assign the port forwarding rules yourself to make it work.</p>
<p>With the network set up and the smartphone connected, you’re ready to add devices. That’s the easy, albeit somewhat time consuming, part. Assuming you have a few Insteon devices already installed, things like switches, plug modules, thermostats, motion sensors, etc., you just walk around to each one, hold the set button, and the phone will find it and the Hub will add it. You can name the device and assign it to a room. Of course you have to create the rooms first, but that’s fairly trivial.</p>
<p>Once all your devices are in the system, you can begin to create scenes. Scenes are where the magic happens. A scene allows you to group a set of devices, set the levels for them &#8211; for dimmers, etc. and set an on and off time for the scene. They can be set to automatically come on or turn off at any time of the day or automatically at sunrise or sunset. You can also choose which days to enable the automated on and off functionality.</p>
<p>&nbsp;</p>
<h4>Results</h4>
<p>The Hub is very easy to use and very easy to set up, but it lacks many of the features we have grown accustomed to in our past experience with dedicated software packages. If you’ve never used an automation server before, the Hub will do wonders for your home. It’ll allow you to turn lights on automatically at dusk or off automatically at dawn.  It’ll allow you to turn devices on at certain times in the day, or make sure everything is off when nobody is supposed to be at home or everyone is sleeping. But that’s about as far as it goes.</p>
<p>The Hub will send Email or SMS alerts in response to an event, like a leak detector or a motion detector, but it won’t do anything else. Many times you want to turn on a light or take some other action in your automation system, the Hub won’t let you do that. If you want to turn on the porch light when someone arrives at the front door, or turn on an entry light when the garage opens, you’re out of luck. You can do it manually, by reading the text message, opening the app, and turning on the light, but that kinda kills the point of an automation system.</p>
<p>While the Hub supports many different Insteon devices, it doesn’t offer full support for some of the more advanced devices. It will control the main load (light) attached to a multi button switch, but won’t allow you to program the rest of the buttons on the switch. We couldn’t get it to do anything at all with our IR interface, so we would have to result to manually programming it if we used the hub, which is a real chore.</p>
<p>We also found the smartphone app to be a bit sluggish and at times a little buggy. We knew we were connected to the Hub, but when we hit the button we thought would check for app updates, we got an error message back saying the app couldn’t connect to the Hub. When adjusting the dimmer level on a switch or plug-in module, you don’t get to pick the level. Instead you press an up or down button and it auto adjusts for you by some seemingly random percentage. It may go down from 100% to 86% to 63% to 50%, etc. It became a fun game to guess what percentage we’d get after pressing the up or down buttons.</p>
<p>&nbsp;</p>
<h4>Conclusion</h4>
<p>The Hub is an inexpensive way to make your home come alive. If you’ve been looking for a way to get lights to come on or turn off automatically, the Hub may be the right solution for you. If you’re interested in doing more advanced automation, or fine tuning the details of your automation system, the Hub probably isn’t the right answer for you. In either case, home automation is fun. And when you begin to integrate your automation system with your home theater or whole house music system, that’s when things really come to life.</p>
