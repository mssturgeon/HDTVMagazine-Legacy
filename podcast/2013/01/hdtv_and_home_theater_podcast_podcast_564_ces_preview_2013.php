<div id="_mcePaste">For us Sharp is about TVs and this year we are really interested in seeing the “Largest LED on the Planet”. It measures in at 90 inches and should give some projector setups a run for the money. Sharp showed one of our favorite TVs last year, the 8K LCD. We’re hoping they can top it this year.</div>
<p>&nbsp;</p>
<div><em>Logitech:</em></div>
<div id="_mcePaste">We’ve already seen the Harmony Touch and didn’t like it that much (Podcast #554). What we want to see is the UE Smart Radio. This looks like a very cool device that can stream music from just about any source online (Pandora. local.fm, tunin Radio, etc). We’ll ask the guys if those who invested in the Squeezebox will be left out in the cold or if they can join in on the fun.</div>
<p>&nbsp;</p>
<div><em>Samsung:</em></div>
<div id="_mcePaste">Last year we were blown away by Samsung&#8217;s OLED TV.  We’re sure it will be there again this year but with a little less fanfare. Samsung’s booth will be huge and full of all kinds of electronics but one thing that caught our eye is a see through TV. We’re not too sure what it can be used for but it sounds pretty cool. Samsung is also expected to show a TV with an “unprecedented new TV shape.” Not sure what that means either.</div>
<p>&nbsp;</p>
<div><em>Panasonic:</em></div>
<div id="_mcePaste">Are they killing Plasma or aren’t they? We’ll check to see if there is something called a VT 60?? Panasonic usually has has a large presence most of it taken up by TVs. If they are getting out of the business then we’d expect a smaller booth or something else in its place. Regardless, we’ll see what’s cooking with Panasonic this year.</div>
<p>&nbsp;</p>
<div><em>Sony:</em></div>
<div id="_mcePaste">Last year Sony was showing a technology called Crystal LED. We haven’t heard much about it since. What we expect to see this year is 4K everywhere. Sony usually has some great gadgets as well. Last year they demoed HD goggles this year a brain implanted chip???</div>
<p>&nbsp;</p>
<div><em>Dish Network:</em></div>
<div id="_mcePaste">Dish has been eluding to an announcement about something that will “top the Hopper.”  We’ve been invited to see what&#8217;s next with the DISH Hopper at their press conference, but won’t be able to attend. “On Press Day, DISH Chief Executive Officer Joe Clayton will reveal how DISH will stay a hop ahead of the competition and give the consumer greater choice and control than ever before.”</div>
<p>&nbsp;</p>
<div><em>Projectors:</em></div>
<div id="_mcePaste">There are always a ton of projector demos and we love sitting through them. Last year it was 4K. This year we expect it to be better and cheaper 4K. We are excited to check out the “Affordable” Graywolf series of projectors from Wolf Cinema. The SD8 and SD12 have a MSRP of $8K and $12K respectively. Both have a next-generation, three-chip, D-ILA® light engines. The SD8 is a 1080p projector and the SD12 is 4K.</div>
<p>&nbsp;</p>
<div><em>Home Automation/Security:</em></div>
<div id="_mcePaste">We are always on the lookout for new and better ways to automate our homes. This year we expect to see a wave of security products especially IP Cameras. Ara has discovered how easy it is to setup cameras throughout his home and is hoping that we can find some cool products that everyone can easily setup and use.</div>
<div></div>
<p>&nbsp;</p>
<div id="_mcePaste"><em>Audio/Speakers:</em></div>
<div id="_mcePaste">The last few years has seen a large drop in participation from the likes of Denon, Klipsch, Pioneer, Yamaha, and so on. These companies are still represented but in much smaller scale. The CEDIA show is where they do most of their announcements. But fear not we’ll be on the lookout for them.</div>
<p>&nbsp;</p>
<h4>What we’d like to see:</h4>
<div><em>Something &gt;8K, just ‘cuz</em></div>
<div id="_mcePaste">We know there will be a plethora of 4K televisions at the show this year. We’re also expecting to see a few 8K TVs scattered about the conference halls and exhibits.  What we really want to see is something even more amazing, even more astonishing, even more mind blowing. If a manufacturer can’t win by creating the biggest TV at the show, maybe they can win by cramming the most pixels into a TV ever. 12K? 16K? 20K?</div>
<p>&nbsp;</p>
<div id="_mcePaste"><em>Fully wireless (except power, of course)</em></div>
<div id="_mcePaste">We’d love to see more systems adopt a fully wireless concept.  For example, how about a Home Theater in a Box system that came with seven wireless speakers, a wireless subwoofer and a wireless HDMI transmitter.  You could connect all your components into it in a closet or another room and have it wirelessly beam your home theater into whatever room you wanted &#8211; or even outside. Or how about a box that looks like a seven channel amplifier that is really just a seven channel wireless audio distributor for surround sound?</div>
<p>&nbsp;</p>
<div id="_mcePaste"><em>Glasses-free 3D&#8230;that works</em></div>
<div id="_mcePaste">We’ve been subjected to the glasses-free 3D demos for almost as many years as we’ve been going to CES, but we’re yet to see one that worked well enough to get excited about. This year we’re really hoping someone has cracked it, someone has found a way to immerse viewers in a 3D experience without the need for expensive, headache inducing glasses. We aren’t going to put any money on it, but we’d sure like to see it.</div>
<p>&nbsp;</p>
<div id="_mcePaste"><em>See through cell phones and tablets</em></div>
<div id="_mcePaste">We’ve seen some pretty cool cell phones in the movies over the years, but somehow we never get them in our pockets.  Bruce Wayne and Batman had a pretty sweet portable in the the most recent installment of the Dark Knight movies.  Samsung will be showing off a see through TV. Can’t we get the best of both worlds and show off some sweet see through phones and tablets? Of course, if we want our predictions to come true, we should probably be looking for foldable or rollable tablets instead.</div>
