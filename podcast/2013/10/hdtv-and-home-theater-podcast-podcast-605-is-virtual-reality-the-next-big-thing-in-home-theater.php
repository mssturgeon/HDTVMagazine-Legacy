<h3>Is Virtual Reality the Next Big Thing in Home Theater?</h3>
<p dir="ltr">Many of us are constantly on the lookout for the next big thing in Home Theater. When the HDTV revolution hit, we couldn’t get enough. Then there was HD-DVD and Blu-ray, followed by a flop or two, like 3D. Right now it looks like it might be 4K HD. But what if 3D was just the precursor to the real next big thing, Virtual Reality.</p>
<p>&nbsp;</p>
<h4>What is Virtual Reality?</h4>
<p dir="ltr">When you think Virtual Reality, you probably imagine yourself on the holodeck of the USS Enterprise, hanging out, perhaps, in the old west with Captain Picard. That’s the idea, but we probably won’t see that full implementation anytime soon. The <a href="http://en.wikipedia.org/wiki/Virtual_reality">wikipedia</a> definition is: “a computer-simulated environment that can simulate physical presence in places in the real world or imagined worlds.” It’s you, inside the movie or the game, playing or watching from within &#8211; and being an active participant.</p>
<p>&nbsp;</p>
<h4>Current Technology</h4>
<p dir="ltr">A company called <a href="http://www.oculusvr.com/">Oculus VR</a> is building a VR mask you can wear, called the Oculus Rift. It resembles a black, blacked-out <a href="http://www.fisher-price.com/en_US/brands/viewmaster">ViewMaster</a> you strap to your head. Once you’ve strapped on your VR goggles, you’re instantly transported into whatever world, time or place you can image. It’s like 3D, if the 3D didn’t stop at the edge of the screen. We haven’t used the device ourselves, but have seen similar demonstrations at CES in the past, and it’s pretty cool.</p>
<p dir="ltr">Oculus VR is very focused on the gaming market, and that makes sense. It’s really the only technology that could embrace Virtual Reality anytime soon. The vision is to let gamers feel like they’re really driving the car, throwing the ball or carrying the gun through the battlefield. Imagine taking the microsoft Kinect technology to the next level. Instead of just having your body control the action you see on screen, your body controls the action you see all around you, the action you’re right on the middle of.</p>
<p dir="ltr">Another company, called <a href="http://www.avegant.com/">Avegant</a>, is building a wearable Virtual Reality headset that <a href="http://www.telepresenceoptions.com/2013/10/avegants_prototype_display_pro/">projects images directly onto your retina</a>. At first this sounds painful, then scary, then super futuristic and cool. It’s like beaming images directly into your brain. A technology like this requires very precise alignment, which is why most companies aren’t pursuing it. But Avegant thinks they have it down. If they do, the visual experience will be unparalleled because the beamed image should cover your entire visual experience.</p>
<p>&nbsp;</p>
<h4>Limitations</h4>
<p dir="ltr">Processing power is an issue for current Virtual Reality systems, and would prove to be very challenging if anyone tried to scale it to a large format like the holodeck. It takes a lot of CPU and graphics processing to produce what amounts to any potential view of any reality at any time. The computational decisions on what to render, and the graphics ability to render it in real-time are a big limiting factor in how pervasive VR can become, even for gaming.</p>
<p dir="ltr">Like 3D for home theater, VR also suffers from physical side-effects like motion sickness and headaches. In the industry it is known as simulation sickness. Like motion sickness, it occurs when your brain and body don’t agree on what’s actually going on. You brain senses movement, but your body doesn’t. This can lead to some serious queesyness.</p>
<p dir="ltr">And of course, there’s the issue of space. If you’ve played a Wii or used the XBox360 with Kinect, you know it’s easy to run out of space pretty quickly. This isn’t an issue if you happen to be driving a car or flying a plane, but if you’re running through a battlefield, or across a football field &#8211; how do you run without really running? How do you get from here to there, when ‘there’ is bigger than the room you’re in?</p>
<p>&nbsp;</p>
<h4>Applications for Home Theater</h4>
<p dir="ltr">When you imagine watching a movie as if you were in the film itself, it sounds amazing, until you start to look at the limitations. But there may be ways to introduce Virtual Reality concepts into home theater and make it work. It could be like what 3D should be &#8211; the movie is actually occurring all around you. Movement might be tricky, and there may be some scenes where placing the viewer would be tricky or awkward, but that’s solvable. Imagine if, when a character walked onscreen, the actually walked right past you.  Or if something was going on to the left, or to the right, or above, you could turn your head to get a better view.</p>
<p dir="ltr">There may be some movies that VR wouldn’t be good for. It sounds cool for action films like Saving Private Ryan, but would you really want to be that close to the action? Sometimes viewing from a distance, as a removed observer, is the only way to reasonably experience something. Most of us wouldn’t really want to storm the beach at Normandy and see the devastation that close. But for nature documentaries, like we see on Discovery or NatGeo, sitting in the middle of a pack of lions or walking inside an ant colony, it could be amazing.</p>
<p dir="ltr">Sports could be fun in Virtual Reality as well.  The amount of cameras required to make it happen is probably unfeasible. But it would be great if you could move closer to a play on the football field. Or place yourself on second base to watch a baseball game. Do your own replay on something you saw and move around to get a better view. Or zoom closer to see it first hand. These are all things Oculus VR and Avegant are trying to enable for gaming, but maybe, in the future, we’ll be able to apply them to home theater as well.</p>
