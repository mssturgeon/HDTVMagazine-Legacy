<h3>Understanding Speaker Specs</h3>
<p dir="ltr">We threw out a speaker specification a couple episodes back while reviewing the <a href="http://www.htguys.com/podcasts/2013/9/27/podcast-602-cerwin-vega-ve-series-speakers.html">Cerwin Vega VE Series Speakers</a> and afterwards realized that we all may not share the same level of comfort and understanding with the various specs and measurements thrown around when shopping for or comparing speakers.  Of course how they sound to you is really all that matters, but often a solid understanding of what all those numbers mean can help you make a more informed buying decision.</p>
<p dir="ltr">
<h4>Sensitivity</h4>
<p dir="ltr">This is the spec we mentioned with the Cerwin Vega speakers and one we use routinely to rank speakers when purley going by paper, not by sound.  If you’re doing your homework on<a href="http://www.htguys.com/amazon">Amazon </a>or another online retailer, keep an eye out for sensitivity.  It gives you an idea of how efficient a speaker is; in other words, how hard it is going to make your receiver or amplifier work to play back those explosions you want to hear louder than you probably should.  What it really measures is how loud the speaker will play when given a standard test input and measured at a specific distance,  typically 1 meter.</p>
<p dir="ltr">As you can imagine, when fed the same test signal, the louder a speaker will play, the more efficient it is.  So sensitivity is a measure of the speaker’s volume, expressed (as volume often is) in decibels. The higher the number, the higher the efficiency and the better your speaker will perform.  Your receiver or amplifier won’t have to work as hard to produce the same volume level. Typical numbers are in the mid to high 80s; anything over 90 is considered excellent. Sensitivity won’t tell you how good a speaker sounds, but it will tell you how easy it will be to crank it up.</p>
<p>&nbsp;</p>
<h4>Frequency Response</h4>
<p dir="ltr">Measures the range of audible frequencies a speaker reproduces sound across the entire audio spectrum. This spec helps you assemble a set of speakers that allow you to hear everything you’re supposed to. The general rule of thumb is that we humans can hear really low sounds down to 20 Hz all the way up to really high-pitch, piercing sound at 20 kHz. Many argue that the highest and lowest frequencies are less important because the human ear doesn’t hear them as well.  But for the lower range, it may not be as important to hear it as it is to feel it.</p>
<p dir="ltr">Larger speakers tend to cover a wider range of frequencies, which is why you typically want larger speakers for your front and center channels.  You can get away with smaller speakers in the surround channels because the sound there doesn&#8217;t tend to be as dynamic as the front of the room.  Although some very large speakers will cover the lowest end of the spectrum, down to 20 Hz, most home theater speakers don’t go that low, so you need a subwoofer to fill that gap. Without the really the low end frequencies, a home theater tends to lack punch and the audio doesn’t feel as full.</p>
<p>&nbsp;</p>
<h4>Impedance</h4>
<p dir="ltr">This is another measurement, like sensitivity, that is of no value when it comes to the pure audio quality of the speaker, but it can help guide some buying decisions.  Where sensitivity tells you how hard the amplifier needs to work to produce a particular volume level, impedance tells you how much strain the speaker itself puts on your amplifier.  Most speakers are rated at 8 ohms, and most receiver specs are quoted assuming an 8 ohm speaker load. The lower the impedance number, the more strain, so if you come across a sweet pair of 4 or 6 ohm speakers, you’ll need to make sure your receiver can handle them.</p>
<p dir="ltr">Also keep in mind that impedance is something you can influence if you decide to add more speakers to your home theater.  You can’t simply add more speakers to the same channel. When you do, you change the overall load or impedance for that amplifier channel. Adding a second speaker to a channel, when connected in parallel, will actually cut the impedance in half, so instead of the amplifier working to run one 8 ohm speaker, it now has to work as if it is connected to one 4 ohm speaker. This could have a negative impact on your amp. Connecting speakers in series, however, actually has the opposite impact, but that may be too deepa discussion for this episode. Bottom line, make sure you know what you’re doing if you decide to add multiple speakers to the same surround sound channel.</p>
<p>&nbsp;</p>
<h4>Power Handling</h4>
<p dir="ltr">This tells you the maximum amount of power you can run into a speaker without damaging it.  To be honest, the spec is somewhat useless. A 200 watt per channel amplifier will rarely, if ever, run at the full 200 watts to each channel.  If you tried it, you’d probably have blood coming from your ears before your speakers, that may be rated for 100 or 125 max watts per channel, would give out or blow.  The 180 watt or 200 watt receiver is probably going to be a higher quality item than a 50 or 80 watt unit, so even though the smaller ones will never have the chance to ruin your speakers, they won’t sound as good either. Use common sense and you should be just fine.</p>
