<p dir="ltr">This may or may not be the year of home automation, but if you still haven’t given it a try for yourself, you really should. You bought a smart TV, so now its time to get some smart lighting and home control. But if you want to go beyond the basics of dimmers and plugs, you’ll want an automation server running to allow you to process events, customize activities and really make your home operate like you want.</p>
<p dir="ltr">There are several great automation software packages like Indigo, the one Ara uses, and SmartHome’s own HouseLinc for Windows, the one Braden previously used. That’s the route we typically recommend. If you have an old computer sitting around, or can assemble one for relatively low cost, just buy the software and your automation server is done. You had the computer anyways, so what not turn it into a control server to make your home a little smarter?</p>
<p dir="ltr">But there are drawbacks to the computer approach. You have to leave the computer running 24 hours a day, 7 days a week. That may be a little more power hungry than you’d like. If it isn’t always on, the events you want to occur may not happen. If your computer is set to automatically apply updates, it may restart on you, causing you to lose automation for a brief time. And if it was an old computer you had sitting around, it was probably sitting around for a reason, so it is really capable of doing everything you want in a reasonable amount of time?</p>
<p dir="ltr">But don’t fret, you can have smart lights (and many other items in your home) without leaving a computer running all the time. You simply pick up an ISY-994i from Universal Devices for around $200 from <a href="http://click.linksynergy.com/fs-bin/click?id=w2Z/veGBaPc&amp;offerid=173671.10000217&amp;type=4&amp;subid=0">SmartHome</a> or <a href="http://www.amazon.com/?%5Fencoding=UTF8&amp;tag=hdtvandhometh-20">Amazon</a> and you don’t need to. In our case, because we use Insteon, we also had to purchase an Insteon control module, the Dual Band PLM 2413S. SmartHome sells them in a <a href="http://www.smarthome.com/12237DB/ISY994i-INSTEON-Compatible-Automation-Controller-with-Dual-Band-PLM/p.aspx">package</a> for $300.</p>
<p dir="ltr">
<h4>Setup</h4>
<p dir="ltr">Installation is pretty simple. The PLM plugs into a wall outlet and has a cable connection that plugs into the back of the ISY-994i using a standard Ethernet cable. You run another ethernet cable from the ISY to your router for control, configuration and status over the network. Of course the ISY needs power, so you have to do that as well, but that’s it for installation.</p>
<p dir="ltr">Once you’re all plugged in, you can connect to the ISY from any browser on any computer that’s connected to the same network. This is where things may get a little shaky. For many, the connection will “just work.” We weren’t so lucky. Our browser wasn’t able to find the server by name, so we had to look up the IP address in our router. Connecting with the IP address, however, was seamless. Once we got past that hurdle, we were ready to start programming.</p>
<p dir="ltr">Step one in setting up the server itself is to add all your automation devices to it. This is as easy as telling the server to enter an “add devices” mode and walking around to all your devices and clicking their set buttons. You may grow weary after a while if you have a lot of devices, but that’s the price you pay for automating your home. Our devices added without a glitch, we renamed them to friendly, descriptive names, the promptly starting programming.</p>
<p>&nbsp;</p>
<h4>Use and Programming</h4>
<p dir="ltr">As with most automation servers, you start with scenes. Scenes are collections of lights or other modules at pre-set on, off or dimmed settings. That allows you to turn on a group of lights, pre-configured for a specific usage, such as everything on and bright for ‘dinner party’ or just a couple on, really dim, to light your path to the kitchen for ‘midnight snack. Once you have a scene or two set up, you can change light switches, or IR commands from your universal remote, or buttons on your smartphone, to turn the scenes on or off as a unit.</p>
<p dir="ltr">From there, you jump over to custom programming. This is where you can program lights or a scene to come on at dusk or at dawn, to activate at a particular time of day, or when another event occurs, like a motion sensor is tripped, a leak sensor is activated or a door is opened. Custom programs can turn lights on or off, send emails or even communicate with other external systems. Once you start programming, its hard to stop.</p>
<p dir="ltr">Programming on the ISY-994i is quite simple. You have 3 main blocks, the IF block determines what will cause the program to run. For example, you can say “If the motion sensor is tripped and it is dark outside,” or “if it is dusk and a weekday.” After you’ve decided what will activate the program, you simply fill in the THEN block. These are the actions that will be performed, like tunr on a light or scene, send a notification, run a different program, etc. There’s also an ELSE block that can perform actions if the IF block doesn’t fire.</p>
<p>&nbsp;</p>
<h4>What we didn’t like</h4>
<p dir="ltr">Our main complaint about the ISY-994i is the interface. The main configuration interface is a Java application. Not that Java is bad, but this UI shows some signs of age. It does everything it is supposed to do, but is a tad cumbersome and can be pretty slow at times. There is a simple status and on/off web interface you can use instead of the Java GUI. Although quite basic, it is nice and feels much more modern. It presents a nice alternative to the Java console, but doesn’t allow any of the program or customization. For that, you have to use the Java admin interface.</p>
<p>&nbsp;</p>
<h4>Other Cool Bits</h4>
<p dir="ltr">It turns out the ISY-994i is field upgradable. You can buy the base model and if, in the future, you find you need additional capacity for more devices, or you’d like to add IR control capabilities, you can do that without buying a whole new ISY. This allows you to do like we typically suggest, jump in at a low cost and start automating. Let the system grow with you. From that aspect, it’s the perfect home automation server.</p>
<p>&nbsp;</p>
<h4>Conclusion</h4>
<p>We can argue whether or not 2013 is the year of home automation, but what we agree on is that home automation is fun, and pretty darn rewarding. It’s cool to have the best TV around, or the biggest subwoofer, or the loudest surround sound system, but it doesn’t have to stop there. It’s pretty cool to have your lights fade in and out or have your shades open and close in sync with the activity in your theater, like when you turn it on or pause a movie. That’s what turns a home theater into your home theater. If you’re looking for a very simple, cost-effective, yet powerful and flexible way to add server control to your automation system, the ISY-994i checks all the boxes.</p>
