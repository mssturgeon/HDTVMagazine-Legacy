<p>We had the opportunity to check out a very affordable 3D projection package from <a href="http://optomausa.com/index.asp">Optoma</a> this past week. The package is made up of two pieces, the <a href="http://optomausa.com/product_detail.asp?product_id=536">HD6700</a> projector and the <a href="http://optomausa.com/store_productdetail.asp?product_subcategory=29&amp;productcategory=3D%20Accessories">BG-3DXL</a> 3D converter box. Of course you need active 3D glasses, so Optoma rounds out the package with a pair of <a href="http://optomausa.com/store_productdetail.asp?product_subcategory=29&amp;productcategory=3D%20Accessories">BG-ZD101</a> active shutter glasses. All tolled, the package has a retail price less than $1200: around $700 for the projector, $399 for the converter box and $99 for the glasses. Of course you can add as many pairs of glasses as you want for an additional $99 each.</p>
<h4>Setup</h4>
<p>The whole system sets up pretty quickly. You run your 3D source, such as a Blu-ray player &#8211; we used the <a href="http://www.htguys.com/shop?id=B004K1EOB6">Sony BDP-S470</a> &#8211; into the 3D-XL using HDMI. Make sure the converter box is set to output 720p. Then run the output from the converter box to the HD6700. That’s it. Of course in the real world you’ll have a receiver in there for surround sound, but there really isn’t much to do. Oh, the glasses have an ‘On’ button. Make sure you turn them on before watching any 3D content.</p>
<h4>The Projector</h4>
<p>The HD6700 is a 720p projector that retails for under $700, so we honestly didn’t expect it to blow us away. The first thing we noticed about it, though, is how bright it is. The spec sheet reports 1800 lumen output and we had a great viewing experience even in rooms where we couldn’t completely control ambient light. In the room where we could control ambient light, we used it on our bright white 100&#8243; <a href="http://www.dragonflyscreens.com/">Dragonfly</a> screen and it really lit up the room.</p>
<p>We’ll admit that although we tell you most people can’t see the difference between 720p and 1080p, in the back of our minds we expected to see clarity and detail differences between the HD6700 and the other 1080p projectors we’ve used. And of course, in some areas and with some content, we did notice a bit of degradation in clarity. But we had to look pretty hard. And if you factor in the affordability, once we got engrossed in something on the screen, it looked really good and we lost all knowledge that it was a 720p projector.</p>
<p>As far as the actual 3D experience goes, we had our ups and downs. The projector did really, really well with the depth aspect of the 3D image. It really looked like the screen sunk into the wall, like a virtual diorama. And some the objects that were supposed to be popping out of the screen came right out as well. Some of those pop-out objects, however, didn’t work quite as well. It seemed like the further an object was supposed to pop out, the more faint it was, to where they appeared more like holograms than physical objects. Think: “Help me Obi-Wan Kenobi, You&#8217;re My Only Hope.&#8221; They appeared to work a bit better on our gray screen than the bright white one, but that might just be our imagination. And that would directly contradict generally accepted theory that higher gain is better for active 3D.</p>
<p>The HD6700 lacks some of the features you’d want in a permanently installed projector for a dedicated theater. It doesn’t allow for lens shift, so you have to get things lined up just right. The zoom distance isn’t overly impressive either, so we actually had to move the projector quite a bit closer to the screen than we’ve had to with other projectors in other reviews. So it doesn’t work well as a dedicated home theater unit, but it would work great in a loft or bonus room, or as the projector you pull out and put on the coffee table when you want to watch something in 3D.</p>
<h4>The Converter Box</h4>
<p>The 3D-XL is where things got really interesting. The HD6700 is what they call 3D ready, meaning it can display 3D content if you connect it to a source capable of outputting the 720p/120Hz video it needs for 3D. That’s what you get from the 3D-XL. Without it you’d need to use a computer with a 3D graphics card in it. That’s certainly doable, but not nearly as plug and play as a simple box you run HDMI into and out of.</p>
<p>The converter has two HDMI inputs. So if you have two 3D sources such as a Blu-ray player and a set top box for the ever so rare 3D TV content, and you don’t have a 3D capable receiver or HDMI switch, you can still get away with just running one HDMI cable to the projector. Switching between sources is as simple as pressing a button on the front of the unit. Our demo model didn’t come with an IR remote, nor do we believe one exists. If you wanted the 3D-XL in your theater, that would have been a nice touch.</p>
<p>In addition to the 720p/120Hz outptut, the 3D-XL is also capable of splitting the 3D signal into separate left and right 1080p video signals for creating your own passive 3D system. It can only output one at a time, so you’d need two of them to make it work. We only received one in our demo system, so we weren’t able to try it. Of course you’d need two identical 1080p projectors as well, lined up and calibrated exactly the same. In theory, this sounds awesome. All we’d have to do is go watch Thor in 3D a couple times, keep the glasses, and we’d be all set for home 3D viewing parties. Of course you would need two polarizing filters and a silver screen as well.</p>
<h4>Conclusion</h4>
<p>Bottom line, we still aren’t sold on 3D. Although, truth be told, we did find ourselves getting engrossed in the content once it got rolling. And while a 100 or 120 inch screen still isn’t the same as an IMAX, it’s a closer approximation and makes the 3D pretty fun. The Optoma package of an HD6700 and a 3D-XL for under $1200 is an incredibly inexpensive way to dip your toe in the water. Even if you only pull it out for special movie watching occasions, it’s worth looking into at that price. You’d be able to watch 3D movies on your big screen, and that’s certainly something you can brag about. If the glasses weren’t $100/pair, we’d seriously consider it (at least Braden would).</p>
