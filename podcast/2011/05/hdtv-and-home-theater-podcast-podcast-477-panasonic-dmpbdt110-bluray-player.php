<p>You notice that this is a different player before you even open the box. Its half as deep as a typical player. This is a great feature because you can plug in your cables and put it on a shelf in your rack and not have to worry about cable clearance. The player measures ~17&#8243; x ~1 1/2&#8243; x ~7&#8243;  or (430mm x 37mm x 179mm) and has first rate fit and finish.</p>
<h4>Setup</h4>
<p>Setup is straight forward. For our tests we used HDMI to a switching receiver and we connected the device to the Internet via an Ethernet cable. The unit is Wi-Fi ready but it requires and optional antenna. If you want you can go with the BDT210 (<a href="http://www.htguys.com/shop?id=B004G8HXXO">Buy Now $170</a>) with built in Wi-Fi.  Once powered up we performed a firmware update. This is important because previous versions of the units firmware did not perform well with Netflix. The whole process with the firmware update took about 30 minutes.</p>
<h4>Performance</h4>
<p>With this player you will always have something to watch and you won’t have to leave your house to get to it. For this review we looked at DVD, Blu-ray, Netflix, and Vudu. We look at each one individually.</p>
<p><em>DVD</em> &#8211; We watched a few movies and found the BDT-110 to be a capable upconverting player. The Harry Potter movies almost looked like HD. It could be due to the dark lighting but we were quite impressed with how good the video looked. Other movies showed improvement as well. What we found is that movies that have great Blu-ray transfers also have high quality DVD transfers which upconvert quite well. Regardless, your standard DVDs will look quite good on this player.</p>
<p><em>Blu-ray</em> &#8211; Your HD movies will look stunning! But you expect that with any Blu-ray player today. One thing that irritates Blu-ray owners is how long it takes some players to load Blu-ray discs. The 110 does this quickly. Our baseline is loading Close Encounters of the Third Kind. Some of our early players would take as much as three minutes to load this title. The 110 was able to load it in 10 seconds. Audio was equally good. The player will decode all next generation audio formats or it will send the bitstream to your receiver.</p>
<p><em>Netflix</em> &#8211; Streaming movies through <a href="http://gan.doubleclick.net/gan_click?lid=41000000035479074&amp;pubid=21000000000247790">Netflix</a> looked quite good. We have a very high speed connection so there was no buffering of the movies. This experience will vary based on your connection. We also find hardwired works better than Wi-Fi regardless of the speed of your connection.</p>
<p><em>Vudu</em> &#8211; This is where we were really impressed with this player. <a href="http://www.vudu.com/">Vudu</a> has a format called <a href="http://www.vudu.com/product_hdx.html">HDX</a> which is high quality 1080p video. This video is the closest to Blu-ray you can get with any streaming technology. Vudu also includes a 5.1 Dolby Digital+ soundtrack that many say sound as good as lossless formats.  HDX movies cost more to rent but for some titles its worth it. We compared Blu-ray versions of Harry Potter Deathly Hallows to the HDX version and couldn’t see a difference on our 58 inch plasma.  Audio sounded as good as the Blu-ray as well. We remember when you had to buy a Vudu box for more than the price of this player.</p>
<p><em>3D</em> &#8211; The 110 supports native 3D and will convert your 2D content to 3D as well. Native 3D looked quite good when displayed on our 58 inch plasma. For the 2D to 3D conversion&#8230; let’s just say its still a work in progress in our opinion. Sure you get 3D elements and you can dial in how much of the effect you want, but it just didn’t look right at times. The best we can say is that sometimes it looked really good and sometimes it looked pretty bad. One final note about the 2D to 3D conversion, we have read that if you own a Mitsubishi or Samsung DLP &#8217;3D Ready&#8217; TV, you will not be able to use the feature.</p>
<h4>Everything Else</h4>
<p>This player is loaded with a lot of cool features.</p>
<ul>
<li>Touch-Free Sensor &#8211; The front panel opens without the need to touch anything.</li>
<li>Skype Button &#8211; Launch Skype without going through the Viera Cast menus</li>
<li>Netflix Button &#8211; Launch Netflix without going through the Viera Cast menus</li>
<li>VIERA CAST</li>
<li>DLNA</li>
<li>SD Memory Card</li>
</ul>
<h4>Conclusion</h4>
<p>The Panasonic DMP-BDT110 has become our Blu-ray player of choice for anyone who wants it all! The only downside with this player is that it does not support WiFi natively. Great performance and tons of useful features combined with two high quality movie services means you will always have something to watch.</p>
