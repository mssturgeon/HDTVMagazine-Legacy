<h3>What is RVU?</h3>
<p>DirecTV recently began testing what they’re calling a new “media center” that will allow customers to watch live and DVR recorded programming on any TV in the house without the need for a set-top box in each room.  This new media center is built on a technology called RVU.  But what exactly is RVU?  There’s an <a href="http://www.rvualliance.org/">RVU Alliance</a>, but what do they do?  What does “RVU” even mean?</p>
<h4>What does RVU stand for?</h4>
<p>The first question we had was, what exactly does RVU stand for?  Is it an acronym?  The answer is no, it is not an acronym.  It is pronounced R-view and is somewhat a short form for the phrase “remote view.”  So bottom line, RVU isn’t an acronym.  Weird.</p>
<h4>What does it do?</h4>
<p>From the RVU Alliance website:<br />
“<em>RVU allows the television viewer to watch live or recorded programming on various manufacturer-branded TVs or clients while experiencing a consistent user interface-no matter which client device is employed. Once connected, the TV viewer can watch the service provider content from any room of the home.</em>”</p>
<p>In a nutshell, RVU is the technical specification for distribution of media content (movies, TV, music, etc.) in your home.  That isn’t new, many of us have been doing that for years.  But what RVU adds is what they refer to as “pixel accurate remote user interface graphics.”  That means a consistent look and feel across all devices.</p>
<p>The idea that you can record and watch TV on one device, but play it back on others isn’t a new concept.  People have been doing this for years with Windows Media Center, SageTV, BeyondTV, Media Portal and a host of others.  But RVU defines a standard so all clients can talk to your server, regardless of who makes it.</p>
<p>They also make it easy on the client by putting all the smarts in the server.  The client simply issues commands to the server.  The server builds the UI screens and “streams” them back to the client.  The client is more like a web browser than a traditional media player on the network.  So instead of implementing an entire UI on the client, the RVU protocol (called RUI) clients are very thin, but they still somehow provide a robust, consistent UI experience across all devices.</p>
<h4>Technical details</h4>
<p>RVU is based on UPnP and DLNA, to us it looks like DLNA with a better UI.  RVU clients are able to connect to DLNA servers and stream content, you don’t need an RVU server.  But if you want the cool look and feel, all you have to do is hook that RVU client into an RVU server and enjoy.  In fact, standard DLNA players can even stream content from the RVU server.  Although, in this case, the user experience will be “dumbed-down” to the ever so familiar DLNA experience.</p>
<p>Just like DLNA, the RVU protocol works over your existing network, either wired or wireless.  The website lists support for hard-wired Ethernet, MoCA, HomePlug and WiFi &#8211; although they require 802.11n.  The video content can go up to 1080p as can the graphicall elements created for the user interface.  And for those who were wondering, the answer is yes, “The RVU specification is scalable to provide multiple viewing planes as used by 3D Digital TVs.”</p>
<h4>Who is the RVU Alliance?</h4>
<p>From the RVU Alliance website:<br />
“<em>The RVU Alliance is backed by leading content service provider, semiconductor, and consumer electronic companies. The founding members include Broadcom, Cisco, DIRECTV Samsung and Verizon.</em>”  Other notable names listed on the website include: LG, Motorola, EchoStar and Sony.</p>
<h4>What’s next?</h4>
<p>According to DirecTV, their RVU-based media center, the HR34 server, and their C30 RVU clients (because it isn’t built into any TVs yet) are expected to be certified for the RVU spec in June.  DirecTV has announced plans to begin rolling out theses RVU-enabled products to customers nationwide in October of this year.</p>
<p>We haven’t had a chance to test it, but it sounds pretty cool.  Of course Hana sounded cool as well, but the actual implementation left something to be desired and that one fizzled.  DirecTV seems to be aggressively pushing RVU, so we’ll keep our fingers crossed that things turn out differently.</p>
<p>If you’ve already built a similar system with one of the other options already available, we don’t know if RVU will provide any advantages.  The only one we can see is that eventually the RVU client will be built directly into your TV, so no need for an extra box.  Built into your <em>Samsung</em> TV at least.</p>
