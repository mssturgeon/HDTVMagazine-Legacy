<p>According to news reports, Google is investigating the possibility of offering pay TV service in the Kansas City Metropolitan Area and and it could go live as soon as 2012.  Google is building another installation of their gigabit-per-second experimental fiber-to-home network in the area and would reportedly build the TV service on top of the high bandwidth broadband access.  They could offer traditional telephone service over the same lines, moving them right into the heart of the traditional Cable “triple-play” arena.</p>
<p>Google is rolling out an update to their Google TV software right now.  The software could serve as a basis for the operating system at the heart of a Google television offering.  They also recently purchased both Sage TV and Motorola, expanding their capabilities into the DVR and set top box realm.  With YouTube in the fold as well, Google has many of the pieces already to make a significant push into the living room.  There are a lot of questions about the strategy, though.</p>
<p>In the cellular phone market, Google has opted to be mostly a software provider, with limited involvement in the hardware side.  Why, when it comes to the living room, would they branch out from the software business and take on the cable and satellite companies directly?  They could build set-top boxes and partner with the Comcast, Time Warner, DirecTVs of the world.  Instead they’re gunning for them.  It’s an interesting play.  We’ll have to wait and see how it plays out.</p>
<p>It also remains to be seen whether Google’s push into content distribution will be of any real benefit to us as consumers.  Will Google just be another provider, with the same cost structure and offerings as everyone else, or will they be able to do something different?  Can Google finally bring true a la carte options to pay TV?  They’ve recently released new original programming channels on YouTube.  They could probably use this concept and charge a small fee for the traditional broadcast channels, allowing us to build our own Cable TV service</p>
<h4>AppleTV</h4>
<p>Google isn’t the only company looking into providing a new way to watch TV.  CBS has basically come out and said that Apple is trying to build their own monthly subscription service.  Apple’s service would be a bit different than Google’s.  Apple would be built on top of their Apple TV boxes (and potentially Apple TV Televisions), not the underlying broadband connection.  Customers would simply need an Apple TV and an Internet connection and they’d be able to stream live broadcasts directly.</p>
<p>Apple’s play is a direct move against traditional pay TV services.  They would reportedly offer everything (or close to everything) you can get from Cable or Satellite for a fraction of the cost.  The iTunes model is already an a la carte system.  Apple could allow you to pick the channels you want to see live, like ESPN and CNN, and supplement with the shows you want to watch, like CSI and NCIS, very easily.  If it could all be done for a fraction of the price of Cable or Satellite, it could be a huge hit.</p>
<h4>Boxee Live TV</h4>
<p>The rest of the streaming boxes, like Roku and Boxee, would be dead in the water if the Google and Apple boxes had access to live content.  That’s the one piece those boxes don’t have, the one thing that makes them a supplement to Cable and Satellite instead of a replacement.  Boxee is reportedly working to solve that.  Boxee Box owners will soon be able to watch live television through the device using a special USB tuner dongle for free over-the-air HD TV signals.  Boxee is taking us full circle, Boxee and an Antenna coule be all you need.</p>
<p>The Boxee model is unique.  It provides a box that can access all the content you want to get from the Internet, like YouTube, Netflix, Vudu and Hulu (limited support). As Internet video grows, this meets most typical normal television needs, but still lacks the critical live TV component that’s often critical.  Adding the ability to tune in live TV broadcasts makes the Boxess Box a true alternative to Cable, for absolutley no monthly cost.  Of course you can’t record on it, but a Boxee Box 2 with a built-in hard drive could solve that.</p>
<h4>Who will win?</h4>
<p>If all the content becomes somewhat universal, meaning all providers, from Cable to Satellite, Google to Apple, Roku to Boxee are providing the same content, which one will come out on top?  Perhaps they all can.  There’s plenty of room for Sony, Panasonic, Samsung, LG and JVC in the TV market, plenty of room for Ford, Chevy, Toyota and Mazda in the car market, plenty of room multiple companies in many markets.  It will come down to personal preference.  Some will choose based on price.  Some will choose based on brand loyalty, some will choose based on features or ease of use.</p>
<p>But we’ll all assume that we can get anything we want from the provider we choose, so in the short term, it might be the provider that does the best job aggregating what’s already out there.  Instead of providing apps for each content feed, providing one app that seamlessly integrates all the feeds.  Treat content less like a computer or a tablet and more like a television.  We want to see what’s on Netflix, Hulu, CBS and HBO all at once, instead of having to look at one, exit, look at another, and so on.  If we had to do that with our guides on TV, we’d go crazy.</p>
<p>Frontier communications, a broadband ISP provider spread out across 27 states in the US, is trying to build a website to do just that.  One stop for all your online video needs.  If they can provide a site to do it, why can’t Google or Apple do the same thing in a device connected to your TV?  And if all the online content can be aggregated, why not mix in the live content as well?  A search for Castle or Chicago Bears gives you all the archived online content available to watch immediately as well as the listings for upcoming airings so you can watch live.</p>
