<li><strong>Dialog Emphasis (DE)</strong> &#8211;  When you push the &#8220;DE&#8221; button on the remote control you engage a circuit that mimics the functions of a hearing aid. The frequencies used by human voices are emphasized and compressed, while other frequencies are minimized.</li>
<li><strong>Output Leveling (OL) </strong>- Push the OL button and a sophisticated compression processor takes over, making soft sounds louder and loud sounds softer.</li>
<li><strong>Disappearing Display</strong>. The 580 features a four-digit display located behind the speaker grille that shows the current setting for volume, bass, treble and PhaseCue II® (virtual surround) &#8211; and also shows when you have engaged the Mute, Output Leveling (OL) or Dialog Emphasis (DE) features. A few seconds after you stop using your remote (or front panel) controls, the display disappears completely.</li>
<li><strong>Multiple Inputs: </strong>including front-panel connection for iPod® and other portable devices. The 580 has two analog audio inputs, one optical (Toslink) digital input, one coaxial digital input &#8211; plus a front panel 3.5mm analog stereo input for convenient connection of your iPod or other portable audio device.</li>
</ul>
<h4>Setup</h4>
<p>Setup is pretty straight forward. The unit measures 36&#8243; w x 16.5&#8243; d x 5&#8243; h and weighs 33 pounds (91cm w x 42cm d X 13cm h and weighs 15Kg) so there is a little heft to it. It comes in hand lacquered high gloss black so it will look great under almost any TV so long as they are 160 pounds or less.</p>
<p>We connected a DirecTV receiver and an AppleTV via digital inputs and we connected power and we were off and running. For simplicity, ZVOX recommends that you connect the output of your TV to the 580. This is a good way to go if you set your TV to turn off automatically while you are in bed. If you go directly from your Cable Box the audio will continue to play when the TV turns off.</p>
<h4>Controls</h4>
<p>The 580 has the standard volume, mute, bass, and treble but also include a surround setting. There are three levels that adjust the amount of the virtual surround. We found that for the most part we preferred the first level. It was the one with the best dialog clarity. In fact some shows it was the only way to hear the dialog. If you have a Harmony Remote you will want to have this function added to the touch screen. We found that you will want to adjust the surround quite a bit. You will optimize the affect based on channel and program.</p>
<p>There is also an Output Leveling feature that prevents large swings in volume. We found that it did indeed prevent variations in audio without taking away from the experience. The Dialog Emphasis feature works along the same lines. It boosts the frequencies of the human voice while minimizing the others. When you engage the Dialog Emphasis feature it will over ride the surround and leveling functions.</p>
<p>The front panel of the 575 didn’t have any controls or inputs. The 580 has added Power, Mute, Volume, and input selection. There is also a 3.5 mm stereo jack that can be used to connect an mp3 player.</p>
<p>Finally, you can teach the 580 the learn the volume, mute, and power commands of your satellite or cable box remote.</p>
<h4>Performance</h4>
<p>Like the 575 we didn’t expect the 580 to blow us away but with the addition of digital inputs and 5.1 sources we were expecting an improvement. We were not disappointed. In a side by side comparison we were able to hear improvements in the surround processing, dialog clarity and music playback. With that said, don’t expect that you will hear sounds coming from behind you. Its more like the sound stage has become wider. We like music on surround setting 3. We also felt that the 580 could use a bit more bass punch. The 580 does have a subwoofer output that will make the experience a bit better.</p>
<h4>Conclusion</h4>
<p>Our take on the 580 is pretty much that of the ZVOX 575. The ZVOX 580 is a good solution for those who want more than a TV&#8217;s speaker for watching movies and listening to music. Its a perfect device for an apartment dweller, den, or a bedroom because its so dead simple to setup. The addition of digital inputs, improved audio processing, and upgraded front panel all for $100 less than the original 575 pricing makes the 580 a great deal.</p>
