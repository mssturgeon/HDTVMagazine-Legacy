<h4>Planning and Lay Out</h4>
<p>Once you have found a suitable wall for the project make sure that there is enough space for the size screen you want and be sure to leave two to three inches on all sides for the border. Determine the size of your screen. You can do this mathematically but the easiest way to do it is use an online calculator. <a href="http://www.projectorcentral.com/projection-calculator.cfm">Projector Central</a> has a nice one that will tell you what size screen your projector will support given a specified distance. Of course you can always mount your projector and turn it on and pencil out the corners of the screen.  That is another benefit of painting on a screen, you can get a custom size that is perfect for your room!</p>
<h4>Painting Prep</h4>
<p>Mask off the area of the screen. Then use a fine grit sand paper to make the wall as smooth as you can. This will assure that you have a consistent image on the screen without any hot spots. Once you have completed the sanding clean up with dry lint free cloth. Finally you’ll want to apply the primer to the wall. Allow to dry completely.</p>
<h4>Final Steps</h4>
<p>Apply the screen pain to the manufacturer’s instructions and allow to dry. In most cases the drying stage may take 24 hours. Apply pain as evenly as you can. You may need two coats. Once the paint has dried you can either paint on or tack on a black border. And Voila! You have  a fixed screen for a fraction of the cost.</p>
<h4>Home Depot</h4>
<p>One of our listeners, Nelson Wilkinson, took an even more basic approach. He really stretched to get his projector and there wasn’t much budget left for the screen. So he figured he’d just paint the wall white. He followed the steps above and rather than buy screen paint, he went with a pure white ceiling paint. Total cost including primer was less than $20.</p>
<p>To mark off the screen area he projected the pure white opening scene from Ice Age. He masked off the area and put on the primer and then the white. He said that if it didn’t look good he was out about $20 and some effort. Nelson, didn’t originally have a border but after some research he decided that it would give a perceived improvement in contrast. He built it out of 1X4 Poplar wood that he painted black. Six years later Nelson feels no need to change anything.</p>
<p>His advice for anyone doing the same:</p>
<ul>
<li>Prep the wall. Make sure it is smooth. Same as we discussed above.</li>
<li>Get as pure white paint you can find.</li>
<li>Calibrate the projector. This get you the best picture and will improve your experience.</li>
</ul>
<h4>Final Thoughts</h4>
<p>Many people will debate the quality of these screens. But at the price its hard to beat. Sure it will cost you a weekend but think of the savings. If you really can’t live with the  results you can always hang a fixed screen over it in the future. But if you need a custom sized screen without breaking the bank, this just may be the way to go.</p>
