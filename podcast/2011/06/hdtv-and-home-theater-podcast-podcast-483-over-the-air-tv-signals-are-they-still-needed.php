<h3 id="internal-source-marker_0.14975239417023967">Over the Air TV Signals &#8211; Are They Still Needed?</h3>
<p>On the last two shows we discussed the following comments made by CEA President and CEO Gary Shapiro:<blockquote>Using huge swaths of wireless spectrum to deliver TV to homes no longer makes economic sense. Congress should pass legislation to allow for incentive auctions so free market dynamics can find the best purposes for underused broadcast spectrum, such as wireless broadband.</blockquote>In the CEAs findings they stated that only 8% of the US population receives their TV signals exclusively through the air. We feel that this number is artificially stated as low. The survey polled 1,256 adults but it did not say where the respondents were located. If the survey was done in rural communities that number may be as high as 25%.</p>
<p>Regardless, we put together a quick survey to see which side our listeners/readers come down on the subject. Today we’ll discuss the results.</p>
<h4>1) How do you primarily receive your HDTV?</h4>
<ul>
<li>Over the Air 61%</li>
<li>Cable 20%</li>
<li>Satellite 14%</li>
<li>Telco (AT&amp;T/Verizon 4%</li>
</ul>
<p>At first glance it may seem a bit surprising that 61% of our listeners use OTA as their PRIMARY source for picking up their TV signals. But when you think about it, OTA is the highest quality signal available for picking up HDTV signals and our listeners are really into HDTV! How would that question translate to the general public? Well just look around, how many antennas do you see on roofs in your neighborhood? In our neighborhoods its pretty much just the HT Guys.</p>
<p>In reality that number would be far less than the 61% of our listeners/readers but probably nowhere near the 8% of the CEA survey. Our take away from this question, the CEA better not succeed in turning off OTA or it will have a rebellion on its hands from all the consumers they convinced to buy HDTVs in the first place.</p>
<h4>2) Do you plan on (or have already) completely cutting the cord to receive your TV VIA Internet and OTA?</h4>
<ul>
<li>Yes 66%</li>
<li>No 34%</li>
</ul>
<p>Based on the response to our first question these results don’t surprise us at all. Our listeners/readers are on the forefront of technology and have found alternative ways to get their entertainment. Whether its movies through Netflix and Vudu or watching the latest video on Youtube the vast majority of you no longer need to pay a monthly fee for content you don’t watch. With high quality HDTV coming in over the air, all of you are informed and entertained for free.  We’ll talk about why the 34% who said no are not willing to cut the cord in a bit.</p>
<p>For those who answered yes 6% plan on cutting the cord by year’s end, 11% in one to two years, 3% in three years and 3% in more than three years. What really was interesting is that 44% of you have already cut the cord.</p>
<p>Some of the reasons given for not cutting the cord were:</p>
<ul>
<ul>
<li>Bandwidth caps/Internet speed</li>
<li>There is not a  readily available DVR that works with OTA that doesn’t require a HTPC</li>
<li>Specific programming is not available OTA (Food Network, F1 Racing, Sports packages, etc)</li>
<li>Channel surfing becomes harder. (buffering, no accidental discovery, no consistent way of getting access to content)</li>
<li>Any room DVR, Web Access to setup recording, convenience</li>
<li>Poor Reception</li>
<li>OTA used as an extension of cable/satellite not a replacement</li>
</ul>
</ul>
<p>&nbsp;</p>
<h4>3) Do you use any of the following services?</h4>
<ul>
<li>Netflix 82%</li>
<li>Amazon VOD 25%</li>
<li>iTunes 43%</li>
<li>Hulu 49%</li>
<li>Zediva 1%</li>
<li>Cable/Satellite VOD 19%</li>
</ul>
<p>For fun we wanted to see what streaming services were being used by our listeners. Netflix was the overwhelmingly most used streaming service with 82% of survey takers saying that they use use it. It makes sense since the service is available on almost every platform you can think of. Next up was Hulu at 51%. We did not distinguish between Hulu and Hulu+. The two things these services have in common are that they are all you can eat for a flat fee. Its pretty clear to us that all you can eat for a flat fee (or free with quick ads like in Hulu) will win the day.</p>
<p>Apple’s iTunes was the most used a la carte style service at 45% followed by Amazon with 26% and cable/satellite VOD at 18%. Zediva registered 1% even though they stream current hits on demand.</p>
<p>Between these services you will be able to get your A&amp;E, Food Network, or other cable channel without a TV service.  Many shows like Diners, Drive-ins, and Dives are available for download without commercial, usually the day after the show airs. A season pass to the upcoming season of Burn Notice, on USA Network, will run you $45. Less than half a month of a typical cable bill. If you over the air you can buy programs a la carte for current shows or just go Netflix for many older TV series so you don’t have to feel like you are missing anything.</p>
<p>Of course not all programs are available for download, for instance HBO’s Game of Thrones is not available on iTunes at this time. That could change at any time, but in the mean time, cord cutters may have to ask their work friends to discuss some shows when you are out of ear shot. But anyone with a DVR is already used to doing that!</p>
<h4>4) What new services would you like to see offered VIA the airwaves that broadcast TV is now using that would make it worthwhile to forgo OTA broadcasting?</h4>
<p>Now that we have established that listeners of the HDTV and Home Theater Podcast are big proponents of OTA broadcasting, we were curios to see if there would be a service that could be offered in place of television that would make it worthwhile to give up OTA. We got a lot of comments but they boiled down to fast wireless Internet without data caps.</p>
<h4>Something to Consider</h4>
<p>If you could get 100Mbps or better Internet access then you could stream your TV to a set top box. After all, digital TV is 19Mbps digital streams at best and about 11Mbps at worst. This could be a boon for 1080p content. Broadcasters wouldn’t have to make huge investments in equipment to support 1080p.  In fact they could vary the data rate based on the content being streamed.  By allowing the airwaves to be used for Internet, rural areas would now have access that wasn’t there before. In areas with cable and DSL there would be more competition which could force down prices.  One of our news stories talked about Gigabit Internet access. If you had this coming into your house you would have no need for OTA what so ever. So let’s make it a requirement that before any ATSC signals are turned off, the broadcast area must be served by a minimum of 100Mbps service at a nominal cost.</p>
