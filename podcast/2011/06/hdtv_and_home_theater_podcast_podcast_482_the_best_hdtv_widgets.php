<h3>Best HDTV Widgets</h3>
<p>An HDTV Widget is an application that runs on an Internet-connected HDTV, sometimes called a “Smart TV” or other home-theater device, like many Blu-ray players, a Roku, the Boxee Box or a Google TV, that offers functionality beyond the traditional TV watching experience. There are a plethora of these widgets, some useful, some not so useful. We’ve assembled our list of the best, or most useful, HDTV Widgets available right now.</p>
<h4>1. Netflix</h4>
<p>Right now Netflix has to be both the most widely available and possibly the most useful HDTV Widget. Of course it requires a monthly Netflix subscription fee of $7.99 (if you also want to receive DVDs in the mail, you need to pay a little more each month). But for that 8 dollars, you get unlimited access to thousands of movies and TV episodes. The quality is quite good and some titles are available in 5.1 surround (on select platforms).</p>
<h4>2. Vudu</h4>
<p>Why do you want the best home theater on the block? To watch movies, of course. And if you’ve put that much of an investment into your home setup, you want to use it with only the highest quality audio and video you can. Right now the best option is Blu-ray, but a close second is renting movies from Vudu in HDX format. The video is superb and some titles are available in Dolby Digital Plus, the best audio quality of any streaming service.  And you certainly can’t beat the convenience factor.</p>
<h4>3. Amazon</h4>
<p>Amazon Video on Demand could easily get lumped in with all the other movie rental services.  You can rent a movie from the comfort of your couch, which is nice. The audio and video quality certainly don’t compare with Vudu, but the recent integration with Amazon Prime is what gives this widget a slight edge over the rest of the pack. If you already have Amazon Prime for the great shipping benefits, you can now get a ton of free movies and TV episodes streamed as well. The offering is similar to Netflix, but the library isn’t nearly as big and the quality isn’t quite as good either.  But there’s potential &#8211; and it is a bit cheaper than Netflix.</p>
<h4>4. YouTube</h4>
<p>How many times has someone asked you if you’ve seen a particular clip on YouTube? Or maybe you missed a sports highlight, a flub from a local newscaster, or simply have a craving for a particular Weird Al video (<a href="http://www.youtube.com/watch?v=gicDoopws-4" target="_blank">Soccer ball to the face</a>). With YouTube built directly into your TV, you can pull up anything you want, without asking all your friends and family to huddle around your computer or tablet. Sharing the fun is much easier on your big screen (<a href="http://www.youtube.com/watch?v=GuFcXWvSNzY" target="_blank">Soccer ball in the face</a>).</p>
<h4>5. Hulu Plus</h4>
<p>A recent entrant to the Widget game, Hulu Plus isn’t as widely available as many of the other apps on the list, but there’s potential for this app to become very popular, very quickly. Most home theaters are equipped with a DVR these days. That DVR has limits on how many programs it can record at once. With Hulu plus, you can choose not to record the ones you know will be available the next day on Hulu and your DVR capacity grows tremendously.  We’d like to see Hulu put some work into the HD side of things and improve the audio/video experience, but we get the appeal of the widget.</p>
<h4>6. Flickr/Picasa</h4>
<p>While photo sharing apps aren’t the most useful thing in the world right now, they could do wonders for grandma in the years to come. We put Flickr and Picasa on the list based solely on potential, not because we use them or even care about them at all right now. In the future, if grandma could turn on her TV and get a notification that her picture sharing widget had new items to view, she could browse through all those wonderful pics of the grand kids without having to figure out how to log into the computer and navigate her way to them in the Internet. Yes, mom, we know we’ll still need to call more often.</p>
<h4>7. Napster/Pandora/Rhapsody</h4>
<p>Sometimes you just want to rock out. Sometimes you want mood music for a party or event. With the streaming music apps like Napster, Pandora and Rhapsody you can use all the 5.1, 6.1 or 7.1 goodness you’ve built into your home theater to do just that. Of course there are a ton of other ways to get music to your home theater, but having an app built right into your TV or Blu-ray player makes it pretty simple. Dial up just the right music from your plethora of personalized Pandora stations and you can sit back and serve the martinis without worrying about having to change CDs.</p>
