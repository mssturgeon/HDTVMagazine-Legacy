<h3>PlayLater by MediaMall Technologies</h3>
<p>Have you ever sat down to watch a TV Show or Movie at your favorite streaming site, only to find that what you wanted to watch is no longer available? Sure, maybe you saw it just yesterday, but for some reason it has disappeared now. If so, you’ll want to check out a new application called <a href="http://www.playon.tv/playlater/">PlayLater</a> by MediaMall Technologies, the makers of <a href="http://www.playon.tv/index.php">PlayOn</a>.</p>
<p>PlayLater is currently in a closed, invitation-only Beta program. We were fortunate enough to get an invitation so we could play with the software. Hopefully it will come out of Beta soon so everyone can have a look.</p>
<h4>About PlayLater</h4>
<p>We all realize that the streaming video sites on the Internet don’t have unlimited contracts with content owners. They get to stream movies and TV episodes to you for a limited time; if they want it for longer, they need to re-up. That’s why movies disappear on you from sites like <a href="http://www.netflix.com/">Netflix</a>.  We also know that sites like <a href="http://www.hulu.com/">Hulu</a> want you to sign up for premium services, so they limit what you can access. But then the premium services don’t always have all the content the free ones do. Sometimes it’s just downright annoying.</p>
<p>What if there was a DVR for online video? A program for your computer that would let you record those online movies and TV Shows so you could watch them whenever you want.  PlayLater is just that. According to the documentation:</p>
<p>“PlayLater is a software program that gives you the ability to record movies and TV shows available through the PlayOn media server in order to watch them later at your convenience.”</p>
<h4>Using PlayLater</h4>
<p>Currently PlayLater only runs on Windows (XP, Vista, 7, 2003), so if you’re a Mac-only household, you’re out of luck. But if you’re running Windows, it is incredibly easy to get installed and running. The installation is quick and picks pretty standard defaults for where to store recorded videos. The installation process takes about 2 minutes.</p>
<p>Once installed, usage is very simple. You get an icon for each of the video sites supported that you can click on to browse available content. There are currently 30 different choices including the big ones like Netflix, Hulu, Amazon, TV.com, CBS, ESPN, ESPN3, NFL, MLB, etc. Many of the sites require a subscription to access, so you simply pop open the options dialog, fill in your account info for the ones you are registered with, and away you go.</p>
<p>To find a show, you can browse or search each site. Search is currently site specific, so you can’t do one search across all providers. PlayLater doesn’t actually play anything, it just records it, and recording is done in real time. It takes 45 minutes to record a 45 minute show. When the recording is done, you click on the play button and the video plays in Windows Media Player. According to the docs, it takes roughly 500 MB to store a half hour show, 1 GB for an hour show and 2 GB for a 2 hour movie. You can choose to record to whatever folder you want, so you can pick one that has a lot of space.</p>
<p>Videos are locked to the PC where they were recorded. You can’t simply grab a movie file from the storage folder and move it to another computer. This is understandable for legal reasons. In that respect it works just like a DVR. You can’t grab a show from a DVR and move it to another DVR. Unfortunately though, PlayLater went one step further and they won’t let you stream the shows back on a different player using DLNA. This one surprised us. PlayOn supports DLNA, so they could easily do it, and whole-home DVRs allow it. Hopefully they’ll turn this on before the Beta is done.</p>
<p>Audio and video quality are exactly as you’d expect. Obviously no better than watching the shows directly at the site you recorded them from, but for the most part no worse either. We were unable to locate anything with any better that 2 channel audio. But that makes sense too. Most browser versions of these applications and services limit the audio to 2 channels. You don’t get the multichannel audio unless you’re on a more capable player like a PS3 or Xbox 360.</p>
<p>Of course we stumbled across some bugs and errors in our review, but we don’t think it’s very fair to get into those. The software is in Beta, so you don’t expect it to be perfect. Overall, though, it worked pretty well and did exactly what it was supposed to do. It even let us record rented content from Amazon, a neat little back door that’s available in Beta. We don’t know if that will be there in the final version, though.</p>
<h4>Our Wishlist</h4>
<p>While we really like the concept of PlayLater and think it could be a great piece of software, there are a couple things we really wish it could do to put it over the top. If it hit these items, we’d call it a no-brainer for sure.</p>
<ul>
<li>Stream videos locally using DLNA. We already touched on this, but it’s obvious. We don’t watch movies and TV on our computers, we watch them on TV. PlayOn can do it, so can whole-home DVRs. PlayLater should do it as well.</li>
<li>Stream local content using DLNA. This is almost a correlary to the last item. If you could add your own content to the recorded content, you’d have one super library you go to for anything you want to watch. Killer feature.</li>
<li>Better management of recorded shows. Right now the recordings are just one long list of videos. There should be a better way to group and sort them. It would be nice if the software could auto-delete older shows if the drive started to run out of space or after they had been sitting around for a while.</li>
<li>Allow videos to be exported for portable devices. It would be great if I could take the shows with my on a smart phone or tablet. Should be as simple as a transcode to a lower resolution video.</li>
<li>Find a way to record the multichannel audio versions of movies and TV Episodes. Of course this really only matters if you can play it back on your TV, but it would be nice.</li>
<li>Recurring timers or season pass recording. Right now there’s no way to tell the application to record every new episode of a particular show. You have to run the software each morning and tell it to record the new ones. It would be nice if this could be automated.</li>
</ul>
