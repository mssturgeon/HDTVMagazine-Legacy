<h3>Step by Step DIY Home Automation</h3>
<p>Many of our listeners have lights on timers so that their homes look lived in when they are away or so they don’t come into a dark home. With the end of Summer and day light savings quickly approaching, we thought it would be a good idea to give you some step by step tips for home automation so you never have to reset your timers again!</p>
<p>With that said, home automation is far more than making lights turn on and off automatically. Automation can be used to keep your home at the perfect temperature, run your entertainment system and provide security for you when you are away from home. Through automation you can lower your utility bills and make your home more secure. Today we will walk through the steps required to design a home automation system. Note &#8211; we will only briefly mention home entertainment in this discussion. Audio and Video controlled through automation is something that most DIYers are better off leaving to professional integrators.</p>
<h4>Step One &#8211; Start Fresh</h4>
<p>Don’t think about cost. Instead, take a clean sheet approach to your situation. Go room by room and decide what you want to control. Take an actual clean sheet of paper into each room and write down what you want to automate. Your master bedroom may have a few lights that you want to come on at different times of the day. Maybe you want them to turn on when you enter the room? Do you want to be able to turn on your air conditioner remotely? Don&#8217;t forget about security. And be sure to include the kitchen and garage in your automation inventory.</p>
<p>Once you have gone through the home and decided what you want to automate, rank the rooms in the order of importance. Stack each sheet of paper on top of each other with the most important room on top. You can use the ranked list as your automation plan. Most likely automating everything on the list will cost you more than your budget. Even if it doesn&#8217;t cost more you&#8217;ll want to do the work in phases so working from highest to lowest priority rooms is a good idea.</p>
<h4>Step Two &#8211; Visualize your Automated Home</h4>
<p>Now go back to your stack of paper and for each room come up with triggers for each item in the room that is to be automated. Let&#8217;s look at a simple light switch:</p>
<ul>
<li>Flip the switch and the light goes on (manual)</li>
<li>Light goes on 20 minutes after sunset (No more adjusting timers! The light will come on 20 minutes after sunset every day of the year!)</li>
<li>Light goes off at 10:00 PM</li>
<li>Light goes on when sensor picks up movement after midnight</li>
</ul>
<p>You may want to tie multiple actions together with macros. For instance, when you pause your Blu-ray player you may want the lights to brighten. Likewise, you’ll want them to dim when you hit play.  When you are done with this step you will have a plan for the automation of your home starting with the most important room. Next you need to determine your budget and see how much of your plan can be funded. Remember unless you have money to spare your DIY automation project will probably be completed in phases.</p>
<h4>Step Three &#8211; Select the Equipment and Prep the House</h4>
<p>Selecting the modules and controllers is pretty straight forward. If you need to control a light you need a switch. If you want to control a plug in lamp, you’ll need a module to turn it on and off. There are a few DIY technologies out there for lighting and climate control. Some of the more popular technologies are <a href="http://www.insteon.com/">Insteon</a>, <a href="http://www.z-wave.com/">Z-Wave</a>, <a href="http://www.lutron.com/">Lutron</a>, and Life-touch. Once you have determined the technology you are going with you’ll need to determine how you will control your system. This can be hardware or software based. If you already have a PC that you don’t mind dedicating to your home automation you may want to go software based. It will save you some money. You may not want mix home control with daily PC activities so in that case you may want to buy a dedicated controller.</p>
<p>Some things to consider when selecting your technology is how difficult it will be to install. Wireless is typically easier to install but less reliable. Plus you’ll need to change batteries. Hardwired systems are more reliable but require far more effort to install. Some systems use power lines to transmit signals. These work well but not all components, like IR Sensors for example, connect to power. As a result they need to bridge via RF, so you still need to swap batteries from time to time. Some homes may use one or more  technologies to build out their system:</p>
<ul>
<li>Powerline – Powerlines in the home are used to connect devices with controller</li>
<li>Wireless – RF signals are transmitted between devices and control unit. Most solutions use each device as a relay so that the more devices you have the more reliable the network</li>
<li>Ethernet – Your network is used to transmit signals. Can be wired or wireless</li>
<li>Infrared (IR) – Signals similar to a typical remote control</li>
<li>Hard Wired – Physical Wires (RS-232, RS-485, Cat 5) connect the controller to each device.</li>
</ul>
<h4>Step 4 &#8211; Do it!</h4>
<p>Now its time to put all your research and planning into action. Start out small, add a device, control it through your home automation system. Set up triggered events. Then add the next device and so on. Build out your macros a little at a time. If you look at everything you want to do all at once you’ll be overwhelmed.</p>
<h4>Step 5 &#8211; Get Creative</h4>
<p>Now that you have your system in place start thinking cool ways to use it. We have ours setup to sense when we get home via Bluetooth. As soon as our cell phone connects to our computer it sets the system in “At Home” mode. Once we leave, the system automatically goes into “Away” mode. Why pay a security company to monitor your home. Our homes text us when packages are left at the door or if someone opens a gate. When the house is in “Security” mode all the lights turn on, the alarm goes off, and we are texted when an inside motion detector is tripped.</p>
<p>Doing the project can be fun and it can save you a lot of money. Lastly, the most important bit of advice we can give you is to plan everything and then review your plan! Rework costs you time and money!</p>
