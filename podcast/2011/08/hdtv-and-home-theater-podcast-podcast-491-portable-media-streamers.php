<h3 id="internal-source-marker_0.1074427628508865">Portable Media Streamers</h3>
<p>A trend that we have been following for a while now is portability of your media. In the future many believe that the cloud will house all our media and make it available to us everywhere we go. But until we have universal high speed access at low costs we will remain dependent on physical storage. The current crop of portable devices have at most 64GB of storage so often you have to compromise on what media you take with you.</p>
<p>Today we take a look at two devices that make it easy to take all your content with you and make it available to all your portable devices. We’re talking about the <a href="http://www.seagate.com/www/en-us/products/external/external-hard-drive/goflex-satellite">Seagate GoFlex Wireless Storage</a> (<a href="http://www.htguys.com/shop?id=B004Z0S7K6">Buy Now $199.99</a>) and the <a href="http://www.airstash.com/">AirStash</a> ($99). Each of these devices allow you to store your media and stream them to your portable devices via its own wifi network.</p>
<p>The GoFlex is a hard drive based unit that is just slightly larger than an external hard drive. The AirStash is closer to a USB stick in size and uses SD cards for the storage.  By the way, the AirStash does not include a SD card for the $99. If space and ultra portability are important to you, you’ll want to go with the AirStash. Keep in mind you’ll need multiple SD cards to store all your movies. A 32GB SD goes for about <a href="http://t.co/HFLd3u9">$45 to $50</a>. The GoFlex while still quite portable will not fit in your pocket as easy as the AirStash but it will store 500GB of content.</p>
<p>To begin using the devices you plug them into your computer’s USB port and transfer files. The device charges via the USB port as well. Once your files are copied over you can access them via a browser from your portable device or an iOS app. No word on when an Android app will be available. The web access works well on iOS, however, when we tested it on Android devices they wanted to download the video rather than play within the browser. Neither the web or the dedicated iOS app displays meta data so what you name your files will make finding movies and music easy or difficult.</p>
<h4>Performance</h4>
<p>Movies and music played in Quicktime so if you have DRM content you’ll be able to watch as long as your iOS device is authorized. If you rip your own content be sure to select a format that will play on your device. If you are using iOS we’d recommend using Handbrake at the AppleTV 2 preset. We were able to stream 5 connections on the AirStash. Their documentations claim that it will support up to 8 simultaneous connections at a range of 160 feet. We did not have more than 5 devices to test. Through walls we were only able to get about 50 feet in range but with greatly reduced performance. This is really not a big issue as the use case for this device is a car, airplane, or coffee shop. While in the confines of a car or airplane the device should keep most typical families occupied.</p>
<p>The GoFlex only supports 3 simultaneous connections and range of 30 feet. Again, for the use case scenarios it will be more range than you will need. We connected three devices and took it for a spin.</p>
<p>Both devices did what they claimed to do as far as streaming goes. The Seagate device claims a battery life of five hours. We found while streaming three movies we got about 4 hours. The AirStash also claims 5 hours an we were able to get five hours with three streams of video playing.</p>
<h4>Which One?</h4>
<p>For a typical family either device will serve video to your portable devices. It comes down to what’s more important to you. If you want one unit that has 500GB of storage that is reasonably transportable go with the GoFlex. If ultra portability is important to you and you have a bunch of SD cards laying around go with the AirStash. Lastly, both devices seem to work better with iOS than Android right now. The web interface is kind of clunky so if you are an Android user you may be better served by waiting until they release an Android app for your device.</p>
