Vizio 42 inch EDTV Plasma  P42HD $1500<br />
Akai 42 inch EDTV PDP4296HD  $1500</strong></em></p>
<p>They all had similar features and inputs. None of the plasmas had an HDMI port, although all supported DVI. All three shipped with NTSC tuners for basic cable or standard definition over the air broadcasts. If you want to watch HDTV you&#8217;ll need an external cable/satellite box. All three support picture in picture. These plasmas sport a lot of features (check out the links above) but it really doesn&#8217;t change the fact that the execution of these features leaves much to be desired.</p>
<p>The bottom line is that these units are cheap, both in price and construction. There is really nothing else we see that is redeeming about these TVs. Colors did not look right. The sharpness compared to a Pioneer HDTV plasma made you think you needed glasses. All three TVs were displayed right next to a 50 inch Pioneer PureVision plasma display. It really showed you the flaws in the three we are reviewing. The Pioneer&#8217;s blacks were actually black, the picture looked sharp, and the color was accurate. The Pioneer is available for $4700 after rebate, which is a pretty good price.</p>
<h4>LCDs</h4>
<p><em><strong>The LCDs were much better in quality for both picture and construction. We looked at the following:<br />
Maxent 26 inch HD-Ready LCD MX-26X3 $799<br />
Proview 32 inch HD LCD RX-326 $999</strong></em></p>
<p>Both units looked good with decent color and sharpness. These units should not be compared with a Sharp or Philips. However for the $500 difference in price between the Maxent and a Sharp, you won&#8217;t be dissatisfied. The Maxent has a 12 ms response time, the Proview is stated as &lt; 16 ms. Both should be OK for gaming. Although we did not test games it is generally accepted that an LCD with a response time of &lt; 16 ms should be acceptable for gaming.</p>
<h4>Today</h4>
<p>The first thing we noticed when we arrived at Costco was the sheer number of televisions available. Costco used to have one model in each size, occasionally two, where one was a value unit and the other was more of a premium model. Today there are rows of TVs, with often 3 or more models of the same size to choose from.</p>
<p>This really speaks to the commoditization of HDTVs. Seeing the volume of TV options available even at a warehouse store really opened our eyes to why manufacturers are so eager to push 3D and Internet widgets. Trying to convince a buyer to buy one set over the other, based purely on quality, is a losing proposition. Especially when the viewing area is a warehouse with horrible florescent lighting.</p>
<h4>Plasma</h4>
<p>In 2005, you could get the pretty bad 50” AKAI plasma for $3000 or the really good Pioneer Plasma for $4700 (something we called a “good price”).  In 2011 you can get:<br />
<strong><br />
Panasonic TC-46PGT24 46” 3D 1080p plasma $879<br />
Panasonic TC-50PX34 50” 720p plasma $699</strong></p>
<p>Although of course we weren’t able to compare the 2005 Pioneer side by side with the 2011 Panasonic 50”, they are both 720p TVs and have similar features. We’d guess that the 2011 Panasonic outperforms the Pioneer in most cases simply due to how far the technology has come. Even if they were exactly the same, the 2011 model has dropped in price by $4000. It’s funny to think that $4700 was a good price back then.</p>
<h4>LCD</h4>
<p>We had 2 models in the Round-up in 2005: a 26” and a 32”. They were both 720p resolution and had response times of 12 and 16 ms respectively. But at prices of $799 and $999, we didn’t expect to see gigantic adjustments in price, yet we did. In 2011 you can get:</p>
<p><strong>Vizio 42” E422VA 1080p 60Hz LCD with Internet Apps $579<br />
Vizio XVT3D424SV 42” 3D Edge Lit LED LCD $899<br />
Vizio E550VA 1080p 120Hz LCD $974<br />
Philips 55PFL7505D 55” 1080p 120Hz Edge Lit LED LCD $1199<br />
Samsung UN55D6050 55” 1080p 120Hz LED LCD $1799<br />
Vizio XVT3D650SV 65” 3D Edge Lit LED LCD $2999</strong></p>
<p>This is only a small sampling of what’s available, but you get the picture. For roughly the same price as a 32” 720p LCD in 2005 you can take your pick between a 42” 3D LED model or a 55” model. Sure they have 32” models as well, but when you can get a 42” for almost half the price, we didn’t even venture into the smaller screen isle.</p>
<p>Then taking a look at the high-end premium sets, we keyed in on the 65” 3D Vizio for $2999. This is the exact same price as the 50” AKAI plasma from 2005. The plasma that was so bad we recommended everyone stay away from it. But today you can get a 65” 3D LCD. At 65 inches, 3D might make sense, but for $2999 it certainly isn’t crazy.</p>
