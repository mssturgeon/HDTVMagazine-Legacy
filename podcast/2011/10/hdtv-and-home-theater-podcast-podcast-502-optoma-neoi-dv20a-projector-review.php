<li>Universal Dock compatible with all iPhone models and iPod models with video capability</li>
<li>Charges the iPod/iPhone while docked</li>
<li>Project large widescreen images of up to 120&#8243; diagonal</li>
<li>2000:1 contrast ratio</li>
<li>Optional iPad add-on kit &#8211; share content from the iPad</li>
<li>16-watt stereo audio with DSP and Bass Reflex technologies</li>
<li>Lightweight at 2.2 pounds, instant on/off and cool-operating temperature</li>
<li>LED light source lasts over 20,000 hours while producing excellent color</li>
<li>HDMI and VGA ports, for a full range of connection options</li>
<li>Native WVGA resolution (854 x 480 pixels)</li>
<li>50 ANSI Lumens</li>
</ul>
<p>&nbsp;</p>
<h4>Setup</h4>
<p>The Neo-i projector is very easy to set up, easy as plug, dock and play. You plug it into the wall, dock the iPod or iPhone and away you go. Of course it doesn’t have any lens shift capabilities, so the projector needs to be lined up just right with your wall or screen to look its best. If you don’t want to use an iPod or iPhone, you can use any other device with the VGA, HDMI and/ or AV inputs. It should work with just about any portable device that can play video.</p>
<p>While setup should be easy, nothing easy is ever simple. It took use several times docking and undocking the iPhone to actually get video to project. The iPhone would say that the video was being displayed “on the TV” but all we got was a blank screen. But patience prevailed and by the 5th or 6th time redocking it, we were able to get video.</p>
<h4>Performance</h4>
<p>When you get down to it, the Neo-i is a Pico Projector.  Sure it has built-in speakers and an iPod/iPhone dock, but you get Pico Projector performance out of the video.  It’s all the drawbacks of a Pico Projector, without the small, easy to transport benefits.  But when you think about it, to get the equivalent functionality with a traditional Pico Projector, you’d also need to haul around a video cable, an iPhone charger, some speakers and an audio cable. When you add all that up, its probably more cumbersome than just taking a Neo-i with you.</p>
<p>So what does it mean when we say you get Pico Projector performance out of the video?  As you can imagine, it isn’t very bright, so don’t count on using it in an even remotely well lit room.  The colors aren’t very vivid and the picture overall looks pretty soft. Bottom line, you aren’t buying this projector for the video quality.</p>
<p>On the audio side the Neo-i sounds decent, but nothing to jump up and down about. After a while of using it, we were longing for some better audio. It’s like listening to the sound for a movie or video through your laptop speakers. You can do it, but you know there are better alternatives. Yes, it’s a bit better than laptop speakers, but not much.</p>
<h4>Other stuff</h4>
<p>The Neo-i includes a small credit card style remote control that is somewhat useless. It doesn’t control the iPhone menus, so you still have to get on the phone to select a video, fast forward, pause, rewind, etc.  If you’re already doing that anyways, might as well just adjust the volume while you’re there. Since the Neo-i is supposed to be portable, a travel case would have been nice, but it doesn’t come with one. It does come with adapters for any different size i-device that supports video playback.</p>
<h4>Conclusion</h4>
<p>The Neo-i isn’t meant to be an installed projector for your home theater. We don’t even think it’s meant to be an installed projector for a dorm room or bonus room It’s meant to be pulled out on special occasions to watch a video on the wall, or taken on vacation.  For that purpose, it’s actually quite convenient. You don’t have to haul around a ton of cables and parts, just the projector and its power cord.</p>
<p>If you set your expectations correctly going into it, we’re sure you can find clever ways to use it. And for only $279, it’s a pretty good deal.  On a daily basis you could even use it as a dock for your phone or iPod and take advantage of the speakers for music. Then when you need a projector for that special 120” display of your kid’s first piano recital or grandma’s 85th birthday, you’re all set.</p>
