<h6>* The theoretical maximum channel data transfer rate is derived from IEEE 1901 specifications. Actual data transfer rate will vary from network environment including: distance, network traffic, noise on electrical wires, quality of electrical installation and other adverse conditions.</h6>
<h4>Background</h4>
<p>The HT guys are no strangers to Powerline networking.  We&#8217;ve talked about Powerline networking on the show in the past. In fact we have reviewed a few products over the years.  Early devices were rough, they claimed 85 Mbps speeds but barely delivered 10. Then the 200 Mbps spec came out and we found devices that could deliver on the promise of Powerline networking to the Home Theater.  We even use 200 Mbps Powerline devices in one of our recording studios.  The ZyXEL PLA4205 represents the next generation in the progression, and it actually costs less than the 200 Mbps units did when they came out.</p>
<h4>Setup:</h4>
<p>as you can imagine, setup is so easy even a Cave Man can do it.  You plug one adapter into the wall near your router and connect it to the router with an Ethernet cable. Then you plug the other adapter into an outlet near your home theater equipment and you are ready to go.  Easy as that.  If you have multiple devices in your home theater that need an Internet connection, you can plug the Ethernet connection from the PLA4205 into a network switch to get more ports.  The until needs to be plugged directly into the wall, not into a power strip, so keep that in mind.  You’ll lose one of your outlets.  Supposedly there are power strips available that support Homeplug, but they’re tough to find.</p>
<p>The package includes a software utility you can run to manage the name of the network created by the two adapters and to see the devices currently running on it.  According to the documentation, the utility only runs on Windows XP and Vista 32-bit.  We didn’t need it and didn’t use it.</p>
<h4>Usage:</h4>
<p>We used the 500 Mbps Powerline adapters to stream anything we could find, we used it to watch the Slingbox Pro, played movies and DVDs off a local Video Server, Netflix Watch it Now, and OTA HD via HDHomeRun. All of them worked perfectly, without all the glitches you get used to with WiFi connections. We tried all the same tests between direct hard-wired connections and through the Homeplug adapters and couldn’t find any discernible differences.  We even streamed multiple kinds of content to different players (PS3, Google TV, Mac Mini, and Samsung connected Blu-ray player) and had no issues.</p>
<p>One cool benefit of HomePlug AV is that it is backward compatible with older devices.  So if you happen to have some 200 Mbps devices already in use, like we do, you can simply add these new 500 Mbps units to the collection and everything will continue to work.  You won’t get the faster theoretical speeds out of the older units, they’ll simply throttle down the connection.  But odds are you’ll never get anywhere near 200 Mbps in the foreseeable future, so that shouldn’t be an issue.</p>
<p>Along those lines, we knew we’d never get anywhere near 500 Mbps trying to stream audio and video content through our homes, so we decided to see if we could test that theoretical 500 Mbps using pure data transfers to see how fast it would go.  We downloaded a simply utility to test the data transfer rate between two computers.  Using straight hardwired connections, we got around 300-350 Mbps.  Using the ZyXEL we were able to get 44 Mbps and using our existing 200 Mbps powerline adapters we got 36 Mbps.  The speed varied greatly depending on what power outlet we used, but in general the ZyXEL was consistent or a bit faster than the 200 Mbps units.</p>
<p>As a side note, we have been asked in the past if devices like these can be used in conjunction with other powerline technologies, such as Insteon.  We both have Insteon in use in our homes, so it would be nearly impossible to test these units without running them on the same lines as the Insteon signals.  The results we found are while the Insteon devices were active and communicating.  So in this case, at least for Insteon, the two can play together quite nicely.</p>
<h4>Conclusion:</h4>
<p>We don’t want to make one of the infamous quotes about how you’ll never need 500 Mbps transfer speeds in your home, but you certainly won’t need that much anytime soon.  However, if you’re looking for a rock solid way to add you home theater gear to your network with a fast, reliable connection, the ZyXEL 4205 will do just that.  It will be a better solution than WiFi and certainly costs a lot less than running wires through your walls.</p>
