<p>The  BDP-93 is just as easy to setup as any other Blu Ray player.  Oppo has  included a setup wizard to make the task easy. The wizard asks  you six  questions about how your player is connected, what resolution  you want  to output, aspect ratio, and so on. When that done you are  ready to go  for basic playback. If you want advanced features like  streaming video  you will need to go into the setup menus.</p>
<p>Getting   the unit onto the Internet is easy and the people at Oppo have given   you two options, wired and WiFi.  If you go the WiFi route you will need   to connect the included wireless N dongle.</p>
<p>Oppo  has added an  additional HDMI output to the BDP-93 so that if you want  to enjoy 3D  and next generation audio with your non-3D compliant  receiver, you can  route one of the outputs to the TV and the other to  your receiver.</p>
<p>Oppo   includes options for custom installers as well. There is an IR in port   on the back of the unit so that you can install the player in an out  of  the way area and still use it with an IR remote control.  There is  also  an RS-232 control port so that the player can be integrated into a  home  automation environment.</p>
<h4>Performance:</h4>
<p>We  expected a lot out of this player because of its name and price.  With  Blu Ray players in the $150 range that give you BD-Live and  Netflix  Streaming why would you pay $300 more for this player. Well  that’s  simple. because its some of the best video we have seen on our  displays!  If you are into quality video you may want to consider this  player.</p>
<p>The  key to the high performance is the Marvell Kyoto-G2  video processor  with the second generation Qdeo™ technology. We saw a  demo of their  first generation technology at CES in 2008 and were  impressed with what  it did to content on an iPod. Adding this  processing to Blu Ray made for  some incredible images on our displays.  For your DVDs, the Oppo  performs Per-pixel motion-adaptive  de-interlacing and advanced scaling  to upconvert the source. Then the  Kyoto-G2 applies its technology to  create some of the best upconverted  content we have seen in a Blu Ray  player.</p>
<p>We  watched all movies  at 24 frames per second. The unit does an excellent  job of reproducing  a theater like experience at that frame rate.  However, you do need a  display/projector that can accept a 24 fps  signal. Most newer LCDs and  plasmas will.</p>
<p>You’ll  be surprised by what blew us away. We  watched a few scenes of the Rocky  Horror picture show. Ara had seen  that movie dozens of times in the  80’s (at his girlfriend’s insistence  of course) and he couldn’t remember  it being so vivid. The colors were  incredible and so clear. We kept  looking for things that couldn’t have  been detected in the original  film. Speaking of color, the BDP-93 has  custom picture adjustment  section. When Ara had his projector  calibrated by Ray Coronado, he went  into the picture adjustment section  on Ara’s BDP-83 to make sure that  the player was at its best. If you  are not using a professional  calibrator we recommend leaving the player  in the default settings.</p>
<p>In  general, we found the Oppo did  well with everything we threw at it. Of  course a player like this  really shines when its mated with a large  HDTV. Because of the price we  recommend that you should consider this TV  if you have a 50 inch or  larger display. The benefits on smaller  displays are hard to  distinguish.</p>
<p>DVD  performance was equally impressive. While we  won’t say that the DVDs  were turned into high definition we will say  the picture vastly  improved. With that said, we still find that some  DVDs upconvert better  than others. More modern titles seem to look  better than some older ones  we have. The higher the quality of the  transfer results in a higher  quality upconversion. We figure the newer  titles look better since they  were mastered for Blu Ray and then  downconverted for DVD.</p>
<h4>Odds and Ends</h4>
<ul>
<li><strong>Streaming Video</strong> &#8211; The BDP-93 Blu Ray player  supports Netflix Instant Streaming and  Blockbust On Demand. Both  interfaces are functional and the quality of  the streams are similar to  other devices. These are nice features if you  don’t have a TV or a set  top box with this functionality. Now we each  have three ways to watch  Netflix on the same TV!</li>
<li><strong>Audio</strong> &#8211; The Oppo supports Dolby® TrueHD, DTS-HD Master Audio™, 7.1-Channel Analog Output</li>
<li><strong>Media File Playback</strong> &#8211; The Oppo will playback media  across your network with DLNA support as  well as multimedia content off  of Optical, USB, and e-SATA drives.</li>
</ul>
<p>&nbsp;</p>
<h4>Conclusion:</h4>
<p>There  are a lot of Blu Ray players out there, many of which cost  less, but if  you want the highest quality picture with Blu Ray and  Standard DVD, you  only have one choice. The Oppo BDP-93!</p>
