<p>JVC has a suggested retail price of $950 for this set, but if you shop around, you can find it for as low as $700.  We have it at the HT Guys Store for around $785 (<a href="http://www.htguys.com/shop?id=B0056VM8OO">buy now</a>).</p>
<p>Listen to the show and the interview with Tom Paterniti to get the full run-down on the features of the set.</p>
<h4>Setup:</h4>
<p>Setup is simple: plug it in and turn it on.  In fact, the built-in Auto Power Off feature also functions as an Auto Power On feature, so you don’t even have to actually turn it on.  Simply turn on your Blu-ray player or other video device and the TV will magically come to life.</p>
<p>The set includes a stand, but the stand isn’t attached to the TV out of the box.  This makes the box itself very thin, but also means you have to attach the stand yourself.  JVC went the extra mile and actually included a screwdriver in the box so you don’t even have to hunt for the right tools.  The TV is so light Braden was able to assemble the stand and get the TV up and running single-handedly.</p>
<h4>Performance:</h4>
<p>When you listen to the show and the interview you’ll hear that JVC intentionally left off the “extra” features like Internet widgets and 3D so they could focus on the audio and video quality of the television.  Since we could care less about 3D right now and can add widgets with pretty much any Blu-ray player or a wide array of other devices, we loved this decision.  After all, what is a TV really for?  Primarily video quality, but in some environments audio quality can be equally important.</p>
<p>The model we tested absolutely delivered on the hype.  The video quality was as good as any CCFL LCD TV we’ve seen.  We’ve seen slightly better in some LED models, but for the cathode units it is certainly at or near the top of the list.  It even bests some of the early plasmas we’ve reviewed in the past, which is impressive for a non-LED LCD.  It isn’t quite up to modern plasma quality, but very close and offer some advantages over plasma in size, weight and energy efficiency.  An if you want a set that will go toe to toe with plasma, don’t worry, JVC has a LED model set to come out very soon.</p>
<p>As good as the video was, what really blew us away was the audio quality.  It sounded better than any flat panel TV we could remember.  Not having all of them available to direct comparison makes it tough to draw definitive conclusions but let’s just say we couldn’t recall a TV sounding this good.  In a home theater you’ll still want a dedicated surround system, but in a lot of environments like a loft, bonus room or bedroom, you’ll be more than happy with these built-in speakers.  We were.</p>
<h4>Conclusion:</h4>
<p>For somewhere in the $700-$900 price range, there’s a slight premium for the BlackCrystal set when you factor in the lack of extra features.  But the premium really isn’t that large, and it certainly impresses with audio and video quality.  If you need an LCD in a room that won’t have a dedicated surround system, buy this TV.  If you’ll have dedicated surround, absolutely put it on your short list.</p>
