<li>On-Screen GUI Display</li>
<li>Multi-zone audio (7.1 or 5.1 + 2)</li>
<li>Digital Formats: JPEG, MP3, WAV, WMA</li>
</ul>
<p>&nbsp;</p>
<h4>Setup:</h4>
<p>Like  the little brother, the 1120 feels pretty light; it is heavier  that the  820, but still weighs in at around 28 pounds.  Of course it’s a   receiver, so you have to connect speakers, input sources, and power.   Since this unit supports Internet and network connected features, you   can plug an Ethernet cable in as well.  The default DHCP configuration   grabbed an IP address right away, so for us, network setup didn’t add   any time at all. We spent a lot of time with the Bluetooth   functionality of the 820, so we decided to skip that in the review of   the 1120.</p>
<p>The  auto calibration was very easing using the  included calibration mic. It  plugs into the front of the receiver with a  cord easily long enough to  reach our ideal listening position.   Calibration took a while, but we  got a nice on-screen GUI on the HDMI  output that showed us what was  going on.  That helped pass the time a  bit. Pioneer&#8217;s exclusive  Multi-Channel Acoustic Calibration system  (MCACC) did a pretty good job,  but of course we fined tuned things a  bit as well.  Nothing beats a  trusty <a href="http://www.htguys.com/shop?id=B000I4ZVHU">Sound Pressure Meter</a> for getting your audio dialed in just right.</p>
<h4>Performance:</h4>
<p>With  all your video sources going through your reciever these days,  it’s  tough to say that we buy a receiver for it’s audio performance  anymore.   These days video is just as important as audio.  The 1120 has  Marvell  video processing so you can upscale your picture to digital  1080p from  virtually any source, even digital HDMI.  While the video  looked good,  we experienced quite a few video drop-outs we weren’t used  to seeing  with other receivers from brands like Onkyo and Denon.   While it was on,  it looked great, we just wish it stayed on all the  time.</p>
<p>The  more we used the unit, the worse the dropouts became.   Eventually, it  was just plain unusable as an AV Receiver.  For the  sake of this review,  we assumed it was a bad unit so we could continue  with our testing. But for us, this unit is not at all usable.  It’s a  shame, too, because  the video processing was very good.  The Marvell  technology really  worked, while it was on screen.</p>
<p>As to audio, this unit did really well.  It supports Dolby True HD, Dolby Pro-logic IIz and DTS Master Audio.  Like the <a href="http://www.htguys.com/podcasts/2010/8/6/podcast-437-onkyo-tx-sr608-review.html">Onkyo TX-SR608</a> we recently reviewed, the Pioneer won’t let you run 9 speakers at once,   even if you connect an external amplifier to the audio pre-outs.    That’s annoying, but since there really isn’t any content for the 9   channels, we can live with it.  The 1120 produced very good sound.  We   would describe the sound as very accurate and clear.  Other receivers   are louder, others might have a “fuller” sound, but the Pioneer is very   crisp.  We tried with several speaker configurations and got the same   impression.</p>
<h4>Other Features:</h4>
<p>The  1120 includes an iPod cable so you can connect your iPod, iPhone  or  iPad directly to the front of the receiver. It works just like the  820,  so we don’t need to get into it too much.  You can also use the  front  USB for other devices that store digtal files.  Beyond the iPod  cable,  the 1120 also works with Pioneer’s free iControl app.  We  actually found  it to be quite useful.  Of course nothing beats an good  universal  remote, but for quick access to the Pioneer without having to  pull out  the factory remote or dig through device menus, it works  really well.</p>
<p>The  network connection is for more than just iPhone  control, though.  You  can use it control the unit from your PC or Mac  as well.  We didn’t see a  whole lot of use for that, but it’s there if  you want it.  The 1120  will also connect to the Internet and allow you  to stream Internet radio  directly to the receiver.  This gives you  literally thousands of  stations &#8211; almost unlimited amount of choices  for things to listen to.   We don’t do a lot of radio listening in our  home theaters, so the  feature might be wasted on us, but for those who  do, this should come in  pretty handy and save you from having to buy a  secondary device.</p>
<p>While  the 820 didn’t provide any on screen  display over HDMI, the 1120 does  provide a rich GUI over HDMI for setup  and configuration.  This is  great, but it fell short of being perfect.   Many other receivers in this  price range will also display status  information onscreen, over-layed  on top of the video you’re watching.   For example, volume levels,  changes in audio mode, etc.  With the  Pioneer you have to keep an eye on  the front LCD display to know what’s  going on.  We would have expected  more from such a feature rich  receiver.</p>
<h4>Conclusion:</h4>
<p>The  Pioneer VSX-1120-K does add quite a bit of capabilities to our  go to  receiver for value, the VSX-820-K and we believe it’s worth the  extra  $200 if you can swing it &#8211; if you can ignoring the video dropout  issue  assuming ours was a bum unit. We won’t go as far as saying it’s  the best  receiver we’ve used in this price range, but it does a solid  job and  should satisfy most needs.  It’s a good receiver, but it would  have to  be a bit better to get a unanimous seal of approval.</p>
