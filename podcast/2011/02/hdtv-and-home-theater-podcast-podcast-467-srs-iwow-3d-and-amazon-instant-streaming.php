<h3 id="internal-source-marker_0.797481354314502">SRS iWow 3D</h3>
<p>The <a href="http://www.htguys.com/shop?id=B0026650XS">SRS iWow 3D</a> is a device that plugs into your iPhone, iPod, iPod nano, or iPad via   the 30-pin Apple connector and has a  receptacle for your headphones.   Its purpose is to improve the sound quality of whatever you are playing.</p>
<p>To  get started you have to download an app to your device that  allows you  to enable the various modes. The app does not run after the  mode is set.  SRS has tuned the device for three environments:</p>
<ul>
<li>Headphones</li>
<li>Speakers</li>
<li>Car</li>
</ul>
<p>There  are also advanced settings that provide you more control. We  tested the  device in Headphone and Speaker mode. The iWow 3D has a  button on it so  you can enable and disable the audio processing making  it quite easy to  hear the improvement it provides. There is also a cool  music trivia  game included with the app that we scored pretty poorly  on.</p>
<p>The  additional controls are really needed to help find the  settings that  work for you. For instance, the bass feature really pumps  up the bass,  if you don’t like that you will definitely want to turn  it off. When  listening to high quality rips, or even lossless, with  good quality  headphones you may not find that the iWow improves your  music. In some  cases, you may find that the processing is distracting.  For some of our  music we found the best performance was to turn all the  options off. Let  your own ears be the guide.</p>
<p>We  did uncover  one issue when listening on an iPad with 3G. The iWow  introduced a  hissing sound. SRS was able to recreate the issue in their  lab and they  are looking into it.</p>
<p>Overall  we were quite pleased with what we  heard. We definitely heard a deeper  and richer bass and the dialog in  movies were clear and easy to make  out. We noticed an increase in the  loudness as well. At $50 it easy for  us to recommend iWow 3D, iPad 3G  issue not withstanding.</p>
<p>Last  note, if you have an iPhone you  won’t be able to use the iWow for  telephone calls. You’ll need to  unplug the iWow to take or make a call.</p>
<p>There are two models only differing in what’s included:</p>
<ul>
<li><a href="http://www.htguys.com/shop?id=B0026650XS">iWow 3D Adapter $49.99</a></li>
<li><a href="http://www.htguys.com/shop?id=B004L2LE30">iWow 3D Adapter with Multicolor Faceplates and Headphones $69.99 </a></li>
</ul>
<p>&nbsp;</p>
<h3 id="internal-source-marker_0.8382999161620829">Amazon Instant Streaming</h3>
<p>This week Amazon announced that <a href="http://amzn.to/hAp8Lh">Amazon Prime</a> members will get instant streaming of 5,000 movies and TV shows. We are big fans of <a href="http://amzn.to/hAp8Lh">Amazon Prime</a>.   You get free two day shipping on almost anything Amazon sells. But  with  free unlimited streaming of 5,000 movies its a no brainer&#8230;or is  it?</p>
<p>First  off if you are already an Amazon Prime member this is a  good thing. But  if you are joining solely for the reason to stream  movies read on  before you plunk down your hard earned cash.</p>
<h4>5,000 Titles</h4>
<p>Amazon  states that they have 5,000 movies and TV shows but that  number is a  bit deceptive.  We found 1,704 movies and 484 TV shows that  were prime  eligible. The way Amazon (and Netflix by the way) inflate  the numbers is  to count each episode of a TV show as a new title. Five  thousand is  definitely better than 2,188!</p>
<h4>Studios</h4>
<p>There are just over <a href="http://www.amazon.com/gp/search/other/ref=sr_sa_p_studio?rh=n%3A16261631%2Cn%3A%2116261641%2Cn%3A16386761%2Cp_85%3A2470955011&amp;bbn=16386761&amp;pickerToList=studio&amp;ie=UTF8&amp;qid=1298496822">50 studios</a> offering movies for the streaming service. Many of which you have never heard of. Here is a partial list:</p>
<ul>
<li>Sony Pictures &#8211; 142</li>
<li>Columbia Pictures &#8211; 6</li>
<li>Magnolia &#8211; 163</li>
<li>Reel Enterprises &#8211; 293</li>
<li>Egami &#8211; 279</li>
</ul>
<p>As far as TV goes there are <a href="http://www.amazon.com/s/ref=amb_link_355368542_4?ie=UTF8&amp;rh=n%3A16262841%2Cp_85%3A1&amp;page=1&amp;pf_rd_m=ATVPDKIKX0DER&amp;pf_rd_s=gateway-center-column&amp;pf_rd_r=1TG3B878M9BPDQHG9WNK&amp;pf_rd_t=101&amp;pf_rd_p=1288992182&amp;pf_rd_i=507846">25 studios</a>. Missing from the list are ABC, CBS, NBC, CW, and Fox. What you do get is:</p>
<ul>
<li>BBC America &#8211; 132</li>
<li>BBC &#8211; 102</li>
<li>PBS &#8211; 70</li>
<li>National Geographic &#8211; 43</li>
</ul>
<p>&nbsp;</p>
<h4>Content</h4>
<p>The  content is not too compelling. With the exception of Sony  Pictures  there isn’t too much main stream stuff to choose from. If you  like  independent or real old movies you may find something here.</p>
<h4>HD and 5.1 Audio</h4>
<p>Forget  about it! We could not find a title that was 5.1 audio for  streaming.  Now we didn’t check the entire list but the movies we did  check were  stereo. As far as HD goes, there are HD titles but the  quality is  nothing we’d call HD. In fact we’ve seen DVDs that looked  better. In  general video quality ranged from pretty bad to decent. The  newer the  content the better the quality is what we found.</p>
<h4>Final Thoughts</h4>
<p>Again  we want to state that we love Amazon Prime for buying  everything from  HDTVs to toothpaste. Should you sign-up for the service  just for the  free streaming? Quite simply put, No. We are sure the  selection will  improve over time and we’ll reevaluate then. Also, if  you have a free  Amazon Prime account because you are a student or a new  mother you will  not be eligible for the service.</p>
