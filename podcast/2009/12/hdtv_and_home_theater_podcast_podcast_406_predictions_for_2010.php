<p><strong>OLED will break the 11 inch barrier for a commercially available model</strong> &#8211; Look for LG to introduce a 40 inch model before the year is over. Don&#8217;t expect that it will be affordable until our 2013 predictions show. At some point OLED will be the technology of choice. It&#8217;s thin, has vivid colors and sips electricity. While we want this technology to succeed we are not holding our breath. We have been reporting on OLED since we started this show in 2005.</p>
<p><strong>Plasma will hold on to market share if not get a little stronger</strong> &#8211; People will realize that Plasma technology is still the best way to watch HDTV. Its time to put the Plasma myths to bed. Burn in is no longer an issue, Plasmas do not need to be recharged every couple of years, a properly calibrated Plasma uses only slightly more power than a similarly sized LCD, and new screen coatings have minimized screen glare. Why pay a premium for 240Hz or LED backlighting? These technologies were created just so they can compete with Plasma. A 58 inch plasma goes for $1500 and a 55 inch 240Hz LED lit LCD goes for $3000. Its a no brainer!</p>
</div>
<h4>Braden&#8217;s Predictions</h4>
<div>
<p><strong>Netflix will make some new releases available via streaming</strong> &#8211; It won&#8217;t be all new releases, but Netflix will work out an arrangement with at least one studio to make their new release movies available the same time they show up on Amazon, AppleTV and Vudu.  This may require a new pricing structure: an added fee on top of your existing monthly cost to get access to the new releases, but they will start to move in that direction.</p>
<p><strong>Blockbuster will make the transition to kiosk</strong> &#8211; Over the course of the year, Blockbuster will begin to close down the traditional brick and mortar rental stores in favor of more kiosks.  They will need to invest in their online business to combat Netflix and their kiosk business to combat Redbox.  This will require closing many of the traditional Blockbuster stores.  There will still be stores at the end of the year, but significantly less than there are now.</p>
<p><strong>High Definition streaming will become a reality</strong> &#8211; Someone with a little more market penetration than Vudu, someone like Amazon, Netflix or Apple, will make the same video quality as Vudu HDX available to their customers.  This will be the streaming version of HD-DVD: video quality will rival Blu-ray, and some movies will include Dolby Digital+ audio tracks.  Who knows, one of the bigger players may even gobble up Vudu to get their hands on the HDX technology.</p>
<p><strong>3D in the home will flop</strong> &#8211; 3D in the home will go the way of SACD and laser disc.  It will work great, and really please a small group of people, but won&#8217;t make it much further than that.  People won&#8217;t rush out to buy new TVs.  Many of the movies that come out on Blu-ray will include a 3D version, but you&#8217;ll simply get it for free with the regular Blu-ray and most people won&#8217;t use it.</p>
<p><strong>4K TV will emerge as the &#8220;next big thing&#8221;</strong> &#8211; There are already 4K projectors, albeit very expensive ones, available today.  A handful of prototype TVs have come and gone.  But in 2010, we&#8217;ll start to see 4K televisions in demo and prototype form all over the place before the end of the year.  As they emerge, groups such as the ATSC will begin to work on the next generation of TV broadcast specs to include even more definition than the current HDTV spec.</p>
</div>
