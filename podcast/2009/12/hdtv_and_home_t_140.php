<p>When we recorded the show, <a href="http://www.htguys.com/shop?id=B0021L8FR6" target="_blank">Lost: The Complete Seasons 1-5 on Blu-ray</a> was only $109.  It&#8217;s up to $206 now.  Sorry.  If you keep watching, it may come back down.</p>
<h3><strong>Last Minute Shopping Guide 2009</strong></h3>
<h4><strong>For the Special Someone on Any Home Theater Enthusiast&#8217;s List</strong></h4>
<p>You know we&#8217;re always looking out for you, so we&#8217;ve decided to revisit the last minute shopping guide we assembled last year.  We know you&#8217;ve been busy, and so have we, but if you screw up on the gift you get for special someone in your life, you&#8217;ll be paying for it for a long, long time.  We do recognize that procrastination could be strategic, you need to make sure you get the absolute perfect gift, so we aren&#8217;t trying to judge here.  Whatever the reason, if you still need a gift, we have some tips for you.</p>
<p>Like last year, these are gift suggestions for that special someone in your life, a person who perhaps doesn&#8217;t share your audiophile tendencies or your gadget fetishes.</p>
<p><strong>Top Five Gift Suggestions</strong></p>
<p><em>5. Gift basket</em><br />
Pretty much anything that comes in a basket with a little bow on it is a sure-fire hit.  Ok, so maybe you should stay away from the sausage and cheese basket, but wine and chocolate should work just fine.  There are even special cream and lotion baskets.  You don&#8217;t need to know why they like it, just that they do.</p>
<p><em>4. A photo album<br />
</em>Crack open the old hard drive and start uploading pictures to <a id="vbcb" title="Shutterfly" href="http://www.shutterfly.com/">Shutterfly</a> or <a id="w:8v" title="Snapfish" href="http://www.snapfish.com/" target="_blank">Snapfish</a>.  One of the big bummers in the age of digital photos is that they get stuck on the computer and never looked at.  Assemble an album of your memories together.  She&#8217;ll love it, guaranteed.  You&#8217;ll need to get cracking on this one, shipping is getting expensive in a hurry.  We&#8217;d caution against including those risque pictures you took that one time when you&#8230;well, you know.</p>
<p><em>3. Pajamas</em><br />
Ok, so we know you don&#8217;t always want to see your significant other in the old sweats she seems to love so much.  Why not buy her some new ones, some that might be a little more visually appealing at the same time?  She&#8217;ll love getting new PJs and you&#8217;ll love seeing her in them.  But don&#8217;t go too crazy; they actually need to be comfortable and warm so she wants to wear them.  If you&#8217;re feeling generous, go ahead and throw in a pair of slippers.</p>
<p><em>2. </em><em>Flowers</em><br />
We still aren&#8217;t sure why, but nothing says &#8220;I love you&#8221; like a really expensive bouquet of flowers.  Never mind the fact that they&#8217;ll be dead in a week and you&#8217;ll have completely wasted a ton of hard earned money.  Or that she was all over you for spending money on speakers that we all know will last for many, many years.  But we digress.  Don&#8217;t ask us why, but flowers will work.</p>
<p><em>1. A new car<br />
</em>Ok, so we ran out of ideas.  Do you know how hard it is to think of gift ideas that aren&#8217;t home theater gadgets?  It&#8217;s like trying to find a reason to watch Lifetime.  But one thing is for sure, if you can pull this one off, she&#8217;ll be very thankful.  Who knows, maybe she&#8217;ll even wear the new PJs and let you get some pictures you can&#8217;t put in next years photo album.  A guy can dream, can&#8217;t he?</p>
<p><strong>Top Five Gifts to Avoid</strong></p>
<p><em>5. A digital scale<br />
</em>There are some pretty cool digital scales on the market, scales that remember your age and height, and in addition to measuring your weight can automatically calculate your body fat percentage.  These things are awesome.  Stay away from them.  Run from them like they&#8217;re carrying the crazy disease the trees inflicted on everyone in The Happening.  It&#8217;s a very bad idea.<br />
<em><br />
4. A Netflix subscription</em><br />
Yep, we&#8217;re advising you against getting something that we both love, a Netflix subscription.  We all know who this is for.  You may tell her you want to spend more quality time together, and they have something like 12,000 movies you can instantly watch together.  That&#8217;s almost three years of movies &#8211; imagine the bonding time.  It&#8217;s a great gift for your brother or a buddy, but if you really want it, just get it for yourself.  It&#8217;s not that expensive, cheapskate.</p>
<p><em>3. An electric razor</em><br />
This is one of those things that she might want, heck electric razors are incredibly convenient, but it&#8217;s pretty dicey as a Christmas present.  Basically, you&#8217;re telling her, &#8220;hey Chewbaca, you need to shave more often.  I know you abused your last one so bad it finally died, so here&#8217;s a new one.&#8221;  Not sure how well that will go over.  Let us know if it works out for you.</p>
<p><em>2. Exercise equipment</em><br />
You know that phrase, &#8220;you can&#8217;t go wrong&#8221; well it doesn&#8217;t apply to giving exercise equipment for Christmas.  Last year when we cautioned you to stay away from gym memberships it wasn&#8217;t because most people get them and never go, wasting all the money.  Again, your heart may be in the right place, but you&#8217;ll be resting your head on the couch for many lonely nights with this one.</p>
<p><em>1. Home beer tap system</em><br />
It&#8217;s for the kitchen, it makes it easier for her to serve beer to you and your buddies when they&#8217;re over watching football, we get it.  To us, it makes perfect sense.  If you already bought one, don&#8217;t worry, just send it to us.  We&#8217;ll love it.  Your significant other, on the other hand, may beat you with it.  We know you just want to make her life easier and add some high tech flair to her kitchen, but we don&#8217;t think she&#8217;ll see it that way.</p>
