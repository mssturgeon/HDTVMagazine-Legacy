started as a hardcore geek experiment using Home Theater and Media Center PCs slowly grew into a legitimate consumer electronics 
phenomenon in 2008 with the help of products like Vudu, Apple TV and TiVO.  We're now poised for an all out explosion in 2009 
and one company vying to be at the forefront is Yahoo!
<br><br>
<strong>Yahoo! Connected TV</strong>
<br><br>
Here are some excerpts from the <a target="_blank" href="http://connectedtv.yahoo.com/">Yahoo! Connected TV</a> website:
<br><br>
<u>TV Widgets change what it means to Watch TV.</u><em> TV Widgets give you the best of the Internet in perfect harmony with the 
simplicity and reliability of your television. They're as rich, varied, and useful as your favorite sites on the Web, 
reinterpreted for TV. Check out behind-the-scene interviews from popular TV shows, read the blogs on your favorite actors, 
or catch up on missed episodes. No complexity, no keyboard or mouse. Just lean back and stay connected.
Enjoy Internet content while watching your favorite TV programs.</em>
<br><br>
<u>Interact with content and services that complement your TV viewing with TV Widgets.</u><em>  Press one button on your remote 
to bring up the TV Widget Dock, select a TV Widget, and view content, designed for your TV screen. Track your favorite sports 
team, watch financial stocks, share photos with friends and family, go shopping, play games, view movies or web videos while you 
watch your favorite show.</em>
<br><br>
<u>Enabling The Cinematic Internet<sup><font size="1">TM</font></sup>.</u><em>  The Cinematic Internet is Yahoo!’s vision 
for the emerging world of Internet-connected TV—combining the Internet’s choice, community, and personalization with the power 
of television. This combination will transform traditional TV into something bigger, better, and more exciting than ever. Yahoo! 
and our partners are working on rich TV Widgets that will bring the Cinematic Internet to life.</em>
<br><br>
<em>To ensure that the Cinematic Internet is open and powerful, Yahoo!&#174; is working with the biggest brands in consumer 
entertainment and Internet services to create a vibrant ecosystem. Together with Intel®, Yahoo! is making a Widget Development 
Kit (WDK) available to the industry. This will enable developers and publishers to continuously change and improve what it 
means to watch TV.</em>
<br><br>
Bottom line, Yahoo is trying to be the glue that connects CE manufacturers like Sony, Samsung, LG and Vizio with IT manufacturers 
like Intel and Internet content providers.  Of course Yahoo! will ofter their own content such as news, weather, sports, video 
and Flickr photos, but there will also be content from eBay, Amazon, The New York Times, CBS, Showtime, Blockbuster, Netflix, 
CinemaNow, MySpace, Twitter and USA Today.  All of this built right into your TV, no need for an external box.  Or it could even 
be built into a set top box or Blu-ray player - maybe all of the above.
<br><br>
It's a great idea, and we applaud Yahoo! for trying to tackle it.  Because Yahoo! doesn't have an overpowering amount of content 
to offer the home theater viewer, they need to make sure their platform is better than any other platform.  For example, we 
already know Roku has chosen to open their box to anyone and everyone who want to server content to it.  What can Yahoo! do 
to differentiate itself?
<br><br>
HT Guys ideas for the ultimate Internet connected TV platform
<ul>
<li>Make it open to anyone and everyone; let the end user decide which widgets to use.  Of course there could be some management 
headaches with this, as Apple has seen with their App Store, but open is better (hint, hint Apple).</li>
<li>Allow the platform to "merge" widgets.  For example, allow the user to search across all their widgets.  If Netflix, 
Blockbuster, Amazon and CinemaNow are all available, I don't want to have to search four times to try to find a movie.  
Let me search once and show me the widgets that have a match.</li>
<li>Allow widget control from a computer on the network.  This may be widget provider specific, but if I see a movie that 
looks interesting while browsing the web, or hear about something on a podcast, I'd like to be able to queue it up in my 
TV right there and not have to go to the TV to find it all over again.</li>
<li>Allow the widget interface to control other home theater devices (local widgets).  If the widget interface could tap 
into something like HDMI CEC so that I could see a widget for each device in my home theater - or even any device in the 
house - that would be pretty powerful.  This will require more coordination with the manufacturers, but man will it simplify 
things for an average user.</li>
</ul>
