web browsing, email, and light general computing. Their main draw is cost and size when compared to a regular laptop. When Ara 
saw the new HP Mini Netbook in Costco he wondered if this device could be used as a portable media device. This feature will 
only concentrate on using this device in that capacity. This will not be a full review of the Netbook.
<br><br>
<strong>
<a target="_blank" href="http://www.hp.com/united-states/campaigns/mini1000/hpmini1000.html">HP Mini XP Edition</a> 
(<a target="_blank" href="http://www.htguys.com/shop.php?id=B001J6N9J8">Street Price $450</a>)<br>
The Netbook has the following features:</strong>
<ul>
<li>10.2-inch (Diagonal) WSVGA LCD Infinity BrightView LED Display, 1024 x 600 Resolution</li>
<li>1.60 GHz Intel Atom Processor N270 with 512KB L2 Cache</li>
<li>1024MB DDR2 System Memory (1 Dimm), 60GB (4200RPM) Hard Drive</li>
<li>Intel Graphics Media Accelerator 950 (shared) with up to 128MB Total Available Graphics Memory</li>
<li>802.11b/g WLAN & Bluetooth</li>
<li>Genuine Windows XP Home Edition</li>
<li>Dimensions in inches: 6.56 (W) x 10.3 (D) x 0.99 (H) approx., 2.38 lbs</li>
</ul>
<br>
The first thing you notice about this computer is that is is very small, thin, and light. It makes it very easy to move from 
room to room or take with you on a trip. The other thing you notice is that it does not have a DVD drive. Without a drive the 
Netbook has its limitations. In Ara's use, all movies were converted from DVD to AppleTV format and loaded into iTunes. This 
works well as you can easily store 20 to 30 movies and have space left over on the hard drive. The Atom processor had no problems 
playing back movies in this format as long as the content was on the local hard drive. Movies were unwatchable when playing via 
the wireless network. Unless you have the ability to rip your DVDs this solution may not be suitable for you. Fortunately the 
number of DVD/Blu Ray discs that come with a digital copy is growing and in the future copying movies to the Netbook will be 
as simple as drag and drop.
<br><br>
Loading music onto the device was as simple as copying files to the hard drive. If you have a lot of music with iTunes DRM 
you'll have to authorize the Netbook. Once you do you'll be good to go. The sound is loud enough to hear but the quality is 
not so good when played through the computer's speakers. You will want to use headphones or external speakers.
<br><br>
Watching the Slingbox was no different than watching it on any other computer. We tested both a regular Slingbox and the newly 
released HD version. The regular Slingbox worked great. The HD Version stuttered every so often. Enough that it made it 
unwatchable. Using the Netbook in the Kitchen to watch TV while getting dinner ready was easy and fun. The size of this 
device makes it very easy to find a spot on the counter. Battery life is very good, we were getting about 3 to 4 hours of 
use depending on what we were doing. The device also comes with a built in webcam for video chat.
<br><br>
Online sources like Sling.com, Hulu.com, and ABC.com look good on the smaller screen. One of the issues we have running these 
sites on a HTPC connected to a 50 inch screen is that you can see more artifacts. On the 10 inch screen of the HP Netbook these 
sites look great. We also ran the Netflix Watch it now plug-in in Firefox with no issues. There is no place for a PCI Express 
3G card so we were not able to test it with a 3G connection. But we get decent results with Ara's MacBook Pro so if you have a 
USB based 3G connection you should be able to stream movies while in the car or on a train. 
<br><br>
HD via the HD Homerun did not fare very well. The Atom processor just doesn't have the horsepower required to pull HD off.
<br><br>
Overall, the device did what we wanted and when you compare it to some other high end media players its a no brainer. But if all 
you want is a device to watch DVDs you'll be better off buying a portable DVD player based on price alone.
