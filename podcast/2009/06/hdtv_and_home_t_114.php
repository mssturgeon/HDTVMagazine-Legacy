<strong>Today's Show:</strong><br>
Some say that Plasma is dead but they forgot to tell Panasonic. Today we take a look at the G10 line of plasmas more specifically 
the TC-P54G10 54 inch THX Certified 1080p TV. From what we can tell, plasmas are not dead yet! At $1900 it the best bang for the 
buck flat panel on the market.
<br><br>
<a href="http://www.htguys.com/shop.php?id=B00267PY6K" target="_blank">Panasonic VIERA G10 Series TC-P54G10 54-Inch 1080p Plasma HDTV</a> (Street Price $1900)
<br><br>
<b>Features</b>
<ul>
<li>VieraCast™&nbsp; web content without requiring a PC</li>
<li>1920 x 1080</li>
<li>Native contrast 40,000:1</li>
<li>Infinite black for the brightest whites and darkest blacks</li>
<li>3 HDMI</li>
<li>THX Certified display</li>
<li>PC Input</li>
</ul>
One of the things that drew us to this set was its screen size. You don't see too many plasmas at 54 inches so its a nice 
compromise between the very large and expensive 60 inch plasmas and the smaller 50 inch sets that have become so affordable. 
For comparison purposes a 55 inch LCD with LED backlight and 120Hz from Samsung goes for about $3300. Right now LED LCDs 
with 120Hz refresh rates are the only way to match a plasma in picture quality.
<br><br>
The G10 is 4.2 inches thick while the LED TV is only 1.2 inches and the weighs just a bit more than half that of the plasma 
(48.5 pounds vs 83.8 pounds). The dimensions and weight are not to big of a deal but we just wanted to note that a 42 inch 
plasma from four years ago weighed about 100 pounds so plasmas have come a long way in that area. Another area where plasmas 
have improved is power consumptions. The G10 is also EnergyStar compliant.
<br><br>
<b>Picture Quality:</b><br>
Wow! The blacks are incredibly deep and colors are very accurate. Some have complained about Green reproduction but we did 
not find it overly offending. The TV is THX certified and that mode may take a bit of getting used to. The THX mode dims the 
picture a bit so if you like the brightness of an LCD we recommend that you calibrate the TV to your taste. We have two 
calibration settings at the end of this review, one for THX mode and regular watching. We found more detail in this TV than our 
DLP and LCD TVs that we normally watch. The TV really shows its strength in darker scenes. There is plenty of contrast to 
make out even the most subtle shadows. Blacks are very deep. Panasonic calls their technology "Infinite Black". From what 
we could find out about it is that the TV shuts off power to the pixel to achieve "Infinite Black". Whatever they call it it 
works.
<br><br>
We tested with Blu Ray movies and found that the Pixar animated movies almost look like they are in 3D. In general we enjoyed 
Blu Ray and found the TV really showed its stuff with Blu Ray. For live sports we watched the NBA playoffs which were viewed 
via DirecTV and OTA. Both looked stunning. There was no motion blur that we could detect. SD when upconverted through the DirecTV 
set top box was acceptable.
<br><br>
<b>VieraCast™:</b><br>
VieraCast is a technology that allows the 
Television to display content from third party sources right on the screen. These are not widgets but a Panasonic technology 
with limited partners to start. An Internet connection is required. With VieraCast you can display videos, photos, weather and 
stock information from familiar sources like Google, Bloomberg, The Weather Channel and Amazon. We found this feature very 
useful and easy to operate from the remote control. Youtube content looked pretty good considering the low quality of the 
source material. Panasonic says they will continually add to this feature. What we'd like to see are sports, traffic, and 
news headlines. What would really make this feature extremely valuable is an RSS Reader that would support enclosures so you 
could watch and listen to your favorite podcasts. We would be very surprised if that does not happen soon!
<br><br>
<b>Odds and Ends:</b><br>
<ul><li><b>VieraLink</b> - We did not test this feature out but if you have all Panasonic gear VieraLink controls them all with 
minimal configuration provided that it all connected via HDMI.</li>
<li><b>600Hz Sub-field Drive</b> - This is a marketing spec to say that Plasmas are better than 120Hz LCDs. 120Hz LCDs were 
created because they did not perform as good as Plasmas. Its not really important for plasma televisions.</li>
<li><b>AR Filter</b> - One issue we have against plasma televisions is the reflection the screens produce. In a room with windows 
this can become very annoying. The G10 has an anti-reflective filter that works pretty well. We saw less reflection in bright 
rooms but we're not going to say its on par with LCDs in this regard.</li>
<li><b>Remote Control</b> - If you use VieraLink the remote will serve you well. If not put it aside and get yourself a good 
universal remote.</li>
<li><b>Audio Quality</b> - Good sound and a surprising amount of bass. But it would be a shame if this TV is not connected to a 
proper sound system!</li>
</ul>
<br><b>Bottom Line:</b><br>
Overall we are very impressed with the performance of the G10. We don't really have any major complaints. You are not going to 
find a better 54 inch flat panel display for less than $2000!
