<p><strong>Insteon</strong> &#8211; Sure, I&#8217;ve known about home automation, lighting control, the whole shot, for many years.  But ever since I started actually putting it in my home, it&#8217;s like a part of me has come to life that i never knew existed.  This is the most excited I&#8217;ve been about a technology or gadget since the PS3&#8230;</p>
<p><strong>PS3</strong> &#8211; Ah, the Sony Playstation 3, it truly is the home theater Swiss army knife.  First of all, it&#8217;s a Blu-ray player.  But not any old Blu-ray player, probably the most capable one out there.  and you know when managed copy hits, it&#8217;ll be the first to support it.  It&#8217;s also a DLNA player, so it can stream movies from anywhere on the network.  The Netflix integrations is superb.  Oh yeah, and it plays some cool games, too.</p>
<p><strong>High Definition Television</strong> &#8211; Every time I&#8217;m forced to watch anything in standard definition it reminds me of how thankful I am for high definition.  This one might be getting old for some, but it&#8217;s still a has a huge impact on my enjoyment of Home Theater.  I honestly can&#8217;t imagine watching NCIS or Flash Forward in standard def.  I tried watching football at a restaurant the other day and gave up.  What&#8217;s the point if you can&#8217;t watch it in high def?</p>
<p><strong>The DVR</strong> &#8211; While I&#8217;m not thankful for DVR guilt, and I am still suffering from it (Sorry Numb3rs, you probably won&#8217;t make it to next season), I love my DVR.  It is the absolute best technology since the invention of the refrigerator or the flush toilet.  I honestly don&#8217;t know how I&#8217;d survive without any of those three.  Sliced bread I could live without, but not my DVR.</p>
<p><em><strong>Ara:</strong></em></p>
<p><strong>High Speed Internet</strong> &#8211; I know we live in a bubble here in Orange County CA and our Internet access is quite good. But with that said I am very thankful for big fat pipes. It makes things like  Netflix Watch it Now enjoyable. High Speed Internet is necessary for the future of digital downloads and the connected living room.</p>
<p><strong>Slingbox</strong> &#8211; I visit my in-laws quite a bit. They do not have DirecTV so I can&#8217;t watch my Bears on Sunday. Right now that may be a good thing. But with my SlingBox HD I can not only watch on my 15&#8243; MacBook Pro but its an enjoyable experience. We have even used it in the car with 3G while driving up CA State Route 99.</p>
<p><strong>Remote DVR Programming</strong> &#8211; How many times have you wished you could set something to be recorded when you are away from home? With this feature you no longer have to miss a special event. Its available on DirecTV, Dish Network, FiOS and some cable company&#8217;s DVRs.</p>
<p><strong>Netflix</strong> &#8211; I pay $20 a month to have Netflix store just about every DVD made. And for that price then send me any title I request for free and provide return shipping. All this with a one day turn around in most cases.</p>
