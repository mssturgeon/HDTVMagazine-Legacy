<p><a title="Onkyo TX-SR607 7.2-Channel A/V Surround Home Theater Receiver" href="http://www.htguys.com/shop?id=B001VEI2KO" target="_blank">Onkyo TX-SR607 7.2-Channel A/V Surround Home Theater Receiver</a> &#8211; The 606 made our list last year and cost $320.  The 607 is a little more expensive at $370, but you get more for it.  Of course you get HDMI v1.3a, 1080p video processing powered by Faroudja, TrueHD, and DTS-HD Decoding.  But you get 2 more HDMI inputs (total of 6), 2 subwoofer outputs (7.2), and Audyssey Dynamic Volume and Dolby Pro Logic IIz.  Still the best value out there!</p>
<p><a id="jh-l" title="Denon AVR1910 7.1-Channel Multi-Zone Home Theater Receiver" href="http://www.htguys.com/shop?id=B002AKKFPI" target="_blank">Denon AVR-1910 7.1-Channel Multi-Zone Home Theater Receiver</a> &#8211; The spec sheet for this Denon reads much like the Onkyo 607.  It&#8217;s got HDMI v1.3a, 1080p video processing, TrueHD, and DTS-HD Decoding, Audyssey Dynamic Volume and Dolby Pro Logic IIz.  It is more expensive than the Onkyo, but at $499, it&#8217;s actually $100 less then the 1909 that made out list last year in the $500-$1000 category.</p>
<p><strong>Greater than $500 and Less than $1000</strong></p>
<p><a id="f7:b" title="Yamaha RX-V1065BL 7.2-Channel Digital Home Theater Receiver" href="http://www.htguys.com/shop?id=B002CVTOXE" target="_blank">Yamaha RX-V1065BL 7.2-Channel Digital Home Theater Receiver</a> &#8211; This is a powerful beast with a pretty low price tag of only $649.  Of course it will handle analog video upscaling to HDMI 1080p, supports HD Audio decoding, can run 2 zones and HD Radio Receiver, XM and SIRIUS ready.  But it also has a fancy Graphical User Interface that can display album art.  It has a USB port for external music sources and has Yamaha&#8217;s own version of a dynamic volume control technology called Yamaha Adaptive DRC (Dynamic Range Control).\</p>
<p><a id="jf0o" title="SONY STR-DA4400 ES 120 Watts 7.1-Channel Home Theater Receiver" href="http://www.htguys.com/shop?id=B001CSCCNM" target="_blank">SONY STR-DA4400 ES 120 Watts 7.1-Channel Home Theater Receiver</a> &#8211; The Sony ES line is good.  No doubt about it. Your $969 will go a long way with this one. It has 6 HDMI inputs that are compatible with 1080 60p/24p, deep color and x.v.color video signals and will upconvert analog video to 1080p using Faroudja DCDi Cinema technology.  In addition to TrueHD and DTS HD, supports Direct stream digital (DSD) decoding.  It&#8217;s also a true multi zone receiver, supporting multi-room HD video (up to 2 rooms) and audio (up to 3 rooms).  This means you can start a movie in the living room and finish it in the bedroom or listen to your favorites songs from your iPod located in the living room, on the patio in the backyard.</p>
<p><strong>Greater than $1000</strong></p>
<p><a id="wvmq" title="Denon AVR4310CI 7.1-Channel Multi-Zone Home Theater Receiver with Networking Capability" href="http://www.htguys.com/shop?id=B002AKKFQC" target="_blank">Denon AVR4310CI 7.1-Channel Multi-Zone Home Theater Receiver with Networking Capability</a> &#8211; We listed the precursor to this model, the 4308, as our &#8220;Ultimate Christmas Present&#8221; last year because of its whopping $2149 price tag.  Here&#8217;s an instance where waiting may have worked out in your favor.  The newer 4310 has dropped in price to $1699.  It has everything.  For video you&#8217;ve got HDMI 1.3a Repeating (5 in, 2 out) with Anchor Bay VRS processing to HD quality (up to 1080 24p/60p).  On the audio side of course Dolby TrueHD, dts-HD, Audyssey DSX, Dolby Pro Logic IIz, Audyssey MultEQ XT, Dynamic Volume and Dynamic EQ.  And for that special touch, networking capability opens up your AV system to audio and jpeg photo streaming and Internet radio.  Additionally, subscription music services like Rhapsody and Napster are supported.</p>
<p><a id="y2x-" title="Pioneer SC-27 Elite 7.1 Channel A/V THX Receiver" href="http://www.htguys.com/shop?id=B002N44W64" target="_blank">Pioneer SC-27 Elite 7.1 Channel A/V THX Receiver</a> &#8211; For $1299 we both looked at this with our jaws on the floor.  It does everything and then some.  At its core, the Pioneer Elite SC-27 A/V receiver was designed to deliver best-in-class sound quality for full-scale immersion into today&#8217;s new high-definition multi-channel home theaters. It supports HDMI 1.3 on 5 HDMI inputs, uses Pioneers exclusive Direct Energy HD amplifier with ICEpower Class-D technology, will play Dolby TrueHD and DTS-HD Master soundtracks that we all know and love. It has AIR Studios Monitor Sound Tuning Certification and is THX Ultra2 Certified.  Quite a deal for under $1300.</p>
<p><strong>One to watch for:</strong></p>
<p><a id="rgey" title="Sherwood R-904N 100 Watt 7.1-Channel Dual-Zone receiver" href="http://www.htguys.com/shop?id=B002S4084O" target="_blank">Sherwood R-904N 100 Watt 7.1-Channel Dual-Zone receiver</a> &#8211; This one isn&#8217;t availble yet, but should start shipping soon for around $649.  On the surface it looks like a standard 100 watt 7.1 home theater receiver.  You get 3 HDMI inputs, support for Dolby TrueHD and DTS HD, but the future is the network.  This unit can connect to the Internet so you can watch stuff like YouTube, Hulu, Amazon, or Netflix directly from your receiver.  No need for a Blu-ray player, no need for a separate box.  If you think you can get away with just watching video content from the Internet, and considering services like Hulu and Netflix, that really isn&#8217;t too far fetched an idea, this really would be the only box you&#8217;d need.</p>
