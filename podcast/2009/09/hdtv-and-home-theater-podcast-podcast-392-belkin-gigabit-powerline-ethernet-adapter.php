<h3><strong>Belkin Gigabit Powerline Ethernet Adapter </strong>(MSRP $149.99)</h3>
<p>With so many devices connecting to the Internet these days we like to see products like Powerline Ethernet adapters come to market. In general the technology has improved vastly since our first review back in 2006. At that time we reviewed a product that was rated at 85Mbps and we were lucky if we got 10 Mbps. More recently we reviewed the HomeNet Powerline Adapter (<a id="h4mn" title="Podcast 358 Audio Only" href="http://www.htguys.com/podcasts/2009/2/27/homenet-powerline-networking-by-corinex-podcast-358.html" target="_blank">Podcast 358 Audio Only</a>) which was rated at 200Mbps. The HomeNet was actually pretty close to the 85Mbps that the first product was rated at.  So imagine our excitement when we heard about the Gigabit Adapter from Belkin (Model # F5D4076). Unfortunately our excitement ended shortly after we took the adapters out of the box.</p>
<div><strong>Setup:</strong></div>
<div>This was easy enough. Like the HomeNet, you plug one adapter into the wall near your router and then connect it to the router via the supplied Ethernet cable. Then you plug the other adapter into any outlet in your home and you are ready to go. Our particular pair of adapters did not find each other out of the box. We were forced to do a reset of the devices. Once they were reset the adapters found each other without any further intervention. You can also lock the devices to each other with a simple procedure that is described in the quick start guide. Adding additional adapters is as easy as plugging it into a wall socket.</p>
</div>
<div><strong>Performance:</strong></div>
<div>The device says its Gigabit but we did not expect to reach anywhere near that level of throughput. For comparison sake we have a hard wired Gigabit network and we did some tests. We copied 12.61GB of movie files from our movie server to another computer on the network. The process yielded a data rate of 173Mbps. That&#8217;s about 1.3 GB per minute. So even in the hard wired case actual throughput was not near the rated speed of a Gigabit network.</div>
<div></div>
<div>Next up was to copy the same files via 802.11n. This test took three times longer with a data rate of 57Mbps. This data rate was also lower than than the theoretical 802.11n rate of 300Mbps.</div>
<div></div>
<div>Based on the previous two tests we were hoping for data rates somewhere between the two. Unfortunately we got something less than 802.11g. In actuality we gave up on the copying of the files two hours into the process. We then wanted to see if it could pull a DVD off of the server without stuttering. To achieve this feet the adapter would have had to support a data rate of up to 10Mbps. Here the adapter failed again. We couldn&#8217;t play a movie without stuttering every few seconds. There is an LED indicator that tells you how fast the connection is. In our case it always showed the slowest connection speed possible. We have pretty clean power too.</div>
<div>We tried different outlets but still no luck. In contrast the HomeNet PowerLine adapters supported HD, DVD, and Music streams simultaneously. Its unfortunate too. Belkin usually makes great gear.</p>
</div>
<div><strong>Recommendation:</strong></div>
<div>If you can&#8217;t run Ethernet cables to your gear PowerLine may be a solution. You may want to give the Belkin Gigabit Adapter a try. It may work better for you. Just buy them from a place that will take them back in case your results match ours.</div>
