<p>We thought it might be interesting to compare the relative pros and cons of watching Football at home or away - in this case, 'away' means away from your home theater. There are reasons to do either, and of course costs associated with both. In the end, which one makes the most sense? We'll let you decide.<br /><br />We'll use the Chargers as our example throughout the discussion. We live close enough to San Diego to to attend a game without buying airline tickets. For those who live further away from your favorite team, like Ara and his beloved Chicago Bears, you'll probably opt to stay home for a vast majority of the games.<br /><br /><strong>Watching the Game</strong><br />So what does it cost to attend a regular season football game? Tickets start at around $45, but that's for the worst seats in the house. There's really no comparison to watching on TV because you can barely see what's going on. For sake of argument, let's jump up to the $100 seats so we can actually see the game. For a family of 5, that's $500 plus parking and gas, let's say $550.<br /><br />Now let's say you stay home. Of course you have to have some kind of HDTV service to see the game, but you can get 4 games per month on one bill, plus there's all the other content you watch when football isn't on. So if you have a $100 per month HDTV bill, three hours out of the month for a game is roughly $3.33, assuming you watch approximately 3 hours of TV per day.<br /><br /><strong>Snacks</strong><br />Doesn't it seem that when you go to a football game, or any live sporting event for that matter, everyone is hungrier than normal? They down nachos, hot dogs, pizza, cokes, beer, popcorn, candy, chips, pretty much anything and everything. Assuming each person in the family of 5 can eat on $20, you're looking at $100 for food.<br /><br />At home, you can eat all you want an barely crack the $20 mark. Stock up on snacks at Costco or Sam's Club and $100 can easily last you for 4 or 5 football games. Unless you're throwing a party, we'll be generous and say that you can mow through $20 worth of junk food in a 3 hour sitting. That's for the family of 5.<br /><br /><strong>Other</strong><br />Many would say that you need an HDTV to watch the games from home, so that cost has to be included in the equation. We don't agree. An HDTV is something you have anyways. We aren't charging you for a new car to go watch the football game, are we? But for sake of argument, let's say you needed to upgrade your TV to get the best possible experience. You can get a <a id="d893" title="65&quot; 1080p HDTV" href="http://www.htguys.com/shop?id=B001XUR5F4" target="_blank">65" 1080p HDTV</a> for $1600. You break even after 3 games, so you have the last 13 games of the season, and hopefully the preseason, to enjoy the TV for free.<br /><br /><strong>Attending in person (away)</strong><br />Pros</p>
<ul>
<li>You can't beat the live atmosphere</li>
<li>You're supporting your team</li>
</ul>
<p>Cons</p>
<ul>
<li>Cost</li>
<li>You can't escape the live atmosphere</li>
</ul>
<p><br /><strong>Attending at home</strong><br />Pros</p>
<ul>
<li>Very economical, any way you look at it</li>
<li>Comfort and convenience of your own home</li>
<li>Better view of the game</li>
</ul>
<p>Cons</p>
<ul>
<li>There's nothing like "being there"</li>
<li>going to a game is a fun experience, especially for the kids</li>
</ul>
