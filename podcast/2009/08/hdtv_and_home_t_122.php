<strong>Today's Show:</strong><br>
Imagine with me, if you will, a day when a small box no bigger than a standard dictionary will be able to hold as many pictures as you can ever take, as many songs as you could ever listen to and a ton of movies and video as well. That day has come, and HP calls it the MediaSmart Server LX195. We got a chance to play around with one, and really liked it.<br /><br />
<h4><strong>HP MediaSmart Server LX195</strong></h4>
<strong>(<a id="d8jy" title="Buy Now $299" href="http://www.htguys.com/shop?id=B0021L9HKK" target="_blank">Buy Now $499</a>)</strong><br />
<h4><strong>Specs:</strong></h4>
<ul>
<li>Microsoft Windows Home Server </li>
<li>Intel 1.6 GHZ Atom Processor 230</li>
<li>1GB DDR2 DRAM</li>
<li>1 X 640 GB SATA 7200 RPM</li>
<li>4 USB 2.0 ports</li>
<li>Expandability limited only by drive sizes - Assuming 1 TB drives, total capacity (internal and external) = 5 TB</li>
<li>4" x 8" x 8"</li>
<li>Whisper Quiet (25 degrees C &lt; 25 dba at one meter)</li>
</ul>
<br />
<h4><strong>Set-up</strong></h4>
In all honesty, it took us two LX195s before we could get it up and running. But since we get demo units, we prefer to blame the problems with the first unit on the previous reviewer. That's allot easier to do than admit we were only seeing a flurry of id10t errors.<br /><br />The second unit was a snap to set up. It requires a hard-wired connection to your Ethernet network, but with that and a power cord, it's completely installed. Hit the power button, it gets an IP address from your router and you're off to the races. You use any standard browser to connect to the server and download the software. It takes about 15 minutes to download, install and configure before you're ready to use it. But it's all very simple and wizard driven.<br /><br />All you have to do is turn on the features you want to use and set a few schedules for when the unit should run backups or aggregate media. It's actually really easy.<br /><br />
<h4><strong>Use</strong></h4>
Once you have it setup, you simply pop open the software and configure it to do whatever you want it to do. It is primarily designed to backup all the computers on your network and share all your media files in one central location.<br /><br />
<h4><strong>Digital Media</strong></h4>
HP tells us that the MediaSmart server was designed for digital media from the ground up. It allows you to access your media anywhere on your home network or even away from home with any Internet-connected computer. So you can stream music, watch movies and show off your photos anywhere, anytime. <br /><br />It also includes TwonkyMedia as a DLNA server, so you can stream movies and music to your TVs using any DLNA player like the Xbox 360 or PlayStation3. If you're more of an iTunes user, the MediaSmart Server also includes a Server for iTunes. This server allows you to stream your music and playlists to computers that are running iTunes, or compatible devices - including protected content.<br /><br />Here's the cool part, the LX195 considers every drive attached to it to be part of one big "storage pool." So as you run out of space, you simply add another drive and you don't need to make any other configuration changes. Media can span multiple drives, but still be accessible through one shared folder.<br /><br />
<h4><strong>Automatic backup</strong></h4>
More than just a media aggregator and server, the LX195 is also a central backup system for all your home computers. You can automatically manage daily backup, virus protection, media collection, and power management, all behind the scenes. Backups work with Windows using Microsoft Windows Home Server Backup and with Mac using Apple Time Machine. For those who want even more protection, you can sign up for an Amazon S3 account and have your data automatically copied off-site for a little extra peace of mind. <em>Note - While the MediaSmart Server is Mac compatible it requires a PC to set it up for the first time.</em><br /><br />
<h4><strong>Other features</strong></h4>
The LX195 can be used as a remote access gateway, allowing you and anyone you give access to, the ability to access files on the server and even direct access to supported computers from any location (XP Pro SP2, Media Center Edition 2005 SP2, or Vista Ultimate). You can actually share full resolution images without spending hours trying to upload them to a sharing site. You can also upload files to the server from a remote computer.<br /><br />
<h4><strong>Conclusion</strong></h4>
If you're looking for a central server to manage all your digital media and do automatic backups, and you want it to work seamlessly with PCs and Macs, the HP MediaSmart server is an excellent choice. The included 640 GB of storage should get you going, but using the 4 USB ports you can literally make it as big as you want. And for under $300, you really won't find much out there that can compete.<br />
