<br><br>
<strong>What to Expect with the Reclaimed Analog Spectrum</strong>
<br><br>
A question many of you may have is &quot;Why are we doing this?&quot; The answer that the FCC gives is the following:
<br><br><em>An
important benefit of the switch to all-digital broadcasting is that it
will free up parts of the valuable broadcast spectrum for public safety
communications such as police, fire departments, and rescue squads.
Also, some of the spectrum will be auctioned to companies that will be
able to provide consumers with more advanced wireless services (such as
wireless broadband).</em><br>
<br>
Public safety for
Police and Fire is a good reason but we think the bigger reason is
commercial. Companies like Verizon, AT&amp;T, and even Google got their
hands on the 700 Mhz spectrum because of its properties that make it
easy to sell us new services. The 700 Mhz spectrum is desirable because
it penetrates walls and can be transmitted a long distance. To cover 20
square miles adequately at 7000 Mhz you only need one tower. Think
about how many cellphone towers it would take to cover the same
distance. So its more cost effective to deploy a 700 MHz network.
<br><br>
When
the PCS mobile phone network was deployed in the 90's it cost carriers
$4 billion. Because of the better coverage of the 700 MHz network,
estimates for the deployment run around $2 Billion. The telcos have put
up $20 Billion to lease the old airwaves for these purposes.
<br><br>
What do we get for all this inconvenience? The HT Guys have come up with some ideas:
<ul>
<li>TV in the car - Whether it is slingbox or direct streams similar to V-Cast. This can make long drives with the kids much easier.</li>
<li>Internet
Connected Radios - This competes directly with XM and Sirius radio. You
can have all your music with you when you want. Plus look for Verizon
and AT&amp;T to offer an all you can eat plan for a monthly
subscription</li>
<li>GPS, Traffic, and Weather - Imagine using GPS and
Google tied right into this broadband network. You could get instant
traffic and weather updates that are targeted at your location.<br>
</li>
<li>Netflix Watch it on the Run - Your family can dial up movies and TV shows on the fly with the New Roku car unit.</li>
<li>Broadband
for everyone - Having another provider of broadband access to the
internet is a good thing. Competition will help lower prices.</li></ul>
What ideas would you like to see implemented?<br><br>
<strong><a target="_blank" href="http://www.mitsubishi-hometheater.com/hc6500.asp">Mitsubishi HC6500</a> Review</strong><br>
<br><strong>Features:</strong>
<ul>
<li>True 1080p (1920 x 1080) resolution</li>
<li>15,000:1 Contrast ratio</li>
<li>1200 lumens</li>
<li>0.74&quot; inorganic 3LCD technology with micro lens</li>
<li>Silicon Optix Reon-VX HQV (Hollywood Quality Video) processing</li>
<li>Ultraquiet 17dBA operation</li>
<li>1 mini D-sub 9-pin, 2 HDMI, 1 S-video, 1 component and 1 composite video input</li></ul><strong>Style</strong><br>
The Mitsubishi HC6500 projector looks like a really well built device.  Overall the look of a projector is probably less important than a TV because it's out of sight most of the time, but it looks great nonetheless.  One neat detail is the cover for the back connection panel.  Once you get everything plugged in, you can put the cover on to control all the wire mess.  Not a huge deal, but a nice touch.  Overall it's quite stylish and not at all &quot;industrial&quot; looking. <br>
<br><strong>Performance</strong><br>
You expect a 1080p projector to have superb detail and the HC6500 doesn't disappoint.  All video source we watched, from HD movies, to regular HDTV content, to live action sports looked stellar.  Of course the projector can only look as good as what you're feeding into it, but with pristine video like Blu-ray, it looks great. <br>
<br>
One knock Braden has always had on LCD projectors is that they don't seem to look as &quot;natural&quot; as their DLP counterparts.  The HC6500 turned that notion into a misconception in a hurry.  It has excellent detail, great color, nice smoothness and an overall picture that looks as good as any DLP projector we've reviewed.  Of course you'll want to calibrate it because out of the box it doesn't look that great, but by now that should go without saying.<br>
<br>
Where the HC6500 really shines is contrast and black level.  It does an excellent job with black level, providing deep, inky blacks that are really very impressive.  In fact this is probably the one area that we would say really differentiates it from the competition.  Pound for pound you'll struggle to find black levels this good in any other similarly priced projector.  And it easily leaves the lesser priced models behind.<br>
<br>
At 1200 lumens this projector is certainly bright enough for a true light controlled home theater, but it may be questionable for daytime use in a room where light isn't as easily controlled.  If you plan to install it in a family room with lots of windows, be prepared to add some really thick window coverings for those afternoon football games.  If you can control the ambient light, you'll be fine, but when we couldn't, we had some issues with it.<br>
<br>
The HC6500 is whisper quiet.  You can easily hear a PS3 humming away over the volume coming out of it.  The published &quot;ultraquiet&quot; 17 dBA only applies to operation in low mode, but we can tell you that it doesn't get much louder in full operation either.  It makes a good choice even if you'll have it directly overhead.  Of course any projector that close will take some getting used to, but the HC6500 is among the better choices.<br>
<br><strong>Odds and Ends</strong><br>
The remote and user interface are pretty basic and easy to understand.  Not much to say about those one way or the other.<br>
<br><strong>Conclusion</strong><br>
The HC6500 is one of the Mitsubishi models that isn't available for sale online; you have to buy it from a store.  That said, <a target="_blank" href="http://www.bestbuy.com/site/olspage.jsp?skuId=8988198&amp;type=product&amp;id=1218006548501">Best Buy</a> is a store that also happens to carry it online for around $3500, but you can't get it from online-only outfits like the HT Guys store.  At $3500 it's significantly more expensive than most of the 1080p projectors included in our earlier round-up.  So the question is: is it worth it?  Answer: that depends.<br>
<br>
From a video quality standpoint it's a great projector, but not leaps and bounds greater than the rest.  From a black level perspective, it's really much better.  Then it all comes down to how important black levels are to you.  If you have the money in your budget, go for it.  But if you need to scale back a little, even the &quot;one step down&quot; <a target="_blank" href="http://www.mitsubishi-hometheater.com/hc5500.asp">Mitsubishi HC5500</a> for $1599 (<a target="_blank" href="http://www.htguys.com/shop.php?id=B001B6ARDW">buy now</a>) from our roundup is a great choice, on par with the HC6500 in all areas but black level.<br>
