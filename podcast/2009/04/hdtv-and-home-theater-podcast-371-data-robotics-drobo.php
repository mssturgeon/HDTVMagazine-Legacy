<strong>Setup:</strong><br>
The Drobo ships without drives. You can order it with drives if you wish or if you have some drives laying around you can use your own. You insert the drives and then connect the unit to your computer via Firewire or USB 2.0. There is an application that you install that configures your drive. Here you can determine the size of the volume. For instance if you put four one terabyte drives into the Drobo you won't have a four terabyte drive on your desktop. The Drobo needs to manage the space so that your files are protected. An installation with four one terabyte drives will give you up to 2.7 terabytes of storage with the rest used by the Drobo to manage protecting your data. Once everything is powered on you'll see green lights on the front panel of the Drobo indicating that the Drobo is good to go. At that point you can drag and drop you files onto the Drobo just like any other external hard drive and let Drobo manage your content.
<br><br>
Data Robotics also make a device called the <a target="_blank" href="http://drobo.com/products/droboshare.php">Drobo Share</a> (<a target="_blank" href="http://www.htguys.com/shop.php?id=B0012MF4G0">Buy Now $180</a>) which turns the Drobo into a Network Attached Storage device. Instead of plugging the Drobo into a computer you plug the Drobo into this device and then attach the Drobo Share to your network. The Drobo Share supports two Drobos. When we connected the Drobo Share to our network the Drobo became available to every computer on the network within seconds. No software was needed to be installed. We did install Dobo Management software on a couple computers but that is only needed if you want to check on the health and manage of your Drobo remotely. The entire process from unboxing to copying the first data took less than one hour.
<br><br>
<strong>Replacing a Drive:</strong><br>
There are two reasons you will want to replace a drive, either its full or it failed. We did not have a drive fail or fill up on us but we wanted to test the Drobo's data management so we ejected one drive and inserted a new one. The Drobo quickly recognized the new drive and begun rebuilding the data. The entire process is truly plug an play. The Data Robotics website has a full video based "<a target="_blank" href="http://drobo.com/howto/index.php">How To</a>" help section. 
<br><br>
<strong>DroboApps:</strong><br>
<a target="_blank" href="http://drobo.com/droboapps/index.php">DroboApps</a> are applications that extend the capability of the Drobo. These applications are developed by the community and not supported by Data Robotics. The are a number of apps but the one we thought would be valuable to our listeners is The Firefly iTunes media server. Firefly is an iTunes media server that has been updated to run on the DroboShare. It makes the DroboShare look like an iTunes "Shared" library. We copied our entire iTunes library via the network to the Dobo and within an hour or so the Library was available to any iTunes client on the network. The benefit here is that no computer has to be on to see the library. This is a great solution if you want one Library for the whole family. Just a bit of advice. It is not straight forward to setup Firefly so we recommend downloading the DoboApps Admin Utility. It makes installing and configuring DroboApps a bit easier.
<br><br>
<strong>Bottom Line:</strong><br>
If you have a lot of content that you want to protect you need to back it up. Drobo makes managing that process easy! It works on both Macs and PCs and supports <a target="_blank" href="http://www.apple.com/macosx/features/timemachine.html">Apple's Time Machine</a>. 
