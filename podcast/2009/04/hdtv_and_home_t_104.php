<p><strong>Today's Show:</strong><br />
It's annual income tax time here in the United States, and odds are quite a few of those listening will be getting a refund back from the government. If you haven't left things to the last minute, you may already know how much is coming back. If you have to pay this year, we're sorry for you. Better luck next year. </p>

<p><strong>How to spend your Refund Check </strong></p>

<p>It's time to reward yourself for a long year of hard work. Here are some ideas. </p>

<p>If your check is in the $150-$200 range, you're all set for a new Harmony One advanced universal remote control. You worked hard, you earned it. Enough with the five or six different remotes already, or the clunky situation of trying to get your receiver or set top box remote to act like a universal remote. The Harmony One has a full color touch screen, is rechargable and is drop dead easy to program. Refund check well spent. </p>

<p>While you'll certainly be happy if you get a check for around $300, it might actually give you a reason to be Blu. Invest in better resolution movies with the Samsung BD-P2500 1080p Blu-ray Disc Player. Not only does the BD-P2500 have HQV processing for amazing DVD upconversion, it's also got Netflix streaming built right in. A firmware upgrade will bring that up to Netflix HD streaming. Talk about getting a lot for a little. </p>

<p>If you happen to get a check for a little more, say in the $500-$700 range, you're in prime Onkyo TX-SR607 7.2-Channel A/V Surround Home Theater Receiver. The latest and greatest from Onkyo, it's got HDMI 1.3, so you get Dolby TrueHD and DTS HD Master Audio. It even has Dolby ProLogic IIz, so you'll get sound above your head as soon as movies are encoded that way. Talk about being future proof. Very wise financial decision. </p>

<p>If you've managed to get around $1000 back from the government this year, spend it quick. They may need it back - we hear the folks at AIG are due another round of bonuses. And what better way to invest it than a Sharp Aquos LC42D85U 42-Inch 1080p 120Hz LCD HDTV. Think about it, a 42-inch, 120Hz 1080p HDTV for under $1000? It also utilizes Sharp's proprietary Advanced Super View/Black TFT Panel with Spectral Contrast Engine, providing high Dynamic-Contrast Ratio, 4ms response time and 176-degrees wide viewing angles. Even the guys at AIG know that's a sound investment. </p>

<p>So what do you do if you're sitting on a $1500 check - sounds pretty good, right? Well it will sound even better when the 7.1 version of the Aperion Intimus 4B Harmony SD speakers arrive. You just traded a little piece of paper for 8 very good, very loud speakers. And Aperion will let you try them out, risk free, for 30 days. So they're even willing to send you a refund check if it doesn't work out. Talk about a shrewd spending. </p>

<p>For those lucky enough to get a refund of $2000, you don't want to just squander it on a fancy new espresso machine, no, you want to get a nice, big HDTV like the Mitsubishi WD-737 73-Inch 1080p DLP HDTV. Wow, 73 inches for under $2000, now that's big bang for the buck. It's a a great TV that's so big you feel like you're right in the middle of all the action. And it's 3D Ready, so when you get 3D movies you really will be in the middle of all the action! Put your money to work. </p>

