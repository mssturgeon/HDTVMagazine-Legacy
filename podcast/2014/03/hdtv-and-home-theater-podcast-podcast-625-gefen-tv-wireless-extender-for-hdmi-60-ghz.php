<h4>Setup</h4>
<p dir="ltr">Setting up the GefenTV unit is just as easy as any other wireless video system.  You plug your source equipment into the sender, marked with an ‘S’, plug your display device in the receiver, marked with an ‘R’, and you&#8217;re done.  The two units find each other automatically, link up and work with minimal intervention. The sender and receiver units are quite small, maybe the smallest of any set we’ve tested, making them very easy to place almost anywhere.</p>
<p>&nbsp;</p>
<h4>Features</h4>
<ul>
<li>Wireless extension of HDMI up to 33 feet (10 meters)</li>
<li>Supports resolutions up to 1080p Full HD</li>
<li>HDCP pass-through</li>
<li>3DTV pass-through</li>
<li>CEC pass-through</li>
<li>Dolby® TrueHD, DTS-HD Master Audio™, and LPCM digital audio streams up to 7.1 channels</li>
<li>Lip Sync</li>
<li>Uncompressed High Definition A/V from source to display</li>
<li>Near zero latency (less than one frame)</li>
<li>Field upgradable via USB port</li>
<li>Frequency Band Range: 60 GHz</li>
</ul>
<p>&nbsp;</p>
<h4>Performance</h4>
<p dir="ltr">The manufacturer recommends a maximum of 33 feet (10 meters) between the receiver and transmitter and also requires direct line of sight between the two. This makes it a bit less flexible than other units we’ve tested.  We’ve had units that could go 50 feet and almost 30 feet through walls.  The GefenTV won’t do that.  We got a reliable connection at 25 feet line of sight and in that regard, in work exactly as advertised. The marketing spin is that this allows you to run multiple wireless HDMI systems in adjacent rooms or close proximity. We think it would be more convenient if it could go through walls or cabinet doors.</p>
<p dir="ltr">The GefenTV is very finicky on the line of sight requirement. It doesn’t just want the two units to be visible to each other, they need to be pointed at each other. Turning one to face a different direction kills the signal. We didn’t have any trouble getting them to work in normal installation scenarios, but it’s something you need to keep in mind if one will be in a TV equipment stand and the other up high near a projector, or perhaps facing down or sideways mounted near a flat panel TV. It also cannot be mounted behind the TV,but needs to be next to, above or below the TV depending on where your sender will be located.</p>
<p dir="ltr">Despite the installation speedbumps to overcome, the GefenTV really shines in where it counts: audio quality, video quality and reliability.  It is a champ. Other units we’ve looked at have been good, in fact, we’ve even made the statement that we couldn’t tell the difference between an actual cable and the wireless version.  That was mostly true, specifically from a pixelation, loss of signal perspective.  But with the GefenTV it is as close to a reality as we’ve ever seen. We even did some blind taste tests with a few family members and they couldn’t see or hear a difference between wired HDMI and the Gefen.</p>
<p dir="ltr">We had a strange overscan issue with the Gefen on one of our test TVs, a Vizio LCD, that we didn’t see with any other sources on the same TV. We didn’t experience the same issue on a different test TV or on our test projector. It was tough for us to blame the TV or the Gefen, and could have just been a compatibility weirdness between the two.</p>
<p dir="ltr">We tested using HDTV, Blu-ray and a Windows 7 laptop.  With a good signal, the video quality was great.  We even tried 3D and it worked as expected.  Movies and TV looked and sounded great. Video games played without a hitch. Web surfing and documents and spreadsheets worked, and had no delay, but lacked the fine detail resolution you typically want for that kind of activity. Web video,however, like Netflix and Hulu, was great.,  No matter what we threw at it from a video perspective, it handled the task with ease.</p>
<p dir="ltr">
<h4>Conclusion</h4>
<p dir="ltr">The $449 price point is still a bit high, the $300 street price is closer to many other wireless HDMI units on the market. Sometimes, however, you get what you pay for. If you need a solution that will go 50 or 60 feet, or allow you to hide your devices in a closet somewhere, the Gefen isn’t the right choice for you. But if you want to run a front projector or mount a flat panel TV, and want the best possible video you can get from a wireless HDMI solution, the GefenTV is pretty awesome. Not as flexible, but it makes up for it in quality.</p>
