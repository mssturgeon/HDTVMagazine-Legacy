<h4>Ara’s Predictions:</h4>
<p dir="ltr"><strong>Netflix will have at least 50 4K titles for streaming</strong> - Its not really going out on a limb predicting that Netflix will have 4K titles. They’ve said as much. Its the number that I think is the real prediction. If you have a high speed connection and a 4K TV you will have some content display. Look for Youtube to have 4K content as well.</p>
<p dir="ltr"><strong>OLED TV market share will remain insignificant</strong> - We have seen OLED TVs that have blown us away but when compared side by side with plasma or even the Elite LCDs they are not worth the huge price differential. Sure they can be extremely thin but is a ½ in too thick? Who cares if an OLED is half that size. Its a catch 22, until quantities go up price won’t go down. And since the quality differential isn’t worth the price I see no reason for quantities to go up.</p>
<p dir="ltr"><strong>Cable and Satellite providers will offer cloud based DVR services</strong> - Imagine a world where you can have unlimited storage for your DVR recording. We see cloud storage all over the place so why not with your DVR. With better compression and a downspeed of about 4 Mbps you could watch most of your programs with little quality difference. Translate, anything the wife and kids want to record goes to the cloud. All of your programming goes to the hard drive at full quality!</p>
<p dir="ltr"><strong>Aereo to win in the Supreme Court</strong> - This case has been going on for a while. The broadcasters would love to see Aereo shut down. I think this is the year that Aereo expands to new cities without the burden of lawsuits hanging around their necks.</p>
<p dir="ltr"><strong>Illegal downloads to exceed traditional broadcast viewership for top three pirated  shows</strong> - Game of Thrones is already illegally downloaded more than its watched on television. Breaking Bad and The Walking Dead are still viewed more on TV than downloaded illegally.</p>
<p>&nbsp;</p>
<h4>Braden’s Predictions:</h4>
<p dir="ltr"><strong>The year of 4K</strong> - Manufacturers will push 4K as the new upgrade cycle for 2014. We’ll see many, many more models and prices will come down quickly. Driven down primarily by Chinese manufacturers. 3D didn’t do it; OLED is still too far off. Queue the endless debates and hand wringing over 1080p vs 4K, just like the 720p vs 1080p of yesteryear. I may have just described a few of our shows for 2014…</p>
<p dir="ltr"><strong>Netflix will win at least one Content Award</strong> - Netflix is pushing into the original content space with a vengeance, trying to become the next online HBO. The industry will take them seriously this year and you’ll even see a Netflix show or Actor/Actress win an award. It may not be an Emmy, but maybe a People’s Choice or something else, but we’ll see Netflix get a trophy.</p>
<p dir="ltr"><strong>9 Channel Surround goes Mainstream</strong> - Most home theater receivers on the market are 7.1. The low cost, entry models are 5.1, some of the higher end units support 9.1. In 2014 we’ll see 9.1 receivers replace 7.1 as the standard and only the low cost, entry models will remain 7.1. The 5.1 receiver will be a relic. Dolby and DTS will both have native, discrete 9.1 support but it’ll take a while for it to show up in any content.</p>
<p dir="ltr"><strong>Intel and Wal-mart Shock the World</strong> - If there are any companies big enough to pull off a major disruptive change in the home theater business, its Walmart and Intel. They’re already working together with Vudu and UltraViolet, so 2014 will see them take the next step to do something really unique. It could be first run TV shows available for streaming the same time they air, or an all-you-can-eat, a la carte TV subscription, or the ability to watch first run movies at home via&#8230;</p>
<p dir="ltr"><strong>Virtual Movie Going Experience</strong> - The major studios will work in partnership with local movie theaters, to allow you to buy tickets but watch the movie in the comfort of your own home. The theater will sell the tickets, hopefully at a discount, so they share in the revenue, and everybody wins.  This sets the stage to remove the theater as the middle man altogether.</p>
