<h4>Setup</h4>
<p dir="ltr">This is where the Revolv Home Automation Hub excels! It was quite easy getting the Hub on our network.</p>
<p>The first thing you do is download and launch the iOS app (Android coming soon). Next you plug in the hub. Finally you transfer the wifi network information to the hub via the iPhone’s camera flash. After the hub gets on the network it updates itself and then its ready to go. To add devices you select “Add Devices” from the app’s setup menu and then put the device you are adding into the configure state and bingo! There it is. The Revolve app adds an icon depicting the device and you now have immediate control. We went around the house adding Insteon, Z-Wave, and wifi devices. In all, within 30 minutes of the unboxing we were controlling multiple devices throughout the house.</p>
<h4>Actions “Triggers”</h4>
<p dir="ltr">Like all good automation systems, Revolv has “actions” which can be activated in one of four ways:</p>
<ol>
<li>Sensor &#8211; And right now this means motion sensor. Revolv is constantly adding devices so you may see contact sensors in the future as well. Typical action could be turning on a light when a sensor is tripped.</li>
<li>Time &#8211; This is a straight forward as it sounds. An action will take place at the desired time.</li>
<li>Location &#8211; Right now there are two choices here, home and away. Come home and your air conditioner turns on. Leave and it turns off. Anything you can control can be triggered this way.</li>
<li>Just do it &#8211; Essentially this is a macro. You can define a sequence of events that occur when you press the button.</li>
</ol>
<p>While not complete, its a good start for a version one application. We spoke with co-founder Mike Soucie who assures us they are working on adding functionality as soon as they can. He said conditional triggers or actions based on other devices on are on the road map. The company has an active forum where they solicit ideas and which devices to support from users. The most requested ideas/devices are given higher priorities.</p>
<h4>Controlling the Home</h4>
<p dir="ltr">We’ve been using the Home Automation Hub for a few weeks now and it has performed flawlessly. When in the home, the response is quick. Over the Internet, its a little laggy but nothing that would cause anyone grief.</p>
<p dir="ltr">We set up macros that mimic our Indigo setup and with a touch of a button our theater lights were dimmed creating a mood perfect for watching movies. Our porch light was scheduled to turn on at sunset and it faithfully did. It just would have been nice to have one of our sensors trigger our stairway lights to turn on at 20% only after 10:00pm. Perhaps in the next release. And that’s another nice thing about the system, it will be updated without you having to do anything. The hub is connected to the Internet and will receive updates in the background. Likewise, the iOS app will be updated through the app store adding more functionality.</p>
<h4>Limitations</h4>
<p dir="ltr">While this is a good version one there are some areas that can be improved. We briefly mentioned in the previous section that conditional triggers would be nice. This would be something like turning on the kitchen lights at 6:00 in the morning if we weren’t in vacation mode. And that would be the other point, it would be nice to be able to set variables that can be manipulated manually or automatically based on actions. It would also be cool to get notifications. If my front door is unlocked I would like a notification or email. A web interface into the hub would also make setting up triggers and devices a little easier. Finally it would be nice if the GUI could be customized.</p>
<h4>What’s to come</h4>
<p dir="ltr">As stated earlier we had a chance to speak with co-founder Mike Soucie who shed a little light on the future. We asked if there would be a web interface to set up devices and macros. He said that is possible for the future but didn’t give a timetable.  We asked about variables and more complex triggers. Those too are on the roadmap but not expected soon. What we can expect in Q1 of 2014 are notifications, an Android app, and possibly an iPad app time permitting. There are other deeper features coming but Mike could not get into details. Mike was excited about what’s coming up and based on our conversation so are we!</p>
<h4>Conclusion</h4>
<p dir="ltr">When we first learned about a device that could unify all the various home automation and control devices out there we were sceptical. But after putting the Revolv Home Automation Hub through its paces, we can say, yes you can control everything regardless who makes it. Well maybe not everything yet. But we are sure the engineers at Revolv are working diligently to make that happen!</p>
