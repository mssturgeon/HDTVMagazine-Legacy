<strong>Today's Show:</strong><br>
Listener Kevin sent us a link to <a title="TidalTV.com" href="http://www.tidaltv.com/" target="_blank">TidalTV.com</a>
a new service that mimics the Cable or Satellite experience over the
Internet.&nbsp; You get a complete channel guide and can tune into shows on
various networks such as CBS, MSNBC, Food Network, HGTV,&nbsp; Sports
Illustrated and the Weather Channel.&nbsp; What Hulu might be to a DVR
replacement, TidalTV wants to be for your set top box replacement.&nbsp;
It's currently in Beta, so we decided to have a look to see if it might
be the next big thing.<br>

<br>
<strong>Is TidalTV the Next Big Thing?</strong><br>
First of all, if you
think you'll be able to toss out the Slingbox anytime soon, think
again.&nbsp; TidalTV isn't actually airing what's on the broadcast network,
it's simply streaming shows in a sequence that mimics a regular TV
broadcast.&nbsp; It shouldn't be too difficult, from a technical
perspective, to get the two delivery mechanisms in sync, but for now it
isn't happening.&nbsp; It would be cool, though.&nbsp; Imagine a website that
allowed you to browse a channel guide just like your set top box at
home, and tune into any of the channels live, from any Internet
connected computer.&nbsp; Here on the west coast of the U.S. we could watch
the east coast feeds and go to sleep three hours earlier.&nbsp; And say goodbye to the Slingbox, it's a thing of the past.<br>

<br>But
what about quality?&nbsp; Would anyone in their right mind actually give up HDTV for the convenience of watching shows from anywhere.&nbsp; Not anyone on this show.&nbsp; The quality of TidalTV is pretty bad.&nbsp; It would have to at least approach the DVD+ quality we get from the so called "high definition" movie downloads.&nbsp; TidalTV makes Max Headroom look good.  In the small screen you get while the guide is up, shows are somewhat watchable.  But go full screen, or try to put them on an HDTV in your home theater, and you'll want to stop as quickly as you can.  It's painful.<br>

<br>TidalTV offers the pseudo-live style of viewing in addition to an On Demand section that lets you pull up past shows at your convenience.  This is a lot closer to the Hulu way of doing things, but just with less available content and a slightly worse viewing experience.  You can view recently aired episodes of CBS shows like CSI and Swingtown, but there just isn't much to choose from.  It sure would be great if everyone could play together nice and put all the content in one place.<br>
<br>But if it's that bad, there has to be a point.&nbsp; There has to be a reason for putting the site together.&nbsp; We can imagine some cool uses for a site like TidalTV, but all of them require some pretty big changes to what's there now.&nbsp; Granted it's still in Beta, so what we get when it truly goes live may be different.  But for now, let's just say we didn't bookmark the site.<br><br>
