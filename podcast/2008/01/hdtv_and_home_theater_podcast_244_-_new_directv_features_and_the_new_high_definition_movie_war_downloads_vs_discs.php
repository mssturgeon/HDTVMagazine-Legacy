<p><strong>DirecTV's New Features</strong></p>

<p><em>Schedule Recordings over the Internet</em><br />
On the last show we talked about DirecTV's new feature called "Remote Booking". Since then we have had a chance to use the feature and can report on its functionality. The process is easy enough. You go to the DirecTV website log in, go to the program guide, and click on a show. There you will be given an option to record to a receiver. If you have multiple DVRs you will be given an drop down menu that allows you to specify the DVR you want to record to. When you select a show for recording shows up on the DVRs program guide within a few seconds. There is also a cool option that lets you do this from a mobile device as well. Use this link (m.directv.com) in your mobile phone. Ara was able to set up recordings using his iPhone in a matter of seconds. Right now the service only works with the HR20 DVR. DirecTV will be supporting more receivers in the near future.</p>

<p>The only downside to the whole process is that we could not a way to cancel a recording once it was set. But that's a minor nit. The ability to record a show that you forgot to set up far outweighs this minor issue. Overall, this is a great feature.</p>

<p><em>HD Downloads</em><br />
With all this talk of HD downloads to come on Vudu and AppleTV (which has been ordered for review very soon!) we tend to overlook other ways to get HD on demand. Many cable companies already offer this feature but today we will focus on DirecTVs HD on demand. First of all, its not really on demand. The download took about four hours. Maybe even longer, it completed while Ara's family was sound asleep.</p>

<p>Right now there are only five (there were only three when Ara first downloaded the movie two weeks ago) HD titles that are available for download (in addition to Evan Almighty you can rent The Hoax, I now pronounce you Chuck and Lary, Mr Brooks, and Ratatouille). We chose Evan Almighty. As stated above the download took quite some time to complete. We never saw the point where we could watch while the rest of the movie downloaded. That's because we started the process at 7:00PM and had to go to sleep. We're sure, based on other downloads that at some point the you could have started watching while the rest of the movie downloaded. So for HD, you really have to plan ahead. It may be faster than putting the movie on the Netflix queue, it certainly is not faster than driving to your local video store.</p>

<p>The quality of the movie is quite good. We were very surprised at how good the quality was. But Blu Ray and HD DVD have nothing to worry about. Still the quality s better than DVD. We will be doing a comparison with the AppeTV once it arrives. But we will be very surprised if there is any difference since AppleTV and Vudu probably get their content from the same source. The audio on the the movie was matrix Dolby Pro Logic. For this movie it was fine but we would hope that action movies will come with Dolby Digital. We were given two months to watch the movie but just like the ApleTV, once you hit play the movie expires in 24 hours.</p>
