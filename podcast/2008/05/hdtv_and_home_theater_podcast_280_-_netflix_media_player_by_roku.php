<p><strong>Today's Show:</strong><br />
So you want to watch movies with Netflix watch it now but you aren't thrilled about sitting in front of your computer to do it. <a target="_blank" href="http://www.netflix.com/NetflixReadyDevices?lnkctr=wnph_nfrd">Netflix and Roku</a> have partnered together bring the Watch it Now functionality to your TV. We have one of these players and have spent a week putting it through its paces.</p>

<p><strong>The NetFlix Media Player by Roku</strong></p>

<p>The player costs $99 and requires a Netflix subscription that includes unlimited instant viewing. Your DVD delivery subscription remains the same. Currently Netflix has over 10,000 movie and TV titles available for instant viewing. Movie titles are mostly back catalog but there are some very recent TV programs available. The content is 480p at 3 Mbps and the audio is only stereo. The box supports HD but at this time there is no HD content available.</p>

<p><strong>Setup</strong><br />
Setup was trivial! Plug in your Ethernet cable, HDMI, and power. The box supports HDMI, component, s-video, and composite connections. Once the system was turned on we were asked to upgrade the firmware which took about five minutes. We restarted the player and were given a four digit code that needed to be entered at the Netflix site. The code ties the box to your account. You can setup up to four boxes in a 12 month period but simultaneous viewing is limited by the number of movies you can have out at a time. So if you have a three out plan you can watch three movies on three different boxes simultaneously.</p>

<p>For the record, a Netflix ready device can only be used in the 50 US States and the District of Columbia. Movies and TV episodes cannot be watched instantly in any other location.</p>

<p><strong>Performance</strong><br />
At this point if you don't have any content in your queue the screen will be blank. There is no way to add content from the player. You have to go online and add programming to your queue. Once you have content navigating your selections is very easy but nothing we would compare to Apple or Vudu. You navigate with the nine button remote control. Once you hit play the movie buffers for about 30 seconds and then starts playing. Quality was good but not what we would call DVD quality and the audio was stereo with the two movies watched being Pro Logic.</p>

<p>With that said. This product is a must have for anyone who already has an unlimited Netflix account! It was so much fun going through the Netflix site and finding programs to put on the queue. Its a great way to watch old programs on your terms. We watched old episodes of Magnum PI, Rockford Files, Adam-12, and Charles in Charge. These old programs were 4:3 and looked less than DVD quality.</p>

<p>We also watched some newer content like 30-Rock and Heroes which were 16:9 and looked much closer to DVD quality. Movies were good as far as quality goes but we were disappointed that the movie "Point of No Return", which was an Anamorphic wide screen movie, didn't look right on the screen. Air Force One looked great and had a decent Pro Logic Mix.</p>

<p>We also liked the ability to pause, fast forward and rewind what we were watching. Even though you stream the content you can move forward to a point and re-buffer the stream. The system also remembers where you left off if you switch to something else. The only issue we had with remembering where we left off is if the box restarts. We did this once and the player forget all our places.</p>

<p><strong>What does the Future Hold?</strong><br />
Roku says the hardware will support High Def video and multi channel audio but has not announced any dates. Netflix is working on bringing this functionality to other devices like Blu Ray players, Game Consoles, and Televisions. Netflix says the first devices will be available later this year.</p>

<p><strong>Recommendation</strong><br />
If you are a Netflix Subscriber and have an unlimited instant viewing plan go out and buy this device! It is a lot of fun and there is a ton of great TV content. The only real knock we have against the current service is that we would like to see more and newer movies, HD and digital Audio. With that said having the ability to dial up an episode of Magnum PI on the fly is pretty cool! And when you consider that all TV before HD had at best two channel audio and less than DVD video you really aren't giving up anything.<br />
</p>
